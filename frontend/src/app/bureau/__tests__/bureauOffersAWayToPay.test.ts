import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { безКомментариев } from "@/lib/__tests__/helpers/sourceWithoutComments";

/**
 * На странице бюро есть путь к оплате.
 *
 * ЗАЧЕМ. Бюро авторства — главный денежный канал по прямому слову основателя
 * 28.09.2026, рассылка идёт каждый день, и все письма ведут СЮДА. Замер того же
 * дня: на странице не было ни чипа цены, ни вызова кассы, ни даже ссылки на
 * /pricing. Ноль путей к оплате.
 *
 * При этом касса исправна: `POST /api/pricing/checkout/session` с
 * `tierId: "lite"`, `appId: "ip_bureau"` отвечает 200 и настоящей ссылкой
 * Lemon Squeezy; в `checkout/healthz` все пять сроков бюро — в продаже.
 * То есть купить было можно, но не отсюда: человек читал письмо, приходил,
 * брал бесплатный анонимный сертификат и платного продукта не видел.
 *
 * Этот класс не краснеет сам: страница отвечает 200, всё на ней работает,
 * ошибок нет. Не хватает только того, ради чего страницу показывают.
 *
 * ГРАНИЦА: сторож читает исходник и отвечает «путь к оплате на странице есть»,
 * а не «человек дошёл до кассы». Второе проверяется браузером и покупкой.
 */

const PAGE = join(__dirname, "..", "page.tsx");
const src = безКомментариев(readFileSync(PAGE, "utf8"));

describe("бюро можно купить со страницы бюро", () => {
  it("контроль: файл прочитан и это нужная страница", () => {
    expect(src.length).toBeGreaterThan(5000);
    expect(src).toContain("PageTracking page=\"bureau\"");
  });

  it("путь к оплате на месте", () => {
    expect(
      src.includes("ModulePricingChip"),
      "на главной странице главного денежного канала снова нечем заплатить",
    ).toBe(true);
  });

  it("чип назван тем модулем, который продаётся", () => {
    /*
     * Не любой чип годится: `moduleId` должен разрешаться в каталоге.
     * `"bureau"` отображается в `aevion-ip-bureau` (termPricing, findApp), и
     * именно эти позиции `app_ip_bureau_*` числятся продаваемыми в
     * checkout/healthz. Чужой id дал бы пустой чип — то есть ту же дыру,
     * только незаметнее.
     */
    expect(src).toContain('ModulePricingChip moduleId="bureau"');
  });
});
