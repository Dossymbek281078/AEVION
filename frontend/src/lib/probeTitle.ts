/**
 * Служебное ли это название — один ответ для всех витрин.
 *
 * ЗАЧЕМ ОБЩИЙ ДОМ. Правило §19 говорит: создающий запрос на прод помечается в
 * названии (`smoke-`, `probe-`) и убирается следом. Но «убрать» оказалось не
 * одним действием: у QRight скрытие проб ВСТРОЕНО в выдачу витрины (запрос
 * исключает `ownerName = 'smoke-test'`), а конвейер `/api/pipeline/protect`
 * пишет сразу в несколько мест — и в Quantum Shield запись уезжает БЕЗ поля
 * владельца, только с названием объекта.
 *
 * Замер 28.09.2026, на собственной пробе: я проверил витрину QRight, увидел
 * ноль и счёл уборку сделанной. Проверка целей поста нашла ту же пробу на
 * витрине Quantum Shield — 1 запись из 7, видна любому посетителю. То есть
 * «убрал из одной витрины» не равно «убрал»: у одной записи столько витрин,
 * сколько модулей её увидели.
 *
 * Поэтому признак живёт отдельно от места: любая витрина спрашивает его по
 * НАЗВАНИЮ, которое видно человеку, а не по внутреннему полю, которого у неё
 * может не быть.
 *
 * ГРАНИЦА. Это фильтр показа, а не удаление: запись остаётся в базе и по
 * прямой ссылке открывается. Так и задумано — прятать от постороннего глаза
 * можно, а стирать чужие данные по эвристике имени нельзя.
 */

/** Метки, которыми мы сами помечаем свои прогоны по §19. */
const МЕТКИ = ["smoke", "probe", "test-", "тест-", "проба"];

export function служебноеНазвание(title: string | null | undefined): boolean {
  const t = String(title ?? "").trim().toLowerCase();
  if (!t) return false; // пустое название — не повод прятать чужую работу
  return МЕТКИ.some((м) => t.startsWith(м) || t.includes(" " + м));
}
