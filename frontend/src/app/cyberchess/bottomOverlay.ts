/* Насколько плавающий элемент должен отступить снизу, чтобы не лечь на навигацию.
 *
 * На телефоне (`vwPx < 769`, кроме стрим-режима) внизу страницы стоит `cc-bottom-nav` —
 * пять кнопок, которыми на телефоне и переключаются разделы. Всё, что приклеено к низу
 * экрана через `position: fixed`, ложится поверх неё: панель `sticky` и в споре за место
 * проигрывает фиксированному элементу с большим z-index.
 *
 * Найдено 11.08.2026 сразу в трёх местах:
 *   - предупреждение «прогресс перестал сохраняться» (bottom 12, z-index 9999) — оно
 *     висит до перезагрузки, то есть накрыло бы навигацию НАВСЕГДА: единственный экран,
 *     сообщающий о потере прогресса, стал бы единственным, с которого нельзя уйти;
 *   - свёрнутая кнопка голосового коуча (bottom 16, справа) — накрывала крайнюю кнопку;
 *   - кнопка «вернуться к партии» (bottom 20, по центру) — появляется РОВНО тогда, когда
 *     человек ушёл с доски в другой раздел, то есть когда навигация ему и нужна.
 *
 * Высота панели: иконка 20 + подпись ~12 + отступы 10/8 + рамка 2 ≈ 56–60 пикселей.
 * Берём 72 с запасом и прибавляем безопасную зону — панель делает то же самое.
 *
 * Почему константа, а не число по месту: в модуле уже жили `bottom: 56` и `bottom: 64`,
 * подобранные на глаз под ту же панель. Три разных числа для одного расстояния — это
 * гарантия, что при изменении панели поедет часть из них.
 */

/** Отступ снизу, при котором элемент гарантированно выше нижней навигации. */
export const ABOVE_BOTTOM_NAV = "calc(72px + env(safe-area-inset-bottom, 0px))";

/**
 * Показывается ли сейчас нижняя навигация.
 * Условие обязано совпадать с тем, по которому рендерится `BottomNav` — иначе отступ
 * появится там, где панели нет, или пропадёт там, где она есть.
 */
export function bottomNavShown(vwPx: number, streamerMode: boolean): boolean {
  return !streamerMode && vwPx < 769;
}

/** Отступ снизу для плавающего элемента: над панелью на телефоне, обычный на десктопе. */
export function bottomOffset(
  vwPx: number,
  streamerMode: boolean,
  desktop: number,
): string | number {
  return bottomNavShown(vwPx, streamerMode) ? ABOVE_BOTTOM_NAV : desktop;
}
