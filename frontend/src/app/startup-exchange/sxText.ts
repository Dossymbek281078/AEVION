/** Строки с числом внутри, которые собирает lib.ts: регулярка → шаблон en. */
const SX_PATTERNS: Array<[RegExp, string]> = [
  [/^Ошибка (\d+)\. Попробуйте ещё раз\.$/, "Error $1. Please try again."],
  [/^Сервер ответил (\d+) без данных$/, "The server replied $1 with no data"],
];

function fill(src: string, vars?: Record<string, string | number>): string {
  if (!vars) return src;
  return src.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

export function sx(lang: string | undefined, src: string, vars?: Record<string, string | number>): string {
  if (lang === "ru" || !lang) return fill(src, vars);
  const entry = Object.prototype.hasOwnProperty.call(SX_TEXT, src) ? SX_TEXT[src] : undefined;
  if (lang === "kk") return fill(entry?.kk ?? src, vars);
  if (entry?.en) return fill(entry.en, vars);
  for (const [re, en] of SX_PATTERNS) {
    if (re.test(src)) return src.replace(re, en);
  }
  return fill(src, vars);
}

/** Дата и время по языку страницы (раньше стоял жёсткий ru-RU). */
export function sxLocale(lang: string | undefined): string {
  return lang === "ru" ? "ru-RU" : lang === "kk" ? "kk-KZ" : "en-US";
}
