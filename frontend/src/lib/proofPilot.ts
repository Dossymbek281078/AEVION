/** Цена пилота в долларах. Решение основателя 12.10.2026 («490»). */
export const PILOT_USD = 490;

/** Сколько записей входит в пилот. */
export const PILOT_RECORDS = 10_000;

/** Срок пилота в днях — про человеческую работу, не про скорость криптографии. */
export const PILOT_DAYS = 7;

/**
 * Размер манифеста на 10 000 записей, в мегабайтах (одна цифра после запятой).
 *
 * 🔴 Это число названо покупателю НАМЕРЕННО, хотя оно неудобное: 6.8 МБ не
 * влезает в разумное письмо, то есть поставка отдаётся ссылкой на файл. Узнать
 * об этом на последнем шаге первого же пилота дороже, чем сказать заранее.
 */
export const PILOT_MANIFEST_MB = 6.8;

/** Адрес для заказа. Тот же, что на остальной странице. */
export const PILOT_CONTACT = "data@aevion.app";

/**
 * Письмо-заказ с заранее заполненными темой и телом.
 *
 * Тема и тело заполнены не для красоты: письмо без объёма и формата поставки
 * неотличимо от обычного вопроса, а нам нужен именно состав — иначе первый
 * ответ уйдёт на выяснение того, что человек мог написать сразу.
 */
export function pismoZakaza(): string {
  const subject = `Pilot request - $${PILOT_USD}`;
  const body = ["Records to sign:", "Delivery format:", "Deadline:", ""].join("\n");
  return `mailto:${PILOT_CONTACT}?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
}

