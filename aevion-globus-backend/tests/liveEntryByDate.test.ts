import { describe, expect, test } from "vitest";
import { isLiveNow } from "../src/lib/constitutionBrevo";

// Найдено 29.08.2026, за сутки до запуска шахмат: список «уже открыто» был
// статическим, и подписавшийся 30-го получил бы письмо «Открываем по плану
// 30 августа» — в сам день запуска. Ручной шаг, о котором никто не вспомнит в
// день запуска, — не шаг, а ловушка; поэтому переход идёт ПО ДАТЕ.
describe("модуль становится открытым по дате, а не рукой", () => {
  const LAUNCH = Date.UTC(2026, 7, 30); // 30 августа 2026

  test("накануне — ещё не открыт", () => {
    expect(isLiveNow(LAUNCH, new Date("2026-08-29T10:00:00Z"))).toBe(false);
  });

  test("в день запуска — открыт", () => {
    expect(isLiveNow(LAUNCH, new Date("2026-08-30T06:00:00Z"))).toBe(true);
  });

  test("после запуска — открыт", () => {
    expect(isLiveNow(LAUNCH, new Date("2026-09-02T00:00:00Z"))).toBe(true);
  });

  // Главное здесь — часовой пояс. Запуск ведётся в Алматы (UTC+5), значит день
  // запуска начинается в 19:00 UTC накануне. Без сдвига письмо шесть часов
  // считало бы, что запуск ещё не наступил, — ровно в те часы, когда первые
  // люди приходят по письму.
  test("день запуска начинается по времени Алматы, а не по UTC", () => {
    expect(isLiveNow(LAUNCH, new Date("2026-08-29T18:59:00Z")), "18:59 UTC — ещё 29-е в Алматы").toBe(false);
    expect(isLiveNow(LAUNCH, new Date("2026-08-29T19:01:00Z")), "19:01 UTC — уже 30-е в Алматы").toBe(true);
  });

  test("без даты перехода запись считается открытой всегда", () => {
    expect(isLiveNow(undefined, new Date("2020-01-01T00:00:00Z"))).toBe(true);
  });
});
