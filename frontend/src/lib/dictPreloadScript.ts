/**
 * Скрипт предзагрузки словаря — отдельным модулем, чтобы его можно было
 * ИСПОЛНИТЬ в проверке.
 *
 * Жил внутри layout.tsx, и сторож, импортирующий макет, падал на шрифтах
 * (`TypeError: Geist is not a function`) — то есть проверить поведение скрипта
 * было нечем. Тот же приём уже применён в этом репозитории к globusLocale.ts
 * и по той же причине: тест не должен тянуть за собой полстраницы.
 *
 * Порядок источников языка здесь ОДИН на весь сайт: адрес → кука → хранилище
 * → язык браузера. Почему кука раньше хранилища — в комментарии ниже и в
 * стороже dictPreloadPrefersCookie.
 */
export function скриптПредзагрузкиСловаря(отпечатокСборки: string): string {
  return (
    // 29.09.2026: АДРЕС ПЕРВЫМ. До этого скрипт брал сохранённый выбор и куку, а
    // путь /en/... не смотрел вовсе — и качал русский словарь для человека, которому
    // прислали английскую ссылку. Он же и рисовал русское меню с первой секунды:
    // словарь приезжал раньше, чем React успевал что-то решить.
    "try{var L=null;try{var P=(location.pathname||'').split('/')[1]||'';" +
    "if(P.length===2){var pl=P.toLowerCase();if(pl==='ru'||pl==='kk'||pl==='en')L=pl}}catch(e){}" +
    // 🔴 07.10.2026: КУКА РАНЬШЕ ХРАНИЛИЩА. До этого порядок был обратный, и
    // устаревшее значение в localStorage перебивало свежую куку.
    //
    // Как это случалось у живого человека. Куку языка ставит не только
    // переключатель: middleware.ts:125 выставляет `aevion_lang_v1=en` НА
    // СЕРВЕРЕ при переадресации с /en/... на канонический адрес (308), и
    // localStorage при этом не трогает — из сервера до него не дотянуться.
    // Значит у посетителя, который раньше выбрал русский, а потом открыл
    // английскую ссылку, кука становится en, а хранилище остаётся ru.
    // Этот скрипт брал ru и качал русский словарь: страница выходила русской
    // при английской куке. Соседний скрипт (ниже по телу) ставил при этом
    // lang="en" — он куку читает, а хранилище нет. Два разных ответа на один
    // вопрос в одном документе.
    //
    // Почему главной выбрана кука, а не хранилище: так уже решено в
    // I18nProvider (src/lib/i18n.tsx) дословно — «кука переживает чистку
    // storage и приходит с других вкладок — выбор старше догадки», и он на
    // монтировании СИНХРОНИЗИРУЕТ хранилище из куки. Выбивался из общего
    // правила только этот скрипт. Теперь источники согласованы все три:
    // предзагрузка словаря, установка lang и провайдер.
    //
    // Хранилище остаётся запасным путём намеренно: у части посетителей кука
    // могла не доехать (блокировщики, строгие настройки), а выбор у них
    // сохранён. Оно просто больше не старше куки.
    "if(!L){var c=document.cookie.split('; ');for(var i=0;i<c.length;i++){var p=c[i].split('=');" +
    "if(p[0]==='aevion_lang_v1'){L=decodeURIComponent(p[1]||'');break}}}" +
    "if(!L){try{L=localStorage.getItem('aevion_lang_v1')}catch(e){}}" +
    "if(!L){var n=(navigator.language||'en').toLowerCase();" +
    "var m=['kk','kz','ru','de','fr','es','zh','ja','ar','pt','tr'];" +
    "for(var j=0;j<m.length;j++){if(n.indexOf(m[j])===0){L=m[j]==='kz'?'kk':m[j];break}}}" +
    "var ok={ru:1,kk:1,de:1,fr:1,es:1,zh:1,ja:1,ar:1,pt:1,tr:1};" +
    "if(L&&ok[L]){window.__aevionDict={lang:L,promise:fetch('/i18n/'+L+'?v=" +
    encodeURIComponent(отпечатокСборки) +
    "').then(function(r){return r.ok?r.json():null}).catch(function(){return null})}}}catch(e){}"
  );
}
