import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Язык из АДРЕСА должен выигрывать ещё ДО оживления страницы.
 *
 * 29.09.2026. Соседнее окно прочтением живого сайта: на /en/devhub меню было русским
 * С ПЕРВОЙ СЕКУНДЫ, а через несколько секунд на русский перерисовывался и текст. Мой
 * curl того же адреса отдавал чистый английский — значит виноват не сервер.
 *
 * Причина нашлась в двух пре-гидрационных скриптах корневого макета: один ставит
 * атрибут языка документу, второй начинает качать словарь. Оба читали сохранённый
 * выбор и куку и НЕ смотрели на путь. Человек, которому прислали английскую ссылку,
 * получал русский словарь, если когда-то выбирал русский в этом браузере.
 *
 * Здесь проверяется сам текст скриптов: они исполняются в браузере до React, и
 * поведенчески их в этом наборе не запустить. Зато можно закрепить порядок ИСТОЧНИКОВ
 * — а это ровно то, что сломалось.
 */
const layout = readFileSync(join(__dirname, "..", "..", "app", "layout.tsx"), "utf8");

/** Кусок исходника между двумя метками — чтобы судить о КАЖДОМ скрипте отдельно. */
function кусок(от: string, длина = 1200): string {
  const i = layout.indexOf(от);
  expect(i, `не найдено: ${от}`).toBeGreaterThan(-1);
  return layout.slice(i, i + длина);
}

describe("предзагрузка словаря", () => {
  const скрипт = кусок("const DICT_PRELOAD_SCRIPT");

  it("сначала смотрит адрес, потом сохранённый выбор", () => {
    const iПуть = скрипт.indexOf("location.pathname");
    const iВыбор = скрипт.indexOf("localStorage.getItem('aevion_lang_v1')");
    expect(iПуть, "адрес не читается вовсе").toBeGreaterThan(-1);
    expect(iПуть, "сохранённый выбор читается раньше адреса").toBeLessThan(iВыбор);
  });

  it("берёт из адреса только настоящие языки витрины", () => {
    // «/energy» начинается с «en», но это не префикс языка: регулярка требует
    // ровно две буквы и границу.
    expect(скрипт).toContain("'ru'");
    expect(скрипт).toContain("'kk'");
    expect(скрипт).toContain("'en'");
  });
});

describe("атрибут языка документа", () => {
  const скрипт = кусок("data-lang-src");

  it("источник называется честно: путь или кука", () => {
    expect(скрипт).toContain("'path'");
    expect(скрипт).toContain("'cookie'");
  });

  it("кука не перебивает адрес", () => {
    // Кука читается только если путь языка не дал — иначе вернулись бы к дефекту.
    const iПуть = скрипт.indexOf("location.pathname");
    const iКука = скрипт.indexOf("document.cookie");
    expect(iПуть).toBeGreaterThan(-1);
    expect(iПуть).toBeLessThan(iКука);
    // Флаг вместо чтения атрибута: document в проверках подменяют объектом без
    // getAttribute, и вызов ронял весь скрипт — тоже проверено запуском.
    expect(скрипт).toContain("if(!S)");
  });
});
