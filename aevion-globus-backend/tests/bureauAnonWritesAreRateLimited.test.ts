/**
 * ОТКРЫТАЯ запись в бюро обязана быть под пределом частоты.
 *
 * 🔴 ЗАЧЕМ. Замер на боевом проде 09.09.2026, за сутки до выхода модуля:
 * `POST /api/bureau/verify/start` без единого заголовка и с ПУСТЫМ телом
 * ответил 201 и вставил строку в "BureauVerification". Проверки прав там нет
 * по устройству — `resolveUser` для анонимного возвращает userId=null,
 * email=null, и вставка идёт всё равно. Предела не было: из 40 маршрутов
 * модуля под ограничителем 9, а из 15 ПИШУЩИХ — ровно один (/waitlist).
 *
 * Одна мусорная строка создана этой самой пробой; она названа в отчёте
 * основателю, чтобы её не искали как чужую.
 *
 * `/payment/intent` попадает в тот же класс: он анонимен и принимает
 * verificationId, который кто угодно выпускает предыдущей ручкой, — это
 * продолжение цепочки, а не отдельная поверхность.
 *
 * 🔴 ПОЧЕМУ ПОВЕДЕНЧЕСКИЙ ТЕСТ, А НЕ ПРОВЕРКА ИСХОДНИКА. Текстовый сторож
 * («в файле есть слово bureauAnonWriteRateLimit») переживёт лимитер, у
 * которого max подняли до миллиона или окно сделали нулевым: форма на месте,
 * силы нет. Здесь ограничитель стоит ДО обработчика, поэтому база не нужна
 * вовсе — 429 приходит, не дойдя до запроса. Это и делает проверку дешёвой.
 *
 * Предел здесь БОЕВОЙ, переменными не глушится: иначе защита проверялась бы
 * в заглушенном виде и её отсутствие прошло бы незамеченным.
 */

