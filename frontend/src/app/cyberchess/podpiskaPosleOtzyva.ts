/**
 * Что показывать первым после партии: отзыв или окно подписки на запуск.
 *
 * Решение оркестратора 16.10.2026 по данным, не на вкус: за 7 дней окно подписки
 * после конца партии дало 0 живых адресов (waitlist_submit с source
 * cyberchess-game-over — 0 событий; живых сессий с концом партии — 1 из 26,
 * остальные пробы). Поэтому до 20.10 первым идёт отзыв: окно подписки не
 * всплывает, пока на плашке открыто поле отзыва, и показывается после
 * «Отправить» или после закрытия плашки. Правило «один раз на устройство»
 * остаётся: отметка aevion_chess_waitlist_seen ставится в момент показа.
 */
export type SostoyaniePodpiski = {
  /** Конец партии наступил, окно подписки ещё не показывали и повод — game-over. */
  ждёт: boolean;
  /** Человек нажал «Отправить» в поле отзыва на плашке. */
  otzyvOtpravlen: boolean;
  /** Плашка после партии ещё на экране (партия окончена, новая не начата). */
  plashkaOtkryta: boolean;
};

/** Пора ли показывать окно подписки сейчас. */
export function podpiskaPora(s: SostoyaniePodpiski): boolean {
  if (!s.ждёт) return false;
  return s.otzyvOtpravlen || !s.plashkaOtkryta;
}
