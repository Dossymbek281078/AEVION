import { describe, expect, test } from "vitest";
import { chislaPartii } from "../page";

/*
 * 🔴 Два числа о длине партии: пары ходов и полуходы. Проверяется СВЯЗЬ между ними.
 *
 * ПОВОД — замер 08.10.2026 на живом проде: я сдался ДО первого хода, и `game_end`
 * ушёл (на экране буквально «Вы сдались, белые, партия ещё не начата»). Значит
 * «доиграли» будет включать тех, кто не играл. А поле `moves` считает ПАРЫ ходов,
 * поэтому партия в один полуход даёт `moves = 0` — то есть по нему она
 * неотличима от партии вообще без ходов. Порог воронки у окна 98 встаёт на
 * `plies >= 1`, и эта функция обязана давать ему честное число.
 *
 * Слово окна 98 (владелец разреза): «plies добавить, moves не переопределять» —
 * переопределение меняет смысл уже записанных событий, а перемерить их нечем.
 */

const ходы = (n: number) => Array.from({ length: n }, (_, i) => "ход" + i);

describe("числа о длине партии", () => {
  test("ни одного хода → оба нуля", () => {
    expect(chislaPartii([])).toEqual({ moves: 0, plies: 0 });
  });

  test("🔴 ОДИН полуход: plies = 1, а moves всё ещё 0 — ради этого случая поле и добавлено", () => {
    const ч = chislaPartii(ходы(1));
    expect(ч.plies, "полуходов").toBe(1);
    expect(ч.moves, "пар ходов").toBe(0);
    // Именно здесь прежний порог «moves >= 1» отбрасывал настоящую партию.
    expect(ч.plies > 0 && ч.moves === 0).toBe(true);
  });

  test("пара ходов → moves 1, plies 2", () => {
    expect(chislaPartii(ходы(2))).toEqual({ moves: 1, plies: 2 });
  });

  test("семь полуходов → moves 3 (целые пары), plies 7", () => {
    expect(chislaPartii(ходы(7))).toEqual({ moves: 3, plies: 7 });
  });

  test("🔴 оба значения — ЧИСЛА, не строки", () => {
    // Предупреждение окна 98, проверенное у них контролем: строка «1» не зачтётся
    // ходом и уедет в отдельный счётчик. Тип — часть договора, а не косметика.
    const ч = chislaPartii(ходы(3));
    expect(typeof ч.moves, "тип moves").toBe("number");
    expect(typeof ч.plies, "тип plies").toBe("number");
  });

  test("КОНТРОЛЬ: единицы РАЗНЫЕ, а не два имени одного числа", () => {
    // Без этого проверки прошли бы и у функции, где plies равен moves: все
    // «нормальные» партии чётной длины совпадали бы по смыслу, и подмена
    // осталась бы незамеченной до первой партии в один полуход.
    const пары = [1, 3, 5, 9].map((n) => {
      const ч = chislaPartii(ходы(n));
      return ч.plies - ч.moves;
    });
    expect(пары.every((d) => d > 0), `разницы: ${пары.join(", ")}`).toBe(true);
  });
});
