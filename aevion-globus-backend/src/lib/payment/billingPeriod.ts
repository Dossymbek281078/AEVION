import type { BillingPeriod } from "../../data/pricing";

/**
 * Период покупки выводится ИЗ ССЫЛКИ ЗАКАЗА, а не назначается месячным.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Правило жило в трёх копиях: своя функция у paybox,
 * такая же у paypal, встроенное выражение у gumroad. Четвёртая касса,
 * Lemon Squeezy, копии не получила и зашивала `period: "monthly"` — то есть
 * годовая покупка записывалась месячной, срок считался на месяц, и человек
 * терял доступ через месяц после того, как заплатил за год. Следующего
 * события от кассы пришлось бы ждать одиннадцать месяцев.
 *
 * Правило одно на все кассы, поэтому и место у него одно: пока копий было
 * три, отставание четвёртой ничем не выдавало себя.
 *
 * Ссылку строит витрина: `checkout.ts` собирает `tier_${id}_${period}`,
 * значит слово "annual" в ссылке и есть признак годовой покупки.
 */
export function periodForReference(ref: string): BillingPeriod {
  return ref.toLowerCase().includes("annual") ? "annual" : "monthly";
}
