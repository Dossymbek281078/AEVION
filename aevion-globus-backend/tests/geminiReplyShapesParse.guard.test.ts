import { describe, it, expect } from "vitest";
import { __parseGeneratedFilesForTest as разобрать } from "../src/routes/devhub";

/**
 * Формат ответа Gemini проходит тот же разбор, что и прежние поставщики.
 *
 * ЗАЧЕМ. 05.10.2026 бесплатные гости переведены на Gemini первым поставщиком
 * (решение основателя по замеру: в 30 раз дешевле). Разбор ответа писался, когда
 * генерацию вёл Anthropic. Gemini отвечает СВОБОДНЫМ ТЕКСТОМ — responseMimeType
 * мы ему не задаём (providers.ts, вызов generateContent), — то есть обычно
 * оборачивает JSON в забор кода и нередко добавляет пояснение до и после.
 *
 * ЧТО СТОИТ НА КОНУ. При неудачном разборе человек получает НЕ пустоту и НЕ
 * молчание, а один файл, в содержимом которого лежит сырой ответ модели целиком
 * (mode "fallback"). Снаружи похоже на «сайт собрался», а внутри проза вместо
 * кода. Поэтому каждый случай уходит в Sentry: «devhub generate: reply
 * unparseable, raw-dump fallback» — 1 раз за 26.09–03.10.
 *
 * Сторож судит по ФОРМАМ ответа, а не по словам в коде: подменить реализацию и
 * оставить его зелёным нельзя.
 */

const ЗАБОР = "```";

const ОБЫЧНЫЙ = {
  files: [
    { path: "index.html", content: "<h1>Привет</h1>", language: "html" },
    { path: "style.css", content: "body{margin:0}", language: "css" },
  ],
};

const файлы = (о: unknown) => JSON.stringify(о);

describe("ответ Gemini разбирается в файлы, а не в сырой дамп", () => {
  it("прибор исправен: голый JSON разбирается, и это НЕ fallback", () => {
    const r = разобрать(файлы(ОБЫЧНЫЙ));
    expect(r.mode).toBe("parsed");
    expect(r.files.map((f) => f.path)).toEqual(["index.html", "style.css"]);
  });

  it("КОНТРОЛЬ: чистая проза без JSON — честный fallback, а не выдуманные файлы", () => {
    // Без этого контроля сторож был бы зелёным и на разборе, который ВСЕГДА
    // отвечает «parsed»: он не отличал бы успех от провала.
    const r = разобрать("Конечно! Вот как я бы это сделал. Сначала создадим страницу…", ["app.tsx"]);
    expect(r.mode).toBe("fallback");
    expect(r.files).toHaveLength(1);
    expect(r.files[0].path).toBe("app.tsx");
  });

  it("забор кода вокруг JSON — обычная форма Gemini", () => {
    const r = разобрать(ЗАБОР + "json\n" + файлы(ОБЫЧНЫЙ) + "\n" + ЗАБОР);
    expect(r.mode, "ответ в заборе кода ушёл в сырой дамп").toBe("parsed");
    expect(r.files).toHaveLength(2);
  });

  it("пояснение ДО и ПОСЛЕ забора — Gemini так делает постоянно", () => {
    const r = разобрать(
      "Отлично, вот готовая страница:\n\n" + ЗАБОР + "json\n" + файлы(ОБЫЧНЫЙ) +
      "\n" + ЗАБОР + "\n\nГотово! Файлы можно выкатывать.",
    );
    expect(r.mode, "пояснение вокруг JSON сломало разбор").toBe("parsed");
    expect(r.files).toHaveLength(2);
  });

  it("забор без пометки json", () => {
    const r = разобрать(ЗАБОР + "\n" + файлы(ОБЫЧНЫЙ) + "\n" + ЗАБОР);
    expect(r.mode).toBe("parsed");
  });

  it("внутри содержимого файла ТОЖЕ есть забор кода", () => {
    /*
     * Самый правдоподобный отказ, и он не выдуман: DevHub постоянно генерирует
     * README и разметку, а забор кода в них — обычное дело. Регулярка забора
     * нежадная: она закроется на ПЕРВОМ внутреннем заборе и отдаст обрезанный,
     * невалидный JSON.
     */
    const сЗабором = {
      files: [
        { path: "README.md", content: "Запуск:\n\n" + ЗАБОР + "bash\nnpm run dev\n" + ЗАБОР, language: "markdown" },
        { path: "index.html", content: "<h1>ok</h1>", language: "html" },
      ],
    };
    const r = разобрать("Вот файлы:\n" + ЗАБОР + "json\n" + файлы(сЗабором) + "\n" + ЗАБОР);
    expect(r.mode, "забор внутри содержимого увёл ответ в сырой дамп").toBe("parsed");
    // Замерено 05.10: именно "parsed", а не спасение из обрывка — то есть
    // разбор справляется честно. Утверждение точное намеренно: «не fallback»
    // было бы зелёным и при тихой потере файлов через salvage.
    expect(r.files.length, "файлы потеряны").toBeGreaterThanOrEqual(2);
    const readme = r.files.find((f) => f.path === "README.md");
    expect(readme?.content, "содержимое README потеряно").toContain("npm run dev");
  });

  it("в пояснении ДО JSON есть фигурная скобка", () => {
    /*
     * Запасной путь разбора берёт «от первой { до последней }». Скобка в прозе
     * сдвигает начало, и этот путь перестаёт работать. Проза вида «объект
     * { files } содержит…» для модели совершенно естественна.
     */
    const r = разобрать(
      "Я верну объект { files: [...] } со всеми файлами:\n" + ЗАБОР + "json\n" + файлы(ОБЫЧНЫЙ) + "\n" + ЗАБОР,
    );
    expect(r.mode, "скобка в пояснении увела ответ в сырой дамп").toBe("parsed");
    expect(r.files.length).toBeGreaterThanOrEqual(2);
  });

  it("обрыв по лимиту токенов: целые файлы спасаются", () => {
    // Замер прежних окон: ответ 8.8 КБ обрывался посреди значения CSS.
    const обрыв =
      '{"files":[{"path":"a.html","content":"<h1>a</h1>","language":"html"},' +
      '{"path":"b.css","content":"body{color:#ff';
    const r = разобрать(обрыв);
    expect(r.mode, "целые файлы из обрыва не спасены").toBe("salvaged");
    expect(r.files[0].path).toBe("a.html");
  });
});
