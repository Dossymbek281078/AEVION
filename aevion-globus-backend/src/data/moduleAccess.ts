/** Строка таблицы по идентификатору модуля, либо null. */
export function доступМодуля(moduleId: string): ДоступМодуля | null {
  const ключ = moduleId.trim().toLowerCase();
  return ДОСТУП_МОДУЛЕЙ.find((м) => м.moduleId.toLowerCase() === ключ) ?? null;
}

/** Продаём ли модуль отдельно — по ЗАМЫСЛУ. Состояние кассы спрашивают у кассы. */
export function продаётсяОтдельно(moduleId: string): boolean {
  return доступМодуля(moduleId)?.продаётся === true;
}

/**
 * Модули, у которых стена включена ПО ДАННЫМ.
 *
 * Это значение по умолчанию для planGate: переменная сервиса PAYWALL_MODULES
 * по-прежнему сильнее (аварийный рычаг, им же гасили ошибочное включение
 * qcoreai 16.07). На 01.10 данные и переменная СОВПАДАЮТ, поэтому чтение
 * любой стороной даёт один ответ — это проверяет сторож moduleAccessMatchesProd.
 */
export function модулиСоСтенойПоДанным(): string[] {
  return ДОСТУП_МОДУЛЕЙ.filter((м) => м.стена).map((м) => м.moduleId);
}

export interface РасхожденияДоступа {
  /** Продаётся, но ничем не закрыто: купивший получает то, что и так бесплатно. */
  продаётсяБезСтены: string[];
  /** Закрыто, но отдельно не продаётся: отказ без предложения. */
  стенаБезПродажи: string[];
  /** Продаётся И закрыто — то, ради чего всё это и делается. */
  оплатаОткрывает: string[];
  /** Сколько строк проверено: ноль охвата у отчёта означает дефект отчёта. */
  проверено: number;
}

/**
 * Отчёт расхождений. Печатается скриптом scripts/module-access-report.mjs и
 * проверяется сторожем — именно он отвечает на вопрос «что оплата открывает».
 */
export function расхожденияДоступа(): РасхожденияДоступа {
  return {
    продаётсяБезСтены: ДОСТУП_МОДУЛЕЙ.filter((м) => м.продаётся && !м.стена).map((м) => м.moduleId),
    стенаБезПродажи: ДОСТУП_МОДУЛЕЙ.filter((м) => !м.продаётся && м.стена).map((м) => м.moduleId),
    оплатаОткрывает: ДОСТУП_МОДУЛЕЙ.filter((м) => м.продаётся && м.стена).map((м) => м.moduleId),
    проверено: ДОСТУП_МОДУЛЕЙ.length,
  };
}

/**
 * Список приложений для витрины: цена из прайса, право продавать — из таблицы
 * доступа. Ручка `/api/pricing` берёт список ТОЛЬКО отсюда, чтобы «продаётся»
 * существовало в одном экземпляре.
 *
 * ⚠️ Честная граница этой проверки. На 01.10 все девять строк прайса помечены
 * `продаётся: true`, поэтому обход этой функции даёт ТОТ ЖЕ ответ — отличить
 * обход от настоящего вызова по выводу ручки сегодня невозможно никаким тестом
 * (мутация «убрать вызов» законно не ловится). Поэтому сам механизм проверяется
 * отдельно: сторож зовёт функцию с подставной таблицей, где флаг снят, и
 * убеждается, что приложение из выдачи исчезает. Как только основатель снимет
 * флаг у настоящего модуля, обход поймает и сторож на живую ручку.
 *
 * Параметры с умолчаниями — не украшение, а единственный способ проверить
 * поведение, не правя боевые данные.
 */
export function приложенияДляВитрины(
  доступ: ДоступМодуля[] = ДОСТУП_МОДУЛЕЙ,
  прайс: StandaloneApp[] = STANDALONE_APPS,
): StandaloneApp[] {
  const можно = new Set(
    доступ.filter((м) => м.продаётся).map((м) => м.moduleId.toLowerCase()),
  );
  return прайс.filter((a) => можно.has(a.moduleId.toLowerCase()));
}

/**
 * Сверка с прайсом. Связь НЕСИММЕТРИЧНА, и это не упущение:
 *
 *   продаётся  ⇒  цена есть        — обязательно; иначе продаём непонятно что;
 *   цена есть  ⇒  продаётся        — НЕ обязательно с 01.10.2026.
 *
 * Вторая половина была обязательной до 01.10. Её пришлось снять, когда четыре
 * модуля сняли с продажи: цены у них верные и нужны, а продавать их нечем, пока
 * нет своего товара в кассе. Ослабление инварианта названо здесь прямо, чтобы
 * его нельзя было принять за забывчивость, и каждый такой модуль обязан быть
 * перечислен в `сЦенойНоНеПродаются` — молчаливого «ну и ладно» тут нет.
 */
export function расхожденияСПрайсом(): { безЦены: string[]; сЦенойНоНеПродаются: string[] } {
  const вПрайсе = new Set(STANDALONE_APPS.map((a) => a.moduleId.toLowerCase()));
  const продаём = ДОСТУП_МОДУЛЕЙ.filter((м) => м.продаётся).map((м) => м.moduleId.toLowerCase());
  return {
    безЦены: продаём.filter((id) => !вПрайсе.has(id)),
    сЦенойНоНеПродаются: [...вПрайсе].filter((id) => !продаём.includes(id)),
  };
}

/**
 * Модули, которые мы объявили продаваемыми, а своего товара в кассе у них НЕТ.
 *
 * 🔴 Правило, закрывающее класс навсегда: продавать модуль можно ТОЛЬКО через
 * его собственный вариант. Пока своего нет, покупка идёт вариантом планеты, и
 * страница оплаты обещает цену планеты — замер 01.10.2026 на живой кассе:
 * «$400.00 billed every month» при модуле за $24. Контроль того же дня: DevHub
 * со своим товаром показывает «200,00 $ / $200.00», числа совпадают.
 *
 * ТРИ ИСХОДА, а не два, и это принципиально. Признак своего товара читается из
 * переменных окружения; в тестах и на машине разработчика их нет, и тогда
 * ответ «список пуст» был бы ЛОЖНЫМ успокоением — ровно тот «зелёный при нуле
 * охвата», который мы считаем дефектом сторожа. Поэтому:
 *   null            — касса не настроена, ОТВЕТА НЕТ (не «всё хорошо»);
 *   []              — всё продаваемое имеет свой товар;
 *   [имена…]        — вот кого продавать нельзя.
 */
export function продаваемыеБезСвоегоТовара(): string[] | null {
  if (!lemonSqueezyTiersConfigured()) return null;
  const плохие: string[] = [];
  for (const м of ДОСТУП_МОДУЛЕЙ) {
    if (!м.продаётся) continue;
    const app = STANDALONE_APPS.find((a) => a.moduleId.toLowerCase() === м.moduleId.toLowerCase());
    if (!app) continue; // это ловит расхожденияСПрайсом, здесь другой вопрос
    // Свой товар — это вариант под ЭТО приложение, а не вариант планеты.
    const свой = TERM_TIERS.some((t) => resolveLemonSqueezyVariant(`app_${app.slug}_${t}`));
    if (!свой) плохие.push(м.moduleId);
  }
  return плохие;
}
