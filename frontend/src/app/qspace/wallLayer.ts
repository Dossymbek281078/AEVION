/**
 * Какой слой чертежа — стены. ОДНО правило на DXF и PDF.
 *
 * Слой — самый надёжный признак стены, какой вообще есть в чертеже: CAD-программа
 * хранит его у каждой линии, а человек сам разложил стены, размеры и мебель по
 * разным слоям. Угадывание по длине или толщине линии этого не заменяет.
 *
 * Правило живёт здесь, а не в каждом разборщике: два способа решать одно и то
 * же расходятся молча. До 14.09.2026 оно было только в разборе DXF, а PDF слоёв
 * не читал вовсе.
 *
 * Штриховка стен исключена. Настоящий план из AutoCAD (LA VIE, planirovka.kz)
 * держит заливку стен на слое «A-WALL-PATT»: 1122 короткие косые черты внутри
 * толщины стены. По имени это «wall», и прежнее правило взяло бы их стенами —
 * модель получила бы тысячу косых перегородок. Штриховка рисует ВНУТРЕННОСТЬ
 * стены, а не её грань.
 */
const СТЕНА = /(wall|стен|перегород|w-|a-wall)/i;
const ШТРИХОВКА = /(patt|hatch|штрих)/i;

export function isWallLayer(name: string): boolean {
  return СТЕНА.test(name) && !ШТРИХОВКА.test(name);
}
