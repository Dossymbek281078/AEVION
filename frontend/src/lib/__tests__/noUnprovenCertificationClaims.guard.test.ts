/*
 * Сертификация, которой у нас нет, не обещается в витрине.
 *
 * 🔴 Повод 01.10.2026. Публичная ручка /api/pricing отдавала у тарифа Enterprise
 * строку с пакетом двух международных сертификатов, а страница «Банкам» обещала
 * весь контур под ними. Сертификатов нет: на нашей же странице безопасности
 * статус читался «контроли внедрены, аудит не пройден» — две поверхности
 * платформы утверждали противоположное, и там же предлагалось «запросить полный
 * отчёт Type II», которого не может существовать.
 *
 * Для компании, которая продаёт ДОКАЗАТЕЛЬСТВО авторства, ложное заявление о
 * сертификации бьёт по самому товару: покупателю нечем отличить наше «мы
 * сертифицированы» от нашего же «вот доказательство, что документ ваш».
 *
 * ГРАНИЦА СТОРОЖА НАМЕРЕННАЯ. Запрещено в ОБЕЩАНИЯХ — в тарифах и в отраслевых
 * доводах. Разрешено там, где термин ОБЪЯСНЯЮТ или честно называют статус:
 * глоссарий и карточки состояния на странице безопасности. Иначе сторож краснел
 * бы на верном тексте «аудит не пройден», а такие проверки отключают.
 */
import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const ЦЕНЫ_БЭКЕНД = join(ЗДЕСЬ, "..", "..", "..", "..", "aevion-globus-backend", "src", "data", "pricing.ts");
const ЯЗЫКИ = ["ru", "en", "kk"] as const;

/*
 * Заявление о соответствии в любом написании.
 *
 * Шесть терминов добавлены 01.10.2026 по правилу «утверждаем только то, что можем
 * доказать»: SOC 2 и ISO 27001 — аудит не пройден; GDPR — независимого аудита нет
 * (проверяемы только политика и удаление по запросу); 152-ФЗ — локализации данных
 * в РФ у нас нет; PCI DSS — карточные данные к нам не попадают, их принимает касса
 * провайдера, и это надо писать именно так, а не словом «соответствуем».
 */
const ЗАЯВЛЕНИЕ = /soc[ -]?2|iso[ -]?27001|gdpr|152-??[ФFфf][ЗZзz]|pci ?dss/i;

/** Ключи, где обещают продукт. Глоссарий и статус соответствия сюда НЕ входят. */
const ОБЕЩАНИЯ = ["pricing.tierDetail.", "pricing.forIndustry."];

function словарь(язык: string): Array<[string, string]> {
  const src = readFileSync(join(ЗДЕСЬ, "..", "i18n-lang", `${язык}.ts`), "utf8");
  const пары: Array<[string, string]> = [];
  for (const строка of src.split("\n")) {
    const m = /^\s*"([^"]+)":\s*"(.*)",?\s*$/.exec(строка);
    if (m) пары.push([m[1], m[2]]);
  }
  return пары;
}

describe("витрина не обещает сертификации, которой нет", () => {
  it("контроль прибора: словари читаются и образец находит заявление", () => {
    for (const язык of ЯЗЫКИ) {
      const пары = словарь(язык);
      expect(пары.length, `словарь ${язык} не прочитался — сторож ослеп`).toBeGreaterThan(5000);
      expect(
        пары.some(([k]) => k.startsWith("pricing.tierDetail.audience.enterprise.")),
        `ключи тарифа Enterprise не найдены в ${язык} — проверять было нечего`,
      ).toBe(true);
    }
    // Положительный контроль: образец обязан ловить все написания.
    for (const обр of ["SOC2", "SOC 2", "soc-2", "ISO27001", "ISO 27001", "GDPR", "gdpr", "152-ФЗ", "152-FZ", "PCI DSS", "PCIDSS"]) {
      expect(ЗАЯВЛЕНИЕ.test(обр), `образец не ловит «${обр}»`).toBe(true);
    }
    // Отрицательный контроль: соседние термины НЕ должны ловиться.
    expect(ЗАЯВЛЕНИЕ.test("eIDAS, TSP и NDA / DPA / MSA")).toBe(false);
  });

  it("в обещаниях тарифов и отраслей сертификации нет — на всех языках", () => {
    const виновные: string[] = [];
    let проверено = 0;
    for (const язык of ЯЗЫКИ) {
      for (const [ключ, значение] of словарь(язык)) {
        if (!ОБЕЩАНИЯ.some((п) => ключ.startsWith(п))) continue;
        проверено += 1;
        if (ЗАЯВЛЕНИЕ.test(значение)) виновные.push(`${язык}: ${ключ} = ${значение.slice(0, 70)}`);
      }
    }
    expect(проверено, "ни одного ключа обещаний не проверено — сторож пуст").toBeGreaterThan(100);
    expect(виновные, `проверено ключей обещаний: ${проверено}`).toEqual([]);
  });

  it("цены бэкенда — источник правды витрины — тоже чисты", () => {
    const src = readFileSync(ЦЕНЫ_БЭКЕНД, "utf8");
    expect(src.length, "файл цен не прочитался").toBeGreaterThan(1000);
    const строки = src.split("\n").filter((л) => ЗАЯВЛЕНИЕ.test(л));
    expect(строки, "обещание сертификации вернулось в тарифы").toEqual([]);
  });
});
