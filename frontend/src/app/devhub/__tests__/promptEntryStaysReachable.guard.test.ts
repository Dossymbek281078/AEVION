import { describe, test, expect } from "vitest";
import { DEVHUB_DICT } from "../i18n";

/**
 * Замер 09.09.2026, накануне запуска, живой прод, поле «опишите идею»:
 *
 *   360×640  поле на 879px — ПОД СГИБОМ
 *   390×844  поле на 831px — видно, но запас 13 пикселей
 *   412×915  831px — видно
 *   1280×900 491px — видно
 *
 * То есть prompt-first вход (правило продукта: модуль открывается промтом
 * «опиши — сделаю», а не инвентарём) на типичном телефоне держится на
 * тринадцати пикселях: одна лишняя строка текста — и он уезжает за экран у
 * большинства посетителей.
 *
 * Арифметика первого экрана на 360px: 218 общая шапка сайта + 193 навигация
 * модуля + 42 заголовок + 68 подзаголовок шапки + 41 кнопка + 60 заголовок
 * промпт-блока + 122 его подзаголовок. Из этого в моей зоне — два текста.
 *
 * Сокращён самый длинный (230 → 169 знаков ru). Дальше сокращать нельзя:
 * попытка убрать хвост про Visual Edit уронила сторожа
 * visualEditPromiseIsHonest, и он был ПРАВ — без оговорки «после деплоя»
 * обещание правки кликами становится нечестным.
 *
 * Порог 200 знаков — не вкус: на 360px строка вмещает ~45 знаков и занимает
 * ~22px, то есть каждые 45 знаков сверх нынешних 169 стоят строки экрана.
 * 200 оставляет запас в одну строку и краснеет раньше, чем поле уедет.
 */
const PORÓG = 200;

describe("promt-вход не уезжает под сгиб", () => {
  test("прибор работает: подзаголовок есть во всех трёх языках", () => {
    for (const lang of ["ru", "en", "kk"] as const) {
      expect(DEVHUB_DICT[lang]["hero.subtitle"].length, `${lang}: подзаголовка нет`).toBeGreaterThan(40);
    }
  });

  test("подзаголовок промпт-блока не отрастает обратно", () => {
    for (const lang of ["ru", "en", "kk"] as const) {
      const v = DEVHUB_DICT[lang]["hero.subtitle"];
      expect(
        v.length,
        `${lang}: ${v.length} знаков — каждые 45 сверх этого уводят поле ввода ещё на строку вниз`,
      ).toBeLessThanOrEqual(PORÓG);
    }
  });

  test("оговорка про деплой осталась — иначе обещание правки кликами нечестно", () => {
    expect(DEVHUB_DICT.ru["hero.subtitle"], "ru: пропала оговорка").toMatch(/после деплоя|после публикации/);
    expect(DEVHUB_DICT.en["hero.subtitle"], "en: пропала оговорка").toMatch(/after deploy/i);
  });

  test("подзаголовок шапки не отрастает: он второй по величине кусок", () => {
    for (const lang of ["ru", "en", "kk"] as const) {
      expect(DEVHUB_DICT[lang]["hero.sub"].length, `${lang}: подзаголовок шапки вырос`).toBeLessThanOrEqual(150);
    }
  });
});
