/**
 * Число из строки запроса, которое НЕ может оказаться NaN.
 *
 * Зачем отдельная функция. `Number(req.query.limit ?? 50)` выглядит защищённым
 * — умолчание же есть. Но `??` ловит только null и undefined, а `?limit=zzz`
 * даёт строку: `Number("zzz")` = NaN. Дальше NaN проходит сквозь любой зажим,
 * потому что `Math.min(NaN, 200)` и `Math.max(NaN, 1)` — тоже NaN, и уезжает
 * в `LIMIT $1`. Postgres отвечает ошибкой, наружу уходит 500 и запись в Sentry
 * — на запрос, который целиком неверен со стороны клиента (см. правило 15г:
 * 5xx поднимает людей и хоронит настоящие аварии в шуме).
 *
 * Там, где значение не доезжает до СУБД, NaN не падает, а молчит: `slice(0, NaN)`
 * возвращает пустой массив, и человек видит «ничего не найдено» вместо данных.
 * Это тише и потому хуже.
 *
 * Замер 19.08.2026: таких мест было 14 в пяти файлах. Два соседних файла уже
 * закрывали дыру проверкой `Number.isFinite` вручную — идиом взят оттуда, чтобы
 * не заводить третий способ делать одно и то же.
 *
 * Обрезки до целого здесь НЕТ намеренно: часть вызовов передаёт дробные
 * (радиус в километрах), и округление сменило бы им поведение.
 */
export function queryNumber(raw: unknown, fallback: number): number {
  if (raw === null || raw === undefined) return fallback;
  // Массив приходит на ?limit=1&limit=2 — Number([...]) даёт NaN, а не первое
  // значение. Берём первое: так же ведут себя обработчики, читающие строку.
  const one = Array.isArray(raw) ? raw[0] : raw;
  // Пустая строка и одни пробелы — это «параметр не передан», а не ноль:
  // Number("") и Number("   ") дают 0, и ?limit= молча отдавал бы пустую
  // страницу вместо страницы по умолчанию.
  if (typeof one === "string" && one.trim() === "") return fallback;
  const n = Number(one);
  return Number.isFinite(n) ? n : fallback;
}
