import { describe, expect, test } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

import { MEDIUM_BUNDLE } from "../src/data/pricing";

// Обещание про тариф на посадочной обязано совпадать с составом тарифа — 20.08.2026.
//
// Посадочная мультичата говорит: «Отдельной подписки на модуль пока нет — он входит
// в тарифы Medium и Full». Проверено фактом: `multichat-engine` действительно в
// MEDIUM_BUNDLE, а тот входит в medium, full и enterprise. То есть сегодня правда.
//
// Зачем сторож. Связь держится на честном слове в ДВУХ файлах разных половин
// репозитория: уберут модуль из набора — и страница продолжит обещать тариф,
// которого он больше не даёт. Человек заплатит за Medium и не найдёт купленного.
// Это тот же класс, что я поймал у себя часом раньше: текст страницы обещал одно,
// метаданные — другое.
//
// Направление проверки: обещание → факт. Уберут фразу со страницы — сторож молчит,
// потому что обещания больше нет и сторожить нечего. Так он не мешает менять текст
// и не наказывает за отказ от обещания.

const PAGES = [
  {
    module: "multichat-engine",
    page: join(__dirname, "..", "..", "frontend", "src", "app", "multichat-engine", "launch", "page.tsx"),
  },
];

/** Фраза про включение в тарифы — в любом из встречающихся написаний. */
// Кириллица и `\w` несовместимы: в JS `\w` — это [A-Za-z0-9_], поэтому «вход\w*»
// НЕ совпадает с «входит», и первая версия шаблона дала ложный ноль. Поймал
// отрицательный контроль, для этого он и стоит. Класс записан в памяти
// (feedback_regex_word_boundary_cyrillic) и повторяется у меня раз в несколько дней.
const TIER_CLAIM = /вход[а-яё]*\s+в\s+тариф[а-яё]*\s+Medium\s+и\s+Full/i;

describe("обещание про тариф совпадает с составом тарифа", () => {
  test("прибор находит обещание там, где оно есть", () => {
    // Отрицательный контроль: без него «обещания нет» читалось бы как «всё сходится»,
    // а на деле означало бы, что я не умею его найти (шаблон, регистр, кириллица).
    const src = readFileSync(PAGES[0].page, "utf8");
    expect(
      TIER_CLAIM.test(src),
      "Фразу про тарифы на странице не нашёл. Возможны ровно две причины, и они " +
        "требуют разного:\n" +
        "  • обещание переписали другими словами — поправьте TIER_CLAIM, иначе " +
        "сторож молча перестанет проверять;\n" +
        "  • обещание убрали НАМЕРЕННО (появилась отдельная подписка) — тогда " +
        "удалите и этого сторожа, ему больше нечего охранять.\n" +
        "Красное здесь означает «подтвердите, что так и хотели», а не «сломано».",
    ).toBe(true);
  });

  test.each(PAGES)("$module: обещанный тариф действительно включает модуль", ({ module, page }) => {
    const src = readFileSync(page, "utf8");
    if (!TIER_CLAIM.test(src)) return; // обещания нет — сторожить нечего
    expect(
      MEDIUM_BUNDLE,
      `страница обещает Medium и Full, но «${module}» нет в MEDIUM_BUNDLE — ` +
        `покупатель заплатит и не найдёт купленного`,
    ).toContain(module);
  });

  test("контроль: модуль вне набора обещание не подтверждает", () => {
    // Проверяем сам критерий, а не только его результат: иначе toContain мог бы
    // проходить на любом непустом списке.
    expect(MEDIUM_BUNDLE).not.toContain("qventure-aevia-not-in-bundle");
    expect(MEDIUM_BUNDLE.length).toBeGreaterThan(3);
  });
});
