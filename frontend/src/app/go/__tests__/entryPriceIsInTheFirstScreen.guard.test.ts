import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { STANDALONE_APPS, termPricePerMonth } from "@/lib/termPricing";

/**
 * НА ПОСАДОЧНОЙ СОЦСЕТЕЙ ЕСТЬ ЦЕНА ВХОДА И ССЫЛКА НА КАРТОЧКУ.
 *
 * Повод 30.09.2026. `/ig`, `/li` и `/bs` ведут на ОДИН адрес `/go`. Замер на
 * 390 px: пути к покупке в первом экране не было вовсе, единственная ссылка на
 * цены стояла последней (2.8 экрана из 3.4) и называла «от $200/мес · от $400
 * за месяц» — самое большое наше число. Воронка за сутки: из Instagram до цен
 * дошли 2 из 62, из LinkedIn 0 из 18, при 28 % у прямых заходов.
 *
 * Проверка читает ИСХОДНИК, а не отрисовку: страница серверная и тянет данные
 * из нескольких ручек, поднимать её в стенде ради одной строки дорого.
 * Положение на экране меряется браузером на проде — здесь держатся три вещи:
 * строка есть, цена берётся из общего списка (а не вписана руками), ссылка
 * ведёт на существующий слаг и несёт метку канала.
 */

const ИСХОДНИК = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");

describe("посадочная /go: цена входа", () => {
  it("строка входа стоит в шапке, до бесплатных разделов", () => {
    const шапка = ИСХОДНИК.indexOf("</header>");
    const строка = ИСХОДНИК.indexOf("Нужен инструмент сразу?");
    expect(строка, "строки входа нет вовсе").toBeGreaterThan(0);
    expect(строка, "строка входа ушла из первого экрана (ниже шапки)").toBeLessThan(шапка);
  });

  it("цена берётся из общего списка, а не вписана руками", () => {
    expect(
      ИСХОДНИК.includes("termPricePerMonth(ВХОД.baseMonthly"),
      "цена посчитана не из STANDALONE_APPS — разойдётся с /pricing при первой правке",
    ).toBe(true);
    const вход = STANDALONE_APPS.find((a) => a.slug === "multichat")!;
    const цена = termPricePerMonth(вход.baseMonthly, "lite");
    // Контроль осмысленности: цена входа не ноль и не равна цене планеты.
    expect(цена).toBeGreaterThan(0);
  });

  it("ссылка ведёт на СУЩЕСТВУЮЩИЙ слаг и несёт метку канала", () => {
    // Слаг сверяем со списком: оркестратор называл `multichat-engine`, а
    // карточка на /pricing помечена `multichat` — неверный слаг дал бы ссылку
    // в никуда, и это заметили бы только по нулям в воронке.
    expect(STANDALONE_APPS.some((a) => a.slug === "multichat")).toBe(true);
    expect(
      ИСХОДНИК.includes('keep(`/pricing?app=${ВХОД.slug}#apps`)'),
      "ссылка без keep(): метка канала потеряется ровно на переходе к покупке",
    ).toBe(true);
  });
});
