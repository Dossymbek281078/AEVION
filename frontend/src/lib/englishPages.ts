/*
 * ОДИН список английских страниц — и для middleware, и для самих страниц.
 *
 * 🔴 Повод: бесконечная переадресация на проде 01.10.2026. Замер с курлом:
 *   /longevity с кукой aevion_lang_v1=en → 307 /en/longevity → 308 /longevity → …
 *   шесть шагов и снова 307; без куки 200. То же у /qskyway.
 *   Контроль: /go и /shop с той же кукой — один шаг и 200.
 *
 * Причина — два РАЗНЫХ набора. Страница решала «у гостя английская кука, уведу на
 * /en/<имя>», а middleware знал отдельный список адресов, у которых английская
 * версия ЕСТЬ, и всё остальное возвращал обратно. Пока наборы совпадали, круг не
 * замыкался; как только страница ушла вперёд списка — посетитель попал в петлю.
 *
 * Цена ошибки конкретная: на /longevity пришли ОБА платежа за всё время, а
 * английская кука ставится на год при любом заходе по англоссылке.
 *
 * Поэтому список один и живёт здесь. Страница спрашивает `hasOwnEnglishPage`
 * перед тем, как уводить, middleware — перед тем, как возвращать. Разойтись им
 * больше негде.
 */
export const АНГЛИЙСКИЕ_СТРАНИЦЫ_СО_СВОИМ_АДРЕСОМ = [
  "/en/devhub",
  "/en/devhub/launch",
  "/en/shop",
  "/en/go",
];

/** Есть ли у этого английского адреса своя страница. Сравнение без регистра. */
export function hasOwnEnglishPage(путь: string | null | undefined): boolean {
  const п = String(путь ?? "").trim().toLowerCase();
  if (!п) return false;
  return АНГЛИЙСКИЕ_СТРАНИЦЫ_СО_СВОИМ_АДРЕСОМ.includes(п);
}

/**
 * Куда уводить англоязычного гостя с русского адреса — или null, если уводить
 * НЕКУДА и он остаётся здесь.
 *
 * Именно отсутствие этой проверки и замыкало круг: страница уводила на адрес,
 * которого нет, а middleware возвращал обратно.
 */
export function englishVersionFor(путь: string | null | undefined): string | null {
  const п = String(путь ?? "").trim();
  if (!п.startsWith("/")) return null;
  const кандидат = "/en" + (п === "/" ? "" : п);
  return hasOwnEnglishPage(кандидат) ? кандидат : null;
}
