import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Дата на /go совпадает с датой посадочной страницы запуска.
 *
 * В самом файле /go стоял комментарий «дата и содержание совпадают с
 * посадочной» — обещание без проверки. 30.08.2026 оно оказалось ложным:
 * запуск перенесли на 30 сентября, посадочную поправили, а /go продолжал
 * обещать 30 августа. Это самая видная страница платформы: единственная
 * кликабельная ссылка в шапках соцсетей.
 *
 * Сторож сверяет две страницы МЕЖДУ СОБОЙ и не знает «правильной» даты —
 * значит переживёт следующий перенос и покраснеет только на расхождении.
 */
const read = (p: string) => readFileSync(join(process.cwd(), p), "utf8");

/** Дата после слова-маркера, позиционно: собранный из строки шаблон здесь уже терял слэши. */
function dateAfter(src: string, marker: string): string | null {
  const i = src.indexOf(marker);
  if (i < 0) return null;
  const tail = src.slice(i + marker.length, i + marker.length + 40);
  const cut = tail.split("<")[0].split('"')[0].trim();
  return cut.length > 3 ? cut : null;
}

describe("дата запуска одна на всех страницах", () => {
  // ПЕРЕПИСАНО 30.08.2026 вечером, после смены плана основателем.
  //
  // Прежняя редакция сверяла дату карточки /go с посадочной шахмат — потому
  // что карточка «Ближайший запуск» была про шахматы. Планом от 30.08
  // ближайший запуск стал другим (10 сентября, семь модулей), карточка
  // переехала на него, и сравнение потеряло предмет: у семи модулей нет
  // общей посадочной.
  //
  // Выключать сторожа нельзя — молчащая проверка хуже отсутствующей.
  // Поэтому он теперь стережёт ДВА свойства, которые от плана не зависят:
  //   1) если /go называет шахматы с датой, она совпадает с посадочной;
  //   2) /go вообще называет какую-то дату — карточка без даты бесполезна.
  test("если /go называет дату шахмат, она совпадает с посадочной", () => {
    const go = read("src/app/go/page.tsx");
    const i = go.indexOf("CyberChess");
    if (i < 0) return; // шахмат на /go нет — сверять нечего
    const near = go.slice(i, i + 120);
    const goDate = dateAfter(near, "открываем ");
    if (!goDate) return; // упомянуты без даты — тоже законно
    const landing = dateAfter(read("src/app/cyberchess/launch/page.tsx"), "Открываем ");
    expect(goDate, `посадочная обещает «${landing}», а /go про шахматы — «${goDate}»`)
      .toBe(landing);
  });

  test("карточка ближайшего запуска называет дату", () => {
    const src = read("src/app/go/page.tsx");
    const kicker = dateAfter(src, 'kicker="');
    expect(kicker, "у карточки запуска нет подписи").toBeTruthy();
    // Мутация показала, что «непустая подпись» — не проверка: «скоро · семь
    // модулей» её проходило. Требуем НАЗВАНИЕ МЕСЯЦА: обещание без даты
    // человеку ничего не говорит, а «скоро» не устаревает и потому не чинится.
    const MONTHS = ["январ", "феврал", "март", "апрел", "ма", "июн", "июл",
                    "август", "сентябр", "октябр", "ноябр", "декабр"];
    expect(
      MONTHS.some((m) => String(kicker).includes(m)),
      `подпись карточки «${kicker}» не называет месяц — это не дата`,
    ).toBe(true);
  });
});
