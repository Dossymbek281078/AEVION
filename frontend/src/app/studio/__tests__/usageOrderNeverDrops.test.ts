import { describe, test, expect } from "vitest";
import { CAP_META, порядокПоказа } from "../usageOrder";

/**
 * Полосы остатка на /studio: ни одна возможность не теряется молча.
 *
 * Замер 02.09.2026: страница перечисляла пять полос вручную, а её тип
 * объявлял ровно пять ключей. Две новые возможности начали списываться и не
 * показывались вовсе — человек тратит квоту, которой не видит. У страницы при
 * этом НЕ БЫЛО НИ ОДНОГО теста, хотя именно она показывает платящему остаток.
 *
 * Проверяется ПОВЕДЕНИЕ, а не разметка: страница клиентская, состояние в неё
 * при статической отрисовке не подложить, а порядок показа — чистая функция.
 */
describe("порядок полос остатка", () => {
  test("прибор исправен: список подписей непуст", () => {
    // Контроль охвата: на пустом CAP_META все утверждения ниже прошли бы
    // впустую — самый частый вид ложного зелёного.
    expect(Object.keys(CAP_META).length).toBeGreaterThan(4);
  });

  test("известные возможности идут в заданном порядке", () => {
    const usage = { deploy: {used:0,limit:1}, video: {used:0,limit:1}, image: {used:0,limit:1} };
    // Порядок берётся из CAP_META, а НЕ из порядка ключей ответа сервера:
    // иначе экран перестраивался бы от того, как база вернула строки.
    expect(порядокПоказа(usage as never)).toEqual(["video", "image", "deploy"]);
  });

  test("НЕЗНАКОМАЯ возможность показывается, а не пропадает", () => {
    // Главное утверждение файла. Спрятать списываемую возможность хуже, чем
    // показать её некрасиво: человек хотя бы увидит, что у него что-то
    // расходуется, и спросит.
    const usage = { video: {used:0,limit:1}, чтотоНовое: {used:0,limit:1} };
    const порядок = порядокПоказа(usage as never);
    expect(порядок, "новая возможность исчезла с экрана").toContain("чтотоНовое");
    expect(порядок[порядок.length - 1]).toBe("чтотоНовое");
  });

  test("возможность из подписей, которой нет в ответе, не рисуется пустой полосой", () => {
    // Обратная сторона: подпись есть, данных нет — полоса «0 из 0» соврала бы
    // о наличии возможности.
    expect(порядокПоказа({ video: {used:0,limit:1} } as never)).toEqual(["video"]);
  });
});

import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Расход покупателя не исчезает с экрана молча.
 *
 * Прямая задача основателя 03.09.2026: «открою кабинет как покупатель и увижу,
 * сколько потратили мои запуски». Строку легко убрать при следующей правке
 * вёрстки, и никто не заметит — задача перестанет быть выполненной тихо.
 *
 * Сторож читает исходник: страница клиентская, состояние в неё при статической
 * отрисовке не подложить (пробовал 02.09, потратил два десятка заходов).
 */
describe("расход покупателя показан на экране", () => {
  const страница = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");

  test("прибор исправен: файл страницы прочитан", () => {
    expect(страница.length, "страница не прочитана — сторож охраняет пустоту").toBeGreaterThan(2000);
  });

  test("страница спрашивает расход у ручки", () => {
    expect(страница, "запроса расхода нет — показывать нечего").toContain("/api/devhub/studio/spend");
  });

  test("и показывает его человеку, а не кладёт в переменную", () => {
    expect(страница, "ответ получен, но на экран не выведен").toContain("Ваши запуски");
  });

  test("отказ показан отказом, а не нулём", () => {
    // Самое важное: «вы потратили $0» и «посчитать не удалось» — разные
    // утверждения, и первое успокаивает ложно.
    expect(страница, "нет ветки отказа — ноль и незнание сольются").toContain("spendFailed");
    expect(страница, "отказ не объясняет, что это НЕ ноль").toMatch(/не ноль/);
  });
});
