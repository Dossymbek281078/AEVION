import type { RoomRun } from "./rooms";

/**
 * Куда встать камере внутри комнаты и куда смотреть.
 *
 * Замер 30.09.2026 на плане «LA VIE»: «Взгляд изнутри» ставил камеру по
 * формуле «центр комнаты минус отступ по диагонали» — в двух кадрах из трёх
 * больше половины кадра занимала пустая стена вплотную к объективу, потому
 * что центр комнаты (cx, cy) у Г-образной комнаты лежит НЕ в комнате, а
 * смещение всегда шло в одну и ту же сторону (−x, +z). Это и был «вид»,
 * которым модуль показывал себя человеку.
 *
 * Здесь камера ищется по РАЗМЕТКЕ комнаты: стоит в самом открытом месте и
 * смотрит вдоль самого длинного просвета. Обе величины возвращаются числами,
 * поэтому их можно проверить тестом, а не глазами.
 */

export interface ТочкаОбзора {
  /** где стоит камера, в метрах плана */
  x: number;
  y: number;
  /** куда смотрит, в метрах плана */
  целевойX: number;
  целевойY: number;
  /** сколько метров свободно вокруг камеры до ближайшей стены */
  просвет: number;
  /** сколько метров комнаты видно по направлению взгляда */
  дальность: number;
}

/** Шаг разметки комнат — тот же, что в rooms.ts. */
const КЛЕТКА = 0.05;
/** Дальше этого не мерим: жилых комнат длиннее 20 м не бывает. */
const ПРЕДЕЛ_М = 20;

/** Точка внутри комнаты? Полосы заданы по строкам с шагом клетки. */
function создатьПринадлежность(runs: RoomRun[]): (x: number, y: number) => boolean {
  const поСтрокам = new Map<number, Array<[number, number]>>();
  for (const r of runs) {
    const ключ = Math.round(r.y / КЛЕТКА);
    const список = поСтрокам.get(ключ);
    if (список) список.push([r.x0, r.x1]);
    else поСтрокам.set(ключ, [[r.x0, r.x1]]);
  }
  return (x: number, y: number) => {
    const список = поСтрокам.get(Math.round(y / КЛЕТКА));
    if (!список) return false;
    for (const [x0, x1] of список) if (x >= x0 && x <= x1) return true;
    return false;
  };
}

/** Сколько метров можно пройти из точки в направлении, не выйдя из комнаты. */
function пробег(
  внутри: (x: number, y: number) => boolean,
  x: number, y: number, dx: number, dy: number,
): number {
  let d = 0;
  while (d < ПРЕДЕЛ_М) {
    const следующий = d + КЛЕТКА * 2;
    if (!внутри(x + dx * следующий, y + dy * следующий)) break;
    d = следующий;
  }
  return d;
}

/** Просвет вокруг точки: минимальный пробег по четырём сторонам. */
function просветВокруг(внутри: (x: number, y: number) => boolean, x: number, y: number): number {
  if (!внутри(x, y)) return 0;
  return Math.min(
    пробег(внутри, x, y, 1, 0), пробег(внутри, x, y, -1, 0),
    пробег(внутри, x, y, 0, 1), пробег(внутри, x, y, 0, -1),
  );
}

/**
 * Выбрать точку обзора.
 *
 * `шаг` — насколько часто пробуем места (м). 0.25 хватает: нам нужно открытое
 * место, а не точный центр вписанной окружности.
 */
export function точкаОбзора(runs: RoomRun[], шаг = 0.25): ТочкаОбзора | null {
  if (runs.length === 0) return null;
  const внутри = создатьПринадлежность(runs);

  let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
  for (const r of runs) {
    if (r.x0 < minX) minX = r.x0;
    if (r.x1 > maxX) maxX = r.x1;
    if (r.y < minY) minY = r.y;
    if (r.y > maxY) maxY = r.y;
  }

  let лучшая: { x: number; y: number; просвет: number } | null = null;
  for (let y = minY; y <= maxY + 1e-9; y += шаг) {
    // Пробуем ровно по разметке: клетки заданы с шагом КЛЕТКА, и точка между
    // ними не принадлежит ни одной строке — проверка бы всегда отвечала «нет».
    const yк = Math.round(y / КЛЕТКА) * КЛЕТКА;
    for (let x = minX; x <= maxX + 1e-9; x += шаг) {
      const п = просветВокруг(внутри, x, yк);
      if (п > 0 && (!лучшая || п > лучшая.просвет)) лучшая = { x, y: yк, просвет: п };
    }
  }
  if (!лучшая) return null;

  // Куда смотреть: вдоль самого длинного просвета. Шестнадцать направлений —
  // достаточно, чтобы поймать длинную ось комнаты и не смотреть в угол.
  let лучшееНаправление = { dx: 1, dy: 0, длина: 0 };
  for (let i = 0; i < 16; i++) {
    const угол = (i / 16) * Math.PI * 2;
    const dx = Math.cos(угол), dy = Math.sin(угол);
    const длина = пробег(внутри, лучшая.x, лучшая.y, dx, dy);
    if (длина > лучшееНаправление.длина) лучшееНаправление = { dx, dy, длина };
  }

  // Камера отступает НАЗАД вдоль взгляда, пока остаётся в комнате: так в кадр
  // попадает больше комнаты. Отступ маленький — 0.6 м; дальше начинается стена
  // за спиной, и кадр опять упирается в неё.
  const назад = Math.min(0.6, пробег(внутри, лучшая.x, лучшая.y, -лучшееНаправление.dx, -лучшееНаправление.dy));
  const x = лучшая.x - лучшееНаправление.dx * назад;
  const y = лучшая.y - лучшееНаправление.dy * назад;

  // Цель — не сама стена: не доходим до неё полметра, иначе взгляд упирается.
  const доЦели = Math.max(1, назад + лучшееНаправление.длина - 0.5);
  return {
    x, y,
    целевойX: x + лучшееНаправление.dx * доЦели,
    целевойY: y + лучшееНаправление.dy * доЦели,
    просвет: лучшая.просвет,
    дальность: лучшееНаправление.длина,
  };
}
