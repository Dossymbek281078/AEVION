import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { stripComments } from "../../__tests__/helpers/sourceCode";
import { ALL_PRODUCTS } from "@/lib/products";

/**
 * На /go есть САМАЯ ДЕШЁВАЯ книга каталога, с ценой и с меткой канала.
 *
 * ЗАЧЕМ. Замер 20.09.2026: за всё время у AEVION две продажи, и обе — книга
 * за $9.99, самая дешёвая позиция каталога. При этом /go — главный вход
 * воронки, единственная ссылка в шапках соцсетей — показывала только полный
 * пакет за $29.99, а про дешёвую версию говорила словами «есть версии
 * дешевле» со ссылкой в магазин БЕЗ ЦЕНЫ. Единственный товар, который у нас
 * покупают, стоял на переход дальше остальных и без числа.
 *
 * ГРАНИЦА ЧЕСТНО: сторож исходникового уровня. Он утверждает, что карточка
 * НЕ ИСЧЕЗЛА из разметки и что цена с меткой берутся механизмами каталога.
 * Он НЕ утверждает, что на проде она видна человеку — это проверяется
 * браузером или выдачей страницы.
 */
const HERE = dirname(fileURLToPath(import.meta.url));
// Комментарии вырезаем: пояснение выше само содержит и цену, и id, и сторож
// по сырому исходнику остался бы зелёным при УДАЛЁННОЙ карточке.
const src = stripComments(readFileSync(join(HERE, "..", "page.tsx"), "utf8"));

// Товар вычисляем ИЗ КАТАЛОГА, а не вписываем id: подорожает книга или
// появится позиция дешевле — сторож обязан заметить расхождение сам.
const книги = ALL_PRODUCTS.filter((p) => p.kind === "book" && p.billing === "once");
const самаяДешёвая = [...книги].sort((a, b) => a.priceUsd - b.priceUsd)[0];

describe("/go предлагает самую дешёвую книгу каталога", () => {
  it("ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: в каталоге вообще есть разовые книги", () => {
    // Без этого пустой каталог сделал бы все проверки ниже бессмысленно
    // зелёными: «не нашли товар, значит и требовать нечего».
    expect(книги.length).toBeGreaterThan(1);
    expect(самаяДешёвая.priceUsd).toBeGreaterThan(0);
  });

  it("карточка этого товара есть на странице", () => {
    expect(src).toContain(`productById("${самаяДешёвая.id}")`);
    expect(src).toContain("product={bookText}");
  });

  it("цена берётся из каталога, а не вписана числом", () => {
    expect(src).toContain("price={priceOf(bookText)}");
    // Отрицательный контроль: числа цены в разметке быть не должно — иначе
    // страница разойдётся с кассой при первой же правке каталога.
    expect(src).not.toContain(String(самаяДешёвая.priceUsd));
  });

  it("ссылка помечена каналом", () => {
    expect(src).toContain('withChannel(bookText.href, channel, "go")');
  });

  it("полный пакет при этом никуда не делся", () => {
    // Дешёвая книга ДОБАВЛЕНА, а не заменила собой дорогую: замена была бы
    // потерей выручки, а не починкой воронки.
    expect(src).toContain("product={bookFull}");
  });
});
