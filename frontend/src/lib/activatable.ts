import type { KeyboardEvent } from "react";

/**
 * Делает НЕ-кнопку доступной с клавиатуры.
 *
 * Зачем. Замер 28.08.2026 по исходникам: 144 элемента (`div`, `span`, строки
 * таблиц) имеют `onClick` и `cursor: pointer`, но ни роли, ни фокуса, ни
 * обработки клавиш. Мышью нажимается, клавиатурой недостижимо ВООБЩЕ — Tab
 * такие элементы пропускает. Проверенная выборка: строки списка шаблонов в
 * мультичате применяют шаблон и подставляют текст, и добраться до них можно
 * было только мышью.
 *
 * Почему помощник, а не правка на месте. Единого способа в репозитории не
 * было: 121 место обрабатывает Enter вручную и лишь 4 из них — ПРОБЕЛ. То
 * есть «как у соседей» означало бы наполовину сломанное поведение: у
 * настоящей кнопки пробел срабатывает всегда.
 *
 * Правильный вариант всегда — настоящий `<button>`. Помощник нужен там, где
 * кнопкой обернуть нельзя без переделки вёрстки (строки списка, карточки).
 *
 * @param onActivate что сделать при нажатии — мышью, Enter или пробелом
 * @param label      имя для читалки, если внутри нет своего текста
 */
export function activatable(onActivate: () => void, label?: string) {
  return {
    role: "button" as const,
    tabIndex: 0,
    ...(label ? { "aria-label": label } : {}),
    onClick: onActivate,
    onKeyDown: (e: KeyboardEvent) => {
      // Пробел прокручивает страницу — для роли кнопки это надо отменить,
      // иначе нажатие уедет вместе с экраном.
      if (e.key === "Enter" || e.key === " " || e.key === "Spacebar") {
        e.preventDefault();
        onActivate();
      }
    },
  };
}
