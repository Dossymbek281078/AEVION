import { describe, expect, it } from "vitest";
import { mergeDoubleWalls } from "./wallMerge";
import { demoPlan, generateWiring } from "./planModel";
import type { Wall } from "./planModel";

/**
 * Стена, начерченная ДВАЖДЫ.
 *
 * В CAD-файлах линию нередко обводят повторно — при копировании, при правке
 * поверх старого слоя. В модели это невидимо: два одинаковых отрезка рисуются
 * один поверх другого. В расчётах — нет.
 *
 * Замер до правки: одна дублированная стена демо-квартиры давала ТРИ лишние
 * точки электрики (18 против 15), то есть лишние розетки и метры кабеля в
 * смете, которую человек несёт в магазин.
 */
const с = (x1: number, y1: number, x2: number, y2: number): Wall =>
  ({ x1, y1, x2, y2, thickness: 0.2, height: 2.7 });

describe("дублированные стены выбрасываются", () => {
  it("точный дубль убран, остальные целы", () => {
    const r = mergeDoubleWalls([с(0, 0, 8, 0), с(0, 0, 8, 0), с(8, 0, 8, 6)]);
    expect(r.dropped).toBe(1);
    expect(r.walls.length).toBe(2);
  });

  it("дубль, начерченный в ОБРАТНУЮ сторону, тоже убран", () => {
    // при копировании направление часто меняется, а стена та же
    const r = mergeDoubleWalls([с(0, 0, 8, 0), с(8, 0, 0, 0)]);
    expect(r.dropped, "обратный дубль не опознан").toBe(1);
  });

  it("следствие: розетки не удваиваются", () => {
    const p = demoPlan();
    const было = generateWiring(p).points.length;
    const сДублем = { ...p, walls: [...p.walls, { ...p.walls[0] }] };
    // дубли снимаются на импорте, поэтому проверяем через ту же функцию
    const очищенный = { ...сДублем, walls: mergeDoubleWalls(сДублем.walls).walls };
    expect(generateWiring(очищенный).points.length,
      "дубль стены раздул электрику").toBe(было);
  });

  it("контроль: РАЗНЫЕ стены не считаются дублями", () => {
    // иначе «убираем дубли» неотличимо от «убираем всё подряд»
    const r = mergeDoubleWalls([с(0, 0, 8, 0), с(0, 3, 8, 3), с(0, 6, 8, 6)]);
    expect(r.dropped).toBe(0);
    expect(r.walls.length).toBe(3);
  });

  it("контроль: линии в 1 см друг от друга — РАЗНЫЕ, а не дубль", () => {
    // допуск миллиметровый, а не сантиметровый: на чертеже со штриховкой
    // шагом 1 см сантиметровый допуск объявил бы дублями 116 разных линий
    const r = mergeDoubleWalls([с(0, 0, 8, 0), с(0, 0.01, 8, 0.01)]);
    expect(r.dropped, "штриховка принята за дубли").toBe(0);
  });

  it("контроль: сдвиг в 0.5 мм — это шум округления, дубль", () => {
    // граница с другой стороны: пересчёт единиц даёт микросдвиги, и они
    // не должны порождать вторую стену
    const r = mergeDoubleWalls([с(0, 0, 8, 0), с(0, 0.0005, 8, 0.0005)]);
    expect(r.dropped).toBe(1);
  });
});
