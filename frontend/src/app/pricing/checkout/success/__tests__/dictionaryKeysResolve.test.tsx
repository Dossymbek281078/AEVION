/**
 * Каждая подпись, которую просит экран, должна найтись в словаре.
 *
 * Ненайденный ключ у нас не падает и не пустеет — он печатается КАК ЕСТЬ, и так
 * ведут себя ОБА словаря платформы:
 *
 *   i18n.tsx:128        tbl[lang]?.[key] || tbl["en"]?.[key] || key
 *   pricingI18n.ts:1012 (dict[lang] ?? dict.en ?? {})[key] ?? dict.en?.[key] ?? key
 *
 * То есть человек, только что заплативший, увидел бы вместо заголовка строку
 * `pricing.checkoutSuccess.titleActivatedNoTier`.
 *
 * Повод не выдуманный. Словарь платформы существует в двух устройствах: в живой
 * сборке это монолит `i18n-data.ts`, а в ветках будущей сборки он разбит на
 * файлы `i18n-lang`, и монолит там — заглушка. Любая такая миграция переносит
 * ключи, существующие НА МОМЕНТ переноса; добавленные позже уедут молча. Ни
 * типы, ни сборка этого не заметят: падения нет, экран просто печатает ключ.
 *
 * Поэтому сторож спрашивает не словарь, а ЭКРАН: ни один ключ, который просит
 * страница, не должен остаться на нём видимым текстом. От устройства словаря
 * проверка не зависит и переживёт переход.
 */
import { describe, it, expect, vi, afterEach } from "vitest";
import { render, cleanup, act } from "@testing-library/react";
import { readFileSync } from "node:fs";
import { I18nProvider } from "@/lib/i18n";

const параметры = { value: "" };
vi.mock("next/navigation", () => ({
  useSearchParams: () => new URLSearchParams(параметры.value),
  useRouter: () => ({ push: vi.fn(), replace: vi.fn() }),
  usePathname: () => "/pricing/checkout/success",
}));

/**
 * Ключи берём из исходника страницы, а не списком в тесте: список пришлось бы
 * пополнять руками, и он молча отстал бы от страницы — то есть новый ключ, ради
 * которого сторож и написан, как раз остался бы непроверенным.
 *
 * Ищем имя функции перед скобкой, а не подстроку. Первая версия искала `t("` и
 * ошиблась дважды: считала `get("tier")` за вызов перевода, а вызовы `tp("` не
 * видела вовсе — и я на этом основании написал, что экран отмены не переводится.
 * Он переводится, просто вторым словарём.
 *
 * Разбор без регулярных выражений намеренно: одиночная обратная косая теряется
 * на границе вызова инструмента, и шаблон тогда компилируется, но ищет не то.
 */
function ключиИзИсходника(путь: string): string[] {
  const текст = readFileSync(путь, "utf8");
  const частьИмени = (c: string) =>
    (c >= "a" && c <= "z") || (c >= "A" && c <= "Z") || (c >= "0" && c <= "9") || c === "_" || c === "$";
  const открывающая = '("';
  const найденные: string[] = [];
  let i = текст.indexOf(открывающая);
  while (i !== -1) {
    let n = i;
    while (n > 0 && частьИмени(текст[n - 1])) n -= 1;
    const имя = текст.slice(n, i);
    const предыдущий = n > 0 ? текст[n - 1] : " ";
    const от = i + открывающая.length;
    const до = текст.indexOf('"', от);
    const ключ = до > от ? текст.slice(от, до) : "";
    // Переводящих функций две: t() из общего словаря и tp() из словаря цен.
    // Точка перед именем отсекает чужие методы вроде obj.t("...").
    const переводит = имя === "t" || имя === "tp";
    // Ключи словаря у нас всегда с точками; строка без точки — не подпись.
    if (переводит && предыдущий !== "." && ключ.includes(".")) найденные.push(ключ);
    i = текст.indexOf(открывающая, до === -1 ? от : до);
  }
  return Array.from(new Set(найденные));
}

async function открыть(модуль: string, поиск: string) {
  параметры.value = поиск;
  const m = await import(/* @vite-ignore */ модуль);
  const Страница = m.default as () => JSX.Element;
  await act(async () => {
    render(
      <I18nProvider>
        <Страница />
      </I18nProvider>,
    );
  });
}

async function проверить(исходник: string, модуль: string, поиск: string, минимум: number) {
  const ключи = ключиИзИсходника(исходник);
  // Знаменатель обязателен: без него сторож, разучившийся находить ключи,
  // остался бы зелёным и означал бы «проверено ноль штук».
  expect(ключи.length, `ключи со страницы не разобрались: ${исходник}`).toBeGreaterThan(минимум);

  await открыть(модуль, поиск);
  const текст = document.body.textContent ?? "";
  expect(текст, "экран пуст").not.toBe("");
  for (const ключ of ключи) {
    expect(текст, `на экране виден ключ словаря: ${ключ}`).not.toContain(ключ);
  }
}

afterEach(() => cleanup());

describe("подписи экранов после кассы находятся в словаре", () => {
  it("экран оплаты не показывает ключей вместо текста", async () => {
    await проверить(
      "src/app/pricing/checkout/success/page.tsx",
      "@/app/pricing/checkout/success/page",
      "paybox=1&ref=abc&tier=lite&total=4900",
      10,
    );
  }, 60000);

  it("экран отмены не показывает ключей вместо текста", async () => {
    await проверить(
      "src/app/pricing/checkout/cancel/page.tsx",
      "@/app/pricing/checkout/cancel/page",
      "paybox=1&ref=abc&tier=lite&total=4900",
      3,
    );
  }, 60000);
});
