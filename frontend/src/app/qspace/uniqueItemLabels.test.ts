import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * Два одинаковых предмета в сцене обязаны различаться в списке выбора.
 *
 * Найдено 13.09.2026 платформенной проверкой имён (aevion-a11y-names): из 135
 * органов управления страницы без имени не было ни одного, зато нашлось «одно
 * имя у нескольких действий» — «стул», 2 шт. В демо стоят два стула, и обе
 * кнопки назывались просто «Стул».
 *
 * Чем это плохо: выбрать нужный нельзя ни глазом, ни экранным диктором —
 * человек жмёт наугад и смотрит, что подсветилось в 3D. Для читалки это два
 * неразличимых действия подряд.
 *
 * Номер добавляется ТОЛЬКО там, где имя повторяется: единственному стулу
 * номер не нужен и мешал бы — «Стул 1» при одном стуле выглядит как ошибка.
 */
const КЛИЕНТ = readFileSync(path.join(__dirname, "_client.tsx"), "utf8")
  .split(/\r?\n/)
  .filter((строка) => !/^\s*\/\//.test(строка))
  .join(String.fromCharCode(10));

describe("одинаковые предметы различимы в списке", () => {
  it("подпись кнопки считает повторы имени, а не берёт имя как есть", () => {
    expect(КЛИЕНТ, "список снова рисует p.name без номера").toMatch(
      /placed\.filter\(\(q\) => q\.name === p\.name\)\.length/,
    );
    expect(КЛИЕНТ, "номер экземпляра не считается").toMatch(
      /placed\.slice\(0, i \+ 1\)\.filter\(\(q\) => q\.name === p\.name\)\.length/,
    );
  });

  it("номер ставится ТОЛЬКО при повторе — единственному предмету он мешает", () => {
    expect(КЛИЕНТ).toMatch(/сколько > 1 \? `\$\{p\.name\} \$\{номер\}` : p\.name/);
  });

  /**
   * Поведенческая половина: повторяем ту же арифметику на списке имён и
   * проверяем результат. Без неё проверки выше стерегут ФОРМУ кода, а не то,
   * что подписи действительно различаются.
   */
  it("на списке из двух стульев и одного дивана подписи различны", () => {
    const placed = [{ name: "Стул" }, { name: "Диван" }, { name: "Стул" }];
    const подписи = placed.map((p, i) => {
      const сколько = placed.filter((q) => q.name === p.name).length;
      const номер = placed.slice(0, i + 1).filter((q) => q.name === p.name).length;
      return сколько > 1 ? `${p.name} ${номер}` : p.name;
    });
    expect(подписи).toEqual(["Стул 1", "Диван", "Стул 2"]);
    expect(new Set(подписи).size, "подписи повторяются — выбрать нужный нельзя").toBe(3);
  });
});
