import type { Response } from "express";

/**
 * Общий выключатель dev-заглушек.
 *
 * 28.07.2026 на проде жили три заглушки, каждая закрытая не признаком среды, а
 * ОТСУТСТВИЕМ конфига провайдера — то есть fail-open: конфига в проде нет,
 * значит заглушка включена.
 *
 *   • `POST /api/qpaynet/deposit/confirm-stub` — зачисляет депозит, не получив
 *     денег; выключался только настроенным Stripe (`STRIPE_SK` не задан).
 *   • `GET /api/bureau/kyc-stub/:sessionId` — имитирует пройденный KYC;
 *     выключался переменной `BUREAU_KYC_PROVIDER`, которой в проде нет.
 *   • `POST /api/bank/test-webhook/*` — проверки среды не было вообще.
 *
 * Единственной реальной защитой у всех трёх был вход в аккаунт, а регистрация
 * открытая. Тот же класс 26.07.2026 раздавал тариф Universe ($249.99/мес)
 * бесплатно через заглушку чекаута.
 *
 * Правило: заглушка включается ЯВНЫМ разрешением, а не отсутствием чего-то.
 * По умолчанию в проде — выключена.
 */

/** Разрешены ли dev-заглушки в текущей среде. */
export function stubsAllowed(): boolean {
  if (process.env.AEVION_ALLOW_STUBS === "1") return true;
  return process.env.NODE_ENV !== "production";
}

/**
 * Ставится ПЕРВОЙ строкой обработчика заглушки, до любых проверок провайдера и
 * до проверки токена: иначе по коду ответа видно, сработал гейт или нет.
 *
 * @returns `true`, если ответ уже отправлен и обработчику надо остановиться.
 */
export function stubBlocked(res: Response): boolean {
  if (stubsAllowed()) return false;
  res.status(410).json({
    error: "gone",
    message:
      "Dev-заглушка отключена в этой среде. Используйте настоящий платёжный " +
      "или верификационный путь.",
  });
  return true;
}
