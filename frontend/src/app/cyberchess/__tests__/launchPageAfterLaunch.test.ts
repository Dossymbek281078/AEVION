import { describe, expect, test } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Страница запуска не должна спорить сама с собой в день открытия.
 *
 * Замер 29.08.2026: абзац уже умел переключаться («Через N дней» → «Уже
 * открыто»), а заголовок оставался статичным — «Открываем 30 августа». То есть
 * 30 августа шапка обещала бы будущее, а текст под ней сообщал, что всё
 * случилось. Человек верит крупному, и крупное было бы неправдой.
 *
 * Сторож держит именно СВЯЗЬ: если в тексте есть ветка «после запуска», она
 * обязана быть и в заголовке.
 */
const STRANICA = fs.readFileSync(
  path.join(__dirname, "..", "launch", "page.tsx"),
  "utf-8",
);

describe("страница запуска в день открытия", () => {
  test("заголовок переключается вместе с текстом, а не остаётся в будущем времени", () => {
    const h1 = STRANICA.match(/<h1[^>]*>([\s\S]{0,200}?)<\/h1>/);
    expect(h1, "заголовок первого уровня пропал со страницы запуска").not.toBeNull();
    expect(h1![1]).toContain("left > 0");
  });

  test("текст под заголовком тоже знает про день после запуска", () => {
    expect(STRANICA).toContain("Уже открыто");
  });

  test("картинка превью тоже не остаётся в будущем времени", () => {
    // Её видит человек, которому ПЕРЕСЛАЛИ ссылку. 29.08.2026 она говорила
    // «Открываем 30 августа» и от даты не зависела: после запуска превью
    // обещало бы будущее, хотя всё уже случилось.
    const kartinka = fs.readFileSync(
      path.join(__dirname, "..", "launch", "opengraph-image.tsx"),
      "utf-8",
    );
    expect(kartinka).toContain("daysUntilLaunch(");
    expect(kartinka).toContain("Уже открыт");
  });

  test("форма подписки не обещает письмо о прошедшем запуске", () => {
    // 29.08.2026 форма звалась «Написать вам в день запуска» и обещала «одно
    // письмо на запуск». После 30-го это обещание про уже случившееся событие,
    // а форма остаётся полезной — человек может хотеть новостей. Значит текст
    // переключается, а не исчезает.
    expect(STRANICA).toContain('title={left > 0');
    expect(STRANICA).toContain("description={left > 0");
  });

  test("дата берётся общим расчётом, а не своим", () => {
    // Свой расчёт разошёлся бы с остальными страницами на часовой пояс запуска.
    expect(STRANICA).toContain("daysUntilLaunch(");
  });
});
