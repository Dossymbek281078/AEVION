import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Страница проверки сертификата обещала больше, чем знает (28.08.2026).
 *
 * Заголовок был честен — «Номер сертификата корректен»: сверяется ФОРМАТ
 * номера. А предложение под ним утверждало, что сертификат с этим номером
 * «был сгенерирован в модуле AEVION». Реестра страница не спрашивает —
 * обращений к серверу в файле НОЛЬ. Любой выдуманный номер нужного вида
 * давал ту же зелёную галочку и ту же фразу.
 *
 * Опасна именно вторая строка: она конкретнее первой и читается как
 * подтверждение подлинности.
 *
 * Сторож держит границу: пока страница не спрашивает сервер, она не имеет
 * права утверждать факт выдачи. Появится подпись на бэкенде — появится и
 * обращение к серверу, и проверка ниже сама разрешит формулировку.
 *
 * РЕГУЛЯРОК ЗДЕСЬ НЕТ НАМЕРЕННО. Слэши теряются на границе вызова, и тогда
 * файл молча перестаёт разбираться: vitest отвечает «no tests», а это не
 * зелёный и не красный — это молчание, которое выглядит как пройденная
 * проверка. На этом сторож уже один раз сломался, пока его писали.
 */

const PAGE = join(
  dirname(fileURLToPath(import.meta.url)),
  "..", "smeta-trainer", "verify", "[id]", "page.tsx",
);

/** Утверждения о ФАКТЕ выдачи — их нельзя делать без обращения к реестру. */
const ISSUANCE_CLAIMS = [
  "был сгенерирован",
  "был выдан",
  "действительно выдан",
  "подтверждаем подлинность",
];

/**
 * Те же слова встречаются в ЧЕСТНОЙ оговорке («подтвердить, что сертификат
 * действительно выдан, она не может»). Первая версия сторожа на ней и
 * покраснела — то есть кричала на правду, а таких отключают в первый день.
 */
const NEGATIONS = ["не может", "не можем", "не подтвержда", "не спрашивает", "а не подлинност"];

describe("проверка сертификата не утверждает того, чего не знает", () => {
  const src = readFileSync(PAGE, "utf8");

  const affirmative = (claim: string): boolean => {
    let from = 0;
    for (;;) {
      const at = src.indexOf(claim, from);
      if (at < 0) return false;
      const around = src.slice(Math.max(0, at - 160), at + claim.length + 60);
      if (!NEGATIONS.some((n) => around.includes(n))) return true;
      from = at + claim.length;
    }
  };

  it("контроль прибора: файл на месте и это та самая страница", () => {
    expect(src.length).toBeGreaterThan(500);
    expect(src, "не нашёл формат номера — читаю не тот файл").toContain("AEV-СМТ");
    expect(src, "не нашёл честный заголовок").toContain("Номер сертификата корректен");
  });

  it("либо спрашивает сервер, либо не утверждает факт выдачи", () => {
    if (src.includes("fetch(")) return; // появился реестр — утверждать можно
    const claims = ISSUANCE_CLAIMS.filter(affirmative);
    expect(
      claims,
      `страница не обращается к серверу, но утверждает факт выдачи: ${claims.join(", ")}`,
    ).toEqual([]);
  });

  it("прямо называет свой предел, а не молчит о нём", () => {
    const hedged = src.includes("проверка ФОРМАТА") || src.includes("а не подлинност");
    expect(hedged, "нет оговорки, что проверяется формат, а не подлинность").toBe(true);
  });

  it("контроль: прежняя формулировка была бы поймана", () => {
    const old = "Сертификат с этим номером был сгенерирован в модуле AEVION";
    expect(
      ISSUANCE_CLAIMS.some((c) => old.includes(c)),
      "сторож не поймал бы прежний текст — значит список утверждений пуст по делу",
    ).toBe(true);
  });
});
