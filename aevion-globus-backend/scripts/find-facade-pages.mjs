/**
 * Страницы, которые ВЫГЛЯДЯТ работающими, но ни к чему не обращаются.
 *
 * Приём родился 19.08.2026 на живой находке: страница «Chessy Экономика» —
 * 620 строк, кнопки «сделать ставку», «арендовать коуча», «подписаться на
 * стримера», и НОЛЬ обращений к серверу. Все три действия писали только в
 * localStorage: аукцион существовал в одном экземпляре у каждого человека, и
 * ставка никому не была видна. Слов «скоро» или «в разработке» на странице не
 * было.
 *
 * Это родня выдуманных гроссмейстеров в таблице лидеров, но глубже: там
 * выдумка была в данных, здесь — в устройстве страницы.
 *
 * ЧТО СЧИТАЕТ: обращения к серверу в самой странице И в её локальных импортах
 * на один уровень. Один уровень нужен обязательно — первая версия считала по
 * файлу и подняла ложную тревогу на `repertoire`, где запрос живёт в
 * компоненте `OpeningRepertoire`.
 *
 * ЧЕГО НЕ ВИДИТ (говорю прямо, чтобы «ноль находок» не читался как «всё
 * проверено»):
 *   • импорты глубже одного уровня;
 *   • запросы через обёртки, не содержащие слова fetch;
 *   • страницы, которые честно обращаются к серверу, но показывают выдумку.
 * Поэтому вывод — КАНДИДАТЫ, а не приговор: каждую строку открывают глазами.
 *
 * ЗАЧЕМ ОГРАНИЧЕН ОДНИМ МОДУЛЕМ — замер, а не осторожность. Прогон по всей
 * платформе (828 страниц) дал 205 кандидатов, 176 без оговорки. Выборка из
 * шести оказалась тренажёрными упражнениями smeta-trainer: «проверить ответ»,
 * «показать решение», «сбросить». Им сервер не нужен, и никому они ничего не
 * обещают.
 *
 * Попытка отсеять их словарём («аукцион», «ставка», «баланс», «аренда») не
 * помогла: у сметного тренажёра это его собственная предметная область, и
 * осталось 56. Признак витрины словами не выражается — шахматную нашло ЧТЕНИЕ,
 * а метрика лишь подтвердила. Поэтому приём остаётся модульным и человеческим:
 * список кандидатов открывают глазами, а не считают находками.
 *
 * Запуск:  node scripts/find-facade-pages.mjs [каталог]
 * Код 1 — есть кандидаты; 0 — нет.
 */
import fs from "node:fs";
import path from "node:path";

const ROOT = process.argv[2] || path.join(process.cwd(), "..", "frontend", "src", "app", "cyberchess");
const ПОРОГ_ДЕЙСТВИЙ = 3; // одна-две кнопки бывают навигацией, а не механизмом

const читать = (p) => { try { return fs.readFileSync(p, "utf-8"); } catch { return ""; } };

function локальныеИмпорты(src, база) {
  const пути = [];
  for (const m of src.matchAll(/from\s+["'](\.[^"']+)["']/g)) {
    const c = path.normalize(path.join(база, m[1]));
    for (const ext of [".tsx", ".ts", "/index.tsx", "/index.ts"]) {
      if (fs.existsSync(c + ext) && fs.statSync(c + ext).isFile()) { пути.push(c + ext); break; }
    }
  }
  return пути;
}

function обойти(dir, acc = []) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) { if (e.name !== "__tests__") обойти(p, acc); }
    else if (e.name === "page.tsx") acc.push(p);
  }
  return acc;
}

if (!fs.existsSync(ROOT)) {
  console.error(`каталог не найден: ${ROOT}`);
  process.exit(2); // спросить не удалось — это НЕ «находок нет»
}

const кандидаты = [];
let всего = 0;
for (const p of обойти(ROOT)) {
  всего++;
  const src = читать(p);
  const свои = (src.match(/fetch\(/g) || []).length;
  const вКомпонентах = локальныеИмпорты(src, path.dirname(p))
    .reduce((n, i) => n + (читать(i).match(/fetch\(/g) || []).length, 0);
  const действий = (src.match(/onClick=/g) || []).length;
  if (свои + вКомпонентах === 0 && действий >= ПОРОГ_ДЕЙСТВИЙ) {
    const помечена = /образец|витрина замысла|демо|прототип/i.test(src);
    кандидаты.push({ p: path.relative(ROOT, p), действий, помечена });
  }
}

console.log(`проверено страниц: ${всего}`);
if (!кандидаты.length) {
  console.log("кандидатов нет (в пределах того, что этот приём видит — см. шапку)");
  process.exit(0);
}
for (const k of кандидаты) {
  console.log(`  ${k.помечена ? "помечена" : "БЕЗ ОГОВОРКИ"}  ${k.p} — действий ${k.действий}, обращений к серверу 0`);
}
const без = кандидаты.filter((k) => !k.помечена).length;
console.log(`\nкандидатов: ${кандидаты.length}, из них без оговорки: ${без}`);
process.exit(без ? 1 : 0);
