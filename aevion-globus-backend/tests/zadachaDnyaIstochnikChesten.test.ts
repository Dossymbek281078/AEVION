import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Страница задачи дня писала «Задача дня из общего банка — одна и та же у
 * всех игроков сегодня» ровно тогда, когда банк НЕ ответил.
 *
 * Причина — проверка ПОДСТРОКИ: клиент делал `source.includes('банк')`, а
 * строка отказа «резервный пул из 30 задач: банк не ответил» это слово
 * содержит. Комментарий рядом уверял, что «признак берётся из ответа
 * сервера, а не угадывается» — намерение было верным, исполнение обратным.
 *
 * Замер 02.09.2026: сервер ответил «банк не ответил», экран сказал обратное.
 */

const СЕРВЕР = () => readFileSync(join(__dirname, "..", "src", "routes", "cyberchessDaily.ts"), "utf8");

describe("источник задачи дня", () => {
  it("сервер отдаёт МАШИННЫЙ признак, а не только текст", () => {
    expect(СЕРВЕР()).toContain("fromBank: !!fromBank,");
  });

  it("обе подписи остались человеческими и различимыми", () => {
    const к = СЕРВЕР();
    expect(к).toContain("ChessPuzzle — настоящий банк задач");
    expect(к).toContain("резервный пул из 30 задач: банк не ответил");
  });

  it("строка ОТКАЗА содержит слово «банк» — значит подстрокой решать нельзя", () => {
    // Это не придирка к тексту, а причина дефекта: пока отказ так написан,
    // любая проверка по подстроке будет давать обратный ответ.
    const отказ = "резервный пул из 30 задач: банк не ответил";
    expect(отказ.includes("банк")).toBe(true);
    expect(СЕРВЕР()).toContain(отказ);
  });
});
