/**
 * У промпта тренера есть жёсткий предел длины — и он назван главнее абзацев.
 *
 * ПОВОД 29.09.2026. После починки бюджета (запрошенное × 4 + 1024) ответы
 * перестали рваться не у всех: замер соседнего окна на 12 позициях — 3 ответа
 * обрываются без знака препинания при длине 717–755 знаков. Причина не в
 * бюджете, а в промпте: блоки уровня просят «2-4 абзаца», модель начинает
 * длинный разбор и упирается.
 *
 * Решение оркестратора: не поднимать множитель (это платить за невидимое
 * размышление на КАЖДОМ запросе ради трёх случаев из двенадцати), а попросить
 * короче. Предел обязан быть НАЗВАН главнее указаний про абзацы: два
 * противоречивых требования в одном промпте дают разброс, а не краткость.
 */

import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const КОД = readFileSync(join(__dirname, "..", "AiCoach.tsx"), "utf8");

describe("предел длины ответа в промпте", () => {
  it("предел задан числом", () => {
    expect(КОД).toMatch(/ЧЕТЫРЁХ предложени/);
  });

  it("🔴 названо, что предел ГЛАВНЕЕ указаний про абзацы", () => {
    // Без этого промпт противоречит сам себе: «2-4 абзаца» против «4
    // предложения». Модель выбирает наугад, и обрывы возвращаются.
    const и = КОД.indexOf("ЧЕТЫРЁХ предложени");
    const блок = КОД.slice(и, и + 400);
    expect(блок).toContain("важнее");
    expect(блок).toContain("абзац");
  });

  it("контроль: указания про абзацы никуда не делись", () => {
    // Мы не вычищаем педагогику, а расставляем приоритет. Если блоки уровня
    // исчезнут, проверка выше станет бессмысленной.
    expect(КОД).toMatch(/2-4 абзаца|2-3 абзаца/);
  });

  it("контроль: правила правды не тронуты", () => {
    expect(КОД).toContain("Ходы приводи только из блока Best Lines");
  });
});
