/**
 * Сторож заявлений о масштабе экосистемы.
 *
 * ЗАЧЕМ. pitchNumbers.guard проверяет ИМЕНОВАННЫЙ список отставных чисел на
 * ИМЕНОВАННОМ списке поверхностей. Этого хватало ровно до тех пор, пока
 * устаревшая цифра появлялась там, куда уже смотрели. 27.07.2026 сплошной
 * обход нашёл 31 расхождение — почти всё под /pricing, куда ходят клиенты, и
 * ни один файл из тех не был в списке поверхностей.
 *
 * Показательный случай: бейдж матрицы сравнения печатал «27 МОДУЛЕЙ × 4
 * ТАРИФА» строкой, пока фильтр в нескольких пикселях правее рисовал живое
 * data.modules.length из того же ответа API. Два числа на одном экране, и оба
 * в бейдже неверны.
 *
 * Поэтому здесь наоборот: сканируется ВЕСЬ фронтенд, а исключения
 * перечисляются поимённо и с причиной. Новое устаревшее число падает по
 * умолчанию; чтобы его пропустить, надо осознанно дописать строку сюда.
 *
 * Сеть не нужна: истина читается из projects.ts, как и в соседнем стороже.
 */
import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";

const SRC_ROOT = path.resolve(__dirname, "../..");
const REGISTRY = path.resolve(SRC_ROOT, "../../aevion-globus-backend/src/data/projects.ts");

/** Каталоги, где чисел про модули экосистемы быть не может по смыслу. */
const SKIP_DIRS = new Set([
  "node_modules",
  ".next",
  "__tests__",
  // Учебные чертежи сметного тренажёра: там «Модуль #278» — номер урока.
  "drawings-practice",
]);

/**
 * Законные вхождения. Каждое — с причиной, потому что без причины это просто
 * способ заглушить сторож. Совпадение по подстроке строки исходника.
 */
const ALLOWED: Array<{ fragment: string; reason: string }> = [
  {
    fragment: "the other 38 modules are upside",
    reason: "три флагмана + 38 = 41; арифметика сходится с реестром",
  },
  {
    fragment: "the launched 12 modules",
    reason:
      "рамка аудита объективности #484: выложено ≠ доделано (~a dozen feature-complete)",
  },
  {
    fragment: "score cp -45 nodes",
    reason: "узлы перебора шахматного движка, не модули",
  },
  {
    fragment: "~11 module pages",
    reason: "комментарий о числе файлов, импортирующих кнопку апгрейда",
  },
  {
    fragment: "(~11 модулей)",
    reason: "то же самое, русский комментарий",
  },
  {
    fragment: '"29 modules"',
    reason: "пример отставного числа внутри объясняющей шапки pitchFacts",
  },
  {
    fragment: "19 modules and 30 services",
    reason:
      "индекс API — свой счёт эндпоинтов, не реестр модулей. Не сверено (см. бэклог), но и не выдаёт себя за число реестра",
  },
  {
    fragment: "30 modules (those copy)",
    reason: "приблизительная формулировка в аргументе о ценности, не счёт",
  },
];

/** Строки чейнджлога описывают, что было выпущено ТОГДА. Это не устаревание. */
const CHANGELOG_LINE = /changelog/i;

/**
 * Файлы-летописи целиком. Запись «выпущено: 12 модулей, 15 узлов» описывает,
 * что было НА ТОТ МОМЕНТ, — это историческая правда, а не устаревшее число.
 * Переписать её значит подделать историю проекта.
 *
 * Признак — путь файла, а не слово в строке: строки самих записей слова
 * «changelog» не содержат, и проверка выше их не покрывала.
 */
const HISTORY_FILES = /^app\/changelog\//;

/** Комментарий, который объясняет само устаревание, а не утверждает число. */
const EXPLANATORY_COMMENT = /Раньше тут стояло|stale module count|retired/i;

/**
 * Строка целиком комментарий — её читатель страницы не увидит никогда.
 *
 * До 10.08.2026 объяснения пропускались по списку фраз («Раньше тут стояло»,
 * «stale module count», «retired»). Список — это второй источник правды: я
 * написал в investor/page.tsx комментарий «здесь стояло ?? 27 при 41 записи
 * в реестре», объясняющий ровно ту поломку, ради которой сторож и живёт, и
 * сторож покраснел на объяснении. Ложно краснеющего сторожа отключают, а
 * вместе с ним пропадает и настоящая проверка.
 *
 * Признак теперь структурный, а не по фразе: строка начинается с `//`, `*`
 * или `/*`. Число внутри комментария пользователю не показывается по
 * определению, поэтому пропускать его безопасно.
 */
const COMMENT_LINE = /^\s*(?:\/\/|\/\*|\*|\{\/\*)/;
// `{/*` добавлен 11.08. Как только проверка научилась читать кириллицу, она
// первым делом покраснела на JSX-комментарии в /pricing/compare, который
// объясняет ровно ту поломку, ради которой сторож и написан: «Раньше тут
// стояло „27 МОДУЛЕЙ × 4 ТАРИФА“». Третий за сутки случай, когда сторож
// краснеет на собственном объяснении — объяснения живут рядом с починкой,
// и распознавать их надо структурно, а не по фразе.

/**
 * Раскрывает `\uXXXX` перед сканированием.
 *
 * Слепое пятно, стоившее полутора месяцев: файл переводов хранит русский и
 * казахский экранированными кодами. Для грепа по кириллице таких строк не
 * существует вовсе, а для этой проверки «27 модулей» выглядело как набор
 * escape-последовательностей без слова «модул». Проверка честно возвращала
 * «расхождений нет», пока подзаголовок ГЛАВНОЙ страницы говорил
 * «40 product nodes» по-английски и «27 продуктовыми узлами» по-русски.
 *
 * Декодирование не меняет файлы — только то, что видит сканер. Обратный
 * слэш перед не-`u` не трогаем: `\n` внутри строки перевода должен остаться
 * как есть, иначе строка «схлопнется» и соседние слова слипнутся.
 */
function decodeEscapes(line: string): string {
  return line.replace(/\\u([0-9a-fA-F]{4})/g, (_, hex) =>
    String.fromCharCode(parseInt(hex, 16)),
  );
}

/**
 * Вычищает блочные комментарии, СОХРАНЯЯ нумерацию строк.
 *
 * Построчной проверки «строка начинается с //» не хватает: у многострочного
 * комментария так выглядит только первая строка, а продолжения — обычный
 * текст. Именно на такой строке проверка покраснела, как только научилась
 * читать кириллицу: в /pricing/compare объяснение «Раньше тут стояло
 * „27 МОДУЛЕЙ × 4 ТАРИФА“» лежит на второй строке комментария.
 *
 * Заменяем содержимое пробелами, а не удаляем: номера строк в отчёте должны
 * оставаться настоящими, иначе по ним не найти место.
 */
function stripBlockComments(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, (m) =>
    m.replace(/[^\n]/g, " "),
  );
}

function countRegistryTotal(): number {
  const src = readFileSync(REGISTRY, "utf8");
  return Array.from(src.matchAll(/status:\s*["'](\w+)["']/g)).length;
}

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (/\.(ts|tsx)$/.test(name) && !/\.test\./.test(name)) out.push(full);
  }
  return out;
}

/**
 * Число рядом со словом масштаба, в обе стороны. Намеренно шире, чем нужно:
 * первая версия этого обхода требовала уточнения после существительного
 * («modules deployed»), и голое «27 MODULES» на /pricing/roadmap проскочило.
 */
const SCALE_WORD =
  // «AEVION products» добавлено 11.08: строка primer.investor.b3 говорила
  // «each of 27 AEVION products» и пряталась от проверки, потому что слова
  // «products» в списке не было. Узко, с обязательным «AEVION» перед ним:
  // просто «products» — слишком частое слово, дало бы ложные тревоги.
  //
  // Русские окончания — через `[\p{L}]*`, а НЕ `\w*`.
  //
  // `\w` в JavaScript тоже ASCII-only: `модул\w*` захватывает ровно «модул» и
  // обрывается на «е» слова «модулей». Вместе с проверкой «дальше не буква»
  // это гарантированный промах — то есть сторож с кириллическими основами
  // НЕ ЛОВИЛ КИРИЛЛИЦУ НИ РАЗУ с момента появления. Найдено 11.08 мутацией:
  // «27 продуктовыми узлами» на главной оставалось незамеченным даже после
  // того, как проверка научилась раскрывать \uXXXX.
  "(?:product\\s+nodes?|AEVION\\s+products?|nodes?|modules?|[Мм][Оо][Дд][Уу][Лл][\\p{L}]*|[Уу][Зз][Лл][\\p{L}]*)";
// До двух определений между числом и существительным: «29 живых модулей»,
// «40 product nodes», «12 live MVPs». Без этого проверка ловила только
// вплотную стоящую пару и пропускала ровно те формулировки, которыми на
// русских страницах и пишут. Тот же шаблон, что в pitchNumbers.guard, —
// две проверки не должны расходиться в том, что считают счётчиком.
const NUM_THEN_WORD = new RegExp(
  // Ровно ОДНО определение, не два. С двумя проверка краснела на честной
  // строке «18 px return node» — там между числом и словом просто оказались
  // два чужих слова. Одного хватает всем реальным формулировкам:
  // «29 живых модулей», «27 AEVION modules», «40 product nodes».
  // Конец слова — «дальше не буква», а НЕ `\b`.
  //
  // `\b` в JavaScript опирается на ASCII-класс `\w`, и кириллица в него не
  // входит. Поэтому `узлами\b` не совпадает никогда: после «и» идёт пробел,
  // но для движка это не граница слова — обе стороны «не-\w».
  //
  // Стоило это второй слепоты за день: даже после того, как проверка
  // научилась раскрывать `\uXXXX`, мутация «27 продуктовыми узлами» её не
  // роняла. Та же грабля описана в feedback_regex_word_boundary_cyrillic и
  // уже правилась в pitchNumbers.guard — а здесь пережила.
  `\\b(\\d{2,3})\\s*\\+?(?:\\s+[\\p{L}-]{1,15})?\\s+${SCALE_WORD}(?![\\p{L}])`,
  "giu",
);

describe("заявления о масштабе экосистемы сверены с реестром", () => {
  const total = countRegistryTotal();
  const nodes = total - 1; // globus — оболочка карты, не продуктовый узел

  /**
   * Числа, которые не являются устаревшими:
   *   total  — записей в реестре
   *   nodes  — узлов на карте
   *   live   — живых модулей (считается ниже)
   *   43     — модулей в тарифном реестре (свой список, шире экосистемного)
   * Плюс «N+», пока N не превышает факта: «30+ модулей» при 41 — правда.
   */
  const registrySrc = readFileSync(REGISTRY, "utf8");
  const live = Array.from(registrySrc.matchAll(/status:\s*["']live["']/g)).length;
  const EXACT_OK = new Set([String(total), String(nodes), String(live), "43"]);

  it("реестр читается и не пуст (сам счётчик не должен молча вернуть 0)", () => {
    expect(total).toBeGreaterThan(20);
    expect(live).toBeGreaterThan(10);
  });

  it("ни одно число рядом со словом масштаба не разошлось с реестром", () => {
    const violations: string[] = [];
    const seen = new Set<string>();

    for (const file of walk(SRC_ROOT)) {
      const rel = path.relative(SRC_ROOT, file).replace(/\\/g, "/");
      if (HISTORY_FILES.test(rel)) continue;
      const lines = stripBlockComments(readFileSync(file, "utf8"))
        .split("\n")
        .map(decodeEscapes);

      lines.forEach((line, idx) => {
        // Гигантские сгенерированные строки переводов сканируем, но без
        // экстремальных: там одна строка может быть на пол-экрана.
        if (line.length > 900) return;
        if (CHANGELOG_LINE.test(line)) return;
        if (COMMENT_LINE.test(line)) return;
        if (EXPLANATORY_COMMENT.test(line)) return;
        if (/Модуль\s*#\d/.test(line)) return;
        if (ALLOWED.some((a) => line.includes(a.fragment))) return;

        // Окно в ДВЕ строки, а не одна.
        //
        // Проверка требовала, чтобы число и слово стояли рядом в одной
        // строке, — и потому не видела главного своего случая. В JSX они
        // почти всегда на разных: `{registry?.total ?? 27}` и следом
        // <div>modules tracked</div>. Именно так /investor полтора месяца
        // печатал «27 modules tracked» при 41 записи в реестре, а сторож
        // был зелёным. Мутация 10.08 это подтвердила: возврат `?? 27`
        // в код проверку не ронял.
        //
        // Запятая, скобка или кавычка между числом и словом разрывают
        // совпадение (шаблон допускает между ними только пробелы и «+»),
        // поэтому склейка не даёт ложных срабатываний на соседстве вида
        // `fontSize: 12,` + следующая строка со словом «modules».
        // Три строки, потому что между числом и подписью почти всегда стоит
        // закрывающий тег: `{total ?? 27}` / `</div>` / `<div>modules</div>`.
        // Теги вырезаются — заодно исчезают числа из инлайновых стилей
        // (`style={{ fontSize: 12 }}` живёт внутри тега), которые иначе дали
        // бы ложные срабатывания. Фигурные скобки становятся пробелами,
        // иначе `27}` не считается стоящим перед словом.
        const window = [line, lines[idx + 1] ?? "", lines[idx + 2] ?? ""]
          .filter((l) => l.length <= 900 && !COMMENT_LINE.test(l))
          .join(" ")
          .replace(/<[^>]*>/g, " ")
          .replace(/[{}]/g, " ")
          .replace(/\s+/g, " ");

        for (const m of window.matchAll(NUM_THEN_WORD)) {
          const num = m[1];
          if (EXACT_OK.has(num)) continue;
          const value = Number(num);
          if (value > 100) continue; // явно не про счёт модулей
          // «N+» — занижение, а не ошибка, пока N не больше факта.
          if (m[0].includes("+") && value <= total) continue;
          // Окно в три строки перекрывается, поэтому одно и то же место
          // попадает в отчёт трижды подряд с разными номерами строк. Читателю
          // это выглядит как три разных дефекта, и он теряет доверие к
          // списку — дедуплицируем по файлу и тексту совпадения.
          const entry = `${rel}:${idx + 1}  «${m[0].trim()}»`;
          if (!seen.has(`${rel}|${m[0].trim()}`)) {
            seen.add(`${rel}|${m[0].trim()}`);
            violations.push(entry);
          }
        }
      });
    }

    expect(
      violations,
      `Реестр держит ${total} записей (${nodes} узлов на карте, ${live} live), ` +
        `но найдены расходящиеся числа:\n  ${violations.join("\n  ")}\n\n` +
        "Либо поправь число, либо — если оно про что-то другое — впиши его в " +
        "ALLOWED в этом файле С ПРИЧИНОЙ. Молча заглушать нельзя: " +
        "исключение без причины ничем не отличается от бага.",
    ).toEqual([]);
    // 30с, а не дефолтные 5: тест обходит весь src на диске. В одиночку это
    // ~0.4с, но при параллельном прогоне всего набора конкуренция за диск
    // выводила его за лимит — и падение выглядело как найденное расхождение,
    // хотя было таймаутом.
  }, 30_000);
});
