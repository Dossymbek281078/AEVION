import { describe, test, expect } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { GET } from "../../api/health/route";

/**
 * Сторож: на КАЖДОЙ странице оплаты видна пометка «демонстрация», а состояние
 * называет режим, а не аварию.
 *
 * 🔴 Замер окна кассы 05.10.2026: за поверхностями /payments/* нет эквайрера, данные
 * засеяны (seedSettlements кладёт «$1245.00 paid», «€389.00 scheduled»), а пометки на
 * страницах не было вовсе. Посетитель видел «оплачено $1245» как настоящие деньги.
 * Компонент ComplianceBanner при этом существовал и не был смонтирован ни на одной
 * странице — «написано, но не вызывается».
 *
 * Второе: /api/health отдавал status «degraded» просто потому, что не настроено KV.
 * Снаружи это читается как «платежи сломаны», то есть как потеря денег, — тогда как
 * денег здесь нет вовсе. Теперь поверхности помечены mode: "demo" и статус не роняют,
 * а примечание про память процесса осталось: оно правда.
 */

const КОРЕНЬ = join(__dirname, "..");

/** Все страницы под /payments — считаем, чтобы печатать ЗНАМЕНАТЕЛЬ. */
function страницы(): string[] {
  const найдено: string[] = [];
  const обход = (каталог: string) => {
    for (const имя of readdirSync(каталог)) {
      const путь = join(каталог, имя);
      if (statSync(путь).isDirectory()) {
        if (имя === "__tests__") continue;
        обход(путь);
      } else if (имя === "page.tsx") {
        найдено.push(путь);
      }
    }
  };
  обход(КОРЕНЬ);
  return найдено;
}

describe("пометка демонстрации на страницах оплаты", () => {
  // Проверку «layout монтирует баннер с вариантом financial» НЕ повторяем: её делает
  // сторож Кассы complianceBannerMounted.test.ts в этом же каталоге, и эта ветка
  // собрана поверх её вершины 71c3b8afc. Здесь — только то, чего у неё нет:
  // ЗНАМЕНАТЕЛЬ охвата и честный режим в /api/health.

  test("знаменатель: сколько страниц накрыто", () => {
    const список = страницы();
    // Печатаем число, а не «все»: если страниц вдруг станет меньше, это тоже повод
    // посмотреть — страницу могли вынести из-под layout, и она осталась без пометки.
    // Печать именно в поток ошибок, а не console.log: замер 05.10 на этом же
    // прогоне — репортёр проглотил console.log у ПРОХОДЯЩЕГО теста (0 вхождений
    // в выводе), а process.stderr.write дошёл (1). Знаменатель, которого не видно,
    // знаменателем не является.
    const ПЕРЕВОД = String.fromCharCode(10); // слэш-эскейп съедается на границе вызова (§2е)
    process.stderr.write(
      `[сторож] страниц под /payments накрыто общим layout: ${список.length}` + ПЕРЕВОД,
    );
    expect(
      список.length,
      "страниц стало меньше 14 — проверьте, не вынесли ли страницу из-под layout",
    ).toBeGreaterThanOrEqual(14);
    for (const п of список) {
      expect(п.startsWith(КОРЕНЬ), `страница вне зоны layout: ${п}`).toBe(true);
    }
  });

  test("состояние называет РЕЖИМ, а не аварию", async () => {
    const ответ = await GET();
    const тело = (await ответ.json()) as {
      status: string;
      paymentsMode?: string;
      surfaces?: Array<{ name: string; mode?: string; note?: string }>;
    };
    expect(тело.paymentsMode, "режим платёжных поверхностей не назван").toBe("demo");
    const демо = (тело.surfaces ?? []).filter((s) => s.mode === "demo");
    expect(демо.length, "поверхности оплаты не помечены демонстрационными").toBeGreaterThanOrEqual(5);
    expect(
      тело.status,
      "без настроенного KV статус всё ещё читается как авария платежей",
    ).not.toBe("degraded");
  });

  test("КОНТРОЛЬ: правда про хранение в памяти НЕ скрыта", async () => {
    // Иначе починка ложной тревоги превратилась бы в ложное «всё хорошо».
    const ответ = await GET();
    const тело = (await ответ.json()) as { surfaces?: Array<{ note?: string }> };
    const сПримечанием = (тело.surfaces ?? []).filter((s) => (s.note ?? "").includes("памяти"));
    expect(
      сПримечанием.length,
      "примечание про память процесса исчезло — это ложное «ок»",
    ).toBeGreaterThanOrEqual(5);
  });
});
