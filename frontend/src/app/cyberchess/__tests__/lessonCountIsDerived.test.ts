import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

import { LESSONS } from "../coachLessons";

/**
 * Число уроков на экране приходит из данных, а не вписано рядом.
 *
 * 28.08.2026 на кнопке стояло «📖 Курс (14 уроков)», и в подсказке палитры
 * команд — тоже 14. Уроков действительно четырнадцать, то есть в ту минуту
 * подпись была правдой. Но она была правдой СЛУЧАЙНО: добавит кто-то
 * пятнадцатый урок — и обе подписи станут врать, не сломав ни одного теста.
 *
 * Это тот же класс, что «12 турниров» и «prizePool: 250» того же дня: число,
 * посчитанное в одном месте и повторённое в другом, расходится молча.
 */

const PAGE = readFileSync(
  join(dirname(fileURLToPath(import.meta.url)), "..", "page.tsx"),
  "utf8",
);

describe("счётчик уроков не вписан числом", () => {
  test("подпись кнопки берёт длину из LESSONS", () => {
    expect(PAGE).toContain("📖 Курс ({LESSONS.length} уроков)");
  });

  test("подсказка палитры команд — тоже", () => {
    expect(PAGE).toContain("${LESSONS.length} уроков beginner");
  });

  test("вписанного числа на месте подписи не осталось", () => {
    // Именно рядом со словом «уроков»: числа в других местах страницы законны
    // (контроль времени 3+0, рейтинг 1200), и запрещать их скопом нельзя.
    expect(
      /\(\s*\d+\s*уроков\s*\)/.test(PAGE),
      "число уроков снова вписано рядом с подписью",
    ).toBe(false);
  });

  test("контроль: уроки вообще есть, иначе проверка бессмысленна", () => {
    // Без этого «длина берётся из данных» было бы зелёным и при пустом курсе.
    expect(LESSONS.length).toBeGreaterThan(5);
  });
});

describe("и на первом экране новичка — то же число из данных", () => {
  // Третье место с тем же «14» нашлось ПОСЛЕ выкатки: подпись в окне
  // «С чего начать» рисуется на клиенте, и в разметке её не видно — увидел
  // только чистый браузер. Две правки из трёх без этой проверки выглядели бы
  // как «починил», пока человек читал бы старое число на первом же экране.
  const OVERLAY = readFileSync(
    join(dirname(fileURLToPath(import.meta.url)), "..", "OnboardingOverlay.tsx"),
    "utf8",
  );

  test("подсказка «Учиться» берёт длину из LESSONS", () => {
    expect(OVERLAY).toContain("Курс из ${LESSONS.length} уроков");
  });

  test("вписанного числа в подсказке не осталось", () => {
    expect(/Курс из \d+ уроков/.test(OVERLAY), "число уроков снова вписано").toBe(false);
  });
});
