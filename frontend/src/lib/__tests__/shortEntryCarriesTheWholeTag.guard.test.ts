/**
 * Короткий вход несёт ВХОДЯЩУЮ метку целиком — иначе разрез «какой пост дал
 * переход» не считается вовсе.
 *
 * ДЕФЕКТ, ради которого сторож написан (замер 07.10.2026). Все 31 коротких
 * входа подставляли свою метку ЖЁСТКО: `/yt?c=yt-30-dney-devhub` уезжала на
 * `/go?c=yt`, и хвост `-30-dney-devhub` исчезал по дороге. То есть ссылка под
 * конкретным роликом работала, человек приходил, канал записывался — а ролик
 * нет. 27 из 28 входов строку запроса не читали вовсе (`force-static`), а
 * починенный 06.10 `/example` читал, но прогонял метку через
 * `channelFrom + keepChannel`, то есть НОРМАЛИЗОВАЛ её до канала: ключ поста
 * терялся так же тихо, другим механизмом.
 *
 * ПОЧЕМУ СТОРОЖ ЗВОНИТ В СТРАНИЦУ, А НЕ ЧИТАЕТ ЕЁ ИСХОДНИК. Проверка «в файле
 * есть помощник» зелена и у страницы, которая помощника позвала и результат
 * выбросила. Поэтому здесь каждая страница-вход ИСПОЛНЯЕТСЯ с настоящим
 * `searchParams`, а утверждение делается об адресе, который она вернула
 * перенаправлением, — это ответ, а не замысел (правило 0-СТОРОЖ-ДЕЛАЕТ-ЗАПРОС).
 */
import { describe, it, expect, vi } from "vitest";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

import { channelFrom, postFrom } from "../products";

/** Перенаправление Next бросает исключение; ловим его и достаём адрес. */
vi.mock("next/navigation", () => ({
  redirect: (url: string) => {
    throw Object.assign(new Error("NEXT_REDIRECT"), { url });
  },
}));

const APP = join(process.cwd(), "src/app");

type Вход = { вход: string; метка: string; цель: string; файл: string };

/** Перечисляет короткие входы так же, как shortEntryTargetsReadTheChannel: по
 *  дословному вызову перенаправления с `?c=` в коде страницы. */
function короткиеВходы(): Вход[] {
  const найдено: Вход[] = [];
  const обход = (dir: string, префикс: string) => {
    for (const имя of readdirSync(dir, { withFileTypes: true })) {
      if (!имя.isDirectory()) continue;
      if (имя.name.startsWith("[") || имя.name.startsWith("_")) continue;
      const путь = join(dir, имя.name);
      const файл = join(путь, "page.tsx");
      if (existsSync(файл)) {
        const код = readFileSync(файл, "utf8");
        const МАРКЕР = 'redirect("';
        let i = код.indexOf(МАРКЕР);
        while (i >= 0) {
          const конец = код.indexOf('"', i + МАРКЕР.length);
          const адрес = код.slice(i + МАРКЕР.length, конец);
          if (адрес.includes("?c=") && !адрес.includes("&")) {
            найдено.push({
              вход: префикс + "/" + имя.name,
              метка: адрес.split("?c=")[1],
              цель: адрес.split("?c=")[0],
              файл,
            });
          }
          i = код.indexOf(МАРКЕР, конец);
        }
      }
      обход(путь, префикс + "/" + имя.name);
    }
  };
  обход(APP, "");
  return найдено;
}

/** Исполняет страницу-вход и возвращает адрес, на который она перенаправила. */
async function кудаВедёт(файл: string, c?: string): Promise<string> {
  const модуль = (await import(pathToFileURL(файл).href)) as {
    default: (аргументы: { searchParams: Promise<{ c?: string }> }) => Promise<void>;
  };
  try {
    await модуль.default({ searchParams: Promise.resolve(c === undefined ? {} : { c }) });
  } catch (e) {
    const url = (e as { url?: string }).url;
    if (typeof url === "string") return url;
    throw e;
  }
  throw new Error("страница не перенаправила вовсе");
}

const входы = короткиеВходы();

describe("короткие входы несут входящую метку целиком", () => {
  it("входы вообще найдены", () => {
    /*
     * ЗНАМЕНАТЕЛЬ. Пустой список дал бы зелёное «все входы несут метку». Порог
     * 32 — замер 07.10.2026 (29 в корне, включая найденный сторожем /meta, плюс три английских). Упадёт ниже —
     * значит вход удалили или перестали находить, и это повод смотреть, а не
     * радоваться зелёному.
     */
    expect(входы.length, "коротких входов не найдено — сторож проверял пустоту")
      .toBeGreaterThanOrEqual(32);
  });

  it.each(входы)("$вход доносит метку с хвостом целиком", async ({ вход, метка, цель }) => {
    const пришло = `${метка}-post-7`;
    const адрес = await кудаВедёт(join(APP, вход, "page.tsx"), пришло);
    expect(new URL(адрес, "https://aevion.app").searchParams.get("c"),
      `${вход} потерял хвост метки — разрез по постам считаться не будет`).toBe(пришло);
    expect(адрес.split("?")[0], `${вход} сменил цель`).toBe(цель);
  });

  it.each(входы)("$вход несёт ЧУЖОЙ канал с хвостом (ссылка из другого места)",
    async ({ вход }) => {
      // Ролик может вести на любой короткий адрес; метка в нём — канала ролика.
      const адрес = await кудаВедёт(join(APP, вход, "page.tsx"), "tg-anons-devhub");
      expect(new URL(адрес, "https://aevion.app").searchParams.get("c")).toBe("tg-anons-devhub");
    });

  it.each(входы)("$вход помечает НАШУ пробу как нашу", async ({ вход }) => {
    /*
     * Правило 0-НАШИ-ЗАХОДЫ-С-МЕТКОЙ: наши заходы помечаются `probe-<окно>`.
     * Подмени такую метку своей — и проба окна станет в отчёте живым человеком
     * из этого канала. Ровно так 30.09 пять начал оплаты читались покупателями.
     */
    const адрес = await кудаВедёт(join(APP, вход, "page.tsx"), "probe-ls-devhub");
    expect(new URL(адрес, "https://aevion.app").searchParams.get("c")).toBe("probe-ls-devhub");
  });

  it.each(входы)("$вход без метки доносит свою", async ({ вход, метка, цель }) => {
    const адрес = await кудаВедёт(join(APP, вход, "page.tsx"));
    expect(адрес).toBe(`${цель}?c=${метка}`);
  });

  it.each(входы)("$вход подставляет свою метку вместо мусора", async ({ вход, метка, цель }) => {
    /*
     * Отрицательный контроль: несущая способность не должна стать дырой, через
     * которую в учёт (и в адрес кассы) уезжает что угодно из строки запроса.
     *
     * Мусор взят НАЧИНАЮЩИМСЯ С ИЗВЕСТНОГО КАНАЛА намеренно. Первая редакция
     * подавала «../../evil?x=1», и мутация «снять проверку формата» её прошла:
     * у такой строки начало не канал, поэтому она отсеивалась и БЕЗ проверки —
     * контроль был зелёным у сломанного кода. Различает две версии только
     * строка, которая без проверки формата уехала бы дальше целиком.
     */
    const адрес = await кудаВедёт(join(APP, вход, "page.tsx"), "yt-../../evil?x=1");
    expect(адрес).toBe(`${цель}?c=${метка}`);
  });

  it.each(входы)("$вход: донесённую метку приёмная сторона читает как свой канал",
    async ({ вход, метка, цель }) => {
      /*
       * САМОЕ ВАЖНОЕ утверждение файла: оно связывает ДВА конца. Нести метку
       * целиком имеет смысл только тогда, когда страница назначения прочитает из
       * неё ТОТ ЖЕ канал. Замер 07.10.2026 показал, что это выполнялось не для
       * всех: у четырёх каналов дефис есть в самом ключе, и `ads-devhub-post-7`
       * приходил вовсе без канала, а `x-devhub-post-7` — каналом «x». То есть
       * починка входа без починки разбора сделала бы хуже: вместо потерянного
       * поста терялся бы или подменялся КАНАЛ. Разбор исправлен тем же заходом
       * (ключКанала в products.ts), и ровно это здесь и проверяется.
       */
      const адрес = await кудаВедёт(join(APP, вход, "page.tsx"), `${метка}-post-7`);
      const донесено = new URL(адрес, "https://aevion.app").searchParams.get("c");
      expect(channelFrom(донесено), `${вход}: канал после переноса метки другой`)
        .toBe(channelFrom(метка));
      expect(postFrom(донесено), `${вход}: пост не читается — разреза по постам не будет`)
        .toBe("post-7");
      expect(цель.startsWith("/"), `${вход} ведёт наружу`).toBe(true);
    });
});
