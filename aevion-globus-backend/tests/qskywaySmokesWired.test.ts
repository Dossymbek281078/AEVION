import { describe, it, expect } from "vitest";
import * as fs from "fs";
import * as path from "path";

// Вторая половина того же дефекта, что и в npmScriptRunners.test.ts.
//
// Починить npm-команду было мало: трёх смоков слоя доверия FAA не было в
// scripts/all-smokes.js — единственном месте, которое знает «все смоки» и
// которое зовёт ежедневный прогон. С рабочим раннером их всё равно никто бы не
// запускал, и они сгнили бы снова.
//
// Проверка НАМЕРЕННО ограничена смоками QSkyway. По всему репозиторию она была
// бы красной сразу: на 28.07 в scripts/ лежат 13 смоков других модулей, которых
// не зовёт ни агрегатор, ни CI, ни npm (список — на рабочем столе). Подключать
// чужие молча нельзя: молчавший месяцами смок скорее всего красный, и он уронил
// бы ежедневный прогон другим сессиям. Владелец модуля запускает свой сам.

const SCRIPTS = path.join(__dirname, "..", "scripts");
const aggregator = fs.readFileSync(path.join(SCRIPTS, "all-smokes.js"), "utf8");

/**
 * Именно ЗАПИСЬ в списке, а не упоминание.
 *
 * Первая версия искала имя файла подстрокой — и покраснела на `ots-smoke.ts`,
 * который в агрегаторе только упомянут комментарием о том, почему он исключён.
 * Ошибка симметрична и опаснее в другую сторону: подстрока одинаково «находит»
 * и подключённый смок, и смок, названный в комментарии, — то есть подтвердила бы
 * подключение, которого нет.
 */
const isWired = (file: string): boolean =>
  new RegExp(String.raw`script:\s*["'\`]` + file.replace(/\./g, String.raw`\.`) + String.raw`["'\`]`).test(aggregator);

/** Смоки QSkyway, которые ОБЯЗАНЫ быть в общем прогоне. */
const MUST_BE_WIRED = [
  "airspace-freshness-smoke.ts",
  "trust-anchor-smoke.ts",
  "trust-signature-smoke.ts",
  "qskyway-smoke.js",
];

/**
 * Осознанные исключения — с причиной. Список существует, чтобы «сирота» не
 * читалась как недоделка и чтобы её не «починили» подключением.
 */
const DELIBERATELY_EXCLUDED: Record<string, string> = {
  "ots-smoke.ts":
    "штампует хеш в публичные календари OpenTimestamps (запись во внешний мир) "
    + "и по построению не бывает зелёным сразу: свежий штамп часами ждёт блока Bitcoin",
};

describe("смоки QSkyway подключены к общему прогону", () => {
  // Перебор по пустому списку зелен и бесполезен: если из MUST_BE_WIRED
  // однажды всё вычистят, файл продолжит отчитываться об успехе.
  it("список смоков не пуст — иначе проверки ниже ничего не перебирают", () => {
    expect(MUST_BE_WIRED.length).toBeGreaterThan(0);
  });

  it("файлы, которые проверяются, действительно существуют", () => {
    // Иначе тест зелёный на опечатке в имени: несуществующий файл невозможно
    // не найти в агрегаторе, и проверка проверяла бы саму себя.
    for (const f of [...MUST_BE_WIRED, ...Object.keys(DELIBERATELY_EXCLUDED)]) {
      expect(fs.existsSync(path.join(SCRIPTS, f)), `${f} не найден в scripts/`).toBe(true);
    }
  });

  it.each(MUST_BE_WIRED)("«%s» перечислен в all-smokes.js", (file) => {
    expect(
      isWired(file),
      `${file} не перечислен в scripts/all-smokes.js. Смок, которого нет в агрегаторе, `
        + `не запускается ежедневным прогоном — и его молчание будет прочитано как здоровье.`,
    ).toBe(true);
  });

  it.each(Object.entries(DELIBERATELY_EXCLUDED))(
    "«%s» исключён осознанно, и причина записана рядом со списком",
    (file, reason) => {
      expect(isWired(file), `${file} подключён к общему прогону, хотя ${reason}`).toBe(false);
      // Причина должна жить в самом агрегаторе, а не только здесь: правку делают
      // там, и там же её должно останавливать объяснение.
      expect(
        /ots-smoke\.ts.*(?:СПЕЦИАЛЬНО|намеренно|сознательно)/s.test(aggregator),
        `в all-smokes.js нет объяснения, почему ${file} исключён — следующая сессия «починит» подключением`,
      ).toBe(true);
    },
  );
});
