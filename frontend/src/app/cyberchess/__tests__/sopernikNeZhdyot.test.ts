import { describe, it, expect } from "vitest";
import { readFileSync } from "fs";
import { join } from "path";

/**
 * Соперник отвечал всё медленнее: 1.6 → 4 → 6.6 → 8.8 секунды на КЛУБНОМ
 * уровне, и дальше росло. Замер на живой сборке 31.08.2026.
 *
 * Причина названа замером, а не догадкой: перехватил команды поиска. За четыре
 * хода движок обслужил 15 поисков — 6 глубины 8 (разбор ходов), 6 глубины 18
 * (метрики CPI, три линии) и 3 глубины 13 (оценка позиции). Всё это на ОДНОМ
 * воркере, строго по очереди, вместе с поиском хода соперника.
 *
 * Замысел автора виден в коде: сбор метрик обёрнут в requestIdleCallback. Но
 * он ждёт простоя ГЛАВНОГО ПОТОКА, а узкое место — единственный воркер движка.
 *
 * До починки движка (тот же день) этого не было видно: он не работал вовсе,
 * и партия казалась быстрой, потому что не считалось ничего.
 */

const KOD = () => readFileSync(join(process.cwd(), "src/app/cyberchess/page.tsx"), "utf8");

describe("тяжёлые расчёты не занимают движок в ход соперника", () => {
  it("метрики собираются только когда ходит человек", () => {
    const s = KOD();
    expect(s.length).toBeGreaterThan(100000); // контроль: файл прочитан
    expect(s).toContain("if(!myT)return; // ход соперника — движок занят его поиском, не мешаем");
  });

  it("признак хода человека есть в зависимостях эффекта", () => {
    // Без этого эффект не пересоберётся при смене очереди хода, и условие
    // будет читать устаревшее значение — то есть охранять не будет.
    const s = KOD();
    expect(s).toContain("},[bk,on,over,tab,p2pMode,hotseat,setup,sfOk,myT]);");
  });

  it("незаконченный поиск метрик обрывается, когда человек сходил", () => {
    // Отмена флага НЕ освобождает воркер: поиск идёт дальше и держит очередь.
    // Замер лентой 31.08.2026: соперник отвечает за 1.2 с, а следующий за ним
    // поиск метрик занимает движок 7.1 секунды (6383 → 13475 мс), и ответ на
    // СЛЕДУЮЩИЙ ход человека ждёт за ним.
    const s = KOD();
    expect(s).toContain("if(poiskIdyot){try{sfR.current?.stop()}catch{}}");
    // Метка ставится перед поиском и снимается в ответе — иначе оборвём чужой.
    // Инвариант, а не число: метка ставится и снимается ПОРОВНУ. Число мест
    // может измениться, парность — нет.
    const stavim = (s.match(/poiskIdyot=true/g) || []).length;
    const snimaem = (s.match(/poiskIdyot=false/g) || []).length;
    expect(stavim).toBeGreaterThan(0);
    // +1 — это объявление `let poiskIdyot=false`, оно не снятие метки.
    expect(snimaem).toBe(stavim + 1);
  });

  it("обрыв только своего поиска, а не любого", () => {
    // Безусловный stop() в уборке оборвал бы и поиск хода соперника.
    // Проверяем это счётом: вызов ровно один и он под условием.
    const s = KOD();
    // Каждый вызов stop() обязан стоять под условием — безусловный оборвал бы
    // и поиск хода соперника.
    const vyzovy = s.split("sfR.current?.stop()").length - 1;
    const podUsloviem = s.split("if(poiskIdyot){try{sfR.current?.stop()}catch{}}").length - 1;
    expect(vyzovy).toBeGreaterThan(0);
    expect(podUsloviem).toBe(1);
  });

  it("сбор метрик не удалён, а отложен", () => {
    // Лёгкий способ «починить» — выкинуть метрики совсем; тогда пропадёт
    // оценка силы игрока. Проверяем, что механизм на месте.
    const s = KOD();
    expect(s).toContain("setPendingTop3");
    expect(s).toContain("recordMoveWithMultiPV");
  });

  it("глубину метрик не понизили втихую", () => {
    // Второй лёгкий путь — уронить глубину и потерять точность CPI.
    // Умолчание остаётся 18, оно настраивается человеком в настройках.
    const s = KOD();
    expect(s).toContain('localStorage.getItem("aevion_chess_sf_depth_v1")||"18"');
  });
});
