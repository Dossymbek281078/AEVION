import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Запасной перевод идёт через Gemini, Anthropic — только последним.
 *
 * Это сторож о ДЕНЬГАХ, не о качестве. Замер на проде 01.10.2026: квота DeepL
 * исчерпалась (ответ честно сказал `fallbackReason: "deepl_quota_exhausted"`), и
 * перевод ушёл на Anthropic. Расход через Anthropic API основатель считает самой
 * больной тратой — за месяц по нему ушло больше $800, и правило 0-ПОДПИСКА
 * написано ровно против этого.
 *
 * Gemini при этом живой и несёт основную работу: в тот же день генерация кода и
 * картинок шла через него (картинка 200 за 6.7 с после падения openai и
 * workers-ai).
 *
 * Почему Anthropic НЕ убран совсем: тогда у перевода не останется последнего
 * звена, а молчаливый отказ хуже дорогого ответа. Он включается, только когда не
 * ответил никто другой.
 */
const ИСХОДНИК = readFileSync(join(__dirname, "..", "src", "routes", "devhub.ts"), "utf8");

/** Порядок переводчиков из исходника — читаем, а не повторяем своими словами. */
function порядок(): string[] {
  const m = /const LLM_TRANSLATE_ORDER = \[([^\]]+)\]/.exec(ИСХОДНИК);
  if (!m) return [];
  return m[1]
    .split(",")
    .map((s) => s.trim().replace(/^["']|["']$/g, ""))
    .filter(Boolean);
}

describe("запасной перевод предпочитает Gemini", () => {
  it("прибор исправен: порядок прочитан и в нём есть все звенья", () => {
    const п = порядок();
    expect(п.length, "порядок переводчиков не прочитался — проверки ниже пусты").toBeGreaterThanOrEqual(3);
    expect(п, "в порядке нет gemini").toContain("gemini");
    expect(п, "в порядке нет anthropic — у перевода не останется последнего звена").toContain("anthropic");
  });

  it("Gemini стоит ПЕРВЫМ", () => {
    expect(порядок()[0], "первым зовётся не gemini — перевод снова уйдёт на платный канал").toBe("gemini");
  });

  it("Anthropic стоит ПОСЛЕДНИМ", () => {
    const п = порядок();
    expect(п[п.length - 1], "anthropic не последний — он включится раньше дешёвых").toBe("anthropic");
    // И строго позже gemini: без этого «последний» можно было бы получить,
    // оставив в списке один anthropic.
    expect(п.indexOf("anthropic")).toBeGreaterThan(п.indexOf("gemini"));
  });

  it("запасной путь перебирает СПИСОК, а не одного кандидата", () => {
    // 17.09 запасное звено было одно, и оно умерло вместе с кредитами OpenAI.
    // Если перебор вернётся к одному кандидату, порядок перестанет что-то значить.
    expect(ИСХОДНИК, "перебор кандидатов исчез").toContain("const candidates = llmTranslateCandidates()");
  });

  it("причина перехода называется, а не молчит", () => {
    // Без причины «перевод работает» и «перевод работает дорого» выглядят
    // одинаково — именно так трата через Anthropic и жила незамеченной.
    expect(ИСХОДНИК).toContain("deepl_quota_exhausted");
    expect(ИСХОДНИК, "фактический исполнитель не уходит в учёт расхода").toContain("out.provider");
  });
});
