import { withCors, LINKS_ARE_MEMORY_ONLY } from "../_lib";
import { kvBackend, kvDegradedSince } from "../_persist";

/**
 * GET /api/payments/v1/health — переживут ли платёжные данные перезапуск.
 *
 * ЗАЧЕМ. Слой хранения умеет работать на запасной памяти процесса, когда
 * настоящее хранилище не настроено или отвалилось, и честно об этом знает:
 * есть kvBackend() и kvDegradedSince(), есть проверяемые чтения
 * kvGetChecked/kvListChecked.
 *
 * Замер 29.08.2026: проверяемые чтения не звал НИКТО, а состояние хранилища
 * наружу не отдавалось нигде. То есть возвраты, споры и аудиторский след
 * могли писаться в Map, исчезающую при перезапуске, и каждый ответ выглядел
 * бы нормальным. Механизм был, читателя не было — тот же класс, что с
 * providerStatus() в бэкенде.
 *
 * ЧТО ОТДАЁМ. Только ответ на вопрос, а не устройство системы: `durable`
 * вместо имени хранилища. Наружу — категория, не инфраструктура.
 */
export async function GET() {
  const durable = kvBackend() === "kv";
  // Поле durable отвечает ТОЛЬКО за записи, которые идут через KV: возвраты,
  // споры, аудит, очередь вебхуков. Сами платёжные ссылки в KV не пишутся
  // вовсе, поэтому у них свой ответ. Без этого разделения поле оказалось бы
  // шире того, что измеряет: настроят Redis — durable станет true, и
  // «сохраняются долговременно» будет неправдой про ссылки.
  const linksDurable = !LINKS_ARE_MEMORY_ONLY;
  const degraded = kvDegradedSince();
  return withCors(
    Response.json({
      ok: true,
      // Переживут ли записи перезапуск процесса.
      durable,
      // Если хранилище отвалилось на ходу — когда это случилось.
      degradedSince: degraded?.at ?? null,
      // Ссылки живут в памяти процесса независимо от настройки хранилища.
      linksDurable,
      note: durable
        ? "Платёжные записи сохраняются долговременно."
        : "ВНИМАНИЕ: записи хранятся в памяти процесса и исчезнут при перезапуске.",
    })
  );
}
