/**
 * Запасной выбор задачи дня — когда сервер недоступен.
 *
 * Основной путь серверный (одна задача на всех, чтобы результаты в таблице
 * сравнивались честно). Этот код срабатывает, только если сервер не ответил,
 * и обязан давать ОДИНАКОВЫЙ ответ всем в один и тот же день: иначе двое
 * решают разные задачи и сравнивают несравнимое.
 *
 * Вынесено из page.tsx 28.08.2026. Проверка рядом: __tests__/dailyPick.test.ts
 */
function daysSinceEpoch(){return Math.floor(Date.now()/86400000)}

export function pickDailyIdx(total:number){if(total<=0)return 0;const n=daysSinceEpoch();let h=n*2654435761;h=(h^(h>>>16))>>>0;return h%total}
