import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { bezKommentariev } from "./bezKommentariev";

/**
 * Оверлей для OBS уходит В ЭФИР: его смотрят зрители стрима, а не мы.
 *
 * Замер 04.09.2026: точка «в эфире» была зелёной ВСЕГДА — при обрыве потока
 * менялось только мигание. То есть на трансляцию шёл живой индикатор рядом с
 * застывшей позицией, и зритель читал старый ход как текущий. Там же в
 * русский эфир уходило английское «Game ended».
 *
 * Сторож читает исходник, а не отрисовку: страница живёт на SSE, поднимать её
 * в тесте дороже, чем закрепить сами решения. Граница честная — он стережёт
 * ЗАВИСИМОСТЬ индикатора от состояния связи, а не то, как это выглядит.
 */
const ФАЙЛ = join(__dirname, "..", "obs", "[gameId]", "page.tsx");

describe("оверлей OBS не врёт про эфир", () => {
  const код = bezKommentariev(readFileSync(ФАЙЛ, "utf8"));

  it("цвет точки зависит от связи, а не задан постоянным", () => {
    expect(код).toContain("background: connected ?");
  });

  it("«ещё не подключились» и «связь оборвалась» — разные подписи", () => {
    expect(код).toContain("Связь потеряна");
    expect(код).toContain("Подключаемся…");
    // разными они должны быть и по смыслу: одинаковый текст лишает флаг силы
    expect(код).toContain("byloSoedinenie ?");
  });

  it("при обрыве не показывается ход и счёт ходов как текущие", () => {
    // подпись хода стоит ПОД условием connected, а не рядом с ним
    expect(код).toContain("{connected");
  });

  it("в эфир не уходит английский текст завершения", () => {
    expect(код).not.toContain("Game ended");
    expect(код).toContain("Партия завершена");
  });
});
