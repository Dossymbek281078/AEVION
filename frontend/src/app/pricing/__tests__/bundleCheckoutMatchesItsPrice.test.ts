import { describe, test, expect } from "vitest";
import { gumroadPermalink, GUMROAD_DEFAULT_PERMALINK } from "@/lib/gumroad";
import { productById } from "@/lib/products";
import pricing from "./__fixtures__/pricing.json";

/**
 * Цена на карточке набора совпадает с ценой в кассе, куда ведёт её кнопка.
 *
 * 🔴 НАЙДЕНО 02.09.2026, ПРОВЕРЕНО КАК ПОКУПАТЕЛЕМ. На `/pricing` три набора
 * показывают цену и кнопку «Get Access →». Кнопка ведёт не туда:
 *
 *     IP Suite        $29/мес   →  AEVION All-Access $59/мес
 *     AI Suite        $33/мес   →  то же
 *     Fintech Suite   $39/мес   →  то же
 *
 * Конечный адрес кассы, прочитанный по кнопке IP Suite:
 *
 *     gumroad.com/checkout?…&id=xpxzam&price=5900&recurrence=monthly
 *
 * ПОЧЕМУ. У наборов нет своей кассы нигде — ни в каталоге сайта, ни у
 * провайдера. Страница строит ссылку как `gumroadCheckoutUrl({ key: b.id })`,
 * а неизвестный ключ отдаёт товар ПО УМОЛЧАНИЮ, и по умолчанию это
 * All-Access. В `lib/gumroad.ts` это описано прямым текстом и названо
 * отдельной задачей — но речь там о МОДУЛЯХ, наборы в тот список не попали.
 *
 * Класс общий: цена приходит из ответа `/api/pricing`, а ссылка — из карты
 * пермалинков, и сойтись они не обязаны ничем. Проверяющий видит поле
 * «цена» и поле «ссылка» порознь, а человек видит ПАРУ.
 *
 * ЧТО РЕШАЕТ ОСНОВАТЕЛЬ, а не этот файл: заводить ли товары под наборы,
 * убрать ли цены с карточек, снять ли наборы до запуска. Цена и состав
 * пакетов — не наше решение, поэтому здесь ничего не «чинится»: сторож лишь
 * не даёт ЧЕТВЁРТОМУ набору появиться с той же ошибкой незамеченно.
 * Разбор для основателя: 06-Витрина-цены-SEO\2026-09-02-НАБОРЫ-цена-…
 *
 * ГРАНИЦА. Проверяются НАБОРЫ. У тарифов ссылка строится иначе (через
 * `tier`), и молчание сторожа о них — честное «не проверял», а не «там
 * хорошо».
 */

/**
 * Известные расхождения. Убирать записи ТОЛЬКО вместе с починкой: у набора
 * появилась своя касса, либо цена с карточки снята, либо набор убран.
 * Дописывать сюда новые — значит признать, что мы сознательно показываем
 * человеку одну цену, а берём другую. Так делать нельзя.
 */
const ИЗВЕСТНЫЕ = new Map<string, string>([
  ["ip-suite", "ждёт решения основателя от 02.09.2026: своей кассы нет"],
  ["ai-suite", "ждёт решения основателя от 02.09.2026: своей кассы нет"],
  ["fintech-suite", "ждёт решения основателя от 02.09.2026: своей кассы нет"],
]);

interface Набор {
  id: string;
  name: string;
  priceMonthly?: number;
}

const НАБОРЫ = (pricing as { bundles?: Набор[] }).bundles ?? [];

/** Цена в кассе, куда ведёт кнопка набора. */
function ценаВКассе(id: string): { permalink: string; цена?: number } {
  const permalink = gumroadPermalink({ key: id });
  return { permalink, цена: productById(permalink)?.priceUsd };
}

describe("цена набора совпадает с ценой в его кассе", () => {
  test("контроль: наборы прочитаны и у них есть цены", () => {
    // Пустой список сделал бы проверку ниже зелёной при любом состоянии.
    expect(НАБОРЫ.length, "в ответе прода нет наборов — разбор сломан").toBeGreaterThanOrEqual(3);
    expect(
      НАБОРЫ.filter((b) => typeof b.priceMonthly === "number").length,
      "ни у одного набора нет цены — сравнивать нечего",
    ).toBeGreaterThanOrEqual(3);
  });

  test("контроль: способ вообще умеет находить цену в кассе", () => {
    // Проба с известным ответом: у товара по умолчанию цена есть.
    expect(
      productById(GUMROAD_DEFAULT_PERMALINK)?.priceUsd,
      "не нахожу цену даже у товара по умолчанию — способ негоден",
    ).toBeGreaterThan(0);
  });

  test("ни один набор не показывает цену, отличную от кассовой", () => {
    const расхождения: string[] = [];
    for (const b of НАБОРЫ) {
      if (typeof b.priceMonthly !== "number") continue;
      const { permalink, цена } = ценаВКассе(b.id);
      if (typeof цена !== "number") continue;
      if (цена === b.priceMonthly) continue;
      if (ИЗВЕСТНЫЕ.has(b.id)) continue;
      расхождения.push(`${b.id}: на карточке $${b.priceMonthly}, в кассе $${цена} (${permalink})`);
    }
    expect(
      расхождения,
      "набор показывает одну цену, а ведёт в кассу с другой — человек видит " +
        "подмену суммы в момент оплаты и чаще всего просто уходит",
    ).toEqual([]);
  });

  test("список известных не протух: каждая запись всё ещё расходится", () => {
    // Иначе список переживёт починку и будет прикрывать уже здоровое место.
    const починенные: string[] = [];
    for (const [id, причина] of ИЗВЕСТНЫЕ) {
      const b = НАБОРЫ.find((x) => x.id === id);
      if (!b || typeof b.priceMonthly !== "number") continue;
      const { цена } = ценаВКассе(id);
      if (typeof цена === "number" && цена !== b.priceMonthly) continue;
      починенные.push(`${id} (${причина})`);
    }
    expect(починенные, "запись больше не расходится — уберите её из списка").toEqual([]);
  });
});
