/** Входы с ценами и страницы оплаты. Порядок не важен, важна полнота. */
export const ПУТИ_БЕЗ_ЗНАЧКА = [
  "/pricing", // страница оплаты: значок стоял над кнопкой «Купить»
  "/bureau", // адрес из писем лабораториям
  "/go", // единственный вход, который доводит до цен (16 из 19 у Instagram)
  "/devhub", // вход Product Hunt: 14 сессий, до цен 0
  "/cyberchess", // бесплатный магнит, с которого единственная живая попытка оплаты
] as const;

/**
 * Прятать ли значок на этом пути.
 *
 * `null` значит «путь неизвестен» (usePathname() так отвечает вне контекста
 * маршрутизации) — тогда ведём себя как раньше и показываем. Без этого запаса
 * значок падал и РОНЯЛ ВСЮ ШАПКУ: поймано прогоном 02.10 на чужом тесте
 * keepChannelLink с «Cannot read properties of null».
 */
export function скрытьЗначокПрогресса(путь: string | null | undefined): boolean {
  const п = путь ?? "";
  if (!п) return false;
  return ПУТИ_БЕЗ_ЗНАЧКА.some((пр) => п === пр || п.startsWith(`${пр}/`));
}
