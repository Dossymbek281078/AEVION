/**
 * Отказ поставщика писем не должен быть невидимым.
 *
 * Самый тихий провал на денежном пути: человек заплатил, письмо с доступом не
 * ушло — и об этом не знает никто. Признак `emailSent` из
 * `provisionSubscription` возвращается вызывающему, но замер 01.09.2026: его не
 * читает НИ ОДНА из четырёх касс (gumroad, lemonSqueezy, paybox, paypal).
 *
 * Соседние ветки той же функции при отказе капчурят — исключение, пустой id,
 * вырожденный режим. Молчала ровно одна: отказ поставщика по HTTP. Такая
 * непоследовательность внутри одной функции почти всегда недосмотр, а не выбор.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const исходник = readFileSync(join(process.cwd(), "src/routes/provisioning.ts"), "utf8");

/** Кусок функции отправки: от объявления до конца её catch. */
function телоОтправки(): string {
  const от = исходник.indexOf("export async function sendEmail");
  expect(от, "не нашёл функцию отправки — проверка смотрит не туда").toBeGreaterThan(0);
  const до = исходник.indexOf("\n}", исходник.indexOf("catch", от));
  return исходник.slice(от, до);
}

/**
 * Ветка отказа поставщика — от `if (!r.ok)` до следующей ветки.
 *
 * Границу берём по `if (!j.id)`, а НЕ по слову «degraded»: оно стоит ещё в
 * сигнатуре функции, то есть ДО ветки отказа, и срез выходил пустым. Проверка
 * `not.toContain` на пустой строке проходит всегда — так у меня одна проверка
 * (про персональные данные) была вакуумной и зелёной. Поймано мутацией: она
 * ловилась СОСЕДНИМ утверждением, и пустоту это маскировало.
 */
function веткаОтказа(тело: string): string {
  const от = тело.indexOf("if (!r.ok)");
  const до = тело.indexOf("if (!j.id)");
  expect(от, "не нашёл ветку отказа").toBeGreaterThan(0);
  expect(до, "не нашёл следующую ветку — граница среза неверна").toBeGreaterThan(от);
  return тело.slice(от, до);
}

describe("отказ поставщика писем виден", () => {
  const тело = телоОтправки();

  it("контроль охвата: в теле есть и ветка отказа, и соседние", () => {
    // Без него «capture на месте» одинаково выглядит при исправном коде и при
    // вырезке, которая ухватила не ту часть файла.
    expect(тело).toContain("if (!r.ok)");
    expect(тело).toContain("degraded");
  });

  it("ветка отказа оставляет след", () => {
    const отказ = тело.slice(тело.indexOf("if (!r.ok)"));
    expect(
      отказ.slice(0, отказ.indexOf("return")),
      "отказ поставщика уходит молча: человек заплатил, письма нет, и никто не знает",
    ).toContain("capture(");
  });

  it("след есть и в журнале, и в Sentry — это не избыточность", () => {
    // Sentry видит тот, кто за ним следит. Журнал сервиса читают, когда
    // разбирают конкретную жалобу «я заплатил, письма нет». Моя первая
    // редакция писала ТОЛЬКО в Sentry, и чужой поведенческий тест это
    // справедливо поймал: на проде без Sentry отказ снова стал бы невидимым.
    const отказ = веткаОтказа(тело);
    expect(отказ, "нет следа в журнале").toContain("console.warn(");
    expect(отказ, "нет следа в Sentry").toContain("capture(");
    // В журнале обязаны быть домен и код ответа: по ним отличают
    // «домен отправителя не подтверждён» от «получатель отвергнут».
    expect(отказ).toContain("доменПолучателя");
    expect(отказ).toContain("HTTP ${r.status}");
  });

  it("след называет ЧТО и КОМУ — иначе он бесполезен", () => {
    expect(тело).toContain("subject: payload.subject");
    expect(тело).toContain("recipientDomain");
  });

  it("адрес получателя целиком в след не пишем", () => {
    // Персональные данные. Для разбора хватает домена: именно по нему
    // различаются «домен отправителя не подтверждён» и «получатель отвергнут».
    const отказ = веткаОтказа(тело);
    expect(отказ).not.toContain("to: payload.to");
  });

  it("письмо по-прежнему не роняет выдачу доступа", () => {
    // Отправка возвращает признак, а не бросает: доступ важнее письма.
    expect(тело).toContain('return { ok: false, mode: "real", error: причина };');
  });
});
