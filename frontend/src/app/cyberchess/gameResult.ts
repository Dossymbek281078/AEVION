/* Исход сохранённой партии одной функцией.

   Было три разных классификации в трёх местах, и одна из них — в панели статистики
   по контролям — считала победы как `result.includes("win")`. Строка поражения
   «Checkmate — AI wins» тоже содержит "win", поэтому такая партия попадала И в
   победы, И в поражения; ничьи там считаются как total−w−l и уходили в МИНУС, а
   процент побед был завышен. Плюс «Time out» и «You resigned» не подходили ни под
   один фильтр и молча зачислялись в ничьи.

   Каноном взята та классификация, что уже стояла в расчёте серий: она верна для
   всех строк, которые ставит sOver(...). */
/* Список строк ниже — полный набор того, что реально передаётся в sOver(...):
   "Checkmate! You win! 🏆", "Checkmate — AI wins", "Stalemate",
   "Threefold repetition", "Insufficient material", "50-move draw",
   "AI timed out — you win!", "Draw agreed", "Time out", "You resigned",
   "Ничья (договорились)", "<соперник> сдался — Вы победили!",
   и — ОТДЕЛЬНЫМ словарём — исходы вариантов, которые ставит тот же sOver:
   "⚡ Три шаха — победа!" / "⚡ Соперник дал 3 шаха — поражение",
   "⛰ Король взошёл на холм — победа!" / "⛰ Соперник занял центр — поражение",
   "💥 Король соперника взорван — победа!" / "💥 Твой король взорван — поражение",
   "Королевский ферзь соперника пал — победа!" / "Твой королевский ферзь пал — поражение".

   Первая версия этой функции знала не все: тройное повторение, недостаток
   материала и русская «Ничья (договорились)» уходили в поражения, а победа в
   партии с живым соперником («сдался — Вы победили!») — тоже в поражения.
   Здесь считается рейтинг и серии, поэтому промах стоит игроку рейтинга.

   Третий промах того же рода (2026-07-27): список выше объявлял себя ПОЛНЫМ, но
   четыре варианта — Три шаха, Король на холме, Атомные, Королевский ферзь —
   заканчиваются словом «победа!», которого здесь не было. Партия сохраняется в
   историю эффектом на `over`, то есть варианты в неё попадают наравне со всеми,
   и выигранная партия в варианте молча шла в ПОРАЖЕНИЯ: рейтинг, серия, DNA,
   зеркало, дашборд и тег результата в PGN — всё считало её проигрышем. Урок тот
   же, что и в прошлые два раза: комментарий «полный набор» стареет ровно тогда,
   когда кто-то добавляет пятый sOver в другом конце файла. Тест ниже держит
   словарь в тонусе — он перечисляет строки поимённо. */
export function gameResultOf(result: string): "W" | "L" | "D" {
  const r = result.toLowerCase();
  // «поражение» проверяется ПЕРВЫМ: у вариантов победа и поражение — соседние
  // ветки одного тернарника, и порядок здесь единственное, что их разводит.
  if (r.includes("поражение")) return "L";
  if (r.includes("you win") || r.includes("win!") || r.includes("вы победили") || r.includes("победа")) return "W";
  if (
    r.includes("draw") ||
    r.includes("stalemate") ||
    r.includes("repetition") ||
    r.includes("insufficient") ||
    r.includes("ничья") ||
    r.includes("пат")
  ) return "D";
  return "L";
}
