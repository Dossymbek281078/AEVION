/**
 * Решение «возвращать ли задачу, которую просил адрес».
 *
 * Зачем отдельной функцией, а не условиями внутри эффекта. 07.10 я закрыл ОДИН
 * путь подмены задачи по ссылке и доложил «починено»; проверка на проде 08.10
 * показала, что ссылка по-прежнему открывает чужую задачу. Второй раз отдавать
 * непроверенную починку нельзя, а эффект на странице из 16 тысяч строк вызовами с
 * известным ответом не проверишь. Здесь — проверишь.
 *
 * Мера оборонительная, и это сказано вслух: она не знает, КТО подменяет задачу
 * (установщиков в модуле больше десяти, и воспроизвести порядок без наблюдения на
 * живой странице не удалось). Она лишь возвращает на доску то, что просил адрес,
 * пока открыто короткое окно после загрузки.
 *
 * Ограничения обязательны, иначе лечение хуже болезни: без них человек нажмёт
 * «другая задача», а она вернётся — и экран станет неуправляемым.
 */

export interface ЦельСсылки {
  /** Позиция, которую просил адрес. */
  fen: string;
  /** Сколько раз уже возвращали. */
  попытки: number;
  /** До какого момента (мс эпохи) возвращать. */
  доМс: number;
}

export type РешениеВозврата =
  | { действие: "ничего"; причина: string }
  | { действие: "вернуть"; причина: string }
  | { действие: "сдаться"; причина: string };

/**
 * @param цель что просил адрес (или null — ссылки не было)
 * @param текущаяFen позиция, которая стоит на доске сейчас (или null)
 * @param сейчасМс текущее время
 * @param естьВПуле есть ли запрошенная позиция в доступном пуле задач
 *
 * «сдаться» означает: окно кончилось, попытки исчерпаны или вернуть нечем —
 * цель сбрасывается, и больше в неё не возвращаемся. Это НЕ ошибка: ссылка могла
 * указывать на задачу, которую сузили фильтры, и человеку надо сказать это, а не
 * молча показывать чужую.
 */
export function reshenieVozvrata(
  цель: ЦельСсылки | null,
  текущаяFen: string | null,
  сейчасМс: number,
  естьВПуле: boolean,
): РешениеВозврата {
  if (!цель) return { действие: "ничего", причина: "ссылки не было" };
  if (сейчасМс > цель.доМс) return { действие: "сдаться", причина: "окно возврата истекло" };
  if (цель.попытки >= 3) return { действие: "сдаться", причина: "попытки исчерпаны" };
  if (!текущаяFen) return { действие: "ничего", причина: "на доске пока ничего нет" };
  if (текущаяFen === цель.fen) return { действие: "ничего", причина: "на доске та самая задача" };
  if (!естьВПуле) return { действие: "сдаться", причина: "запрошенной задачи нет в текущем пуле" };
  return { действие: "вернуть", причина: "на доске чужая задача, окно ещё открыто" };
}
