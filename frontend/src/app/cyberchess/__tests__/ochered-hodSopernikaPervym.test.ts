import { describe, it, expect } from "vitest";
import { readFileSync } from "fs";
import { join } from "path";

/**
 * Один воркер движка обслуживает четыре задачи: ход соперника, разбор сыгранных
 * ходов, оценку позиции и сбор данных для рейтинга. До правки очередь была
 * строго по порядку поступления, и ход соперника ждал за чужим расчётом.
 *
 * Замер лентой 31.08.2026 (мс от нажатия человека):
 *    1190  ← соперник ответил        сам ход считается 1.2 с
 *    6383  go depth 18               начался расчёт рейтинга
 *   13475  ← bestmove                держал воркер 7.1 с
 * Ответ на СЛЕДУЮЩИЙ ход стоял за ним. Отсюда рост 1 → 4 → 6 → 8 секунд.
 *
 * Правило: ход соперника — единственное, чего человек ЖДЁТ за доской.
 * Результата остальных расчётов он в этот момент не видит.
 */

const KOD = () => readFileSync(join(process.cwd(), "src/app/cyberchess/page.tsx"), "utf8");

describe("ход соперника идёт первым", () => {
  it("встаёт в НАЧАЛО очереди, а не в конец", () => {
    const s = KOD();
    expect(s.length).toBeGreaterThan(100000); // контроль: файл прочитан
    expect(s).toContain('if(job.kind==="go"){');
    expect(s).toContain("this.q.unshift(job);");
  });

  it("прерывает чужой расчёт, но не такой же ход", () => {
    const s = KOD();
    expect(s).toContain('if(this.cur&&this.cur.kind!=="go"){try{this.w?.postMessage("stop")}catch{}}');
  });

  it("остальные запросы по-прежнему в конец", () => {
    // Если бы приоритет получили все, очередь стала бы стопкой и самый старый
    // запрос не выполнялся бы никогда.
    const s = KOD();
    expect(s).toContain("}else{\n      this.q.push(job);\n    }");
  });

  it("правило «по одному запросу каждого вида» сохранено", () => {
    // Оно отбрасывает устаревшие запросы прошлой позиции. Приоритет не должен
    // был его отменить.
    const s = KOD();
    expect(s).toContain("this.q=this.q.filter(j=>j.kind!==job.kind);");
  });
});
