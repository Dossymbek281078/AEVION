import { describe, it, expect } from "vitest";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Чек цепочки не превращает «не знаем» в «не подтверждено».
 *
 * Страница обещает проверяемость, поэтому у неё ЧЕТЫРЕ исхода на шаг, а не два:
 * подтверждено / отозвано / не найдено / проверить не удалось. Схлопывание
 * последних двух в «не подтверждено» обвиняло бы человека в подделке из-за
 * нашего же обрыва связи — это ровно тот класс, который мы весь месяц
 * вычищаем из кода.
 *
 * Сторож читает ИСХОДНИК: страница ходит в сеть, и поднимать её ради проверки
 * набора состояний дороже пользы. Границу называю честно — отрисовку он не
 * проверяет.
 */

const СТРАНИЦА = readFileSync(
  join(__dirname, "..", "page.tsx"),
  "utf8",
);

function безКомментариев(src: string): string {
  // Блочные комментарии вырезаем ПО СОДЕРЖИМОМУ, а не по началу строки.
  //
  // Построчный отбор пропускал JSX-комментарий: он начинается с `{`, а не с
  // `/*`, — и весь его текст доезжал до проверок как код. 04.09.2026 это дало
  // ложную находку «русский текст зашит», указывающую на строку, которой в
  // разметке нет вовсе.
  return src
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .split("\n")
    .filter((l) => {
      const t = l.trim();
      return !t.startsWith("//") && !t.startsWith("*") && !t.startsWith("/*");
    })
    .join("\n");
}

describe("чек цепочки честен", () => {
  it("контроль: файл прочитан и это действительно страница", () => {
    expect(СТРАНИЦА.length, "файл пуст или не найден").toBeGreaterThan(1500);
    expect(СТРАНИЦА, "не похоже на страницу").toContain("export default function");
  });

  it("четыре исхода на шаг, а не два", () => {
    for (const с of ["ok", "revoked", "missing", "failed"]) {
      expect(СТРАНИЦА, `исход «${с}» пропал — «не знаем» схлопнется в «подделка»`)
        .toContain(`"${с}"`);
    }
  });

  it("сетевой отказ даёт «не удалось», а не «не подтверждено»", () => {
    // В catch обязан стоять именно failed: это утверждение о НАШЕЙ связи,
    // а не о подписи человека.
    const i = СТРАНИЦА.indexOf("catch");
    expect(i, "нет обработки отказа сети вовсе").toBeGreaterThan(-1);
    expect(
      СТРАНИЦА.slice(i, i + 260),
      "после обрыва связи страница утверждает что-то о подписи",
    ).toContain("failed");
  });

  it("про предварительный режим сказано вслух", () => {
    const src = безКомментариев(СТРАНИЦА);
    expect(src, "страница молчит о preview — обещает проверяемость, которой нет")
      .toContain("previewWarn");
    expect(src, "признак preview не читается из ответа").toContain("preview");
  });

  it("ссылка «открыть шаг» ведёт в существующий маршрут", () => {
    // Демонстрационная страница ссылается на комнату подписи. Мёртвая
    // ссылка здесь дороже обычной: человек пришёл ПРОВЕРЯТЬ, и первый же
    // переход, ведущий в никуда, отменяет всё, ради чего страница есть.
    // Замер 04.09.2026: маршрут qsign/verify/[id] существует.
    const src = безКомментариев(СТРАНИЦА);
    expect(src, "страница перестала ссылаться на комнату подписи")
      .toContain("/qsign/verify/");
    const marshrut = join(__dirname, "..", "..", "qsign", "verify", "[id]");
    expect(existsSync(marshrut), `маршрута ${marshrut} нет — ссылка ведёт в 404`).toBe(true);
  });

  it("подписи идут через словарь, а не зашиты", () => {
    const src = безКомментариев(СТРАНИЦА);
    // Проверяем СОДЕРЖИМОЕ строковых литералов, а не строки файла.
    //
    // Первая редакция искала кириллицу шаблоном «кавычка … кириллица …
    // кавычка» и склеивала ДВА СОСЕДНИХ литерала через промежуток между
    // ними. Стоило появиться кириллическому имени переменной между двумя
    // строками — { состояние: "missing", подпись: "unknown" } — и сторож
    // объявил нарушением четыре строки исправного кода. Имена переменных
    // человек не читает; читает он содержимое литералов.
    const литералы: string[] = [];
    let i = 0;
    while (i < src.length) {
      const c = src[i];
      if (c === '"' || c === "'" || c === "`") {
        const конец = src.indexOf(c, i + 1);
        if (конец < 0) break;
        литералы.push(src.slice(i + 1, конец));
        i = конец + 1;
      } else {
        i += 1;
      }
    }
    // Подстановки внутри шаблонных строк — это КОД, а не текст: имя переменной
    // человек не читает. Убираем их, иначе сторож ловит то, ради чего не заводился.
    const русские = литералы
      .map((v) => v.replace(/\$\{[^}]*\}/g, ""))
      .filter((v) => /[А-Яа-яЁё]{3,}/.test(v));
    expect(русские.map((v) => v.slice(0, 60)), "русский текст зашит в разметке")
      .toEqual([]);
  });
});
