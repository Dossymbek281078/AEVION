/**
 * Потолок гостей у тренера — ОБЩАЯ корзина, и её размер решает день запуска.
 *
 * Ограничитель считает всех незалогиненных ОДНИМ ключом "anon": предел не «на
 * человека», а на всю платформу сразу. При 120/мин двести пришедших по два
 * вопроса выбирают его за минуту, и отказ получают ВСЕ, включая того, кто
 * спросил первым. Решение оркестратора 28.09 к запуску 30.09 — поднять до 600.
 *
 * Здесь закрепляется не «красивое число», а ДВА свойства, потеря которых
 * незаметна глазом: корзина у гостей общая (значит предел надо читать как
 * платформенный) и вошедший считается отдельно от гостей.
 */

import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const КОД = readFileSync(join(__dirname, "..", "src", "routes", "coach.ts"), "utf8");
const БЛОК = КОД.slice(КОД.indexOf("const anonCoachCeiling"), КОД.indexOf("coachRouter.post(\"/chat\""));

describe("потолок гостей у тренера", () => {
  it("рассчитан на день запуска, а не на пять посетителей", () => {
    const m = /max:\s*(\d+)/.exec(БЛОК);
    expect(m, "у потолка нет числа").toBeTruthy();
    const предел = Number(m![1]);
    // 200 пришедших × 2 вопроса = 400 в минуту. Запас обязан быть выше.
    expect(предел).toBeGreaterThanOrEqual(400);
  });

  it("окно осталось минутой — иначе число значит другое", () => {
    // Без этой проверки предел можно «поднять», растянув окно, и получить
    // ту же тесноту под большим числом.
    expect(БЛОК).toContain("windowMs: 60_000");
  });

  it("корзина у гостей общая, а вошедший считается отдельно", () => {
    // Это и есть причина, по которой предел читается как платформенный.
    // Если ключ гостя перестанет схлопываться — число 600 надо пересмотреть.
    expect(БЛОК).toContain('? "anon"');
    expect(БЛОК).toMatch(/u:\$\{/);
  });
});
