import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * Нажатие, которое не удалось, оставляет след на экране.
 *
 * ПОВОД (29.08.2026, ворота запуска 4). Кнопка «построить обоснование»
 * при отказе бэкенда делала `setJustState("idle")` — уходила в «…» и
 * возвращалась к исходной подписи, не сказав ни слова. Для человека это
 * неотличимо от «я не нажимал»: он жмёт ещё раз и получает ту же тишину.
 *
 * Признак, по которому это нашлось за минуту: НЕПОСЛЕДОВАТЕЛЬНОСТЬ
 * ВНУТРИ ОДНОЙ ПАНЕЛИ. Соседняя кнопка «проверить» отказ показывала
 * честно («— неизвестно»), а «построить» молчала. Один автор, одно
 * место, разное поведение — почти всегда недосмотр, а не решение.
 *
 * Закрепляем три вещи, каждая из которых по отдельности обходится:
 *   1) отказ построения ведёт в СВОЁ состояние, а не в исходное;
 *   2) у этого состояния есть текст на экране (иначе оно невидимо);
 *   3) состояние вообще объявлено в типе (иначе пункт 1 не соберётся).
 */
const NEWLINE = String.fromCharCode(10);
const SOURCE = readFileSync(path.join(__dirname, "_client.tsx"), "utf8");

function bodyOf(name: string): string {
  const at = SOURCE.indexOf("const " + name + " = useCallback");
  expect(at, "обработчик " + name + " не найден — сканер смотрит не туда").toBeGreaterThan(-1);
  // Окном, а не регуляркой: собранная из строки регулярка на этой
  // машине теряет обратные слэши и молча находит ноль.
  return SOURCE.slice(at, at + 1600);
}

describe("отказ нажатия виден человеку", () => {
  it("построение обоснования не возвращается в исходное состояние молча", () => {
    const body = bodyOf("requestJustification");
    const at = body.indexOf("} catch");
    expect(at, "у построения обоснования нет обработки отказа вовсе").toBeGreaterThan(-1);
    // Только КОД: строки-комментарии выбрасываем. Первая версия этого
    // сторожа покраснела на комментарии, который я сам же написал внутри
    // catch — там процитирован прежний вызов. Свой пояснительный текст
    // попадает под собственный шаблон так же легко, как чужой.
    const handler = body
      .slice(at, at + 700)
      .split(NEWLINE)
      .filter((l) => !l.trim().startsWith("//"))
      .join(NEWLINE);

    expect(
      handler.includes('setJustState("idle")'),
      "отказ построения возвращает панель в исходное состояние — человек не отличит это от ненажатой кнопки",
    ).toBe(false);
    expect(
      handler.includes('setJustState("failed")'),
      "отказ построения не переводит панель ни в какое видимое состояние",
    ).toBe(true);
  });

  it("состояние отказа объявлено и показывается", () => {
    expect(SOURCE.includes('| "failed">'), "состояния failed нет в типе").toBe(true);
    expect(
      SOURCE.includes('t("qskyway.just.failed")'),
      "состояние есть, а текста для человека нет — отказ снова невидим",
    ).toBe(true);
  });

  it("соседняя кнопка проверки по-прежнему показывает свой отказ", () => {
    // Отрицательный контроль по образцу: если бы «неизвестно» исчезло,
    // правило выше можно было бы выполнить, сделав ОБЕ кнопки молчащими,
    // и сторож этого не заметил бы.
    expect(SOURCE.includes('t("qskyway.just.unknown")'), "проверка перестала показывать свой отказ").toBe(true);
  });
});
