/**
 * 🔴 ТАРИФ DevHub «СТАРТ» $15/мес — ПО НОРМАМ, И ОНИ ЧЕСТНО МЕЖДУ.
 *
 * Слово основателя 12.10.2026: «Старт по нормам — да»; названы четыре числа —
 * 300 генераций, 100 выкаток, 60 картинок, 15 видео в месяц, помесячно.
 *
 * ПОЧЕМУ НОРМЫ, А НЕ «ОДИН САЙТ». Первая постановка была «$15 = один живой
 * сайт», и я начал её строить. Остановил вопрос «а что гость получает даром?».
 * Замер по коду: у гостя 30 генераций и 10 выкаток в месяц, живой адрес
 * БЕССРОЧНО, свой домен без гейта и неограниченное число сайтов. То есть «один
 * сайт» за деньги продавал бы МЕНЬШЕ, чем бесплатный вход даёт бесплатно.
 *
 * Сторож держит три свойства:
 *   1. четыре числа основателя стоят литералами — политику пишем числом;
 *   2. ступень лежит СТРОГО между `registered` и `pro` по КАЖДОЙ норме, иначе
 *      платный тариф оказался бы местами хуже бесплатного или равен полному;
 *   3. механизм СПИТ, пока вариант товара не заведён: ни один человек не может
 *      оказаться на ступени, которую нельзя купить.
 */
import { describe, it, expect } from "vitest";
import { НОРМЫ_СТАРТ, ЦЕНА_СТАРТ_USD, СЛАГ_СТАРТ, tarifStartZaveden, ПЕРЕМЕННАЯ_ВАРИАНТА_СТАРТ } from "../src/lib/devhubStart";

/** Нормы соседних ступеней — копия из routes/devhub.ts, сверяется проверкой ниже. */
const REGISTERED = { video: 9, image: 30, tts: 30000, music: 15, deploy: 30, speech: 15, translate: 150, generate: 90 };
const PRO = { video: 50, image: 200, tts: 200000, music: 100, deploy: -1, speech: 100, translate: 1000, generate: 1000 };

describe("тариф «Старт»", () => {
  it("🔴 четыре числа основателя — литералами", () => {
    expect(ЦЕНА_СТАРТ_USD).toBe(15);
    expect(НОРМЫ_СТАРТ.generate).toBe(300);
    expect(НОРМЫ_СТАРТ.deploy).toBe(100);
    expect(НОРМЫ_СТАРТ.image).toBe(60);
    expect(НОРМЫ_СТАРТ.video).toBe(15);
  });

  it("🔴 по КАЖДОЙ норме строго больше вошедшего и строго меньше полного", () => {
    const нарушения: string[] = [];
    for (const ключ of Object.keys(НОРМЫ_СТАРТ) as Array<keyof typeof НОРМЫ_СТАРТ>) {
      const с = НОРМЫ_СТАРТ[ключ] as number;
      const r = REGISTERED[ключ];
      const p = PRO[ключ];
      if (!(с > r)) нарушения.push(`${ключ}: ${с} не больше вошедшего ${r} — платить не за что`);
      // У pro «−1» означает «без предела»: любое конечное число меньше него.
      if (p !== -1 && !(с < p)) нарушения.push(`${ключ}: ${с} не меньше полного ${p} — полный тариф обесценен`);
    }
    expect(нарушения).toEqual([]);
  });

  it("🔴 нормы перечислены ПОЛНОСТЬЮ — знаменатель 8 из 8", () => {
    // Пропущенный ключ означал бы, что на этой ступени предела нет вовсе.
    expect(Object.keys(НОРМЫ_СТАРТ).sort()).toEqual(Object.keys(REGISTERED).sort());
  });

  it("🔴 механизм СПИТ, пока вариант товара не заведён", () => {
    const было = process.env[ПЕРЕМЕННАЯ_ВАРИАНТА_СТАРТ];
    delete process.env[ПЕРЕМЕННАЯ_ВАРИАНТА_СТАРТ];
    expect(tarifStartZaveden(), "ступень выдаётся без товара — купить её нельзя, а нормы уже даны").toBe(false);
    process.env[ПЕРЕМЕННАЯ_ВАРИАНТА_СТАРТ] = "  ";
    expect(tarifStartZaveden(), "пробелы считаются заведённым товаром").toBe(false);
    process.env[ПЕРЕМЕННАЯ_ВАРИАНТА_СТАРТ] = "123456";
    expect(tarifStartZaveden()).toBe(true);
    if (было === undefined) delete process.env[ПЕРЕМЕННАЯ_ВАРИАНТА_СТАРТ];
    else process.env[ПЕРЕМЕННАЯ_ВАРИАНТА_СТАРТ] = было;
  });

  it("слаг подписки назван и отличается от отдельного приложения devhub", () => {
    // `devhub` — это отдельное приложение за $200; «Старт» другой объём того же
    // модуля, и путать их нельзя: иначе купивший Старт получил бы полный тариф.
    expect(СЛАГ_СТАРТ).toBe("devhub_start");
    expect(СЛАГ_СТАРТ).not.toBe("devhub");
  });

  it("🔴 копия соседних норм в этом файле совпадает с кодом — иначе проверка сравнивает с выдумкой", () => {
    const src = require("node:fs").readFileSync(require("node:path").join(__dirname, "../src/routes/devhub.ts"), "utf8");
    for (const [ключ, знач] of Object.entries(REGISTERED)) {
      expect(src, `норма registered.${ключ} в коде не ${знач}`).toContain(`${ключ}: ${знач}`);
    }
  });
});
