export type ТранспортПисьма = "smtp" | "resend" | "нет";

export interface ИсходОтправки {
  ok: boolean;
  транспорт: ТранспортПисьма;
  причина: string | null;
  при: string;
}

const ИСХОДЫ: ИсходОтправки[] = [];
let всегоОтправлено = 0;
let всегоНеудач = 0;

/** Убирает адрес из текста ошибки провайдера: он там бывает дословно. */
export function безАдреса(текст: string): string {
  return текст.replace(/[^\s<>"']+@[^\s<>"']+/g, "<адрес>").slice(0, 200);
}

/**
 * Отметить исход одной отправки.
 *
 * Отказ SMTP с последующей удачей Resend даёт ОДИН отказ и ОДНУ отправку —
 * это намеренно: «письмо ушло вторым каналом» и «первый канал сломан» разные
 * факты, и нужны оба.
 */
export function записатьИсход(
  ok: boolean,
  транспорт: ТранспортПисьма,
  причина?: string,
): void {
  ИСХОДЫ.push({
    ok,
    транспорт,
    причина: причина ? безАдреса(причина) : null,
    при: new Date().toISOString(),
  });
  // Храним только хвост: это сигнал о состоянии, а не архив.
  if (ИСХОДЫ.length > 10) ИСХОДЫ.shift();
  if (ok) всегоОтправлено += 1;
  else всегоНеудач += 1;
}

/**
 * Состояние отправки для ручки здоровья.
 *
 * `последнийОтказ: null` значит «отказов не было С ЗАПУСКА процесса», а не
 * «всё хорошо вообще»: счёт начинается заново после каждой выкатки.
 */
export function статусОтправки(): {
  отправлено: number;
  неудач: number;
  последнийОтказ: ИсходОтправки | null;
  последний: ИсходОтправки | null;
} {
  const отказы = ИСХОДЫ.filter((x) => !x.ok);
  return {
    отправлено: всегоОтправлено,
    неудач: всегоНеудач,
    последнийОтказ: отказы.length ? отказы[отказы.length - 1] : null,
    последний: ИСХОДЫ.length ? ИСХОДЫ[ИСХОДЫ.length - 1] : null,
  };
}
