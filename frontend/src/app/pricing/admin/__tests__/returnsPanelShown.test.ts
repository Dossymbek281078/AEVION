/**
 * Отказы по кассам должны быть НА ЭКРАНЕ — и вместе с оговоркой.
 *
 * Событие `checkout_cancel` с кассой в мете пишется с 01.09, а читать его было
 * некому: ни сводки, ни панели. Данные собирались и умирали в журнале.
 *
 * Второе утверждение важнее первого. Адрес отмены задают только PayBox и
 * PayPal; у Gumroad и LemonSqueezy его нет, и отказ до нас НЕ ДОХОДИТ. Таблица
 * без этой оговорки читается наоборот: касса, про которую мы ничего не узнаём,
 * выглядит кассой без отказов, то есть лучшей. Числа тут ведут к выбору кассы,
 * и цена неверного вывода — деньги.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stripComments } from "../../../__tests__/helpers/sourceCode";

const страница = stripComments(
  readFileSync(join(process.cwd(), "src/app/pricing/admin/page.tsx"), "utf8"),
);

describe("панель возвратов из касс", () => {
  it("страница читает поля ответа", () => {
    expect(страница, "панель не читает разбивку по кассам").toContain("summary.returnsByProvider");
    expect(страница, "не показан общий счёт успехов").toContain("summary.returnsSuccess");
    expect(страница, "не показан общий счёт отказов").toContain("summary.returnsCancel");
  });

  it("рядом с таблицей стоит оговорка про кассы без адреса отмены", () => {
    /*
     * Проверяем СМЫСЛ, а не дословную фразу: текст оговорки будут править, и
     * сторож, закреплённый на написании, покраснеет от улучшения. Обе кассы,
     * от которых отказ не доходит, должны быть названы поимённо — иначе
     * оговорка не помогает выбрать.
     */
    const оговорка = страница.includes("не узнаём") || страница.includes("не доходит");
    expect(оговорка, "таблица без оговорки: ноль отказов прочтут как хороший показатель").toBe(true);
    expect(страница, "не названа касса, от которой отказ не доходит").toContain("Gumroad");
    expect(страница, "не названа вторая такая касса").toContain("LemonSqueezy");
  });

  it("пустую таблицу не показываем", () => {
    // Панель без строк читается как «отказов нет», хотя это «данных нет».
    expect(страница, "нет проверки на пустоту").toContain(
      "Object.keys(summary.returnsByProvider).length > 0",
    );
  });
});
