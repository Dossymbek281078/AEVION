const NAMES = ["title", "aria-label", "placeholder", "alt", "label", "tooltip", "ariaLabel"];
const ATTRS = NAMES.map((n) => n + "={");

// ВТОРАЯ ФОРМА ЗАПИСИ: подсказка="текст" БЕЗ фигурных скобок.
//
// 01.09.2026, тот же день. Сторож читал только форму со скобками, и я
// с ним же прошёл по платформе: получил 125 мест. Настоящих оказалось
// 1365 — занижение в одиннадцать раз, и успело разойтись по окнам.
// Именно так был записан русский в общем чипе: label="Провенанс данных".
//
// Отрицательный взгляд назад «(?<![A-Za-z-])» обязателен: без него
// subtitle= совпадает с title=, а ariaLabel= с label=.
const PLAIN = new RegExp(
  "(?<![A-Za-z-])(" + NAMES.join("|") + ")=\"([^\"]*)\"",
  "g",
);

function attributeExpressions(src: string): { at: number; expr: string }[] {
  const out: { at: number; expr: string }[] = [];
  const NL = String.fromCharCode(10);
  for (const a of ATTRS) {
    let i = 0;
    for (;;) {
      i = src.indexOf(a, i);
      if (i < 0) break;
      // Скобки считаем позиционно. Регулярка с классом, собранным строкой,
      // на этой машине теряет слэши на границе вызова и молча даёт ноль —
      // проверено дважды, оба раза сторож был зелёным на сломанном коде.
      let j = i + a.length;
      let depth = 1;
      while (j < src.length && depth > 0) {
        if (src[j] === "{") depth += 1;
        else if (src[j] === "}") depth -= 1;
        j += 1;
      }
      out.push({ at: src.slice(0, i).split(NL).length, expr: src.slice(i, j) });
      i = j;
    }
  }
  PLAIN.lastIndex = 0;
  for (;;) {
    const m = PLAIN.exec(src);
    if (!m) break;
    out.push({ at: src.slice(0, m.index).split(NL).length, expr: m[0] });
  }
  return out;
}

const hasCyrillic = (s: string) => /[\u0430-\u044f\u0410-\u042f]/.test(s);

function moduleFiles(): string[] {
  return fs
    .readdirSync(__dirname)
    .filter((f) => f.endsWith(".tsx") && !f.includes(".test."))
    .map((f) => path.join(__dirname, f));
}

describe("подсказки говорят на языке посетителя", () => {
  test("ни в одном атрибуте нет сырого русского текста", () => {
    const files = moduleFiles();

    // Контроль охвата. Без него «находок 0» неотличимо от «не прочитал ни
    // одного файла» — а именно так выглядел бы сторож, если каталог
    // переедет или расширение сменится.
    expect(files.length, "не прочитано ни одного файла модуля").toBeGreaterThan(0);

    let checked = 0;
    const bad: string[] = [];
    for (const f of files) {
      const src = fs.readFileSync(f, "utf8");
      for (const { at, expr } of attributeExpressions(src)) {
        checked += 1;
        if (hasCyrillic(expr)) {
          bad.push(path.basename(f) + ":" + at + "  " + expr.split(/[\s]+/).join(" ").slice(0, 90));
        }
      }
    }

    // Второй контроль: атрибуты вообще нашлись. Ноль проверенных выражений
    // дал бы зелёный цвет при полной слепоте разборщика скобок.
    expect(checked, "не найдено ни одного атрибута — разборщик ослеп").toBeGreaterThan(5);

    expect(
      bad,
      "сырой русский в атрибуте (" + bad.length + " из " + checked + "): подсказка не переведётся. " +
        bad.join(" | "),
    ).toEqual([]);
  });
});
