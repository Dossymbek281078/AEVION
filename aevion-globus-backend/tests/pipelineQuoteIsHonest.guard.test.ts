// Смета «книга → озвучка → фильм» обязана быть ЧЕСТНОЙ до запуска.
//
// ЗАЧЕМ. Человек просит сделать книгу, озвучить и снять по ней фильм. Текст
// идёт по нашим ключам, голос и видео — по кредитам Higgsfield. Не назвав цену
// заранее, мы либо ставим человека перед неожиданным счётом, либо молча платим
// сами. Здесь проверяется главное свойство прибора: он не преуменьшает цену и
// НЕ выдаёт неизвестное за известное.
import { describe, it, expect } from "vitest";
import { сметаРаботы, хватитЛи, РАСЦЕНКИ } from "../src/lib/pipelineQuote";

describe("смета до запуска", () => {
  it("прибор видит предмет: расценки взяты из замера, а не нули", () => {
    expect(РАСЦЕНКИ.видеоЗаСекунду).toBeGreaterThan(0);
    expect(РАСЦЕНКИ.озвучкаЗа1000Знаков).toBeGreaterThan(0);
  });

  it("книга с озвучкой и фильмом считается по измеренным расценкам", () => {
    const с = сметаРаботы({ знаковКниги: 20000, озвучка: true, секундВидео: 60 });
    // 20 000 знаков × 5/1000 = 100 кредитов, 60 с × 1.5 = 90 кредитов.
    expect(с.итогоКредитов).toBe(190);
    expect(с.строки.map((r) => r.шаг)).toEqual(["текст книги", "озвучка", "фильм"]);
  });

  it("без озвучки и без фильма кредиты не тратятся", () => {
    const с = сметаРаботы({ знаковКниги: 20000, озвучка: false, секундВидео: 0 });
    expect(с.итогоКредитов).toBe(0);
    expect(с.строки).toHaveLength(1);
  });

  // ОБНОВЛЕНО 28.09, вечер: курс кредита ИЗМЕРЕН по прайсу Higgsfield (пачка
  // 4000 за $190 → $0.0475 за кредит), поэтому доллары теперь называются
  // целиком. Прежняя редакция требовала null — она закрепляла ОТСУТСТВИЕ
  // замера, а не правило; правило было «не выдумывать курс», и оно цело:
  // число пришло из прайса, а не из головы, и смета предупреждает, что
  // мелкими пачками дороже.
  it("доллары считаются по ИЗМЕРЕННОМУ курсу и оговорены", () => {
    const с = сметаРаботы({ знаковКниги: 20000, озвучка: true, секундВидео: 60 });
    expect(с.долларыНеполные).toBe(false);
    // 190 кредитов × $0.0475 = $9.03 плюс копейки за текст.
    expect(с.итогоДолларов).toBeGreaterThan(9);
    expect(с.итогоДолларов).toBeLessThan(9.1);
    expect(с.предупреждения.join(" "), "курс назван без оговорки про пачки")
      .toMatch(/пачке 4000/);
  });

  it("цена кредита не занижена: мелкая пачка дороже, и это сказано", () => {
    expect(РАСЦЕНКИ.долларЗаКредит).toBeGreaterThanOrEqual(0.0475);
    expect(РАСЦЕНКИ.долларЗаКредит).toBeLessThanOrEqual(0.052);
  });

  it("хватает ли кредитов: «не знаю» отличается от «нет»", () => {
    const с = сметаРаботы({ знаковКниги: 20000, озвучка: true, секундВидео: 60 });
    expect(хватитЛи(с, 279.32)).toEqual({ хватает: true, нехватка: 0 });
    expect(хватитЛи(с, 100)).toEqual({ хватает: false, нехватка: 90 });
    expect(хватитЛи(с, null).хватает, "незнание выдали за отказ").toBeNull();
  });

  it("цена растёт вместе с работой, а не стоит на месте", () => {
    const мало = сметаРаботы({ знаковКниги: 5000, озвучка: true, секундВидео: 10 });
    const много = сметаРаботы({ знаковКниги: 50000, озвучка: true, секундВидео: 120 });
    expect(много.итогоКредитов).toBeGreaterThan(мало.итогоКредитов * 5);
  });
});
