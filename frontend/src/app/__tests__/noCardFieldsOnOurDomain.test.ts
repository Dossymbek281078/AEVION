import { describe, test, expect } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

/**
 * Мы не просим номер карты на своём домене — ни на одной странице.
 *
 * Замер 23.08.2026, страница `/qcoreai/upgrade` (на проде отвечала 200):
 * поля «Card number», «MM / YY» и «CVC» стояли прямо в разметке — без `value`,
 * без `onChange`, без формы вокруг и без единого вызова API во всём файле.
 * То есть человек мог ввести НАСТОЯЩИЕ данные карты, а страница их даже не
 * читала. Рядом обещалось «Card via Stripe» и «You will be redirected to
 * PayBox KZ», хотя касса платформы работает через Lemon Squeezy
 * (`/api/pricing/checkout/healthz` -> primaryProvider lemonsqueezy).
 *
 * Опасность тут не в мёртвой вёрстке, а в приглашении: форма выглядит рабочей.
 * Настоящая оплата у нас всегда уходит на страницу поставщика, и собственных
 * полей карты не должно быть ни одного — ни рабочих, ни «пока не подключённых».
 *
 * Сторож нарочно смотрит на ПЛЕЙСХОЛДЕР, а не на разбор JSX: попытка ловить
 * `<button>` регуляркой уже давала 5 ложных срабатываний из 7 (шаблон рвётся
 * на `>` внутри выражения в атрибуте). Плейсхолдер — это ровно то, что видит
 * человек, и подделать его нечем.
 */

const APP = join(__dirname, "..");

/**
 * ⚠️ 05.09.2026: шаблон видел ПОДПИСЬ, а не поле.
 *
 * Он искал слова «Card number», «CVC», «MM / YY». А на демо-кассе поля
 * подписаны ПРИМЕРАМИ — `4242 4242 4242 4242`, `12/28`, `123`, — и сторож их
 * не видел. Три поля карты жили на нашем домене при зелёном стороже, чьё имя
 * обещает «ни на одной странице».
 *
 * Замер после расширения: 1865 файлов, поля карты по существу ровно на ОДНОЙ
 * странице — демо-кассе. То есть слепота была узкой, но полной.
 */
const CARD_FIELD =
  /placeholder\s*=\s*["'`][^"'`]*(card\s*number|cvc|cvv|mm\s*\/\s*yy|номер\s*карты)/i;

/**
 * Поле карты, узнанное по СУТИ: пример номера, пример срока, автозаполнение.
 *
 * ⚠️ КОГДА ЭТО ДАСТ ЛОЖНЫЙ КРАСНЫЙ — и что делать. Проверено пробой
 * 05.09.2026: под первый шаблон попадает телефон, записанный БЕЗ плюса
 * (`7 700 000 00 00`), под второй — диапазон вида `10/20`. В сегодняшнем коде
 * ни того, ни другого нет: совпадение по всей платформе ровно одно, и оно
 * настоящее.
 *
 * Если сторож покраснеет на таком поле — НЕ ослаблять шаблон. Правильный
 * выход: посмотреть, что это за поле, и либо поправить плейсхолдер (телефон
 * с плюсом читается человеком не хуже), либо внести файл в ИСКЛЮЧЕНИЯ ниже с
 * причиной. Шаблон, ослабленный ради одного ложного красного, перестаёт
 * ловить настоящее — а настоящее здесь стоит номера чужой карты.
 */
const CARD_SHAPED = [
  /placeholder\s*=\s*["'`]\s*\d[\d ]{13,22}\s*["'`]/,
  /placeholder\s*=\s*["'`]\s*\d{2}\s*\/\s*\d{2}\s*["'`]/,
  /autoComplete\s*=\s*["'`]cc-/i,
];

/**
 * ИСКЛЮЧЕНИЯ — явные, с причиной, а не молчаливая слепота шаблона.
 *
 * `/pay/[id]` — публичная касса ДЕМОНСТРАЦИОННОГО платёжного модуля. Она
 * прямо пишет «Demo: any 16-digit number works», модуль объявлен
 * демонстрационным и в каталоге, и на странице модуля, а настоящих денег это
 * API не двигает вовсе.
 *
 * ⚠️ ВОПРОС ОСНОВАТЕЛЮ, а не решение разработчика: опасность, ради которой
 * сторож написан, здесь ОСТАЁТСЯ — человек может ввести настоящий номер в
 * поле, которое выглядит рабочим. Надпись «демо» этого не отменяет. Убирать
 * поля из демонстрации продукта я в одиночку не стал: это продуктовое
 * решение. Пока оно не принято, исключение стоит здесь ВИДИМЫМ.
 */
const ИСКЛЮЧЕНИЯ: Array<{ файл: string; причина: string }> = [
  {
    файл: "pay/[id]/page.tsx",
    причина: "демо-касса демонстрационного модуля; ждёт решения основателя",
  },
];

function sourceFiles(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name === "__tests__") continue;
    const full = join(dir, name);
    if (statSync(full).isDirectory()) sourceFiles(full, out);
    else if (/\.(tsx|ts)$/.test(name) && !/\.test\.tsx?$/.test(name)) out.push(full);
  }
  return out;
}

describe("на нашем домене не собирают данные карты", () => {
  const files = sourceFiles(APP);

  test("контроль: обход дошёл до страниц и видит плейсхолдеры", () => {
    // Пустой обход дал бы «нарушений нет» — ответ на невыполненный поиск.
    expect(files.length).toBeGreaterThan(100);
    expect(files.some((f) => readFileSync(f, "utf8").includes("placeholder"))).toBe(true);
  });

  test("контроль: шаблон краснеет на настоящих полях карты", () => {
    expect(CARD_FIELD.test('<input placeholder="Card number" />')).toBe(true);
    expect(CARD_FIELD.test('<input placeholder="CVC" />')).toBe(true);
    expect(CARD_FIELD.test('<input placeholder="MM / YY" />')).toBe(true);
    // И не краснеет на безобидном
    expect(CARD_FIELD.test('<input placeholder="Email" />')).toBe(false);
    expect(CARD_FIELD.test('<input placeholder="Card design name" />')).toBe(false);
  });

  test("ни одна страница не просит номер карты, CVC или срок действия", () => {
    const bad = files
      .filter((f) => {
        const код = readFileSync(f, "utf8");
        return CARD_FIELD.test(код) || CARD_SHAPED.some((r) => r.test(код));
      })
      // Разделители нормализуем: на Windows путь идёт обратными слэшами,
      // и разбиение только по прямым давало ОДИН элемент — исключение по
      // относительному пути тогда не совпадало никогда.
      .map((f) => f.split(/[\\\/]/).slice(-3).join("/"))
      .filter((rel) => !ИСКЛЮЧЕНИЯ.some((e) => rel.endsWith(e.файл)));
    expect(
      bad,
      `оплата уходит на страницу поставщика; своих полей карты быть не должно:\n${bad.join("\n")}`,
    ).toEqual([]);
  });
});

describe("кнопка оплаты на /qcoreai/upgrade не молчит", () => {
  const PAGE = join(APP, "qcoreai", "upgrade", "page.tsx");

  test("у главной кнопки есть обработчик", () => {
    const code = readFileSync(PAGE, "utf8");
    // Раньше здесь стоял <button> без onClick, без type и без формы: нажатие
    // не делало ничего, а страница обещала переход к оплате.
    expect(code).toContain("onClick");
    expect(code).toMatch(/window\.location\.href\s*=\s*["'`]\/pricing/);
  });
});
