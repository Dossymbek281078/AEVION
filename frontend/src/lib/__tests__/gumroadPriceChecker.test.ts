/**
 * Цена на странице против цены, которую возьмёт касса.
 *
 * Девять позиций каталога продаются ПРЯМОЙ ссылкой на Gumroad, и наша сумма в
 * такую ссылку не передаётся вовсе: платит человек столько, сколько выставлено
 * у продавца. Ни при переходе в кассу, ни при подтверждении покупки суммы никто
 * не сверяет — проверено грепом по провайдеру и вебхуку (контроль прибора
 * пройден: слово `permalink` в том же файле находится 9 раз).
 *
 * Расхождение опасно в обе стороны: вверх — человек платит больше обещанного;
 * вниз — мы отдаём доступ дешевле, и видно это только по выручке, задним числом.
 *
 * Замер 01.09.2026: все девять сходятся. Сходятся СЕГОДНЯ — цену меняют в двух
 * разных местах. Сеть в тестах не трогаем: здесь проверяется РАЗБОР и то, что
 * у каждой позиции есть с чем сверять.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { позицииИзКаталога, ценыСоСтраницы } from "../../../scripts/check-gumroad-prices.mjs";

const каталог = readFileSync(join(process.cwd(), "src/lib/products.ts"), "utf8");

describe("сверка цены каталога с кассой", () => {
  it("разбор каталога находит позиции — проверено пробой", () => {
    // Контроль умения находить: без него ноль ниже одинаково выглядит при
    // исправном каталоге и при сломанном шаблоне.
    const проба = позицииИзКаталога('{ id: "x", priceUsd: 42, href: GUM("abc123") }');
    expect(проба).toEqual([{ permalink: "abc123", usd: 42 }]);
    expect(позицииИзКаталога("ничего похожего")).toEqual([]);
  });

  it("у КАЖДОЙ позиции с прямой ссылкой есть цена — иначе сверять не с чем", () => {
    const позиции = позицииИзКаталога(каталог);
    expect(позиции.length, "в каталоге не нашлось прямых ссылок — сломан шаблон").toBeGreaterThan(0);
    const безЦены = позиции.filter((p) => p.usd === null).map((p) => p.permalink);
    expect(безЦены, "позиция продаётся, но сверить её цену не с чем").toEqual([]);
  });

  it("цены со страницы разбираются, служебные нули отбрасываются", () => {
    const html = '&quot;price_cents&quot;:0 ... &quot;price_cents&quot;:5900 ... &quot;price_cents&quot;:5900';
    expect(ценыСоСтраницы(html)).toEqual([5900]);
    expect(ценыСоСтраницы("страница без цен")).toEqual([]);
  });
});
