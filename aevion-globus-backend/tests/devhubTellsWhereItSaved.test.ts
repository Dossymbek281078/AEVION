import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stripComments } from "./helpers/sourceCode";

/**
 * DevHub называет хранилище там, где человек теряет свою работу.
 *
 * Замер 19.08.2026: в файле 28 ответов, перед которыми в пределах 15 строк
 * стоит запись в память. Помечены ПЯТЬ — те, где теряется то, что человек
 * создал сам: проект (создание и правка) и файл (три ручки сохранения).
 *
 * Устройство здесь отличается от других модулей, и это важно для починки:
 * запасной путь срабатывает по ИСКЛЮЧЕНИЮ, а не по флагу готовности базы.
 *
 *   try { await dbSaveProject(project); }
 *   catch { memProjects.set(...); }        ← подмена случается здесь
 *   res.json({ project });                 ← а ответ о ней молчал
 *
 * Поэтому признак нельзя вычислить из isDbReady() — нужна локальная переменная,
 * выставляемая ровно в catch. Проверка следит именно за этим.
 *
 * Остальные 23 места не тронуты сознательно: файл правят 11 веток, из них одна
 * разошлась на 347 строк. Широкая правка создала бы им поверхность конфликта
 * там, где выигрыш меньше. Список — на доске запуска.
 */

const SRC = stripComments(readFileSync(join(__dirname, "..", "src", "routes", "devhub.ts"), "utf8"));

describe("DevHub не выдаёт память за сохранение", () => {
  test("контроль: файл прочитан и содержит обе ветки", () => {
    expect(SRC.length).toBeGreaterThan(10000);
    expect(SRC).toContain("memProjects.set");
    expect(SRC).toContain("memFiles.set");
  });

  // Число намеренно НЕ зашито: 21.08.2026 я добавил шестое место (сохранение
  // перевода файла), и сторож покраснел на РАСШИРЕНИИ охраны — то есть наказал
  // за прогресс. Точное число здесь ничего не охраняет: важно, что мест не
  // стало МЕНЬШЕ и что признак выставляется в catch, а не угадывается.
  test("места с локальным признаком не исчезают", () => {
    const decls = SRC.match(/let storage: "db" \| "memory" = "db";/g) ?? [];
    expect(
      decls.length,
      "признак объявляется не там, где нужно — проверьте, не переписали ли обработчик",
    ).toBeGreaterThanOrEqual(5);
  });

  test("признак выставляется РОВНО в catch, а не угадывается", () => {
    // Если бы его считали из isDbReady() после записи, на восстановившейся базе
    // ветка памяти вернула бы "db" и соврала снова.
    // Храповик, а не точное число — по той же причине, что у соседа выше:
    // 28.08 две сессии независимо закрывали ЭТОТ ЖЕ класс, и при сведении
    // часть мест ушла на общую константу MEMORY_NOTE. Точное число делает
    // сторожа красным от чужой работы, а не от дефекта.
    const setInCatch = SRC.match(/storage = "memory";/g) ?? [];
    expect(setInCatch.length, "подмена происходит в catch — там же и помечается").toBeGreaterThanOrEqual(5);
  });

  // Мутация 28.08 вскрыла пробел: проверки выше считают ОБЪЯВЛЕНИЯ и подмену
  // в catch, но не то, что признак доезжает до ответа. Убрать `storage` из
  // возвращаемого значения помощника генерации можно было незаметно — флаг
  // велся бы честно и выбрасывался. Это тот же класс «поле есть, читателя
  // нет», только на уровень выше.
  test("помощник генерации ВОЗВРАЩАЕТ признак, а не только ведёт его", () => {
    expect(
      /checkpointId, projectId: project\.id, storage,/.test(SRC),
      "признак генерации ведётся, но не уходит в ответ — платный шаг снова молчит",
    ).toBe(true);
  });

  test("выдача базы предупреждает В ОБЕИХ ветках текста, а не в одной", () => {
    // Первая правка приклеила предупреждение только ко второй ветке тернарника
    // ("схема не найдена"), а первая ("схема применена") молчала бы. Скобка
    // вокруг всего тернарника — то, что это чинит.
    expect(
      /note: \(result\.appliedSchemaSql[\s\S]*?\) \+ savedNote/.test(SRC),
      "предупреждение о памяти попадает не во все ветки текста",
    ).toBe(true);
  });

  test("предупреждение включается ИМЕННО признаком памяти", () => {
    // Мутация показала дыру: проверка формы текста выше зелена и когда условие
    // подменено на невозможное (`storage === "nope"`), то есть предупреждение
    // не покажется никогда. Форма без условия ничего не охраняет.
    expect(
      /const savedNote = storage === "memory"/.test(SRC),
      "условие предупреждения подменено — оно не сработает никогда",
    ).toBe(true);
  });

  test("создание проекта отвечает с признаком", () => {
    expect(SRC).toMatch(/res\.status\(201\)\.json\(\{ project, storage \}\)/);
  });

  test("сохранение файла отвечает с признаком", () => {
    const marked = SRC.match(/res\.json\(\{ file, storage \}\)/g) ?? [];
    expect(marked.length, "не все ручки сохранения файла помечены").toBe(2);
    expect(SRC).toMatch(/bytes: content\.length, mimeType: meta\.mimeType, storage/);
  });
});
