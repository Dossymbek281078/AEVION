import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Каждая страница DevHub обязана быть в списке сторожа страниц.
 *
 * Ворота запуска №7 требуют этого прямым текстом, но выполнялись вручную —
 * значит рано или поздно не выполнились. Замер 08.09.2026: русские двери
 * модуля (`/devhub`, `/devhub/launch`, `/devhub/link`) в списке с самого
 * начала, а АНГЛИЙСКАЯ `/en/devhub` — нет, хотя это дверь для Show HN и
 * западных писем у модуля за $149. Ломается она так же, а узнали бы мы от
 * посетителя, а не от сторожа.
 *
 * Шире картина того же замера: английских страниц в выкаченном дереве десять,
 * под присмотром было четыре. Остальные пять — чужих модулей, и добавлять их
 * должны их окна: /en/shop прямо сейчас правит соседняя ветка. Все пять живы
 * (проверено, контроль на выдуманный адрес даёт 404), замер им передан.
 *
 * Устройство сторожа взято у соседей (`chessPagesAllUnderSmoke`), а не
 * придумано заново: один способ делать одно.
 *
 * ПОЧЕМУ ТОЛЬКО DEVHUB. Тот же список по всей платформе покраснел бы сразу и
 * навсегда, а постоянно красная проверка перестаёт читаться и защищает хуже
 * своего отсутствия.
 *
 * Динамические адреса (`[id]`) исключены: постоянного URL у них нет.
 */

const REPO_ROOT = path.join(__dirname, "..", "..");
const APP = path.join(REPO_ROOT, "frontend", "src", "app");
const SMOKE_FILE = path.join(__dirname, "..", "scripts", "pages-live-smoke.js");

/** Статические страницы каталога, найденные по файловой системе. */
function pagesOnDisk(dir: string, urlPrefix: string): string[] {
  const out: string[] = [];
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (entry.name.startsWith("[") || entry.name === "__tests__") continue;
      out.push(...pagesOnDisk(path.join(dir, entry.name), `${urlPrefix}/${entry.name}`));
    } else if (entry.name === "page.tsx") {
      out.push(urlPrefix);
    }
  }
  return out;
}

const SMOKE = fs.readFileSync(SMOKE_FILE, "utf8");

describe("страницы DevHub под ежедневным сторожем", () => {
  test("прибор исправен: список смоука прочитан и непуст", () => {
    expect(SMOKE.length).toBeGreaterThan(2000);
    expect(SMOKE, "читается не тот файл").toContain('"/devhub"');
    // Контроль: у смоука есть намеренно выдуманный адрес — он доказывает, что
    // проверка умеет краснеть. Пропади он — краснеть будет нечему.
    expect(SMOKE, "контрольный несуществующий адрес исчез из смоука").toContain("net-takogo-proekta-zzz");
  });

  test("все статические страницы модуля перечислены в смоуке", () => {
    const страницы = pagesOnDisk(path.join(APP, "devhub"), "/devhub");
    expect(страницы.length, "страниц модуля не найдено — сторож стерёг бы пустоту").toBeGreaterThanOrEqual(3);
    const вне = страницы.filter((p) => !SMOKE.includes(`"${p}"`));
    expect(вне, "страница модуля вне ежедневного сторожа — пропади она, узнаем от посетителя").toEqual([]);
  });

  test("английский вход модуля тоже под сторожем", () => {
    // Отдельным тестом, потому что он живёт в другом каталоге и его легко
    // потерять при перечислении «страниц модуля».
    //
    // Утверждение БЕЗУСЛОВНОЕ, и это не мелочь. Первая редакция начиналась с
    // `if (!fs.existsSync(...)) return` — «страницы нет в этой ветке, стеречь
    // нечего», — и тест ПРОШЁЛ, не проверив ничего: страница живёт в ветке
    // выкатки, а не в моей. Зелёный цвет означал бы «не запускалось».
    //
    // Требование не зависит от того, чья ветка держит файл: дверь открыта на
    // проде (200, контроль на выдуманный адрес — 404), значит она обязана быть
    // под ежедневным сторожем.
    expect(SMOKE, "английская дверь модуля вне смоука").toContain('"/en/devhub"');
  });
});
