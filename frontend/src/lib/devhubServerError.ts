/**
 * Текст серверной ошибки — на языке человека, а не сервера.
 *
 * Замер 28.08.2026: у ручек модуля 119 разных текстов ошибок, по-русски
 * СЕМЬ. А в рабочем окне они выводятся так:
 *
 *     throw new Error(data.error || "Не удалось создать контрольную точку")
 *
 * то есть русская строка — ЗАПАСНАЯ: она видна, только когда сервер молчит.
 * Когда сервер отвечает — а он отвечает почти всегда — человек читает
 * «prompt required» и «imageUrl (http/https) is required» посреди русского
 * интерфейса.
 *
 * Почему не переводить сами ручки. Их тексты — контракт API: по ним пишут
 * условия другие клиенты и смоук. Перевод сломал бы проверки и чужие
 * интеграции ради косметики. Граница показа — единственное место, где язык
 * можно менять безнаказанно.
 *
 * Почему незнакомую ошибку не прячем. Спрятать — значит лишить человека
 * единственной подсказки и себя единственной зацепки в жалобе. Незнакомый
 * текст показывается как есть: пусть лучше по-английски, чем никак.
 */

/** Пары «кусок английского текста» → «что это значит человеку». */
const RULES: Array<[RegExp, string]> = [
  // Не хватает поля. Самая частая группа: 30+ ручек отвечают «X required».
  [/^(\w[\w .()\/-]*?) (?:is )?required\b/i, "Не заполнено обязательное поле: $1"],
  [/^missing (\w[\w .-]*)/i, "Не передано: $1"],

  // Канал не настроен — это не поломка, а незаконченная настройка.
  [/not configured/i, "Канал не подключён — нужен ключ провайдера. Мы это видим и настроим."],

  // Не найдено.
  [/\bnot found\b/i, "Не найдено — возможно, уже удалено."],

  // Пределы и оплата.
  // Месячная квота исчерпана — САМОЕ важное сообщение денежного пути, и оно не
  // было покрыто ни одним правилом. Замер 28.08.2026: сервер отвечает 402 с
  // текстом «Monthly deploy limit reached» (а также video/image/music/tts), и
  // человек читал его по-английски ровно в тот момент, когда решает, платить
  // ли. Название возможности сохраняем: без него непонятно, ЧТО исчерпалось.
  [/^monthly (\w+) limit reached/i, "Месячная норма исчерпана: $1. Она обновится первого числа, а платный тариф поднимает предел."],
  [/rate limit|too many requests/i, "Слишком часто. Подождите минуту и повторите."],
  [/\b(insufficient|not enough) (credits?|balance)\b/i, "Не хватает средств на счёте модуля."],
  [/\bpayment required\b|\bupgrade\b/i, "Нужен платный тариф."],

  // Доступ.
  [/unauthori[sz]ed|forbidden|access denied/i, "Нет доступа. Войдите заново."],

  // Хранилище — у нас для этого есть отдельный признак, но текст тоже бывает.
  [/storage_unavailable/i, "Хранилище временно недоступно. Данные на месте, повторите позже."],

  // Слишком большой вход.
  [/too large|payload too big|exceeds/i, "Слишком большой файл или текст."],
];

/**
 * @param raw   текст из поля `error` ответа сервера (может отсутствовать)
 * @param fallback русский текст на случай, когда сервер не сказал ничего
 */
export function devhubServerError(raw: unknown, fallback: string): string {
  if (typeof raw !== "string") return fallback;
  const s = raw.trim();
  if (!s) return fallback;

  // Сервер уже говорит по-русски (таких семь) — не трогаем.
  if (/[а-яА-ЯёЁ]/.test(s)) return s;

  for (const [re, ru] of RULES) {
    const m = re.exec(s);
    if (!m) continue;
    // $1 подставляем только если правило его ждёт И группа есть.
    return ru.includes("$1") && m[1] ? ru.replace("$1", m[1].trim()) : ru;
  }

  // Незнакомое — показываем как есть, рядом с понятным поводом.
  // Сообщение, называющее переменную окружения, панель поставщика или
  // машинный код, написано для НАС, а не для покупателя. Показывать его
  // человеку вдвойне плохо: помочь оно не может, а устройство системы
  // выдаёт. Замер 29.08.2026: таких сообщений в devhub.ts тридцать пять,
  // и все они доезжали до экрана через подстановку ниже.
  //
  // Текст при этом НЕ теряется — он уходит в консоль. Спрятать его
  // совсем значило бы обменять одну беду на другую: разбирать отказ
  // стало бы не по чему.
  const INFRA = /[A-Z][A-Z0-9]{3,}_[A-Z0-9_]{2,}|in Railway|dash.cloudflare/;
  if (INFRA.test(s)) {
    if (typeof console !== "undefined" && console.warn) {
      console.warn("devhub: техническое сообщение сервера не показано покупателю:", s);
    }
    return "Эта возможность сейчас не настроена на нашей стороне. Мы уже знаем об этом — попробуйте позже.";
  }

  return `${fallback} (${s})`;
}
