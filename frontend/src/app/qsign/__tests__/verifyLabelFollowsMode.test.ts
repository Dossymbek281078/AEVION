import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Подпись называется тем режимом, в котором она сделана.
 *
 * Прод сегодня отвечает `qsign: { mode: "preview", reason: "seed_unset" }` —
 * постквантовая подпись работает как зарезервированное место, и код честно об
 * этом пишет. Интерфейс тоже был честен, но слово «preview» стояло в нём
 * ЗАШИТЫМ: и в подписи блока, и в значении («preview-ok»).
 *
 * Цена этого проявится в день, когда ключ подписи зададут. Подпись станет
 * настоящей (ML-DSA-65, FIPS 204) — а страница продолжит называть её
 * предпросмотром. То есть флагманское обещание продукта будет ЗАНИЖЕНО
 * собственным интерфейсом, и заметить это будет некому: ошибка молчит, тесты
 * зелёные, никто не жалуется.
 *
 * Там же был литеральный тип `mode: "preview"` — сайт объявлял, что другого
 * режима не бывает, тогда как бэкенд возвращает два.
 *
 * Сторож читает исходник страницы: снаружи это не проверить, пока ключ не
 * задан, а задавать его ради теста нельзя.
 */

const PAGE = join(__dirname, "..", "page.tsx");
const src = readFileSync(PAGE, "utf8");

describe("страница подписи называет режим, а не гадает", () => {
  test("контроль: файл прочитан и это нужная страница", () => {
    expect(src.length).toBeGreaterThan(1000);
    expect(src.includes("Dilithium-3")).toBe(true);
  });

  test("тип режима допускает оба значения, как у бэкенда", () => {
    expect(
      src.includes('mode: "preview" | "real"'),
      "тип сузили до одного режима — сайт объявляет, что настоящей подписи не бывает",
    ).toBe(true);
  });

  test("подпись блока проверки берётся из ответа, а не зашита", () => {
    expect(
      src.includes("Dilithium-3 (preview)"),
      "слово preview вернулось в разметку: включат настоящую подпись — страница будет звать её предпросмотром",
    ).toBe(false);
  });

  test("значение проверки тоже следует режиму", () => {
    expect(src.includes('"preview-ok"')).toBe(false);
    expect(src.includes('"preview-mismatch"')).toBe(false);
    expect(src.includes("-ok`")).toBe(true);
  });
});
