/**
 * Значок тарифа для карточек примеров — и защита от незнакомого тарифа.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Защита должна быть проверяема тестом, а из файла
 * страницы Next не даёт экспортировать произвольные символы: там разрешён
 * только оговорённый набор. Пока функция жила внутри страницы, её нельзя было
 * ни позвать из теста, ни сломать мутацией — то есть «защита» держалась на
 * честном слове.
 *
 * ЧТО ОНА ЗАКРЫВАЕТ. На странице примеров значок брался прямо:
 * `TIER_BADGE[c.tier].bg`, где `c.tier` приходит С СЕРВЕРА. Пока сервер отдаёт
 * знакомые пять тарифов — всё работает. Но список примеров редактируется на
 * стороне сервера, БЕЗ правки кода: в день, когда появится пример с тарифом
 * `pro` (настоящий продаваемый тариф, $149 в месяц), поиск вернёт пустоту,
 * обращение к `.bg` бросит, и публичная страница цен упадёт у КАЖДОГО
 * посетителя. Не у автора примера — у всех сразу.
 *
 * Замер 05.09.2026: на проде 6 примеров, тарифы enterprise/full/medium, все
 * покрыты. То есть это мина, а не пожар, — и обезврежена она до того, как
 * сработала.
 *
 * ПОЧЕМУ `hasOwnProperty`, а не простой поиск. Тариф — свободная строка извне,
 * а множество значков закрытое. В обычном объекте служебные имена
 * (`constructor`, `toString`) НАХОДЯТСЯ и возвращают не значок, а функцию из
 * прототипа: `.bg` у неё `undefined`, и на экран уедет пустота вместо цвета.
 * Там, где ключ свободный И множество открытое, правильнее объект без
 * прототипа — но здесь набор закрыт, и проверка собственного свойства точнее.
 */

export type CaseTier = "free" | "lite" | "medium" | "full" | "enterprise";

export interface ЗначокТарифа {
  bg: string;
  fg: string;
}

export const TIER_BADGE: Record<CaseTier, ЗначокТарифа> = {
  free: { bg: "#f1f5f9", fg: "#475569" },
  lite: { bg: "#ccfbf1", fg: "#0f766e" },
  medium: { bg: "#dbeafe", fg: "#1e40af" },
  full: { bg: "#ede9fe", fg: "#6d28d9" },
  enterprise: { bg: "#0f172a", fg: "#f8fafc" },
};

/**
 * Нейтральный значок для тарифа, которого мы не знаем.
 *
 * Намеренно неяркий и читаемый: незнакомый тариф — это наш пробел, а не повод
 * пугать посетителя. Показать серую плашку честнее, чем уронить страницу, и
 * честнее, чем выдать чужой цвет за свой.
 */
export const ЗНАЧОК_НЕИЗВЕСТНОГО: ЗначокТарифа = { bg: "#e2e8f0", fg: "#0f172a" };

export function значокТарифа(tier: string | null | undefined): ЗначокТарифа {
  if (typeof tier !== "string") return ЗНАЧОК_НЕИЗВЕСТНОГО;
  return Object.prototype.hasOwnProperty.call(TIER_BADGE, tier)
    ? TIER_BADGE[tier as CaseTier]
    : ЗНАЧОК_НЕИЗВЕСТНОГО;
}
