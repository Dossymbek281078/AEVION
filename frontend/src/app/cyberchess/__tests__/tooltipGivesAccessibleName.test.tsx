import { describe, expect, it } from "vitest";
import { render, screen } from "@testing-library/react";
import { Tooltip } from "../ui";

/**
 * Подпись тултипа обязана становиться ИМЕНЕМ кнопки-значка.
 *
 * ЗАМЕР вкладки доступности 04.09.2026: на /cyberchess/studio четыре кнопки
 * объявлялись одним значком — «⇄, кнопка», «✕, кнопка». Подпись у них БЫЛА,
 * но жила в тултипе: он рисует отдельный span и с кнопкой ничем не связан,
 * а по правилам вычисления имени содержимое кнопки побеждает всё остальное.
 * Глазами подпись видна, читалке — нет.
 *
 * Проверяем СЛЕДСТВИЕ (какое имя у кнопки), а не форму (есть ли атрибут):
 * `getByRole(name)` спрашивает ровно то, что спросит читалка.
 */

describe("Tooltip даёт доступное имя", () => {
  it("кнопка-значок получает имя из подписи", () => {
    render(
      <Tooltip label="Сменить источник">
        <button>⇄</button>
      </Tooltip>,
    );
    // Контроль прибора: без имени кнопка нашлась бы по значку, а не по слову.
    expect(screen.getByRole("button", { name: "Сменить источник" })).toBeTruthy();
  });

  it("своё имя НЕ перебивается подписью", () => {
    // Вызывающий мог назвать точнее — например, различить одинаковые кнопки
    // в списке. Подпись тултипа такого различия не несёт.
    render(
      <Tooltip label="Удалить">
        <button aria-label="Удалить этап 3">✕</button>
      </Tooltip>,
    );
    expect(screen.getByRole("button", { name: "Удалить этап 3" })).toBeTruthy();
    expect(screen.queryByRole("button", { name: "Удалить" })).toBeNull();
  });

  it("без подписи ничего не выдумывает", () => {
    // Отрицательный контроль: пустая подпись не должна давать пустое имя,
    // иначе кнопка станет «безымянной официально» — хуже, чем была.
    render(
      <Tooltip label="">
        <button>значок</button>
      </Tooltip>,
    );
    expect(screen.getByRole("button", { name: "значок" })).toBeTruthy();
  });
});
