async function поднять() {
  const { bureauRouter } = await import("../src/routes/bureau.js");
  const a = express();
  a.use(express.json());
  a.use("/api/bureau", bureauRouter);
  return a;
}

describe("анонимная запись в бюро под пределом частоты", () => {
  /*
   * ОДИН тест на обе ручки намеренно. Лимитер у них общий, значит и ведро
   * общее: разбив проверку надвое, я получил второй тест, который проходил
   * только потому, что ведро выбрал первый. Он выглядел зелёным и не
   * утверждал ничего — самый тихий вид пустой проверки.
   *
   * Здесь порядок обратный и он честен: сначала выбираем ведро на первой
   * ручке, затем ОДНИМ запросом показываем, что вторая ручка сидит на том же
   * лимитере. Если бы её забыли подключить, она ответила бы 400
   * («verificationId is required»), а не 429 — то есть различие настоящее.
   */
  test("подряд идущие анонимные записи упираются в 429, и обе ручки под одним пределом", async () => {
    const a = await поднять();
    const коды: number[] = [];
    for (let i = 0; i < 14; i++) {
      const r = await request(a)
        .post("/api/bureau/verify/start")
        .set("Content-Type", "application/json")
        .send({});
      коды.push(r.status);
    }

    expect(
      коды.some((c) => c !== 404),
      "маршрут /verify/start не отвечает вовсе — сторож смотрит не туда",
    ).toBe(true);

    expect(
      коды.includes(429),
      `четырнадцать анонимных записей подряд прошли без отказа: ${коды.join(",")}. ` +
        "Открытая ручка, вставляющая строку в базу, обязана иметь предел частоты — " +
        "иначе любой скрипт наполняет таблицу бюро за минуты.",
    ).toBe(true);

    const продолжение = await request(a)
      .post("/api/bureau/payment/intent")
      .set("Content-Type", "application/json")
      .send({});
    expect(
      продолжение.status,
      "оплата не под тем же пределом: 400 значит, что ограничитель к ней не подключён " +
        "и цепочку можно продолжать бесконечно",
    ).toBe(429);
  }, 60_000);
});
