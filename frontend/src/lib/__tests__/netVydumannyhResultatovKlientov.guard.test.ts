/**
 * 🔴 НА САЙТЕ НЕТ ВЫДУМАННЫХ РЕЗУЛЬТАТОВ КЛИЕНТОВ.
 *
 * Внешних клиентов у AEVION ноль. Значит любое «−73% времени на подпись»,
 * «$2.3M экономии в год», «−74% на регистрацию» — это выдуманные чужие числа
 * на продающей странице, и мы продаём ровно доказуемость, то есть бьём по
 * тому, чем торгуем.
 *
 * ИСТОРИЯ, из-за которой сторож и нужен: сами «кейсы клиентов» сняли 20.09.2026
 * — данные убрали (CASE_STUDIES пуст, прод отдаёт items: []), тексты унесли в
 * cases.unpublished.ts. А ОПИСАНИЯ страниц и КАРТИНКИ для соцсетей остались и
 * три недели показывали те же числа всюду, куда пересылали ссылку. Удалить
 * данные и забыть поверхности, которые их пересказывают, — это полпочинки, и
 * именно эту половину сторож и стережёт.
 *
 * Он идёт по ВСЕМУ дереву фронта, а не по трём известным файлам: четвёртая
 * поверхность с тем же числом появится завтра.
 */
import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const КОРЕНЬ = join(__dirname, "../..");

/** Числа, которые были выдуманы и названы таковыми. Не «похожие», а ровно эти. */
/*
 * ⚠️ Знак минуса НЕ должен стоять после цифры — иначе ловится диапазон.
 * Прибор первой редакции нашёл «−68% time-to-market» в тексте про сметы, где
 * на самом деле написано «62-68% Cr» (содержание хрома). Это была МОЯ ошибка
 * измерения, а не возврат обещания: ложная тревога в стороже опаснее молчания,
 * к ней привыкают и перестают читать.
 */
const ВЫДУМАННЫЕ: Array<{ образец: RegExp; что: string }> = [
  { образец: /(?<!\d)[−-]\s?73\s?%/, что: "−73% против DocuSign" },
  { образец: /(?<!\d)[−-]\s?74\s?%/, что: "−74% на регистрацию IP" },
  { образец: /(?<!\d)[−-]\s?68\s?%/, что: "−68% time-to-market" },
  { образец: /\$2[.,]3\s?M/i, что: "$2.3M экономии в год" },
  { образец: /экономия\s+42-74\s?%/i, что: "экономия 42-74%" },
];

function файлы(каталог: string, найдено: string[] = []): string[] {
  for (const имя of readdirSync(каталог)) {
    if (имя === "node_modules" || имя === ".next" || имя === "__tests__") continue;
    const путь = join(каталог, имя);
    if (statSync(путь).isDirectory()) файлы(путь, найдено);
    else if (/\.(ts|tsx)$/.test(имя)) найдено.push(путь);
  }
  return найдено;
}

/** Строка кода без комментариев: наш разбор дефекта — не обещание человеку. */
function безКомментариев(src: string): string {
  return src
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .split("\n")
    .map((с) => с.replace(/^\s*\/\/.*$/, " "))
    .join("\n");
}

describe("выдуманных результатов клиентов нет нигде", () => {
  const все = файлы(КОРЕНЬ);

  it("🔴 контроль прибора: дерево обходится и файлы читаются", () => {
    expect(все.length, "обход фронта не нашёл файлов — прибор слеп").toBeGreaterThan(300);
  });

  it("🔴 ни одного выдуманного числа в видимом коде — знаменатель по всему фронту", () => {
    const находки: string[] = [];
    for (const путь of все) {
      const текст = безКомментариев(readFileSync(путь, "utf8"));
      for (const { образец, что } of ВЫДУМАННЫЕ) {
        if (образец.test(текст)) находки.push(`${путь.replace(КОРЕНЬ, "")} → ${что}`);
      }
    }
    expect(находки, "выдуманный результат клиента вернулся на страницу").toEqual([]);
  });

  it("🔴 контроль: прибор ловит такое число, если его подложить", () => {
    // Без этого «ноль находок» означал бы «не умею искать».
    const подделка = 'const x = "клиенты считают −73% времени";';
    expect(ВЫДУМАННЫЕ.some(({ образец }) => образец.test(безКомментариев(подделка)))).toBe(true);
    // И наоборот: то же число ВНУТРИ комментария — это наш разбор, не обещание.
    expect(ВЫДУМАННЫЕ.some(({ образец }) => образец.test(безКомментариев("// было −73%")))).toBe(false);
    // И диапазон вида «62-68% Cr» — не обещание: прибор обязан его пропустить.
    expect(ВЫДУМАННЫЕ.some(({ образец }) => образец.test('const t = "FeCr 62-68% Cr";'))).toBe(false);
  });
});
