import { describe, test, expect } from "vitest";
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { MODULES } from "@/lib/products";

/**
 * ПОДПИСЬ КАРТОЧКИ DEVHUB ПРИВЯЗАНА К НАСТОЯЩИМ НОРМАМ, А НЕ К ПАМЯТИ.
 *
 * Повод 06.10.2026. Замер по заданию оркестратора: за что платят в четырёх продаваемых
 * модулях. У трёх из четырёх на сервере не менялось НИЧЕГО, у DevHub меняется измеримо
 * (тариф студии становится pro), и на карточке об этом не было сказано ни слова.
 *
 * Числа в подписи — это ОБЕЩАНИЕ покупателю, а обещание обязано совпадать с механизмом.
 * Поэтому сторож читает ту же таблицу TIER_LIMITS из бэкенда, что отвечает на запросе:
 * второй копии чисел на фронте не появилось. Поменяются нормы — покраснеет подпись,
 * и человек, который их менял, увидит, что обещание разошлось с продуктом.
 *
 * Чего сторож НЕ проверяет, и это названо вслух: что нормы на ПРОДЕ сейчас такие же,
 * как в репозитории. Это другой вопрос, и у него свой прибор —
 * живая ручка /api/devhub/studio/credits, которая отдаёт tierInfo всеми тарифами.
 */

const ТАБЛИЦА = join(__dirname, "..", "..", "..", "..", "aevion-globus-backend", "src", "routes", "devhub.ts");
const ПЕРЕВОД = String.fromCharCode(10); // эскейп съедается на границе вызова (§2е)

/** Нормы одного тарифа из настоящей таблицы бэкенда. */
function нормы(тариф: string): Record<string, number> {
  const src = readFileSync(ТАБЛИЦА, "utf8");
  const i = src.indexOf("const TIER_LIMITS");
  expect(i, "в бэкенде не нашлась таблица TIER_LIMITS — сторож смотрит не туда").toBeGreaterThan(0);
  const блок = src.slice(i, src.indexOf("};", i));
  const строка = блок
    .split(ПЕРЕВОД)
    .find((l) => l.trim().startsWith(тариф + ":"));
  expect(строка, `в таблице нет тарифа ${тариф}`).toBeTruthy();
  const из: Record<string, number> = {};
  // Разбор без регулярок намеренно: эскейпы вида "backslash d" съедаются на границе
  // вызова и доезжают настоящими символами — на этом же файле регулярка оказалась
  // незакрытой и тест не загрузился вовсе (§2е, съеденный слэш).
  for (const кусок of (строка as string).split(",")) {
    const где = кусок.lastIndexOf(":");
    if (где < 0) continue;
    // В ПЕРВОМ куске строки лежит и имя тарифа ("pro: { video: 50"), поэтому имя
    // берётся после открывающей скобки, а не до первого двоеточия. Первая версия
    // прочитала здесь "pro" и дала video=undefined — прибор соврал, а выглядело
    // как непрочитанная норма.
    const сырое = кусок.slice(0, где);
    const ключ = (сырое.includes("{") ? сырое.slice(сырое.lastIndexOf("{") + 1) : сырое).trim();
    const число = Number(кусок.slice(где + 1).replace("}", "").trim());
    if (ключ && Number.isFinite(число)) из[ключ] = число;
  }
  return из;
}

const подпись = MODULES.find((m) => m.id === "devhub")?.desc ?? "";

describe("карточка DevHub говорит, за что деньги", () => {
  test("ЗНАМЕНАТЕЛЬ: сколько норм сверено с таблицей бэкенда", () => {
    expect(existsSync(ТАБЛИЦА), "файл бэкенда с таблицей не найден — проверка невозможна").toBe(true);
    const pro = нормы("pro");
    const free = нормы("free");
    const сверяем = ["video", "image", "music", "tts"] as const;
    process.stderr.write(
      `[сторож] норм сверено: ${сверяем.length}; pro ` +
        сверяем.map((k) => `${k}=${pro[k]}`).join(" ") +
        `; free ` + сверяем.map((k) => `${k}=${free[k]}`).join(" ") + ПЕРЕВОД,
    );
    expect(сверяем.length, "сверять нечего — сторож пуст").toBeGreaterThanOrEqual(4);
    for (const k of сверяем) {
      expect(Number.isFinite(pro[k]), `норма pro.${k} не прочитана`).toBe(true);
      expect(Number.isFinite(free[k]), `норма free.${k} не прочитана`).toBe(true);
    }
  });

  test("каждое число подписи есть в таблице — обещание совпадает с механизмом", () => {
    const pro = нормы("pro");
    const free = нормы("free");
    for (const k of ["video", "image", "music", "tts"] as const) {
      expect(
        подпись.includes(String(pro[k])),
        `подпись не называет норму pro.${k} = ${pro[k]}: обещание разошлось с продуктом`,
      ).toBe(true);
      expect(
        подпись.includes(String(free[k])),
        `подпись не называет бесплатную норму ${k} = ${free[k]}: сравнивать не с чем`,
      ).toBe(true);
    }
  });

  test("«выкладки без предела» — правда, а не фигура речи", () => {
    expect(нормы("pro").deploy, "в таблице у pro КОНЕЧНОЕ число выкладок, а подпись обещает «без предела»").toBe(-1);
    expect(подпись).toContain("без предела");
  });

  test("КОНТРОЛЬ: подпись не стала голым обещанием без самого продукта", () => {
    // Иначе «за что деньги» вытеснило бы то, ЧТО это такое, и карточка перестала бы
    // отвечать человеку, впервые её открывшему.
    expect(подпись, "из подписи исчезло описание самого модуля").toMatch(/IDE|VS Code/);
    expect(подпись.length, "подпись стала длиннее, чем читают на карточке").toBeLessThan(400);
  });
});
