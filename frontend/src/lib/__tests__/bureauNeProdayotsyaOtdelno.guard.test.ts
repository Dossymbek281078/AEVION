/**
 * 🔴 БЮРО НЕ ПРЕДЛАГАЕТСЯ К ПОКУПКЕ ОТДЕЛЬНО — слово основателя 12.10.2026.
 *
 * Повод: кнопка «Купить IP Bureau» за $16–32/мес продавала то, что гость уже
 * получает бесплатно (у `aevion-ip-bureau` в данных доступа стена false), а
 * единственное платное в модуле — отметка Verified — купить нельзя: проверка
 * личности заглушка, провайдер платежей бюро настроен неверно. Это ложное
 * обещание на продающей странице.
 *
 * Сторож держит ОБЕ стороны, потому что ошибиться можно в любую:
 *   • бюро пропало из предложения — и на витрине, и в разметке для поиска,
 *     и на плашке своего модуля;
 *   • остальные ЧЕТЫРЕ приложения на месте. Запрет, который снёс всё, — это
 *     не исполнение слова, а новая беда; знаменатель назван числом.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { STANDALONE_APPS } from "@/lib/termPricing";
import { predlagaemOtdelno, НЕ_ПРОДАЁТСЯ_ОТДЕЛЬНО } from "@/lib/neProdayotsyaOtdelno";

/*
 * Знаменатели названы числами, и их ДВА — я сам спутал их в первой редакции и
 * проверка справедливо упала («expected 9 to be 5»):
 *   9 — приложений в КАТАЛОГЕ (STANDALONE_APPS), у каждого есть цена;
 *   5 — из них с заведённым вариантом в кассе, то есть реально покупаемых
 *       (cyberchess, multichat, qventure, ip_bureau, devhub — по ответу
 *       /api/pricing/checkout/healthz от 12.10.2026).
 * Слово основателя убирает из ПРЕДЛОЖЕНИЯ одно из этих пяти, значит кнопок
 * «Купить» на витрине остаётся четыре — ровно то число, которое велено
 * проверить замером после выкатки.
 */
const В_КАТАЛОГЕ = 9;
const ПОКУПАЕМЫХ_БЫЛО = 5;
// 19.10.2026, слово основателя: один план — отдельно остаются только шахматы.
const ПОКУПАЕМЫХ_СТАЛО = 1;
const ПОКУПАЕМЫЕ = ["cyberchess", "multichat", "qventure", "ip_bureau", "devhub"];

describe("бюро убрано из предложения, остальное цело", () => {
  it("🔴 бюро не предлагается; с 19.10 из пяти остаются только шахматы", () => {
    expect(STANDALONE_APPS.length, "каталог приложений изменился — пересчитайте знаменатель").toBe(В_КАТАЛОГЕ);
    expect(predlagaemOtdelno("ip_bureau")).toBe(false);
    const покупаемыеСейчас = ПОКУПАЕМЫЕ.filter((s) => predlagaemOtdelno(s));
    expect(покупаемыеСейчас.length, `кнопок «Купить» останется ${покупаемыеСейчас.length}, ждали ${ПОКУПАЕМЫХ_СТАЛО}`).toBe(ПОКУПАЕМЫХ_СТАЛО);
    expect(ПОКУПАЕМЫЕ.length).toBe(ПОКУПАЕМЫХ_БЫЛО);
    for (const слаг of ["cyberchess"]) {
      expect(predlagaemOtdelno(слаг), `${слаг} пропал из предложения — снесли лишнее`).toBe(true);
    }
    // И остальные четыре каталога (qright, qsign, startup_exchange, qskyway)
    // не тронуты: у них своей кассы и так нет, но из предложения их никто не убирал.
    for (const слаг of ["multichat", "qventure", "devhub", "qright", "qsign", "startup_exchange", "qskyway"]) {
      expect(predlagaemOtdelno(слаг), `${слаг}: 19.10 снят с отдельной продажи, а предлагается`).toBe(false);
      expect(НЕ_ПРОДАЁТСЯ_ОТДЕЛЬНО[слаг], `${слаг}: у запрета нет причины`).toContain("19.10.2026");
    }
  });

  it("🔴 у запрета названа ПРИЧИНА — иначе через месяц строку никто не поймёт", () => {
    const причина = НЕ_ПРОДАЁТСЯ_ОТДЕЛЬНО["ip_bureau"];
    expect(причина, "причина не записана").toBeTruthy();
    expect(причина.length).toBeGreaterThan(40);
    expect(причина.toLowerCase()).toMatch(/verified|kyc/);
  });

  it("🔴 бюро не осталось в самом списке приложений — доступ купившим не сломан", () => {
    // Слаг обязан ОСТАТЬСЯ в STANDALONE_APPS: по нему считаются цены, узнаётся
    // уже оплаченная подписка и берётся имя модуля на экране заплатившего.
    // Вычеркнуть его оттуда значило бы сломать доступ тем, кто уже купил.
    expect(STANDALONE_APPS.some((a) => a.slug === "ip_bureau"), "слаг выкинули из каталога — у купивших отвалится доступ").toBe(true);
  });

  it("🔴 все три точки покупки спрашивают ОДИН список", () => {
    const файл = (п: string) => readFileSync(join(process.cwd(), п), "utf8");
    const точки: Array<[string, string]> = [
      ["витрина /pricing", "src/app/pricing/page.tsx"],
      ["разметка для поиска", "src/lib/appsJsonLd.ts"],
      ["плашка модуля", "src/components/ModulePricingChip.tsx"],
    ];
    const без = точки.filter(([, п]) => !файл(п).includes("predlagaemOtdelno"));
    expect(без.map(([имя]) => имя), "точка покупки не спрашивает список").toEqual([]);
  });

  it("контроль прибора: незнакомый слаг предлагается, запрет не ловит всё подряд", () => {
    expect(predlagaemOtdelno("выдуманный_слаг")).toBe(true);
  });
});
