/**
 * Награда за возвращение: сколько дней подряд и сколько Chessy за это.
 *
 * Вынесено из page.tsx отдельным файлом, потому что ЭТО и есть причина
 * вернуться завтра — а закреплено оно ничем не было (28.08.2026). Внутри
 * страницы функцию не покрыть тестом: страница клиентская и тянет за собой
 * весь модуль.
 *
 * Чистый расчёт: одни и те же входы дают один и тот же ответ.
 */
export function наградаЗаВозврат(
  lastDaily: string | undefined,
  streak: number,
  сегодня: string,
  вчера: string,
): { streak: number; bonus: number } | null {
  if (lastDaily === сегодня) return null; // сегодня уже приходил
  const новая = lastDaily === вчера ? streak + 1 : 1; // пропустил день — серия с нуля
  const bonus = новая >= 14 ? 200 : новая >= 7 ? 100 : новая >= 3 ? 30 : 5;
  return { streak: новая, bonus };
}
