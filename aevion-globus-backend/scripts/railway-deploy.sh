#!/usr/bin/env bash
# Выкатка бэкенда на Railway с честной отметкой коммита.
#
# Зачем скрипт, а не одна команда `railway up`. В /health есть поле `commit`, и
# оно единственное, чем снаружи можно доказать, КАКОЙ код сейчас на проде.
# Railway подставляет RAILWAY_GIT_COMMIT_SHA только когда собирает из git-репо;
# мы с 27.07 грузим папкой (GitHub закрыт), поэтому поле молча показывало
# "unknown" — то есть проверка после выкатки отвечала «сервер жив», но не
# отвечала «выкатилось то, что я собрал». Разница дорогая: ровно так однажды
# оказалось, что задеплоена не та ветка.
#
# Запасное поле GIT_SHA в коде было всегда, выставлять его было некому. Теперь
# выставляется здесь, одним заходом с выкаткой, — забыть нельзя.
#
# Использование:
#   bash scripts/railway-deploy.sh "короткое описание выкатки"
#
# Только выкатка. Ничего не удаляет, наружу в git не ходит.

set -euo pipefail

MSG="${1:-выкатка без описания}"
BACKEND_DIR="$(cd "$(dirname "$0")/.." && pwd)"
# Грузить надо КОРЕНЬ репозитория, а не каталог бэкенда.
#
# Проверено 14.08.2026 запросом настроек сервиса: у сервиса AEVION
# rootDirectory не задан, а сборка идёт командой
# `cd aevion-globus-backend && npm install && npm run build`. Если залить сам
# каталог бэкенда, этот `cd` падает первым же шагом — внутри него нет вложенной
# папки с таким именем. Прежняя версия скрипта заходила в каталог бэкенда, и
# поэтому отметка коммита ни разу не доехала: сборка не собиралась вовсе.
REPO_ROOT="$(cd "$BACKEND_DIR/.." && pwd)"
cd "$REPO_ROOT"

SHA="$(git rev-parse HEAD)"
BRANCH="$(git rev-parse --abbrev-ref HEAD)"
DIRTY=""
if ! git diff --quiet || ! git diff --cached --quiet; then
  # Незакоммиченные правки означают, что отметка коммита будет ВРАТЬ: уедет
  # рабочая копия, а /health назовёт последний коммит. Лучше остановиться.
  echo "ОСТАНОВКА: в рабочей копии есть незакоммиченные изменения." >&2
  echo "Отметка коммита в /health показала бы ${SHA:0:12}, а уехало бы другое." >&2
  git status --short | head -20 >&2
  exit 1
fi

echo "ветка:  $BRANCH"
echo "коммит: ${SHA:0:12}"
echo "повод:  $MSG"

# ── чья ветка сейчас на проде ──────────────────────────────────────────
#
# Сервис AEVION один на всю платформу, а выкатка заменяет образ ЦЕЛИКОМ.
# 14.08.2026 в него выкатились пять разных сессий подряд, и каждая унесла
# работу предыдущей — ни одна выкатка при этом не была ошибкой, просто никто
# не спрашивал, чьё там сейчас.
#
# Три исхода различаются намеренно: своя ветка, чужая, и «спросить не удалось».
# Последний — НЕ разрешение: неотвеченный вопрос не равен ответу «свободно».
PROD_URL="${PROD_HEALTH_URL:-https://api.aevion.app/health}"
PROD_JSON="$(curl -s --max-time 20 "$PROD_URL" 2>/dev/null || true)"
PROD_BRANCH="$(printf '%s' "$PROD_JSON" | node -pe "try{JSON.parse(require('fs').readFileSync(0,'utf8')).branch||''}catch(e){''}" 2>/dev/null || true)"
PROD_COMMIT="$(printf '%s' "$PROD_JSON" | node -pe "try{JSON.parse(require('fs').readFileSync(0,'utf8')).commit||''}catch(e){''}" 2>/dev/null || true)"

if [ -z "$PROD_JSON" ]; then
  PROD_STATE="не ответил"
elif [ -z "$PROD_BRANCH" ] || [ "$PROD_BRANCH" = "null" ]; then
  PROD_STATE="ветку не называет"
elif [ "$PROD_BRANCH" = "$BRANCH" ]; then
  PROD_STATE="своя"
elif [ -n "$PROD_COMMIT" ] && git merge-base --is-ancestor "$PROD_COMMIT" HEAD 2>/dev/null; then
  # Имя чужое, но коммит прода лежит в истории нашей ветки — значит их работа
  # уже внутри и сносить нечего. Признак — РОДСТВО, а не имя.
  #
  # 19.08.2026: правильно собранная объединённая ветка получила здесь отказ,
  # тогда как aevion-deploy-check.mjs на том же состоянии отвечал «выкатывать
  # можно». Два прибора об одном — источник расхождений, а ложный отказ хуже
  # отсутствия проверки: к обходу через ALLOW_OVERWRITE привыкают, и защита
  # перестаёт работать в том случае, ради которого написана.
  PROD_STATE="чужая по имени ($PROD_BRANCH), но целиком внутри вашей"
else
  PROD_STATE="чужая: $PROD_BRANCH"
fi
echo "на проде: $PROD_STATE"

case "$PROD_STATE" in "своя"|"чужая по имени"*) SAFE=1 ;; *) SAFE=0 ;; esac
if [ "$SAFE" = "0" ] && [ -z "${ALLOW_OVERWRITE:-}" ]; then
  {
    echo ""
    echo "ОСТАНОВКА: выкатка заменит образ целиком, а на проде не ваша ветка."
    echo "  на проде: ${PROD_BRANCH:-неизвестна}"
    echo "  у вас:    $BRANCH"
    echo ""
    echo "Соберите ветку, где живёт и та работа, и ваша. Подробности и готовые"
    echo "команды: node C:\Users\user\aevion-deploy-check.mjs"
    echo "Если объединение уже сделано и вы понимаете, что делаете:"
    echo "  ALLOW_OVERWRITE=1 bash scripts/railway-deploy.sh \"$MSG\""
  } >&2
  exit 1
fi


# Отметка едет ВНУТРИ загружаемой папки, а не в переменных сервиса.
#
# Первая версия ставила GIT_SHA переменной — и это оказалось хуже отсутствия
# отметки. Переменные живут в сервисе и переживают чужие выкатки: ночью 14.08
# соседняя сессия выкатила в тот же сервис AEVION свою ветку, а /health
# продолжал называть мой коммит. Проверка отвечала «сборка совпадает» при
# полностью подменённом проде.
#
# ВАЖНО: отметка не должна быть скрыта от git НИКАКИМ способом.
#
# Первая версия правила клала её в .gitignore — и образ уезжал без отметки.
# Вторая перенесла запись в .git/info/exclude, рассудив, что `railway up`
# смотрит только в .gitignore. 14.08.2026 проверено: не так. CLI использует
# полную цепочку git-исключений, info/exclude в неё входит, и отметка снова
# оставалась дома. Поэтому строка оттуда убрана (см. соседний скрипт-проверку).
# Файл живёт секунды и убирается сразу после загрузки — засорить рабочие копии
# соседних сессий он не успевает.
# Уборка ставится ДО создания файла, а не после. Если процесс умрёт между
# записью и объявлением trap (Ctrl+C, обрыв сети, нет места), файл останется в
# рабочей копии — а он специально НЕ в игноре, значит уедет в следующий
# `git add .` и будет врать коммитом несостоявшейся выкатки. Случилось
# 19.08.2026: клиент railway отвалился по таймауту API, отметка осталась.
# `rm -f` на ещё не созданный файл безвреден.
trap 'rm -f "$BACKEND_DIR/build-info.json"' EXIT

cat > "$BACKEND_DIR/build-info.json" <<JSON
{
  "commit": "$SHA",
  "branch": "$BRANCH",
  "source": "railway-deploy.sh",
  "builtAt": "$(date -u +%Y-%m-%dT%H:%M:%SZ)"
}
JSON

# Отметка обязана быть ВИДНА git, иначе она не уедет. Проверяем до загрузки:
# молчаливая потеря отметки — ровно та неисправность, ради которой всё это.
if git check-ignore -q "$BACKEND_DIR/build-info.json"; then
  echo "ОСТАНОВКА: build-info.json скрыт git-исключением — отметка не уедет." >&2
  git check-ignore -v "$BACKEND_DIR/build-info.json" >&2
  exit 1
fi

# Код возврата CLI НЕ решает, состоялась ли выкатка.
#
# 19.08.2026: `railway up` отвалился с «operation timed out» на своём запросе к
# API, а сборка на сервере продолжилась и доехала. Скрипт при этом завершился
# бы с ошибкой и сказал «не выкатилось» — про успешную выкатку. Обрыв связи с
# клиентом это не ответ о состоянии прода; ответ даёт сам прод, и он ниже.
# ── Привязан ли ЭТОТ каталог к проекту Railway ───────────────────────────
#
# 23.08.2026: в свежем worktree привязки нет. Она живёт не в репозитории, а в
# общем ~/.railway/config.json, и ключом ей служит АБСОЛЮТНЫЙ ПУТЬ каталога —
# то есть новый worktree не наследует её ни от репозитория, ни от соседей.
# Клиент в таком случае отвечает «No linked project found» и НЕ ГРУЗИТ НИЧЕГО.
#
# Скрипт при этом объявлял ровно то же, что и при обрыве связи: «сборка могла
# продолжиться на сервере», и потом пять минут ждал коммит, которого никто не
# отправлял. Ожидание снаружи неотличимо от выкатки. Различие настоящее и
# дешёвое: обрыв API — это «не знаю», отсутствие привязки — это твёрдое «нет».
#
# Три исхода: файла привязок нет вовсе — говорим вслух и едем (сам механизм
# мог смениться, и вечный отказ здесь хуже); файл есть, а нас в нём нет —
# отказ до загрузки; нашлись — молчим и едем.
LINK_CFG="$HOME/.railway/config.json"
if [ ! -f "$LINK_CFG" ]; then
  echo "ВНИМАНИЕ: $LINK_CFG не найден — привязку проверить НЕ УДАЛОСЬ." >&2
  echo "  Это не «всё хорошо»: если каталог не привязан, загрузки не будет." >&2
elif ! grep -q "$(basename "$REPO_ROOT")" "$LINK_CFG"; then
  echo "ОСТАНОВКА: каталог $REPO_ROOT не привязан к проекту Railway." >&2
  echo "  Клиент ответит «No linked project found» и не загрузит НИЧЕГО," >&2
  echo "  а проверка ниже будет пять минут ждать коммит, которого не отправляли." >&2
  echo "  Привяжите каталог (railway link) — проект nurturing-creativity," >&2
  echo "  сервис AEVION, окружение production." >&2
  exit 1
fi

# ── День запуска: предупреждение, а не запрет ────────────────────────────
#
# Очередь соперников и идущие партии CyberChess живут в ПАМЯТИ процесса
# (`QUEUE`, `MATCHES`, `PRESENCE` в routes/cyberchessMatchmaking.ts). Выкатка
# заменяет образ целиком, то есть обрывает все партии, которые идут прямо
# сейчас. Результаты и рейтинг переживают — они в базе, — а человек, который
# в этот момент играл, теряет партию.
#
# 30 августа люди приходят пачкой по письму, и цена такой выкатки выше обычной.
# Запрещать не берусь: бывают срочные починки, ради которых прервать партии
# правильнее, чем оставить сломанное. Поэтому говорим вслух и продолжаем —
# решение остаётся за человеком, но принимается со знанием.
LAUNCH_DAY="${AEVION_LAUNCH_DAY:-2026-08-30}"
if [ "$(date +%Y-%m-%d)" = "$LAUNCH_DAY" ]; then
  hour=$(date +%H)
  if [ "$hour" -ge 9 ] && [ "$hour" -lt 21 ]; then
    echo >&2
    echo "⚠ СЕГОДНЯ ДЕНЬ ЗАПУСКА CYBERCHESS, и сейчас часы притока людей." >&2
    echo "  Эта выкатка заменит образ целиком и оборвёт ВСЕ идущие партии" >&2
    echo "  и очередь соперников — они живут в памяти процесса." >&2
    echo "  Результаты и рейтинг сохранятся, партия у человека — нет." >&2
    echo "  Если починка не срочная, лучше после 21:00." >&2
    echo >&2
  fi
fi

set +e
env -u RAILWAY_TOKEN railway up -c -m "$MSG"
UP_CODE=$?
set -e
if [ "$UP_CODE" -ne 0 ]; then
  echo "  ⚠️ клиент railway вернул $UP_CODE — сборка могла продолжиться на сервере." >&2
  echo "     Решает не он, а ответ прода ниже." >&2
fi

echo
echo "Проверить, что доехало именно это (поле commit должно стать ${SHA:0:12}):"
echo "  curl -s https://api.aevion.app/health"

# ── проверка ПОСЛЕ выкатки ─────────────────────────────────────────────
#
# Раньше скрипт заканчивался советом «проверьте сами». Совет — не проверка:
# 14.08 прод трижды за день оказывался чужим, и каждый раз это выяснялось
# случайно, часы спустя. Проверка, которую надо не забыть выполнить, ничем не
# отличается от отсутствующей.
#
# Здесь только ЧТЕНИЕ и только универсальное — ничего специфичного для одного
# модуля: скрипт общий для всех вкладок.

echo
echo "── проверяю, что доехало именно это ──"

LANDED=""
# Сколько ждать. Первая версия ждала минуту и дважды объявила неудачу об ИДУЩЕЙ
# сборке: Railway собирает две-четыре минуты. Сторож, краснеющий на здоровой
# выкатке, научит себя игнорировать быстрее, чем поймает первую поломку.
# Выход досрочный, поэтому длинное окно платится только в плохом случае.
WAIT_TRIES="${DEPLOY_WAIT_TRIES:-25}"
for i in $(seq 1 "$WAIT_TRIES"); do
  GOT="$(curl -s --max-time 15 "$PROD_URL" 2>/dev/null | node -pe \
    "try{JSON.parse(require('fs').readFileSync(0,'utf8')).commit||''}catch(e){''}" 2>/dev/null || true)"
  if [ "$GOT" = "${SHA:0:12}" ]; then LANDED=1; break; fi
  # Третий коммит — не наш и не тот, что был до старта — означает, что пока мы
  # ждали, на прод въехала ЧУЖАЯ выкатка. Прежде сообщение на этом месте
  # говорило «либо сборка упала, либо выкатился кто-то ещё», то есть называло
  # две болезни разом и не помогало выбрать. Различаем фактом.
  if [ -n "$GOT" ] && [ "$GOT" != "$PROD_COMMIT" ]; then OVERTAKEN="$GOT"; fi
  # Печатаем раз в минуту, а не каждую попытку: два десятка одинаковых строк
  # читаются как поломка сами по себе.
  if [ $((i % 5)) -eq 1 ]; then
    printf '  ждём сборку (%s/%s): на проде %s\n' "$i" "$WAIT_TRIES" "${GOT:-нет ответа}"
  fi
  sleep 12
done

if [ -n "$LANDED" ]; then
  echo "  ✓ на проде ${SHA:0:12} — доехало"
else
  # Пять минут заведомо больше наблюдаемого времени сборки — молчание после
  # такого срока это уже не «ещё катится».
  echo "  ✗ за $((WAIT_TRIES * 12)) с прод так и не назвал ${SHA:0:12}." >&2
  if [ -n "${OVERTAKEN:-}" ]; then
    echo "    ПРИЧИНА НАЗВАНА: пока шла ваша сборка, на прод въехала чужая выкатка" >&2
    echo "    (на проде $OVERTAKEN, до старта был ${PROD_COMMIT:-неизвестен})." >&2
    echo "    Ваша работа не потеряна — она в ветке; вобрать их коммит и выкатить" >&2
    echo "    заново: git merge $OVERTAKEN" >&2
  else
    echo "    Прод всё это время показывал ${PROD_COMMIT:-неизвестное}, чужой выкатки" >&2
    echo "    не видно — значит дело в самой сборке. Логи: railway logs --build" >&2
  fi
  exit 1
fi

# Все ли модули платформы на месте. Проверка читает набор проб из репозитория;
# нет файла — молча пропускаем, скрипт не должен зависеть от чужой части дерева.
if [ -f "$BACKEND_DIR/scripts/prod-module-surface.js" ]; then
  echo
  echo "── все ли модули на месте ──"
  ( cd "$BACKEND_DIR" && node scripts/prod-module-surface.js ) || {
    echo "  ⚠️ проверка модулей нашла расхождение — читайте вывод выше" >&2
  }
fi

echo
echo "Полное доказательство сохранности данных (пишет в базу, ~2 мин):"
echo "  railway run --service Postgres sh -c 'DATABASE_URL=\"\$DATABASE_PUBLIC_URL\" bash scripts/verify-persistence-live.sh'"

