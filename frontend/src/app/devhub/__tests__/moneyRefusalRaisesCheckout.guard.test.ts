/**
 * Денежный отказ обязан поднимать плашку с кассой — на всех трёх языках.
 *
 * 🔴 ЗАМЕР 07.10.2026, ради которого сторож. Плашка (несмываемая, с кнопкой
 * покупки и ссылкой «уже оплатили?») поднимается в showToast по совпадению
 * текста. Текст приходит с сервера и проходит через devhubServerError, а русская
 * карта там ключуется по АНГЛИЙСКИМ сообщениям. Восемь мест в devhub.ts писали
 * отказ по-русски прямо в ответе — они карту минуют, и условие их не ловило:
 * пять возможностей из девяти (генерации, аудиоэффекты, клонирование голоса,
 * распознавание речи, перевод) показывали тост на четыре секунды и НИ ОДНОЙ
 * кнопки. Это единственное место, где DevHub просит денег у того, кто уже
 * получил пользу, — то есть ровно тот момент, который нельзя терять.
 *
 * ЧТО ИМЕННО СТЕРЕЖЁТСЯ, и почему именно так:
 * 1. Перечисление — из ИСХОДНИКА БЭКЕНДА, а не из списка в этом файле: иначе
 *    завтра добавят 402 с новым текстом, и сторож останется зелёным (класс
 *    «список ведут в двух местах»).
 * 2. Условие подъёма тоже ЧИТАЕТСЯ из страницы, а не копируется сюда. Копия
 *    разошлась бы с правдой молча — а именно расхождение и было дефектом.
 * 3. Проверяется ПОКАЗАННЫЙ текст (после devhubServerError) для ru, en и kk:
 *    решение о плашке принимается именно по нему.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

import { devhubServerError } from "../../../lib/devhubServerError";

const КОРЕНЬ = process.cwd();
const БЭКЕНД = join(КОРЕНЬ, "..", "aevion-globus-backend", "src", "routes", "devhub.ts");
const СТРАНИЦА = join(КОРЕНЬ, "src", "app", "devhub", "[id]", "page.tsx");

/** Условие подъёма плашки — ровно то, что стоит в коде страницы. */
function условиеПодъёма(): RegExp {
  const код = readFileSync(СТРАНИЦА, "utf8");
  const строка = код.split("\n").find((l) => l.includes("setUpgradeNudge(message)") === false
    && l.includes("test(message)") && l.includes("if ("));
  expect(строка, "в странице не найдено условие подъёма плашки кассы").toBeTruthy();
  const от = строка!.indexOf("/");
  const до = строка!.lastIndexOf("/");
  expect(до > от, "не удалось выделить образец условия").toBe(true);
  return new RegExp(строка!.slice(от + 1, до), "i");
}

/** Все литеральные сообщения 402 из бэкенда. */
function отказы402(): string[] {
  const строки = readFileSync(БЭКЕНД, "utf8").split("\n");
  const найдено: string[] = [];
  строки.forEach((l, i) => {
    if (!l.includes("status(402)")) return;
    const блок = строки.slice(i, i + 6).join(" ");
    const m = блок.match(/error:\s*"([^"]+)"/);
    if (m) найдено.push(m[1]);
  });
  return [...new Set(найдено)];
}

/** Отказ ПО ПРЕДЕЛУ — тот, за которым идут деньги. Прочее 402 кассу не поднимает. */
const предел = (с: string) => /limit reached/i.test(с) || /лимит|норма/i.test(с);

const условие = условиеПодъёма();
const все = отказы402();
const пределы = все.filter(предел);

describe("денежный отказ поднимает кассу", () => {
  it("условие и перечисление прочитаны", () => {
    // Контроль приборов: оба могли вернуть пустоту и дать зелёное на ничём.
    expect(условие.test("Monthly deploy limit reached"),
      "условие не ловит даже заведомо денежный отказ — образец выделен неверно").toBe(true);
    expect(условие.test("файл не найден"), "условие ловит ЛЮБОЙ текст — проверка бессмысленна").toBe(false);
    expect(все.length, "в бэкенде не найдено ни одного 402").toBeGreaterThanOrEqual(14);
    expect(пределы.length, "не найдено ни одного отказа по пределу").toBeGreaterThanOrEqual(7);
  });

  for (const lang of ["ru", "en", "kk"]) {
    it(`на языке ${lang} все отказы по пределу поднимают кассу`, () => {
      const глухие = пределы
        .map((с) => ({ с, показано: devhubServerError(с, "fallback", lang) }))
        .filter((x) => !условие.test(x.показано))
        .map((x) => `"${x.с}" -> показано "${x.показано}"`);
      expect(глухие,
        "отказ по пределу не поднимает плашку с кассой: человек увидит тост на 4 секунды и ни одной кнопки",
      ).toEqual([]);
    });
  }

  it("EN-читатель видит денежный отказ по-английски, ru и kk — по-русски", () => {
    /*
     * Найдено мутацией 07.10: я вернул один отказ на русский литерал, и первая
     * редакция сторожа это ПРОПУСТИЛА — потому что страховка в условии поднимает
     * плашку и на русском тексте. Касса появляется, а EN-покупатель читает
     * русское предложение в тот самый момент, когда решает платить. Две разные
     * вещи: поднялась ли касса и на каком языке её повод.
     */
    const кириллица = /[а-яА-ЯёЁ]/;
    const поАнглийски = пределы
      .map((с) => ({ с, показано: devhubServerError(с, "fallback", "en") }))
      .filter((x) => кириллица.test(x.показано))
      .map((x) => `"${x.с}" -> EN видит "${x.показано}"`);
    expect(поАнглийски, "EN-покупатель читает русский текст в денежный момент").toEqual([]);
    const поРусски = пределы
      .map((с) => ({ с, показано: devhubServerError(с, "fallback", "ru") }))
      .filter((x) => !кириллица.test(x.показано))
      .map((x) => `"${x.с}" -> ru видит "${x.показано}"`);
    expect(поРусски, "русский покупатель читает английский текст в денежный момент").toEqual([]);
  });

  it("в русском тексте нет английского имени нормы", () => {
    /*
     * Карта имён (IMYA_NORMY) переводит «deploy» в «публикации». Имени в ней не
     * оказалось — и русский читатель видит «Месячная норма исчерпана: voice
     * clone». Плашка при этом поднимается, поэтому проверка выше такое пропустит:
     * это отдельный вопрос — что человек ЧИТАЕТ, а не поднялась ли касса.
     * Поймано мутацией 07.10 (снятие «voice clone» из карты).
     */
    const имена = пределы
      .map((с) => ({ с, имя: (с.match(/^monthly ([\w ]+?) limit reached/i) || [])[1] }))
      .filter((x) => x.имя);
    expect(имена.length, "ни одного английского отказа по пределу не разобрано").toBeGreaterThanOrEqual(7);
    const протекло = имена
      .map((x) => ({ ...x, показано: devhubServerError(x.с, "fallback", "ru") }))
      .filter((x) => x.показано.toLowerCase().includes(x.имя!.toLowerCase()))
      .map((x) => `"${x.с}" -> показано "${x.показано}"`);
    expect(протекло, "русский текст содержит английское имя нормы — карта имён не знает его").toEqual([]);
  });

  it("внутреннее сообщение о счёте поставщика НЕ показывается покупателю", () => {
    // Вторая находка того же замера: ru/kk получали человеческий текст, а EN
    // читал «top up the Replicate account» — имя поставщика и наш счёт.
    const внутреннее = "Video provider has no credit — top up the Replicate account to generate";
    for (const lang of ["ru", "en", "kk"]) {
      const показано = devhubServerError(внутреннее, "fallback", lang);
      expect(показано.toLowerCase(), `на языке ${lang} покупателю видно имя поставщика`)
        .not.toContain("replicate");
    }
  });
});
