import { describe, it, expect } from "vitest";
import { gameResultOf } from "../gameResult";

/* Полный перечень того, что попадает в `over`, и ожидаемый класс каждой строки.
   Нужен потому, что вокруг этого значения выросли СЕМЬ независимых словарей —
   строка состояния, итог коуча, профиль соперника, призрак, конфетти, статистика
   вариантов и турнирная сетка, — и каждый знал свой кусок.

   Самая дорогая ошибка была в турнире: всё, что не подошло под два английских
   шаблона, объявлялось НИЧЬЁЙ. «You resigned» под них не подходит, поэтому сдача
   записывалась ничьёй, двигала сетку как ничью и платила 5 Chessy — сдаться было
   выгоднее, чем проиграть. Отсюда последний тест файла: неизвестный текст обязан
   падать в поражение, а не в ничью. */

const ENDINGS: Array<[string, "W" | "L" | "D"]> = [
  ["Checkmate! You win! 🏆", "W"],
  ["Checkmate — AI wins", "L"],
  ["AI timed out — you win!", "W"],
  ["Time out", "L"],
  ["You resigned", "L"],
  ["Alex сдался — Вы победили!", "W"],
  ["Stalemate", "D"],
  ["Threefold repetition", "D"],
  ["Insufficient material", "D"],
  ["50-move draw", "D"],
  ["Draw agreed", "D"],
  ["Ничья (договорились)", "D"],
  ["⚡ Три шаха — победа!", "W"],
  ["⚡ Соперник дал 3 шаха — поражение", "L"],
  ["⛰ Король взошёл на холм — победа!", "W"],
  ["⛰ Соперник занял центр — поражение", "L"],
  ["💥 Король соперника взорван — победа!", "W"],
  ["💥 Твой король взорван — поражение", "L"],
  ["Королевский ферзь соперника пал — победа!", "W"],
  ["Твой королевский ферзь пал — поражение", "L"],
];

describe("словарь исходов партии", () => {
  for (const [line, want] of ENDINGS) {
    it(`«${line}» → ${want}`, () => expect(gameResultOf(line)).toBe(want));
  }

  it("сдача — поражение, а не ничья", () => {
    // В турнире ничья платила 5 Chessy, поражение — ноль. Пока это поражение,
    // сдаваться невыгодно; если кто-то вернёт сюда ничью, награда станет фармом.
    expect(gameResultOf("You resigned")).toBe("L");
  });

  it("неизвестное окончание падает в поражение, а не в ничью", () => {
    // Ничья — оплачиваемый исход, поэтому она не может быть значением по умолчанию.
    expect(gameResultOf("что-то, чего ещё не существует")).toBe("L");
  });

  it("побед ровно столько, сколько их в перечне", () => {
    const w = ENDINGS.filter(([l]) => gameResultOf(l) === "W").length;
    expect(w).toBe(ENDINGS.filter(([, c]) => c === "W").length);
  });
});
