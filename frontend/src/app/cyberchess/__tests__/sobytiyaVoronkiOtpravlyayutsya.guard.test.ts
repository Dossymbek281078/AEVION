import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/*
 * 🔴 Утверждение: события воронки шахмат отправляются ИЗ ТОГО МЕСТА, где событие
 * действительно произошло, — а не с одной из кнопок, ведущих туда.
 *
 * ПОВОД 07.10.2026, замер окна 98: daily_open за 04–06.10 — ноль во все три дня,
 * включая наши собственные пробы. Ни приём события (сервер знает его с 30.09), ни
 * сводка тут не виноваты. Виновато МЕСТО отправки: track стоял на ОДНОЙ из двух
 * кнопок, открывающих задачу дня, и стоял ДО вызова открытия. Отсюда две ошибки
 * в противоположные стороны одновременно:
 *   недосчёт — вторая кнопка открывала задачу молча;
 *   пересчёт — у первой событие уходило раньше трёх проверок внутри открытия,
 *     так что «задача не загрузилась» и «задача повреждена» считались открытием.
 *
 * ГРАНИЦА, и её надо назвать честно. Этот сторож читает ИСХОДНИК, а не делает
 * запрос: страница — 16 тысяч строк, поднять её в jsdom ради этого нельзя.
 * Значит он проверяет РАСПОЛОЖЕНИЕ отправки, а не факт доставки. Доставку
 * проверяет серверная половина (readableTypesCoverWritableTypes: POST → журнал →
 * GET) и замер воронки на проде после выкатки. Сторож по литералам слаб сам по
 * себе — поэтому ниже он смотрит на СТРУКТУРУ (внутри какой функции и после чего
 * стоит вызов), а не на наличие строки.
 */

const СТРАНИЦА = join(process.cwd(), "src/app/cyberchess/page.tsx");
const ФОРМА = join(process.cwd(), "src/components/WaitlistCapture.tsx");
const текст = readFileSync(СТРАНИЦА, "utf8");

/** Тело функции от её объявления до строки, закрывающей её на том же отступе. */
function teloFunkcii(исходник: string, объявление: string): string {
  const i = исходник.indexOf(объявление);
  if (i < 0) return "";
  const ПС = String.fromCharCode(10);
  const строки = исходник.slice(i).split(ПС);
  const отступ = (объявление.match(/^\s*/) ?? [""])[0];
  const куски: string[] = [строки[0]];
  for (let k = 1; k < строки.length; k++) {
    куски.push(строки[k]);
    if (строки[k] === `${отступ}};` || строки[k] === `${отступ}}`) break;
  }
  return куски.join(ПС);
}

describe("события воронки шахмат отправляются из места события", () => {
  it("КОНТРОЛЬ: разбор нашёл тело функции открытия задачи дня", () => {
    // Пустое тело сделало бы все проверки ниже зелёными при любом состоянии кода.
    const тело = teloFunkcii(текст, "  const loadDailyPuzzle=");
    expect(тело.length, "тело loadDailyPuzzle не найдено — разбор смотрит не туда").toBeGreaterThan(200);
    expect(тело, "в теле нет открытия задачи — разбор взял не ту функцию").toContain("postavitZadachuNaDosku");
  });

  it("🔴 daily_open отправляется ровно один раз, и ВНУТРИ открытия задачи дня", () => {
    const всего = (текст.match(/type:"daily_open"/g) ?? []).length;
    expect(всего, `отправок daily_open в файле: ${всего} (должна быть одна, внутри открытия)`).toBe(1);
    const тело = teloFunkcii(текст, "  const loadDailyPuzzle=");
    expect(тело, "daily_open отправляется вне функции открытия — значит, не со всех путей").toContain('type:"daily_open"');
  });

  it("🔴 daily_open стоит ПОСЛЕ проверок, а не до них", () => {
    // Иначе неудача считается открытием. Признак проверяемый: отправка должна
    // идти позже последнего раннего выхода по непрочитанной задаче.
    const тело = teloFunkcii(текст, "  const loadDailyPuzzle=");
    const гдеОтправка = тело.indexOf('type:"daily_open"');
    const гдеПроверка = тело.lastIndexOf("srvDailyFailed");
    expect(гдеПроверка, "проверка «задача не загрузилась» исчезла из открытия").toBeGreaterThan(-1);
    expect(гдеОтправка, "отправка daily_open стоит раньше проверок — неудача считается открытием").toBeGreaterThan(гдеПроверка);
  });

  it("🔴 ни одна кнопка не шлёт daily_open сама", () => {
    // Ровно это и было сломано: событие на кнопке, а кнопок две.
    const наКnопках = (текст.match(/onClick=\{\(\)=>\{track\(\{type:"daily_open"/g) ?? []).length;
    expect(наКnопках, "событие снова висит на кнопке — второй путь открытия будет молчать").toBe(0);
  });

  it("🔴 game_end отправляется один раз и из эффекта, следящего за концом партии", () => {
    const всего = (текст.match(/type:"game_end"/g) ?? []).length;
    expect(всего, `отправок game_end: ${всего}`).toBe(1);
    const i = текст.indexOf('type:"game_end"');
    // В пределах 1500 знаков перед отправкой обязаны стоять признаки
    // централизованного эффекта: ранний выход по !over и отпечаток против
    // повторной отправки. Иначе это снова отправка с какого-то одного конца
    // партии, а их больше пятнадцати.
    const окрестность = текст.slice(Math.max(0, i - 1500), i);
    // Проверяется, что отправка идёт ЧЕРЕЗ общее решение, а не по условиям,
    // выписанным здесь же. РАЗДЕЛЕНИЕ ТРУДА названо прямо, чтобы не казалось,
    // будто этот сторож проверяет поведение: он проверяет только место вызова.
    // Сами условия (повтор одной партии, загруженный архив, пустой исход)
    // проверяются вызовами с известным ответом в ishodPartii.test.ts, и все три
    // мутации там ловятся. Пока условия стояли в эффекте, мутация «убрать
    // защиту от повтора» проходила сквозь ЭТУ проверку насквозь: имя защиты в
    // тексте оставалось, а поведение менялось.
    expect(окрестность, "game_end шлётся мимо общего решения о конце партии").toContain("resheniePoKontsuPartii({");
    expect(окрестность, "решение есть, но его ответ не проверяется перед отправкой").toContain("if(!reshenie.otpravlyat)return;");
  });

  it("🔴 начало партии шлётся из newG, единственного места, где партия начинается", () => {
    const i = текст.indexOf('feature:"chess_game_start"');
    expect(i, "события начала партии нет вовсе").toBeGreaterThan(-1);
    // Окно 2200 знаков, а не на глаз: расстояние от отметки начала до отправки
    // ИЗМЕРЕНО — 1466 знаков, и почти всё это разбор в комментарии. Первая
    // версия взяла 800 и покраснела на совершенно верном коде; красное на
    // верном опаснее отсутствия сторожа. Запас есть, но не настолько, чтобы в
    // окно попало соседнее начало партии: ближайшее — за тысячи знаков.
    const окрестность = текст.slice(Math.max(0, i - 2200), i);
    expect(окрестность, "начало партии шлётся не там, где ставится отметка начала").toContain("gameStartTimeRef.current=Date.now();");
  });

  it("🔴 в событии про адрес НЕТ самого адреса", () => {
    // Ручка сводки воронки открыта без токена. Личное в неё попадать не может.
    const форма = readFileSync(ФОРМА, "utf8");
    const i = форма.indexOf('type: "waitlist_submit"');
    expect(i, "событие об оставленном адресе не отправляется").toBeGreaterThan(-1);
    // Сам вызов track: от его начала до закрывающей скобки с точкой с запятой.
    const вызов = форма.slice(i, форма.indexOf("});", i) + 3);
    for (const запрещено of ["email", "value", "адрес"]) {
      expect(вызов.includes(запрещено), `в событие попадает «${запрещено}»: ${вызов}`).toBe(false);
    }
    expect(вызов, "в событии нет источника — разрез по странице собрать нечем").toContain("source");
  });

  it("🔴 событие об адресе отправляется ПОСЛЕ подтверждения постоянного хранения", () => {
    // Два отказа выше (опечатка в адресе, непостоянное хранилище) означают, что
    // человека в списке НЕТ. Событие до них считало бы их подписчиками.
    const форма = readFileSync(ФОРМА, "utf8");
    const гдеСобытие = форма.indexOf('type: "waitlist_submit"');
    const гдеПроверка = форма.lastIndexOf('storage !== "postgres"');
    expect(гдеПроверка, "проверка постоянного хранения исчезла").toBeGreaterThan(-1);
    expect(гдеСобытие, "событие уходит раньше проверки хранения — незаписанный адрес считается подписчиком").toBeGreaterThan(гдеПроверка);
  });

  it("КОНТРОЛЬ: разбор тела умеет находить ОТСУТСТВИЕ вызова", () => {
    // Без этого «в теле есть daily_open» могло бы проходить у разбора, который
    // возвращает весь файл: тогда проверка «внутри функции» ничего не значит.
    const тело = teloFunkcii(текст, "  const loadDailyPuzzle=");
    expect(тело.includes('type:"checkout_start"'), "разбор вернул больше, чем тело функции").toBe(false);
    expect(teloFunkcii(текст, "  const takojFunkciiNet="), "разбор придумал тело отсутствующей функции").toBe("");
  });
});
