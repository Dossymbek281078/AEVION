"use client";

import { useEffect } from "react";
import { useFunnel, type ConstitutionEvent } from "@/lib/useFunnel";

/**
 * Один шаг воронки конституции для СЕРВЕРНОЙ страницы.
 *
 * Зачем. В словаре `ConstitutionEvent` объявлено 18 событий, а слали их 11.
 * Часть нулей безобидна (возможности нет вовсе), но `blog_view` — не тот
 * случай: блог существует и открыт людям, а верх воронки модуля не мерился
 * ничем. Поставить хук прямо в страницу нельзя: она серверная, и делать её
 * клиентской ради одного замера значило бы потерять `generateMetadata`,
 * то есть выдачу в поиске. Поэтому замер въезжает крохотным клиентским
 * ребёнком, а страница остаётся серверной.
 *
 * НЕ ПУТАТЬ с `PageTracking`. Тот шлёт в ОБЩИЙ счётчик платформы
 * (`@/lib/track` → `{ type, source }`); этот — в СОБСТВЕННУЮ воронку
 * конституции (`useFunnel` → `/api/constitution/funnel/track`). Счётчика в
 * проекте два, и ставить оба на одну страницу значит посчитать заход дважды.
 *
 * Повтор эффекта в dev гасится throttle-окном внутри `useFunnel`: ref живёт
 * в том же экземпляре компонента, поэтому второй вызов отсекается.
 *
 * Ставится одной строкой: <ConstitutionFunnelPing event="blog_view" />
 */
export function ConstitutionFunnelPing({
  event,
  props,
}: {
  event: ConstitutionEvent;
  props?: Record<string, string | number | boolean>;
}) {
  const { track } = useFunnel();
  // Подпись значений, а не сам объект: у литерала новая ссылка на каждом
  // рендере, и он гнал бы событие бесконечно. Но и БЕЗ него был недосчёт:
  // при переходе между постами React может переиспользовать этот же
  // экземпляр, зависимости [track, event] не меняются, и заход на второй
  // пост не считался бы вовсе — недосчёт ровно там, где он и чинится.
  // Найдено вычиткой дифа, не тестом.
  const signature = JSON.stringify(props ?? {});

  useEffect(() => {
    track(event, props);
    // props намеренно вне зависимостей: объектный литерал у вызывающего меняет
    // ссылку на каждом рендере и слал бы событие снова и снова.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [track, event, signature]);

  return null;
}
