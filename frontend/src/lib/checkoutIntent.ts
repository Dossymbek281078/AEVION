import type { CanonicalTier } from "./paywall";

/**
 * Что человек собирался купить, когда уходил в кассу.
 *
 * ЗАЧЕМ. Кассы возвращают отказавшегося на `/pricing/checkout/cancel?paybox=1`
 * — только с меткой кассы. Тарифа в адресе нет, а экран отмены рисует кнопку
 * «вернуться к тарифу X» лишь при нём. Замерено отрисовкой 02.09.2026:
 *
 *   ?paybox=1             → /pricing, /pricing/contact, /pricing
 *   ?paybox=1&tier=lite   → те же ПЛЮС /pricing/lite     ← контроль
 *
 * То есть единственная кнопка, ведущая обратно к покупке, есть в коде и в проде
 * не появляется НИКОГДА — ровно у того человека, которого ещё можно вернуть.
 * Заодно все события отказа уходят без тарифа: по ним нельзя сказать, от какого
 * тарифа отказываются.
 *
 * Чинить это адресом должна касса, и строка для неё передана владельцу файла
 * (наши копии провайдеров отстали на три месяца, править их значило бы откатить
 * чужую работу). Здесь — половина, которая не зависит ни от кого: страница цен
 * ЗНАЕТ тариф в момент входа в кассу, надо просто не забыть его.
 *
 * ПОЧЕМУ sessionStorage, а не localStorage. Намерение живёт ровно одну вкладку:
 * человек уходит в кассу и возвращается в неё же. Переживи оно закрытие
 * браузера — недельной давности тариф подставился бы к сегодняшнему отказу, и
 * кнопка повела бы не туда. Тот же выбор и по той же причине сделан для канала
 * в `channelNow.ts`, но правило там ОБРАТНОЕ: канал запоминается первый, а
 * намерение — последнее. Поэтому модуль отдельный: в одном файле эти два
 * правила рано или поздно перепутают.
 *
 * 15.09.2026: тариф — это СРОК доступа ко всей планете (lite…max), периода
 * месяц/год больше нет. Зато появилась покупка отдельного приложения на сроке:
 * у неё тариф в записи — это срок, и кнопка «вернуться к тарифу Lite» после
 * отказа от покупки CyberChess повела бы на страницу ВСЕЙ планеты. Поэтому
 * приложение запоминается рядом, а `тарифНамерения()` его отсекает.
 */

const КЛЮЧ = "aevion_checkout_intent";

/** Позже этого срока намерение считается чужим. */
const ЖИВЁТ_МС = 2 * 60 * 60 * 1000;

export type НамерениеПокупки = {
  /** Тариф-срок (lite…max) или free/enterprise. */
  tier: string;
  /** Отдельное приложение (slug кассы), если покупали его, а не планету. */
  app?: string;
  ts: number;
};

/** Запомнить, что человек уходит в кассу за этим тарифом (и приложением, если оно есть). */
export function запомнитьНамерение(tier: string, app?: string): void {
  if (typeof window === "undefined") return;
  const чистый = String(tier ?? "").trim();
  if (!чистый) return;
  const приложение = typeof app === "string" ? app.trim() : "";
  try {
    const запись: НамерениеПокупки = { tier: чистый, ts: Date.now(), ...(приложение ? { app: приложение } : {}) };
    sessionStorage.setItem(КЛЮЧ, JSON.stringify(запись));
  } catch {
    // Приватное окно и запрет хранилища — не повод ломать переход в кассу.
  }
}

/**
 * Чем человек интересовался. `undefined`, если не знаем — и это ЧЕСТНЫЙ ответ:
 * подставлять тариф наугад значит вести кнопкой не туда, а это хуже отсутствия
 * кнопки.
 */
export function вспомнитьНамерение(): НамерениеПокупки | undefined {
  if (typeof window === "undefined") return undefined;
  try {
    const сырое = sessionStorage.getItem(КЛЮЧ);
    if (!сырое) return undefined;
    const з = JSON.parse(сырое) as Partial<НамерениеПокупки>;
    if (typeof з?.tier !== "string" || !з.tier.trim()) return undefined;
    if (typeof з.ts !== "number" || !Number.isFinite(з.ts)) return undefined;
    // Просроченное намерение хуже отсутствующего: оно выглядит как знание.
    if (Date.now() - з.ts > ЖИВЁТ_МС) return undefined;
    const app = typeof з.app === "string" && з.app.trim() ? з.app.trim() : undefined;
    return { tier: з.tier.trim(), ts: з.ts, ...(app ? { app } : {}) };
  } catch {
    return undefined;
  }
}

/**
 * Тариф, к которому честно вести кнопку «вернуться к тарифу».
 *
 * Если человек покупал отдельное приложение, срок в записи — не тариф планеты:
 * страница `/pricing/<срок>` продаёт всю планету, и кнопка повела бы не к той
 * покупке. Такой случай отвечает `undefined` — кнопки не будет, останется
 * общая ссылка на страницу цен.
 */
export function тарифНамерения(): string | undefined {
  const н = вспомнитьНамерение();
  return н && !н.app ? н.tier : undefined;
}

/**
 * Тариф из ссылки кассы, если он там есть.
 *
 * Форма ссылки с 15.09.2026 — `tier_<срок>` (`tier_lite`, `tier_max`); прежняя
 * `tier_<id>_<период>` (`tier_lite_monthly`) понимается тоже: такие ссылки ещё
 * живут в продлениях. Ссылка приложения `app_<slug>_<срок>` тарифом планеты не
 * является и отвечает `undefined`.
 *
 * Нужен, когда касса всё-таки передаст `ref` в адрес отмены: адрес всегда
 * точнее памяти вкладки, поэтому у него приоритет.
 */
export function тарифИзСсылки(ref: string | null | undefined): string | undefined {
  const s = String(ref ?? "");
  if (!s.startsWith("tier_")) return undefined;
  const части = s.split("_");
  // tier_<id> или tier_<id>_<period>: идентификатор — ровно вторая часть.
  const id = части[1];
  return id && id.trim() ? id.trim() : undefined;
}

/**
 * Тарифы, которые МОГУТ прийти в ссылке кассы.
 *
 * Это НЕ то же самое, что `CanonicalTier` из `paywall.ts`, и различие стоило
 * дефекта. Платная стена знает свои пять тарифов и не знает сроков `pro` и
 * `max`: у неё свои правила доступа. А каталог продаёт пять сроков планеты —
 * lite, medium, pro, full, max.
 *
 * Пока проверка опиралась на словарь платной стены, человек, бросивший оплату
 * `pro`, оставался без кнопки «вернуться к тарифу»: его тариф считался
 * неизвестным. Молча — потому что кнопка просто не рисовалась. Тот же пропуск
 * повторился бы с `max` (новый срок 15.09.2026), поэтому он здесь сразу.
 *
 * Замер 04.09.2026: единого списка тарифов в проекте НЕТ, он объявлен заново в
 * пяти файлах, и варианты расходятся. Здесь закреплено ровно то, что нужно
 * этому месту, и написано, почему список именно такой; расхождение со страницей
 * цен ловит `checkoutIntent.test.ts`.
 */
export type ТарифВСсылкеКассы = CanonicalTier | "pro" | "max";

const ИЗВЕСТНЫЕ_ТАРИФЫ: Record<ТарифВСсылкеКассы, true> = {
  free: true,
  lite: true,
  medium: true,
  pro: true,
  full: true,
  max: true,
  enterprise: true,
};

/**
 * Знаем ли мы такой тариф. Всё незнакомое отвергается: подставлять тариф наугад
 * значит вести кнопкой не туда, а это хуже отсутствия кнопки.
 *
 * ЗАЧЕМ вообще проверять. На экране отмены тариф берётся из адреса и оттуда
 * попадает в ТРИ места: в адрес кнопки `/pricing/<тариф>`, в её подпись и в
 * событие учёта. Страницы тарифов живут на динамическом маршруте, поэтому
 * любое значение что-то отрисует — то есть по подобранной ссылке кнопка
 * возврата ведёт в никуда, на экране печатается чужой текст, а в учёт попадает
 * мусорный тариф.
 *
 * Список НЕ ДУБЛИРУЕТСЯ, а сверяется типом: `Record<ТарифВСсылкеКассы, true>`
 * требует перечислить все тарифы, и добавление нового в тип ломает сборку
 * здесь. Второй список, живущий своей жизнью, разошёлся бы молча.
 *
 * Ключ свободный (из адреса), а множество закрытое — поэтому проверяем
 * собственное свойство: служебное имя честно отбрасывается. Там, где ключ
 * свободный И множество открытое (накопители сводок), правильнее объект без
 * прототипа — см. routes/events.ts.
 */
export function тарифИзвестен(t: string | null | undefined): t is ТарифВСсылкеКассы {
  return typeof t === "string" && Object.prototype.hasOwnProperty.call(ИЗВЕСТНЫЕ_ТАРИФЫ, t.trim());
}
