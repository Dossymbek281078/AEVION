/**
 * Экран после оплаты ОТРИСОВЫВАЕТСЯ — а не только проходит проверку исходника.
 *
 * Всё, что я закрепил на этом экране за два дня, проверялось чтением кода:
 * «строка есть», «признак применяется». Ни одна проверка не открывала страницу.
 * А самый дорогой экран платформы человек видит целиком, и падение отрисовки
 * выглядит для него так же, как неудавшаяся оплата.
 *
 * Здесь три случая: настоящий возврат из кассы, голый заход и заглушка.
 */
import { describe, it, expect, vi, afterEach } from "vitest";
import { render, cleanup, act } from "@testing-library/react";
import { I18nProvider } from "@/lib/i18n";

const параметры = { value: "" };
vi.mock("next/navigation", () => ({
  useSearchParams: () => new URLSearchParams(параметры.value),
  useRouter: () => ({ push: vi.fn(), replace: vi.fn() }),
  usePathname: () => "/pricing/checkout/success",
}));

async function открыть(поиск: string) {
  параметры.value = поиск;
  const m = await import("@/app/pricing/checkout/success/page");
  const Страница = m.default as () => import("react").JSX.Element;
  // Страница берёт подписи из поставщика переводов — без него useI18n бросает.
  await act(async () => {
    render(
      <I18nProvider>
        <Страница />
      </I18nProvider>,
    );
  });
}

afterEach(() => cleanup());

describe("экран после оплаты при отказе сервера", () => {
  it("не показывает внутренностей", async () => {
    /*
     * Класс найден соседним окном на странице цен: при недоступном бэкенде
     * покупателю показывали внутренний адрес API, сообщение движка и инструкцию
     * запустить сервер. Грепом это не находится принципиально — строка
     * собиралась из трёх мест, порознь безобидных.
     *
     * Здесь тот же вопрос к самому дорогому экрану: что человек увидит, если
     * сервер не ответит ПОСЛЕ того, как деньги уже списаны.
     */
    vi.stubGlobal("fetch", async () => {
      throw new Error("Failed to parse URL from /api-backend/api/me/entitlements");
    });
    await открыть("paybox=1&ref=abc&tier=lite&total=4900");
    const текст = document.body.textContent ?? "";
    expect(текст, "экран пуст при отказе сервера").not.toBe("");
    for (const внутреннее of ["/api-backend", "/api/", "npm run", "localhost", "Failed to parse"]) {
      expect(текст, `на экране внутренности: ${внутреннее}`).not.toContain(внутреннее);
    }
    vi.unstubAllGlobals();
  }, 60000);
});

describe("экран после оплаты отрисовывается", () => {
  it("возврат PayBox: страница живая и НЕ выдумывает сумму до подтверждения", async () => {
    await открыть("paybox=1&ref=abc&tier=lite&total=4900");
    // Контракт сменился мержем 06.09, и это решение КОДА, а не теста: сумма
    // из адреса возврата (?total=) — утверждение «мы получили от вас $49»,
    // а его до ответа сервера страница делать не вправе (рядом с «оплата
    // принята» это читалось как факт; ?total пишет кто угодно). Пока сервер
    // не подтвердил, экран честно ждёт — и обязан быть живым и понятным.
    const текст = document.body.textContent ?? "";
    expect(текст, "экран пуст").not.toBe("");
    expect(текст, "нет упоминания PayBox — человек не поймёт, где он").toContain("PayBox");
    expect(текст, "непроверенная сумма показана как факт").not.toContain("49");
  }, 60000);

  it("голый заход не падает и не показывает сумму", async () => {
    await открыть("");
    const текст = document.body.textContent ?? "";
    expect(текст, "страница не отрисовалась").not.toBe("");

    /*
     * ВТОРАЯ ПОЛОВИНА НАЗВАНИЯ ДО СЕГОДНЯ НЕ ПРОВЕРЯЛАСЬ. Случай обещал «и не
     * показывает сумму», а утверждение было одно — что экран непуст. Любой
     * текст его удовлетворял, включая экран с суммой.
     *
     * Сумма на голом заходе — это не косметика: страница публичная, и цифра
     * рядом со словами «оплата принята» читается как списание, которого не было.
     *
     * Ищем не подпись (её текст меняют), а ФОРМУ: доллар, за которым цифра.
     * Без регулярного выражения намеренно — одиночная обратная косая теряется
     * на границе вызова инструмента.
     */
    const естьСумма = текст
      .split("$")
      .slice(1)
      .some((часть) => часть.length > 0 && часть[0] >= "0" && часть[0] <= "9");
    expect(естьСумма, "на голом заходе показана сумма").toBe(false);
  }, 60000);

  it("заглушка отрисовывается своим путём", async () => {
    await открыть("stub=true&tier=free");
    const текст = document.body.textContent ?? "";
    expect(текст, "страница не отрисовалась").not.toBe("");

    /*
     * «Своим путём» тоже не проверялось: непустой экран удовлетворял и обычной
     * ветке. А заглушка обязана отличаться видимо — иначе прогон смоука
     * неотличим от настоящей покупки, и мы уже теряли на этом числа.
     *
     * Отличие закреплено по значку: у заглушки 🔬, у настоящей покупки 🎉.
     */
    expect(текст, "заглушка не отличается от настоящей покупки").toContain("🔬");
    expect(текст, "заглушка показана как настоящая покупка").not.toContain("🎉");
  }, 60000);
});
