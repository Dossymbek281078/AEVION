/**
 * Честная надпись о том, ГДЕ лежат данные платёжной панели.
 *
 * ЧТО НАШЛОСЬ 27.08.2026. Панель `/payments/dashboard` читает не сервер, а
 * localStorage браузера (ключи `aevion.payments.*`). Сказано об этом было —
 * но ТОЛЬКО в пустом состоянии: «this dashboard reflects the same localStorage
 * your other surfaces write to». Создал первую ссылку — блок пропал, и дальше
 * экран выглядит обычной платёжной панелью.
 *
 * То есть оговорка показывалась ровно тогда, когда терять нечего, и исчезала
 * ровно тогда, когда у человека появились данные. Это тот же вид, что зелёный
 * баннер сертификата над красной плиткой: утверждение живёт дольше проверки,
 * которая за ним стоит.
 *
 * Отдельно: у сайта есть и серверное состояние — `GET /api/health` отвечает
 * `persistence: "memory"` (замер 27.08.2026, ветка launch/2026-08-30). Оно про
 * ДРУГИЕ поверхности (API платежей), не про эту панель, и гасится подключением
 * постоянного хранилища — это шаг основателя. Поэтому здесь два независимых
 * повода для надписи, и они НЕ смешиваются: браузерное хранение — свойство
 * панели навсегда, серверное — временное состояние площадки.
 *
 * Здесь только РЕШЕНИЕ, отдельно от рисования: его можно прогнать тестом
 * напрямую, а не выскабливать текст из разметки.
 */

/** Где лежат данные API платежей по словам самого сервера. */
export type ServerPersistence = "kv" | "memory" | "unknown";

/**
 * Три исхода, а не два: «спросить не удалось» — это НЕ «всё хорошо».
 * Молчание сервера не даёт права обещать сохранность.
 */
export function readServerPersistence(health: unknown): ServerPersistence {
  if (typeof health !== "object" || health === null) return "unknown";
  const v = (health as { persistence?: unknown }).persistence;
  return v === "kv" ? "kv" : v === "memory" ? "memory" : "unknown";
}

export type Notice = {
  tone: "warn" | "info";
  title: string;
  body: string;
};

/**
 * Надпись для панели. Возвращает ВСЕГДА — данные этой панели лежат в браузере
 * при любом состоянии сервера, и молчать об этом нельзя ни в одном случае.
 *
 * `hasData` меняет не факт, а формулировку: пока пусто, это приглашение
 * попробовать; когда данные есть — предупреждение о том, что их легко потерять.
 */
export function dashboardNotice(
  server: ServerPersistence,
  hasData: boolean,
): Notice {
  const local = hasData
    ? "Всё, что вы здесь создали, хранится ТОЛЬКО в этом браузере: очистка данных сайта, другой браузер или другое устройство — и записей не будет. Это витрина возможностей, а не касса: настоящие деньги через неё не проходят."
    : "Данные этой панели хранятся только в вашем браузере — это витрина возможностей, а не касса. Созданное здесь не увидят ни коллеги, ни другое ваше устройство, и настоящие деньги через неё не проходят.";

  if (server === "memory") {
    return {
      tone: "warn",
      title: "Витрина: данные не покидают ваш браузер",
      body:
        local +
        " Постоянное хранилище платёжного API на площадке пока не подключено, поэтому и серверные поверхности сейчас работают в том же режиме.",
    };
  }
  if (server === "unknown") {
    return {
      tone: "warn",
      title: "Витрина: данные не покидают ваш браузер",
      body:
        local +
        " Состояние серверного хранилища выяснить не удалось — до выяснения не считайте сохранённым ничего.",
    };
  }
  return {
    tone: hasData ? "warn" : "info",
    title: "Витрина: данные не покидают ваш браузер",
    body: local,
  };
}
