import { getApiBase } from "@/lib/apiBase";

/**
 * Отвечает ли путь НАШИМ обработчиком на боевом сервере. Для посадочных запуска.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Функция появилась в двух посадочных сразу двумя копиями,
 * и третья страница запуска породила бы третью.
 *
 * ⚠️ ПРЕЖНЕЕ ПРАВИЛО «живо = не 404» БЫЛО НЕВЕРНО В ОБЕ СТОРОНЫ. Замер по проду
 * 19.08.2026 на четырёх случаях:
 *
 *   GET  /api/multichat/shared/launch-page-probe → 404 {"error":"not_found_or_revoked"}
 *        маршрут ЖИВ, просто нет такого токена — а правило объявляло его мёртвым;
 *   GET  /api/multichat/no-such-route-xyz        → 402 {"error":"upgrade_required"}
 *        маршрута НЕТ, но платная стена модуля отвечает раньше маршрутизации —
 *        а правило объявляло его живым;
 *   GET  /api/no-such-module-xyz/abc             → 404, HTML «Cannot GET …»
 *        действительно мёртво;
 *   POST /api/multichat/receipt/verify с {}      → 400 {"error":"not_a_receipt"}
 *        жив (именно так его и пробует посадочная — методом POST, не GET).
 *
 * Один и тот же код означает и «живо», и «мертво» — и 404, и 402. Различает только
 * ТЕЛО. Поэтому теперь решает оно:
 *
 *   мертво        — HTML от Express («Cannot GET»): путь никуда не ведёт;
 *   не доказано   — `upgrade_required`: это ответ платной стены МОДУЛЯ, он приходит
 *                   до маршрутизации и о существовании пути не говорит ничего;
 *   живо          — любой другой ответ нашего обработчика, включая 400/402/404 с
 *                   доменной ошибкой.
 *
 * Почему «не доказано» приравнено к «не живо»: страница пишет о возможностях
 * человеку, и лучше промолчать, чем объявить живым то, чего мы не проверили.
 * Хотите проверить возможность за платной стеной — пробуйте путь, который стену не
 * задевает (как POST на receipt/verify), а не GET по тому же адресу.
 *
 * Сетевая ошибка — тоже «не подтвердилось», а не «мертво»: страница честно скажет
 * «проверяется», и это лучше, чем объявить контур сломанным из-за таймаута сборки.
 *
 * Ни одна проба ничего не создаёт: пробы идут при сборке и посылают заведомо
 * неверные данные, чтобы получить осмысленный отказ (приём из
 * scripts/contact-channels-smoke.mjs).
 */
export interface ProbeOptions {
  /**
   * Считать 404 признаком ЖИЗНИ, а не смерти.
   *
   * Нужно для ручек, которые ищут объект по идентификатору: у них 404 —
   * законный и правильный ответ на «такого нет». Замер 19.08.2026:
   * `GET /api/multichat/shared/launch-page-probe` отвечает
   * `{"error":"not_found_or_revoked"}` с кодом 404, потому что токена с таким
   * именем не существует — и не должно существовать, проба его не создаёт.
   *
   * По умолчанию проба считала это смертью, и метка «Совет можно открыть
   * ссылкой» на посадочной Multichat не могла стать «работает» НИКОГДА,
   * сколько бы контур ни работал.
   *
   * Отличить «нет объекта» от «нет роутера» по коду здесь нельзя, и вот
   * почему: несуществующий путь внутри multichat отвечает не 404, а **402**
   * `upgrade_required` — платная стена срабатывает раньше маршрутизации.
   * Значит для таких проб единственный честный критерий — «сервер вообще
   * ответил», и он ниже.
   */
  aliveOn404?: boolean;
}

export async function probeLive(
  path: string,
  init?: RequestInit,
  opts?: ProbeOptions,
): Promise<boolean> {
  try {
    const r = await fetch(`${getApiBase()}${path}`, { ...init, next: { revalidate: 1800 } });
    // Явная просьба вызывающего: «достаточно того, что сервер ответил».
    // Нужна там, где проба сама создаёт условие для 404 (ищем заведомо
    // несуществующий объект), а внутри multichat платная стена отвечает 402
    // РАНЬШЕ маршрутизации — значит по статусу «нет объекта» и «нет роутера»
    // не различить. Замер и разбор — в комментарии к ProbeOptions.
    //
    // Стоит ДО чтения тела и намеренно: иначе строгие правила ниже отменили бы
    // просьбу, и метка не смогла бы стать «работает» никогда — ровно тот дефект,
    // ради которого опция и появилась.
    if (opts?.aliveOn404) return true;
    // Тело читаем всегда: статус здесь неинформативен (замер выше). У ответов
    // проб оно короткое — это либо доменная ошибка, либо страница Express.
    const body = typeof r.text === "function" ? await r.text() : "";
    if (/Cannot (GET|POST|PUT|DELETE|PATCH)/i.test(body)) return false;
    if (/"error"\s*:\s*"upgrade_required"/.test(body)) return false;
    if (!body) return r.status !== 404; // тело недоступно — старое правило как запас
    return true;
  } catch {
    return false;
  }
}

/**
 * Читает ответ пробы как JSON — чтобы обещание опиралось на СОДЕРЖИМОЕ, а не на то,
 * что маршрут ответил.
 *
 * Зачем помимо `probeLive`. Живость доказывает, что путь ведёт к обработчику. Но
 * посадочная обещает человеку возможность, а не маршрут, и здесь наличие ответа не
 * равно наличию содержимого:
 *
 *   /api/devhub/templates            — пустой список тоже 200, а начал бы не было;
 *   /api/devhub/media/video/models   — отдаёт СТАТИЧЕСКИЙ каталог всегда и сам
 *                                      сообщает `configured: !!REPLICATE_API_TOKEN`.
 *                                      То есть 200 не говорит о генерации ничего, а
 *                                      настоящий ответ лежит в теле.
 *
 * Замер 19.08.2026: на проде `configured: true`, моделей 6 — обещание верно
 * сегодня. Но проба его не читала, поэтому уберите токен, и страница продолжила бы
 * обещать; а она прямым текстом говорит, что отметка ставится по ответу боевого
 * сервера. Это тот же класс, что «наличие ≠ содержимое».
 *
 * Возвращает `null` при любом сомнении — мертво, стена, не-JSON, сетевая ошибка.
 * Вызывающий обязан трактовать `null` как «не подтвердилось», а не как пустоту.
 */
export async function probeJson<T>(path: string, init?: RequestInit): Promise<T | null> {
  try {
    const r = await fetch(`${getApiBase()}${path}`, { ...init, next: { revalidate: 1800 } });
    const body = typeof r.text === "function" ? await r.text() : "";
    if (!body) return null;
    if (/Cannot (GET|POST|PUT|DELETE|PATCH)/i.test(body)) return null;
    if (/"error"\s*:\s*"upgrade_required"/.test(body)) return null;
    return JSON.parse(body) as T;
  } catch {
    return null;
  }
}

/**
 * Сколько дней осталось до даты запуска.
 *
 * Считается по UTC-полуночи с обеих сторон: иначе страница, собранная вечером,
 * и страница, собранная утром того же дня, показали бы разное число дней.
 * Даты запуска модулей — в aevion-globus-backend/src/lib/launchAnnounce.ts, и у
 * четырёх из пяти они НЕ подтверждены (стоят null). Подтверждена только дата
 * шахмат. Не подставляйте дату, которой основатель не называл.
 */
export function daysUntil(year: number, monthIndex: number, day: number): number {
  const launch = Date.UTC(year, monthIndex, day);
  const now = new Date();
  const today = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());
  return Math.round((launch - today) / 86_400_000);
}
