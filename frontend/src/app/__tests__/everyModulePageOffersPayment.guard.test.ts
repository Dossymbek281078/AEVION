import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * У страницы модуля есть путь к оплате.
 *
 * Замер 20.09.2026 по всем 44 модулям прайса: 35 несли ModulePricingChip на
 * своей странице, DevHub / бюро / конституция — собственную кассу, а два места
 * не показывали покупателю НИЧЕГО:
 *
 *   • src/app/[id]/page.tsx — общая страница-подхват. На неё падает любой
 *     модуль без своей папки (в тот день qpaynet-embedded и qbuild, завтра —
 *     любой новый). Оплаты на ней не было вовсе: греп по checkout|Купить|
 *     pricing давал ноль при контроле 15 совпадений на заведомо существующем.
 *   • src/app/qreal/_client.tsx — своя страница и ни чипа, ни кассы.
 *
 * Дефект тихий: страница отвечает 200, сторож страниц зелёный, человек видит
 * описание модуля и уходит, потому что платить нечем. Ни один существующий
 * сторож этого не ловил — checkoutLinksAreReal проверяет, что УЖЕ имеющиеся
 * ссылки настоящие, но не то, что ссылка вообще есть.
 *
 * Поэтому проверка — по НАЛИЧИЮ предложения оплаты, а не по его виду.
 */

const FRONTEND_SRC = path.resolve(__dirname, "..", "..");

/** Страницы, которые обязаны предлагать оплату, и почему именно они. */
const MUST_OFFER: Array<{ file: string; why: string }> = [
  {
    file: path.join("app", "[id]", "page.tsx"),
    why: "общая страница-подхват: на неё падает любой модуль без своей папки",
  },
  {
    file: path.join("app", "qreal", "_client.tsx"),
    why: "QReal: своя страница, собственной кассы у неё нет",
  },
];

/**
 * Признаки предложения оплаты. Достаточно одного — у модулей это либо общий
 * чип, либо своя касса, и требовать конкретный вид значило бы запретить
 * законную починку (класс feedback_guard_on_source_form_blocks_the_fix).
 *
 * ⚠️ Компоненты ищутся как ОТКРЫВАЮЩИЙ ТЕГ, а не по имени. Первая редакция
 * искала подстроку "ModulePricingChip" — и забытый импорт без единого
 * использования проходил бы проверку. Поймано мутацией в день написания:
 * заменить саму разметку она отказалась («встречается 3 раза»), и стало
 * видно, что два из трёх вхождений — импорт и комментарий, то есть текст О
 * кнопке, а не кнопка.
 */
const PAYMENT_MARKERS = ["<ModulePricingChip", "<PaddleUpgradeButton", "PRICING_TERMS", "PRICING_APP"];

function read(rel: string): string {
  return fs.readFileSync(path.join(FRONTEND_SRC, rel), "utf8");
}

describe("на странице модуля есть чем заплатить", () => {
  for (const { file, why } of MUST_OFFER) {
    it(`${file} предлагает оплату (${why})`, () => {
      const src = read(file);
      const found = PAYMENT_MARKERS.filter((m) => src.includes(m));
      expect(
        found.length,
        `В ${file} нет ни одного признака оплаты (${PAYMENT_MARKERS.join(", ")}). ` +
          "Человек дочитает страницу модуля и уйдёт: платить нечем.",
      ).toBeGreaterThan(0);
    });
  }

  /**
   * Контроль прибора: сторож обязан УМЕТЬ краснеть. Файл без единого признака
   * оплаты должен проверку не пройти — иначе список выше можно очистить, и
   * сторож останется зелёным, ничего не проверяя.
   */
  it("контроль: файл без признаков оплаты проверку НЕ проходит", () => {
    const withoutPayment = "export default function Page() { return null; }";
    const found = PAYMENT_MARKERS.filter((m) => withoutPayment.includes(m));
    expect(found.length).toBe(0);
  });

  /**
   * Второй контроль, в обратную сторону: список признаков не пуст. Пустой
   * список сделал бы первую проверку невыполнимой всегда, а не всегда верной —
   * но проверить это дешевле, чем потом разбирать, почему сторож врёт.
   */
  it("контроль: список признаков оплаты не пуст", () => {
    expect(PAYMENT_MARKERS.length).toBeGreaterThan(0);
  });
});
