import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { ТАРИФЫ_ПО_ЕДИНИЦАМ, ценаПоЕдиницам } from "../src/lib/unitPricing";

/**
 * Тариф действует только для ТОГО поставщика, по чьему прайсу он посчитан.
 *
 * Замер на проде 01.10.2026. Квота DeepL исчерпалась, и перевод ушёл на запасной
 * канал — ответ честно сказал `provider: "anthropic"`,
 * `fallbackReason: "deepl_quota_exhausted"`. А в журнал расхода легла цена по
 * прайсу DeepL: $0.00105 за 42 знака. Арифметика сошлась до копейки — и была
 * бессмысленна, потому что считали по одному поставщику, а платили другому.
 *
 * Почему это хуже отсутствия цены. По журналу расхода принимают решения о деньгах:
 * сколько стоит один заказ, выгоден ли тариф, пора ли менять поставщика. Пустая
 * клетка заставляет пойти и выяснить. Клетка с чужой ценой — нет.
 *
 * Поэтому при несовпадении цена не выдумывается, а честно не считается, и в
 * журнале остаётся имя того, кто работу выполнил: «цена неизвестна, работал
 * anthropic» — это решаемо, в отличие от тишины и в отличие от лжи.
 */
const МАРШРУТ = readFileSync(join(__dirname, "..", "src", "routes", "devhub.ts"), "utf8");

describe("тариф принадлежит своему поставщику", () => {
  it("прибор исправен: тарифы есть и у каждого назван поставщик", () => {
    const ключи = Object.keys(ТАРИФЫ_ПО_ЕДИНИЦАМ);
    expect(ключи.length, "таблица тарифов пуста — проверки ниже ничего не значат").toBeGreaterThan(3);
    for (const [к, т] of Object.entries(ТАРИФЫ_ПО_ЕДИНИЦАМ)) {
      expect(т.поставщик, `у тарифа ${к} не назван поставщик`).toBeTruthy();
      expect(т.источник, `у тарифа ${к} нет источника`).toBeTruthy();
    }
  });

  it("свой поставщик — цена считается", () => {
    // 1000 знаков по $0.025 за 1000 = ровно $0.025.
    expect(ценаПоЕдиницам("translate", 1000, "deepl")).toBe(0.025);
    expect(ценаПоЕдиницам("stt", 60, "elevenlabs")).toBeGreaterThan(0);
  });

  it("ЧУЖОЙ поставщик — цены нет, а не чужая цена", () => {
    // Ровно случай 01.10: работу сделал anthropic, тариф посчитан по DeepL.
    expect(ценаПоЕдиницам("translate", 1000, "anthropic")).toBeNull();
    expect(ценаПоЕдиницам("translate", 1000, "openai")).toBeNull();
    expect(ценаПоЕдиницам("stt", 60, "deepl")).toBeNull();
  });

  it("поставщик не назван — считаем по тарифу, как раньше", () => {
    // Совместимость: вызывающий, который поставщика не знает, не становится от
    // этого неправ. Иначе правка обнулила бы учёт там, где он работал.
    expect(ценаПоЕдиницам("translate", 1000)).toBe(0.025);
    expect(ценаПоЕдиницам("translate", 1000, null)).toBe(0.025);
    expect(ценаПоЕдиницам("translate", 1000, "")).toBe(0.025);
  });

  it("перевод ПЕРЕДАЁТ фактического поставщика в учёт", () => {
    // Без этого вся таблица выше остаётся теорией: тариф умеет отличать
    // поставщика, а место вызова ему об этом не говорит.
    expect(
      МАРШРУТ,
      "ручка перевода не передаёт out.provider в учёт — тариф снова станет слепым",
    ).toContain('учтиПоОбъёму("translate", String(text ?? "").length, trUserId, out.provider)');
  });

  it("имя поставщика попадает в журнал, когда цены нет", () => {
    // «Цена неизвестна» должно быть РЕШАЕМЫМ: видно, чей прайс идти искать.
    const тело = МАРШРУТ.slice(МАРШРУТ.indexOf("function учтиБезЦены"));
    expect(тело.slice(0, 600), "поставщик не попадает в имя модуля").toContain("БЕЗ-ЦЕНЫ${кто");
  });
});
