import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Приглашение «сыграй со мной» обязано нести метку канала и вести туда, где
 * партия начинается без регистрации.
 *
 * Зачем сторож. Петля роста ценна ровно настолько, насколько она измерима:
 * 20.09 метка ?c=post уже терялась молча, и 37 постов мерили воронку в
 * пустоту. Если из ссылки однажды уберут ?c=chess-share, канал перестанет
 * считаться, и мы узнаем об этом не сразу, а по отсутствию роста.
 *
 * Проверяется ИСХОДНИК страницы, а не отрисовка: сама кнопка живёт в окне
 * после партии, до которого тест не доигрывает.
 */
const код = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");

describe("приглашение на партию", () => {
  it("контроль: блок приглашения вообще есть в странице", () => {
    expect(код).toContain("сыграй со мной");
  });

  it("ссылка несёт метку канала chess-share", () => {
    expect(код).toContain("/cyberchess?c=chess-share");
  });

  it("ведёт на вход в игру, а не на страницу оплаты", () => {
    // Контроль в другую сторону: приглашение, ведущее на /pricing, убило бы
    // сам смысл канала — человека зовут играть, а не платить.
    const i = код.indexOf("chess-share");
    const рядом = код.slice(Math.max(0, i - 200), i + 200);
    expect(рядом).not.toContain("/pricing");
  });

  it("отказ буфера обмена не остаётся молчаливым", () => {
    // Нажал и ничего не произошло — худший исход: человек решит, что сломано.
    expect(код).toContain("Скопируйте ссылку:");
  });
});
