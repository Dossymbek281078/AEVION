import { redirect } from "next/navigation";

import type { Metadata } from "next";

// Метаданные обязательны у каждой публичной страницы (сторож pageMetadata), и
// у перенаправления они решают отдельную задачу: закрыть его от поисковика.
// Короткий адрес — вход для человека из каталога, а не страница: в выдаче ему
// делать нечего, и без noindex он соревновался бы за показы с той страницей,
// на которую ведёт.
export const metadata: Metadata = {
  title: { absolute: "AEVION" },
  robots: { index: false, follow: true },
};

// /sh — короткий адрес для каталога SaaSHub (saashub.com/submit).
//
// ЗАЧЕМ. Канал отрабатывает ОДИН раз: карточку публикуют, и проверять разметку
// после публикации поздно. Без метки `channelFrom` вернул бы null, переход лёг
// бы в «прямые заходы», и на вопрос «сработал ли SaaSHub» ответа бы не нашлось.
// Ровно это случилось 29.09.2026 с запуском на Product Hunt: все переходы
// оттуда стали неизмеримы.
//
// Метка заведена с двух сторон: `?c=sh` в нашей ссылке и `?ref=` в
// REF_ALIASES — на случай, если каталог допишет свой параметр сам, как это
// делает Product Hunt.
//
// Особенность этой площадки: каталог SaaS.
export const dynamic = "force-static";

export default function Page() {
  /*
   * Ведём на СТРАНИЦУ ПРОДУКТА, а не на общий вход, — так же, как /ph и /un: в
   * каталоге стоит карточка DevHub, и человек должен попасть на то, что он там
   * увидел. Замер 07.10.2026 подтверждает, что страница своё обещание держит:
   * у `/en/devhub` первый заголовок «Describe it. Get a deployed project.», а
   * бесплатная кнопка «Open DevHub» видна в первом экране и на телефоне
   * (390×844: заголовок 141px, кнопка 591px).
   *
   * ⚠️ Что при этом известно и чего ждать: за 14 дней Product Hunt дал 22 живых
   * человека, и до цен из них дошли НОЛЬ. Сама страница исправна, а прочитать
   * этот ноль мы пока не можем: для продукта с бесплатной пробой первый шаг —
   * «начал генерацию» (событие feature_use), а публичная воронка его не отдаёт.
   * Если каталог даст ту же картину, вопрос будет не к перенаправлению.
   */
  redirect("/en/devhub?c=sh");
}
