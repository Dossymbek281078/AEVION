/**
 * Кому разрешено ходить в этот API из браузера.
 *
 * Повод (21.09.2026). Форма заявок на сайте агентства молча падала в запасной
 * путь — «Пока не отправлено, пришлите письмом». Ручка была жива и отвечала на
 * curl, тесты исходника были зелёные, на странице не было ни одной ошибки:
 * запрос отбивал браузер, потому что домен витрины забыли дописать в
 * CORS_ALLOWED_ORIGINS. Видно это только браузером и только по ОТСУТСТВИЮ
 * заголовка access-control-allow-origin в ответе.
 *
 * Поэтому наши собственные витрины живут в КОДЕ рядом с этим объяснением, а не
 * только в переменной окружения, которую легко забыть при заведении нового сайта.
 */

/** Наши витрины, которые ходят в API из браузера. */
export const СВОИ_ВИТРИНЫ = ["https://aevion-agency-site.vercel.app"];

/**
 * Пустая переменная = «разрешено всё» (так было и раньше, для локальной
 * разработки). Дописывать свои домены в пустой список НЕЛЬЗЯ: открытый режим
 * молча стал бы закрытым, и отвалились бы все остальные витрины разом.
 */
export function разрешённыеИсточники(изОкружения: string | undefined): string[] {
  const заданы = String(изОкружения || "")
    .split(",")
    .map((o) => o.trim())
    .filter(Boolean);
  if (заданы.length === 0) return [];
  return Array.from(new Set(заданы.concat(СВОИ_ВИТРИНЫ)));
}
