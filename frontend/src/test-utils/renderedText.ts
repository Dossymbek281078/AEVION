/**
 * Сбор того, что ВИДИТ человек на отрисованной странице.
 *
 * ЗАЧЕМ ОБЩИЙ ФАЙЛ. За три дня один языковой сторож четырежды получал новую
 * форму записи подписи — текст между тегами, атрибут, свойство объекта,
 * аргумент функции, — и каждый раз оставался зелёным при живом английском на
 * экране. Перечисление форм не сходится: их столько, сколькими способами
 * фреймворк умеет доставить строку в DOM.
 *
 * Отрисовка снимает вопрос целиком: неважно, КАК текст попал на экран.
 * Держать эту логику в каждом модуле отдельно значит размножить не только
 * сбор, но и три контроля, без которых такая проверка пуста (см. ниже).
 *
 * ГРАНИЦА, которую обязан знать каждый, кто этим пользуется: отрисовка
 * показывает НАЧАЛЬНОЕ состояние страницы. Сообщения об ошибках, отказы
 * платной стены и экраны результата сюда не попадают — для них нужны свои
 * проверки. Зелёный цвет здесь означает «то, что человек видит СРАЗУ».
 */

/** Подписи, которые доходят до человека помимо собственного текста узла. */
const ATRIBUTY = ["aria-label", "title", "placeholder", "alt"] as const;

export interface VidimyjTekst {
  /** Текстовые узлы: то, что читается глазами. */
  tekst: string[];
  /** Значения подписывающих атрибутов: то, что произносит читалка. */
  atributy: string[];
  /** Всё вместе — для проверок, которым источник неважен. */
  vsyo: string[];
}

/**
 * Собирает видимый текст из отрисованного узла.
 *
 * Собираются ОБА источника раздельно намеренно: мутация показала, что при
 * общем счёте отключение сбора атрибутов проходит молча — текстовых узлов
 * хватает на порог, а подписи для читалки выпадают из проверки целиком.
 */
export function sobratVidimyj(koren: Element): VidimyjTekst {
  const tekst: string[] = [];
  const atributy: string[] = [];

  // Содержимое <style> и <script> — НЕ видимый текст: это правила оформления
  // и код. Первая версия собирала их наравне с подписями, и на первой же
  // странице выдала «@keyframes pulse-dot {…}» как английскую надпись.
  // Шум такого рода опаснее пропуска: он приучает не читать список.
  const NEVIDIMYE = new Set(["STYLE", "SCRIPT", "NOSCRIPT", "TEMPLATE"]);

  koren.querySelectorAll("*").forEach((el) => {
    if (NEVIDIMYE.has(el.tagName)) return;
    for (const a of ATRIBUTY) {
      const v = el.getAttribute(a);
      if (v && v.trim()) atributy.push(v.trim());
    }
    el.childNodes.forEach((n) => {
      if (n.nodeType === 3) {
        const t = (n.textContent || "").trim();
        if (t) tekst.push(t);
      }
    });
  });

  return { tekst, atributy, vsyo: [...tekst, ...atributy] };
}

/**
 * Латиница по природе и термины, которые в русской речи НЕ переводят.
 * Список общий и короткий намеренно: длинный превращает сторожа в решето,
 * а «перевод» термина делает интерфейс хуже, а не лучше.
 */
export const TERMINY_OBSHIE = [
  "AEVION", "AI", "PDF", "USD", "EUR", "KZT", "API", "URL", "ID", "OK",
  "GitHub", "Cloudflare", "Vercel", "Railway", "Gumroad", "Postgres",
  "Monaco", "VS", "Code", "SPA", "ZIP", "CDN", "SSL", "DNS", "SMS",
];

/**
 * Похоже на ЗНАЧЕНИЕ, а не на подпись: адрес, имя файла, домен, число с
 * единицей. Такие строки приходят из данных и латиницей по природе.
 *
 * Различаем по ФОРМЕ, а не по числу слов. Правило «без пробела — не подпись»
 * выглядит проще и было бы ошибкой: 03.09.2026 оно ослепило соседнего сторожа
 * ровно на однословных подписях — Building, Pending, Failed, Draft.
 */
export function pohozheNaZnachenie(s: string): boolean {
  if (s.includes("://")) return true;                    // адрес
  if (/^[\w.-]+\.[a-z]{2,5}$/i.test(s)) return true;      // файл или домен
  if (/^[0-9][0-9.,]*\s?[a-z%]{1,4}$/i.test(s)) return true; // 0ms, 12.5kb, 40%
  if (/^[0-9\s.,:+-]+$/.test(s)) return true;             // только числа и знаки
  return false;
}

/** Есть латинские буквы и нет кириллицы. */
export function tolkoLatinica(s: string): boolean {
  return /[A-Za-z]/.test(s) && !/[А-ЯЁа-яё]/.test(s);
}

/** Убирает термины и смотрит, осталось ли латинское СЛОВО. */
export function ostalosLatinskoeSlovo(s: string, terminy: string[]): boolean {
  let out = s;
  for (const t of terminy) out = out.split(t).join(" ");
  return /[A-Za-z]{2,}/.test(out);
}

/**
 * Английские строки на русском экране.
 *
 * Вызывающий обязан ОТДЕЛЬНО проверить охват (сколько собрано текста и
 * атрибутов) и само правило: без этого сборщик, вернувший пустоту, и
 * правило, всегда отвечающее «нет», оставляют сторожа зелёным. Обе дыры
 * вскрыты мутацией 03.09.2026 на первом же таком стороже.
 */
export function angliyskieStroki(v: VidimyjTekst, terminy: string[] = TERMINY_OBSHIE): string[] {
  const bad = v.vsyo.filter(
    (s) => tolkoLatinica(s) && !pohozheNaZnachenie(s) && ostalosLatinskoeSlovo(s, terminy),
  );
  return [...new Set(bad)];
}
