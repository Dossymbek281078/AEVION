import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/*
 * 🔴 139б (14.10.2026). Замер на проде 9c0c0b6a6, игра, 768×1024: колонка 48 соперник | 724 доска | 51 буквы |
 * 102 карточка «С чего начать» | 48 «Вы» → низ строки «Вы» 1092 при окне 1024 — часы игрока за кадром; на 390×844
 * карточка 146 px, «Вы» 782. Во время партии карточка онбординга под доской не рисуется (новая партия — в ряду
 * кнопок); после партии и на экране настройки — как была.
 */
const src = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");

describe("карточка «С чего начать» не отодвигает строку «Вы» во время партии (139б)", () => {
  it("🔴 под доской на телефоне/планшете карточка рисуется только вне идущей партии", () => {
    expect(src).toContain("{isMobileLayout&&!(on&&!over)&&полоскаСтарта(bw)}");
    expect(src).not.toContain("{isMobileLayout&&полоскаСтарта(bw)}");
  });
  it("на экране настройки и на десктопе карточка на месте", () => {
    expect(src).toContain('{полоскаСтарта("100%")}');
    expect(src).toContain('{!isMobileLayout&&полоскаСтарта("100%")}');
  });
});
