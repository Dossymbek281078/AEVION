import { describe, test, expect } from "vitest";
import { readFileSync, existsSync, readdirSync } from "node:fs";
import { join, basename, dirname } from "node:path";

/**
 * Ни одна посадочная не обещает дату, которая уже прошла.
 *
 * 30.08.2026 страница запуска шахмат писала «Открываем 30 августа» и тут же
 * «Уже открыто»: отсчёт дошёл до нуля, а запуска не было — его перенесли на
 * сентябрь, и дату забыли поменять. То же висело на /go, самой видной странице
 * платформы. Заметил падающий тест про письмо, а не человек и не сторож.
 *
 * Эта проверка нарочно ЗАВИСИТ ОТ СЕГОДНЯШНЕГО ДНЯ. Обычно это недостаток, но
 * здесь в этом весь смысл: обещание протухает по календарю, и краснеть сторож
 * должен именно в день, когда обещание стало ложным. Чинится он не правкой
 * теста, а решением — перенести дату или убрать отсчёт.
 *
 * Эталонных дат сторож не знает: он не устареет от следующего переноса.
 *
 * ГРАНИЦА, названная честно. Сегодняшний случай он поймал бы только ЗАВТРА:
 * дата равна сегодняшнему дню, а в день запуска «Открываем сегодня» —
 * законная надпись. Проверено мутацией: дата = сегодня проходит, дата на
 * десять дней назад краснеет. То есть сторож ловит ЗАБЫТОЕ обещание, а не
 * несостоявшийся запуск в день его объявления. Второе ловится только тем,
 * что человек посмотрел на страницу.
 */
const APP = join(process.cwd(), "src/app");

function launchPages(): string[] {
  const out: string[] = [];
  for (const d of readdirSync(APP, { withFileTypes: true })) {
    if (!d.isDirectory()) continue;
    const p = join(APP, d.name, "launch", "page.tsx");
    if (existsSync(p)) out.push(p);
  }
  return out;
}

/** Дата из daysUntilLaunch(Date.UTC(год, месяц, день)) — позиционно, без регулярки. */
/**
 * 🔴 Две формы записи даты, а не одна — иначе сторож слепнет от ПОЧИНКИ.
 *
 * Прежняя версия знала только литерал `daysUntilLaunch(Date.UTC(…))`. Но
 * правильное направление правки обратное: дату надо брать из общей константы,
 * а не держать литералом. Как только страница это делает — `daysUntilLaunch(
 * DEVHUB_LAUNCH_AT)` или `daysUntilLaunch(PLATFORM_LAUNCH_UTC)` — разбор
 * возвращал null, тест выходил через `if (!d) return;` и страница тихо
 * уходила из-под проверки.
 *
 * Замер 30.09.2026: под охватом оставалась ОДНА страница из четырёх (bureau);
 * devhub и multichat вынесли дату в свои константы ещё 21.09 и с тех пор не
 * проверялись вовсе. Сторож при этом был зелёный.
 *
 * Поэтому имя разрешаем: сперва в самом файле (`const X = Date.UTC(…)`),
 * потом в общем модуле дат. Ниже стоит контроль, что разрешение вообще
 * работает, — без него «дат не найдено» снова стало бы тихим зелёным.
 */
function разобратьUtc(текст: string): { ms: number; where: string } | null {
  const nums = текст.split(",").map((s) => Number(s.trim()));
  if (nums.length < 3 || nums.some((n) => !Number.isFinite(n))) return null;
  return { ms: Date.UTC(nums[0], nums[1], nums[2]), where: текст };
}

function promisedDate(src: string): { ms: number; where: string } | null {
  const literal = "daysUntilLaunch(Date.UTC(";
  const i = src.indexOf(literal);
  if (i >= 0) {
    return разобратьUtc(src.slice(i + literal.length, i + literal.length + 24).split(")")[0]);
  }

  const поИмени = src.match(/daysUntilLaunch\(\s*([A-Z_][A-Z0-9_]*)\s*\)/);
  if (!поИмени) return null;
  const имя = поИмени[1];

  // Ищем `ИМЯ = Date.UTC(…)` по тексту, а не регуляркой из шаблонной строки:
  // в шаблоне `\s` — это просто «s», и первая версия этой проверки искала
  // «consts+ИМЯ». Пробелы приводим к одному, чтобы не зависеть от вёрстки.
  const найтиУтебя = (текст: string): { ms: number; where: string } | null => {
    const плоско = текст.replace(/\s+/g, " ");
    const k = плоско.indexOf(имя + " = Date.UTC(");
    if (k < 0) return null;
    const от = k + (имя + " = Date.UTC(").length;
    return разобратьUtc(плоско.slice(от, плоско.indexOf(")", от)));
  };

  const свой = найтиУтебя(src);
  if (свой) return свой;

  for (const путь of [join(APP, "launchDate.ts"), join(APP, "cyberchess", "launchDate.ts")]) {
    if (!existsSync(путь)) continue;
    const найдено = найтиУтебя(readFileSync(путь, "utf8"));
    if (найдено) return найдено;
  }
  return null;
}

/**
 * Умеет ли страница переключаться по календарю: есть ли ветка по остатку дней.
 * Ищем ПО СМЫСЛУ, а не по одному написанию: `left > 0`, `left <= 0`,
 * `daysUntil > 0` — всё это одна и та же развилка.
 */
function переключаетсяПоДате(src: string): boolean {
  const s = src.replace(/\s+/g, " ");
  return /(left|days?Until[A-Za-z]*|остал[а-я]*)\s*(>|<=|===|!==)\s*0/i.test(s);
}

describe("посадочные не обещают прошедших дат", () => {
  const pages = launchPages();

  test("посадочные вообще найдены — иначе проверка пуста", () => {
    expect(pages.length, "не найдено ни одной страницы */launch/page.tsx").toBeGreaterThan(0);
  });

  for (const p of pages) {
    // Имя берём инструментом пути, а не делением строки по косой: в Windows
    // разделитель другой, и прежняя строка давала `undefined` — сообщение о
    // находке не называло страницу, ради которой оно написано (замер 21.09.2026,
    // три падения подряд с текстом «страница undefined обещает…»).
    const name = basename(dirname(dirname(p)));
    test(`${name}: обещанная дата не в прошлом`, () => {
      const src = readFileSync(p, "utf8");
      const d = promisedDate(src);
      if (!d) return; // страница без отсчёта ничего не обещает — проверять нечего
      const today = Date.UTC(
        new Date().getUTCFullYear(), new Date().getUTCMonth(), new Date().getUTCDate(),
      );
      if (d.ms >= today) return;

      // Прошедшая дата — ещё НЕ ложное обещание. Замер 21.09.2026 по живым
      // страницам: devhub и multichat после даты печатают «Уже открыт», бюро —
      // «Обещали 20 сентября, напишем, как только откроем». Обещания там нет,
      // есть честная развилка по календарю. Сторож же смотрел на КОНСТАНТУ и со
      // дня запуска краснел бы навсегда, а вечно красного перестают читать.
      //
      // Поэтому прошедшая дата допускается ровно тогда, когда страница умеет
      // переключаться: в исходнике есть ветка по остатку дней.
      const переключается = переключаетсяПоДате(src);
      expect(
        переключается,
        `страница ${name} обещает запуск на Date.UTC(${d.where}), он уже прошёл, ` +
        "и переключения по дате в исходнике нет. Либо перенесите дату, либо " +
        "добавьте ветку «уже открыто» — сейчас страница обещает вчерашнее.",
      ).toBe(true);
    });
  }

  test("КОНТРОЛЬ охвата: дата разобрана НЕ У ОДНОЙ страницы", () => {
    /*
     * Без этого «нарушений нет» верно и при сломанном разборе. Именно так
     * сторож и жил после 21.09: devhub и multichat вынесли дату в свои
     * константы, разбор их перестал видеть, тест остался зелёным.
     *
     * Порог не «больше нуля», а «больше одной»: одна разобранная страница —
     * ровно то состояние, в котором он был слеп к трём остальным.
     */
    const сДатой = pages.filter((p) => promisedDate(readFileSync(p, "utf8")));
    expect(
      сДатой.length,
      "дату удалось разобрать меньше чем у двух страниц запуска — разбор отстал от кода: " +
        "дату стали писать иначе, и проверка тихо перестала кого-либо проверять",
    ).toBeGreaterThan(1);
  });

  test("КОНТРОЛЬ прибора: прошедшая дата БЕЗ развилки остаётся находкой", () => {
    const безРазвилки = "const left = daysUntilLaunch(Date.UTC(2020, 0, 1)); return <p>Открываем скоро</p>;";
    const сРазвилкой = "const left = daysUntilLaunch(Date.UTC(2020, 0, 1)); return left > 0 ? <p>Через {left}</p> : <p>Уже открыто</p>;";
    expect(переключаетсяПоДате(безРазвилки), "страница без развилки признана переключающейся").toBe(false);
    expect(переключаетсяПоДате(сРазвилкой), "страница с развилкой не признана").toBe(true);
  });
});
