import type { Metadata } from "next";

/* Запрет индексации — экран после входа: показывается один раз и вне своего пути бессмыслен.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ robots.txt. Эти адреса уже перечислены в общем списке
 * запретов (`app/robots.ts`), и карта сайта фильтрует по нему же. Но
 * robots.txt только просит НЕ СКАНИРОВАТЬ: страница, на которую пришла
 * внешняя ссылка, всё равно может попасть в выдачу — без описания, одним
 * адресом. `index: false` в метаданных запрещает именно ПОКАЗ.
 *
 * Два механизма отвечают на разные вопросы, поэтому нужны оба:
 *   robots.txt      — «сюда не ходи»
 *   index: false    — «это не показывай»
 *
 * Заведено 30.08.2026 вместе с разбором страниц, наследующих чужой canonical:
 * этим наследование безвредно (они и не должны быть в поиске), но пусть
 * запрет будет назван прямо, а не выводиться из общего списка. */
export const metadata: Metadata = {
  robots: { index: false, follow: true },
};

