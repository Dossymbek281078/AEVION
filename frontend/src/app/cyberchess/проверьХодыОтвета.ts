/**
 * Тренер не имеет права назвать ход, которого в позиции нет.
 *
 * ПОВОД — прямой вопрос основателя 28.09.2026: «ChatGPT проиграл Карлсену и
 * придумывал несуществующие ходы — адекватен ли наш ИИ-тренер». Нашло окно
 * user-c8, я подтвердил замером: в трёх местах, зовущих тренера, проверок
 * ответа НОЛЬ (AiCoach.tsx, WhatIfButton.tsx, окно после партии).
 *
 * Устройство у нас правильное: до запроса считает Stockfish (depth 22,
 * MultiPV 3), модель получает готовый отчёт и работает переводчиком при
 * движке, а системный промпт прямо запрещает ходы не из отчёта. Но это
 * ПРОСЬБА, а не механизм: промпт держится на добросовестности модели, и с
 * 28.09 тренер при закрытом счёте Anthropic отвечает Gemini, у которого свои
 * повадки. Класс известен: «комментарий обещает защиту, которой в коде нет».
 *
 * ⚠️ ГЛАВНОЕ ПРИ РАЗБОРЕ ТЕКСТА: наш тренер пишет ходы ПО-РУССКИ. Системный
 * промпт сам просит «белые играют 14.Кf3» — «К» здесь кириллическая. Проверка
 * только по латинской записи дала бы ровно ноль находок и успокоила бы зря.
 * Поэтому принимаются обе записи: Кр→K, Ф→Q, Л→R, С→B, К→N (Кр проверяется
 * ПЕРЕД К, иначе король станет конём).
 *
 * ⚠️ И ГЛАВНОЕ ПРО НАПРАВЛЕНИЕ ОШИБКИ. Ложная тревога здесь дороже пропуска:
 * если принять за ход обычное упоминание поля («слон смотрит на e5»), мы
 * спрячем ВЕРНЫЙ разбор. Поэтому ходом считается только то, что заявлено как
 * ход: с буквой фигуры, со взятием, с шахом, с превращением, рокировка или с
 * номером хода впереди («14.e4», «14...e4»). Голое «e5» в тексте — это поле,
 * а не утверждение о ходе, и мы его не судим. Это осознанный пропуск, а не
 * недосмотр: выдуманный ПЕШЕЧНЫЙ ход без номера проверка не поймает.
 */

import { Chess } from "chess.js";

/** Русская буква фигуры → латинская. «Кр» обязана стоять раньше «К». */
const ФИГУРЫ: Array<[string, string]> = [
  ["Кр", "K"],
  ["Ф", "Q"],
  ["Л", "R"],
  ["С", "B"],
  ["К", "N"],
];

/** Запись хода в латинскую форму, понятную chess.js. */
export function вЛатинскуюЗапись(ход: string): string {
  let h = ход.trim();
  for (const [ru, en] of ФИГУРЫ) {
    if (h.startsWith(ru)) {
      h = en + h.slice(ru.length);
      break;
    }
  }
  // Превращение тоже бывает по-русски: e8=Ф
  for (const [ru, en] of ФИГУРЫ) {
    h = h.replace("=" + ru, "=" + en);
  }
  // Ноль вместо буквы O в рокировке — частая запись.
  if (/^0-0(-0)?[+#]?$/.test(h)) h = h.replace(/0/g, "O");
  // Двоеточие как знак взятия (старая русская запись).
  h = h.replace(":", "x");
  return h;
}

const ПОЛЕ = "[a-h][1-8]";
const ФИГУРА = "(?:Кр|[КФЛС]|[KQRBN])";
const ХВОСТ = "(?:=(?:[ФЛСК]|[QRBN]))?[+#]?";

/**
 * Ходы, ЗАЯВЛЕННЫЕ как ходы. Возвращает их в исходном написании.
 *
 * Четыре признака заявления, любой достаточен: буква фигуры, знак взятия,
 * шах/мат/превращение, рокировка, номер хода впереди.
 */
export function ходыИзТекста(текст: string): string[] {
  const t = String(текст || "");
  const образцы = [
    // рокировка
    "(?:O-O-O|O-O|0-0-0|0-0)[+#]?",
    // с буквой фигуры: Кf3, Кре2, Лxd8+, Сc4
    ФИГУРА + "[a-h]?[1-8]?[x:]?" + ПОЛЕ + ХВОСТ,
    // пешечное взятие: exd5, e:d5
    "[a-h][x:]" + ПОЛЕ + ХВОСТ,
    // с номером хода: 14.e4, 14...e4, 14. e4
    "[0-9]{1,3}[.]{1,3} ?" + ПОЛЕ + ХВОСТ,
    // пешка с шахом или превращением: e8=Ф, d5+
    ПОЛЕ + "(?:=(?:[ФЛСК]|[QRBN]))[+#]?",
  ];
  const re = new RegExp("(?:" + образцы.join("|") + ")", "g");
  const найдено = t.match(re) || [];
  // У варианта с номером хода номер в ход не входит.
  return найдено.map((h) => h.replace(/^[0-9]{1,3}[.]{1,3} ?/, "").trim()).filter(Boolean);
}

/**
 * Ходы из текста, которых в позиции НЕТ. Пустой список — возражений нет.
 *
 * Три исхода, а не два: позицию не разобрать (пустой или битый FEN) — это
 * «не знаю», и мы возвращаем пустой список, а не обвиняем ответ. Судить по
 * неизвестной позиции значило бы прятать верные разборы при нашей же поломке.
 */
export function нелегальныеХоды(fen: string, текст: string): string[] {
  if (!fen) return [];
  let база: Chess;
  try {
    база = new Chess(fen);
  } catch {
    return [];
  }
  const плохие: string[] = [];
  for (const ход of ходыИзТекста(текст)) {
    const латиница = вЛатинскуюЗапись(ход);
    let ок = false;
    try {
      const c = new Chess(база.fen());
      ок = !!c.move(латиница);
    } catch {
      ок = false;
    }
    // Ход мог быть ответом соперника (вторым полуходом линии) — тогда он
    // легален у ДРУГОЙ стороны. Разбор говорит о линии, а не только о первом
    // ходе, поэтому пробуем и позицию с переданной очередью хода.
    if (!ок) {
      try {
        const части = база.fen().split(" ");
        части[1] = части[1] === "w" ? "b" : "w";
        части[3] = "-"; // взятие на проходе после смены очереди недействительно
        const c2 = new Chess(части.join(" "));
        ок = !!c2.move(латиница);
      } catch {
        /* остаётся не ок */
      }
    }
    if (!ок && !плохие.includes(ход)) плохие.push(ход);
  }
  return плохие;
}

/**
 * Что показать ВМЕСТО ответа, в котором нашёлся несуществующий ход.
 *
 * Молчать нельзя: подмена обязана называть себя, иначе человек решит, что
 * тренер просто немногословен. И нельзя делать вид, что разбора не было —
 * поэтому даём то, что заведомо верно: ход движка.
 *
 * @param лучшийХод лучший ход из отчёта Stockfish, если он под рукой
 */
export function текстВместоОтвета(лучшийХод?: string): string {
  const движком = лучшийХод
    ? ` По движку сильнейшее — ${лучшийХод}.`
    : " Нажми «Анализ» — движок покажет сильнейший ход.";
  return (
    "♟ Разбор словами не показываю: в ответе оказался ход, которого в этой позиции нет." +
    движком +
    " Движок и задачи работают как обычно."
  );
}
