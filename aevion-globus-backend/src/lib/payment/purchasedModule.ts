import {
  isAppReference,
  appSlugForReference,
  type LemonSqueezyReference,
} from "../../data/lemonSqueezyVariants";
import { STANDALONE_APPS } from "../../data/pricing";

/**
 * Куплен ОДИН МОДУЛЬ или тариф на всю планету — один ответ для всех касс.
 *
 * 🔴 ЗАЧЕМ. Замер 29.09.2026: у четырёх модулей нет своего товара в кассе, и они
 * продаются вариантом тарифа с подменой цены (QSkyway $16, QRight/QSign $24,
 * Биржа $40). Вебхук писал такую покупку ПЛАТФОРМЕННЫМ тарифом, а с 15.09 тариф
 * означает срок доступа ко ВСЕЙ планете: `normalizeTier` превращает lite в
 * `full`, и `isModuleEntitled` при full пускает куда угодно. То есть покупатель
 * за $16 получал доступ, который стоит $400 в месяц, включая Multichat за $40.
 *
 * На Lemon Squeezy это закрыто 29.09 (коммит dc5d45658). У PayBox и PayPal тот
 * же путь остался: они разбирают `module` из данных кассы и вдобавок превращают
 * ссылку приложения в тариф (`app_qskyway_lite` → `lite` → `full`, проверено
 * прогоном). Обе кассы на проде выключены, поэтому утечка там спящая — но
 * включение её открывает, и включать PayBox для Казахстана без этой починки
 * нельзя.
 *
 * Правило живёт ЗДЕСЬ, а не тремя копиями в вебхуках: именно так разошлись
 * `tierForReference` (см. tierFromOrderReference.ts) — у второй копии шумная
 * запись о незнакомой ссылке появилась отдельно, спустя месяц.
 *
 * Два признака покупки одного модуля, и оба нужны:
 *   1. касса передала выбранный модуль (`custom_data.module`, `pg_param_module`)
 *      — так выглядит продажа модуля через вариант ТАРИФА с подменой цены;
 *   2. ссылка заказа — ссылка приложения (`app_<слаг>_<ступень>`) — так выглядит
 *      продажа модуля со своим товаром.
 *
 * Возвращает слаг модуля либо null, если куплен тариф. Слаг — то самое имя,
 * которое ждёт `upsertAppSubscription`; перевод «слаг ↔ id модуля» делает
 * `appSubscriptionState`, и второй раз его здесь делать не надо.
 */
/**
 * Модуль, НАЗВАННЫЙ покупкой, без разбора, продаётся ли он отдельно.
 *
 * Нужен ОТДЕЛЬНО от `купленныйМодуль`, и это не дублирование: у двух мест два
 * разных вопроса. На выдаче важно «является ли это продажей одного модуля»
 * (и там узкое условие обязательно — иначе право на модуль без своего товара
 * записать можно, а прочитать нельзя). На ВОЗВРАТЕ важно другое: «какое право
 * могло быть записано, чтобы теперь его снять». Снимать надо всё названное,
 * включая старые записи вида «lite + qcoreai»: узкое условие здесь оставило бы
 * человеку доступ после возврата денег — замер 29.09.2026, четыре упавших
 * сторожа поймали это сразу.
 */
export function названныйМодуль(
  reference: string | null | undefined,
  модульИзКассы?: string | null,
): string | null {
  const явный = typeof модульИзКассы === "string" ? модульИзКассы.trim() : "";
  if (явный) return явный;
  const ref = typeof reference === "string" ? reference.trim() : "";
  if (!ref) return null;
  const какСсылка = ref as LemonSqueezyReference;
  return isAppReference(какСсылка) ? appSlugForReference(какСсылка) ?? null : null;
}

export function купленныйМодуль(
  reference: string | null | undefined,
  модульИзКассы?: string | null,
): string | null {
  const явный = typeof модульИзКассы === "string" ? модульИзКассы.trim() : "";
  // 🔴 ТОЛЬКО то, что продаётся ОТДЕЛЬНЫМ товаром, и это не формальность.
  //
  // Прежняя ступень lite (до 15.09.2026) означала «один модуль на выбор», и
  // выбрать можно было ЛЮБОЙ модуль платформы — например `qcoreai` или `qlearn`,
  // у которых своего товара нет. Право на такой модуль записать можно, а
  // ПРОЧИТАТЬ нельзя: `appSubscriptionState` переводит id модуля в слаг через
  // список отдельно продаваемых, и для остальных отвечает «не куплено». То есть
  // без этой проверки покупка «lite + qcoreai» превратилась бы из доступа по
  // тарифу в невидимое право — «заплатил и не опознан», ровно тот класс, что
  // ломал выдачу у DevHub Studio Pro и у startup_exchange.
  //
  // Поэтому: модуль, у которого нет своего товара, покупкой одного модуля НЕ
  // считается — такая запись остаётся тарифом и доступ даёт тариф.
  if (явный) return продаётсяОтдельно(явный) ? явный : null;

  const ref = typeof reference === "string" ? reference.trim() : "";
  if (!ref) return null;
  // Приведение типа здесь честное и необходимое: на входе ЛЮБАЯ строка из
  // данных кассы, а `isAppReference` — как раз тот, кто решает, наша ли это
  // ссылка. Проверять «наша ли» до вызова проверяющего было бы вторым способом
  // отвечать на тот же вопрос.
  const какСсылка = ref as LemonSqueezyReference;
  // Ссылка приложения названа его слагом: `app_qskyway_lite` → `qskyway`.
  if (isAppReference(какСсылка)) {
    const слаг = appSlugForReference(какСсылка);
    return слаг && продаётсяОтдельно(слаг) ? слаг : null;
  }
  return null;
}

/** Есть ли у модуля свой товар, то есть можно ли его купить отдельно. */
function продаётсяОтдельно(слагИлиId: string): boolean {
  return STANDALONE_APPS.some((a) => a.slug === слагИлиId || a.moduleId === слагИлиId);
}
