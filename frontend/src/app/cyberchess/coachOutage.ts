/**
 * Отказ ИИ-тренера, сказанный человеческими словами.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Тренера зовут из трёх мест шахмат (окно после партии,
 * панель «Спроси тренера», кнопка «А что если»), и человеческий текст был
 * только в одном. В остальных до экрана доезжала строка провайдера дословно:
 *
 *     You have reached your specified API usage limits.
 *     You will regain access on 2026-10-01 at 00:00 UTC.
 *
 * На русской странице это выглядит поломкой сайта, хотя сломан не сайт, а
 * счёт у поставщика модели. Найдено окном user-c8 замером прода 28.09.2026
 * (`POST /api/coach/chat` → 400 с этим телом), за два дня до запуска шахмат.
 *
 * Правило ворот №4: отказ показывается отказом, и текст — человеческий.
 * Копировать текст в три места нельзя: копии расходятся молча.
 *
 * ВАЖНО ПРО СРОК. Лимит провайдера — это НЕ «попробуй через минуту»: он
 * держится до даты сброса. Обещать скорый возврат значит соврать, поэтому
 * дату берём из самого ответа, а не выдумываем.
 */

/** Ответ говорит «кончился счёт у поставщика», а не «наш сервер упал». */
export function лимитПровайдера(сообщение: string): boolean {
  return /usage limit|quota|credit balance|regain access/i.test(String(сообщение || ""));
}

/** Дата сброса из текста ответа («2026-10-01») либо null, если её там нет. */
export function датаВозвратаИзОтвета(сообщение: string): string | null {
  const m = String(сообщение || "").match(/[0-9]{4}-[0-9]{2}-[0-9]{2}/);
  return m ? m[0] : null;
}

const МЕСЯЦЫ = [
  "января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря",
];

/**
 * « — вернётся 1 октября» либо пустая строка, если даты в ответе нет.
 *
 * Пустая строка здесь — правильный исход, а не заглушка: без даты фраза
 * остаётся верной («разбор словами сейчас выключен»), просто без срока.
 */
export function когдаВернётся(сообщение: string): string {
  const дата = датаВозвратаИзОтвета(сообщение);
  if (!дата) return "";
  const d = new Date(дата + "T00:00:00Z");
  if (Number.isNaN(d.getTime())) return "";
  return ` — вернётся ${d.getUTCDate()} ${МЕСЯЦЫ[d.getUTCMonth()]}`;
}

/**
 * Что показать вместо ответа тренера.
 *
 * @param сообщение текст ошибки (тело ответа или e.message)
 * @param имяОшибки e.name — «AbortError» для таймаута
 *
 * Разбор словами выключается, но НЕ выключается сам продукт: движок, задачи и
 * партия работают всегда, и текст обязан это назвать — иначе человек решит,
 * что не работает ничего.
 */
export function отказТренера(сообщение: string, имяОшибки?: string): string {
  const текст = String(сообщение || "");
  if (лимитПровайдера(текст)) {
    пометитьЛимит(текст);
    return (
      `💬 Разбор словами сейчас выключен${когдаВернётся(текст)}. ` +
      `Партия, задачи и разбор движком (Stockfish) работают как обычно.`
    );
  }
  if (имяОшибки === "AbortError") {
    return "⏱ ИИ-тренер думал слишком долго. Попробуй ещё раз или разбери позицию движком.";
  }
  if (/fetch|network|Failed to fetch/i.test(текст)) {
    return "⚠ Не удалось связаться с ИИ-тренером. Проверь соединение или используй разбор движком.";
  }
  return "⚠ ИИ-тренер сейчас недоступен. Партия, задачи и разбор движком работают.";
}

/* ───── Состояние: знаем ли мы, что разбор словами сейчас выключен ─────
 *
 * ЗАЧЕМ. Витрина шахмат обещает «🎓 ИИ-тренер» в трёх местах. Пока счёт у
 * поставщика исчерпан, обещание неверно, и человек узнаёт об этом только
 * нажав. Ворота №1: «обещает = делает».
 *
 * Спросить об этом некого: `/api/coach/health` отвечает `ok:true` и при
 * исчерпанном лимите (проверено запросом 28.09.2026 — health ok, а
 * `/api/coach/chat` тем же запросом отдаёт 400 с текстом лимита). Это
 * «доступность не равна пригодности»: ручка отвечает за себя, а не за то,
 * ради чего её зовут. Чинить её — в зоне ядрового бэкенда, передано.
 *
 * Поэтому знание берём оттуда, где оно и так появляется: из первого же
 * отказа. Пометка живёт в sessionStorage — она про ЭТОТ визит и исчезает
 * сама, когда тренер снова отвечает (см. `тренерОтветил`). Ни сервера, ни
 * лишнего запроса это не стоит.
 *
 * Хранилище может быть недоступно (приватное окно, запрет на данные сайта),
 * поэтому каждое обращение обёрнуто: без него страница обязана работать.
 */

const КЛЮЧ = "cc:coach-outage-until";

/** Запомнить отказ по лимиту. Зовётся из `отказТренера`, одной точкой на все места. */
function пометитьЛимит(сообщение: string): void {
  const дата = датаВозвратаИзОтвета(сообщение);
  try {
    sessionStorage.setItem(КЛЮЧ, дата || "неизвестно");
  } catch {
    /* хранилище закрыто — тогда просто не показываем пометку */
  }
}

/** Тренер ответил — прежняя пометка больше не верна. */
export function тренерОтветил(): void {
  try {
    sessionStorage.removeItem(КЛЮЧ);
  } catch {
    /* см. выше */
  }
}

/**
 * Что показать на витрине: пустая строка — пометка не нужна.
 *
 * Пусто значит «мы НЕ знаем об отказе», а не «всё точно работает». Это
 * честная граница: врать в другую сторону (пугать отказом, которого нет)
 * так же плохо, как обещать разбор, которого нет.
 */
export function пометкаОВыключенномРазборе(): string {
  let знач: string | null = null;
  try {
    знач = sessionStorage.getItem(КЛЮЧ);
  } catch {
    return "";
  }
  if (!знач) return "";
  const срок = знач === "неизвестно" ? "" : когдаВернётся(знач);
  return `💬 Разбор словами сейчас выключен${срок}. Партия, задачи и разбор движком работают как обычно.`;
}
