import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * Восстановление обязано вернуть ВСЁ, что проект несёт, а не почти всё.
 *
 * Найдено 13.09.2026 сквозной пробой, а не чтением кода. Поставил предмет,
 * задал высоту 3.1, перезагрузил страницу — и получил на одном экране два
 * наших ответа о высоте:
 *
 *     до правки            поле 2.7   стены 115.3 м²
 *     после ввода 3.1      поле 3.1   стены 132.4 м²
 *     ПОСЛЕ перезагрузки   поле 2.7   стены 132.4 м²
 *
 * Третья строка и есть дефект: подпись говорит 2.7, а смета посчитана по 3.1.
 * Человек верит полю и покупает краску не на ту площадь — разница около 15 %,
 * и заметит это только тот, кто сверит два числа между собой.
 *
 * Причина структурная и потому повторяемая: высота хранится У СТЕН плана, а
 * поле ввода — отдельное состояние. `applyProject` возвращал план, материалы,
 * перегородку и слои, а поле не трогал. Любое НОВОЕ поле ввода, заведённое
 * рядом, повторит эту ошибку по той же схеме.
 *
 * Сторож смотрит состав `applyProject`: всё, что проект несёт, обязано в нём
 * восстанавливаться. Список ведётся вручную и осознанно — добавили поле в
 * проект, добавьте сюда же.
 */
const КЛИЕНТ = readFileSync(path.join(__dirname, "_client.tsx"), "utf8")
  .split(/\r?\n/)
  .filter((строка) => !/^\s*\/\//.test(строка))
  .join(String.fromCharCode(10));

function телоApplyProject(): string {
  const i = КЛИЕНТ.indexOf("const applyProject = useCallback((pr: Project) => {");
  expect(i, "applyProject не найдена — сторож устарел").toBeGreaterThan(-1);
  const конец = КЛИЕНТ.indexOf("}, [", i);
  expect(конец, "конец applyProject не найден").toBeGreaterThan(i);
  return КЛИЕНТ.slice(i, конец);
}

describe("восстановление возвращает ВСЁ, что несёт проект", () => {
  const ОБЯЗАНЫ = [
    ["план", "setPlan(pr.plan)"],
    ["материал стен", "setWallMatId(pr.wallMatId)"],
    ["материал пола", "setFloorMatId(pr.floorMatId)"],
    ["перегородка", "setPartition(pr.partition)"],
    ["слои", "setLayers(pr.layers)"],
    // Поле высоты — то самое, чего не хватало: высота живёт у стен плана,
    // а поле ввода отдельное, и без явной строки они расходятся.
    ["поле высоты потолка", "setHeightM("],
  ] as const;

  it("контроль прибора: тело функции найдено и непустое", () => {
    expect(телоApplyProject().length).toBeGreaterThan(150);
  });

  it("каждое состояние проекта восстанавливается", () => {
    const тело = телоApplyProject();
    const пропущены = ОБЯЗАНЫ.filter(([, признак]) => !тело.includes(признак))
      .map(([имя]) => имя);
    expect(
      пропущены,
      "после открытия проекта это останется прежним, а человек решит, что вернулось всё",
    ).toEqual([]);
  });

  it("высота берётся ИЗ ПЛАНА, а не из умолчания", () => {
    // setHeightM(String(WALL_HEIGHT)) выглядел бы как починка и ею не был:
    // поле показало бы 2.7 при любой восстановленной высоте.
    expect(телоApplyProject()).toMatch(/setHeightM\(String\(planWallHeight\(pr\.plan\)\)\)/);
  });
});
