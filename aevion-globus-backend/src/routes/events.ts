/** Похожа ли метка канала на нашу. Точное совпадение или наше слово с разделителем. */
function нашаМетка(значение: string | null | undefined): boolean {
  const v = String(значение ?? "").trim().toLowerCase();
  if (!v) return false;
  return НАШИ_МЕТКИ_КАНАЛА.some((m) => v === m || v.startsWith(`${m}-`) || v.startsWith(`${m}_`));
}

/**
 * Отдельный параметр `probe=<окно>` в адресе — явное «это наш заход».
 *
 * 🔴 Замер 05.10.2026: окно данных зашло с `?c=mail-ai3&probe=40`, чтобы проверить
 * разрез по постам, и воронка посчитала его ЖИВЫМ человеком: признак «наше»
 * читал только метку канала вида `probe-*`. То есть любой наш проверочный
 * заход, сохраняющий настоящую метку канала (а он обязан её сохранять, иначе
 * нечего проверять), попадал в живые числа.
 *
 * Разделение намеренное: метка канала отвечает «откуда пришли», а `probe=` —
 * «кто пришёл». Смешивать их в одном параметре значит выбирать между «проверить
 * атрибуцию» и «не испортить счёт».
 */
function пробаИзПути(path: string | null | undefined): string | null {
  const m = /[?&]probe=([^&#]*)/.exec(String(path ?? ""));
  if (!m) return null;
  return безопаснаяМетка(decodeURIComponent(m[1] || "")) || "безымянная";
}

/**
 * Проба ОКНА — отдельный признак, а не расширение «нашего».
 *
 * 🔴 Почему отдельный. «Наше» уже отвечает на вопрос «наша ли это попытка
 * оплаты» и питает `checkoutStartOurs`/`paidOurs`. Подмешать туда проверочные
 * ЗАХОДЫ значило бы снова заставить один признак отвечать на два вопроса — у
 * нас это уже ломало счёт дважды за неделю. Поэтому две приметы живут порознь:
 *   `c=probe-*`  → наша попытка оплаты (старое, не трогаем);
 *   `?probe=<окно>` → проверочный ЗАХОД окна (новое, этот признак).
 *
 * Вынесено функцией ради проверяемости: пока условие стояло строкой внутри
 * цикла, мутация «убрать примету» выжила — сторож смотрел на потребление
 * готового множества, а не на то, как оно собирается.
 */
export function этоПробаОкна(path: string | null | undefined): boolean {
  return Boolean(пробаИзПути(path));
}

/**
 * Два множества сессий из журнала: наши попытки оплаты и проверочные заходы окон.
 *
 * Вынесено из обработчика РАДИ ПРОВЕРЯЕМОСТИ. Пока сбор стоял строками внутри
 * запроса, мутация «убрать примету probe=» выживала: сторож проверял разрез,
 * которому множество передают готовым, а не то, как оно собирается.
 *
 * Работает и ЗАДНИМ ЧИСЛОМ, по уже собранным событиям: примета живёт в адресе
 * страницы, а не в теле события.
 */
export function разобратьСессии(content: string): {
  нашиСессии: Set<string>;
  пробыОкон: Set<string>;
} {
  const нашиСессии = new Set<string>();
  const пробыОкон = new Set<string>();
  for (const line of content.split(String.fromCharCode(10))) {
    if (!line.trim()) continue;
    let ev: AnalyticsEvent;
    try {
      ev = JSON.parse(line) as AnalyticsEvent;
    } catch {
      continue;
    }
    if (ev.type !== "page_view" || !ev.sid) continue;
    if (нашаМетка(меткаИзПути(ev.path))) нашиСессии.add(ev.sid);
    if (этоПробаОкна(ev.path)) пробыОкон.add(ev.sid);
    // Сказанное прямо сильнее выведенного из адреса: если окно пометило
    // событие флагом, метка в адресе уже не нужна.
    if (ev.probe === true) пробыОкон.add(ev.sid);
  }
  return { нашиСессии, пробыОкон };
}

/**
 * 🔴 ВНЕШНИЙ ОБХОДЧИК ССЫЛОК: сессии, которые выглядят живыми и живыми не являются.
 *
 * Замер 07.10.2026, мой собственный, по публичной ручке за двое суток:
 * у канала youtube 37 постов в разрезе, и у **33 из них ровно по 2 живых визита**
 * (распределение 1:1, 2:33, 3:3), всего 76 визитов, до цен дошёл ОДИН. Прирост
 * просмотров роликов за то же время — от +1 до +74, то есть числа визитов с
 * живым вниманием не связаны вовсе. Ровное число по почти всем меткам — подпись
 * машины: человек не открывает 33 разные ссылки за минуты.
 * Окно 99 независимо получило те же числа; всплеск пришёлся на правку описаний
 * роликов, то есть похоже на проверку ссылок самой площадкой.
 *
 * Чего этот признак НЕ делает, и это важнее того, что делает:
 *   • НЕ считает обходчиком сессию с одним просмотром. Человек, закрывший
 *     страницу сразу, выглядит так же, и отсеивать его значило бы прятать
 *     настоящих посетителей — худшее, что может сделать учёт.
 *   • НЕ опирается на строку браузера: у обходчика она бывает человеческой
 *     (ровно поэтому его не поймали ни `видОтправителя`, ни `webdriver`).
 *   • НЕ трогает НАШИ заходы: они уже помечены отдельно, и смешивать два
 *     ответа в одном счётчике нельзя. Наши смоук-прогоны сами ходят по многим
 *     страницам и попали бы под этот признак — поэтому они исключаются ПЕРВЫМИ.
 *
 * Что он делает: ищет ОДНУ строку браузера, которая за короткое окно пришла по
 * МНОГИМ РАЗНЫМ меткам, и каждая такая сессия — один просмотр без продолжения.
 * Человек так не ходит; обходчик ссылок ходит только так.
 *
 * Пороги названы числами и объяснены: 8 разных меток (при настоящих 33 — запас
 * вчетверо) за 15 минут. Выше человеческого поведения с большим отрывом; ниже
 * наблюдаемого шаблона машины.
 */
export const ОБХОД_МЕТОК_МИНИМУМ = 8;
export const ОБХОД_ОКНО_МС = 15 * 60 * 1000;

export function обходчики(content: string): { сессии: Set<string>; причина: string } {
  type Запись = {
    sid: string;
    метка: string;
    t: number;
    событий: number;
    внимание: boolean;
    /** Разные адреса сессии без запроса: человек ходит по сайту, машина — нет. */
    пути: Set<string>;
  };
  const поБраузеру = new Map<string, Map<string, Запись>>();

  for (const line of content.split(String.fromCharCode(10))) {
    if (!line.trim()) continue;
    let ev: AnalyticsEvent;
    try {
      ev = JSON.parse(line) as AnalyticsEvent;
    } catch {
      continue;
    }
    if (!ev.sid) continue;
    const t = Date.parse(ev.ts || "");
    if (!Number.isFinite(t)) continue;
    const ua = typeof ev.ua === "string" ? ev.ua : "";
    if (!ua) continue;
    if (!поБраузеру.has(ua)) поБраузеру.set(ua, new Map());
    const сессии = поБраузеру.get(ua)!;
    const признакВнимания = ev.type === "engaged" || ev.type === "feature_use";
    const путь = String(ev.path ?? "").split("?")[0].split("#")[0];
    const прежняя = сессии.get(ev.sid);
    if (прежняя) {
      прежняя.событий += 1;
      if (признакВнимания) прежняя.внимание = true;
      if (путь) прежняя.пути.add(путь);
      continue;
    }
    if (ev.type !== "page_view") continue;
    const метка = меткаИзПути(ev.path) ?? "";
    сессии.set(ev.sid, {
      sid: ev.sid,
      метка,
      t,
      событий: 1,
      внимание: false,
      пути: new Set(путь ? [путь] : []),
    });
  }

  const найденные = new Set<string>();
  for (const [, сессии] of поБраузеру) {
    /*
     * 🔴 ПОПРАВКА 07.10.2026, нашло окно 99: условие было «ровно одно событие
     * в сессии», и обходчик его ОБХОДИЛ, как только нажимал ссылку покупки.
     * Живой замер: 8 «начал оплату» на /qmelanin с восьми разных роликов, у
     * каждого ровно 2 визита, 0 до цен, 1 старт, и `checkoutStartOurs` ноль —
     * то есть восемь поддельных денежных шагов выглядели живыми покупателями.
     *
     * Теперь исключение не по ЧИСЛУ событий, а по признаку ВНИМАНИЯ: сессия
     * выпадает из шаблона, если в ней есть `engaged` (похоже на чтение) или
     * `feature_use` (что-то сделал). Нажатие «купить» от шаблона больше не
     * спасает: машина нажимает ссылки, а читать и пользоваться — нет.
     *
     * Два условия вместо прежнего одного, и второе важнее: сессия должна
     * касаться ОДНОГО адреса. Прежняя защита («сессия с продолжением — не
     * обходчик») тем самым сохранена для человека, который пошёл по сайту
     * дальше, но больше не спасает машину, нажавшую «купить» на той же
     * странице: у неё адрес один, а событий два.
     *
     * Цена решения названа честно: любопытный человек, открывший восемь разных
     * ссылок за четверть часа, ни на одной не задержавшийся и ни с одной не
     * ушедший на вторую страницу, попадёт в обходчиков. Пока событие `engaged` не выкачено на сайт, у такого человека
     * нет и способа отличиться — в эти дни признак строже, чем будет потом.
     * Обратная ошибка дороже: поддельное «начал оплату» ведёт к решению тратить
     * деньги на канал, которого нет.
     */
    const одиночные = [...сессии.values()].filter(
      (з) => !з.внимание && з.пути.size <= 1 && з.метка,
    );
    if (одиночные.length < ОБХОД_МЕТОК_МИНИМУМ) continue;
    одиночные.sort((a, b) => a.t - b.t);
    // Скользящее окно: нужны МНОГО РАЗНЫХ меток внутри короткого промежутка.
    for (let i = 0; i < одиночные.length; i += 1) {
      const окно = одиночные.filter(
        (з) => з.t >= одиночные[i].t && з.t <= одиночные[i].t + ОБХОД_ОКНО_МС,
      );
      const метки = new Set(окно.map((з) => з.метка));
      if (метки.size >= ОБХОД_МЕТОК_МИНИМУМ) {
        for (const з of окно) найденные.add(з.sid);
      }
    }
  }

  return {
    сессии: найденные,
    причина: `одна строка браузера пришла по ${ОБХОД_МЕТОК_МИНИМУМ}+ разным меткам за ${
      ОБХОД_ОКНО_МС / 60000
    } мин, каждая сессия — один просмотр без продолжения`,
  };
}

/** Метка канала из адреса страницы: `/pricing?c=cold-visit-check` → `cold-visit-check`. */
function меткаИзПути(path: string | null | undefined): string | null {
  const p = String(path ?? "");
  const m = /[?&]c=([^&#]+)/.exec(p);
  return m ? decodeURIComponent(m[1]) : null;
}

