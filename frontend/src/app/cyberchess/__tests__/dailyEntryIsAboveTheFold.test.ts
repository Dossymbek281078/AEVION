/**
 * Вход в задачу дня стоит на ПЕРВОМ экране.
 *
 * 🔴 ПОВОД 30.09.2026, день запуска шахмат. За сутки пришло 99 человек и
 * задачу дня решил НОЛЬ. Механизм возврата в тот день чинили целиком — серия,
 * цели, плитка, подсказка, — и он работает: проверено ручкой прода, серия
 * 0 → 1. Не работало другое: до него не доходили.
 *
 * ЗАМЕР, из которого всё следует (живое окно 1568×744, /cyberchess):
 *   вход «🌐 Задача дня · Lichess» — 1046 пикселей от верха → 1,4 экрана вниз
 *   вход «Задача дня» (плитка)     — 1296 пикселей от верха → 1,7 экрана вниз
 *   строка «Цели на сегодня»       —  ~580 пикселей         → ВЫШЕ линии сгиба
 * Поэтому вход добавлен именно в строку целей.
 *
 * Проверка по исходнику, а не браузером, и это осознанно: браузерный
 * инструмент в этом окне 30.09 трижды подряд отвечал «Couldn't determine which
 * page», и ждать его — значит не проверить вовсе. Утверждение здесь слабее
 * пиксельного, и я это называю прямо: оно стережёт, что вход лежит В ТОМ ЖЕ
 * блоке, чьё положение измерено. Уедет блок — уедет и вход, но об этом скажет
 * уже другой замер.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/** Снять комментарии: иначе объяснение ПРО вход считается входом. */
function безКомментариев(src: string): string {
  let out = "";
  let i = 0;
  while (i < src.length) {
    const два = src.slice(i, i + 2);
    if (два === "/*") { const к = src.indexOf("*/", i + 2); i = к < 0 ? src.length : к + 2; continue; }
    if (два === "//" && src[i - 1] !== ":") { const к = src.indexOf(String.fromCharCode(10), i); i = к < 0 ? src.length : к; continue; }
    out += src[i]; i += 1;
  }
  return out;
}

const код = безКомментариев(readFileSync(join(__dirname, "..", "page.tsx"), "utf8"));

// 05.10.2026 подпись «Цели на сегодня» уехала в словарь (перевод на казахский),
// и якорь по литералу перестал находиться: проверка молча смотрела в начало
// файла. Якорем теперь служит сам вызов словаря — он и есть место строки целей.
const ЯКОРЬ_СТРОКИ_ЦЕЛЕЙ = 'cc.t("goals.title")';

describe("вход в задачу дня на первом экране", () => {
  it("прибор исправен: комментарии не считаются кодом", () => {
    expect(безКомментариев('a /* Задача дня */ b')).not.toContain("Задача дня");
    expect(безКомментариев('const u = "https://a.app"; // x')).toContain("https://a.app");
  });

  it("🔴 вход лежит внутри строки «Цели на сегодня»", () => {
    const строкаЦелей = код.indexOf(ЯКОРЬ_СТРОКИ_ЦЕЛЕЙ);
    expect(строкаЦелей, "строка целей не найдена — проверка смотрит не туда").toBeGreaterThan(0);
    // Блок строки целей заканчивается на «+30 Chessy завтра!» — это последний
    // её элемент. Вход обязан быть ВНУТРИ, то есть раньше него.
    const конецБлока = код.indexOf("+30 Chessy завтра!", строкаЦелей);
    expect(конецБлока).toBeGreaterThan(строкаЦелей);
    const блок = код.slice(строкаЦелей, конецБлока);
    // 🔴 ПЕРЕНАЦЕЛЕНО 07.10.2026, и это не косметика: в прежнем виде проверка
    //    ТРЕБОВАЛА дефекта. Она ждала `type:"daily_open"` ВНУТРИ строки целей,
    //    то есть настаивала, чтобы событие отправляла кнопка. А кнопок,
    //    открывающих задачу дня, две — и вторая молчала; плюс событие на кнопке
    //    уходило раньше проверок внутри открытия, так что неудача считалась
    //    открытием. Замер окна 98: daily_open за 04–06.10 — ноль во все три дня.
    //    Теперь отправка живёт в самом открытии, а здесь стережём ровно то, о чём
    //    и была эта проверка: вход на первом экране есть и ведёт в задачу дня.
    expect(блок, "вход в задачу дня вне строки целей").toMatch(/loadDailyPuzzle\(/);
    // Поверхность передаётся, иначе в событии не будет видно, откуда пришли,
    // и разрез «каким входом пользуются» снова станет недоступен.
    expect(блок, "вход не называет себя — поверхность в событии будет неизвестна")
      .toContain('loadDailyPuzzle("goals-row")');
    expect(блок.includes('type:"daily_open"'),
      "событие снова отправляется с кнопки: второй вход в задачу дня будет молчать").toBe(false);
  });

  it("контроль: прежние входы всё ещё существуют и НЕ считаются за этот", () => {
    // Вход на первом экране добавлен, а не переставлен: плитка ниже осталась.
    // Если бы проверка выше ловила её, она была бы зелёной и до правки.
    const строкаЦелей = код.indexOf(ЯКОРЬ_СТРОКИ_ЦЕЛЕЙ);
    const конецБлока = код.indexOf("+30 Chessy завтра!", строкаЦелей);
    const после = код.slice(конецБлока);
    expect(после, "нижний вход пропал — это не то, о чём договаривались").toMatch(/loadDailyPuzzle\(/);
    // И он тоже называет себя — именно он до 07.10.2026 открывал задачу дня
    // МОЛЧА, и из-за него счётчик открытий недосчитывал.
    expect(после, "нижний вход не передаёт поверхность — его открытия снова станут безымянными")
      .toContain('loadDailyPuzzle("puzzles-panel")');
  });

  it("🔴 событие называет, КАКИМ входом открыли задачу дня", () => {
    // ПЕРЕНАЦЕЛЕНО 07.10.2026. Проверка ждала source:"cyberchess/goals" — то
    // есть опиралась на то, что событие отправляет сама кнопка целей. Пока это
    // было так, второй вход (панель задач) открывал задачу МОЛЧА, и счётчик
    // открытий недосчитывал; замер окна 98 дал ноль за 04–06.10.
    //
    // Теперь отправка одна, из самого открытия, а вход называет себя полем
    // meta.surface. Стережём то же самое СВОЙСТВО — «по событию видно, каким
    // входом пользуются», — но по новому месту, и сразу для ОБОИХ входов:
    // проверка на один вход и была причиной слепоты ко второму.
    expect(код, "событие не называет источник — разрез по входам собрать нечем")
      .toContain('source:"cyberchess/daily"');
    expect(код, "поверхность не передаётся в событие").toMatch(/meta:\{surface,/);
    for (const вход of ["goals-row", "puzzles-panel"]) {
      expect(код, `вход «${вход}» не называет себя — его открытия будут безымянными`)
        .toContain(`loadDailyPuzzle("${вход}")`);
    }
  });
});
