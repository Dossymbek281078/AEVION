import { describe, expect, test } from "vitest";
import { kanonicheskoeReshenie } from "../page";

/*
 * 🔴 Серверу уходит КАНОНИЧЕСКОЕ решение задачи дня, включая ход соперника.
 *
 * ПОВОД — замер на живом проде 08.10.2026, перехваченное ТЕЛО запроса (не
 * рассуждение): ручка задачи дня отдала решение из шести ходов
 * ["a5a6","e2f2","h2g1","f2g2","g1f1","e4g3"], а страница отправила пять — без
 * первого хода соперника `a5a6`, — и сервер ответил **400**. Ходы при этом
 * ПРИМЕНЯЛИСЬ: клетка-источник пустела, цель занималась, занятых клеток 12 —
 * ровно столько в FEN задачи. То есть человек решал правильно, а мы отвечали ему
 * «решение не попало в таблицу лидеров».
 *
 * Два последствия помимо таблицы: `daily_solved` не уходил с этого пути никогда,
 * а предложение адреса после решённой задачи висит на `r.ok` того же запроса —
 * значит адрес не предлагали никому.
 *
 * ⚠️ Чего эти проверки НЕ доказывают: что сервер теперь принимает решение. Это
 * мерится только проходом пути человека на проде (прибор
 * `zamer-adres-posle-reshennoy-zadachi-dnya.mjs`: ожидается `daily_solved` и
 * просьба адреса). До зелёного ответа прибора «починено» говорить нельзя.
 */

const СЫРОЕ = ["a5a6", "e2f2", "h2g1", "f2g2", "g1f1", "e4g3"];
const ПОКАЗАННОЕ = ["e2f2", "h2g1", "f2g2", "g1f1", "e4g3"];

describe("какое решение задачи дня уходит на сервер", () => {
  test("есть каноническое — отправляем ЕГО, целиком и с ходом соперника", () => {
    const ушло = kanonicheskoeReshenie({ sol: ПОКАЗАННОЕ, solRaw: СЫРОЕ });
    expect(ушло).toEqual(СЫРОЕ);
    // Длина — отдельное утверждение: именно её сверяет сервер, и именно она
    // расходилась (6 против 5).
    expect(ушло.length, `у задачи ${СЫРОЕ.length} ходов, отправлено ${ушло.length}`).toBe(6);
    expect(ушло[0]).toBe("a5a6");
  });

  test("🔴 КОНТРОЛЬ: отправленное НЕ равно показанному игроку", () => {
    // Без этого проверка выше прошла бы и у функции, возвращающей srv.sol: в
    // старом коде оба списка были «решением задачи», и подмена была незаметна.
    const ушло = kanonicheskoeReshenie({ sol: ПОКАЗАННОЕ, solRaw: СЫРОЕ });
    expect(ушло).not.toEqual(ПОКАЗАННОЕ);
    expect(ушло.length).not.toBe(ПОКАЗАННОЕ.length);
  });

  test("канонического нет — отправляем показанное, но НЕ молчим вовсе", () => {
    // Худший случай: сервер, скорее всего, откажет, и человек увидит отказ. Это
    // лучше, чем не отправить: тогда решивший не попадёт в таблицу и не узнает
    // почему.
    expect(kanonicheskoeReshenie({ sol: ПОКАЗАННОЕ })).toEqual(ПОКАЗАННОЕ);
    expect(kanonicheskoeReshenie({ sol: ПОКАЗАННОЕ, solRaw: [] })).toEqual(ПОКАЗАННОЕ);
  });

  test("КОНТРОЛЬ: функция РАЗЛИЧАЕТ случаи, а не возвращает одно и то же", () => {
    const с = kanonicheskoeReshenie({ sol: ПОКАЗАННОЕ, solRaw: СЫРОЕ });
    const без = kanonicheskoeReshenie({ sol: ПОКАЗАННОЕ });
    expect([с.length, без.length], `с каноническим ${с.length}, без ${без.length}`).toEqual([6, 5]);
  });

  test("нечётное решение (игрок ходит первым) не ломается", () => {
    // У таких задач ход соперника не нужен, и каноническое равно показанному.
    const нечёт = ["e2e4", "d7d5", "e4d5"];
    expect(kanonicheskoeReshenie({ sol: нечёт, solRaw: нечёт })).toEqual(нечёт);
  });
});
