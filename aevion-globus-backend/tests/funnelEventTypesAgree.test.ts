import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Список типов событий воронки одинаков на сервере и на клиенте.
 *
 * ЗАЧЕМ. Клиент шлёт события через `navigator.sendBeacon` — он не читает ответ
 * по устройству. Сервер на незнакомый тип отвечает `400 invalid_type` и в
 * журнал НИЧЕГО не пишет. Сложите одно с другим: тип, который есть на фронте и
 * забыт на сервере, теряется МОЛЧА. Ни страница не узнает, ни оператор.
 *
 * Пострадает при этом ровно та цифра, ради точности которой воронка и заведена:
 * шаг просто перестанет считаться, а дашборд покажет заниженное число с тем же
 * уверенным видом. Это класс «отказ, который выглядит успехом», только со
 * стороны учёта.
 *
 * ЗАМЕР 31.08.2026: списки сходятся, 16 против 16, расхождений в обе стороны
 * ноль. То есть сторож ставится НЕ по факту поломки, а потому что расхождение
 * здесь невидимо — а два списка ведутся порознь, в разных половинах репозитория,
 * и разойтись им ничего не мешает.
 *
 * ГРАНИЦА. Сторож сверяет ОБЪЯВЛЕНИЯ, а не фактические вызовы: тип, объявленный
 * на фронте и нигде не отправляемый, он пропустит. Это осознанно — вопрос здесь
 * «поймёт ли сервер то, что фронт умеет слать», а не «шлём ли мы всё, что
 * объявили».
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const SERVER = resolve(HERE, "..", "src", "routes", "events.ts");
const CLIENT = resolve(HERE, "..", "..", "frontend", "src", "lib", "track.ts");

/** Типы, которые сервер соглашается принять. */
function serverTypes(): string[] {
  const m = /ALLOWED_TYPES = new Set\(\[([\s\S]*?)\]\)/.exec(readFileSync(SERVER, "utf8"));
  if (!m) return [];
  return [...new Set(m[1].match(/"[a-z_]+"/g)?.map((s) => s.slice(1, -1)) ?? [])].sort();
}

/** Типы, которые клиент умеет слать. */
function clientTypes(): string[] {
  const m = /export type EventType\s*=([\s\S]*?);/.exec(readFileSync(CLIENT, "utf8"));
  if (!m) return [];
  return [...new Set(m[1].match(/"[a-z_]+"/g)?.map((s) => s.slice(1, -1)) ?? [])].sort();
}

describe("типы событий воронки одинаковы на сервере и клиенте", () => {
  const server = serverTypes();
  const client = clientTypes();

  test("контроль: оба списка прочитаны и непусты", () => {
    // Пустой список сделал бы сравнение ниже зелёным при любом состоянии —
    // в том числе если объявление переименуют и разбор перестанет попадать.
    expect(server.length, `сервер: ${server.join(", ")}`).toBeGreaterThanOrEqual(10);
    expect(client.length, `клиент: ${client.join(", ")}`).toBeGreaterThanOrEqual(10);
  });

  test("контроль: разбор берёт ИМЕННО эти списки, а не что попало", () => {
    // Проба с заранее известным ответом: оба списка обязаны содержать шаг,
    // без которого воронка не воронка.
    expect(server, "сервер не принимает checkout_success").toContain("checkout_success");
    expect(client, "клиент не умеет слать checkout_success").toContain("checkout_success");
  });

  test("фронт не шлёт того, чего сервер не примет", () => {
    const lost = client.filter((t) => !server.includes(t));
    expect(
      lost,
      "клиент умеет слать эти типы, а сервер их отвергает — событие пропадёт МОЛЧА: " +
        "sendBeacon ответа не читает, сервер отказ не журналирует, и шаг воронки " +
        "просто перестанет считаться",
    ).toEqual([]);
  });

  test("сервер не ждёт того, чего фронт не шлёт", () => {
    // Обратная сторона мягче, но тоже стоит внимания: лишний тип на сервере
    // означает либо забытую страницу, либо мёртвую строку, и по нему нельзя
    // понять, что именно. Список должен описывать одно и то же с двух сторон.
    const orphan = server.filter((t) => !client.includes(t));
    expect(
      orphan,
      "сервер принимает типы, которых клиент не умеет слать: либо страница потеряна, " +
        "либо строка мертва — по списку не отличить",
    ).toEqual([]);
  });
});
