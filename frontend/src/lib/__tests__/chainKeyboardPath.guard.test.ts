import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { ЦЕПОЧКА_ПЛАНЕТЫ } from "../planetChain";

/**
 * ЦЕПОЧКА ПЛАНЕТЫ: что этот сторож покрывает, а что НЕТ.
 *
 * 🔴 ГРАНИЦА, и она важнее зелёного цвета. Читайте её, прежде чем считать
 * путь проверенным.
 *
 *   ПОКРЫТО:     ни один орган управления не выпадает из обхода Tab.
 *                Замер 03.09.2026 на проде: 210 органов на четырёх
 *                страницах, недостижимых 0. Три «пропуска» оказались
 *                кнопками disabled — они законно вне обхода и включаются
 *                после заполнения формы.
 *
 *   НЕ ПОКРЫТО:  проход С ДАННЫМИ — заполнить, отправить, получить на
 *                следующем шаге ТУ САМУЮ отметку. Это требует стенда с
 *                бэкендом: на проде такой проход создал бы настоящие записи
 *                в реестре, а на локальной сборке без бэкенда /qsign
 *                отрисовывает 2 ссылки вместо семидесяти органов.
 *
 * То есть зелёный здесь означает «на каждом шаге ничего не выпало из
 * обхода», а НЕ «путь проходим целиком». Разница между этими двумя
 * утверждениями — ровно то, чем «заявление сильнее продукта» и живёт.
 *
 * Стенд с бэкендом поставлен в план после 10.09.2026 (решение окна запуска).
 */

const КОРЕНЬ = path.join(__dirname, "..", "..");

describe("цепочка планеты: путь между комнатами", () => {
  it("объявитель смонтирован на всех страницах, а не на четырёх", () => {
    // Потеря фокуса при переходе — свойство платформы, а не цепочки:
    // клиентский переход не переносит фокус и ничего не объявляет.
    // Починка в общей обёртке, иначе через месяц её продублируют в пятой
    // комнате и разойдутся.
    const s = fs.readFileSync(
      path.join(КОРЕНЬ, "components", "ClientProviders.tsx"), "utf8");
    expect(s).toContain("<RouteAnnouncer />");
  });

  it("порядок комнат берётся из ОДНОГО источника", () => {
    // Если бы каждая страница знала свой номер сама, расхождение объявляло
    // бы человеку «шаг 2 из 4» на третьей комнате.
    const объявитель = fs.readFileSync(
      path.join(КОРЕНЬ, "components", "RouteAnnouncer.tsx"), "utf8");
    expect(объявитель).toContain("местоВЦепочке");
    expect(ЦЕПОЧКА_ПЛАНЕТЫ.length).toBeGreaterThanOrEqual(3);
  });

  it("имя комнаты приходит из словаря, а не зашито", () => {
    // Платформа трёхъязычная: зашитая строка звучала бы смесью языков.
    for (const к of ЦЕПОЧКА_ПЛАНЕТЫ) {
      expect(к.ключ.startsWith("chain.room.")).toBe(true);
    }
    const словарь = fs.readFileSync(path.join(КОРЕНЬ, "lib", "i18n-data.ts"), "utf8");
    for (const к of ЦЕПОЧКА_ПЛАНЕТЫ) {
      // ключ обязан быть во ВСЕХ трёх языках: в двух — значит на третьем
      // человек услышит сам ключ
      const сколько = словарь.split(`"${к.ключ}"`).length - 1;
      expect(сколько).toBe(3);
    }
    expect(словарь.split('"chain.step"').length - 1).toBe(3);
  });

  it("формула шага — целая фраза, а не склейка из кусков", () => {
    // В казахском порядок слов другой: «{m} қадамның {n}-сі». Склейка
    // «Шаг» + номер + «из» + всего дала бы кальку с русского во всех языках.
    const словарь = fs.readFileSync(path.join(КОРЕНЬ, "lib", "i18n-data.ts"), "utf8");
    const строки = словарь
      .split("\n")
      .filter((l) => l.includes('"chain.step"'));
    expect(строки.length).toBe(3);
    for (const s of строки) {
      expect(s).toContain("{n}");
      expect(s).toContain("{m}");
    }
  });

  it("граница записана в самом стороже, а не только в переписке", () => {
    // Иначе через неделю зелёный прочтут как «путь проходим целиком».
    const я = fs.readFileSync(__filename, "utf8");
    expect(я).toContain("НЕ ПОКРЫТО");
    expect(я).toContain("проход С ДАННЫМИ");
  });
});
