/**
 * Дата турнира так, как её читает человек.
 *
 * С сервера время приходит меткой вида `2026-08-12T18:11:04.050Z`, и она
 * попадала на экран как есть. Замер 27.08.2026 на живой странице турниров:
 * ДВЕНАДЦАТЬ таких меток разом — вместо «12 августа, 23:11» человек видел
 * машинную строку.
 *
 * Ни один тест этого не ловил: строка непустая, компонент отрисован, ошибок
 * нет. Нашлось чтением того, что реально написано на экране.
 *
 * Про гидрацию: образцы в списке записаны без часового пояса
 * («2026-05-18 19:00»), и такая строка на сервере и в браузере даёт один и
 * тот же текст. Метки с Z приходят из запроса, то есть уже после
 * монтирования, — расхождения нет.
 */

const МЕСЯЦЫ = [
  "января",
  "февраля",
  "марта",
  "апреля",
  "мая",
  "июня",
  "июля",
  "августа",
  "сентября",
  "октября",
  "ноября",
  "декабря",
];

// 24.10.2026: на /en и /kk месяцы шли по-русски (⚠️ kk — черновой перевод, нужна вычитка носителя).
const МЕСЯЦЫ_EN = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
const МЕСЯЦЫ_KK = ["қаңтар", "ақпан", "наурыз", "сәуір", "мамыр", "маусым", "шілде", "тамыз", "қыркүйек", "қазан", "қараша", "желтоқсан"];

export function человеческаяДата(s: string, язык: string = "ru"): string {
  if (!s) return "";
  // "2026-05-18 19:00" → "2026-05-18T19:00": без T такую строку разбирают
  // по-разному разные браузеры.
  const d = new Date(s.includes("T") ? s : s.replace(" ", "T"));
  // Непонятную строку возвращаем как есть: показать сырое лучше, чем
  // показать «Invalid Date» или пустоту — человек хотя бы увидит данные.
  if (isNaN(d.getTime())) return s;
  const чч = String(d.getHours()).padStart(2, "0");
  const мм = String(d.getMinutes()).padStart(2, "0");
  if (язык === "en") return МЕСЯЦЫ_EN[d.getMonth()] + " " + d.getDate() + ", " + чч + ":" + мм;
  const месяцы = язык === "kk" ? МЕСЯЦЫ_KK : МЕСЯЦЫ;
  return d.getDate() + " " + месяцы[d.getMonth()] + ", " + чч + ":" + мм;
}
