/* Вырезание комментариев для сторожей — с разбором строк, а не регуляркой.
 *
 * Наивное `s.replace(/\/\*[\s\S]*?\*\//g, "")` ломается на первом же `/*` внутри
 * строкового литерала. В `page.tsx` таким оказался `accept="image/*"`: он открыл
 * фальшивый комментарий, который закрылся только на следующем настоящем `*​/` — через
 * 7574 символа и 77 строк кода. Вместе с ними исчезли, например, переключатели звука.
 *
 * Замерено 11.08.2026: наивный вариант выбрасывал **13.3% файла** (144 КБ из 1088 КБ).
 * Опаснее всего это для отрицательных проверок вида `expect(src).not.toMatch(...)`:
 * выброшенный кусок делает их зелёными независимо от того, что там на самом деле.
 * То есть сторож молча перестаёт сторожить — ровно тот класс дефектов, который эти
 * сторожа и должны ловить.
 *
 * Здесь простой посимвольный проход: помним, находимся ли внутри строки (', ", `),
 * и комментарии вырезаем только снаружи. Экранирование учитывается. Регулярные
 * литералы не разбираются — в этом модуле `/*` внутри регулярки не встречается, а
 * полноценный разбор JS ради тестов не нужен.
 */

export function stripComments(src: string): string {
  let out = "";
  let i = 0;
  const n = src.length;
  let quote: string | null = null;

  while (i < n) {
    const c = src[i];
    const next = src[i + 1];

    if (quote) {
      out += c;
      if (c === "\\") {
        // экранированный символ переносим как есть — иначе \" закроет строку
        if (i + 1 < n) out += src[i + 1];
        i += 2;
        continue;
      }
      if (c === quote) quote = null;
      i += 1;
      continue;
    }

    if (c === '"' || c === "'" || c === "`") {
      quote = c;
      out += c;
      i += 1;
      continue;
    }

    if (c === "/" && next === "*") {
      const end = src.indexOf("*/", i + 2);
      i = end === -1 ? n : end + 2;
      continue;
    }

    if (c === "/" && next === "/") {
      const nl = src.indexOf("\n", i);
      i = nl === -1 ? n : nl;
      continue;
    }

    out += c;
    i += 1;
  }

  return out;
}
