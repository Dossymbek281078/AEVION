/**
 * Кто СЕЙЧАС основная касса — один ответ на всю платформу.
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. На 29.09.2026 на этот вопрос отвечали ТРИ ручки, и
 * ответы расходились на живом проде:
 *
 *   /api/pricing/checkout/healthz → primaryProvider: "lemonsqueezy"   (считал)
 *   /api/payments                 → lemonsqueezy.primary: true        (считал)
 *   /api/revenue/health           → gumroad.primary: **true**         (литерал)
 *
 * Третья врала константой, оставшейся с тех времён, когда живым процессингом
 * действительно был Gumroad. Цена лжи не косметическая: у Gumroad сейчас не
 * настроено НИ ОДНОЙ из 50 продаваемых позиций (замер `gumroad.sellable.missing`
 * — 50 из 50), то есть отчёт называл основной кассой того, кто не может продать
 * ничего. Читатель отчёта — человек, принимающий решения о деньгах.
 *
 * Отдельно поучительно, как расхождение выжило: в `payments.ts` его УЖЕ
 * однажды починили и в комментарии прямо написали «второй способ отвечать на
 * тот же вопрос и есть причина расхождения» — а починку сделали копией
 * выражения из `checkout.ts`. Диагноз был верен, лечение воспроизвело болезнь:
 * копий стало три вместо двух. Поэтому теперь выражение живёт здесь, а ручки
 * его ЗОВУТ.
 *
 * Правило, ради которого всё это: основным считается тот, кто способен ВЫДАТЬ
 * купленное, а не тот, кто способен взять деньги. Без секрета вебхука
 * Lemon Squeezy отвечает кассе 200 и молча игнорирует событие — деньги списаны,
 * доступ не выдан, и снаружи всё зелено.
 */

/** Готова ли касса ВЗЯТЬ деньги: есть ключ и магазин. */
export function lemonSqueezyCanCharge(): boolean {
  return (
    Boolean(process.env.LEMON_SQUEEZY_API_KEY?.trim()) &&
    Boolean(process.env.LEMON_SQUEEZY_STORE_ID?.trim())
  );
}

/** Дойдёт ли покупка до ВЫДАЧИ: к предыдущему нужен секрет вебхука. */
export function lemonSqueezyCanDeliver(): boolean {
  return lemonSqueezyCanCharge() && Boolean(process.env.LEMON_SQUEEZY_WEBHOOK_SECRET?.trim());
}

/**
 * Основная касса: та, через которую сейчас реально пойдёт покупатель.
 *
 * Значение читают и люди (отчёты), и код (маршрутизация), поэтому имена
 * возвращаются ровно те, что уже стоят в ответах ручек.
 */
/**
 * Может ли Gumroad вообще оформить покупку: есть хотя бы один товар.
 *
 * Ссылка на товар задаётся переменной на позицию (`GUMROAD_PERMALINK_<ССЫЛКА>`) либо
 * общей `GUMROAD_DEFAULT_PERMALINK`. Нет ни одной — касса не продаст ничего, сколько
 * бы ключей у неё ни было.
 */
export function gumroadCanSell(env: NodeJS.ProcessEnv = process.env): boolean {
  if (env.GUMROAD_DEFAULT_PERMALINK?.trim()) return true;
  return Object.keys(env).some(
    (k) => k.startsWith("GUMROAD_PERMALINK_") && Boolean(env[k]?.trim()),
  );
}

/**
 * Основная касса: та, через которую сейчас реально пойдёт покупка.
 *
 * 🔴 ИСХОДОВ ТРИ, А НЕ ДВА — поправка 05.10.2026 к моей же версии от 29.09.
 *
 * Прежняя возвращала «gumroad» всякий раз, когда Lemon Squeezy не может выдавать. И
 * это противоречило замеру, записанному в шапке ЭТОГО ЖЕ файла: у Gumroad не
 * настроено ни одной продаваемой позиции. Замер прода 05.10: у Lemon Squeezy товаров
 * 30, у Gumroad — 0 из 30. То есть при отказе LS платформа называла бы основной
 * кассой ту, которая не может продать ничего, и говорила бы это и людям (отчёты), и
 * коду (маршрутизация). Я написал диагноз в шапке и не применил его в функции —
 * ровно тот класс, за который сам же ругал чужой код.
 *
 * Поэтому: «none» — честный третий исход «кассы сейчас нет». Он хуже для отчёта и
 * лучше для правды: отсутствие кассы видно сразу, а не после первой неудачной
 * покупки. Правило трёх исходов у нас записано: «нет», «есть», «не знаю/нечем» —
 * путать последние два нельзя.
 */
export function primaryCheckoutProvider(): "lemonsqueezy" | "gumroad" | "none" {
  if (lemonSqueezyCanDeliver()) return "lemonsqueezy";
  if (gumroadCanSell()) return "gumroad";
  return "none";
}
