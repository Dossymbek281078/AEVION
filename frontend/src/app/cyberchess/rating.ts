/**
 * Рейтинг игрока после партии с ИИ.
 *
 * Формула жила двумя строками внутри компонента и не была закреплена ничем
 * (28.08.2026), хотя это ядро прогресса: по ней человек видит, растёт он или
 * нет. Числа подобраны так, что победа над более сильным даёт больше, а над
 * заведомо слабым — минимум 5.
 *
 * Границы 100…3000 не косметика: без них рейтинг уходит в минус после серии
 * поражений и обнуляет смысл шкалы.
 */
export const РЕЙТИНГ_МИН = 100;
export const РЕЙТИНГ_МАКС = 3000;

export function новыйРейтинг(текущий: number, силаСоперника: number, победа: boolean): number {
  if (победа) {
    const прирост = Math.max(5, Math.round((силаСоперника - текущий) * 0.1 + 15));
    return Math.min(РЕЙТИНГ_МАКС, текущий + прирост);
  }
  const убыль = Math.max(5, Math.round((текущий - силаСоперника) * 0.1 + 10));
  return Math.max(РЕЙТИНГ_МИН, текущий - убыль);
}

/**
 * Звание по рейтингу. Человек видит его в шапке рядом с цифрой, и оно
 * единственное, что говорит новичку «ты вырос»: цифра 1240 сама по себе
 * ничего не значит, а «Клубный» — значит.
 *
 * Вынесено из page.tsx 28.08.2026 вместе с таблицей порогов. При поломке не
 * падает: просто показывает не то звание, и человек считает, что не растёт.
 *
 * Титулы CM/FM/IM/GM оставлены как есть — это принятые шахматные звания,
 * а не жаргон.
 */
export const RANKS = [{min:0,t:"Начинающий",i:"●"},{min:600,t:"Новичок",i:"◆"},{min:900,t:"Любитель",i:"■"},{min:1200,t:"Клубный",i:"▲"},{min:1500,t:"Турнирный",i:"★"},{min:1800,t:"CM",i:"✦"},{min:2000,t:"FM",i:"✧"},{min:2200,t:"IM",i:"✪"},{min:2400,t:"GM",i:"♛"}];

export function gRank(e:number){return[...RANKS].reverse().find(r=>e>=r.min)||RANKS[0]}
