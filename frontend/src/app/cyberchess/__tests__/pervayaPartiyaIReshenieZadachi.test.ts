import { describe, expect, test } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { УРОВЕНЬ_ИИ_ПО_УМОЛЧАНИЮ } from "../page";

const СТРАНИЦА = join(process.cwd(), "src/app/cyberchess/page.tsx");
const текст = readFileSync(СТРАНИЦА, "utf8");

/*
 * 🔴 Первая партия новичка должна быть выигрываемой, а событие «задача решена»
 * обязано уходить со ВСЕХ путей решения.
 *
 * ЧИСЛА. За 7 дней 10 живых с YouTube начали партию и НОЛЬ доиграли (замер окна
 * воронки). Замер 11.10: рейтинг игрока по умолчанию 800, а соперник по
 * умолчанию стоял 1200 — новичка сажали против заведомо более сильного; задача
 * дня в тот же день имела рейтинг 2269 (замер окна 3d на живой ручке).
 *
 * Отдельно: события «задача решена» не было вовсе, то есть на вопрос «решил ли
 * зритель ролика ту задачу, ради которой пришёл» ответить было нечем.
 */

describe("первая партия новичка", () => {
  test("🔴 уровень ИИ по умолчанию — не выше рейтинга самого игрока (800)", () => {
    // ALS: 0 Beginner 400, 1 Casual 800, 2 Club 1200. Игрок по умолчанию 800.
    expect(УРОВЕНЬ_ИИ_ПО_УМОЛЧАНИЮ, "индекс уровня в ALS").toBeLessThanOrEqual(1);
  });

  test("КОНТРОЛЬ: прежнее значение (Клубный, индекс 2) проверку НЕ прошло бы", () => {
    // Без этого контроля проверка выше прошла бы и у порога, пропускающего всё.
    expect(2).toBeGreaterThan(1);
  });

  test("рейтинг игрока по умолчанию в коде по-прежнему 800", () => {
    // Если его поднимут, порог выше надо пересматривать вместе с ним —
    // проверка держит ПАРУ чисел, а не одно.
    expect(текст, "ожидалось useState(800) для рейтинга игрока").toContain("const[rat,sRat]=useState(800)");
  });
});

describe("событие «задача решена»", () => {
  test("🔴 шлётся из ОБОИХ мест признания решения, а не из одного", () => {
    const признаний = (текст.match(/addChessy\(reward,"задача решена"\)/g) ?? []).length;
    const отправок = (текст.match(/soobschitORescheniiZadachi\(pzCurrent,/g) ?? []).length;
    expect(признаний, "мест признания решения в файле").toBeGreaterThanOrEqual(2);
    expect(отправок, `мест признания ${признаний}, отправок события ${отправок}`).toBe(признаний);
  });

  test("КОНТРОЛЬ: прибор видит оба числа непустыми", () => {
    // Иначе «равны» было бы истиной при нуле и нуле — зелено и бессмысленно.
    expect((текст.match(/addChessy\(reward,"задача решена"\)/g) ?? []).length).toBeGreaterThan(0);
    expect((текст.match(/soobschitORescheniiZadachi\(/g) ?? []).length).toBeGreaterThan(1);
  });
});
