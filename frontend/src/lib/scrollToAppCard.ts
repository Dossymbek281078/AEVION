/**
 * Довезти человека до карточки приложения на странице цен.
 *
 * Повод 29.09.2026. Переход по кнопке витрины модуля (`/pricing?app=<слаг>`)
 * оставлял человека наверху: замер на ширине телефона (390 px, 7 секунд
 * ожидания) дал прокрутку 0, а карточка CyberChess стояла на 6162 px — 7.3
 * экрана вниз при длине страницы в 23 экрана. Прежнее ожидание считало ТАКТЫ
 * (40 попыток по 150 мс = 6 секунд), а такты кончаются раньше отрисовки на
 * медленном телефоне, холодном кэше и слабой сети.
 *
 * Здесь ждут СОБЫТИЕ появления узла. Срок остался, но у него другой смысл:
 * не «сколько ждать отрисовку», а «когда признать, что карточки не будет»
 * (переименовали слаг, изменили разметку). Промах при этом не молчит — о нём
 * сообщают вызывающему, и страница показывает человеку строку со ссылкой.
 *
 * Вынесено в отдельный файл намеренно: сторож должен проверять ТОТ ЖЕ код,
 * который выполняется на проде, а не его копию в тесте. Копия расходится с
 * оригиналом молча и создаёт ложную уверенность.
 */
export interface ОжиданиеКарточки {
  /** Отменить ожидание (уход со страницы). */
  отменить: () => void;
}

export function ждатьКарточкуПриложения(
  слаг: string,
  опции: {
    приДоставке: (карточка: Element) => void;
    приПромахе: (слаг: string) => void;
    срокМс?: number;
    документ?: Document;
  },
): ОжиданиеКарточки {
  const d = опции.документ ?? document;
  const срок = опции.срокМс ?? 15000;
  const найти = () =>
    d.querySelector(`[data-app="${typeof CSS !== "undefined" && CSS.escape ? CSS.escape(слаг) : слаг}"]`);

  const сразу = найти();
  if (сразу) {
    опции.приДоставке(сразу);
    return { отменить: () => {} };
  }

  let закрыто = false;
  const наблюдатель = new MutationObserver(() => {
    if (закрыто) return;
    const карточка = найти();
    if (!карточка) return;
    закрыто = true;
    наблюдатель.disconnect();
    clearTimeout(предел);
    опции.приДоставке(карточка);
  });
  наблюдатель.observe(d.body, { childList: true, subtree: true });

  const предел = setTimeout(() => {
    if (закрыто) return;
    закрыто = true;
    наблюдатель.disconnect();
    // Ещё одна попытка найти: карточка могла появиться ровно на границе срока.
    const поздняя = найти();
    if (поздняя) опции.приДоставке(поздняя);
    else опции.приПромахе(слаг);
  }, срок);

  return {
    отменить: () => {
      if (закрыто) return;
      закрыто = true;
      наблюдатель.disconnect();
      clearTimeout(предел);
    },
  };
}
