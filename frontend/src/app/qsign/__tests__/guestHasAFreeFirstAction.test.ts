  test("контроль: файл прочитан и это нужная страница", () => {
    // Без этого пустой или чужой файл дал бы зелёное «всё на месте».
    expect(src.length).toBeGreaterThan(5000);
    expect(src).toContain("/api/qsign/v2/verify");
  });

  /*
   * 🔴 19.10.2026: ссылка больше НЕ из recent.items[0]. Замер на проде 19.10
   * (окно Продукт): первая запись ленты была отозванной пробой, после одного
   * прогона пути гостя — свежей пробой с payload {"probe":…}. «Настоящая запись
   * ленты» оказалась самой ненадёжной: её меняет любой наш прогон. Теперь —
   * закреплённая демо-подпись AEVION по константе, а лента и счётчики на бэке
   * чистятся от проб (lib/qsignV2/probes).
   */
