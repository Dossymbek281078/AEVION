/**
 * Устойчивый идентификатор устройства для гостевой нормы.
 *
 * 🔴 ЗАЧЕМ. Бесплатная норма Мультичата («2 запроса без входа») считается на
 * сервере по устройству ИЛИ по адресу — устройства он берёт из заголовка
 * `x-aevion-device`. Замер 29.09.2026 показал, что страница этого заголовка НЕ
 * посылала вовсе, значит норма считалась ТОЛЬКО по IP.
 *
 * Для запуска это плохо: мобильные операторы держат тысячи абонентов за одним
 * адресом. Двое человек с одного оператора исчерпали бы норму на всех
 * остальных — «предел превращается в отказ толпе», ровно тот класс, который у
 * нас уже был с общим ключом. Идентификатор устройства делает норму личной.
 *
 * Не отпечаток браузера: случайное число, выданное один раз и сохранённое у
 * человека. Оно ничего о нём не сообщает и не связывает его посещения разных
 * сайтов — только наши собственные запросы в пределах одного браузера.
 *
 * Хранилище может быть недоступно (приватное окно, запрет на данные сайта),
 * поэтому все обращения обёрнуты, и при отказе возвращается пустая строка:
 * тогда сервер честно считает норму по адресу, как считал раньше. Пустая строка
 * лучше выдуманной: одно и то же подставное значение у всех гостей склеило бы их
 * норму в одну.
 */
const КЛЮЧ = "aevion-guest-device";

export function идентификаторУстройства(): string {
  if (typeof window === "undefined") return "";
  try {
    const было = window.localStorage.getItem(КЛЮЧ);
    if (было && /^[0-9a-z]{8,64}$/i.test(было)) return было;
    const новый =
      typeof crypto !== "undefined" && typeof crypto.randomUUID === "function"
        ? crypto.randomUUID().replace(/-/g, "")
        : Math.random().toString(36).slice(2) + Date.now().toString(36);
    window.localStorage.setItem(КЛЮЧ, новый);
    return новый;
  } catch {
    return "";
  }
}

/** Заголовки для гостевых запросов: пустых значений не отправляем. */
export function заголовкиУстройства(): Record<string, string> {
  const id = идентификаторУстройства();
  return id ? { "x-aevion-device": id } : {};
}
