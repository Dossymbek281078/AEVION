import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Ноль голосов и «мы не смогли их прочитать» — разные вещи.
 *
 * Замер 29.08.2026. Счётчики голосов рисовались как `data?.votes.up ?? 0`, а
 * `data` остаётся null не только пока идёт загрузка: функция загрузки при
 * неудачном ответе делала `if (!r.ok) return`, а исключение глотала целиком.
 * Значит недоступный сервер выглядел на экране как «👍 0 👎 0» — то есть как
 * утверждение «никто не голосовал», хотя мы просто не измерили.
 *
 * Дефект двойной, и чинить надо обе половины: отказ перестаёт быть невидимым
 * (появляется признак), а показ перестаёт называть незнание нулём.
 *
 * Три состояния теперь различаются: числа есть — число; идёт загрузка — «…»;
 * не удалось — «—».
 *
 * ГРАНИЦА СТОРОЖА, честно: он читает ИСХОДНИК, а не отрисованную страницу.
 * Значит он поймает возврат к `?? 0` и пропажу признака, но не докажет, что
 * человек увидел «—». Полное доказательство — рендер, он дороже и в этот
 * файл не помещается.
 */

const PAGE = join(__dirname, "..", "page.tsx");
const src = readFileSync(PAGE, "utf8");

describe("незагруженные голоса не выдаются за ноль", () => {
  test("контроль: это нужная страница и счётчики на месте", () => {
    expect(src.includes("ConstitutionPage"), "сторож смотрит не туда").toBe(true);
    expect(src.includes("votes.up"), "счётчик голосов исчез — проверять нечего").toBe(true);
  });

  test("отказ загрузки оставляет признак, а не проходит молча", () => {
    expect(
      src.includes("setVotesUnknown(true)"),
      "отказ снова проглатывается: страница не узнает, что чисел нет",
    ).toBe(true);
    // Успешная загрузка обязана признак СНИМАТЬ, иначе он залипнет навсегда
    // после первой же неудачи и «—» останется при живых числах.
    expect(
      src.includes("setVotesUnknown(false)"),
      "признак не снимается при успехе — залипнет после первой неудачи",
    ).toBe(true);
  });

  test("ни один счётчик голосов не подставляет ноль вместо незнания", () => {
    const lies = ["votes.up ?? 0", "votes.down ?? 0", "votes.total ?? 0"];
    const found = lies.filter((l) => src.includes(l));
    expect(
      found,
      "счётчик снова называет незнание нулём: недоступный сервер прочтётся " +
        `как «никто не голосовал» — ${found.join(", ")}`,
    ).toEqual([]);
  });

  test("показ различает ТРИ состояния, а не два", () => {
    // Без «…» загрузка была бы неотличима от отказа: человек увидел бы «—»
    // на исправной системе и решил, что счётчики сломаны.
    expect(src.includes('votesUnknown ? "—" : "…"'), "нет различия «идёт» и «не смогли»").toBe(true);
  });
});
