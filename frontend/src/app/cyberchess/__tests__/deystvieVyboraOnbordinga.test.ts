import { describe, expect, test } from "vitest";
import { deystvieVyboraOnbordinga } from "../page";

/*
 * 🔴 Плитка «♟ Играть» обязана НАЧИНАТЬ партию — она это обещает текстом.
 *
 * ПОВОД 11.10.2026. Подпись плитки: «Партия против ИИ 800–2400 — 5 секунд до
 * старта». Замер окна user-37 на проде (пустое хранилище, чтение через 1, 3, 6 и
 * 10 секунд) каждый раз давал одно и то же: партии нет, на доске «Нажмите доску»,
 * рядом панель настройки. Поломки в коде не было — было расхождение обещания с
 * устройством, и для первого экрана магнита это то же самое: человек нажал
 * «Играть» и не играет.
 *
 * Решение оркестратора: обещание исполняем, партия начинается на умолчаниях.
 *
 * ⚠️ Чего эти проверки НЕ доказывают: что на живой странице после нажатия идёт
 * партия. Это проверяется рендером на проде — приёмка user-37 после выкатки.
 */

describe("что делает выбор в приветственном окне", () => {
  test("🔴 «Играть» начинает партию, а не открывает настройки", () => {
    const д = deystvieVyboraOnbordinga("play");
    expect(д.startGame, "партия должна начаться").toBe(true);
    expect(д.setup, "экран настройки показывать НЕ надо").toBe(false);
    expect(д.tab).toBe("play");
  });

  test("«Учиться» ведёт к тренеру и партию не начинает", () => {
    expect(deystvieVyboraOnbordinga("learn")).toEqual({ tab: "coach", setup: false, startGame: false });
  });

  test("«Задачи» ведут к задачам и партию не начинают", () => {
    expect(deystvieVyboraOnbordinga("puzzles")).toEqual({ tab: "puzzles", setup: false, startGame: false });
  });

  test("КОНТРОЛЬ: партию начинает РОВНО один выбор из трёх", () => {
    // Без этого проверка выше прошла бы и у функции, которая запускает партию
    // всегда — а тогда «Задачи» уводили бы человека в партию.
    const сколько = (["play", "learn", "puzzles"] as const)
      .filter((i) => deystvieVyboraOnbordinga(i).startGame).length;
    expect(сколько, `партию начинают ${сколько} выбора из 3`).toBe(1);
  });

  test("КОНТРОЛЬ: ни один выбор не оставляет человека на экране настройки", () => {
    // Прежнее поведение (setup=true у «Играть») и было поводом правки: именно оно
    // показывало панель вместо партии.
    for (const i of ["play", "learn", "puzzles"] as const) {
      expect(deystvieVyboraOnbordinga(i).setup, `выбор ${i}`).toBe(false);
    }
  });
});
