/**
 * Что сообщить рекламным площадкам о состоявшейся покупке.
 *
 * Вынесено из `AdPixels.tsx` отдельной функцией по одной причине: решение
 * здесь не техническое, а денежное — от него зависит, какую выручку увидят
 * Meta и TikTok и по каким числам будет тратиться бюджет. Внутри компонента
 * его нельзя проверить иначе как поднимая всю страницу с переменными
 * окружения; здесь оно проверяется прямо.
 *
 * Возвращает `null`, если события площадкам слать не надо.
 */
export type ПокупкаНаЭкране = {
  value?: unknown;
  meta?: Record<string, unknown>;
};

export type СигналПлощадкам = {
  /** Meta ждёт `Purchase`. Ложь означает: за нас его пришлёт сама касса. */
  вMeta: boolean;
  /** TikTok ждёт `CompletePayment`. */
  вTikTok: boolean;
  /** Сумма и валюта — или `undefined`, если сумма неизвестна. */
  деньги?: { value: number; currency: string };
};

export function сигналОПокупке(d: ПокупкаНаЭкране): СигналПлощадкам | null {
  // Бесплатное — не покупка. У свободного тарифа возврат несёт `total=0`,
  // у заглушки `stub=true`. Посчитать их значило бы учить площадку приводить
  // людей, которые не платят, — то есть тратить бюджет ровно мимо цели.
  if (d.meta?.stub === true) return null;
  const сумма = typeof d.value === "number" ? d.value : null;
  if (сумма === 0) return null;

  return {
    // Meta у возврата Gumroad пропускается: Gumroad шлёт Purchase сам, полем
    // Facebook Pixel ID в настройках товара. Свой поверх дал бы ДВОЙНОЙ счёт,
    // а завышенная выручка хуже отсутствующей — по ней решают о бюджете.
    // Обратная сторона честная: если поле в Gumroad не заполнено, Meta покупок
    // оттуда не увидит. Это ручной шаг, он описан в шапке AdPixels.tsx.
    вMeta: d.meta?.provider !== "gumroad",
    // TikTok шлём всегда: у Gumroad поле только для Facebook, и без нас
    // TikTok не узнает о покупке ни от одной кассы.
    вTikTok: true,
    // Сумму передаём, только если знаем: у PayBox в адрес возврата уходит ref,
    // а не сумма. Ноль вместо неизвестного сказал бы, что покупка ничего не
    // стоила, и это хуже молчания.
    деньги: сумма === null ? undefined : { value: сумма, currency: "USD" },
  };
}
