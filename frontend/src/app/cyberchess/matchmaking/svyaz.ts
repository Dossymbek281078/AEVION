/**
 * Когда сказать человеку, что связь пропала, а не «ищем соперника».
 *
 * Опрос очереди идёт раз в 2 секунды, и одиночный сбой сети — обычное дело:
 * кричать на каждый было бы хуже молчания, человек перестанет читать. А вот
 * молчать бесконечно нельзя: при упавшем сервере экран показывает бегущий
 * счётчик «Прошло: 3:20» и живую пульсацию, то есть уверенно сообщает, что
 * поиск идёт, — хотя не идёт ничего.
 *
 * Порог в пять подряд — это около десяти секунд: дольше любого блипа и
 * заметно раньше, чем человек решит, что соперников просто нет.
 */
export const PODRYAD_DO_TREVOGI = 5;

export function svyazPoteryana(podryadOshibok: number): boolean {
  return podryadOshibok >= PODRYAD_DO_TREVOGI;
}
