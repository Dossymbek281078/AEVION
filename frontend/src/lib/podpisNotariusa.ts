/**
 * Что сказать человеку о подписи нотариуса на странице сертификата.
 *
 * 🔴 ЗАЧЕМ. Значок NOTARIZED показывался одинаково и для настоящей подписи
 * Ed25519, и для демонстрационной HMAC (`demo-hmac-sha256`), которой на проде
 * до 12.10.2026 были ВСЕ подписи. Бюро продаётся за доказуемость — значит
 * демо-подпись обязана быть названа своим именем там, где её видит покупатель,
 * а не только в JSON сертификата. Слово оркестратора 12.10: «старые
 * demo-сертификаты помечаются честно, не выдаём их за настоящие».
 *
 * Источник правды — ручка проверки /api/bureau/cert/:id/notarization/verify:
 * та же, которой проверит третья сторона. Здесь только текст по её ответу.
 */
export type ОтветПроверки = {
  ok: boolean;
  reason?: string | null;
  keyId?: string | null;
  algorithm?: string | null;
};

export type СтрокаПодписи = { текст: string; тон: "ok" | "demo" | "warn" };

export function podpisNotariusaTekst(о: ОтветПроверки | null): СтрокаПодписи {
  if (!о) return { текст: "Подпись нотариуса: проверка недоступна", тон: "warn" };
  if (о.ok) {
    const ключ = о.keyId ? ` · ключ ${о.keyId}` : "";
    return { текст: `Подпись нотариуса проверена · ${о.algorithm ?? "ed25519"}${ключ}`, тон: "ok" };
  }
  if (о.reason === "demo-signature") {
    return { текст: "Демо-подпись — доказательством не является", тон: "demo" };
  }
  if (о.reason === "key-mismatch") {
    return { текст: "Подписано другим ключом — проверка по текущему ключу невозможна", тон: "warn" };
  }
  return { текст: `Подпись не проверена: ${о.reason ?? "причина не названа"}`, тон: "warn" };
}
