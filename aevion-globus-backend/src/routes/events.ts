export function разрезВоронки(
  events: Array<Pick<AnalyticsEvent, "type" | "path" | "meta" | "sid" | "refHost">>,
  нашиСессии: ReadonlySet<string> = new Set(),
  пробыОкон: ReadonlySet<string> = new Set(),
): РазрезВоронки {
  /*
   * 🔴 ДЛЯ ВИЗИТОВ «наш заход» — ОБЪЕДИНЕНИЕ двух примет, и это не возврат к
   * одному признаку на два вопроса.
   *
   * Вопросов по-прежнему два, и они разные:
   *   «наша ли это попытка ОПЛАТЫ» → `нашиСессии` (метка канала `probe-*`),
   *      ею и считаются checkoutStartOurs / paidOurs, как считались;
   *   «наш ли это ЗАХОД» → обе приметы сразу: и `probe-*` в метке канала, и
   *      отдельный параметр `?probe=<окно>`.
   * Разделять их на уровне визита значило бы оставить половину наших заходов
   * в живых числах — а именно от этого разрез и страхует.
   *
   * Повод: замер 06.10.2026 — наши заходы с `?c=ig` раздули Instagram до
   * «70 % дошли до цен», и пометки «наше» у визитов не было вовсе: она стояла
   * только у начатых оплат.
   */
  const нашЗаход = (sid: string | undefined): boolean =>
    Boolean(sid && (нашиСессии.has(sid) || пробыОкон.has(sid)));
  const byChannel = Object.create(null) as РазрезВоронки["byChannel"];
  const byApp = Object.create(null) as РазрезВоронки["byApp"];
  const byPost = Object.create(null) as РазрезВоронки["byPost"];
  const byUnknownTag = Object.create(null) as РазрезВоронки["byUnknownTag"];
  /** Путь без запроса, до трёх участков, идентификаторы скрыты. */
  const чистыйПуть = (raw: string | null | undefined): string => {
    const без = String(raw ?? "/").split("?")[0].split("#")[0];
    const участки = без.split("/").filter(Boolean).slice(0, 3);
    const безИд = участки.map((у) =>
      /^[0-9a-f]{8,}$/i.test(у) || /^\d{4,}$/.test(у) || у.length > 24 ? ":id" : у.toLowerCase(),
    );
    return "/" + безИд.join("/");
  };

  /*
   * Итог: считается ДО всякого `continue` и без оглядки на канал, поэтому в
   * него попадает и трафик с незнакомых меток, и события без метки вовсе.
   */
  /*
   * Источник сессии: первое её событие в окне и есть вход. Журнал дописывается
   * по времени, поэтому «первое встреченное» и есть «первое по времени».
   */
  const источникСессии = new Map<string, string>();
  const byReferrerHost = Object.create(null) as РазрезВоронки["byReferrerHost"];
  const НАШИ_ДОМЕНЫ = new Set(["aevion.app", "www.aevion.app", "aevion.vercel.app"]);

  const людиИтог = new Set<string>();
  const людиИтогНаши = new Set<string>();
  const людиЦенИтог = new Set<string>();
  const людиЦенИтогНаши = new Set<string>();
  const итог = {
    visits: 0,
    visitsOurs: 0,
    pricing: 0,
    pricingOurs: 0,
    checkoutStart: 0,
    checkoutStartOurs: 0,
    thankYouOpened: 0,
    paid: 0,
    paidOurs: 0,
    tried: 0,
    triedOurs: 0,
    engaged: 0,
    engagedOurs: 0,
  };

  /** Пара «канал + сессия»: чтобы визит считался один раз, как в итоге. */
  const виденныеСессии = new Set<string>();

  for (const ev of events) {
    const сырой = ev.meta?.channel;
    const канал = typeof сырой === "string" && сырой.trim() ? сырой.trim() : "direct";
    if (!byChannel[канал]) {
      byChannel[канал] = пустойКанал();
    }
    const к = byChannel[канал];

    const сыройПост = ev.meta?.post;
    const пост = typeof сыройПост === "string" && сыройПост.trim() ? сыройПост.trim().slice(0, 40) : null;
    const ключПоста = пост ? `${канал}/${пост}` : null;
    if (ключПоста && !byPost[ключПоста]) {
      byPost[ключПоста] = пустойПост();
    }
    const п = ключПоста ? byPost[ключПоста] : null;

    /*
     * Итог — здесь, на каждом событии, независимо от канала и до `continue`.
     * Единица визита та же, что у суточного разреза воронки: уникальная
     * сессия. Событие без `sid` считается отдельным — иначе анонимные заходы
     * исчезли бы совсем (вариант «считать их одним» однажды уже дал ноль там,
     * где люди были).
     */
    const нашЭтот = нашЗаход(ev.sid);
    if (ev.type === "page_view" && ev.sid && !источникСессии.has(ev.sid)) {
      const хост = typeof ev.refHost === "string" ? ev.refHost.trim().toLowerCase() : "";
      источникСессии.set(
        ev.sid,
        !хост ? "(не назван)" : НАШИ_ДОМЕНЫ.has(хост) ? "(внутри сайта)" : хост,
      );
    }
    if (ev.type === "page_view") {
      if (ev.sid) {
        людиИтог.add(ev.sid);
        if (нашЭтот) людиИтогНаши.add(ev.sid);
      } else {
        итог.visits += 1;
        if (нашЭтот) итог.visitsOurs += 1;
      }
      if (typeof ev.path === "string" && ev.path.includes("/pricing")) {
        if (ev.sid) {
          людиЦенИтог.add(ev.sid);
          if (нашЭтот) людиЦенИтогНаши.add(ev.sid);
        } else {
          итог.pricing += 1;
          if (нашЭтот) итог.pricingOurs += 1;
        }
      }
    } else if (ev.type === "checkout_start") {
      итог.checkoutStart += 1;
      if (ev.sid && нашиСессии.has(ev.sid)) итог.checkoutStartOurs += 1;
    } else if (ev.type === "checkout_success") {
      итог.thankYouOpened += 1;
    } else if (ev.type === СОБЫТИЕ_ОПЛАТА_ПОДТВЕРЖДЕНА) {
      /*
       * 🔴 ОПЛАТА — ТОЛЬКО ПО ИМЕНИ СОБЫТИЯ, НИКАКИХ «ИНАЧЕ».
       *
       * Здесь стояла ветка `else`, и она считала оплатой ВСЁ, что не просмотр,
       * не начало оплаты и не страница «спасибо»: нажатия кнопок, открытия
       * калькулятора, ежедневные задачи. На проде это дало «оплаты: живые 27»
       * за 05.10 при двух продажах за всю историю (нашла приёмка, 06.10).
       *
       * 🔴 Дефект был ровно в ОДНОМ месте — в этом. Разрезы по каналам,
       * приложениям и постам считают оплаты НИЖЕ фильтра, пропускающего только
       * три типа события, и их `else` был безопасен; я же поставил счёт итога
       * ВЫШЕ фильтра, где мимо проходят все события журнала. То есть виновато
       * не слово `else`, а `else` ДО фильтра — и мой первый диагноз («тот же
       * дефект и в byChannel») был неверен, проверено мутацией.
       *
       * Ручка воронки дефект не показывала, потому что ПОДМЕНЯЕТ поле перед
       * отдачей (`paid: оплатыЗаОкно` по кассе), а сводка дня брала итог как
       * есть. То есть маска прятала дефект ровно до появления второго читателя.
       *
       * Правило на будущее: денежное поле считается по ИМЕНИ своего события.
       * `else` в таком месте — это «любое новое событие станет оплатой»: класс
       * ошибки, который растёт сам, без чьей-либо правки.
       */
      итог.paid += 1;
      if (ev.meta?.свой === true) итог.paidOurs += 1;
    }

    if (ev.type === "page_view") {
      // 🔴 ВИЗИТЫ СЧИТАЕМ ТАК ЖЕ, КАК ИТОГ — по уникальным сессиям.
      // Замер 30.09.2026: итог давал 167 визитов за 14 дней, а сумма по каналам
      // 519, потому что здесь считался КАЖДЫЙ просмотр страницы. Два разных
      // числа под одним словом в одном ответе: основатель увидел бы 167 или 519
      // в зависимости от того, куда посмотрел.
      const наш = нашЗаход(ev.sid);
      if (ev.sid) {
        const ключ = `${канал}|${ev.sid}`;
        if (!виденныеСессии.has(ключ)) {
          виденныеСессии.add(ключ);
          к.visits += 1;
          if (наш) к.visitsOurs += 1;
        }
      } else {
        к.visits += 1;
        if (наш) к.visitsOurs += 1;
      }
      /*
       * 🔴 «Дошли до цен» — ТОЖЕ УНИКАЛЬНЫЕ СЕССИИ, а не просмотры.
       *
       * До 06.10.2026 рядом в одном объекте жили две единицы: `visits` считал
       * сессии, а `pricing` — каждый просмотр страницы цен. Человек, открывший
       * цены трижды, давал «1 визит и 3 до цен», и доля доходимости вылезала
       * за 100 %. Читающий отчёт об этом не знал.
       */
      if (typeof ev.path === "string" && ev.path.includes("/pricing")) {
        const ключЦен = `цены|${канал}|${ev.sid ?? Math.random()}`;
        if (!виденныеСессии.has(ключЦен)) {
          виденныеСессии.add(ключЦен);
          к.pricing += 1;
          if (наш) к.pricingOurs += 1;
        }
      }
      if (п) {
        // Та же единица, что у канала: уникальные сессии, а не просмотры —
        // и для визитов, и для «дошли до цен».
        if (ev.sid) {
          const ключПостаСессии = `post|${ключПоста}|${ev.sid}`;
          if (!виденныеСессии.has(ключПостаСессии)) {
            виденныеСессии.add(ключПостаСессии);
            п.visits += 1;
            if (наш) п.visitsOurs += 1;
          }
        } else {
          п.visits += 1;
          if (наш) п.visitsOurs += 1;
        }
        if (typeof ev.path === "string" && ev.path.includes("/pricing")) {
          const ключЦенПоста = `цены|post|${ключПоста}|${ev.sid ?? Math.random()}`;
          if (!виденныеСессии.has(ключЦенПоста)) {
            виденныеСессии.add(ключЦенПоста);
            п.pricing += 1;
            if (наш) п.pricingOurs += 1;
          }
        }
      }
      // Чужая метка — только когда канал не распознан. Считаем так же, как
      // канал: визиты по уникальным сессиям, иначе одна вкладка с десятью
      // страницами выглядела бы десятью площадками.
      const чужая = чужаяМетка(канал, ev.path);
      if (чужая) {
        if (!byUnknownTag[чужая]) byUnknownTag[чужая] = { visits: 0, visitsOurs: 0, pricing: 0, pricingOurs: 0 };
        const м = byUnknownTag[чужая];
        if (ev.sid) {
          const ключМетки = `tag|${чужая}|${ev.sid}`;
          if (!виденныеСессии.has(ключМетки)) {
            виденныеСессии.add(ключМетки);
            м.visits += 1;
            if (наш) м.visitsOurs += 1;
          }
        } else {
          м.visits += 1;
          if (наш) м.visitsOurs += 1;
        }
        /*
         * 🔴 НАЙДЕНО ПРИЁМКОЙ 06.10.2026, уже после выкатки. Третий разрез отстал
         * от двух остальных, и отстал в обе стороны:
         *
         * 1) `pricing` считал КАЖДЫЙ просмотр, пока `visits` считал сессии — то
         *    есть внутри одного объекта снова жили две единицы под одним словом.
         *    Это тот самый дефект, который в этот же день починили у byChannel и
         *    byPost («человек открыл цены трижды → 1 визит и 3 до цен», доля
         *    доходимости за 100 %). У чужих меток он остался.
         * 2) `visitsOurs` и `pricingOurs` объявлялись в объекте и НЕ УВЕЛИЧИВАЛИСЬ
         *    НИКОГДА — всегда ноль. Значит наши собственные пробы по чужой метке
         *    шли за живых людей, а живое число считается как разность.
         *
         * Почему это дороже, чем кажется: чужая метка — единственное место, где
         * мы замечаем НОВЫЙ источник трафика (каталог дописывает свой ref сам).
         * Если там наши пробы не отделены, новый источник выглядит настоящим,
         * когда это мы. Ровно так воронка однажды оказалась на 91 % нашей.
         *
         * Найдено не глазами: мутировал ВСЕ пять мест дедупа в этом файле, а не
         * одно. Четыре оказались под надзором, это — нет, и разница назвала
         * слабое звено.
         */
        if (typeof ev.path === "string" && ev.path.includes("/pricing")) {
          const ключЦенМетки = `цены|tag|${чужая}|${ev.sid ?? Math.random()}`;
          if (!виденныеСессии.has(ключЦенМетки)) {
            виденныеСессии.add(ключЦенМетки);
            м.pricing += 1;
            if (наш) м.pricingOurs += 1;
          }
        }
      }
      continue;
    }
    if (
      ev.type !== "checkout_start" &&
      ev.type !== "checkout_success" &&
      ev.type !== СОБЫТИЕ_ОПЛАТА_ПОДТВЕРЖДЕНА
    ) {
      continue;
    }

    const сыройApp = ev.meta?.app;
    const приложение = typeof сыройApp === "string" && сыройApp.trim() ? сыройApp.trim() : "plan";
    if (!byApp[приложение]) {
      byApp[приложение] = { checkoutStart: 0, checkoutStartOurs: 0, paid: 0, paidOurs: 0 };
    }

    if (ev.type === "checkout_start") {
      к.checkoutStart += 1;
      if (п) п.checkoutStart += 1;
      if (ev.sid && нашиСессии.has(ev.sid)) к.checkoutStartOurs += 1;
      byApp[приложение].checkoutStart += 1;
      if (ev.sid && нашиСессии.has(ev.sid)) byApp[приложение].checkoutStartOurs += 1;
    } else if (ev.type === "checkout_success") {
      // 🔴 ЭТО НЕ ОПЛАТА. Здесь `paid` считался по загрузке страницы «спасибо»,
      // и разрез отдавал «direct: paid 3» при нуле подтверждённых оплат в итоге —
      // то есть отвечал ложью на главный вопрос. Открытия страницы возврата
      // теперь живут своим полем, как и в итоге.
      к.thankYouOpened += 1;
    } else if (ev.type === СОБЫТИЕ_ОПЛАТА_ПОДТВЕРЖДЕНА) {
      /*
       * Имя события названо прямо, хотя здесь `else` был БЕЗОПАСЕН: двадцатью
       * строками выше стоит фильтр, пропускающий дальше только три типа. Это
       * проверено, а не предположено — мутация «вернуть else» здесь проходит
       * зелёной именно потому, что чужие события сюда не доходят.
       *
       * Оставляю явное имя, чтобы защита не зависела от фильтра на расстоянии:
       * стоит кому-то расширить фильтр — и `else` снова начнёт считать деньги
       * по нажатиям, как это случилось у итога (он считался ДО фильтра).
       */
      к.paid += 1;
      if (п) п.paid += 1;
      if (ev.meta?.свой === true) {
        к.paidOurs += 1;
        byApp[приложение].paidOurs += 1;
      }
      byApp[приложение].paid += 1;
    }
  }
  // Страницы входа считаются по сессиям, а не по событиям: сначала собираем по
  // каждой сессии её первую страницу и дошла ли она до цен, потом складываем.
  /*
   * 🔴 «ПОПРОБОВАЛ» — первый настоящий шаг там, где покупка не первая.
   *
   * Задание окна 99 через оркестратора, 07.10.2026, и оно верное по сути: у
   * DevHub человек сперва ЧТО-ТО ДЕЛАЕТ (генерация, публикация, сборка из
   * идеи), а до цен доходит много позже. Воронка умела спрашивать только «дошёл
   * до цен» — и на вопрос «попробовал ли кто-нибудь из 21 человека с Product
   * Hunt» ответить было нечем: ни «да», ни «нет», просто нет такой ступени.
   *
   * Считается ТОЛЬКО ЧИСЛО сессий с событием `feature_use`, без имён действий и
   * без содержимого: ответ публичный, и состав чужой работы в него попадать не
   * должен. Единица — сессия, как у визитов, чтобы числа складывались.
   */
  interface Заход {
    канал: string;
    вход: string;
    доЦен: boolean;
    начал: boolean;
    наш: boolean;
    попробовал: boolean;
    /** Ключ поста первого касания, если метка его несла: нужен для byPost. */
    ключПоста: string | null;
    /** Похоже на чтение: событие `engaged` в этой сессии. */
    внимателен: boolean;
  }
  const заходы = new Map<string, Заход>();
  for (const ev of events) {
    if (!ev.sid) continue;
    const сырой = ev.meta?.channel;
    const канал = typeof сырой === "string" && сырой.trim() ? сырой.trim() : "direct";
    let з = заходы.get(ev.sid);
    if (!з) {
      if (ev.type !== "page_view") continue; // сессия без просмотра — входа нет
      // Канал и признак «наше» берутся у ПЕРВОГО просмотра сессии и больше не
      // меняются: именно первое касание отвечает на вопрос «кто привёл».
      з = {
        канал,
        вход: чистыйПуть(ev.path),
        доЦен: false,
        начал: false,
        наш: нашЗаход(ev.sid),
        попробовал: false,
        внимателен: false,
        ключПоста: (() => {
          const сыройПост = ev.meta?.post;
          const пост =
            typeof сыройПост === "string" && сыройПост.trim()
              ? сыройПост.trim().slice(0, 40)
              : null;
          return пост ? `${канал}/${пост}` : null;
        })(),
      };
      заходы.set(ev.sid, з);
    }
    if (ev.type === "page_view" && typeof ev.path === "string" && ev.path.includes("/pricing")) {
      з.доЦен = true;
    }
    if (ev.type === "checkout_start") з.начал = true;
    if (ev.type === "feature_use") з.попробовал = true;
    if (ev.type === "engaged") з.внимателен = true;
  }

  // Денежная ступень по СЕССИОННОЙ единице: сессия, начавшая оплату, засчитывается
  // каналу своего ПЕРВОГО касания. Канал, которого нет в byChannel, здесь появиться
  // не может: у каждой сессии есть события, а byChannel строится по всем событиям.
  /*
   * «Попробовали» начисляется по сессионной единице и каналу ПЕРВОГО касания —
   * тому же, по которому считаются визиты. Иначе число нельзя сопоставить с
   * «дошли до цен» в той же строке, а сравнивают их именно между собой.
   */
  /*
   * Внимание — отдельным проходом, по той же сессионной единице. Считается и в
   * итог, и по каналу: вопрос «какой канал приводит ЧИТАЮЩИХ» дороже вопроса
   * «какой приводит заходы», особенно когда заходов много, а нажатий ноль.
   */
  for (const з of заходы.values()) {
    if (!з.внимателен) continue;
    итог.engaged += 1;
    if (з.наш) итог.engagedOurs += 1;
    const кв = byChannel[з.канал];
    if (кв) {
      кв.engaged += 1;
      if (з.наш) кв.engagedOurs += 1;
    }
  }

  for (const з of заходы.values()) {
    if (!з.попробовал) continue;
    итог.tried += 1;
    if (з.наш) итог.triedOurs += 1;
    const кп = byChannel[з.канал];
    if (кп) {
      кп.tried += 1;
      if (з.наш) кп.triedOurs += 1;
    }
    // И посту первого касания: иначе «какой ролик привёл того, кто попробовал»
    // останется без ответа — а это тот же вопрос, только на шаг точнее.
    const пп = з.ключПоста ? byPost[з.ключПоста] : null;
    if (пп) {
      пп.tried += 1;
      if (з.наш) пп.triedOurs += 1;
    }
  }

  for (const з of заходы.values()) {
    if (!з.начал) continue;
    const к = byChannel[з.канал];
    if (!к) continue;
    к.checkoutStartSessions += 1;
    if (з.наш) к.checkoutStartSessionsOurs += 1;
  }

  const сырыеВходы = new Map<
    string,
    {
      сессий: number;
      сессийНаших: number;
      доЦен: number;
      доЦенНаших: number;
      началиОплату: number;
      попробовали: number;
      попробовалиНаших: number;
      внимание: number;
      вниманиеНаших: number;
    }
  >();
  for (const з of заходы.values()) {
    const ключ = `${з.канал}|${з.вход}`;
    const т = сырыеВходы.get(ключ) ?? пустойВход();
    т.сессий += 1;
    if (з.наш) т.сессийНаших += 1;
    if (з.доЦен) т.доЦен += 1;
    if (з.доЦен && з.наш) т.доЦенНаших += 1;
    if (з.начал) т.началиОплату += 1;
    if (з.попробовал) т.попробовали += 1;
    if (з.попробовал && з.наш) т.попробовалиНаших += 1;
    if (з.внимателен) т.внимание += 1;
    if (з.внимателен && з.наш) т.вниманиеНаших += 1;
    сырыеВходы.set(ключ, т);
  }

  // 🔴 ПРЕДЕЛ НА КАЖДЫЙ КАНАЛ, А НЕ ОДИН НА ВСЕХ — поправка 30.09.2026.
  //
  // Сперва я брал двенадцать самых частых страниц по ВСЕМ каналам. Замер сразу
  // после выкатки показал изъян: у Instagram в разрезе осталась ровно одна
  // страница (`/go`, 16 сессий, 14 до цен), а его мелкие страницы входа
  // провалились в общий хвост вместе с чужими. На вопрос «куда приходят люди с
  // этого канала» такой разрез отвечает только про самый крупный канал.
  //
  // Теперь предел применяется внутри канала, и хвост у каждого канала свой
  // (`<канал>|прочие`). Число ключей по-прежнему ограничено: каналов закрытый
  // список, значит их не больше десятка.
  /*
   * 🔴 ПОПРАВКА 07.10.2026 по слову оркестратора: страница, у которой есть хотя
   * бы ОДНА живая сессия, получает свою строку. «Прочие» остаются только для
   * страниц без живых — то есть для наших проб и пустышек.
   *
   * Повод прямой: сосед спросил живые визиты на `/qspace`, а в разрезе их не
   * было — страница провалилась в «прочие» вместе с чужими, потому что предел
   * брал восемь САМЫХ ЧАСТЫХ. Разрез, который отвечает только про крупное,
   * бесполезен ровно там, где ищут новое: у нового всегда мало сессий.
   *
   * Предел всё равно нужен, и он назван числом: ответ публичный, а число
   * страниц ничем не ограничено сверху. Поэтому живые страницы режутся по
   * ПРЕДЕЛ_ЖИВЫХ_НА_КАНАЛ, и остаток уходит в ОТДЕЛЬНУЮ строку
   * `<канал>|прочие-живые` — не в ту же, что наши и пустые. Смешать их значило
   * бы снова получить ведро, по которому ничего не видно.
   */
  const ПРЕДЕЛ_ЖИВЫХ_НА_КАНАЛ = 100;
  const поКаналам = new Map<
    string,
    Array<
      [
        string,
        {
          сессий: number;
          сессийНаших: number;
          доЦен: number;
          доЦенНаших: number;
          началиОплату: number;
          попробовали: number;
          попробовалиНаших: number;
          внимание: number;
          вниманиеНаших: number;
        },
      ]
    >
  >();
  for (const [ключ, т] of сырыеВходы) {
    const канал = ключ.slice(0, ключ.indexOf("|"));
    const список = поКаналам.get(канал) ?? [];
    список.push([ключ, т]);
    поКаналам.set(канал, список);
  }

  const byEntryPage = Object.create(null) as РазрезВоронки["byEntryPage"];
  const живыхВстрочке = (т: { сессий: number; сессийНаших: number }) => т.сессий - т.сессийНаших;
  for (const [канал, список] of поКаналам) {
    const живые = список
      .filter(([, т]) => живыхВстрочке(т) >= 1)
      .sort((a, b) => живыхВстрочке(b[1]) - живыхВстрочке(a[1]) || b[1].сессий - a[1].сессий);
    const безЖивых = список.filter(([, т]) => живыхВстрочке(т) < 1);

    for (const [ключ, т] of живые.slice(0, ПРЕДЕЛ_ЖИВЫХ_НА_КАНАЛ)) byEntryPage[ключ] = т;

    const сверхПредела = живые.slice(ПРЕДЕЛ_ЖИВЫХ_НА_КАНАЛ);
    if (сверхПредела.length) {
      // Отдельное имя, а не общие «прочие»: иначе живые страницы сверх предела
      // смешались бы с нашими пробами, и строка перестала бы что-либо значить.
      byEntryPage[`${канал}|прочие-живые`] = сверхПредела.reduce(
        (а, [, т]) => ({
          сессий: а.сессий + т.сессий,
          сессийНаших: а.сессийНаших + т.сессийНаших,
          доЦен: а.доЦен + т.доЦен,
          доЦенНаших: а.доЦенНаших + т.доЦенНаших,
          началиОплату: а.началиОплату + т.началиОплату,
          попробовали: а.попробовали + т.попробовали,
          попробовалиНаших: а.попробовалиНаших + т.попробовалиНаших,
          внимание: а.внимание + т.внимание,
          вниманиеНаших: а.вниманиеНаших + т.вниманиеНаших,
        }),
        {
          сессий: 0,
          сессийНаших: 0,
          доЦен: 0,
          доЦенНаших: 0,
          началиОплату: 0,
          попробовали: 0,
          попробовалиНаших: 0,
          внимание: 0,
          вниманиеНаших: 0,
        },
      );
    }

    const хвост = безЖивых;
    if (хвост.length) {
      byEntryPage[`${канал}|прочие`] = хвост.reduce(
        (а, [, т]) => ({
          сессий: а.сессий + т.сессий,
          сессийНаших: а.сессийНаших + т.сессийНаших,
          доЦен: а.доЦен + т.доЦен,
          доЦенНаших: а.доЦенНаших + т.доЦенНаших,
          началиОплату: а.началиОплату + т.началиОплату,
          попробовали: а.попробовали + т.попробовали,
          попробовалиНаших: а.попробовалиНаших + т.попробовалиНаших,
          внимание: а.внимание + т.внимание,
          вниманиеНаших: а.вниманиеНаших + т.вниманиеНаших,
        }),
        {
          сессий: 0,
          сессийНаших: 0,
          доЦен: 0,
          доЦенНаших: 0,
          началиОплату: 0,
          попробовали: 0,
          попробовалиНаших: 0,
          внимание: 0,
          вниманиеНаших: 0,
        },
      );
    }
  }

  // Топ-20 по визитам: ответ публичный, и без ограничения десяток выдуманных
  // меток раздул бы его, а на вопрос «кто нас приводит» отвечают верхние.
  const топМеток = Object.create(null) as РазрезВоронки["byUnknownTag"];
  for (const [метка, числа] of Object.entries(byUnknownTag)
    .sort((a, b) => b[1].visits - a[1].visits)
    .slice(0, 20)) {
    топМеток[метка] = числа;
  }

  /*
   * Разрез собирается ПОСЛЕ цикла, из «источника сессии» и уже посчитанных
   * множеств: визит считается один раз на сессию, то есть той же единицей, что
   * и итог, и числа законно складываются между собой.
   */
  for (const [sid, источник] of источникСессии) {
    if (!byReferrerHost[источник]) {
      byReferrerHost[источник] = { visits: 0, visitsOurs: 0, pricing: 0, pricingOurs: 0 };
    }
    const и2 = byReferrerHost[источник];
    и2.visits += 1;
    const нашаСессия = нашиСессии.has(sid) || пробыОкон.has(sid);
    if (нашаСессия) и2.visitsOurs += 1;
    if (людиЦенИтог.has(sid)) {
      и2.pricing += 1;
      if (нашаСессия) и2.pricingOurs += 1;
    }
  }

  итог.visits += людиИтог.size;
  итог.visitsOurs += людиИтогНаши.size;
  итог.pricing += людиЦенИтог.size;
  итог.pricingOurs += людиЦенИтогНаши.size;

  return {
    byChannel,
    byApp,
    byPost,
    byEntryPage,
    byUnknownTag: топМеток,
    byReferrerHost,
    total: итог,
    totalUnits:
      "визиты и доЦен — уникальные сессии за всё окно (не сумма по каналам: " +
      "визит уникален в пределах канала, и человек с двумя метками попал бы в оба); " +
      "началиОплату и оплаты — события; оплаты подтверждает касса, страница «спасибо» " +
      "живёт отдельным полем thankYouOpened",
  };
}

/**
 * Разбивка НАЧАЛ ОПЛАТЫ по поверхности и по каналу привлечения.
 *
 * Вынесено отдельной чистой функцией, чтобы тест проверял тот самый код,
 * который выполняется в проде, а не его копию, переписанную в тесте: копия
 * расходится с оригиналом молча и создаёт ровно ту ложную уверенность,
 * ради борьбы с которой тест и пишется.
 *
 * `bySource` в сводке считает ВСЕ события, поэтому в нём доминируют
 * page_view и намерение купить тонет. Здесь — только `checkout_start`.
 * Канал приезжает в `meta.channel` из метки `?c=` (lib/products withChannel
 * + components/BuyLink). Ключи нейтральные: дашборд открывают и в EN/KK.
 */
/*
 * Накопители сводок создаются БЕЗ ПРОТОТИПА (`Object.create(null)`), а не как
 * обычные объекты. Ключ здесь свободный: он приходит из поля события, то есть
 * в конечном счёте из адреса, который открыл посторонний.
 *
 * У обычного объекта `byX["constructor"]` возвращает функцию, а
 * `byX["__proto__"]` — прототип. Строка не заводится, число уходит в
 * наследство, и в отчёте её просто НЕТ, а сумма выглядит целой. Соседнее окно
 * замерило это 04.09 на отчёте о выручке: подали три канала — в ответе остался
 * один.
 *
 * Где ключ ЗАКРЫТЫЙ (сверяется со списком), правильнее hasOwnProperty — имя
 * тогда честно отбрасывается. Здесь имя надо сохранить, поэтому без прототипа.
 */
export function summarizeCheckoutStarts(events: Array<Pick<AnalyticsEvent, "type" | "source" | "meta">>): {
  bySource: Record<string, number>;
  byChannel: Record<string, number>;
} {
  const bySource = Object.create(null) as Record<string, number>;
  const byChannel = Object.create(null) as Record<string, number>;
  for (const ev of events) {
    if (ev.type !== "checkout_start") continue;
    const src = ev.source?.trim() || "unknown";
    bySource[src] = (bySource[src] ?? 0) + 1;
    const ch = ev.meta?.channel;
    const chKey = typeof ch === "string" && ch.trim() ? ch.trim() : "direct";
    byChannel[chKey] = (byChannel[chKey] ?? 0) + 1;
  }
  return { bySource, byChannel };
}

/**
 * Возвраты из касс: сколько дошло до оплаты и сколько отвалилось, ПО КАССАМ.
 *
 * Зачем. Отказ мы записываем с 01.09 (`checkout_cancel` с кассой в мете), но не
 * читает его никто: ни сводка, ни панель. Событие пишется в журнал и умирает
 * там — то есть мы платим за сбор данных и не получаем ответа на вопрос «у
 * какой кассы люди отваливаются», а это разные починки: у одной чинят форму
 * карты, у другой — валюту, у третьей вообще ничего не чинят.
 *
 * Считаем ПАРУ, а не отказы отдельно. Голое «41 отказ у PayBox» не значит
 * ничего: у кассы с большим потоком отказов будет больше просто потому, что
 * через неё идут все. Пара «успехи и отказы» сравнима, потому что оба события
 * приходят одинаково — с нашего же экрана возврата.
 *
 * ЧЕГО ЭТА ПАРА НЕ ЗНАЕТ, и это надо читать вместе с числами. Адрес отмены
 * задают только PayBox и PayPal; у LemonSqueezy и Gumroad он не настроен, и их
 * отказ до нашего экрана НЕ ДОХОДИТ вовсе. Ноль отказов у них означает «мы не
 * узнаём», а не «никто не отваливается» — прочитать это как хороший показатель
 * значит выбрать худшую кассу за лучшую.
 */
export function summarizeCheckoutReturns(
  events: Array<Pick<AnalyticsEvent, "type"> & { meta?: Record<string, unknown> }>,
): {
  byProvider: Record<string, { успехов: number; отказов: number }>;
  успехов: number;
  отказов: number;
} {
  const byProvider = Object.create(null) as Record<string, { успехов: number; отказов: number }>;
  let успехов = 0;
  let отказов = 0;

  for (const ev of events) {
    const успех = ev.type === "checkout_success";
    const отказ = ev.type === "checkout_cancel";
    if (!успех && !отказ) continue;
    // Заглушка — не покупка и не отказ: она вообще не про деньги.
    if (ev.meta?.stub === true) continue;

    const p = ev.meta?.provider;
    // Касса неизвестна — своя корзина, а не приписывание к чужой: приписанное
    // число выглядит достовернее, чем оно есть.
    const key = typeof p === "string" && p.trim() ? p.trim() : "unknown";
    const строка = byProvider[key] ?? { успехов: 0, отказов: 0 };
    if (успех) {
      строка.успехов += 1;
      успехов += 1;
    } else {
      строка.отказов += 1;
      отказов += 1;
    }
    byProvider[key] = строка;
  }

  return { byProvider, успехов, отказов };
}

/**
 * Покупки по каналам — и отдельно выручка по тем, у кого сумма известна.
 *
 * Зачем отдельно от `byChannel`. Тот считает ВСЕ события подряд: просмотры,
 * нажатия, заходы в кассу. Канал с большим трафиком и нулём продаж выглядит в
 * нём лучше канала с одной покупкой — то есть по этому числу нельзя решать,
 * куда тратить деньги, а выглядит оно как раз таким числом.
 *
 * Сумма известна не у всех: у возврата PayBox в адрес уходит `ref`, а не сумма.
 * Поэтому выручка и счёт покупок разведены, а рядом едет `сКоторыхИзвестнаСумма`
 * — знаменатель. Без него частичная выручка читается как полная и занижает
 * канал молча, а это ровно тот случай, когда решение принимают по числу.
 */
export function summarizePurchases(
  events: Array<Pick<AnalyticsEvent, "type" | "value"> & { meta?: Record<string, unknown> }>,
): {
  byChannel: Record<string, number>;
  revenueByChannel: Record<string, number>;
  total: number;
  сКоторыхИзвестнаСумма: number;
} {
  const byChannel = Object.create(null) as Record<string, number>;
  const revenueByChannel: Record<string, number> = {};
  let total = 0;
  let сКоторыхИзвестнаСумма = 0;

  for (const ev of events) {
    if (ev.type !== "checkout_success") continue;
    // Заглушка и бесплатный тариф покупкой не считаются: иначе канал,
    // приводящий любителей бесплатного, выглядит как приносящий деньги.
    if (ev.meta?.stub === true) continue;
    const сумма = typeof ev.value === "number" ? ev.value : null;
    if (сумма === 0) continue;

    total += 1;
    const ch = ev.meta?.channel;
    const chKey = typeof ch === "string" && ch.trim() ? ch.trim() : "direct";
    byChannel[chKey] = (byChannel[chKey] ?? 0) + 1;
    if (сумма !== null) {
      сКоторыхИзвестнаСумма += 1;
      revenueByChannel[chKey] = (revenueByChannel[chKey] ?? 0) + сумма;
    }
  }

  return { byChannel, revenueByChannel, total, сКоторыхИзвестнаСумма };
}

