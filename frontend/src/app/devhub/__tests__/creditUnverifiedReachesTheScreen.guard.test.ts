import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Пометка «расход не сверили» доезжает до экрана.
 *
 * Проверка кредита падает ОТКРЫТО: если расход прочитать не удалось, трату
 * разрешают, чтобы не блокировать платящего из-за икоты базы, и помечают
 * ответ полем creditUnverified. Решение защитимое — но только пока человеку
 * об этом говорят.
 *
 * Замер 29.08.2026: сервер ставил пометку на двух платных ручках, витрина не
 * читала её НИ РАЗУ. Правда доезжала до границы API и умирала там.
 *
 * Замер 04–05.09.2026: пометку ставят СЕМЬ ручек, читали её ДВЕ — картинка и
 * видео. Озвучка-в-текст, перевод текста, перевод файлов (поштучный и
 * пакетный) и генерация проекта молчали, хотя списание там такое же. Текст
 * предупреждения жил в двух копиях; теперь он в одной точке, и каждый вызов
 * зовёт её.
 *
 * ПОЧЕМУ СТОРОЖ ПЕРЕПИСАН. Прежняя редакция брала ПЕРВОЕ вхождение слова в
 * файле и требовала `showToast` в шестистах символах после него. Стоило
 * появиться пояснению в комментарии — и первым вхождением стал он, а сторож
 * покраснел на улучшении. Правило, описывающее ГДЕ именно искать, слепнет от
 * любой перестановки; проверять надо СВОЙСТВО.
 */
const WS = path.join(__dirname, "..", "[id]", "page.tsx");

/** Без комментариев: иначе собственные пояснения попадают под свой же шаблон. */
function безКомментариев(s: string): string {
  return s
    .split("\n")
    .filter((l) => {
      const t = l.trim();
      return !t.startsWith("//") && !t.startsWith("*") && !t.startsWith("/*");
    })
    .join("\n");
}

describe("несверенный расход виден человеку", () => {
  const src = fs.readFileSync(WS, "utf8");
  const код = безКомментариев(src);

  it("прибор исправен: файл прочитан и комментарии отброшены", () => {
    // Контроль в обе стороны. Без первого сторож охранял бы пустоту; без
    // второго — не заметил бы, что вырезалка съела весь файл.
    expect(src.length, "файл рабочего окна не прочитался").toBeGreaterThan(10000);
    expect(код.length, "вырезалка комментариев съела код").toBeGreaterThan(5000);
  });

  it("есть ОДНА точка, которая превращает пометку в видимое предупреждение", () => {
    // Одна, а не в каждом вызове: разойдутся копии — человек получит разные
    // объяснения одного события. Дважды за неделю так и было.
    const объявление = код.indexOf("const предупредитьЕслиНеСверили");
    expect(объявление, "точки предупреждения нет — пометке некуда доехать").toBeGreaterThan(0);

    const тело = код.slice(объявление, объявление + 400);
    expect(тело, "точка не читает саму пометку").toContain("creditUnverified");
    expect(тело, "точка ничего не показывает человеку").toContain("showToast");
  });

  it("её зовут все платные пути, а не один", () => {
    // Семь ручек ставят пометку; вызовов должно быть столько же порядка, иначе
    // часть путей снова замолчит. Порог не точное число: место вызова может
    // обслуживать две ручки сразу, и наказывать за это нечестно.
    const вызовы = код.split("предупредитьЕслиНеСверили(").length - 1;
    expect(
      вызовы,
      `точку предупреждения зовут ${вызовы} раз — при семи ручках, ставящих ` +
        "пометку, это значит, что часть платных путей снова молчит",
    ).toBeGreaterThanOrEqual(6);
  });
});

