// QSkyway — snapshot the BAZL/FOCA drone geo-zones over the Zurich twin into
// src/routes/qskyway.airspace.zurich.ts (CityAirspace, polygon cells).
//
// Источник: слой `ch.bazl.einschraenkungen-drohnen` в geo.admin.ch (REST
// identify по конверту квадрата, GeoJSON с геометрией). Замер 16–17.09.2026:
// над квадратом две зоны — CTR ZURICH (3060/3060 клеток) и CTR DUEBENDORF
// (1974/3060), обе «БПЛА тяжелее 250 г запрещены выше 120 м над землёй;
// исключение — по разрешению компетентного органа». Потолок берётся ИЗ ТЕКСТА
// правила (число перед «m above ground»), а не зашивается: сменит BAZL 120 на
// 150 — снимок и сторож свежести это увидят.
//
//   node scripts/fetch-bazl-airspace.mjs [--write]
import fs from "node:fs";
import { stableCellId } from "./lib/airspace-cell-id.mjs";

const TWIN = new URL("../src/routes/qskyway.city.zurich.ts", import.meta.url);
const OUT = new URL("../src/routes/qskyway.airspace.zurich.ts", import.meta.url);
const twinText = fs.readFileSync(TWIN, "utf8");
const bbox = JSON.parse(twinText.match(/"bbox":(\{[^}]+\})/)[1]);

const IDENTIFY = "https://api3.geo.admin.ch/rest/services/api/MapServer/identify";
const params = new URLSearchParams({
  geometry: `${bbox.minLon},${bbox.minLat},${bbox.maxLon},${bbox.maxLat}`,
  geometryType: "esriGeometryEnvelope", layers: "all:ch.bazl.einschraenkungen-drohnen",
  tolerance: "0", sr: "4326", geometryFormat: "geojson", returnGeometry: "true",
});
const r = await fetch(`${IDENTIFY}?${params}`, { headers: { "User-Agent": "AEVION-QSkyway/1.0 (bazl airspace snapshot)" }, signal: AbortSignal.timeout(60_000) });
if (!r.ok) throw new Error(`identify HTTP ${r.status}`);
const j = await r.json();
const ICAO = { "CTR ZURICH": ["LSZH", "Zürich Airport"], "CTR DUEBENDORF": ["LSMD", "Dübendorf Air Base"] };

const cells = (j.results || []).map((f) => {
  const p = f.properties || {};
  const polys = f.geometry.type === "MultiPolygon" ? f.geometry.coordinates : [f.geometry.coordinates];
  const rings = polys.map((poly) => poly[0].map(([lon, lat]) => [+lon.toFixed(7), +lat.toFixed(7)]));
  const pts = rings.flat();
  const m = String(p.zone_restriction_en || "").match(/(\d+)\s*m above ground/);
  if (!m) throw new Error(`зона ${p.zone_name_en}: в тексте правила нет высоты «N m above ground» — потолок не выведен: ${p.zone_restriction_en}`);
  const ceilingM = Number(m[1]);
  const minLat = Math.min(...pts.map((q) => q[1])), minLon = Math.min(...pts.map((q) => q[0]));
  const [icao, name] = ICAO[p.zone_name_en] ?? [null, p.zone_name_en];
  return {
    id: stableCellId({ minLat, minLon, airportIcao: null }, { prefix: "bazl" }),
    minLon, maxLon: Math.max(...pts.map((q) => q[0])), minLat, maxLat: Math.max(...pts.map((q) => q[1])),
    ceilingFt: Math.round(ceilingM / 0.3048), ceilingM,
    airspaceClass: String(p.zone_restriction_id || "CTR"),
    airportIcao: icao, airportName: name, laanc: false, effective: null, rings,
    // Не в подписи, но полезно читателю файла: что именно сказал регулятор.
    note: `${p.zone_name_en}: ${p.zone_restriction_en}${p.zone_message_en ? " / " + p.zone_message_en : ""}`,
  };
});
if (!cells.length) throw new Error("identify вернул ноль зон — снимок не пишем");

const today = new Date().toISOString().slice(0, 10);
const src = {
  source: "BAZL/FOCA UAS geo-zones (ch.bazl.einschraenkungen-drohnen, geo.admin.ch)",
  sourceUrl: "https://map.geo.admin.ch/?layers=ch.bazl.einschraenkungen-drohnen",
  authority: "BAZL / FOCA (Federal Office of Civil Aviation, Switzerland)",
  regime: "EU 2019/947 UAS geo-zones as published by BAZL: inside a CTR, UAS over 250 g are prohibited above 120 m AGL; exemption permits from the competent authority",
  effective: `layer as served by geo.admin.ch on ${today} (BAZL publishes no per-zone effective date)`,
  fetched: today,
  bbox,
  feed: "bazl",
  cells,
};
const header = `// QSkyway — BAZL/FOCA drone geo-zone ceilings over the Zurich twin.
// Generated by scripts/fetch-bazl-airspace.mjs ${today}. Do not edit by hand.
//
// Real regulator-published data (BAZL geo-zones in geo.admin.ch, open REST, no
// key). Each cell is a POLYGON zone (\`rings\`, [lon, lat]); the ceiling is the
// altitude AGL above which UAS over 250 g are prohibited in that zone — parsed
// from the regulator's own rule text, not typed in. This is an EU 2019/947
// small-UAS geo-zone, NOT eVTOL air-taxi certification; QSkyway uses it as the
// authoritative altitude-constraint layer and says so.
/* eslint-disable */
import type { CityAirspace } from "./qskyway.airspace";

export const AIRSPACE_ZURICH: CityAirspace = `;
const body = header + JSON.stringify(src, null, 2) + ";\n";
process.stderr.write(`зон: ${cells.length} — ${cells.map((c) => `${c.airportName} (${c.ceilingM} м, вершин ${c.rings.reduce((s, rr) => s + rr.length, 0)})`).join("; ")}\n`);
if (process.argv.includes("--write")) { fs.writeFileSync(OUT, body); process.stderr.write(`wrote ${OUT.pathname}\n`); }
else process.stdout.write(body.slice(0, 1200) + "\n…\n");
