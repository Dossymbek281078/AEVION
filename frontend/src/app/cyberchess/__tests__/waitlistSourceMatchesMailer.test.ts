import { describe, expect, test } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Метка подписки со страницы запуска шахмат должна попадать в отбор рассылки.
 *
 * Связь тонкая и рвётся молча: страница ставит `source`, а рассылка на сервере
 * отбирает получателей правилом «метка равна cyberchess или начинается с
 * cyberchess-». Поменяй формат на странице (скажем, на «chess-ig») — тесты
 * рассылки останутся зелёными, они проверяют функцию на своих примерах. А
 * человек, подписавшийся в день запуска, письма не получит, и узнаем мы об
 * этом только по тишине.
 *
 * Поэтому сторож стоит здесь, у источника метки, и держит её ФОРМАТ.
 * Правило отбора на сервере: src/lib/launchAnnounce.ts, matchesModule.
 *
 * С ДРУГОЙ СТОРОНЫ ту же связь стережёт tests/launchAnnounce.test.ts в
 * бэкенде: он обходит ВСЕ страницы запуска и спрашивает каждую, признаёт ли
 * её метку реестр модулей. Это не дубль, а вторая половина: тот сторож ловит
 * «метки нет в реестре», этот — «формат метки на странице сломан». Правите
 * одно — посмотрите на второе.
 */
const STRANICA = fs.readFileSync(
  path.join(__dirname, "..", "launch", "page.tsx"),
  "utf-8",
);

describe("метка подписки понятна рассылке", () => {
  test("страница запуска ставит source вида cyberchess или cyberchess-<канал>", () => {
    const m = STRANICA.match(/const source = [^;]+;/);
    expect(m, "строка, задающая source, исчезла со страницы запуска").not.toBeNull();
    const stroka = m![0];
    // Обе ветви — с каналом и без — обязаны начинаться со слага модуля.
    expect(stroka).toContain('`cyberchess-${channel}`');
    expect(stroka).toContain('"cyberchess"');
  });

  test("форма приёма адреса на этой странице действительно есть", () => {
    // Без неё метка не важна: подписаться будет негде.
    expect(STRANICA).toContain("WaitlistCapture");
    expect(STRANICA).toContain("source={source}");
  });
});
