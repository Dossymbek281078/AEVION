import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Выкатка кончается живым адресом, а не служебной записью про DNS.
 *
 * Нашли Ролики 05.10.2026: после УСПЕШНОЙ выкатки человек видел
 * «адрес pages.dev — …aevion.app пока не разрешается, запись DNS ещё не видна».
 * Формально верно — собственный домен действительно подключается минутами. Но в
 * момент, когда всё получилось, человек читает это как поломку. Сайт при этом
 * работает по выданному адресу.
 *
 * То же было в панели результата: сверху стоял собственный домен (которого может
 * ещё не быть), а РАБОТАЮЩИЙ адрес — под ним, шрифтом 11px и без кнопки. То есть
 * в момент успеха первым показывалось то, что не работает.
 *
 * ⚠️ ГРАНИЦА: сторож читает исходник и проверяет ПОРЯДОК и состав разметки. Он не
 * доказывает, как это выглядит на экране — это живой прогон после выкатки.
 */
const ФАЙЛ = join(__dirname, "..", "[id]", "page.tsx");
const src = readFileSync(ФАЙЛ, "utf8");

describe("успех выкатки показывает живой адрес", () => {
  it("прибор исправен: блок результата найден", () => {
    expect(src.includes("pagesResult?.liveUrl"), "блок результата выкатки не найден").toBe(true);
    expect(src.length, "файл не прочитан").toBeGreaterThan(10000);
  });

  it("живой адрес идёт ПЕРЕД собственным доменом, а не после", () => {
    // Порядок и есть суть правки: было наоборот, и человек в момент успеха
    // видел сначала то, что ещё не работает.
    const блок = src.slice(src.indexOf("pagesResult || project?.customDomain"));
    const живой = блок.indexOf("GL.siteLive");
    const домен = блок.indexOf("project.customDomain}");
    expect(живой, "живого адреса нет в блоке результата").toBeGreaterThan(0);
    expect(домен, "собственного домена нет в блоке").toBeGreaterThan(0);
    expect(живой, "собственный домен снова стоит впереди работающего адреса").toBeLessThan(домен);
  });

  it("условие показа живого адреса ничем не отключено", () => {
    /*
     * Нужно потому, что проверка ПОЗИЦИИ текста слепа к выключателю: мутация
     * «{(false && pagesResult?.liveUrl ...» убрала блок с экрана, а порядок
     * строк в исходнике не изменился, и тест остался зелёным. Поймал мутатором.
     *
     * Честная граница сохраняется: полностью это проверяется только рендером,
     * которого в этом стороже нет. Здесь — что условие опирается на адрес и не
     * содержит заведомо ложного.
     */
    const i = src.indexOf("{(pagesResult?.liveUrl");
    expect(i, "условие показа живого адреса не найдено — его подменили").toBeGreaterThan(0);
    const условие = src.slice(i, src.indexOf(") && (", i) + 6);
    expect(условие, "условие опирается не на адрес").toContain("pagesResult?.liveUrl");
    expect(условие, "потерян запасной адрес pages.dev").toContain("pagesResult?.pagesUrl");
    expect(условие, "потерян адрес из проекта").toContain("project?.deployUrl");
    expect(/false/.test(условие), "в условии показа появился выключатель false").toBe(false);
    expect(/true/.test(условие), "условие подменено на всегда-истину").toBe(false);
  });

  it("рядом с адресом есть кнопка «Открыть»", () => {
    // Выкатка должна кончаться живым сайтом, а не строкой текста.
    expect(src, "кнопки открытия нет").toContain("GL.openSite");
  });

  it("служебная запись про DNS больше не главная", () => {
    // Старый текст целиком: он и читался как отказ.
    expect(
      src.includes("пока не разрешается (запись DNS ещё не видна)"),
      "служебный текст про DNS вернулся в сообщение об успехе",
    ).toBe(false);
    // А спокойная формулировка — на месте.
    expect(src, "нет спокойной формулировки про домен").toContain("GL.domainSoon");
  });

  it("сообщение об успехе называет, что сайт в интернете", () => {
    const i = src.indexOf("d.domainReady && d.domain");
    expect(i, "ветка сообщения об успехе не найдена").toBeGreaterThan(0);
    expect(src.slice(i, i + 900), "в сообщении нет «сайт в интернете»").toContain("GL.siteLive");
  });

  it("живой адрес НЕ мельче домена — иначе вернётся исходная жалоба", () => {
    /*
     * 🔴 Дописано приёмкой 05.10.2026. Сторож проверял порядок, условие показа
     * и кнопку — но НЕ размер, а именно размер и был исходной жалобой: живой
     * адрес стоял «мелким 11px и без кнопки». Проверено мутацией: уменьшил
     * подпись живого адреса с 12/800 до 11/400 — все проверки остались
     * ЗЕЛЁНЫМИ. То есть половину дефекта можно было вернуть молча.
     *
     * Проверяем связь, а не абсолютное число: живой адрес обязан быть не
     * мельче строки про собственный домен. Так правка размеров по всей
     * странице не покраснеет зря, а перестановка «кто крупнее» — покраснеет.
     */
    const блок = src.indexOf('{(pagesResult?.liveUrl');
    expect(блок, "блок живого адреса не найден — сторож проверяет пустоту").toBeGreaterThan(0);
    /*
     * Границу ставим по НАЧАЛУ строки домена `{project?.customDomain && (`.
     * Две неверные границы я уже проверил на себе, прежде чем отдавать:
     *   по слову `customDomain` — оно есть уже в первой строке блока
     *     (marginBottom: customDomain ? 6 : 0), срез выходил пустым;
     *   по печатаемому `https://{project.customDomain}` — тогда «после»
     *     попадала ЧУЖАЯ кнопка 14px, и проверка врала «домен крупнее».
     * Замер по факту: живой адрес 12px (подпись, ссылка, кнопка), строка
     * домена 11px. То есть свойство выполняется, и сторож это подтверждает,
     * а не подгоняется под ответ.
     */
    const строкаДомена = src.indexOf("{project?.customDomain && (", блок);
    expect(строкаДомена, "строка собственного домена не найдена").toBeGreaterThan(блок);

    const размеры = (кусок: string) =>
      [...кусок.matchAll(/fontSize:\s*(\d+)/g)].map((m) => Number(m[1]));
    const живой = размеры(src.slice(блок, строкаДомена));
    const домен = размеры(src.slice(строкаДомена, строкаДомена + 220));

    expect(живой.length, "у живого адреса не задан размер").toBeGreaterThan(0);
    expect(домен.length, "у строки домена не задан размер").toBeGreaterThan(0);
    expect(
      Math.min(...живой),
      `живой адрес (${Math.min(...живой)}px) мельче домена (${Math.max(...домен)}px) — это и была жалоба`,
    // СТРОГО больше, а не «не мельче»: требование звучит «крупнее». С нестрогим
    // сравнением мутация «живой адрес снова 11px» проходила — 11 >= 11, то есть
    // половина исходной жалобы возвращалась молча. Проверено мутацией дважды.
    ).toBeGreaterThan(Math.max(...домен));
  });

  it("все три текста переведены на три языка", () => {
    for (const ключ of ["siteLive", "openSite", "domainSoon"]) {
      expect(
        (src.match(new RegExp(ключ + ': "', "g")) ?? []).length,
        `ключ ${ключ} не в трёх словарях — язык молча откатится`,
      ).toBe(3);
    }
    expect(src).toContain("Сайт в интернете");
    expect(src).toContain("Your site is live");
    expect(src).toContain("Сайт интернетте");
  });
});
