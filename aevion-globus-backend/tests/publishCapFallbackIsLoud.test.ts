import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stripComments } from "./helpers/sourceCode";

/**
 * Запасной счёт публикаций не уходит в тишину.
 *
 * Предел бесплатного тарифа (5 публикаций) считается запросом к базе, а при
 * её недоступности — картой в памяти процесса. Устройство верное: ронять
 * публикацию из-за сбоя базы нельзя.
 *
 * Но память после выкатки ПУСТА. Значит при сбое базы счёт начинается с нуля,
 * и предел бесплатного тарифа тихо снимается — снаружи это неотличимо от
 * человека, который ещё ничего не публиковал.
 *
 * Найдено 30.08.2026 проверкой соседей: чинил суточный лимит ИИ в
 * `constitutionGate`, спросил, нет ли рядом однотипных — и нашёл этот. Сам по
 * себе он не падает и не краснеет.
 *
 * Сторож требует ВИДИМОСТИ, а не отказа: поведение осталось прежним.
 */

const SRC = readFileSync(
  join(__dirname, "..", "src", "routes", "planetConstitution.ts"),
  "utf8",
);

/** Тело функции счёта, а не весь файл: иначе сторож зеленел бы от чужой строки. */
function countBody(): string {
  const start = SRC.indexOf("async function countOwnerArtifacts(");
  expect(start, "функция счёта публикаций не найдена").toBeGreaterThan(-1);
  const end = SRC.indexOf("export const planetConstitutionRouter", start);
  expect(end, "конец блока не найден — граница сторожа сломана").toBeGreaterThan(start);
  return stripComments(SRC.slice(start, end));
}

const BODY = countBody();

describe("переход на счёт в памяти не молчит", () => {
  test("контроль: разобрана та функция и в ней есть оба пути", () => {
    expect(BODY.includes("planet_constitution_artifacts"), "разобрана не та функция").toBe(true);
    expect(BODY.includes("memOwnerCounts"), "запасного пути нет — проверять нечего").toBe(true);
  });

  test("у ветки отказа есть запись в журнал", () => {
    expect(
      BODY.includes("console.warn") || BODY.includes("console.error"),
      "счёт публикаций молча берётся из памяти: предел бесплатного тарифа " +
        "снимется при сбое базы, и об этом никто не узнает",
    ).toBe(true);
  });

  test("в записи сказано, ЧТО произошло, а не просто «ошибка»", () => {
    // Мутация «опустошить текст» первую редакцию не краснила: сторож требовал
    // наличия вызова, а не содержания. След без указания на предел бесполезен —
    // читающий журнал не поймёт, что именно перестало действовать.
    for (const part of ["публикаций", "предел"]) {
      expect(BODY.includes(part), `в записи нет слова «${part}» — след не объясняет`).toBe(true);
    }
  });

  test("поведение НЕ изменилось: запасной путь остался", () => {
    // Сторож стережёт видимость, а не отказ. Ронять публикацию из-за сбоя
    // базы нельзя — пусть смена направления будет осознанным решением.
    expect(BODY.includes("memOwnerCounts.get(email) ?? 0"), "запасной путь убран — это смена поведения").toBe(true);
  });
});
