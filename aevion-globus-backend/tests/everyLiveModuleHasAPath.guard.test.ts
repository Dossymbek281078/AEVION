import { describe, test, expect } from "vitest";
import { projects as PROJECTS } from "../src/data/projects";
import { MODULE_RUNTIME, getModuleRuntime } from "../src/data/moduleRuntime";

/**
 * У каждого приложения реестра есть ПУТЬ, по которому его открывает человек.
 *
 * Повод 09.10.2026. `qmelanin`, `qrenew` и `qreal` отсутствовали в
 * `MODULE_RUNTIME` ВОВСЕ и молча падали в `DEFAULT_META`: `/api/globus/projects`
 * отдавал им `primaryPath: null` и `tier: "portal_only"`. Снаружи это читается
 * как «приложения нет», хотя все три страницы на проде живые (замер: 200,
 * собственный заголовок, содержимое, кнопка покупки, признаков «не найдено»
 * нет).
 *
 * Промах был невидим не по невнимательности: умолчание отвечает за
 * пропущенных МОЛЧА, а шапка карты обещала «полное покрытие 39 узлов» — в
 * реестре их стало 45. Список перестал поспевать, и сказать об этом было
 * некому.
 *
 * 🔴 Знаменатель здесь обязателен: без него проверка «у всех живых есть путь»
 * останется зелёной и тогда, когда живых в выборке окажется ноль.
 */

const ЖИВЫЕ = PROJECTS.filter((p) => p.status === "live");

describe("у каждого живого приложения есть путь", () => {
  test("знаменатель: реестр не усох", () => {
    // Если приложений внезапно стало меньше — проверка ниже начнёт охранять
    // меньшее, оставаясь зелёной. Порог меняется ОСОЗНАННО, вместе с реестром.
    expect(PROJECTS.length, "в реестре стало меньше приложений, чем было").toBeGreaterThanOrEqual(45);
    expect(ЖИВЫЕ.length, "живых приложений стало меньше — это не повод зеленеть").toBeGreaterThanOrEqual(38);
  });

  test("🔴 каждое живое приложение имеет primaryPath", () => {
    const без = ЖИВЫЕ.filter((p) => !getModuleRuntime(p.id).primaryPath);
    expect(
      без.map((p) => p.id),
      `живые приложения без пути — снаружи их «нет»: ${без.map((p) => p.id).join(", ")}`,
    ).toEqual([]);
  });

  test("🔴 ни одно живое приложение не падает в умолчание", () => {
    // Отдельный вопрос от предыдущего: запись может ОТСУТСТВОВАТЬ в карте и
    // получить путь только потому, что умолчание однажды перестанет быть
    // пустым. Тогда первый же тест позеленеет, а карта останется дырявой.
    const нет = ЖИВЫЕ.filter((p) => !(p.id in MODULE_RUNTIME));
    expect(
      нет.map((p) => p.id),
      `живых приложений нет в MODULE_RUNTIME: ${нет.map((p) => p.id).join(", ")}`,
    ).toEqual([]);
  });

  test("путь начинается со слэша и не ведёт на портал целиком", () => {
    const плохие = ЖИВЫЕ.map((p) => [p.id, getModuleRuntime(p.id).primaryPath] as const)
      .filter(([id, путь]) => id !== "globus" && (!путь || !путь.startsWith("/") || путь === "/"));
    expect(плохие, `путь задан, но он не адрес приложения: ${JSON.stringify(плохие)}`).toEqual([]);
  });

  test("охват назван прямо: проверяются ЖИВЫЕ, не все 45", () => {
    // 🔴 Без этой строки знаменатель читается сильнее, чем он есть. Проверка
    // покрывает статус `live`; у статуса `mvp` путь не требуется, и мутация
    // «убрать mvp-модуль из карты» ею НЕ ловится — это замысел, а не дыра.
    // Пример на 09.10: страница `/qreal` на проде живая и отвечает 200, но в
    // реестре у него `status: "mvp"`. Расхождение названо оркестратору:
    // менять статус — продуктовое решение, не моё.
    const mvp = PROJECTS.filter((p) => p.status !== "live");
    expect(ЖИВЫЕ.length + mvp.length).toBe(PROJECTS.length);
    expect(mvp.length, "модулей вне охвата стало больше — проверка покрывает меньше").toBeLessThanOrEqual(7);
  });

  test("контроль: выдуманное приложение путь НЕ получает", () => {
    // Без этого контроля проверка прошла бы и при умолчании, раздающем путь
    // кому угодно, — то есть перестала бы что-либо значить.
    expect(getModuleRuntime("такого-модуля-нет").primaryPath).toBeNull();
  });
});
