import { describe, it, expect } from "vitest";
import { readFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { CHANGELOG } from "../src/data/changelog";

/**
 * Сторож: адрес, названный в публичном журнале изменений, обязан чем-то
 * обслуживаться.
 *
 * ЗАЧЕМ. `/api/pricing/changelog` отдаёт 38 записей, и страница
 * `aevion.app/pricing/changelog` их показывает — проверено живым запросом
 * 29.08.2026, обе отвечают 200. То есть это НЕ внутренний файл, а витрина:
 * каждая запись — публичное обещание, что нечто существует.
 *
 * Обещания стареют молча. В тот же день там нашлось обещание, ставшее
 * ложным: запись 22.07 сообщала покупателю подорожание до $24/$39/$89,
 * которое 13.08 отменили, — человек читал её рядом с ценником на $19.
 *
 * ЧТО ЛОВИМ. Только проверяемое механически: упомянутый АДРЕС, за которым
 * ничего нет. Смысловые обещания («стало быстрее») сторож не судит и не
 * должен: он бы тогда краснел на формулировках.
 *
 * ЧТО СЧИТАЕТСЯ ОБСЛУЖИВАНИЕМ. Одно из двух, потому что журнал пишут
 * по-разному: страница сайта (каталог с page.tsx) ИЛИ маршрут бэкенда
 * (строка пути в исходниках роутеров). Записи ссылаются на второе в
 * укороченном виде — «POST /affiliate/apply» вместо
 * `/api/pricing/affiliate/apply`, и требовать полный путь значило бы
 * заставить автора журнала писать не так, как ему удобно.
 *
 * Замер при написании: 38 записей, 22 адреса, необслуживаемых 0. Сторож
 * заводится на чистом состоянии — иначе он краснел бы с первого дня, и его
 * бы отключили.
 */
const APP = join(__dirname, "..", "..", "frontend", "src", "app");
const BACKEND_SRC = join(__dirname, "..", "src");

/** Все адреса, названные в журнале. Динамические сегменты пропускаем. */
export function путиИзЖурнала(): string[] {
  const out = new Set<string>();
  for (const c of CHANGELOG as Array<{ title?: string; body?: string }>) {
    const текст = `${c.title ?? ""} ${c.body ?? ""}`;
    for (const m of текст.matchAll(/(?<![\w])(\/[a-z][a-z0-9/_-]{2,})/g)) {
      const p = m[1];
      if (p.includes("[") || p.endsWith("/")) continue;
      out.add(p);
    }
  }
  return [...out].sort();
}

/** Страница сайта: каталог с page.tsx, буквально, без подстановки [id]. */
function естьСтраница(p: string): boolean {
  let d = APP;
  for (const s of p.split("/").filter(Boolean)) {
    d = join(d, s);
    if (!existsSync(d) || !statSync(d).isDirectory()) return false;
  }
  return existsSync(join(d, "page.tsx")) || existsSync(join(d, "page.ts"));
}

/**
 * Маршрут бэкенда. Роутеры монтируются с префиксом, поэтому путь из журнала
 * почти никогда не совпадает со строкой в `router.get(...)`: ручка
 * `/api/pricing/events/by-variant` зарегистрирована как `"/by-variant"`.
 * Полный путь при этом стоит в комментарии над ней — у нас так принято.
 *
 * ⚠️ Известная граница: путь, упомянутый ТОЛЬКО в комментарии, сторож
 * засчитает. Он отвечает на вопрос «мы вообще такое обслуживаем», а не
 * «маршрут смонтирован» — на второй честно отвечает лишь проба живого
 * сервера, и она не дело статического сторожа.
 */
function естьМаршрут(p: string, файлы: string[]): boolean {
  const хвост = "/" + p.split("/").filter(Boolean).slice(-2).join("/");
  return файлы.some((f) => {
    const t = readFileSync(f, "utf8");
    return t.includes(p) || t.includes(`"${хвост}"`);
  });
}

function исходники(dir: string, out: string[] = []): string[] {
  for (const n of readdirSync(dir)) {
    if (n === "node_modules") continue;
    const full = join(dir, n);
    if (statSync(full).isDirectory()) исходники(full, out);
    // Сам журнал из списка исключён: иначе любой адрес «находился» бы в нём
    // же, и сторож подтверждал бы сам себя (feedback_check_matches_its_own_observer).
    // Исключение поставлено ПО РАССУЖДЕНИЮ, а не по пойманному дефекту: тот
    // прогон, который я принял за «мутация не поймана», на деле падал —
    // MSYS_NO_PATHCONV отключил преобразование пути и у самого инструмента.
    // Проверено после починки запуска: обе мутации ловятся.
    else if (n.endsWith(".ts") && !n.includes(".test.") && n !== "changelog.ts") out.push(full);
  }
  return out;
}

describe("публичный журнал изменений не обещает несуществующих адресов", () => {
  it("каждый адрес обслуживается страницей или маршрутом", () => {
    const пути = путиИзЖурнала();
    // Знаменатель называем вслух: «ноль нарушений» без него читается как
    // «проверять было нечего».
    expect(пути.length).toBeGreaterThan(10);

    const файлы = исходники(BACKEND_SRC);
    const мёртвые = пути.filter((p) => !естьСтраница(p) && !естьМаршрут(p, файлы));

    expect(
      мёртвые,
      `Журнал обещает адреса, за которыми ничего нет. Он публичный: его отдаёт\n` +
        `GET /api/pricing/changelog и показывает страница /pricing/changelog.\n` +
        `Адреса: ${мёртвые.join(", ")}\n` +
        `Либо адрес исчез — тогда чинить продукт или править запись, либо он\n` +
        `назван иначе, чем в коде, — тогда привести запись к тому, что есть.`,
    ).toEqual([]);
  });

  it("проверка умеет находить мёртвый адрес", () => {
    // Отрицательный контроль: без него «ноль нарушений» не отличить от
    // сломанного поиска. Проверяем ОБЕ ветки — и страницу, и маршрут.
    const файлы = исходники(BACKEND_SRC);
    expect(естьСтраница("/pricing")).toBe(true);
    expect(естьСтраница("/takoy-stranicy-net-nikogda")).toBe(false);
    expect(естьМаршрут("/takogo-marshruta-net", файлы)).toBe(false);
  });
});
