import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Заголовок записи в реестре обязан нести имя модуля.
 *
 * ЗАЧЕМ. Замер на проде 04.09.2026: реестр QRight ищет по заголовку и описанию,
 * вида объекта не видит. Поиск «UASFM» находит нашу запись, «qskyway» и
 * «airspace» — ноль. То есть зритель демонстрации, который только что работал с
 * модулем, ищет его имя и не находит ничего.
 *
 * ГРАНИЦА, названная прямо: это проверка ПО ИСХОДНИКУ, а не по ответу. Заголовок
 * строится внутри ручки внесения, которая пишет в базу; в ответе его нет вовсе,
 * а без базы ручка до этого места не доходит. Наблюдать нечем — поэтому
 * закрепляем шаблон, а не результат. Появится заголовок в ответе — проверку
 * надо будет переписать на него, она сильнее.
 */
const NL = String.fromCharCode(10);

describe("запись в реестре находится по имени модуля", () => {
  const src = readFileSync(join(__dirname, "..", "src", "routes", "qskyway.ts"), "utf8");

  test("шаблон заголовка содержит имя модуля", () => {
    const line = src.split(NL).find((l) => l.includes("const title = "));
    expect(line, "строка построения заголовка не найдена - проверка ослепла").toBeTruthy();
    expect(String(line), "имени модуля нет в заголовке: запись не найдётся поиском").toContain("QSkyway");
  });

  test("заголовок по-прежнему называет источник и город", () => {
    // Контроль обратной стороны: добавив имя модуля, легко потерять то, по чему
    // запись находили раньше. Поиск «UASFM» должен продолжать работать.
    const line = String(src.split(NL).find((l) => l.includes("const title = ")));
    expect(line).toContain("src.source");
    expect(line).toContain("resolved.city.city");
  });
});
