/**
 * Один вход в ИИ для модулей, которые раньше звали поставщика напрямую.
 *
 * ПОВОД, 07.10.2026. Четыре места звали Anthropic своим кодом: healthai и
 * qgood — первым в собственной цепочке, QBuild (`lib/build/ai.ts`) и
 * agentRuntime (`services/agentRuntime/anthropicClient.ts`) — вообще без
 * запаса. При этом на счёте Anthropic $8.93 и консоль пытается автопополнить
 * $20, у OpenAI деньги кончились (проверка провайдеров на проде отвечает
 * «КЛЮЧ ГОДЕН, НО ДЕНЕГ НЕТ»), а у Gemini они есть.
 *
 * Своя цепочка в каждом модуле — это ещё и четыре места, где решение «уйти с
 * поставщика» принимается заново. Общий реестр уже умеет перебор при отказе,
 * считает стоимость и пишет переключения в журнал; этим модулям не хватало
 * только входа в него.
 *
 * ПОРЯДОК НАМЕРЕННО НЕ ТОТ, ЧТО В РЕЕСТРЕ. Массив провайдеров начинается с
 * `anthropic`, то есть при первой осечке звонок уходил бы именно в платный и
 * почти пустой счёт. Здесь порядок задан на вызов: сперва тот, у кого есть
 * деньги, платный — последним.
 */

import { callProvider, getProviders, type ПорядокЗапаса } from "../services/qcoreai/providers";

/** Gemini → OpenAI → Anthropic: платный и почти пустой счёт идёт последним. */
export const ПОРЯДОК_ДЕШЕВЛЕ_СНАЧАЛА: ПорядокЗапаса = ["gemini", "openai", "anthropic"];

export interface ЗапросКИИ {
  /** Системная роль: кем модель должна себя считать. Необязательна. */
  роль?: string;
  /** Вопрос человека или задание модуля. */
  вопрос: string;
  /** Предел длины ответа. Без него поставщик решает сам. */
  максТокенов?: number;
  /** 0 — предсказуемо, 1 — свободно. По умолчанию 0.3: это рабочие ответы. */
  температура?: number;
  /**
   * Ответ должен быть СТРУКТУРНЫМ (JSON и подобное).
   *
   * Обрыв свободного текста — неполный, но читаемый ответ; обрыв JSON делает
   * ответ неразбираемым целиком. Поэтому такие вызовы просят модель не
   * размышлять независимо от размера бюджета.
   */
  структурныйОтвет?: boolean;
}

export interface ОтветИИ {
  текст: string;
  /** Кто в итоге ответил: нужен и в журнале, и в приёмке. */
  поставщик: string;
  /** Пришлось ли перескакивать — видно, что запас сработал. */
  переключение: boolean;
  /** Кого пробовали до ответившего: нужно модулям, которые это показывают. */
  перебор: string[];
  /** Модель, которой ответили: уходит в ответ ручек как было. */
  модель: string;
}

/**
 * Спросить ИИ с запасом. Бросает, только если отказали ВСЕ по порядку.
 *
 * Пустой ответ считается отказом внутри реестра (там это уже сделано), так
 * что сюда «ok, но пусто» не доходит: модулю не придётся отличать молчание от
 * ответа.
 */
export async function спроситьИИ(запрос: ЗапросКИИ): Promise<ОтветИИ> {
  const сообщения = [
    ...(запрос.роль ? [{ role: "system" as const, content: запрос.роль }] : []),
    { role: "user" as const, content: запрос.вопрос },
  ];
  // Первым берём того из порядка, кто НАСТРОЕН: иначе первый же вызов
  // потратится на отказ «нет ключа», и запас сработает на пустом месте.
  const настроенные = ПОРЯДОК_ДЕШЕВЛЕ_СНАЧАЛА.map((id) => getProviders().find((p) => p.id === id)).filter(
    (p): p is NonNullable<typeof p> => Boolean(p?.configured),
  );
  if (!настроенные.length) throw new Error("Ни один поставщик ИИ не настроен");
  const первый = настроенные[0];
  const res = await callProvider(
    первый.id,
    сообщения,
    // Модель НЕ пустая: пустая строка уходит прямо в запрос к поставщику.
    первый.defaultModel,
    запрос.температура ?? 0.3,
    undefined,
    запрос.максТокенов,
    undefined,
    ПОРЯДОК_ДЕШЕВЛЕ_СНАЧАЛА,
    запрос.структурныйОтвет,
  );
  return {
    текст: String(res.reply ?? ""),
    поставщик: res.providerUsed ?? первый.id,
    переключение: Boolean(res.failedOver),
    перебор: res.failedOver?.tried ?? [],
    модель: String(res.model ?? ""),
  };
}
