/**
 * Отметка сборки САЙТА. Значения здесь — заглушки; настоящие подставляет
 * scripts/vercel-deploy.sh перед загрузкой и возвращает файл обратно после.
 *
 * ЗАЧЕМ ФАЙЛ, А НЕ ПЕРЕМЕННАЯ ОКРУЖЕНИЯ. Проверено выкаткой 18.08.2026:
 * `vercel deploy` из рабочего каталога НЕ подставляет VERCEL_GIT_COMMIT_SHA —
 * /api/health честно ответил "unknown". Переменные проекта не годятся по другой
 * причине, и она дороже: они живут в проекте, а не в сборке, и переживают чужую
 * выкатку. На Railway это уже случилось — /health уверенно называл коммит,
 * которого на проде не было.
 *
 * Поэтому отметка едет ВНУТРИ артефакта, как build-info.json у бэкенда.
 * Заглушки остаются в git намеренно: сборка не должна падать оттого, что кто-то
 * собрал сайт не через скрипт, — она должна честно сказать "unknown".
 */
export type BuildStamp = {
  commit: string;
  branch: string;
  builtAt: string | null;
};

/**
 * Тип объявлен ЯВНО и без `as const`. С `as const` типы сужаются до литералов,
 * и сравнение `BUILD_STAMP.commit !== "unknown"` в /api/health становится
 * ошибкой типов ровно тогда, когда отметка ЗАПОЛНЕНА, — то есть сборка падает
 * только на настоящей выкатке и проходит на заглушке. Проверено 18.08.2026:
 * так и вышло, выкатка упала на сборке (прод при этом не пострадал —
 * Vercel оставляет прежнюю версию, пока новая не собралась).
 */
export const BUILD_STAMP: BuildStamp = {
  commit: "unknown",
  branch: "unknown",
  builtAt: null,
};
