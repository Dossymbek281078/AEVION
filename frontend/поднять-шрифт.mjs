// Поднять инлайновые размеры шрифта на странице, сохраняя порядок.
//   node поднять-шрифт.mjs <файл> [--применить]
//
// Замер 01.10.2026 на экране 390x844: продающий текст наших страниц набран
// 11–13 px (на /bureau — 32 узла из 33, на /pricing — 119 из 127). Это не
// сноски, а карточки «что мы делаем» и состав тарифов.
//
// Перевод сделан так, чтобы РАЗНИЦА между уровнями осталась: что было мельче,
// остаётся мельче. Числа крупнее 14 не трогаются — там заголовки, они и так
// в порядке.
import { readFileSync, writeFileSync } from "node:fs";

const КАРТА = new Map([
  ["10", "13"], ["10.5", "13"],   // совсем мелкие подписи остаются подписями
  ["11", "15"], ["11.5", "15"],
  ["12", "15"], ["12.5", "15"],
  ["13", "15.5"], ["13.5", "15.5"],
  ["14", "16"], ["14.5", "16"],
]);

const файл = process.argv[2];
const применить = process.argv.includes("--применить");
if (!файл) { console.error("нужен путь к файлу"); process.exit(2); }

const было = readFileSync(файл, "utf8");
const счёт = new Map();
const стало = было.replace(/fontSize: (\d+(?:\.\d+)?)/g, (всё, число) => {
  const новое = КАРТА.get(число);
  if (!новое) return всё;
  счёт.set(число + "→" + новое, (счёт.get(число + "→" + новое) ?? 0) + 1);
  return "fontSize: " + новое;
});

const строки = [...счёт.entries()].sort().map(([k, v]) => `${k} (${v})`).join(", ");
console.log(файл);
console.log("  замен:", [...счёт.values()].reduce((a, b) => a + b, 0), "|", строки || "нечего менять");
const осталось = [...стало.matchAll(/fontSize: (\d+(?:\.\d+)?)/g)].map((m) => Number(m[1])).filter((x) => x < 15);
console.log("  останется мельче 15:", осталось.length, осталось.length ? "→ " + [...new Set(осталось)].sort((a, b) => a - b).join(", ") : "");
if (применить) {
  writeFileSync(файл, стало);
  console.log("  ЗАПИСАНО");
} else {
  console.log("  (проба, файл не тронут — добавьте --применить)");
}
