import type { MetadataRoute } from "next";

const BASE_URL = process.env.NEXT_PUBLIC_SITE_URL?.replace(/\/+$/, "") || "https://aevion.app";

/**
 * Единственный источник правды о том, что закрыто от поисковика.
 *
 * Экспортируется, потому что этот же список нужен карте сайта: до 21.08.2026
 * она собиралась обходом каталогов и ничего про запреты не знала, поэтому
 * ОТДАВАЛА поисковику 19 адресов, которые здесь же запрещены — 9 админских,
 * 8 в админке QPayNet, личный кабинет и админку конституции. Google на такое
 * отвечает документированно: адрес попадает в выдачу БЕЗ содержимого, то есть
 * ссылка на админку видна, а вместо описания стоит «заблокировано в
 * robots.txt». Плюс постоянная ошибка в Search Console.
 *
 * Второй список заводить нельзя: разъедется — и мы снова будем звать
 * поисковика туда, куда сами его не пускаем.
 */
export const DISALLOWED_PATHS = [
  "/admin/",
  "/api/",
  "/api-backend/",
  "/pay/",
  "/r/",
  "/account/",
  "/_next/",
  "/qpaynet/admin/",
  "/qpaynet/admin",
  "/constitution/admin",
  "/constitution/admin/",

  // Служебные экраны: показываются ПОСЛЕ действия и вне своего пути
  // бессмысленны. Найдены 30.08.2026 тем же приёмом, что и пятёрка выше:
  // карта сайта строится обходом каталогов и не знает про canonical, поэтому
  // подавала в поиск страницы, которые сами отдают canonical родителя —
  // то есть говорят «я копия». Карта звала, страница прогоняла.
  "/auth/success",
  "/pricing/admin",
  "/pricing/checkout/success",
  "/pricing/checkout/cancel",

  // Короткие адреса каналов (/tt, /ig, /yt и их английские пары). Это ВХОДЫ
  // для человека из подписи под роликом, а не страницы: они только
  // перенаправляют и в выдаче соревновались бы с той посадочной, на которую
  // ведут.
  //
  // Список общий с картой сайта (sitemap.ts фильтрует по нему же), и это не
  // случайность: 28.08.2026 у страниц уже стоял robots noindex, а в карту они
  // всё равно попали — пять адресов, о которых карта говорила «индексируй», а
  // сама страница «нет». Запрет в ОДНОМ месте убирает расхождение сразу с двух
  // сторон.
  "/tt",
  "/ig",
  "/yt",
  // dz/vk/tg заведены 29.08.2026 — те же короткие входы, та же причина.
  // Без этой строки они попадают в карту сайта: проверено на проде,
  // dz/vk/tg были там по одной записи, а tt/ig/yt отсутствовали.
  "/dz",
  "/vk",
  "/tg",
  // th/fb/x/qr заведены 30.08.2026. Замер: каталог знает ДЕСЯТЬ меток каналов,
  // а коротких входов было шесть. Метки работали (проверено на проде: /go?c=th
  // и остальные три доводят метку до кассы, 4 кассы из 4), но /th, /fb, /x,
  // /qr отвечали 404 — то есть в подпись под постом было нечего поставить.
  // Для /qr это важнее прочих: с печатного материала адрес не набирают, но
  // короткий читается сканером надёжнее и проверяется глазом.
  "/th",
  "/fb",
  "/x",
  "/qr",
  "/en/tt",
  "/en/ig",
  "/en/yt",
] as const;

export default function robots(): MetadataRoute.Robots {
  return {
    rules: [
      {
        userAgent: "*",
        allow: "/",
        disallow: [...DISALLOWED_PATHS],
      },
    ],
    sitemap: [
      `${BASE_URL}/sitemap.xml`,
      `${BASE_URL}/api-backend/api/aevion/sitemap.xml`,
    ],
  };
}
