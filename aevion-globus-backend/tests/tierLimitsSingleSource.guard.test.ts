import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Пределы тарифа объявлены в ОДНОМ месте.
 *
 * Замер 27.08.2026: таблица `TIER_LIMITS` стояла в файле дважды — один раз как
 * та, по которой стоит ограничитель расхода, второй раз литеральной копией,
 * которую ручка отдаёт клиенту как `tierInfo`. Числа совпадали, поэтому дефекта
 * не было видно. Он появился бы при первом же изменении тарифа: поправят одно
 * место — витрина обещает 50 видео, ограничитель считает 30, и человек упирается
 * в предел раньше обещанного. Такое расхождение не падает и не пишется в журнал.
 *
 * Это денежная поверхность: $149/мес продаются числами «50 AI видео · 200
 * изображений», и они обязаны приходить оттуда же, откуда берётся отказ.
 */

const FILE = path.join(__dirname, "..", "src", "routes", "devhub.ts");

function source(): string {
  return fs.readFileSync(FILE, "utf8");
}

/** Строки кода без комментариев: объяснение дефекта обязано называть числа. */
function code(): string {
  return source()
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .split("\n")
    .filter((l) => !l.trim().startsWith("//"))
    .join("\n");
}

describe("пределы тарифа — один источник", () => {
  test("прибор работает: файл читается и таблица в нём есть", () => {
    const c = code();
    expect(c.length).toBeGreaterThan(1000);
    expect(c).toContain("TIER_LIMITS");
  });

  test("строка тарифа pro объявлена ровно один раз", () => {
    // Ищем сам набор пределов, а не имя переменной: копия имени не носила.
    const declarations = [...code().matchAll(/pro:\s*\{\s*video:/g)];
    expect(
      declarations.length,
      "пределы тарифа объявлены больше одного раза — витрина и ограничитель разойдутся при первой же правке цены",
    ).toBe(1);
  });

  test("клиенту отдаётся та же таблица, а не её копия", () => {
    expect(code(), "tierInfo снова собран литералом").toContain("tierInfo: TIER_LIMITS");
  });

  test("направление: таблица не опустела", () => {
    // «Объявлений ровно одно» выполняется и удалением обоих. Проверяем, что
    // оставшееся объявление содержит все три тарифа и продаваемые числа.
    const c = code();
    expect(c).toMatch(/free:\s*\{\s*video:/);
    expect(c).toMatch(/enterprise:\s*\{\s*video:/);
    expect(c).toMatch(/pro:\s*\{\s*video:\s*50,\s*image:\s*200/);
  });
});
