/**
 * @vitest-environment jsdom
 */
import { describe, it, expect, vi } from "vitest";
import { renderToStaticMarkup } from "react-dom/server";

/**
 * Строка «сам протокол бесплатно» на /go — ЦЕЛЬ НАЖАТИЯ, а не просто текст.
 *
 * Повод, а не гипотеза. Замер 08.10.2026 на телефоне (iframe 390x844, кука
 * языка сброшена — так приходит гость из ролика): в первом экране страницы
 * четыре ссылки, все доступны, перекрытия нет. Но у ссылки на бесплатный
 * протокол высота была 18 px — палец в такую попадает не с первого раза.
 * За 07.10 с YouTube на /go пришло 7 живых человек, попробовали 0; сюда ведут
 * одиннадцать роликов через короткий вход /yt, и обещают они именно протокол.
 *
 * 🔴 ПОРЯДОК НЕ ПРОВЕРЯЕМ И НЕ ТРОГАЕМ. Платная книга стоит ПЕРВОЙ по прямому
 * решению основателя от 01.10.2026 (довод в самой странице: за всё время
 * платформа продавала только книгу за $9.99). Сторож охраняет размер цели, а
 * не очерёдность — иначе он начал бы спорить с решением.
 *
 * Проверяем ОТРИСОВКОЙ: вызываем серверный компонент и смотрим на разметку,
 * которая уедет посетителю. Исходник сказал бы лишь, что стиль объявлен, —
 * а не что он доехал до элемента.
 */

vi.mock("next/headers", () => ({
  cookies: async () => ({ get: () => undefined }),
}));

import GoPage from "../page";

async function разметка(): Promise<string> {
  const элемент = await GoPage({ searchParams: Promise.resolve({}) });
  return renderToStaticMarkup(элемент as React.ReactElement);
}

function разобрать(html: string): HTMLDivElement {
  const d = document.createElement("div");
  d.innerHTML = html;
  return d;
}

/** Высота цели нажатия из объявленного стиля, в пикселях. */
function высотаЦели(el: Element): number {
  const s = (el as HTMLElement).style;
  const v = s.minHeight || s.height || "";
  const m = /^(\d+(?:\.\d+)?)px$/.exec(v.trim());
  return m ? Number(m[1]) : 0;
}

describe("бесплатный протокол на /go — цель нажатия, а не строка текста", () => {
  it("прибор видит предмет: страница отрисовалась и в ней есть ссылки", async () => {
    const d = разобрать(await разметка());
    const ссылки = d.querySelectorAll("a[href]");
    // ЗНАМЕНАТЕЛЬ: если отрисовка сломается, проверки ниже станут зелёными
    // на пустоте — поэтому сначала утверждаем, что смотреть есть на что.
    expect(ссылки.length, "ссылок в разметке нет — отрисовка сломана").toBeGreaterThan(8);
    expect(d.textContent).toContain("Сам протокол открыт целиком и бесплатно");
  });

  it("у ссылки на протокол объявлена цель не меньше 44 px", async () => {
    const d = разобрать(await разметка());
    const все = [...d.querySelectorAll("a[href]")];
    const свободный = все.find((a) => (a.textContent || "").includes("Сам протокол открыт целиком"));
    expect(свободный, "ссылки на бесплатный протокол нет вовсе").toBeTruthy();
    const h = высотаЦели(свободный as Element);
    expect(
      h,
      `цель нажатия ${h} px — на телефоне в такую не попасть; 44 px это нижняя граница`,
    ).toBeGreaterThanOrEqual(44);
    // Проверено ЗНАМЕНАТЕЛЕМ: сколько ссылок осмотрено ради одной находки.
    expect(все.length).toBeGreaterThan(8);
  });

  it("ОТРИЦАТЕЛЬНЫЙ контроль: проверка не считает целью любую ссылку", async () => {
    const d = разобрать(await разметка());
    const все = [...d.querySelectorAll("a[href]")];
    const обычные = все.filter((a) => высотаЦели(a) === 0);
    // Если бы высотаЦели возвращала 44 для всего подряд, проверка выше была бы
    // зелёной всегда. Обычные ссылки на странице есть — значит она различает.
    expect(обычные.length, "все ссылки объявили высоту — проверка ничего не различает").toBeGreaterThan(0);
  });

  it("порядок не тронут: платная книга идёт РАНЬШЕ бесплатной строки", async () => {
    // Не требование сторожа, а защита решения основателя от 01.10.2026:
    // если кто-то переставит блоки, он узнает об этом здесь, а не из выручки.
    const html = await разметка();
    const книга = html.indexOf("Книга, из которой вырос протокол");
    const свободный = html.indexOf("Сам протокол открыт целиком");
    expect(книга, "карточки книги нет в разметке").toBeGreaterThan(-1);
    expect(свободный, "строки про бесплатный протокол нет").toBeGreaterThan(-1);
    expect(книга, "бесплатное встало впереди платного — это отменяет решение 01.10").toBeLessThan(свободный);
  });
});
