import { describe, test, expect, vi, afterEach } from "vitest";
import { render } from "@testing-library/react";
import { readFileSync } from "node:fs";
import { join } from "node:path";
// Зовём ТУ ЖЕ функцию поиска, что и страница. Своя копия (поиск по массиву MODULES)
// дала знаменатель 5 вместо 6: карточка qrenew ищется по productId "kkiavh", который
// лежит в другом массиве каталога — страница его находит, копия правила нет.
import { productById } from "@/lib/products";
import { EN_TEXTS } from "@/lib/enTexts";

/**
 * ВИТРИНА /apps ПОКАЗЫВАЕТ ПОДПИСЬ КАТАЛОГА — ПРОВЕРЯЕТСЯ ПО ОТРИСОВАННОМУ.
 *
 * 🔴 Повод 06.10.2026, и это разбор МОЕЙ ошибки. Днём я написал подпись карточки
 * DevHub, которая называет, за что деньги, и поставил на неё сторожа. Сторож был
 * зелёным, а человек на /apps подписи НЕ ВИДЕЛ: у витрины была своя строка
 * («Full-stack browser IDE + AI + deploy»). Я проверил ЗАМЫСЕЛ (каталог) вместо
 * РАБОТЫ (страницы) — ровно то, от чего предостерегает правило про сторожей.
 * Расхождение нашла приёмка, не я.
 *
 * Поэтому здесь страница РИСУЕТСЯ, и утверждения делаются о тексте на экране.
 */

vi.mock("@/lib/apiBase", () => ({ apiUrl: (p: string) => p }));

const ПЕРЕВОД = String.fromCharCode(10); // эскейп съедается на границе вызова (§2е)

/** Карточки витрины, связанные с каталогом: знаменатель охвата. */
/**
 * Ожидаемая подпись — ТА ЖЕ цепочка источников, что у страницы: английский текст
 * каталога, затем русский, затем своя строка. Своей копии порядка здесь нет, иначе
 * сторож начал бы охранять другое правило, чем работает в проде.
 */
function ожидаемаяПодпись(pid: string): string {
  return EN_TEXTS[pid]?.desc ?? productById(pid)?.desc ?? "";
}

function связанные(): Array<{ id: string; desc: string }> {
  const src = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");
  const найдено: Array<{ id: string; desc: string }> = [];
  // Разделитель С КАВЫЧКОЙ: без неё первая версия посчитала слово productId из
  // МОЕГО ЖЕ комментария в page.tsx и назвала devhub дважды. Текст о вещи неотличим
  // от вещи, если не привязаться к синтаксису.
  const куски = src.split('productId: "');
  const виденные = new Set<string>();
  for (let i = 1; i < куски.length; i++) {
    const m = куски[i].match(/^([^"]+)"/);
    const pid = m ? m[1] : "";
    if (!pid || виденные.has(pid)) continue;
    виденные.add(pid);
    const подпись = ожидаемаяПодпись(pid);
    if (подпись) найдено.push({ id: pid, desc: подпись });
  }
  return найдено;
}

async function нарисовать(): Promise<string> {
  vi.stubGlobal(
    "fetch",
    vi.fn(async () => new Response(JSON.stringify({ ok: true, modules: [] }), { status: 200 })),
  );
  const { default: Стр } = await import("../page");
  render(<Стр />);
  await new Promise((r) => setTimeout(r, 40));
  return document.body.textContent || "";
}

describe("/apps показывает подпись каталога", () => {
  afterEach(() => vi.unstubAllGlobals());

  test("ЗНАМЕНАТЕЛЬ: сколько карточек связано с каталогом", () => {
    const св = связанные();
    process.stderr.write(
      `[сторож] карточек, связанных с каталогом: ${св.length} — ${св.map((с) => с.id).join(", ")}` + ПЕРЕВОД,
    );
    // Ноль связанных означал бы, что productId исчезли, а проверки ниже зеленели молча.
    expect(св.length, "ни одна карточка не связана с каталогом — сторож ослеп").toBeGreaterThanOrEqual(5);
  });

  test("на ЭКРАНЕ у каждой связанной карточки стоит текст каталога", async () => {
    const экран = await нарисовать();
    const нет: string[] = [];
    for (const пара of связанные()) {
      // По началу подписи: этого довольно, чтобы отличить текст каталога от прежней
      // собственной строки витрины, и не ломается от переносов в разметке.
      if (!экран.includes(пара.desc.slice(0, 40))) нет.push(пара.id);
    }
    expect(нет, "у этих карточек на экране НЕ текст каталога — витрина снова говорит своё").toEqual([]);
  });

  test("подпись доехала ЦЕЛИКОМ, вместе с числами в хвосте", async () => {
    /*
     * Первая версия проверяла наличие голых чисел ("50", "200", "200000") — и мутация
     * «50 видео, 200 картинок» → «40 видео, 150 картинок» её НЕ УРОНИЛА: в «150»
     * есть «50», а «200000» осталось на месте. Утверждение про голые числа почти
     * неопровержимо, то есть сторож охранял пустоту.
     *
     * Теперь берём ХВОСТ подписи из каталога — там, где числа и живут, — и требуем
     * его на экране. Это ловит настоящий риск: кто-нибудь подрежет подпись ради
     * вёрстки (slice, line-clamp), и человек снова не увидит, за что деньги.
     *
     * Правильность САМИХ чисел охраняет другой сторож и по другому источнику:
     * devhubCardSaysWhatMoneyBuys сверяет их с таблицей TIER_LIMITS бэкенда. Здесь
     * проверяется доставка до экрана, и смешивать два вопроса в одном тесте нельзя.
     */
    const подпись = ожидаемаяПодпись("devhub");
    expect(подпись, "нет ожидаемой подписи DevHub — проверять нечего").toBeTruthy();
    const хвост = подпись.slice(-60);
    const экран = await нарисовать();
    expect(
      экран.includes(хвост),
      `хвост подписи до экрана не доехал (подрезали?): ожидался «${хвост}»`,
    ).toBe(true);
  });

  test("ни одна связанная карточка не осталась без подписи вовсе", async () => {
    // Это регрессия, которую я почти внёс: удалив свои строки у связанных карточек,
    // карточка с productId, у которого в каталоге нет desc, осталась бы ПУСТОЙ.
    // Проверять надо не «текст каталога стоит», а «подпись есть хоть какая-то».
    const src = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");
    const экран = await нарисовать();
    const куски = src.split('productId: "');
    const пустые: string[] = [];
    const виденные = new Set<string>();
    for (let i = 1; i < куски.length; i++) {
      const m = куски[i].match(/^([^"]+)"/);
      const pid = m ? m[1] : "";
      if (!pid || виденные.has(pid)) continue;
      виденные.add(pid);
      const своя = куски[i].match(/tagline: "([^"]*)"/);
      // Та же цепочка, что у страницы: английский текст → русский → своя строка.
      // Прежде здесь стоял только productById, и после перехода витрины на английский
      // текст тест ждал русскую подпись, которой на экране уже нет.
      const ждём = ожидаемаяПодпись(pid) || (своя ? своя[1] : "");
      if (!ждём || !экран.includes(ждём.slice(0, 30))) пустые.push(pid);
    }
    expect(пустые, "у этих связанных карточек на экране нет никакой подписи").toEqual([]);
  });

  test("ЯЗЫК: подписи связанных карточек на том же языке, что остальные на этой витрине", async () => {
    /*
     * 🔴 Регрессию внёс я 06.10: русская подпись каталога поехала на /apps, и шесть
     * связанных карточек заговорили по-русски там, где остальные подписи английские.
     * Нашла приёмка живым замером прода; прежний сторож был зелёным, потому что
     * спрашивал «доехала ли подпись» и не спрашивал «можно ли её прочитать».
     *
     * ⚠️ ПЕРВУЮ версию этой проверки (кириллицы нет, если корень объявлен lang="en")
     * мы с приёмкой ОТМЕНИЛИ, и это важнее самой проверки. Атрибут в ответе сервера —
     * не язык содержимого: в корневом макете он статический, а настоящий язык ставит
     * скрипт из пути или cookie. Замер приёмки: главная отдаёт lang="en" при 31 строке
     * кириллицы, /acquire — при 116 строках против 36 латиницей. Сторож на таком
     * приборе краснел бы на законных русских страницах.
     *
     * Поэтому сравнение идёт ВНУТРИ страницы: подписи карточек БЕЗ каталога здесь
     * заведомо английские (они сохранены сознательно), и связанные обязаны быть на том
     * же языке. Прибор проверяется тут же: сперва утверждаем, что эталон латинский.
     */
    const кириллица = /[Ѐ-ӿ]/;
    const src = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");
    const свои = [...src.matchAll(/tagline: "([^"]+)"/g)].map((m) => m[1]);
    // Контроль прибора: эталон должен существовать и быть латинским, иначе требовать
    // латиницу от связанных карточек нельзя — страница могла стать русской целиком.
    expect(свои.length, "на витрине не осталось карточек со своей подписью — эталона нет").toBeGreaterThanOrEqual(5);
    const эталонРусский = свои.filter((т) => кириллица.test(т));
    expect(
      эталонРусский,
      "подписи карточек без каталога стали русскими — тогда и требование латиницы ниже неверно, пересмотрите проверку",
    ).toEqual([]);

    const сРусским = связанные().filter((п) => кириллица.test(п.desc));
    expect(
      сРусским.map((п) => п.id),
      "остальные подписи этой витрины английские, а подпись этих карточек русская — смесь языков на одной странице",
    ).toEqual([]);
  });

  test("у каждой связанной карточки есть ИМЕННО английский текст каталога", async () => {
    // Предложение приёмки, и оно строже прежнего: проверяем не «нет кириллицы», а
    // совпадение с EN_TEXTS. Тогда сторож охраняет ровно то, что сломалось, и не
    // зависит ни от атрибута языка, ни от скрипта, который его меняет.
    const экран = await нарисовать();
    const без: string[] = [];
    const неНаЭкране: string[] = [];
    for (const п of связанные()) {
      const англ = EN_TEXTS[п.id]?.desc;
      if (!англ) { без.push(п.id); continue; }
      if (!экран.includes(англ.slice(0, 40))) неНаЭкране.push(п.id);
    }
    expect(без, "у этих карточек НЕТ английского текста: витрина молча покажет русский").toEqual([]);
    expect(неНаЭкране, "английский текст есть, но на экране его нет").toEqual([]);
  });

  test("КОНТРОЛЬ: карточка БЕЗ каталога сохранила свою строку", async () => {
    // Иначе правка «брать из каталога» молча обнулила бы подписи у бесплатных
    // приложений, и витрина стала бы наполовину безымянной.
    const экран = await нарисовать();
    // Строки взяты ЗАМЕРОМ по файлу, а не по памяти: сперва я поставил сюда
    // «A council of models…», и контроль честно покраснел — эта строка не подпись
    // карточки вовсе. Ниже — подписи карточек, у которых productId НЕТ.
    const свои = [
      "Multi-model AI assistant",
      "Publish finished videos to your own TikTok",
      "Embedded payment infrastructure",
    ];
    expect(свои.filter((с) => !экран.includes(с)), "у карточек без productId исчезла подпись").toEqual([]);
  });
});
