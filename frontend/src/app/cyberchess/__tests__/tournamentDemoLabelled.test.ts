import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { stripComments } from "./_stripComments";

/* Список турниров: образец обязан говорить о себе сам.
 *
 * У турнира есть признак `realPlayers`. Подписан был только он: турниры с
 * живыми игроками получали тег «⚡ real players», а посевные — НИЧЕГО. То есть
 * образец отличался от настоящего лишь отсутствием метки, а отсутствие метки
 * человек не читает как «выдумано». Рядом с честно подписанным соседом он,
 * наоборот, берёт его доверие.
 *
 * Замер на проде 12.08.2026: в списке 13 турниров, из них 11 посевных —
 * «Spring Blitz Open», «Weekly Rapid #22», «Swiss Arena — Май» и другие. Три
 * значились «live», а «Winter Arena #12» — «завершён», то есть с результатами,
 * которых не было. Фильтр «только реальные» на странице есть, но по умолчанию
 * выключен, а посетитель о нём не знает.
 */

const PAGE = "src/app/cyberchess/tournaments/page.tsx";
const src = stripComments(readFileSync(PAGE, "utf8"));

describe("образец в списке турниров подписан", () => {
  it("у турнира без живых игроков есть своя метка", () => {
    expect(src).toMatch(/образец/);
  });

  it("метка стоит в ветке ИНАЧЕ у признака realPlayers", () => {
    /* Важно не наличие слова где-то в файле, а то, что оно показывается именно
       когда realPlayers не выставлен. */
    expect(src).toMatch(/t\.realPlayers \?[\s\S]{0,400}образец/);
  });

  it("настоящие турниры по-прежнему подписаны своим тегом", () => {
    /* Обратная сторона: новая метка не должна вытеснить старую — иначе
       различие снова исчезнет, только в другую сторону. */
    expect(src).toMatch(/real players/);
  });
});
