describe("реестр каналов и короткие входы — одна сущность", () => {
  // ЗАЧЕМ ОТДЕЛЬНАЯ ПРОВЕРКА. Список ROUTES выше ведётся руками, и это верно:
  // он утверждение о том, какие входы мы обещаем. Но сам по себе он не связан
  // с каталогом CHANNELS — можно завести метку канала и забыть про вход.
  //
  // Ровно это и было. Замер 30.08.2026: каталог знал ДЕСЯТЬ меток, коротких
  // входов существовало шесть. Метки при этом работали — /go?c=th и остальные
  // три доводили метку до кассы на живом проде, — а /th, /fb, /x, /qr
  // отвечали 404. То есть в подпись под постом было нечего поставить, и
  // человек приходил без метки, в канал direct.
  //
  // Проверка связывает две сущности: каждая метка каталога обязана иметь вход.
  it("у каждой метки каталога есть короткий вход", () => {
    const known = new Set(ROUTES.filter(([r]) => !r.startsWith("en/")).map(([r]) => r));
    const missing = Object.keys(CHANNELS).filter((c) => !known.has(c));
    expect(missing, "метка канала есть, а короткого адреса для подписи нет").toEqual([]);
  });

  it("каждый короткий вход ведёт ИЗВЕСТНУЮ каталогу метку", () => {
    /*
     * 🔴 Обратная сторона той же связи, и её здесь НЕ БЫЛО. Найдено мутацией
     * 02.10.2026: убрал метку `un` из CHANNELS — оба сторожа остались ЗЕЛЁНЫМИ.
     * А страница /un при этом жива и продолжает присылать `?c=un`, которого
     * каталог уже не знает: channelFrom вернёт null, и переход ляжет в «прямые
     * заходы». То есть ровно та потеря, ради которой проверка выше и написана,
     * только с другой стороны — и она проходила молча.
     *
     * Проверка односторонней связи стережёт половину: «у каждой метки есть
     * вход» и «каждый вход ведёт известную метку» — разные утверждения, и
     * ломаются они по-разному.
     *
     * Замер на момент добавления: маршрутов 30, меток 27, чужих 0.
     */
    const метки = new Set(Object.keys(CHANNELS));
    const чужие = ROUTES.map(([r]) => r.split("/").pop()!).filter((м) => !метки.has(м));
    expect(ROUTES.length, "список маршрутов пуст — проверка ничего не значит").toBeGreaterThan(20);
    expect(
      чужие,
      "короткий вход присылает метку, которой каталог не знает: переход ляжет в «прямые заходы»",
    ).toEqual([]);
  });

  it("каталог вообще не пуст — иначе проверка выше ничего не значит", () => {
    // Контроль охвата: переименуют CHANNELS или сломается импорт — список
    // станет пустым, и проверка «нет пропущенных» пройдёт, не проверив ничего.
    expect(Object.keys(CHANNELS).length).toBeGreaterThanOrEqual(8);
  });
});

describe("короткие адреса каналов", () => {
  it("каждый существует и ведёт по своему адресу с меткой", () => {
    for (const [route, target] of ROUTES) {
      const file = join(APP, ...route.split("/"), "page.tsx");
      expect(existsSync(file), `нет страницы для /${route}`).toBe(true);
      const src = readFileSync(file, "utf8");
      expect(src, `/${route}: нет redirect()`).toContain("redirect(");
      expect(src, `/${route}: ведёт не на ${target}`).toContain(`redirect("${target}")`);
    }
  });

  it("метка канала в цели совпадает с самим адресом", () => {
    // Ловит опечатку копипасты: страница /ig, а метка c=tt. Такую ошибку
    // невозможно увидеть по цифрам — канал просто окажется не тот.
    for (const [route, target] of ROUTES) {
      const channel = route.split("/").pop();
      expect(target, `/${route}: метка не совпадает с адресом`).toContain(`c=${channel}`);
    }
  });

  it("короткие адреса закрыты от поисковика", () => {
    // Иначе они соревнуются в выдаче с той страницей, на которую ведут.
    for (const [route] of ROUTES) {
      const src = readFileSync(join(APP, ...route.split("/"), "page.tsx"), "utf8");
      expect(src, `/${route}: нет metadata`).toContain("export const metadata");
      expect(src.replace(/\s+/g, ""), `/${route}: индексация не запрещена`).toContain("index:false");
    }
  });

  /*
   * 🔴 ИСКЛЮЧЕНИЕ ОБУСЛОВЛЕНО, А НЕ СНЯТО (приёмка, 06.10.2026).
   *
   * Правило ниже написано против тихого увода посетителя: «любое условие здесь
   * означает, что часть посетителей уедет не туда, и заметить это будет нечем».
   * Оно верное, и я его не ослабляю.
   *
   * Но у `/example` появилась ЗАКОННАЯ причина ветвиться: вход обязан ПРОПУСКАТЬ
   * входящую метку (`/example?c=yt` доезжает как `c=yt`) и ставить свою только
   * когда метки нет или она неизвестна. До правки ролик со ссылкой `?c=yt`
   * ложился в канал `example`, то есть эффект ролика считался не по тому каналу —
   * ровно та беда, от которой правило и писалось, только с другой стороны.
   *
   * Поэтому исключение дано не странице, а ПАРЕ «ветвление + поведенческий
   * сторож на оба пути». Опасение правила («заметить будет нечем») снимается
   * сторожем, который зовёт страницу и разбирает перенаправление, а не словом
   * автора. Исчезнет сторож или перестанет проверять оба пути — исключение
   * перестаёт действовать, и правило снова запрещает ветвление.
   */
  const ВЕТВЛЕНИЕ_РАЗРЕШЕНО: Record<string, string> = {
    example: "devhub/__tests__/exampleEntryKeepsChannel.guard.test.ts",
  };

  it("исключение на ветвление ОПЛАЧЕНО поведенческим сторожем", () => {
    const имена = Object.keys(ВЕТВЛЕНИЕ_РАЗРЕШЕНО);
    expect(имена.length, "список исключений пуст — проверять нечего").toBeGreaterThan(0);
    for (const [маршрут, путь] of Object.entries(ВЕТВЛЕНИЕ_РАЗРЕШЕНО)) {
      const файл = join(APP, ...путь.split("/"));
      expect(existsSync(файл), `${маршрут}: обещанного сторожа ${путь} НЕТ — исключение не оплачено`).toBe(true);
      const сторож = readFileSync(файл, "utf8");
      // Оба пути обязательны: сторож, проверяющий только случай «без метки»,
      // оставил бы потерю входящей метки незамеченной.
      expect(сторож, `${маршрут}: сторож не проверяет, что входящая метка ДОЕЗЖАЕТ`).toMatch(/c=yt|c=tg|c=li/);
      expect(сторож, `${маршрут}: сторож не проверяет случай БЕЗ метки`).toContain("c=" + маршрут);
      const утверждений = (сторож.match(/expect\(/g) ?? []).length;
      expect(
        утверждений,
        `${маршрут}: утверждений в стороже ${утверждений} — меньше четырёх, этого мало для исключения`,
      ).toBeGreaterThanOrEqual(4);
    }
  });

  it("в них нет никакой логики, кроме перенаправления", () => {
    // Короткий адрес — вход, а не страница. Любое условие здесь означает, что
    // часть посетителей уедет не туда, и заметить это будет нечем.
    for (const [route] of ROUTES) {
      const src = readFileSync(join(APP, ...route.split("/"), "page.tsx"), "utf8");
      const code = src
        .split("\n")
        .filter((l) => !l.trim().startsWith("//") && !l.trim().startsWith("*") && !l.trim().startsWith("/*"))
        .join("\n");
      if (ВЕТВЛЕНИЕ_РАЗРЕШЕНО[route]) continue; // исключение проверено тестом выше
      expect(code, `/${route}: появилось ветвление`).not.toMatch(/\bif\s*\(|\?\s*.+\s*:/);
      expect(code, `/${route}: появился запрос к сети`).not.toMatch(/fetch\(|await /);
    }
  });
});
