import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { безКомментариев } from "@/lib/__tests__/helpers/sourceWithoutComments";

/**
 * Платный шаг не предлагается раньше, чем спросили, работает ли он.
 *
 * ЗАЧЕМ. Замер 28.09.2026 на живом проде: страница QRight показывала кнопку
 * «⭐ Upgrade to Verified ($19)» ВСЕМ и ВСЕГДА, а ручка за ней отвечает
 * `503 Paid verification is not available: the identity and payment providers
 * are not configured yet` (stubBarriers: identity, payment). Человеку предлагали
 * заплатить ровно в тот момент, когда он только что защитил свою работу, — в
 * момент наибольшего доверия, — и упирали в отказ.
 *
 * Ручка состояния была всё это время: `/api/bureau/health` честно отвечает
 * `kyc: stub`, `payment: misconfigured`, `notarySignature: demo`. Интерфейс её
 * просто не спрашивал. Это наше правило «доступность ≠ пригодность»: у канала,
 * который обещает интерфейс, есть ручка состояния, и интерфейс обязан её
 * спрашивать.
 *
 * Почему это не краснеет само: страница отвечает 200, кнопка рисуется, Sentry
 * молчит. Ломается только доверие покупателя, и увидеть это можно лишь пройдя
 * путь до конца своими руками.
 *
 * ГРАНИЦА: сторож читает исходник и отвечает «страница спрашивает состояние и
 * различает исходы», а не «в браузере кнопка скрылась». Проверить второе без
 * прогона браузером нельзя, и ради одной кнопки он дороже, чем стоит.
 */

const PAGE = join(__dirname, "..", "page.tsx");
/*
 * Комментарии снимаем ДО проверок. Без этого сторож находил `/api/bureau/health`
 * в моём же объяснении рядом с правкой и оставался зелёным, когда саму строку
 * убирали. Мутация «перестали спрашивать состояние» это и показала.
 */
const src = безКомментариев(readFileSync(PAGE, "utf8"));

describe("платный апгрейд не обещают вслепую", () => {
  test("контроль: файл прочитан и это нужная страница", () => {
    expect(src.length).toBeGreaterThan(5000);
    expect(src).toContain("Upgrade to Verified");
  });

  test("страница спрашивает состояние бюро", () => {
    expect(
      src.includes("/api/bureau/health"),
      "кнопка платного шага рисуется, не спросив, работает ли он",
    ).toBe(true);
  });

  test("оба стоп-признака учтены: заглушка личности И ненастроенная оплата", () => {
    /*
     * Проверять один из двух мало: на проде сегодня стоят ОБА
     * (kyc: stub, payment: misconfigured), и уберут их по отдельности.
     * Читать только payment значило бы открыть кнопку в тот день, когда
     * оплату подключат, а личность останется заглушкой.
     */
    expect(src).toContain('kyc !== "stub"');
    expect(src).toContain('payment !== "misconfigured"');
  });

  test("исходов ТРИ, а не два: «ещё не спросили» отличается от «нельзя»", () => {
    /*
     * Держимся за ИМЯ переменной, а не за общие строки.
     *
     * Первая редакция проверяла `toContain("=== false")` и мутацию не поймала:
     * это сочетание встречается в файле дважды, и снятие МОЕГО условия ничего
     * не меняло для теста. Сторож, привязанный к строке, которая живёт и в
     * чужом коде, охраняет чужой код вместо своего.
     */
    expect(src).toContain("платнаяПроверкаДоступна, установитьДоступность] = useState<boolean | null>(null)");
    expect(
      src.includes("платнаяПроверкаДоступна === false"),
      "кнопку снова рисуют, не глядя на ответ ручки состояния",
    ).toBe(true);
  });

  test("отказ показывается отказом, а не пустым местом", () => {
    // Молча спрятать шаг — тоже обман: человек не узнает, что он существует.
    expect(src).toContain("not available yet");
  });
});
