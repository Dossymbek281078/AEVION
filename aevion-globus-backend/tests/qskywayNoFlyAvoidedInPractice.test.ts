import { describe, expect, it } from "vitest";
import { __engineForTests } from "../src/routes/qskyway";
import { CITY } from "../src/routes/qskyway.city";
import { NOFLY } from "../src/routes/qskyway.zones";
import type { CityData } from "../src/routes/qskyway.city";

/**
 * Обход запретных зон проверялся только НА УРОВНЕ ГЕОМЕТРИИ: соседний набор
 * qskywayNoFlyClaim берёт функцию пересечения и кормит её парами точек. Это
 * правильные тесты, и они ловят тонкости — например, зону ПОЗАДИ площадки
 * вылета. Но сквозной заявки они не проверяют ни разу: слова
 * `cellsOnPathInsideZone` в том файле нет.
 *
 * То есть помощник был проверен, а САМ ОБХОД — нет. Разница не теоретическая:
 * до 27.08.2026 поле `avoidsNoFly` сообщало свойство ГОРОДА («в городе есть
 * зоны») под именем свойства маршрута и потому всегда отвечало true. Работал
 * ли обход на самом деле, снаружи было не узнать.
 *
 * Здесь проверка именно сквозная и на случае, где ей есть что показать: пара
 * площадок, у которой ПРЯМАЯ идёт через зону. Найдена пробой прода 28.08.
 */

const B = __engineForTests;

describe("запретные зоны обходятся на деле, а не в описании", () => {
  it("контроль: в этом городе зоны вообще есть, иначе проверка пуста", () => {
    // Без этого «ноль ячеек в зоне» верно и для города без зон — то есть
    // ни о чём не говорит.
    const r = B.buildRoute("astana", CITY, 0, 1, false);
    expect(r).not.toBeNull();
    expect(r!.noFly.zonesInCity).toBeGreaterThan(0);
  });

  it("контроль: у этой пары ПРЯМАЯ действительно идёт через зону", () => {
    // Если однажды зоны или площадки сдвинут и прямая перестанет пересекать,
    // проверка ниже станет бессмысленной — и мы узнаем об этом ЗДЕСЬ, а не
    // получим тихо зелёный набор.
    const r = B.buildRoute("astana", CITY, 0, 1, false);
    expect(
      r!.noFly.directLineCrosses,
      "пара 0→1 больше не пересекает зону по прямой: подберите другую пару, "
        + "иначе сквозная проверка обхода ничего не проверяет",
    ).toBe(true);
  });

  it("маршрут при этом НЕ проходит ни через одну ячейку зоны", () => {
    const r = B.buildRoute("astana", CITY, 0, 1, false);
    expect(
      r!.noFly.cellsOnPathInsideZone,
      "маршрут задевает запретную зону — обход не сработал",
    ).toBe(0);
  });

  it("и поле avoidsNoFly говорит о МАРШРУТЕ, а не о городе", () => {
    // Прямая пересекает, значит обход был нужен и состоялся: поле обязано
    // это отражать. Раньше оно отвечало по свойству города и было бесполезным.
    const r = B.buildRoute("astana", CITY, 0, 1, false);
    expect(r!.avoidsNoFly).toBe(r!.noFly.directLineCrosses);
  });

  it("контроль СИЛЫ запрета: зона поверх всего коридора — маршрута НЕТ", () => {
    // Этот контроль важнее, чем кажется, и он изменил мой вывод о поле.
    //
    // Сперва я хотел проверить, что счётчик `cellsOnPathInsideZone` умеет быть
    // больше нуля — иначе утверждение «он равен нулю» не отличает посчитанный
    // ноль от константы (мутация это подтвердила: заменил вычисление на `0`,
    // набор остался зелёным).
    //
    // Выяснилось, что БОЛЬШЕ НУЛЯ он быть не может: запрет для маршрутизатора
    // жёсткий, и через зону он не ведёт вовсе. Значит поле тавтологично для
    // любого построенного маршрута и само по себе ничего не доказывает.
    //
    // Доказывают обход ДВЕ другие вещи, и обе проверены выше и здесь:
    //   маршрут СУЩЕСТВУЕТ, хотя прямая идёт через зону — обошёл;
    //   когда обойти нельзя, маршрута НЕТ — то есть запрет не декоративный.
    const cols = 12, rows = 1, cell = 20;
    const twin: CityData = {
      city: "тестовый твин, зона поверх всего коридора",
      bbox: { minLat: 51.1, maxLat: 51.11, minLon: 71.4, maxLon: 71.41 },
      meters: { w: cols * cell, h: rows * cell },
      grid: { cols, rows, cell, heights: new Array(cols * rows).fill(0), src: new Array(cols * rows).fill(0) },
      buildings: [],
      vertiports: [{ c: 0, r: 0, x: 10, y: 10 }, { c: 11, r: 0, x: 230, y: 10 }],
      dataQuality: { total: 0, measured: 0, derived: 0, guessed: 0, measuredPct: 0, realPct: 0, source: "test", note: "test" },
    };
    const id = "zz-nofly-control";
    NOFLY[id] = [{
      id: "zz", name: "контрольная зона", kind: "permanent",
      center: [71.405, 51.105], radiusM: 5000,
      realityNote: "синтетическая зона теста: накрывает весь коридор",
    } as (typeof NOFLY)[string][number]];
    try {
      expect(
        B.buildRoute(id, twin, 0, 1, false),
        "зона накрывает весь коридор, а маршрут построился — запрет не работает",
      ).toBeNull();
    } finally {
      delete NOFLY[id];
    }
  });
});
