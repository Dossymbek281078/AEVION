import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Отказ чтения месячного расхода обязан оставлять след.
 *
 * Замер 29.08.2026. `getMonthUsage` при ошибке запроса делала `catch { return 0 }`.
 * Ноль уходит в `checkCredit` как `used`, и проверка `used + amount <= limit`
 * становится истинной почти всегда. Предел закрывает СЕМЬ платных ручек —
 * видео, изображения, озвучку по символам, музыку и три места выкатки, — и
 * пока база не отвечает, генерации идут без предела. Платим мы.
 *
 * Снаружи это неотличимо от честного нулевого расхода: ни в журнале, ни в
 * ответе, ни в Sentry не оставалось ничего.
 *
 * ЧТО ЭТОТ СТОРОЖ ТРЕБУЕТ, а что нет. Он требует ВИДИМОСТИ отказа и не
 * требует отказа в обслуживании: менять направление на денежном пути — это
 * продуктовое решение (закрыться значит остановить платящего клиента при сбое
 * базы; разумная граница — закрывать НЕОБРАТИМОЕ, то есть расход у внешнего
 * поставщика). Пока решения нет, поведение прежнее, но молчания больше нет.
 *
 * Разбор: 15-Аудиты-и-сводки/DEVHUB-отказ-базы-снимает-месячный-лимит-29-08.md
 */

const SRC = readFileSync(join(__dirname, "..", "src", "routes", "devhub.ts"), "utf8");

/** Тело функции, а не весь файл: иначе сторож зеленел бы от чужой строки. */
function getMonthUsageBody(): string {
  const start = SRC.indexOf("async function getMonthUsage(");
  expect(start, "функция getMonthUsage не найдена — сторож смотрит не туда").toBeGreaterThan(-1);
  const end = SRC.indexOf("async function checkCredit(", start);
  expect(end, "конец блока не найден — граница сторожа сломана").toBeGreaterThan(start);
  return SRC.slice(start, end);
}

const BODY = getMonthUsageBody();

describe("отказ чтения расхода не проходит молча", () => {
  test("контроль: тело функции разобрано и оно про расход", () => {
    expect(BODY.length, "тело пустое — проверять нечего").toBeGreaterThan(200);
    expect(BODY.includes("DevHubUsage"), "разобрана не та функция").toBe(true);
  });

  test("у ветки отказа есть запись в журнал", () => {
    expect(
      BODY.includes("console.warn") || BODY.includes("console.error"),
      "отказ чтения расхода снова невидим: предел на семь платных ручек " +
        "перестанет применяться, и об этом никто не узнает",
    ).toBe(true);
  });

  test("в записи названо ЧТО и КОМУ не удалось", () => {
    // След без этих двух вещей бесполезен: по нему нельзя ни понять масштаб,
    // ни найти пострадавшего.
    for (const part of ["user=", "capability="]) {
      expect(BODY.includes(part), `в записи нет ${part} — по такому следу ничего не найти`).toBe(true);
    }
  });

  test("запись расхода: запасной путь в память тоже не молчит", () => {
    // Симметричная половина. При отказе ЗАПИСИ трата уходит в память
    // процесса, а память обнуляется при каждой выкатке — месячный счёт
    // начинается заново. Это тише отказа чтения и потому опаснее: отказ
    // виден в момент отказа, а обнуление выглядит нормальной работой.
    const start = SRC.indexOf("async function debitCredit(");
    expect(start, "функция debitCredit не найдена").toBeGreaterThan(-1);
    const end = SRC.indexOf("async function getAllMonthUsage(", start);
    expect(end, "конец блока не найден").toBeGreaterThan(start);
    const body = SRC.slice(start, end);
    expect(body.includes("memUsage.set"), "разобрана не та функция").toBe(true);
    expect(
      body.includes("console.warn") || body.includes("console.error"),
      "трата ушла в память процесса молча: месячный счёт обнулится при выкатке, и об этом никто не узнает",
    ).toBe(true);
    expect(body.includes("user="), "в записи не назван пострадавший").toBe(true);
  });

  test("направление отказа: при отказе чтения возвращается null, а не число", () => {
    // НАПРАВЛЕНИЕ ИЗМЕНЕНО 30.08.2026, и это осознанное решение другой сессии,
    // а не побочное следствие. Прежняя редакция сторожа требовала нуля и
    // говорила: «менять можно, но пусть это будет решением». Оно им и стало.
    //
    // Обоснование сильнее моего, поэтому принимаю: ноль — честный ответ для
    // нового месяца, и отвечая нулём на ОТКАЗ чтения, мы делали аварию базы
    // неотличимой от человека, который ничего не потратил. Все пределы
    // открывались на всё время аварии. `null` заставляет вызывающего решить,
    // что делать с неизвестностью, — неверное число ему больше не подсунуть.
    //
    // Роль сторожа прежняя: он стережёт, чтобы направление не менялось МОЛЧА.
    expect(
      /return null;/.test(BODY),
      "ветка отказа больше не возвращает null — направление изменилось, проверьте осознанно",
    ).toBe(true);
    expect(
      /Promise<number \| null>/.test(BODY),
      "тип перестал допускать неизвестность — вызывающему снова можно подсунуть число",
    ).toBe(true);
  });
});
