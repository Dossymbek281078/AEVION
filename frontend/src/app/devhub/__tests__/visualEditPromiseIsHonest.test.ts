import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Витрина DevHub не должна обещать правку кликами РАНЬШЕ, чем она появляется.
 *
 * Замер 27.08.2026. Строка на витрине шла так: «покажет живое превью и диффы.
 * Дальше — правь кликами (Visual Edit), … деплой в один клик» — то есть Visual
 * Edit обещан сразу после превью и ДО деплоя. В продукте порядок другой:
 * клик-редактирование включено сразу только на статике, а стек по умолчанию —
 * `next` (`stack = "next"` в обработчике создания проекта). Для него вкладка до
 * деплоя показывает заглушку.
 *
 * Цена ошибки не косметическая: человек за $149 ищет обещанную кнопку, не
 * находит и решает, что модуль сломан. Назвать условие дешевле, чем обещать
 * порядок, которого нет.
 *
 * Заодно сторож держит язык: заглушки этого экрана были по-английски посреди
 * русской страницы.
 */

const STOREFRONT = path.join(__dirname, "..", "page.tsx");
// Текст витрины переехал в словарь модуля (страница трёхъязычная), поэтому
// сторож читает ОБА места: иначе он краснеет на честном переносе.
const DICT = path.join(__dirname, "..", "i18n.ts");
const EDITOR = path.join(__dirname, "..", "[id]", "page.tsx");

const read = (p: string) => fs.readFileSync(p, "utf8");

/**
 * Видимый текст: комментарии выброшены ЦЕЛИКОМ, а не построчно.
 *
 * Построчный фильтр («строка начинается с `//`, `*`, `{/*`») здесь не работает,
 * и это выяснилось на первом же прогоне: продолжение JSX-комментария начинается
 * с обычного слова, поэтому объяснение дефекта попадало в «видимый текст» и
 * сторож находил там `Visual Edit` раньше, чем в самой витрине. Собственный
 * комментарий, прочитанный как содержимое страницы, — тот же класс, что свой
 * префикс вывода, принятый за находку.
 */
function visible(src: string): string {
  return src
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, " ") // JSX-комментарии
    .replace(/\/\*[\s\S]*?\*\//g, " ") // блочные
    .split("\n")
    .filter((l) => !l.trim().startsWith("//"))
    .join("\n");
}

describe("обещание правки кликами совпадает с продуктом", () => {
  test("прибор работает: витрина читается и содержит обещание", () => {
    const v = [visible(read(STOREFRONT)), read(DICT)].join(" ");
    expect(v.length).toBeGreaterThan(1000);
    expect(v).toContain("Visual Edit");
  });

  test("рядом с Visual Edit названо условие — деплой", () => {
    const v = [visible(read(STOREFRONT)), read(DICT)].join(" ");
    const i = v.indexOf("Visual Edit");
    // Условие должно стоять В ТОМ ЖЕ предложении, а не где-то на странице:
    // сноска внизу экрана обещания не исправляет.
    const around = v.slice(Math.max(0, i - 220), i + 120);
    expect(around, "витрина обещает правку кликами, не назвав, что она после деплоя").toMatch(
      // Условие — на языке записи: словарь несёт ru/en/kk.
      /После деплоя|после деплоя|After deploy|after deploy|Орналастырғаннан кейін/,
    );
  });

  test("витрина не ставит Visual Edit перед деплоем в перечислении", () => {
    const v = [visible(read(STOREFRONT)), read(DICT)].join(" ");
    expect(v, "прежняя формулировка вернулась").not.toContain("Дальше — правь кликами");
  });
});

describe("экран правки кликами говорит по-русски", () => {
  test("английских заглушек не осталось", () => {
    const v = visible(read(EDITOR));
    for (const phrase of [
      "Deploy this project to use Visual Edit",
      "Building the live preview",
      "No index.html found",
    ]) {
      expect(v, `английская строка на русской странице: ${phrase}`).not.toContain(phrase);
    }
  });

  test("русские замены на месте — иначе строка могла просто исчезнуть", () => {
    // Проверка направления: «нет английского» выполняется и удалением текста,
    // а это не починка.
    const v = visible(read(EDITOR));
    expect(v).toContain("Сначала разверните проект");
    expect(v).toContain("Собираем живое превью");
    expect(v).toContain("Не найден index.html");
  });
});
