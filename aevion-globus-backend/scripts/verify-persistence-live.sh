#!/usr/bin/env bash
# «Данные переживают выкатку» — доказательство целиком, одним вызовом.
#
# Пять прогонов против НАСТОЯЩЕЙ базы, каждый в своём процессе. Отдельные
# процессы не прихоть: модуль хранит состояние в переменных уровня файла, и
# второй импорт в том же процессе получил бы уже поднятое состояние — проверка
# «свежий контейнер» доказывала бы тогда обратное задуманному.
#
#   1. турниры пишутся в базу
#   2. задача дня пишется в базу
#   3. состояние ПОДНИМАЕТСЯ из базы на пустом томе (обе половины обещания)
#   4. начисление Chessy доходит до базы и не платит дважды
#   5. разные дни дают разные задачи, один день — одну и ту же (ворота запуска:
#      «возврат на второй день»)
#
# Четвёртый прогон работает во ВРЕМЕННОЙ СХЕМЕ той же базы: кошельки и таблицу
# лидеров читает прод, и даже несколько секунд синтетических игроков были бы
# видны людям. Схема удаляется в конце, её отсутствие проверяется.
#
# Почему это отдельный смоук, а не часть обычных тестов: обычные тесты работают
# с поддельной базой. Она уже ТРИЖДЫ отвечала не так, как настоящая (rowCount,
# поле эпохи, недостающий экспорт) и пропускала дефекты, которые живой прогон
# находил за минуту.
#
# Запуск (адрес базы берёт сама Railway, пароль в консоль не попадает):
#   railway run --service Postgres sh -c 'DATABASE_URL="$DATABASE_PUBLIC_URL" \
#     bash scripts/verify-persistence-live.sh'
#
# Коды выхода: 0 — всё доказано; 1 — что-то не сошлось; 2 — базы нет.
#
# Каждый прогон убирает свои следы и ПРОВЕРЯЕТ, что убрал.

set -u
cd "$(dirname "$0")/.."

if [ -z "${DATABASE_URL:-}" ]; then
  echo "DATABASE_URL не задан — проверять нечего. См. шапку файла." >&2
  exit 2
fi

RUN="npx ts-node-dev --transpile-only --no-notify --respawn=false"
failed=0
declare -a RESULTS=()

for step in \
  "турниры пишутся в базу|verify-tournaments-write-live" \
  "задача дня пишется в базу|verify-daily-write-live" \
  "состояние поднимается из базы|verify-adopt-from-db-live" \
  "начисление Chessy доходит до базы|verify-money-path-live" \
  "разные дни дают разные задачи|verify-daily-across-days-live"
do
  title="${step%%|*}"
  file="${step##*|}"
  echo
  echo "═══ $title ═══"
  if $RUN "scripts/$file.ts"; then
    RESULTS+=("  ✓ $title")
  else
    RESULTS+=("  ✗ $title")
    failed=1
  fi
done

echo
echo "═══ ИТОГ ═══"
for line in "${RESULTS[@]}"; do echo "$line"; done
echo
if [ "$failed" -eq 0 ]; then
  echo "Данные шахмат переживут выкатку: запись и чтение доказаны на боевой базе."
else
  # Формулировка намеренно жёсткая: «частично доказано» читается как «работает».
  echo "НЕ ДОКАЗАНО. Пока красная хотя бы одна строка, обещание «данные переживут"
  echo "выкатку» не подтверждено — независимо от того, сколько строк зелёных."
fi
exit "$failed"
