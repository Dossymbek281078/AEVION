import type { Metadata } from "next";

/* Запрет индексации: переход по личной ссылке приглашения.
 *
 * В адресе — ТОКЕН, и попадание такого адреса в поисковый индекс означает, что
 * доступ становится виден любому, кто прочитает выдачу. Прямой аналог —
 * `bank/r/[code]` и `qpaynet/r/[token]`: обе закрыты по той же причине.
 *
 * Найдено 30.08.2026 обходом всех адресов с секретом в пути: из двенадцати
 * таких страниц шесть были без запрета. Класс известен и закрывался по одной,
 * а не разом.
 *
 * Две отдельные причины, обе достаточные сами по себе:
 *   1. Токенов бесконечно много, и каждый отвечал бы 200 с полной страницей —
 *      бесконечный индексируемый мусор.
 *   2. В выдачу попали бы личные идентификаторы рекрутёров. Секретом токен не
 *      является (так и написано в page.tsx), но это не повод публиковать его.
 *
 * Метаданные живут ЗДЕСЬ, а не в page.tsx, потому что страница браузерная
 * ("use client"), а Next не разрешает экспортировать metadata из такой.
 *
 * `follow: true` намеренно: запрещён показ САМОЙ страницы, обход ссылок с неё
 * полезен и не мешает.
 *
 * Сведено 31.08 при сборке к 10.09: обе ветки закрыли этот адрес независимо и
 * одинаково по сути. Взяты оба пояснения — они дополняют друг друга, а не
 * спорят: одно даёт масштаб класса, другое причины и ограничение Next. */
export const metadata: Metadata = {
  robots: { index: false, follow: true },
};

