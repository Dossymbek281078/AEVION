import { describe, expect, it } from "vitest";
import { planningHeights } from "../src/routes/qskyway";
import { CITY } from "../src/routes/qskyway.city";

/**
 * Подстановка высоты слепым ячейкам ПОДГОТОВЛЕНА, но выключена: высоты
 * коридоров — решение основателя. Этот набор существует, чтобы выключенная
 * ветка не протухла: он гоняет ОБА состояния, передавая флаг параметром.
 *
 * Без него получился бы свой же класс «написано, но не вызывается»: код есть,
 * тесты зелёные, а исполняется он никогда — и в день включения выяснится, что
 * он не работает.
 */

const G = CITY.grid;

describe("подстановка высоты слепым ячейкам", () => {
  it("выключенная — отдаёт тот же массив, что и твин, без копии", () => {
    // Именно ТОТ ЖЕ объект: копия означала бы лишнюю память на каждый запрос
    // и, что важнее, риск разойтись с твином незаметно.
    expect(planningHeights(G, false)).toBe(G.heights);
  });

  it("по умолчанию выключена — прод не должен меняться молча", () => {
    expect(
      planningHeights(G),
      "подстановка включилась по умолчанию. Высоты коридоров — решение "
        + "основателя: включать её можно только по его слову, и вместе с "
        + "замером до/после на настоящих маршрутах.",
    ).toBe(G.heights);
  });

  it("включённая поднимает слепые ячейки и НЕ трогает известные", () => {
    const on = planningHeights(G, true);
    expect(on).not.toBe(G.heights);
    let raised = 0;
    for (let i = 0; i < G.heights.length; i++) {
      const isBlind = G.heights[i] > 0 && (G.src?.[i] ?? 0) === 2;
      if (!isBlind) {
        // Известную высоту не трогаем ни на метр: подстановка касается только
        // того, про что мы не знаем ничего.
        expect(on[i]).toBe(G.heights[i]);
        continue;
      }
      // И только ВВЕРХ: понижать записанную высоту нельзя никогда — коридор
      // прошёл бы ниже крыши.
      expect(on[i]).toBeGreaterThanOrEqual(G.heights[i]);
      if (on[i] > G.heights[i]) raised++;
    }
    // Замер 28.08.2026 по этому твину: поднимается 360 ячеек из 498 слепых.
    // Проверяем ПОРЯДОК величины, а не точное число: точное закрепило бы
    // случайность данных, а падение до десятков означало бы, что подстановка
    // перестала работать.
    expect(
      raised,
      "подстановка перестала поднимать слепые ячейки. Замер 28.08.2026 по этому "
        + "твину: 360 из 498. Падение до десятков означает, что она сломалась, "
        + "а не что данные изменились.",
    ).toBeGreaterThan(200);
  });

  it("контроль прибора: слепые ячейки в твине вообще есть", () => {
    // Иначе проверка выше зелена на пустом множестве и не значит ничего.
    let blind = 0;
    for (let i = 0; i < G.heights.length; i++) {
      if (G.heights[i] > 0 && (G.src?.[i] ?? 0) === 2) blind++;
    }
    expect(blind).toBeGreaterThan(100);
  });

  it("повторный вызов отдаёт тот же результат — кэш не портит данные", () => {
    const a = planningHeights(G, true);
    const b = planningHeights(G, true);
    expect(b).toBe(a);
  });
});
