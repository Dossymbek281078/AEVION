// Метаданные обязательны у каждой публичной страницы (сторож pageMetadata), и
// у перенаправления они решают отдельную задачу: закрыть его от поисковика.
// Короткий адрес — это вход для человека из подписи под роликом, а не
// страница: в выдаче ему делать нечего, и без noindex он соревновался бы за
// показы с той страницей, на которую ведёт.
export const metadata: Metadata = {
  title: "AEVION",
  robots: { index: false, follow: true },
};


// /vk — короткий адрес для VK.
//
// ЗАЧЕМ. Замер 29.08.2026: каталог знает девять меток каналов, а коротких
// входов было ТРИ (tt, ig, yt). Остальные адреса отвечали 404 — то есть
// метка vk заведена 21.08.2026 вместе с dz — по тем же причинам. Метка канала берётся из адреса (/go?c=vk), и проставляется она
// только при переходе ПО ССЫЛКЕ. Пока в шапке профиля ссылки нет (личный
// аккаунт TikTok не даёт поле «сайт» до тысячи подписчиков), адрес пишется в
// подписи ТЕКСТОМ — и человек, набирая его руками, приходит без метки, в
// канал direct. То есть ролики работают, а по цифрам этого не видно.
//
// Короткий адрес решает обе задачи разом: его проще набрать с телефона, и он
// сам доставляет метку. Никакой логики здесь нет и быть не должно — только
// перенаправление.
