import { describe, expect, it } from "vitest";
import { allTranslations } from "../__tests__/localeSource";

/**
 * Форма приёма адресов не обещает рассылки, которой нет.
 *
 * ПОВОД (31.08). Обещание написал я сам накануне: «одно письмо на КАЖДЫЙ
 * подключённый город: откуда взяты ограничения, что покрывает сетка
 * потолков и чего она не покрывает». Проверил на следующий день —
 * механизма нет вовсе: подписчику уходит только подтверждение адреса.
 *
 * То есть я пообещал человеку периодическую рассылку с конкретным
 * содержимым, которой никто не пишет и не планировал. Отправка писем
 * вдобавок не моя зона — создать её я бы и не мог.
 *
 * Сторож не про текст, а про ГРАНИЦУ обещания: описание может звать
 * оставить адрес, но не может обещать периодичность («на каждый город»,
 * «per city»), потому что периодичность требует механизма.
 */
// ГРАНИЦА, названная вслух (02.09.2026, найдена мутацией).
//
// Список ЛИТЕРАЛЬНЫЙ и ловит одно: обещание ПЕРИОДИЧНОСТИ — «письмо на
// каждый город». Проверено мутацией: подставил такую фразу, сторож покраснел.
//
// А обещание СОБЫТИЯ он пропускает. Мутация «напишем, как только в вашем
// городе запустятся аэротакси» прошла свободно — и это не дефект сторожа, а
// его область. Я сперва счёл его пустым и полез бы чинить: мутация была вне
// того, что он обязан ловить, и клевета была бы моей ошибкой.
//
// Расширять списком не стоит: перечень фраз против ЛЮБОГО преувеличения
// станет машиной ложных срабатываний, а его начнут отключать. Если тут
// понадобится больше — проверять надо не текст, а наличие механизма, который
// обещание исполняет.
const CADENCE_PROMISES = [
  "каждый подключённый город",
  "каждый город",
  "letter per city",
  "per city we",
  "әр қала бойынша",
];

describe("обещание формы подписки не шире того, что мы делаем", () => {
  it("не обещает письмо на каждый город", () => {
    const T = allTranslations();
    const langs = Object.keys(T);
    // Отрицательный контроль: без языков проверка пуста и зелена.
    expect(langs.length, "словарь пуст — проверять нечего").toBeGreaterThan(1);

    // Проверяем только языки, где ключи модуля ЕСТЬ. Замер 31.08: в
    // словаре 11 языков, ключи qskyway.* есть в трёх (en, ru, kk).
    // Остальные восемь получают английский по цепочке отката
    // (`tbl[lang] || tbl["en"] || key`) — это непереведённость, а не
    // дефект: мусор из имён ключей на экран не попадает.
    //
    // Первая версия требовала ключ у ВСЕХ языков и покраснела бы вечно.
    // Такие проверки отключают, и защиты не остаётся вовсе.
    const translated = langs.filter((l) => (T as Record<string, Record<string, string>>)[l]["qskyway.wait.desc"]);
    expect(translated.length, "ключа нет ни в одном языке — форма без описания").toBeGreaterThan(0);

    const offenders: string[] = [];
    for (const lang of translated) {
      const t = (T as Record<string, Record<string, string>>)[lang];
      const desc = t["qskyway.wait.desc"] ?? "";
      expect(desc.length, lang + ": описание пустое").toBeGreaterThan(10);
      for (const p of CADENCE_PROMISES) {
        if (desc.toLowerCase().includes(p.toLowerCase())) offenders.push(lang + ": " + p);
      }
    }

    expect(
      offenders,
      "форма обещает периодическую рассылку, а механизма нет — уходит только подтверждение адреса: " +
        JSON.stringify(offenders),
    ).toEqual([]);
  });
});
