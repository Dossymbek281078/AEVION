/**
 * Точное число задач на экране обязано быть ПОДПИСАНО как размер банка.
 *
 * Ручка /api/cyberchess-puzzles/meta различает две величины: bankTotal 502 584
 * (сколько задач в банке) и poolSize 500 000 (сколько обслуживается сейчас,
 * упирается в потолок загрузки, capped: true). Страницы берут bankTotal — так
 * прямо написано в роутере, и это осознанное решение, а не случайность.
 *
 * Но голое «502 584 задачи» человек читает как «столько доступно прямо
 * сейчас», а доступен пул. Разница мала (0,5 %), и дело не в ней: на одной
 * странице число уже подписано «в банке» в двух местах, а в шапке стояло без
 * подписи. Одна вещь называлась двумя способами на одном экране.
 *
 * Круглое «500 000+» на /compare оставлено намеренно: там число ЗАШИТО в
 * текст, а зашитое точное разъезжается с продуктом молча — это записано в
 * products.ts, где мутация «десять миллионов» не покраснила ни одного сторожа.
 */

import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { bezKommentariev } from "./bezKommentariev";
import { ruOf } from "./_ruSlovar";

const СТРАНИЦА = bezKommentariev(readFileSync(join(__dirname, "..", "page.tsx"), "utf8"));

describe("число задач на экране", () => {
  it("в шапке подписано как банк", () => {
    // 13–19.10.2026: для не-русских языков подпись — ключ pz.bank; русская осталась с склонением (ccPlural)
    expect(СТРАНИЦА).toContain('+" в банке":cc.t("pz.bank")}{useSF');
    expect(ruOf("pz.bank")).toContain("в банке");
  });

  it("контроль: счётчик по-прежнему живой, а не зашитое число", () => {
    // Если кто-то заменит счётчик литералом, подпись останется верной, а
    // число начнёт врать молча — ровно то, от чего предостерегает products.ts.
    expect(СТРАНИЦА).toContain("pzCountLabel");
    expect(СТРАНИЦА).toContain("bankTotal");
  });

  it("контроль: точное число нигде не зашито в текст страницы", () => {
    expect(СТРАНИЦА).not.toContain("502 584");
    expect(СТРАНИЦА).not.toContain("502584");
  });
});
