import { describe, expect, it } from "vitest";
import { readFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Русские страницы объявляют свой язык, а не наследуют корневой lang="en".
 *
 * ЗАЧЕМ. В корневом макете стоит lang="en" — и для большей части сайта это
 * верно. Но страницы с русским текстом наследуют это объявление, и браузер,
 * видя несоответствие, предлагает (а при включённой настройке — молча делает)
 * машинный перевод НАШЕГО текста. Замер 28.08.2026 на проде: /go и /longevity
 * отдавали 174 и 198 русских слов под lang="en".
 *
 * Скрипты в макете чинят это в браузере (по куке и по содержимому), но само
 * объявление в отдаваемом HTML остаётся неверным — а по нему судят поисковик,
 * экранная читалка и предзагрузочная эвристика браузера.
 *
 * ПОЧЕМУ ЛОКАЛЬНО, А НЕ В ШАБЛОНЕ. Ближайший lang выигрывает у корневого,
 * поэтому хватает пометки на блоке. Приём и вид проверки взяты у
 * cyberchess/launch — чтобы способ на сайте был ОДИН, а не второй свой.
 *
 * Список ведётся руками: он и есть утверждение. Добавили русскую страницу —
 * впишите её сюда, и проверка сразу скажет, помечена ли она.
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, "..");

// Список ищется ОБХОДОМ, а не ведётся руками.
//
// Утром 29.08.2026 здесь был литеральный массив из трёх страниц. К вечеру
// пометку lang="ru" несли ПЯТЬ файлов (добавились /auth и /cyberchess/launch),
// и две из них сторож не проверял вовсе. Список, который ведут руками,
// охраняет не класс, а перечень — и молчит ровно о том, что забыли дописать.
const RU_PAGES: Array<[string, string]> = (() => {
  const out: Array<[string, string]> = [];
  const walk = (dir: string, segs: string[]) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.isDirectory()) {
        if (e.name.startsWith("_") || e.name.startsWith("(") || e.name.startsWith("[")) continue;
        if (segs.length === 0 && (e.name === "api" || e.name === "__tests__")) continue;
        walk(join(dir, e.name), [...segs, e.name]);
      } else if (e.name === "page.tsx" || e.name === "_client.tsx") {
        const src = readFileSync(join(dir, e.name), "utf8");
        if (src.includes('lang="ru"')) out.push(["/" + segs.join("/"), join(dir, e.name)]);
      }
    }
  };
  walk(APP, []);
  return out;
})();

describe("русские страницы объявляют свой язык", () => {
  it("обход находит русские страницы — иначе проверки ниже пусты", () => {
    // Без этого поломка обхода делает сторожа зелёным и бессмысленным.
    // ГРАНИЦА ЭТОГО ПОРОГА, замерено мутацией 30.08.2026. Список RU_PAGES
    // страница попадает ПО ПРИЗНАКУ lang="ru" — то есть убрав признак, её
    // выводят и из проверки тоже. Сегодня страниц ровно 5 при пороге 5, и
    // потеря любой роняет сторожа (проверено: замена lang="ru" на "en" в
    // /go ловится). Появится ШЕСТАЯ — запас станет единицей, и пропажа
    // признака у одной страницы пройдёт молча.
    // Тогда порог надо поднять до фактического числа, а не оставлять 5.
    expect(RU_PAGES.length).toBeGreaterThanOrEqual(5);
  });

  it("на блоке содержимого стоит lang=ru", () => {
    for (const [route, file] of RU_PAGES) {
      const src = readFileSync(file, "utf8");
      expect(src, `${route}: нет <main lang="ru"> — страница наследует корневой lang="en"`)
        .toContain('<main lang="ru"');
    }
  });

  it("страницы действительно русские — иначе пометка стала бы ложью", () => {
    // Пометка ru на английской странице так же вредна, как её отсутствие на
    // русской: она врёт в другую сторону. Считаем по видимой части, без
    // комментариев — они по-русски и в английских файлах тоже.
    for (const [route, file] of RU_PAGES) {
      const src = readFileSync(file, "utf8")
        .replace(/\/\*[\s\S]*?\*\//g, " ")
        .replace(/\/\/[^\n]*/g, " ");
      const cyr = (src.match(/[а-яА-ЯёЁ]/g) || []).length;
      expect(cyr, `${route}: русского текста почти нет — проверьте, верна ли ещё пометка ru`)
        .toBeGreaterThan(400);
    }
  });

  it("английские страницы пометку ru НЕ несут", () => {
    // Обратный контроль: без него проверка выше проходила бы и при пометке,
    // расставленной везде подряд.
    for (const p of [join(APP, "en", "go", "page.tsx"), join(APP, "en", "longevity", "page.tsx")]) {
      expect(readFileSync(p, "utf8"), `${p}: английская страница помечена как русская`)
        .not.toContain('lang="ru"');
    }
  });
});
