import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Признак хранилища доходит до ЭКРАНА, а не только до ответа.
 *
 * 28.08.2026 ручки модуля научились честно говорить, куда легла запись
 * (`storage: "db" | "memory"`). В тот же день выяснилось, что поле не читал
 * НИКТО: греп по всему модулю дал ноль обращений (контроль на заведомой строке
 * — 93 совпадения, то есть прибор был исправен). Правда останавливалась на
 * границе API и до человека не доходила.
 *
 * Это не мелочь именно для переменных окружения: туда кладут ключи провайдеров
 * и строки подключения. Легло в память процесса — при перезапуске исчезнет,
 * выкатка соберётся без них, и причину человек будет искать в своём коде.
 * Зелёный тост «Переменная сохранена» это скрывал.
 *
 * Сторож закрепляет трёх читателей: создание проекта на витрине, сохранение и
 * удаление переменной в рабочем окне.
 */

const DIR = path.resolve(__dirname, "..");
const STOREFRONT = fs.readFileSync(path.join(DIR, "page.tsx"), "utf8");
const WORKSPACE = fs.readFileSync(path.join(DIR, "[id]", "page.tsx"), "utf8");

// Тосты 06.09 переехали в словарь TOAST_UI (доводчик не успевает за ними,
// нужен ru/en/kk). Сторож резолвит showToast(TL.key) в русскую строку из
// ru-блока ТОГО ЖЕ файла — косвенность закреплена, а не прощена: пропади
// ключ или слово из словаря, счёт упадёт и сторож покраснеет.
function resolveToastKeys(ws: string): string {
  const m = ws.match(/const TOAST_UI[^=]*= \{\s*ru: \{([\s\S]*?)\n  \},/);
  const map: Record<string, string> = {};
  if (m) {
    for (const line of m[1].split(String.fromCharCode(10))) {
      const km = line.match(/^\s*([A-Za-z0-9_]+): "(.*)",\s*$/);
      if (km) map[km[1]] = km[2];
    }
  }
  return ws.replace(/TL\.([A-Za-z0-9_]+)/g, (_, k) => '"' + (map[k] ?? '') + '"');
}

describe("признак хранилища доходит до экрана", () => {
  test("прибор исправен: файлы прочитаны и не пусты", () => {
    // Без этого пустой файл сделал бы любую проверку ниже бессмысленной,
    // а `toMatch` по пустой строке просто упал бы непонятной ошибкой.
    expect(STOREFRONT.length).toBeGreaterThan(2000);
    expect(WORKSPACE.length).toBeGreaterThan(2000);
  });

  test("создание проекта на витрине проверяет признак", () => {
    expect(
      /data\.storage === "memory"/.test(STOREFRONT),
      "витрина снова показывает успех, не спросив, куда лёг проект",
    ).toBe(true);
  });

  test("сохранение переменной окружения проверяет признак", () => {
    expect(
      /saved\?\.storage === "memory"/.test(WORKSPACE),
      "тост «Переменная сохранена» снова безусловен",
    ).toBe(true);
  });

  test("удаление переменной окружения проверяет признак", () => {
    // Молчание на удалении читается как успех, а переменная вернётся после
    // перезапуска.
    expect(
      /done\?\.storage === "memory"/.test(WORKSPACE),
      "удаление снова молчит о том, что убрало только из памяти",
    ).toBe(true);
  });

  test("результат платной генерации проверяет признак", () => {
    // Дороже прочего: человек уже заплатил за прогон модели. Файлы в памяти
    // процесса исчезнут при перезапуске, а тост говорил «Создано файлов: N».
    expect(
      /data\.storage === "memory"/.test(WORKSPACE),
      "тост о созданных файлах снова безусловен",
    ).toBe(true);
  });

  test("предупреждения переведены, а не вшиты по-английски", () => {
    // Модуль говорит по-русски; английский текст в тосте — отдельный класс,
    // за которым следит workspaceSpeaksOneLanguage. Здесь проверяем только,
    // что новые строки не появились на латинице.
    const warns = resolveToastKeys(WORKSPACE).match(/showToast\("[^"]*(память|памяти)[^"]*"/g) ?? [];
    expect(warns.length, "предупреждений о памяти не найдено вовсе").toBeGreaterThanOrEqual(2);
  });

  test("откат правок ИИ тоже ПРЕДУПРЕЖДАЕТ, а не просто проверяет признак", () => {
    // Первая версия считала вхождения условия — и мутация её пережила: убрать
    // текст предупреждения можно было, не тронув условие. Третий раз за день
    // тот же дефект: форма закреплена, следствие нет.
    // Считаем ЛЮБУЮ форму: показы идут через data.storage, d.storage, saved?.storage
    // и done?.storage. Прежняя версия знала одну и насчитала 4 из 8 — та же слепая
    // зона детектора, что ловила меня сегодня трижды.
    const nl2 = String.fromCharCode(10);
    const uses = WORKSPACE.split('storage === "memory"').length - 1;
    expect(uses, "показов признака стало меньше шести").toBeGreaterThanOrEqual(6);

    // Считаем СЛЕДСТВИЕ, а не точную фразу: формулировки разные («пропадёт»,
    // «откатится назад», «вернётся»), общее у них одно — человеку сказано про
    // перезапуск. Погоня за дословным совпадением делала сторожа хрупким.
    // Предупреждение про память теперь бывает и СЛОВАРНЫМ (GEN_UI.memoryWarn,
    // локализация гостевого пути 06.09): текст «перезапуск» живёт в словаре, а
    // showToast зовёт GL.memoryWarn. Косвенность закрепляем ЯВНО: словарная
    // строка обязана говорить про перезапуск — иначе ссылка на неё не считается.
    expect(WORKSPACE, "GEN_UI.ru.memoryWarn больше не предупреждает про перезапуск")
      .toMatch(/memoryWarn: "[^"]*перезапуск/);
    const warns = resolveToastKeys(WORKSPACE).split(nl2).filter(
      (s) => s.includes("showToast(") && (s.includes("перезапуск") || s.includes("GL.memoryWarn")),
    ).length;
    expect(warns, "условие есть, а предупреждения нет").toBeGreaterThanOrEqual(uses);
  });
});
