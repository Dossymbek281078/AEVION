/**
 * ЕДИНСТВЕННОЕ место, где проверки берут словари.
 *
 * ⚠️ ЗАЧЕМ ЭТОТ ФАЙЛ ВООБЩЕ СУЩЕСТВУЕТ. Ветка
 * `fix/devhub-media-insert-not-overwrite` (worktree aevion-qrenew) разбирает
 * `i18n-data.ts` на `lib/i18n-lang/{язык}.ts`: 2457 КБ → 2.7 КБ, экспорта
 * `translations` там больше нет. Замер 14.08.2026, на 18.08 в `main` ещё не
 * сошлось.
 *
 * До появления этого файла тот же импорт стоял в ДВУХ проверках, и вторую я
 * завёл сам, уже зная о перестройке. Три копии одной хрупкой зависимости
 * означают три места, где при слиянии надо вспомнить одно и то же, — а
 * вспоминают обычно два.
 *
 * ПОРЯДОК ПРИ СЛИЯНИИ: переключить импорт ЗДЕСЬ, и только здесь. Проверки
 * ниже по течению трогать не нужно — они спрашивают функцию, а не файл.
 * Списки ключей в них удалять нельзя: они и есть доказательство, что перенос
 * ничего не потерял.
 *
 * И почему проверки спрашивают МОДУЛЬ, а не читают исходник: разбор
 * `i18n-data.ts` регуляркой дал три неверных ответа подряд — границы блоков по
 * отступу не совпадают с границами локалей, часть пар упакована по многу в
 * строку, часть значений записана как `\uXXXX` (и сравнение исходного текста
 * объявляло одинаковые строки разными). Импорт снимает все три сразу.
 */

export type LocaleTable = Record<string, Record<string, string>>;

/** Все словари: язык → ключ → строка. */
export function allTranslations(): LocaleTable {
  return translations as LocaleTable;
}

/** Языки платформы в порядке объявления. */
export function allLangs(): readonly string[] {
  return LANGS;
}

