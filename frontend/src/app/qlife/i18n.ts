const DICT: Partial<Record<string, Record<Key, string>>> = { en: EN, ru: RU, kk: KK };

export function tQlife(lang: string, key: Key, vars?: Record<string, string | number>): string {
  let s = DICT[lang]?.[key] ?? EN[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export const QLIFE_KEYS = Object.keys(EN) as Key[];
export const QLIFE_DICT = DICT;

/** Перевод + подпись типа биомаркера (ключ из API → слово на языке страницы). */
export function useQlifeT() {
  const lang = useI18nOptional()?.lang ?? "ru";
  const t = useCallback((key: Key, vars?: Record<string, string | number>) => tQlife(lang, key, vars), [lang]);
  const typeLabel = useCallback((type: string) => (`type.${type}` in EN ? tQlife(lang, `type.${type}` as Key) : type), [lang]);
  return { t, typeLabel, lang };
}
