import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Список измерений конституции объявлен ТРИЖДЫ, в трёх файлах одной области:
 * оценка ИИ, сборка PDF и сравнение конституций. Согласие между ними сейчас
 * есть — и не закреплено ничем.
 *
 * Разойдутся — не упадёт ничего. Документ покажет восемь ползунков, ИИ оценит
 * семь, сходство посчитается по своему набору. Наружу это выглядит как
 * работающий продукт с необъяснимо странными числами.
 *
 * Замер 30.08.2026: три набора по 8 ключей, совпадают полностью. Сторож нужен
 * не для сегодняшнего дня, а для правки, которая добавит девятое измерение в
 * один файл из трёх.
 *
 * Почему не свести в один модуль: это правка в трёх чужих маршрутах сразу, и
 * у каждого своя ветка. Сторож дешевле и ловит тот же класс; свести можно
 * потом, одной сессией.
 */

const R = join(__dirname, "..", "src", "routes");
const FILES = ["constitutionAi.ts", "constitutionPdf.ts", "planetConstitution.ts"];

function keysOf(file: string): string[] {
  const src = readFileSync(join(R, file), "utf8");
  // Совпадение должно быть ТОЧНЫМ: indexOf("const SLIDER_KEYS") находит и
  // SLIDER_KEYS_RENAMED, потому что это префикс. Мутация переименования
  // проходила незамеченной, а комментарий обещал, что она ловится.
  const m = src.match(/const SLIDER_KEYS(?![A-Za-z0-9_])/);
  const i = m ? (m.index as number) : -1;
  if (i < 0) return [];
  const j = src.indexOf("]", i);
  return [...src.slice(i, j).matchAll(/"([a-zA-Z]+)"/g)].map((m) => m[1]);
}

describe("список измерений конституции одинаков во всех копиях", () => {
  it("каждая копия найдена и непуста — иначе сравнение ниже пусто", () => {
    // Отрицательный контроль: без него исчезнувший или переименованный список
    // дал бы два пустых массива, «равных» друг другу, и зелёный тест.
    for (const f of FILES) {
      expect(keysOf(f).length, `${f}: ключей не найдено`).toBeGreaterThan(4);
    }
  });

  it("наборы совпадают по составу и порядку", () => {
    const [a, ...rest] = FILES.map((f) => keysOf(f));
    for (let i = 0; i < rest.length; i++) {
      expect(rest[i], `${FILES[i + 1]} против ${FILES[0]}`).toEqual(a);
    }
  });
});
