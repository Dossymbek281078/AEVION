/**
 * 🔴 ПОД-МЕТКА КАМПАНИИ ДОЖИВАЕТ ДО АНГЛИЙСКОЙ СТРАНИЦЫ.
 *
 * Повод 12.10.2026, идут платные показы $20/день: рекламная ссылка Meta
 * `/longevity?c=meta-book-12-10` у человека с английской кукой уводится на
 * `/en/longevity`, и метка срезалась до `meta`. Мы платили за показы и не
 * могли сказать, какое объявление привело человека: разрез по постам
 * недосчитывал сессии.
 *
 * Причина — не в редиректе: 07.10 у `keepChannel` появился третий довод
 * (сырая метка целиком), а помощник `keepChannelOrProbe` звал его БЕЗ этого
 * довода и тем самым отменял починку. Механизм написан и не позван.
 *
 * Поэтому проверяется СКВОЗНОЙ путь: то, что отдаёт помощник, которым страница
 * собирает адрес английской версии.
 */
import { describe, it, expect } from "vitest";
import { keepChannel, keepChannelOrProbe, channelFrom } from "@/lib/products";

describe("под-метка кампании не срезается на языковом прыжке", () => {
  it("🔴 метка кампании доезжает ЦЕЛИКОМ", () => {
    const сырая = "meta-book-12-10";
    const канал = channelFrom(сырая);
    expect(канал, "метка кампании перестала опознаваться как канал").toBeTruthy();
    const адрес = keepChannelOrProbe("/en/longevity", сырая, канал);
    expect(адрес, `адрес вышел «${адрес}» — под-метка срезана`).toContain(сырая);
  });

  it("🔴 контроль: без починки было бы «c=meta» — проверка это отличает", () => {
    // Если помощник снова начнёт звать keepChannel без сырой метки, адрес
    // станет ровно таким — и проверка выше покраснеет.
    const безПодметки = keepChannel("/en/longevity", channelFrom("meta-book-12-10"));
    expect(безПодметки).not.toContain("meta-book-12-10");
    expect(безПодметки).toContain("meta");
  });

  it("чужая метка в другой канал под-меткой не подменяет канал", () => {
    // Сырая строка доносится, только если ведёт в ТОТ ЖЕ канал: иначе по
    // дороге канал подменился бы чужим словом из адреса.
    const адрес = keepChannelOrProbe("/en/longevity", "yt-nonsense", "instagram");
    expect(адрес).not.toContain("yt-nonsense");
  });

  it("метки нет вовсе — адрес не портится", () => {
    expect(keepChannelOrProbe("/en/longevity", undefined, null)).toBe("/en/longevity");
  });

  it("массив из адреса (Next отдаёт и так) разбирается, а не ломает путь", () => {
    const адрес = keepChannelOrProbe("/en/longevity", ["meta-book-12-10"], channelFrom("meta-book-12-10"));
    expect(адрес).toContain("meta-book-12-10");
  });
});
