/**
 * Что показывать на странице входа из списка внешних провайдеров.
 *
 * ЗАМЕР НА ПРОДЕ 27.08.2026: `GET /api/auth/oauth/providers` отвечает
 *   {"providers":[{"id":"google","configured":false},
 *                 {"id":"github","configured":false}]}
 * — не настроен НИ ОДИН. Условие отрисовки при этом было
 * `oauthProviders.length > 0`, а длина массива равна двум: блок показывался
 * всегда. Кнопки были честно погашены (disabled, серые, пунктир), то есть
 * мёртвыми их назвать нельзя — но человек видел на странице регистрации два
 * способа входа, из которых не работает ни один.
 *
 * И вторая, более грубая часть: подсказка при наведении говорила покупателю
 * «Provider not configured. Set GOOGLE_OAUTH_CLIENT_ID on the backend» —
 * внутренний жаргон на публичной странице.
 *
 * Здесь только РЕШЕНИЕ, отдельно от разметки: его можно прогнать тестом
 * напрямую, а не выскабливать текст из отрисованного дерева.
 */

export type Provider = {
  id: "google" | "github";
  name: string;
  configured: boolean;
};

/**
 * Показывать ли блок внешних входов.
 *
 * Правило одно: блок имеет смысл, только если им можно ВОСПОЛЬЗОВАТЬСЯ хотя
 * бы одним способом. Ноль настроенных — блока нет вовсе: вход по почте на
 * странице есть, и предлагать рядом две нерабочие кнопки значит обещать
 * выбор, которого нет.
 *
 * `null` (список ещё не пришёл или спросить не удалось) — тоже не показываем:
 * пустое место честнее кнопки, про которую неизвестно, работает ли она.
 */
export function shouldShowOauthBlock(providers: Provider[] | null): boolean {
  if (!providers) return false;
  return providers.some((p) => p.configured);
}

/**
 * Подсказка к кнопке. Появляется только там, где блок вообще показан, то есть
 * когда часть провайдеров работает, а часть нет.
 *
 * Никаких имён переменных окружения: человек, наводящий мышь на кнопку входа,
 * не может и не должен ничего настраивать на сервере.
 */
export function providerHint(p: Provider): string {
  return p.configured
    ? `Войти через ${p.name}`
    : `Вход через ${p.name} пока не подключён — воспользуйтесь почтой`;
}
