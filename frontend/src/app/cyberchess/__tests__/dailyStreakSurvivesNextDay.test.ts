import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Серия — единственное, ради чего человек возвращается на второй день.
 * Сбрасывается она по условию diff > 1, где diff — разница в сутках между
 * сегодня и днём последнего решения.
 *
 * Порог здесь на волосок от катастрофы: `>= 1` вместо `> 1` обнулял бы серию
 * КАЖДЫЙ день, то есть ровно у того, кто вернулся, — и выглядело бы это как
 * «человек сам пропустил». Ни один существующий тест этого не ловит: серия
 * считается внутри компонента, при монтировании.
 */
const KOD = readFileSync(join(__dirname, "..", "daily", "page.tsx"), "utf8");

describe("серия переживает возврат на следующий день", () => {
  it("сброс только при пропуске БОЛЬШЕ суток", () => {
    // именно > 1: >= 1 сбрасывал бы у вернувшегося назавтра
    expect(KOD).toMatch(/diff\s*>\s*1\b/);
    expect(KOD).not.toMatch(/diff\s*>=\s*1\b/);
  });

  it("разница считается в сутках, а не в миллисекундах", () => {
    expect(KOD).toMatch(/86400000/);
  });

  it("арифметика дней на разборе дат, а не на строках", () => {
    // сравнение строк "2026-08-31" и "2026-09-01" вычитанием дало бы NaN
    const i = KOD.indexOf("const diff");
    expect(i).toBeGreaterThan(0);
    const stroka = KOD.slice(i, KOD.indexOf("\n", i));
    expect(stroka).toContain("Date.parse");
  });
});
