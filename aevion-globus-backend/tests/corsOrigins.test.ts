/**
 * Кому разрешено ходить в API из браузера.
 *
 * Повод (21.09.2026): форма заявок на витрине агентства молча падала в запасной
 * путь, потому что её домен не попал в CORS_ALLOWED_ORIGINS. Дефект невидим для
 * curl и для тестов исходника — виден только браузеру. Здесь закрываем решение,
 * которое к этому привело: какие источники считаются разрешёнными.
 */
import { describe, it, expect } from "vitest";
import { разрешённыеИсточники, СВОИ_ВИТРИНЫ } from "../src/lib/corsOrigins";

describe("разрешённые источники CORS", () => {
  it("к заданному списку всегда добавляются наши витрины", () => {
    const r = разрешённыеИсточники("https://aevion.app");
    expect(r).toContain("https://aevion.app");
    for (const v of СВОИ_ВИТРИНЫ) expect(r).toContain(v);
  });

  it("КОНТРОЛЬ: пустая переменная оставляет открытый режим, а не закрывает его", () => {
    // Иначе одна наша строка превратила бы «разрешено всё» в «разрешены только мы»
    // и отвалились бы все остальные витрины разом.
    expect(разрешённыеИсточники(undefined)).toEqual([]);
    expect(разрешённыеИсточники("")).toEqual([]);
    expect(разрешённыеИсточники("  ,  ")).toEqual([]);
  });

  it("КОНТРОЛЬ: чужой домен не появляется сам по себе", () => {
    expect(разрешённыеИсточники("https://aevion.app")).not.toContain("https://zloy-sait.example");
  });

  it("повторы не задваиваются", () => {
    const r = разрешённыеИсточники("https://aevion.app," + СВОИ_ВИТРИНЫ[0]);
    expect(r.filter((x) => x === СВОИ_ВИТРИНЫ[0]).length).toBe(1);
  });

  it("витрина агентства в списке — именно тот домен, что на проде", () => {
    expect(СВОИ_ВИТРИНЫ).toContain("https://aevion-agency-site.vercel.app");
  });
});
