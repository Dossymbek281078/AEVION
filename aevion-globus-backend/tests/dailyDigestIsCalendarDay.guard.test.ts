import { describe, it, expect } from "vitest";
import { границыДняАлматы, СМЕЩЕНИЕ_АЛМАТЫ_МС } from "../src/routes/events";

/**
 * Сводка дня считает КАЛЕНДАРНЫЙ день Алматы, а не последние 24 часа.
 *
 * 🔴 Зачем отдельный сторож. Отчёт в 21:00 по скользящему окну захватывает
 * кусок позавчера и теряет кусок вчера — число выглядит правдоподобно и не
 * отвечает на вопрос «сколько было ВЧЕРА». У нас это уже записано правилом
 * (0-ДОКЛАД-ПРОВЕРЕН, п. 7: `days=1` — скользящие сутки).
 *
 * Границы проверяем краями, а не серединой: ошибка в сутки видна только на
 * первой и последней минуте дня.
 */
describe("границы календарного дня Алматы", () => {
  it("день начинается в 19:00 UTC предыдущих суток", () => {
    const { дата, от, до } = границыДняАлматы("2026-10-05");
    expect(дата).toBe("2026-10-05");
    expect(new Date(от).toISOString()).toBe("2026-10-04T19:00:00.000Z");
    expect(new Date(до).toISOString()).toBe("2026-10-05T19:00:00.000Z");
    expect(до - от, "сутки обязаны быть ровно сутками").toBe(24 * 60 * 60 * 1000);
  });

  it("🔴 КРАЯ: 23:59 Алматы — ещё этот день, 00:01 — уже следующий", () => {
    const { от, до } = границыДняАлматы("2026-10-05");
    const почтиПолночь = Date.parse("2026-10-05T23:59:00.000Z") - СМЕЩЕНИЕ_АЛМАТЫ_МС;
    const послеПолуночи = Date.parse("2026-10-06T00:01:00.000Z") - СМЕЩЕНИЕ_АЛМАТЫ_МС;
    expect(почтиПолночь >= от && почтиПолночь < до, "последняя минута дня выпала из дня").toBe(true);
    expect(послеПолуночи >= до, "первая минута следующего дня попала в прошлый").toBe(true);
  });

  it("без даты берётся ВЧЕРА по Алматы, а не сегодня", () => {
    // 06.10 в 02:00 по Алматы — это 05.10 21:00 UTC. Вчера = 05.10.
    const сейчас = new Date("2026-10-05T21:00:00.000Z");
    expect(границыДняАлматы("", сейчас).дата).toBe("2026-10-05");
  });

  it("КОНТРОЛЬ: мусор в параметре не притворяется датой", () => {
    const сейчас = new Date("2026-10-06T10:00:00.000Z");
    const вчера = границыДняАлматы("", сейчас).дата;
    for (const мусор of ["вчера", "2026-13-99", "05.10.2026", "'; DROP TABLE"]) {
      expect(границыДняАлматы(мусор, сейчас).дата, `«${мусор}» принято за дату`).toBe(вчера);
    }
  });

  it("КОНТРОЛЬ: скользящие сутки дали бы ДРУГОЕ окно — ради этого всё и писано", () => {
    const сейчас = new Date("2026-10-06T10:00:00.000Z");
    const { от } = границыДняАлматы("", сейчас);
    const скользящее = сейчас.getTime() - 24 * 60 * 60 * 1000;
    expect(от, "календарное окно совпало со скользящим — проверка ничего не значит").not.toBe(скользящее);
  });
});
