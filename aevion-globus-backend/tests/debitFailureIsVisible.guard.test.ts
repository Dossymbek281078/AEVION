import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Отказ списания расхода не имеет права быть молчаливым.
 *
 * Замер 28.08.2026: девять маршрутов DevHub списывали расход как
 * `debitCredit(...).catch(() => {})`. Это денежная поверхность — списание
 * платного действия, — и по правилу молчать можно только при УБОРКЕ
 * (откат транзакции, закрытие соединения), а не при осмысленном действии.
 *
 * Проверено до правки, что это защита в глубину, а не рабочая ветка:
 * `debitCredit` сам ловит отказ базы и паркует списание в память, а чтение
 * тарифа не бросает. То есть сегодня внешний catch сработать не может — но
 * убирать его нельзя: если внутренности однажды начнут бросать, маршрут упадёт
 * УЖЕ ПОСЛЕ удачной генерации, и человек потеряет результат, за который
 * заплатил.
 *
 * Поэтому отказ остался не смертельным и стал видимым: `debitQuietly` пишет в
 * журнал ЧТО и У КОГО не списалось и отправляет событие в Sentry.
 *
 * СТОРОЖ ПО ИСХОДНИКУ, и это его названная слабость. Поведенческий путь сюда
 * упирается в провайдера: списание стоит ПОСЛЕ успешной генерации, а в тестовых
 * харнесах провайдеров нет намеренно. Он ловит возврат молчаливого проглатывания,
 * но не докажет, что журнал получил именно то сообщение.
 */

/**
 * ПОЛНЫЙ РАЗБОР КЛАССА, чтобы следующий не проходил его заново.
 *
 * В `devhub.ts` было тринадцать мест, где ошибка проглатывается молча. Разобрано
 * по правилу «молчать можно при уборке, нельзя при осмысленном действии»:
 *
 *   9 — списание расхода (`debitCredit`). ДЕФЕКТ, починен: см. `debitQuietly`.
 *   1 — вердикт после выкатки (live/failed). ДЕФЕКТ, починен: без следа
 *       выкатка застревала бы в промежуточном состоянии навсегда.
 *   1 — продвижение тарифа в userId-таблицу. ДОПУСТИМО: тариф уже прочитан
 *       верно, запись лишь ускоряет будущие чтения; её провал не меняет ответа.
 *   2 — удаление временного голоса у ElevenLabs после неудачной озвучки.
 *       ДОПУСТИМО: это уборка, и её провал не должен маскировать исходную
 *       ошибку, ради которой мы и уходим.
 *
 * То есть из тринадцати настоящих дефектов было два. Записывать все тринадцать
 * в находки значило бы утопить эти два.
 */

const FILE = path.join(__dirname, "..", "src", "routes", "devhub.ts");

const read = () => fs.readFileSync(FILE, "utf8");

/** Код без комментариев: объяснение дефекта обязано цитировать прежний вид. */
function code(): string {
  return read()
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .split("\n")
    .filter((l) => !l.trim().startsWith("//"))
    .join("\n");
}

describe("отказ списания виден", () => {
  test("прибор работает: файл читается и списание в нём есть", () => {
    const c = code();
    expect(c.length).toBeGreaterThan(1000);
    expect(c).toContain("debitCredit");
  });

  test("ни одно списание не зовётся мимо обёртки", () => {
    // ПОЧЕМУ НЕ РЕГУЛЯРКОЙ ПО ВЫЗОВУ. Прежняя версия искала
    // `debitCredit(...).catch(() => {})` шаблоном, где аргументы — «что угодно
    // без закрывающей скобки». 28.08.2026 выяснилось, что это делало сторожа
    // декоративным ровно для существующего случая: в вызове списания за
    // озвучку аргумент был `text.trim().length`, скобки внутри, и шаблон
    // обрывался раньше. Сторож отвечал «0» при настоящей находке.
    //
    // Считаем иначе и надёжнее: `debitCredit` имеет право упоминаться только
    // в СВОЁМ объявлении и внутри обёртки. Любое третье упоминание в коде —
    // обход, независимо от того, как записаны аргументы.
    const lines = code()
      .split("\n")
      .map((l, n) => [n + 1, l] as const)
      .filter(([, l]) => l.includes("debitCredit("));
    const allowed = lines.filter(
      ([, l]) =>
        l.includes("async function debitCredit(") ||
        l.includes("return debitCredit(userId, capability, amount)"),
    );
    expect(
      lines.filter((x) => !allowed.includes(x)).map(([n, l]) => `${n}: ${l.trim()}`),
      "списание зовут мимо обёртки — отказ снова невидим",
    ).toEqual([]);
    expect(allowed.length, "объявление и обёртка должны быть на месте").toBe(2);
  });

  test("обёртка называет И что, И у кого не списалось", () => {
    const c = code();
    expect(c).toContain("function debitQuietly");
    // Без обоих след бесполезен: «не списалось» без имени возможности и без
    // пользователя нельзя ни найти, ни возместить.
    expect(c).toMatch(/СПИСАНИЕ НЕ ВЫПОЛНЕНО[^`]*\$\{capability\}/);
    expect(c).toMatch(/СПИСАНИЕ НЕ ВЫПОЛНЕНО[^`]*\$\{userId\}/);
  });

  test("отказ уходит и в Sentry, а не только в консоль", () => {
    // Журнал контейнера переживает перезапуск плохо; денежная пропажа обязана
    // попасть туда, где её увидят на следующий день.
    expect(code()).toMatch(/captureException\(e, \{ route: "devhub\/debitCredit"/);
  });

  test("вердикт выкатки тоже не теряется молча", () => {
    // Та же семья: фоновая задача решает, жив ли деплой, и записывает вердикт.
    // Её отказ оставил бы выкатку в промежуточном состоянии навсегда, а на
    // экране это неотличимо от «ещё собирается».
    const c = code();
    expect(c, "фоновая проверка деплоя снова глотает отказ молча").not.toMatch(
      /\}\)\(\)\.catch\(\(\) => \{\}\)/,
    );
    expect(c).toContain("ВЕРДИКТ ВЫКАТКИ НЕ ЗАПИСАН");
    expect(c).toMatch(/captureException\(e, \{ route: "devhub\/deploy:verify"/);
  });

  test("направление: обёртка НЕ роняет маршрут", () => {
    // «Видно» не должно превратиться в «падает»: генерация уже выполнена и
    // оплачена, терять её из-за учёта нельзя.
    const c = code();
    const body = c.slice(c.indexOf("function debitQuietly"), c.indexOf("type UsageCell"));
    expect(body).toContain(".catch(");
    expect(body).not.toMatch(/throw\s/);
  });
});
