import { describe, it, expect } from "vitest";
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { СМЕЩЕНИЕ_АЛМАТЫ_МС as СМЕЩЕНИЕ_В_СТОРОЖАХ } from "./helpers/суткиАлматы";

/*
 * 🔴 «КАКОЙ СЕГОДНЯ ДЕНЬ» В СТОРОЖАХ СЧИТАЕТСЯ ОДНИМ СПОСОБОМ.
 *
 * Повод в ночь 11→12.10.2026: двенадцать проверок в семи сторожах краснели
 * ровно с 00:00 до 05:00 по Алматы. Ручка `/day` режет сутки по Алматы, а
 * сторожа брали «сегодня» по UTC; с 19:00 UTC даты расходятся, и сторож
 * спрашивал вчерашний день Алматы, записав события сегодняшним.
 *
 * Класс ошибки живуч по двум причинам, и сторож закрывает обе:
 *   1. Смещение `5 * 60 * 60 * 1000` было скопировано в шесть файлов, и в
 *      седьмом функция НАЗЫВАЛАСЬ `деньАлматы`, а считала UTC. Имя лгало, и
 *      прочитать это по имени было нельзя.
 *   2. Ошибка видна только пять часов в сутки. Прогон в рабочее время зелёный,
 *      поэтому «починить и забыть» не работает — нужен надзор, не память.
 *
 * ⚠️ Сторож требует ИМПОРТ помощника, а не запрещает образец «дата по UTC».
 * Запрет был бы ложно-красным: у разреза `byDay` ключи именно в UTC, и дата UTC
 * там законна. Требование положительное: файл, который ПЕРЕДАЁТ дату в ручку
 * суток Алматы, обязан брать её из одного места.
 */

const КАТАЛОГ = __dirname;

/** Этот файл исключён из обхода: он содержит текст О образцах, а не их применение. */
const СВОЙ_ФАЙЛ = "almatyDayIsOneSourceOfTruth.guard.test.ts";

/** Ручки, которые режут сутки по Алматы и принимают дату параметром. */
const ПЕРЕДАЁТ_ДАТУ = [/[?&]day=\$\{/, /[?&]date=\$\{/];

/** Дата, посчитанная как UTC, — ровно то, что ломалось ночью. */
const ДАТА_ПО_UTC = /new Date\(\)\.toISOString\(\)\.slice\(0,\s*10\)/;

const ИМПОРТ_ПОМОЩНИКА = /from\s+"\.\/helpers\/суткиАлматы"/;

/** Своя копия смещения Алматы. Их было шесть, и каждая — ночная мина. */
const ЛИТЕРАЛ_СМЕЩЕНИЯ = /5 \* 60 \* 60 \* 1000/;

/** Любое вычисление даты-строки из времени, чьей бы зоны оно ни было. */
const ВЫЧИСЛЯЕТ_ДАТУ = /toISOString\(\)\.slice\(0,\s*10\)/;

function сторожа(): Array<{ имя: string; текст: string }> {
  return readdirSync(КАТАЛОГ)
    .filter((и) => и.endsWith(".ts") && и !== СВОЙ_ФАЙЛ)
    .map((и) => ({ имя: и, текст: readFileSync(join(КАТАЛОГ, и), "utf8") }));
}

describe("сутки Алматы в сторожах — один источник правды", () => {
  it("🔴 смещение в помощнике совпадает с тем, что считает сервер", async () => {
    /*
     * Два числа об одной вещи обязаны быть связаны проверкой, иначе они
     * разъедутся молча. Помощник держит литерал намеренно (иначе проверка стала
     * бы тавтологией), а связь — здесь.
     */
    const модуль = await import("../src/routes/events");
    const серверное = (модуль as unknown as { СМЕЩЕНИЕ_АЛМАТЫ_МС?: number }).СМЕЩЕНИЕ_АЛМАТЫ_МС;
    expect(типЧисла(серверное), "сервер перестал экспортировать смещение Алматы").toBe(true);
    expect(серверное, "смещение у сторожей и у сервера разъехалось").toBe(СМЕЩЕНИЕ_В_СТОРОЖАХ);
    expect(СМЕЩЕНИЕ_В_СТОРОЖАХ, "смещение Алматы перестало быть UTC+5").toBe(5 * 60 * 60 * 1000);
  });

  it("🔴 литерал смещения Алматы живёт ТОЛЬКО в помощнике", async () => {
    /*
     * Правило намеренно НЕ «обязан импортировать помощник»: первая версия
     * требовала импорт у всех, кто передаёт дату, и покраснела на
     * `dailyDigestAnswersTheHandle`, где дата жёсткая («2026-10-05») и ничего не
     * ломается. Ложно-красный сторож опаснее отсутствующего — к нему привыкают.
     *
     * Правило про литерал точнее: оно убивает именно дубли (их было шесть) и
     * тем самым заставляет взять помощник всякого, кому нужно «сегодня».
     */
    const все = сторожа();
    // Знаменатель печатается и охраняется: зелёный при нулевом охвате — дефект
    // сторожа, а не достижение.
    expect(все.length, "обход не нашёл сторожей — каталог или фильтр изменились").toBeGreaterThan(
      20,
    );
    const сКопией = все.filter((ф) => ЛИТЕРАЛ_СМЕЩЕНИЯ.test(ф.текст));
    expect(
      сКопией.map((ф) => ф.имя),
      "своя копия смещения Алматы: из-за таких копий 12 проверок краснели каждую ночь",
    ).toEqual([]);
  });

  it("🔴 кто САМ считает дату для суточной ручки, берёт её из помощника", async () => {
    /*
     * Охват сужен до суточных ручек ВОРОНКИ намеренно. Вторая версия правила
     * («никто не считает дату-строку сам») покраснела бы на восьми шахматных
     * сторожах задачи дня: у них свой день, возможно по UTC по смыслу продукта,
     * и это чужая зона — судить её, не измерив, значило бы ломать работающее.
     *
     * Файл с ЖЁСТКОЙ датой («2026-10-05») правило не трогает: он ничего не
     * считает от часов, и ночью не краснеет.
     */
    const все = сторожа();
    const передающие = все.filter((ф) => ПЕРЕДАЁТ_ДАТУ.some((о) => о.test(ф.текст)));
    expect(
      передающие.length,
      "файлов, передающих дату в суточную ручку, стало меньше 8 — проверь образец, а не радуйся",
    ).toBeGreaterThanOrEqual(8);

    const считающие = передающие.filter((ф) => ВЫЧИСЛЯЕТ_ДАТУ.test(ф.текст));
    const без = считающие.filter((ф) => !ИМПОРТ_ПОМОЩНИКА.test(ф.текст));
    expect(
      без.map((ф) => ф.имя),
      "эти сторожа считают дату сами: ночью они покраснеют, и вину спишут на чужую правку",
    ).toEqual([]);
  });

  it("🔴 ни один из них не считает «сегодня» по UTC", async () => {
    const все = сторожа();
    const больные = все.filter(
      (ф) => ПЕРЕДАЁТ_ДАТУ.some((о) => о.test(ф.текст)) && ДАТА_ПО_UTC.test(ф.текст),
    );
    expect(
      больные.map((ф) => ф.имя),
      "дата UTC в файле, который спрашивает сутки Алматы, — та самая ночная ошибка",
    ).toEqual([]);
  });

  it("КОНТРОЛЬ: оба образца находят подставленный пример", async () => {
    /*
     * Без этого «ноль нарушений» выше значил бы «не умею искать». Образцы
     * проверяются на строках, ответ по которым известен заранее, и на строках,
     * которые похожи, но нарушением НЕ являются.
     */
    const нарушение = 'await request(app).get(`/api/pricing/events/day?date=${новый()}`)';
    const датаUTC = "const день = new Date().toISOString().slice(0, 10);";
    expect(ПЕРЕДАЁТ_ДАТУ.some((о) => о.test(нарушение))).toBe(true);
    expect(ДАТА_ПО_UTC.test(датаUTC)).toBe(true);
    expect(ЛИТЕРАЛ_СМЕЩЕНИЯ.test("const СМЕЩЕНИЕ = 5 * 60 * 60 * 1000;")).toBe(true);
    expect(ЛИТЕРАЛ_СМЕЩЕНИЯ.test("const СМЕЩЕНИЕ = СМЕЩЕНИЕ_АЛМАТЫ_МС;")).toBe(false);
    // Отрицательные контроли: отличаются РОВНО проверяемым признаком.
    expect(ПЕРЕДАЁТ_ДАТУ.some((о) => о.test("get('/api/pricing/events/day')"))).toBe(false);
    expect(ДАТА_ПО_UTC.test("new Date(Date.now() + смещение).toISOString().slice(0, 10)")).toBe(
      false,
    );
  });
});

function типЧисла(значение: unknown): boolean {
  return typeof значение === "number" && Number.isFinite(значение);
}
