import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * Всякий, кто меняет расстояние в телеметрии, обязан сказать, ОТКУДА оно.
 *
 * ПОВОД (29.08.2026, ворота запуска 4 — «отказ показывается отказом»).
 * Когда бэкенд не отвечает, страница не пустеет: она считает маршрут
 * прямо в браузере и показывает его цифры. Уверенность по высотам и
 * обмеренные участки при этом честно гасятся, а расстояние, высота и
 * время выглядели РОВНО как серверные — по ним и судят о модуле.
 *
 * Признак `local` живёт в самих данных телеметрии, поэтому обновление
 * с полным объектом ловит компилятор: он и нашёл третье место сброса,
 * про которое я забыл.
 *
 * ⚠️ НО СПРЕД КОМПИЛЯТОР НЕ ЛОВИТ. `setStats((s) => ({ ...s, distKm: X }))`
 * без `local` соберётся молча и унаследует признак ПРОШЛОГО маршрута:
 * серверный полёт после запасного останется подписан «посчитано в
 * браузере», и наоборот — запасной прикинется серверным. Второе хуже:
 * ровно от него и заводилась подпись.
 *
 * Отсюда правило, проверяемое статически: кто трогает `distKm`, тот
 * обязан задать и `local`. Оно строже необходимого (можно вообразить
 * правку, меняющую только дистанцию), и это осознанно: цена ложного
 * срабатывания — одно слово в строке, цена пропуска — подпись,
 * описывающая не тот полёт.
 */
const SOURCE = readFileSync(path.join(__dirname, "_client.tsx"), "utf8");

function setStatsCalls(): string[] {
  const out: string[] = [];
  let i = 0;
  for (;;) {
    const at = SOURCE.indexOf("setStats(", i);
    if (at < 0) break;
    // Берём окном, а не регуляркой: собранная из строки регулярка на
    // этой машине теряет обратные слэши и молча находит ноль.
    out.push(SOURCE.slice(at, at + 700));
    i = at + 1;
  }
  return out;
}

describe("телеметрия всегда говорит, откуда её числа", () => {
  it("каждое обновление с distKm задаёт и local", () => {
    const calls = setStatsCalls();

    // Отрицательный контроль: если вызовов не нашлось, проверка пуста,
    // а выглядит зелёной — тот же класс, что «no tests».
    expect(calls.length, "вызовов setStats не найдено — сканер смотрит не туда").toBeGreaterThan(2);

    const touchingDistance = calls.filter((c) => c.includes("distKm:"));
    expect(touchingDistance.length, "ни один вызов не трогает distKm").toBeGreaterThan(2);

    const silent = touchingDistance.filter((c) => !c.includes("local:"));
    expect(
      silent.length,
      "обновление телеметрии меняет distKm и молчит про источник — " +
        "признак останется от прошлого маршрута: " + silent.map((c) => c.slice(0, 90)).join(" ||| "),
    ).toBe(0);
  });

  it("оба состояния действительно встречаются в коде", () => {
    // Без этого правило выше выполнилось бы и при `local: false` везде,
    // то есть при подписи, которая не включается никогда.
    expect(SOURCE.includes("local: true"), "нет ни одного пути, помечающего маршрут местным").toBe(true);
    expect(SOURCE.includes("local: false"), "нет ни одного пути, помечающего маршрут серверным").toBe(true);
    expect(SOURCE.includes('t("qskyway.tel.localRoute")'), "признак есть, а на экран его не выводят").toBe(true);
  });
});
