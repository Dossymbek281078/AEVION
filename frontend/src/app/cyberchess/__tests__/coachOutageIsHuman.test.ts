/**
 * Отказ ИИ-тренера не имеет права доехать до экрана по-английски.
 *
 * ПОВОД. Замер прода 28.09.2026 (окно user-c8, подтверждён мной тем же
 * запросом): `POST /api/coach/chat` отвечает 400 и телом
 *
 *     You have reached your specified API usage limits.
 *     You will regain access on 2026-10-01 at 00:00 UTC.
 *
 * То есть до 1 октября разбор словами не работает вовсе, а полный запуск
 * шахмат — 30.09. Из трёх мест, откуда зовут тренера, человеческий текст был
 * только в одном; в двух других английская строка печаталась дословно.
 *
 * ПОЧЕМУ ПРЕЖНИЕ СТОРОЖА ЭТОГО НЕ ВИДЕЛИ. `angliyskiyNaRusskomEkrane` читает
 * ИСХОДНИК страницы и ловит английские литералы в коде. Здесь литерала нет:
 * строка приходит с сервера во время работы. Проверка исходника по построению
 * слепа к тексту, которого в исходнике нет, — и это не её вина, а граница.
 *
 * Поэтому проверяется ПРЕОБРАЗОВАНИЕ (что показываем на данный ответ) и
 * отдельно — что места вызова больше не печатают сырое сообщение.
 */

import { describe, it, expect, beforeEach } from "vitest";
import { readFileSync } from "fs";
import { join } from "path";
import {
  отказТренера,
  лимитПровайдера,
  пометкаОВыключенномРазборе,
  тренерОтветил,
  пометкаЗапаснойМодели,
} from "../coachOutage";

const ОТВЕТ_ПРОВАЙДЕРА =
  "You have reached your specified API usage limits. " +
  "You will regain access on 2026-10-01 at 00:00 UTC.";

const читать = (имя: string) =>
  readFileSync(join(process.cwd(), "src/app/cyberchess", имя), "utf8");

beforeEach(() => {
  тренерОтветил();
});

describe("отказ тренера человеческими словами", () => {
  it("лимит поставщика распознаётся", () => {
    expect(лимитПровайдера(ОТВЕТ_ПРОВАЙДЕРА)).toBe(true);
  });

  it("контроль: обычная ошибка лимитом НЕ считается", () => {
    // Без этого контроля проверка выше проходила бы и у функции,
    // которая отвечает «да» на что угодно.
    expect(лимитПровайдера("Server error 500")).toBe(false);
    expect(лимитПровайдера("")).toBe(false);
  });

  it("на экран идёт русский текст со сроком, а не строка поставщика", () => {
    const текст = отказТренера(ОТВЕТ_ПРОВАЙДЕРА);
    expect(текст).toContain("1 октября");
    expect(текст.toLowerCase()).not.toContain("usage limit");
    expect(текст.toLowerCase()).not.toContain("regain access");
  });

  it("текст называет, что продолжает работать — иначе человек решит, что сломано всё", () => {
    expect(отказТренера(ОТВЕТ_ПРОВАЙДЕРА)).toContain("движком");
  });

  it("без даты в ответе срок не выдумывается", () => {
    const текст = отказТренера("You have reached your specified API usage limits.");
    expect(текст).toContain("выключен");
    expect(текст).not.toContain("вернётся");
  });

  it("таймаут и сеть остаются своими сообщениями, а не «лимитом»", () => {
    expect(отказТренера("aborted", "AbortError")).toContain("долго");
    expect(отказТренера("Failed to fetch")).toContain("соединение");
  });

  it("любой неизвестный отказ тоже по-русски, а не эхом сообщения", () => {
    const текст = отказТренера("Some internal English failure text");
    expect(текст).not.toContain("Some internal English failure text");
    expect(текст).toContain("недоступен");
  });
});

describe("пометка на витрине появляется по состоянию и снимается", () => {
  it("до отказа пометки нет", () => {
    expect(пометкаОВыключенномРазборе()).toBe("");
  });

  it("после отказа по лимиту пометка есть и называет срок", () => {
    отказТренера(ОТВЕТ_ПРОВАЙДЕРА);
    expect(пометкаОВыключенномРазборе()).toContain("1 октября");
  });

  it("обычный отказ пометку НЕ ставит — иначе пугали бы выключением, которого нет", () => {
    отказТренера("Server error 500");
    expect(пометкаОВыключенномРазборе()).toBe("");
  });

  it("ответ тренера пометку снимает", () => {
    отказТренера(ОТВЕТ_ПРОВАЙДЕРА);
    expect(пометкаОВыключенномРазборе()).not.toBe("");
    тренерОтветил();
    expect(пометкаОВыключенномРазборе()).toBe("");
  });
});

describe("подмена модели не проходит молча", () => {
  it("ответ основной модели ничем не помечается", () => {
    // Пусто здесь — это «перехода не было», а не «мы не знаем»: поле
    // failedOver появляется ТОЛЬКО при переходе.
    expect(пометкаЗапаснойМодели({ content: [], provider: "anthropic" })).toBe("");
    expect(пометкаЗапаснойМодели(null)).toBe("");
  });

  it("ответ запасной модели назван — витрина обещает разбор уровня супер-GM", () => {
    const текст = пометкаЗапаснойМодели({ failedOver: { from: "anthropic", tried: ["anthropic", "gemini"] } });
    expect(текст).toContain("запасная модель");
    // И тут же сказано, что продолжает работать в полную силу.
    expect(текст).toContain("движок");
  });

  it("оба места вызова приклеивают пометку к ответу", () => {
    for (const имя of ["page.tsx", "AiCoach.tsx"]) {
      expect(читать(имя), имя).toContain("пометкаЗапаснойМодели(data)");
    }
  });
});

describe("места вызова тренера не печатают сырое сообщение", () => {
  it("AiCoach больше не показывает e.message как есть", () => {
    const код = читать("AiCoach.tsx");
    expect(код).toContain("отказТренера(");
    expect(код).not.toContain('sError(e?.message');
    expect(код).not.toContain("Connection failed");
  });

  it("«А что если» читает ТЕЛО ответа и показывает человеческий текст", () => {
    const код = читать("WhatIfButton.tsx");
    expect(код).toContain("отказТренера(");
    // Раньше тело не читали вовсе — человек видел «Ошибка: HTTP 400».
    expect(код).not.toContain("Ошибка: ${e?.message");
  });

  it("окно после партии считает признак лимита там же, где остальные", () => {
    const код = читать("page.tsx");
    expect(код).toContain("лимитПровайдера(");
    // Второй копии правила распознавания в странице быть не должно:
    // копии расходятся молча.
    expect(код).not.toContain("credit balance");
  });
});
