/**
 * Раскладка рабочего окна проекта DevHub: дерево файлов и рабочая область.
 *
 * Замер 12.10.2026 на проде (388b8a56589b, окно 390×844, путь покупателя
 * «описал фразой → Построить → смотрю, что получилось»): после генерации
 * превью открывается само и без прокрутки — но шириной 115 px из 390, то есть
 * 29 % экрана. Остальное забирает дерево файлов: у него стояло
 * `width: 260, flexShrink: 0`, и на телефоне 260 из 390 — это две трети.
 * В кадре было видно «Мой Спис Дел» в три строки по слову и обрезанное поле
 * ввода. Человек платит за приложение, которого не видит.
 *
 * На широком окне (1463×724) превью занимало 1188 px — там всё в порядке,
 * и перекладывать нечего. Поэтому порог, а не переделка макета.
 */

/** Ниже этой ширины окна колонки не помещаются рядом (тот же порог, что в шахматах). */
export const УЗКИЙ_ЭКРАН_PX = 769;

/** Высота дерева файлов, когда оно уезжает наверх отдельной полосой. */
export const ВЫСОТА_ДЕРЕВА_СВЕРХУ_PX = 148;

/** Ширина дерева файлов на широком окне. */
export const ШИРИНА_ДЕРЕВА_PX = 260;

export type МакетРабочегоОкна = {
  /** true — дерево и рабочая область идут друг под другом, а не рядом. */
  другПодДругом: boolean;
  /** Ширина дерева файлов. */
  ширинаДерева: number | string;
  /** Высота дерева, когда оно сверху; иначе растягивается на всю колонку. */
  высотаДерева: number | string;
  /** Где у дерева граница — справа (колонкой) или снизу (полосой сверху). */
  границаДереваСнизу: boolean;
};

/**
 * Раскладка по ширине окна. Решение принимается ОДНИМ числом, поэтому его
 * можно проверить без браузера — и мутация порога сразу краснеет.
 */
export function maketRabochegoOkna(ширинаОкна: number): МакетРабочегоОкна {
  const узкий = ширинаОкна < УЗКИЙ_ЭКРАН_PX;
  return {
    другПодДругом: узкий,
    ширинаДерева: узкий ? "100%" : ШИРИНА_ДЕРЕВА_PX,
    высотаДерева: узкий ? ВЫСОТА_ДЕРЕВА_СВЕРХУ_PX : "auto",
    границаДереваСнизу: узкий,
  };
}

/**
 * Сколько останется рабочей области по ширине при данной раскладке.
 * Нужна ровно для того, чтобы утверждение «превью во всю ширину» было
 * числом, а не обещанием: на телефоне это вся ширина окна, на широком —
 * окно минус дерево.
 */
export function shirinaRabochejOblasti(ширинаОкна: number): number {
  return maketRabochegoOkna(ширинаОкна).другПодДругом
    ? ширинаОкна
    : ширинаОкна - ШИРИНА_ДЕРЕВА_PX;
}
