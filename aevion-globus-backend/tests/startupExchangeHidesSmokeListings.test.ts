import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { isSmokeListing, PUBLIC_LISTING_SQL } from "../src/routes/startupExchange";

/**
 * Публичное лицо биржи не состоит из наших же проверок.
 *
 * Замер на проде 01.09.2026: `/api/startupx/ideas?limit=50` вернул 19 заявок,
 * из них 18 с заголовком «Smoke Idea smoke-1784…», девятнадцатая — «T».
 * То есть витрина главного продукта была целиком нашими смоук-прогонами.
 *
 * Инвестор, пришедший смотреть заявки, видел девятнадцать пустых записей.
 * Основатель стартапа видел то же и не подавал свою.
 */

/** Настоящие заголовки с прода — не выдуманные. */
const СЛУЖЕБНЫЕ = [
  "Smoke Idea smoke-1784775224034",
  "Smoke Idea smoke-1778836053723",
  "smoke-1779081653057",
  "T",
];

/**
 * Так выглядят заголовки людей. Половина списка подобрана НАРОЧНО похожей:
 * если признак ловит начало слова, а не служебность, эти строки его выдадут.
 */
const ЛЮДИ = [
  "Smokehouse — доставка мяса",
  "Smoked glass UI kit",
  "Trucker — биржа перевозок",
  "T-Bank для самозанятых",
  "Тепличное хозяйство под ключ",
];

describe("витрина биржи не показывает служебные заявки", () => {
  it("узнаёт все служебные заголовки с прода", () => {
    for (const t of СЛУЖЕБНЫЕ) {
      expect(isSmokeListing(t), `не распознан служебный: ${t}`).toBe(true);
    }
  });

  it("НЕ трогает заголовки людей — иначе спрячем настоящие заявки", () => {
    // Контроль важнее находки: фильтр, прячущий всё подряд, сделал бы витрину
    // честно пустой и одинаково бесполезной. «Smokehouse» и «T-Bank» обязаны
    // остаться — иначе признак ловит начало слова, а не служебность.
    for (const t of ЛЮДИ) {
      expect(isSmokeListing(t), `настоящую заявку приняли за смоук: ${t}`).toBe(false);
    }
  });

  it("условие для базы и предикат для памяти описаны одними правилами", () => {
    // Два источника правды по устройству: SQL исполняет Postgres, предикат — мы.
    // Разойтись они могут молча, и тогда счётчик и список снова заспорят.
    expect(PUBLIC_LISTING_SQL).toContain("^Smoke Idea");
    expect(PUBLIC_LISTING_SQL).toContain("^smoke([-_0-9]|$)");
    expect(PUBLIC_LISTING_SQL).toContain("title = 'T'");
  });

  it("условие применено ВЕЗДЕ, где спрашивается публичность", () => {
    /*
     * Здесь и был настоящий дефект-близнец: отфильтруй мы только список, а
     * счётчики оставь — витрина заспорила бы сама с собой («0 заявок» рядом с
     * «19 всего»). Ровно это чинилось часом раньше в QPersona.
     */
    const src = readFileSync(join(__dirname, "..", "src", "routes", "startupExchange.ts"), "utf8");
    const своиКопии = src.split("visibility='public'").length - 1;
    expect(
      своиКопии,
      "где-то осталась своя копия условия публичности — счётчик разойдётся со списком",
    ).toBe(1); // ровно одно: внутри самой константы
    const вПамяти = src.split('visibility === "public"').length - 1;
    const сФильтром = src.split('!isSmokeListing(').length - 1;
    expect(сФильтром, "путь в памяти закрыт не везде").toBeGreaterThanOrEqual(вПамяти);
  });
});
