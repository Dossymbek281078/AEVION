import { describe, test, expect, vi, afterEach } from "vitest";
import { render, screen, waitFor } from "@testing-library/react";
import { I18nProvider } from "@/lib/i18n";
import Client from "./_client";

/**
 * Ворота запуска 2 и 4, на уровне ПОВЕДЕНИЯ, а не разметки.
 *
 * ПОВОД (29.08.2026). У страницы одиннадцать кнопок, и обработчики есть у
 * всех — это я проверил перечислением. Но ворота спрашивают не «есть ли
 * обработчик», а что видит человек. Ни один тест страницу не отрисовывал:
 * все проверки были либо статические (греп по исходнику), либо на
 * вынесенных модулях.
 *
 * Здесь страница поднимается целиком в jsdom с УПАВШЕЙ сетью — состояние,
 * в котором она оказывается у любого, к кому не доехал бэкенд. Требуется
 * ровно одно: человек видит человеческий текст, а не пустой чёрный экран
 * и не «Error: city 500».
 *
 * ⚠️ Граница: canvas в jsdom не рисует, поэтому карта и телеметрия здесь
 * не проверяются — только то, что показывается ВМЕСТО них при отказе.
 */
// Отказ на трёх языках: тест не должен зависеть от того, какую локаль
// подставит провайдер по умолчанию.
const FAILURE_TEXTS = [
  "Could not load the city data",
  "Не удалось загрузить данные города",
  "Қала деректерін жүктеу мүмкін болмады",
];

const realFetch = globalThis.fetch;
afterEach(() => {
  globalThis.fetch = realFetch;
  vi.restoreAllMocks();
});

function renderWithDeadBackend() {
  globalThis.fetch = vi.fn(() => Promise.reject(new Error("network down"))) as unknown as typeof fetch;
  return render(
    <I18nProvider>
      <Client />
    </I18nProvider>,
  );
}

describe("страница при недоступном бэкенде", () => {
  test("показывает человеческий отказ, а не пустой экран", async () => {
    const r = renderWithDeadBackend();

    await waitFor(
      () => {
        const text = r.container.textContent ?? "";
        // Язык провайдера в тесте не задан, поэтому принимаем ЛЮБОЙ из
        // трёх: первая версия ждала русский, получила английский и
        // покраснела на исправной странице. Проверяем смысл, не локаль.
        expect(
          FAILURE_TEXTS.some((t) => text.includes(t)),
          "при мёртвой сети страница не сказала человеку ничего — он видит пустой экран и уходит",
        ).toBe(true);
      },
      { timeout: 8000 },
    );
  }, 30000);

  test("в тексте отказа нет кодов и адресов серверов", async () => {
    // Ворота 4 дословно: «тексты ошибок — человеческие, без кодов и
    // адресов серверов». Сырая ошибка живёт в подсказке (title), и это
    // осознанно; проверяем ВИДИМЫЙ текст.
    const r = renderWithDeadBackend();
    await waitFor(() => expect((r.container.textContent ?? "").length).toBeGreaterThan(0), { timeout: 8000 });

    const visible = r.container.textContent ?? "";
    for (const leak of ["localhost", "127.0.0.1", "/api/", "Error:", "TypeError"]) {
      expect(visible.includes(leak), "в видимом тексте утекло служебное: " + leak).toBe(false);
    }
  }, 30000);

  test("кнопок на экране всё же несколько — страница не схлопнулась в заглушку", async () => {
    // Отрицательный контроль. Без него оба утверждения выше прошли бы и
    // на странице, которая при отказе рисует ОДНУ строку и ничего больше:
    // формально «человеческий текст есть», а продукта нет.
    const r = renderWithDeadBackend();
    await waitFor(
      () => expect(FAILURE_TEXTS.some((t) => (r.container.textContent ?? "").includes(t))).toBe(true),
      { timeout: 8000 },
    );
    // Порог 1, а не «побольше». Первая версия требовала больше двух —
    // число взято из моей головы, а не из требования, и покраснела на
    // ИСПРАВНОМ поведении: при мёртвых данных страница честно прячет
    // сетку (`{!err && …}`) и оставляет отказ плюс управление. Это верно:
    // рисовать интерфейс поверх отсутствующих данных хуже, чем не рисовать.
    // Контроль нужен ровно против одного — экрана, где НЕТ НИЧЕГО.
    expect(
      r.container.querySelectorAll("button").length,
      "на экране отказа не осталось ни одного управляющего элемента — человеку нечем даже повторить",
    ).toBeGreaterThan(0);
  }, 30000);
});
