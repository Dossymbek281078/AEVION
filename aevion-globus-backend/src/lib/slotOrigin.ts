// Кем оставлена бронь в рынке 4D-слотов: человеком или нашим же смоук-прогоном.
//
// 10.08.2026, живой aevion.app: `GET /api/qskyway/slots` отдавал `count: 34`, и
// 33 из них были маршруты `smoke-route-…` с держателями `op0..op3`, `late`,
// `verify`, `smoke-holder`. Причина не в единичном сбое: прод-смок бронирует
// пять-шесть слотов КАЖДЫЙ прогон (`scripts/qskyway-smoke.js`, уникальный
// routeId на запуск, чтобы не ловить коллизию) и ничего за собой не убирает.
// То есть число росло бы вечно, а публичная страница выдавала бы его за
// глубину рынка.
//
// Чиним не удалением: право там зафиксировано по-настоящему, квитанция честная,
// и стирать записи ради красивой цифры — худшее из решений. Отделяем: сервер
// по-прежнему отдаёт всё, но говорит про каждую запись, тестовая ли она, и
// считает отдельно «живую» глубину рынка. Признак живёт ЗДЕСЬ, на сервере,
// чтобы у фронта и у смока не завелось по своей копии правила.

export interface SlotOriginLike {
  routeId?: string | null;
  holder?: string | null;
}

/** Держатели, которыми представляются смоук-сценарии (см. scripts/*-smoke.js). */
const SMOKE_HOLDERS = new Set([
  "smoke-holder", "verify", "op0", "op1", "op2", "op3", "late", "h0", "h1", "h2", "h3",
]);

/**
 * Тестовая ли бронь.
 *
 * Маршрут — основной признак: смоки строят `smoke-route-…`. Держатель — второй,
 * для записей, где маршрут назван иначе. Оба намеренно грубые: ошибка в сторону
 * «пометил тестовой настоящую» видна человеку и чинится, обратная — снова
 * выдаёт наш прогон за рынок.
 */
export function isSmokeSlot(slot: SlotOriginLike): boolean {
  const route = (slot.routeId ?? "").toLowerCase();
  if (route.startsWith("smoke-") || route.includes("-smoke-")) return true;
  return SMOKE_HOLDERS.has((slot.holder ?? "").toLowerCase());
}

/** Сколько записей в списке оставлено не смоком. */
export function countLiveSlots(slots: readonly SlotOriginLike[]): number {
  return slots.reduce((n, s) => n + (isSmokeSlot(s) ? 0 : 1), 0);
}
