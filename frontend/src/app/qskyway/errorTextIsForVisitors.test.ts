import { describe, expect, it } from "vitest";
import { allTranslations } from "../__tests__/localeSource";

/**
 * Сообщение об ошибке QSkyway говорило посетителю: «Проверь, что бэкенд поднят
 * (/api/qskyway/city)». Человек, зашедший на публичную страницу, поднять
 * бэкенд не может — такой текст лишь сообщает ему, что о нём не думали.
 *
 * Найдено 28.08.2026 чтением страницы глазами новичка, а не проверкой
 * правильности: сообщение было ВЕРНЫМ по смыслу и переведённым на три языка.
 *
 * ⚠️ Граница: сторож смотрит ТОЛЬКО ключи `qskyway.err.*`, то есть тексты
 * отказов. Технические слова в подсказках и раскрытиях модуля он не трогает
 * НАМЕРЕННО: «слоты живут в памяти процесса и теряются при перезапуске» — это
 * честное раскрытие ограничения демо, и запрещать его значило бы поощрять
 * умолчание. Аудитория модуля — инженеры и регуляторы, им техническое слово в
 * подсказке уместно. Недопустимо оно там, где человек ждёт, что ему скажут,
 * ЧТО ДЕЛАТЬ.
 */

// Слова, которые в тексте ОТКАЗА означают «сделай работу разработчика».
const DEV_ONLY = ["бэкенд", "backend", "localhost", ":4001", "npm ", "docker", "консол"];

describe("тексты отказов QSkyway обращены к посетителю", () => {
  const T = allTranslations();

  it("контроль прибора: словари прочитаны и ключи отказов в них есть", () => {
    // Иначе «запрещённых слов нет» верно и для пустого словаря.
    expect(Object.keys(T).length).toBeGreaterThan(2);
    const errKeys = Object.keys(T.ru || {}).filter((k) => k.startsWith("qskyway.err."));
    expect(errKeys.length, "ключей qskyway.err.* нет — проверять нечего").toBeGreaterThan(0);
  });

  for (const lang of ["en", "ru", "kk"]) {
    it(`${lang}: отказ не просит человека чинить инфраструктуру`, () => {
      const table = (T[lang] || {}) as Record<string, string>;
      const bad: string[] = [];
      for (const [k, v] of Object.entries(table)) {
        if (!k.startsWith("qskyway.err.")) continue;
        const low = String(v).toLowerCase();
        for (const w of DEV_ONLY) {
          if (low.includes(w)) { bad.push(k + ": " + String(v).slice(0, 60)); break; }
        }
      }
      expect(
        bad,
        "в тексте отказа стоит инструкция разработчику. Посетитель не может её "
          + "выполнить: скажите, что делать ЕМУ (обновить страницу, зайти позже), "
          + "а техническую подробность положите в подсказку или журнал.",
      ).toEqual([]);
    });
  }
});
