import { describe, it, expect } from "vitest";
import { bezKommentariev } from "./bezKommentariev";
import { readFileSync } from "fs";
import { join } from "path";
import { SUPPORTED_LOCALES, tFor } from "../i18n";

/**
 * Английские слова на русском экране шахмат.
 *
 * Найдено не грепом, а перехватом того, что модуль САМ отправляет на живой
 * перевод: на каждый свежий заход /cyberchess уходит POST с семью строками.
 * Список отправленного и есть список того, что модуль считает нерусским.
 *
 * Замер на проде 31.08.2026 показал важное: имена (CyberChess, Chessy,
 * Puzzle Rush) возвращаются НЕИЗМЕННЫМИ и кэшируются — бренд не мнётся, и
 * тревоги здесь нет. А вот «AI» возвращается как «AI»: платный путь идёт и
 * не даёт ничего, потому что чинить надо в исходнике.
 *
 * Сторож намеренно НЕ запрещает имена собственные: Lichess, Chessy,
 * CyberChess и Puzzle Rush остаются как есть — это названия, а не перевод.
 */

const KOD = () => readFileSync(join(process.cwd(), "src/app/cyberchess/page.tsx"), "utf8");

describe("на экране шахмат нет английских слов вместо русских", () => {
  // Перечень дословных фраз ловит только те места, о которых я знал. Класс
  // шире: 01.09.2026 подпись ползунка силы соперника была ровно «AI», и все
  // прежние проверки её пропустили — они искали «AI ≈ {rat}» и «Master AI».
  // Нашла её не проверка, а сама страница: она отправила «AI» живому
  // переводчику как нерусское слово.
  it("нет и СОСТАВНЫХ «AI-…» — они пережили прошлую чистку", () => {
    // 03.09.2026: одиночное «AI» я убрал 01.09 и отчитался. Составные жили
    // дальше и были видны человеку: «AI-уровень» в поиске, «AI-соперник» в
    // описании, «AI-наставник» в палитре команд, «AI-движок Stockfish» на
    // витрине модуля. Шаблон на одиночное слово их не ловил.
    const s = bezKommentariev(KOD());
    const места = [...s.matchAll(/AI-/g)].length;
    expect(места, "«AI-…» на русском экране: пиши «ИИ-…»").toBe(0);
    // контроль прибора в обе стороны
    expect([...bezKommentariev('const a = "AI-тренер";').matchAll(/AI-/g)].length).toBe(1);
    expect([...bezKommentariev('// тут был AI-тренер').matchAll(/AI-/g)].length).toBe(0);
  });

  it("на экране нет ОДИНОЧНОГО «AI» — только «ИИ»", () => {
    const s = KOD();
    const места = [...s.matchAll(/>\s*AI\s*</g)].length;
    expect(места, "подпись ровно «AI»: пиши «ИИ»").toBe(0);
    // контроль прибора: он обязан находить одиночное слово, а не молчать всегда
    expect([...">AI<".matchAll(/>\s*AI\s*</g)].length).toBe(1);
    // и обязан НЕ трогать составные — «AI-тренер» это другой разговор
    expect([...">AI-тренер<".matchAll(/>\s*AI\s*</g)].length).toBe(0);
  });

  it("«AI» рядом с рейтингом соперника — по-русски", () => {
    // 05.10.2026 подпись уехала из кода в словарь (перевод на казахский).
    // Спрашиваем словарь: требовать литерал в page.tsx теперь значит краснеть
    // на верной правке. Смысл проверки тот же — на русском экране не «AI».
    const рус = tFor("ru", "mode.quick.sub");
    expect(рус, "ключа mode.quick.sub нет в русском словаре").not.toBe("mode.quick.sub");
    expect(рус).toContain("ИИ");
    expect(рус).not.toContain("AI");
    // И в английском он обязан БЫТЬ — иначе проверка выше доказывает лишь то,
    // что слова «AI» нет нигде.
    expect(tFor("en", "mode.quick.sub")).toContain("AI");
  });

  it("подписи задачи дня Lichess переведены, имя сервиса сохранено", () => {
    const s = KOD();
    expect(s).not.toContain("🌐 Lichess Daily");
    const рус = tFor("ru", "chip.lichessDaily");
    expect(рус, "ключа chip.lichessDaily нет в русском словаре").not.toBe("chip.lichessDaily");
    expect(рус).toContain("Задача дня");
    // Имя сервиса обязано остаться на ВСЕХ языках: это не перевод, а название.
    for (const { code } of SUPPORTED_LOCALES) {
      expect(tFor(code, "chip.lichessDaily"), `${code}: пропало имя сервиса`).toContain("Lichess");
    }
  });

  it("название уровня в описании совпадает с кнопкой", () => {
    // На кнопке уровень уже назывался «Мастер», в описании оставался
    // «Master AI» — два имени одного и того же в одном интерфейсе.
    const s = KOD();
    expect(s).not.toContain("Открытие Master AI");
    expect(s).toContain("Открытие уровня «Мастер»");
    // 05.10.2026 подпись уровня уехала в словарь (перевод на казахский), и
    // требование литерала краснело бы на верной правке. Проверяем, что имя
    // берётся из словаря, а в русском словаре оно по-прежнему «Мастер».
    expect(s, "подпись закрытого уровня больше не подставляется из словаря").toContain('🔒 {cc.t("ai.master")}');
    expect(tFor("ru", "ai.master"), "в русском словаре уровень назван иначе, чем на кнопке").toBe("Мастер");
  });
});
