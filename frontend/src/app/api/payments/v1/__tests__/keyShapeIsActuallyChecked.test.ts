import { describe, test, expect } from "vitest";
import { NextRequest } from "next/server";
import { authError } from "../_lib";

/**
 * Сторож: проверка формы ключа не декоративная.
 *
 * ЗАЧЕМ. Авторизация этого API намеренно проверяет только ФОРМУ ключа —
 * сверки с базой нет, и это осознанный размен для демонстрационного контура.
 * Но именно поэтому форма и есть весь вход: ослабь её, и подойдёт любая
 * строка после слова Bearer.
 *
 * Замер 01.09.2026: мутация «принимать что угодно» (PREFIX_RE → /.*\/) НЕ была
 * поймана — все 38 тестов остались зелёными. То есть единственная преграда
 * ничем не охранялась.
 *
 * Проверяются ОБЕ преграды, потому что они независимы: отсутствие заголовка и
 * непохожий ключ отбиваются разными ветками.
 */
function запрос(заголовок?: string) {
  return new NextRequest("https://example.test/api/payments/v1/links", {
    headers: заголовок ? { Authorization: заголовок } : {},
  });
}

describe("вход по ключу проверяется по-настоящему", () => {
  test("КОНТРОЛЬ: правильный по форме ключ проходит", () => {
    // Без этого «всё отбивается» означало бы, что сторож про другое.
    expect(authError(запрос("Bearer sk_test_abcdefgh12345678"))).toBeNull();
  });

  test("заголовка нет — отказ 401", () => {
    const e = authError(запрос());
    expect(e?.code).toBe(401);
  });

  test.each([
    ["мусор после Bearer", "Bearer not-a-key-at-all"],
    ["ключ без префикса", "Bearer abcdefgh12345678"],
    ["префикс есть, длины нет", "Bearer sk_test_abc"],
    ["пустой ключ", "Bearer "],
    ["чужая схема", "Basic sk_test_abcdefgh12345678"],
  ])("%s — отказ 401", (_имя, заголовок) => {
    const e = authError(запрос(заголовок));
    expect(e?.code, `вход принял «${заголовок}»`).toBe(401);
  });
});
