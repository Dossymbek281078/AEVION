import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * Действие, которое человек НАЧАЛ, не имеет права закончиться тишиной.
 *
 * Найдено 13.09.2026 чтением запасного пути «нет WebGL». Кнопка «Скачать
 * модель (GLB)» рисуется всегда, а обработчик начинался строкой
 *
 *     const t = three.current; if (!t) return;
 *
 * Без WebGL сцены нет, значит нажатие не делало НИЧЕГО: ни файла, ни
 * сообщения, ни следа. Человек жмёт второй раз, третий — и уходит, считая
 * сломанным весь модуль, хотя смета, разбивка по помещениям и чертёж в SVG
 * в этот момент исправны: они считаются из плана, а не из сцены.
 *
 * Отличать законное молчание от дефекта: молчать МОЖНО, когда проваливается
 * уборка или обработчик указателя (в этом же файле таких возвратов
 * четырнадцать, и они оставлены намеренно). Молчать НЕЛЬЗЯ, когда
 * проваливается действие, начатое нажатием.
 *
 * Сторож смотрит ровно одно: у обработчика выгрузки ранний выход обязан
 * что-то СКАЗАТЬ. Шире он не лезет — правило «каждый ранний выход обязан
 * говорить» было бы неверным и покраснело бы на четырнадцати законных.
 */
// Комментарии вырезаются ДО разбора. Первая редакция резала ветку по слову
// "return" — и находила его в собственном комментарии «молчаливый return»,
// то есть обрезала кусок раньше setWarnings и краснела на исправном коде.
// Четвёртый случай этого класса за день: текст О вещи неотличим от вещи.
const КЛИЕНТ = readFileSync(path.join(__dirname, "_client.tsx"), "utf8")
  .split(/\r?\n/)
  .filter((строка) => !/^\s*\/\//.test(строка))
  .join(String.fromCharCode(10));

function телоФункции(имя: string): string {
  const i = КЛИЕНТ.indexOf(`const ${имя} = useCallback(`);
  expect(i, `функция ${имя} не найдена — сторож проверял бы пустоту`).toBeGreaterThan(-1);
  // Хватает начала: ранний выход по отсутствию сцены стоит первым делом.
  return КЛИЕНТ.slice(i, i + 1200);
}

describe("выгрузка не отказывает молча", () => {
  it("контроль прибора: тело функции найдено и непустое", () => {
    expect(телоФункции("exportGlb").length).toBeGreaterThan(400);
  });

  it("при отсутствии сцены выгрузка говорит человеку, а не молчит", () => {
    const тело = телоФункции("exportGlb");
    const естьРанний = /if\s*\(!t\)/.test(тело);
    expect(естьРанний, "проверка на отсутствие сцены исчезла — сторож устарел").toBe(true);
    // Признак — вызов, который что-то ПОКАЗЫВАЕТ, внутри этой же ветки.
    const ветка = тело.slice(тело.search(/if\s*\(!t\)/));
    const доКонцаВетки = ветка.slice(0, ветка.indexOf("return"));
    expect(
      /setWarnings\(|setError\(/.test(доКонцаВетки),
      "выход без сцены снова молчит: кнопка нажимается и не делает ничего",
    ).toBe(true);
  });

  // Признак ДВУСОСТАВНЫЙ, и это не придирка. Первая редакция требовала
  // только слова «смета» рядом — и мутация, превратившая фразу в «Смета,
  // разбивка по ничего не выйдет», прошла молча: слово на месте, а
  // утверждения, что оно РАБОТАЕТ, больше нет. Назвать возможность и не
  // сказать, что она жива, — это не сообщение, это обрывок.
  const ЖИВОЕ = /смет|чертёж|помещени|площад/i;
  const РАБОТАЕТ = /работа(ют|ет)|считаются|можно пользоваться|доступн/i;

  it("сообщение называет, что ПРОДОЛЖАЕТ работать, а не только что сломалось", () => {
    const тело = телоФункции("exportGlb");
    expect(тело, "отказ не называет ни одной живой возможности").toMatch(ЖИВОЕ);
    expect(тело, "возможность названа, но не сказано, что она работает").toMatch(РАБОТАЕТ);
  });

  it("запасной текст при отсутствии WebGL тоже называет живое", () => {
    const i = КЛИЕНТ.indexOf("Браузер не дал создать WebGL-контекст");
    expect(i, "запасной текст исчез").toBeGreaterThan(-1);
    const кусок = КЛИЕНТ.slice(i, i + 700);
    expect(кусок, "запасной текст не называет ни одной живой возможности").toMatch(ЖИВОЕ);
    expect(кусок, "возможность названа, но не сказано, что она работает").toMatch(РАБОТАЕТ);
  });
});
