/** Пробы, созданные до соглашения об именовании. Только точные совпадения id. */
export const ПРОБЫ_БЕЗ_МЕТКИ = new Set<string>([
  "cert-c597672d2aab5cd1", // "claim check 2" — прогон окна приёмки
  "cert-f7ac411b5a1929ad", // "1" — пустая проба
  "cert-54825970871a4eb6", // "Музыка 1" — пустая проба
]);

/** Название или автор помечены как наш прогон — по соглашению §19. */
export function этоНашаПроба(запись: { id?: unknown; title?: unknown; author?: unknown }): boolean {
  const id = String(запись.id ?? "");
  if (ПРОБЫ_БЕЗ_МЕТКИ.has(id)) return true;
  const текст = `${String(запись.title ?? "")} ${String(запись.author ?? "")}`.toLowerCase();
  return /\bprobe\b|probe-|\bsmoke\b|smoke-|smoke test|\bqa-cycle\b/.test(текст);
}
