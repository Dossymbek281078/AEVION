import { describe, it, expect } from "vitest";
import { readdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { АНГЛИЙСКИЕ_СТРАНИЦЫ_СО_СВОИМ_АДРЕСОМ } from "../englishPages";

/**
 * Каждая страница под app/en обязана быть в списке английских адресов.
 *
 * Повод, а не гипотеза. Замер 08.10.2026 на проде: `/en/yt`, `/en/ig` и
 * `/en/tt` отвечали 308 и уводили на `/yt`, `/ig`, `/tt` — то есть на РУССКИЕ
 * страницы, хотя сами эти страницы существуют и перенаправляют на английские
 * посадочные. Причина: их не было в списке, и middleware считал их адресами
 * «без своей английской версии», для которых префикс надо срезать.
 *
 * Что видел человек: под английским роликом в описании стоит короткий вход,
 * он нажимает — и попадает на «Что почитать и попробовать», кириллицы 1470
 * против 156 латиницы (замер с заголовком Accept-Language: en).
 *
 * Проверяем КЛАСС, а не три случая: список сверяется с содержимым каталога.
 * Заведут завтра `app/en/tg` и забудут строку — узнаем здесь, а не из того,
 * что англоязычный зритель молча ушёл.
 */
const HERE = dirname(fileURLToPath(import.meta.url));
const EN = join(HERE, "..", "..", "app", "en");

/** Все адреса вида /en/..., у которых на диске есть page.tsx. */
function страницыПодEn(каталог: string, префикс = "/en"): string[] {
  const out: string[] = [];
  for (const e of readdirSync(каталог, { withFileTypes: true })) {
    if (!e.isDirectory() || e.name === "__tests__") continue;
    const путь = join(каталог, e.name);
    const адрес = `${префикс}/${e.name}`;
    if (existsSync(join(путь, "page.tsx"))) out.push(адрес);
    out.push(...страницыПодEn(путь, адрес));
  }
  return out;
}

describe("английские адреса не теряются по дороге к посетителю", () => {
  const найденные = страницыПодEn(EN);

  it("прибор видит предмет: страницы под /en найдены", () => {
    // ЗНАМЕНАТЕЛЬ. Без него проверка ниже стала бы зелёной на пустом обходе:
    // «ни одной страницы не нашли — значит все перечислены».
    expect(найденные.length, "обход каталога app/en ничего не нашёл").toBeGreaterThan(8);
    expect(найденные).toContain("/en/go");
  });

  it("каждая существующая страница под /en перечислена в списке", () => {
    const список = new Set(АНГЛИЙСКИЕ_СТРАНИЦЫ_СО_СВОИМ_АДРЕСОМ as readonly string[]);
    const потерянные = найденные.filter((а) => !список.has(а));
    expect(
      потерянные,
      `эти адреса существуют, но middleware срежет им префикс и уведёт на русскую страницу: ${потерянные.join(", ")}`,
    ).toEqual([]);
  });

  it("ОТРИЦАТЕЛЬНЫЙ контроль: список не объявляет несуществующего", () => {
    // Обратная ошибка тише: адрес объявлен английским, страницы нет, человек
    // получает 404 вместо русской версии.
    const лишние = (АНГЛИЙСКИЕ_СТРАНИЦЫ_СО_СВОИМ_АДРЕСОМ as readonly string[]).filter(
      (а) => !найденные.includes(а),
    );
    expect(лишние, `объявлены английскими, но страниц нет: ${лишние.join(", ")}`).toEqual([]);
  });

  it("короткие входы роликов на месте — именно они приводят людей", () => {
    for (const вход of ["/en/yt", "/en/ig", "/en/tt"]) {
      expect(найденные, `страницы ${вход} нет на диске`).toContain(вход);
      expect(
        АНГЛИЙСКИЕ_СТРАНИЦЫ_СО_СВОИМ_АДРЕСОМ as readonly string[],
        `${вход} не в списке — англоязычный зритель уйдёт на русскую страницу`,
      ).toContain(вход);
    }
  });
});
