import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Касса, у которой разбор тарифа имеет УМОЛЧАНИЕ, обязана сперва спросить:
 * а это вообще про подписку?
 *
 * ЗАЧЕМ. Вебхук приходит на ВЕСЬ аккаунт кассы, а не только на заказы нашего
 * чекаута. Прямой перевод, счёт, старая подписка — событие придёт, почта в нём
 * будет, ссылки нашего формата не будет. Дальше `tierForReference` возвращает
 * умолчание `lite`, и человек, не покупавший у нас ничего, получает доступ.
 *
 * У PayBox это закрыто 04.09 после замера. В тот же вечер нашлось, что у PayPal
 * ровно та же цепочка и ни одного сторожа: единственная проверка была на почту.
 *
 * ГРАНИЦА, названная честно. Это сторож ФОРМЫ: он видит, что вызов правила
 * стоит в файле, но не проверяет, что путь исполнения через него проходит.
 * Поведение самого правила закреплено отдельно и мутационно
 * (paymentWithoutTierGrantsNoTier). Форма здесь нужна ради другого: чтобы блок
 * нельзя было удалить незаметно — а именно так тихие правки и происходят.
 *
 * ПОЧЕМУ GUMROAD НЕ В СПИСКЕ — и точная формулировка, потому что первая была
 * неточной. Разбор тарифа у него ТАКОЙ ЖЕ подстрочный и с тем же умолчанием
 * `lite`; я написал в коммите «явная таблица» и, перепроверив, увидел, что
 * таблица относится к другому месту.
 *
 * Защита у Gumroad есть и стоит ВЫШЕ умолчания: `KNOWN_PERMALINK_REFERENCE` —
 * явная карта известных товаров, где книги и разовые руководства помечены как
 * `external` и подписки не выдают. Карта появилась после настоящего убытка:
 * три книжные покупки (27 и 29 мая, 2 июня) выдали платный тариф.
 *
 * Остаточный риск у него другой по природе: новый товар, не внесённый в карту,
 * снова провалится в умолчание. Это стережётся не вопросом «про подписку ли
 * ссылка» (у Gumroad ссылка — permalink, а не наш формат), а полнотой карты.
 * Требовать от него нашего правила значило бы завести сторожа, краснеющего на
 * правильном коде.
 */

const SRC = join(__dirname, "..", "src", "routes");

/** Кассы, у которых разбор тарифа заканчивается умолчанием. */
const С_УМОЛЧАНИЕМ = ["payboxWebhook.ts", "paypalWebhook.ts"];

describe("вебхуки с умолчанием спрашивают, про подписку ли ссылка", () => {
  it("контроль: файлы читаются и содержат разбор тарифа", () => {
    // Иначе «правило вызывается везде» означало бы «я читаю пустоту».
    for (const f of С_УМОЛЧАНИЕМ) {
      const код = readFileSync(join(SRC, f), "utf8");
      expect(код.length, `${f} пуст`).toBeGreaterThan(500);
      expect(код, `${f} не разбирает тариф — список устарел`).toContain("tierForReference(reference)");
    }
  });

  it("каждая такая касса зовёт общее правило", () => {
    const без = С_УМОЛЧАНИЕМ.filter(
      (f) => !readFileSync(join(SRC, f), "utf8").includes("ссылкаПодписки(reference)"),
    );
    expect(
      без,
      "касса разбирает тариф с умолчанием и НЕ спрашивает, про подписку ли ссылка: " +
        "платёж мимо нашего чекаута выдаст человеку доступ",
    ).toEqual([]);
  });

  it("правило берётся из общего модуля, а не копией", () => {
    // Три копии разбора тарифа уже разошлись между кассами. Четвёртой копии
    // правила быть не должно.
    for (const f of С_УМОЛЧАНИЕМ) {
      const код = readFileSync(join(SRC, f), "utf8");
      expect(код, `${f} не импортирует общее правило`).toContain(
        'from "../lib/payment/subscriptionReference"',
      );
    }
  });
});
