import { describe, it, expect } from "vitest";
import { keepChannel, withChannel, channelFrom, postFrom, CHANNELS, нашаМетка } from "@/lib/products";

/** Подменяет адрес страницы: метка по умолчанию читается именно оттуда. */
function наАдресе(search: string) {
  Object.defineProperty(window, "location", {
    configurable: true,
    value: { ...window.location, search },
  });
}

/*
 * 🔴 ПОД-МЕТКА ПЕРЕЖИВАЕТ ВТОРОЙ ПРЫЖОК.
 *
 * Нашло окно fd 07.10.2026, подтвердил по коду я: страницы берут из адреса
 * НОРМАЛИЗОВАННЫЙ канал и строят из него внутренние ссылки, а `keepChannel`
 * писал канонический КЛЮЧ. То есть `/en/devhub?c=ph-launch1` → нажатие →
 * `/devhub?c=ph`: канал цел, имя поста умирает на втором прыжке. Вызовов 53,
 * на горячих путях 15.
 *
 * Чем это стоило: разрез по постам отвечает «какой ролик или какое объявление
 * привело человека», и терялся он у тех, кто пошёл дальше первой страницы —
 * у самых заинтересованных. Для платной кампании это разница между «канал
 * окупился» и «окупилось вот это объявление».
 *
 * Проверяется КРУГОМ: из построенного адреса метка должна читаться обратно в
 * тот же канал и тот же пост. Сравнивать строки адреса бессмысленно — важно,
 * что разбор вернёт то же самое.
 */
function меткаИз(url: string): string | null {
  const m = /[?&]c=([^&#]+)/.exec(url);
  return m ? decodeURIComponent(m[1]) : null;
}

describe("под-метка переживает внутренний переход", () => {
  it("🔴 keepChannel доносит сырую метку целиком", () => {
    const адрес = keepChannel("/devhub", "product-hunt", "ph-launch1");
    const метка = меткаИз(адрес);
    expect(метка, "под-метка потеряна на втором прыжке").toBe("ph-launch1");
    // Круг: из адреса читаются и канал, и пост.
    expect(channelFrom(метка!)).toBe("product-hunt");
    expect(postFrom(метка!)).toBe("launch1");
  });

  it("🔴 метка берётся ИЗ АДРЕСА, когда её не передали явно", async () => {
    /*
     * Нашло окно fd: механизм я сделал, а вызовы к нему не подключил — сырую
     * метку передавали четыре места из 53. Среди голых вызовов был самый
     * дорогой: `/en/devhub` → бесплатная проба, единственный путь с английской
     * посадочной. Подключать 53 места по одному значило бы чинить случаи и
     * оставить 54-й следующему, поэтому метка читается из адреса страницы.
     */
    наАдресе("?c=ph-launch1");
    const адрес = keepChannel("/devhub", "product-hunt");
    expect(меткаИз(адрес), "метка из адреса не подхвачена").toBe("ph-launch1");
    expect(postFrom(меткаИз(адрес)!)).toBe("launch1");
  });

  it("🔴 НАША проба доносится, иначе её второй просмотр станет живым человеком", () => {
    /*
     * Вторая находка того же окна, и она дороже первой. У метки `probe-fd`
     * канал null и пост null, поэтому прежнее условие её не доносило: заход
     * `/en/devhub?c=probe-fd` на втором прыжке терял метку, и просмотр
     * записывался ЖИВЫМ. Ровно это завышение «прямых» 30.09 дало пять начал
     * оплаты, прочитанных покупателями.
     */
    expect(нашаМетка("probe-fd"), "список наших меток не знает probe-*").toBeTruthy();
    наАдресе("?c=probe-fd");
    const адрес = keepChannel("/devhub", null);
    expect(меткаИз(адрес), "наша проба потеряна на втором прыжке").toBe("probe-fd");
  });

  it("КОНТРОЛЬ: явный аргумент сильнее адреса", () => {
    // Иначе ссылка, построенная НЕ для текущей страницы, унесла бы чужую метку.
    наАдресе("?c=ph-launch1");
    expect(меткаИз(keepChannel("/devhub", "youtube", "yt-anons"))).toBe("yt-anons");
    // И пустая строка как явный аргумент означает «метки нет», а не «возьми из адреса».
    expect(меткаИз(keepChannel("/devhub", "product-hunt", ""))).toBe("ph");
  });

  it("КОНТРОЛЬ: чужая метка ИЗ АДРЕСА канал не подменяет", () => {
    наАдресе("?c=yt-anons");
    expect(меткаИз(keepChannel("/devhub", "product-hunt")), "канал подменён из адреса").toBe("ph");
  });

  it("🔴 без сырой метки поведение прежнее — канонический ключ", () => {
    // Обратная сторона: страницы, которые сырую метку не передают, не должны
    // внезапно получить пустую ссылку или чужое значение.
    const адрес = keepChannel("/devhub", "product-hunt");
    expect(меткаИз(адрес)).toBe("ph");
    expect(channelFrom("ph")).toBe("product-hunt");
  });

  it("🔴 КОНТРОЛЬ: сырая метка ЧУЖОГО канала не подменяет канал", () => {
    // Строка приходит из адреса, то есть снаружи. Если бы её брали на веру,
    // ссылка «?c=yt-anons» на странице Product Hunt унесла бы человека в
    // youtube — подмена канала, которую в разрезе незнакомых меток не видно.
    const адрес = keepChannel("/devhub", "product-hunt", "yt-anons");
    expect(меткаИз(адрес), "чужая метка подменила канал").toBe("ph");
  });

  it("КОНТРОЛЬ: мусор в сырой метке не попадает в адрес", () => {
    const адрес = keepChannel("/devhub", "product-hunt", "ph-launch1<script>");
    const метка = меткаИз(адрес);
    // Либо очищенная метка того же канала, либо откат к ключу — но не мусор.
    expect(метка === "ph-launch1script" || метка === "ph").toBe(true);
    expect(метка).not.toContain("<");
  });

  it("🔴 касса получает СЫРУЮ метку, а не только канал", () => {
    /*
     * Иначе продажа придёт с каналом «meta» и без имени кампании, и
     * сопоставить выручку с конкретным объявлением будет нечем. Канал из сырой
     * метки восстанавливается разбором, обратно — нет.
     */
    const адрес = withChannel(
      "https://store.lemonsqueezy.com/buy/abc-123",
      "meta",
      "longevity",
      "meta-book-06-10",
    );
    expect(адрес, "в кассу ушёл только канал").toContain(
      `checkout[custom][channel]=${encodeURIComponent("meta-book-06-10")}`,
    );
  });

  it("КОНТРОЛЬ: ПОДПИСАННЫЙ адрес кассы не дополняется ничем", () => {
    // Замер 20.09.2026: добавление параметра к подписанному адресу даёт 403.
    // Это правило старше моей правки и должно остаться в силе.
    const подписанный = "https://store.lemonsqueezy.com/checkout/buy/x?signature=abc";
    expect(withChannel(подписанный, "meta", "longevity", "meta-book-06-10")).toBe(подписанный);
  });

  it("метка кампании книги переживает круг целиком", () => {
    // Путь, который пойдёт завтра: приход на /longevity?c=meta-book-06-10,
    // затем внутренний переход.
    const внутренняя = withChannel("/pricing", "meta", "longevity", "meta-book-06-10");
    const метка = меткаИз(внутренняя);
    expect(метка).toBe("meta-book-06-10");
    expect(channelFrom(метка!)).toBe("meta");
    expect(postFrom(метка!)).toBe("book-06-10");
  });

  it("КОНТРОЛЬ прибора: каталог каналов непуст и знает оба ключа", () => {
    // Иначе все утверждения выше были бы истиной ни о чём.
    /*
     * ⚠️ Порог взят ИЗМЕРЕНИЕМ, а не на глаз: ключей в каталоге 29 (07.10.2026).
     * Первая версия этой строки требовала «не меньше 30» — число я назвал по
     * памяти и сторож честно покраснел. Днём того же дня я указывал соседу на
     * литерал вместо порога; тут наступил на то же сам. Поэтому порог с
     * запасом вниз: он ловит исчезновение каталога, но не ломается на добавлении.
     */
    expect(Object.keys(CHANNELS).length).toBeGreaterThanOrEqual(25);
    expect(CHANNELS.ph).toBe("product-hunt");
    expect(CHANNELS.meta).toBe("meta");
  });
});
