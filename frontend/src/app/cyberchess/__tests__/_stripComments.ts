/* Вырезание комментариев для сторожей.
 *
 * Два способа сделать это плохо, оба измерены на живом коде 11.08.2026:
 *
 * 1. НАИВНАЯ РЕГУЛЯРКА `/\/\*[\s\S]*?\*\//`. Принимает `/*` внутри строкового литерала
 *    за начало комментария. В `page.tsx` таким оказался `accept="image/*"`: фальшивый
 *    комментарий закрылся только на следующем настоящем `*​/` — через 7574 символа и
 *    77 строк живого кода, среди которых, например, переключатели звука. Итого из файла
 *    выбрасывалось 13.3% вместо 7.4% настоящих комментариев: около 64 КБ кода сторожа
 *    просто не видели.
 *
 * 2. ПОЛНЫЙ РАЗБОР СО СТРОКАМИ И ШАБЛОНАМИ. Ломается наоборот: одна незакрытая (с точки
 *    зрения наивного разбора) обратная кавычка — и весь остаток файла считается
 *    шаблонной строкой, комментарии перестают вырезаться совсем. На `AiCoach.tsx` так и
 *    вышло: выжил комментарий, ради которого сторож и был написан, и проверка «вызов
 *    существует» стала бы зелёной на ЗАКОММЕНТИРОВАННОМ вызове.
 *
 * Отказ №2 опаснее: он даёт ложный ЗЕЛЁНЫЙ, а №1 в положительных проверках даёт красный.
 *
 * Здесь третий вариант — построчный разбор. Состояние кавычек сбрасывается на каждой
 * строке (обычный литерал не переносится), а шаблонные литералы намеренно НЕ
 * отслеживаются: цена — `//` внутри многострочного шаблона будет вырезан, то есть
 * потеряется одна строка, а не семьдесят семь. Из трёх зол это единственное, у которого
 * ущерб ограничен строкой и не зависит от того, что написано этажом выше.
 */

export function stripComments(src: string): string {
  const out: string[] = [];
  let inBlock = false;

  for (const line of src.split("\n")) {
    let res = "";
    let quote: '"' | "'" | null = null;
    let i = 0;

    while (i < line.length) {
      const c = line[i];
      const next = line[i + 1];

      if (inBlock) {
        if (c === "*" && next === "/") {
          inBlock = false;
          i += 2;
        } else {
          i += 1;
        }
        continue;
      }

      if (quote) {
        res += c;
        if (c === "\\") {
          if (i + 1 < line.length) res += line[i + 1];
          i += 2;
          continue;
        }
        if (c === quote) quote = null;
        i += 1;
        continue;
      }

      if (c === '"' || c === "'") {
        quote = c;
        res += c;
        i += 1;
        continue;
      }

      if (c === "/" && next === "*") {
        inBlock = true;
        i += 2;
        continue;
      }

      if (c === "/" && next === "/") {
        break; // остаток строки — комментарий
      }

      res += c;
      i += 1;
    }

    out.push(res);
  }

  return out.join("\n");
}
