import { describe, test, expect, vi, beforeEach } from "vitest";
import { tierForReference as поPayBox } from "../src/routes/payboxWebhook";
import { tierForReference as поPayPal } from "../src/routes/paypalWebhook";
import { TIERS } from "../src/data/pricing";

/**
 * Сторож: за какой тариф заплатили, тот и выдаём.
 *
 * ЗАЧЕМ. Ручка чекаута принимает тарифы явным списком, а ссылку заказа строит
 * из id тарифа. Разбор ссылки в вебхуках знал только часть имён, и всё
 * незнакомое проваливалось в дефолт `lite`. Замер до починки (31.08.2026):
 * `tier_pro_monthly` -> "lite" при контроле `tier_medium_monthly` -> "medium",
 * то есть покупатель старшего тарифа получал самый дешёвый.
 *
 * С 15.09.2026 тариф — это СРОК, и касса строит ссылку `tier_<ступень>`
 * (tier_lite … tier_max). Прежние ссылки `tier_<тариф>_<период>` не продаются,
 * но по ним уже купили, и продление придёт с ними же: они обязаны выдавать
 * тариф новой лестницы (lite→lite, medium→medium, full/planet/pro→full).
 *
 * Обе кассы держат СВОЮ обёртку разбора, поэтому проверяются обе: сторож на одну
 * из двух — это ровно то «хотя бы один», что переживает потерю второго.
 */
const кассы: Array<[string, (r: string) => string]> = [
  ["PayBox", поPayBox],
  ["PayPal", поPayPal],
];

describe.each(кассы)("%s: ссылка заказа выдаёт купленный тариф", (_имя, разбор) => {
  beforeEach(() => {
    // Незнакомая ссылка предупреждает — шум глушим, иначе он утонет в выводе.
    vi.spyOn(console, "warn").mockImplementation(() => {});
  });

  test.each([
    // Ссылки лестницы сроков — то, что касса строит сейчас.
    ["tier_lite", "lite"],
    ["tier_medium", "medium"],
    ["tier_pro", "pro"],
    ["tier_full", "full"],
    ["tier_max", "max"],
    ["tier_enterprise", "enterprise"],
    // Прежние ссылки — продления уже купленного.
    ["tier_lite_monthly", "lite"],
    ["tier_medium_monthly", "medium"],
    ["tier_full_annual", "full"],
    ["tier_pro_monthly", "full"],
    ["tier_planet_annual", "full"],
    ["tier_enterprise_annual", "enterprise"],
  ])("%s -> %s", (ссылка, ожидаем) => {
    expect(разбор(ссылка)).toBe(ожидаем);
  });

  test("КОНТРОЛЬ: прежняя tier_pro_monthly НЕ выдаёт новую ступень pro", () => {
    // Прежний «pro» был всей экосистемой помесячно, а новый pro — шесть месяцев
    // вперёд. Выдать по старой ссылке новую ступень значило бы подарить полгода.
    expect(разбор("tier_pro_monthly")).not.toBe("pro");
    expect(разбор("tier_pro")).toBe("pro");
  });

  test("подстрока не выдаёт себя за тариф: tier_promo_ это НЕ pro", () => {
    // `includes("pro")` поймал бы промо-ссылку и выдал бы за неё старший тариф.
    // Точный разбор этого не делает.
    expect(разбор("tier_promo_monthly")).not.toBe("pro");
    expect(разбор("tier_promo")).not.toBe("pro");
  });

  test("незнакомая ссылка по-прежнему падает в lite, а не в старший тариф", () => {
    // Направление дефолта осознанное: ошибиться в пользу платящего дороже,
    // чем раздать всем старший тариф. Меняется только то, что известные
    // тарифы больше не считаются незнакомыми.
    expect(разбор("совершенно-другой-формат-42")).toBe("lite");
  });
});

describe("храповик: новый тариф в каталоге обязан быть понят кассой", () => {
  // Сегодняшний дефект родился не из опечатки, а из РАСХОЖДЕНИЯ ДВУХ СПИСКОВ:
  // каталог продавал шесть тарифов, разбор ссылки знал четыре образца, и
  // разницу не считал никто. Точечная проверка «pro даёт pro» этого класса не
  // закрывает — она закрывает один его случай.
  //
  // Здесь список берётся ИЗ КАТАЛОГА, а не переписывается в тест. Заведут
  // ещё один тариф — сторож покраснеет до того, как первый покупатель получит
  // не то, за что заплатил.
  const продаваемые = TIERS.filter((t) => t.id !== "free");

  test("в каталоге есть что проверять", () => {
    // Контроль охвата: если TIERS однажды опустеет или переименуется, проверка
    // ниже станет пустой и будет молча зелёной.
    expect(продаваемые.length).toBeGreaterThanOrEqual(6);
    expect(продаваемые.map((t) => t.id)).toContain("max");
  });

  test.each(кассы)("%s понимает каждый тариф каталога", (_имя, разбор) => {
    // Ссылка строится ТАК ЖЕ, как её строит касса: `tier_<id>` (routes/checkout.ts).
    const немые = продаваемые
      .map((t) => [t.id, разбор(`tier_${t.id}`)] as const)
      .filter(([id, выдано]) => выдано !== id);
    expect(немые, "касса выдаёт не тот тариф, за который заплатили").toEqual([]);
  });
});
