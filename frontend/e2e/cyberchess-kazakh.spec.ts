import { test, expect } from "@playwright/test";

/**
 * Казахский на экране шахмат — проверяем КАДР, а не список языков.
 *
 * Повод. Замер 05.10.2026 на проде: переключатель предлагал «Қазақша» и работал,
 * словарь модуля содержал 169 казахских ключей — а на странице при выбранном KZ
 * из 57 текстовых элементов казахские буквы были ровно в ОДНОМ («Болдырмау»).
 * Подписи были жёстко вписаны в код мимо словаря, а четырёх ключей `tc.*` в
 * казахском не было вовсе: пропуск перевода не падает, он ТИХО откатывается на
 * русский. Снаружи это выглядит как «язык поддерживается».
 *
 * Поэтому сторож меряет не наличие словаря и не выбранный язык, а долю видимых
 * элементов, в которых есть буквы, которых в русском алфавите НЕТ
 * (ә ғ қ ң ө ұ ү һ і). Казахский текст без них почти не встречается, а русский
 * их не содержит вовсе — признак дешёвый и не обманывается.
 *
 * Знаменатель печатается всегда: сторож, который не говорит, сколько элементов
 * он посмотрел, зеленеет и при нулевом охвате.
 */

const АДРЕС = "/cyberchess?c=probe-61";

/** Буквы, которых нет в русском алфавите. */
const КАЗАХСКИЕ = /[әғқңөұүһі]/;

/**
 * Порог. Цель, поставленная оркестратором 05.10.2026 — 90 %.
 *
 * 🔴 ЧЕСТНО: это число НЕ ИЗМЕРЕНО на отрисованной странице.
 * Померить было нечем: на проде правки ещё нет, а локальный `next dev` эту
 * страницу не отрисовывает — чанк шахмат не успевает собраться, HMR-сокет не
 * поднимается, и экран остаётся на «Подгружаю шахматы…». Три попытки, дальше
 * не копал.
 *
 * Поэтому 40 — это НЕ замер, а заведомо достижимый низ: переведены первые два
 * экрана (шапка, цели дня, доска, цвет и контроль времени, нижняя навигация,
 * режимы игры, статистика, карточки «С чего начать» и «Чего нет у конкурентов»),
 * а всего на странице 71 русский элемент (замер браузером на проде 05.10, 390px).
 *
 * ЧТО СДЕЛАТЬ ПРИЁМКЕ: прогнать этот сторож на превью
 * (PLAYWRIGHT_BASE_URL=<превью> npx playwright test e2e/cyberchess-kazakh.spec.ts),
 * взять напечатанную долю и поставить её сюда МИНУС небольшой запас. Если доля
 * вышла ниже 40 — это находка, а не шум сторожа: значит подписи приходят не
 * оттуда, где я их переводил.
 */
const ПОРОГ_ДОЛИ = 40;

/** Листовые элементы с видимым текстом: иначе один текст считается и у родителей. */
async function видимыеСтроки(page: import("@playwright/test").Page) {
  return page.evaluate(() => {
    const строки: string[] = [];
    for (const el of Array.from(document.querySelectorAll("body *"))) {
      if (el.children.length > 0) continue;
      const b = el.getBoundingClientRect();
      if (b.width === 0 || b.height === 0) continue;
      const t = (el.textContent || "").trim().replace(/\s+/g, " ");
      if (t) строки.push(t);
    }
    return строки;
  });
}

/** Строки с буквами хоть одного из двух алфавитов — только их и судим. */
function судимые(строки: string[]) {
  return строки.filter((t) => /[А-Яа-яЁёӘҒҚҢӨҰҮҺІәғқңөұүһі]/.test(t));
}

async function открытьНаЯзыке(page: import("@playwright/test").Page, язык: "ru" | "kk") {
  await page.goto(АДРЕС);
  await page.evaluate((l) => {
    try {
      localStorage.setItem("aevion_lang_v1", l);
      localStorage.setItem("aevion_locale", l);
      document.cookie = `aevion_lang_v1=${l}; path=/`;
    } catch {
      /* приватное окно — тогда проверка просто не состоится, и это видно */
    }
  }, язык);
  await page.goto(АДРЕС);
  await page.waitForLoadState("networkidle");
}

test.describe("казахский на /cyberchess", () => {
  test("при KZ большинство надписей действительно по-казахски", async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await открытьНаЯзыке(page, "kk");

    const все = await видимыеСтроки(page);
    const судим = судимые(все);

    // Охват: если судить стало нечего, сторож ослеп, а не страница похорошела.
    expect(судим.length, `элементов с текстом для оценки: ${судим.length} — слишком мало, сторож ослеп`).toBeGreaterThan(20);

    const наКазахском = судим.filter((t) => КАЗАХСКИЕ.test(t));
    const доля = Math.round((100 * наКазахском.length) / судим.length);
    const русскими = судим.filter((t) => !КАЗАХСКИЕ.test(t));

    // Знаменатель — в самом сообщении, а не в рассуждении рядом.
    expect(
      доля,
      `по-казахски ${наКазахском.length} из ${судим.length} (${доля} %), порог ${ПОРОГ_ДОЛИ} %.\n` +
        `Остались по-русски (до 15): ${русскими.slice(0, 15).join(" | ")}`
    ).toBeGreaterThanOrEqual(ПОРОГ_ДОЛИ);
  });

  test("контроль: русский интерфейс не изменился — казахских букв там нет", async ({ page }) => {
    // Половина работы перевода — не сломать исходный язык. Если казахские буквы
    // протекли в русский экран, значит ключ подставился не туда.
    await page.setViewportSize({ width: 390, height: 844 });
    await открытьНаЯзыке(page, "ru");

    const судим = судимые(await видимыеСтроки(page));
    expect(судим.length, `элементов для оценки: ${судим.length}`).toBeGreaterThan(20);

    const протекли = судим.filter((t) => КАЗАХСКИЕ.test(t));
    expect(
      протекли,
      `проверено ${судим.length} элементов; казахский текст на русском экране: ${протекли.join(" | ")}`
    ).toEqual([]);
  });
});
