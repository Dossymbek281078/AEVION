/**
 * Сторож: на стартовом экране видна доска.
 *
 * До 27.08.2026 человек, открывший шахматы, доски не видел вовсе — экран
 * начинался с панели настроек партии, а доска появлялась только после
 * нажатия «ИГРАТЬ». Замер на телефоне 375 пикселей: ни на первом экране, ни
 * на втором ни одной шахматной клетки. Для пришедшего с ролика это решается
 * за секунды — он пришёл играть, а видит форму.
 *
 * Проверяется САМ компонент предпросмотра (64 клетки, 32 фигуры, разворот по
 * цвету, нажатие начинает партию) плюс одна структурная проверка, что он
 * действительно вставлен в стартовый экран страницы. Без второй первый набор
 * остался бы зелёным, даже если компонент выкинуть из разметки: это класс
 * «правда останавливается на границе» — модуль правильный, читателя нет.
 */
import { describe, it, expect, vi } from "vitest";
import { render, screen } from "@testing-library/react";
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import SetupBoardPreview from "../SetupBoardPreview";
import { SUPPORTED_LOCALES, tFor } from "../i18n";
import { klyuchEstVYazyke } from "./_slovar";

const HERE = dirname(fileURLToPath(import.meta.url));
const PAGE = readFileSync(join(HERE, "..", "page.tsx"), "utf8");

function draw(orientation: "w" | "b", onStart = () => {}) {
  return render(
    <SetupBoardPreview
      orientation={orientation}
      light="#eee"
      dark="#769656"
      border="#769656"
      onStart={onStart}
    />,
  );
}

describe("доска на стартовом экране", () => {
  it("рисует все 64 клетки", () => {
    const { container } = draw("w");
    const grid = container.querySelector("div[style*='repeat(8,1fr)']");
    expect(grid, "сетка доски не найдена").not.toBeNull();
    expect(grid!.children.length).toBe(64);
  });

  it("расставляет 32 фигуры — полный комплект", () => {
    const { container } = draw("w");
    // Набор фигур рисуется вложенным элементом внутри клетки; пустые клетки
    // остаются без содержимого.
    const grid = container.querySelector("div[style*='repeat(8,1fr)']")!;
    const занятых = Array.from(grid.children).filter((c) => c.children.length > 0).length;
    expect(занятых).toBe(32);
  });

  it("нижние два ряда заняты, середина пуста", () => {
    const { container } = draw("w");
    const cells = Array.from(
      container.querySelector("div[style*='repeat(8,1fr)']")!.children,
    );
    const занята = (i: number) => cells[i].children.length > 0;
    // Ряды 0-1 и 6-7 заняты, 2-5 пусты — иначе это не начальная позиция.
    for (const i of [0, 7, 8, 15, 48, 55, 56, 63]) expect(занята(i), `клетка ${i}`).toBe(true);
    for (const i of [16, 23, 24, 31, 32, 39, 40, 47]) expect(занята(i), `клетка ${i}`).toBe(false);
  });

  it("разворачивается по выбранному цвету", () => {
    // Играя чёрными, человек должен видеть свою сторону снизу. Сравниваем
    // разметку двух ориентаций: она обязана отличаться.
    const белые = draw("w").container.innerHTML;
    const чёрные = draw("b").container.innerHTML;
    expect(чёрные, "доска не разворачивается — чёрные видят чужую сторону").not.toBe(белые);
  });

  it("нажатие по доске начинает партию", () => {
    const start = vi.fn();
    draw("w", start);
    // Доска — это кнопка: она заодно самая крупная цель на экране.
    screen.getByRole("button", { name: "Начать партию" }).click();
    expect(start).toHaveBeenCalledOnce();
  });

  it("доска не сжимается родителем — иначе она невидима при 64 клетках", () => {
    // Замер на живой странице 27.08: высота доски была 3 пикселя при ширине
    // 340. Все клетки и фигуры на месте, просто раздавлены — родитель flex-
    // колонка, а элемент с пропорцией без запрета на сжатие схлопывается.
    //
    // Проверки выше этого НЕ ловят: в jsdom вёрстка не считается, aspect-ratio
    // там ничего не делает, и «64 клетки, 32 фигуры» проходят на невидимой
    // доске. Тот же зелёный набор был у меня на схлопнутой версии — поэтому
    // здесь закрепляется САМО СВОЙСТВО, а не результат раскладки.
    const { container } = draw("w");
    const btn = container.querySelector("button") as HTMLButtonElement;
    expect(btn.style.flexShrink, "доска сожмётся в полоску во flex-родителе").toBe("0");
    // Движок стилей нормализует «1» в «1 / 1» — сравниваем по смыслу, иначе
    // проверка краснеет на исправном коде (уже поймал это дважды за вечер:
    // так же нормализуется repeat(8,1fr) → repeat(8, 1fr)).
    expect(
      btn.style.aspectRatio.replace(/\s/g, ""),
      "доска перестанет быть квадратной",
    ).toMatch(/^1(\/1)?$/);
  });

  it("стартовый экран страницы действительно её показывает", () => {
    // Структурная проверка: без неё компонент мог бы остаться правильным и
    // не отрисованным. Закрепляем связку с состоянием setup и со стартом.
    const i = PAGE.indexOf("<SetupBoardPreview");
    expect(i, "компонент не вставлен в страницу").toBeGreaterThan(-1);
    const блок = PAGE.slice(i, i + 500);
    expect(блок, "доска не разворачивается по выбранному цвету").toContain("orientation={pCol}");
    expect(блок, "нажатие по доске не начинает партию").toContain("newG()");
  });

  it("призыв виден ГЛАЗАМИ, а не только скринридеру", () => {
    // Замер 28.09.2026 на живом проде, 1280x768: доска видна целиком
    // (206–622) и щелчок по ней партию запускает — но на экране НИЧЕГО об
    // этом не говорило: label уходил только в aria-label и title. Явная
    // кнопка «ИГРАТЬ» лежала на 820 при окне 768, то есть за кромкой.
    // Человек с ролика видел доску, таймеры и ни одной подсказки.
    const { container } = draw("w");
    const текст = container.textContent || "";
    expect(текст, "подписи на доске нет — человек не знает, что делать").toContain("Начать партию");
    // Контроль в другую сторону: подпись не должна перехватывать нажатие,
    // иначе видимость мы добавили, а старт сломали.
    const подпись = [...container.querySelectorAll("span")].find((e) => (e.textContent || "").includes("Начать партию"));
    expect(подпись, "подпись не найдена как элемент").toBeTruthy();
    expect(подпись!.getAttribute("style") || "", "подпись перехватит щелчок по доске").toContain("pointer-events: none");
  });

  it("страница зовёт нажать доску и уступает место кнопке на невысоком экране", () => {
    const i = PAGE.indexOf("<SetupBoardPreview");
    const блок = PAGE.slice(i, i + 1400);
    // Текст призыва: не техническое «Начать партию», а действие, которое видно.
    // 05.10.2026 текст призыва уехал в словарь (перевод на казахский): здесь
    // проверяем, что призыв ПОДСТАВЛЯЕТСЯ, а в словаре — что он не пустой и
    // есть на каждом языке. Требовать литерал значило бы краснеть на верной правке.
    expect(блок, "на странице нет видимого призыва нажать доску").toMatch(/label=\{`▶ \$\{cc\.t\("board\.cta\.start"\)\}`\}/);
    for (const { code } of SUPPORTED_LOCALES) {
      const текст = tFor(code, "board.cta.start");
      // Наличие — у словаря: tFor при пропуске откатится на русский и соврёт.
      expect(klyuchEstVYazyke(code, "board.cta.start"), `${code}: призыва нет в словаре этого языка`).toBe(true);
      expect(текст.length, `${code}: призыв подозрительно короток — «${текст}»`).toBeGreaterThan(8);
    }
    // Бюджет высоты: на невысоком рабочем столе доска обязана уступить место,
    // иначе выбор цвета (772) и «ИГРАТЬ» (820) остаются за кромкой окна 768,
    // а страница листается всего на 50 px и колесо проносит блок мимо.
    // 06.10.2026 ветка ВЫСОКОГО стола стала считаться из свободной высоты
    // (vhPx − 480) вместо числа 420 — превью занимало 41 % при доступных 53 %.
    // Смысл ЭТОЙ проверки в другой ветке: на НЕВЫСОКОМ экране доска обязана
    // уступить место кнопке, и там по-прежнему 300. Её и проверяем, а не весь
    // литерал целиком — иначе сторож краснеет на верной правке соседней ветки.
    expect(блок, "на невысоком экране доска не уступает место кнопке ИГРАТЬ").toContain("lowDesktop?300:");
    // И контроль, что высокую ветку не выродили обратно в константу: там
    // обязана остаться зависимость от высоты окна. Размер на 1990×1015 и на
    // 1280×768 меряет e2e/cyberchess-board-size.spec.ts.
    expect(блок, "высокая ветка снова не зависит от высоты окна").toContain("vhPx-480");
  });
});

/**
 * Отдельно про ИГРОВОЙ экран (не стартовый).
 *
 * Раскладку тестами не проверить — в jsdom её попросту нет. Поэтому здесь
 * закрепляется свойство, от которого она зависит, ровно как у предпросмотра
 * выше: колонка вокруг доски обязана уметь сжиматься.
 */
describe("игровая доска не переполняет свою колонку", () => {
  it("у колонки вокруг доски задан minHeight:0", () => {
    // Без него действует min-height:auto — колонка не может стать ниже
    // содержимого и вылезает вверх, наезжая на панель быстрых действий.
    // Замер 27.08 на телефоне 375×812: колонка 685 пикселей в области 449,
    // доска вылезала на 48 и закрывала 36 пикселей панели. Играя чёрными,
    // человек не видел свой верхний ряд. На десктопе дефекта нет вовсе —
    // поэтому глазами на большом экране его не поймать.
    const i = PAGE.indexOf('flex:"0 1 auto",minWidth:0');
    expect(i, "контроль: колонка вокруг доски не найдена").toBeGreaterThan(-1);
    const объявление = PAGE.slice(i, i + 120);
    expect(объявление, "колонка переполнит родителя и наедет на панель").toContain("minHeight:0");
  });
});
