export type BuildKey = keyof typeof T;
type Dict = Record<BuildKey, string>;

function column(i: 0 | 1 | 2): Dict {
  const out = {} as Dict;
  for (const k of Object.keys(T) as BuildKey[]) out[k] = T[k][i];
  return out;
}

const EN = column(0);
const RU = column(1);
const KK = column(2);
const DICT: Record<string, Dict> = { en: EN, ru: RU, kk: KK };

/** Перевод по ключу; язык без словаря → en. Подстановки `{name}`. */
export function tBuild(lang: string | null | undefined, key: BuildKey, vars?: Record<string, string | number>): string {
  const s = (DICT[lang ?? "en"] ?? EN)[key] ?? EN[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, v: string) => (v in vars ? String(vars[v]) : m)) : s;
}

/** Форма множественного числа: ru — one/few/many, en — one/many, kk — без изменения. */
export function pluralForm(lang: string | null | undefined, n: number): "one" | "few" | "many" {
  const a = Math.abs(n);
  if (lang === "ru") {
    const d = a % 10;
    const h = a % 100;
    if (d === 1 && h !== 11) return "one";
    if (d >= 2 && d <= 4 && (h < 12 || h > 14)) return "few";
    return "many";
  }
  if (lang === "kk") return "many";
  return a === 1 ? "one" : "many";
}

type PluralBase = BuildKey extends infer K ? (K extends `${infer B}.one` ? B : never) : never;

export function tBuildN(lang: string | null | undefined, base: PluralBase, n: number, vars?: Record<string, string | number>): string {
  return tBuild(lang, `${base}.${pluralForm(lang, n)}` as BuildKey, { n, ...vars });
}

/** Подпись статуса; неизвестное значение показывается как пришло. */
export function tStatus(lang: string | null | undefined, kind: "pstatus" | "vstatus" | "astatus" | "label" | "tstatus", value: string): string {
  const k = `${kind}.${value}` as BuildKey;
  return k in T ? tBuild(lang, k) : value;
}

/**
 * Проекты-образцы (флаг `example` с бэкенда: data/buildExampleProjects, плашка «Пример
 * проекта») написаны по-русски и не переводятся. Решение Оркестратора 29.10.2026: на en/kk
 * их карточки на /build не показываются; на ru — остаются. В счётчики витрины образцы и так
 * не входят (stats.ts: неОбразецSql), поэтому счётчики от фильтра не меняются.
 */
export function visibleProjects<P extends { example?: boolean }>(projects: P[], lang: string | null | undefined): P[] {
  return lang === "ru" ? projects : projects.filter((p) => !p.example);
}

