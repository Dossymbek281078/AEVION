import { describe, expect, it } from "vitest";
import { findRooms } from "./rooms";
import type { Plan } from "./planModel";

/**
 * Площадь помещения считается по клеткам сетки 5 см, и стены штампуются на неё.
 * Раньше штамп был КВАДРАТНОЙ кистью радиусом ceil(t / 2 / CELL) клеток, то есть
 * всегда шире стены и тем сильнее, чем «неудобнее» толщина: у стены 0.21 м полоса
 * выходила 0.35 м. Лишние 14 см съедались из площади с двух сторон, и смета
 * занижала площадь помещения — человек платил бы за меньшее, чем у него есть.
 *
 * Эталон не выдуман: прямоугольник по осевым 5 x 4 м со стеной t даёт в свету
 * ровно (5 - t) x (4 - t). Допуск — ОДНА клетка сетки на каждую сторону: точнее
 * сетка не умеет в принципе, а промах старой кисти был втрое больше.
 */
const CELL = 0.05;
const прямоугольник = (t: number): Plan => ({
  walls: [
    { x1: 0, y1: 0, x2: 5, y2: 0, thickness: t },
    { x1: 5, y1: 0, x2: 5, y2: 4, thickness: t },
    { x1: 5, y1: 4, x2: 0, y2: 4, thickness: t },
    { x1: 0, y1: 4, x2: 0, y2: 0, thickness: t },
  ],
  openings: [],
  height: 2.7,
});

const проверить = (t: number) => {
  const r = findRooms(прямоугольник(t));
  expect(r.rooms.length, `при толщине ${t} помещение не одно`).toBe(1);
  const по = (сторона: number) => сторона - t;
  const эталон = по(5) * по(4);
  const предел = (по(5) + CELL) * (по(4) + CELL) - эталон + 1e-9;
  expect(Math.abs(r.rooms[0].area - эталон),
    `толщина ${t}: площадь ${r.rooms[0].area.toFixed(2)} против эталона ${эталон.toFixed(2)}`)
    .toBeLessThanOrEqual(предел);
};

describe("ширина штампа стены на сетке площадей", () => {
  it("толщина 0.21 м — площадь по эталону, а не на три клетки меньше", () => проверить(0.21));
  it("толщина 0.26 м — то же самое", () => проверить(0.26));
  it("толщина 0.10 м — тонкая стена не съедает лишнего", () => проверить(0.1));
  it("толщина 0.30 м — помещение остаётся замкнутым, заливка не протекает", () => {
    expect(findRooms(прямоугольник(0.3)).rooms.length).toBe(1);
  });
});
