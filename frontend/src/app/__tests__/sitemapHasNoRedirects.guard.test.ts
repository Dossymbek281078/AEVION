import { describe, it, expect } from "vitest";
import sitemap from "../sitemap";

/**
 * Карта сайта перечисляет КОНЕЧНЫЕ адреса, а не перенаправления.
 *
 * ПОВОД. Замер 29.08.2026 сторожем `aevion-sitemap-live.mjs` (он проверяет
 * КАЖДЫЙ адрес карты, а не 119 отобранных): из 765 адресов пять отвечали
 * 307/308 — `/legal/terms`, `/legal/privacy`, `/legal/refund`,
 * `/pricing/paddle`, `/en/yt`.
 *
 * Сами перенаправления верные и нужные. Беда в том, что они попали в КАРТУ:
 * поисковик идёт по адресу и получает не страницу, а указание идти дальше.
 * Это признак небрежности, и он тратит бюджет обхода на пустые переходы.
 *
 * ПОЧЕМУ СТОРОЖ, А НЕ ПРОСТО ПРАВКА. Маршруты в карту попадают ОБХОДОМ
 * дерева, а не списком: заведёт кто-нибудь новую страницу-перенаправление —
 * и она молча вернётся в карту. Здесь эта регрессия краснеет.
 *
 * ГРАНИЦА. Признак исключения намеренно узкий: файл зовёт
 * redirect/permanentRedirect И ничего не рисует. Страницу, которая
 * перенаправляет УСЛОВНО и в остальных случаях работает, исключать нельзя.
 * Замер по всему дереву в день написания: строго перенаправляющих 10,
 * условных 0.
 */

const ПЕРЕНАПРАВЛЯЮЩИЕ = [
  "/legal/terms",
  "/legal/privacy",
  "/legal/refund",
  "/pricing/paddle",
  "/yt",
  "/tt",
  "/ig",
];

describe("карта сайта не рекламирует перенаправления", () => {
  it("страниц, которые ТОЛЬКО перенаправляют, в карте нет", async () => {
    const items = await sitemap();
    const пути = items.map((x: { url: string }) => new URL(x.url).pathname);
    const остались = ПЕРЕНАПРАВЛЯЮЩИЕ.filter((p) => пути.includes(p));
    expect(
      остались.join(", "),
      "Эти адреса отвечают 307/308. В карте место конечному адресу, " +
        "а не указанию идти дальше.",
    ).toBe("");
  });

  it("ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: обычные страницы в карте есть", async () => {
    // Без него пустая карта прошла бы первую проверку и обещала бы
    // охват, которого нет.
    const items = await sitemap();
    const пути = items.map((x: { url: string }) => new URL(x.url).pathname);
    expect(пути).toContain("/pricing");
    expect(пути.length).toBeGreaterThan(100);
  });
});
