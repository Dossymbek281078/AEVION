import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Окно приветствия обязано быть диалогом ДЛЯ ЧИТАЛКИ, а не только на вид.
 *
 * Замер прода 28.08.2026: окно занимает весь экран (1265x900), перехватывает
 * нажатия, но не имеет ни `role="dialog"`, ни `aria-modal`. Для экранного
 * диктора это обычная часть страницы: он продолжает читать содержимое ПОД
 * окном, где нажать уже ничего нельзя.
 *
 * Там же нашлись пять кнопок без имени — точки-шаги. Читалка объявляла их
 * просто «кнопка», пять раз подряд.
 *
 * Проверка по исходнику, а не по рендеру: разметка здесь статическая, и
 * сломать её можно только правкой этих самых строк.
 */

// Пробел перед именем атрибута обязателен: без него `toContain` совпадает
// и внутри более длинного имени — `data-role="dialog"` содержит
// `role="dialog"`, и мутация проходит незамеченной. Поймано мутацией.
const FILE = join(__dirname, "..", "OnboardingModal.tsx");

describe("окно приветствия тренажёра доступно читалке", () => {
  it("объявлено диалогом и связано со своим заголовком", () => {
    const s = readFileSync(FILE, "utf8");
    expect(s, "пропал role=dialog — окно снова обычная часть страницы")
      .toContain(' role="dialog"');
    expect(s, "пропал aria-modal — диктор продолжит читать под окном")
      .toContain(' aria-modal="true"');
    expect(s, "окно не связано с заголовком — диалог будет безымянным")
      .toContain(' aria-labelledby="smeta-onboarding-title"');
    expect(s, "у заголовка пропал id — связывать не с чем")
      .toContain(' id="smeta-onboarding-title"');
  });

  it("точки-шаги названы, а не «кнопка» пять раз подряд", () => {
    const s = readFileSync(FILE, "utf8");
    expect(s, "точки снова без имени").toContain("aria-label={`Шаг ${i + 1}`}");
    expect(s, "не помечено, какой шаг текущий").toContain("aria-current");
  });
});
