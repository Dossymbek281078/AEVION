import { describe, it, expect } from "vitest";
import { сметаПродукта, РАСЦЕНКИ_ПРОДУКТА, сметаРаботы } from "../src/lib/pipelineQuote";

/**
 * Смета, которую видит ПОКУПАТЕЛЬ, обязана считаться по каналам, которыми заказ
 * реально пойдёт.
 *
 * 29.09.2026. Первая смета считала в кредитах Higgsfield — и это верно для нашей
 * внутренней работы (ролики через окно Claude), но НЕ для продукта: у бэкенда нет
 * ключа Higgsfield. Замер по переменным сервиса: только ELEVENLABS_API_KEY и
 * REPLICATE_API_TOKEN. Человек с сайта до Higgsfield не дотянется, и назвать ему
 * цену в его кредитах значило бы назвать цену чужого поставщика.
 *
 * Класс ошибки тот же, что у нас записан про приборы: измеряли НЕ ТОТ канал.
 */
describe("смета продукта считает наши каналы", () => {
  it("расценки названы и взяты по верхней границе — занижать себестоимость нельзя", () => {
    expect(РАСЦЕНКИ_ПРОДУКТА.долларЗаОзвучку1000Знаков).toBe(0.1);
    expect(РАСЦЕНКИ_ПРОДУКТА.долларЗаСекундуВидео).toBe(0.15);
    expect(РАСЦЕНКИ_ПРОДУКТА.долларЗаГенерациюТекста).toBe(0.00206);
  });

  it("заказ «книга 20 000 знаков + озвучка + минута фильма» считается целиком", () => {
    const с = сметаПродукта({ знаковКниги: 20000, озвучка: true, секундВидео: 60 });
    // озвучка: 20 × 0.10 = 2.00; видео: 60 × 0.15 = 9.00; текст: 3 прогона × 0.00206
    expect(с.строки.map((r) => r.шаг)).toEqual(["книга", "озвучка", "фильм"]);
    expect(с.строки.find((r) => r.шаг === "озвучка")!.доллары).toBeCloseTo(2, 4);
    expect(с.строки.find((r) => r.шаг === "фильм")!.доллары).toBeCloseTo(9, 4);
    expect(с.итогоДолларов).toBeGreaterThan(11);
    expect(с.итогоДолларов).toBeLessThan(11.1);
  });

  it("без озвучки и видео остаётся только текст — он стоит центы", () => {
    const с = сметаПродукта({ знаковКниги: 20000, озвучка: false, секундВидео: 0 });
    expect(с.строки.map((r) => r.шаг)).toEqual(["книга"]);
    expect(с.итогоДолларов).toBeLessThan(0.02);
  });

  it("про верхнюю границу цены видео сказано вслух, а не спрятано", () => {
    const с = сметаПродукта({ знаковКниги: 1000, озвучка: false, секундВидео: 10 });
    expect(с.предупреждения.join(" ")).toContain("верхней границе");
    // без видео предупреждения нет — иначе оно станет шумом
    expect(сметаПродукта({ знаковКниги: 1000, озвучка: true, секундВидео: 0 }).предупреждения).toEqual([]);
  });

  it("пустой замысел не даёт отрицательных или выдуманных чисел", () => {
    const с = сметаПродукта({ знаковКниги: 0, озвучка: true, секундВидео: 0 });
    expect(с.итогоДолларов).toBeGreaterThanOrEqual(0);
    // озвучки нет, потому что нечего озвучивать
    expect(с.строки.map((r) => r.шаг)).toEqual(["книга"]);
  });

  it("прежняя смета в кредитах ЖИВА — она про нашу внутреннюю работу, не про продукт", () => {
    // Две разные единицы и два разных поставщика: сливать их в одно число нельзя,
    // иначе о результате нельзя сказать, чей он.
    const внутренняя = сметаРаботы({ знаковКниги: 20000, озвучка: true, секундВидео: 60 });
    expect(внутренняя.итогоКредитов).toBe(190);
    const продуктовая = сметаПродукта({ знаковКниги: 20000, озвучка: true, секундВидео: 60 });
    expect(продуктовая).not.toHaveProperty("итогоКредитов");
  });
});
