"use client";

import { useEffect, useRef } from "react";
import { usePathname } from "next/navigation";
import { местоВЦепочке } from "@/lib/planetChain";

/**
 * Переход между страницами в Next.js — клиентский: документ не перезагружается,
 * поэтому браузер НЕ переносит фокус и НЕ объявляет новую страницу. По
 * умолчанию после перехода фокус оказывается на body.
 *
 * Замер 03.09.2026 на проде, цепочка планеты:
 *
 *   /qright    -> /qcontract   фокус ПОТЕРЯН (body), живых областей 0
 *   /qcontract -> /qsign       то же
 *   /qsign     -> /qpaynet     то же
 *
 * Что это значит для человека. Без мыши: следующий Tab начинается с самого
 * верха документа, то есть каждый переход стоит прохода через всю шапку
 * заново. С читалкой: не объявляется НИЧЕГО — человек нажал ссылку, и тишина;
 * понять, что комната сменилась, можно только начав читать страницу сначала.
 *
 * Компонент делает две вещи, и обе нужны:
 *   1) переносит фокус на заголовок новой страницы — дальше Tab идёт по её
 *      содержимому, а не по шапке;
 *   2) объявляет название комнаты в живой области.
 *
 * Первый переход НЕ объявляется намеренно: это обычная загрузка страницы,
 * браузер и читалка делают это сами, и повтор звучал бы как заикание.
 */
export default function RouteAnnouncer() {
  const путь = usePathname();
  const первый = useRef(true);
  const областьRef = useRef<HTMLDivElement | null>(null);

  useEffect(() => {
    if (первый.current) {
      первый.current = false;
      return;
    }
    // Заголовок появляется не мгновенно: страница может дорисовываться.
    // Ждём его недолго, а не гадаем фиксированной паузой.
    let отменено = false;
    let попыток = 0;

    const попробовать = () => {
      if (отменено) return;
      const заголовок =
        document.querySelector<HTMLElement>("main h1") ||
        document.querySelector<HTMLElement>("h1") ||
        document.querySelector<HTMLElement>("main");

      if (!заголовок) {
        if (++попыток < 20) setTimeout(попробовать, 100);
        return;
      }

      // h1 фокус не принимает — даём временно. preventScroll: страница уже
      // показана сверху, а прыжок вниз выглядел бы как сбой.
      if (!заголовок.hasAttribute("tabindex")) заголовок.setAttribute("tabindex", "-1");
      заголовок.focus({ preventScroll: true });

      // Замер 03.09.2026 на собранной сборке: на переходе /qcontract -> /qsign
      // объявление срабатывало, а фокус слетал обратно на body. Причина не в
      // фокусе, а в том, что React дорисовывает страницу ПОСЛЕ нашего вызова и
      // заменяет узел, на котором фокус стоял. Проверяем, удержался ли он, и
      // повторяем — иначе половина переходов чинится, а половина нет.
      let попытокУдержать = 0;
      const удержать = () => {
        if (отменено) return;
        // 🔴 Условие именно «фокус ПОТЕРЯН», а не «фокус не на заголовке».
        // Первая редакция прекращала цикл, как только фокус оказывался на
        // месте, — и поздняя дорисовка страницы его уже не возвращала (тест
        // это и вскрыл). Но безусловный возврат был бы хуже дефекта: он
        // отнимал бы фокус у человека, который за эту секунду успел уйти
        // дальше по странице. Вмешиваемся только когда фокуса нет ни на чём.
        const потерян = !document.activeElement || document.activeElement === document.body;
        if (!потерян) {
          if (++попытокУдержать < 10) setTimeout(удержать, 120);
          return;
        }
        const свежий =
          document.querySelector<HTMLElement>("main h1") ||
          document.querySelector<HTMLElement>("h1") ||
          document.querySelector<HTMLElement>("main");
        if (свежий) {
          if (!свежий.hasAttribute("tabindex")) свежий.setAttribute("tabindex", "-1");
          свежий.focus({ preventScroll: true });
        }
        if (++попытокУдержать < 10) setTimeout(удержать, 120);
      };
      setTimeout(удержать, 120);

      const заголовокТекст = (заголовок.textContent || "").trim().replace(/\s+/g, " ").slice(0, 120);

      // Место в цепочке планеты, если страница в неё входит. «Шаг 2 из 4»
      // отвечает на вопрос «где я», а заголовок — только на «что это».
      // Место, где не понимаешь, где ты, — не место жительства.
      const место = местоВЦепочке(путь);
      const имя = место
        ? `${место.имя}. Шаг ${место.номер} из ${место.всего}. ${заголовокТекст}`
        : заголовокТекст;
      if (областьRef.current) {
        // Пустое значение перед новым заставляет читалку произнести повтор
        // (переход на ту же по названию комнату иначе прозвучал бы тишиной).
        областьRef.current.textContent = "";
        const текст = имя || путь;
        setTimeout(() => {
          if (!отменено && областьRef.current) областьRef.current.textContent = текст;
        }, 60);
      }
    };

    попробовать();
    return () => {
      отменено = true;
    };
  }, [путь]);

  return (
    <div
      ref={областьRef}
      role="status"
      aria-live="polite"
      aria-atomic="true"
      style={{
        position: "absolute",
        width: 1,
        height: 1,
        margin: -1,
        padding: 0,
        overflow: "hidden",
        clip: "rect(0 0 0 0)",
        whiteSpace: "nowrap",
        border: 0,
      }}
    />
  );
}
