import { describe, test, expect } from "vitest";
import * as fs from "node:fs";
import * as path from "node:path";
import { stripComments } from "./_stripComments";
import { SUPPORTED_LOCALES } from "../i18n";
import { znachenieVYazyke } from "./_slovar";

// Страница экономики говорит о себе правду. 19.08.2026.
//
// Замер: 620 строк, НОЛЬ обращений к серверу. Кнопки «сделать ставку»,
// «арендовать коуча», «подписаться на стримера» пишут только в localStorage.
// Аукцион существует в одном экземпляре у каждого человека, и ставка никому не
// видна. Слов «скоро» или «в разработке» на странице не было.
//
// Отдельно опасен баланс: Chessy — настоящая валюта с серверным кошельком
// CyberWallet, а здесь читается местная копия. Списание настоящего баланса не
// меняет, и человек вправе решить, что потратил заработанное.
//
// Тот же класс, что выдуманные гроссмейстеры в таблице лидеров: экран выглядит
// работающим механизмом, за которым ничего нет.

const SRC = path.join(__dirname, "..", "economy", "page.tsx");
const src = () => stripComments(fs.readFileSync(SRC, "utf-8"));

describe("страница экономики не выдаёт себя за работающую биржу", () => {
  test("оговорка есть и названа своими словами", () => {
    const s = src();
    expect(s).toMatch(/economy-prototype-notice/);
    expect(s).toMatch(/витрина замысла/);
  });

  test("сказано главное: только этот браузер и не настоящие Chessy", () => {
    const s = src();
    // Пробелы гибкие: в разметке текст переносится по строкам, и жёсткий
    // шаблон ломался бы о форматирование, а не о смысл. На этом я и попался.
    expect(s.replace(/\s+/g, " ")).toMatch(/только в этом браузере/);
    expect(s.replace(/\s+/g, " ")).toMatch(/настоящие Chessy он не списывает/);
  });

  test("оговорка нужна ровно потому, что сервера здесь нет", () => {
    // Если однажды страница начнёт ходить на сервер, это утверждение
    // покраснеет — и оговорку можно будет пересмотреть, а не тащить по привычке.
    const s = src();
    expect(s).not.toMatch(/fetch\(/);
  });
});

// 07.09.2026: сама страница честна (сторож выше), но ВХОД на неё — карточка
// «Chessy Экономика» на лендинге /cyberchess — обещал «подписки на стримеров»
// без пометки, что это концепт. Человек кликал «Войти» в расчёте на рабочую
// экономику, а попадал на «витрину замысла». По воротам запуска §3.1 обещанного,
// чего нет, быть не должно даже планами без пометки. Здесь закрепляем: где на
// лендинге обещаны стримеры, рядом обязана стоять оговорка (превью/замысл/скоро).
const LANDING = path.join(__dirname, "..", "page.tsx");
const landing = () => stripComments(fs.readFileSync(LANDING, "utf-8"));

describe("карточка-вход в экономику не выдаёт концепт за рабочую фичу", () => {
  test("обещание стримеров на лендинге помечено как превью замысла", () => {
    // 05.10.2026 текст карточки уехал в словарь. Честность проверяем ТАМ, где
    // текст теперь живёт, и на КАЖДОМ языке: обещание, переведённое без оговорки,
    // — то же самое обещание без оговорки.
    let проверено = 0;
    for (const { code } of SUPPORTED_LOCALES) {
      // Берём значение ИМЕННО этого языка: tFor откатился бы на русский, и
      // непереведённая карточка выглядела бы честной за счёт русского текста.
      const desc = znachenieVYazyke(code, "killer.economy.desc");
      expect(desc, `${code}: описания экономики нет в словаре этого языка`).not.toBeNull();
      expect(
        desc,
        `${code}: обещание без пометки, что это замысел — «${desc}»`
      ).toMatch(/превью|замысл|скоро|в плане|preview|soon|идея|идеяның|жақында|әзірге/i);
      проверено++;
    }
    expect(проверено, `проверено языков: ${проверено}`).toBe(SUPPORTED_LOCALES.length);
  });
});
