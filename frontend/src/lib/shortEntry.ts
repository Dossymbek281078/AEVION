/**
 * Метка, которую короткий вход несёт дальше.
 *
 * ЗАЧЕМ. Короткие адреса (`aevion.app/yt`, `/ph`, `/habr`) стоят в подписях под
 * роликами, в шапках профилей и в объявлениях. До 07.10.2026 каждый из них
 * подставлял СВОЮ метку жёстко: `/yt` всегда перенаправлял на `/go?c=yt`, что
 * бы ни пришло в адресе. Поэтому ссылка `/yt?c=yt-30-dney-devhub`, которую мы
 * кладём под конкретный ролик, теряла хвост `-30-dney-devhub` — в воронку
 * попадал только канал. Разрез «какой РОЛИК дал переход» не считался вовсе,
 * хотя метка была написана правильно и видна в адресной строке.
 *
 * ПРАВИЛО. Пришедшая метка несётся ЦЕЛИКОМ, если её начало — известный канал
 * (или канал этого самого входа, или наша проба). Своя подставляется только
 * тогда, когда входящей метки нет или она не распознана. Так короткий вход
 * перестаёт быть глушителем и остаётся источником правды о канале.
 *
 * ПОЧЕМУ ПРОБЫ НЕСУТСЯ ТОЖЕ. Наши заходы помечаются `?c=probe-<окно>`
 * (правило 0-НАШИ-ЗАХОДЫ-С-МЕТКОЙ). Если такую метку заменить на `yt`, проба
 * окна станет в отчёте живым человеком с YouTube — ровно тот дефект, из-за
 * которого 30.09 пять начал оплаты читались как покупатели.
 */
import { CHANNELS } from "./products";

/** Метка — только буквы, цифры и разделители, и не длиннее этого. */
const ДЛИНА_МАКС = 64;
const ДОПУСТИМА = /^[a-z0-9]+(?:[-_][a-z0-9]+)*$/;

/** Префиксы наших собственных проб: воронка отделяет их от живых людей. */
const НАШИ_ПРЕФИКСЫ = ["probe", "smoke"];

export function меткаДляПерехода(
  raw: string | string[] | undefined,
  свой: string,
): string {
  const v = Array.isArray(raw) ? raw[0] : raw;
  const метка = (v ?? "").trim().toLowerCase();
  if (!метка || метка.length > ДЛИНА_МАКС || !ДОПУСТИМА.test(метка)) return свой;

  // Своя метка с хвостом (`yt-30-dney`) — самый частый случай, и он не зависит
  // от того, есть ли дефис в самом названии канала (`x-devhub`, `ads-multichat`).
  if (метка === свой || метка.startsWith(свой + "-")) return метка;

  const дефис = метка.indexOf("-");
  const начало = дефис > 0 ? метка.slice(0, дефис) : метка;

  // Прямая индексация находит и УНАСЛЕДОВАННОЕ: `CHANNELS["constructor"]` —
  // функция, то есть значение, и `?? null` её не отсеивает. Та же защита, что
  // в channelFrom (замер 02.09.2026: `?c=constructor` уезжал в адрес кассы).
  if (Object.prototype.hasOwnProperty.call(CHANNELS, начало)) return метка;
  if (НАШИ_ПРЕФИКСЫ.includes(начало)) return метка;

  return свой;
}
