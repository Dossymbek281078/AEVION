/* AEVION CyberChess — приведение пазлов к рабочему виду на входе.

   Пазлы приходят в приложение из трёх мест: пул с бэкенда, слайс на 400 задач для
   «быстрого пазла» на главной и запасной public/puzzles.json. Раньше каждое место
   клало данные в состояние как есть, и два дефекта проезжали в интерфейс. Здесь обе
   правки собраны в одном месте, чтобы «починили один путь из трёх» не повторилось. */

import { Chess } from "chess.js";
import { themeLabel } from "./puzzleThemes";

/* Половина корпуса пришла из дампа Lichess с темами вида "fork" и "attraction", вторая
   несёт русские ("Вилка", "Завлечение"). Для кода это РАЗНЫЕ темы: в списке фильтра они
   стояли двумя пунктами, и выбор одного прятал задачи другого, счётчики и статистика по
   теме делились пополам, а эмодзи с цветом не находились вовсе — THEME_META ключуется по
   русским названиям. themeLabel неизвестную тему возвращает как есть. */
export function normalizeThemes<T extends { theme?: string }>(list: T[]): T[] {
  return list.map((p) => (p.theme ? { ...p, theme: themeLabel(p.theme) } : p));
}

/* Формат Lichess: FEN — позиция ДО хода соперника, и первый ход решения принадлежит
   именно сопернику. Пул на бэкенде собран БЕЗ этого сдвига, поэтому игроку показывали
   позицию на полуход раньше и ждали от него ход СОПЕРНИКА как правильный ответ.

   Замер боевого пула 2026-07-27 по выборке 20 000 задач: чётная длина решения у всех
   20 000; среди 6370 матовых мат во ВСЕХ ставил соперник — игрок доигрывал «решение» и
   получал мат; у 13 630 задач «лучший ход» играющий терял в среднем 2.89 пешки. После
   сдвига: мат ставит игрок (400 из 400 проверенных), средняя дельта материала +3.56.

   Признак — чётная длина: после верного сдвига игрок ходит первым и последним, то есть
   полуходов нечётное число. Запасной public/puzzles.json собран верным импортёром, там
   все решения нечётные, и функция его не трогает. */
export function repairUnshiftedPuzzles<T extends { fen: string; sol: string[]; side?: string }>(
  list: T[],
): T[] {
  return list.map((p) => {
    if (!Array.isArray(p.sol) || p.sol.length < 2 || p.sol.length % 2 === 1) return p;
    try {
      const c = new Chess(p.fen);
      const uci = p.sol[0];
      if (!c.move({ from: uci.slice(0, 2), to: uci.slice(2, 4), promotion: uci[4] })) return p;
      return { ...p, fen: c.fen(), sol: p.sol.slice(1), side: c.turn() };
    } catch {
      return p; // испорченную запись оставляем как есть — её отсеет проверка хода
    }
  });
}

/** Единственный вход для пазлов: тема к одному виду, позиция к ходу игрока. */
export function ingestPuzzles<T extends { fen: string; sol: string[]; side?: string; theme?: string }>(
  list: T[],
): T[] {
  return repairUnshiftedPuzzles(normalizeThemes(list));
}
