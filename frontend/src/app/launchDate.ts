/**
 * Дата запуска ПЛАТФОРМЫ — одна на все страницы.
 *
 * Зачем константа. 13.09.2026 замер показал, что на проде /go звала
 * «открываем 10 сентября» — дату, прошедшую три дня назад, — и ни один тест
 * не покраснел. Причина не в невнимательности: дата стояла литералом, а все
 * проверки сверяли страницы ДРУГ С ДРУГОМ («все ли называют одну дату»).
 * Согласие не равно правде: когда дата устарела ВЕЗДЕ, сверять нечего.
 * Опыт: вернул 10 сентября во всех 22 файлах — три сторожа дат, 10 тестов,
 * все зелёные.
 *
 * Поэтому здесь не только число, но и ТЕКСТ, который меняется сам. Иначе
 * страница снова протухнет молча — а запуск уже дважды переносили
 * (10 -> 20 сентября, шахматы 30.08 -> 30.09), значит перенос это норма,
 * а не исключение.
 *
 * Образец рядом: cyberchess/launchDate.ts (там тот же класс стоил месяца
 * несобранных адресов). Бэкенд уже отвечает правильно — planPhrase в
 * lib/constitutionBrevo.ts; формулировки ниже повторяют его дословно, чтобы
 * письмо и страница не начали говорить разное.
 *
 * Месяцы в Date.UTC считаются с нуля: 8 — это сентябрь.
 */
export const PLATFORM_LAUNCH_UTC = Date.UTC(2026, 8, 20);

/** Человеку — словами. Сверяется с числом выше тестом, чтобы не разошлись. */
export const PLATFORM_LAUNCH_HUMAN = "20 сентября";

/** Родительный падеж — как месяц пишут в тексте страницы. */
export const MONTHS_RU = [
  "января", "февраля", "марта", "апреля", "мая", "июня",
  "июля", "августа", "сентября", "октября", "ноября", "декабря",
];

/**
 * Часовой пояс запуска — Алматы, UTC+5, тот же, что у обратного отсчёта и у
 * письма. Без сдвига страница на шесть часов считала бы, что день ещё не
 * наступил.
 */
const LAUNCH_TZ_OFFSET_MS = 5 * 3_600_000;

/** Прошёл ли день запуска по алматинскому времени. */
export function launchHasPassed(now: Date = new Date(), launchUtc = PLATFORM_LAUNCH_UTC): boolean {
  const shifted = new Date(now.getTime() + LAUNCH_TZ_OFFSET_MS);
  const today = Date.UTC(shifted.getUTCFullYear(), shifted.getUTCMonth(), shifted.getUTCDate());
  return today > launchUtc;
}

/**
 * Подпись карточки «Ближайший запуск».
 *
 * После даты НЕ пишем «уже открыто»: календарь не доказывает, что модули
 * работают, и 30.08.2026 это уже стоило нам письма, звавшего в запуск,
 * которого не было. Честное третье состояние — «обещали такого-то».
 */
export function launchKicker(now: Date = new Date()): string {
  return launchHasPassed(now)
    ? `Обещали ${PLATFORM_LAUNCH_HUMAN} · семь модулей`
    : `${PLATFORM_LAUNCH_HUMAN} · семь модулей`;
}

/** Заголовок карточки. `modules` — перечисление, дата приходит отсюда. */
export function launchTitle(modules: string, now: Date = new Date()): string {
  return launchHasPassed(now)
    ? `${modules} — обещали ${PLATFORM_LAUNCH_HUMAN}, напишем, как только откроем`
    : `${modules} — открываем ${PLATFORM_LAUNCH_HUMAN}`;
}
