import { channelFrom, channelFromRef, channelParam, postFrom } from "./products";

/**
 * Канал, из которого пришёл этот человек — единый ответ для всех, кто
 * спрашивает.
 *
 * Зачем понадобилось. С 31.08 метка переживает поход в кассу: она лежит в
 * хранилище вкладки и возвращается вместе с покупателем. Но так научилось
 * только событие замера; четыре места, строящие АДРЕС КАССЫ, по-прежнему
 * читали адрес страницы. Получалось, что два наших собственных ответа об одном
 * и том же расходятся: наша сводка говорит «пришёл из TikTok», а в заказе у
 * кассы канала нет. Сверить их между собой стало бы невозможно — и непонятно,
 * какому верить, притом что второй и есть денежная правда.
 *
 * Хранится КОРОТКАЯ метка, а не разобранное имя, и приводится к ней ЯВНО
 * (`каноничная` ниже): с 30.09 в адрес приходят и длинные имена, и написания
 * площадок. Первая редакция клала имя, и канал молча пропадал после кассы.
 *
 * Держим ПЕРВОЕ касание и не перезаписываем — так же считает сервер у списка
 * подписчиков (COALESCE), и два источника не должны спорить.
 *
 * Сознательно НЕ долгое хранилище: оно пережило бы закрытие вкладки, и покупка
 * досталась бы каналу, по которому заходили неделю назад. Завышение опаснее
 * пропуска — по нему увеличивают бюджет каналу, который его не заработал.
 */
const CHANNEL_KEY = "aevion_gtm_channel";
/*
 * 🔴 Пост хранится ОТДЕЛЬНЫМ ключом, а не внутри канального.
 *
 * В канальном лежит КАНОНИЧЕСКАЯ короткая метка («yt»), и это намеренно: в
 * кассе канал обязан называться одним именем. Но из неё подметку уже не
 * достать, поэтому после первого же перехода `postNow()` отвечал null —
 * пост доезжал только с посадочной страницы, а деньги случаются позже, на
 * кассе. Вопрос «какой ролик привёл к оплате» оставался без ответа.
 *
 * Класть подметку в канальный ключ нельзя: его читает `channelFrom`, и
 * «yt-chess-level» в кассе стало бы отдельным «каналом».
 */
const POST_KEY = "aevion_gtm_post";

/**
 * КАНОНИЧЕСКАЯ метка канала — то, что кладём в память и что уедет в кассу.
 *
 * 🔴 Зачем функция, а не «что пришло в адресе». Со 30.09 `channelFrom` принимает
 * не только короткую метку: длинное имя (`?c=instagram`, его пишет клиент,
 * переписывая ссылку) и написание площадки (`?c=producthunt`). Положи в память
 * то, что пришло, — и один канал заживёт под тремя именами: в памяти
 * «instagram», в наших ссылках «ig», в отчёте оба. Сводка разошлась бы сама с
 * собой, а денежная правда лежит в заказе у кассы.
 *
 * Поэтому храним ответ `channelParam`: у каждого имени он берёт ПЕРВЫЙ короткий
 * ключ, то есть тот же, что ставит в ссылки наш собственный код.
 */
function каноничная(имя: string): string | undefined {
  return channelParam(имя) ?? undefined;
}

function запомнитьПост(пост: string | null): void {
  try {
    if (пост && !sessionStorage.getItem(POST_KEY)) sessionStorage.setItem(POST_KEY, пост);
  } catch {
    // Хранилище закрыто — пост доедет только с посадочной. Потеря точности.
  }
}

function вспомнитьПост(): string | undefined {
  try {
    return sessionStorage.getItem(POST_KEY) ?? undefined;
  } catch {
    return undefined;
  }
}

function запомнить(метка: string): void {
  try {
    if (!sessionStorage.getItem(CHANNEL_KEY)) sessionStorage.setItem(CHANNEL_KEY, метка);
  } catch {
    // Хранилище может быть закрыто (приватный режим). Тогда метка просто не
    // переживёт кассу — это потеря точности, а не поломка.
  }
}

function вспомнить(): string | undefined {
  try {
    return sessionStorage.getItem(CHANNEL_KEY) ?? undefined;
  } catch {
    return undefined;
  }
}

/** Разобранное имя канала или `null`. Адрес страницы старше памяти. */
/**
 * ВХОДЯЩАЯ метка `?c=` как есть, без нормализации.
 *
 * Нужна ровно для одного: внешняя касса должна увидеть НАЗВАНИЕ КАМПАНИИ. `channelNow`
 * для этого не годится намеренно — он отдаёт канонический канал и роняет всё
 * неизвестное в null, иначе один канал зажил бы под тремя именами. А рекламная метка
 * составная («meta-book-<кампания>»), и в отчёте кассы нужна она целиком.
 *
 * В память НЕ кладём и в наши внутренние переходы НЕ подставляем: там по-прежнему
 * канонический ключ.
 */
export function сыраяМеткаКанала(): string | null {
  if (typeof window === "undefined") return null;
  try {
    const v = new URLSearchParams(window.location.search).get("c");
    return v && v.trim() ? v.trim() : null;
  } catch {
    // Адрес не разобрался — это «не знаю», а не «метки нет»; ведём себя как без метки.
    return null;
  }
}

export function channelNow(): string | null {
  if (typeof window === "undefined") return null;
  const параметры = new URLSearchParams(window.location.search);
  const метка = параметры.get("c") ?? undefined;
  const изАдреса = channelFrom(метка);
  if (изАдреса) {
    // Кладём КАНОНИЧЕСКУЮ метку, а не пришедшую: адрес мог нести длинное имя или
    // написание площадки, и в кассе канал обязан называться одним именем.
    const к = каноничная(изАдреса);
    if (к) запомнить(к);
    return изАдреса;
  }
  // Запасной ключ: площадки метят исходящие ссылки своим `?ref=` и переписать
  // его нельзя (карточка Product Hunt ведёт на /en/devhub?ref=producthunt).
  // `c` главнее намеренно: если стоят оба, наша метка точнее — её ставили мы
  // под конкретный пост, а ref говорит только про площадку.
  const реф = параметры.get("ref") ?? undefined;
  const изРефа = channelFromRef(реф);
  if (изРефа && реф) {
    // Запоминаем КОРОТКУЮ метку канала, а не сырой ref: в памяти и в кассе
    // канал должен называться одним именем, иначе сводка разойдётся сама с собой.
    const короткая = каноничная(изРефа);
    if (короткая) запомнить(короткая);
    return изРефа;
  }
  // Из памяти — только когда в адресе метки нет: так возврат из кассы и переход
  // без метки сохраняют источник, а обычные страницы по-прежнему верят адресу.
  return channelFrom(вспомнить());
}

/**
 * Пост, с которого пришли: подметка `?c=ig-kartinka3` → «kartinka3».
 *
 * 🔴 Зачем отдельной функцией, а не частью канала. Замер 30.09.2026: Instagram —
 * единственный канал, приводящий людей до цен, и трафик идёт рывками, то есть
 * постами. Но «какой пост сработал» ответить нечем: у всех ссылок одна метка.
 * Пост уезжает в учёт ОТДЕЛЬНЫМ полем: подмешай его к имени канала, и каждый пост
 * стал бы «новым каналом» — сравнить Instagram с YouTube было бы нечем.
 *
 * Память та же, что у канала: адрес старше памяти, при закрытом хранилище пост
 * живёт до перехода на другую страницу. Потеря точности, не поломка.
 */
export function postNow(): string | null {
  if (typeof window === "undefined") return null;
  const параметры = new URLSearchParams(window.location.search);
  const изАдреса = postFrom(параметры.get("c") ?? undefined);
  if (изАдреса) {
    /*
     * 🔴 Проверочный заход (`?probe=<окно>`) подметку НЕ закрепляет.
     *
     * Иначе наша проба пачкает вкладку: человек, зашедший следом по этой же
     * вкладке без метки, унаследовал бы наш пост и уехал в отчёт как пришедший
     * с него. Сам заход при этом метку несёт и считается — он помечен нашим на
     * стороне воронки по тому же параметру.
     */
    if (!параметры.has("probe")) запомнитьПост(изАдреса);
    return изАдреса;
  }
  // Память — только когда в адресе подметки нет. Адрес старше памяти, как и
  // у канала: иначе первый пост вкладки прилипал бы ко всем следующим.
  return вспомнитьПост() ?? null;
}

/**
 * Метка захода, которая уезжает В ЗАПИСЬ ПРОЕКТА DevHub.
 *
 * 🔴 Зачем отдельно от `channelNow`/`postNow`. Те два отвечают учёту: канал
 * канонический, пост отдельным полем, неизвестное роняется в null — иначе один
 * канал зажил бы под тремя именами. Записи проекта нужно другое: ОДНО поле,
 * по которому потом можно сказать «с какого ролика человек дошёл до сборки».
 * Воронка знает заходы на страницу, а проект до 12.10.2026 не знал ничего:
 * источник обрывался на входе, и самый ценный шаг пути — «собрал приложение» —
 * был безымянным.
 *
 * Поэтому здесь берётся СЫРАЯ метка целиком («yt-chess-level», а не «youtube»):
 * она и называет ролик. Нет её в адресе — берём из памяти вкладки (пост точнее
 * канала, поэтому он первым). Нет ничего — null, честное «не знаем»: выдуманная
 * метка хуже отсутствующей, потому что по ней потом сделают вывод.
 *
 * Вторая польза, ради которой это сделано сейчас: по метке `probe-*` сервер сам
 * снимает наши пробные сайты. До этого единственным признаком пробы было ИМЯ
 * проекта, и соседним окнам приходилось портить его словом «probe» — а у окна
 * роликов имя проекта видно в кадре.
 */
export function меткаЗаходаДляЗаписи(): string | null {
  if (typeof window === "undefined") return null;
  /*
   * ⚠️ `postNow`/`channelNow` зовутся ВСЕГДА и первыми, даже когда ответ у нас
   * уже есть. Запоминают метку только они, и своего хранилища здесь нет
   * намеренно — второй способ помнить то же самое разошёлся бы с первым.
   * Поймано своим же сторожем: ранняя версия возвращала сырую метку, минуя их,
   * и человек, пришедший с ролика на /devhub и нажавший «Новый проект» уже без
   * метки в адресе, попадал в запись БЕЗ источника. То есть правило теряло
   * ровно тот случай, ради которого написано.
   */
  const пост = postNow();
  const канал = channelNow();
  const изАдреса = сыраяМеткаКанала() ?? проверочныйЗаход();
  // Длину и состав ограничиваем здесь же, а не только на сервере: метка едет в
  // базу и в сводки, и «любая строка из адреса» — это чужой ввод.
  if (изАдреса && /^[A-Za-z0-9_-]{1,60}$/.test(изАдреса)) return изАдреса.toLowerCase();
  // Из памяти: пост точнее канала — он называет ролик, а канал только площадку.
  return пост ?? канал;
}

/** `?probe=<окно>` — заход нашего окна по НАСТОЯЩЕЙ метке канала (§0-НАШИ-ЗАХОДЫ). */
function проверочныйЗаход(): string | null {
  try {
    const v = new URLSearchParams(window.location.search).get("probe");
    return v && v.trim() ? `probe-${v.trim()}` : null;
  } catch {
    return null;
  }
}
