import { join } from "node:path";

/**
 * У гостя на странице QSign есть бесплатное действие, и оно ведёт на публичную
 * проверку настоящей подписи.
 *
 * ЗАЧЕМ. Замер 28.09.2026 по четырём продаваемым модулям: QSkyway строит
 * маршрут (200, 8 городов), QRight защищает объект в один клик (201 за 1.2 с,
 * сертификат), Биржа разбирает идею (200 за 0.5 с). У QSign гость не мог
 * сделать НИЧЕГО: главное действие «подписать» закрыто входом (requireAuth на
 * v2/sign, прод отвечает 401). Человек приходил со страницы цен, где модуль
 * стоит $24, и уходил, не увидев продукта, — единственный из четырёх.
 *
 * Открытая дверь была всё это время: проверка подписи входа не требует, а у
 * каждой подписи есть публичная страница `/qsign/verify/<id>`, которая у гостя
 * открывается и показывает VALID (проверено на проде 28.09). Не хватало одного:
 * с главной страницы модуля на неё ничто не вело.
 *
 * Сторож держит именно СВЯЗЬ: лента настоящих подписей на странице есть давно,
 * и её наличие ничего не доказывает — доказывает ссылка из неё на публичную
 * проверку. Уберут блок или заменят ссылку на якорь внутри страницы — проверка
 * покраснеет.
 *
 * ГРАНИЦА, названная честно: это проверка ИСХОДНИКА, а не браузера. Она
 * отвечает «ссылка на публичную проверку строится из настоящей записи», но не
 * «человек её увидел». Снаружи это не проверить без прогона браузером, а ради
 * одного блока его заводить дороже, чем он стоит.
 */

const PAGE = join(__dirname, "..", "page.tsx");
const src = readFileSync(PAGE, "utf8");

