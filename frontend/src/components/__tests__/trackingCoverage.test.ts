import { describe, test, expect } from "vitest";
import { readFileSync, existsSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

/**
 * Страница, которая ведёт к покупке, обязана считать посещения.
 *
 * Замер 13.08.2026: из посадочных считала одна `/pricing`, а ролики вели на
 * `/qrenew` и `/qmelanin`, где не считалось НИЧЕГО. Поставили PageTracking на
 * шесть страниц. 14.08 оказалось, что этого мало: `/constitution`, её
 * собственный прайс, `/devhub` и `/studio` тоже ведут к оплате и тоже молчали
 * — а `/constitution` вдобавок вела свою отдельную воронку, из-за чего в
 * сводке платформы её посетителей не было вовсе.
 *
 * Дважды находить это руками — плохой способ. Сторож считает страницы с
 * кнопкой покупки и требует, чтобы каждая умела считать посещение: либо через
 * PageTracking, либо своим вызовом page_view.
 *
 * Ложное срабатывание тут дороже пропуска, поэтому берём только ЯВНЫЕ признаки
 * покупки: ссылку в магазин или переход на чекаут.
 */

const APP = join(__dirname, "..", "..", "app");

/** Ссылка в кассу или на чекаут — то есть страница ведёт к оплате. */
const BUY_MARKERS = [/gumroad\.com\/l\//, /lemonsqueezy\.com/, /\bGUM\(/, /\bLS\(/];

/**
 * Сбор адресов - это тоже деньги, только на шаг раньше.
 *
 * Замер 28.08.2026: правило "страница ведёт к ОПЛАТЕ" пропускало посадочные,
 * где кассы нет, а есть форма подписки. Молчали пять, включая ГЛАВНУЮ и
 * посадочные модулей 2, 3 и 4 очереди запуска.
 *
 * Цена пропуска не абстрактная: воронка считает переходы ОТ page_view, значит
 * посетители таких страниц не попадали в знаменатель - конверсия выглядела
 * лучше, чем есть. А для запуска это вопрос "продаж нет из-за страницы или
 * из-за отсутствия трафика", и без числа заходов на него не ответить.
 */
const LEAD_MARKERS = [/<WaitlistCapture\b/, /<EmailCapture\b/];

/** Умеет ли страница считать посещение хоть каким-то способом. */
const VIEW_MARKERS = [/<PageTracking\b/, /track\(\s*"page_view"/, /type:\s*"page_view"/];

/**
 * Страницы, где ссылка на магазин есть, но покупки на них не происходит.
 * Каждое исключение — с причиной: без неё список тихо разрастётся до бесполезного.
 */
const NOT_A_SALES_PAGE: Record<string, string> = {
  "legal/privacy/page.tsx": "юридический текст, ссылка упомянута как обработчик платежей",
  "revenue/page.tsx": "внутренний дашборд выручки, не для покупателя",
  "qmelanin/_client.tsx": "часть страницы qmelanin — замер стоит в её page.tsx, второй считал бы то же посещение дважды",
  "longevity/_client.tsx": "часть страницы longevity — замер стоит в её page.tsx, второй считал бы то же посещение дважды",
  "qskyway/_client.tsx": "часть страницы qskyway — замер стоит в её page.tsx, второй счётчик дал бы ДВА события на заход. Проверено 01.09.2026: PageTracking в page.tsx 3 раза, в _client.tsx 0; форма подписки живёт в клиенте, поэтому сторож видел клиент без счётчика. Переносить счётчик в клиент нельзя — потеряется ветка платной стены, а посещение есть посещение.",
  "devhub/[id]/page.tsx": "рабочее место внутри DevHub: касса там нужна пользователю, чтобы продать СВОЙ материал, а не нам — свой",
};

function walk(dir: string, acc: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, acc);
    // Тесты не страницы: render-проверка посадочной содержит <WaitlistCapture>
    // и попадала под правило про сбор адресов. Исключаем классом, а не поимённо.
    else if (name.endsWith(".tsx") && !name.includes(".test.") && !p.includes("__tests__")) acc.push(p);
  }
  return acc;
}

const rel = (p: string) => p.slice(APP.length + 1).replace(/\\/g, "/");

describe("страницы с покупкой умеют считать посещение", () => {
  const files = walk(APP);

  test("контроль: файлы страниц вообще нашлись", () => {
    // Пустой обход дал бы зелёный на любом состоянии кода.
    expect(files.length).toBeGreaterThan(20);
  });

  test("контроль: признак покупки находит уже известные страницы", () => {
    // Если разметку ссылок изменят, сторож должен упасть здесь, а не молча
    // перестать что-либо проверять.
    const withBuy = files.filter((f) => {
      const src = readFileSync(f, "utf8");
      return BUY_MARKERS.some((re) => re.test(src));
    });

    expect(withBuy.length, "ни одной страницы с кнопкой покупки — сторож ослеп").toBeGreaterThan(3);
  });

  test("контроль: признак сбора адресов тоже находит страницы", () => {
    // Второму признаку нужен свой контроль: переименуют компонент формы - и
    // правило про адреса тихо перестанет что-либо проверять, оставаясь зелёным.
    const withLead = files.filter((f) => LEAD_MARKERS.some((re) => re.test(readFileSync(f, "utf8"))));
    expect(withLead.length, "ни одной страницы со сбором адресов — сторож ослеп").toBeGreaterThan(3);
  });

  test("у каждой такой страницы есть замер посещения", () => {
    const silent: string[] = [];

    for (const f of files) {
      const src = readFileSync(f, "utf8");
      const sells = BUY_MARKERS.some((re) => re.test(src));
      const collects = LEAD_MARKERS.some((re) => re.test(src));
      if (!sells && !collects) continue;
      /*
       * ⚠️ 01.09.2026: исключение стало УСЛОВНЫМ, и это не строгость ради
       * строгости.
       *
       * Раньше запись в списке снимала проверку НАСОВСЕМ. Вписав сюда
       * `qskyway/_client.tsx` с причиной «замер стоит в page.tsx», я прогнал
       * мутацию — сломал импорт счётчика в САМОМ page.tsx — и сторож остался
       * зелёным. То есть модуль перестал проверяться вовсе: клиент прощён
       * списком, а страница не попадает под правило, потому что признаков
       * продажи в ней нет.
       *
       * Причина «замер стоит в соседнем файле» верна ровно до тех пор, пока он
       * там ДЕЙСТВИТЕЛЬНО стоит. Теперь это проверяется, а не берётся на веру.
       *
       * Прежние две записи (qmelanin, longevity) той же формы — они тоже
       * начинают проверяться, и это правильно: у них ровно то же обоснование.
       */
      if (NOT_A_SALES_PAGE[rel(f)]) {
        const соседняя = f.replace(/_client\.tsx$/, "page.tsx");
        if (f.endsWith("_client.tsx") && existsSync(соседняя)) {
          const рядом = readFileSync(соседняя, "utf8");
          if (!VIEW_MARKERS.some((re) => re.test(рядом))) {
            silent.push(rel(f) + " (прощён списком, но в соседней page.tsx замера НЕТ)");
          }
        }
        continue;
      }
      if (VIEW_MARKERS.some((re) => re.test(src))) continue;
      silent.push(rel(f));
    }

    expect(
      silent,
      `страницы ведут к оплате или собирают адреса, но не считают посещение: ` +
        `${silent.join(", ")}. ` +
        `Поставьте <PageTracking page="…" /> или внесите в NOT_A_SALES_PAGE с причиной.`,
    ).toEqual([]);
  });
});
