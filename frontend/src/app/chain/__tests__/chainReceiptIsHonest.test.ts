import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Чек цепочки не превращает «не знаем» в «не подтверждено».
 *
 * Страница обещает проверяемость, поэтому у неё ЧЕТЫРЕ исхода на шаг, а не два:
 * подтверждено / отозвано / не найдено / проверить не удалось. Схлопывание
 * последних двух в «не подтверждено» обвиняло бы человека в подделке из-за
 * нашего же обрыва связи — это ровно тот класс, который мы весь месяц
 * вычищаем из кода.
 *
 * Сторож читает ИСХОДНИК: страница ходит в сеть, и поднимать её ради проверки
 * набора состояний дороже пользы. Границу называю честно — отрисовку он не
 * проверяет.
 */

const СТРАНИЦА = readFileSync(
  join(__dirname, "..", "page.tsx"),
  "utf8",
);

function безКомментариев(src: string): string {
  return src
    .split("\n")
    .filter((l) => {
      const t = l.trim();
      return !t.startsWith("//") && !t.startsWith("*") && !t.startsWith("/*");
    })
    .join("\n");
}

describe("чек цепочки честен", () => {
  it("контроль: файл прочитан и это действительно страница", () => {
    expect(СТРАНИЦА.length, "файл пуст или не найден").toBeGreaterThan(1500);
    expect(СТРАНИЦА, "не похоже на страницу").toContain("export default function");
  });

  it("четыре исхода на шаг, а не два", () => {
    for (const с of ["ok", "revoked", "missing", "failed"]) {
      expect(СТРАНИЦА, `исход «${с}» пропал — «не знаем» схлопнется в «подделка»`)
        .toContain(`"${с}"`);
    }
  });

  it("сетевой отказ даёт «не удалось», а не «не подтверждено»", () => {
    // В catch обязан стоять именно failed: это утверждение о НАШЕЙ связи,
    // а не о подписи человека.
    const i = СТРАНИЦА.indexOf("catch");
    expect(i, "нет обработки отказа сети вовсе").toBeGreaterThan(-1);
    expect(
      СТРАНИЦА.slice(i, i + 260),
      "после обрыва связи страница утверждает что-то о подписи",
    ).toContain("failed");
  });

  it("про предварительный режим сказано вслух", () => {
    const src = безКомментариев(СТРАНИЦА);
    expect(src, "страница молчит о preview — обещает проверяемость, которой нет")
      .toContain("previewWarn");
    expect(src, "признак preview не читается из ответа").toContain("preview");
  });

  it("подписи идут через словарь, а не зашиты", () => {
    const src = безКомментариев(СТРАНИЦА);
    const русские = src
      .split("\n")
      .filter((l) => /["'`][^"'`]*[А-Яа-яЁё]{3,}[^"'`]*["'`]/.test(l))
      .filter((l) => !l.includes('lang="ru"'));
    expect(русские.map((l) => l.trim().slice(0, 60)), "русский текст зашит в разметке")
      .toEqual([]);
  });
});
