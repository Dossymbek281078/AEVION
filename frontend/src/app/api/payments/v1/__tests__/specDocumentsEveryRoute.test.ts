import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

/**
 * Сторож: у каждого живого маршрута есть описание в опубликованной спеке.
 *
 * ЗАЧЕМ. Интегратор читает не страницу, а /api/openapi.json. Спека и код —
 * два наших ответа об одном, и расходятся они молча: маршрут появляется,
 * спека остаётся прежней, и снаружи API выглядит меньше, чем есть.
 *
 * ⚠️ Первая версия смотрела только каталоги ПЕРВОГО уровня и потому не
 * видела /v1/webhooks/{id}/test — единственный неописанный маршрут из
 * тринадцати. Слепую зону нашёл сразу после того, как объявил сторож
 * готовым, поэтому обход теперь рекурсивный: находки в слепой зоне по
 * одной не приходят.
 *
 * ГРАНИЦА, названная прямо: сторож проверяет ОДНУ сторону — что живой
 * маршрут описан. Обратную (описан, но не существует) он НЕ проверяет:
 * для этого нужен запуск приложения, здесь его нет.
 */
const V1 = join(__dirname, "..");
const spec = readFileSync(join(V1, "..", "..", "openapi.json", "route.ts"), "utf8");

function маршруты(dir: string, prefix = "/v1"): string[] {
  const out: string[] = [];
  const items = readdirSync(dir, { withFileTypes: true });
  if (items.some((i) => i.isFile() && i.name === "route.ts") && prefix !== "/v1") {
    out.push(prefix);
  }
  for (const i of items) {
    if (!i.isDirectory() || i.name === "__tests__") continue;
    // [id] в файловой системе — это {id} в спеке.
    const segment = i.name.replace(/^\[(.+)\]$/, "{$1}");
    out.push(...маршруты(join(dir, i.name), `${prefix}/${segment}`));
  }
  return out;
}

describe("спека описывает каждый живой маршрут", () => {
  it("у всех маршрутов, включая вложенные, есть путь в спеке", () => {
    const все = маршруты(V1);

    // Знаменатель обязателен: без него зелёный цвет мог бы означать
    // «маршрутов не нашлось», а не «все описаны».
    expect(все.length, "маршрутов не найдено — сторож проверял пустоту").toBeGreaterThan(10);
    // Контроль обхода: вложенный маршрут обязан попасть в выборку, иначе
    // рекурсия сломана и ноль будет ложным.
    expect(все, "рекурсия не дошла до вложенных маршрутов").toContain(
      "/v1/webhooks/{id}/test"
    );

    const необъявленные = все.filter((m) => !spec.includes(`"${m}"`));
    expect(необъявленные, "маршрут живёт, а в спеке его нет").toEqual([]);
  });

  it("каждый обещанный МЕТОД существует в коде", () => {
    // Проверка путей ничего не говорит о методах: спека может обещать POST
    // там, где обработчик умеет только GET, и запрос по документации получит
    // 405. Здесь без регулярок — разбор по строкам, чтобы экранирование не
    // съело шаблон (оно уже съедало у меня слэши сегодня).
    const NL = String.fromCharCode(10);
    const МЕТОДЫ = ["get", "post", "patch", "delete", "put"];
    const обещано = new Map<string, string[]>();
    let текущий = "";
    for (const line of spec.split(NL)) {
      const t = line.trim();
      if (t.startsWith('"/v1/') && t.endsWith('": {')) {
        текущий = t.slice(1, t.indexOf('": {'));
        обещано.set(текущий, []);
      } else if (текущий) {
        for (const m of МЕТОДЫ) {
          if (line.startsWith(`      ${m}: {`)) обещано.get(текущий)!.push(m);
        }
      }
    }

    const всегоМетодов = [...обещано.values()].reduce((a, b) => a + b.length, 0);
    // Знаменатель на обеих осях: и пути, и методы. Пустые множества дали бы
    // зелёный цвет при сломанном разборе.
    expect(обещано.size, "путей в спеке не разобрано").toBeGreaterThan(10);
    expect(всегоМетодов, "методов в спеке не разобрано").toBeGreaterThan(15);

    const нет: string[] = [];
    for (const [путь, методы] of обещано) {
      const rel = путь.replace("/v1/", "").replace("{id}", "[id]");
      const файл = join(V1, rel, "route.ts");
      const src = readFileSync(файл, "utf8");
      for (const m of методы) {
        // Скобка обязательна: без неё "GETX" содержит "GET" как подстроку, и
        // мутация переименования метода проходит незамеченной. Поймано
        // мутацией на этом самом стороже.
        if (!src.includes(`export async function ${m.toUpperCase()}(`)) {
          нет.push(`${m.toUpperCase()} ${путь}`);
        }
      }
    }
    expect(нет, "контракт обещает метод, которого нет в коде").toEqual([]);
  });
});
