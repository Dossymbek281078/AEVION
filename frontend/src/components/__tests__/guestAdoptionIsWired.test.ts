import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Гостевая работа обязана переезжать в аккаунт при входе — и НЕ САМА СОБОЙ.
 *
 * Замер 03.09.2026, двумя независимыми способами:
 *   поиск по именам   claimGuest|migrateGuest|adoptGuest  -> 0
 *   поиск по СПОСОБНОСТИ  SET "userId" в SQL              -> 0
 * То есть человек, попробовавший DevHub гостем и затем вошедший, терял свои
 * проекты из виду: они остаются на «guest:<id>», а личностью после входа
 * становится sub из токена. Ни одного отказа при этом не происходит —
 * список просто приходит пустым, и это неотличимо от «у вас ничего нет».
 *
 * Ручка переноса написана (`POST /api/devhub/studio/adopt-guest`) и закрыта
 * тестами на стороне бэкенда. Здесь охраняется ВТОРАЯ половина, которой у
 * платформы уже не раз не хватало: «механизм собран, части не связаны».
 * Ручка без вызывающего работает ровно как отсутствующая.
 *
 * Сторож намеренно читает ИСХОДНИК, а не рендерит компонент: он ничего не
 * рисует и в тесте пришлось бы подменять и fetch, и хранилище, и токен —
 * тогда проверялись бы заглушки. Цена решения честная: перенос вызова в
 * соседний модуль сторож увидит как пропажу. Это не ложная тревога, а повод
 * прийти сюда и перенести проверку следом.
 */

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const ФАЙЛ = join(ЗДЕСЬ, "..", "DevHubGuestIdentity.tsx");
const src = readFileSync(ФАЙЛ, "utf8");

describe("гостевая работа переезжает в аккаунт: вызов на месте", () => {
  it("прибор исправен: файл прочитан и это тот компонент", () => {
    // Контроль охвата. Без него пустой или чужой файл дал бы «расхождений
    // нет» — самый частый вид ложного зелёного.
    expect(src.length, "файл пуст — сторож охраняет пустоту").toBeGreaterThan(200);
    expect(src, "прочитан не тот файл").toContain("installDevhubGuestHeader");
  });

  it("ручка переноса действительно вызывается", () => {
    expect(
      src,
      "Вызов POST /api/devhub/studio/adopt-guest исчез. Ручка на бэкенде " +
        "останется зелёной по своим тестам, а человек после входа перестанет " +
        "видеть работу, сделанную гостем. Если вызов ПЕРЕЕХАЛ в другой модуль " +
        "— перенесите сюда и эту проверку, а не удаляйте её.",
    ).toContain("/api/devhub/studio/adopt-guest");
    expect(src, "перенос должен идти методом POST").toContain('method: "POST"');
  });

  it("вызов снабжён токеном — иначе ручка не знает, КОМУ переносить", () => {
    // Без Authorization ручка отвечает not_signed_in, и перенос молча
    // не происходит: та же пустота, только с лишним запросом.
    expect(src, "токен входа не читается").toContain("getAuthToken");
    expect(src, "заголовок Authorization не отправляется").toContain("Authorization");
  });

  it("вызов не делается без входа и без гостевой личности", () => {
    // Обе проверки нужны: без входа переносить некуда, без гостя нечего.
    // Их отсутствие — не авария, но это запрос на каждый заход анонимного
    // посетителя, то есть шум в журналах и лишняя нагрузка.
    expect(src, "не проверяется наличие токена и гостевого идентификатора")
      .toMatch(/if\s*\(!\s*[^)]*\|\|\s*!/);
    expect(src, "гостевой идентификатор не читается").toContain("getDevhubGuestId");
  });

  it("успех запоминается, а отказ — нет", () => {
    // Отметка при ОТКАЗЕ означала бы «попробовали один раз и молча сдались»:
    // сеть моргнула — работа потеряна навсегда. Поэтому отметка ставится
    // строго внутри ветки r.ok.
    const at = src.indexOf("setItem");
    expect(at, "отметка о переносе не ставится вовсе — ручку будут звать при каждом заходе")
      .toBeGreaterThan(0);
    const строка = src.slice(src.lastIndexOf("\n", at) + 1, src.indexOf("\n", at));
    expect(
      строка,
      "Отметка ставится вне проверки r.ok — при отказе перенос больше " +
        "никогда не повторится, и гостевая работа будет потеряна насовсем.",
    ).toContain("r.ok");
  });
});
