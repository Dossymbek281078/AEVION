describe("страница не говорит по-русски мимо выбора языка", () => {
  // ⚠️ Раньше читался ОДИН файл — `_client.tsx`. 28.08.2026 это дало пропуск:
  // соседний `HeightDisputePanel.tsx` показывал восемь строк зашитого русского
  // англоязычному посетителю, и сторож молчал, потому что не читал его вовсе.
  // Слепота была не в правиле, а в ОХВАТЕ — тот же класс, что «шаблон видел
  // одну форму записи из двух».
  //
  // Теперь обходим всю папку страницы. Тесты и сторожа исключены: русский в
  // них адресован разработчику. Сборки и переводы сюда не попадают — каталог
  // содержит только исходники самой страницы.
  const files = readdirSync(__dirname)
    .filter((f) => f.endsWith(".ts") || f.endsWith(".tsx"))
    .filter((f) => !f.includes(".test.") && !f.includes(".guard."))
    .sort();
  const found = files
    .flatMap((f) => stripComments(readFileSync(path.join(__dirname, f), "utf8")))
    .map((l) => decodeEscapes(l))
    .filter((l) => hasCyrillic(l))
    .filter((l) => !l.includes("t(" + String.fromCharCode(34)))
    .filter((l) => !l.includes("ru ?") && !l.includes("ru?"))
    .filter((l) => !l.includes("lang ===") && !l.includes("lang==="))
    // Записи в журнал исключены НАМЕРЕННО: их читает разработчик, а не
    // посетитель, и язык там дело автора. Сторож про то, что видит человек
    // на экране. Без этого исключения он гонит к худшему: писать в журнал
    // по-английски ради зелёного цвета или не писать вовсе.
    .filter((l) => !l.includes("console."))
    .map((l) => l.split(" ").filter(Boolean).join(" "));

  it("контроль охвата: читается вся папка, а не один файл", () => {
    // Именно этого утверждения не хватало: пока сторож читал один файл, он был
    // зелёным и слепым, и отличить «чисто» от «не смотрел» было нельзя.
    expect(files.length).toBeGreaterThan(3);
    expect(files).toContain("_client.tsx");
    expect(files).toContain("HeightDisputePanel.tsx");
    expect(files.some((f) => f.includes(".test."))).toBe(false);
  });

  it("новых мест с русским текстом мимо выбора языка нет", () => {
    const fresh = found.filter((l) => !KNOWN.has(l));
    expect(
      fresh,
      "новый русский текст мимо выбора языка. Либо переведите через t() и ключ "
        + "в трёх языках, либо внесите строку в KNOWN вместе с объяснением, "
        + "почему её нельзя перевести сейчас. Просто добавить в список — значит "
        + "спрятать долг, а не признать его.",
    ).toEqual([]);
  });

  it("список известных мест не оторвался от файла", () => {
    // Переведённая строка обязана уйти из списка: иначе долг выглядит больше,
    // чем он есть, и следующий читатель не поверит ни одной цифре.
    const stale = Array.from(KNOWN).filter((k) => !found.includes(k));
    expect(
      stale,
      "эти строки уже переведены — уберите их из KNOWN. Список, из которого не "
        + "убирают сделанное, показывает долг больше настоящего, и цифрам "
        + "перестают верить.",
    ).toEqual([]);
  });

  it("список известных только СОКРАЩАЕТСЯ, а не растёт", () => {
    // ⚠️ Этой стороны у храповика не было до 28.08.2026, и нашлась она приёмом,
    // применённым к чужому сторожу: у него при удалении записи краснели ДВА
    // утверждения, у меня одно.
    //
    // Без неё храповик наполовину декоративный: можно добавить новую русскую
    // строку И ТУТ ЖЕ вписать её в KNOWN — обе прежние проверки промолчат, а
    // долг вырастет. Список, который умеет расти, ничего не стережёт: он
    // просто протокол того, что мы уже согласились не чинить.
    //
    // Число опускать МОЖНО и нужно — вместе с настоящим переводом строки.
    // Поднимать нельзя: это и есть тот случай, ради которого проверка стоит.
    expect(
      KNOWN.size,
      "список известных вырос: значит русский текст добавили и сразу узаконили. "
        + "Переведите строку вместо того, чтобы вписывать её в долг.",
    ).toBeLessThanOrEqual(14);
  });

  it("сама проверка видит кириллицу и не видит латиницу", () => {
    // Отрицательный контроль. Без него зелёный ответ не отличить от «поиск не
    // сработал» — а именно так соврал первый прогон этого свипа 28.08.
    expect(hasCyrillic(String.fromCharCode(1084, 47, 1089))).toBe(true);
    expect(hasCyrillic("m/s")).toBe(false);
    expect(found.length).toBeGreaterThan(0);
  });
});
