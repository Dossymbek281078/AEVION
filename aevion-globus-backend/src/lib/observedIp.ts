/**
 * Адрес, который НАБЛЮДАЛ наш прокси, — для записи в журнал сессий и аудита.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. До 27.08.2026 в проекте было ЧЕТЫРЕ копии функции
 * «взять адрес клиента», и они разошлись. Две из них — в `routes/auth.ts` и
 * `routes/authOauth.ts` — читали ЛЕВОЕ значение заголовка `X-Forwarded-For`:
 *
 *     const first = xff.split(",")[0]?.trim();
 *     return first || req.ip || ...
 *
 * Прокси дописывает свой адрес СПРАВА, поэтому левое значение пишет сам
 * вызывающий, и не проверяет его никто. То есть любой мог прислать
 * `X-Forwarded-For: 8.8.8.8` и получить этот адрес в записи о своём входе.
 *
 * Ограничители частоты этим НЕ затронуты (проверено: вход ограничивается
 * `rateLimit()` без своего keyFn, а он берёт нормализованный `req.ip`).
 * Затронуты записи — те самые, по которым разбираются ПОСЛЕ инцидента:
 * список «недавние входы» у пользователя и журнал аудита. Подделываемый
 * след хуже отсутствующего: отсутствующий не вводит в заблуждение.
 *
 * Здесь берётся `req.ip`. Express выводит его из того же заголовка, но
 * только по тем шагам, которые приложение объявило доверенными
 * (`app.set("trust proxy", 1)` в index.ts), — то есть это адрес, который
 * действительно видел фронтовый прокси.
 *
 * ⚠️ НЕ нормализуем до /64, в отличие от ключа ограничителя: там нужно
 * схлопывание, чтобы человек не получал свежее окно с каждого адреса своей
 * подсети, а здесь нужен ТОЧНЫЙ адрес — журнал аудита тем и ценен.
 */
export function observedIp(req: {
  ip?: string;
  socket?: { remoteAddress?: string };
}): string | null {
  return req.ip || req.socket?.remoteAddress || null;
}
