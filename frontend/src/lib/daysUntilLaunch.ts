/**
 * Сколько дней осталось до запуска модуля — по календарю ЗАПУСКА, не по UTC.
 *
 * ЗАМЕР, из которого это выросло. 28.08.2026 в 00:20 по местному (19:20 UTC)
 * посадочная CyberChess печатала «Через 3 дня», а календарь читателя показывал
 * 28 августа — то есть два. Обе страницы запуска считали по UTC, а читатель
 * живёт в UTC+5: расхождение живёт пять часов в СУТКИ, каждые сутки.
 *
 * Хуже всего последний день. 30 августа с 00:00 до 05:00 по местному страница
 * сказала бы «Через 1 день» — В САМ ДЕНЬ ЗАПУСКА, человеку, который открыл
 * ссылку из письма про сегодняшний запуск. Письмо и страница противоречили бы
 * друг другу в самый заметный момент.
 *
 * Почему один модуль, а не по функции на страницу: копий было две
 * (`cyberchess/launch` и `bureau/launch`), и обе с одним дефектом. Второй
 * способ считать то же самое разошёлся бы с первым на первом же краевом случае.
 *
 * Почему смещение, а не Intl с именем зоны: нужен один вопрос — «какое сегодня
 * число там, откуда ведут запуск». Для читателя западнее счёт может оказаться
 * на несколько часов «раньше», и это безопасная сторона ошибки: никому не
 * скажут «ещё день», когда день уже настал.
 */

/** Часовой пояс, в котором ведётся запуск (Алматы, UTC+5). */
export const LAUNCH_TZ_OFFSET_MS = 5 * 3_600_000;

/**
 * @param launchUtcMidnight — `Date.UTC(год, месяц, день)` дня запуска.
 * @param now — вынесен параметром ради проверки: иначе прогнать полночь и
 * границу часового пояса можно было бы только подменой системного времени,
 * то есть проверяя окружение, а не эту функцию.
 * @returns 0 в день запуска, отрицательное — после него.
 */
export function daysUntilLaunch(launchUtcMidnight: number, now: Date = new Date()): number {
  const shifted = new Date(now.getTime() + LAUNCH_TZ_OFFSET_MS);
  const today = Date.UTC(shifted.getUTCFullYear(), shifted.getUTCMonth(), shifted.getUTCDate());
  return Math.round((launchUtcMidnight - today) / 86_400_000);
}
