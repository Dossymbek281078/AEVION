import { describe, test, expect } from "vitest";
import { clearedUpToMFor } from "../src/routes/qskyway";

/**
 * `clearedUpToM` — заявление о безопасности: «этот коридор терпит препятствие
 * не выше N метров». Сейчас N это константа `FLOOR - CLEAR` = 35, то есть
 * ответ для случая «коридор лежит на полу». Участок со съеденным штрафом может
 * стоять и выше, и тогда настоящий выдержанный просвет больше — константа
 * ЗАНИЖАЕТ.
 *
 * Занижение безопасно, поэтому включение считается по факту готово, но
 * ВЫКЛЮЧЕНО: публиковать бо́льшую терпимую высоту — решение основателя.
 *
 * Проверяются ОБА состояния. Тест только на выключенном оставил бы включённое
 * непроверенным ровно до того дня, когда его включат, — то есть до худшего
 * момента.
 */
describe("clearedUpToM: константа против фактической высоты коридора", () => {
  test("выключено — прежнее поведение, что бы ни пришло на вход", () => {
    expect(clearedUpToMFor(null, false)).toBe(35);
    expect(clearedUpToMFor(50, false)).toBe(35);
    // Даже высокий коридор не поднимает заявление, пока выключатель закрыт.
    expect(clearedUpToMFor(125, false)).toBe(35);
  });

  test("включено — заявление считается по самому низкому такому участку", () => {
    // Коридор на полу: ответ совпадает с прежним — это контроль, что включение
    // не сдвигает случай, в котором старая константа была ВЕРНА.
    expect(clearedUpToMFor(50, true)).toBe(35);
    // Коридор на ступень выше: 75 − 15 = 60.
    expect(clearedUpToMFor(75, true)).toBe(60);
    expect(clearedUpToMFor(125, true)).toBe(110);
  });

  test("участков со съеденным штрафом не было — уточнять нечего", () => {
    // null это «случая не возникло», а не «высота ноль». Ноль здесь дал бы
    // clearedUpToM = −15, то есть заявление, что коридор не терпит ничего.
    expect(clearedUpToMFor(null, true)).toBe(35);
  });

  test("включение никогда не ЗАНИЖАЕТ прежнее заявление", () => {
    // Направление важнее чисел: правка обязана только уточнять вверх. Если
    // когда-нибудь она начнёт давать меньше 35, это уже не уточнение, а
    // ужесточение, и о нём надо знать отдельно.
    for (const alt of [50, 55, 75, 100, 125, 200]) {
      expect(clearedUpToMFor(alt, true), "коридор на " + alt + " м").toBeGreaterThanOrEqual(35);
    }
  });
});
