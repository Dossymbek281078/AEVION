import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stripComments } from "./helpers/sourceCode";

/**
 * Публичный список продаж не отдаёт адрес покупателя.
 *
 * 🔴 ЗАЧЕМ. Замер 08.09.2026: GET /api/revenue/gumroad/recent без единого
 * заголовка возвращал список продаж с полем email — настоящие адреса живых
 * покупателей. Роутер /api/revenue смонтирован без проверки прав (isAdmin в
 * файле нет вовсе), то есть данные были доступны любому, кто знает адрес.
 * Подтверждено независимо вторым окном: 200, три записи, три адреса в теле.
 *
 * Починка: вместо адреса наружу уходит признак internal. Разделение
 * внутренних покупок сохранено — isInternalPurchase считает их ВНУТРИ
 * бэкенда.
 *
 * 🔴 ГРАНИЦА, И ОНА ШИРЕ, ЧЕМ ХОТЕЛОСЬ. Этот файл стережёт ОДНУ ручку, а не
 * класс. Я пробовал общий признак — «поле email в перечислении внутри файла
 * маршрута, где нет проверки прав» — и он оказался неработоспособен в обе
 * стороны:
 *
 *   широко: ловил `email: user.email` в signToken (свой токен, законно),
 *           `email: string` в сигнатуре функции и разбор ответа Gumroad —
 *           три ложных из трёх;
 *   узко:   не отличал ответ наружу от внутреннего преобразования, потому
 *           что текстом это не различается вовсе.
 *
 * Сторож, краснеющий на исправном коде, будет отключён в первый же день,
 * поэтому общий вариант я не оставил. Настоящий охват этого класса даёт не
 * текстовая проверка, а живая проба ответов — она в отдельной работе.
 */
const RE = join(__dirname, "..", "src", "routes", "revenue.ts");

describe("список продаж не отдаёт почту наружу", () => {
  const src = stripComments(readFileSync(RE, "utf8"));

  it("прибор видит предмет: ручка на месте", () => {
    // без этого «утечки нет» означало бы «файл переименовали»
    expect(src).toContain('get("/gumroad/recent"');
    expect(src).toContain("isInternalPurchase");
  });

  it("в ответе есть признак internal, а не адрес", () => {
    const at = src.indexOf('get("/gumroad/recent"');
    expect(at, "ручка не найдена").toBeGreaterThan(-1);
    // тело ручки: до следующего объявления маршрута
    const след = src.indexOf("revenueRouter.", at + 10);
    const тело = src.slice(at, след < 0 ? src.length : след);

    expect(
      /^\s*email:/m.test(тело),
      "ручка снова кладёт email в ответ — это адреса живых покупателей, "
      + "и роутер /api/revenue анонимен",
    ).toBe(false);

    expect(
      тело,
      "признак internal исчез: внутренние покупки перестанут отделяться",
    ).toContain("internal: isInternalPurchase");
  });
});
