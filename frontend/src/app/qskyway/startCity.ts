/** Город по умолчанию, если в адресе ничего не просили. */
// Нью-Йорк — решение основателя 14.09.2026 (до этого значение намеренно не
// закреплялось, пока решение ждали).
//
// Почему не Астана, как было: всё, что модуль продаёт как доказуемость, —
// издание ограничений FAA, доказательство даты в Bitcoin, запись в реестре
// QRight — существует только у Нью-Йорка. Первый посетитель попадал в Астану и
// видел «недоступно» ровно там; вдобавок над твином Астаны действует запретная
// зона UAP28, то есть демо по умолчанию прокладывало маршруты там, где летать
// нельзя. Астана и Токио остаются в один клик.
//
// Значение ЗАКРЕПЛЕНО в `startCity.test.ts`. На бэкенде та же константа
// (`DEFAULT_CITY` в routes/qskyway.ts), и её сторож проверяет причину, а не имя:
// у города по умолчанию издание ограничений доступно.
//
// Чего НЕ делать: заводить на фронте список известных городов, чтобы проверять
// принадлежность. Список живёт на бэкенде (`CITIES` в routes/qskyway.ts), и
// вторая копия разойдётся с первой молча — ровно тот класс, который этот
// модуль и ловит в чужих данных.
export const DEFAULT_CITY = "nyc";

/**
 * Какой город грузить при открытии.
 *
 * @param search строка запроса (`location.search`), с «?» или без
 *
 * Незнакомый город здесь НЕ подменяется на город по умолчанию: возвращаем ровно то, что
 * попросили, и пусть загрузка честно упрётся в 404, а страница скажет «не
 * удалось загрузить город». Тихая подмена показала бы человеку чужой город под
 * его же ссылкой — ровно тот класс ошибки, от которого этот модуль и лечит.
 * Проверять список городов здесь нечем и незачем: он приезжает с сервера, и
 * единственный надёжный судья принадлежности — сам сервер.
 */
export function resolveStartCity(search: string): string {
  let raw: string | null = null;
  try {
    raw = new URLSearchParams(search.startsWith("?") ? search.slice(1) : search).get("city");
  } catch {
    return DEFAULT_CITY;
  }
  const wanted = raw?.trim().toLowerCase() ?? "";
  return wanted || DEFAULT_CITY;
}
