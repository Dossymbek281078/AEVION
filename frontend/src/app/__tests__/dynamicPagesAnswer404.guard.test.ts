import { describe, expect, it } from "vitest";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { dirname, join, sep } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Страница с динамическим сегментом обязана уметь ответить 404.
 *
 * ПОВОД. Замер 28.08.2026 по живому проду: из 74 семейств динамических
 * маршрутов 68 отвечали 200 с полной страницей на выдуманный идентификатор.
 * Несуществующих id бесконечно много, поисковик обходит карту из 761 адреса —
 * каждое такое семейство порождает бесконечный индексируемый мусор, а на
 * реестрах (сертификаты, нотариусы, объекты прав) выдуманный адрес ещё и
 * выглядел как настоящая запись.
 *
 * Причина была НЕ «забыли notFound()». Загрузчики схлопывали ТРИ исхода в два:
 *
 *     if (!res.ok) return null;   // «нет такого» и «мы сломались» — одно
 *     catch { return null; }      // обрыв и таймаут — туда же
 *
 * Пока исходы схлопнуты, вызывать notFound() НЕКУДА: неоткуда узнать, какой
 * случай. Поэтому сторож требует одного из двух признаков — разбора кода
 * ответа (`status === 404`) или самого вызова.
 *
 * 🔴 ЧЕГО ДЕЛАТЬ НЕЛЬЗЯ, и почему сторож не требует notFound() у всех:
 * отдать 404 при НАШЕЙ аварии значит сказать поисковику, что живых страниц
 * не существует. 404 ставится только по авторитетному коду сервера. Есть и
 * страницы, где 404 вообще неуместен: `build/skill` — это ПОИСК, любая
 * строка допустима, и пустой результат законен; там правильный ответ —
 * noindex на пустоте, а не ложный 404.
 *
 * ГРАНИЦА. Сторож смотрит только СЕРВЕРНЫЕ страницы, которые сами делают
 * fetch. Страницу, чьё тело делегирует браузерному компоненту, он не видит и
 * видеть не должен: сервер там в момент ответа не знает, существует ли
 * объект. Признак «нет use client» для этого НЕ годится — тело может быть
 * одной строкой `<Client />` (так у qcoreai/shared), поэтому такие случаи
 * перечислены в планке поимённо.
 */

const SRC = join(dirname(fileURLToPath(import.meta.url)), "..", "..");

/**
 * Известные исключения. Список должен ХУДЕТЬ от починок, а не расти от
 * поблажек: каждая строка объясняет, почему приём неприменим, а не почему
 * «пока некогда».
 */
const OZHIDAYUT = new Map<string, string>([
  [
    "app/qcoreai/shared/[token]/page.tsx",
    "тело страницы это <SharedRunClient />, серверный fetch только ради " +
      "метаданных — сервер в момент ответа не знает, существует ли токен",
  ],
]);

function obojti(dir: string, out: string[] = []): string[] {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) {
      if (e === "node_modules" || e === "__tests__") continue;
      obojti(p, out);
    } else if (e === "page.tsx") {
      out.push(p);
    }
  }
  return out;
}

function narushiteli(): string[] {
  const bad: string[] = [];
  for (const p of obojti(join(SRC, "app"))) {
    const rel = p.slice(SRC.length + 1).split(sep).join("/");
    if (!rel.includes("[")) continue;
    const src = readFileSync(p, "utf8");
    // Клиентские страницы вне охвата: сервер там ничего не знает.
    if (src.slice(0, 400).includes("use client")) continue;
    // Без запроса к серверу и вопроса нет.
    if (!src.includes("fetch(")) continue;
    // Требуем САМ ВЫЗОВ, а не «любой из признаков».
    //
    // Первая версия считала достаточным наличие разбора кода ЛИБО вызова —
    // и мутационная проверка показала, что она пустая: убрал notFound() из
    // починенной страницы, сторож смолчал (остался разбор кода); убрал
    // разбор — снова смолчал (остался вызов). Она ловила только страницу,
    // где нет НИ ОДНОГО признака, то есть совсем новую.
    //
    // Замер показал, что можно строже без единой поблажки: страниц без
    // вызова во всём фронтенде ровно одна, и она уже в планке. Теперь
    // частичный откат любой из четырнадцати починок краснеет.
    if (!/(^|[^A-Za-z])notFound\(\)/.test(src)) bad.push(rel);
  }
  return bad;
}

describe("динамические страницы умеют отвечать 404", () => {
  it("сканер вообще что-то видит", () => {
    // Отрицательный контроль: переименуют каталог — проверка станет зелёной
    // молча и будет обещать охват, которого нет.
    expect(obojti(join(SRC, "app")).length).toBeGreaterThan(100);
  });

  it("новых страниц без вызова notFound() не появилось", () => {
    const novye = narushiteli().filter((f) => !OZHIDAYUT.has(f));
    expect(
      novye.join("\n"),
      "Страница с динамическим сегментом делает fetch и не различает «нет " +
        "такого» и «не смогли спросить». Разделите исходы: 404/410 от " +
        "сервера -> notFound(); прочие неуспехи -> прежний вид с кодом 200.",
    ).toBe("");
  });

  it("список исключений не протух: каждое всё ещё без вызова", () => {
    const est = new Set(narushiteli());
    const pochinennye = [...OZHIDAYUT.keys()].filter((f) => !est.has(f));
    expect(
      pochinennye.join("\n"),
      "Эти страницы уже зовут notFound() — вычеркните их из OZHIDAYUT, " +
        "дефект вернётся в них незамеченным.",
    ).toBe("");
  });

  it("у каждого исключения есть причина, а не пустая строка", () => {
    const bezPrichiny = [...OZHIDAYUT.entries()]
      .filter(([, why]) => why.trim().length < 20)
      .map(([f]) => f);
    expect(bezPrichiny.join("\n")).toBe("");
  });
});
