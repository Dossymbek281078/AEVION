#!/usr/bin/env node
/**
 * Цена на нашей странице против цены, которую возьмёт касса.
 *
 * ЗАЧЕМ. Девять позиций каталога продаются ПРЯМОЙ ссылкой на Gumroad. У этих
 * ссылок наша сумма не передаётся вовсе — платит человек столько, сколько
 * выставлено в настройках товара у продавца. То есть страница может обещать
 * $49, а списаться $59, и наоборот. Ни при переходе в кассу, ни при
 * подтверждении покупки суммы никто не сверяет: проверено грепом по провайдеру
 * и вебхуку, сверки нет ни одной.
 *
 * Расхождение опасно в ОБЕ стороны: вверх — человек платит больше обещанного,
 * это возвраты и потеря доверия; вниз — мы отдаём доступ дешевле, и заметить
 * это можно только по выручке, задним числом.
 *
 * Замер 01.09.2026: все девять сходятся. Но сходятся они СЕГОДНЯ — цену меняют
 * в двух разных местах, и ничто не мешает им разъехаться завтра.
 *
 * СЕКРЕТЫ НЕ НУЖНЫ: страницы товаров публичные, ключ продавца не требуется.
 *
 * Коды выхода — как у прочих инструментов AEVION:
 *   0 — все цены сходятся;
 *   1 — есть расхождение;
 *   2 — спросить не удалось (сеть, разбор). Это НЕ «всё хорошо».
 */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), "..");
const КАТАЛОГ = join(КОРЕНЬ, "src/lib/products.ts");
const МАГАЗИН = "https://aevion.gumroad.com/l/";

/** Позиции, продаваемые прямой ссылкой: цена у нас и постоянная ссылка. */
export function позицииИзКаталога(исходник) {
  const из = [];
  const шаблон = /GUM\("([a-z0-9]+)"\)/g;
  let m;
  while ((m = шаблон.exec(исходник)) !== null) {
    const начало = исходник.lastIndexOf("{", m.index);
    const блок = исходник.slice(начало, m.index + 400);
    const цена = /priceUsd:\s*([0-9.]+)/.exec(блок);
    из.push({ permalink: m[1], usd: цена ? Number(цена[1]) : null });
  }
  return из;
}

/** Цены со страницы товара, в центах, без нулевых (у Gumroad это служебные). */
export function ценыСоСтраницы(html) {
  const все = [...html.matchAll(/&quot;price_cents&quot;:(\d+)/g)].map((m) => Number(m[1]));
  return [...new Set(все.filter((c) => c > 0))].sort((a, b) => a - b);
}

async function main() {
  let исходник;
  try {
    исходник = readFileSync(КАТАЛОГ, "utf8");
  } catch (e) {
    console.log("не удалось прочитать каталог:", e.message);
    process.exitCode = 2;
    return;
  }

  const позиции = позицииИзКаталога(исходник);
  if (позиции.length === 0) {
    // Ноль здесь означает «разучился искать», а не «нечего проверять»:
    // прямые ссылки в каталоге есть, это и есть повод для инструмента.
    console.log("в каталоге не найдено ни одной прямой ссылки — проверь шаблон");
    process.exitCode = 2;
    return;
  }

  let расхождений = 0;
  let неотвеченных = 0;
  for (const { permalink, usd } of позиции) {
    if (usd === null) {
      console.log(`  /${permalink}  у позиции нет цены в каталоге — сверять не с чем`);
      неотвеченных += 1;
      continue;
    }
    let html = "";
    try {
      const r = await fetch(МАГАЗИН + permalink, { redirect: "follow" });
      if (!r.ok) {
        console.log(`  /${permalink}  страница товара ответила ${r.status}`);
        неотвеченных += 1;
        continue;
      }
      html = await r.text();
    } catch (e) {
      console.log(`  /${permalink}  не ответила: ${e.message}`);
      неотвеченных += 1;
      continue;
    }
    const центы = ценыСоСтраницы(html);
    const наша = Math.round(usd * 100);
    if (центы.length === 0) {
      console.log(`  /${permalink}  цену со страницы извлечь не удалось`);
      неотвеченных += 1;
    } else if (центы.includes(наша)) {
      console.log(`  /${permalink}  $${usd} — сходится`);
    } else {
      const их = центы.map((c) => `$${(c / 100).toFixed(2)}`).join(", ");
      console.log(`  /${permalink}  РАСХОЖДЕНИЕ: у нас $${usd}, у продавца ${их}`);
      расхождений += 1;
    }
  }

  console.log(
    `\nпроверено ${позиции.length}, расхождений ${расхождений}, без ответа ${неотвеченных}`,
  );
  // Неотвеченный вопрос не равен благополучию.
  process.exitCode = расхождений > 0 ? 1 : неотвеченных > 0 ? 2 : 0;
}

// Запускаем ТОЛЬКО при прямом вызове: иначе `import` из теста выполнил бы
// сетевую проверку сам, а проверять чистые функции нужно без сети.
// Сравниваем через resolve, а не регуляркой по разделителям: обратный слэш
// в исходнике — верный способ потерять его на границе инструмента.
const этотФайл = fileURLToPath(import.meta.url);
const позванНапрямую = Boolean(process.argv[1]) && resolve(process.argv[1]) === resolve(этотФайл);
if (позванНапрямую) await main();
