import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { DEVHUB_EXAMPLES } from "../examples";

/**
 * Каждый адрес галереи — под надзором смоука живых страниц.
 *
 * 🔴 ПОВОД, найденный на себе 06.10.2026. Список адресов витрины ведётся в ДВУХ
 * местах: здесь рядом (examples.ts) и в
 * aevion-globus-backend/scripts/pages-live-smoke.js, где адреса вписаны руками.
 * Я добавил четвёртый пример и про второй файл забыл — то есть «доказательство
 * продукта» осталось бы без наблюдения, и его пропажу никто бы не заметил.
 *
 * Хуже того: в тот же день я заменил пример и УДАЛИЛ прежний проект до того, как
 * замена выкатилась. Оркестратор поймал это первым — волна 18 везёт карточку на
 * прежний адрес, и после выкатки витрина показала бы мёртвую ссылку. Сам смоук
 * тогда промолчал бы вдвойне: удалённого адреса в нём не было, нового тоже.
 *
 * Класс ровно тот же, что у меток каналов (everyChannelHasShortEntry): запись
 * добавляют там, где это дёшево и очевидно, а вторую половину забывают. Ошибка
 * не падает и не краснеет — она проявляется тем, что витрина однажды показывает
 * мёртвое, и мы узнаём об этом от человека.
 */
const СМОУК = join(__dirname, "..", "..", "..", "..", "..", "aevion-globus-backend", "scripts", "pages-live-smoke.js");

describe("адреса галереи под надзором смоука", () => {
  it("прибор исправен: файл смоука прочитан и в нём есть адреса", () => {
    const src = readFileSync(СМОУК, "utf8");
    expect(src.length, "файл смоука не прочитан — сторож смотрит не туда").toBeGreaterThan(2000);
    expect(src, "в смоуке не осталось ни одного адреса pages.dev").toContain(".pages.dev");
    // Знаменатель: без него пустая галерея дала бы зелёный «все под надзором».
    expect(DEVHUB_EXAMPLES.length, "галерея пуста — сторожить нечего").toBeGreaterThan(0);
  });

  it.each(DEVHUB_EXAMPLES.map((e) => e.url))("адрес %s перечислен в смоуке", (url) => {
    const src = readFileSync(СМОУК, "utf8");
    expect(
      src.includes(url),
      `адрес галереи ${url} не перечислен в scripts/pages-live-smoke.js — его пропажу никто не заметит`,
    ).toBe(true);
  });

  it("КОНТРОЛЬ: сторож не зелёный от подстроки — выдуманный адрес не находится", () => {
    // Иначе проверка выше проходила бы и при сравнении по кусочкам.
    const src = readFileSync(СМОУК, "utf8");
    expect(src.includes("https://aevion-takogo-adresa-net-000000.pages.dev")).toBe(false);
  });
});
