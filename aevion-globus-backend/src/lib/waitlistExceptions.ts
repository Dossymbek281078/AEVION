/**
 * Метки форм подписки, намеренно НЕ входящие в рассылку запуска.
 *
 * Список вынесен из теста в обычный модуль 29.09.2026 по решению оркестратора:
 * сторожей стало ДВА (everyWaitlistFormReachesTheMailing и
 * waitlistSourceReachesTheRegistry), и каждый держал своё представление о том,
 * что законно. Два списка об одном — это гарантированное расхождение: один
 * краснеет на честном случае, второй зеленеет на настоящем нарушении.
 *
 * ⚠️ Запись здесь — это УТВЕРЖДЕНИЕ «форма не обещает письма», а не разрешение
 * молчать. У каждой строки названа причина и условие снятия; отдельный тест
 * следит, чтобы исключение не пережило свою причину.
 */
export const ИСКЛЮЧЕНИЯ_РАССЫЛКИ: Record<string, string> = {
  "en-go": "письмо запуска существует только по-русски; отправить его тому, кто оставил адрес на английской странице, значит прислать не то",
  longevity: "форма книги: обещает протокол долголетия, а не запуск модуля",
  "en-longevity": "то же, английская страница книги",
  // 21.09.2026: QSpace не в LAUNCH_MODULES и без цены — письма запуска у него
  // нет; форма говорит «адрес попадёт в счёт спроса», письма не обещает.
  // СНЯТЬ, когда основатель назовёт цену и qspace войдёт в LAUNCH_MODULES.
  qspace: "форма считает спрос на платный расчёт и письма не обещает; модуля нет в LAUNCH_MODULES, цены нет",
};

/**
 * Условие снятия исключения, проверяемое машиной, а не глазами.
 *
 * Пока такое условие есть только у qspace: его исключение держится на том, что
 * модуля нет в списке запуска. Появился там — исключение обязано уйти, иначе
 * человек подпишется на письмо, которого не получит.
 */
export function исключениеПережилоПричину(
  метка: string,
  вСпискеЗапуска: (слаг: string) => boolean,
): boolean {
  if (!(метка in ИСКЛЮЧЕНИЯ_РАССЫЛКИ)) return false;
  if (метка === "qspace") return вСпискеЗапуска("qspace");
  return false;
}
