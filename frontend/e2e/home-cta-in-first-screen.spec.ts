import { test, expect, type Page } from "@playwright/test";

/**
 * Главная кнопка героя ЦЕЛИКОМ видна в первом экране — замером в браузере.
 *
 * ПОВОД (07.10.2026). Я сделал герою `min-height: 100svh`, чтобы блок покупок
 * ушёл за сгиб, и это сработало. Но user-db заметил то, чего я не проверил:
 * на 390×844 ВЫСОТА героя оказалась 933 при окне 844. `100svh` — это МИНИМУМ,
 * а не максимум: герой может быть выше экрана. Кнопка попадала в кадр только
 * потому, что текст сейчас короткий. Добавят абзац, удлинится перевод,
 * вырастет шрифт — и главное действие уедет за кромку, а все наши проверки
 * останутся зелёными: в разметке кнопка есть, порядок секций верный, число
 * действий «в первом экране» по старым меркам не изменилось.
 *
 * ПОЧЕМУ БРАУЗЕРОМ, А НЕ ПО ИСХОДНИКУ. Это вопрос про ПИКСЕЛИ в конкретном
 * окне: высота героя складывается из переводов, переносов и шрифтов. По коду
 * она не вычисляется — её можно только измерить.
 *
 * ДВЕ ПРОВЕРКИ НА КАЖДОЕ ОКНО, и обе нужны:
 *   1) `rect.bottom <= innerHeight` — кнопка целиком выше кромки. Не `top`:
 *      наполовину видная кнопка не считается видной.
 *   2) `elementFromPoint` в её центре возвращает её же — иначе «существует в
 *      разметке» подменит «видно человеку». У нас это уже было: плавающая
 *      панель накрывала элемент, а проверка по координатам its не замечала.
 *
 * ЧУВСТВИТЕЛЬНОСТЬ ПРОВЕРЕНА МУТАЦИЕЙ (07.10.2026, против прода). В героя
 * добавлялся абзац за абзацем, пока низ кнопки не уходил за кромку:
 *
 *   окно        низ кнопки / окно   свободно   ломается после
 *   390x844        468 / 844          376px     3 абзацев
 *   360x740        492 / 740          248px     2 абзацев
 *   1366x720       461 / 720          259px     5 абзацев
 *
 * То есть сторож краснеет на росте героя — но ОДНОГО абзаца мало, запас
 * настоящий. Это стоит знать обоим: и тому, кто решит, что проверка пустая
 * (она не пустая), и тому, кто решит, что места сколько угодно (его 2–3 абзаца).
 * Самое узкое окно — 360x740: там запас меньше всего.
 *
 * ЗНАМЕНАТЕЛЬ ПЕЧАТАЕТСЯ НАМЕРЕННО. Проверка, молча обошедшая ноль окон, —
 * зелёный отчёт при нулевом охвате; у нас такое уже случалось.
 */

const АДРЕС = "/?c=probe-golos-cta";

/** Окна, на которых меряем. Список ведётся руками: он и есть утверждение. */
const ОКНА: Array<{ имя: string; width: number; height: number }> = [
  // Телефон, самый частый размер.
  { имя: "390x844", width: 390, height: 844 },
  // Телефон поменьше — на нём первым ломается всё, что зависит от высоты.
  { имя: "360x740", width: 360, height: 740 },
  // Ноутбук с низким окном: 1366x768 минус шапка браузера.
  { имя: "1366x720", width: 1366, height: 720 },
];

async function главнаяКнопка(page: Page) {
  // Ищем структурно: первая ссылка на /devhub внутри ПЕРВОЙ секции страницы.
  // Не по тексту: он переводится на три языка и меняется.
  return page.locator("section").first().locator('a[href^="/devhub"]').first();
}

test.describe("главная: единственное действие видно в первом экране", () => {
  for (const окно of ОКНА) {
    test(`кнопка героя целиком в кадре — ${окно.имя}`, async ({ page }) => {
      await page.setViewportSize({ width: окно.width, height: окно.height });
      await page.goto(АДРЕС, { waitUntil: "domcontentloaded" });

      const кнопка = await главнаяКнопка(page);
      await expect(кнопка, `${окно.имя}: главной кнопки героя нет вовсе`).toBeVisible();

      const замер = await кнопка.evaluate((el) => {
        const r = el.getBoundingClientRect();
        const cx = r.left + r.width / 2;
        const cy = r.top + r.height / 2;
        const под = document.elementFromPoint(cx, cy);
        return {
          top: Math.round(r.top),
          bottom: Math.round(r.bottom),
          высотаОкна: window.innerHeight,
          высотаГероя: Math.round(
            (document.querySelector("section") as HTMLElement | null)?.getBoundingClientRect().height ?? 0,
          ),
          подНей: под === el || el.contains(под) || (под ? под.contains(el) : false),
          текст: (el.textContent || "").trim().slice(0, 40),
        };
      });

      // 1) целиком выше кромки — не «началась», а ПОМЕСТИЛАСЬ
      expect(
        замер.bottom,
        `${окно.имя}: кнопка «${замер.текст}» выходит за кромку — низ ${замер.bottom} при окне ${замер.высотаОкна} (высота героя ${замер.высотаГероя})`,
      ).toBeLessThanOrEqual(замер.высотаОкна);

      // 2) её действительно видно, а не только «есть в разметке»
      expect(
        замер.подНей,
        `${окно.имя}: в центре кнопки лежит другой элемент — её чем-то накрыло`,
      ).toBe(true);
    });
  }

  test("проверено 3 окна — охват назван числом", async () => {
    // Контроль охвата: если список окон опустеет или усохнет, краснеет ЭТА
    // проверка, а не молчит весь набор.
    expect(ОКНА.length, "список окон усох — проверка потеряла охват").toBe(3);
    expect(new Set(ОКНА.map((о) => о.имя)).size, "в списке окон есть дубли").toBe(3);
  });
});
