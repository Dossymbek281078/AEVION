export const ПРОЕКТЫ_ОБРАЗЦЫ: readonly string[] = [
  "40e033e0-331b-40a0-99a8-5fa3384c500f",
  "6f5da38e-e88c-4260-9f2d-d324bf333839",
  "c4a008af-71b0-4578-8b43-502fb275f202",
  "78897ee8-2eeb-4f02-aae8-152bf895f60e",
  "6fb1bbda-47d3-4fa9-abdd-4768b4b6b598",
];

const образцы = new Set(ПРОЕКТЫ_ОБРАЗЦЫ);

export function проектОбразец(id: unknown): boolean {
  return typeof id === "string" && образцы.has(id);
}

/** SQL-условие «это не образец» для колонки id проекта (литералы — константы выше). */
export function неОбразецSql(колонкаId: string): string {
  return `${колонкаId}::text NOT IN (${ПРОЕКТЫ_ОБРАЗЦЫ.map((id) => `'${id}'`).join(", ")})`;
}
