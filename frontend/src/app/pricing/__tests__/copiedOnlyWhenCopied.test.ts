/**
 * «Скопировано» обещается только по факту копирования.
 *
 * Кнопка промокода делала три вещи подряд: применяла код в калькуляторе, звала
 * буфер обмена с проглоченной ошибкой и БЕЗУСЛОВНО показывала «Скопировано».
 * То есть при отказе буфера человек читал успех, уходил вставлять код в другое
 * место и вставлял пустоту.
 *
 * Класс тот же, что мы чиним весь день: неудача, выглядящая успехом. Здесь она
 * мелкая — промокод всё равно применяется в калькуляторе, и цель нажатия
 * достигается, — но утверждение на экране было ложным, а это чинится дёшево.
 *
 * Сторож смотрит ПОРЯДОК: подпись должна стоять внутри обработчика успеха, а не
 * рядом с вызовом. Проверять отрисовкой здесь нечем: буфер обмена в тестовой
 * среде не работает по-настоящему, и подделка проверяла бы подделку.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stripComments } from "../../__tests__/helpers/sourceCode";

const страница = stripComments(
  readFileSync(join(process.cwd(), "src/app/pricing/page.tsx"), "utf8"),
);

describe("подпись «скопировано»", () => {
  it("стоит в ветке успеха, а не безусловно", () => {
    // Признак: setCopiedPromo вызывается ВНУТРИ .then(...) буфера.
    const от = страница.indexOf("writeText(p.code)");
    expect(от, "кнопка промокода не найдена — сторож смотрит не туда").toBeGreaterThan(0);
    const окно = страница.slice(от, от + 260);
    expect(окно, "нет ветки успеха у копирования").toContain(".then(");
    const доThen = окно.indexOf(".then(");
    const доПодписи = окно.indexOf("setCopiedPromo");
    expect(доПодписи, "подпись не найдена рядом с копированием").toBeGreaterThan(-1);
    expect(
      доПодписи > доThen,
      "«Скопировано» обещается до того, как копирование удалось",
    ).toBe(true);
  });

  it("промокод применяется независимо от буфера", () => {
    /*
     * Обратная сторона: чиня обещание, легко утащить в ветку успеха и САМО
     * применение кода — тогда при недоступном буфере человек не получил бы
     * скидку вовсе. Это было бы хуже исходного дефекта.
     */
    const от = страница.indexOf("setCalcPromo(p.code)");
    const доКопирования = страница.indexOf("writeText(p.code)");
    expect(от, "применение промокода не найдено").toBeGreaterThan(0);
    expect(от < доКопирования, "применение кода уехало внутрь ветки буфера").toBe(true);
  });
});
