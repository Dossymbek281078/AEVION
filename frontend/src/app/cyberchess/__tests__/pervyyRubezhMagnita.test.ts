import { describe, expect, test } from "vitest";
import { nuzhnoLiPokazatStrokuAdresa, nuzhnoLiSoobschitOUhode, etoGranitsaProgressa, ГРАНИЦЫ_ПРОГРЕССА,
  ВЫСОТА_НИЖНЕЙ_ПАНЕЛИ, ВЫСОТА_РЯДА_КНОПОК, ЗАЗОР_ПРИЛИПШИХ, nuzhnoLiPrilepit, chislaRubezha, ЗАДЕРЖКА_СКРЫТИЯ_СТРОКИ_МС } from "../page";

/*
 * 🔴 Два решения первого рубежа магнита, оба проверяются вызовами с известным
 * ответом, потому что внутри страницы на 16 тысяч строк их не проверить.
 *
 * ЧИСЛА, РАДИ КОТОРЫХ ЭТО СДЕЛАНО (замер окна воронки за 14 дней, 585 сессий,
 * 51 ключ): `доиграли` 3 — все наши; `задача дня решена` 2 — оба наши; а
 * `попробовали` у ЖИВЫХ — 12. То есть первый ход единственный рубеж, до которого
 * живые доходят, и оба прежних повода предложить адрес (конец партии, решённая
 * задача дня) для живого человека недостижимы.
 *
 * Отдельно: за 7 дней 10 живых с YouTube начали партию и 0 доиграли — значит
 * люди теряются ВНУТРИ партии, а спросить «на каком ходу» было нечем.
 */

const базаСтроки = { партияИдёт: true, завершена: false, полуходов: 1, ужеПоказывали: false, ужеПредлагали: false };
const базаУхода = { партияИдёт: true, завершена: false, былХод: true, ужеСообщили: false };

describe("строка адреса под доской", () => {
  test("после первого хода живой партии — показываем", () => {
    expect(nuzhnoLiPokazatStrokuAdresa(базаСтроки)).toBe(true);
  });

  test("🔴 до первого хода — НЕ показываем", () => {
    // Иначе предложение встречает человека на пустой доске, а рубеж «попробовал»
    // ещё не пройден.
    expect(nuzhnoLiPokazatStrokuAdresa({ ...базаСтроки, полуходов: 0 })).toBe(false);
  });

  test("партия завершена или не идёт — не показываем (на это есть прежние поводы)", () => {
    expect(nuzhnoLiPokazatStrokuAdresa({ ...базаСтроки, завершена: true })).toBe(false);
    expect(nuzhnoLiPokazatStrokuAdresa({ ...базаСтроки, партияИдёт: false })).toBe(false);
  });

  test("🔴 уже показывали в этой сессии или уже предлагали — молчим", () => {
    // Человек, закрывший строку, не должен получать её снова; подписавшийся —
    // тем более.
    expect(nuzhnoLiPokazatStrokuAdresa({ ...базаСтроки, ужеПоказывали: true })).toBe(false);
    expect(nuzhnoLiPokazatStrokuAdresa({ ...базаСтроки, ужеПредлагали: true })).toBe(false);
  });

  test("КОНТРОЛЬ: функция РАЗЛИЧАЕТ случаи, а не отвечает одинаково", () => {
    const ответы = new Set([
      nuzhnoLiPokazatStrokuAdresa(базаСтроки),
      nuzhnoLiPokazatStrokuAdresa({ ...базаСтроки, полуходов: 0 }),
    ]);
    expect(ответы.size, "разных ответов должно быть 2").toBe(2);
  });
});

describe("сообщение об уходе из незавершённой партии", () => {
  test("ушёл посреди партии с ходами — сообщаем", () => {
    expect(nuzhnoLiSoobschitOUhode(базаУхода)).toBe(true);
  });

  test("🔴 партия без единого хода — НЕ уход, а передумал", () => {
    // Иначе «ушли из партии» раздуется теми, кто её и не начинал, и число
    // перестанет отвечать на вопрос «на каком ходу теряем».
    expect(nuzhnoLiSoobschitOUhode({ ...базаУхода, былХод: false })).toBe(false);
  });

  test("партия завершена — это game_end, а не уход", () => {
    expect(nuzhnoLiSoobschitOUhode({ ...базаУхода, завершена: true })).toBe(false);
  });

  test("🔴 второй раз не сообщаем", () => {
    // pagehide и visibilitychange приходят оба, и без защиты один уход дал бы
    // два события — число ушедших оказалось бы вдвое больше правды.
    expect(nuzhnoLiSoobschitOUhode({ ...базаУхода, ужеСообщили: true })).toBe(false);
  });

  test("КОНТРОЛЬ: решения двух функций НЕ совпадают по смыслу", () => {
    // На пустой доске строку показывать не надо И уход сообщать не надо, но при
    // одном ходе ответы расходятся: строка — да, уход — да; а при завершённой
    // партии обе дают нет. Проверяем, что это разные правила, а не копия.
    const строка = nuzhnoLiPokazatStrokuAdresa({ ...базаСтроки, ужеПредлагали: true });
    const уход = nuzhnoLiSoobschitOUhode(базаУхода);
    expect([строка, уход]).toEqual([false, true]);
  });
});

describe("прогресс партии по границам корзин", () => {
  test("🔴 событие шлётся РОВНО на границах, а не на каждом ходу", () => {
    // Разрез окна 85 кладёт сессию в корзину, поэтому важны границы 1, 3, 11,
    // 21, 41; сто событий за партию ничего не добавили бы и утопили ручку.
    const границы = [1, 3, 11, 21, 41];
    for (const п of границы) expect(etoGranitsaProgressa(п), `полуходов ${п}`).toBe(true);
    for (const п of [0, 2, 4, 10, 12, 20, 22, 40, 42, 99]) {
      expect(etoGranitsaProgressa(п), `полуходов ${п} — не граница`).toBe(false);
    }
  });

  test("КОНТРОЛЬ: границ ровно пять и они совпадают с корзинами разреза", () => {
    // Если список разойдётся с корзинами 0 / 1–2 / 3–10 / 11–20 / 21–40 / 41+,
    // гистограмма «на каком ходу уходят» потеряет разрешение молча.
    expect([...ГРАНИЦЫ_ПРОГРЕССА]).toEqual([1, 3, 11, 21, 41]);
  });

  test("КОНТРОЛЬ прибора: функция различает границу и не-границу", () => {
    const ответы = new Set([etoGranitsaProgressa(3), etoGranitsaProgressa(4)]);
    expect(ответы.size, "функция ответила одинаково на границу и не-границу").toBe(2);
  });
});

describe("две прилипшие полосы не наезжают друг на друга", () => {
  /*
   * ЧИСЛА — замеры на живом проде 11.10.2026, 390×844, два окна независимо:
   * нижняя панель y 774–844 (у приёмки 775–844) — высота 70; ряд «Сдаться»
   * y 872–916 — высота 44, то есть он был ниже кадра на 28 px, и БЕЗ строки
   * адреса тоже (приёмка проверила, закрыв её). Между низом доски и рядом
   * 206 px, прокрутка 194 px.
   */
  test("🔴 строка адреса поднимается выше ряда кнопок, когда он есть", () => {
    const безРяда = ВЫСОТА_НИЖНЕЙ_ПАНЕЛИ + ЗАЗОР_ПРИЛИПШИХ;
    const сРядом = безРяда + ВЫСОТА_РЯДА_КНОПОК + ЗАЗОР_ПРИЛИПШИХ;
    expect(сРядом - безРяда, "подъём должен быть не меньше высоты ряда").toBeGreaterThanOrEqual(ВЫСОТА_РЯДА_КНОПОК);
    // Контроль: полосы не перекрываются — зазор строго положительный.
    expect(сРядом - безРяда - ВЫСОТА_РЯДА_КНОПОК, "зазор между полосами").toBeGreaterThan(0);
  });

  test("ряд кнопок помещается над панелью в кадре 844", () => {
    // Низ ряда = высота панели + зазор + высота ряда от низа окна.
    const отНизаОкна = ВЫСОТА_НИЖНЕЙ_ПАНЕЛИ + ЗАЗОР_ПРИЛИПШИХ + ВЫСОТА_РЯДА_КНОПОК;
    expect(отНизаОкна, `полоса занимает ${отНизаОкна} px снизу`).toBeLessThan(844 / 3);
  });

  test("🔴 КОНТРОЛЬ: высоты — измеренные числа, а не нули", () => {
    // Ноль в любой из них тихо сложил бы полосы в одну точку.
    expect(ВЫСОТА_НИЖНЕЙ_ПАНЕЛИ).toBe(70);
    expect(ВЫСОТА_РЯДА_КНОПОК).toBe(44);
    expect(ЗАЗОР_ПРИЛИПШИХ).toBeGreaterThan(0);
  });
});

describe("строка адреса прилипает по МЕСТУ, а не по ширине", () => {
  /* Все три случая — замеры приёмки на живом проде 11.10.2026. */
  test("🔴 390×844: низ строки 916 при панели 70 — прилипает", () => {
    expect(nuzhnoLiPrilepit({ низСтроки: 916, высотаОкна: 844, ширинаОкна: 390 })).toBe(true);
  });

  test("🔴 1463×724 (ноутбук, панели нет): низ 802 — прилипает, хотя ширина большая", () => {
    // Ровно случай, который правило «уже 769 px» пропускало: не хватало высоты.
    expect(nuzhnoLiPrilepit({ низСтроки: 802, высотаОкна: 724, ширинаОкна: 1463 })).toBe(true);
  });

  test("🔴 КОНТРОЛЬ: то же окно, но высокое — НЕ прилипает", () => {
    // Иначе правило прилипало бы всегда, и проверки выше ничего не значили.
    expect(nuzhnoLiPrilepit({ низСтроки: 802, высотаОкна: 900, ширинаОкна: 1463 })).toBe(false);
  });

  test("КОНТРОЛЬ: панель учитывается только на узких", () => {
    // Низ строки 800 при окне 844: на широком влезает, на узком — нет (панель 70).
    expect(nuzhnoLiPrilepit({ низСтроки: 800, высотаОкна: 844, ширинаОкна: 1024 })).toBe(false);
    expect(nuzhnoLiPrilepit({ низСтроки: 800, высотаОкна: 844, ширинаОкна: 390 })).toBe(true);
  });
});

describe("попытка хода считается наравне с ходом", () => {
  /* Решение оркестратора 11.10 после общего замера: в задаче неверная попытка в
     hist не попадает, и ошибившийся человек не попадал ни в строку, ни в
     знаменатель byChessPlies — в числах он был неотличим от того, кто доску не
     трогал. А 22 живые сессии из 22 пришли именно по ?puzzle=. */
  test("🔴 только попытка: строку показываем", () => {
    expect(nuzhnoLiPokazatStrokuAdresa({ партияИдёт: true, завершена: false, полуходов: 0,
      попыток: 1, ужеПоказывали: false, ужеПредлагали: false })).toBe(true);
  });

  test("🔴 только попытка: в событие уходит plies 1 и признак «от попытки»", () => {
    const ч = chislaRubezha(0, 1);
    expect(ч.plies, "иначе сессия не попадёт в корзины вовсе").toBe(1);
    expect(ч.attempts).toBe(1);
    expect(ч.отПопытки, "признак обязателен: иначе попытка неотличима от хода").toBe(true);
  });

  test("КОНТРОЛЬ: настоящие ходы считаются как ходы, а не как попытки", () => {
    const ч = chislaRubezha(7, 3);
    expect([ч.plies, ч.moves, ч.attempts, ч.отПопытки]).toEqual([7, 3, 3, false]);
  });

  test("КОНТРОЛЬ: ни хода, ни попытки — ничего не показываем и plies 0", () => {
    expect(nuzhnoLiPokazatStrokuAdresa({ партияИдёт: true, завершена: false, полуходов: 0,
      попыток: 0, ужеПоказывали: false, ужеПредлагали: false })).toBe(false);
    expect(chislaRubezha(0, 0).plies).toBe(0);
  });
});

