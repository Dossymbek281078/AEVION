/**
 * Исходник БЕЗ комментариев — для сторожей, которые ищут по коду.
 *
 * Зачем. Сторож, проверяющий «такая строка должна БЫТЬ», удовлетворяется
 * совпадением в комментарии: закомментируй проверяемое место — и он останется
 * зелёным, охраняя пустоту. Поймано мутацией 21.08.2026 сразу на двух
 * сторожах, один из которых был написан в тот же день.
 *
 * Обратная сторона так же реальна: сторож «такой строки быть НЕ должно»
 * краснеет на упоминании в комментарии — например в разборе того самого
 * дефекта, который он стережёт. Красный на объяснении приучает не читать
 * сторожа вовсе.
 *
 * Реализация намеренно простая и предсказуемая: убираются блочные и строчные
 * комментарии. Строковые литералы с «//» внутри (URL) при этом обрезаются —
 * для сторожей по КОДУ это приемлемо, а если сторожу нужен именно URL, он
 * должен читать исходник как есть и знать почему.
 */
export function stripComments(src: string): string {
  const noBlock = src.replace(/\/\*[\s\S]*?\*\//g, "");
  return noBlock
    .split(/\r?\n/)
    .map((line) => {
      const t = line.trimStart();
      if (t.startsWith("//") || t.startsWith("*")) return "";
      const i = line.indexOf("//");
      return i >= 0 ? line.slice(0, i) : line;
    })
    .join("\n");
}
