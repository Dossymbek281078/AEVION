import { describe, test, expect } from "vitest";
import * as fs from "node:fs";
import * as path from "node:path";
import { stripComments } from "./_stripComments";

// Страница экономики говорит о себе правду. 19.08.2026.
//
// Замер: 620 строк, НОЛЬ обращений к серверу. Кнопки «сделать ставку»,
// «арендовать коуча», «подписаться на стримера» пишут только в localStorage.
// Аукцион существует в одном экземпляре у каждого человека, и ставка никому не
// видна. Слов «скоро» или «в разработке» на странице не было.
//
// Отдельно опасен баланс: Chessy — настоящая валюта с серверным кошельком
// CyberWallet, а здесь читается местная копия. Списание настоящего баланса не
// меняет, и человек вправе решить, что потратил заработанное.
//
// Тот же класс, что выдуманные гроссмейстеры в таблице лидеров: экран выглядит
// работающим механизмом, за которым ничего нет.

const SRC = path.join(__dirname, "..", "economy", "page.tsx");
const src = () => stripComments(fs.readFileSync(SRC, "utf-8"));

describe("страница экономики не выдаёт себя за работающую биржу", () => {
  test("оговорка есть и названа своими словами", () => {
    const s = src();
    expect(s).toMatch(/economy-prototype-notice/);
    expect(s).toMatch(/витрина замысла/);
  });

  test("сказано главное: только этот браузер и не настоящие Chessy", () => {
    const s = src();
    // Пробелы гибкие: в разметке текст переносится по строкам, и жёсткий
    // шаблон ломался бы о форматирование, а не о смысл. На этом я и попался.
    expect(s.replace(/\s+/g, " ")).toMatch(/только в этом браузере/);
    expect(s.replace(/\s+/g, " ")).toMatch(/настоящие Chessy он не списывает/);
  });

  test("оговорка нужна ровно потому, что сервера здесь нет", () => {
    // Если однажды страница начнёт ходить на сервер, это утверждение
    // покраснеет — и оговорку можно будет пересмотреть, а не тащить по привычке.
    const s = src();
    expect(s).not.toMatch(/fetch\(/);
  });
});
