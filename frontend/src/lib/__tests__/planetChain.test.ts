import { describe, it, expect } from "vitest";
import { ЦЕПОЧКА_ПЛАНЕТЫ, местоВЦепочке } from "../planetChain";

/**
 * Порядок комнат — ОДИН источник на все страницы. Сторож закрепляет не
 * состав (он может измениться: основатель ещё выбирает состав демонстрации),
 * а СВОЙСТВА, без которых объявление «шаг N из M» станет ложью.
 */

describe("порядок комнат цепочки", () => {
  it("шаги идут подряд и без дыр", () => {
    for (let i = 0; i < ЦЕПОЧКА_ПЛАНЕТЫ.length; i++) {
      const м = местоВЦепочке(ЦЕПОЧКА_ПЛАНЕТЫ[i].путь);
      expect(м).not.toBeNull();
      expect(м!.номер).toBe(i + 1);
      expect(м!.всего).toBe(ЦЕПОЧКА_ПЛАНЕТЫ.length);
    }
  });

  it("страница вне цепочки даёт null, а не «шаг 0»", () => {
    // Вне цепочки и первая в цепочке — разные вещи, объявлять их одинаково
    // нельзя: «шаг 0 из 4» человеку не значит ничего.
    expect(местоВЦепочке("/pricing")).toBeNull();
    expect(местоВЦепочке("/")).toBeNull();
    expect(местоВЦепочке("")).toBeNull();
  });

  it("вложенная страница комнаты остаётся в своей комнате", () => {
    // /qsign/verify — та же комната, а не «вне цепочки»: иначе человек,
    // ушедший на подстраницу подписи, услышит, что вышел из пути.
    const м = местоВЦепочке("/qsign/verify");
    expect(м?.имя).toBe(местоВЦепочке("/qsign")?.имя);
  });

  it("похожий путь НЕ считается комнатой", () => {
    // /qsignature начинается с /qsign, но это другая страница. Без
    // разделителя проверка бы её присвоила.
    expect(местоВЦепочке("/qsignature")).toBeNull();
  });

  it("пути уникальны: иначе два шага получат один номер", () => {
    const пути = ЦЕПОЧКА_ПЛАНЕТЫ.map((к) => к.путь);
    expect(new Set(пути).size).toBe(пути.length);
  });

  it("у каждой комнаты есть произносимое имя", () => {
    for (const к of ЦЕПОЧКА_ПЛАНЕТЫ) {
      expect(к.имя.trim().length).toBeGreaterThan(2);
      // имя произносится вслух — путь вместо имени звучал бы как «слэш ку райт»
      expect(к.имя.startsWith("/")).toBe(false);
    }
  });
});
