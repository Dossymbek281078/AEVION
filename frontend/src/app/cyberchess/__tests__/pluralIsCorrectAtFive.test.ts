import { describe, it, expect } from "vitest";
import { ccPlural } from "../ccPlural";

/**
 * Ручное склонение через тернарник ошибается на числах второго десятка, а
 * видит эту ошибку тот, у кого число выросло, — самый прилежный игрок.
 * Найдено два таких места: «5 темы» вместо «5 тем» и «2 ходов» вместо
 * «2 хода».
 */
describe("склонение по числу", () => {
  const t = (n: number) => `${n} ${ccPlural(n, "тема", "темы", "тем")}`;

  it("единица, малые и большие", () => {
    expect(t(1)).toBe("1 тема");
    expect(t(2)).toBe("2 темы");
    expect(t(4)).toBe("4 темы");
    expect(t(5)).toBe("5 тем");
    expect(t(0)).toBe("0 тем");
  });

  it("второй десяток — исключение, там всегда «тем»", () => {
    // именно здесь ошибаются ручные тернарники: 11 % 10 === 1
    for (const n of [11, 12, 14, 15, 19]) expect(ccPlural(n, "тема", "темы", "тем")).toBe("тем");
  });

  it("после второго десятка правило возвращается", () => {
    expect(ccPlural(21, "тема", "темы", "тем")).toBe("тема");
    expect(ccPlural(22, "тема", "темы", "тем")).toBe("темы");
    expect(ccPlural(25, "тема", "темы", "тем")).toBe("тем");
  });
});
