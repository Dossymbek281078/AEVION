import { createHash } from "node:crypto";
/**
 * Живой консилиум ГОСТЮ — без входа, но по счёту.
 *
 * 🔴 ЗАЧЕМ. Замер 28.09.2026 живым браузером: у гостя кнопка «Спросить
 * консилиум» ВЫКЛЮЧЕНА, работает только пример с заранее записанными ответами.
 * То есть человек, пришедший по ролику или посту, видит витрину чужого опыта и
 * уходит, не попробовав своего вопроса. Продавать при этом мы пытаемся $40 в
 * месяц: цена названа раньше, чем польза показана.
 *
 * Правило простое: два ЖИВЫХ запроса без входа, дальше — вход по почте.
 *
 * 🔴 ПОЧЕМУ ИМЕННО ПО УСТРОЙСТВУ И АДРЕСУ. Один запрос веером стоит реальных
 * денег: он зовёт несколько моделей разом. Без привязки к устройству бесплатная
 * норма превращается в бесплатный хостинг для скриптов. Адрес берём тем же
 * помощником, что и ограничители (clientIp), устройство — необязательной
 * пометкой от страницы; считаем по ПАРЕ, и совпадение любого из двух тратит
 * норму.
 *
 * ⚠️ ЧЕСТНАЯ ГРАНИЦА. Счёт живёт в памяти процесса: перезапуск сервиса обнуляет
 * его. Это осознанный размен — база ради двух бесплатных запросов не стоит
 * усложнения, а злоупотребление ограничено сверху ещё и общим ограничителем
 * темпа. Если норму начнут выедать скриптами, счёт переносится в таблицу.
 */
import type { Request } from "express";
import { clientIp } from "./rateLimit";

/** Сколько живых запросов получает гость в сутки. */
export function гостевойЛимит(): number {
  const raw = Number(process.env.MULTICHAT_GUEST_FREE_PER_DAY ?? "2");
  return Number.isFinite(raw) && raw >= 0 ? Math.floor(raw) : 2;
}

/** Ключ суток — норма обновляется в полночь UTC, а не «через 24 часа». */
function сутки(now = new Date()): string {
  return now.toISOString().slice(0, 10);
}

const счёт = new Map<string, number>();

/** Гость — тот, у кого нет разобранного входа. */
export function этоГость(req: Request): boolean {
  return !req.auth?.sub;
}

/** Идентификатор устройства, если страница его прислала. Одно место на модуль. */
function устройствоЗапроса(req: Request): string {
  return String(
    req.get("x-aevion-device") || (req.body as Record<string, unknown> | undefined)?.deviceId || "",
  ).trim().slice(0, 64);
}

function ключи(req: Request): string[] {
  const день = сутки();
  const ip = clientIp(req);
  const устройство = устройствоЗапроса(req);
  const out = [`ip:${ip}:${день}`];
  if (устройство) out.push(`dev:${устройство}:${день}`);
  return out;
}

/**
 * Устойчивая ЛИЧНОСТЬ гостя — чтобы его консилиум принадлежал ему же.
 *
 * 🔴 Зачем это понадобилось (замер 29.09.2026 на живом проде). Гостевой пропуск
 * снимал платную стену, но обработчик берёт владельца из `req.auth!.sub`, а у
 * гостя его нет: запрос отбивался 401 «auth required» ещё до всякой проверки
 * нормы, при том что страница честно писала «осталось 2 запроса». То есть
 * бесплатный вход, который и был первым экраном страницы цен, не работал вовсе.
 *
 * Идентификатор НЕ содержит суток: консилиум, начатый в 23:59, должен остаться
 * своим и в 00:01 — иначе ответ агентов уйдёт в чужую переписку. Норму по-прежнему
 * считают дневные ключи выше, это разные вопросы.
 *
 * IP и идентификатор устройства не кладём в базу как есть: это персональные
 * данные. Кладём короткий хеш — его достаточно, чтобы связать создание и выдачу.
 */
export function гостевойИдентификатор(req: Request): string {
  const основа = устройствоЗапроса(req) || clientIp(req) || "неизвестно";
  return `guest_${createHash("sha256").update(основа).digest("hex").slice(0, 16)}`;
}

export interface ОстатокГостя {
  лимит: number;
  использовано: number;
  осталось: number;
}

/** Сколько живых запросов у этого гостя ещё есть. Ничего не тратит. */
export function остатокГостя(req: Request): ОстатокГостя {
  const лимит = гостевойЛимит();
  const использовано = Math.max(0, ...ключи(req).map((k) => счёт.get(k) ?? 0));
  return { лимит, использовано, осталось: Math.max(0, лимит - использовано) };
}

/** Тратит одну единицу нормы. Зовётся, когда гостя ПУСКАЮТ, а не когда он пришёл. */
export function засчитатьГостю(req: Request): ОстатокГостя {
  for (const k of ключи(req)) счёт.set(k, (счёт.get(k) ?? 0) + 1);
  return остатокГостя(req);
}

/** Только для тестов: обнулить счёт между случаями. */
export function сброситьСчётГостей(): void {
  счёт.clear();
}

/**
 * Какие вызовы мультичата открыты гостю. Ровно два: завести разговор и один
 * веер по нему. Всё остальное — за платной стеной, как было.
 */
export function гостевойПуть(method: string, path: string): boolean {
  if (method.toUpperCase() !== "POST") return false;
  return path === "/conversations" || /^\/conversations\/[^/]+\/dispatch$/.test(path);
}

/**
 * Решение по ОДНОМУ запросу: пускать ли гостя мимо платного гейта и тратить ли
 * единицу нормы. Тратим только на веере: создание пустого разговора моделей не
 * зовёт и денег не стоит, а списание за него съедало бы норму впустую.
 *
 * Функция экспортирована намеренно: её зовёт index.ts, и сторож проверяет ЕЁ,
 * а не свою копию правила.
 */
export function решениеПоГостю(req: Request): { пускать: boolean; тратить: boolean } {
  if (!гостевойПуть(req.method, req.path)) return { пускать: false, тратить: false };
  if (!этоГость(req)) return { пускать: false, тратить: false };
  if (остатокГостя(req).осталось <= 0) return { пускать: false, тратить: false };
  return { пускать: true, тратить: req.path.endsWith("/dispatch") };
}
