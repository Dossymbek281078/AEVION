import { redirect } from "next/navigation";

import type { Metadata } from "next";

// Метаданные обязательны у каждой публичной страницы, а у перенаправления
// решают отдельную задачу: закрыть адрес от поиска. Короткий вход — дверь для
// человека из каталога, а не страница для индексации; без noindex он
// соревновался бы в выдаче с той страницей, на которую ведёт.
export const metadata: Metadata = {
  title: { absolute: "AEVION" },
  robots: { index: false, follow: true },
};

// /launchnest — вход для каталога LaunchNest.
//
// ЗАЧЕМ. Заявка подана 30.09.2026 (listing launchnest.io/p/aevion-devhub, тариф
// Free, очередь бесплатных мест — 05.11.2026). Обратная ссылка несёт ?c=launchnest,
// и без этого входа метка жила бы только в самом адресе страницы продукта.
//
// ПОЧЕМУ имя каталога целиком, а не короткое «ln». Сторож коротких входов
// сверяет имя маршрута С КЛЮЧОМ канала в CHANNELS: `/ln` при ключе `launchnest`
// оставил бы проверку красной, а красная проверка при исправной системе хуже
// отсутствующей — к ней привыкают. Короткое имя стоило бы второго ключа в
// каталоге, то есть одной сущности под двумя именами.
//
// Никакой логики здесь нет и быть не должно: только перенаправление.
export const dynamic = "force-static";

export default function Page() {
  // Ведём на страницу продукта, а не на общий вход: в каталоге мы заявлены
  // как DevHub, и человек идёт смотреть именно его. Английская версия —
  // потому что каталог англоязычный. Страница читает ?c= (channelFrom) и
  // доносит метку до кассы.
  redirect("/en/devhub?c=launchnest");
}
