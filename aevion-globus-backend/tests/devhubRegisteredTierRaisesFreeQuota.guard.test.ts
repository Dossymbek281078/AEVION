// Проверяется ТА ЖЕ функция, которую зовёт checkCredit, а не копия правила.
import { describe, it, expect } from "vitest";
import { ступеньЗапроса } from "../src/routes/devhub";

describe("ступень запроса в DevHub", () => {
  it("гость остаётся на гостевой норме", () => {
    expect(ступеньЗапроса("free", "anonymous")).toBe("free");
    expect(ступеньЗапроса("free", "guest:abc123")).toBe("free");
  });

  it("вошедший по почте поднимается до registered", () => {
    expect(ступеньЗапроса("free", "user_7f3a")).toBe("registered");
    expect(ступеньЗапроса("free", "founder@example.com")).toBe("registered");
  });

  it("платящего НЕ понижает: pro и enterprise остаются собой", () => {
    expect(ступеньЗапроса("pro", "user_7f3a")).toBe("pro");
    expect(ступеньЗапроса("enterprise", "user_7f3a")).toBe("enterprise");
    expect(ступеньЗапроса("pro", "anonymous")).toBe("pro");
  });
});
