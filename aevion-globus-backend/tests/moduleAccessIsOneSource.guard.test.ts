/*
 * «Что продаём» и «что закрываем» — ОДИН источник, и он сверен с прайсом,
 * с продом и с живой ручкой витрины.
 *
 * 🔴 Замер 01.10.2026 (таблица 63): списки разошлись молча. Продаётся 9
 * модулей, стена стоит на 6, пересечение ОДНО — multichat. То есть 8 модулей
 * продаются, ничем не будучи закрыты (оплата не даёт ничего, чего нет даром),
 * а 5 закрыты, не продаваясь (человек получает отказ, а купить ему нечего).
 *
 * Сторож делает ЗАПРОС к ручке цен и проверяет ТЕЛО ответа: проверять свою же
 * копию таблицы бессмысленно — она совпадёт с собой при любой ошибке.
 */
import { describe, expect, it } from "vitest";
import express from "express";
import request from "supertest";
import {
  ДОСТУП_МОДУЛЕЙ,
  модулиСоСтенойПоДанным,
  приложенияДляВитрины,
  продаётсяОтдельно,
  расхожденияДоступа,
  расхожденияСПрайсом,
} from "../src/data/moduleAccess";
import { STANDALONE_APPS } from "../src/data/pricing";
import { pricingRouter } from "../src/routes/pricing";

/**
 * Значение стены на проде на момент правки, снятое `railway variables`
 * 01.10.2026. Записано здесь, чтобы расхождение данных с продом краснело, а не
 * обнаруживалось отказом платящему. Меняется ВМЕСТЕ с переменной сервиса.
 */
const СТЕНА_НА_ПРОДЕ_01_10 = ["qfusionai", "multichat-engine", "healthai", "qai", "qlearn", "qnews"];

describe("доступ модулей описан одним источником", () => {
  it("источник не пуст и каждая строка названа причиной", () => {
    // Ноль охвата у сторожа — дефект сторожа, а не хорошая новость.
    expect(ДОСТУП_МОДУЛЕЙ.length, "таблица доступа пуста — сторож ничего не проверяет").toBeGreaterThan(10);
    const безПричины = ДОСТУП_МОДУЛЕЙ.filter((м) => !м.почему || м.почему.trim().length < 10);
    expect(безПричины.map((м) => м.moduleId), `проверено строк: ${ДОСТУП_МОДУЛЕЙ.length}`).toEqual([]);
    // Один модуль — одна строка: дубль означает, что ответ зависит от порядка.
    const имена = ДОСТУП_МОДУЛЕЙ.map((м) => м.moduleId.toLowerCase());
    expect([...new Set(имена)].length, "в таблице есть повторяющийся модуль").toBe(имена.length);
  });

  it("данные о стене совпадают с переменной прода — иначе разойдутся молча", () => {
    expect([...модулиСоСтенойПоДанным()].sort()).toEqual([...СТЕНА_НА_ПРОДЕ_01_10].sort());
  });

  it("прайс и источник согласны в ОБЕ стороны", () => {
    const { безЦены, безСтроки } = расхожденияСПрайсом();
    expect(безЦены, "продаём модуль, у которого нет цены").toEqual([]);
    expect(безСтроки, "в прайсе есть модуль, которого нет в источнике доступа").toEqual([]);
    expect(STANDALONE_APPS.length, "прайс пуст — сверка ничего не значит").toBeGreaterThan(5);
  });

  it("контроль прибора: отчёт различает три состояния, а не отвечает одним", () => {
    const р = расхожденияДоступа();
    expect(р.проверено).toBe(ДОСТУП_МОДУЛЕЙ.length);
    // Все три множества непусты — значит отчёт действительно разделяет случаи.
    expect(р.оплатаОткрывает.length, "ни один модуль не открывается оплатой").toBeGreaterThan(0);
    expect(р.продаётсяБезСтены.length, "отчёт не видит продаваемых без стены").toBeGreaterThan(0);
    expect(р.стенаБезПродажи.length, "отчёт не видит закрытых без продажи").toBeGreaterThan(0);
    // И они не пересекаются: модуль не может быть в двух сразу.
    const пересечение = р.продаётсяБезСтены.filter((id) => р.стенаБезПродажи.includes(id));
    expect(пересечение, "один модуль попал в два взаимоисключающих списка").toEqual([]);
  });

  it("замеренное 01.10 расхождение воспроизводится числами 8 и 5", () => {
    /*
     * Числа зафиксированы намеренно. Когда основатель скажет «закрыть бюро»,
     * этот тест покраснеет — и это правильно: правка данных ОБЯЗАНА менять
     * отчёт, иначе данные ни на что не влияют. Красный здесь означает «числа
     * сдвинулись, обнови замер», а не «сломалось».
     */
    const р = расхожденияДоступа();
    expect(р.продаётсяБезСтены.length).toBe(8);
    expect(р.стенаБезПродажи.length).toBe(5);
    expect(р.оплатаОткрывает).toEqual(["multichat-engine"]);
  });

  it("снятый флаг «продаётся» ДЕЙСТВИТЕЛЬНО убирает приложение из выдачи", () => {
    /*
     * Проверка самого механизма, а не текущего совпадения. Сегодня все девять
     * строк прайса помечены «продаётся», поэтому обход фильтра даёт тот же
     * ответ — мутация «убрать вызов» законно не ловится выводом ручки. Поэтому
     * зовём функцию с ПОДСТАВНОЙ таблицей, где флаг снят, и смотрим поведение.
     */
    const всё = приложенияДляВитрины();
    expect(всё.length, "витрина пуста — проверять нечего").toBeGreaterThan(5);

    const жертва = всё[0].moduleId;
    const подставная = ДОСТУП_МОДУЛЕЙ.map((м) =>
      м.moduleId === жертва ? { ...м, продаётся: false } : м,
    );
    const после = приложенияДляВитрины(подставная).map((a) => a.moduleId);

    expect(после, `снят флаг у ${жертва}, а он всё равно в выдаче`).not.toContain(жертва);
    expect(после.length, "исчезло больше одного приложения").toBe(всё.length - 1);

    // Обратный контроль: вернули флаг — приложение вернулось. Без него тест
    // проходил бы и на функции, которая всегда возвращает пустой список.
    expect(приложенияДляВитрины(ДОСТУП_МОДУЛЕЙ).map((a) => a.moduleId)).toContain(жертва);
  });

  it("ЖИВАЯ ручка цен отдаёт ровно то, что помечено «продаётся»", async () => {
    /*
     * Запрос к настоящей ручке из того же модуля, что в проде. Сторож на
     * функцию здесь не годился бы: ручка могла бы считать список правильно и
     * не положить его в ответ — этот класс мы уже ловили на разрезах воронки.
     */
    const app = express();
    app.use(express.json());
    app.use("/api/pricing", pricingRouter);

    const r = await request(app).get("/api/pricing");
    expect(r.status).toBe(200);
    const отдано: string[] = (r.body.standaloneApps ?? []).map((a: { moduleId: string }) => a.moduleId);
    expect(отдано.length, "ручка не отдала ни одного приложения — проверять нечего").toBeGreaterThan(5);

    // Каждое отданное помечено «продаётся»…
    const лишние = отдано.filter((id) => !продаётсяОтдельно(id));
    expect(лишние, `отдано приложений: ${отдано.length}`).toEqual([]);
    // …и ничего помеченного «продаётся» не потеряно по дороге.
    const потеряны = ДОСТУП_МОДУЛЕЙ.filter((м) => м.продаётся).map((м) => м.moduleId)
      .filter((id) => !отдано.includes(id));
    expect(потеряны, "модуль продаётся, но витрина его не показывает").toEqual([]);

    // Отрицательный контроль: закрытое-без-продажи наружу НЕ попадает.
    const нельзяПродавать = расхожденияДоступа().стенаБезПродажи;
    expect(отдано.filter((id) => нельзяПродавать.includes(id))).toEqual([]);
  });
});
