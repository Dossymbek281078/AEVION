/**
 * Пользовательский вебхук QCoreAI не должен указывать внутрь нашей сети.
 *
 * ЗАЧЕМ. Ручка `PUT /api/qcoreai/me/webhook` позволяет пользователю назвать
 * СВОЙ адрес, куда мы будем слать события. Если адрес указывает внутрь, наш
 * сервер сходит туда сам — это классический SSRF. Самая ценная цель —
 * `169.254.169.254`: служебный адрес метаданных облака, отдающий сведения об
 * инстансе вплоть до учётных данных.
 *
 * 28.08.2026 прежний список пропускал СЕМЬ форм из двенадцати проверенных.
 * Ручка требует авторизации (401 без токена), поэтому речь о зарегистрированном
 * пользователе, а не о ком угодно из интернета, — но своя учётка стоит ноль.
 *
 * ГРАНИЦА. Это проверка ИМЕНИ, а не разрешённого адреса: имя, которое DNS
 * отдаёт как приватный адрес, здесь не ловится. Полностью класс закрывается
 * только проверкой ПОСЛЕ разрешения имени, на уровне доставки; тест этого не
 * обещает и не должен читаться как обещание.
 */

import { describe, expect, it } from "vitest";
import { validateWebhookUrl } from "../src/services/qcoreai/userWebhooks";
import { isInternalHost } from "../src/lib/internalHost";

/** Формы, которые обязаны блокироваться. Каждая проверена прогоном 28.08. */
const MUST_BLOCK: Array<[string, string]> = [
  ["http://localhost/x", "имя петли"],
  ["http://127.0.0.1/x", "петля"],
  ["http://127.0.0.2/x", "петля, не первый адрес"],
  ["http://127.1/x", "короткая форма — URL приводит к 127.0.0.1"],
  ["http://2130706433/x", "петля десятичным числом"],
  ["http://0.0.0.0/x", "«этот хост»"],
  ["http://169.254.169.254/latest/meta-data/", "МЕТАДАННЫЕ ОБЛАКА"],
  ["http://metadata.google.internal/x", "метаданные Google по имени"],
  ["http://[::1]/x", "петля IPv6"],
  ["http://[0:0:0:0:0:0:0:1]/x", "та же петля полной записью"],
  ["http://[::ffff:127.0.0.1]/x", "петля, отображённая из IPv4"],
  ["http://10.0.0.5/x", "приватная сеть"],
  ["http://192.168.1.1/x", "приватная сеть"],
  ["http://172.16.0.1/x", "приватная сеть"],
  ["http://100.64.0.1/x", "адрес провайдера (CGNAT)"],
  ["http://box.local/x", "имя в локальной зоне"],
];

/** Законные адреса — они обязаны проходить, иначе проверка бесполезна. */
const MUST_PASS = [
  "https://example.com/hook",
  "https://hooks.slack.com/services/T/B/X",
  "http://11.0.0.1/x",      // 11/8 — публичный диапазон, не приватный
  "https://172.32.0.1/x",   // 172.32 вне приватного 172.16–31
  "https://192.169.0.1/x",  // 192.169 не равно 192.168
];

describe("вебхук пользователя не указывает внутрь сети", () => {
  it("контроль прибора: законные адреса проходят", () => {
    // Без этого тест можно было бы «пройти», запретив вообще всё.
    for (const u of MUST_PASS) {
      expect(validateWebhookUrl(u), `законный адрес отвергнут: ${u}`).not.toBeNull();
    }
  });

  it("все известные формы внутренних адресов отклонены", () => {
    const passed = MUST_BLOCK.filter(([u]) => validateWebhookUrl(u) !== null)
      .map(([u, why]) => `${u}  (${why})`);
    expect(
      passed,
      "эти адреса указывают внутрь нашей сети и НЕ были отклонены:\n  " + passed.join("\n  "),
    ).toEqual([]);
  });

  it("не URL и не http(s) отклоняются", () => {
    for (const bad of [null, 42, "", "   ", "не-адрес", "ftp://example.com/x", "file:///etc/passwd",
                       "javascript:alert(1)"]) {
      expect(validateWebhookUrl(bad as unknown), `принято: ${String(bad)}`).toBeNull();
    }
  });

  it("контроль: проверка имени сама по себе видит адрес метаданных", () => {
    // Отдельно от URL — чтобы поломка была видна на уровне предиката.
    expect(isInternalHost("169.254.169.254")).toBe(true);
    expect(isInternalHost("metadata.google.internal")).toBe(true);
    expect(isInternalHost("example.com")).toBe(false);

    // Имена НАШЕЙ площадки: на Railway сервисы видят друг друга как
    // <сервис>.railway.internal, и это адреса нашей же базы. Проверено
    // 28.08 — попадают под правило `.internal`.
    expect(isInternalHost("backend.railway.internal"), "внутреннее имя Railway").toBe(true);
    expect(isInternalHost("postgres.railway.internal"), "база на Railway").toBe(true);

    // И контроль в другую сторону: слово internal ВНУТРИ имени — не повод
    // блокировать, иначе сторож начнёт мешать законным адресам.
    expect(isInternalHost("internal-tools.example.com"), "ложная тревога").toBe(false);
    expect(isInternalHost("api.aevion.app"), "наш публичный домен").toBe(false);
  });
});
