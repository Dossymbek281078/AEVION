/* Точность партии — одна формула на всё приложение.
 *
 * Она была скопирована в четыре места: всплывающая подсказка после разбора,
 * спарклайн тренда, панель статистики партии и пост-матчевый оверлей. Веса на
 * момент сведения совпадали во всех четырёх, но три из них по-разному вели себя
 * на пустом входе — 0, 50 и деление на ноль, — а расхождение весов было вопросом
 * времени: править одну копию из четырёх дешевле, чем найти остальные три.
 *
 * Веса взяты из исходной формулы без изменений и здесь НЕ подстраивались:
 * blunder не приносит ничего, mistake — треть, inacc — две трети, good — 0.85,
 * great и brilliant — полный балл.
 */

/** Вес хода в проценте точности. Всё, чего нет в таблице, считается «good». */
const WEIGHT: Record<string, number> = {
  brilliant: 1,
  great: 1,
  good: 0.85,
  inacc: 0.6,
  mistake: 0.3,
  blunder: 0,
};

/**
 * Процент точности по разобранным ходам ОДНОЙ стороны.
 * Пустой вход возвращает null: точности у партии без разобранных ходов не
 * существует, и подставлять сюда число — значит выдумывать его.
 */
export function accuracyOf(moves: readonly { quality: string }[]): number | null {
  if (!moves.length) return null;
  const sum = moves.reduce((s, m) => s + (m.quality in WEIGHT ? WEIGHT[m.quality] : WEIGHT.good), 0);
  return Math.round((100 * sum) / moves.length);
}
