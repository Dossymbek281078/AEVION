// Человеческий текст для отказа агента.
//
// Зачем отдельный модуль: карточка агента рисовала `r.error` как есть, а бэкенд
// присылает туда технические английские строки. Самая частая из них —
// `rate_limit_exceeded: max 30 chat requests per minute` — человеку непонятна.
//
// 🔴 История этого текста стоит отдельного слова, потому что она про то, как
// правдивый текст становится ложным без единой правки.
//
// Первая версия объясняла: «это общий предел, а не ваш личный». Тогда так и
// было — отправка ходит к своему же API по внутренней петле, и адрес у ВСЕХ
// пользователей получался один, поэтому предел действительно был общим на всю
// платформу. Человек читал «per IP» как «я слишком часто нажимал» и уходил.
//
// 13.08.2026 дефект в лимитере починен: он считает по аккаунту, и предел стал
// именно личным. С этого момента правдивое объяснение превратилось в неправду —
// теперь оно уверяет, что виноват кто-то другой, тогда как исчерпал предел сам
// пользователь. Текст, который ОБЪЯСНЯЕТ поведение, обязан меняться вместе с
// поведением, иначе он врёт тем убедительнее, чем лучше написан.
//
// Правило модуля: показать человеку понятную причину и НЕ спрятать настоящую.
// Поэтому возвращаются две строки — `human` для глаза и `technical` для мелкого
// шрифта рядом, чтобы отчёт об ошибке от пользователя оставался полезным.

import { tm } from "./mcText";

export type AgentFailure = {
  /** Понятная причина на языке страницы (исходник — русский; без lang — русский). */
  human: string;
  /** Исходная строка сервера, если она добавляет что-то к human. */
  technical: string | null;
};

/**
 * Сколько ждать, если сервер сказал. 30.10.2026: lang — язык страницы; без него, как раньше, русский
 * (замер на проде 4f71ad70f: на /en отказ агента и «Повторите через…» оставались русскими).
 */
export function retryHint(retryAfterSec: unknown, lang?: string): string {
  const n = typeof retryAfterSec === "number" && Number.isFinite(retryAfterSec) ? Math.ceil(retryAfterSec) : null;
  if (n === null || n <= 0) return "";
  const en = lang === "en";
  if (n < 60) return en ? ` Try again in ${n} s.` : ` ${tm(lang ?? "ru", "Повторите через")} ${n} ${tm(lang ?? "ru", "с.")}`;
  const min = Math.ceil(n / 60);
  return en ? ` Try again in ${min} min.` : ` ${tm(lang ?? "ru", "Повторите через")} ${min} ${tm(lang ?? "ru", "мин.")}`;
}

export function agentFailure(raw: unknown, lang?: string): AgentFailure {
  const f = причинаПоРусски(raw);
  return lang && lang !== "ru" ? { ...f, human: tm(lang, f.human) } : f;
}

function причинаПоРусски(raw: unknown): AgentFailure {
  const s = typeof raw === "string" ? raw.trim() : "";
  if (!s) return { human: "Агент не ответил.", technical: null };
  const low = s.toLowerCase();

  // Предел частоты. Персональный — считается по аккаунту (лимитер починен
  // 13.08.2026). Поэтому и текст персональный: обещать «это не вы» теперь
  // значит отправить человека искать причину не там.
  if (low.includes("rate_limit") || low.includes("too many requests") || low.includes("429")) {
    return {
      human:
        "Ваш предел запросов в минуту исчерпан — это личный счёт, чужие отправки его не расходуют. " +
        "Счёт восстановится через минуту. Один совет тратит столько запросов, сколько в нём агентов.",
      technical: s,
    };
  }

  // Кончились деньги/квота у провайдера — это НЕ то же самое, что предел частоты:
  // ожиданием не лечится, и обещать «через минуту» было бы неправдой.
  if (low.includes("quota") || low.includes("billing") || low.includes("insufficient")) {
    return {
      human: "У провайдера модели закончился оплаченный объём. Ожидание не поможет — нужен другой провайдер или пополнение.",
      technical: s,
    };
  }

  if (low.includes("empty reply")) {
    return {
      human: "Провайдер вернул пустой ответ. Это сбой на его стороне, а не ваш вопрос — попробуйте ещё раз.",
      technical: s,
    };
  }

  if (low.includes("timeout") || low.includes("etimedout") || low.includes("aborted")) {
    return { human: "Провайдер не ответил вовремя. Попробуйте ещё раз.", technical: s };
  }

  if (low.includes("unauthorized") || low.includes("401") || low.includes("token")) {
    return { human: "Сессия истекла — войдите заново.", technical: s };
  }

  if (low.startsWith("upstream ") || /\b5\d\d\b/.test(s)) {
    return { human: "Сервис моделей ответил ошибкой. Попробуйте ещё раз.", technical: s };
  }

  // Неизвестная причина: не выдумываем объяснение и не прячем строку.
  return { human: "Агент не ответил.", technical: s };
}

/**
 * Короткое имя роли для заголовка карточки.
 *
 * Роли приходят в виде «Аналитик — только факты и цифры, без оценок»: целиком в
 * заголовок не влезает, а `agentId` («analyst») в русском интерфейсе выглядит
 * как утечка внутреннего кода. Берём часть до тире.
 */
export function agentTitle(role: string | undefined, agentId: string): string {
  const name = (role || "").split("—")[0].trim();
  return name || agentId;
}
