import { describe, expect, it } from "vitest";
import { readdirSync, readFileSync, statSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { stripComments } from "./helpers/sourceCode";

/**
 * Один заход — одно событие page_view.
 *
 * 🔴 ЗАЧЕМ. Замер 08.09.2026 перехватом запросов браузера: /en/devhub и
 * /en/go отправляли ДВА POST в /api/pricing/events за одну загрузку, /devhub —
 * один. Причина: два компонента шлют одно и то же событие. PageTracking
 * (30.08, source = имя страницы + meta.channel) и LandingView (19.08,
 * source с каналом в имени). Второй завели, когда трекера на посадочных не
 * было; первый добавили позже, и они сложились.
 *
 * Так было на ВОСЬМИ страницах — всех входах воронки, включая четыре
 * посадочные запуска. Отчёт /api/events/summary считает каждое событие
 * (`+= 1`, дедупликации по посетителю там нет), значит заходы удваивались, а
 * конверсия «заход → покупка» на этих страницах была занижена вдвое — ровно
 * на тех числах, по которым судят об успехе запуска и о том, окупился ли
 * канал.
 *
 * Оставлен PageTracking: он кладёт канал в meta, а сводка воронки читает
 * ТОЛЬКО meta (прямо сказано в lib/track.ts). Канал в имени источника не
 * разбирает ни один отчёт — проверено грепом по бэкенду.
 *
 * ГРАНИЦА. Сторож считает ОБЪЯВЛЕНИЯ учёта в исходнике страницы. Он не
 * видит, сколько событий уйдёт на самом деле (это работа браузерной пробы) и
 * не знает про компоненты, которые страница подключает через другие
 * компоненты. И он НЕ ловит два одинаковых отправителя в одной ветке —
 * различить ветки текстом нельзя, а ложная тревога на /qskyway дороже
 * узкой границы: сторожа, краснеющего на здоровом, отключают.
 */
const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, "..");

/** Компоненты, каждый из которых шлёт page_view сам по себе. */
const ОТПРАВИТЕЛИ = ["<PageTracking", "<LandingView"];

function страницы(dir: string, out: string[] = []): string[] {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) {
      if (e !== "node_modules" && e !== "__tests__") страницы(p, out);
    } else if (e === "page.tsx") out.push(p);
  }
  return out;
}

describe("один заход — одно событие", () => {
  const файлы = страницы(APP);

  it("прибор видит предмет: страницы найдены, учёт где-то стоит", () => {
    expect(файлы.length).toBeGreaterThan(100);
    const сУчётом = файлы.filter((f) => /<PageTracking/.test(readFileSync(f, "utf8")));
    // без этого «дублей нет» означало бы «учёта нет нигде»
    expect(сУчётом.length, "ни одна страница не считает заходы").toBeGreaterThan(5);
  });

  it("ни одна страница не отправляет page_view дважды", () => {
    const дубли: string[] = [];
    for (const f of файлы) {
      const код = stripComments(readFileSync(f, "utf8"));
      /*
       * Считаем РАЗНЫЕ отправители, а не повторы одного.
       *
       * Повтор одного компонента законен: у /qskyway два <PageTracking> стоят
       * в разных ветках возврата (платная стена и содержимое), выполнится
       * ровно один, и это осознанно — считать надо всех, кто увидел модуль,
       * включая упершихся в стену. Первая редакция сторожа считала вхождения
       * подряд и покраснела на этом исправном коде.
       *
       * Настоящий дефект был именно в СОЧЕТАНИИ двух разных отправителей:
       * каждый шлёт своё событие безусловно, и они складываются.
       */
      const разных = ОТПРАВИТЕЛИ.filter((к) => код.includes(к)).length;
      if (разных > 1) {
        дубли.push(`${relative(APP, f)} → отправителей ${разных} (разных)`);
      }
    }
    expect(
      дубли,
      "страница считает один заход дважды: конверсия по ней будет занижена вдвое.\n"
      + дубли.join("\n"),
    ).toEqual([]);
  });
});
