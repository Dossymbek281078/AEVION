/*
 * Бесконечной переадресации нет ни на одной странице.
 *
 * 🔴 ЗАМЕР НА ПРОДЕ 01.10.2026 (волна 7, bdac5b064), курлом с кукой:
 *     /longevity  + aevion_lang_v1=en → 6 шагов, итог 307, конец снова /longevity
 *     /qskyway    + aevion_lang_v1=en → 6 шагов, итог 307, конец снова /qskyway
 *     /go, /shop  + та же кука        → 1 шаг, 200 (контроль: тут всё верно)
 *     /longevity  без куки            → 0 шагов, 200 (контроль)
 * Кука ставится на ГОД при любом заходе по англоссылке, а на /longevity пришли
 * ОБА платежа за всё время — то есть круг стоял ровно на денежной странице.
 *
 * Причина: два РАЗНЫХ набора. Страница уводила на /en/<имя>, middleware знал свой
 * список адресов с настоящей английской версией и всё остальное возвращал назад.
 *
 * Сторож проходит переадресацию ОБЕИМИ настоящими функциями — той, что решает за
 * страницу, и той, что решает за middleware. Это не HTTP, и я называю границу
 * честно: сервер в тесте не поднимается. Зато обе стороны здесь настоящие, а
 * именно их расхождение и дало петлю.
 */
import { describe, expect, it } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { АНГЛИЙСКИЕ_СТРАНИЦЫ_СО_СВОИМ_АДРЕСОМ, englishVersionFor } from "../englishPages";
import { английскийРедирект } from "../../middleware";

const ПРИЛОЖЕНИЕ = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "app");

/** Проход переадресаций: куда приедет гость и за сколько шагов. */
function пройти(старт: string, кукаEn: boolean, пределШагов = 5) {
  const путь: string[] = [старт];
  let текущий = старт;
  for (let шаг = 0; шаг < пределШагов; шаг += 1) {
    const следующий = текущий.toLowerCase().startsWith("/en/") || текущий.toLowerCase() === "/en"
      ? английскийРедирект(текущий)
      : кукаEn
        ? englishVersionFor(текущий)
        : null;
    if (!следующий) return { конец: текущий, шагов: шаг, зациклился: false, путь };
    if (путь.includes(следующий)) return { конец: следующий, шагов: шаг + 1, зациклился: true, путь: [...путь, следующий] };
    путь.push(следующий);
    текущий = следующий;
  }
  return { конец: текущий, шагов: пределШагов, зациклился: true, путь };
}

function страницы(каталог: string, собрано: string[] = []): string[] {
  for (const имя of readdirSync(каталог)) {
    const п = join(каталог, имя);
    if (statSync(п).isDirectory()) {
      if (имя === "__tests__" || имя === "node_modules") continue;
      страницы(п, собрано);
    } else if (имя === "page.tsx") собрано.push(п);
  }
  return собрано;
}

const ПРОВЕРЯЕМ = [
  "/longevity", "/qskyway", "/shop", "/go", "/devhub", "/pricing", "/bureau", "/cyberchess",
  ...АНГЛИЙСКИЕ_СТРАНИЦЫ_СО_СВОИМ_АДРЕСОМ,
  "/en/longevity", "/en/qskyway", "/en/pricing", "/en",
];

describe("языковая переадресация никогда не зацикливается", () => {
  it("контроль прибора: проход видит и движение, и остановку", () => {
    // Движение есть там, где английская страница существует.
    expect(пройти("/go", true).конец).toBe("/en/go");
    // И остановка там, где её нет: гость остаётся на русской.
    expect(пройти("/longevity", true).конец).toBe("/longevity");
    // Без куки не двигаемся вообще.
    expect(пройти("/go", false).шагов).toBe(0);
  });

  it("с кукой и без — ни одного круга, не больше двух шагов", () => {
    const плохие: string[] = [];
    for (const старт of ПРОВЕРЯЕМ) {
      for (const кука of [true, false]) {
        const р = пройти(старт, кука);
        if (р.зациклился) плохие.push(`${старт} (кука=${кука}): ${р.путь.join(" → ")}`);
        else if (р.шагов > 2) плохие.push(`${старт} (кука=${кука}): ${р.шагов} шагов`);
      }
    }
    expect(плохие, `проверено адресов: ${ПРОВЕРЯЕМ.length} × 2`).toEqual([]);
  });

  it("редирект на вычисленный английский адрес стоит ПОД проверкой", () => {
    /*
     * Дыра, найденная мутацией 01.10.2026. Обход по исходнику ищет дословный
     * "/en/…" в строке редиректа — а страница, которая берёт адрес из общего
     * списка, пишет `redirect(enUrl)`, без литерала. Убери у неё условие — и
     * прежний обход остаётся зелёным, хотя гость снова попадает в круг (а при
     * пустом адресе — в ошибку времени выполнения).
     *
     * Поэтому: файл, который берёт адрес из списка, обязан этот адрес ПРОВЕРИТЬ.
     * Проверка текстовая, и границу называю честно: она видит форму условия, а
     * не поток данных. Зато ловит ровно тот случай, который мутация и показала.
     */
    const файлы = страницы(ПРИЛОЖЕНИЕ);
    const виновные: string[] = [];
    let проверено = 0;
    for (const путь of файлы) {
      const текст = readFileSync(путь, "utf8");
      if (!текст.includes("englishVersionFor(")) continue;
      проверено += 1;
      const естьПроверка = /if\s*\([^)]*enUrl|&&\s*enUrl|enUrl\s*[?&]/.test(текст);
      if (!естьПроверка) виновные.push(путь.replace(ПРИЛОЖЕНИЕ, "app"));
    }
    expect(проверено, "ни одна страница не берёт адрес из списка — сторож пуст").toBeGreaterThan(3);
    expect(виновные, `проверено страниц со списком: ${проверено}`).toEqual([]);
  });

  it("ни одна страница не уводит на английский адрес вне общего списка", () => {
    const файлы = страницы(ПРИЛОЖЕНИЕ);
    expect(файлы.length, "страниц не найдено — сторож пуст").toBeGreaterThan(20);
    const виновные: string[] = [];
    for (const путь of файлы) {
      const текст = readFileSync(путь, "utf8");
      for (const строка of текст.split("\n")) {
        if (!/redirect\(/.test(строка)) continue;
        const m = /"(\/en\/[a-z0-9\-\/]*)"/i.exec(строка);
        if (m && !АНГЛИЙСКИЕ_СТРАНИЦЫ_СО_СВОИМ_АДРЕСОМ.includes(m[1].toLowerCase())) {
          виновные.push(`${путь.replace(ПРИЛОЖЕНИЕ, "app")}: ${m[1]}`);
        }
      }
    }
    expect(виновные, `проверено страниц: ${файлы.length}`).toEqual([]);
  });
});
