import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Дедуп вебхуков обязан лежать ТАМ ЖЕ, где хранилище событий.
 *
 * Замер 30.08.2026. Дедуп платёжных вебхуков (gumroad, lemonsqueezy, paybox,
 * paypal) пишется в файл `data/webhook-dedup.jsonl`. Он защищает от повторной
 * обработки платежа: придёт повтор — доступ выдастся дважды.
 *
 * Проверил прод: том смонтирован, `eventsStore.onVolume` = true, и дедуп лежит
 * в том же каталоге. То есть СЕГОДНЯ всё верно и повторной обработки нет.
 *
 * Но верно это ПО СОВПАДЕНИЮ путей, а не по устройству:
 *
 *   хранилище событий  спрашивает себя «лежу ли я под точкой монтирования»
 *                      и отдаёт ответ в /health полем onVolume
 *   дедуп вебхуков     берёт путь от рабочего каталога и НЕ спрашивает ничего
 *
 * Разойдись они — событий мы недосчитаемся заметно, а дедуп исчезнет молча, и
 * узнаем мы об этом по двойной выдаче доступа.
 *
 * Сторож закрепляет СОВПАДЕНИЕ КАТАЛОГОВ, а не конкретный путь: путь могут
 * поменять осознанно, и тогда поменяют обоим. Разъезд же почти всегда
 * недосмотр.
 *
 * Прибор в /health не добавлял намеренно: index.ts расходится в трёх версиях
 * по веткам, и правка там дала бы конфликт на общем файле ради поля, которое
 * пока некому читать. Задача записана в передаточный документ.
 */

const SRC = join(__dirname, "..", "src");
const DEDUP = readFileSync(join(SRC, "lib", "webhookDedup.ts"), "utf8");
const EVENTS = readFileSync(join(SRC, "routes", "events.ts"), "utf8");

/** Каталог по умолчанию из выражения вида join(process.cwd(), "data", ...). */
function defaultDirOf(src: string): string | null {
  const i = src.indexOf('join(process.cwd(), "');
  if (i < 0) return null;
  const start = i + 'join(process.cwd(), "'.length;
  const end = src.indexOf('"', start);
  return end < 0 ? null : src.slice(start, end);
}

describe("дедуп вебхуков и хранилище событий лежат в одном каталоге", () => {
  test("контроль: оба файла прочитаны и оба задают путь по умолчанию", () => {
    expect(DEDUP.length, "модуль дедупа не прочитан").toBeGreaterThan(200);
    expect(EVENTS.length, "модуль событий не прочитан").toBeGreaterThan(200);
    expect(defaultDirOf(DEDUP), "у дедупа не найден путь по умолчанию").not.toBeNull();
    expect(defaultDirOf(EVENTS), "у событий не найден путь по умолчанию").not.toBeNull();
  });

  test("каталог по умолчанию у них ОДИН", () => {
    expect(
      defaultDirOf(DEDUP),
      "дедуп и события разъехались по каталогам: том смонтирован в один, и " +
        "второй окажется в образе. События мы недосчитаем заметно, а дедуп " +
        "исчезнет молча — узнаем по двойной выдаче доступа за один платёж.",
    ).toBe(defaultDirOf(EVENTS));
  });

  test("у дедупа есть СВОЙ путь через переменную — иначе его нельзя увести на том", () => {
    // Если переменной нет, единственный способ положить дедуп на том — совпадение
    // рабочего каталога с точкой монтирования. Это не настройка, а везение.
    expect(DEDUP.includes("process.env.WEBHOOK_DEDUP_FILE"), "нет способа задать путь").toBe(true);
  });
});
