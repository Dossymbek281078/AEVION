import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Посадочная запуска не называет чисел, за которыми не стоит жизни.
 *
 * 28.08.2026 страница печатала «12 турниров с сеткой и рейтингом». Двенадцать
 * записей в `/api/cyberchess-tournaments/list` правда есть, но это ЗАГОТОВКИ
 * (`buildSeedFixtures` в cyberchessTournaments.ts), и число участников у них
 * вписано числом: 87, 64, 211 из 256. Настоящих регистраций во всех двенадцати
 * НОЛЬ — проверено запросом, `registeredUserIds` пуст везде.
 *
 * Человек читает «12 турниров», заходит и находит турнир на 211 участников,
 * которых не существует. Это первый пункт ворот запуска: каждое обещание
 * проверено.
 *
 * Возможность при этом настоящая — сетка, круги, регистрация и таблица
 * работают. Поэтому убрано ЧИСЛО, а не пункт.
 */

const PAGE = readFileSync(
  join(dirname(fileURLToPath(import.meta.url)), "..", "launch", "page.tsx"),
  "utf8",
);

/** Код без комментариев: разбор ниже спрашивает, что видит ЧЕЛОВЕК. */
const CODE = PAGE.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");

describe("посадочная запуска: числа только те, за которыми есть жизнь", () => {
  test("счётчик турниров не печатается в заголовке факта", () => {
    // Именно подстановка числа в текст, а не сам факт про турниры.
    expect(
      /\$\{tournaments\}\s*турнир/.test(CODE),
      "вернулось «N турниров»: число означает активность, а регистраций ноль",
    ).toBe(false);
  });

  test("пункт про турниры остался — возможность настоящая", () => {
    expect(CODE).toContain("Турниры с сеткой и рейтингом");
  });

  test("банк задач число называет — оно из базы и настоящее", () => {
    // Отрицательный контроль: проверка не должна запрещать ЛЮБЫЕ числа, иначе
    // она снесла бы и честные. 502 584 приходят из `/meta` при сборке.
    // Утверждение по ТОЧНОЙ форме, которая уезжает в разметку. Первая версия
    // писала `${bank` и проходила по префиксу от `${bankLabel}` — то есть была
    // бы зелёной и в случае, когда честного числа на странице не осталось.
    expect(CODE).toContain("${bankLabel} задач в банке");
  });
});
