import { describe, it, expect } from "vitest";
import { gameResultOf } from "../gameResult";

/* Партии вариантов сохраняются в историю тем же эффектом на `over`, что и обычные,
   поэтому классификатор обязан знать их словарь. До 2026-07-27 не знал: все четыре
   победные строки кончаются на «победа!», а в списке слов его не было — выигранная
   партия в варианте шла в ПОРАЖЕНИЯ и стоила игроку рейтинга и серии.

   Строки ниже скопированы из sOver(...) в page.tsx буква в букву, включая эмодзи и
   тире, — тест ловит и переформулировку строки, и потерю слова в классификаторе. */

const VARIANTS: Array<[string, string, "W" | "L"]> = [
  ["Три шаха", "⚡ Три шаха — победа!", "W"],
  ["Три шаха", "⚡ Соперник дал 3 шаха — поражение", "L"],
  ["Король на холме", "⛰ Король взошёл на холм — победа!", "W"],
  ["Король на холме", "⛰ Соперник занял центр — поражение", "L"],
  ["Атомные", "💥 Король соперника взорван — победа!", "W"],
  ["Атомные", "💥 Твой король взорван — поражение", "L"],
  ["Королевский ферзь", "Королевский ферзь соперника пал — победа!", "W"],
  ["Королевский ферзь", "Твой королевский ферзь пал — поражение", "L"],
];

describe("gameResultOf — варианты", () => {
  for (const [variant, line, want] of VARIANTS) {
    it(`${variant}: «${line}» → ${want}`, () => {
      expect(gameResultOf(line)).toBe(want);
    });
  }

  it("ни одна победа в варианте не считается поражением", () => {
    const wins = VARIANTS.filter(([, , w]) => w === "W").map(([, line]) => line);
    expect(wins.map(gameResultOf)).toEqual(wins.map(() => "W"));
  });

  it("слово «поражение» перебивает «победа», если строка содержит оба", () => {
    // Победа и поражение — ветки одного тернарника; порядок проверок в классификаторе
    // единственное, что разводит их, и он не должен зависеть от того, какое слово раньше.
    expect(gameResultOf("победа соперника — твоё поражение")).toBe("L");
  });

  it("прежний словарь не сломан", () => {
    expect(gameResultOf("Checkmate! You win! 🏆")).toBe("W");
    expect(gameResultOf("Checkmate — AI wins")).toBe("L");
    expect(gameResultOf("AI timed out — you win!")).toBe("W");
    expect(gameResultOf("Alex сдался — Вы победили!")).toBe("W");
    expect(gameResultOf("Draw agreed")).toBe("D");
    expect(gameResultOf("Ничья (договорились)")).toBe("D");
    expect(gameResultOf("Time out")).toBe("L");
    expect(gameResultOf("You resigned")).toBe("L");
  });
});
