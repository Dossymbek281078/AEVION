import { describe, it, expect } from "vitest";
import { spendCompleteness, seriesRecency } from "../spendCompleteness";

// Три исхода, и средний — тот, ради которого всё это вынесено из страницы.
// «Поля нет» тихо превращается в «всё хорошо» одной невнимательной правкой:
// достаточно заменить `== null` на проверку на ложность.

describe("полнота сводки расходов различает три исхода", () => {
  it("поля нет — НЕ ЗНАЕМ, а не «полно»", () => {
    expect(spendCompleteness(undefined).kind).toBe("unknown");
    expect(spendCompleteness(null).kind).toBe("unknown");
  });

  it("ноль — полно", () => {
    expect(spendCompleteness(0).kind).toBe("complete");
  });

  it("больше нуля — неполно, и число потерь названо", () => {
    const c = spendCompleteness(7);
    expect(c.kind).toBe("incomplete");
    // Число обязано доехать: «неполно» без величины не даёт решить, тревога
    // это или единичный сбой.
    expect(c).toMatchObject({ lost: 7 });
  });

  it("ноль и отсутствие поля НЕ совпадают", () => {
    // Ключевое утверждение файла. Обе проверки выше по отдельности пережили
    // бы схлопывание двух исходов в один; эта — нет.
    expect(spendCompleteness(0).kind).not.toBe(spendCompleteness(undefined).kind);
  });

  it("мусор вместо числа не выдаётся за неполноту", () => {
    // NaN приходит от Number(...) на нечисловом ответе. Это «не знаю» по
    // происхождению, но тревогой быть не должно: считаем полным и молчим.
    expect(spendCompleteness(Number.NaN).kind).toBe("complete");
  });
});

describe("свежесть ряда расходов различает пусто, свежо и протухло", () => {
  it("пустой ряд — это «пусто», а не «сегодня»", () => {
    expect(seriesRecency([], "2026-08-31").kind).toBe("empty");
  });

  it("последний день сегодня — свежо", () => {
    expect(seriesRecency(["2026-08-30", "2026-08-31"], "2026-08-31").kind).toBe("current");
  });

  it("отставание считается и НАЗЫВАЕТСЯ числом", () => {
    const r = seriesRecency(["2026-07-16"], "2026-08-31");
    expect(r.kind).toBe("stale");
    // Настоящий замер прода 31.08: последняя запись 16 июля, 46 дней назад.
    // Без числа «протухло» не даёт решить, тревога это или норма.
    expect(r).toMatchObject({ lastDate: "2026-07-16", daysBehind: 46 });
  });

  it("порядок дат не важен — берётся последняя", () => {
    // Ряд приходит отсортированным, но полагаться на это нельзя:
    // проверка ловит замену сортировки на «взять последний элемент».
    const r = seriesRecency(["2026-08-31", "2026-01-01"], "2026-08-31");
    expect(r.kind).toBe("current");
  });

  it("мусор среди дат не выдаётся за данные", () => {
    expect(seriesRecency(["не-дата", ""], "2026-08-31").kind).toBe("empty");
  });

  it("пусто и протухло — РАЗНЫЕ исходы", () => {
    // Ключевое утверждение: обе проверки выше пережили бы схлопывание
    // «нет данных» и «данные старые» в один ответ, а для панели это
    // противоположные новости.
    expect(seriesRecency([], "2026-08-31").kind)
      .not.toBe(seriesRecency(["2026-07-16"], "2026-08-31").kind);
  });
});
