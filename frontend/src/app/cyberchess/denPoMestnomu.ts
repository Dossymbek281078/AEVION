/**
 * День в виде «ГГГГ-ММ-ДД» по МЕСТНОМУ времени человека.
 *
 * Повод 13.10.2026 (замер bd на проде c17379338, три свежих контекста, 00:48 по
 * месту): `cc_login_streak_v1` записал lastDay = 2026-10-12 — день по UTC. У нас
 * UTC+5, и до 05:00 утра «сегодня» для приложения ещё вчера: серия входов
 * растёт дважды за одни сутки по часам человека, а «день N подряд» — это
 * утверждение о человеке, которое он может опровергнуть сам. Тот же шаблон
 * стоял в девяти местах страницы и в вопросе дня тренера.
 *
 * Формат совпадает с прежним (первые десять знаков ISO-строки), поэтому уже
 * сохранённые значения в localStorage читаются как раньше; меняется только
 * граница суток — теперь полночь по месту, а не 05:00.
 */
export function denPoMestnomu(d: Date = new Date()): string {
  const г = d.getFullYear();
  const м = String(d.getMonth() + 1).padStart(2, "0");
  const дн = String(d.getDate()).padStart(2, "0");
  return `${г}-${м}-${дн}`;
}

/** Вчерашний день по местному времени — для проверки «серия продолжается». */
export function vcheraPoMestnomu(now: Date = new Date()): string {
  const d = new Date(now);
  d.setDate(d.getDate() - 1);
  return denPoMestnomu(d);
}
