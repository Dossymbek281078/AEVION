import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { isSmokeAlias, SMOKE_ALIAS_SQL } from "../src/routes/qpersona";

/**
 * Служебные записи смоук-прогонов не попадают ни в галерею, ни в счётчик.
 *
 * Замер на проде 01.09.2026: `/api/qpersona/personas?limit=100` вернул 37
 * записей, ВСЕ 37 — наши смоук-прогоны, настоящих персон ноль. Витрина при
 * этом писала посетителю «37 personas created».
 *
 * Число на витрине по нашему стандарту берётся из фактического прогона.
 * Здесь оно считало наши же проверки и выдавало их за людей.
 */

/** Настоящие псевдонимы с прода — не выдуманные, взяты из ответа ручки. */
const СЛУЖЕБНЫЕ = [
  "sm1784803084136",
  "smoke-1784775240406-x",
  "sm1784775188392",
  "smoke-test-xyz",
];

/** Так выглядят псевдонимы людей: короткие, со смыслом, не из цифр. */
const ЛЮДИ = ["anna", "dev_marat", "sm", "smart-alex", "sample", "smokey-eyes"];

describe("витрина QPersona не показывает служебные записи", () => {
  it("узнаёт все служебные псевдонимы с прода", () => {
    for (const a of СЛУЖЕБНЫЕ) {
      expect(isSmokeAlias(a), `не распознан служебный: ${a}`).toBe(true);
    }
  });

  it("НЕ трогает псевдонимы людей — иначе спрячем настоящих", () => {
    // Отрицательный контроль важнее положительного: фильтр, который прячет
    // всё подряд, сделал бы витрину честно пустой и одинаково бесполезной.
    // «smokey-eyes» и «smart-alex» начинаются с тех же букв — они обязаны
    // остаться, иначе признак ловит не служебность, а начало слова.
    for (const a of ЛЮДИ) {
      expect(isSmokeAlias(a), `человека приняли за смоук: ${a}`).toBe(false);
    }
  });

  it("условие для базы и предикат для памяти согласны между собой", () => {
    /*
     * Здесь два источника правды по устройству: SQL исполняет Postgres, а
     * предикат — мы. Разойтись они могут молча, и тогда счётчик и галерея
     * снова начнут спорить — ровно то, ради чего правка и делалась.
     *
     * Полного разбора SQL тут нет и не нужно: сверяем, что обе формы описаны
     * ОДНИМИ И ТЕМИ ЖЕ двумя правилами. Меняешь одно — обязан менять второе,
     * и этот тест краснеет, если забудешь.
     */
    expect(SMOKE_ALIAS_SQL).toContain("^smoke([-_0-9]|$)");
    expect(SMOKE_ALIAS_SQL).toContain("^sm[0-9]{6,}$");
    expect(isSmokeAlias("smoke-anything")).toBe(true);
    expect(isSmokeAlias("sm123456")).toBe(true);
    expect(isSmokeAlias("sm12345")).toBe(false); // пять цифр — не метка времени
  });

  it("счётчик и галерея берут ОДНО условие, а не два похожих", () => {
    // Расхождение здесь и было настоящим дефектом: галерея отбирала публичные,
    // а счётчик считал всё подряд. Проверяем по коду, что оба места ссылаются
    // на общий признак, а не повторяют его своими словами.
    const src = readFileSync(join(__dirname, "..", "src", "routes", "qpersona.ts"), "utf8");
    const вSql = src.split("SMOKE_ALIAS_SQL").length - 1;
    expect(вSql, "общее условие применено меньше трёх раз — где-то осталась своя копия")
      .toBeGreaterThanOrEqual(4); // объявление + список + счёт + последние
    expect(src).toContain("visibility = 'public' AND NOT ${SMOKE_ALIAS_SQL}");
  });
});
