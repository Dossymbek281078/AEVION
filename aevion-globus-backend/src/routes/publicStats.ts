/**
 * Публичный счётчик зарегистрированных — ОДНО число, которым меряется цель.
 *
 * 🔴 ЗАЧЕМ. 28.09.2026 основатель поставил цель 100 000 пользователей к концу
 * года, а измерить её было НЕЧЕМ: у платформы нет ни одной ручки, которая
 * отвечает «сколько людей зарегистрировалось». Замер того дня: у DevHub на
 * проде 2 проекта и один «пользователь» anonymous — оба проекта наши пробы.
 * Цель без прибора превращается в спор, поэтому прибор идёт первым.
 *
 * ЧТО ОТДАЁТ И ЧЕГО НЕ ОТДАЁТ. Только числа: всего, за сегодня, за 7 дней.
 * Ни адресов, ни имён, ни идентификаторов — ручка публичная, и личным данным
 * в ней делать нечего.
 *
 * 🔴 НАШИ ПРОБЫ СЧИТАЮТСЯ ОТДЕЛЬНО. Мы сами заводим учётки вида smoke-…,
 * probe-… и anonymous, и если смешать их с людьми, счётчик будет показывать
 * рост, которого нет — ровно та ошибка, из-за которой воронка однажды на 91 %
 * состояла из нашей же автоматики. Поэтому у ответа два поля: `люди` и
 * `пробы`, и складывать их обязан читатель, а не ручка.
 *
 * 🔴 БАЗА НЕДОСТУПНА — ЭТО НЕ НОЛЬ. Ноль означает «никто не зарегистрировался»,
 * и отвечать им на неотвеченный вопрос значит врать в самую важную сторону.
 * При отказе базы поля равны null, а `измерено` равно false.
 */
import { Router, type Request, type Response } from "express";
import { getPool } from "../lib/dbPool";

export const publicStatsRouter = Router();

const pool = getPool();

/** Учётки, которые завели МЫ: их нельзя показывать как рост. */
/**
 * Слово-проба ТОЛЬКО с разделителем после него — то же правило, что в
 * `lib/probeRows.ts` для витрин.
 *
 * 🔴 Почему не голый префикс (поправка 30.09.2026 по разбору соседнего окна).
 * Было `ILIKE 'test%'`, и это съедало ЖИВЫХ людей: `testov@…` — обычная фамилия
 * Тестов латиницей, `testing@<компания>` — рабочий ящик отдела тестирования у
 * настоящего клиента. То же по остальным словам: `smokehouse@ресторан`,
 * `probes@лаборатория` — живые адреса.
 *
 * Смещение было в сторону честности (счёт людей ВНИЗ), и это лучше обратного. Но
 * живых заявок у нас единицы, и один потерянный лид — заметная доля.
 *
 * Наши собственные пробы от этого не теряются: мы называем их с разделителем
 * всегда — `smoke-c2-2026-09-29@aevion.app`, `probe-price-30-09@aevion.app`.
 * Проверено на настоящих адресах из журнала проб.
 */
const СЛОВО_ПРОБЫ = (поле: string) =>
  ["smoke", "probe", "test"]
    .flatMap((w) =>
      // Разделители только `-` и `@`, и это НЕ лень, а обход двух ловушек сразу.
      //
      // 1. В `ILIKE` подчёркивание — шаблонный символ (любой один знак), значит
      //    `'smoke_%'` совпало бы с `smokehouse@…` и вернуло ту самую широту,
      //    ради снятия которой правка делается. Экранировать пришлось бы
      //    обратным слэшем — а он на границе «исходник → строка» съедается:
      //    проверено 30.09.2026, в файле лежало два слэша, в значении не было ни
      //    одного (это известный класс, см. CLAUDE.md §2е).
      // 2. Точка в `ILIKE` не шаблон, но оставлять её без пары с подчёркиванием
      //    значит делать признак несимметричным без причины.
      //
      // Наши пробы этим не теряются: мы называем их `smoke-…`, `probe-…` и
      // `test@…` — с дефисом или собакой. Проверено на адресах из журнала проб.
      ["-", "@"].map((р) => `${поле} ILIKE '${w}${р}%'`),
    )
    .join(" OR ");

/**
 * Признак пробы ПО ИМЕНИ ИСТОЧНИКА — второй, не вместо адреса.
 *
 * 🔴 Замер соседнего окна 30.09.2026 на живом проде: признак смотрел только на
 * адрес, и 16 «людей» из 26 (62 %) сидели в источниках, чьё имя прямо говорит,
 * что это наш прогон — `branch-check` 5, `crowd-check` 5, `cyberchess-probe` 2
 * (буквально слово «проба»), `cyberchess-launch-check`, `launch-readiness-check`,
 * `rate-check`, `same-check` по одному. В живые они попали лишь потому, что адрес
 * был правдоподобным. Число живых заявок читает основатель, и завышение вдвое с
 * половиной здесь дороже любой экономии.
 *
 * ⚠️ ПРИВЯЗКА К ГРАНИЦЕ СЛОВА, а не к вхождению, и это главное в этой правке.
 * `%check%` съел бы живой источник `checkout-page` и `checklist` — то есть
 * недооценка вместо переоценки, а её заметить труднее (она выглядит
 * осторожностью). Поэтому четыре формы: слово целиком, `слово-…`, `…-слово`,
 * `…-слово-…`. Подчёркивание в шаблонах не используется: в `ILIKE` это шаблонный
 * символ, экранировать его нечем — обратный слэш съедается на границе
 * «исходник → строка» (CLAUDE.md §2е).
 */
const СЛОВО_В_ИМЕНИ = (поле: string) =>
  ["check", "probe", "smoke", "test"]
    .flatMap((w) => [
      `${поле} ILIKE '${w}'`,
      `${поле} ILIKE '${w}-%'`,
      `${поле} ILIKE '%-${w}'`,
      `${поле} ILIKE '%-${w}-%'`,
    ])
    .join(" OR ");

const ПРОБА =
  `(${СЛОВО_ПРОБЫ('"email"')}` +
  ` OR "email" ILIKE '%@example.com' OR "email" ILIKE '%@test%'` +
  ` OR "name" ILIKE 'anonymous%' OR ${СЛОВО_ПРОБЫ('"name"')})`;

export interface СчётПользователей {
  измерено: boolean;
  люди: { всего: number | null; заСегодня: number | null; за7дней: number | null };
  пробы: { всего: number | null };
  наМомент: string;
  почему?: string;
}

export async function счётЗарегистрированных(): Promise<СчётПользователей> {
  const наМомент = new Date().toISOString();
  try {
    const { rows } = await pool.query(
      `SELECT
         COUNT(*) FILTER (WHERE NOT ${ПРОБА})::int                                            AS люди_всего,
         COUNT(*) FILTER (WHERE NOT ${ПРОБА} AND "createdAt" >= NOW() - INTERVAL '1 day')::int  AS люди_сутки,
         COUNT(*) FILTER (WHERE NOT ${ПРОБА} AND "createdAt" >= NOW() - INTERVAL '7 days')::int AS люди_неделя,
         COUNT(*) FILTER (WHERE ${ПРОБА})::int                                                AS пробы_всего
       FROM "AEVIONUser"
       WHERE "deletedAt" IS NULL`,
    );
    const r = rows[0] ?? {};
    return {
      измерено: true,
      люди: {
        всего: Number(r.люди_всего ?? 0),
        заСегодня: Number(r.люди_сутки ?? 0),
        за7дней: Number(r.люди_неделя ?? 0),
      },
      пробы: { всего: Number(r.пробы_всего ?? 0) },
      наМомент,
    };
  } catch (e) {
    // Молчать здесь нельзя: счётчик, отвечающий нулём на собственную поломку,
    // опаснее отсутствующего счётчика — по нему принимают решения.
    console.error("[stats/users] счёт не удался", e);
    return {
      измерено: false,
      люди: { всего: null, заСегодня: null, за7дней: null },
      пробы: { всего: null },
      наМомент,
      почему: "база не ответила",
    };
  }
}

/** GET /api/stats/users — публично, только числа. */
publicStatsRouter.get("/users", async (_req: Request, res: Response) => {
  const счёт = await счётЗарегистрированных();
  res.status(счёт.измерено ? 200 : 503).json(счёт);
});

/** Заявка, которую завели МЫ. Тот же признак, что у учёток, но по адресу. */
const ПРОБА_ЗАЯВКИ =
  `(${СЛОВО_ПРОБЫ('"email"')}` +
  ` OR "email" ILIKE '%@example.com' OR "email" ILIKE '%@aevion.app'` +
  // Второй признак: имя источника. Адрес и имя врут по-разному, и вместе они
  // закрывают оба случая — правдоподобный адрес в прогоне с говорящим именем и
  // прогон с чужого адреса.
  ` OR ${СЛОВО_В_ИМЕНИ('"source"')})`;

export interface ЗаявкиПоИсточнику {
  измерено: boolean;
  поИсточнику: Record<string, { люди: number; пробы: number }>;
  итого: { люди: number | null; пробы: number | null };
  наМомент: string;
  почему?: string;
}

/**
 * Сколько адресов собрал КАЖДЫЙ модуль — и сколько из них наши пробы.
 *
 * 🔴 Зачем публично. Вопрос «оставил ли модуль хоть одного живого человека»
 * стоит денег: по нему решают, что доделывать и что продавать. До сих пор ответ
 * жил в админской ручке, у которой есть токен прода, и окна выясняли его
 * перепиской. 30.09.2026 соседнее окно спросило «сколько в списке адресов с
 * source=qventure-result, кроме моего?» — и ответить было нечем.
 *
 * Отдаём ТОЛЬКО числа: ни адресов, ни имён. Пробы считаются отдельной колонкой,
 * а не вычитаются молча — читатель обязан видеть оба числа. Замер того же дня:
 * из 113 «пользователей» 108 оказались нашими пробами, и если бы счётчик
 * вычитал их сам, спорить о его правоте было бы нечем.
 *
 * Адреса на нашем домене (`@aevion.app`) считаются пробой по определению:
 * внешним подписчиком такой адрес быть не может.
 */
export async function заявкиПоИсточнику(): Promise<ЗаявкиПоИсточнику> {
  const наМомент = new Date().toISOString();
  try {
    const { rows } = await pool.query(
      `SELECT COALESCE(NULLIF("source", ''), 'unknown') AS источник,
              COUNT(*) FILTER (WHERE NOT ${ПРОБА_ЗАЯВКИ})::int AS люди,
              COUNT(*) FILTER (WHERE ${ПРОБА_ЗАЯВКИ})::int     AS пробы
         FROM constitution_waitlist
        GROUP BY 1
        ORDER BY 2 DESC, 1 ASC`,
    );
    const поИсточнику: Record<string, { люди: number; пробы: number }> = {};
    let людиВсего = 0;
    let пробыВсего = 0;
    for (const r of rows) {
      const люди = Number(r.люди ?? 0);
      const пробы = Number(r.пробы ?? 0);
      поИсточнику[String(r.источник)] = { люди, пробы };
      людиВсего += люди;
      пробыВсего += пробы;
    }
    return { измерено: true, поИсточнику, итого: { люди: людиВсего, пробы: пробыВсего }, наМомент };
  } catch (e) {
    // Тот же принцип, что у счёта учёток: пустой разрез вместо отказа читался бы
    // как «ни один модуль не собрал никого», а это решение о деньгах.
    console.error("[stats/leads] разрез не удался", e);
    return {
      измерено: false,
      поИсточнику: {},
      итого: { люди: null, пробы: null },
      наМомент,
      почему: "база не ответила",
    };
  }
}

publicStatsRouter.get("/leads-by-source", async (_req, res) => {
  const ответ = await заявкиПоИсточнику();
  res.status(ответ.измерено ? 200 : 503).json(ответ);
});
