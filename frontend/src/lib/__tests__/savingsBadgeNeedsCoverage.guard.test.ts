/*
 * Значок экономии молчит, пока охват мал или неизвестен.
 *
 * 🔴 Замер прода 01.10.2026, GET /api/qcoreai/smart/savings:
 *     runs 145, экономия записана у 3 вызовов,
 *     показывали «сэкономлено $0.23 = 2.05 %»,
 *     а собственные поля того же ответа давали $9.56 = 85.7 % —
 *     расхождение 41.7 раза, потому что знаменатель брал ВСЕ вызовы,
 *     а числитель приходил с трёх.
 * Значок при этом стоял в шапке КАЖДОЙ страницы, включая /pricing, где мы
 * просим $400 в месяц: первое денежное число, которое видел покупатель, —
 * двадцать три цента.
 *
 * Сторож проверяет ПОВЕДЕНИЕ решающей функции на всех трёх исходах, а не
 * наличие порога в тексте: порог может стоять в коде и не применяться.
 */
import { describe, expect, it } from "vitest";
import { МИН_ОХВАТ_ДЛЯ_ПОКАЗА, счётчикГоденДляПоказа, type AiSavings } from "../aiSavings";

/** Ответ ровно той формы, что приходит с прода. */
function ответ(над: Partial<AiSavings>): AiSavings {
  return {
    runs: 145,
    facts: 145,
    light: 0,
    deep: 0,
    totalCostUsd: 1.6019,
    estAlwaysCouncilUsd: 0.231,
    savedUsd: 0.2293,
    savedPct: 99.2,
    ...над,
  };
}

describe("значок экономии требует охвата", () => {
  it("порог назван числом и он не бутафорский", () => {
    expect(МИН_ОХВАТ_ДЛЯ_ПОКАЗА).toBeGreaterThan(1);
    expect(Number.isFinite(МИН_ОХВАТ_ДЛЯ_ПОКАЗА)).toBe(true);
  });

  it("ЗАМЕР 01.10 (охват 3 из 145) — молчим", () => {
    expect(счётчикГоденДляПоказа(ответ({ runsCompared: 3 }))).toBe(false);
  });

  it("охват НЕИЗВЕСТЕН (старый сервер без поля) — тоже молчим", () => {
    // Три исхода, а не два: «не знаю» нельзя превращать в «можно».
    const без = ответ({});
    delete (без as Partial<AiSavings>).runsCompared;
    expect(счётчикГоденДляПоказа(без)).toBe(false);
  });

  it("ответа нет вовсе — молчим", () => {
    expect(счётчикГоденДляПоказа(null)).toBe(false);
  });

  it("контроль в ОБРАТНУЮ сторону: достаточный охват — показываем", () => {
    // Без этого контроля сторож проходил бы и на функции, которая всегда
    // отвечает «нельзя», то есть на навсегда погашенном значке.
    expect(счётчикГоденДляПоказа(ответ({ runsCompared: МИН_ОХВАТ_ДЛЯ_ПОКАЗА }))).toBe(true);
    expect(счётчикГоденДляПоказа(ответ({ runsCompared: МИН_ОХВАТ_ДЛЯ_ПОКАЗА + 1000 }))).toBe(true);
  });

  it("граница проверена с обеих сторон, а не только внутри", () => {
    expect(счётчикГоденДляПоказа(ответ({ runsCompared: МИН_ОХВАТ_ДЛЯ_ПОКАЗА - 1 }))).toBe(false);
    expect(счётчикГоденДляПоказа(ответ({ runsCompared: 0 }))).toBe(false);
  });
});
