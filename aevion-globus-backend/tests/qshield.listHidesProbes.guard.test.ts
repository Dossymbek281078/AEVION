import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Общий список щитов не отдаёт наши служебные записи.
 *
 * ЗАЧЕМ. Правило §19: создающий запрос на прод помечается в названии и
 * убирается следом. Замер 28.09.2026 показал, что «убрать» — не одно действие.
 * Конвейер `/api/pipeline/protect` пишет сразу в несколько мест: у QRight
 * скрытие ВСТРОЕНО в выдачу витрины (`ownerName = 'smoke-test'`), и там пробы
 * не было, а сюда запись уезжает БЕЗ поля владельца — только с `objectTitle`.
 * Моя собственная проба «probe-28-09 …» висела в публичном списке, 1 из 7.
 *
 * Я проверил витрину QRight, увидел ноль и счёл уборку сделанной. У одной
 * записи столько витрин, сколько модулей её увидели.
 *
 * Почему фильтр в РУЧКЕ, а не только на странице: список читает не одна наша
 * страница. Сторож целей поста, любой сторонний клиент и наш же следующий
 * модуль получают то же самое. Фильтр на стороне страницы прячет пробу от
 * посетителя, но не от них.
 *
 * ГРАНИЦА: это фильтр ВЫДАЧИ, а не удаление. Запись остаётся в базе и по
 * прямой ссылке `/records/:id` открывается — прятать от общего списка можно,
 * стирать данные по эвристике имени нельзя. И при `?mine=1` фильтра нет
 * намеренно: там человек смотрит свои записи, включая пробные.
 */

const SRC = readFileSync(
  join(__dirname, "..", "src", "routes", "quantum-shield.ts"),
  "utf8",
);

describe("список щитов прячет служебные записи", () => {
  it("контроль: файл прочитан и это нужный маршрут", () => {
    expect(SRC.length).toBeGreaterThan(5000);
    expect(SRC).toContain("handleList");
  });

  it("обе наши метки исключены", () => {
    // Одной мало: §19 разрешает и `smoke-`, и `probe-`, и пишут их разные окна.
    expect(SRC).toContain("NOT ILIKE 'probe-%'");
    expect(SRC).toContain("NOT ILIKE 'smoke-%'");
  });

  it("запись без названия НЕ прячется", () => {
    /*
     * `NULL NOT ILIKE ...` в SQL даёт NULL, то есть строка отсеивается. Без
     * явного `IS NULL` мы бы тихо потеряли все записи без названия — чужие,
     * настоящие. Это половина важнее первой: слишком жадный фильтр обедняет
     * витрину, и заметить это некому.
     */
    expect(SRC).toContain('"objectTitle" IS NULL OR');
  });

  it("фильтр применён к ОБЩЕМУ списку, а не к своему", () => {
    // При ?mine=1 человек смотрит свои записи, включая пробные: прятать их от
    // владельца незачем, и подмена условия здесь была бы дефектом.
    expect(SRC).toContain("where = `WHERE ${СЛУЖЕБНОЕ}`");
  });
});
