import { redirect } from "next/navigation";

import { меткаДляПерехода } from "@/lib/shortEntry";

import type { Metadata } from "next";

// Метаданные обязательны у каждой публичной страницы (сторож pageMetadata), и у
// перенаправления они закрывают его от поисковика: короткий адрес — вход для
// человека из объявления, а не страница, и в выдаче ему делать нечего.
export const metadata: Metadata = {
  title: { absolute: "AEVION" },
  robots: { index: false, follow: true },
};

/*
 * /meta — короткий вход для платной рекламы Meta.
 *
 * ЗАЧЕМ ОН ПОЯВИЛСЯ ИМЕННО СЕЙЧАС. Волна 23 завела в каталоге метку `meta`
 * (платная кампания размечается ТОЛЬКО как `meta-*`, а `fb-*` остаётся
 * органическим facebook — иначе окупаемость платного и бесплатного склеится).
 * Но входа у метки не было, и это поймали сразу два сторожа:
 * everyChannelHasShortEntry («нет короткого адреса /meta — ссылка в объявлении
 * даст 404») и shortChannelUrls («у каждой метки каталога есть короткий вход»).
 * Связь держат в обе стороны намеренно: метка без входа — это ссылка в рекламе,
 * ведущая в 404, а вход без метки — переход, падающий в «прямые».
 *
 * КУДА ВЕДЁТ И ПОЧЕМУ. На страницу книги: реклама Meta запускается под книгу за
 * $9.99 (разметка кампаний `meta-book-<кампания>`), и вести объявление надо на
 * то, что в нём обещано, а не на общий вход. Та же причина, по которой /hn ведёт
 * на страницу DevHub, а не на /go.
 *
 * Сами объявления понесут полную метку (`?c=meta-book-<кампания>`) прямо в
 * адресе; этот короткий вход нужен для случаев, когда адрес набирают руками или
 * ставят в профиль, и для того, чтобы метка каталога не осталась без двери.
 *
 * Никакой логики здесь нет и быть не должно — только перенаправление.
 * Исключение на ветвление есть ровно у /example, и оно оплачено поведенческим
 * сторожем (см. shortChannelUrls.guard).
 */
export const dynamic = "force-dynamic";

export default async function Page({
  searchParams,
}: {
  searchParams: Promise<{ c?: string | string[] }>;
}) {
  const метка = меткаДляПерехода((await searchParams).c, "meta");
  if (метка !== "meta") redirect(`/longevity?c=${метка}`);
  redirect("/longevity?c=meta");
}
