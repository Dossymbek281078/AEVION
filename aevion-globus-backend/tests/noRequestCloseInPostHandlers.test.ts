/**
 * В POST-обработчиках нельзя слушать `close` у ЗАПРОСА.
 *
 * 🔴 ЦЕЛЫЙ КЛАСС, найденный 30.09.2026 в день запуска шахмат. В Node событие
 * `close` у запроса срабатывает и при обычном, ПОЛНОМ его прочтении — не
 * только когда клиент ушёл. У POST с телом это происходит раньше, чем
 * поставщик пришлёт первый токен. Если обработчик вешает на это событие флаг
 * «клиент ушёл», а потом гасит им выдачу, человек получает пустой поток: код
 * 200, корректный `message_stop`, ни одной ошибки. Ровно так тренер отдавал
 * КАЖДОМУ 31 байт, и никто не замечал, потому что фронт молча переспрашивал.
 *
 * Замер, отделяющий POST от GET (голый express, это же окружение):
 *   POST с телом — reqClose=true уже через 60 мс, до первого кадра;
 *   GET без тела  — reqClose=false, событие приходит только в конце.
 * Поэтому запрет здесь только для POST/PUT/PATCH.
 *
 * И почему запрет, а не «где сломалось». Из четырёх POST-маршрутов с этим
 * образцом сломан был один. Остальные держались на СЛУЧАЙНОСТИ: между
 * разбором тела и навешиванием слушателя у них есть await, и событие успевало
 * пройти раньше. Проверено в обе стороны на больном коде тренера: вставил
 * один await перед слушателем — дефект исчез, убрал — вернулся. То есть
 * здоровье этих маршрутов ломается перестановкой строк, молча.
 *
 * Правильно: `res.on("close")` — закрытие ОТВЕТА и значит «клиент ушёл».
 */
import { describe, test, expect } from "vitest";
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";

const КАТАЛОГ = join(__dirname, "..", "src", "routes");

/** Снять комментарии: иначе объяснение ПРО запрет само его нарушает. */
function безКомментариев(src: string): string {
  let out = "";
  let i = 0;
  while (i < src.length) {
    const два = src.slice(i, i + 2);
    if (два === "/*") { const к = src.indexOf("*/", i + 2); i = к < 0 ? src.length : к + 2; continue; }
    if (два === "//" && src[i - 1] !== ":") { const к = src.indexOf(String.fromCharCode(10), i); i = к < 0 ? src.length : к; continue; }
    out += src[i]; i += 1;
  }
  return out;
}

/** Метод ближайшего объявления маршрута ВЫШЕ этой позиции. */
function методВыше(код: string, позиция: number): string | null {
  const до = код.slice(0, позиция);
  const объявления = [...до.matchAll(/\.\s*(get|post|put|patch|delete)\s*\(\s*["'`]/g)];
  const последнее = объявления[объявления.length - 1];
  return последнее ? последнее[1].toLowerCase() : null;
}

function нарушения(): Array<{ файл: string; строка: number; метод: string }> {
  const итог: Array<{ файл: string; строка: number; метод: string }> = [];
  for (const имя of readdirSync(КАТАЛОГ)) {
    if (!имя.endsWith(".ts")) continue;
    const код = безКомментариев(readFileSync(join(КАТАЛОГ, имя), "utf8"));
    for (const m of код.matchAll(/req\s*\.\s*on\s*\(\s*["'`]close["'`]/g)) {
      const метод = методВыше(код, m.index ?? 0);
      if (метод === "post" || метод === "put" || метод === "patch") {
        итог.push({ файл: имя, строка: код.slice(0, m.index).split(String.fromCharCode(10)).length, метод });
      }
    }
  }
  return итог;
}

describe("слушатель close в POST-обработчиках", () => {
  test("прибор исправен: находит запрещённое и не считает комментарий кодом", () => {
    const образец = 'router.post("/x", (req,res)=>{ req.on("close", ()=>{}); });';
    expect(методВыше(образец, образец.indexOf("req.on"))).toBe("post");
    expect(безКомментариев('a // req.on("close"\nb')).not.toContain("req.on");
    expect(безКомментариев('/* req.on("close") */ b')).not.toContain("req.on");
    // GET не запрещаем — у него событие приходит в конце, это замерено
    const гет = 'router.get("/y", (req,res)=>{ req.on("close", ()=>{}); });';
    expect(методВыше(гет, гет.indexOf("req.on"))).toBe("get");
  });

  test("🔴 ни один POST-обработчик не слушает close у запроса", () => {
    const плохие = нарушения();
    expect(
      плохие.map((н) => `${н.файл}:${н.строка} (${н.метод})`),
      "в POST-обработчике слушается close ЗАПРОСА: он срабатывает при обычном " +
        "дочитывании тела, флаг «клиент ушёл» погаснет до первого кадра и поток " +
        "уйдёт пустым при коде 200. Слушайте res.on(\"close\").",
    ).toEqual([]);
  });

  test("контроль: знаменатель назван — файлы маршрутов действительно прочитаны", () => {
    const файлов = readdirSync(КАТАЛОГ).filter((и) => и.endsWith(".ts")).length;
    expect(файлов, "каталог маршрутов пуст — проверка смотрит не туда").toBeGreaterThan(20);
  });
});
