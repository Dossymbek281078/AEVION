import { describe, expect, test } from "vitest";
import { CITY } from "../src/routes/qskyway.city";
import { CITY_NYC } from "../src/routes/qskyway.city.nyc";
import { CITY_TOKYO } from "../src/routes/qskyway.city.tokyo";
import { NOFLY } from "../src/routes/qskyway.zones";

/**
 * У каждого города каталога есть запись о запретных зонах.
 *
 * ПОВОД (29.08.2026). Список городов публикует `noFlyZones:
 * (NOFLY[id] ?? []).length`. Тип `Record<string, NoFlyZone[]>` НЕ требует,
 * чтобы запись была у каждого города: добавят новый — соберётся молча и
 * опубликует «зон: 0», то есть «летайте где хотите».
 *
 * Это не сегодняшний дефект (все три города записи имеют), а ловушка
 * будущего: она срабатывает ровно в момент расширения на новый город,
 * когда никто не смотрит на счётчик зон.
 *
 * Типом это закрывалось бы строже, но `CITIES` объявлен как
 * `Record<string, CityData>`, и переход на точные ключи каскадом задевает
 * полтора десятка мест. Проверка ловит тот же случай ценой одной строки.
 *
 * ⚠️ Список городов здесь ПОВТОРЁН намеренно: импортировать `CITIES` из
 * `qskyway.ts` значит поднять весь роутер со всеми его побочными
 * эффектами. Цена повтора — эта проверка не заметит город, добавленный
 * только в `CITIES`; поэтому вторая проверка следит за длиной списка.
 */
const CATALOGUE: Record<string, unknown> = {
  astana: CITY,
  nyc: CITY_NYC,
  tokyo: CITY_TOKYO,
};

describe("каталог городов и данные о зонах не расходятся", () => {
  test("у каждого города есть запись о запретных зонах", () => {
    const missing = Object.keys(CATALOGUE).filter((id) => !Array.isArray(NOFLY[id]));
    expect(
      missing,
      "город без записи о зонах опубликует «зон: 0» — это читается как «ограничений нет»: " +
        JSON.stringify(missing),
    ).toEqual([]);
  });

  test("городов ровно столько, сколько знает эта проверка", () => {
    // Отрицательный контроль к повтору списка выше: если город добавят в
    // каталог и забудут здесь, первая проверка промолчит. Число сверяем
    // с реальным экспортом зон — он растёт вместе с городами.
    expect(Object.keys(CATALOGUE).length, "список городов в проверке разошёлся с каталогом").toBe(3);
    expect(Object.keys(NOFLY).length, "городов с зонами стало больше, чем знает проверка").toBeGreaterThanOrEqual(3);
  });
});
