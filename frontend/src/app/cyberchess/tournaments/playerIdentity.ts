/**
 * Личность игрока для турниров — один источник на обе страницы.
 *
 * Раньше эти две функции жили внутри `tournaments/[id]/page.tsx` и наружу не
 * отдавались, поэтому список турниров регистрировал ПУСТЫМ телом: сервер в
 * таком случае выдаёт `anon_…`, место в турнире занимается, а связать его с
 * живым человеком уже нечем — и билет, который сервер теперь хранит, оказывался
 * записан на этот одноразовый id. Записавшись со списка, игрок не находил себя
 * ни в участниках, ни по билету.
 *
 * Ключи здесь ровно те же, что были: перенос без изменения поведения.
 *
 * СВЕДЕНО К ОДНОМУ КЛЮЧУ 19.08.2026. Раньше здесь жил `cc_user_id`, а задача
 * дня, таблица лидеров, история и матчмейкинг читали `cyberchess.userId` — то
 * есть один человек был в турнирах и в остальном модуле ДВУМЯ разными игроками.
 *
 * Почему выбран `cyberchess.userId`, а не наоборот: он не локальная выдумка, а
 * личность платформы. При входе в общий аккаунт главная страница перезаписывает
 * его настоящим id пользователя (`localStorage.setItem("cyberchess.userId",
 * u.id)`), и серверные рейтинг с историей следуют за человеком между
 * устройствами. Ключ `cc_user_id` за аккаунтом не следовал никогда.
 *
 * Почему это стало можно сделать. Прежде здесь стояла пометка «переназначит
 * личность всем, у кого есть история, — решение, а не уборка». Опасение
 * проверено запросом к боевой базе: в 12 турнирах **ноль** записей о
 * регистрации (`registeredUserIds` пуст везде), а пишет туда именно
 * регистрация — `cyberchessTournaments.ts:1072`. Терять некому.
 *
 * `cc_user_id` остаётся как запасное чтение: если он у кого-то лежит, а
 * платформенного нет, человек сохраняет свой id и не превращается в нового
 * игрока. Записываем только в платформенный.
 */

import { readDisplayName } from "../displayName";

/** Личность платформы: при входе в аккаунт сюда кладётся настоящий id. */
const USER_ID_KEY = "cyberchess.userId";
/** Прежний турнирный ключ. Только читается — ради тех, у кого он уже есть. */
const LEGACY_USER_ID_KEY = "cc_user_id";

/** Постоянный id игрока в этом браузере. Создаётся при первом обращении. */
export function tournamentUserId(): string {
  if (typeof window === "undefined") return `anon_${Math.random().toString(36).slice(2, 10)}`;
  let id: string | null = null;
  try {
    id = window.localStorage.getItem(USER_ID_KEY) || window.localStorage.getItem(LEGACY_USER_ID_KEY);
  } catch {
    // приватный режим — работаем без сохранения
  }
  if (!id) {
    id = `u_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 8)}`;
    try {
      window.localStorage.setItem(USER_ID_KEY, id);
    } catch {
      // ignore
    }
  }
  return id;
}

/**
 * Отображаемое имя. Пустая строка означает «пусть сервер придумает сам».
 *
 * Читает через `readDisplayName()` из `../displayName`, а не сам: там же
 * лежат ПРЕЖНИЕ названия ключа (`cc_display_name`, `aevion_user_display_name`),
 * под которыми имя сохранилось у тех, кто играл раньше. Своё чтение одного
 * ключа теряло бы их имя молча — хуже исходной поломки.
 */
export function tournamentDisplayName(): string {
  return readDisplayName();
}

/**
 * Личность, если она УЖЕ есть. Пустая строка — «не знаю».
 *
 * Отдельная функция нужна потому, что просмотр таблицы лидеров или истории не
 * должен ЗАВОДИТЬ игрока: зашедший посмотреть получал бы id и попадал в счёт
 * наравне с играющими. Эти страницы спрашивают «кто я, если известно», и ответ
 * «не знаю» для них законный.
 */
export function knownUserId(): string {
  if (typeof window === "undefined") return "";
  try {
    return window.localStorage.getItem(USER_ID_KEY) || window.localStorage.getItem(LEGACY_USER_ID_KEY) || "";
  } catch {
    return "";
  }
}
