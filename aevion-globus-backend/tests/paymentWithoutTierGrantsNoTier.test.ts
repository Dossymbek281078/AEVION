import { describe, it, expect } from "vitest";
import { tierForReference, ссылкаПодписки } from "../src/routes/payboxWebhook";

/**
 * Платёж, который тарифом не является, тарифа и не получает.
 *
 * 🔴 НАЙДЕНО 04.09.2026 проверкой условия, которое оставил прежний автор.
 * Он написал в файле: дефолт `lite` для незнакомой ссылки безопасен, «пока
 * номер заказа делает payboxProvider… но стоит кому-нибудь строить его
 * иначе — незнакомый заказ пойдёт сюда, и человек получит САМЫЙ ДЕШЁВЫЙ
 * тариф за любую сумму».
 *
 * Условие выполнено. Второй путь оплаты (`routes/payments.ts` →
 * POST /paybox/init) строит номер как `aevion-<время>-<id>`, а разбор
 * снимает только хвост `_цифры`. Ссылка не распознаётся. При этом сам путь
 * принимает «сумму и валюту» и тарифа НЕ ЗНАЕТ — то есть произвольный
 * платёж выдавал бы подписку.
 *
 * Класс не теоретический: у Gumroad по такому же пути прошли ТРИ настоящие
 * продажи книг (27 и 29 мая, 2 июня) — покупка файла за $9.99 выдавала
 * платный тариф.
 *
 * ГРАНИЦА. Дефолт `lite` для подписочных ссылок СОХРАНЁН: менять выдачу
 * тарифов вслепую нельзя, и прежний автор был прав. Меняется только случай,
 * когда ссылка тарифом не является.
 */

describe("разбор тарифа из ссылки заказа", () => {
  it("контроль: подписочные ссылки ОПОЗНАЮТСЯ как подписочные", () => {
    // Иначе «произвольный платёж не похож на подписку» проходило бы и на
    // предикате, который всегда false, — то есть сломало бы все покупки.
    expect(ссылкаПодписки("tier_medium_monthly")).toBe(true);
    expect(ссылкаПодписки("tier_lite_monthly")).toBe(true);
  });

  it("контроль: подписочные ссылки по-прежнему разбираются", () => {
    // Без этого контроля можно было бы «починить» всё в отказ и не заметить.
    expect(tierForReference("tier_medium_monthly")).toBe("medium");
    expect(tierForReference("tier_full_annual")).toBe("full");
    expect(tierForReference("tier_lite_monthly")).toBe("lite");
  });

  it("незнакомая подписочная ссылка по-прежнему даёт lite", () => {
    // Прежнее поведение сохранено намеренно: у этой ветки своя история и
    // свои основания, трогать её без нужды нельзя.
    expect(tierForReference("tier_pro_monthly")).toBe("pro");
  });

  it("номер второго пути оплаты НЕ похож на подписку", () => {
    // Ровно та строка, которую строит POST /paybox/init.
    const ссылка = "aevion-1757000000000-ab12cd34";
    expect(
      ссылкаПодписки(ссылка),
      "произвольный платёж принят за покупку подписки — человек получит тариф за любую сумму",
    ).toBe(false);
  });

  it("ссылка оплаты бюро тоже не похожа на подписку", () => {
    // Бюро подставляет идентификатор проверки и узнаёт об оплате САМО,
    // опрашивая провайдера. Тариф ему не нужен и не должен выдаваться.
    expect(ссылкаПодписки("bureau_7f3a91")).toBe(false);
  });


  it("слово тарифа ВНУТРИ другого слова подпиской не считается", () => {
    // Находка при вычитке собственного дифа 04.09. Предикат искал слова где
    // угодно в строке, поэтому «promo» содержал «pro», «proforma» — тоже. Такая
    // ссылка проходила как подписочная, тариф из неё не разбирался и уходил в
    // умолчание — то есть выдавался lite. Ровно тот дефект, который я этим
    // предикатом и закрывал; он пережил починку внутри неё самой.
    //
    // Проба на живом коде до правки: promo-2026-09 -> ПОДПИСКА -> выдаём lite.
    for (const ссылка of ["promo-2026-09", "proforma-118", "profile-77", "teamwork-3"]) {
      expect(
        ссылкаПодписки(ссылка),
        `"${ссылка}" принята за подписку: слово тарифа найдено внутри другого слова, 
          и человек получит доступ за платёж, который подпиской не был`,
      ).toBe(false);
    }
  });

  it("контроль: настоящие подписочные ссылки границей не сломаны", () => {
    // Сузив правило, легко отсечь законное. Здесь проверяются все формы,
    // которые касса и каталог действительно порождают.
    for (const ссылка of ["tier_pro_monthly", "tier_all-access_annual", "team_annual", "full-2026", "lite"]) {
      expect(ссылкаПодписки(ссылка), `законная ссылка "${ссылка}" перестала опознаваться`).toBe(true);
    }
  });
});
