import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { stripComments } from "./_stripComments";

/* Таблица лидеров задачи дня. 12.08.2026.
 *
 * Две разные нечестности на одном экране, обе из тех, что выглядят как норма.
 *
 * 1. Отказ сервера превращался в утверждение. При `!r.ok` и при исключении
 *    страница ставила пустой список, а пустой список подписан словами «Пока
 *    никто не решал — таблица пустая. Реши сегодняшнюю задачу, и первая строка
 *    будет твоей». Это заявление обо ВСЕХ игроках, полученное из запроса,
 *    который не выполнился.
 *
 * 2. Числа в таблице — самооценка. Серию, время и подсказки присылает браузер
 *    игрока; сервер их ограничивает разумными рамками, но проверить не может —
 *    в отчёте о решении нет ходов. Об этом честно сказано в комментарии
 *    бэкенда и не было сказано человеку, который смотрит на таблицу.
 */

const PAGE = "src/app/cyberchess/daily/page.tsx";
const src = stripComments(readFileSync(PAGE, "utf8"));

describe("таблица лидеров дня не выдаёт отказ за пустоту", () => {
  it("у неудачной загрузки своё состояние, а не пустой список", () => {
    expect(src).toMatch(/standingsFailed/);
  });

  it("на отказе сказано, что таблица не пуста, а недоступна", () => {
    expect(src).toMatch(/не удалось загрузить/i);
    expect(src).toMatch(/не значит, что она пустая/i);
  });

  it("текст «никто не решал» показывается только при успешном ответе", () => {
    /* Иначе починка наполовину: состояние есть, а старая фраза по-прежнему
       выводится на том же условии. */
    expect(src).toMatch(/leaderboard !== null && !standingsFailed && leaderboard\.length === 0/);
  });

  it("успешный пустой ответ остаётся пустым, а не ошибкой", () => {
    /* Обратная сторона: сторож не должен превратить нормальный пустой ответ в
       отказ — иначе первый игрок дня увидит поломку вместо приглашения. */
    expect(src).toMatch(/setStandingsFailed\(false\)/);
  });
});

describe("таблица лидеров дня называет происхождение чисел", () => {
  it("сказано, что серии присылают сами игроки", () => {
    expect(src).toMatch(/игроки отправляют сами/i);
  });

  it("сказано и то, что сервер их не перепроверяет", () => {
    /* «Отправляют сами» человек может прочитать как «сервер потом сверяет».
       Важна вторая половина. */
    expect(src).toMatch(/не перепроверя/i);
  });
});
