/**
 * След оплаты: чем возврат из кассы отличается от простого захода.
 *
 * Адреса `/pricing/checkout/success` и `/pricing/checkout/cancel` публичные. Их
 * открывает бот, поисковик, любопытный, человек, которому переслали ссылку.
 * Оба экрана слали своё событие БЕЗУСЛОВНО, при любом открытии.
 *
 * Для покупки это прямая ложь в деньгах: заход считался покупкой и в сводке, и
 * (при включённой рекламе) в Purchase для площадок. Для отказа тише, но хуже
 * по-своему: покупки я отфильтровал, а отказы остались бы завышенными — и
 * ОТНОШЕНИЕ, то есть видимая доля доводящих оплату до конца, стало бы хуже
 * настоящего. По такому числу принимают решение «воронка плохая, надо чинить»,
 * и чинили бы несуществующее.
 *
 * Признак один на оба экрана НАМЕРЕННО: два разных правила для одной пары чисел
 * разъедутся молча, и сверить их будет нечем.
 *
 * Пропускать он обязан ВСЕ четыре кассы:
 *   PayBox        ?paybox=1&ref=…     — провайдер и ссылка на заказ;
 *   PayPal        ?paypal=1&ref=…     — то же;
 *   Gumroad       ?gumroad=true&…     — провайдер (или sale_id);
 *   LemonSqueezy  ?tier=…&total=4900  — провайдера НЕТ, но есть сумма.
 * Голый заход не несёт ни одного из трёх признаков.
 */
export type СледОплаты = {
  /** Имя кассы, если её удалось опознать по адресу возврата. */
  provider?: string | null;
  /** Ссылка на заказ или сессию: ref, sale_id, session_id. */
  ref?: string | null;
  /** Сумма из адреса возврата, в долларах. */
  total?: number | null;
  /** Возврат заглушки — это тоже настоящий проход по пути оплаты. */
  stub?: boolean;
};

/*
 * ПОЧЕМУ «СУММА» ОСТАЁТСЯ ПРИЗНАКОМ, хотя по ней можно подделать след.
 *
 * Замер 03.09.2026: каждая из четырёх касс опознаётся ЯВНОЙ меткой —
 * `?paypal=1`, `?paybox=1`, `?sale_id` у Gumroad, `?provider=lemonsqueezy`
 * (последнюю стал ставить общий помощник адреса успеха). То есть для
 * настоящего возврата признак «сумма» уже не нужен ни одному провайдеру, и
 * убрав его, мы закрыли бы поверхность: заход по подобранному адресу
 * `?total=4900` сейчас засчитывается как покупка.
 *
 * И всё-таки НЕ убираю. Ссылки возврата уже уходили покупателям в прежнем
 * виде; возврат, начатый до выкатки, придёт без метки кассы, и ужесточение
 * потеряет НАСТОЯЩУЮ покупку. Потеря настоящей дороже лишней: подделанный
 * след виден только в панели «ожидаемая выручка», которая так и названа и
 * считается по сообщениям браузера, а «фактически списано» берётся из записей
 * вебхука и подделке недоступна.
 *
 * Убирать — когда пройдёт срок жизни ссылок возврата после выкатки, и тогда
 * одним движением: `p.total` из условия, а не «ужесточить заодно».
 */
export function естьСледОплаты(p: СледОплаты): boolean {
  return (
    Boolean(p.provider) ||
    Boolean(p.ref) ||
    // Ноль суммы следом не считается: у бесплатного возврата Gumroad total=0,
    // и он не должен выглядеть оплатой.
    (typeof p.total === "number" && p.total > 0) ||
    Boolean(p.stub)
  );
}
