import { describe, it, expect } from "vitest";
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

/**
 * «Пусто» и «не смогли спросить» — разные ответы, и экран обязан их различать.
 *
 * Замер 01.09.2026 на живом проде: адрес `/api/payments/v1` отвечает 404 (ручки
 * есть в сборке, сайт выкачен старее). При этом страница споров писала
 * посетителю «No disputes yet», а страница аудита — «No audit entries yet».
 *
 * Обе утверждали факт О ДАННЫХ, которых ни разу не получили. Отказ и пустота
 * выглядели одинаково, и человек верил более уверенному: делал вывод, что
 * возможности нет вовсе.
 *
 * ⚠️ Правка полезна и ПОСЛЕ выкатки, поэтому сторож не временный: сервис может
 * лечь и потом, а страница снова скажет «споров нет».
 */

const СТРАНИЦЫ = [
  { имя: "disputes", путь: ["..", "disputes", "page.tsx"], пусто: "No disputes yet" },
  { имя: "audit", путь: ["..", "audit", "page.tsx"], пусто: "No audit entries yet" },
];

describe("страницы платежей не выдают незнание за пустоту", () => {
  for (const с of СТРАНИЦЫ) {
    const файл = join(__dirname, ...с.путь);

    it(`контроль: страница ${с.имя} читается и имеет пустое состояние`, () => {
      // Без контроля «ветка отказа найдена» была бы зелёной и на пустом файле.
      expect(existsSync(файл), `нет файла страницы ${с.имя}`).toBe(true);
      const src = readFileSync(файл, "utf8");
      expect(src.length).toBeGreaterThan(2000);
      expect(src, "пустое состояние исчезло — сторож смотрит не туда").toContain(с.пусто);
    });

    it(`${с.имя}: отказ показывается ОТДЕЛЬНО от пустоты`, () => {
      const src = readFileSync(файл, "utf8");
      expect(
        src.includes("спросили === false"),
        "экран не различает «не смогли спросить» и «нет записей»",
      ).toBe(true);
      // И ветка отказа обязана стоять РАНЬШЕ пустой: иначе она недостижима,
      // а проверка выше осталась бы зелёной. Тот же порядок, что у подписи
      // валюты на странице цен.
      /*
       * Ищем в КОДЕ, а не в пояснениях. Мой собственный комментарий над
       * состоянием цитирует ту же фразу «No disputes yet», и наивный поиск
       * находил её первой — сторож объявлял ветку отказа недостижимой на
       * верной работе.
       *
       * Третий случай этого класса за день: свой комментарий попадает под свой
       * же шаблон. Признак опасности — рядом с починкой написано длинное
       * объяснение, и оно повторяет искомые слова.
       */
      const строки = src.split(String.fromCharCode(10));
      const кода = строки.map((l) => {
        const t = l.trim();
        return t.startsWith("*") || t.startsWith("//") || t.startsWith("/*") ? "" : l;
      });
      const отказ = кода.findIndex((l) => l.includes("спросили === false"));
      const пусто = кода.findIndex((l) => l.includes(с.пусто));
      expect(отказ).toBeGreaterThan(-1);
      expect(пусто).toBeGreaterThan(-1);
      expect(
        отказ,
        "ветка отказа стоит ПОСЛЕ пустой — значит недостижима",
      ).toBeLessThan(пусто);
    });

    it(`${с.имя}: состояние ставится в ОБЕ стороны, а не только при отказе`, () => {
      // Если ставить только false, «спросили» навсегда остаётся ложным после
      // первого сбоя, и успешное обновление продолжит показывать ошибку.
      const src = readFileSync(файл, "utf8");
      expect(src).toContain("setСпросили(false)");
      expect(src, "успех не отмечается — экран застрянет на сообщении об отказе")
        .toContain("setСпросили(true)");
    });
  }
});
