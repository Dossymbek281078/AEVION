/**
 * Простой заход на «оплата принята» — не покупка.
 *
 * Адрес публичный: его открывает бот, поисковик, любопытный, человек, которому
 * переслали ссылку. Событие отправлялось безусловно, и каждый такой заход шёл в
 * сводку «покупки по каналам», а при включённой рекламе — в Purchase для Meta и
 * TikTok. По этим числам решают, куда тратить бюджет; завышение выглядит как
 * успех и подталкивает платить за канал, который ничего не заработал.
 *
 * Признак должен пропускать ВСЕ четыре кассы и не пропускать голый заход.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stripComments } from "../../../../__tests__/helpers/sourceCode";
import { естьСледОплаты as следОплаты } from "@/lib/paymentTrace";

describe("след оплаты", () => {
  it("голый заход покупкой не считается", () => {
    expect(следОплаты({})).toBe(false);
  });

  it("возврат каждой из четырёх касс распознаётся", () => {
    expect(следОплаты({ provider: "paybox", ref: "abc" }), "PayBox").toBe(true);
    expect(следОплаты({ provider: "paypal", ref: "abc" }), "PayPal").toBe(true);
    expect(следОплаты({ provider: "gumroad" }), "Gumroad").toBe(true);
    // У LemonSqueezy в адресе НЕТ провайдера — только tier/period/total.
    expect(следОплаты({ total: 49 }), "LemonSqueezy").toBe(true);
  });

  it("бесплатный возврат Gumroad не выдаёт себя за покупку суммой", () => {
    // total=0 — признак не должен срабатывать ПО СУММЕ; провайдер там есть,
    // и покупкой это не станет уже ниже по цепочке, по правилу «ноль — не покупка».
    expect(следОплаты({ total: 0 })).toBe(false);
  });

  it("отказ не считается дважды: защёлка на месте", () => {
    // В режиме разработки React вызывает эффект дважды. Без защёлки один отказ
    // считался бы за два, и доля брошенных оплат выросла бы вдвое на пустом
    // месте. Приём взят у соседнего окна, чинившего это же место параллельно.
    const s = stripComments(
      readFileSync(join(process.cwd(), "src/app/pricing/checkout/cancel/page.tsx"), "utf8"),
    );
    // Требуем и ПРОВЕРКУ, и ВЗВЕДЕНИЕ: первая редакция искала только упоминание
    // защёлки и пережила мутацию «убрать взведение» — условие-то осталось, а
    // защёлка перестала работать. Мутация это и вскрыла.
    expect(s, "нет проверки защёлки").toContain("ужеОтмечено.current) return;");
    expect(s, "защёлка не взводится — значит не работает").toContain(
      "ужеОтмечено.current = true;",
    );
    expect(s, "касса в мете: без неё не видно, у какой кассы отваливаются").toContain(
      "meta: { provider: касса }",
    );
  });

  it("покупка вообще кем-то учитывается", () => {
    // Без этого сторож стерёг УСЛОВИЕ и не стерёг САМ УЧЁТ: мутация
    // «перестать учитывать покупку вовсе» проходила молча. А это худший
    // исход из возможных — покупки просто исчезают из сводки и из рекламы.
    const s = stripComments(
      readFileSync(join(process.cwd(), "src/app/pricing/checkout/success/page.tsx"), "utf8"),
    );
    expect(s, "на экране покупки нет учёта").toContain("<PurchaseReturnTracker");
    // И он обязан получить сумму: без неё выручка по каналам станет пустой.
    expect(s, "учёт без суммы — выручка по каналам обнулится").toContain(
      "value={totalUsd ?? undefined}",
    );
  });

  it("ОБА экрана применяют признак, а не только объявляют", () => {
    // Признак один на покупку и на отказ намеренно: два разных правила для
    // одной пары чисел разъедутся молча, и сверить их будет нечем.
    for (const путь of [
      "src/app/pricing/checkout/success/page.tsx",
      "src/app/pricing/checkout/cancel/page.tsx",
    ]) {
      const s = stripComments(readFileSync(join(process.cwd(), путь), "utf8"));
      expect(s, `${путь} не зовёт общий признак`).toContain("естьСледОплаты({");
      // Проверяем СМЫСЛ, а не написание: на экране отмены к тому же условию
      // добавлена защёлка от двойного срабатывания, и точная строка там иная.
      // Первая редакция требовала дословного совпадения и покраснела на
      // улучшении — сторож, мешающий улучшать, чинят удалением.
      // Способов применения ДВА, и оба верны:
      //   экран отмены  — ранний выход из эффекта: `if (!следОплаты`;
      //   экран покупки — общий компонент учёта под условием: `{следОплаты &&`.
      // Второй появился, когда учёт покупки переехал в PurchaseReturnTracker,
      // чтобы при слиянии со сборкой покупка не посчиталась ДВАЖДЫ.
      expect(
        s.includes("if (!следОплаты") || s.includes("{следОплаты &&"),
        `${путь} объявляет признак, но не применяет`,
      ).toBe(true);
    }
  });
});
