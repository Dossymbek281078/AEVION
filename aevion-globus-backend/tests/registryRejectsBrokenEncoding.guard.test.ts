/*
 * Порченный текст не попадает в публичный реестр.
 *
 * 🔴 Замер 01.10.2026: в реестре лежит сертификат от 27.08 с названием из 17
 * символов, и ВСЕ они — U+FFFD, символ замены. По одному символу на каждый
 * исходный знак: отправитель прислал однобайтовую кодировку (CP1251), а
 * разборщик тела прочитал её как UTF-8.
 *
 * Где теряется: в express.json(). Он декодирует тело как UTF-8 и заменяет
 * негодные байты ДО обработчика — восстановить их после приёма нельзя, исходные
 * байты остаются только в req.rawBody. Значит единственное место, где можно
 * действовать, — вход.
 *
 * Саму запись НЕ трогаем (она история), но новую такую не принимаем: текст с
 * символом замены не станет читаемым никогда, а в публичной витрине живёт вечно.
 */
import { describe, expect, it } from "vitest";
import request from "supertest";
import express from "express";
import { pipelineRouter } from "../src/routes/pipeline";

const ЗАМЕНА = String.fromCharCode(0xfffd);

function приложение() {
  const app = express();
  app.use(express.json());
  app.use("/api/pipeline", pipelineRouter);
  return app;
}

describe("реестр не принимает текст, который уже испорчен", () => {
  it("название из символов замены — 400", async () => {
    const r = await request(приложение())
      .post("/api/pipeline/protect")
      .send({ title: ЗАМЕНА.repeat(8), kind: "other", contentHash: "a".repeat(64) });
    expect(r.status, "испорченное название снова принимается").toBe(400);
    // Текст ошибки НЕ проверяем: платформа намеренно обезличивает сообщения
    // (правило про утечку инфраструктуры), и ждать здесь свою формулировку
    // значило бы стеречь не поведение, а обход этого правила.
  });

  it("испорченное имя автора — тоже 400", async () => {
    const r = await request(приложение())
      .post("/api/pipeline/protect")
      .send({ title: "Нормальное название", authorName: `Иван ${ЗАМЕНА}`, kind: "other", contentHash: "a".repeat(64) });
    expect(r.status).toBe(400);
  });

  it("контроль: обычная кириллица проходит эту проверку", async () => {
    /*
     * Без контроля сторож был бы зелёным и у ручки, которая отбивает всё русское.
     * Базы в тесте нет, поэтому дальше запрос упадёт на вставке — важно, что
     * падает НЕ на проверке кодировки.
     */
    const r = await request(приложение())
      .post("/api/pipeline/protect")
      .send({ title: "Протокол долголетия", authorName: "Иван Петров", kind: "other", contentHash: "a".repeat(64) });
    expect(r.status, "обычная кириллица отбита как порча").not.toBe(400);
  });
});
