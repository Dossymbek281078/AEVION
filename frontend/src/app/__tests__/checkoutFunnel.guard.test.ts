/**
 * Сторож воронки оплаты: у каждой точки входа в чекаут есть событие.
 *
 * ЗАЧЕМ. `/pricing/admin` показывает число checkout_start как факт. До
 * 10.08.2026 это событие слалось РОВНО из одного места — таблицы тарифов на
 * `/pricing`. Кнопка «Купить» на страницах модулей, апгрейд-баннер на девяти
 * страницах, весь магазин `/apps`, гайды `/qmelanin`, Studio Pro в `/devhub`
 * и `/studio` — всё это вело в реальную оплату и не слало ничего. Дашборд
 * при этом выглядел достоверно: он не мог сказать «я не знаю», он показывал
 * заниженное число.
 *
 * Дыры нашлись руками, поэтому и появился этот файл: следующую кнопку оплаты
 * нельзя будет добавить молча.
 *
 * ЧТО СЧИТАЕТСЯ СОБЫТИЕМ. Две воронки существуют осознанно: платформенная
 * (`lib/track` → `/api/pricing/events`) и своя у Constitution (`lib/useFunnel`
 * → `/api/constitution/funnel/track`). Сторож принимает любую из них — он
 * следит за наличием сигнала, а не диктует, куда его слать. Побочный вывод,
 * который стоит помнить: продажи Constitution НЕ попадают в `/pricing/admin`,
 * так что это не полная картина выручки. Объединять их — продуктовое решение,
 * не техническое.
 */
import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import path from "node:path";

const SRC_ROOT = path.resolve(__dirname, "../..");
const SKIP_DIRS = new Set([
  "node_modules",
  ".next",
  "__tests__",
  // Учебные чертежи сметного тренажёра: огромное дерево без единой кнопки
  // оплаты. Читать его целиком — это те самые лишние секунды, из-за которых
  // сторож упирался в дефолтный таймаут vitest на загруженной машине.
  "drawings-practice",
]);

/** Признаки того, что файл ведёт человека в оплату. */
const CHECKOUT_MARKERS = [
  "gumroadCheckoutUrl(",
  "pricing/checkout/session",
  "lemonsqueezy.com/checkout/buy/",
  "gumroad.com/l/",
  // Каталог отдаёт и цену, и href чекаута — страница, которая его читает,
  // почти всегда рисует кнопку покупки.
  "productById(",
];

/**
 * Любая из двух воронок засчитывается — плюс делегирование обёртке `<BuyLink>`,
 * которая шлёт событие сама. Требовать `track(` в файле, который уже отдал эту
 * работу компоненту, значило бы принуждать к дублирующему трекингу.
 */
const FUNNEL_MARKERS = ["checkout_start", "upgrade_click", "<BuyLink"];

/**
 * Файлы, которые содержат признак чекаута, но кнопкой не являются.
 * Причина обязательна — без неё это просто способ отключить сторож.
 */
const EXEMPT: Array<{ rel: string; reason: string }> = [
  {
    rel: "lib/products.ts",
    reason: "сам каталог товаров: хранит ссылки, ничего не рисует",
  },
  // components/ProductNotice.tsx исключением БЫЛ: он читал каталог через
  // productById() и потому попадал в обход, ничего не продавая. С 15.09.2026 он
  // берёт оговорку через productNotice(), признаков чекаута в нём нет вовсе, и
  // запись стала бы тихой дырой — сторож сам требует такие удалять.
  {
    rel: "lib/gumroad.ts",
    reason: "конструктор ссылок Gumroad, UI в нём нет",
  },
  /*
   * Эти двое ВЕДУТ на /pricing, а событие шлёт сама страница цен — слать его и
   * здесь значило бы посчитать покупку дважды. Причина настоящая, и в коде
   * обоих файлов она написана словами.
   *
   * До 29.09.2026 они проходили сторожа МОЛЧА и ложно: он находил слово
   * `checkout_start` в их же комментарии, где сказано ровно обратное — «здесь
   * событие не шлём». Сторож принимал объяснение за исполнение. Как только он
   * научился снимать комментарии, оба честно всплыли — и вот их настоящее
   * место, с настоящей причиной.
   */
  {
    rel: "components/UpgradeButton.tsx",
    reason: "ведёт на /pricing, где событие шлёт сама страница цен — дубль посчитал бы покупку дважды",
  },
  {
    rel: "lib/homeBuyLinks.ts",
    reason: "внутренние ссылки на /pricing; событие шлёт страница цен, здесь дублировать нельзя",
  },
  // components/AdPixels.tsx убран из списка 29.09.2026: его причина была
  // «ссылки на оплату упомянуты только в комментарии», а теперь сторож
  // комментарии снимает сам — исключение стало лишним. Список, из которого не
  // убирают сделанное, показывает долг больше настоящего.
  {
    rel: "app/devhub/[id]/page.tsx",
    reason: "placeholder поля ввода: это ссылка на товар ПОЛЬЗОВАТЕЛЯ, не на оплату AEVION",
  },
  {
    rel: "app/cyberchess/page.tsx",
    reason:
      "кнопка ведёт на /pricing, а не в кассу: прямых признаков чекаута в файле нет " +
      "(проверено 29.09.2026 — gumroad/lemonsqueezy/checkout-session по нулю, есть только " +
      "productById). Шаг «дошёл до цен» воронка считает по page_view на /pricing, а сам клик " +
      "страница шлёт как cta_click. Слать отсюда checkout_start было бы враньём: касса " +
      "открывается на /pricing, и мы завысили бы ровно то число, по которому видно провал " +
      "(за 14 дней 22 дошли до цен, 0 начали оплату)",
  },
];

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (/\.(ts|tsx)$/.test(name) && !/\.test\./.test(name)) out.push(full);
  }
  return out;
}

/**
 * Один обход на модуль: тестов здесь три, и без кеша дерево читалось трижды.
 * Именно эти лишние секунды упирались в дефолтный таймаут vitest при полном
 * прогоне на загруженной машине — сторож краснел из-за очереди на диск, а не
 * из-за находки.
 */
let cache: Array<{ rel: string; src: string }> | null = null;

/**
 * Исходник БЕЗ комментариев.
 *
 * ЗАЧЕМ. 29.09.2026 сторож объявил `app/bureau/page.tsx` кнопкой оплаты,
 * которая молчит. Кнопки там нет: признак чекаута нашёлся В КОММЕНТАРИИ —
 * разбор рядом с правкой цитировал `POST /api/pricing/checkout/session`,
 * объясняя, почему путь к оплате вообще появился. Два окна успели принять это
 * за настоящую находку и начали чинить несуществующее.
 *
 * Текст О вещи неотличим от вещи, если смотреть подстрокой. Признаки чекаута —
 * это ВЫЗОВЫ, и искать их надо в коде.
 *
 * Границы простые и намеренные: снимаются блочные комментарии и строки,
 * начинающиеся с `//`. Строковый литерал с `/*` внутри тоже посчитается
 * началом комментария — для поиска вызовов такая точность избыточна, а
 * настоящий разбор кода стоил бы дороже задачи.
 */
function безКомментариев(код: string): string {
  const части = код.split("/*");
  const безБлочных = части
    .map((часть, i) => (i === 0 ? часть : часть.slice(часть.indexOf("*/") + 2)))
    .join("");
  return безБлочных
    .split(String.fromCharCode(10))
    .filter((строка) => !строка.trim().startsWith("//"))
    .join(String.fromCharCode(10));
}

function checkoutFiles(): Array<{ rel: string; src: string }> {
  if (cache) return cache;
  const found: Array<{ rel: string; src: string }> = [];
  for (const file of walk(SRC_ROOT)) {
    const src = безКомментариев(readFileSync(file, "utf8"));
    if (!CHECKOUT_MARKERS.some((m) => src.includes(m))) continue;
    found.push({ rel: path.relative(SRC_ROOT, file).replace(/\\/g, "/"), src });
  }
  cache = found;
  return found;
}

/** Обход дерева, а не юнит — дефолтные 5 секунд vitest тут не про этот тест. */
const SWEEP_TIMEOUT_MS = 30_000;

describe("воронка оплаты — каждая точка входа шлёт событие", () => {
  it("ни одна кнопка оплаты не молчит", () => {
    const silent = checkoutFiles()
      .filter(({ rel }) => !EXEMPT.some((e) => e.rel === rel))
      .filter(({ src }) => !FUNNEL_MARKERS.some((m) => src.includes(m)))
      .map(({ rel }) => rel);

    expect(
      silent,
      `Эти файлы ведут человека в оплату, но не шлют событие воронки — значит, ` +
        `их покупки не видит /pricing/admin:\n  ${silent.join("\n  ")}\n\n` +
        `Добавь track({ type: "checkout_start", source: "<откуда>" }) в обработчик ` +
        `(или upgrade_click через useFunnel, если модуль ведёт свою воронку). ` +
        `Если файл кнопкой не является — впиши его в EXEMPT С ПРИЧИНОЙ.`,
    ).toEqual([]);
  }, SWEEP_TIMEOUT_MS);

  it("список исключений не протух", () => {
    // Исключение, которое больше ни на что не указывает, выглядит как
    // осознанное решение и потому не перепроверяется. Это тихая дыра.
    const present = new Set(checkoutFiles().map((f) => f.rel));
    const stale = EXEMPT.filter((e) => !present.has(e.rel)).map((e) => e.rel);
    expect(
      stale,
      `Эти записи EXEMPT больше не содержат признаков чекаута — удали их:\n  ${stale.join("\n  ")}`,
    ).toEqual([]);
  });

  it("событие есть у главной точки входа — таблицы тарифов", () => {
    // Явная проверка самого нагруженного входа, чтобы правка обработчика не
    // убрала событие незаметно для сплошного обхода.
    const files = new Map(checkoutFiles().map((f) => [f.rel, f.src]));
    const rel = "app/pricing/page.tsx";
    expect(files.get(rel), `${rel} перестал быть точкой входа в оплату — проверь, что это осознанно`).toBeTruthy();
    expect(files.get(rel), `${rel} больше не шлёт checkout_start`).toContain("checkout_start");
  }, SWEEP_TIMEOUT_MS);

  it("чип модуля ведёт к выбору срока и шлёт намерение, а не второе начало оплаты", () => {
    // 15.09.2026 — новая ценовая политика: чип больше НЕ открывает кассу сам
    // (прямой кассы на лестницу сроков нет), он ведёт на /pricing, где и уходит
    // checkout_start. Поэтому здесь проверяется другое: путь к оплате в чипе
    // есть, и нажатие видно воронке событием намерения. Слать checkout_start и
    // тут значило бы считать одну покупку дважды.
    const src = readFileSync(path.join(SRC_ROOT, "components", "ModulePricingChip.tsx"), "utf8");
    const code = src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
    expect(code, "чип не ведёт ни к приложению, ни к подписке").toMatch(/PRICING_APP\(/);
    expect(code).toMatch(/PRICING_TERMS/);
    expect(code, "нажатие чипа не видно воронке").toContain('type: "cta_click"');
    expect(code, "чип снова шлёт checkout_start — покупка посчитается дважды").not.toContain('type: "checkout_start"');
  });
});
