// Страница реестра нотариусов была ТЁМНОЙ, а бюро — светлое. Человек уходил
// с карточки тарифа по кнопке «View Notary Registry» и попадал на страницу
// другого вида: разрыв заметен сразу и читается как «это другой сайт».
//
// Правило платформы — светлый газетный интерфейс. Здесь оно закреплено на тех
// страницах бюро, которые ему уже следуют, чтобы тёмная палитра не вернулась
// незаметно при следующей правке.
//
// ⚠️ Охват НАЗВАН ПОИМЁННО и намеренно узок. Страница отдельного нотариуса
// (`notaries/[notaryId]`) сюда НЕ входит: её правит чужая ветка
// (fix/press-kit-dead-links, 28.08), она осталась тёмной, и включить её сюда
// значило бы уронить сторож на чужой работе. Когда её переведут — добавить
// строкой ниже.
import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const BUREAU = path.resolve(HERE, "..");

/** Страницы, которые ОБЯЗАНЫ быть светлыми. */
const LIGHT_PAGES = ["notaries/page.tsx"];

/** Тёмный ФОН — вот что делает страницу тёмной. `text-white` намеренно НЕ
 *  в списке: белый текст на цветной кнопке-акценте — верное решение, и
 *  первая версия сторожа справедливо на нём краснела. */
const DARK = /\b(bg-(slate|gray|zinc|neutral)-(7|8|9)\d{2}|bg-black)\b/g;

describe("страницы бюро следуют светлому интерфейсу", () => {
  it("список проверяемых страниц не пуст и все файлы на месте", () => {
    // Без этой проверки сторож молча позеленел бы, если файл переименуют:
    // пустой обход даёт ноль находок и выглядит как успех.
    expect(LIGHT_PAGES.length).toBeGreaterThan(0);
    for (const rel of LIGHT_PAGES) {
      expect(fs.existsSync(path.join(BUREAU, rel)), rel).toBe(true);
    }
  });

  it.each(LIGHT_PAGES)("%s — тёмных классов нет", (rel) => {
    const src = fs.readFileSync(path.join(BUREAU, rel), "utf8");
    const found = src.match(DARK) || [];
    expect(
      found,
      `тёмная палитра вернулась в ${rel}: ${[...new Set(found)].join(", ")}`,
    ).toEqual([]);
  });

  it("шаблон умеет находить — контроль на заведомо тёмной строке", () => {
    // Прибор проверяется на случае с известным ответом: без этого «ноль
    // находок» одинаково значит «чисто» и «шаблон не работает».
    expect('<div className="bg-slate-900">'.match(DARK)).toHaveLength(1);
    // Обратный контроль: законное сочетание ловиться НЕ должно, иначе
    // сторож краснеет на верной вёрстке и его отключат.
    expect('<button className="bg-teal-700 text-white">'.match(DARK)).toBeNull();
  });
});
