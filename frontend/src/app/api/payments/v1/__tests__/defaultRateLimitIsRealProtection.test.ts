import { describe, test, expect } from "vitest";
import { NextRequest } from "next/server";
import { enforceRate } from "../_lib";

/**
 * Сторож: предел по умолчанию остаётся защитой, а не формальностью.
 *
 * ЗАЧЕМ. Рядом лежит тест «ограничитель действительно отказывает» — и он
 * настоящий, но задаёт СВОЙ предел (5). То есть проверяет МЕХАНИЗМ, а не
 * умолчание, которым пользуются все ручки, не указавшие предел явно.
 *
 * Замер 01.09.2026: мутация «предел по умолчанию = 1 000 000» НЕ ловилась ни
 * одним из 45 тестов API. Защита исчезала молча.
 *
 * Проверяется ПОРЯДОК ВЕЛИЧИНЫ, а не точное число: настройку 60 → 100 наказывать
 * незачем, а возврат к «фактически без предела» поймать надо.
 */
function запрос(ключ: string) {
  return new NextRequest("https://example.test/api/payments/v1/links", {
    headers: { Authorization: `Bearer ${ключ}` },
  });
}

/** Сколько запросов подряд проходит, прежде чем ограничитель откажет. */
function пропущено(ключ: string, потолок = 5000): number {
  for (let i = 1; i <= потолок; i += 1) {
    if (!enforceRate(запрос(ключ)).ok) return i - 1;
  }
  return потолок;
}

describe("предел по умолчанию — настоящая защита", () => {
  test("КОНТРОЛЬ: явно заданный предел работает", () => {
    // Иначе «умолчание защищает» могло бы означать, что отказывает вообще всё.
    const ключ = `sk_test_ctl${Date.now()}`;
    expect(enforceRate(запрос(ключ), 1).ok).toBe(true);
    expect(enforceRate(запрос(ключ), 1).ok).toBe(false);
  });

  test("умолчание отказывает в разумных пределах, а не через миллион", () => {
    const прошло = пропущено(`sk_test_def${Date.now()}`);

    // Нижняя граница: защита не должна быть настолько тугой, чтобы мешать
    // обычной работе интеграции.
    expect(прошло, "предел по умолчанию слишком мал для нормальной работы")
      .toBeGreaterThanOrEqual(10);

    // Верхняя: за минуту одному ключу нечего делать сотнями запросов. Если
    // сюда once упрётся настоящая нагрузка — поднимайте ОСОЗНАННО и правьте
    // эту границу вместе с пределом, а не молча.
    expect(прошло, "предел по умолчанию поднят до уровня «защиты нет»")
      .toBeLessThanOrEqual(600);
  });
});
