"use client";

import { useEffect, useRef } from "react";
import { useSearchParams } from "next/navigation";
import { track } from "@/lib/track";

/**
 * Отметка «покупка завершена» на странице, куда провайдер возвращает человека.
 *
 * Замер 29.08.2026. Адрес возврата у каждого провайдера свой, и только часть
 * из них ведёт на `/pricing/checkout/success`, где отметка уже стоит:
 *
 *   PayBox, PayPal → /pricing/checkout/success        ✅ считается
 *   Конституция    → /constitution?upgrade=success    ✅ своей воронкой
 *   Stripe         → /bureau?paid=1                   🔴 не считалось
 *   QPayNet        → /qpaynet/deposit/success         🔴 не считалось
 *
 * ⚠️ ТАБЛИЦА ВЫШЕ ОПИСЫВАЕТ 29.08 — состояние на 31.08 другое, и держать её
 * без пометки значило бы врать следующему читателю. Сверка того же дня:
 *
 *   /bureau?paid=1              ✅ отмечает, гейт по `paid`
 *   /qpaynet/deposit/success    ✅ отмечает, гейт по `cid` (см. successValue="*")
 *   /constitution               ✅ своей воронкой, событие по НАЖАТИЮ — гейт
 *                                  по устройству: открытие страницы не считается
 *   /pricing/checkout/success   🔴 своя копия useEffect БЕЗ условия: отметка
 *                                  уходит при каждом открытии адреса, и воронка
 *                                  считает заходы вместо покупок. Файл правят
 *                                  чужие ветки, находка передана владельцу;
 *                                  храповик — everyPaymentReturnIsCounted.
 *
 * Деньги при этом не терялись: вебхуки провайдеров пишут покупку в базу
 * независимо от страницы. Не хватало другого — связи оплаты с каналом, из
 * которого пришёл человек. Без отметки реклама, ролик и рассылка выглядят
 * одинаково, и вопрос «что окупилось» остаётся без ответа.
 *
 * Компонент, а не копия `useEffect` на каждой странице: копия одного и того же
 * действия расходится молча, и разницу видно только при сравнении — тем же
 * вечером ровно так разошлась запись прав после оплаты в двух вебхуках.
 *
 * Отметка ставится ОДИН раз за монтирование: страницы возврата перерисовываются
 * (загрузка данных о платеже, смена языка), а повторное событие завысило бы
 * число продаж — то есть испортило бы именно ту цифру, ради которой всё и
 * делается.
 */
export function PurchaseReturnTracker({
  source,
  provider,
  successParam,
  successValue,
  tier,
  value,
  meta,
}: {
  /** Откуда пришли: попадает в воронку как источник. */
  source: string;
  /** Касса, вернувшая человека. */
  provider: string;
  /**
   * Параметр адреса, по которому видно УСПЕХ.
   *
   * ⚠️ Если не задан — успехом считается сам факт попадания на страницу. Это
   * запасной путь, и пользоваться им стоит только там, где признака нет вовсе:
   * иначе отметка уходит при КАЖДОМ открытии адреса, и воронка считает заходы
   * вместо покупок. Ровно такой дефект нашёлся 31.08.2026 на
   * `/pricing/checkout/success` — там своя копия `useEffect` без условия.
   */
  successParam?: string;
  /**
   * Значение параметра, означающее успех. По умолчанию `"1"`.
   *
   * Особое значение `"*"` — «любое непустое». Понадобилось для
   * `/qpaynet/deposit/success`: провайдер возвращает туда `?cid=<uuid>`, то есть
   * признак успеха ЕСТЬ, но он не равен фиксированной строке. До появления `"*"`
   * эта страница была вынуждена работать без признака вовсе и отмечала покупку
   * при любом заходе — дыра в интерфейсе самого компонента, а не в странице.
   */
  successValue?: string;
  /**
   * Тариф покупки, если страница его знает.
   *
   * Заведено 31.08.2026 по замечанию соседнего окна. Оно применило приём этого
   * компонента у себя, но НЕ заменило свой учёт на него — и по верной причине:
   * их событие несёт `tier`, `value` и `period`, а компонент их не умел.
   * Замена ради единообразия стоила бы трёх полей воронки, то есть ровно тех,
   * по которым видно, ЧТО покупают.
   *
   * Это второй за день случай, когда пропущенное применение общего компонента
   * означало не небрежность, а отсутствие у него нужного поля. Инструмент,
   * который беднее места применения, будут обходить — и правильно сделают.
   */
  tier?: string;
  /** Сумма покупки в долларах, если известна. */
  value?: number;
  /** Дополнительные поля события: период, вариант A/B и прочее. */
  meta?: Record<string, string | number | boolean | null>;
}) {
  const params = useSearchParams();
  const fired = useRef(false);

  // Отказ страницы не должен зависеть от отметки, поэтому читаем всё мягко.
  const raw = successParam ? params.get(successParam) : null;
  const isSuccess = successParam
    ? successValue === "*"
      ? raw !== null && raw.trim() !== ""
      : raw === (successValue ?? "1")
    : true;

  useEffect(() => {
    if (!isSuccess || fired.current) return;
    fired.current = true;
    track({
      type: "checkout_success",
      source,
      ...(tier ? { tier } : {}),
      ...(typeof value === "number" ? { value } : {}),
      meta: {
        provider,
        reference: params.get("reference"),
        checkoutId: params.get("cid"),
        stub: params.get("stub") === "1",
        // Поля страницы кладутся ПОСЛЕ общих: если страница знает про
        // провайдера или ссылку точнее нас, побеждает она.
        ...(meta ?? {}),
      },
    });
  }, [isSuccess, source, provider, params, tier, value, meta]);

  return null;
}

export default PurchaseReturnTracker;
