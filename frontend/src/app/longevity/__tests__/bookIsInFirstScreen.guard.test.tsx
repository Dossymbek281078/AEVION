/*
 * Платная книга видна В ПЕРВОМ ЭКРАНЕ телефона, и якорь #kniga ведёт на неё.
 *
 * 🔴 Замер 01.10.2026, из-за которого правка. `instagram|/go` — 17 сессий,
 * 15 дошли до цен (88 %, лучший отрезок всей воронки), 0 нажали «Купить».
 * Instagram приходит за долголетием. А за всё время платформа продала ТРИ раза
 * один и тот же товар — книгу `orcfbo` за $9.99; пакет `ghvzq` за $29.99,
 * который показывали, не купил никто. Платное лежало на ШЕСТОМ экране, первым
 * шло бесплатное.
 *
 * ⚠️ ЧТО ЭТОТ СТОРОЖ МОЖЕТ И ЧЕГО НЕ МОЖЕТ, честно. jsdom не считает вёрстку:
 * все размеры в нём нулевые, поэтому «выше 600 px» здесь НЕ проверяется — это
 * проверяется живым заходом (scripts/longevity-first-screen-probe.mjs) и
 * записано в его выводе. Здесь проверяется то, что от вёрстки не зависит и
 * ломается чаще: ПОРЯДОК блоков в разметке, наличие цены и кнопки у книги,
 * наличие якоря и то, что бесплатное не исчезло.
 */
import { describe, expect, it } from "vitest";
import { render } from "@testing-library/react";
import LongevityClient from "../_client";
import { productById } from "@/lib/products";

const КНИГА = productById("orcfbo");
const ПАКЕТ = productById("ghvzq");

describe("книга в первом экране /longevity", () => {
  it("карточка НАЗЫВАЕТ книгу так же, как касса: название из каталога", () => {
    /*
     * 🔴 Повод 06.10.2026, нашла приёмка. В карточке стояла своя фраза «Книга, из
     * которой вырос протокол», а в кассе Gumroad товар называется иначе. Покупатель
     * читал одно, а платил за другое по названию — и это та самая развилка, где
     * человек уходит: имя в кассе должно быть знакомым.
     *
     * Сверяется с КАТАЛОГОМ, а не с ожидаемой строкой в тесте: иначе у названия
     * появилась бы третья копия, и переименование товара разошлось бы молча.
     */
    const { container } = render(<LongevityClient />);
    const карточка = container.querySelector("#kniga");
    expect(карточка, "якоря #kniga нет — карточка книги пропала").toBeTruthy();
    const текст = карточка?.textContent ?? "";
    expect(КНИГА?.title, "у товара в каталоге нет названия").toBeTruthy();
    expect(
      текст.includes(КНИГА!.title),
      `карточка не называет книгу: в каталоге «${КНИГА!.title}», а в карточке «${текст.slice(0, 80)}»`,
    ).toBe(true);
  });

  it("контроль набора: оба товара есть в каталоге и цены те, что замерены", () => {
    // Без этого сторож мог бы проверять пустоту и быть зелёным.
    expect(КНИГА, "товара orcfbo нет в каталоге — проверять нечего").toBeTruthy();
    expect(ПАКЕТ, "товара ghvzq нет в каталоге").toBeTruthy();
    expect(КНИГА!.priceUsd, "цена книги сменилась — обнови замер и рекламу").toBe(9.99);
    expect(ПАКЕТ!.priceUsd, "цена пакета сменилась").toBe(29.99);
  });

  it("якорь #kniga стоит на карточке ПРОДАВАВШЕГОСЯ товара, а не на пакете", () => {
    const { container } = render(<LongevityClient channel={null} />);
    const якорь = container.querySelector("#kniga");
    expect(якорь, "якоря #kniga нет — платный клик приедет в начало страницы").not.toBeNull();

    const ссылка = якорь!.querySelector('a[href]');
    expect(ссылка, "внутри якоря нет ссылки на покупку").not.toBeNull();
    const href = ссылка!.getAttribute("href") ?? "";
    expect(href, `якорь ведёт не на orcfbo: ${href}`).toContain("orcfbo");
    // Отрицательный контроль: именно НЕ пакет. Их легко перепутать — я и
    // перепутал бы, если бы не сверил с кассой, что продавался $9.99.
    expect(href, "якорь #kniga ведёт на пакет $29.99, который не покупали").not.toContain("ghvzq");
  });

  it("у книги в якоре есть и ЦЕНА, и кнопка", () => {
    const { container } = render(<LongevityClient channel={null} />);
    const текст = (container.querySelector("#kniga") as HTMLElement).textContent ?? "";
    expect(текст, "в карточке книги нет цены").toContain("$9.99");
    // Кнопка — видимая подпись, а не только атрибут: подпись для скринридера
    // человек не видит, на этом мы уже обжигались.
    expect(текст.replace(/ /g, " "), "в карточке книги нет кнопки").toMatch(/Книга\s*→/);
  });

  it("карточка первого экрана остаётся ПЛОТНОЙ — иначе цена уедет за 600 px", () => {
    /*
     * Замер на живом проде 02.10.2026 (волна 9d, iframe 390×700): над карточкой
     * заголовок 154 px и медицинская оговорка 143 px, карточка начинается на
     * 469. С обычной карточкой правый блок переносится под текст, высота 254, и
     * низ цены оказывается на 698 — ниже первого экрана. По одному изменению:
     *   перенос + описание → 698 | без переноса и описания → 656
     *   плюс заголовок короче → 579 (запас 21 px)
     *
     * Пиксели здесь не проверяются (jsdom их не считает), а проверяется ровно
     * то, что регрессирует и возвращает 698: описание и перенос. Границу
     * называю прямо, чтобы тест не выглядел проверкой вёрстки.
     */
    const { container } = render(<LongevityClient channel={null} />);
    const карточка = container.querySelector("#kniga") as HTMLElement;
    const текст = карточка.textContent ?? "";

    expect(
      текст,
      "в карточку первого экрана вернулось описание — цена уедет ниже 600 px",
    ).not.toContain(КНИГА!.desc);
    expect(карточка.querySelectorAll("p").length, "в плотной карточке появился абзац").toBe(0);

    const ссылка = карточка.querySelector("a") as HTMLElement;
    expect(ссылка.style.flexWrap, "перенос вернулся — правый блок уйдёт под текст").toBe("nowrap");
  });

  it("ПОРЯДОК: книга $9.99 → пакет $29.99 → бесплатный протокол", () => {
    const { container } = render(<LongevityClient channel={null} />);
    const весь = container.textContent ?? "";
    const iКнига = весь.indexOf("$9.99");
    const iПакет = весь.indexOf("$29.99");
    // «Собрать план» — кнопка бесплатного инструмента, он идёт после платного.
    const iБесплатно = весь.indexOf("Собрать план");

    expect(iКнига, "цены книги нет в разметке").toBeGreaterThan(-1);
    expect(iПакет, "цены пакета нет в разметке").toBeGreaterThan(-1);
    expect(iБесплатно, "бесплатный инструмент ПРОПАЛ — его убирать не просили").toBeGreaterThan(-1);

    expect(iКнига, "пакет $29.99 стоит выше книги $9.99").toBeLessThan(iПакет);
    expect(iПакет, "платное оказалось ниже бесплатного — порядок прежний").toBeLessThan(iБесплатно);
  });

  it("у якоря задан отступ прокрутки — иначе карточка уедет под липкую шапку", () => {
    const { container } = render(<LongevityClient channel={null} />);
    const якорь = container.querySelector("#kniga") as HTMLElement;
    // Проверяем ЗАДАННОЕ значение (inline-стиль), а не вычисленное: вычислять
    // jsdom не умеет, и притворяться, что умеет, было бы ложью.
    expect(якорь.style.scrollMarginTop, "без отступа якорь приводит под шапку").not.toBe("");
  });

  it("в первом экране есть ссылка на бесплатный вход, и якорь, куда она ведёт", () => {
    /*
     * Добавлено 07.10.2026. Замер прода в тот день (Chrome 154, окно 390x844):
     * кнопка бесплатного плана лежит на y=2042 — ТРЕТИЙ экран, — а на страницу
     * ведут 11 роликов с обещанием бесплатного протокола. Порядок блоков
     * (решение 01.10: касса первой) не меняем, добавлена ссылка-якорь.
     *
     * Как и весь этот файл: размеры в jsdom нулевые, «в первом экране»
     * проверяется ПОРЯДКОМ в разметке, а высота — живым заходом.
     */
    const { container } = render(<LongevityClient channel={null} />);

    const ссылка = container.querySelector('a[href="#besplatno"]');
    expect(ссылка, "ссылки на бесплатный вход нет в первом экране").not.toBeNull();

    const текст = (ссылка!.textContent || "").trim();
    expect(текст.length, "ссылка без видимой подписи — человек её не увидит").toBeGreaterThan(5);
    expect(текст, "подпись не называет, что там бесплатно").toMatch(/бесплатн/i);

    const цель = container.querySelector("#besplatno");
    expect(цель, "якорь #besplatno не найден — ссылка ведёт в никуда").not.toBeNull();

    // ссылка обязана стоять ВЫШЕ цели и выше платной карточки, иначе она не в первом экране
    const html = container.innerHTML;
    const пСсылки = html.indexOf('href="#besplatno"');
    const пЦели = html.indexOf('id="besplatno"');
    const пКниги = html.indexOf('id="kniga"');
    expect(пСсылки, "ссылка не найдена в разметке").toBeGreaterThan(-1);
    expect(пЦели, "якорь не найден в разметке").toBeGreaterThan(-1);
    expect(пСсылки, "ссылка стоит НИЖЕ своей цели — в первый экран не попадёт").toBeLessThan(пЦели);
    if (пКниги > -1) {
      expect(пСсылки, "ссылка стоит ниже платной карточки — порядок первого экрана нарушен").toBeLessThan(пКниги);
    }
    process.stderr.write(
      `[сторож] ссылка на бесплатное: позиция ${пСсылки}, книга ${пКниги}, якорь ${пЦели}${String.fromCharCode(10)}`,
    );
  });

});
