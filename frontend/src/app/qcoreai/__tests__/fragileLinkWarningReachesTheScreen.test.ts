import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Признак «ссылка временная» обязан дойти до ЭКРАНА, а не только до ответа.
 *
 * 28.08.2026 бэкенд научили честно отвечать `durable: false`, когда ссылку не
 * удалось сохранить и она живёт до перезапуска сервера. Само по себе это ничего
 * не меняет: за одно окно я трижды наступал на то, что признак доезжает до
 * ответа и не доходит до человека. Поле в JSON, которое никто не читает, — это
 * не починка, а её видимость.
 *
 * Поэтому проверка спрашивает обе половины пути:
 *   1) страница ЧИТАЕТ признак из ответа;
 *   2) прочитанное ПОКАЗЫВАЕТСЯ — переменная стоит в условии разметки.
 *
 * Мутационно проверено с обеих сторон: убрать чтение или убрать показ —
 * проверка краснеет. Она намеренно не привязана к тексту предупреждения:
 * формулировку правят, и сторож, падающий на редактуре, будет отключён.
 */

const PAGE = path.resolve(__dirname, "../multi/page.tsx");

describe("предупреждение о временной ссылке доходит до экрана", () => {
  const src = fs.readFileSync(PAGE, "utf-8");

  test("страница читает признак долговечности из ответа сервера", () => {
    expect(
      /invite\.durable/.test(src),
      "ответ сервера про долговечность ссылки не читается вовсе",
    ).toBe(true);
  });

  test("прочитанное попадает в разметку, а не остаётся в состоянии", () => {
    // Имя состояния берём из самого чтения, чтобы переименование не сделало
    // сторожа слепым молча.
    const m = src.match(/set([A-Za-z0-9_]+)\(\s*invite\.durable\s*===\s*false\s*\)/);
    expect(m, "признак прочитан, но никуда не сохранён").not.toBeNull();

    const stateName = m![1][0].toLowerCase() + m![1].slice(1);
    // Показ — это использование переменной в условии JSX: `{имя && (`.
    // Регулярка здесь НЕ строится из строки: на этой машине обратные слэши
    // съедаются на границе вызова, и такой шаблон либо падает разбором, либо
    // — что хуже — молча не находит ничего. Позиционный поиск от этого свободен.
    const compact = src.replace(/\s+/g, "");
    const shown = compact.includes("{" + stateName + "&&(");
    expect(
      shown,
      `признак «${stateName}» прочитан, но на экране не показывается — человек не узнает, что ссылка временная`,
    ).toBe(true);
  });
});
