/**
 * Задача дня обязана просить ход РЕШАЮЩЕГО, а не ход соперника.
 *
 * ПОВОД 29.09.2026. Банк — сырой формат lichess: первый ход решения делает
 * соперник, и `fen` показан ДО него. Основной раздел «Задачи» это учитывает
 * (`normalizePuzzle`), а страница задачи дня — нет: в её коде было записано
 * «игрок ходит по чётным индексам», то есть игрок должен сыграть `sol[0]`.
 *
 * Замер на настоящей задаче дня 29.09 (прод): линия
 * `Bc3 Ne5 dxe5 Rxc4 bxc4 Nxc3`, материал белых падает с +2 до −2 —
 * выигрывают чёрные, а `Bc3` это зевок белых. Страница предлагала сыграть
 * именно его, и подсказка указывала туда же.
 *
 * ⚠️ И ВТОРАЯ ПОЛОВИНА, без которой починка ломает засчитывание: сервер
 * `/solve` сверяет присланные ходы с КАНОНИЧЕСКИМ решением дня целиком,
 * включая ход соперника, и требует совпадения длины. Поэтому играем по
 * нормализованному, а отправляем сырое.
 */

import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { Chess } from "chess.js";
import { normalizePuzzle, solverSide } from "../puzzleNormalize";

// Настоящая задача дня 29.09.2026, как её отдаёт прод.
const ДЕНЬ = {
  fen: "6k1/1p3pp1/2p3n1/B2n4/P1QPr3/1P5P/5KP1/8 w - - 1 32",
  sol: ["a5c3", "g6e5", "d4e5", "e4c4", "b3c4", "d5c3"],
  name: "",
  r: 0,
  theme: "Тактика",
};

const СТРАНИЦА = readFileSync(join(__dirname, "..", "daily", "page.tsx"), "utf8");

describe("задача дня: ход просят у решающего", () => {
  it("на настоящей задаче решает ЧЁРНЫЙ, и первый ход — Ne5", () => {
    const н = normalizePuzzle(ДЕНЬ);
    const g = new Chess(н.fen);
    expect(solverSide(ДЕНЬ), "решает чёрный").toBe("b");
    expect(g.turn(), "после хода соперника ходят чёрные").toBe("b");
    const первый = g.move({ from: н.sol[0].slice(0, 2), to: н.sol[0].slice(2, 4) });
    expect(первый?.san, "первый ход решающего").toBe("Ne5");
  });

  it("контроль: до нормализации ход белых, и это зевок", () => {
    // Иначе проверка выше прошла бы и на задаче, где нормализация не нужна.
    const g = new Chess(ДЕНЬ.fen);
    expect(g.turn()).toBe("w");
    const зевок = g.move({ from: "a5", to: "c3" });
    expect(зевок?.san).toBe("Bc3");
  });

  it("страница зовёт общую нормализацию, а не свой механизм", () => {
    expect(СТРАНИЦА).toContain("normalizePuzzle");
    // Прежнее предположение «игрок ходит по чётным индексам» верно ТОЛЬКО
    // после нормализации; без неё оно и было причиной дефекта.
    expect(СТРАНИЦА).toContain("кЗадаче(");
  });

  it("🔴 на сервер уходит СЫРОЕ решение, иначе решивший получит «wrong_solution»", () => {
    // /solve сверяет с каноническим решением дня целиком, включая ход
    // соперника, и требует совпадения длины.
    expect(СТРАНИЦА).toContain("moves: puzzle.solRaw ?? puzzle.sol");
    expect(СТРАНИЦА).not.toContain("moves: puzzle.sol,");
  });

  it("контроль сырого: нормализованное решение КОРОЧЕ сырого ровно на один ход", () => {
    const н = normalizePuzzle(ДЕНЬ);
    expect(ДЕНЬ.sol.length - н.sol.length).toBe(1);
    expect(н.sol[0]).toBe(ДЕНЬ.sol[1]);
  });
});
