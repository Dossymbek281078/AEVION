"use client";

import { useEffect } from "react";
import { installDevhubGuestHeader, getDevhubGuestId } from "@/lib/devhubGuest";
import { getAuthToken } from "@/lib/auth";
import { apiUrl } from "@/lib/apiBase";

// Ставится при вычислении модуля, а НЕ в useEffect: эффекты идут после
// монтирования, и первый список проектов успел бы уехать без заголовка —
// показать общий ящик, а после обновления страницы вдруг свой. Модули
// вычисляются раньше любого запроса.
installDevhubGuestHeader();

/**
 * Забирает гостевую работу в аккаунт при первом заходе после входа.
 *
 * Замер 03.09.2026: человек, попробовавший DevHub гостем и затем вошедший,
 * ТЕРЯЛ свои проекты из виду — они остаются на «guest:<id>», а личностью
 * становится sub из токена. Ручка переноса без вызова была бы «механизмом,
 * части которого не связаны», поэтому вызов живёт здесь: этот компонент уже
 * смонтирован везде, где работает DevHub, и уже знает про гостевую личность.
 *
 * Вызывается ОДИН раз на браузер: повторять незачем, а лишние запросы при
 * каждом переходе — шум. Отметка в localStorage, а не в состоянии: страница
 * перезагружается.
 */
const ОТМЕТКА = "aevion.devhub.guest.adopted";

function перенестиОдинРаз(): void {
  if (typeof window === "undefined") return;
  try {
    if (window.localStorage.getItem(ОТМЕТКА)) return;
    const токен = getAuthToken();
    const гость = getDevhubGuestId();
    // Без входа переносить некуда, без гостя — нечего. Обе проверки нужны:
    // ручка ответит понятным отказом, но дёргать её впустую незачем.
    if (!токен || !гость) return;
    void fetch(apiUrl("/api/devhub/studio/adopt-guest"), {
      method: "POST",
      headers: { Authorization: `Bearer ${токен}` },
    })
      .then((r) => { if (r.ok) window.localStorage.setItem(ОТМЕТКА, "1"); })
      // Молчим намеренно: перенос — удобство, а не операция, ради которой
      // человек пришёл. Уронить из-за него страницу нельзя. Но и отметку при
      // отказе НЕ ставим, чтобы попытка повторилась в следующий заход.
      .catch(() => {});
  } catch { /* хранилище недоступно (приватный режим) — просто не переносим */ }
}

/** Ничего не рисует: нужен только чтобы модуль попал в клиентскую сборку. */
export function DevHubGuestIdentity() {
  useEffect(() => { перенестиОдинРаз(); }, []);
  return null;
}
