/**
 * Ответ ПОСРЕДНИКА, а не нашего кода: у Railway это «Application failed to
 * respond» с request_id, у прочих прокси — «Bad Gateway».
 *
 * Замер 09.09.2026, за сутки до запуска: проба «соберёт ли человек приложение»
 * упала с 502 на генерации, а повтор через минуту прошёл за 18 секунд и
 * принёс три файла. То есть отказ ПРЕХОДЯЩИЙ и повтор помогает — значит
 * человеку надо сказать именно это.
 *
 * Почему отдельный класс, а не INFRA: INFRA отвечает «возможность не настроена
 * на нашей стороне», и здесь это было бы НЕПРАВДОЙ — всё настроено, сервис
 * просто не ответил. Ложное объяснение хуже технической фразы: по нему человек
 * уйдёт, вместо того чтобы нажать ещё раз.
 *
 * И почему это касается EN-ветки, где карта намеренно не применяется: там
 * правило «тексты сервера на английском родные для EN-читателя», а это НЕ наш
 * текст и не контракт — это фраза чужой инфраструктуры. Замер: EN-посетитель
 * видел голое «Application failed to respond».
 */
const POSREDNIK = /Application failed to respond|failed to respond|Bad Gateway/i;

const INFRA = /[A-Z][A-Z0-9]{3,}_[A-Z0-9_]{2,}|in Railway|dash.cloudflare/;

/**
 * @param raw   текст из поля `error` ответа сервера (может отсутствовать)
 * @param fallback русский текст на случай, когда сервер не сказал ничего
 * @param lang  язык читателя. Для en КАРТА НЕ ПРИМЕНЯЕТСЯ: тексты сервера —
 *   контракт на английском, для EN-читателя они родные, а русская замена
 *   была бы шагом назад (замер 06.09.2026: EN-визитёр в момент решения
 *   «платить ли» читал русское сообщение о квоте; тосты — слепая зона
 *   машинного доводчика, живут секунды). kk идёт по русской карте, как и
 *   весь модуль (fallback ru).
 */
export function devhubServerError(raw: unknown, fallback: string, lang: string = "ru"): string {
  const s = typeof raw === "string" ? raw.trim() : "";

  // Посредник не ответил — единственный случай, где верный совет «повторите»:
  // проверено замером, повтор проходит. Говорим это на языке читателя, ДО
  // языковых развилок ниже.
  if (s && POSREDNIK.test(s)) {
    return lang === "ru" || lang === "kk"
      ? "Сервис не ответил — попробуйте ещё раз через минуту."
      : "The service did not respond — please try again in a minute.";
  }
  if (lang !== "ru" && lang !== "kk") {
    if (!s) return "The request failed. Please try again.";
    if (INFRA.test(s)) {
      if (typeof console !== "undefined" && console.warn) {
        console.warn("devhub: техническое сообщение сервера не показано покупателю:", s);
      }
      return "This capability is not set up on our side yet. We know about it — please try again later.";
    }
    return s;
  }
  if (!s) return fallback;

  // Сервер уже говорит по-русски (таких семь) — не трогаем.
  if (/[а-яА-ЯёЁ]/.test(s)) return s;

  for (const [re, ru] of RULES) {
    const m = re.exec(s);
    if (!m) continue;
    // $1 подставляем только если правило его ждёт И группа есть.
    return ru.includes("$1") && m[1] ? ru.replace("$1", m[1].trim()) : ru;
  }

  // Незнакомое — показываем как есть, рядом с понятным поводом.
  // Сообщение, называющее переменную окружения, панель поставщика или
  // машинный код, написано для НАС, а не для покупателя. Показывать его
  // человеку вдвойне плохо: помочь оно не может, а устройство системы
  // выдаёт. Замер 29.08.2026: таких сообщений в devhub.ts тридцать пять,
  // и все они доезжали до экрана через подстановку ниже.
  //
  // Текст при этом НЕ теряется — он уходит в консоль. Спрятать его
  // совсем значило бы обменять одну беду на другую: разбирать отказ
  // стало бы не по чему.
  if (INFRA.test(s)) {
    if (typeof console !== "undefined" && console.warn) {
      console.warn("devhub: техническое сообщение сервера не показано покупателю:", s);
    }
    return "Эта возможность сейчас не настроена на нашей стороне. Мы уже знаем об этом — попробуйте позже.";
  }

  return `${fallback} (${s})`;
}

/**
 * Языковая обёртка: язык берётся из общего контекста сайта, вне провайдера —
 * русский (прежнее поведение, тесты рисуют без провайдера). Компоненты зовут
 * ЕЁ, а не голую функцию, — иначе язык пришлось бы протаскивать через 54
 * вызова руками.
 */
export function useDevhubServerError(): (raw: unknown, fallback: string) => string {
  const lang = useI18nOptional()?.lang ?? "ru";
  return useCallback((raw: unknown, fallback: string) => devhubServerError(raw, fallback, lang), [lang]);
}
