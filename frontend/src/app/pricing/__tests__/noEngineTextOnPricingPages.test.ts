/**
 * Публичные страницы цен не показывают человеку внутренности.
 *
 * Класс находили дважды: соседнее окно — на странице цен (покупателю выводили
 * адрес API и инструкцию запустить бэкенд), я — на форме связи. 03.09.2026
 * нашёл ещё два места: `/pricing/cases` и `/pricing/compare` печатали
 * «/api/pricing/cases — <сообщение движка>» прямо под заголовком об ошибке.
 *
 * Человек читает это в момент, когда ему и так не повезло, и вывод делает не
 * «сервис на минуту недоступен», а «у них всё сломано».
 *
 * Сторож закрепляет ДВЕ вещи: внутреннего адреса в разметке нет, и человеческая
 * подсказка есть. Первое без второго дало бы пустой экран вместо объяснения.
 *
 * СВИП ПО ВСЕЙ ЗОНЕ 04.09.2026, повторять не нужно: 165 файлов
 * (`app/pricing`, `components`, `app/go`, `app/account`), поиск по тексту
 * МЕЖДУ тегами — без ограничения строкой, иначе он слеп, см. ниже.
 * 8 кандидатов → 3 законных (блок документации нашего API, где адреса ручек
 * и есть содержание) → 5 артефактов прибора → 0 дефектов.
 *
 * Артефакты стоит знать заранее: `>` и `<` берутся не только из тегов, но и
 * из обобщённых типов `safeFetch<{...}>` и стрелок `=>`. Такой поиск всегда
 * даёт немного шума — это не повод считать кандидатов находками.
 *
 * И ГЛАВНОЕ ПРО САМ ПРИЁМ: 02.09 я записал «свип сделан, ноль» — и ноль был
 * ЛОЖНЫМ. Тот свип искал признаки в ОДНОЙ строке, а в разметке тег открыт на
 * одной строке, текст на другой. Из-за этого главная страница цен два дня
 * показывала посетителю адрес ручки и совет «проверь, что бэкенд запущен».
 * Свип по строке для разметки не годится.
 *
 * СВИП ПО ЗОНЕ СДЕЛАН 03.09.2026, повторять не нужно: 67 файлов `src/app/pricing`,
 * поиск по разметке признаков внутренностей (`/api/`, localhost, npm run,
 * «Failed to», e.message, String(e)) — кандидатов НОЛЬ после этой починки.
 *
 * Ноль проверен контролем, иначе он ничего не значил бы: тот же прибор,
 * натравленный на ПРЕДЫДУЩУЮ версию cases/page.tsx, находит ровно строку 111
 * — то есть умеет находить этот класс, а не молчит по неумению.
 *
 * Граница у свипа честная: он смотрит РАЗМЕТКУ. Текст, собранный в переменную
 * выше по файлу и выведенный как `{сообщение}`, он не поймает — такие случаи
 * ловит только отрисовка (см. соседние сторожа экранов кассы).
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stripComments } from "../../__tests__/helpers/sourceCode";

const страницы = [
  "src/app/pricing/cases/page.tsx",
  "src/app/pricing/compare/page.tsx",
  // Добавлена 04.09: главная страница цен показывала посетителю адрес ручки,
  // сообщение движка И совет «проверь, что бэкенд запущен (npm run ...)» —
  // инструкцию разработчику на самой посещаемой странице. Под проверкой её не
  // было, потому что утренний свип искал признаки В ОДНОЙ СТРОКЕ, а там `<p>`
  // открыт на одной строке, текст на другой.
  "src/app/pricing/page.tsx",
];

describe("страницы цен при отказе сервера", () => {
  it.each(страницы)("%s не печатает внутренний адрес ручки", (путь) => {
    const код = stripComments(readFileSync(join(process.cwd(), путь), "utf8"));
    // Ищем адрес ручки именно В РАЗМЕТКЕ: в fetch он законен и нужен.
    const вРазметке = /<p[^>]*>\s*\/api\//.test(код) || />\s*\/api\/[a-z/-]+\s*—/.test(код);
    expect(вРазметке, "внутренний адрес ручки уходит на экран").toBe(false);
  });

  it.each(страницы)("%s даёт человеку понятную подсказку", (путь) => {
    const код = stripComments(readFileSync(join(process.cwd(), путь), "utf8"));
    /*
     * Ключ не закрепляем дословно. 04.09 выяснилось, что ветка сборки починила
     * эти же два экрана раньше и СВОИМ ключом (`error.whatNow`), а я завёл
     * параллельный `error.retryHint`. Взял их сторону — она ближе к выкатке, —
     * но закреплять теперь их имя значило бы повторить ту же ошибку с другой
     * стороны: сторож должен требовать ПОДСКАЗКУ, а не конкретное слово.
     *
     * Проверяем: под заголовком стоит вторая строка из словаря, и это не
     * заголовок. Имя ключа менять можно свободно.
     */
    const подсказки = [...код.matchAll(/tp\("(error\.[a-zA-Z]+)"\)/g)].map((m) => m[1]);
    expect(подсказки, "экран не берёт из словаря ничего").not.toHaveLength(0);
    expect(
      подсказки.filter((к) => к !== "error.unavailable").length,
      "под заголовком нет человеческой подсказки — только заголовок",
    ).toBeGreaterThan(0);
  });

  it.each(страницы)("%s не теряет подробность — она уходит в журнал", (путь) => {
    const код = stripComments(readFileSync(join(process.cwd(), путь), "utf8"));
    // Убрать с экрана мало: без записи в журнал причина исчезает вовсе,
    // и следующий разбор начинается с нуля.
    /*
     * Способ записи не закрепляем: 04.09 я требовал именно `console.warn` и
     * получил красное на ветке сборки, где стоит `console.error`. Подробность
     * там НЕ потеряна — потерян был смысл моей проверки, закреплявшей написание.
     */
    const вЖурнал = /console\.(warn|error|log)\(/.test(код);
    expect(вЖурнал, "подробность потеряна вместо журнала").toBe(true);
  });

  it("подсказка есть в обоих языках словаря цен", () => {
    /*
     * Ключ БЕРЁМ ИЗ СТРАНИЦЫ, а не пишем сюда: 04.09 я закрепил здесь своё имя
     * `error.retryHint`, а ветка сборки чинила те же экраны своим
     * `error.whatNow`. Сторож с зашитым именем краснеет на чужой верной
     * починке — и заставляет сохранять имя ради сторожа.
     */
    const код = stripComments(
      readFileSync(join(process.cwd(), "src/app/pricing/cases/page.tsx"), "utf8"),
    );
    const ключи = [...код.matchAll(/tp\("(error\.[a-zA-Z]+)"\)/g)]
      .map((m) => m[1])
      .filter((к) => к !== "error.unavailable");
    expect(ключи.length, "страница не берёт подсказку из словаря").toBeGreaterThan(0);

    const словарь = readFileSync(join(process.cwd(), "src/lib/pricingI18n.ts"), "utf8");
    for (const ключ of new Set(ключи)) {
      const счёт = словарь.split('"' + ключ + '"').length - 1;
      expect(счёт, `подсказка ${ключ} заведена не во всех языках`).toBeGreaterThanOrEqual(2);
    }
  });
});
