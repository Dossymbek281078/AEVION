// Развилка «страница или приложение» на входе DevHub.
//
// 28.09.2026. Сегодня вход строит только static — единственный стек, доходящий до живого
// адреса. Приложение с базой и входом станет возможным, когда появится сборка на стороне
// Vercel (маршрут /deploy/vercel написан и ждёт токена). Поэтому выбор НЕ включается
// вручную и не обещает заранее: он спрашивает возможности сервера. Нет сборки — выбора нет.
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { доступенРежимПриложения, стекДляРежима, stackForIdea } from "../../../lib/devhubStackChoice";

const страница = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");
const словарь = readFileSync(join(__dirname, "..", "i18n.ts"), "utf8");

describe("развилка появляется только когда приложение реально можно собрать", () => {
  it("есть сборка — режим приложения доступен", () => {
    expect(доступенРежимПриложения((id) => id === "vercel")).toBe(true);
  });

  it("нет сборки — режима нет: Pages отдаёт файлы как есть и приложение не соберёт", () => {
    expect(доступенРежимПриложения(() => false)).toBe(false);
    // и наличие ТОЛЬКО Pages не открывает режим — это и была причина мёртвых адресов
    expect(доступенРежимПриложения((id) => id === "pages")).toBe(false);
  });

  it("стек следует за режимом, а не за догадкой по тексту", () => {
    expect(стекДляРежима("app")).toBe("next");
    expect(стекДляРежима("page")).toBe("static");
    // прежнее поведение сохранено: без выбора идея всегда даёт static
    expect(stackForIdea("магазин с корзиной и оплатой")).toBe("static");
  });

  it("страница показывает выбор под условием доступности, а не всегда", () => {
    expect(страница).toContain("режимПриложенияДоступен && (");
    expect(страница).toContain("доступенРежимПриложения(");
  });

  it("выбор человека главнее догадки по тексту", () => {
    const i = страница.indexOf("const stack =");
    expect(i).toBeGreaterThan(0);
    const кусок = страница.slice(i, i + 220);
    expect(кусок).toContain('режим === "app" && режимПриложенияДоступен');
    expect(кусок).toContain("stackForIdea(idea)");
  });

  it("подписи есть на всех трёх языках страницы", () => {
    for (const ключ of ["hero.mode.page", "hero.mode.app", "hero.mode.hint"]) {
      const сколько = (словарь.match(new RegExp('"' + ключ + '":', "g")) || []).length;
      expect(сколько, ключ).toBe(3);
    }
  });
});
