import type { VerifyResult } from "./types";

/**
 * Вердикт строится по ДВУМ фактам сразу, и это не косметика.
 *
 * До 28.07 заголовок красился по одному `hashMatches` и гласил «содержимое не
 * изменено». Проверено прогоном: чек, сочинённый с нуля, даёт `hashMatches:
 * true` — хеш считается от того же файла, который проверяют, поэтому у любой
 * самосогласованной подделки он сходится по построению. Хуже того, у
 * подделанного ПОДПИСАННОГО чека с пересчитанным хешем заголовок выходил
 * зелёным «содержимое не изменено», а «Подпись: НЕ действительна» стояла
 * мелкой строкой ниже — то есть крупный текст прямо противоречил правде.
 *
 * Совпадение хеша доказывает ровно одно: файл не побился при передаче.
 * Происхождение доказывает только подпись. Поэтому зелёный — исключительно
 * при действительной подписи.
 */
export type Verdict = { tone: "good" | "bad" | "warn"; title: string; detail: string };

export function verdictOf(res: VerifyResult): Verdict {
  if (!res.hashMatches) {
    return {
      tone: "bad",
      title: "Хеш не сходится — файл изменён после выдачи",
      detail:
        "Либо файл отредактировали, либо это чек другого ответа. Сравните поле hash в файле с пересчитанным ниже.",
    };
  }
  switch (res.signature) {
    case "valid":
      return {
        tone: "good",
        title: "Чек подлинный — подпись AEVION действительна",
        detail: "Содержимое соответствует хешу, а хеш подписан нашим ключом. Это и есть доказательство.",
      };
    case "invalid":
      return {
        tone: "bad",
        title: "Подпись недействительна — чеку доверять нельзя",
        detail:
          "Хеш сошёлся, но само по себе это ничего не значит: подделку пересчитывают вместе с её хешем. Не сходится именно подпись — значит, содержимое не то, что мы выдали.",
      };
    case "absent":
      return {
        tone: "warn",
        title: "Подписи нет — происхождение не подтверждено",
        detail:
          "Хеш соответствует содержимому, но такой чек может составить кто угодно: хеш считается от того же файла. Подлинность доказывает только подпись, а её здесь нет.",
      };
    default:
      return {
        tone: "warn",
        title: "Подпись не проверена — происхождение не подтверждено",
        detail:
          "Ключ подписи не разрешается, поэтому подтверждена только целостность файла. Пока подпись не проверена, чек не доказывает происхождение.",
      };
  }
}
