import type { TierId } from "../../data/pricing";
import { tierIdForReference } from "./billingPeriod";

/**
 * Какой ТАРИФ означает ссылка заказа — один ответ для всех касс.
 *
 * 🔴 ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Правило жило ДВУМЯ копиями: `tierForReference` в
 * `payboxWebhook.ts` и в `paypalWebhook.ts`. Логика в них совпадала знак в знак
 * (проверено сравнением 29.09.2026 — расходились только комментарии и текст
 * записи в журнал), но такая пара расходится молча: у PayPal шумную запись о
 * незнакомой ссылке пришлось добавлять отдельно, уже после того как у PayBox
 * она появилась и была закреплена сторожем. Два писателя одного правила — и
 * вторая копия отстаёт на одну починку.
 *
 * ⚠️ ЗДЕСЬ НАМЕРЕННО ОСТАВЛЕНА ЭВРИСТИКА ПО ПОДСТРОКЕ, и у неё есть известный
 * изъян, записанный в очередь работ на 30.09.2026: ссылка ПРИЛОЖЕНИЯ
 * (`app_qskyway_lite`, `app_devhub_full`) тоже разбирается как тариф, потому что
 * содержит «lite» или «full». Тариф с 15.09 означает доступ ко всей планете,
 * поэтому покупка одного модуля через эти кассы дала бы доступ на $400 за цену
 * модуля. Здесь это НЕ лечится: ссылку приложения должен перехватить сам рельс
 * и выдать право на модуль, как уже сделано у Lemon Squeezy (коммит dc5d45658).
 * Обе кассы сейчас выключены на проде, поэтому утечка спящая.
 *
 * Эвристика нужна для ЧУЖИХ ссылок: собственные (`tier_<ступень>` и прежние
 * `tier_<тариф>_<период>`) разбирает точное правило `tierIdForReference`.
 * Сверяем точным префиксом, а не подстрокой везде, где можно: `includes("pro")`
 * поймал бы и `tier_promo_*`.
 */
export function тарифПоСсылкеЗаказа(
  ref: string,
  рельс: "paybox" | "paypal",
  сообщить: (e: Error, ctx: Record<string, unknown>) => void,
): TierId {
  const r = ref.toLowerCase();

  // Точное правило: лестница сроков и прежние ссылки с периодом. До его
  // появления `tier_pro_monthly` проваливался в дефолт `lite` — человек платил
  // за старший тариф и получал самый дешёвый.
  const точно = tierIdForReference(r);
  if (точно) return точно;

  if (r.includes("medium")) return "medium";
  if (r.includes("full") || r.includes("all-access") || r.includes("business") || r.includes("team")) {
    return "full";
  }

  // Незнакомая ссылка НЕ должна выдавать платный тариф МОЛЧА.
  //
  // Поведение оставлено прежним — выдаём lite: покупатель заплатил, и не выдать
  // ему ничего хуже, чем выдать меньше обещанного. Но он мог оплатить ДРУГОЙ
  // тариф, и тогда это наша ошибка, о которой надо знать. У PayBox это было
  // закреплено сторожем `payboxUnknownReferenceIsLoud`, у PayPal тот же провал
  // шёл без единого следа (замер 02.09.2026).
  if (!r.includes("lite")) {
    console.warn(`[${рельс}/webhook] незнакомая ссылка заказа "${ref}" — выдан lite по умолчанию`);
    сообщить(new Error(`${рельс}: неизвестная ссылка заказа "${ref}", выдан lite по умолчанию`), {
      route: `${рельс}/webhook`,
      reference: ref,
    });
  }
  return "lite";
}
