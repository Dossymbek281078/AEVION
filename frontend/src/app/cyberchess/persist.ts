/* Чтение сохранённого состояния с диска — одна функция на все модули.
 *
 * Загрузчики CyberChess написаны по одному образцу, и в нём две ошибки:
 *
 *   const r = JSON.parse(s);
 *   if (!r || r.v !== 1) return DEFAULT;   // (1)
 *   return r;                              // (2)
 *
 * (1) Незнакомая версия ОБНУЛЯЕТ состояние. Поля в этих структурах добавляются,
 *     а не переименовываются, поэтому старое состояние читается новым кодом как
 *     есть — отвергать его незачем. Зато первое же поднятие версии стирает
 *     игроку заработанное, молча и без ошибки в консоли. Это не гипотеза:
 *     DailyState подняли с v1 до v2 — и все сохранённые состояния отбросились.
 *
 * (2) Совпала версия — объект возвращается КАК ЕСТЬ, без наложения на умолчания.
 *     Значит поле, добавленное в структуру без поднятия версии, у существующих
 *     игроков будет undefined, и код, который на него рассчитывает, тихо считает
 *     от undefined. Две ошибки взаимно маскируются: пока версию не трогают,
 *     работает (2)-путь; тронут — сработает (1).
 *
 * Здесь версия ничего не отвергает, а результат всегда накладывается на
 * умолчания, так что отсутствующее поле берётся из них.
 */

const isPlainObject = (v: unknown): v is Record<string, unknown> =>
  typeof v === "object" && v !== null && !Array.isArray(v);

/**
 * Читает строку из localStorage в структуру состояния.
 * `null` на входе (ключа нет) отдаёт копию умолчаний — вызывающий, которому важно
 * отличать «нет записи» от «пустая запись», проверяет наличие ключа сам.
 */
export function readStored<T extends object>(raw: string | null, fallback: T): T {
  if (!raw) return { ...fallback };
  try {
    const r: unknown = JSON.parse(raw);
    if (!isPlainObject(r)) return { ...fallback };
    const merged = { ...fallback, ...r } as T;
    // Версия состояния всегда текущая: читаем старое, пишем новое.
    if ("v" in (fallback as Record<string, unknown>)) {
      (merged as Record<string, unknown>).v = (fallback as Record<string, unknown>).v;
    }
    return merged;
  } catch {
    return { ...fallback };
  }
}
