import { test, expect, type Page } from "@playwright/test";

/**
 * Цена DevHub видна БЕЗ ПРОКРУТКИ на телефоне.
 *
 * Почему координатой, а не чтением исходника. 01.10.2026 я поставил цену в первый
 * экран, сторож по исходнику дал 5 из 5 зелёных — и приёмка замерила на проде:
 * верх блока стоял на y=764 при высоте окна 844. На настоящем телефоне адресная
 * строка браузера съедает около 100 px, видимая высота около 740, и цена уходила
 * под сгиб. Сторож по исходнику остаётся зелёным ровно в этом случае: он
 * доказывает, что блок ОБЪЯВЛЕН рядом с первым экраном, и ничего не говорит о том,
 * где он оказался после вёрстки.
 *
 * Цена этого различия измеряется деньгами: с Product Hunt и LaunchNest пришло
 * 16 сессий, до страницы цен не дошёл НИ ОДИН человек.
 *
 * ДВЕ ВЫСОТЫ не для симметрии. 844 — паспортная высота окна, 700 — то, что
 * остаётся от неё на настоящем телефоне после адресной строки и панелей. Порог
 * 600 взят от второй: блок должен начинаться с запасом, а не «ровно на границе».
 */
const ПРЕДЕЛ_СВЕРХУ = 600;
const ШИРИНА = 390;
const ВЫСОТЫ = [844, 700];

/** Верх блока цены относительно окна. null — блока нет вовсе. */
async function верхБлокаЦены(page: Page): Promise<number | null> {
  const блок = page.locator("[data-devhub-price]").first();
  if ((await блок.count()) === 0) return null;
  const рамка = await блок.boundingBox();
  return рамка ? рамка.y : null;
}

for (const адрес of ["/devhub", "/en/devhub"]) {
  test.describe(`цена видна без прокрутки: ${адрес}`, () => {
    for (const высота of ВЫСОТЫ) {
      test(`${ШИРИНА}x${высота}`, async ({ page }) => {
        await page.setViewportSize({ width: ШИРИНА, height: высота });
        // Метка канала — требование оркестратора: без неё замер попадёт в прямые
        // заходы и в «начала оплаты» и испортит воронку, которую мы же и мерим.
        await page.goto(`${адрес}?c=probe-0c`, { waitUntil: "domcontentloaded" });
        // Страница клиентская: ждём, пока блок появится после гидрации.
        await page.locator("[data-devhub-price]").first().waitFor({ state: "visible", timeout: 20_000 });

        const верх = await верхБлокаЦены(page);
        expect(верх, "блока цены нет на странице вовсе").not.toBeNull();
        expect(
          Math.round(верх!),
          `верх блока цены на y=${Math.round(верх!)} при окне ${ШИРИНА}x${высота}. ` +
            `Предел ${ПРЕДЕЛ_СВЕРХУ}: на настоящем телефоне адресная строка съедает ` +
            "около 100 px, и всё ниже уходит под сгиб. Поднимите блок выше в разметке — " +
            "менять порог нельзя, он взят из замера приёмки.",
        ).toBeLessThanOrEqual(ПРЕДЕЛ_СВЕРХУ);
      });
    }

    test(`${адрес}: прибор исправен — координаты вообще меряются`, async ({ page }) => {
      // Без этого контроля «y меньше предела» было бы зелёным и при нулевой
      // рамке, то есть на невидимом или нулевом по размеру блоке.
      await page.setViewportSize({ width: ШИРИНА, height: 844 });
      await page.goto(`${адрес}?c=probe-0c`, { waitUntil: "domcontentloaded" });
      const блок = page.locator("[data-devhub-price]").first();
      await блок.waitFor({ state: "visible", timeout: 20_000 });
      const рамка = await блок.boundingBox();
      expect(рамка, "рамка блока не измерилась").not.toBeNull();
      expect(рамка!.height, "высота блока нулевая — он невидим, и координата ничего не значит").toBeGreaterThan(8);
      expect(рамка!.width, "ширина блока нулевая").toBeGreaterThan(40);
      // И сама цена внутри: блок без числа бесполезен, как бы высоко он ни стоял.
      const текст = (await блок.innerText()).trim();
      expect(текст.length, "блок цены пуст").toBeGreaterThan(10);
      expect(/\$\d/.test(текст), `в блоке цены нет суммы: ${текст.slice(0, 80)}`).toBe(true);
    });
  });
}
