import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Поле ввода промта стоит ВЫШЕ объяснения, а не под ним.
 *
 * Модуль открывается промтом «опиши — сделаю», а не абзацами: это прямое
 * требование основателя (feedback_devhub_prompt_first_ux), и оно же вытекает из
 * замера. Вертикальный бюджет витрины на 360×640, снятый браузером на
 * выкаченном проде 09.09.2026:
 *
 *   218px  шапка сайта          — не наша зона
 *   189px  навигация волны      — не наша зона
 *    28px  отступы контейнера   — не наша зона
 *   169px  заголовок + подпись + кнопка
 *    60px  заголовок карточки
 *   101px  подзаголовок карточки   ← перенесён ПОД поле
 *   -----
 *   859px  до поля ввода при сгибе 640
 *
 * То есть единственный орган управления, ради которого страница существует,
 * лежал на 219px ниже первого экрана телефона. Из наших четырёхсот пикселей
 * подзаголовок — единственный, который можно перенести, ничего не потеряв:
 * человек читает объяснение ПОСЛЕ того, как увидел, куда писать.
 *
 * Сторож охраняет ПОРЯДОК, а не текст. Текст держат соседи: длину строк —
 * promptEntryStaysReachable, оговорку про Visual Edit — он же по словарю.
 *
 * ⚠️ Граница честная: порядок в разметке — не то же самое, что порядок на
 * экране (CSS умеет переставлять). Пиксели подтверждает только браузер, и
 * ожидание записано в коммите: на 390×844 поле должно стать видно целиком.
 */

const PAGE = path.join(__dirname, "..", "page.tsx");

function source(): string {
  return fs.readFileSync(PAGE, "utf8");
}

describe("поле ввода промта стоит выше объяснения", () => {
  test("оба ориентира на месте — иначе сторож ослеп, а не позеленел", () => {
    const s = source();
    expect(s.indexOf("<textarea"), "не нашёл поле ввода на витрине").toBeGreaterThan(0);
    expect(s.indexOf('t("hero.subtitle")'), "не нашёл подзаголовок").toBeGreaterThan(0);
  });

  test("поле идёт в разметке РАНЬШЕ подзаголовка", () => {
    const s = source();
    const field = s.indexOf("<textarea");
    const explanation = s.indexOf('t("hero.subtitle")');
    expect(
      field,
      "подзаголовок вернулся выше поля: на телефоне это опускает поле ввода " +
        "примерно на 115px и уводит его за первый экран",
    ).toBeLessThan(explanation);
  });

  test("подзаголовок никуда не делся — переносили, а не удаляли", () => {
    const s = source();
    expect(s.split('t("hero.subtitle")').length - 1, "подзаголовок должен быть ровно один").toBe(1);
  });
});
