import { describe, test, expect } from "vitest";
import * as fs from "node:fs";
import * as path from "node:path";
import { stripComments } from "./_stripComments";

// Оценочная статистика дебютов подписана как оценочная. 19.08.2026.
//
// Пока настоящие цифры не пришли, панель подставляла выдуманные: число партий и
// проценты побед. Подстановка была молчаливой — человек видел «из 1240 партий:
// White 54%» и выбирал дебют по цифрам, которых никто не считал.
//
// Ряд намеренно НЕ убирается: пустая таблица на месте статистики хуже честной
// прикидки — человек решит, что дебют не изучен вовсе. Разницу делает подпись.

const SRC = path.join(__dirname, "..", "OpeningRepertoire.tsx");
const src = () => stripComments(fs.readFileSync(SRC, "utf-8"));

describe("оценочные цифры дебютов подписаны", () => {
  test("признак подстановки заведён", () => {
    expect(src()).toMatch(/const usingSample = !replies;/);
  });

  test("подпись показывается именно при подстановке", () => {
    const s = src();
    expect(s).toMatch(/\{usingSample && !loading && \(/);
    expect(s).toMatch(/book-stats-sample/);
  });

  test("подпись говорит, ЧТО именно оценочное", () => {
    // «Данные примерные» без уточнения человек пропускает мимо: важно назвать
    // проценты и число партий, потому что решение принимается по ним.
    const s = src();
    expect(s).toMatch(/Проценты и число партий/);
  });

  test("данные не исчезают — подписываются", () => {
    // Проверка обратной стороны: «починка» вида «не показывать ничего» прошла
    // бы как успех и сделала бы панель бесполезной.
    expect(src()).toMatch(/const stats = replies \|\| mockBookStats\(branch\);/);
  });
});
