import { describe, expect, it } from "vitest";

import { CHANNELS } from "@/lib/products";
import { readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Короткие адреса каналов ведут туда, куда обещают, И несут метку.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ТЕСТ. Сторож живых страниц (`pages-live-smoke.js`) ходит с
 * `redirect: "follow"` и видит только итог: страница открылась, размер годный,
 * бренд на месте. Если короткий адрес однажды поведёт на `/go` БЕЗ метки —
 * он этого не заметит, потому что итоговая страница будет исправной.
 *
 * А цена ошибки тут ровно та, ради которой адреса и заведены: без метки
 * посетитель попадает в канал `direct`, и ноль в `tt` читается как «ролики не
 * сработали», хотя не сработала атрибуция.
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, "..");

/** Короткий адрес → куда обязан вести. Список ведётся руками намеренно: он и
 *  есть утверждение, которое проверяется. */
const ROUTES: Array<[string, string]> = [
  ["tt", "/go?c=tt"],
  ["ig", "/go?c=ig"],
  ["yt", "/go?c=yt"],
  ["dz", "/go?c=dz"],
  ["vk", "/go?c=vk"],
  ["tg", "/go?c=tg"],
  ["th", "/go?c=th"],
  ["fb", "/go?c=fb"],
  ["x", "/go?c=x"],
  ["qr", "/go?c=qr"],
  // 15.09.2026: метки li/bs пришли в CHANNELS выкаткой 970e30d1d72e без входов.
  ["li", "/go?c=li"],
  ["bs", "/go?c=bs"],
  // Западные площадки, 08.09.2026. Ведут НЕ на /go, а на английскую страницу
  // продукта: черновики Show HN и Product Hunt написаны про DevHub, и вести
  // человека из объявления на общий вход «что почитать и попробовать» значит
  // терять его на первом же экране.
  ["hn", "/en/devhub?c=hn"],
  ["ph", "/en/devhub?c=ph"],
  // 30.09.2026: каталог LaunchNest. Имя маршрута — ключ канала целиком, а не
  // короткое «ln»: проверка ниже сверяет имя маршрута с ключом в CHANNELS.
  ["launchnest", "/en/devhub?c=launchnest"],
  // 02.10.2026: каталог Uneed. Ключ канала короткий («un»), поэтому и имя
  // маршрута короткое — проверка ниже сверяет имя маршрута с ключом в CHANNELS.
  // Цель та же, что у /ph: в каталоге стоит карточка DevHub, и вести человека
  // на общий вход значит терять его на первом же экране.
  ["un", "/en/devhub?c=un"],
  // 29.09.2026. Эти одиннадцать входов СУЩЕСТВОВАЛИ, а в списке их не было —
  // проверка «у каждой метки каталога есть вход» краснела на исправном коде.
  // Список ведётся руками намеренно (он и есть утверждение), но заводить метку
  // и страницу, не дописав сюда, значит обманывать себя же: сторож покажет
  // дыру там, где её нет, и к нему перестанут прислушиваться.
  // Цели взяты из самих страниц, а не придуманы: русскоязычные площадки ведут
  // на русскую страницу продукта, западные — на английскую.
  ["rd", "/en/devhub?c=rd"],
  ["reddit", "/en/devhub?c=reddit"],
  ["ih", "/en/devhub?c=ih"],
  ["habr", "/devhub?c=habr"],
  ["vc", "/devhub?c=vc"],
  ["mail", "/bureau?c=mail"],
  // Метки, которые ставит НАШ код или платная кампания, а не человек в подписи.
  // Вход им всё равно нужен: по нему приходят с уже опубликованных сайтов
  // (бейдж «Сделано в AEVION») и с рекламных объявлений.
  // 06.10.2026, приёмка волны 18: ветвь 761fe1ec8 завела метку `example`
  // (галерея примеров DevHub) и СОЗДАЛА страницу src/app/example/page.tsx,
  // но в этот список её не внесла — сторож ровно это и поймал. Адрес взят из
  // самой страницы: она делает redirect("/devhub?c=example").
  ["example", "/devhub?c=example"],
  // 07.10.2026: платная реклама Meta. Канал завёден волной 23 (`meta-*` — только
  // платное, `fb-*` остаётся органическим), вход ведёт на страницу книги, под
  // которую реклама и запускается.
  ["meta", "/longevity?c=meta"],
  ["badge", "/devhub?c=badge"],
  ["x-devhub", "/devhub?c=x-devhub"],
  ["x-multichat", "/multichat-engine?c=x-multichat"],
  ["ads-devhub", "/devhub?c=ads-devhub"],
  ["ads-multichat", "/multichat-engine?c=ads-multichat"],
  ["en/tt", "/en/go?c=tt"],
  ["en/ig", "/en/go?c=ig"],
  ["en/yt", "/en/go?c=yt"],
];

describe("реестр каналов и короткие входы — одна сущность", () => {
  // ЗАЧЕМ ОТДЕЛЬНАЯ ПРОВЕРКА. Список ROUTES выше ведётся руками, и это верно:
  // он утверждение о том, какие входы мы обещаем. Но сам по себе он не связан
  // с каталогом CHANNELS — можно завести метку канала и забыть про вход.
  //
  // Ровно это и было. Замер 30.08.2026: каталог знал ДЕСЯТЬ меток, коротких
  // входов существовало шесть. Метки при этом работали — /go?c=th и остальные
  // три доводили метку до кассы на живом проде, — а /th, /fb, /x, /qr
  // отвечали 404. То есть в подпись под постом было нечего поставить, и
  // человек приходил без метки, в канал direct.
  //
  // Проверка связывает две сущности: каждая метка каталога обязана иметь вход.
  it("у каждой метки каталога есть короткий вход", () => {
    const known = new Set(ROUTES.filter(([r]) => !r.startsWith("en/")).map(([r]) => r));
    const missing = Object.keys(CHANNELS).filter((c) => !known.has(c));
    expect(missing, "метка канала есть, а короткого адреса для подписи нет").toEqual([]);
  });

  it("каждый короткий вход ведёт ИЗВЕСТНУЮ каталогу метку", () => {
    /*
     * 🔴 Обратная сторона той же связи, и её здесь НЕ БЫЛО. Найдено мутацией
     * 02.10.2026: убрал метку `un` из CHANNELS — оба сторожа остались ЗЕЛЁНЫМИ.
     * А страница /un при этом жива и продолжает присылать `?c=un`, которого
     * каталог уже не знает: channelFrom вернёт null, и переход ляжет в «прямые
     * заходы». То есть ровно та потеря, ради которой проверка выше и написана,
     * только с другой стороны — и она проходила молча.
     *
     * Проверка односторонней связи стережёт половину: «у каждой метки есть
     * вход» и «каждый вход ведёт известную метку» — разные утверждения, и
     * ломаются они по-разному.
     *
     * Замер на момент добавления: маршрутов 30, меток 27, чужих 0.
     */
    const метки = new Set(Object.keys(CHANNELS));
    const чужие = ROUTES.map(([r]) => r.split("/").pop()!).filter((м) => !метки.has(м));
    expect(ROUTES.length, "список маршрутов пуст — проверка ничего не значит").toBeGreaterThan(20);
    expect(
      чужие,
      "короткий вход присылает метку, которой каталог не знает: переход ляжет в «прямые заходы»",
    ).toEqual([]);
  });

  it("каталог вообще не пуст — иначе проверка выше ничего не значит", () => {
    // Контроль охвата: переименуют CHANNELS или сломается импорт — список
    // станет пустым, и проверка «нет пропущенных» пройдёт, не проверив ничего.
    expect(Object.keys(CHANNELS).length).toBeGreaterThanOrEqual(8);
  });
});

describe("короткие адреса каналов", () => {
  it("каждый существует и ведёт по своему адресу с меткой", () => {
    for (const [route, target] of ROUTES) {
      const file = join(APP, ...route.split("/"), "page.tsx");
      expect(existsSync(file), `нет страницы для /${route}`).toBe(true);
      const src = readFileSync(file, "utf8");
      expect(src, `/${route}: нет redirect()`).toContain("redirect(");
      expect(src, `/${route}: ведёт не на ${target}`).toContain(`redirect("${target}")`);
    }
  });

  it("метка канала в цели совпадает с самим адресом", () => {
    // Ловит опечатку копипасты: страница /ig, а метка c=tt. Такую ошибку
    // невозможно увидеть по цифрам — канал просто окажется не тот.
    for (const [route, target] of ROUTES) {
      const channel = route.split("/").pop();
      expect(target, `/${route}: метка не совпадает с адресом`).toContain(`c=${channel}`);
    }
  });

  it("короткие адреса закрыты от поисковика", () => {
    // Иначе они соревнуются в выдаче с той страницей, на которую ведут.
    for (const [route] of ROUTES) {
      const src = readFileSync(join(APP, ...route.split("/"), "page.tsx"), "utf8");
      expect(src, `/${route}: нет metadata`).toContain("export const metadata");
      expect(src.replace(/\s+/g, ""), `/${route}: индексация не запрещена`).toContain("index:false");
    }
  });

  /*
   * 🔴 ЗАПРЕТ ВЕТВЛЕНИЯ ЗАМЕНЁН ЗАПРЕТОМ ЛИШНЕГО (07.10.2026).
   *
   * Прежнее правило — «в коротком входе нет никакой логики, кроме
   * перенаправления» — писалось против тихого увода посетителя: любое условие
   * означает, что часть людей уедет не туда, и заметить это будет нечем. Оно
   * верное по СТРАХУ и неверное по БУКВЕ: 06.10 исключение пришлось дать
   * /example, а 07.10 ветвиться обязаны ВСЕ входы.
   *
   * Почему обязаны. Вход без ветвления подставляет свою метку жёстко, то есть
   * СТИРАЕТ входящую: /yt?c=yt-30-dney-devhub уезжала на /go?c=yt, и ответ на
   * вопрос «какой ролик дал переход» пропадал. Запрет ветвления охранял канал
   * и ГАРАНТИРОВАЛ при этом потерю поста.
   *
   * Поэтому правило переписано по смыслу, а не ослаблено. Разрешено ровно одно
   * ветвление — выбор между донесённой и своей меткой, — и форма каждого входа
   * сверяется ДОСЛОВНО: три рабочих строки, ни одной лишней. Это СИЛЬНЕЕ
   * прежнего запрета: прежний позволял любой код без «if» (сеть ловилась
   * отдельной строкой, а чтение cookie — нет), новый не позволяет ничего,
   * кроме названной формы.
   *
   * Опасение «заметить будет нечем» снимается не словом автора, а сторожем
   * shortEntryCarriesTheWholeTag: он ИСПОЛНЯЕТ все входы и разбирает оба пути.
   * Проверка ниже требует его наличия, обоих путей и знаменателя — исчезнет
   * он, и форма входов останется без поведенческого подтверждения.
   */
  const ПОВЕДЕНЧЕСКИЙ_СТОРОЖ = "../lib/__tests__/shortEntryCarriesTheWholeTag.guard.test.ts";
  const ПЕРЕВОД = String.fromCharCode(10);
  const КАВЫЧКА = String.fromCharCode(34);
  const ОБРАТНАЯ = String.fromCharCode(96);

  it("ветвление ОПЛАЧЕНО поведенческим сторожем на ВСЕ входы", () => {
    const файл = join(APP, ...ПОВЕДЕНЧЕСКИЙ_СТОРОЖ.split("/"));
    expect(existsSync(файл), "обещанного сторожа НЕТ — форма входов без подтверждения").toBe(true);
    const сторож = readFileSync(файл, "utf8");
    // Оба пути обязательны: сторож только на «без метки» оставил бы потерю
    // входящей метки незамеченной, а только на «с меткой» — потерю своей.
    expect(сторож.includes("post-7"), "сторож не проверяет, что входящая метка ДОЕЗЖАЕТ").toBe(true);
    expect(сторож.includes("без метки доносит свою"), "сторож не проверяет случай БЕЗ метки").toBe(true);
    /*
     * Знаменатель: без него сторож может проверять пустоту и быть зелёным.
     *
     * Число НЕ дословное, и это поправка по замечанию окна 98 (07.10.2026):
     * дословное «32» покраснело бы на следующем же заведённом канале, то есть
     * исправная работа соседа выглядела бы поломкой. Проверяется ПОРОГ не ниже
     * тридцати — он растёт вместе с каталогом, а исчезновение знаменателя
     * по-прежнему ловится.
     */
    const знаменатель = сторож.match(/toBeGreaterThanOrEqual\(\s*(\d+)\s*\)/g) ?? [];
    const числа = знаменатель.map((с) => Number(с.replace(/[^0-9]/g, "")));
    expect(
      числа.some((н) => н >= 30),
      "у сторожа нет знаменателя не ниже 30 — он может проверять пустоту",
    ).toBe(true);
    const утверждений = (сторож.match(/expect\(/g) ?? []).length;
    expect(утверждений, "утверждений в стороже мало для исключения").toBeGreaterThanOrEqual(8);
  });

  it("форма каждого входа — ровно три рабочих строки, ни одной лишней", () => {
    for (const [route, target] of ROUTES) {
      const метка = route.split("/").pop()!;
      const цель = target.split("?c=")[0];
      const src = readFileSync(join(APP, ...route.split("/"), "page.tsx"), "utf8");
      const телоС = src.indexOf("}) {");
      expect(телоС >= 0, "/" + route + ": тело функции не найдено — форма изменилась").toBe(true);
      const рабочие = src
        .slice(телоС + 4)
        .split(ПЕРЕВОД)
        .map((л) => л.trim())
        .filter(
          (л) =>
            л &&
            !л.startsWith("//") &&
            !л.startsWith("*") &&
            !л.startsWith("/*") &&
            л !== "}" &&
            л !== "*/",
        );
      const ожидаемые = [
        "const метка = меткаДляПерехода((await searchParams).c, " + КАВЫЧКА + метка + КАВЫЧКА + ");",
        "if (метка !== " + КАВЫЧКА + метка + КАВЫЧКА + ") redirect(" + ОБРАТНАЯ + цель + "?c=${метка}" + ОБРАТНАЯ + ");",
        "redirect(" + КАВЫЧКА + target + КАВЫЧКА + ");",
      ];
      expect(
        рабочие,
        "/" + route + ": форма входа другая. Короткий вход обязан НЕСТИ входящую метку " +
          "целиком, иначе он её стирает (замер 07.10.2026: так терялся ключ поста). " +
          "Возьмите форму из любого соседнего входа, например src/app/yt/page.tsx.",
      ).toEqual(ожидаемые);
    }
  });

  it("в них нет запроса к сети и чтения состояния", () => {
    // Короткий адрес — вход, а не страница. Проверка формы выше это уже
    // обеспечивает; здесь прямой запрет на самое дорогое, чтобы причина
    // покраснения читалась сразу, без разбора формы.
    for (const [route] of ROUTES) {
      const src = readFileSync(join(APP, ...route.split("/"), "page.tsx"), "utf8");
      const code = src
        .split(ПЕРЕВОД)
        .filter((l) => !l.trim().startsWith("//") && !l.trim().startsWith("*") && !l.trim().startsWith("/*"))
        .join(ПЕРЕВОД);
      for (const запрет of ["fetch(", "localStorage", "sessionStorage", "cookies(", "document."]) {
        expect(code.includes(запрет), "/" + route + ": появилось " + запрет).toBe(false);
      }
    }
  });
});
