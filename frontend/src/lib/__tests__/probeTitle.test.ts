import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { служебноеНазвание } from "../probeTitle";
import { безКомментариев } from "./helpers/sourceWithoutComments";

/**
 * Служебные записи не выходят на публичные витрины.
 *
 * ЗАЧЕМ. Правило §19: создающий запрос на прод помечается в названии и
 * убирается следом. Замер 28.09.2026 показал, что «убрать» — не одно действие.
 * Конвейер `/api/pipeline/protect` пишет сразу в несколько мест. У QRight
 * скрытие проб ВСТРОЕНО в выдачу (`ownerName = 'smoke-test'`), и там моя проба
 * не появилась. А в Quantum Shield запись уезжает БЕЗ поля владельца — только с
 * названием объекта, — и та же самая проба висела на публичной витрине, 1 из 7.
 *
 * Я проверил витрину QRight, увидел ноль и счёл уборку сделанной. У одной
 * записи столько витрин, сколько модулей её увидели, и проверять надо каждую.
 */

describe("служебное название узнаётся", () => {
  it("наши метки по §19", () => {
    expect(служебноеНазвание("probe-28-09 первое действие гостя")).toBe(true);
    expect(служебноеНазвание("smoke-music-test")).toBe(true);
    expect(служебноеНазвание("Test-прогон кассы")).toBe(true);
    expect(служебноеНазвание("Проба пера")).toBe(true);
  });

  it("метка в середине названия тоже считается", () => {
    // Скрипты пишут «Мой объект smoke-3» не реже, чем «smoke-мой объект».
    expect(служебноеНазвание("Мой объект smoke-3")).toBe(true);
  });

  it("ОТРИЦАТЕЛЬНЫЙ контроль: чужую работу не прячем", () => {
    /*
     * Это половина важнее первой: слишком жадный признак стирает с витрины
     * настоящих авторов, и заметить это некому — витрина просто беднее.
     */
    expect(служебноеНазвание("AI Music Generator v2.1")).toBe(false);
    expect(служебноеНазвание("Quantum Shield Protocol Whitepaper")).toBe(false);
    expect(служебноеНазвание("Протест против тестирования животных")).toBe(false);
    expect(служебноеНазвание("Contestant list 2026")).toBe(false);
    expect(служебноеНазвание("")).toBe(false);
    expect(служебноеНазвание(null)).toBe(false);
    expect(служебноеНазвание(undefined)).toBe(false);
  });

  it("витрина Quantum Shield действительно спрашивает признак", () => {
    /*
     * Сам признак может быть исправен, а витрина — не звать его. Комментарии
     * снимаем: в объяснении рядом с правкой это же имя упоминается, и без
     * снятия сторож остался бы зелёным на пустом месте (уже ловилось сегодня).
     */
    const страница = безКомментариев(
      readFileSync(join(__dirname, "..", "..", "app", "quantum-shield", "page.tsx"), "utf8"),
    );
    /*
     * Держимся за ФАКТ вызова, а не за имя: 29.09.2026 признак пришлось
     * ввести в файл под латинским псевдонимом (`as isProbeTitle`) — свои
     * кириллические имена в этом файле ломали другого сторожа, который по
     * ним считал английскую страницу русской. Проверка, привязанная к
     * написанию имени, покраснела бы на верной правке.
     */
    expect(
      страница.includes('from "@/lib/probeTitle"'),
      "витрина Quantum Shield больше не берёт признак пробы из общего дома",
    ).toBe(true);
    expect(
      /\.filter\(\(r\) => !\w+\(r\.objectTitle\)\)/.test(страница),
      "витрина Quantum Shield снова показывает наши пробы посетителю",
    ).toBe(true);
  });
});
