#!/usr/bin/env node
/**
 * QSkyway — ingest FAA UAS Facility Map (UASFM) airspace ceilings for a city twin.
 *
 * The FAA publishes, as an open ArcGIS FeatureServer with no API key, the grid of
 * maximum altitudes at which small-UAS flight can be authorized automatically
 * (LAANC) inside controlled airspace. Each feature is an axis-aligned 1/120°
 * cell carrying CEILING (feet AGL) plus the controlling airspace class/airport.
 *
 * We ingest it as-is — the source cells, not a re-derived approximation — so the
 * committed data can be re-fetched and diffed against the regulator any time.
 *
 * Usage:
 *   node scripts/fetch-faa-airspace.mjs nyc > src/routes/qskyway.airspace.nyc.ts
 *
 * Honest scope: UASFM is a *small-UAS* (Part 107) authorization grid, not eVTOL
 * air-taxi certification. It is used here as the real, regulator-published
 * altitude constraint over the twin — the closest authoritative free feed that
 * exists — and QSkyway labels it exactly that way everywhere it surfaces.
 * US-only: no equivalent keyless feed was found for Astana (KZ) or Tokyo (JCAB).
 */

const FEED =
  "https://services6.arcgis.com/ssFJjBXIUyZDrSYZ/arcgis/rest/services/FAA_UAS_FacilityMap_Data/FeatureServer/0/query";

// bbox must match the committed city twin exactly (qskyway.city.<id>.ts → bbox)
const CITY_BBOX = {
  nyc: { minLat: 40.7474728, maxLat: 40.7629936, minLon: -74.0002478, maxLon: -73.9758674 },
};

const cityId = process.argv[2];
const bbox = CITY_BBOX[cityId];
if (!bbox) {
  console.error(`unknown city "${cityId}" — known: ${Object.keys(CITY_BBOX).join(", ")}`);
  process.exit(1);
}

const params = new URLSearchParams({
  geometry: `${bbox.minLon},${bbox.minLat},${bbox.maxLon},${bbox.maxLat}`,
  geometryType: "esriGeometryEnvelope",
  inSR: "4326",
  outSR: "4326",
  spatialRel: "esriSpatialRelIntersects",
  outFields: "OBJECTID,CEILING,UNIT,MAP_EFF,AIRSPACE_1,APT1_ICAO,APT1_NAME,APT1_LAANC",
  returnGeometry: "true",
  f: "json",
});

const res = await fetch(`${FEED}?${params}`, { signal: AbortSignal.timeout(60_000) });
if (!res.ok) throw new Error(`FAA feed HTTP ${res.status}`);
const data = await res.json();
if (data.error) throw new Error(`FAA feed error: ${JSON.stringify(data.error)}`);
if (data.exceededTransferLimit) throw new Error("FAA feed truncated the result — narrow the bbox or page it");

const features = data.features ?? [];
if (!features.length) throw new Error("FAA feed returned no cells for this bbox");

const FT_TO_M = 0.3048;
const cells = features
  .map((f) => {
    const a = f.attributes;
    if (a.UNIT !== "Feet") throw new Error(`unexpected CEILING unit "${a.UNIT}" — ingest assumes feet`);
    const ring = f.geometry.rings[0];
    const lons = ring.map((p) => p[0]);
    const lats = ring.map((p) => p[1]);
    return {
      id: `faa-${a.OBJECTID}`,
      minLon: +Math.min(...lons).toFixed(7),
      maxLon: +Math.max(...lons).toFixed(7),
      minLat: +Math.min(...lats).toFixed(7),
      maxLat: +Math.max(...lats).toFixed(7),
      ceilingFt: a.CEILING,
      ceilingM: Math.round(a.CEILING * FT_TO_M),
      airspaceClass: a.AIRSPACE_1 ?? null,
      airportIcao: a.APT1_ICAO ?? null,
      airportName: a.APT1_NAME ?? null,
      laanc: a.APT1_LAANC === 1,
      effective: a.MAP_EFF ?? null,
    };
  })
  .sort((a, b) => a.minLat - b.minLat || a.minLon - b.minLon);

const effectives = [...new Set(cells.map((c) => c.effective).filter(Boolean))];
const airspace = {
  source: "FAA UAS Facility Map (UASFM)",
  sourceUrl: "https://services6.arcgis.com/ssFJjBXIUyZDrSYZ/arcgis/rest/services/FAA_UAS_FacilityMap_Data/FeatureServer/0",
  authority: "FAA",
  regime: "Part 107 small-UAS LAANC authorization ceilings",
  effective: effectives.length === 1 ? effectives[0] : effectives.join(", "),
  fetched: new Date().toISOString().slice(0, 10),
  // The exact envelope this snapshot was queried with, so the running service can
  // re-ask the regulator the identical question and detect drift (see
  // qskyway.airspace.freshness.ts). Without it a "freshness" check would compare
  // against a different area and report phantom changes.
  bbox,
  cells,
};

const banner = `// QSkyway — FAA UAS Facility Map airspace ceilings over the ${cityId.toUpperCase()} twin.
// Generated by scripts/fetch-faa-airspace.mjs ${airspace.fetched}. Do not edit by hand.
//
// Real regulator-published data (FAA UASFM, open ArcGIS feed, no key). CEILING is
// the maximum altitude AGL at which small-UAS flight is automatically authorizable
// (LAANC) in that cell; 0 ft means no automatic authorization — ATC coordination
// required. This is a Part 107 small-UAS grid, NOT eVTOL air-taxi certification;
// QSkyway uses it as the authoritative altitude-constraint layer and says so.
/* eslint-disable */
import type { CityAirspace } from "./qskyway.airspace";
`;

process.stdout.write(`${banner}
export const AIRSPACE_${cityId.toUpperCase()}: CityAirspace = ${JSON.stringify(airspace, null, 2)};
`);

console.error(
  `[faa] ${cityId}: ${cells.length} cells, ceilings ft: ${[...new Set(cells.map((c) => c.ceilingFt))].sort((a, b) => a - b).join("/")}, effective ${airspace.effective}`,
);
