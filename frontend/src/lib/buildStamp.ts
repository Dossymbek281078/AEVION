/**
 * Отметка сборки САЙТА. Проставляется scripts/vercel-deploy.sh перед загрузкой
 * и возвращается обратно после — в git обязаны лежать ЗАГЛУШКИ.
 *
 * 29.08.2026 сюда попала настоящая отметка чужой выкатки
 * (`55f3848bc7f2` / `feat/funnel-upsell-allaccess`), то есть скрипт не вернул
 * файл. Чем это опасно: всякий, кто соберёт сайт НЕ через скрипт, отгрузит
 * страницу, уверенно называющую чужой коммит. Ровно так на Railway `/health`
 * однажды сутки называл коммит, которого на проде не было.
 *
 * Заглушки в git — намеренно: сборка не должна падать оттого, что собрали не
 * скриптом, она должна честно ответить "unknown".
 *
 * Тип объявлен ЯВНО и без `as const`: с `as const` типы сужаются до литералов,
 * и сравнение `BUILD_STAMP.commit !== "unknown"` в /api/health становится
 * ошибкой типов ровно тогда, когда отметка ЗАПОЛНЕНА — то есть сборка падает
 * только на настоящей выкатке.
 */
export type BuildStamp = {
  commit: string;
  branch: string;
  builtAt: string | null;
};

export const BUILD_STAMP: BuildStamp = {
  commit: "unknown",
  branch: "unknown",
  builtAt: null,
};
