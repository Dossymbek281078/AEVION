#!/usr/bin/env bash
# Выкатка САЙТА на Vercel с честной отметкой сборки.
#
# Зачем скрипт, а не одна команда `vercel deploy --prod`. У сайта в /api/health
# есть поле build — им снаружи доказывают, КАКОЙ код сейчас работает. Проверено
# выкаткой 18.08.2026: при загрузке рабочей папкой Vercel НЕ подставляет
# VERCEL_GIT_COMMIT_SHA, и поле честно ответило "unknown". Переменные проекта
# для этого не годятся по другой причине, и она дороже: они живут в проекте, а
# не в сборке, и переживают чужую выкатку — на Railway из-за этого /health
# уверенно называл коммит, которого на проде уже не было.
#
# Поэтому отметка едет ВНУТРИ артефакта: скрипт вписывает её в
# src/lib/buildStamp.ts перед загрузкой и возвращает файл обратно после.
#
# Перед выкаткой обязательна проверка, не уберёт ли она чужие страницы:
# Vercel хранит ровно одну сборку сайта, а фронт правят несколько сессий.
#
# Использование:
#   bash frontend/scripts/vercel-deploy.sh "короткое описание"

set -euo pipefail

MSG="${1:-выкатка без описания}"
FRONT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
REPO_ROOT="$(cd "$FRONT_DIR/.." && pwd)"
STAMP="$FRONT_DIR/src/lib/buildStamp.ts"
cd "$REPO_ROOT"

SHA="$(git rev-parse HEAD)"
BRANCH="$(git rev-parse --abbrev-ref HEAD)"

# ── Куда именно поедет эта выкатка ──────────────────────────────────────────
#
# 23.08.2026: скрипт прошёл ВСЕ свои проверки и создал НОВЫЙ проект Vercel.
# Привязка .vercel/project.json лежит вне git — и правильно, это состояние
# CLI, — но значит, что в свежем worktree её просто НЕТ. Публикация в таком
# случае не отказывается: CLI молча заводит проект по имени каталога
# (получился aevion-paylinks), грузит туда КОРЕНЬ репозитория и падает на
# сборке «No Next.js version detected».
#
# Повезло, что упало. Успех был бы хуже: «выкатил» означало бы «опубликовал в
# никуда», aevion.app остался бы со старым кодом, а отметка на сайте — чужой.
# Ровно тот класс, против которого написан весь этот скрипт: успех, которого
# не было.
#
# Три исхода, а не два: привязки нет — отказ; привязка на ЧУЖОЙ проект —
# отказ; совпало — едем и говорим вслух, куда.
LINK="$REPO_ROOT/.vercel/project.json"
WANT_PROJECT="aevion"
if [ ! -f "$LINK" ]; then
  echo "ОСТАНОВКА: нет $LINK — этот worktree не привязан к проекту Vercel." >&2
  echo "  Без привязки CLI ЗАВЕДЁТ НОВЫЙ проект по имени каталога и выкатит в него," >&2
  echo "  а боевой сайт останется со старым кодом." >&2
  echo "  Возьмите привязку у соседнего worktree, например:" >&2
  echo "    mkdir -p .vercel && cp ../aevion-launch/.vercel/project.json .vercel/" >&2
  exit 1
fi
HAVE_PROJECT="$(grep -o '"projectName"[^,]*' "$LINK" | head -1 | cut -d'"' -f4)"
if [ "$HAVE_PROJECT" != "$WANT_PROJECT" ]; then
  echo "ОСТАНОВКА: привязка ведёт в проект '$HAVE_PROJECT', а сайт живёт в '$WANT_PROJECT'." >&2
  echo "  Выкатка ушла бы не туда. Замените $LINK привязкой боевого проекта." >&2
  exit 1
fi
echo "проект Vercel: $HAVE_PROJECT"

# ── Кто-то уже выкатывает прямо сейчас? ──────────────────────────────────────
#
# Щель, которую проверка «чья работа на проде» закрыть НЕ МОЖЕТ. Она спрашивает
# сайт ПЕРЕД загрузкой, а дальше артефакт уходит наружу и Vercel собирает его у
# себя ещё 5–9 минут. Соседняя вкладка за это время успевает выкатить своё, и
# наша сборка, уже необратимо ушедшая, публикуется поверх.
#
# Замер 19.08.2026: так вышло ДВАЖДЫ за час. Первый раз я снёс бы подтверждение
# домена для TikTok, второй — честную подпись сертификата и пять исправленных
# обещаний на витрине. Оба раза спасал не сторож, а то, что я смотрел на список
# выкаток руками.
#
# Отметка общая для всех вкладок, живёт 15 минут (сборка укладывается),
# снимается в trap. Протухшую игнорируем и говорим об этом: иначе упавшая
# выкатка заблокировала бы сайт навсегда, а сторож, валящий работу, будет
# отключён в первый же день.
INFLIGHT="$HOME/.aevion-frontend-deploy-inflight.json"
# 2700 (45 мин), а не 900 (15). Замер 21.08.2026 по трём выкаткам подряд:
# сборка Vercel идёт 25-35 минут. Пятнадцатиминутный замок протухал НА
# СЕРЕДИНЕ чужой сборки, соседнее окно законно считало его брошенным и
# выкатывало своё — и та выкатка, что финишировала позже, откатывала работу
# другой. Ровно это и случилось сегодня: моя выкатка сняла с прода восемь
# чужих коммитов, появившихся, пока она собиралась.
#
# Порог свежести обязан быть БОЛЬШЕ длительности того, что он стережёт,
# иначе он не защищает, а выдаёт разрешение в самый опасный момент.
INFLIGHT_TTL=2700

if [ -f "$INFLIGHT" ]; then
  now=$(date +%s)
  started=$(sed -n 's/.*"startedAtEpoch": *\([0-9]*\).*/\1/p' "$INFLIGHT" 2>/dev/null || true)
  who=$(sed -n 's/.*"branch": *"\([^"]*\)".*/\1/p' "$INFLIGHT" 2>/dev/null || true)
  if [ -z "$started" ]; then
    # Файл есть, но не читается. Это НЕ «свободно» и не повод падать —
    # говорим вслух и едем: направление отказа выбирается по цене, а
    # видимость отказа не выбирается.
    echo "ВНИМАНИЕ: отметка «идёт выкатка» есть, но не разбирается — не знаю," >&2
    echo "выкатывает ли кто-то прямо сейчас. Продолжаю." >&2
  else
    age=$(( now - started ))
    # Отметка могла ПЕРЕЖИТЬ саму выкатку: снятие висит на `trap ... EXIT`, а
    # процесс иногда убивают жёстко (19.08 сборку сняли по таймауту, trap не
    # отработал — случай описан ниже в этом же файле). Тогда слот держится все
    # 45 минут при завершённой работе: 28.08 это стоило трёх заходов подряд.
    #
    # Отличить завершённую выкатку от идущей можно фактом, а не таймером: если
    # коммит из отметки УЖЕ стоит на сайте, значит публикация состоялась и
    # ждать нечего. Пока коммиты разные — держим отказ, ради этого TTL и велик
    # (короткий порог однажды позволил соседнему окну откатить чужую работу).
    marked_sha=$(sed -n 's/.*"commit": *"\([^"]*\)".*/\1/p' "$INFLIGHT" 2>/dev/null || true)
    live_now=$(curl -s --max-time 15 https://aevion.app/api/health 2>/dev/null | grep -o '"commit":"[^"]*"' | head -1 | cut -d'"' -f4 || true)
    if [ -n "$marked_sha" ] && [ -n "$live_now" ] && [ "$live_now" != "unknown" ] && \
       { [ "${live_now#"$marked_sha"}" != "$live_now" ] || [ "${marked_sha#"$live_now"}" != "$marked_sha" ]; }; then
      echo "отметка «идёт выкатка» указывает на коммит $marked_sha, и он УЖЕ на сайте —"
      echo "та выкатка завершилась, слот свободен (её процесс не снял отметку)."
      age=$INFLIGHT_TTL
    fi
    if [ "$age" -lt "$INFLIGHT_TTL" ]; then
      left=$(( (INFLIGHT_TTL - age) / 60 + 1 ))
      echo >&2
      echo "ОСТАНОВКА: прямо сейчас выкатывает другая вкладка (ветка ${who:-неизвестна})," >&2
      echo "начало $age с назад. Её сборка ещё идёт на стороне Vercel, и наша" >&2
      echo "опубликуется поверх — необратимо." >&2
      echo >&2
      echo "Подождите до $left мин и запустите снова. Если та выкатка оборвалась," >&2
      echo "отметка протухнет сама и перестанет мешать." >&2
      exit 1
    fi
    echo "отметка «идёт выкатка» протухла ($age с) — считаю свободным"
  fi
fi

release_inflight() { rm -f "$INFLIGHT" 2>/dev/null || true; }
printf '{ "startedAtEpoch": %s, "branch": "%s", "commit": "%s", "at": "%s" }\n' \
  "$(date +%s)" "$BRANCH" "${SHA:0:12}" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" > "$INFLIGHT"

# ОДИН обработчик на оба следа. В bash второй `trap ... EXIT` ЗАМЕНЯЕТ первый,
# а не добавляется к нему: два трапа рядом означали бы, что одна из уборок
# молча перестала работать, и заметили бы это только по застрявшей отметке.
cleanup() {
  git checkout -- "$STAMP" 2>/dev/null || true
  release_inflight
}
# INT и TERM отдельно: по умолчанию bash выполняет EXIT-обработчик при обычном
# завершении, но НЕ при убийстве сигналом. Проверено 19.08.2026 — прерванная
# выкатка оставляла отметку «идёт выкатка» висеть, и соседняя вкладка ждала
# впустую до истечения срока.
trap cleanup EXIT INT TERM

# Своя отметка, оставшаяся от ПРЕРВАННОЙ выкатки, — не чужие правки.
#
# 19.08.2026: сборку убило по таймауту, trap не отработал, и buildStamp.ts
# остался изменённым. Следующий запуск честно отказался ехать «есть
# незакоммиченные изменения» — верно по сути, но человек видит непонятный
# отказ и лезет разбираться в файл, который скрипт же и правит. Возвращаем
# его сами и говорим об этом вслух.
if ! git diff --quiet -- "$STAMP"; then
  if [ -z "$(git diff --name-only | grep -v "^frontend/src/lib/buildStamp.ts$")" ]      && git diff --cached --quiet; then
    echo "отметка осталась от прерванной выкатки — возвращаю её и продолжаю"
    git checkout -- "$STAMP"
  fi
fi

if ! git diff --quiet || ! git diff --cached --quiet; then
  echo "ОСТАНОВКА: в рабочей копии есть незакоммиченные изменения." >&2
  echo "Отметка показала бы ${SHA:0:12}, а уехало бы другое." >&2
  git status --short | head -20 >&2
  exit 1
fi

# Чужие страницы. Проверка опрашивает ЖИВОЙ сайт, а не читает наши файлы.
if [ -f "$HOME/aevion-frontend-check.mjs" ]; then
  if ! node "$HOME/aevion-frontend-check.mjs" "$BRANCH"; then
    echo >&2
    echo "ОСТАНОВКА: выкатка убрала бы страницы, которые сейчас на сайте." >&2
    exit 1
  fi
else
  echo "ВНИМАНИЕ: aevion-frontend-check.mjs не найден — не проверено, что" >&2
  echo "выкатка не уберёт чужие страницы. Это НЕ «всё чисто»." >&2
fi

# Не снесу ли я чужую работу, которая уже на сайте.
#
# Проверка страниц выше отвечает на другой вопрос — «не исчезнет ли адрес».
# Правки ВНУТРИ существующих страниц она не видит: 19.08.2026 я так стёр
# четыре чужие починки, и все адреса при этом отдавали 200.
#
# Признак — предок, а не имя ветки. Ветка, собранная от текущего сайта,
# называется иначе, но не сносит ничего; по имени она получала бы ложный
# отказ, а к ложным отказам быстро привыкают.
LIVE=$(curl -s --max-time 15 https://aevion.app/api/health 2>/dev/null | grep -o '"commit":"[^"]*"' | head -1 | cut -d'"' -f4 || true)

if [ -z "$LIVE" ] || [ "$LIVE" = "unknown" ]; then
  # «Не знаю» — это не «свободно». Но и валить работу нельзя: сайт может быть
  # выкачен веткой без отметки, и тогда отказ станет вечным. Говорю вслух и еду.
  echo "ВНИМАНИЕ: сайт не называет свой коммит (ответ: '${LIVE:-нет ответа}')." >&2
  echo "Чью работу заменяет эта выкатка — НЕ ПРОВЕРЕНО." >&2
elif git merge-base --is-ancestor "$LIVE" HEAD 2>/dev/null; then
  echo "на сайте $LIVE — предок HEAD, сносить нечего"
else
  echo >&2
  echo "ОСТАНОВКА: на сайте коммит $LIVE, и его НЕТ в истории вашей ветки." >&2
  echo "Выкатка стёрла бы эту работу. Сначала вобрать её:" >&2
  echo "  git merge $LIVE" >&2
  exit 1
fi


echo "ветка:  $BRANCH"
echo "коммит: ${SHA:0:12}"
echo "повод:  $MSG"


cat > "$STAMP" <<TS
/** Проставлено scripts/vercel-deploy.sh при выкатке. В git лежат заглушки. */
export type BuildStamp = {
  commit: string;
  branch: string;
  builtAt: string | null;
};

export const BUILD_STAMP: BuildStamp = {
  commit: "${SHA:0:12}",
  branch: "$BRANCH",
  builtAt: "$(date -u +%Y-%m-%dT%H:%M:%SZ)",
};
TS

# Типы проверяем ПОСЛЕ подстановки отметки и ДО загрузки.
#
# 18.08.2026 первая версия писала отметку с `as const`, и типы сужались до
# литералов: сравнение с "unknown" в /api/health становилось ошибкой ровно
# тогда, когда отметка заполнена. На заглушке всё компилировалось, а выкатка
# падала на сборке. Проверять надо ТО, ЧТО УЕЗЖАЕТ, а не то, что лежит в git.
# ── Чья сборка сейчас на сайте ────────────────────────────────────────────
# Проверка страниц выше отвечает на вопрос «не пропадёт ли адрес», но НЕ на
# вопрос «не снесу ли я чужую работу». 19.08.2026 это стоило дорого: я выкатил
# сайт, не заметив, что у выкаченной чужой ветки четыре починки, которых нет у
# меня. Остановить не вышло — сборка уже ушла на Vercel и опубликовалась сама,
# а сайт остался с build.branch = "unknown".
#
# У бэкенда такая защита есть (aevion-deploy-check.mjs + остановка в
# railway-deploy.sh), у сайта не было. Признак берём тот же и правильный: не
# имя ветки, а ПРЕДОК. Если коммит, из которого собран сайт, лежит в истории
# вашей ветки — сносить нечего, вся чужая работа уже внутри.
#
# Три исхода, а не два: сайт не ответил или отметки нет — это «не знаю», и
# тогда решает человек, а не молчаливый пропуск.
SITE_COMMIT="$(curl -s --max-time 20 https://aevion.app/api/health 2>/dev/null   | node -e "let d='';process.stdin.on('data',c=>d+=c).on('end',()=>{try{console.log((JSON.parse(d).build||{}).commit||'')}catch{console.log('')}})" 2>/dev/null || true)"

if [ -z "$SITE_COMMIT" ] || [ "$SITE_COMMIT" = "unknown" ]; then
  echo "⚠️  на сайте нет отметки сборки — чья там работа, неизвестно."
  echo "    Это не разрешение: посмотрите https://vercel.com или спросите в чате."
  if [ "${ALLOW_OVERWRITE:-0}" != "1" ]; then
    echo "    Если понимаете, что делаете: ALLOW_OVERWRITE=1 bash $0 \"$MSG\"" >&2
    exit 1
  fi
elif git cat-file -e "$SITE_COMMIT" 2>/dev/null; then
  if git merge-base --is-ancestor "$SITE_COMMIT" HEAD 2>/dev/null; then
    echo "на сайте: ${SITE_COMMIT:0:12} — он целиком внутри вашей ветки, сносить нечего"
  else
    echo "ОСТАНОВКА: на сайте сборка ${SITE_COMMIT:0:12}, и её нет в вашей истории." >&2
    echo "  Выкатка заменит сайт целиком — чужие правки исчезнут." >&2
    echo "  Сначала вберите их:" >&2
    echo "    git merge \$(git branch -a --contains $SITE_COMMIT --format='%(refname:short)' | head -1)" >&2
    echo "  Если объединение уже сделано: ALLOW_OVERWRITE=1 bash $0 \"$MSG\"" >&2
    [ "${ALLOW_OVERWRITE:-0}" = "1" ] || exit 1
  fi
else
  echo "⚠️  коммит сайта ${SITE_COMMIT:0:12} неизвестен локально — сравнить не с чем."
  echo "    Подтяните ветки (git fetch mirror) или решайте вручную."
  [ "${ALLOW_OVERWRITE:-0}" = "1" ] || exit 1
fi

echo "проверяю типы с подставленной отметкой…"
( cd "$FRONT_DIR" && npx tsc --noEmit )

# Прод перечитываем ПРЯМО ПЕРЕД публикацией. Между проверкой выше и этим
# местом проходят минуты (проверка типов), а сборка идёт ещё 25-35 - за это
# время соседнее окно успевает выкатить своё. 21.08.2026 так и вышло:
# проверка в начале сказала "предок", а выкатка сняла с прода восемь чужих
# коммитов, появившихся, пока она собиралась.
BEFORE=$(curl -s --max-time 20 https://aevion.app/api/health 2>/dev/null \
  | sed -n 's/.*"commit":"\([^"]*\)".*/\1/p' | head -1)

# Отметку сборки передаём ЯВНО, переменными сборки.
#
# 21.08.2026 сайт отвечал `commit: unknown, source: none`, и выкатка встала:
# проверка ниже честно отказывается работать вслепую. Причина не в скрипте
# отметки — он умеет три источника (наша переменная, переменная хостинга, git).
# Ни один не срабатывал: заливается ПАПКА, а собирается она у хостинга, и там
# нет ни нашего git, ни git-переменных Vercel — те появляются только у сборок,
# запущенных из репозитория.
#
# Локальный export тут не помогает: переменные этой машины в удалённую сборку
# не едут. Передаём флагом --build-env, и тогда version.json отвечает
# source=stamped-at-deploy вместо none.
npx vercel deploy --prod --yes \
  --build-env "AEVION_SOURCE_COMMIT=$(git rev-parse HEAD)" \
  --build-env "AEVION_SOURCE_BRANCH=$(git rev-parse --abbrev-ref HEAD)"

# Кого мы заменили. Отвечает на вопрос, который до сегодняшнего дня никто
# не задавал: не откатила ли НАША публикация чужую, вышедшую во время сборки.
if [ -n "$BEFORE" ] && [ "$BEFORE" != "unknown" ]; then
  if git cat-file -e "$BEFORE" 2>/dev/null; then
    if git merge-base --is-ancestor "$BEFORE" HEAD 2>/dev/null; then
      echo "перед публикацией на сайте был ${BEFORE:0:12} - он внутри вашей ветки, никого не задели."
    else
      echo "ВНИМАНИЕ: пока шла сборка, на сайт вышло ${BEFORE:0:12}, и этого нет в вашей истории." >&2
      echo "  Ваша публикация снимет ту работу. Вберите её (git merge ${BEFORE:0:12}) и повторите." >&2
    fi
  else
    echo "перед публикацией на сайте был ${BEFORE:0:12}, неизвестный локально - проверьте вручную." >&2
  fi
fi

echo
echo "Проверить, что доехало именно это (build.commit должен стать ${SHA:0:12}):"
echo "  curl -s https://aevion.app/api/health"
