/**
 * Довезти человека до карточки приложения на странице цен.
 *
 * Повод 29.09.2026. Переход по кнопке витрины модуля (`/pricing?app=<слаг>`)
 * оставлял человека наверху: замер на ширине телефона (390 px, 7 секунд
 * ожидания) дал прокрутку 0, а карточка CyberChess стояла на 6162 px — 7.3
 * экрана вниз при длине страницы в 23 экрана. Прежнее ожидание считало ТАКТЫ
 * (40 попыток по 150 мс = 6 секунд), а такты кончаются раньше отрисовки на
 * медленном телефоне, холодном кэше и слабой сети.
 *
 * Здесь ждут СОБЫТИЕ появления узла. Срок остался, но у него другой смысл:
 * не «сколько ждать отрисовку», а «когда признать, что карточки не будет»
 * (переименовали слаг, изменили разметку). Промах при этом не молчит — о нём
 * сообщают вызывающему, и страница показывает человеку строку со ссылкой.
 *
 * Вынесено в отдельный файл намеренно: сторож должен проверять ТОТ ЖЕ код,
 * который выполняется на проде, а не его копию в тесте. Копия расходится с
 * оригиналом молча и создаёт ложную уверенность.
 */
/**
 * 🔴 30.09.2026, замер на ЖИВОМ проде (настоящая вкладка, не рамка): переход
 * `/pricing?app=cyberchess#apps` оставлял прокрутку на нуле, карточка была на
 * 2745 px ниже. Причина оказалась НЕ в ожидании, которое я чинил ночью:
 *
 *   scrollIntoView({ block: "center" })                  → прокрутка 2406 ✔
 *   scrollIntoView({ block: "center", behavior: "smooth" }) → прокрутка 0 ✘
 *
 * Плавная прокрутка на этой странице молча не двигает окно (системная
 * настройка «меньше движения» выключена, scroll-behavior не переопределён,
 * страница прокручиваема — проверено). То есть прежний код и моя ночная
 * починка звали действие, которое ничего не делало, и обе выглядели рабочими.
 *
 * Поэтому здесь прокрутка МГНОВЕННАЯ и с проверкой результата: если окно не
 * сдвинулось, довозим вручную. Красота анимации не стоит того, чтобы человек,
 * нажавший цену, остался наверху 23-экранной страницы.
 */
function довезтиНадёжно(карточка: Element, w: Window): boolean {
  const былаПрокрутка = w.scrollY;
  карточка.scrollIntoView({ block: "center" });
  if (Math.abs(w.scrollY - былаПрокрутка) > 8) return true;

  // Не сдвинулось — считаем сами и прокручиваем окно.
  const прямоугольник = карточка.getBoundingClientRect();
  const цель = прямоугольник.top + w.scrollY - w.innerHeight / 2 + прямоугольник.height / 2;
  w.scrollTo(0, Math.max(0, Math.round(цель)));
  return Math.abs(w.scrollY - былаПрокрутка) > 8;
}

export interface ОжиданиеКарточки {
  /** Отменить ожидание (уход со страницы). */
  отменить: () => void;
}

export function ждатьКарточкуПриложения(
  слаг: string,
  опции: {
    приДоставке: (карточка: Element) => void;
    приПромахе: (слаг: string) => void;
    срокМс?: number;
    документ?: Document;
  },
): ОжиданиеКарточки {
  const d = опции.документ ?? document;
  const срок = опции.срокМс ?? 15000;
  const найти = () =>
    d.querySelector(`[data-app="${typeof CSS !== "undefined" && CSS.escape ? CSS.escape(слаг) : слаг}"]`);

  const окно = (опции.документ ?? document).defaultView ?? window;
  const доставить = (карточка: Element) => {
    довезтиНадёжно(карточка, окно);
    опции.приДоставке(карточка);
  };

  const сразу = найти();
  if (сразу) {
    доставить(сразу);
    return { отменить: () => {} };
  }

  let закрыто = false;
  const наблюдатель = new MutationObserver(() => {
    if (закрыто) return;
    const карточка = найти();
    if (!карточка) return;
    закрыто = true;
    наблюдатель.disconnect();
    clearTimeout(предел);
    доставить(карточка);
  });
  наблюдатель.observe(d.body, { childList: true, subtree: true });

  const предел = setTimeout(() => {
    if (закрыто) return;
    закрыто = true;
    наблюдатель.disconnect();
    // Ещё одна попытка найти: карточка могла появиться ровно на границе срока.
    const поздняя = найти();
    if (поздняя) доставить(поздняя);
    else опции.приПромахе(слаг);
  }, срок);

  return {
    отменить: () => {
      if (закрыто) return;
      закрыто = true;
      наблюдатель.disconnect();
      clearTimeout(предел);
    },
  };
}
