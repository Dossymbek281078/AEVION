/**
 * Кому нужны сырые байты тела — и почему это не «все».
 *
 * `express.json({ verify })` получает уже прочитанный буфер и, если сохранить его
 * на `req`, продлевает ему жизнь до конца запроса: без ссылки он стал бы мусором
 * сразу после разбора JSON. Копии не создаётся — удержание, не дублирование.
 *
 * Замер (4 одновременных запроса по 8 МБ, ручка держит 300 мс, счётчик
 * `process.memoryUsage().arrayBuffers`, два прогона в обоих порядках):
 *
 *   без сохранения:  прирост 64.0 МБ и 64.0 МБ
 *   со сохранением:  прирост 80.1 МБ и 104.0 МБ
 *
 * То есть на медиа-путях платформы (base64-аудио расшифровки, клон голоса,
 * картинки DevHub — общий предел тела 10 МБ ради них и поднят) удержание стоит
 * десятки мегабайт при небольшой параллельности. На ноутбуке, который упирается
 * именно в коммит памяти, это ощутимо.
 *
 * Сырые байты нужны РОВНО десяти обработчикам — все проверяют подпись платёжного
 * вебхука побайтно, потому что пересобранный из объекта JSON даёт другую строку и
 * подпись не сходится.
 *
 * ── Почему правило двойное, а не «список путей» ──
 *
 * Список путей — единственная точка, где ошибка стоит денег: переименуют путь или
 * добавят провайдера, список отстанет, и проверка подписи сломается МОЛЧА (тело
 * есть, байтов нет, подпись не сходится, платёж отклонён). Поэтому байты
 * сохраняются, если выполнено ЛЮБОЕ из двух:
 *
 *   1. тело мало (≤ 64 КБ) — все платёжные вебхуки такие, это несколько
 *      килобайт JSON; здесь удерживать нечего, и потому безопасно удерживать всё;
 *   2. путь есть в списке вебхуков — страховка для вебхука, который однажды
 *      придёт крупнее порога.
 *
 * Порядок важен: первое правило работает и тогда, когда список устарел. Второе —
 * когда устарел порог. Молча сломаться может только при совпадении обоих
 * промахов, и на этот случай есть сторож в тестах, сверяющий список с
 * фактическими читателями `req.rawBody` в коде.
 */

/** Тело такого размера удерживать не жаль: платёжные вебхуки — единицы килобайт. */
export const RAW_BODY_SMALL_LIMIT = 64 * 1024;

/**
 * Пути, где сырые байты нужны при ЛЮБОМ размере тела.
 *
 * Собрано не на глаз: по всем чтениям `(req as ...).rawBody` в src/ найдена
 * ближайшая объявленная ручка и её точка монтирования. Сторож в
 * `tests/rawBodyPolicy.test.ts` пересчитывает читателей и краснеет, если их
 * станет больше, чем записей здесь.
 */
export const RAW_BODY_PATHS: readonly string[] = [
  "/api/bureau/verify/webhook",
  "/api/bureau/payment/webhook",
  "/api/gumroad/webhook",
  "/api/lemonsqueezy/webhook",
  "/api/paybox/webhook",
  "/api/paypal/webhook",
  "/api/qpaynet/merchant/charge",
  "/api/qpaynet/deposit/webhook",
  "/api/build/webhooks/payment",
];

/** Нормализованный путь запроса: без строки запроса и без хвостовых слешей. */
export function requestPath(url: string | undefined): string {
  const p = (url || "").split("?")[0].replace(/\/+$/, "");
  return p || "/";
}

export function needsRawBody(url: string | undefined, byteLength: number): boolean {
  if (byteLength <= RAW_BODY_SMALL_LIMIT) return true;
  return RAW_BODY_PATHS.includes(requestPath(url));
}
