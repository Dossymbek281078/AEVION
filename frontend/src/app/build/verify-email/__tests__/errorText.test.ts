import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Страница подтверждения адреса не показывает человеку сырой ответ сервера.
 *
 * ЗАЧЕМ. Сюда приходят по ссылке из письма — часто с телефона и без входа.
 * Замер на проде 28.08.2026: при устаревшем `id` в ссылке на экране было
 * «отсутствует токен bearer». Это внутренний жаргон, и он вдобавок вводит в
 * заблуждение — намекает, что нужно войти, хотя вход здесь не требуется.
 *
 * Причина была не в отсутствии перевода, а в его ОХВАТЕ: перевод стоял ровно
 * на одном коде (`invalid_or_expired_token`), а любой другой ответ печатался
 * дословно. Это тот же класс, что «сторож проверяет одну ветвь из нескольких»:
 * снаружи выглядит сделанным, а покрывает один случай.
 *
 * Тест читает исходник, поэтому НЕ заметит, если файл перестанет
 * компилироваться. Компиляцию проверяет `tsc --noEmit`.
 */

const SRC = readFileSync(
  join(dirname(fileURLToPath(import.meta.url)), "..", "page.tsx"),
  "utf8",
);

describe("подтверждение адреса: текст ошибки", () => {
  it("человеку показывают понятный текст, а не сообщение сервера", () => {
    // Ветка `: msg` означала «показать сырой ответ как основной текст».
    const body = SRC.replace(/\{\/\*[\s\S]*?\*\/\}/g, " ");
    expect(body, "сырое сообщение сервера снова стало основным текстом").not.toMatch(
      /\?\s*t\("build\.verifyEmail\.invalidOrExpired"\)\s*:\s*msg/,
    );
    expect(body, "потерян перевод понятного текста").toContain(
      't("build.verifyEmail.invalidOrExpired")',
    );
  });

  it("технический код всё же виден — иначе поддержке не о чем спросить", () => {
    // Полностью прятать код нельзя: человек по телефону не объяснит, что
    // случилось, а «серым в скобках» он прочитает.
    expect(SRC, "технический код перестали показывать вовсе").toMatch(/\(\{msg\}\)/);
  });

  it("вход на этой странице не требуется", () => {
    // Страница открывается из письма. Любое перенаправление на вход здесь —
    // возврат к дефекту, ради которого всё и делалось.
    const body = SRC.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/\/\/[^\n]*/g, " ");
    expect(body, "появился редирект на вход").not.toMatch(/push\(["'`]\/(auth|login)/);
  });
});
