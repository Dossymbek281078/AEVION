function страницы(каталог: string, префикс = ""): string[] {
  const из: string[] = [];
  for (const имя of readdirSync(каталог)) {
    const полный = join(каталог, имя);
    if (statSync(полный).isDirectory()) {
      if (имя === "__tests__" || имя === "node_modules") continue;
      из.push(...страницы(полный, префикс ? `${префикс}/${имя}` : имя));
    } else if (имя.endsWith(".tsx")) {
      из.push(префикс ? `${префикс}/${имя}` : имя);
    }
  }
  return из;
}

const СМЕРТЕЛЬНЫЙ_ДОМЕН = /@aevion\.app/;

/*
 * Комментарии вырезаем ДО поиска — ОБЩИМ помощником, а не своим.
 *
 * Свой я написал и тут же нашёл в нём беду: наивная вырезалка съела настоящую
 * строку страницы и объявила её комментарием. Помощник в helpers/sourceCode.ts
 * заведён 21.08.2026 ровно от этого класса и уже используется пятью сторожами;
 * второй способ делать то же самое — лишний источник расхождений.
 */

/*
 * ⚠️ Этот файл сведён вручную 01.09.2026 из ДВУХ веток, и обе стороны нужны.
 *
 * Из ветки воронки — вызов общей вырезалки комментариев: без него сторож читает
 * исходник сырым, и страница, где адрес остался только в объяснении «здесь был
 * такой-то адрес», не выйдет из списка НИКОГДА.
 *
 * Из ветки платежей — сокращённый список: четыре страницы починены, и вторая
 * половина сторожа («список не протухает») потребовала их убрать.
 *
 * Взять одну сторону целиком нельзя ни в какую: их файл вернёт четыре записи о
 * починенном, мой — вернёт сырое чтение.
 */
describe("новых мёртвых адресов не появляется", () => {
  const все = страницы(КОРЕНЬ);
  const сАдресом = все.filter((p) =>
    СМЕРТЕЛЬНЫЙ_ДОМЕН.test(stripComments(readFileSync(join(КОРЕНЬ, p), "utf8"))),
  );

  it("обход и поиск работают — проверено подложенной пробой", () => {
    // Контроль охвата: без него «новых нет» одинаково выглядит при исправном
    // коде и при сломанном обходе каталогов.
    expect(все.length, "обход каталогов ничего не нашёл").toBeGreaterThan(100);

    // Умение НАХОДИТЬ проверяем пробой, а не наличием настоящих дефектов.
    // Первая редакция требовала `сАдресом.length > 0` — и была бы верной ровно
    // до тех пор, пока адреса не починят: на чистом коде она покраснела бы,
    // а сторож, краснеющий от успеха, перестают читать. Подсказал сосед,
    // наступивший на это же в своём стороже денежного пути.
    expect(СМЕРТЕЛЬНЫЙ_ДОМЕН.test("пишите на support@aevion.app")).toBe(true);
    expect(СМЕРТЕЛЬНЫЙ_ДОМЕН.test("пишите на support@example.org")).toBe(false);
  });

  it("ни одной новой страницы с адресом на домене без почты", () => {
    const новые = сАдресом.filter((p) => !ИЗВЕСТНЫЕ.has(p));
    expect(
      новые,
      "письмо на @aevion.app не доходит никуда: у домена нет MX. " +
        "Дайте человеку адрес, который принимает почту, или форму на сайте",
    ).toEqual([]);
  });

  it("список не протухает: починенное убирается из него", () => {
    const исчезнувшие = [...ИЗВЕСТНЫЕ].filter((p) => !сАдресом.includes(p));
    expect(
      исчезнувшие,
      "адрес убран со страницы — уберите её и из списка выше, иначе список " +
        "будет обещать беду, которой уже нет",
    ).toEqual([]);
  });
});
