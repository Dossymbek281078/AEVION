import { describe, it, expect } from "vitest";
import { existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { ЯЗЫКОВЫЕ_ПАРЫ, языки } from "@/lib/hreflang";

/**
 * 🔴 Объявлять поисковику можно только СУЩЕСТВУЮЩИЙ двойник.
 *
 * `hreflang` — это утверждение «вот та же страница на другом языке». Если
 * адреса нет, мы отправляем поисковик в 404, и он перестаёт доверять остальным
 * объявлениям на сайте. Ровно такая ловушка рядом: `/en/pricing` отвечает
 * **404**, хотя `/pricing` — наша главная денежная страница, и соблазн
 * объявить ей английский двойник наибольший.
 *
 * Поэтому проверка смотрит не на список (его писал я), а на ФАЙЛЫ страниц:
 * знаменатель берётся независимо от того, что я объявил.
 */
const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const APP = join(ЗДЕСЬ, "../../app");

function страницаЕсть(маршрут: string): boolean {
  const сегмент = маршрут.replace(/^[/]/, "");
  return ["page.tsx", "page.ts", "page.jsx"].some((f) => existsSync(join(APP, сегмент, f)));
}

describe("языковые пары объявляют только существующие страницы", () => {
  it("прибор видит предмет: пары заведены и файлы страниц читаются", () => {
    expect(ЯЗЫКОВЫЕ_ПАРЫ.length).toBeGreaterThan(0);
    // положительный контроль: заведомо существующая страница находится
    expect(страницаЕсть("/shop")).toBe(true);
    // отрицательный контроль: выдуманной страницы нет
    expect(страницаЕсть("/takoy-stranicy-net-zzz")).toBe(false);
  });

  it("у каждой объявленной пары обе страницы существуют", () => {
    const нет: string[] = [];
    for (const п of ЯЗЫКОВЫЕ_ПАРЫ) {
      if (!страницаЕсть(п.ru)) нет.push(п.ru);
      if (!страницаЕсть(п.en)) нет.push(п.en);
    }
    expect(нет, `объявлены двойниками, но страниц нет: ${нет.join(", ")}`).toEqual([]);
  });

  it("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: /pricing двойником не объявлен", () => {
    // /en/pricing на проде отвечает 404 (замер 20.09.2026). Появится страница —
    // строка добавляется осознанно, а не потому, что «цены важнее всего».
    expect(языки("/pricing")).toBeUndefined();
    expect(ЯЗЫКОВЫЕ_ПАРЫ.some((p) => p.ru === "/pricing" || p.en === "/en/pricing")).toBe(false);
  });

  it("обе стороны пары объявляют одно и то же", () => {
    for (const п of ЯЗЫКОВЫЕ_ПАРЫ) {
      expect(языки(п.ru)).toEqual(языки(п.en));
      expect(языки(п.ru)).toEqual({ ru: п.ru, en: п.en, "x-default": п.ru });
    }
  });

  it("для страницы вне списка языки не объявляются", () => {
    expect(языки("/devhub")).toBeUndefined();
  });
});
