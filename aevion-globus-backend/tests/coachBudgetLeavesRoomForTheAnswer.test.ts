/**
 * Бюджет модели должен оставлять место ОТВЕТУ, а не только размышлению.
 *
 * ПОВОД 29.09.2026, живой прод. Замер соседнего окна (user-3f), модель
 * `gemini-2.5-flash`, один промпт и позиция, меняется только лимит:
 *
 *   150  → ответ 17 знаков  (видимых токенов 5,  на размышление 141)
 *   400  → ответ 58 знаков  (видимых 15,         на размышление 381)
 *   1200 → ответ 176 знаков (видимых 48,         на размышление 1148)
 *   4096 → 471 знак, обрыв на полуслове (зажался нашим потолком 1500)
 *
 * То есть `maxOutputTokens` покрывает и мысли, и ответ. Клиент просит ДЛИНУ
 * ОТВЕТА — значит перевод в бюджет обязан делать сервер, иначе каждое место
 * вызова во фронте должно знать повадки поставщика.
 *
 * Здесь проверяется ПЕРЕВОД. Настоящая длина ответа проверяется на проде
 * после выкатки — этого тест заменить не может и не претендует.
 */

import { describe, it, expect } from "vitest";
import { бюджетОтвета, модельРазмышляет } from "../src/routes/coach";

describe("бюджет для думающей модели", () => {
  it("gemini 2.5 опознан как думающая модель", () => {
    expect(модельРазмышляет("gemini", "gemini-2.5-flash")).toBe(true);
  });

  it("контроль: обычные модели не трогаем", () => {
    // Иначе мы задрали бы бюджет там, где он означает ровно длину ответа,
    // и стали бы платить за воздух у Anthropic.
    expect(модельРазмышляет("anthropic", "claude-opus-4-8")).toBe(false);
    expect(модельРазмышляет("openai", "gpt-4o-mini")).toBe(false);
    expect(модельРазмышляет("gemini", "gemini-1.5-pro")).toBe(false);
  });

  it("у думающей модели бюджет заметно больше запрошенной длины", () => {
    // На 150 раньше оставалось 5 видимых токенов — «А что если» не работала.
    expect(бюджетОтвета("gemini", "gemini-2.5-flash", 150)).toBeGreaterThan(1000);
    expect(бюджетОтвета("gemini", "gemini-2.5-flash", 1200)).toBeGreaterThan(4000);
  });

  it("у обычной модели бюджет равен запрошенному", () => {
    expect(бюджетОтвета("anthropic", "claude-opus-4-8", 1200)).toBe(1200);
  });

  it("потолок есть — бесконечно бюджет не растёт", () => {
    // Запас не должен превращаться в бесконтрольный расход.
    expect(бюджетОтвета("gemini", "gemini-2.5-flash", 100000)).toBeLessThanOrEqual(8192);
  });
});
