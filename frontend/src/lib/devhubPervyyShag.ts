/**
 * Первый шаг человека на /devhub: поле не должно встречать его пустым.
 *
 * Замер 12.10.2026 (разрез воронки byFeature, 7 дней): при 66 заходах на
 * /devhub кнопку «Построить» не нажал НИ ОДИН живой человек — все три нажатия
 * были нашими пробами. Кадр на 390×844 объясняет, почему: поле 304×66 на y=342
 * пустое (виден только бледный placeholder), кнопка «⚡ Построить» на y=418
 * ВЫКЛЮЧЕНА до первого набранного знака, а сразу под ней — цена «от $100/мес».
 * Примеры, которые заполняют поле одним нажатием, лежат НИЖЕ цены (y=581+).
 * То есть первое, что страница просит, — придумать текст; первое, что обещает, —
 * счёт.
 *
 * Поэтому поле приходит заполненным живым примером: кнопка сразу рабочая, и
 * между приходом и результатом не стоит «придумай формулировку». Текст видно,
 * и его можно стереть — это подсказка, а не выбор за человека.
 */

export type ПервыйШаг = {
  /** Что уже введено (в том числе набранное до гидратации). */
  введено: string;
  /** Примеры со страницы, в порядке показа. */
  примеры: string[];
};

/**
 * Чем заполнить поле, или null — если заполнять НЕЛЬЗЯ.
 *
 * Заполняем только пустое поле: набранное человеком (и даже начатое им до
 * гидратации) важнее любой подсказки, а стёртый текст — это его решение
 * начать с чистого листа, а не повод подставить пример снова.
 */
export function primerDlyaPustogoPolya({ введено, примеры }: ПервыйШаг): string | null {
  if (введено.trim() !== "") return null;
  const годный = примеры.find((p) => typeof p === "string" && p.trim() !== "");
  return годный ? годный.trim() : null;
}

