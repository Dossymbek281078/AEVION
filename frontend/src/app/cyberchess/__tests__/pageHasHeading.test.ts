import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * У главной страницы модуля должен быть заголовок первого уровня.
 *
        "диктора и для поиска, а глазами это не отличить.",
 * это не отличить: крупный текст выглядит ровно так же, как заголовок.
 * 27.08.2026 h1 на главной шахмат не было вовсе; добавлен, но ничем не
 * закреплён — при следующей перестановке блоков исчез бы молча.
 *
 * Отдельно проверяем, что он не спрятан за условием вида isMobileLayout:
 * заголовок, которого нет на телефоне, — это отсутствующий заголовок для
 * половины людей.
 */
const PAGE = path.join(__dirname, "..", "page.tsx");
const src = fs.readFileSync(PAGE, "utf8");

describe("у главной страницы модуля есть заголовок первого уровня", () => {
  it("h1 присутствует", () => {
    expect(
      src,
      "на главной странице модуля должен быть <h1>. " +
        "Если шапку вынесли в отдельный компонент — не удаляйте эту проверку, " +
        "а укажите здесь новый файл: без h1 страница безымянна для экранного " +
        "диктора и для поиска, а глазами это не отличить.",
    ).toContain("<h1");
  });

  it("h1 не спрятан за условием ширины экрана", () => {
    const i = src.indexOf("<h1");
    expect(i, "h1 не найден").toBeGreaterThan(0);
    // 200 символов перед тегом: там жило бы условие вроде {!isMobileLayout && <h1
    const pered = src.slice(Math.max(0, i - 200), i);
    expect(
      /isMobileLayout\s*&&\s*$|vwPx\s*[<>]/.test(pered),
      "заголовок не должен зависеть от ширины экрана",
    ).toBe(false);
  });
});
