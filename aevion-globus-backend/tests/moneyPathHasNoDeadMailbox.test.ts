import { describe, test, expect } from "vitest";
import { existsSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * На денежном пути человека не зовут писать на ящик, которого нет.
 *
 * ЗАМЕР 01.09.2026, с контролем: у домена aevion.app НЕТ записи MX, тогда как у
 * gmail.com и у aevion.io она находится тем же запросом. Значит ноль настоящий,
 * а не «не умею спрашивать». Письмо на любой адрес нашего домена не доходит
 * никуда: отправитель получает отлуп, мы не узнаём вовсе.
 *
 * ПОЧЕМУ ИМЕННО ДЕНЬГИ. Адрес поддержки в письме о покупке и в чеке видит тот,
 * кто УЖЕ заплатил, и пишет обычно тогда, когда доступ не пришёл. Молчание
 * достаётся ровно недовольному покупателю, и он при этом уверен, что написал
 * нам. Отказ, который выглядит успехом, только со стороны человека.
 *
 * ГРАНИЦА ЧЕСТНАЯ. Отправитель остаётся: письмо им подписывает Resend, подпись
 * домена настроена, и менять его — отдельное решение с риском для доставки.
 * Сторож стережёт ПРИГЛАШЕНИЕ ПИСАТЬ, а не присутствие домена в файле.
 *
 * Это НЕ починка корня: пока записи MX нет, мёртв любой адрес нашего домена,
 * где бы он ни появился. Корень — решение основателя, оно записано в
 * Desktop/АЕВИОН/00-НАЧНИ-ОТСЮДА/2026-09-01-ПОЧТА-на-aevion-app-не-доходит.md
 *
 * Сайтовую половину стережёт сторож соседнего окна (13 страниц с адресами);
 * здесь намеренно только бэкенд и почта платежей, чтобы два храповика не
 * спорили об одних и тех же файлах.
 *
 * Разбор без регулярок намеренно: класс символов, собранный строкой, у нас уже
 * терял обратный слэш и делал сторожа пустым — он «работал» и отвечал нулём.
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(HERE, "..", "src");
const REPO = resolve(HERE, "..", "..");
const NEWLINE = String.fromCharCode(10);
const DOMAIN = "@aevion.app";

/** Файлы, через которые проходят деньги и письма о них. */
/**
 * Известные приглашения, которые чинит ДРУГОЕ окно прямо сейчас.
 *
 * `routes/provisioning.ts` держит вкладка воронки и апселла: она уже перевела
 * поддержку в письме о покупке на форму, но её ветка ещё не пришла ни в сборку,
 * ни в зеркало. Написать то же самое второй рукой — значит получить два решения
 * одной задачи и конфликт на денежном файле.
 *
 * Запись ОБЯЗАНА исчезнуть вместе с их мержем. Если она пережила его — значит
 * починка не доехала, и это находка, а не формальность.
 */
const KNOWN = [{ file: "provisioning.ts", mark: "hello@aevion.app" }];

const MONEY_PATH = [
  join(SRC, "lib", "planningEmail.ts"),
  join(SRC, "lib", "provisioning.ts"),
  join(SRC, "routes", "payments.ts"),
  join(SRC, "routes", "checkout.ts"),
  join(SRC, "routes", "provisioning.ts"),
  join(SRC, "routes", "planningStubs.ts"),
  // Сеть платежей: деньги через неё проходят так же, как через кассу.
  join(SRC, "routes", "qpaynet.ts"),
  // Квоты API: адрес контакта здесь починен 29.08 соседним окном
  // (коммит 886fe5657), сторож нужен, чтобы починку не «улучшили» обратно
  // на красивый адрес нашего домена — почты у него по-прежнему нет.
  join(SRC, "routes", "apiQuotas.ts"),
  join(REPO, "frontend", "src", "app", "api", "payments", "v1", "_email.ts"),
];

/**
 * Строка, где адрес нашего домена — ОТПРАВИТЕЛЬ, а не приглашение.
 *
 * Отличаем по соседству с полем отправителя, а не по имени ящика: `receipts@`
 * завтра могут переименовать, а смысл строки от этого не изменится.
 */
/** Строка комментария: объяснение, а не обещание. */
export function isComment(line: string): boolean {
  const t = line.trim();
  return t.startsWith("//") || t.startsWith("*") || t.startsWith("/*") || t.startsWith("{/*");
}

export function isSenderLine(line: string): boolean {
  // Регистр приводится намеренно: настоящие константы отправителя названы
  // FROM и FROM_EMAIL, а моя первая проба была написана строчными — она
  // совпала с моей же реализацией, а не с кодом, и сторож нашёл это сам.
  const t = line.replace(/ /g, "").toLowerCase();
  // Список ЯВНЫЙ, а не «содержит from»: имя переменной бывает FROM_EMAIL, и
  // подстрока "from=" в нём не встречается вовсе. Первые две редакции этой
  // функции промахнулись именно так, и обе нашёл сам сторож — краснея на
  // исправных строках отправителя.
  const SENDER = ["from=", "from:", "from_email", "resend_from", "smtp_from", "mail_from"];
  return SENDER.some((k) => t.includes(k));
}

/** Приглашения писать на ящик нашего домена. */
function invitations(file: string): string[] {
  if (!existsSync(file)) return [];
  const out: string[] = [];
  for (const line of readFileSync(file, "utf8").split(NEWLINE)) {
    if (!line.includes(DOMAIN)) continue;
    // Комментарий — не обещание пользователю. Отсев тот же, что в платформенном
    // securityContactMatches.guard: там он появился по той же причине, и там же
    // записано, почему ложная тревога в стороже опаснее пропуска — на неё
    // перестают смотреть. У меня этот класс сегодня сработал ТРИЖДЫ: дважды в
    // сторожах сайта и здесь, на взятом чужом файле, где мёртвый адрес живёт в
    // объяснении, ПОЧЕМУ он убран.
    if (isComment(line)) continue;
    if (isSenderLine(line)) continue;
    out.push(line.trim().slice(0, 90));
  }
  return out;
}

describe("на денежном пути нет мёртвых почтовых ящиков", () => {
  test("контроль: файлы денежного пути на месте", () => {
    // Пустой список сделал бы проверку ниже зелёной при любом состоянии кода —
    // и ровно так выглядел бы переезд файлов после рефакторинга.
    const found = MONEY_PATH.filter((f) => existsSync(f));
    expect(found.length, "найдено " + found.length + " из " + MONEY_PATH.length).toBeGreaterThanOrEqual(6);
  });

  test("контроль: способ отличает приглашение от отправителя", () => {
    // Обе стороны пробой. Без первой «ноль приглашений» означало бы «я не умею
    // их видеть»; без второй сторож краснел бы на исправном поле отправителя, и
    // его отключили бы в первый же день.
    expect(
      isSenderLine('const from = process.env.RESEND_FROM ?? "AEVION <receipts@aevion.app>";'),
      "поле отправителя принято за приглашение",
    ).toBe(true);
    expect(
      isSenderLine("  Reply to support@aevion.app if you need help"),
      "приглашение писать принято за поле отправителя",
    ).toBe(false);
    expect(invitations(join(SRC, "lib", "netu-takogo-fajla.ts")), "несуществующий файл дал находки").toEqual([]);

    // Комментарий с адресом — не находка, но и не повод ослепнуть: проверяем обе
    // стороны. Первая редакция краснела на объяснении «почему адрес убран».
    expect(isComment("    // было api@aevion.app, у домена нет записи MX"), "комментарий не опознан").toBe(true);
    expect(isComment('    contact: "support@aevion.app",'), "код принят за комментарий").toBe(false);

    // ПОЛОЖИТЕЛЬНАЯ проба — без неё сторож ничем не нагружен. Замер: пока все
    // приглашения починены, ослепление поиска ничего не меняет, и мутация
    // «искать нечего» проходит молча. То есть зелёный цвет означал бы «в файлах
    // чисто» и «я разучился искать» одинаково.
    const probe = join(HERE, "__proba_priglashenija__.ts");
    writeFileSync(probe, 'const html = `Поддержка: <a href="mailto:support@aevion.app">напишите</a>`;', "utf8");
    try {
      expect(invitations(probe), "подложенное приглашение не найдено — поиск слеп").toHaveLength(1);
    } finally {
      rmSync(probe, { force: true });
    }
  });

  test("ни один файл денежного пути не зовёт писать на наш домен", () => {
    const bad: string[] = [];
    for (const f of MONEY_PATH) {
      const name = f.split("/").pop() ?? f;
      for (const line of invitations(f)) {
        if (KNOWN.some((k) => name.includes(k.file) && line.includes(k.mark))) continue;
        bad.push(name + ": " + line);
      }
    }
    expect(
      bad,
      "человека зовут писать на ящик домена без записи MX: письмо не дойдёт, он " +
        "узнает отлупом, мы не узнаем вовсе — а видит это тот, кто уже заплатил",
    ).toEqual([]);
  });

  test("страница, на которую мы теперь зовём, существует", () => {
    // Замена мёртвого адреса на ссылку в никуда была бы не починкой, а той же
    // поломкой в новой одежде.
    const page = join(REPO, "frontend", "src", "app", "pricing", "contact", "page.tsx");
    expect(existsSync(page), "ссылка на форму ведёт на несуществующую страницу").toBe(true);
  });
});
