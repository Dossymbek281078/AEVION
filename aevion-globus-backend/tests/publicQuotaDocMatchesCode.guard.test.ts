import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Сторож: публичный документ о квотах не расходится с кодом.
 *
 * ЗАЧЕМ. Ответ GET /api/quotas отдаёт клиентам ссылку docsUrl на
 * docs/api/PUBLIC_API_QUOTAS.md В ВЕТКЕ MAIN. Репозиторий публичный
 * (проверено 29.08.2026), то есть документ читают снаружи и по нему
 * планируют нагрузку — а числа в нём живут отдельно от кода.
 *
 * Прод при этом собирают НЕ из main, и main отстаёт неделями. Значит
 * расхождение появится тихо: код поменяли, документ забыли, клиент
 * рассчитывает на старый предел и упирается в новый.
 *
 * Замер при написании: все девять чисел (вызовы, предел в минуту, цена по
 * трём тарифам) в документе присутствуют. Сторож заводится на чистом.
 *
 * ГРАНИЦА. Проверяем НАЛИЧИЕ числа в тексте, а не то, что документ описывает
 * его верно — второе машиной не проверить. Формы записи допускаем разные:
 * 10000, 10,000, 10 000.
 */
const КОД = join(__dirname, "..", "src", "routes", "apiQuotas.ts");
const ДОК = join(__dirname, "..", "..", "docs", "api", "PUBLIC_API_QUOTAS.md");

/** Число в любой записи: с запятыми, пробелами или подчёркиваниями. */
function естьЧисло(текст: string, n: number): boolean {
  const голое = String(n);
  const плоский = текст.replace(/[, \s_](?=\d)/g, "");
  return плоский.includes(голое);
}

describe("публичный документ о квотах совпадает с кодом", () => {
  it("каждое число из кода есть в документе", () => {
    const код = readFileSync(КОД, "utf8");
    const док = readFileSync(ДОК, "utf8");

    const числа = [
      ...[...код.matchAll(/monthlyCalls:\s*([\d_]+)/g)].map((m) => ["monthlyCalls", m[1]] as const),
      ...[...код.matchAll(/perMinute:\s*([\d_]+)/g)].map((m) => ["perMinute", m[1]] as const),
      ...[...код.matchAll(/priceUsdMonthly:\s*([\d_]+)/g)].map((m) => ["priceUsdMonthly", m[1]] as const),
    ].map(([поле, сырое]) => [поле, Number(сырое.replace(/_/g, ""))] as const);

    // Знаменатель вслух: пустой список читался бы как «расхождений нет».
    expect(числа.length, "чисел в коде не найдено — сломан разбор").toBeGreaterThan(5);

    const нет = числа
      .filter(([, n]) => n > 0 && !естьЧисло(док, n))
      .map(([поле, n]) => `${поле}=${n}`);

    expect(
      нет,
      "Число из кода не встречается в публичном документе о квотах.\n" +
        "Документ читают снаружи и по нему планируют нагрузку; ссылка на него\n" +
        "уходит клиентам в ответе /api/quotas.\n  " +
        нет.join("\n  "),
    ).toEqual([]);
  });
});
