import { describe, expect, it } from "vitest";
import { MATERIALS, materialById, повторТекстуры, ДОСОК_В_КАНВЕ, ШИРИНА_ДОСКИ_М } from "./materials";

/**
 * Масштаб рисунка проверяется В МЕТРАХ НА ЭЛЕМЕНТ.
 *
 * Замер 30.09.2026 по кадру изнутри: доска пола выходила 4.8 м в длину и
 * 0.6 м в ширину, плитка 60×60 — 2.4 м. Проверять «выглядит ли похоже»
 * нельзя, поэтому здесь считается ровно то, что видно глазом: сколько метров
 * занимает один элемент рисунка на стене или на полу.
 */

/** Метры на один элемент рисунка по каждой оси. */
function метровНаЭлемент(id: string, roomW: number, roomH: number) {
  const m = materialById(id)!;
  const п = повторТекстуры(m, roomW, roomH);
  const элементовПоX = m.pattern === "planks" ? 1 : m.pattern === "stripes" ? 4 : 1;
  const элементовПоY = m.pattern === "planks" ? ДОСОК_В_КАНВЕ : m.pattern === "stripes" ? 4 : 1;
  return { x: roomW / п.x / элементовПоX, y: roomH / п.y / элементовПоY };
}

describe("масштаб рисунка отделки", () => {
  it("плитка 60×60 занимает 60 см, а не два с половиной метра", () => {
    const { x, y } = метровНаЭлемент("tile-white", 6, 3);
    expect(x).toBeCloseTo(0.6, 2);
    expect(y).toBeCloseTo(0.6, 2);
  });

  it("доска ламината: 1.2 м в длину и 19 см в ширину", () => {
    const { x, y } = метровНаЭлемент("laminate-light", 6, 3);
    expect(x, "длина доски").toBeCloseTo(1.2, 2);
    expect(y, "ширина доски").toBeCloseTo(ШИРИНА_ДОСКИ_М, 2);
  });

  it("масштаб не зависит от размера комнаты — иначе он не масштаб", () => {
    const малая = метровНаЭлемент("laminate-grey", 3, 2);
    const большая = метровНаЭлемент("laminate-grey", 12, 9);
    expect(малая.x).toBeCloseTo(большая.x, 3);
    expect(малая.y).toBeCloseTo(большая.y, 3);
  });

  it("ни один пол и ни одна стена не крупнее метра на элемент", () => {
    // Крупнее метра — это уже не отделка, а декорация: по такому кадру
    // человек и сказал «работа первоклассника».
    const крупные: string[] = [];
    for (const m of MATERIALS) {
      if (m.pattern === "solid") continue;
      const { x, y } = метровНаЭлемент(m.id, 8, 5);
      if (Math.max(x, y) > 1.25) крупные.push(`${m.name}: ${x.toFixed(2)}×${y.toFixed(2)} м`);
    }
    expect(крупные, "элементы рисунка крупнее 1.25 м").toEqual([]);
  });

  it("контроль прибора: проверка умеет краснеть", () => {
    // Прежняя формула — деление на четыре. Если бы она осталась, плитка была
    // бы 2.4 м; проверка выше обязана такое поймать.
    const m = materialById("tile-white")!;
    const староеЧисло = 8 / m.unitM / 4;
    expect(8 / староеЧисло, "прежняя формула давала 2.4 м на плитку").toBeCloseTo(2.4, 2);
    expect(повторТекстуры(m, 8, 5).x).not.toBeCloseTo(староеЧисло, 3);
  });
});
