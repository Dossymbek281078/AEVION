import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { kontrast } from "@/lib/devhubPervyyShag";

/**
 * 🔴 ПОДСКАЗКА В ПОЛЕ ЧИТАЕМА НА ВСЕХ ДЕНЕЖНЫХ СТРАНИЦАХ.
 *
 * Сплошной замер 12.10.2026 живым браузером на проде: из 18 измеренных полей
 * (/devhub 8, /pricing 7, /multichat-engine 2, /cyberchess 1) у ОДИННАДЦАТИ
 * подсказка была ниже нормы 4.5 — 3.38…4.23. Набранный текст везде был в
 * порядке (9.9…20.1), то есть повторения утренней беды «текст невидим» нет.
 *
 * Причина одна на все страницы: своего правила у нас не было, подсказку красил
 * браузер — он берёт 50 % цвета текста. Правило добавлено в globals.css.
 *
 * ЧТО ПРОВЕРЯЕТ ЭТОТ СТОРОЖ: что доля в правиле ДОСТАТОЧНА для реальных пар
 * «цвет текста / фон поля», снятых с прода. Не наличие строки — число.
 * Опусти кто-нибудь долю до прежних 50 % или до промежуточных 60–70 %, и
 * проверка покраснеет с конкретной парой и её контрастом.
 *
 * ⚠️ Чего сторож НЕ утверждает: что на проде нет поля с ДРУГИМИ цветами. Пары
 * ниже — это то, что я измерил, и их знаменатель назван. Появится поле с иным
 * сочетанием — его надо добавить сюда, иначе зелёный цвет будет шире правды.
 */

const CSS = readFileSync(join(process.cwd(), "src/app/globals.css"), "utf8");

/** Пары «цвет текста поля / фон под ним», снятые браузером с прода 12.10.2026. */
const ПАРЫ: Array<{ где: string; текст: [number, number, number]; фон: [number, number, number] }> = [
  { где: "/devhub, /pricing, /proof — белое поле", текст: [15, 23, 42], фон: [255, 255, 255] },
  { где: "/multichat-engine — белое поле", текст: [17, 24, 39], фон: [255, 255, 255] },
  { где: "/devhub — тёмное поле сниппетов", текст: [255, 255, 255], фон: [2, 6, 24] },
  { где: "/devhub, /pricing — поле на #f8fafc", текст: [51, 65, 85], фон: [248, 250, 252] },
];

/** Цвет подсказки = цвет текста, смешанный с фоном в заданной доле. */
function подсказка(
  текст: [number, number, number],
  фон: [number, number, number],
  доля: number,
): [number, number, number] {
  return [0, 1, 2].map((i) => Math.round(текст[i] * доля + фон[i] * (1 - доля))) as [number, number, number];
}

function доляИзCss(): number {
  const m = /::placeholder\s*\{[^}]*color-mix\(in srgb,\s*currentColor\s+(\d+)%/.exec(CSS);
  if (!m) throw new Error("правило ::placeholder с color-mix в globals.css не найдено");
  return Number(m[1]) / 100;
}

describe("подсказка в поле читается", () => {
  it("🔴 правило существует и гасит прозрачность браузера", () => {
    expect(CSS).toContain("::placeholder");
    // Без opacity:1 Firefox приглушает подсказку поверх нашего цвета.
    const блок = /::placeholder\s*\{([^}]*)\}/.exec(CSS)?.[1] ?? "";
    expect(блок, "в правиле нет opacity: 1 — в Firefox правка не сработает").toMatch(/opacity:\s*1/);
  });

  it("🔴 доли хватает на КАЖДОЙ измеренной паре — знаменатель 4 из 4", () => {
    const доля = доляИзCss();
    expect(ПАРЫ.length, "пары с прода должны быть перечислены все").toBe(4);
    for (const п of ПАРЫ) {
      const к = kontrast(подсказка(п.текст, п.фон, доля), п.фон);
      expect(к, `${п.где}: контраст подсказки ${к.toFixed(2)} при доле ${доля}`).toBeGreaterThanOrEqual(4.5);
    }
  });

  it("🔴 контроль: прежние 50 % браузера эту проверку НЕ прошли бы", () => {
    // Без этого контроля нельзя отличить «доля достаточна» от «проверка слепая».
    const плохие = ПАРЫ.filter((п) => kontrast(подсказка(п.текст, п.фон, 0.5), п.фон) < 4.5);
    expect(плохие.length, "умолчание браузера обязано падать хотя бы на части пар").toBeGreaterThanOrEqual(3);
    // И именно столько, сколько намерено живьём: три светлых случая из четырёх.
    expect(плохие.map((п) => п.где)).not.toContain("/devhub — тёмное поле сниппетов");
  });

  it("прибор контраста проверен на известных ответах", () => {
    expect(kontrast([255, 255, 255], [0, 0, 0])).toBeCloseTo(21, 0);
    expect(kontrast([0, 0, 0], [0, 0, 0])).toBeCloseTo(1, 5);
  });
});
