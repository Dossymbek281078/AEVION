export type CriterionDef = { id: string; label: string; weight: number };
/** Оценка одного критерия в якорной шкале 1..5. null = критерий неприменим
 *  к этому кадру (нет речи → липсинк, нет животного → этология). */
export type RawScore = { id: string; score: number | null; note?: string | null };

export type ScoredCriterion = {
  id: string;
  label: string;
  weight: number;
  score: number | null; // 0..1 наружу
  note: string | null;
};

export type JudgeVerdict = {
  totalScore: number | null; // 0..1, взвешенное
  verdict: "pass" | "regenerate" | "insufficient";
  weakest: Array<{ id: string; label: string; score: number }>;
  judgedCriteria: number;
  skippedCriteria: number;
};

/** Порог приёмки кадра. 0.7 по 0..1 = «4 из 5» в якорной шкале: ниже —
 *  зритель уже читает синтетику. Переопределяется env, чтобы прод можно было
 *  подкрутить без релиза. */
export function acceptThreshold(): number {
  const v = Number(process.env.QREAL_QC_THRESHOLD);
  return Number.isFinite(v) && v > 0 && v < 1 ? v : 0.7;
}

const to01 = (score5: number) => (score5 - 1) / 4;

/** Единственная точка конвертации 1..5 → 0..1 и единственное место, где
 *  считается взвешенный тотал. Неприменимые критерии выпадают И из числителя,
 *  И из знаменателя — иначе кадр получает очко за то, чего в нём нет. */
export function scoreCriteria(defs: CriterionDef[], raw: RawScore[]): { criteria: ScoredCriterion[]; verdict: JudgeVerdict } {
  const byId = new Map(raw.map((r) => [r.id, r]));
  const criteria: ScoredCriterion[] = defs.map((d) => {
    const r = byId.get(d.id);
    const s = r && r.score != null ? Number(r.score) : null;
    const valid = s != null && Number.isFinite(s) && s >= 1 && s <= 5;
    return {
      id: d.id,
      label: d.label,
      weight: d.weight,
      score: valid ? to01(s as number) : null,
      note: r?.note ?? null,
    };
  });

  let num = 0;
  let den = 0;
  for (const c of criteria) {
    if (c.score == null) continue;
    num += c.score * c.weight;
    den += c.weight;
  }
  const judged = criteria.filter((c) => c.score != null).length;
  const total = den ? num / den : null;

  // Меньше половины критериев оценено — это не «плохой кадр», это несудимый
  // кадр. Отдавать по нему вердикт «перегенерировать» значит жечь деньги
  // на основании шума.
  const verdict: JudgeVerdict["verdict"] =
    total == null || judged < Math.ceil(defs.length / 2) ? "insufficient" : total >= acceptThreshold() ? "pass" : "regenerate";

  const weakest = criteria
    .filter((c) => c.score != null)
    .sort((a, b) => (a.score as number) - (b.score as number))
    .slice(0, 3)
    .map((c) => ({ id: c.id, label: c.label, score: c.score as number }));

  return {
    criteria,
    verdict: { totalScore: total, verdict, weakest, judgedCriteria: judged, skippedCriteria: criteria.length - judged },
  };
}

/** Промт VLM-судьи. Тот же текст якорей, что видит человек-судья в бенчмарке —
 *  иначе машинный скор и человеческий несопоставимы. */
export function buildJudgePrompt(defs: CriterionDef[], shot: { description: string; dialogue?: string | null; soundscape?: string }): { system: string; user: string } {
  const lines = defs.map((d) => {
    const a = REALISM_ANCHORS[d.id];
    if (!a) return `- ${d.id} (${d.label}) — вес ${d.weight}`;
    return `- ${d.id} (вес ${d.weight}): ${d.label}\n    1 = ${a["1"]}\n    3 = ${a["3"]}\n    5 = ${a["5"]}`;
  });
  return {
    system:
      "Ты — придирчивый судья фотореализма видео. Оценивай ТОЛЬКО то, что видно и слышно в клипе. " +
      "Шкала 1..5 по приложенным якорям. Если критерий физически неприменим к кадру (нет речи — липсинк; " +
      "нет животного — этология; нет человека — руки, кожа, моргание), ставь null, НЕ ставь среднюю оценку. " +
      "Занижай при сомнении: пропущенный дефект дороже лишней перегенерации. " +
      'Ответ — СТРОГО JSON: {"scores":[{"id":"...","score":1-5|null,"note":"что именно увидел"}]}',
    user:
      `Кадр: ${shot.description}\n` +
      (shot.dialogue ? `Реплика: «${shot.dialogue}»\n` : "Реплик нет.\n") +
      (shot.soundscape ? `Задуманный звук: ${shot.soundscape}\n` : "") +
      `\nКритерии и якоря:\n${lines.join("\n")}`,
  };
}

/** Перегенерация тратит деньги (кадр Seedance 6с ≈ $1.82). Поэтому решение
 *  «перерендерить» по умолчанию — РЕКОМЕНДАЦИЯ, а не действие: авто-режим
 *  включается явно и ограничен по числу попыток. */
export function autoRegenPolicy(attempt: number): { auto: boolean; maxAttempts: number; reason: string } {
  const maxAttempts = Number(process.env.QREAL_QC_MAX_REGEN) || 1;
  const auto = process.env.QREAL_QC_AUTOREGEN === "1";
  if (!auto) return { auto: false, maxAttempts, reason: "авто-перегенерация выключена (QREAL_QC_AUTOREGEN=1 включает); отдаём рекомендацию" };
  if (attempt >= maxAttempts) return { auto: false, maxAttempts, reason: `исчерпан лимит попыток (${maxAttempts}) — дальше решает человек` };
  return { auto: true, maxAttempts, reason: `попытка ${attempt + 1} из ${maxAttempts}` };
}
