/**
 * СМЕТА ДО ЗАПУСКА: «книга → озвучка → короткий фильм».
 *
 * 🔴 ЗАЧЕМ. Человек говорит: «сделай книгу по моим мотивам, озвучь и сними по
 * ней фильм». За этим стоят наши деньги: текст идёт по нашим ключам моделей,
 * голос и видео — по кредитам Higgsfield. Пока цена не названа ЗАРАНЕЕ,
 * возможны ровно две плохие вещи: человек получает счёт, которого не ждал,
 * либо мы молча платим за чужую фантазию. Смета закрывает обе.
 *
 * 🔴 РАСЦЕНКИ ИЗМЕРЕНЫ, А НЕ ПРИДУМАНЫ (28.09.2026, предварительный расчёт
 * Higgsfield `get_cost`, без единого потраченного кредита):
 *   • видео kling3_0_turbo 720p: 5 секунд = 7.5 кредита → 1.5 за секунду;
 *   • озвучка seed_audio: 150 знаков = 0.7, 950 знаков = 4.8 → ≈5 за 1000 знаков.
 * Текст считается по таблице цен моделей (`services/qcoreai/pricing`), она уже
 * возвращает ДОЛЛАРЫ по фактическим токенам.
 *
 * ⚠️ ЧЕГО ЗДЕСЬ НЕТ. Перевод кредитов в доллары: цена пачки кредитов живёт в
 * кабинете Higgsfield и у нас не измерена. Поэтому смета называет кредиты
 * честно, а доллары — только там, где они действительно известны. Придумать
 * курс значило бы назвать человеку цену, которой мы не проверяли.
 */

/** Расценки в кредитах Higgsfield. Замер 28.09.2026. */
export const РАСЦЕНКИ = {
  видеоЗаСекунду: 1.5,
  озвучкаЗа1000Знаков: 5,
  /** Наша цена генерации текста, замер окна DevHub 28.09: gemini-2.5-flash. */
  долларЗаГенерациюТекста: 0.00206,
} as const;

export interface ЗамыселРаботы {
  /** Сколько знаков текста в книге. */
  знаковКниги: number;
  /** Озвучивать ли книгу целиком. */
  озвучка: boolean;
  /** Длина фильма в секундах; 0 — фильм не нужен. */
  секундВидео: number;
  /** Сколько раз модель пишет текст (главы + правки). */
  генерацийТекста?: number;
}

export interface СтрокаСметы {
  шаг: string;
  кредиты: number;
  доллары: number | null;
  объяснение: string;
}

export interface Смета {
  строки: СтрокаСметы[];
  итогоКредитов: number;
  итогоДолларов: number | null;
  долларыНеполные: boolean;
  предупреждения: string[];
}

function округлить(x: number): number {
  return Math.round(x * 100) / 100;
}

/**
 * Смета по замыслу. Ничего не запускает и не тратит.
 *
 * Порядок строк = порядок работ, чтобы человек видел, за что платит на каждом
 * шаге, а не одно общее число.
 */
export function сметаРаботы(з: ЗамыселРаботы): Смета {
  const строки: СтрокаСметы[] = [];
  const предупреждения: string[] = [];

  const знаков = Math.max(0, Math.floor(з.знаковКниги || 0));
  // Скобки обязательны: смешивать ?? и || в одном выражении запрещено
  // синтаксисом, и сборщик падает разбором, а не типами.
  const поУмолчанию = Math.ceil(знаков / 4000) || 1;
  const генераций = Math.max(1, Math.floor(з.генерацийТекста ?? поУмолчанию));

  строки.push({
    шаг: "текст книги",
    кредиты: 0,
    доллары: округлить(генераций * РАСЦЕНКИ.долларЗаГенерациюТекста),
    объяснение: `${генераций} обращений к модели на ${знаков} знаков`,
  });

  if (з.озвучка && знаков > 0) {
    строки.push({
      шаг: "озвучка",
      кредиты: округлить((знаков / 1000) * РАСЦЕНКИ.озвучкаЗа1000Знаков),
      доллары: null,
      объяснение: `${знаков} знаков по ${РАСЦЕНКИ.озвучкаЗа1000Знаков} кредита за 1000`,
    });
  }

  const секунд = Math.max(0, Math.floor(з.секундВидео || 0));
  if (секунд > 0) {
    строки.push({
      шаг: "фильм",
      кредиты: округлить(секунд * РАСЦЕНКИ.видеоЗаСекунду),
      доллары: null,
      объяснение: `${секунд} секунд по ${РАСЦЕНКИ.видеоЗаСекунду} кредита за секунду`,
    });
  }

  const итогоКредитов = округлить(строки.reduce((s, r) => s + r.кредиты, 0));
  const известныеДоллары = строки.filter((r) => r.доллары !== null);
  const долларыНеполные = строки.some((r) => r.доллары === null);
  const итогоДолларов = известныеДоллары.length
    ? округлить(известныеДоллары.reduce((s, r) => s + (r.доллары ?? 0), 0))
    : null;

  if (долларыНеполные) {
    предупреждения.push(
      "Цена кредита в долларах у нас не измерена — итог в долларах неполный, кредиты точные.",
    );
  }
  if (итогоКредитов === 0 && знаков === 0) {
    предупреждения.push("Пустой замысел: ни текста, ни озвучки, ни видео.");
  }

  return { строки, итогоКредитов, итогоДолларов, долларыНеполные, предупреждения };
}

/** Хватает ли остатка кредитов на этот замысел. Ответ «не знаю» отличается от «нет». */
export function хватитЛи(
  смета: Смета,
  остатокКредитов: number | null,
): { хватает: boolean | null; нехватка: number } {
  if (остатокКредитов === null || !Number.isFinite(остатокКредитов)) {
    return { хватает: null, нехватка: 0 };
  }
  const нехватка = округлить(Math.max(0, смета.итогоКредитов - остатокКредитов));
  return { хватает: нехватка === 0, нехватка };
}
