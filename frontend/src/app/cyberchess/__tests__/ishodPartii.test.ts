import { describe, it, expect } from "vitest";
import { ishodIzFrazy, ishodDlyaCPI, resheniePoKontsuPartii } from "../ishodPartii";

/*
 * 🔴 Исход партии добывается из ФРАЗЫ, показанной человеку, и у этого разбора
 * два потребителя с разными требованиями: рейтинг CPI и событие воронки
 * game_end. Пока приметы жили внутри одного useEffect, второй потребитель
 * переписал бы их себе — и одна партия считалась бы победой в рейтинге и
 * ничьёй в воронке.
 *
 * Проверяется ровно то, что может разойтись:
 *   порядок проверки (ничья старше победы — на этом держатся прежние рейтинги);
 *   честное "unknown" вместо молчаливой ничьей;
 *   что для CPI поведение НЕ изменилось.
 */

/** Фразы взяты из самого модуля, а не придуманы: иначе проверка охраняет мою
 *  фантазию о тексте, а не текст. */
const ПОБЕДЫ = [
  "Checkmate! You win!",
  "⚡ Три шаха — победа!",
  "⛰ Король взошёл на холм — победа!",
  "💥 Король соперника взорван — победа!",
  "Королевский ферзь соперника пал — победа!",
  "AI timed out — you win!",
  "Вася сдался — Вы победили!",
];
const ПОРАЖЕНИЯ = [
  "Checkmate — AI wins",
  "You resigned",
  "Time out",
  "⚡ Соперник дал 3 шаха — поражение",
  "⛰ Соперник занял центр — поражение",
  "💥 Твой король взорван — поражение",
  "Твой королевский ферзь пал — поражение",
];
const НИЧЬИ = ["Draw agreed", "Stalemate", "Ничья (договорились)", "Draw by repetition", "Insufficient material", "Draw by 50-move rule"];

describe("исход партии из фразы её конца", () => {
  it("победы узнаются все", () => {
    for (const ф of ПОБЕДЫ) expect(ishodIzFrazy(ф), `не узнана победа: «${ф}»`).toBe("win");
  });

  it("поражения узнаются все", () => {
    for (const ф of ПОРАЖЕНИЯ) expect(ishodIzFrazy(ф), `не узнано поражение: «${ф}»`).toBe("loss");
  });

  it("ничьи узнаются все", () => {
    for (const ф of НИЧЬИ) expect(ishodIzFrazy(ф), `не узнана ничья: «${ф}»`).toBe("draw");
  });

  it("🔴 неузнанная концовка — «unknown», а НЕ ничья", () => {
    // Главное утверждение файла. В расчёте CPI цепочка приметок кончалась
    // значением по умолчанию "d": любая концовка, которой нет в списках, молча
    // записывалась ничьёй и была неотличима от настоящей ничьей. Для рейтинга
    // это неточность, для воронки — прямая ложь о числе.
    for (const ф of ["Партия прервана", "Соединение потеряно", "Game aborted", ""]) {
      expect(ishodIzFrazy(ф), `выдуманный исход у «${ф}»`).toBe("unknown");
    }
    expect(ishodIzFrazy(null)).toBe("unknown");
    expect(ishodIzFrazy(undefined)).toBe("unknown");
  });

  it("🔴 порядок проверки: ничья старше победы", () => {
    // Фраза, в которой есть примета И ничьей, и победы. Прежний код проверял
    // ничью первой, и менять это нельзя: иначе уже посчитанные рейтинги
    // сдвинулись бы задним числом. Контроль именно на порядок, а не на список.
    expect(ishodIzFrazy("Draw — you win on tiebreak")).toBe("draw");
  });

  it("регистр не важен", () => {
    expect(ishodIzFrazy("CHECKMATE! YOU WIN!")).toBe("win");
    expect(ishodIzFrazy("ПОБЕДА!")).toBe("win");
  });

  it("🔴 для CPI поведение НЕ изменилось, включая прежнее умолчание", () => {
    expect(ishodDlyaCPI("Checkmate! You win!")).toBe("w");
    expect(ishodDlyaCPI("You resigned")).toBe("l");
    expect(ishodDlyaCPI("Draw agreed")).toBe("d");
    // Прежнее поведение на неузнанном: ничья. Перенесено осознанно, чтобы
    // правка не сдвинула рейтинги; здесь оно зафиксировано, а не спрятано.
    expect(ishodDlyaCPI("Партия прервана"), "умолчание CPI изменилось — рейтинги сдвинутся").toBe("d");
  });

  it("КОНТРОЛЬ: разбор различает исходы, а не отвечает одно и то же", () => {
    // Без этого все проверки выше прошли бы и у функции, возвращающей константу
    // — если бы списки случайно совпали с ожиданиями по одному исходу.
    const все = new Set([
      ishodIzFrazy("Checkmate! You win!"),
      ishodIzFrazy("You resigned"),
      ishodIzFrazy("Draw agreed"),
      ishodIzFrazy("Партия прервана"),
    ]);
    expect(все.size, `разбор вернул ${все.size} разных значений из 4`).toBe(4);
  });
});

describe("решение, сообщать ли о конце партии в воронку", () => {
  const база = { over: "Checkmate! You win!", partiyaIgralas: true, otpechatokNachala: 1700000000000, uzheOtpravleno: null };

  it("законченная сыгранная партия — сообщаем", () => {
    const р = resheniePoKontsuPartii(база);
    expect(р.otpravlyat, р.prichina).toBe(true);
    expect(р.outcome).toBe("win");
  });

  it("🔴 ТА ЖЕ партия второй раз — не сообщаем", () => {
    // Эффект по `over` переснимается на каждое изменение зависимостей (в том
    // числе на список ходов), поэтому без этого одна партия дала бы несколько
    // единиц в ступени. Мутация этого условия прошла сквозь сторож по
    // исходнику — здесь она ловится.
    const первый = resheniePoKontsuPartii(база);
    const второй = resheniePoKontsuPartii({ ...база, uzheOtpravleno: первый.otpechatok });
    expect(второй.otpravlyat, "одна партия сообщается дважды").toBe(false);
    expect(второй.prichina).toBe("уже отправлено");
  });

  it("🔴 ДРУГАЯ партия с тем же исходом — сообщаем", () => {
    // Обратная сторона: защита от повтора не имеет права глушить следующую
    // партию. Отличаются только отметкой начала — ровно тем признаком, который
    // отпечаток и проверяет.
    const первый = resheniePoKontsuPartii(база);
    const следующая = resheniePoKontsuPartii({ ...база, otpechatokNachala: 1700000999999, uzheOtpravleno: первый.otpechatok });
    expect(следующая.otpravlyat, "вторая партия с тем же исходом потерялась").toBe(true);
  });

  it("🔴 партия, загруженная для просмотра, — не сообщаем", () => {
    const р = resheniePoKontsuPartii({ ...база, partiyaIgralas: false });
    expect(р.otpravlyat, "открытый архив чужой партии даёт ступень «доиграл»").toBe(false);
  });

  it("партия не кончилась — не сообщаем", () => {
    for (const пусто of [null, undefined, ""]) {
      expect(resheniePoKontsuPartii({ ...база, over: пусто }).otpravlyat).toBe(false);
    }
  });

  it("🔴 неузнанная концовка СООБЩАЕТСЯ, с outcome unknown", () => {
    // Важно именно так: событие нужно (партия кончилась), а исход честно
    // неизвестен. Молчать здесь значило бы потерять ступень, подставить ничью —
    // соврать о числе.
    const р = resheniePoKontsuPartii({ ...база, over: "Партия прервана" });
    expect(р.otpravlyat).toBe(true);
    expect(р.outcome).toBe("unknown");
  });
});
