import { describe, expect, test } from "vitest";
import { povodPredlozhitAdres } from "../page";

/*
 * 🔴 Сбор адресов на магните был заперт за условием, которого никто не достигает.
 *
 * ПОВОД — замер на проде 08.10.2026 за 14 дней: на /cyberchess пришло 42 живых
 * сессии, а `game_end` равен нулю. Единственное АВТОМАТИЧЕСКОЕ предложение адреса
 * стояло за концом партии — значит его увидел ноль человек, и `waitlist_submit`
 * тоже ноль. Магнит существует, чтобы собирать адреса, и не собрал ни одного.
 *
 * Теперь поводов два, и зачтённое сервером решение задачи дня идёт первым: это
 * тридцать секунд против целой партии.
 *
 * Проверяется вызовами с заранее известным ответом, потому что внутри страницы на
 * 16 тысяч строк это условие не проверить — прошлое молча не срабатывало месяц.
 */

const хранилищеПустое = { getItem: () => null };
const хранилищеУжеПредлагали = { getItem: () => "1" };
const хранилищеБросает = { getItem: () => { throw new Error("приватное окно"); } };

describe("по какому поводу предлагать адрес", () => {
  test("решил задачу дня → повод «daily-solved»", () => {
    expect(povodPredlozhitAdres({ партияОкончена: false, задачаДняЗачтена: true }, хранилищеПустое)).toBe("daily-solved");
  });

  test("закончил партию → повод «game-over» (прежнее поведение цело)", () => {
    expect(povodPredlozhitAdres({ партияОкончена: true, задачаДняЗачтена: false }, хранилищеПустое)).toBe("game-over");
  });

  test("ни то ни другое → не предлагать", () => {
    expect(povodPredlozhitAdres({ партияОкончена: false, задачаДняЗачтена: false }, хранилищеПустое)).toBeNull();
  });

  test("🔴 уже предлагали → не предлагать ни по какому поводу", () => {
    // Иначе человек, однажды отказавшийся, получает окно снова и снова.
    expect(povodPredlozhitAdres({ партияОкончена: true, задачаДняЗачтена: true }, хранилищеУжеПредлагали)).toBeNull();
    expect(povodPredlozhitAdres({ партияОкончена: false, задачаДняЗачтена: true }, хранилищеУжеПредлагали)).toBeNull();
  });

  test("🔴 хранилище бросает → ПРЕДЛАГАЕМ, падаем в сторону работы", () => {
    // Во встроенных браузерах соцсетей localStorage бросает, а именно оттуда
    // приходит поток. Отказ прочитать отметку не должен выглядеть как «человек
    // не захотел оставить адрес» — это разбор от 30.09.2026, он остаётся в силе.
    expect(povodPredlozhitAdres({ партияОкончена: false, задачаДняЗачтена: true }, хранилищеБросает)).toBe("daily-solved");
  });

  test("оба события разом → поводом будет задача дня, предложение одно", () => {
    expect(povodPredlozhitAdres({ партияОкончена: true, задачаДняЗачтена: true }, хранилищеПустое)).toBe("daily-solved");
  });

  test("КОНТРОЛЬ: функция РАЗЛИЧАЕТ случаи, а не возвращает одно и то же", () => {
    // Без этого все проверки выше прошли бы и у функции, отвечающей константой.
    const ответы = new Set([
      povodPredlozhitAdres({ партияОкончена: false, задачаДняЗачтена: true }, хранилищеПустое),
      povodPredlozhitAdres({ партияОкончена: true, задачаДняЗачтена: false }, хранилищеПустое),
      povodPredlozhitAdres({ партияОкончена: false, задачаДняЗачтена: false }, хранилищеПустое),
    ]);
    expect(ответы.size, `различных ответов ${ответы.size} из 3`).toBe(3);
  });
});
