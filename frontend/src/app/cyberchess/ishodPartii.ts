/**
 * Исход партии из человеческой фразы её конца.
 *
 * Почему отдельный модуль, а не две копии приметок. Фраза конца партии в этом
 * модуле — текст для ЧЕЛОВЕКА: "Checkmate! You win!", "⚡ Три шаха — победа!",
 * "Твой королевский ферзь пал — поражение", "Time out", "Ничья (договорились)".
 * Таких фраз в page.tsx больше сорока, и признаки, по которым из них добывается
 * исход, до 07.10.2026 жили внутри одного useEffect (расчёт CPI). Второй
 * потребитель — событие воронки game_end — переписал бы их себе, и дальше два
 * списка расходились бы молча: одна и та же партия считалась бы победой в
 * рейтинге и ничьёй в воронке.
 *
 * 🔴 ЧЕТВЁРТЫЙ ИСХОД — "unknown", и он здесь намеренно.
 * В расчёте CPI цепочка заканчивалась `let cpiResult="d"` — то есть ЛЮБАЯ
 * неузнанная концовка записывалась ничьёй, молча и неотличимо от настоящей
 * ничьей. Пока потребитель был один, это было лишь неточностью рейтинга; в
 * воронке такое умолчание прямо лжёт. Поэтому функция честно говорит "unknown",
 * а решение, что с ним делать, принимает КАЖДЫЙ потребитель сам и явно:
 * воронка отправляет "unknown" как есть (его доля в by-type и есть мера того,
 * насколько приметам можно верить), а CPI продолжает считать ничьёй — ровно как
 * раньше, но теперь это написано, а не спрятано в умолчании.
 *
 * Поведение на известных фразах не меняется: порядок проверки тот же
 * (ничья → победа → поражение), приметы перенесены дословно.
 */

/** Ничья проверяется ПЕРВОЙ: "draw" встречается и в "draw agreed", и там, где
 *  рядом стоят слова про победу, и прежний порядок давал ничью. Менять порядок
 *  нельзя — это изменило бы уже посчитанные рейтинги. */
export const ПРИМЕТЫ_НИЧЬЕЙ = ["draw", "stalemate", "ничья", "repetition", "insufficient", "50-move"] as const;
export const ПРИМЕТЫ_ПОБЕДЫ = ["you win", "победа!", "трофей", "цель достигнута", "ai timed out", "сдался — вы победили"] as const;
export const ПРИМЕТЫ_ПОРАЖЕНИЯ = ["ai wins", "поражение", "you resigned", "time out", "king взорван", "ферзь пал"] as const;

export type ИсходПартии = "win" | "loss" | "draw" | "unknown";

/**
 * @param фраза то, что лежит в состоянии `over` — текст, показанный человеку.
 * @returns исход С ТОЧКИ ЗРЕНИЯ ИГРАЮЩЕГО, либо "unknown", если ни одна примета
 *          не подошла. Пустая строка и null тоже дают "unknown": партия не
 *          кончилась — исхода нет, и выдумывать его нельзя.
 */
export function ishodIzFrazy(фраза: string | null | undefined): ИсходПартии {
  if (!фраза) return "unknown";
  const низ = фраза.toLowerCase();
  if (ПРИМЕТЫ_НИЧЬЕЙ.some((п) => низ.includes(п))) return "draw";
  if (ПРИМЕТЫ_ПОБЕДЫ.some((п) => низ.includes(п))) return "win";
  if (ПРИМЕТЫ_ПОРАЖЕНИЯ.some((п) => низ.includes(п))) return "loss";
  return "unknown";
}

/**
 * Тот же разбор в буквах расчёта CPI. Отдельная функция, а не преобразование на
 * месте, потому что умолчание "неузнанное считаем ничьёй" — это РЕШЕНИЕ CPI, и
 * оно должно быть названо вслух в одном месте, а не повторяться у каждого, кто
 * позовёт разбор.
 */
export function ishodDlyaCPI(фраза: string | null | undefined): "w" | "l" | "d" {
  const и = ishodIzFrazy(фраза);
  if (и === "win") return "w";
  if (и === "loss") return "l";
  // "draw" и "unknown" — ничья. Для "unknown" это ДОПУЩЕНИЕ, перенесённое из
  // прежнего кода без изменений, чтобы правка не сдвинула ничьи в рейтингах
  // задним числом. Если его решат убрать — менять здесь, и это будет видно.
  return "d";
}

/**
 * Решение «сообщать ли о конце ЭТОЙ партии в воронку».
 *
 * Вынесено из эффекта чистой функцией, и причина конкретная: сторож, который
 * читает исходник, умеет проверить только РАСПОЛОЖЕНИЕ вызова — что отправка
 * стоит в эффекте по `over`, а не на каком-то одном конце партии. Поведение он
 * проверить не может: мутация «убрать защиту от повтора» прошла через него
 * насквозь, потому что имя защиты в тексте осталось. Здесь решение можно
 * проверить по существу — вызовом с известным ответом.
 *
 * Три условия, и каждое отвечает за свой вид вранья:
 *   партия не кончилась → сообщать нечего;
 *   партию не играли (её загрузили из архива для просмотра) → это не наш конец
 *     партии, иначе открытый чужой архив даёт ступень «доиграл»;
 *   та же партия с тем же исходом уже отправлена → эффект по `over` переснимается
 *     на каждое изменение зависимостей, и без этого одна партия считалась бы
 *     несколько раз.
 */
export function resheniePoKontsuPartii(d: {
  over: string | null | undefined;
  /** Партия действительно игралась, а не загружена для просмотра. */
  partiyaIgralas: boolean;
  /** Отметка начала партии — вместе с исходом образует отпечаток. */
  otpechatokNachala: number | string;
  /** Что уже отправлено; null — ещё ничего. */
  uzheOtpravleno: string | null;
}): { otpravlyat: boolean; otpechatok: string; outcome: ИсходПартии; prichina: string } {
  const otpechatok = `${d.otpechatokNachala}|${d.over ?? ""}`;
  const outcome = ishodIzFrazy(d.over);
  if (!d.over) return { otpravlyat: false, otpechatok, outcome, prichina: "партия не кончилась" };
  if (d.uzheOtpravleno === otpechatok) return { otpravlyat: false, otpechatok, outcome, prichina: "уже отправлено" };
  if (!d.partiyaIgralas) return { otpravlyat: false, otpechatok, outcome, prichina: "партия не игралась — загружена для просмотра" };
  return { otpravlyat: true, otpechatok, outcome, prichina: "" };
}
