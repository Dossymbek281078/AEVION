import { describe, expect, it } from "vitest";
import { точкаОбзора } from "./interiorView";
import type { RoomRun } from "./rooms";

/**
 * Проверяем ЧИСЛА, а не «функция что-то вернула».
 *
 * Повод: 30.09.2026 «Взгляд изнутри» ставил камеру в стену — в двух кадрах из
 * трёх половину занимала пустая стена вплотную. Дефект был виден только
 * глазами, поэтому здесь у каждой формы комнаты спрашивается то, что глаз и
 * проверял: далеко ли камера от стен и много ли комнаты видно вперёд.
 */
const КЛЕТКА = 0.05;

/** Прямоугольная комната из клеток: x от 0 до ширины, y от 0 до глубины. */
function прямоугольник(ширина: number, глубина: number, x0 = 0, y0 = 0): RoomRun[] {
  const runs: RoomRun[] = [];
  for (let i = 0; i * КЛЕТКА <= глубина + 1e-9; i++) {
    runs.push({ y: +(y0 + i * КЛЕТКА).toFixed(2), x0, x1: x0 + ширина });
  }
  return runs;
}

describe("точка обзора внутри комнаты", () => {
  it("в квадратной комнате камера стоит далеко от стен", () => {
    const т = точкаОбзора(прямоугольник(5, 5));
    expect(т, "для комнаты 5×5 точка обязана найтись").not.toBeNull();
    // 1.5 м — это уже «стою в комнате», а не «вжат в угол».
    expect(т!.просвет, "камера прижата к стене").toBeGreaterThan(1.5);
    expect(т!.дальность, "вперёд видно меньше двух метров").toBeGreaterThan(2);
  });

  it("смотрит вдоль длинной стороны, а не в ближнюю стену", () => {
    // Коридор 6 м в длину и 1.2 м в ширину: взгляд обязан идти ВДОЛЬ.
    const т = точкаОбзора(прямоугольник(6, 1.2))!;
    const dx = Math.abs(т.целевойX - т.x);
    const dy = Math.abs(т.целевойY - т.y);
    expect(dx, "взгляд не идёт вдоль коридора").toBeGreaterThan(dy * 3);
    expect(т.дальность).toBeGreaterThan(3);
  });

  it("Г-образная комната: камера внутри комнаты, а не в вырезе", () => {
    // Полосы: снизу широкая часть, сверху узкая — центр габарита попадает
    // в ВЫРЕЗ, и именно на этом ломалась прежняя формула «центр минус отступ».
    const runs: RoomRun[] = [];
    for (let i = 0; i * КЛЕТКА <= 3; i++) runs.push({ y: +(i * КЛЕТКА).toFixed(2), x0: 0, x1: 6 });
    for (let i = 1; i * КЛЕТКА <= 3; i++) runs.push({ y: +(3 + i * КЛЕТКА).toFixed(2), x0: 0, x1: 1.5 });
    const т = точкаОбзора(runs)!;
    const вКомнате = (x: number, y: number) =>
      runs.some((r) => Math.abs(r.y - y) < КЛЕТКА / 2 && x >= r.x0 && x <= r.x1);
    expect(вКомнате(т.x, Math.round(т.y / КЛЕТКА) * КЛЕТКА), "камера оказалась вне комнаты").toBe(true);
    expect(т.просвет).toBeGreaterThan(0.5);
  });

  it("контроль прибора: у пустой разметки честный null, а не выдуманная точка", () => {
    expect(точкаОбзора([])).toBeNull();
  });

  it("контроль прибора: в тесной каморке просвет МАЛЕНЬКИЙ, а не всегда большой", () => {
    // Если бы функция возвращала «хорошо» всегда, этот случай прошёл бы тоже.
    const т = точкаОбзора(прямоугольник(0.8, 0.8))!;
    expect(т.просвет).toBeLessThan(0.8);
  });
});

/**
 * МЕБЕЛЬ ТОЖЕ ЗАГОРАЖИВАЕТ.
 *
 * Замер 30.09.2026: камера нашла самое открытое место ПО СТЕНАМ и встала так,
 * что ровно по центру кадра оказался холодильник. Формально «внутри комнаты»,
 * а человек видит серую стенку. Стены и предметы для взгляда — одно и то же.
 */
describe("точка обзора обходит предметы", () => {
  const комната = прямоугольник(6, 6);

  it("не встаёт внутрь предмета", () => {
    // Шкаф ровно в геометрическом центре — прежняя версия вставала туда.
    const т = точкаОбзора(комната, 0.25, [{ x: 3, y: 3, r: 1.2 }])!;
    const доШкафа = Math.hypot(т.x - 3, т.y - 3);
    expect(доШкафа, "камера оказалась внутри предмета").toBeGreaterThan(1.2);
  });

  it("не смотрит предмету в стенку с двух шагов", () => {
    const т = точкаОбзора(комната, 0.25, [{ x: 3, y: 3, r: 1.2 }])!;
    // Луч взгляда не должен втыкаться в круг предмета сразу перед камерой.
    const dx = т.целевойX - т.x, dy = т.целевойY - т.y;
    const длина = Math.hypot(dx, dy) || 1;
    let ближайшее = Infinity;
    for (let d = 0; d <= Math.min(2.5, длина); d += 0.1) {
      ближайшее = Math.min(ближайшее, Math.hypot(т.x + (dx / длина) * d - 3, т.y + (dy / длина) * d - 3));
    }
    expect(ближайшее, "предмет стоит вплотную перед объективом").toBeGreaterThan(1.2);
  });

  it("контроль прибора: без предметов та же комната даёт другую точку", () => {
    const сПредметом = точкаОбзора(комната, 0.25, [{ x: 3, y: 3, r: 1.2 }])!;
    const без = точкаОбзора(комната, 0.25)!;
    const сдвиг = Math.hypot(сПредметом.x - без.x, сПредметом.y - без.y);
    expect(сдвиг, "предмет вообще не повлиял на выбор места").toBeGreaterThan(0.5);
  });
});
