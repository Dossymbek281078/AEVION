import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Обещания САМОЙ страницы модуля сверяются с поведением кода.
 *
 * Зачем отдельно от `devhubClaimsFrozen`. Тот сторож замораживает шесть
 * обещаний КАРТОЧКИ на витрине — их можно заморозить, это устойчивые
 * продуктовые заявления. Словарь страницы (261 строка) замораживать нельзя:
 * тексты меняются законно, и сторож стал бы вечно красным, а к вечно красному
 * привыкают и перестают читать.
 *
 * Поэтому здесь не заморозка, а СВЕРКА ДВУХ НАШИХ ОТВЕТОВ об одном: страница
 * что-то обещает, код что-то делает, и они обязаны совпадать.
 *
 * Проверено вручную 01.09.2026 — оба обещания были честными. Этот файл нужен
 * не для того, чтобы найти дефект сегодня, а чтобы завтрашняя правка не
 * рассогласовала их молча: обещание живёт во фронте, поведение — в бэкенде, и
 * автор одного обычно не открывает другой.
 */

const здесь = dirname(fileURLToPath(import.meta.url));
const СЛОВАРЬ = join(здесь, "..", "i18n.ts");
const БЭКЕНД = join(здесь, "..", "..", "..", "..", "..", "aevion-globus-backend", "src", "routes", "devhub.ts");

const словарь = readFileSync(СЛОВАРЬ, "utf8");
const бэкенд = readFileSync(БЭКЕНД, "utf8");

/** Тело обработчика выкатки — от объявления маршрута до следующего маршрута. */
function телоВыкатки(): string {
  const от = бэкенд.indexOf('devhubRouter.post("/projects/:id/deploy"');
  if (от < 0) return "";
  const до = бэкенд.indexOf("devhubRouter.", от + 40);
  return бэкенд.slice(от, до > 0 ? до : от + 4000);
}

describe("обещания страницы DevHub совпадают с тем, что делает код", () => {
  it("приборы исправны: оба файла прочитаны и разобраны", () => {
    // Контроль охвата. Без него пустой разбор дал бы «расхождений нет» —
    // самый частый вид ложного зелёного.
    expect(словарь.length, "словарь страницы не прочитан").toBeGreaterThan(2000);
    expect(телоВыкатки().length, "обработчик выкатки не найден — сторож смотрит не туда").toBeGreaterThan(200);
  });

  it("обещая «аккаунты не нужны», выкатка НЕ требует входа", () => {
    const обещает = /no github or cloud accounts needed/i.test(словарь);
    if (!обещает) return; // обещание убрали — сверять нечего, это законно
    const тело = телоВыкатки();
    expect(
      тело,
      "страница обещает «аккаунты GitHub и облака не нужны», а выкатка требует входа. " +
        "Одно из двух неверно: либо уберите обещание, либо верните verifyBearerOptional. " +
        "Обещание видит покупатель, поведение — нет.",
    ).toContain("verifyBearerOptional");
  });

  it("бесплатному тарифу выкатка доступна — иначе «в один клик» неправда", () => {
    // Стена по исчерпании нормы законна. Стена с ПЕРВОГО клика сделала бы
    // обещание «Deploy → a live public address in one click» ложным для того,
    // кто впервые открыл страницу.
    const от = бэкенд.indexOf("const TIER_LIMITS");
    expect(от, "таблица тарифов не найдена").toBeGreaterThan(0);
    const free = бэкенд.slice(бэкенд.indexOf("free:", от), бэкенд.indexOf("pro:", от));
    const m = free.match(/deploy:\s*(-?\d+)/);
    expect(m, "в бесплатном тарифе нет ключа deploy").toBeTruthy();
    const сколько = Number(m![1]);
    expect(
      сколько === -1 || сколько > 0,
      `бесплатному тарифу выдано ${сколько} выкаток. Страница обещает публичный адрес ` +
        "в один клик — с нулём это обещание ложно для новичка.",
    ).toBe(true);
  });
});

/*
 * У КАЖДОЙ возможности из таблицы тарифов обязана быть человеческая подпись.
 *
 * На экране остатка стоит `USAGE_LABEL[k] ?? k` — запасная ветка печатает СЫРОЙ
 * КЛЮЧ. Она не падает и не краснеет: человек просто видит английское машинное
 * слово среди русских. 02.09.2026 я завёл два ключа (speech, translate) и
 * разбудил ровно эту ветку — поймал глазами, а не прогоном.
 *
 * Сторож смотрит В ОБЕ стороны: подпись без ключа так же вредна, как ключ без
 * подписи, — она означает, что возможность убрали, а слово осталось.
 */
describe("подписи остатка не отстают от таблицы тарифов", () => {
  const страница = readFileSync(join(здесь, "..", "page.tsx"), "utf8");

  function ключиТаблицы(): string[] {
    const i = бэкенд.indexOf("const TIER_LIMITS");
    const о = бэкенд.indexOf("free:", i);
    const строка = бэкенд.slice(о, бэкенд.indexOf("}", о));
    return [...строка.matchAll(/([a-z]+):\s*-?[0-9]/g)].map((m) => m[1]).sort();
  }

  function ключиПодписей(): string[] {
    const i = страница.indexOf("const USAGE_LABEL");
    const тело = страница.slice(i, страница.indexOf("};", i));
    return [...тело.matchAll(/^\s{2}([a-z]+):\s*"/gm)].map((m) => m[1]).sort();
  }

  it("прибор исправен: оба списка разобраны и непусты", () => {
    // Контроль охвата. Пустой разбор дал бы «списки совпали» на двух пустых —
    // самый частый вид ложного зелёного.
    expect(ключиТаблицы().length, "таблица тарифов не разобрана").toBeGreaterThan(4);
    expect(ключиПодписей().length, "словарь подписей не разобран").toBeGreaterThan(4);
  });

  it("у страницы /studio тот же набор: полосы остатка не отстают от таблицы", () => {
    // ТРЕТИЙ потребитель того же факта. Первые два — список возможностей в
    // /studio/credits и словарь подписей на /devhub; оба разошлись 02.09.2026.
    // Урок: расширив перечисление, спроси, КТО ЕЩЁ его перечисляет. Я знал об
    // одном месте, их оказалось три.
    // Читаем usageOrder.ts, а НЕ page.tsx: подписи вынесены туда 02.09.2026,
    // потому что произвольный именованный экспорт из страницы App Router
    // может уронить сборку. Сторож это поймал сам — «смотрю не туда» вместо
    // ложного зелёного, ради чего контроль охвата и стоит.
    const студия = readFileSync(
      join(здесь, "..", "..", "studio", "usageOrder.ts"),
      "utf8",
    );
    const i = студия.indexOf("const CAP_META");
    expect(i, "на /studio не найден CAP_META — сторож смотрит не туда").toBeGreaterThan(0);
    const тело = студия.slice(i, студия.indexOf("};", i));
    const ключи = [...тело.matchAll(/^\s{2}([a-z]+):\s*\{/gm)].map((m) => m[1]).sort();

    expect(ключи.length, "список подписей /studio не разобран").toBeGreaterThan(4);
    expect(
      ключи,
      "Полосы остатка на /studio разошлись с таблицей тарифов. Возможность " +
        "списывается, а полосы у неё нет — человек тратит квоту, которой не " +
        "видит. Заводя ключ возможности, заводите подпись во ВСЕХ местах показа.",
    ).toEqual(ключиТаблицы());
  });

  it("у каждой возможности есть подпись, и лишних подписей нет", () => {
    expect(
      ключиПодписей(),
      "Список подписей на экране остатка разошёлся с таблицей тарифов. Ключ без " +
        "подписи покажет человеку СЫРОЕ английское слово (ветка `?? k` молчит); " +
        "подпись без ключа означает, что возможность убрали, а слово осталось. " +
        "Заводя ключ возможности, заводите и подпись.",
    ).toEqual(ключиТаблицы());
  });
});
