import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Список платных ручек БЕЗ учёта расхода только сокращается.
 *
 * ЗАЧЕМ. 31.08.2026 нашлось, что `/plan` зовёт платного поставщика и не пишет
 * расход вовсе — то есть деньги уходили невидимо. Починили. 01.09 при обходе
 * выяснилось, что таких ручек ещё шесть, и у них причина другая: наша таблица
 * цен знает языковые модели, а звук, голос и распознавание речи идут к ДРУГИМ
 * поставщикам, цен которых у нас нет.
 *
 * Записать их расход нулём было бы хуже молчания: ноль читается как
 * «бесплатно», а не как «цена неизвестна». Поэтому список честный, с причиной
 * у каждой строки, и сторож следит за одним: чтобы он не РОС.
 *
 * Новая платная ручка без учёта — это возврат к тому, что уже стоило нам
 * невидимого расхода.
 */

const ФАЙЛ = join(__dirname, "..", "src", "routes", "devhub.ts");
const src = readFileSync(ФАЙЛ, "utf8");

/** Тело функции. Начало ищем после закрывающей скобки СПИСКА ПАРАМЕТРОВ:
 *  в типе параметра тоже бывают фигурные скобки, и разбор «от первой фигурной»
 *  возвращал тело из нуля строк — на этом я потерял время 01.09. */
function телоФункции(имя: string): string {
  const k = src.indexOf("function " + имя);
  if (k < 0) return "";
  let p = src.indexOf("(", k), d = 0, m = p;
  for (; m < src.length; m++) {
    if (src[m] === "(") d++;
    else if (src[m] === ")") { d--; if (d === 0) break; }
  }
  const o = src.indexOf("{", m);
  d = 0;
  for (let j = o; j < src.length; j++) {
    if (src[j] === "{") d++;
    else if (src[j] === "}") { d--; if (d === 0) return src.slice(k, j + 1); }
  }
  return "";
}

function телоРучки(путь: string): string {
  const i = src.indexOf(`devhubRouter.post("${путь}"`);
  if (i < 0) return "";
  const j = src.indexOf("devhubRouter.", i + 40);
  return src.slice(i, j > 0 ? j : src.length);
}

/**
 * Пишет ли ручка расход — сама или через локального помощника.
 *
 * Признаков три, и третий не лишний: учёт генерации кода лежит на ДВА уровня
 * вглубь (обработчик → generateCodeWithAI → учтиГенерацию), а обход идёт на
 * один. Имя помощника здесь — не костыль: он И ЕСТЬ учёт, и спрашивать надо
 * про способность, а не про то, каким вызовом она достигнута. На этом я
 * ошибся шесть раз за 01.09.
 */
function пишетРасход(путь: string): boolean {
  const t = телоРучки(путь);
  if (!t) return false;
  if (/insertSmartRun|costUsd|учтиГенерацию/.test(t)) return true;
  const помощники = new Set([...t.matchAll(/\b([a-z][A-Za-z0-9]{5,})\(/g)].map((m) => m[1]));
  for (const h of помощники) {
    if (/insertSmartRun|costUsd|учтиГенерацию/.test(телоФункции(h))) return true;
  }
  return false;
}

/** Ручки под ограничителем дорогих вызовов. Определение намеренно ШИРОКОЕ:
 *  сузив его до «доходит до нашей службы поставщиков», я потерял медиа-ручки —
 *  они зовут поставщиков прямым запросом. Широкий список плюс причина у каждого
 *  исключения честнее узкого определения, которое молча теряет предмет. */
function платныеРучки(): string[] {
  return [...src.matchAll(/devhubRouter\.post\("([^"]+)",\s*dhCostlyLimit/g)].map((m) => m[1]);
}

/**
 * Известные ручки без учёта. Причина у каждой обязательна: список без причин
 * превращается в опись поражений, которую перестают читать.
 */
const БЕЗ_УЧЁТА = new Map<string, string>([
  ["/media/sfx", "поставщик звука не в нашей таблице цен"],
  ["/media/voice-clone", "поставщик голоса не в нашей таблице цен"],
  ["/media/voice-clone/preview", "тот же поставщик голоса"],
  ["/media/stt", "поставщик распознавания речи не в нашей таблице цен"],
  ["/media/translate", "поставщик перевода не в нашей таблице цен"],
  ["/projects/:id/files/translate", "тот же поставщик перевода"],
  ["/projects/:id/files/translate-bulk", "тот же поставщик перевода"],
  ["/media/email-template-create", "цена не заведена"],
  // Ниже — не «забыли учесть», а «учитывать нечего»: ограничитель стоит от
  // злоупотребления, платных вызовов ручка не делает.
  ["/projects/:id/agent/workflow", "оркестрация шагов; платит не она, а вызванные ею ручки"],
  ["/projects/:id/agent/workflow/stream", "то же, потоковый вариант"],
  ["/media/upload-image", "загрузка файла, поставщика не зовёт"],
]);

describe("список платных ручек без учёта расхода не растёт", () => {
  it("прибор исправен: платные ручки найдены и разбор функций работает", () => {
    // Двойной контроль. Пустой список ручек дал бы «нарушений нет», а сломанный
    // разбор тела — «никто не пишет расход». Оба уже случались 01.09.
    expect(платныеРучки().length, "платные ручки не найдены").toBeGreaterThan(8);
    expect(телоФункции("planProjectWithAI").length, "разбор тела функции сломан").toBeGreaterThan(500);
    expect(пишетРасход("/plan"), "у /plan учёт есть — если тут false, врёт прибор").toBe(true);

    // Признак «учтиГенерацию» узнаётся по ИМЕНИ — значит выпотрошенный помощник
    // прошёл бы незамеченным. Поймано собственной мутацией 01.09: сняв один
    // вызов из трёх, я оставил сторожа зелёным и понял, что он проверяет форму.
    // Здесь проверяется, что помощник и вправду пишет расход.
    const помощник = телоФункции("учтиГенерацию");
    expect(помощник.length, "помощник учёта исчез — проверьте, не переименован ли").toBeGreaterThan(100);
    expect(
      /insertSmartRun/.test(помощник),
      "помощник учёта больше не пишет расход: имя осталось, дело ушло",
    ).toBe(true);
  });

  it("новых ручек без учёта не появилось", () => {
    const новые = платныеРучки().filter((п) => !пишетРасход(п) && !БЕЗ_УЧЁТА.has(п));
    expect(
      новые,
      "Платная ручка не пишет расход и не внесена в список известных. Деньги " +
        "будут уходить невидимо — именно так /plan прожил до 31.08. Либо " +
        "добавьте учёт, либо внесите в БЕЗ_УЧЁТА С ПРИЧИНОЙ.",
    ).toEqual([]);
  });

  it("список известных не растёт молча", () => {
    expect(БЕЗ_УЧЁТА.size, "известных без учёта стало больше — список обязан сокращаться").toBeLessThanOrEqual(11);
    for (const [путь, причина] of БЕЗ_УЧЁТА) {
      expect(причина.length, `у ${путь} нет причины`).toBeGreaterThan(10);
    }
  });
});
