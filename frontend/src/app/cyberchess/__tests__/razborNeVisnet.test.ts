import { describe, it, expect } from "vitest";
import { readFileSync } from "fs";
import { join } from "path";

/**
 * Разбор партии после её конца — то, ради чего основатель перенёс запуск.
 *
 * Замер на боевой сборке 31.08.2026: сыграл партию, сдался, ждал 50 секунд.
 * Разбор не пришёл. Движок при этом был ЖИВ: шесть запросов stockfish с кодом
 * 200, ходы соперника делались. В его собственном коде вылетает
 * «e.trim is not a function» — одного такого сбоя хватает, чтобы очередь
 * осталась без ответа.
 *
 * Причина найдена сравнением двух соседних путей одного и того же:
 *
 *   живой разбор (во время партии)  — предохранитель 8 секунд на позицию ЕСТЬ
 *   runAnalysis (после партии)      — предохранителя НЕ БЫЛО
 *
 * Один автор, один файл, одна задача, разное поведение — почти всегда
 * недосмотр, а не решение. Наружу это не выходило вовсе: вызывающий обёрнут в
 * пустой catch, а человек видел «Разбираю партию…» без конца.
 */

const KOD = () => readFileSync(join(process.cwd(), "src/app/cyberchess/page.tsx"), "utf8");

describe("разбор партии не может зависнуть навсегда", () => {
  it("у ожидания движка есть предохранитель по времени", () => {
    const s = KOD();
    expect(s.length).toBeGreaterThan(100000); // контроль: файл прочитан
    expect(s).toContain("const storozh=setTimeout(()=>otvet({cp:lastCp,mate:lastMate}),8000);");
  });

  it("ответ отдаётся ровно один раз", () => {
    // Без защёлки и таймер, и настоящий ответ звали бы res() — второй вызов
    // молча теряется, но сторож не должен зависеть от этой случайности.
    const s = KOD();
    expect(s).toContain("if(!gotovo){gotovo=true;clearTimeout(storozh);res(v)}");
  });

  it("оба пути разбора защищены одинаково", () => {
    // Живой разбор имел предохранитель с самого начала. Теперь их два, и если
    // кто-то уберёт один — счёт разойдётся, и тест это увидит.
    const s = KOD();
    const skolko = (s.match(/setTimeout\([^)]*8000\)|,8000\);/g) || []).length;
    expect(skolko).toBeGreaterThanOrEqual(2);
  });
});
