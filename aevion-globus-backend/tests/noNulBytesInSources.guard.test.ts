import { describe, test, expect } from "vitest";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Ни один исходник не содержит байт NUL.
 *
 * ЗАЧЕМ. От ОДНОГО такого байта git считает ВЕСЬ файл двоичным: diff
 * приходит как «Bin 9289 -> 16253 bytes», numstat отдаёт «- -», а коммит
 * выглядит пустым («0 insertions, 0 deletions»). Вычитать код в таком файле
 * нельзя, и мерж пошёл бы двоичным конфликтом.
 *
 * Замер 31.08.2026: байт лежал в lib/qventure/deckExtract.ts — в регулярке
 * чистки текста презентации. Он попал туда обычным для этой машины путём:
 * обратный слэш съедается на границе вызова, в исходнике задумывалось
 * "u0000" как ТЕКСТ, а доехал сам символ.
 *
 * ВАЖНАЯ ОГОВОРКА, чтобы следующий читатель не чинил не то: регулярка с
 * настоящим байтом NUL РАБОТАЕТ — проверено в node, оба варианта убирают
 * символ. То есть дефект был не в поведении, а в читаемости исходника.
 * Утверждение «чистка не делает ничего» было бы неверным.
 */
const REPO = execFileSync("git", ["rev-parse", "--show-toplevel"], {
  encoding: "utf8",
}).trim();

const EXTS = [".ts", ".tsx", ".js", ".mjs", ".cjs", ".json", ".md", ".css", ".ps1", ".sh", ".yml"];

function trackedSources(): string[] {
  // -z обязателен: без него git отдаёт неASCII-пути ЭКРАНИРОВАННЫМИ, и
  // проверка молча пропускает их. У нас кириллица в путях повсюду, поэтому
  // занижение выборки было бы почти гарантировано.
  const out = execFileSync("git", ["ls-files", "-z"], {
    cwd: REPO,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  return out
    .split(String.fromCharCode(0))
    .filter((p) => p.length > 0 && EXTS.some((e) => p.endsWith(e)));
}

const NUL = String.fromCharCode(0);

describe("исходники не содержат байт NUL", () => {
  const files = trackedSources();

  test("контроль: перечисление файлов сработало", () => {
    // Пустой список дал бы «находок нет» на любом состоянии репозитория —
    // ровно тот ложный ноль, против которого сторож и написан.
    expect(files.length, "git ls-files вернул подозрительно мало путей").toBeGreaterThan(1000);
  });

  test("контроль: детектор умеет находить байт", () => {
    // Иначе «ноль находок» означал бы «не умею искать».
    expect(("a" + NUL + "b").includes(NUL), "детектор не видит подложенный байт").toBe(true);
    expect("ab".includes(NUL), "детектор находит байт там, где его нет").toBe(false);
  });

  test("ни в одном исходнике нет байта NUL", () => {
    const bad: string[] = [];
    for (const rel of files) {
      let buf: Buffer;
      try {
        buf = readFileSync(join(REPO, rel));
      } catch {
        // Файл в индексе, но не читается — это НЕ «чисто». Называем его,
        // иначе непрочитанный файл сойдёт за проверенный.
        bad.push(rel + " (не прочитался)");
        continue;
      }
      if (buf.includes(0)) bad.push(rel);
    }
    expect(
      bad,
      "от одного байта NUL git считает файл двоичным: diff станет «Bin X -> Y bytes», " +
        "коммит будет выглядеть пустым, и вычитать правку в этом файле будет нельзя. " +
        "Замените байт на экранированную запись (u0000 через обратный слэш). " +
        "Чаще всего он стоит ВНУТРИ регулярки, которая сама вырезает NUL из текста: " +
        "намерение автора верное, сломана только запись. Открыв файл и увидев " +
        "осмысленную регулярку, легко решить, что сторож капризничает — нет: " +
        "диффы этого файла приходят как Bin X -> Y bytes, и ревью в нём невозможно.",
    ).toEqual([]);
  });

  // Тот же класс, другой байт. 01.09.2026 я сам завёл в ТРЁХ файлах
  // последовательность CR CR LF: писал содержимое с переводами строк и
  // открывал файл с переводом строк — python сложил одно с другим.
  // Один из пострадавших — этот самый сторож: лекарство несло болезнь.
  //
  // Удвоенный возврат каретки законным не бывает. Вреден он тем же, чем
  // NUL, только тише: лишний CR остаётся В КОНЦЕ строки, якорь $ в любой
  // регулярке перестаёт совпадать, и разбор молча уходит в запасную ветку.
  test("ни в одном исходнике нет удвоенного возврата каретки", () => {
    const CR = String.fromCharCode(13);
    // Контроль детектора: он обязан находить подложенное и не находить
    // обычный CRLF, иначе покрасил бы половину репозитория.
    expect(("a" + CR + CR + "b").includes(CR + CR), "детектор не видит подложенный CR CR").toBe(true);
    expect(("a" + CR + String.fromCharCode(10) + "b").includes(CR + CR), "обычный CRLF принят за находку").toBe(false);

    const bad: string[] = [];
    for (const rel of files) {
      let buf: Buffer;
      try {
        buf = readFileSync(join(REPO, rel));
      } catch {
        bad.push(rel + " (не прочитался)");
        continue;
      }
      if (buf.includes(CR + CR)) bad.push(rel);
    }
    expect(
      bad,
      "удвоенный возврат каретки: лишний CR уезжает в конец строки, и любой якорь конца строки перестаёт совпадать",
    ).toEqual([]);
  });

  // ТРЕТИЙ управляющий байт того же рода: 0x08, забой.
  //
  // В регулярке пишут \b как границу слова. Проходя через оболочку или
  // heredoc, обратный слэш съедается, и \b становится САМИМ БАЙТОМ. Регулярка
  // компилируется, ошибки нет, а ветка с этим байтом не срабатывает никогда.
  //
  // Вреден тише двух соседей: NUL делает файл двоичным (видно сразу), CR CR
  // ломает якорь конца строки (видно по пропускам), а забой просто делает
  // ветку недостижимой — и НЕ ПРОИСХОДИТ НИЧЕГО.
  //
  // Известные случаи перечислены поимённо: они в чужих зонах, чинить их не
  // мне, а сторож, вечно красный на том, что некому погасить, приучает не
  // смотреть. Ловим НОВЫЕ.
  test("ни в одном исходнике нет байта забоя (0x08)", () => {
    const BS = String.fromCharCode(8);
    // Контроль детектора в обе стороны.
    expect(("a" + BS + "b").includes(BS), "детектор не видит подложенный забой").toBe(true);
    expect("ab".includes(BS), "детектор находит забой там, где его нет").toBe(false);

    // Разбор 01.09.2026: во всех трёх это \b, задуманный как граница слова.
    // Направление у каждого своё: в secret-leak-scan регулярка ИСКЛЮЧАЕТ шум,
    // поэтому мёртвая ветка даёт лишние находки, а не пропущенные секреты.
    // ЭТОТ СПИСОК — ДОЛГ, А НЕ РЕШЕНИЕ. Он должен уменьшаться.
    // Починили файл — уберите строку отсюда, иначе сторож навсегда останется
    // слепым к нему, и следующий такой байт там пройдёт незамеченным.
    //
    // Готовая команда правки и контрольная строка для проверки движком —
    // в разборе 15-Аудиты-и-сводки/2026-09-01-ТРЕТИЙ-управляющий-байт-*.md
    /*
     * 🔴 СПИСОК ПУСТ с 01.10.2026, и это находка, а не уборка. Все три файла
     * были проверены побайтно: 0x08 нет ни в одном, прочих управляющих тоже.
     * То есть долг давно погасили, а исключение осталось — и сторож ТРИ ФАЙЛА
     * не проверял вовсе, ровно как предупреждает комментарий выше.
     *
     * Список-исключение переживает свою причину молча: он не краснеет и не
     * напоминает о себе. Поэтому правило: исключение заводится ВМЕСТЕ с
     * проверкой, что оно ещё нужно. Здесь эту роль играет пустота — любая
     * новая строка обязана идти с датой и причиной.
     */
    const IZVESTNYE = new Set<string>([]);

    const bad: string[] = [];
    for (const rel of files) {
      if (IZVESTNYE.has(rel)) continue;
      let buf: Buffer;
      try {
        buf = readFileSync(join(REPO, rel));
      } catch {
        bad.push(rel + " (не прочитался)");
        continue;
      }
      if (buf.includes(8)) bad.push(rel);
    }
    expect(
      bad,
      "байт забоя в исходнике: чаще всего это \b, задуманный как граница слова. " +
        "Ветка регулярки с ним не срабатывает НИКОГДА, ошибки при этом нет. " +
        "Проверять починку надо движком, а не глазами: в редакторе байт не виден.",
    ).toEqual([]);
  });

  /*
   * ПО КЛАССУ, А НЕ ПО СЛУЧАЮ — главная правка 01.10.2026.
   *
   * Три проверки выше ловят три байта поимённо: NUL, CR CR, 0x08. Каждая
   * добавлена ПОСЛЕ своего происшествия. Поэтому байт, которым нас ещё не
   * ударило, проходит свободно — и прошёл: U+0082 молча испортил ТРИ файла
   * (пути в комментариях `АЕВИОН\01-CyberChess\2026-08-19` превратились в
   * `АЕВИОН<U+0001>-CyberChess<U+0082>6-08-19`). Виноват тот же съеденный
   * слэш: `\01` стал байтом 0x01, а `\202` из `\2026` — байтом 0x82, то есть
   * ОКТАЛЬНЫМ экранированием.
   *
   * Поэтому ловим весь класс: C0 без tab/LF/CR и C1 целиком (U+0080–U+009F).
   * Ни один из них не имеет законного места в исходнике: разделитель, если он
   * действительно нужен, пишется экранированием `\u001f`, а не сырым байтом —
   * видимый текст можно прочитать, невидимый нельзя.
   */
  test("ни в одном исходнике нет управляющих байтов C0/C1 (класс, а не перечень)", () => {
    const запрещён = (c: number) =>
      (c < 32 && c !== 9 && c !== 10 && c !== 13) || (c >= 0x80 && c <= 0x9f);

    // Контроль детектора в обе стороны и на границах диапазона.
    expect(запрещён(0x08), "не видит забой").toBe(true);
    expect(запрещён(0x82), "не видит U+0082 — тот самый пропущенный байт").toBe(true);
    expect(запрещён(0x80), "не видит нижнюю границу C1").toBe(true);
    expect(запрещён(0x9f), "не видит верхнюю границу C1").toBe(true);
    expect(запрещён(0x09), "табуляция объявлена запрещённой").toBe(false);
    expect(запрещён(0x0a), "перевод строки объявлен запрещённым").toBe(false);
    expect(запрещён(0x0d), "возврат каретки объявлен запрещённым").toBe(false);
    expect(запрещён(0xa0), "неразрывный пробел — не управляющий, ему тут не место").toBe(false);
    expect(запрещён("я".charCodeAt(0)), "кириллица принята за управляющий байт").toBe(false);

    /*
     * Единственное исключение, и оно проверено ЧТЕНИЕМ, а не предположением:
     * `const sep = "<U+001F>"` в coord-update.js — намеренный разделитель
     * полей. Он работает, но написан сырым байтом; переписать его
     * экранированием — правка в чужой зоне, и она ничего не меняет по смыслу.
     * Строка остаётся здесь с причиной и датой, как требует правило выше.
     */
    const СЫРОЙ_РАЗДЕЛИТЕЛЬ = new Set(["aevion-globus-backend/scripts/coord-update.js"]);

    const bad: string[] = [];
    let проверено = 0;
    for (const rel of files) {
      if (СЫРОЙ_РАЗДЕЛИТЕЛЬ.has(rel)) continue;
      let текст: string;
      try {
        текст = readFileSync(join(REPO, rel), "utf8");
      } catch {
        bad.push(rel + " (не прочитался)");
        continue;
      }
      проверено += 1;
      for (const ch of текст) {
        const c = ch.charCodeAt(0);
        if (запрещён(c)) {
          bad.push(`${rel} U+${c.toString(16).padStart(4, "0").toUpperCase()}`);
          break;
        }
      }
    }
    // Знаменатель печатается: зелёный при нулевом охвате — дефект сторожа.
    expect(проверено, "ни один файл не прочитан — сторож пуст").toBeGreaterThan(100);
    expect(
      bad,
      `проверено файлов: ${проверено}. Управляющий байт в исходнике — почти всегда ` +
        "съеденный слэш: \\b стал забоем, \\01 стал байтом 0x01, \\202 из \\2026 — " +
        "байтом 0x82. В редакторе их не видно, ошибки компиляции нет, а ветка " +
        "регулярки или путь в комментарии становятся неверными молча.",
    ).toEqual([]);
  });
});
