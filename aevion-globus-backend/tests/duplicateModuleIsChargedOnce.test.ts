import { describe, test, expect } from "vitest";
import { buildQuote, STANDALONE_APPS, getModulePrice } from "../src/data/pricing";

/**
 * Сторож: один и тот же модуль тарифицируется ОДИН раз.
 *
 * ЗАМЕР 04.09.2026 (проба buildQuote, до починки):
 *   lite [qsign]              = $19
 *   lite [qsign, qsign]       = $28   ← повтор продан как второй продукт
 *   lite [qsign, qright]      = $28   ← а это законно: модули РАЗНЫЕ
 *
 * То есть повтор в списке стоил ровно столько же, сколько настоящий второй
 * модуль. Список приходит из тела запроса и ничем не ограничен, так что
 * достаточно, чтобы он собрался с повтором — восстановление выбора, двойное нажатие.
 *
 * С 15.09.2026 тариф — это срок доступа ко всей планете: на платном сроке модули
 * входят в подписку и не тарифицируются вовсе. Надстройкой платно считаются только
 * отдельные приложения (STANDALONE_APPS) — на free. Там повтор и проверяется.
 *
 * Проверка ДВУСТОРОННЯЯ: без второй половины «повтор бесплатен»
 * удовлетворялось бы кодом, который перестал брать деньги за модули вовсе.
 */
const q = (modules: string[], tierId: Parameters<typeof buildQuote>[0]["tierId"] = "free") =>
  buildQuote({ tierId, seats: 1, modules, currency: "USD" }).total;

/** Приложения с ценой надстройки — то, что на free стоит денег. */
const платные = STANDALONE_APPS.map((a) => a.moduleId).filter((id) => (getModulePrice(id)?.addonMonthly ?? 0) > 0);
const [первый, второй] = платные;

describe("повтор модуля не продаётся дважды", () => {
  test("контроль: платных надстроек хватает на проверку", () => {
    expect(платные.length, "надстроек с ценой меньше двух — проверять нечего").toBeGreaterThanOrEqual(2);
    expect(q([первый]), "надстройка на free бесплатна — сторож мерит не то").toBeGreaterThan(0);
  });

  test("КОНТРОЛЬ: два РАЗНЫХ модуля по-прежнему дороже одного", () => {
    // Иначе «повтор бесплатен» проходило бы и на коде, раздающем модули даром.
    expect(
      q([первый, второй]),
      "два разных модуля перестали стоить дороже — мы раздаём платное"
    ).toBeGreaterThan(q([первый]));
  });

  test("тот же модуль дважды стоит столько же, сколько один раз", () => {
    expect(
      q([первый, первый]),
      "повтор в списке продан как второй продукт: человек платит за то, что у него уже есть"
    ).toBe(q([первый]));
  });

  test("трижды — тоже столько же", () => {
    expect(q([первый, первый, первый])).toBe(q([первый]));
  });

  test("на платном сроке ни повтор, ни сами модули не удорожают — они в подписке", () => {
    const пусто = q([], "medium");
    expect(q([первый], "medium"), "модуль посчитан сверх подписки").toBe(пусто);
    expect(q([первый, первый, второй], "medium"), "на medium повтор всё ещё удорожает").toBe(пусто);
  });
});
