/* Проверки данных, пришедших от соперника по p2p.
 *
 * Это единственный в модуле поток НЕДОВЕРЕННОГО ввода: сообщения приходят напрямую
 * от второго игрока, и он волен прислать что угодно. Раньше они применялись как есть,
 * и это давало две работающие подмены:
 *
 * 1. Имя соперника подставлялось в строку исхода партии:
 *        sOver(`${имя} сдался — Вы победили!`)
 *    а классификатор исхода ищет в этой строке слова «поражение» и «ничья». Соперник,
 *    назвавшийся «поражение», превращал ВАШУ ПОБЕДУ в проигрыш — в рейтинге, серии и
 *    статистике. Назвавшийся «ничья» — в ничью. Лечится не фильтрацией слов, а тем,
 *    что строка исхода больше не собирается из чужого текста вовсе.
 *
 * 2. Ход применялся без проверки, чьей фигурой он сделан. chess.js разрешает ход той
 *    стороны, чья сейчас очередь, поэтому сообщение, присланное когда очередь ВАША,
 *    двигало ВАШУ фигуру: соперник мог сам подставить вашего ферзя.
 */

export type UciMove = { from: string; to: string; promotion?: "q" | "r" | "b" | "n" };

const SQUARE = /^[a-h][1-8]$/;
const PROMO = new Set(["q", "r", "b", "n"]);

/** Разбирает ход в UCI. Возвращает null на любом мусоре — вызывающий ничего не применяет. */
export function parseUciMove(raw: unknown): UciMove | null {
  if (typeof raw !== "string") return null;
  if (raw.length !== 4 && raw.length !== 5) return null;
  const from = raw.slice(0, 2);
  const to = raw.slice(2, 4);
  if (!SQUARE.test(from) || !SQUARE.test(to)) return null;
  if (from === to) return null;
  if (raw.length === 5) {
    const p = raw[4];
    if (!PROMO.has(p)) return null;
    return { from, to, promotion: p as "q" | "r" | "b" | "n" };
  }
  return { from, to };
}

/** Максимум символов в имени соперника — чтобы длинная строка не разносила вёрстку. */
const NAME_MAX = 24;

/**
 * Символ, которого не должно быть в отображаемом имени: управляющие, невидимые
 * и разделители строк. Проверка по коду, а не регуляркой: класс символов с
 * управляющими кодами внутри плохо переживает копирование между инструментами
 * и читается хуже, чем перечисление диапазонов словами.
 */
function isInvisible(cp: number): boolean {
  if (cp < 0x20) return true;                      // управляющие C0, включая перевод строки
  if (cp >= 0x7f && cp <= 0x9f) return true;       // DEL и управляющие C1
  if (cp >= 0x200b && cp <= 0x200f) return true;   // нулевой ширины и метки направления
  if (cp === 0x2028 || cp === 0x2029) return true; // разделители строк и абзацев
  if (cp >= 0x202a && cp <= 0x202e) return true;   // принудительная смена направления письма
  if (cp >= 0x2066 && cp <= 0x2069) return true;   // изоляты направления
  if (cp === 0xfeff) return true;                  // неразрывный пробел нулевой ширины
  return false;
  /* Диапазоны 202A-202E и 2066-2069 добавлены после того, как их пропустил
     собственный тест: ими переворачивают порядок отображения текста, и имя
     соперника может выглядеть на экране совсем не тем, что в нём записано. */
}

/**
 * Имя соперника для показа. Невидимые символы вырезаются, длина ограничена.
 * Имя НИКОГДА не участвует в определении исхода партии — только в отображении.
 */
export function safeOpponentName(raw: unknown): string {
  if (typeof raw !== "string") return "Соперник";
  let cleaned = "";
  for (const ch of raw) {
    const cp = ch.codePointAt(0);
    if (cp !== undefined && !isInvisible(cp)) cleaned += ch;
  }
  cleaned = cleaned.trim();
  if (!cleaned) return "Соперник";
  return cleaned.length > NAME_MAX ? cleaned.slice(0, NAME_MAX) + "…" : cleaned;
}
