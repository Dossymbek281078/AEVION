/**
 * Покупки по каналам должны быть НА ЭКРАНЕ, а не только в ответе сервера.
 *
 * Класс, на который я наступал в этом же окне дважды: поле доезжает до ответа,
 * а страница его не читает — и снаружи это неотличимо от «данных нет». Сводка
 * при этом выглядит полной: соседние панели на месте.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stripComments } from "../../../__tests__/helpers/sourceCode";

const страница = stripComments(readFileSync(join(process.cwd(), "src/app/pricing/admin/page.tsx"), "utf8"));
const словарь = readFileSync(join(process.cwd(), "src/lib/i18n-data.ts"), "utf8");

describe("панели покупок по каналам", () => {
  it("страница читает оба поля ответа", () => {
    expect(страница).toContain("summary.purchaseByChannel");
    expect(страница).toContain("summary.purchaseRevenueByChannel");
  });

  it("у выручки подписан знаменатель — иначе частичная читается как полная", () => {
    // Сумма известна не у всех покупок: у возврата PayBox в адрес уходит ref.
    expect(страница).toContain("summary.purchaseWithKnownAmount");
    expect(страница).toContain("summary.purchaseCount");
  });

  it("ярлык выручки не обещает ПОЛУЧЕННЫЕ деньги", () => {
    // Считается сумма из адреса возврата — наша ожидаемая, а не списанная
    // кассой: цену у Gumroad и LemonSqueezy назначает продавец. Слово
    // «выручка» без «ожидаемая» читается как деньги на счету.
    for (const ключ of ["Expected revenue", "Ожидаемая выручка", "Күтілетін түсім"]) {
      expect(словарь, `нет честного ярлыка: ${ключ}`).toContain(ключ);
    }
  });

  it("фактическая выручка стоит РЯДОМ с ожидаемой, а не вместо", () => {
    // Две колонки нужны именно для расхождения: ожидаемую мы берём из своего
    // каталога, фактическую — из записи подписки. Цену у Gumroad и
    // LemonSqueezy назначает продавец, и до 01.09.2026 их никто не сверял.
    expect(страница).toContain("purchaseRevenueByChannel");
    expect(страница).toContain("chargedRevenueByChannel");
  });

  it("при отсутствии данных НЕ рисуется ноль", () => {
    // «Ноль выручки» и «не спросили» выглядят одинаково, а значат
    // противоположное. Ручка живёт в соседней ветке и до мержа отвечает
    // отказом — панель обязана сказать «не знаем», а не показать пустые
    // столбцы, которые прочтут как «продаж нет».
    expect(страница, "нет ветки на случай отказа").toContain("спросить не удалось");
    expect(страница, "503 должен читаться как замысел, а не поломка").toContain(
      "ручка закрыта",
    );
    // Данные рисуются ТОЛЬКО когда они есть.
    expect(страница).toContain("{фактическая ? (");
  });

  it("у фактической подписан знаменатель по withAmount, а не по total", () => {
    // У PayBox суммы нет вовсе (в адрес возврата уходит ref), поэтому доля
    // считается от числа записей С СУММОЙ, а не от всех.
    expect(страница).toContain("фактическая.withAmount}/${фактическая.total}");
  });

  it("ответ на СТАРОЕ окно не подменяет свежие числа", () => {
    // Запрос фактической выручки идёт отдельно и не дожидается остальных.
    // Панель перезагружают при смене окна (24 ч / 7 дней / 30 дней), и ответ на
    // прошлое окно может прийти последним. Числа стали бы не за тот период, а
    // выглядела бы панель исправной — худший вид ошибки на денежном экране.
    expect(страница, "нет номера запроса").toContain("номерЗапроса");
    // Сверок должно быть ДВЕ: на успешном пути и в ветке отказа. Без второй
    // устаревшая НЕУДАЧА затрёт свежие числа строкой «спросить не удалось» —
    // панель скажет «не знаем» там, где данные есть. Первая редакция требовала
    // одну, и мутация «снять сверку» её пережила: вторая оставалась на месте.
    const сверок = страница.split("мойНомер !== номерЗапроса.current").length - 1;
    expect(сверок, "сверка номера нужна и на успехе, и на отказе").toBe(2);
  });

  it("панель НЕ обещает сравнимости там, где её нет", () => {
    // Тревогу о расхождении я завёл и убрал в тот же час. Колонки считают
    // разные совокупности: ожидаемая — по событиям браузера, фактическая — по
    // записям подписок. Покупка с закрытой вкладкой даёт запись без события,
    // сбой вебхука — событие без записи. Тревога была бы вечно красной.
    expect(страница, "нет пояснения про разные совокупности").toContain(
      "Колонки считают разное",
    );
    expect(страница, "нельзя утверждать расхождение по несравнимым суммам").not.toContain(
      "Списано не столько",
    );
  });

  it("неполная история названа прямо, а не скрыта", () => {
    // Файл покупок лежит в контейнере (путь на проде не задан), значит при
    // каждой выкатке отсчёт начинается заново. Без этой полосы панель показала
    // бы выручку «с последней выкатки» как всю историю — снаружи это
    // неотличимо от «продаж было мало». Признак прислало соседнее окно вместе
    // с ручкой; мы обязаны его ЧИТАТЬ, иначе он бесполезен.
    // Строго `=== false`, а НЕ `!onVolume`: при отсутствии поля (старый сервер)
    // и при onVolume=true панель обязана молчать. Замер соседнего окна на проде
    // 01.09.2026: каталог НА ПОСТОЯННОМ ДИСКЕ, июльские записи живут в
    // августовской сборке, onVolume=true. Мягкая проверка пугала бы на
    // исправной системе, а сторож, кричащий на здоровое, перестают читать.
    expect(страница).toContain("storage?.onVolume === false");
    expect(страница, "мягкая проверка напугала бы на исправной системе").not.toContain(
      "!фактическая.storage?.onVolume",
    );
    expect(страница, "не сказано, что история неполная").toContain("История неполная");
    // Требуем именно УСЛОВИЕ, а не слово: слово стоит и внутри подстановки, и
    // первая редакция пережила мутацию «убрать проверку даты» — второе
    // вхождение оставалось на месте.
    expect(страница, "дата ранней записи не проверяется перед показом").toContain(
      "storage?.oldestRecord",
    );
  });

  it("подписи есть на всех трёх языках", () => {
    const счёт = (k: string) => словарь.split(k).length - 1;
    expect(счёт('"pricing.admin.breakdown.purchaseByChannel"')).toBe(3);
    expect(счёт('"pricing.admin.breakdown.purchaseRevenueByChannel"')).toBe(3);
  });
});
