"use client";

import { useEffect } from "react";
import { track } from "@/lib/track";

/**
 * Отметить заход на /go — страницу, на которую ведёт ЕДИНСТВЕННАЯ кликабельная
 * ссылка из шапок соцсетей.
 *
 * Замер 27.08.2026: события `page_view` шлют шесть страниц платформы, а /go —
 * НЕТ. Покупка при этом помечается каналом (см. BuyLink), то есть после
 * раздачи роликов мы увидели бы продажи с источником и не увидели бы заходов.
 *
 * Разница не косметическая. Без числа заходов «ноль продаж» не отличить от
 * «никто не пришёл»: первое лечат предложением и ценой, второе — трафиком.
 * Это два разных решения, и выбирать между ними наугад дороже, чем измерить.
 *
 * `source` берётся тот же, что у кнопок покупки на этой странице (`go` или
 * `go-<канал>`), чтобы заход и покупка сходились в одной воронке, а не жили
 * под разными именами.
 *
 * Компонент клиентский, потому что сама страница серверная: маячок можно
 * зажечь только в браузере. Отправка идёт через navigator.sendBeacon и не
 * задерживает отрисовку.
 */
export default function PageViewBeacon({
  source,
  channel,
}: {
  source: string;
  channel?: string | null;
}) {
  useEffect(() => {
    track({
      type: "page_view",
      source,
      meta: channel ? { channel } : undefined,
    });
    // Один раз на монтирование: повторные отправки завысили бы заходы, а по
    // ним считается доля покупок.
  }, [source, channel]);

  return null;
}
