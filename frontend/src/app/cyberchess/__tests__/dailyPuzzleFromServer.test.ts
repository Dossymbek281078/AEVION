import { describe, test, expect } from "vitest";
import * as fs from "node:fs";
import * as path from "node:path";
import { stripComments } from "./_stripComments";

// Страница задачи дня берёт позицию С СЕРВЕРА, а встроенную — только запасной.
// 19.08.2026.
//
// Замер: в банке ChessPuzzle 502 584 записи, а страница брала одну из тридцати,
// зашитых в браузерный пакет. Тридцать — цикл повтора в месяц; к запуску 30.08
// человек его заметит. Ручка бэкенда настоящую задачу уже отдавала — страница
// её просто не звала.
//
// Проверка текстовая по исходнику, и это сказано прямо: страница тянет chess.js
// и весь холст, поднимать её в тесте ради одной строки дороже, чем полезно.

const PAGE = path.join(__dirname, "..", "daily", "page.tsx");
const src = () => stripComments(fs.readFileSync(PAGE, "utf-8"));

describe("задача дня приходит с сервера", () => {
  test("страница зовёт ручку задачи дня", () => {
    expect(src()).toMatch(/cyberchess-daily\/puzzle/);
  });

  test("встроенный набор остаётся запасным путём, а не единственным", () => {
    const s = src();
    // Начальное состояние — из встроенного набора: страница обязана работать
    // сразу и при мёртвом бэкенде.
    expect(s).toMatch(/useState<Puzzle>\(\(\) => POOL\[/);
    // И при этом заменяться серверной.
    expect(s).toMatch(/setPuzzle\(/);
  });

  test("смена задачи сбрасывает состояние решения", () => {
    const s = src();
    // Иначе останутся ходы и подсказки от прошлой позиции.
    expect(s).toMatch(/setSolIndex\(0\)/);
    expect(s).toMatch(/setHintsUsed\(0\)/);
    expect(s).toMatch(/setSolved\(false\)/);
  });

  test("источник задачи подписан, и подпись различает два случая", () => {
    const s = src();
    expect(s).toMatch(/daily-puzzle-source/);
    expect(s).toMatch(/из общего банка/);
    expect(s).toMatch(/Резервная задача/);
  });

  test("признак берётся из ответа сервера, а не угадывается", () => {
    // Угадывание по длине пула или по имени id — ровно тот способ, которым
    // подписи начинают врать при первом же изменении данных.
    //
    // 02.09.2026 проверка была ПЕРЕПИСАНА, потому что закрепляла дефект.
    // Она требовала разбора поля `source`, а разбор шёл ПОДСТРОКОЙ:
    // `source.includes("банк")`. Строка отказа — «резервный пул из 30 задач:
    // банк не ответил» — это слово содержит, поэтому страница писала
    // «задача из общего банка, одна и та же у всех» ровно тогда, когда банк
    // не ответил. Сторож при этом был зелёный: он спрашивал «читаешь ли
    // source», а не «получаешь ли верный ответ».
    expect(src()).toMatch(/typeof j\?\.fromBank === 'boolean'/);
    expect(src()).not.toContain("includes('банк')");
  });
});
