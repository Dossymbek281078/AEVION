/**
 * Дата из строки запроса, пригодная для сравнения с колонкой времени.
 *
 * Зачем отдельная функция — тот же довод, что у `queryNumber`, только вместо
 * NaN здесь строка, которую не примет СУБД. `?before=zzz` уходит параметром в
 * `created_at < $1`, Postgres отвечает ошибкой, наружу идёт 500 и запись в
 * Sentry — на запрос, целиком неверный со стороны клиента. Это правило 15г:
 * 5xx поднимает людей и хоронит настоящие аварии в шуме, а место такому ответу
 * — 400.
 *
 * ПРОВЕРЯЕМ ФОРМУ, А НЕ ТОЛЬКО РАЗБОР, и это не перестраховка. `Date.parse("1")`
 * в Node возвращает валидную дату (год 2001), а Postgres такую строку не
 * принимает — то есть проверка одним `Date.parse` СЛАБЕЕ базы, и 500 остаётся.
 * Сначала форма, потом разбор.
 *
 * Замер 28.08.2026: идиома уже была скопирована в трёх файлах (`stories`,
 * `communities`, `shifts`) и отсутствовала в четырёх местах, где значение так
 * же уходит в SQL — три ручки qpaynet и календарь выплат. Функция заведена,
 * чтобы копий стало ноль, а не четыре: три способа делать одно и то же — это
 * три места, где следующий забудет.
 *
 * Возвращаем ИСХОДНУЮ строку, а не Date: параметры уходят в запрос как есть, и
 * превращение в Date добавило бы шаг, на котором часовой пояс может сместиться.
 */

/** ISO-подобная дата: `2026-08-28`, при желании со временем и зоной. */
const ISO_DATE = /^\d{4}-\d{2}-\d{2}([T ][\d:.+\-Z]*)?$/;

/**
 * `null` — параметр не передан (это законно, фильтра просто нет).
 * `undefined` — передан, но непригоден: вызывающий обязан ответить 400.
 */
export function queryDate(raw: unknown): string | null | undefined {
  if (raw === null || raw === undefined) return null;
  // Массив приходит на ?before=a&before=b — берём первое, как и queryNumber.
  const one = Array.isArray(raw) ? raw[0] : raw;
  if (typeof one !== "string") return undefined;
  const s = one.trim();
  // Пустая строка — это «фильтр не задан», а не «неверная дата»: так ведут себя
  // формы, которые отправляют поле пустым.
  if (s === "") return null;
  if (!ISO_DATE.test(s) || Number.isNaN(Date.parse(s))) return undefined;
  return s;
}
