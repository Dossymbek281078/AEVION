/**
 * Размер банка задач на витрине шахмат — только из живого источника.
 *
 * 19.08.2026 на одном экране стояли два разных числа: в шапке 502 584 (из
 * /meta → bankTotal), а в карточке «Реши пазл» — зашитое «500 000 задач в
 * банке». Зашитое число не врало в день, когда его писали, и начало врать
 * молча, как только банк вырос. Витрина, спорящая сама с собой, читается как
 * «здесь никто не считал».
 */
import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

const PAGE = path.join(__dirname, "..", "page.tsx");

describe("счётчик задач на витрине", () => {
  it("страница читается", () => {
    expect(fs.existsSync(PAGE), PAGE).toBe(true);
  });

  it("размер банка нигде не зашит числом", () => {
    const src = fs.readFileSync(PAGE, "utf8");
    // Ищем «500 000», «502 584» и т. п. рядом со словом «задач» — то есть
    // именно заявление о размере банка, а не любое число на странице.
    // Комментарии вырезаем: сторож, краснеющий на объяснении рядом с кодом,
    // приучает себя не читать. Пороги достижений («10 пазлов», «50 пазлов»)
    // — законные постоянные, поэтому ловим только числа от тысячи.
    const code = src.replace(/\/\*[\s\S]*?\*\//g, "").replace(/^\s*\/\/.*$/gm, "");
    const hits = [...code.matchAll(/[0-9][0-9  ]{3,}\s*(задач|пазл)/gi)]
      .map((m) => m[0])
      .filter((t) => Number(t.replace(/[^0-9]/g, "")) >= 1000);
    expect(hits, `зашитый размер банка: ${hits.join(" | ")}`).toEqual([]);
  });

  it("число берётся из bankTotal, а не из загруженной пачки", () => {
    const src = fs.readFileSync(PAGE, "utf8");
    expect(src.includes("bankTotal"), "счётчик потерял источник правды").toBe(true);
    // `total` из ?limit=1 упирается в потолок загрузки — за это уже поймали.
    expect(/cyberchess-puzzles\?limit=1/.test(src), "вернулось поле total вместо bankTotal").toBe(false);
  });
});
