import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { stripComments } from "./helpers/sourceCode";

/**
 * Блок покупки на главной: имя товара не переводится, метка канала доезжает.
 *
 * Два дефекта, замеренных на ЖИВОМ проде 22.09.2026 сразу после выкатки.
 *
 * 1. AutoTranslate превратил «Gratitude ∞ Forever Young» в «Благодарность ∞
 *    Навсегда молодой». В кассе Gumroad товар называется по-английски, то есть
 *    человек видит одно имя на витрине и другое на оплате — обрыв доверия
 *    ровно в точке платежа. Лечится стандартным `translate="no"` (AutoTranslate
 *    его уважает). Вид карточки и цену переводить НУЖНО, поэтому метка только
 *    на имени.
 *
 * 2. Заход по `/?c=yt` клал метку в sessionStorage, но ссылки кассы оставались
 *    БЕЗ неё. Причина не в channelNow: сервер канала не знает и отдаёт голый
 *    адрес, а React при гидрации НЕ переписывает несовпавшие атрибуты — только
 *    предупреждает. Значит серверный href жил до первой перерисовки, которой
 *    не происходило, и покупка с YouTube приходила бы как «источник неизвестен».
 *    Лечится тем, что канал кладётся в состояние ПОСЛЕ монтирования.
 *
 * ГРАНИЦА ЧЕСТНО: сторож исходникового уровня — он закрепляет, что приём не
 * исчез. Что метка реально доезжает на проде, проверяется браузером:
 *   открыть /?c=yt, прочитать href ссылки на gumroad — в нём должен быть channel.
 */
const HERE = dirname(fileURLToPath(import.meta.url));
// Комментарии вырезаем: пояснение выше само содержит и `translate="no"`, и
// `setКанал`, и сторож по сырому исходнику остался бы зелёным при УДАЛЁННОМ коде.
/*
 * 06.10.2026: содержимое главной уехало в _home.tsx — на её месте серверная
 * обёртка ради canonical (клиентский компонент не может экспортировать
 * metadata). Путь здесь обновлён, иначе сторож читал бы обёртку из тридцати
 * строк и был бы зелёным НА ПУСТОМ МЕСТЕ — то есть проверял бы замысел, а не
 * страницу. Охват не изменился.
 */
const src = stripComments(readFileSync(join(HERE, "..", "_home.tsx"), "utf8"));

describe("блок покупки на главной", () => {
  it("ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: блок вообще на месте", () => {
    // Без этого обе проверки ниже были бы зелёными на УДАЛЁННОМ блоке.
    expect(src).toContain("покупкиНаГлавной");
    expect(src).toContain("ПОКУПКИ.map");
  });

  it("имя товара помечено translate=\"no\"", () => {
    expect(src).toMatch(/<span\s+translate="no"[^>]*>\{п\.название\}<\/span>/);
  });

  it("вид и цена НЕ помечены — их переводить нужно", () => {
    // Отрицательный контроль: сплошное `translate="no"` на карточке оставило бы
    // русского посетителя с английскими подписями, то есть починка превратилась
    // бы в свою противоположность.
    expect(src).toMatch(/<span[^>]*>\{п\.вид\}<\/span>/);
    expect(src).not.toMatch(/<span\s+translate="no"[^>]*>\{п\.вид\}/);
    expect(src).not.toMatch(/<span\s+translate="no"[^>]*>\{п\.цена\}/);
  });

  it("канал кладётся в состояние ПОСЛЕ монтирования, а не в useMemo напрямую", () => {
    /*
     * Проверяется ЗАМЫСЕЛ, а не дословная строка: канал обязан читаться в ЭФФЕКТЕ,
     * а не при рендере, иначе первый клиентский кадр разойдётся с серверным.
     *
     * ⚠️ Прежний образец требовал ровно `useEffect(() => setКанал(channelNow())` и
     * покраснел 06.10.2026 на ЗАКОННОЙ правке: в тот же эффект добавилось чтение
     * входящей метки для внешней кассы, и стрелка стала блоком. Сторож по дословной
     * строке краснеет на починке — наш записанный класс. Границы здесь структурные
     * (от первого useEffect до useMemo), регулярок нет намеренно: эскейпы съедаются
     * на границе вызова и ломают образец молча.
     */
    const гдеКанал = src.indexOf("setКанал(channelNow())");
    expect(гдеКанал, "канал не кладётся в состояние вовсе").toBeGreaterThan(0);
    // Нужен БЛИЖАЙШИЙ ПРЕДШЕСТВУЮЩИЙ useEffect, а не первый в файле: замер 06.10 —
    // первый useEffect на позиции 2711, первый useMemo на 9354, а наша строка на 12870.
    // Окно «от первого до первого» попало не туда и соврало, что канал не в эффекте.
    const гдеЭффект = src.lastIndexOf("useEffect(", гдеКанал);
    expect(гдеЭффект, "перед чтением канала нет useEffect — значит это рендер").toBeGreaterThan(0);
    expect(
      src.slice(гдеЭффект, гдеКанал).includes("useMemo("),
      "между useEffect и чтением канала начался useMemo — канал читается при рендере",
    ).toBe(false);
    // И ни одного другого вызова: единственный channelNow() в файле — тот, что в эффекте.
    expect(
      src.split("channelNow(").length - 1,
      "channelNow зовут больше одного раза — проверьте, не из рендера ли",
    ).toBe(1);
    // Канал передаётся помощнику ПЕРВЫМ аргументом. Сверка по началу вызова, а не по
    // дословной строке: 06.10.2026 у помощника появился второй аргумент (входящая метка
    // для внешней кассы), и прежний образец `покупкиНаГлавной(канал)` покраснел на
    // законной правке — тот же класс, что и соседнее утверждение выше.
    expect(
      src.includes("покупкиНаГлавной(канал"),
      "блок покупок на главной строится не через общего помощника или без канала",
    ).toBe(true);
    // Отрицательный контроль: прежняя форма, из-за которой метка не доезжала.
    expect(src).not.toMatch(/покупкиНаГлавной\(channelNow\(\)\)/);
  });
  it("внешние карточки идут через BuyLink, а не через голый <a>", () => {
    // Замер 22.09: на посадочных /go и /shop клик по кассовой ссылке уходит в
    // воронку событием checkout_start (sendBeacon через BuyLink), а блок на
    // ГЛАВНОЙ этого не делал. Покупка видна только по вебхуку кассы, поэтому
    // без события «никто не нажал» и «нажали, но не купили» неразличимы — это
    // два разных диагноза и два разных следующих шага.
    expect(src).toContain('import { BuyLink } from "@/components/BuyLink"');
    expect(src).toMatch(/<BuyLink[\s\S]{0,300}source="home"/);
    expect(src).toMatch(/productId=\{п\.id\}/);
    expect(src).toMatch(/priceUsd=\{п\.ценаUsd\}/);
  });

  it("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: внутренняя ссылка события НЕ шлёт", () => {
    // Сплошной BuyLink слал бы checkout_start на переходе к ВЫБОРУ тарифа,
    // то есть завышал бы воронку ровно на том рубеже, который мы и меряем.
    // Проверяем, что ветка обычной ссылки на месте и выбор идёт по признаку.
    expect(src).toMatch(/if \(п\.внешняя\)/);
    expect(src).toMatch(/<a key=\{п\.href\} href=\{п\.href\}/);
  });

  it("мёртвой ветки старой разметки не осталось", () => {
    // Строительные леса `{false && …}` — это код, который обещает и не делает;
    // он же ослепляет любой греп по разметке.
    expect(src).not.toContain("{false &&");
  });
});
