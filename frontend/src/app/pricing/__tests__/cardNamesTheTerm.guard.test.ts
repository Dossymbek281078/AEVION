import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Дешёвая половина сторожа: карточка собирает ступень и срок из ГОТОВЫХ кусков,
 * а переключатель имеет якорь, по которому карточка к нему приводит.
 *
 * Настоящий контракт («человек видит, что покупает, на 390 px») проверяет
 * e2e/pricing-card-names-the-term.spec.ts — он требует поднятого сервера и идёт
 * в CI. Эта проверка нужна, чтобы правка не прошла молча в обычном прогоне:
 * пропажа якоря или метки краснеет здесь же, за секунды.
 *
 * Повод — замер 06.10.2026: переключатель срока стоял на 793 px выше экрана,
 * видимых из пяти кнопок ноль, по умолчанию Lite; пришедший за Pro покупал месяц.
 */
const СТРАНИЦА = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");

describe("карточка приложения называет срок", () => {
  it("прибор исправен: страница цен прочитана", () => {
    expect(СТРАНИЦА.length, "страница не прочитана — сторож смотрит не туда").toBeGreaterThan(5000);
    expect(СТРАНИЦА, "карточек приложений больше нет").toContain("STANDALONE_APPS.map");
  });

  it("у переключателя срока есть якорь, по которому к нему прокручивают", () => {
    expect(СТРАНИЦА, "якорь переключателя исчез — карточке некуда вести").toContain('id="app-term"');
    // Ссылка на якорь, а не onClick: нативно, работает без скрипта и не ломает
    // чужую проверку, которая опознаёт кнопку ПОКУПКИ как «кнопку в карточке».
    expect(СТРАНИЦА, "карточка не ведёт к переключателю").toContain('href="#app-term"');
  });

  it("метка ступени собрана из готовых кусков, без новых ключей перевода", () => {
    // TERM_NAME — данные, срокТекст — уже существующая подпись. Новый ключ на
    // девяти языках молча откатился бы на английский; в этом файле тот же довод
    // записан про вторую границу цены.
    expect(СТРАНИЦА, "метка ступени не рисуется").toContain("{TERM_NAME[appTerm]} · {срокТекст(месяцев)}");
    expect(СТРАНИЦА, "метку не найти из теста — нет data-атрибута").toContain("data-app-term-badge");
  });

  it("полная сумма за срок на карточке осталась", () => {
    // Она была и до правки; потерять её нельзя — без неё метка назовёт срок,
    // а сумму человек снова не увидит.
    expect(СТРАНИЦА).toContain("заСрок(termTotal(a.baseMonthly, appTerm), месяцев)");
  });
});
