import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/*
 * 🔴 143г (18.10.2026). Замер на проде eaca8fb62, 768×1024, экран игры (телефонная раскладка, доска упёрлась в высоту):
 * верх доски 157, доска vh−300 = 724, ряд под доской «буквы · масштаб · Нашли ошибку?» лежал на 881..950, а
 * закреплённая панель «Сдаться · Ничья · Отменить · Подсказка» (894..946) накрывала и масштаб, и кнопку —
 * elementFromPoint в центре кнопки отдавал панель; приёмка priemka-oshibka-143 красила пару 768×1024.
 * Константа 300 не знала ни измеренного верха доски, ни панели действий. Теперь резерв телефона = измеренный верх
 * (запас 157 до первого замера) + 216 под доской (буквы 26 + ряд 44 + 8, панель 52 + 8, навигация 70 + 8).
 * На 390×844 и 540×900 доску держит ширина, там ничего не меняется.
 */
const src = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");

describe("резерв высоты доски на телефоне — от измеренного верха, не 300 (143г)", () => {
  it("🔴 резерв телефона складывается из измеренного верха доски и 216 под доской", () => {
    expect(src).toContain("const ПОД_ДОСКОЙ_ТЕЛЕФОН=216;");
    expect(src).toContain("const vReserve=vwPx>=769?desktopVReserve:(boardTopPx>0?boardTopPx:157)+ПОД_ДОСКОЙ_ТЕЛЕФОН;");
    expect(src).not.toContain("desktopVReserve:300;");
  });
  it("слагаемые 216 названы в комментарии рядом — чтобы следующий ряд под доской правил число, а не гадал", () => {
    expect(src).toContain("буквы 26 + ряд масштаба 44 + 8, панель действий 52 + 8, нижняя навигация 70 + 8 = 216");
  });
});
