/**
 * 🔴 ВЫЗОВЫ, ТРЕБУЮЩИЕ JSON, ПОМЕЧЕНЫ СТРУКТУРНЫМИ.
 *
 * У моделей с внутренним размышлением (gemini-2.5-flash — основной поставщик
 * генерации DevHub) размышление тратит ТОТ ЖЕ бюджет, что и ответ. Для
 * свободного текста обрыв даёт неполный, но читаемый ответ; для JSON обрыв
 * означает, что ответ не разберётся ВООБЩЕ, и сервер делает второй вызов.
 *
 * Флаг `структурныйОтвет` завели ровно под это 07.10.2026 — и до 12.10 его не
 * передавал НИ ОДИН вызов во всём бэкенде: механизм был написан и не позван.
 * Цена видна в замере 12.10 (пять генераций гостем на одном тексте):
 * 23.3 / 63.0 / 23.9 / 22.5 / 26.3 с, и ровно у медленного прогона стоит
 * `continued: true` — ответ оборвался на пределе 8192 токенов.
 *
 * ⚠️ Что сторож проверяет и чего не может: он смотрит ВЫЗОВЫ в маршруте
 * DevHub — все ли, кто просит JSON, помечены. Он НЕ доказывает, что обрывов
 * стало меньше: это решает живой замер после выкатки, и знаменатель там равен
 * числу прогнанных генераций.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const МАРШРУТ = readFileSync(join(__dirname, "../src/routes/devhub.ts"), "utf8");

/** Вызовы callProvider в маршруте, вместе с их доводами (до закрывающей скобки). */
function вызовы(): string[] {
  const куски: string[] = [];
  const re = /callProvider\(/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(МАРШРУТ))) {
    let глубина = 0, i = m.index + "callProvider".length;
    for (; i < МАРШРУТ.length && i < m.index + 4000; i++) {
      const c = МАРШРУТ[i];
      if (c === "(") глубина++;
      else if (c === ")") { глубина--; if (глубина === 0) break; }
    }
    куски.push(МАРШРУТ.slice(m.index, i + 1));
  }
  return куски;
}

describe("JSON-вызовы не тратят бюджет на размышление", () => {
  it("🔴 контроль прибора: вызовы вообще находятся", () => {
    const в = вызовы();
    expect(в.length, "в маршруте DevHub не найдено ни одного callProvider — прибор слеп").toBeGreaterThanOrEqual(4);
    expect(МАРШРУТ.length).toBeGreaterThan(50_000);
  });

  /*
   * 🔴 ПОЛИТИКА УТОЧНЕНА ЗАМЕРОМ, а не вкусом (12.10.2026, тот же день).
   *
   * Пометив структурными ВСЕ три вызова генерации, я убрал обрывы (0 из 5
   * против 1 из 5) и ускорил медиану с 24 до 13 с — но тот же замер показал
   * цену: страницы стали короче на 38 % (13 929 → 8 674 знака), а script.js
   * пропал во ВСЕХ пяти прогонах, тогда как раньше был в трёх из пяти.
   * Размышление и было тем, что делало страницу богаче.
   *
   * Поэтому политика теперь РАЗНАЯ для разных вызовов, и это не компромисс,
   * а разные задачи:
   *   • ОСНОВНАЯ генерация думает (флага нет), а бюджет удвоен до 16384 —
   *     места хватает и на мысль, и на ответ;
   *   • ДОЗАПРОС и САМОПОЧИНКА помечены структурными: там ответ короткий,
   *     и важна не полнота, а чтобы JSON разобрался.
   */
  it("🔴 основная генерация думает, а бюджет ей удвоен", () => {
    expect(МАРШРУТ).toContain("const GEN_MAX_TOKENS = 16384;");
    const основная = вызовы().find((в) => в.includes("cand.id") && в.includes("GEN_MAX_TOKENS"));
    expect(основная, "основной вызов генерации не найден").toBeTruthy();
    expect(/,\s*true\s*\)$/.test((основная ?? "").replace(/\s+/g, " ")),
      "основной генерации вернули запрет размышления — страницы станут беднее").toBe(false);
  });

  it("🔴 дозапрос и самопочинка помечены структурными — знаменатель 2 из 2", () => {
    const короткие = вызовы().filter((в) => в.includes("GEN_MAX_TOKENS") && !в.includes("cand.id"));
    expect(короткие.length, `коротких вызовов найдено ${короткие.length}`).toBe(2);
    const без = короткие.filter((в) => !/,\s*true\s*\)$/.test(в.replace(/\s+/g, " ")));
    expect(без.length, `без флага: ${без.length} из ${короткие.length}`).toBe(0);
  });

  it("🔴 ручка замысла (/plan) тоже просит JSON и тоже помечена", () => {
    const замысел = вызовы().filter((в) => в.includes("промптЗамыслаСЗапретом"));
    expect(замысел.length).toBe(1);
    expect(/,\s*true\s*\)$/.test(замысел[0].replace(/\s+/g, " ")), "вызов замысла без флага").toBe(true);
  });

  it("контроль: флаг ищется именно последним доводом, а не где попало", () => {
    // Выдуманный вызов с true НЕ на месте флага не должен считаться помеченным.
    const подделка = "callProvider(p.id, msgs, model, 0.2, true, GEN_MAX_TOKENS)";
    expect(/,\s*true\s*\)$/.test(подделка.replace(/\s+/g, " "))).toBe(false);
  });
});
