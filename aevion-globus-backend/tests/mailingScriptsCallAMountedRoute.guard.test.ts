import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Скрипты рассылки зовут адрес, который РЕАЛЬНО смонтирован.
 *
 * 🔴 ЗАЧЕМ. Замер на боевом проде 09.09.2026, за сутки до рассылки:
 *
 *     /api/constitution/waitlist/list        → 404  (как выдуманный адрес)
 *     /api/admin/constitution/waitlist/list  → 403  (существует, нужен доступ)
 *
 * Оба скрипта рассылки — и сухой прогон, и отправка — звали ПЕРВЫЙ. Публичный
 * роутер выгрузки не имеет вовсе: `/list` живёт только на админском, и тот
 * смонтирован отдельной строкой с мая. Скрипты написаны в августе и с самого
 * начала обращались к несуществующему адресу.
 *
 * Значит рассылка не запускалась НИ РАЗУ (сходится с тем, что реестров
 * отправленных на машине нет) и завтра остановилась бы на «HTTP 404».
 * Остановилась бы честно — скрипт отдаёт код 2 и прямым текстом говорит, что
 * это не «никто не подписан», — но намертво, в утро запуска.
 *
 * 🔴 ПОЧЕМУ СТОРОЖ, А НЕ ПРОСТО ПОЧИНКА. Дефект прожил три недели именно
 * потому, что путь нельзя проверить, не сходив на прод: он живёт строкой в
 * скрипте и строкой в `index.ts`, и эти две строки никто не сверял. Здесь они
 * сверяются без сети.
 *
 * ⚠️ ГРАНИЦА. Проверяется, что префикс адреса СМОНТИРОВАН, а не что ручка
 * отвечает: последнее требует живого сервера и доступа админа. Ошибку «не тот
 * роутер» это ловит, ошибку «маршрут внутри роутера переименовали» — нет.
 */
const ИНДЕКС = join(__dirname, "..", "src", "index.ts");
const СКРИПТЫ = ["launch-announce-send.ts", "launch-announce-dry.ts"];

/** Все префиксы, смонтированные в приложении. */
function смонтированные(): string[] {
  const src = readFileSync(ИНДЕКС, "utf8");
  return [...src.matchAll(/app\.use\(\s*"(\/api\/[^"]+)"/g)].map((m) => m[1]);
}

/** Адреса `/api/...`, которые скрипт зовёт через fetch. */
function адресаСкрипта(имя: string): string[] {
  const src = readFileSync(join(__dirname, "..", "scripts", имя), "utf8");
  const без = src.replace(/^\s*\/\/.*$/gm, "").replace(/\/\*[\s\S]*?\*\//g, "");
  return [...без.matchAll(/\$\{BASE\}(\/api\/[A-Za-z0-9/_-]+)/g)].map((m) => m[1]);
}

describe("скрипты рассылки зовут смонтированные адреса", () => {
  const префиксы = смонтированные();

  it("прибор видит предмет: точки монтирования и адреса разобраны", () => {
    // Без этого «все адреса смонтированы» означало бы «я не нашёл ни одного».
    expect(префиксы.length, "точки монтирования не разобраны").toBeGreaterThan(50);
    const всего = СКРИПТЫ.flatMap(адресаСкрипта);
    expect(всего.length, "ни одного адреса в скриптах не найдено").toBeGreaterThan(1);
  });

  for (const имя of СКРИПТЫ) {
    it(`${имя}: каждый адрес лежит под смонтированным префиксом`, () => {
      const плохие = адресаСкрипта(имя).filter(
        (u) => !префиксы.some((p) => u === p || u.startsWith(p + "/")),
      );
      expect(
        плохие,
        `скрипт зовёт адрес, которого нет ни под одним смонтированным префиксом. ` +
          "На проде такой адрес отвечает 404, и рассылка останавливается. " +
          "Сверьте строку в скрипте со строкой app.use(...) в index.ts.",
      ).toEqual([]);
    });
  }

  it("выгрузка подписчиков берётся с АДМИНСКОГО адреса", () => {
    // Отдельно и явно: публичный роутер `/list` не имеет, и обращение к нему
    // даёт 404 — ровно тот дефект, ради которого сторож написан.
    for (const имя of СКРИПТЫ) {
      const адреса = адресаСкрипта(имя);
      const выгрузка = адреса.filter((u) => u.includes("waitlist/list"));
      expect(выгрузка.length, `${имя}: обращения к выгрузке не найдено`).toBe(1);
      expect(
        выгрузка[0],
        `${имя}: выгрузка подписчиков берётся с публичного адреса — там её нет`,
      ).toBe("/api/admin/constitution/waitlist/list");
    }
  });
});
