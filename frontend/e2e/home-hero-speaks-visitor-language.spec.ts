import { test, expect, chromium } from "@playwright/test";

/**
 * ВЕСЬ ТЕКСТ ГЕРОЯ говорит на языке гостя — и СРАЗУ, а не через 5–8 секунд.
 *
 * ПОВОД (07–08.10.2026). user-db замерил в ЧИСТОМ контексте (newContext с
 * локалью, без куки): H1 по-английски, а на странице уже 3057 знаков кириллицы.
 * Я сперва не воспроизвёл — потому что ждал 2.5 секунды и попадал мимо. Ряд по
 * времени показал, что прав был он:
 *
 *   1123мс — переведено 653 знака,  H1 английский
 *   2608мс — переведено 3057 знаков, H1 английский   ← его замер
 *   5450мс — H1 наконец по-русски
 *
 * Пять секунд русский гость читал английский заголовок, когда остальная
 * страница уже была русской. Причина: заголовок стоял ЛИТЕРАЛОМ, и его
 * переводил слой перевода — до H1 он доходил последним. Словарь отдаёт строку
 * сразу, одним рендером.
 *
 * ПОЧЕМУ ЧИСТЫЙ КОНТЕКСТ. В моём обычном браузере лежит `aevion_lang_v1`, и он
 * переопределяет язык. Замер с чужой настройкой отвечает про МОЙ браузер, а не
 * про гостя — на этом я уже ошибался: объявлял дефектом продукта свою локаль.
 */

const БАЗА = process.env.PLAYWRIGHT_BASE_URL || "https://aevion.app";
const СРОК = 1500; // мс: столько даём на первый осмысленный кадр

const СЛУЧАИ = [
  { локаль: "ru-RU", нужнаКириллица: true, имя: "русский гость" },
  { локаль: "en-US", нужнаКириллица: false, имя: "английский гость" },
];

test.describe("главная: весь текст героя на языке гостя", () => {
  for (const с of СЛУЧАИ) {
    test(`весь текст героя — ${с.имя} (${с.локаль})`, async () => {
      const b = await chromium.launch();
      try {
        const ctx = await b.newContext({ locale: с.локаль, viewport: { width: 1280, height: 900 } });
        const page = await ctx.newPage();
        await page.goto(`${БАЗА}/?c=probe-golos-h1`, { waitUntil: "domcontentloaded" });
        await page.waitForTimeout(СРОК);

        // 08.10.2026: смотрим ВСЕ строки героя, а не один заголовок.
        // Повод: первая версия проверяла только H1 — и после правки, которая
        // перевела в словарь лишь заголовок, она бы позеленела, когда главная
        // КНОПКА у русского гостя оставалась английской ещё 7.7 секунды.
        // Зелёный сторож, проверяющий треть, опаснее отсутствующего: он выдаёт
        // разрешение не смотреть.
        const элементы = await page.evaluate(() => {
          const sec = document.querySelector("section");
          const снять = (имя: string, el: Element | null | undefined) => {
            const txt = (el?.textContent || "").trim();
            return {
              имя,
              есть: txt.length > 5,
              текст: txt.slice(0, 60),
              кир: (txt.match(/[а-яА-ЯёЁ]/g) || []).length,
              лат: (txt.match(/[a-zA-Z]/g) || []).length,
            };
          };
          return [
            снять("заголовок", document.querySelector("h1")),
            снять("главная кнопка", sec?.querySelector('a[href^="/devhub"]')),
            снять("ссылка Auth", sec?.querySelector('a[href^="/auth"]')),
            снять("абзац", sec?.querySelector("p")),
          ];
        });

        // Контроль охвата: если элемент не нашёлся, проверка обязана краснеть,
        // а не молча проверить три строки из четырёх.
        const пропали = элементы.filter((э) => !э.есть).map((э) => э.имя);
        expect(пропали, `${с.локаль}: не нашлись элементы героя — ${пропали.join(", ")}`).toEqual([]);
        expect(элементы.length, "список элементов героя усох").toBe(4);

        const плохие = элементы.filter((э) =>
          с.нужнаКириллица ? э.кир <= э.лат : э.лат <= э.кир,
        );
        expect(
          плохие.map((э) => `${э.имя}: «${э.текст}»`),
          `${с.локаль}: через ${СРОК}мс эти строки героя не на языке гостя. До 08.10 так вели себя ВСЕ четыре: словарь отдаёт строку сразу, литерал ждёт слоя перевода 5–8 секунд.`,
        ).toEqual([]);
      } finally {
        await b.close();
      }
    });
  }

  test("проверено 2 языка — охват назван числом", () => {
    expect(СЛУЧАИ.length, "список языков усох — проверка потеряла охват").toBe(2);
    expect(new Set(СЛУЧАИ.map((x) => x.локаль)).size, "в списке языков дубли").toBe(2);
  });
});
