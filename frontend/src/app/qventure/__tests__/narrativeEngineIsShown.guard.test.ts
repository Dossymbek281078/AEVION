import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Человек видит, чем сделан разбор: живой моделью или запасным движком.
 *
 * У QVenture есть честный запасной путь: без ключа провайдера совет из четырёх
 * ролей собирается детерминированно из собственной рубрики. Это правильное
 * поведение — модуль не падает и выдаёт содержательный результат.
 *
 * Но безопасная подстановка безопасна ТОЛЬКО пока она называет себя. Витрина
 * обещает «4-role advice panel»; если страница перестанет показывать, что
 * разбор собран без модели, детерминированный текст будет выдан за работу
 * совета — и никто не заметит, потому что он выглядит осмысленно.
 *
 * Обратная сторона уже закреплена в бэкенде (tests/qventureCouncilOffline:
 * без ключа aiUsed=false, aiProvider="stub"). Здесь закрепляется вторая
 * половина — что эта пометка ДОХОДИТ ДО ЭКРАНА. Поле, которое никто не
 * рисует, снаружи неотличимо от отсутствующего.
 */
const HERE = path.dirname(new URL(import.meta.url).pathname.replace(/^[/]([A-Za-z]:)/, "$1"));
const RESULT = path.resolve(HERE, "..", "_result.tsx");
const SRC = fs.readFileSync(RESULT, "utf8");

const NL = String.fromCharCode(10);
function withoutComments(src: string): string {
  return src.split(NL).filter((l) => !l.trim().startsWith("//")).join(NL);
}

describe("источник разбора виден человеку", () => {
  it("контроль: файл прочитан и это он", () => {
    expect(SRC.length, "разметка разбора не прочитана").toBeGreaterThan(5000);
    // Якорь контроля — КОД, а не подпись на экране: 01.09.2026 перевод модуля
    // покрасил этот сторож при целом продукте, а красное по такой причине
    // читается как поломка продукта и стоит получаса поисков.
    expect(SRC, "читается не тот файл").toContain("istochnikTeksta");
  });

  it("на экране написано, чем собран разбор", () => {
    expect(
      withoutComments(SRC),
      "со страницы пропала строка про движок разбора: детерминированный текст " +
        "будет выдан за работу совета из четырёх ролей, которую обещает витрина",
    ).toContain("Текст собран");
  });

  it("надпись ЗАВИСИТ от aiUsed, а не написана всегда одинаково", () => {
    // Главная проверка. Строка «live model» на месте, но не привязанная к
    // флагу, — это не пометка, а украшение: она соврёт ровно в тот день,
    // когда провайдер отвалится и разбор соберётся без модели.
    const at = withoutComments(SRC).indexOf("Текст собран");
    const line = withoutComments(SRC).slice(at, at + 260);
    expect(
      line,
      "надпись не зависит ни от чего — значит утверждает одно и то же всегда",
    ).toContain("istochnikTeksta");

    // 03.09.2026: состояний стало ТРИ, и это усиление, а не смена формулировки.
    // Прежде признак считался от НАСТРОЙКИ поставщика: при упавших вызовах
     // человек видел заготовку и читал «живая модель». Теперь источник берётся
    // по факту ответа, и частичный случай назван отдельно — иначе он
    // округлялся бы в одну из сторон, а округляют обычно в лучшую.
    const pom = withoutComments(SRC);
    expect(pom, "нет состояния «модель не ответила»").toContain("модель не ответила");
    expect(pom, "нет ЧАСТИЧНОГО состояния — оно округлится в лучшую сторону").toContain("частично");
    expect(pom, "источник считается не по факту, а по настройке").toContain("aiLive");
    expect(pom, "нет честного «не знаю» для старых записей").toContain("не записан");
  });

  it("у КАЖДОГО состояния свой текст, и их три", () => {
    // Прежде ветки жили в тернарном операторе прямо в разметке, и проверка
    // смотрела на строку. 03.09.2026 они переехали в помощник istochnikTeksta —
    // потому что состояний стало три, и тернарный оператор их не вмещает.
    // Проверка переехала следом: смотреть надо туда, где ветки, а не туда,
     // где они были.
    const pom = withoutComments(SRC);
    const at = pom.indexOf("function istochnikTeksta");
    expect(at, "помощника нет — ветки снова где-то ещё").toBeGreaterThan(0);
    const telo = pom.slice(at, at + 900);

    expect(telo, "нет ветки живой модели").toContain("живая модель");
    expect(telo, "нет ветки отказа модели").toContain("не ответила");
    expect(telo, "нет ЧАСТИЧНОЙ ветки").toContain("частично");
    expect(telo, "нет честного «не знаю» для старых записей").toContain("не записан");

    // И главное: источник считается по ФАКТУ ответа, а не по настройке.
    // Вернуть `aiUsed ? ... : ...` без aiLive — значит вернуть прежнюю ложь.
    expect(telo, "источник считается не по факту ответа").toContain("aiLive");
  });
});
