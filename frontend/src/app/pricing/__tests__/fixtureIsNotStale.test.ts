import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Снимок цен не стареет молча.
 *
 * Повод, 30.09.2026: этот fixture был сгенерирован 2 сентября и отстал от прода на
 * ЧЕТЫРЕ приложения — в нём было пять standaloneApps, на проде девять (не хватало
 * qright, qsign, startup_exchange, qskyway). Его читают тесты цены и кассы
 * (bundleCheckoutMatchesItsPrice, successScreenIsReadable), то есть почти месяц они
 * сверяли самое денежное, что у нас есть, с данными сентябрьской давности — и были
 * зелёными.
 *
 * Класс наш записанный: зелёные тесты на синтетике собственного изготовления. Пока
 * снимок не спрашивают о возрасте, он тихо превращается в вымысел, который выглядит
 * как замер.
 *
 * Порог 21 день выбран не на глаз: цены у нас меняются словом основателя, и за
 * сентябрь менялись трижды (лестница сроков 15.09, четыре модуля, база QSkyway).
 * Три недели — срок, за который расхождение ещё дёшево исправить.
 *
 * ⚠️ ЭТОТ ТЕСТ ОБЯЗАН ПОКРАСНЕТЬ САМ, без чьей-либо правки, когда снимок состарится.
 * Это не дефект теста — это его работа. Починка одна, и она не в тесте:
 *   curl -s https://api.aevion.app/api/pricing > \
 *     frontend/src/app/pricing/__tests__/__fixtures__/pricing.json
 * После обновления прогнать оба теста выше. Если они покраснеют — это НАСТОЯЩАЯ
 * находка (цена разошлась с ожиданием), и подгонять их под новый снимок нельзя.
 */
const ФАЙЛ = join(__dirname, "__fixtures__", "pricing.json");
const ПРЕДЕЛ_ДНЕЙ = 21;

/** Возраст снимка в днях. Отдельной функцией, чтобы проверять её на известных датах. */
export function возрастВДнях(generatedAt: unknown, сейчас: number): number | null {
  if (typeof generatedAt !== "string" || !generatedAt.trim()) return null;
  const t = Date.parse(generatedAt);
  if (!Number.isFinite(t)) return null;
  return (сейчас - t) / 86_400_000;
}

describe("снимок цен не стареет молча", () => {
  it("прибор исправен: возраст считается и мусор отличается от даты", () => {
    // Без этой пары «null» ниже был бы неотличим от «дата свежая».
    const база = Date.parse("2026-09-30T00:00:00.000Z");
    expect(возрастВДнях("2026-09-30T00:00:00.000Z", база)).toBe(0);
    expect(возрастВДнях("2026-09-09T00:00:00.000Z", база)).toBe(21);
    expect(возрастВДнях("2026-09-02T00:00:00.000Z", база)).toBe(28);
    expect(возрастВДнях("не дата", база), "мусор принят за дату").toBeNull();
    expect(возрастВДнях(undefined, база)).toBeNull();
    expect(возрастВДнях("", база)).toBeNull();
  });

  it("в снимке есть разбираемая дата генерации", () => {
    const снимок = JSON.parse(readFileSync(ФАЙЛ, "utf8"));
    const возраст = возрастВДнях(снимок.generatedAt, Date.now());
    expect(
      возраст,
      "у снимка цен нет разбираемого generatedAt — тогда его возраст неизвестен, " +
        "а неизвестный возраст хуже старого: он не краснеет никогда",
    ).not.toBeNull();
  });

  it(`снимок не старше ${ПРЕДЕЛ_ДНЕЙ} дней`, () => {
    const снимок = JSON.parse(readFileSync(ФАЙЛ, "utf8"));
    const возраст = возрастВДнях(снимок.generatedAt, Date.now()) ?? Number.POSITIVE_INFINITY;
    expect(
      Math.floor(возраст),
      `снимку цен ${Math.floor(возраст)} дн. (предел ${ПРЕДЕЛ_ДНЕЙ}). Обновите его с ` +
        "живого /api/pricing — команда в шапке этого файла. Тесты цены и кассы читают " +
        "именно его, и со старым снимком они зелёные впустую.",
    ).toBeLessThanOrEqual(ПРЕДЕЛ_ДНЕЙ);
  });

  it("снимок описывает то же, что прод: девять приложений в отдельной продаже", () => {
    // Возраст — не единственная беда: снимок может быть свежим по дате и неполным
    // по составу. Именно так и вышло: пять приложений против девяти.
    const снимок = JSON.parse(readFileSync(ФАЙЛ, "utf8"));
    const апп: Array<{ slug?: string }> = снимок.standaloneApps ?? [];
    expect(апп.length, "в снимке меньше приложений, чем продаётся").toBeGreaterThanOrEqual(9);
    for (const нужный of ["devhub", "cyberchess", "multichat", "ip_bureau", "qventure", "qright", "qsign", "startup_exchange", "qskyway"]) {
      expect(апп.some((a) => a.slug === нужный), `в снимке нет приложения ${нужный}`).toBe(true);
    }
  });
});
