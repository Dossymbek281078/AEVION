/**
 * Разбор данных, которые мы САМИ положили в кассу и получаем обратно из её
 * уведомления. Место общее по той же причине, по которой сюда переехал
 * `periodForReference`: пока правило живёт копиями, отставшая копия ничем
 * себя не выдаёт (замер 04.09.2026 — годовой период у одной кассы из
 * четырёх зашивался месячным именно так).
 *
 * Значения проходят через ЧУЖУЮ систему и возвращаются строками, поэтому
 * проверяются как внешний вход, а не как своё.
 */

/**
 * Верхний предел, чтобы уведомление не могло раздуть запись подписки.
 *
 * Он ОБЯЗАН быть больше каталога, иначе честная покупка «всего сразу»
 * теряет хвост молча. Замер 04.09.2026: в каталоге 43 модуля, а стояло 20 —
 * то есть предел, поставленный против враждебного ввода, резал бы законный.
 * Сторож moduleIdsSurviveTheProviderFilter требует, чтобы весь каталог
 * проходил круговорот целиком, и покраснеет, если каталог перерастёт это
 * число.
 */
const МАКСИМУМ_МОДУЛЕЙ = 100;

/** Идентификатор модуля: строчные буквы, цифры, дефис (qsign, aevion-ip-bureau). */
const ИДЕНТИФИКАТОР = /^[a-z0-9-]{1,64}$/;

/**
 * Число мест из данных кассы.
 *
 * `Number.parseInt` здесь НЕ годится: "3.9" он усечёт до 3, то есть примет
 * дробь молча. Требуем целое — дробь, минус, ноль и буквы дают одно место.
 */
export function местИзКассы(raw: unknown): number {
  const n = Number(String(raw ?? "").trim());
  if (!Number.isInteger(n) || n < 1) return 1;
  return Math.min(1000, n);
}

/**
 * Список модулей из данных кассы.
 *
 * Возвращает ПУСТОЙ список, если ничего годного не пришло, — но вызывающий
 * может передать `одиночный` как запасной путь: у покупок до 04.09.2026 в
 * кассу уезжал только один модуль (`pg_param_module` / `custom_id.module`),
 * и старые уведомления, доставляемые повторно, обязаны читаться по-прежнему.
 */
export function модулиИзКассы(raw: unknown, одиночный?: string): string[] {
  const список = String(raw ?? "")
    .split(",")
    .map((m) => m.trim())
    .filter((m) => ИДЕНТИФИКАТОР.test(m));
  const уникальные = Array.from(new Set(список)).slice(0, МАКСИМУМ_МОДУЛЕЙ);
  if (уникальные.length > 0) return уникальные;
  return одиночный && ИДЕНТИФИКАТОР.test(одиночный) ? [одиночный] : [];
}

/** Тот же отбор для ИСХОДЯЩЕЙ стороны: что мы кладём в кассу. */
export function модулиДляКассы(modules: unknown): string[] {
  const список = (Array.isArray(modules) ? modules : [])
    .filter((m): m is string => typeof m === "string")
    .map((m) => m.trim())
    .filter((m) => ИДЕНТИФИКАТОР.test(m));
  return Array.from(new Set(список)).slice(0, МАКСИМУМ_МОДУЛЕЙ);
}
