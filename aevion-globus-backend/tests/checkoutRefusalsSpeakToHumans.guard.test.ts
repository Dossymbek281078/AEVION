import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { stripComments } from "./helpers/sourceCode";

/**
 * Каждый отказ ЧЕКАУТА говорит с человеком, а не кодом.
 *
 * ЗАЧЕМ ИМЕННО ЗДЕСЬ. Это единственное место платформы, где отказ видит
 * человек, уже решившийся заплатить. Код вместо текста стоит нам не
 * непонимания, а покупки: он закроет вкладку, и мы даже не узнаем.
 *
 * ЗАМЕР 03.09.2026, из-за которого сторож и написан. Считал по всем денежным
 * маршрутам, сколько ответов несут человеческий текст рядом с кодом:
 *
 *     checkout.ts             5 с текстом : 1 без   ← почти чисто, добил
 *     qpaynet.ts              5 : 146
 *     pricing.ts              1 : 68
 *     все четыре вебхука      0 : 19
 *
 * Итого по деньгам 11 против 242. То есть беда платформы шире, чем «страница
 * берёт не то поле»: текста чаще НЕТ ВОВСЕ. Чинить все 242 одним заходом я
 * не стал — это решение о том, как мы отвечаем на отказ, а не дефект файла.
 * Но чекаут добить стоило: там оставался ровно один.
 *
 * ГРАНИЦА. Сторож держит ОДИН файл и не утверждает ничего про остальные.
 * Вебхуки сюда не входят намеренно: их читает машина провайдера, а не
 * человек, и человеческий текст там был бы украшением.
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const FILE = join(HERE, "..", "src", "routes", "checkout.ts");

/** Ответы с кодом ошибки: сколько из них несут текст для человека. */
function ответы(): { сТекстом: number; толькоКод: string[] } {
  const src = stripComments(readFileSync(FILE, "utf8"));
  let сТекстом = 0;
  const толькоКод: string[] = [];
  for (const кусок of src.split("res.status(").slice(1)) {
    const голова = кусок.slice(0, 220);
    if (!голова.includes('error:') && !голова.includes('"error"')) continue;
    if (голова.includes("message:")) сТекстом += 1;
    else толькоКод.push(голова.split("\n")[0].trim().slice(0, 60));
  }
  return { сТекстом, толькоКод };
}

describe("отказы чекаута говорят с человеком", () => {
  const r = ответы();

  it("контроль: ответы вообще найдены", () => {
    // Пустой разбор сделал бы проверку ниже зелёной при любом состоянии.
    expect(r.сТекстом + r.толькоКод.length, "разбор не нашёл ни одного отказа").toBeGreaterThanOrEqual(5);
  });

  it("ни один отказ не оставлен голым кодом", () => {
    expect(
      r.толькоКод,
      "человек, уже решившийся заплатить, увидит машинный код вместо объяснения — " +
        "он закроет вкладку, и мы даже не узнаем",
    ).toEqual([]);
  });
});
