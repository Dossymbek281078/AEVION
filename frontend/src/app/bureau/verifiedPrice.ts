/**
 * Цена отметки Verified на витрине — ОДНО место вместо одиннадцати.
 *
 * 🔴 Повод, замеренный 30.09.2026: «$19» стояло зашитым числом в 11 строках
 * шести файлов бюро, а бэкенд уже считал цену $29 (решение основателя 14.09,
 * период подтверждён 15.09: оплата ежемесячная). Сайт обещал одну цену, касса
 * списала бы другую — и это не косметика, а сломанное обещание на самом
 * денежном шаге платформы: бюро авторства и есть фокус продаж.
 *
 * Одиннадцать копий одного числа расходятся молча и всегда. Поэтому число
 * живёт здесь, а живое значение из `/api/bureau/health` (или из кабинета)
 * всегда главнее: оно приходит от того же кода, который назовёт сумму кассе.
 *
 * ПЕРИОД — часть цены, а не украшение. «$29» без «в месяц» это уже другое
 * обещание, и ломается доверие именно в кассе, где подписка называет себя сама.
 *
 * Сторож `verifiedPriceMatchesBackend.guard.test.ts` читает умолчание бэкенда
 * и краснеет, если числа разошлись, — иначе эта запись стала бы двенадцатой
 * копией, а не источником.
 */
export const ЦЕНА_ПРОВЕРКИ_ЦЕНТЫ = 2900;

/** Только сумма: «$29», а у дробной цены «$29.50». */
export function ценаТекстом(cents: number | null | undefined = ЦЕНА_ПРОВЕРКИ_ЦЕНТЫ): string {
  const центы = typeof cents === "number" && Number.isFinite(cents) && cents >= 0 ? cents : ЦЕНА_ПРОВЕРКИ_ЦЕНТЫ;
  const usd = центы / 100;
  return `$${Number.isInteger(usd) ? usd.toFixed(0) : usd.toFixed(2)}`;
}

/** Сумма вместе с периодом: «$29/month». Для англоязычных экранов бюро. */
export function ценаСПериодом(cents: number | null | undefined = ЦЕНА_ПРОВЕРКИ_ЦЕНТЫ): string {
  return `${ценаТекстом(cents)}/month`;
}
