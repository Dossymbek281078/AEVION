import type { Request } from "express";

/**
 * Личность посетителя DevHub, который не входил в аккаунт.
 *
 * До 21.08.2026 все разлогиненные читались как ОДИН пользователь "anonymous",
 * а владение проверялось строкой `project.userId !== userId`. Из этого следовало
 * три вещи, и все три наблюдались на проде: список проектов был общий для всех
 * посетителей; любой мог править чужие файлы; `DELETE /projects/:id` пускал
 * любого удалить чужой проект — вместе с его базой данных.
 *
 * Пользоваться без аккаунта предполагалось намеренно: лендинг обещает
 * «No GitHub or cloud accounts needed». Чинится не запретом, а тем, что у
 * каждого браузера появляется собственный идентификатор.
 *
 * ГРАНИЦА, которую важно назвать честно: это НЕ авторизация и не секрет.
 * Идентификатор присылает сам браузер, и подделавший чужой получит чужие
 * черновики. Он РАЗДЕЛЯЕТ посетителей между собой, а не защищает от
 * злоумышленника. Защита от злоумышленника — вход в аккаунт, и она уже есть:
 * при живом токене личность берётся из него и заголовок не смотрится вовсе.
 */
export const DEVHUB_GUEST_HEADER = "x-devhub-guest";

/** Формат, который выдаёт браузер: 8–64 знака, только буквы, цифры, `_` и `-`. */
const GUEST_ID = /^[A-Za-z0-9_-]{8,64}$/;

/**
 * Заголовок → личность гостя. Мусор и отсутствие заголовка дают прежнее
 * "anonymous": старые клиенты и смоук-тесты продолжают работать как работали.
 */
export function devhubGuestId(raw: unknown): string {
  const v = Array.isArray(raw) ? raw[0] : raw;
  if (typeof v !== "string") return "anonymous";
  const trimmed = v.trim();
  if (!GUEST_ID.test(trimmed)) return "anonymous";
  // Префикс обязателен. Без него присланное значение попадает в ТО ЖЕ
  // пространство имён, что и `sub` вошедшего пользователя, и заголовком можно
  // было бы выдать себя за него. Двоеточие в формате запрещено, поэтому гость
  // не может подделать и сам префикс.
  return `guest:${trimmed}`;
}

/**
 * Личность того, кто прислал запрос: вошедший пользователь, иначе — гость.
 * `sub` идёт первым аргументом, чтобы на месте вызова было видно, что токен
 * главнее заголовка.
 */
export function requesterId(req: Pick<Request, "headers">, sub?: string | null): string {
  if (typeof sub === "string" && sub.length > 0) return sub;
  return devhubGuestId(req?.headers?.[DEVHUB_GUEST_HEADER]);
}
