#!/usr/bin/env node
/*
 * Отчёт: что оплата открывает, а что мы отдаём даром.
 *
 * Читает единый источник (src/data/moduleAccess.ts) и печатает три списка.
 * Нужен не для красоты: до 01.10.2026 «что продаём» и «что закрываем» жили в
 * РАЗНЫХ местах — в коде и в переменной сервиса — и не сверялись ничем, поэтому
 * расхождение из 13 модулей никто не видел месяцами.
 *
 * С --прод дополнительно спрашивает живой сервис и называет расхождение данных
 * с переменной PAYWALL_MODULES. Значений переменных не печатает.
 *
 * Коды выхода: 0 — расхождений с продом нет, 1 — есть, 2 — спросить не удалось.
 * Код 2 не означает ни «хорошо», ни «плохо»: он означает «ответа нет».
 */
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), "..");
const ИСТОЧНИК = join(КОРЕНЬ, "src", "data", "moduleAccess.ts");

/*
 * Источник читается как ТЕКСТ, а не импортируется: это .ts в проекте на
 * CommonJS, и запуск отчёта не должен требовать сборки — иначе его перестанут
 * звать. Разбор намеренно тупой и обязан СЕБЯ ПРОВЕРИТЬ ниже: разбор, который
 * молча нашёл ноль строк, напечатал бы «расхождений нет» на пустом месте.
 */
function строкиИсточника() {
  const текст = readFileSync(ИСТОЧНИК, "utf8");
  const строки = [];
  const куски = текст.split(/\{\s*\n/).slice(1);
  for (const кусок of куски) {
    const id = /moduleId:\s*"([^"]+)"/.exec(кусок);
    const продаётся = /продаётся:\s*(true|false)/.exec(кусок);
    const стена = /стена:\s*(true|false)/.exec(кусок);
    if (!id || !продаётся || !стена) continue;
    строки.push({
      moduleId: id[1],
      продаётся: продаётся[1] === "true",
      стена: стена[1] === "true",
    });
  }
  return строки;
}

const строки = строкиИсточника();

// Самоконтроль разбора (правило 2е): ноль строк — это неисправность прибора,
// а не отсутствие модулей. Порог взят с запасом вниз от фактических 14.
if (строки.length < 10) {
  console.error(`разбор источника дал ${строки.length} строк — это не похоже на правду, отчёту верить нельзя`);
  process.exitCode = 2;
} else {
  const продаётсяБезСтены = строки.filter((м) => м.продаётся && !м.стена).map((м) => м.moduleId);
  const стенаБезПродажи = строки.filter((м) => !м.продаётся && м.стена).map((м) => м.moduleId);
  const оплатаОткрывает = строки.filter((м) => м.продаётся && м.стена).map((м) => м.moduleId);

  console.log(`проверено строк источника: ${строки.length}`);
  console.log("");
  console.log(`ОПЛАТА ОТКРЫВАЕТ (продаётся И закрыто) — ${оплатаОткрывает.length}:`);
  console.log(`  ${оплатаОткрывает.join(", ") || "НИ ОДНОГО"}`);
  console.log("");
  console.log(`ОТДАЁМ ДАРОМ (продаётся, но стены нет) — ${продаётсяБезСтены.length}:`);
  for (const id of продаётсяБезСтены) console.log(`  ${id}`);
  console.log("");
  console.log(`ОТКАЗ БЕЗ ПРЕДЛОЖЕНИЯ (закрыто, но не продаётся) — ${стенаБезПродажи.length}:`);
  for (const id of стенаБезПродажи) console.log(`  ${id}`);

  if (process.argv.includes("--прод")) {
    const АДРЕС = "https://api.aevion.app/health";
    let ответ = null;
    try {
      const r = await fetch(АДРЕС);
      if (r.ok) ответ = await r.json();
      else console.error(`${АДРЕС} ответил ${r.status}`);
    } catch (e) {
      console.error(`не удалось спросить ${АДРЕС}: ${e.message}`);
    }
    console.log("");
    if (!ответ) {
      console.error("КОД 2: прод не ответил, сверить данные с переменной нечем.");
      process.exitCode = 2;
    } else {
      // Ручка не называет закрытые модули (проверено 01.10: таких полей в
      // /health нет), поэтому честно говорим, чего мы НЕ знаем, вместо того
      // чтобы выдать совпадение данных с собой за сверку с продом.
      console.log(`прод отвечает: commit ${ответ.commit ?? "unknown"}, branch ${ответ.branch ?? "?"}`);
      console.log("ВНИМАНИЕ: /health не называет закрытые модули, поэтому сверка с переменной");
      console.log("PAYWALL_MODULES этим отчётом НЕ делается. Её проверяет сторож");
      console.log("tests/moduleAccessIsOneSource.guard.test.ts по записанному замеру,");
      console.log("а точное значение смотрят через `railway variables` из PowerShell.");
    }
  }
}
