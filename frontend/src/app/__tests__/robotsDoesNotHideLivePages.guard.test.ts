import { describe, expect, test } from "vitest";
import { DISALLOWED_PATHS } from "../robots";
import { isBlockedForCrawlers } from "../sitemap";

/**
 * Запрет для поисковиков не задевает страницы, чьи adresа лишь НАЧИНАЮТСЯ так же.
 *
 * 🔴 ЗАЧЕМ. Замер 09.09.2026, накануне запуска: `/qr` попал в список запретов
 * 30.08 как короткий adres канала — правильно, он только перенаправляет. Но
 * сравнение шло по префиксу строки, а `"/qright".startsWith("/qr")` истинно.
 * Из карты сайта и из robots.txt выпали ПЯТЬ живых страниц:
 *
 *     /qright, /qright/transparency, /qreal, /qrenew, /qrenew/report
 *
 * QRight выходит 10 сентября и продаётся. Страницы при этом отвечали 200 —
 * дефект не ронял ничего, он делал модуль невидимым для поиска, а посадочные
 * страницы запуска живут именно поиском.
 *
 * (Пример адреса посадочной здесь НЕ пишу шаблоном со звёздочкой: сочетание
 * звёздочки и косой черты закрывает этот самый комментарий досрочно, и файл
 * перестаёт разбираться. Проверено на себе минуту назад — vitest ответил
 * «no tests», то есть ни зелёным, ни красным.)
 *
 * 🔴 ПОЧЕМУ ЭТОГО НЕ ВИДЕЛИ ТРИ НЕДЕЛИ. Прежние сторожа проверяли, что
 * закрытое ЗАКРЫТО (админка, оплата, служебные) — и были правы. Никто не
 * проверял обратное: что открытое ОТКРЫТО. Проверка в одну сторону зеленеет
 * и на правиле «запретить всё».
 *
 * Поэтому здесь обе стороны, и вторая важнее первой.
 */

/** Живые страницы, которые обязаны быть видны поиску. Волна запуска и соседи. */
const OTKRYTY = [
  "/qright",
  "/qright/transparency",
  "/qreal",
  "/qrenew",
  "/qrenew/report",
  "/qsign",
  "/devhub",
  "/bureau",
  "/qskyway",
  "/startup-exchange",
  "/qventure",
  "/pricing",
];

/** Адреса, которые обязаны оставаться закрытыми. Контроль в другую сторону. */
const ZAKRYTY = [
  "/admin/awards",
  "/api/health",
  "/pay/ok",
  "/account/settings",
  "/qpaynet/admin/users",
  "/constitution/admin",
  "/qr",
  "/tt",
  "/x",
  "/fb",
];

describe("robots и карта сайта не прячут живые страницы", () => {
  test("прибор видит предмет: список запретов разобран", () => {
    // Без этого «ничего не закрыто» было бы неотличимо от пустого списка.
    expect(DISALLOWED_PATHS.length, "список запретов пуст").toBeGreaterThan(10);
  });

  for (const adres of OTKRYTY) {
    test(`${adres} видна поисковику`, () => {
      expect(
        isBlockedForCrawlers(adres),
        `${adres} закрыт для поисковиков. Скорее всего adres лишь НАЧИНАЕТСЯ так же, ` +
          "как короткий adres канала: сравнивать надо по границе сегмента " +
          '(`p === b || p.startsWith(b + "/")`), а не по префиксу строки.',
      ).toBe(false);
    });
  }

  test("служебные adresа по-прежнему закрыты (контроль в другую сторону)", () => {
    // Без него проверка выше позеленела бы и на правиле «не запрещать ничего»,
    // то есть открыла бы поисковикам админку и оплату.
    for (const adres of ZAKRYTY) {
      expect(isBlockedForCrawlers(adres), `${adres} перестал быть закрытым`).toBe(true);
    }
  });

  test("вложенное под закрытым каталогом тоже закрыто", () => {
    for (const adres of ["/admin/awards/edit", "/api/health/deep", "/account/settings/mail"]) {
      expect(isBlockedForCrawlers(adres), `${adres} должен быть закрыт вместе с каталогом`).toBe(true);
    }
  });
});
