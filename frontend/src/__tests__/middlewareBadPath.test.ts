import { describe, it, expect } from "vitest";
import { isDecodablePath } from "../middleware";

/**
 * Проверяется РАЗБОР пути, а не middleware целиком: поднимать Next ради этого
 * незачем, а функция и есть всё решение — остальное в файле это `NextResponse`.
 *
 * Входы взяты из ЗАМЕРА по проду 28.08.2026, а не выдуманы: каждый «плохой»
 * вход там давал 500, каждый «хороший» — 200 или честный 404.
 */
describe("путь с битой кодировкой распознаётся до маршрутизации", () => {
  // Эти три формы на проде 28.08 роняли рендер на ВСЕХ 74 семействах маршрутов.
  it.each([
    ["%FF%FE", "невалидный UTF-8"],
    ["%C0%AF", "переизбыточная кодировка"],
    ["%E4%F0%EE", "байты cp1251, не UTF-8"],
  ])("«/%s» (%s) — не разбирается", (bad) => {
    expect(isDecodablePath("/" + bad)).toBe(false);
  });

  it("битый сегмент в глубине пути тоже ловится", () => {
    expect(isDecodablePath("/pricing/%FF%FE")).toBe(false);
    expect(isDecodablePath("/qsign/verify/%FF%FE")).toBe(false);
  });

  // Обратная сторона: middleware не имеет права мешать обычным адресам.
  // Без этих проверок «починка» могла бы отдавать 400 всему сайту.
  it.each([
    "/",
    "/pricing",
    "/modules/qcoreai",
    "/build/skill/react",
    // Корректно закодированная кириллица — законный адрес, на проде даёт 404,
    // а не 500. Первое наблюдение выглядело как «кириллица ломает сайт», и это
    // было ложным следом: ломает именно битая кодировка.
    "/%D1%82%D0%B5%D1%81%D1%82",
    // Знак процента, экранированный по правилам.
    "/a%25b",
    "/search?q=%D1%82",
  ])("«%s» — разбирается, пропускаем", (good) => {
    expect(isDecodablePath(good)).toBe(true);
  });

  it("проверка смотрит на разбор, а не на список плохих строк", () => {
    // Мусор без percent-кодирования разбирается штатно и НЕ должен получать 400:
    // за него отвечает обычный 404, а не middleware.
    expect(isDecodablePath("/qqq-no-such-987")).toBe(true);
    expect(isDecodablePath("/../../etc/passwd")).toBe(true);
  });
});
