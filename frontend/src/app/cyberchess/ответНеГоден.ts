/**
 * Годен ли ответ тренера к показу человеку.
 *
 * 🔴 ЗАЧЕМ ЭТО ЖИВЁТ НА ФРОНТЕ, А НЕ ТОЛЬКО В БЭКЕНДЕ (30.09.2026).
 *
 * В бэкенде такая проверка есть — в `/api/coach/chat`: плохой ответ там
 * бракуется, делается один повтор, потом честный отказ. Но панель тренера
 * зовёт СНАЧАЛА `/api/coach/chat/stream`, и повторить там нечего: токены уже
 * ушли на экран. Из-за этого приёмка 29.09 получила на русский вопрос
 * «The Hindi phrase \» — 18 знаков, английских, с оборванным словом, и код
 * ответа был 200: стрим мимо защиты, а фронт засчитывал ЛЮБОЙ непустой
 * обрывок как выданный ответ.
 *
 * Поэтому судим накопленный текст здесь, когда стрим закончился, и при браке
 * не оставляем его на экране, а падаем на обычный `/chat` — тот самый, где
 * повтор и отказ уже работают. Проверка сознательно повторяет бэкендовую
 * дословно: два разных ответа на один вопрос хуже одного строгого.
 */

/**
 * Ответ не на том языке, на котором спросили.
 *
 * Условие про СЛОВО, а не про длину. Прежняя бэкендовая версия молчала на
 * ответах короче 20 знаков — и дырой оказался ровно настоящий случай (18
 * знаков). Ход «Nf3» при этом судить нельзя: латиница в нём законна, слова
 * там нет. «Три буквы подряд в любом письме» разделяет эти два случая и не
 * теряет греческий, ради которого защита и писалась.
 */
export function языкНеТот(вопрос: string, ответ: string): boolean {
  const кириллица = /[а-яёА-ЯЁ]/;
  const текст = String(ответ || "").trim();
  if (!кириллица.test(String(вопрос || ""))) return false;
  if (кириллица.test(текст)) return false;
  return /\p{L}{3}/u.test(текст);
}

/**
 * Ответ оборван на полуслове И при этом короткий.
 *
 * Обрыв сам по себе не повод прятать ответ: длинный разбор без финальной
 * точки человек дочитает. Короткий огрызок пользы не несёт и выглядит
 * поломкой — а у стрима это ещё и самый частый вид брака.
 */
export function ответОгрызок(ответ: string): boolean {
  const t = String(ответ || "").trim();
  if (t.length === 0) return true;
  if (t.length >= 200) return false;
  return !/[.!?…»)]$/.test(t);
}

/** Показывать ли накопленный стримом текст человеку. */
export function стримГоден(вопрос: string, накоплено: string): boolean {
  return !языкНеТот(вопрос, накоплено) && !ответОгрызок(накоплено);
}
