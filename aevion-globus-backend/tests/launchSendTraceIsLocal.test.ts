import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * След отправок ЛОКАЛЬНЫЙ — и скрипт обязан это говорить вслух.
 *
 * Защита от повторной рассылки держится на файле `data/launch-sent-<модуль>.jsonl`
 * рядом с репозиторием. Запуск с другой машины о нём не знает и разошлёт всё
 * заново — по всему списку, живым людям, без возможности отозвать.
 *
 * Границу, о которой не сказано вслух, оператор не увидит: файл лежит молча, а
 * отчёт выглядит одинаково и в первый запуск, и во второй с чужой машины.
 * Поэтому проверяется не поведение, а ЧЕСТНОСТЬ ОТЧЁТА.
 */

const SRC = readFileSync(join(process.cwd(), "scripts/launch-announce-send.ts"), "utf8");

describe("оператор видит, на чём держится защита", () => {
  test("шапка называет границу прямо", () => {
    expect(SRC, "про локальность следа не сказано").toContain("ЛОКАЛЬНЫЙ");
    expect(SRC).toContain("с другой машины");
  });

  test("путь к следу печатается в отчёте", () => {
    // Иначе оператор не знает, что сохранять и что переносить.
    expect(SRC).toContain("След отправок:");
  });

  test("отсутствие следа не выдаётся за «не отправляли»", () => {
    // Пустой след значит одно из двух, и различить их нельзя. Молчаливое
    // «значит, не отправляли» — самая дорогая ошибка в этом скрипте.
    expect(SRC).toContain("либо отправляли с другой машины");
  });
});
