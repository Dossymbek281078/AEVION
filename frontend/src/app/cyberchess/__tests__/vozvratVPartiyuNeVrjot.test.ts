// Плашка «▶ Вернуться к партии» не обещает партии, которой нет.
//
// Повод (замер 12.10.2026, путь человека из комментария к ролику, 390×844,
// youtube/komm-mat3-075iw — 56 живых визитов и ОДИН ход за сутки): открывший
// задачу по ссылке получал эту зелёную строку самым ярким предметом экрана.
// Возвращаться было не к чему — загрузка задачи сама включает партию. Нажатие
// переносило ту же позицию (17 фигур до и после) во вкладку «Играть» с идущими
// часами и «Сдаться», без подсказки, решения и следующей задачи.
//
// Сторож проверяет ПОВЕДЕНИЕ функции, а не текст файла: такой сторож краснеет,
// когда правка неверна, и не краснеет на переписанной разметке.
import { describe, it, expect } from "vitest";
import { pokazatVozvratVPartiyu } from "../page";

const основа = {
  идётПартия: true,
  конецПартии: false,
  вкладка: "puzzles" as const,
  партияСЧеловеком: false,
  задачаНаДоске: false,
};

describe("«Вернуться к партии» показывается только когда есть куда возвращаться", () => {
  it("задача по ссылке во вкладке задач — плашки НЕТ (тот самый случай)", () => {
    expect(pokazatVozvratVPartiyu({ ...основа, задачаНаДоске: true })).toBe(false);
  });

  // ─── отрицательные контроли: сама возможность показать плашку НЕ сломана ───
  it("партия идёт, человек ушёл во вкладку задач и задачи не открывал — плашка ЕСТЬ", () => {
    expect(pokazatVozvratVPartiyu({ ...основа, задачаНаДоске: false })).toBe(true);
  });

  it("партия идёт, человек в анализе — плашка ЕСТЬ даже со старой задачей в памяти", () => {
    // На вкладке анализа доска показывает партию, а не задачу: сужение сюда не лезет.
    expect(pokazatVozvratVPartiyu({ ...основа, вкладка: "analysis", задачаНаДоске: true })).toBe(true);
  });

  it("партия идёт, человек у коуча — плашка ЕСТЬ", () => {
    expect(pokazatVozvratVPartiyu({ ...основа, вкладка: "coach" })).toBe(true);
  });

  // ─── прежние условия не потерялись ───
  it("партии нет — плашки нет", () => {
    expect(pokazatVozvratVPartiyu({ ...основа, идётПартия: false })).toBe(false);
  });

  it("партия кончилась — плашки нет", () => {
    expect(pokazatVozvratVPartiyu({ ...основа, конецПартии: true })).toBe(false);
  });

  it("человек уже на вкладке «Играть» — плашки нет", () => {
    expect(pokazatVozvratVPartiyu({ ...основа, вкладка: "play" })).toBe(false);
  });

  it("партия с человеком — плашки нет (там часы не паузятся)", () => {
    expect(pokazatVozvratVPartiyu({ ...основа, партияСЧеловеком: true })).toBe(false);
  });

  it("знаменатель: из 8 сочетаний «задача во вкладке задач» единственное новое", () => {
    const вкладки = ["play", "puzzles", "analysis", "coach"] as const;
    const было = (в: typeof вкладки[number], з: boolean) =>
      основа.идётПартия && !основа.конецПартии && в !== "play" && !основа.партияСЧеловеком;
    const стало = (в: typeof вкладки[number], з: boolean) =>
      pokazatVozvratVPartiyu({ ...основа, вкладка: в, задачаНаДоске: з });
    const разошлись: string[] = [];
    for (const в of вкладки) for (const з of [false, true]) if (было(в, з) !== стало(в, з)) разошлись.push(в + "/задача=" + з);
    expect(разошлись).toEqual(["puzzles/задача=true"]);
  });
});
