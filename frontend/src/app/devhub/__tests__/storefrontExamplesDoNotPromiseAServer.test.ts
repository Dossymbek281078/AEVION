// Примеры-кнопки на витрине DevHub — это ОБЕЩАНИЕ: человек жмёт и ждёт именно того,
// что написано. Публикуем мы статику, поэтому пример не должен обещать действий,
// которые без сервера не происходят.
//
// 28.09.2026: первым примером стояла «кофейня с меню и ФОРМОЙ БРОНИ». Заявка из такой
// формы складывается в браузер посетителя — владелец кофейни её не увидит никогда.
// Пример заменён; заодно закреплено, что пример про данные («трекер задач с базой»)
// попадает под честную подпись «соберём браузерную версию, данные в браузере».
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { DEVHUB_DICT } from "../i18n";
import { даннымНуженСервер } from "../../../lib/devhubStackChoice";

const ЯЗЫКИ = ["ru", "en", "kk"];
const ПРИМЕРЫ = ["hero.ex1", "hero.ex2", "hero.ex3"];

// Слова про отправку кому-то: на статике этого не происходит вовсе.
const ОБЕЩАЕТ_ОТПРАВКУ = /форм[аыу] (брони|заявки|заказа)|брони|booking form|order form|отправ|письм|e-?mail|оплат|payment|checkout|брондау формасы/i;

describe("примеры на витрине не обещают того, чего статика не делает", () => {
  it("прибор: словарь прочитан и примеры на месте", () => {
    for (const язык of ЯЗЫКИ) {
      for (const ключ of ПРИМЕРЫ) {
        expect(String(DEVHUB_DICT[язык]?.[ключ] ?? ""), `${язык}/${ключ}`).not.toBe("");
      }
    }
  });

  it("ни один пример не обещает отправку заявки, письма или оплату", () => {
    const плохие: string[] = [];
    for (const язык of ЯЗЫКИ) {
      for (const ключ of ПРИМЕРЫ) {
        const текст = String(DEVHUB_DICT[язык]?.[ключ] ?? "");
        if (ОБЕЩАЕТ_ОТПРАВКУ.test(текст)) плохие.push(`${язык}/${ключ}: «${текст}»`);
      }
    }
    expect(плохие, "пример обещает серверное действие — на статике оно не случится").toEqual([]);
  });

  it("КОНТРОЛЬ: прибор ловит именно такой пример", () => {
    expect(ОБЕЩАЕТ_ОТПРАВКУ.test("лендинг кофейни с меню и формой брони")).toBe(true);
    expect(ОБЕЩАЕТ_ОТПРАВКУ.test("coffee shop landing page with a menu and a booking form")).toBe(true);
    expect(ОБЕЩАЕТ_ОТПРАВКУ.test("лендинг кофейни с меню, часами работы и картой проезда")).toBe(false);
  });

  it("ни один пример-кнопка не требует сервера — подпись на них не должна выскакивать", () => {
    // 28.09.2026: раньше вторым примером стоял «трекер задач с базой данных». На проде
    // он работал (адрес 200 за 48 с), но обещал БД, а получал человек localStorage —
    // обещание сильнее продукта. Заменён на страницу мероприятия. Теперь все три примера
    // страничные, и честная подпись про браузерную версию на них не показывается.
    for (const ключ of ПРИМЕРЫ) {
      expect(даннымНуженСервер(String(DEVHUB_DICT.ru?.[ключ] ?? "")), ключ).toBe(false);
    }
  });

  it("но сама подпись жива: идея человека с базой или оплатой её вызывает", () => {
    // Контроль: если признак перестанет срабатывать, предыдущий случай станет зелёным
    // по ложной причине — «подписи нет, потому что она сломана».
    expect(даннымНуженСервер("трекер задач с базой данных и статусами")).toBe(true);
    expect(даннымНуженСервер("магазин с корзиной и оплатой")).toBe(true);
  });

  it("галерея примеров и шаблоны тоже ничего не обещают сверх статики", () => {
    const галерея = readFileSync(join(__dirname, "..", "examples.ts"), "utf8");
    const страницаПроекта = readFileSync(join(__dirname, "..", "[id]", "page.tsx"), "utf8");
    const плохие: string[] = [];
    for (const [имя, текст] of [["examples.ts", галерея], ["[id]/page.tsx", страницаПроекта]] as const) {
      for (const строка of текст.split(/\r?\n/)) {
        if (!/prompt:/.test(строка)) continue;
        if (ОБЕЩАЕТ_ОТПРАВКУ.test(строка)) плохие.push(`${имя}: ${строка.trim().slice(0, 90)}`);
      }
    }
    expect(плохие, "пример или шаблон обещает серверное действие").toEqual([]);
  });
});
