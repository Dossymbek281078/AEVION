import { describe, it, expect } from "vitest";
import { readdirSync, readFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Обещание процента от чужих покупок требует МЕХАНИЗМА привязки.
 *
 * 🔴 НАЙДЕНО 03.09.2026 соседним окном, проверено мной с другой стороны.
 * На `/pricing/affiliate` живёт обещание «AFFILIATE PROGRAM · 20% RECURRING»
 * и «lifetime». Механизма, которым мы узнали бы, что покупателя привёл
 * партнёр, нет:
 *
 *   персональная метка партнёру   нет — механизм каналов знает только
 *                                 соцсети (ig/tt/yt/tg/fb/x/qr/vk)
 *   поле привязки в покупке       нет
 *   начисление комиссии           нет
 *   внешняя партнёрская платформа не подключена
 *
 * ЧТО ЕСТЬ: приём заявок (`data/affiliate.jsonl` в pricing.ts). То есть мы не
 * обещаем в пустоту — мы СОБИРАЕМ заявки людей, рассчитывающих на 20%, и
 * заплатить им по обещанию нечем. Это тревожнее, чем «просто обещание».
 *
 * ⚠️ ГДЕ ИСКАТЬ ТЕКСТ. Обещание лежит в СЛОВАРЕ ЦЕН (`pricingI18n.ts` и его
 * секции), а НЕ в общем `i18n-lang/*.ts` — там ключей `affiliate.*` с
 * комиссией нет вовсе. Первый мой замер дал 1 вхождение вместо 17 именно
 * поэтому. Тот, кто будет снимать обещание, должен знать: искать в словаре
 * цен, иначе уберёт половину и не заметит.
 *
 * ЧТО РЕШАЕТ ОСНОВАТЕЛЬ, а не этот файл: сделать привязку (метка партнёру
 * плюс поле в записи покупки — механизм каналов уже готов) или снять
 * обещание, пока по нему не пришли. Цена и позиционирование не наше решение,
 * поэтому здесь ничего не «чинится».
 *
 * Сторож не даёт появиться ВТОРОМУ такому обещанию незамеченно.
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const LIB = join(HERE, "..", "..", "lib");

/**
 * Известные обещания без механизма. Убирать записи ТОЛЬКО вместе с решением:
 * появилась привязка либо обещание снято со страницы. Дописывать сюда новые —
 * значит сознательно обещать процент, которого не сможем заплатить.
 */
const ИЗВЕСТНЫЕ = new Map<string, string>([
  ["affiliate.badge", "ждёт решения основателя от 03.09.2026: привязки партнёра нет"],
  ["affiliate.subtitle", "то же обещание другими словами — «20% of every subscription»"],
]);

/** Весь словарь цен: сам файл и его секции — это ТРИ источника, не один. */
function словарьЦен(): Array<[string, string]> {
  const out: Array<[string, string]> = [];
  const main = join(LIB, "pricingI18n.ts");
  if (existsSync(main)) out.push(["pricingI18n.ts", readFileSync(main, "utf8")]);
  const sec = join(LIB, "pricingI18n", "sections");
  if (existsSync(sec)) {
    for (const f of readdirSync(sec)) {
      if (f.endsWith(".ts")) out.push([f, readFileSync(join(sec, f), "utf8")]);
    }
  }
  return out;
}

/** Ключи, обещающие долю от чужих покупок. */
function обещанияКомиссии(): string[] {
  const найдено: string[] = [];
  for (const [, текст] of словарьЦен()) {
    for (const строка of текст.split("\n")) {
      const m = /"([a-zA-Z][A-Za-z0-9.]*)"\s*:\s*"([^"]*)"/.exec(строка);
      if (!m) continue;
      const [, ключ, значение] = m;
      const обещает =
        /%/.test(значение) &&
        /(RECURRING|recurring|lifetime|пожизнен|комисси|commission)/.test(значение);
      if (обещает) найдено.push(ключ);
    }
  }
  return [...new Set(найдено)];
}

/** Есть ли в коде механизм привязки покупки к партнёру. */
function естьПривязка(): boolean {
  const каналы = join(LIB, "channels.ts");
  const текст = existsSync(каналы) ? readFileSync(каналы, "utf8") : "";
  // Метка партнёра — это НЕ канал соцсети. Признак механизма: отдельное
  // понятие партнёра в привязке покупки, а не строка в списке каналов.
  return /partnerId|affiliateId|referrerId/.test(текст);
}

describe("обещание комиссии обеспечено механизмом", () => {
  it("контроль: словарь цен прочитан и непуст", () => {
    const части = словарьЦен();
    expect(части.length, "источников словаря цен не найдено").toBeGreaterThanOrEqual(1);
    expect(
      части.reduce((n, [, t]) => n + t.length, 0),
      "словарь цен прочитан пустым",
    ).toBeGreaterThan(10000);
  });

  it("контроль: способ вообще находит обещания процента", () => {
    // Иначе «новых обещаний нет» могло бы значить «мой способ не ищет».
    expect(
      обещанияКомиссии(),
      "разбор не нашёл ни одного обещания процента — а известное точно есть",
    ).toContain("affiliate.badge");
  });

  it("новых обещаний процента без механизма не появилось", () => {
    if (естьПривязка()) return; // механизм появился — сторож больше не нужен
    const новые = обещанияКомиссии().filter((k) => !ИЗВЕСТНЫЕ.has(k));
    expect(
      новые,
      "на витрине обещан процент от чужих покупок, а узнать, что покупателя " +
        "привёл партнёр, нечем: заплатить по такому обещанию мы не сможем",
    ).toEqual([]);
  });
});
