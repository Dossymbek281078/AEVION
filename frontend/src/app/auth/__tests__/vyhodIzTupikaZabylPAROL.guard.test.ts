/**
 * 🔴 ВЫХОД ИЗ ТУПИКА «ЗАБЫЛ ПАРОЛЬ» ЕСТЬ НА СТРАНИЦЕ ВХОДА.
 *
 * Замер 12.10.2026: страница сброса `/build/reset-password` и обе ручки
 * (`/api/auth/password/reset/request` и `/complete`) существуют и на проде
 * отвечают — но со страницы входа на них не было НИ ОДНОЙ ссылки. То есть
 * человек, забывший пароль, упирался в «неверный пароль» и уходил, а механизм
 * восстановления всё это время работал вхолостую. Теряется уже пришедший, в
 * том числе тот, кому мы продали доступ.
 *
 * Сторож держит ТРИ свойства, потому что провалиться можно в каждом:
 * ссылка есть; её цель существует; текст есть на всех трёх языках.
 */
import { describe, it, expect } from "vitest";
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

const ВХОД = readFileSync(join(process.cwd(), "src/app/auth/page.tsx"), "utf8");
const ЦЕЛЬ = "/build/reset-password";

describe("забыл пароль — выход есть", () => {
  it("🔴 на странице входа есть ссылка на сброс пароля", () => {
    expect(ВХОД, "контроль прибора: файл входа прочитан не целиком").toContain("signIn");
    expect(ВХОД, `нет ссылки на ${ЦЕЛЬ} — человек в тупике`).toContain(`href="${ЦЕЛЬ}"`);
  });

  it("🔴 цель ссылки существует — обещание исполняется страницей, а не 404", () => {
    // Ссылка на несуществующий адрес хуже отсутствующей: она обещает выход.
    const файл = join(process.cwd(), "src/app" + ЦЕЛЬ + "/page.tsx");
    expect(existsSync(файл), `цель ссылки не существует: ${файл}`).toBe(true);
    const страница = readFileSync(файл, "utf8");
    // И она должна звать НАСТОЯЩИЕ ручки, а не быть заготовкой.
    expect(страница, "страница сброса не запрашивает письмо").toContain("requestPasswordReset");
    expect(страница, "страница сброса не завершает смену пароля").toContain("completePasswordReset");
  });

  it("🔴 текст есть на трёх языках — знаменатель 3 из 3", () => {
    // Живой доводчик перевода на сайте есть, но ЕДИНСТВЕННЫЙ выход из тупика
    // на него не кладём: он молча обрезает длинные слова и переводит не всё.
    const языки = ["ru", "en", "kk"] as const;
    const начало = ВХОД.indexOf("const AUTH_A11Y");
    const словарь = ВХОД.slice(начало, начало + 1200);
    /*
     * Нарочно БЕЗ регулярных выражений. Эта проверка переписывалась дважды:
     * слэш съедался на границе вызова, "\s" в шаблоне становилось "s", и
     * проверка перестала находить что-либо — покраснев на верном коде.
     * Строковые операции калечить нечему.
     */
    const тексты: string[] = [];
    const КЛЮЧ = 'forgot: "';
    for (const я of языки) {
      const i = словарь.indexOf(я + ": {");
      expect(i, "языка нет в словаре: " + я).toBeGreaterThan(-1);
      const строка = словарь.slice(i, словарь.indexOf("}", i) + 1);
      const ключ = строка.indexOf(КЛЮЧ);
      expect(ключ, "у языка нет текста ссылки: " + я).toBeGreaterThan(-1);
      const от = ключ + КЛЮЧ.length;
      const текст = строка.slice(от, строка.indexOf('"', от));
      expect(текст.length, "текст ссылки слишком короткий у " + я + ": " + текст).toBeGreaterThan(5);
      тексты.push(текст);
    }
    expect(языки.length, "знаменатель: языков проверено").toBe(3);
    // Контроль: тексты РАЗНЫЕ, а не один скопирован трижды — иначе «три языка»
    // было бы зелёным при русском тексте в английской строке.
    expect(new Set(тексты).size, "тексты ссылки совпадают: " + тексты.join(" | ")).toBe(3);
  });

  it("ссылка видна именно на входе, а не при регистрации", () => {
    // При регистрации пароля ещё нет, и ссылка была бы шумом на главном шаге.
    const кусок = ВХОД.slice(Math.max(0, ВХОД.indexOf(`href="${ЦЕЛЬ}"`) - 400), ВХОД.indexOf(`href="${ЦЕЛЬ}"`));
    expect(кусок, "ссылка показана в обоих режимах").toMatch(/mode === "login" \? \(/);
  });
});
