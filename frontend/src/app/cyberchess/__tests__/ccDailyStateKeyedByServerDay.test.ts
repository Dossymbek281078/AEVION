// «Решено сегодня» у задачи дня на главной странице ключуется ДНЁМ СЕРВЕРА (UTC из
// /puzzle), а не местной датой. Разбор 17.09.2026: задача дня сменяется в 00:00 UTC =
// 05:00 Алматы; по местному ключу с 00:00 до 05:00 «сегодня» уже 18-е, а сервер отдаёт
// задачу 17-го. Решив её, человек помечал 18-е решённым, и настоящую задачу 18-го в
// 06:00 награда и отправка в таблицу не принимали — серия на сервере рвалась молча.
// Вторая половина: пока ответ сервера не пришёл, состояние НЕ пишется — иначе местный
// ключ перетирал сохранённое «решено» серверного дня (награда дважды).
// Сторож ИСХОДНИКА (форма). Смена дня на проде — контроль curl 18.09.
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const src = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");
const i = src.indexOf("const tk=srvDaily?.day||todayKey();const saved=ldDaily();");
const block = src.slice(Math.max(0, i - 900), i + 400);

describe("состояние задачи дня ключуется днём сервера", () => {
  it("ключ дня = srvDaily.day, местная дата — только запасной вариант", () => {
    expect(i).toBeGreaterThan(0);
    expect(block).not.toContain("const tk=todayKey();const saved=ldDaily();");
  });
  it("до ответа сервера (ни srvDaily, ни отказа) состояние не пишется", () => {
    expect(block).toContain("if(!srvDaily&&!srvDailyFailed)return;");
  });
  it("эффект пересчитывается при приходе дня сервера и при отказе", () => {
    expect(block).toMatch(/\},\[PUZZLES\.length,srvDaily\?\.day,srvDailyFailed\]\);/);
  });
  it("якорь: награда и отправка по-прежнему требуют !dailyState.solved и совпадение fen с серверной задачей", () => {
    // 🔴 ПЕРЕНАЦЕЛЕНО 30.09.2026, с замером. Якорь требовал условия
    //    `srvDaily?.fen===pzCurrent.fen`, а оно ЛОЖНО для каждой сырой
    //    lichess-задачи: нормализация сдвигает позицию на ход соперника,
    //    и FEN перестаёт совпадать с серверным. Замер на живой задаче:
    //      до     r1bqkb1r/pppp1ppp/2n2n2/4p3/2B1P3/5N2/PPPP1PPP/RNBQK2R w …
    //      после  r1bqkb1r/pppp1ppp/2n2n2/4N3/2B1P3/8/PPPP1PPP/RNBQK2R b …
    //    То есть награда и отправка не срабатывали НИ У КОГО — ровно тот
    //    дефект, из-за которого серия не считалась. Сравнение FEN заменено
    //    явным признаком «сейчас открыта задача дня», который ставит
    //    loadDailyPuzzle и снимает любой другой выбор задачи (ldPz).
    expect(src).toContain("if(dailyState&&!dailyState.solved&&этоЗадачаДня){");
    // 🔴 ПЕРЕНАЦЕЛЕНО 07.10.2026. Стояла дословная строка `sЭтоЗадачаДня(true);`.
    //    Открытие серверной задачи вынесено в общую функцию (две копии десяти
    //    присваиваний расходились: одна показывала позицию ДО хода соперника),
    //    и признак теперь приходит ПАРАМЕТРОМ. Дословной строки не осталось —
    //    проверка покраснела на верной правке. Стережём то же СВОЙСТВО, в трёх
    //    звеньях, иначе проверка снова оказалась бы про текст, а не про смысл:
    //      загрузчик дня просит поставить признак;
    //      общая функция ставит его из параметра, а не наугад;
    //      обычный выбор задачи его снимает.
    expect(src, "загрузчик дня больше не просит признак «это задача дня»")
      .toContain("postavitZadachuNaDosku(pz,{dnevnaya:true})");
    expect(src, "общая функция ставит признак не из параметра — он разойдётся с тем, что открыли")
      .toContain("sЭтоЗадачаДня(dnevnaya);");
    expect(src).toContain("sЭтоЗадачаДня(false)");   // снимается обычным выбором
    // прежнее ложное сравнение не должно вернуться
    expect(src).not.toContain("srvDaily?.fen===pzCurrent.fen");
  });
});
