#!/usr/bin/env node
/**
 * QSkyway — measure the MLIT/JCAB permission regime over a city twin.
 *
 * Japan publishes no ceiling grid comparable to the FAA's UASFM (see the notes
 * in src/routes/qskyway.airspace.ts for exactly what was checked). What it does
 * publish is the Densely Inhabited District layer: under the Civil Aeronautics
 * Act, flying an unmanned aircraft over a DID requires the Minister's
 * permission. That is a different kind of rule from a ceiling — a gate on the
 * flight, not a limit on its altitude — so it is modelled separately rather
 * than bent into the ceiling grid.
 *
 * The layer is published as raster tiles, so this samples the authority's own
 * rendering at the twin's grid-cell centres. Two properties make that a faithful
 * read rather than colour-guessing:
 *   · tiles exist ONLY where a DID exists — outside one the request 404s, which
 *     is an unambiguous "not a DID" rather than a shade to interpret;
 *   · inside, the fill is opaque-flagged (alpha > 0), so the test is presence,
 *     not a colour match.
 * It is still a derived reading of a published raster, not an ingested vector —
 * and the generated file says so, because the difference is the whole point of
 * the provenance vocabulary this platform uses.
 *
 * Usage:
 *   node scripts/sample-did-permission.mjs tokyo > src/routes/qskyway.permission.tokyo.ts
 */

import { PNG } from "pngjs";

const Z = 16;
const TILE = (z, x, y) => `https://cyberjapandata.gsi.go.jp/xyz/did2020/${z}/${x}/${y}.png`;

// Must match the committed city twin exactly (qskyway.city.<id>.ts).
const CITIES = {
  tokyo: {
    name: "Токио — Ниси-Синдзюку",
    bbox: { minLat: 35.683592, maxLat: 35.6978747, minLon: 139.6879457, maxLon: 139.7037075 },
    grid: { cols: 72, rows: 79, cell: 20 },
  },
};

const cityId = process.argv[2];
const city = CITIES[cityId];
if (!city) {
  console.error(`unknown city "${cityId}" — known: ${Object.keys(CITIES).join(", ")}`);
  process.exit(1);
}

const lonLatToPx = (lon, lat, z) => {
  const n = 2 ** z;
  const latR = (lat * Math.PI) / 180;
  return [
    ((lon + 180) / 360) * n,
    ((1 - Math.log(Math.tan(latR) + 1 / Math.cos(latR)) / Math.PI) / 2) * n,
  ];
};

const cellCentre = (c, r) => {
  const { minLat, maxLat, minLon } = city.bbox;
  const lat0 = (minLat + maxLat) / 2;
  const mPerLat = 110540;
  const mPerLon = 111320 * Math.cos((lat0 * Math.PI) / 180);
  const x = (c + 0.5) * city.grid.cell;
  const y = (r + 0.5) * city.grid.cell;
  return [minLon + x / mPerLon, maxLat - y / mPerLat];
};

const tiles = new Map();
async function tileAt(tx, ty) {
  const key = `${tx}/${ty}`;
  if (tiles.has(key)) return tiles.get(key);
  let img = null;
  try {
    const res = await fetch(TILE(Z, tx, ty), { signal: AbortSignal.timeout(30_000) });
    // A 404 is data, not an error: the layer only covers DIDs, so a missing
    // tile means "this area is not a densely inhabited district".
    if (res.ok) img = PNG.sync.read(Buffer.from(await res.arrayBuffer()));
    else if (res.status !== 404) throw new Error(`tile HTTP ${res.status}`);
  } catch (err) {
    tiles.set(key, null);
    throw err;
  }
  tiles.set(key, img);
  return img;
}

let inside = 0;
let total = 0;
for (let r = 0; r < city.grid.rows; r++) {
  for (let c = 0; c < city.grid.cols; c++) {
    const [lon, lat] = cellCentre(c, r);
    const [px, py] = lonLatToPx(lon, lat, Z);
    const tx = Math.floor(px);
    const ty = Math.floor(py);
    const img = await tileAt(tx, ty);
    total++;
    if (!img) continue;
    const ix = Math.min(img.width - 1, Math.floor((px - tx) * img.width));
    const iy = Math.min(img.height - 1, Math.floor((py - ty) * img.height));
    const alpha = img.data[(iy * img.width + ix) * 4 + 3];
    if (alpha > 0) inside++;
  }
}

const coveragePct = +((100 * inside) / Math.max(1, total)).toFixed(1);
const record = {
  authority: "MLIT / JCAB",
  source: "Densely Inhabited District (人口集中地区), 2020 census — GSI layer did2020",
  sourceUrl: "https://cyberjapandata.gsi.go.jp/xyz/did2020/{z}/{x}/{y}.png",
  regime: "Civil Aeronautics Act — unmanned flight over a DID requires the Minister's permission",
  kind: "permission",
  basis: "raster-sampled",
  effective: "2020 census",
  sampled: new Date().toISOString().slice(0, 10),
  sampledCells: total,
  cellsRequiringPermission: inside,
  coveragePct,
};

process.stdout.write(`// QSkyway — MLIT/JCAB permission regime over the ${cityId.toUpperCase()} twin.
// Generated by scripts/sample-did-permission.mjs ${record.sampled}. Do not edit by hand.
//
// Real regulator-published data, but a DIFFERENT KIND of rule from the FAA
// ceiling grid: a gate on whether the flight may happen at all, not a limit on
// its altitude. Kept in its own type for exactly that reason.
//
// Provenance is "raster-sampled", not "ingested": Japan publishes this layer as
// map tiles, so the value below is a faithful reading of the authority's own
// rendering at our grid-cell centres — not a vector dataset we were handed.
/* eslint-disable */
import type { CityPermission } from "./qskyway.permission";

export const PERMISSION_${cityId.toUpperCase()}: CityPermission = ${JSON.stringify(record, null, 2)};
`);

console.error(
  `[did] ${cityId}: ${inside}/${total} cells inside a DID (${coveragePct}%), ${tiles.size} tiles fetched`,
);
