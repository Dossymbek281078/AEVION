import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Кабинет показывает НАЗВАНИЕ тарифа, а не его идентификатор.
 *
 * Замер 31.08.2026: печаталось `{sub.tierId}` с `capitalize`. Человек,
 * заплативший $149 за «Universe», видел у себя «Pro» — подмена выглядела
 * правдоподобно, а не заметно, и потому не искалась.
 *
 * Годами это было верно ПО СОВПАДЕНИЮ: у четырёх тарифов из шести
 * идентификатор и название совпадают (free→Free, lite→Lite, medium→Medium,
 * full→Full). Расходится ровно `pro`.
 *
 * ⚠️ Расхождений в каталоге на самом деле ШЕСТЬ, а не одно: кроме `pro` это
 * `qmelanin`, `qrenew` и три набора (`ip-suite`, `ai-suite`, `fintech-suite`).
 * Сосед, приславший находку, назвал одно — он смотрел список тарифов, а не
 * весь каталог. Это тот же класс, что и сам дефект: неполный список выглядит
 * как полный, пока не спросишь, откуда он взят.
 *
 * Сторож проверяет ФАЙЛ, а не отрисовку: страница кабинета требует входа и
 * живого сервера, а проверка должна работать в обычном прогоне. Граница
 * честная — он поймает возврат к сырому выводу и НЕ поймает случай, когда имя
 * берётся из неверного источника.
 */

const PAGE = join(__dirname, "..", "page.tsx");

describe("кабинет не печатает сырой идентификатор тарифа", () => {
  const src = readFileSync(PAGE, "utf8");

  it("контроль: файл прочитан и в нём есть блок тарифа", () => {
    expect(src.length, "страница кабинета не прочитана").toBeGreaterThan(2000);
    expect(src, "блок тарифа исчез — сторож смотрит не туда").toContain("sub.tierId");
  });

  it("имя берётся из каталога, а не печатается идентификатором", () => {
    // Ищем ПОКАЗ: идентификатор в фигурных скобках как всё содержимое узла.
    // Сравнения вида `sub.tierId === "lite"` — это логика, а не вывод.
    const показСырого = src.includes("{sub.tierId}");
    expect(
      показСырого,
      "кабинет печатает идентификатор тарифа: покупатель Universe увидит «Pro»",
    ).toBe(false);
  });

  it("источник названий — сервер, а не вторая карта на клиенте", () => {
    expect(
      src.includes("/api/pricing/tiers"),
      "названия тарифов должны приходить из каталога: локальная копия разойдётся с ним молча",
    ).toBe(true);
  });

  it("при отказе показываем идентификатор, а не пустоту", () => {
    // Пустое место там, где человек ждёт название своего тарифа, читается как
    // «тарифа нет». Запасной путь обязан быть, и он обязан быть видимым.
    expect(src).toContain("?? sub.tierId");
  });
});
