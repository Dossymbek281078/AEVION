/**
 * Подсказка к задаче дня — ход РЕШАЮЩЕГО, а не соперника.
 *
 * 🔴 ПОВОД 30.09.2026, в день запуска шахмат. Ручка
 * GET /api/cyberchess-daily/puzzle отдавала `solHint: sol[0]`. У задач в
 * сыром формате lichess `sol[0]` — это ход СОПЕРНИКА, который делается из
 * позиции `fen`, а игрок ходит следующим. Живой замер сегодняшней задачи:
 *   fen  6k1/1ppq1ppp/3p4/1P1P4/2PN4/2Q5/r4KPP/B7 w - - 7 25
 *   sol  f2g1, d7g4, a1b2, g4d1
 * Подсказка приходила «f2g1» — ход белых, которого человек не делает;
 * играет он «d7g4». То есть подсказка вела не туда.
 *
 * Почему это чинится, хотя наша страница цела: она `solHint` не читает
 * (проверено 29.09), но ручка ПУБЛИЧНАЯ. Любой, кто её возьмёт — виджет,
 * ролик, партнёр, — получит неверную подсказку и будет прав, что винит нас.
 *
 * Правило распознавания взято у фронта дословно
 * (frontend/src/app/cyberchess/puzzleNormalize.ts, isRawLichess): решение
 * ЧЁТНОЙ длины — сырое, там первый ход чужой. Второй реализацией это стало
 * не по желанию: бэкенд не может импортировать код фронта. Поэтому здесь
 * ровно то же условие, и тест ниже держит его на живой задаче — если
 * правило разойдётся, разойдутся и ответы двух сторон.
 */

/** Сырой формат lichess: первый ход делает соперник. */
export function этоСыраяLichess(sol: unknown): boolean {
  return Array.isArray(sol) && sol.length > 0 && sol.length % 2 === 0;
}

/**
 * Первый ход того, кто РЕШАЕТ. undefined, если решения нет — молчание здесь
 * честнее выдуманного хода: подсказки просто не будет.
 */
export function подсказкаРешающего(sol: unknown): string | undefined {
  if (!Array.isArray(sol) || sol.length === 0) return undefined;
  const ход = этоСыраяLichess(sol) ? sol[1] : sol[0];
  return typeof ход === "string" && ход.length > 0 ? ход : undefined;
}
