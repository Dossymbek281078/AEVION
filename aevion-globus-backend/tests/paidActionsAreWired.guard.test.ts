function всеФайлы(каталог: string): string[] {
  const out: string[] = [];
  for (const имя of readdirSync(каталог)) {
    const п = join(каталог, имя);
    if (statSync(п).isDirectory()) out.push(...всеФайлы(п));
    else if (имя.endsWith(".ts")) out.push(п);
  }
  return out;
}

const исходники = всеФайлы(join(__dirname, "..", "src"));
const весьКод = исходники.map((ф) => readFileSync(ф, "utf8")).join("\n");

describe("платные действия подключены или названы отложенными", () => {
  it("контроль: исходники вообще прочитались", () => {
    expect(исходники.length).toBeGreaterThan(50);
    expect(весьКод).toContain("учестьДействие");
  });

  for (const [ключ, что] of Object.entries(ПЛАТНЫЕ)) {
    it(`${ключ} — ${что}`, () => {
      const подключено = весьКод.includes(`учестьДействие(req, "${ключ}")`);
      if (подключено) {
        expect(подключено).toBe(true);
        expect(
          ОТЛОЖЕНО[ключ],
          `${ключ} подключён — убери его из списка отложенных, иначе список перестанут читать`,
        ).toBeUndefined();
        return;
      }
      expect(
        ОТЛОЖЕНО[ключ],
        `${ключ} не подключён и не объяснён: добавь причину в ОТЛОЖЕНО или подключи`,
      ).toBeTruthy();
    });
  }
});
