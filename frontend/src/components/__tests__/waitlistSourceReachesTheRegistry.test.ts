import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, basename, dirname } from "node:path";

/**
 * Каждая страница с формой подписки шлёт МЕТКУ ИСТОЧНИКА, а бэкенд по ней
 * выбирает письмо: с датой открытия модуля или общее «напишем в день запуска
 * следующего». Метка, которой нет в реестре, молча даёт ОБЩЕЕ письмо.
 *
 * Молчаливо — потому что это не ошибка: поиск возвращает null, письмо уходит,
 * человек получает вежливый текст без даты. Ни падения, ни записи в журнале.
 *
 * Замер 30.08.2026: расхождений НЕТ — девять страниц с формой ровно покрыты
 * двумя реестрами. Сторож нужен не для сегодняшнего дня, а для завтрашней
 * посадочной: заведут её с новой меткой — и подписчик тихо получит не то.
 *
 * ⚠️ Метка бывает ЛИТЕРАЛОМ и ПЕРЕМЕННОЙ. При написании этой проверки я искал
 * только литералы `source="..."` и получил три ложных находки: страницы
 * DevHub, бюро и мультичата собирают метку как `channel ? "devhub-" + channel
 * : "devhub"`. Поэтому разбор ниже берёт ОБЕ формы.
 */

const APP = join(__dirname, "..", "..", "app");
const BACKEND = join(__dirname, "..", "..", "..", "..", "aevion-globus-backend", "src", "lib");

function walk(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    if (name === "node_modules" || name === "__tests__") continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.(tsx|ts)$/.test(name)) out.push(p);
  }
  return out;
}

/** Страницы, которые действительно показывают форму подписки. */
function pagesWithForm(): { file: string; sources: string[] }[] {
  return walk(APP)
    .filter((f) => readFileSync(f, "utf8").includes("WaitlistCapture"))
    .map((file) => {
      const src = readFileSync(file, "utf8");
      const sources = new Set<string>();
      // форма 1: литерал — source="cyberchess"
      for (const m of src.matchAll(/source="([^"]+)"/g)) sources.add(m[1]);
      // форма 2: переменная — const source = channel ? `devhub-${...}` : "devhub"
      for (const m of src.matchAll(/const source\s*=[^;]*?:\s*"([^"]+)"/g)) sources.add(m[1]);
      return { file, sources: [...sources] };
    })
    .filter((p) => p.sources.length > 0);
}

const brevo = readFileSync(join(BACKEND, "constitutionBrevo.ts"), "utf8");
const known = new Set<string>();
for (const m of brevo.matchAll(/prefix: "([^"]+)"/g)) known.add(m[1]);
for (const m of brevo.matchAll(/entry: "([^"]+)"/g)) known.add(m[1]);
// входы, где продукт уже работает, объявлены отдельным списком
for (const m of brevo.matchAll(/source: "([^"]+)"/g)) known.add(m[1]);

describe("метка подписки доезжает до реестра писем", () => {
  it("реестр вообще прочитан — иначе проверка ниже пуста", () => {
    // Отрицательный контроль. Без него пустой разбор дал бы зелёный тест,
    // который не проверяет ничего: «ни одна метка не потерялась» верно и для
    // нуля меток.
    expect(known.size, "префиксов в реестре бэкенда").toBeGreaterThan(3);
    expect(pagesWithForm().length, "страниц с формой").toBeGreaterThan(3);
  });

  /**
   * Известный пробел, закрытый В ДРУГОЙ ВЕТКЕ и потому пока живой у нас.
   *
   * Английские входы (`en-go`, `en-longevity`) реестру неизвестны: бэкенд
   * сверяет метку как `s === prefix` или `s.startsWith(prefix + "-")`, и
   * приставку `en-` не снимает. Подписчик с английской страницы получает
   * ОБЩЕЕ письмо вместо модульного.
   *
   * Починка есть: коммит 2b15c106b «Английская страница — английское письмо»
   * (ветка deploy/launch-2026-08-30, +99 строк в constitutionBrevo.ts). В моей
   * ветке его нет. Заново НЕ переписывать — придёт мержем.
   *
   * Исключение именное, а не по шаблону: появится третья английская метка —
   * сторож её поднимет.
   */
  // ЗАКРЫТО 30.08.2026 черри-пиком 2b15c106b: бэкенд снимает приставку
  // en- перед поиском, поэтому en-longevity находит свой модуль, а en-go
  // законно уходит в общее письмо — как и go. Список пуст намеренно:
  // убрать его совсем значит потерять место, где такие случаи называют.
  const ЖДЁТ_МЕРЖА: string[] = [];

  /**
   * Общий вход платформы получает общее письмо ПО ЗАМЫСЛУ, а не по недосмотру:
   * человек подписался не на модуль, а на платформу, и обещать ему конкретную
   * дату нечего. Это закреплено отдельным тестом в бэкенде («общий вход /go:
   * остаётся прежний текст про следующий модуль»).
   *
   * Моё первое правило было ШИРЕ предмета — требовало модульного письма от
   * всех, включая тех, кому оно не положено. Признак такой ошибки: «находка»
   * противоречит существующему зелёному тесту.
   */
  // pricing добавлен 31.08.2026: страница цен — вход НА ПЛАТФОРМУ, а не на
  // модуль. Человек оттуда подписывается на AEVION целиком, и обещать ему
  // дату конкретного модуля нечего — ровно тот же довод, что для go и home.
  //
  // Второй флаг того же прогона, qskyway, общим входом НЕ является: это модуль
  // запуска 10 сентября, и он добавлен в реестр писем на бэкенде.
  const ОБЩИЙ_ВХОД_ПО_ЗАМЫСЛУ = ["go", "home", "pricing"];

  it("каждая метка со страницы известна реестру", () => {
    const lost: string[] = [];
    for (const { file, sources } of pagesWithForm()) {
      for (const s of sources) {
        // Бэкенд снимает языковую приставку перед поиском (constitutionBrevo,
        // «en-longevity — тот же модуль»). Сторож обязан повторять ЭТО правило,
        // иначе поднимет как пробел то, что нормализуется на той стороне.
        const н = s.replace(/^en-/, "");
        const hit = [...known].some((k) => н === k || н.startsWith(`${k}-`));
        if (!hit && !ЖДЁТ_МЕРЖА.includes(s) && !ОБЩИЙ_ВХОД_ПО_ЗАМЫСЛУ.includes(н)) lost.push(`${s} (${basename(dirname(file))}/${basename(file)})`);
      }
    }
    expect(lost, "метки, по которым уйдёт ОБЩЕЕ письмо вместо модульного").toEqual([]);
  });
});
