/**
 * Письмо о покупке не зовёт туда, откуда нет ответа.
 *
 * Замер 01.09.2026, положительный контроль пройден (у `gmail.com` запись MX
 * находится, у чужого `aevion.io` — тоже): у домена `aevion.app` записи MX НЕТ.
 * Письмо на любой адрес этого домена не доходит никуда, а человек узнаёт об
 * этом отлупом — мы не узнаём вовсе.
 *
 * Хуже места для мёртвого адреса нет: это письмо получает тот, кто уже
 * ЗАПЛАТИЛ, и пишет он обычно тогда, когда доступ не пришёл.
 *
 * Форма `/pricing/contact` проверена по всей цепочке: пишет в файл, каталог на
 * постоянном томе (события с 26 мая целы), читается защищённой ручкой
 * `/api/pricing/leads`, `ADMIN_TOKEN` на проде задан.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stripComments } from "./helpers/sourceCode";

const исходник = readFileSync(
  join(process.cwd(), "src/routes/provisioning.ts"),
  "utf8",
);

/*
 * Вырезалка — ОБЩАЯ, а не своя. Своя повторяла ту же наивную замену по
 * шаблону, у которой 01.09.2026 нашлись два живых промаха: путь-шаблон в
 * комментарии съедал код ниже, а двойная косая внутри кавычек обрубала строку.
 * Второй способ делать то же самое — второй источник тех же ошибок.
 */

describe("поддержка в письме о покупке", () => {
  const письмо = stripComments(исходник);

  it("не зовёт на домен, который не принимает почту", () => {
    // Комментарии вырезаны намеренно: объяснение, ПОЧЕМУ адрес убран, само
    // содержит этот адрес — и без вырезания сторож краснел бы на собственном
    // объяснении. На этом я уже спотыкался.
    // Целим в ПРИГЛАШЕНИЕ написать, а не в подпись отправителя. `FROM_EMAIL`
    // остаётся `noreply@aevion.app` намеренно: этим адресом Resend подписывает
    // письмо (DKIM домена настроен), и менять его — отдельное решение. Дефект
    // же был в том, что письмо ЗВАЛО писать туда, откуда ответа не будет.
    const зовут = письмо.match(/mailto:[a-z0-9._-]+@aevion\.app/g) ?? [];
    expect(зовут, "письмо зовёт на @aevion.app, а у домена нет MX").toEqual([]);
  });

  it("даёт канал в ОБЕИХ версиях письма — и в HTML, и в тексте", () => {
    // Письмо уходит двумя телами. Первая редакция сторожа искала канал во всём
    // файле и пережила мутацию «убрать его из текстовой версии»: HTML-я хватало,
    // чтобы проверка прошла. А многие почтовые клиенты показывают именно текст.
    expect(письмо, "нет канала в HTML-версии").toContain(
      'href="${FRONTEND_URL}/pricing/contact"',
    );
    expect(письмо, "нет канала в текстовой версии").toContain(
      "Поддержка: ${FRONTEND_URL}/pricing/contact",
    );
  });

  it("проверка вообще смотрит на письмо — контроль охвата", () => {
    // Без него «адресов нет» одинаково выглядит при исправном письме и при
    // вырезалке, которая случайно съела весь файл.
    expect(письмо.length).toBeGreaterThan(5000);
    expect(письмо).toContain("ID подписки");
  });
});
