import { записатьСобытиеОтСервера, СОБЫТИЕ_ОПЛАТА_ПОДТВЕРЖДЕНА } from "../../routes/events";
import { нашВнутреннийАдрес } from "../planGate";

/**
 * Записать в воронку ПОДТВЕРЖДЁННУЮ оплату — одинаково для всех касс.
 *
 * 🔴 ЗАЧЕМ ПРИЗНАК «СВОЙ». Замер 29.09.2026: воронка показала «оплатили: 2», и
 * это были две НАСТОЯЩИЕ оплаты — но обе совершил сам основатель, проверяя кассу
 * ($40 Multichat и $16 через запасной путь). Первое же число про деньги
 * прочиталось бы как первые продажи, и разрешалось это перепиской между окнами.
 * Тот же класс, из-за которого 20.09 выяснилось, что воронка на 91 % состояла из
 * нашей автоматики — только теперь про выручку, а её показывают основателю.
 *
 * Почту в событие НЕ пишем: в хранилище воронки персональных данных нет и не
 * должно быть. Пишем один булев признак, вычисленный здесь и сейчас.
 *
 * Помощник один на все кассы намеренно: раньше запись события стояла копиями в
 * двух вебхуках, и добавление признака размножило бы их до четырёх. Ровно так
 * разошлись `tierForReference` у PayBox и PayPal.
 */
export function записатьПодтверждённуюОплату(вход: {
  /** Через какую кассу прошли деньги. */
  source: "lemonsqueezy" | "gumroad" | "paybox" | "paypal";
  /** Что купили: ступень тарифа или слаг модуля — для разреза по товарам. */
  tier?: string | null;
  /** Ссылка заказа, как её знает касса. */
  reference?: string | null;
  /** Имя события кассы — чтобы отличать первую оплату от продления. */
  event?: string | null;
  /** Адрес плательщика: нужен ТОЛЬКО чтобы вычислить признак «свой», в событие не попадает. */
  email?: string | null;
  /** Сумма в долларах, если касса её сообщила. */
  value?: number | null;
  /** Чем именно выдано: тариф или один модуль — видно, каким путём шла покупка. */
  path?: string | null;
}): boolean {
  return записатьСобытиеОтСервера(СОБЫТИЕ_ОПЛАТА_ПОДТВЕРЖДЕНА, {
    source: вход.source,
    ...(вход.tier ? { tier: вход.tier } : {}),
    ...(typeof вход.value === "number" ? { value: вход.value } : {}),
    meta: {
      reference: вход.reference ?? null,
      event: вход.event ?? null,
      ...(вход.path ? { path: вход.path } : {}),
      // Единственное, что говорит об адресе: наш он или чужой.
      свой: нашВнутреннийАдрес(вход.email),
    },
  });
}
