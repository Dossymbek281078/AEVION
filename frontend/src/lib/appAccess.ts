import { apiUrl } from "./apiBase";
import { getAuthToken } from "./auth";

/**
 * Три исхода, а не два.
 *
 * `unknown` — это НЕ «не оплачено». Человек может быть не залогинен, сеть
 * может лежать, база может быть недоступна. Показать «купите» тому, чей
 * статус мы не выяснили, — значит предложить заплатить второй раз тому, кто
 * уже заплатил. В кабинете этот дефект уже ловили и чинили признаком
 * `ownedUnknown`; здесь он закрыт с самого начала.
 */
export type AppAccess = "owned" | "not-owned" | "unknown";

/**
 * Оплачен ли этот модуль текущим пользователем.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ПОМОЩНИК. Замер 28.08.2026 по семи товарам каталога: связь
 * «оплата -> доступ» работает от начала до конца ровно у ОДНОГО (DevHub).
 * У четырёх нет платной логики вовсе, у двух она живёт на своих рельсах и с
 * подпиской каталога не связана.
 *
 * Что именно даёт подписка — решение владельца продукта, и оно ещё не
 * принято. Но проводка от него не зависит: страница модуля должна уметь
 * спросить «оплачено ли», каким бы ни был ответ про состав. Раньше такого
 * способа не было, и каждая страница пришлось бы обвязывать заново.
 *
 * Серверная половина уже есть и закрыта токеном:
 * `GET /api/apps/access/check?app=<slug>` отвечает по ВЛАДЕЛЬЦУ токена, а
 * параметр `email` не читает вовсе — до 28.08 он был публичным и выдавал
 * чужие покупки по адресу.
 *
 * @param slug Слаг модуля так, как его пишет платёжный вебхук: `cyberchess`,
 *   `devhub`, `ip_bureau`. Он НЕ всегда совпадает с `appId` каталога —
 *   сопоставление и объяснение лежат в `appSlugTitle.ts`.
 */
export async function checkAppAccess(slug: string): Promise<AppAccess> {
  if (!slug) return "unknown";
  const token = getAuthToken();
  // Нет токена — мы просто НЕ ЗНАЕМ. Аноним может быть давним покупателем,
  // который открыл страницу в другом браузере.
  if (!token) return "unknown";

  try {
    const res = await fetch(
      apiUrl(`/api/apps/access/check?app=${encodeURIComponent(slug)}`),
      { headers: { Authorization: `Bearer ${token}` } },
    );
    // 401 — токен протух. Это «не знаю», а не «не оплачено»: человек мог
    // купить вчера и всего лишь не перелогиниться.
    if (res.status === 401) return "unknown";
    if (!res.ok) return "unknown";
    const body = (await res.json()) as { active?: unknown };
    // Проверяем ТИП, а не истинность: ручка при сбое базы отвечает 500, но
    // если формат когда-нибудь изменится, «непонятный ответ» обязан быть
    // «не знаю», а не «не оплачено».
    if (typeof body?.active !== "boolean") return "unknown";
    return body.active ? "owned" : "not-owned";
  } catch {
    // Сеть легла — это тоже «не знаю».
    return "unknown";
  }
}
