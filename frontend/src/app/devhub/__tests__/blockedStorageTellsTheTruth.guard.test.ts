import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { DEVHUB_DICT } from "../i18n";

/**
 * Когда браузер блокирует хранилище сайта, обычное «проекты живут в ЭТОМ
 * браузере» — неправда, и неправда в ОПАСНУЮ сторону.
 *
 * Замер прода 08.09.2026: без заголовка личности сервер считает запрос общей
 * строкой `anonymous`, а `canAccess` пускает любого с той же строкой. Список
 * проектов БЕЗ заголовка отдал 17 записей — то есть всё, что создано в такой
 * ситуации, видно и удаляемо посторонним.
 *
 * Человек узнать об этом не мог: заголовок ставит перехватчик молча, браузер о
 * блокировке не сообщает, а витрина показывала успокаивающую строку.
 *
 * Сама общая корзина — продуктовое решение (её стабильность позволяет таким
 * людям вернуться к своему проекту), и оно вынесено основателю. Здесь
 * закреплено только то, что человек об этом ЗНАЕТ до того, как создаст проект.
 */
const PAGE = fs.readFileSync(path.resolve(__dirname, "..", "page.tsx"), "utf8");

describe("заблокированное хранилище названо своим именем", () => {
  test("витрина различает два случая, а не показывает одну строку всегда", () => {
    expect(PAGE, "признак блокировки не вычисляется").toContain("getDevhubGuestId() === null");
    expect(PAGE, "показывается одна и та же строка в обоих случаях").toContain(
      'хранилищеБлокировано ? t("proj.storageBlocked") : t("proj.browserBound")',
    );
  });

  test("текст есть во всех трёх языках и говорит о ЧУЖИХ, а не только о потере", () => {
    // Требуем ДВА признака сразу: посторонних И то, что они могут сделать.
    // Одного слова мало — мутация «созданное здесь могут увидеть и удалить
    // другие» → «проект может потеряться» прошла мимо первой редакции этой
    // проверки: слово «чужих» осталось в другой половине фразы, и сторож
    // промолчал, хотя главное предупреждение исчезло. Проверять надо смысл,
    // а не присутствие слова.
    const признаки: Record<string, { кто: RegExp; что: RegExp }> = {
      ru: { кто: /другие|посторонн|чуж/i, что: /увид\w*.*удал|удал\w*.*увид/i },
      en: { кто: /other visitors|others|them/i, что: /seen.*deleted|see.*delete/i },
      kk: { кто: /басқалар/i, что: /көре.*жоя|жоя.*көре/i },
    };
    for (const [lang, { кто, что }] of Object.entries(признаки)) {
      const t = DEVHUB_DICT[lang]?.["proj.storageBlocked"] ?? "";
      expect(t, `нет текста для ${lang}`).toBeTruthy();
      expect(кто.test(t), `текст на ${lang} не называет посторонних: ${t.slice(0, 110)}`).toBe(true);
      expect(
        что.test(t),
        `текст на ${lang} не говорит, ЧТО посторонние могут сделать — увидеть и удалить: ${t.slice(0, 110)}`,
      ).toBe(true);
    }
  });

  test("обычная строка про браузер осталась для обычного случая", () => {
    // Замена одной строки другой была бы хуже: для человека с работающим
    // хранилищем предупреждение про посторонних — ложная тревога.
    for (const lang of ["ru", "en", "kk"]) {
      expect(DEVHUB_DICT[lang]?.["proj.browserBound"], `пропала обычная строка для ${lang}`).toBeTruthy();
    }
  });
});
