import { describe, it, expect } from "vitest";
import { пустойКанал, пустойПост, пустойВход } from "../src/routes/events";

/*
 * 🔴 СОСТАВ СТРОКИ РАЗРЕЗА ЗАКРЕПЛЁН ЗДЕСЬ, И ТОЛЬКО ЗДЕСЬ.
 *
 * Зачем файл. Приёмка заметила повторяемость: за сутки дважды правка разреза
 * красила чужие сторожа — они сравнивают строгим `toEqual` по составу, и
 * добавление ступени («наши» вчера, «попробовали» и «внимание» сегодня)
 * требовало правки в пяти файлах. Ослабить строгость до `toMatchObject` было
 * бы хуже: именно строгость ловит тихое ИСЧЕЗНОВЕНИЕ поля, а пропавшее поле —
 * это молча обнулившийся показатель в отчёте.
 *
 * Поэтому состав объявлен фабриками в коде, ими же инициализируется разрез, а
 * сторожа строят ожидания как `{ ...пустойКанал(), visits: 2 }`. Но тогда
 * фабрика стала бы и определением состава, и его проверкой — круговая порука,
 * из-за которой любое добавление и любое удаление поля проходят незамеченными.
 *
 * Здесь круг разрывается: ключи перечислены РУКАМИ. Добавили поле — этот
 * сторож краснеет и требует осознанного решения; убрали — тоже. Одно место,
 * где нужно подумать, вместо пяти, где надо не забыть.
 */
describe("состав строк разреза закреплён руками", () => {
  it("🔴 строка канала: ровно эти поля", () => {
    expect(Object.keys(пустойКанал()).sort()).toEqual(
      [
        "checkoutStart",
        // Начала оплаты без единого признака живого человека: не отсев, а
        // названное число (07.10.2026). Добавлено осознанно — сторож состава
        // покраснел и потребовал решения, для этого он и писался.
        "checkoutStartNoSignal",
        "checkoutStartOurs",
        "checkoutStartSessions",
        "checkoutStartSessionsOurs",
        "dailyOpened",
        "dailyOpenedOurs",
        // Добавлены 11.10.2026 по заданию оркестратора: у этих четырёх
        // событий не было ПУБЛИЧНОГО читателя — лежали в журнале, видны были
        // только закрытой ручкой под токеном. Сторож покраснел законно.
        "offerShown",
        "offerShownOurs",
        "waitlistSubmitted",
        "waitlistSubmittedOurs",
        "puzzleSolved",
        "puzzleSolvedOurs",
        "progressed",
        "progressedOurs",
        "engaged",
        "engagedOurs",
        /*
         * Добавлены 12.10.2026, ночью, по замеру окна 16 живым заходом на прод:
         * внутри задачи воронка видела только первый рубеж и решение, поэтому
         * неверный ход и верный давали ОДИН И ТОТ ЖЕ `game_progress`, а
         * подсказка и уход не слали ничего — «ткнул не туда и ушёл» было
         * неотличимо от «начал решать».
         *
         * Смысл у этих трёх ОБРАТНЫЙ соседям: их рост не улучшает воронку, а
         * показывает, где она рвётся. Оговорка об этом стоит в самом ответе
         * (`insidePuzzleNote`), иначе «ошибок 7» прочтут как «семь решают».
         * Сторож состава покраснел законно и потребовал решения — для этого он
         * и писался.
         */
        "wrongMove",
        "wrongMoveOurs",
        "hintTaken",
        "hintTakenOurs",
        "abandonedPuzzle",
        "abandonedPuzzleOurs",
        // 12.10.2026: названное число вместо тихого уменьшения `progressed`
        // (неверная попытка больше не считается ходом; замер окна 37).
        "attemptWithoutMove",
        "attemptWithoutMoveOurs",
        // 12.10.2026: «в какой момент просим адрес» — показ сразу после неверной
        // попытки (замер окна 37: surface=first-move, а первый ход в задаче — попытка).
        "offerShownAfterAttempt",
        "offerShownAfterAttemptOurs",
        // Конец того, что начали: ступень «доиграл партию» (08.10.2026).
        // Добавлено осознанно — сторож состава покраснел и потребовал решения.
        "clicked",
        "clickedOurs",
        "finished",
        "finishedOurs",
        // `game_end` без числа ходов: названное число вместо тихого выбора.
        "finishedWithoutMoves",
        "paid",
        "paidOurs",
        "pricing",
        "pricingOurs",
        "thankYouOpened",
        "tried",
        "triedOurs",
        "visits",
        "visitsOurs",
      ].sort(),
    );
  });

  it("🔴 строка поста: ровно эти поля", () => {
    expect(Object.keys(пустойПост()).sort()).toEqual(
      // Четыре человеческие ступени добавлены 11.10.2026: визиты по метке
      // ролика людей от машин НЕ отличают (замер окна 91: 19 меток ровно по 2
      // визита), а `tried` человеческим шагом не является — его шлёт автомат
      // при заходе по `?puzzle=` (окно 37). Сторож покраснел законно.
      [
        "checkoutStart",
        "paid",
        "pricing",
        "pricingOurs",
        "tried",
        "triedOurs",
        "visits",
        "visitsOurs",
        "engaged",
        "engagedOurs",
        "progressed",
        "progressedOurs",
        "puzzleSolved",
        "puzzleSolvedOurs",
        "waitlistSubmitted",
        "waitlistSubmittedOurs",
        // Знаменатель к подпискам (просьба окна 16): «ноль подписок» без него
        // не отличить от «ноль показов» — это разные выводы.
        "offerShown",
        "offerShownOurs",
        /*
         * Три шага ВНУТРИ задачи, 12.10.2026. Именно по постам они нужнее
         * всего: вопрос «чем работающий ролик отличается от молчащих» решается
         * тем, что происходит с человеком ПОСЛЕ перехода, а до сих пор у поста
         * было видно только «дошёл до порога» — один и тот же признак и у того,
         * кто начал решать, и у того, кто ткнул не туда и ушёл.
         */
        "wrongMove",
        "wrongMoveOurs",
        "hintTaken",
        "hintTakenOurs",
        "abandonedPuzzle",
        "abandonedPuzzleOurs",
        // 12.10.2026: названное число вместо тихого уменьшения `progressed`
        // (неверная попытка больше не считается ходом; замер окна 37).
        "attemptWithoutMove",
        "attemptWithoutMoveOurs",
        // 12.10.2026: «в какой момент просим адрес» — показ сразу после неверной
        // попытки (замер окна 37: surface=first-move, а первый ход в задаче — попытка).
        "offerShownAfterAttempt",
        "offerShownAfterAttemptOurs",
      ].sort(),
    );
  });

  it("🔴 строка страницы входа: ровно эти поля", () => {
    expect(Object.keys(пустойВход()).sort()).toEqual(
      [
        "внимание",
        "вниманиеНаших",
        "доиграли",
        "доигралиНаших",
        "нажали",
        "нажалиНаших",
        "задачаДня",
        "задачаДняНаших",
        // Добавлены 11.10.2026 по заданию оркестратора: у этих четырёх
        // событий не было ПУБЛИЧНОГО читателя — лежали в журнале, видны были
        // только закрытой ручкой под токеном. Сторож покраснел законно.
        "показалиАдрес",
        "показалиАдресНаших",
        "оставилиАдрес",
        "оставилиАдресНаших",
        "решилиЗадачу",
        "решилиЗадачуНаших",
        "дошлиПоПорогу",
        "дошлиПоПорогуНаших",
        /*
         * Пять шагов внутри задачи — по странице входа, 12.10.2026. Разрез
         * отвечает на вопрос «на какой странице входа люди сдаются», и до сих
         * пор у него было видно только «дошёл до порога» — один и тот же
         * признак у того, кто начал решать, и у того, кто ткнул не туда.
         *
         * Этот сторож покраснел законно и ПЯТЫЙ раз за ночь: каждый раз список
         * обновлялся осознанно и с причиной, для этого он и писался.
         */
        "ошиблисьВЗадаче",
        "ошиблисьВЗадачеНаших",
        "взялиПодсказку",
        "взялиПодсказкуНаших",
        "бросилиЗадачу",
        "бросилиЗадачуНаших",
        "толькоПопытка",
        "толькоПопыткаНаших",
        "показПослеПопытки",
        "показПослеПопыткиНаших",
        "доЦен",
        "доЦенНаших",
        "началиОплату",
        // Добавлено 11.10.2026: без «наших» у этой ступени недельный отчёт по
        // цели 31.12 читал наши прогоны кассы как покупателей (у QMELANIN было
        // «касса 2» при нулевом внимании). Этот сторож на правке законно
        // покраснел — он и нужен, чтобы состав строки менялся осознанно.
        "началиОплатуНаших",
        "попробовали",
        "попробовалиНаших",
        "сессий",
        "сессийНаших",
      ].sort(),
    );
  });

  it("фабрики отдают НУЛИ, а не общий объект на всех", () => {
    // Иначе два канала делили бы одну строку, и числа одного попадали бы
    // другому: класс, который однажды уже дал «сумму по каналам больше итога».
    const а = пустойКанал();
    const б = пустойКанал();
    а.visits = 5;
    expect(б.visits, "фабрика вернула тот же объект").toBe(0);
    expect(Object.values(пустойВход()).every((v) => v === 0)).toBe(true);
  });

  it("у каждой пары «всего/наши» есть обе половины", () => {
    // Живое число считается вычитанием, и поле без пары делает его невозможным.
    // Проверяется по именам, а не по памяти автора.
    const ключи = Object.keys(пустойКанал());
    for (const к of ключи.filter((к) => к.endsWith("Ours"))) {
      const база = к.slice(0, -"Ours".length);
      expect(ключи, `у ${к} нет парного ${база}`).toContain(база);
    }
    const вх = Object.keys(пустойВход());
    for (const к of вх.filter((к) => к.endsWith("Наших"))) {
      const база = к.slice(0, -"Наших".length);
      const вариант = база.endsWith("и") ? база : база;
      expect(
        вх.some((и) => и === вариант || и === база),
        `у ${к} нет парного основания`,
      ).toBe(true);
    }
  });
});
