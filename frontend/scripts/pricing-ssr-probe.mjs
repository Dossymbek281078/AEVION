#!/usr/bin/env node
/*
 * Зонд: видны ли цены в ОТВЕТЕ СЕРВЕРА на /pricing.
 *
 * Тест рядом проверяет отрисовку блока без сети — он детерминирован и живёт в
 * наборе. Этот зонд проверяет живой прод и запускается руками после выкатки:
 * сетевой запрос внутри набора тестов сделал бы сборку хрупкой, а сторожа,
 * который краснеет от плохого интернета, перестают читать.
 *
 * Коды выхода: 0 — цены и названия видны, 1 — нет, 2 — спросить не удалось.
 */
const АДРЕС = process.argv[2] || "https://aevion.app/pricing?c=probe-ssr";

function видимыйТекст(html) {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " ");
}

/*
 * Код выхода ВОЗВРАЩАЕТСЯ из функции, а не ставится через process.exit и не
 * выбрасывается исключением. Проверено руками 01.10.2026, оба отказа врали:
 *   process.exit сразу после печати   → ассерт libuv, наружу 127;
 *   throw при заданном process.exitCode → наружу 1, то есть «спросить не
 *   удалось» читалось как «цен нет».
 * Код 2 обязан оставаться кодом 2: он не вывод о странице, а признание, что
 * вывода нет.
 */
async function взятьОтвет() {
  let ответ;
  try {
    ответ = await fetch(АДРЕС, { redirect: "follow" });
  } catch (e) {
    console.error(`не удалось спросить ${АДРЕС}: ${e.message}`);
    return null;
  }
  if (!ответ.ok) {
    console.error(`${АДРЕС} ответил ${ответ.status} — это не ответ про цены`);
    return null;
  }
  return ответ;
}

/*
 * Цена в разметке собрана из ДВУХ элементов: знак и число лежат в разных
 * тегах, поэтому после снятия тегов между ними остаётся пробел (а в части
 * мест — неразрывный, U+00A0, его ставит toLocaleString). Прежняя регулярка
 * требовала "$12" подряд и потому отвечала НОЛЬ на странице с 18 ценами:
 * замер прода 01.10.2026 на волне 8 (fdba4b3260d5) — зонд "цен 0", живой
 * подсчёт "цен 18, первые $ 12.00, $ 24.00". Зонд был красным на исправной
 * странице, а это хуже отсутствия зонда: красное перестают читать.
 */
const ЦЕНА = /[$][\s\u00a0]*\d+(?:[.,]\d{2})?/g;

/**
 * Самоконтроль прибора ДО того, как поверить его нулю (правило 2е): на строке
 * с известным ответом он обязан найти оба вида записи и обязан НЕ находить
 * цену там, где её нет. Без этого ноль от зонда отвечает про его слепоту, а
 * читается как «цен на странице нет» — ровно то, что случилось 01.10.
 */
function приборИсправен() {
  const нашёл = ("от $ 12.00 до $24.00 в месяц".match(ЦЕНА) || []).length;
  const пусто = ("нет цен вовсе".match(ЦЕНА) || []).length;
  if (нашёл === 2 && пусто === 0) return true;
  console.error(`самоконтроль зонда провален: на образце ${нашёл} из 2, на пустом ${пусто} из 0`);
  return false;
}

/** 0 — цены и названия видны, 1 — НЕ видны, 2 — спросить не удалось. */
async function спросить() {
  // Прибор проверяем ПЕРЕД запросом: его неисправность — код 2, а не вывод
  // о странице.
  if (!приборИсправен()) return 2;

  const ответ = await взятьОтвет();
  if (!ответ) return 2;

  const html = await ответ.text();
  const текст = видимыйТекст(html);
  const цены = текст.match(ЦЕНА) || [];
  const имена = ["Multichat", "DevHub", "QRight", "QSign"].filter((n) => текст.includes(n));

  console.log(`адрес:        ${АДРЕС}`);
  console.log(`знаков HTML:  ${html.length}`);
  console.log(`цен в тексте: ${цены.length}${цены.length ? ` (${[...new Set(цены)].slice(0, 6).join(", ")})` : ""}`);
  console.log(`названий:     ${имена.length} из 4 (${имена.join(", ") || "нет"})`);

  if (цены.length === 0 || имена.length === 0) {
    // Называем, чего ИМЕННО нет: «цен или названий» заставляет лезть в HTML
    // руками, а это две РАЗНЫЕ неисправности — не доехал серверный блок
    // против не доехали данные о приложениях.
    const чего = [цены.length === 0 ? "ЦЕН" : null, имена.length === 0 ? "НАЗВАНИЙ" : null]
      .filter(Boolean)
      .join(" и ");
    console.error(`${чего} В ОТВЕТЕ СЕРВЕРА НЕТ — поисковик и превью ссылки видят пустую страницу.`);
    return 1;
  }
  console.log("Цены и названия видны без запуска скриптов.");
  return 0;
}

// Печать успеха стояла ПОСЛЕ проверки и вне условия: зонд сообщал «цены видны»
// одновременно с «ЦЕН В ОТВЕТЕ НЕТ» и кодом 1. Теперь вывод и код — один ответ.
process.exitCode = await спросить();
