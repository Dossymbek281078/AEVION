import { describe, it, expect } from "vitest";
import { readFileSync } from "fs";
import { join } from "path";

/**
 * Нижняя навигация на 320px — самые дешёвые телефоны.
 *
 * Замер браузером на боевой сборке 31.08.2026, ДО починки:
 *   ширина окна 320, прокрутка страницы 354
 *   виновник назван точно: кнопка «👤 Профиль», правый край 354
 *
 * Прибор сперва показал другого виновника — правую панель с краем 592. Это
 * ложный след: она внутри контейнера с собственной прокруткой и страницу не
 * двигает. Настоящих виновников видно только после отсева тех, кого обрезает
 * предок.
 *
 * Почему flex:1 не спасал: у flex-элемента min-width по умолчанию auto, то
 * есть сжаться ниже своего содержимого он не может. Пять кнопок с padding по
 * 16px с каждой стороны в 320px не помещаются никак.
 *
 * ⚠️ Граница этого сторожа: он проверяет ИСХОДНИК, а не отрисовку. Настоящее
 * доказательство — замер в браузере, и он записан выше. Здесь закрепляется,
 * чтобы правку не откатили молча.
 */

const KOD = () => readFileSync(join(process.cwd(), "src/app/cyberchess/page.tsx"), "utf8");

describe("нижняя навигация помещается в 320px", () => {
  it("кнопки умеют сжиматься ниже своего содержимого", () => {
    const s = KOD();
    expect(s.length).toBeGreaterThan(100000); // контроль: файл прочитан
    expect(s).toContain('letterSpacing:0.3,flex:"1 1 0",minWidth:0,');
    // Прежний вариант ломал вёрстку — он не должен вернуться.
    expect(s).not.toContain("letterSpacing:0.3,flex:1,");
  });

  it("боковые отступы не съедают ширину", () => {
    // 5 кнопок × 32px отступов = 160 из 320, то есть половина экрана.
    const s = KOD();
    expect(s).not.toContain('padding:"10px 16px 8px",border:"none",background:"transparent"');
    expect(s).toContain('padding:"10px 6px 8px",border:"none",background:"transparent"');
  });

  it("длинная подпись обрезается, а не расталкивает соседей", () => {
    const s = KOD();
    expect(s).toContain('textOverflow:"ellipsis",whiteSpace:"nowrap"}}>{item.label}');
  });

  it("все пять разделов остаются на месте", () => {
    // Соблазн «убрать пятую кнопку» решил бы вёрстку и отнял бы у человека
    // раздел. Проверяем, что решение не такое.
    const s = KOD();
    for (const p of ["Играть", "Задачи", "Анализ", "Коуч", "Профиль"]) {
      expect(s).toContain(`label:"${p}"`);
    }
  });
});
