import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

/**
 * Наши пробы не жгут норму живых посетителей.
 *
 * Норма DevHub считается по заголовку `x-devhub-guest`. Без него личность —
 * `"anonymous"`, ОДНА на всех, и туда же попадает живой посетитель с
 * заблокированным хранилищем: в приватном окне `getDevhubGuestId()` возвращает
 * null, и метка не ставится вовсе.
 *
 * Замер на проде 30.09.2026, три случая рядом (`/api/devhub/studio/credits`):
 *   с меткой probe-a -> deploy 0/10, translate 0/50
 *   с меткой probe-b -> deploy 0/10, translate 0/50
 *   БЕЗ метки        -> deploy 10/10, translate 50/50   ИСЧЕРПАНО
 *
 * Исчерпали его мы: из пяти скриптов, зовущих DevHub, метку не передавал НИ
 * ОДИН, а `devhub-prod-smoke.js` зовёт метрируемые ручки (/media/image,
 * /media/email, /media/3d/models, /media/drive-search). Следствие денежное:
 * посетитель в приватном окне видел страницу, мог сгенерировать, а выкатить —
 * нет, то есть отказ приходил ровно на главном обещании «идея -> живой адрес».
 *
 * ⚠️ Почему сторож смотрит на МЕТКУ, а не на адрес. Первой попыткой я сделал
 * адрес первичным ключом нормы: сторож из пяти проверок был зелёным, четыре
 * мутации поймались — и правка всё равно была неверной. Поймал её чужой тест
 * квоты, который намеренно подставляет разный `x-forwarded-for`: при
 * `trust proxy` адрес выбирает клиент, значит норма по адресу обходится сменой
 * заголовка, и это ровно та дыра, которую закрыли вторым потолком 15.09.
 * Правку откатил. Сторож по исходнику не умеет ловить «замысел неверен» —
 * это сделал тест, проверяющий ПОВЕДЕНИЕ.
 */
const ПАПКА = join(__dirname, "..", "scripts");

/** Ручки, тратящие нашу норму: их вызов без метки жжёт общее ведро. */
const МЕТРИРУЕМЫЕ = [
  "/api/devhub/media/image",
  "/api/devhub/media/video",
  "/api/devhub/media/tts",
  "/api/devhub/media/music",
  "/api/devhub/media/speech",
  "/api/devhub/media/translate",
  "/api/devhub/media/3d",
  "/api/devhub/media/email",
  "/api/devhub/media/drive-search",
  "/api/devhub/deploy/",
];

function скрипты(): string[] {
  return readdirSync(ПАПКА).filter((f) => f.endsWith(".js") || f.endsWith(".mjs"));
}

/**
 * Текст без комментариев.
 *
 * Понадобилось после того, как первая версия этого сторожа пропустила мутацию
 * «убрать заголовок из headers»: в файле остался мой же КОММЕНТАРИЙ со словами
 * «заголовок x-devhub-guest», и поиск по тексту находил его, когда в коде
 * метки уже не было. Свой рассказ о защите ослепил проверку самой защиты.
 */
function безКомментариев(текст: string): string {
  const БЛОЧНЫЙ = new RegExp("/\\*[\\s\\S]*?\\*/", "g");
  const СТРОЧНЫЙ = new RegExp("(^|[^:])//.*$", "gm");
  return текст.replace(БЛОЧНЫЙ, " ").replace(СТРОЧНЫЙ, "$1");
}

function зовётМетрируемое(текст: string): boolean {
  return МЕТРИРУЕМЫЕ.some((р) => текст.includes(р));
}

describe("пробы не расходуют норму живых посетителей", () => {
  it("прибор исправен: скрипты находятся и признак различает", () => {
    // Без этой пары ноль ниже неотличим от «не умею читать папку».
    expect(скрипты().length, "скрипты не найдены — сторож смотрит не туда").toBeGreaterThan(5);
    expect(зовётМетрируемое('fetch("/api/devhub/media/image")'), "признак не ловит метрируемое").toBe(true);
    expect(зовётМетрируемое('fetch("/api/devhub/health")'), "признак ловит лишнее").toBe(false);
    // Комментарий О метке не должен считаться меткой — на этом сторож уже
    // однажды промолчал, и мутация «убрать заголовок» прошла.
    expect(безКомментариев('/* про x-devhub-guest */ const a = 1;').includes("x-devhub-guest")).toBe(false);
    expect(безКомментариев('// про x-devhub-guest\nconst a = 1;').includes("x-devhub-guest")).toBe(false);
    expect(безКомментариев('h["x-devhub-guest"] = m;').includes("x-devhub-guest")).toBe(true);
  });

  it("каждый скрипт, зовущий метрируемую ручку, передаёт метку гостя", () => {
    const молчат: string[] = [];
    for (const имя of скрипты()) {
      const сырой = readFileSync(join(ПАПКА, имя), "utf8");
      if (!зовётМетрируемое(сырой)) continue;
      // Ищем в КОДЕ, не в тексте: рассказ о заголовке заголовком не является.
      if (!безКомментариев(сырой).includes("x-devhub-guest")) молчат.push(имя);
    }
    expect(
      молчат,
      "скрипт тратит норму безымянного гостя: его запросы уходят в ведро " +
        '"anonymous", общее с живыми посетителями, у которых заблокировано ' +
        "хранилище. Добавьте заголовок x-devhub-guest с меткой probe-/smoke-.",
    ).toEqual([]);
  });

  it("метка держит серверный формат, иначе она молча станет anonymous", () => {
    // devhubGuestId() отвергает мусор и возвращает "anonymous" — то есть
    // НЕВЕРНАЯ метка не отличается от её отсутствия, и починка была бы
    // видимой в коде, но недействующей.
    const GUEST_ID = /^[A-Za-z0-9_-]{8,64}$/;
    const текст = readFileSync(join(ПАПКА, "devhub-prod-smoke.js"), "utf8");
    const m = /smoke-\$\{new Date\(\)\.toISOString\(\)\.slice\(0, 10\)\.replace\(([^)]*)\, ""\)\}/.exec(текст);
    expect(m, "метка смоука собирается не так, как ожидает сторож").not.toBeNull();
    // Собираем ту же строку и проверяем серверным правилом.
    const метка = `smoke-${new Date().toISOString().slice(0, 10).replace(/-/g, "")}`;
    expect(GUEST_ID.test(метка), "метка не пройдёт серверную проверку и станет anonymous").toBe(true);
  });
});
