import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { zapasPodDoskoy, ЗАПАС_ЗАДАЧА_ПО_ССЫЛКЕ, ЗАПАС_НИЗКИЙ_СТОЛ, ЗАПАС_СТОЛ } from "../zapasPodDoskoy";

/**
 * 🔴 ПРИШЁЛ ЗА ЗАДАЧЕЙ — ДОСКА КРУПНЕЕ, ЛИШНЕЕ УБРАНО.
 *
 * Замер 12.10.2026 на проде 7fb9d76ac6a4, окно ноутбука 1463×724, заход по
 * ?puzzle=: доска 257×257 — 18 % ширины экрана, самое маленькое на экране;
 * слева колонка «Оценка / Материал / Партия» 378×573, для задачи бесполезная.
 * На телефоне (390×844) доска 351, 90 % ширины — там беды нет. Единственный
 * живой вход сайта — ролики о шахматах, и смотрят их с компьютера тоже.
 *
 * Размер доски ограничен высотой: boardPx = vhPx − (boardTopPx + запас).
 * Запас 186 держал место под ряды кнопок ПАРТИИ, пришедшему за задачей не
 * нужные. Сторож держит три свойства: запас меньше, рейл скрыт, ряд партии
 * под доской не рисуется — и всё это ТОЛЬКО для захода по ссылке.
 */
const СТРАНИЦА = readFileSync(join(process.cwd(), "src/app/cyberchess/page.tsx"), "utf8");
const КОД = СТРАНИЦА.split("\n").filter((с) => !/^\s*(\/\/|\*|\/\*)/.test(с)).join("\n");

describe("запас под доской", () => {
  it("🔴 заход за задачей — запас меньше, чем у любого режима партии", () => {
    expect(zapasPodDoskoy(true, true)).toBe(ЗАПАС_ЗАДАЧА_ПО_ССЫЛКЕ);
    expect(zapasPodDoskoy(true, false)).toBe(ЗАПАС_ЗАДАЧА_ПО_ССЫЛКЕ);
    expect(ЗАПАС_ЗАДАЧА_ПО_ССЫЛКЕ).toBeLessThan(ЗАПАС_СТОЛ);
    expect(ЗАПАС_ЗАДАЧА_ПО_ССЫЛКЕ).toBeLessThan(ЗАПАС_НИЗКИЙ_СТОЛ);
    // Литералы, не вывод из константы: политика записана числом (урок про тавтологию).
    expect(ЗАПАС_ЗАДАЧА_ПО_ССЫЛКЕ).toBe(96);
  });

  it("обычные режимы не тронуты — знаменатель 2 из 2", () => {
    expect(zapasPodDoskoy(false, true)).toBe(186);
    expect(zapasPodDoskoy(false, false)).toBe(150);
  });

  it("🔴 страница берёт запас из этой функции, а не считает по-своему", () => {
    expect(КОД).toContain("zapasPodDoskoy(зашёлЗаЗадачей,lowDesktop)");
    // Старая формула с литералами внутри страницы не вернулась.
    expect(КОД).not.toMatch(/lowDesktop\?186:150/);
  });
});

describe("раскладка при заходе за задачей", () => {
  it("🔴 рейл «Оценка/Материал/Партия» скрыт при заходе по ссылке", () => {
    expect(КОД).toContain("const railShown=vwPx>=1100&&!зашёлЗаЗадачей;");
    // И aside рисуется ПО railShown, а не по литералу 1100: иначе рейл
    // вернулся бы через вторую дверь, а бюджет ширины считал бы его скрытым.
    expect(КОД).toContain("&&!streamerMode&&railShown&&(()=>{");
    const литералов = (КОД.match(/&&!streamerMode&&vwPx>=1100&&\(\(\)=>\{/g) || []).length;
    expect(литералов, "aside всё ещё рисуется по литералу 1100").toBe(0);
  });

  it("🔴 ряд кнопок партии под доской не рисуется при заходе за задачей НА СТОЛЕ", () => {
    expect(КОД).toContain("{!(зашёлЗаЗадачей&&!isMobileLayout)&&<div style={{display:\"flex\",gap:8,marginTop:SPACE[2],...podDoskoyRow}}>");
  });

  it("флаг ставится только из ?puzzle= и только один раз", () => {
    expect((КОД.match(/sЗашёлЗаЗадачей\(/g) || []).length, "флаг ставится не из одного места").toBe(1);
    expect(КОД).toContain("sЗашёлЗаЗадачей(поСсылке);");
    // Контроль прибора: строка, которой точно нет, не находится.
    expect(КОД).not.toContain("sЗашёлЗаЗадачей(true);");
  });
});
