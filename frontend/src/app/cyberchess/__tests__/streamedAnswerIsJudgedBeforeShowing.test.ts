/**
 * Оборванный или чужеязычный ответ стрима не остаётся на экране.
 *
 * Настоящий случай приёмки 29.09: на русский вопрос панель тренера показала
 * «The Hindi phrase \» и код ответа был 200. Разбор: защита языка и обрыва
 * стояла в `/api/coach/chat`, а панель зовёт СНАЧАЛА `/chat/stream`, где
 * повторить нечего — токены уже на экране. Фронт при этом засчитывал любой
 * непустой обрывок как выданный ответ (`if(acc.trim())streamed=true`).
 */
import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { языкНеТот, ответОгрызок, стримГоден } from "../ответНеГоден";

describe("годность ответа, пришедшего стримом", () => {
  it("🔴 настоящий брак приёмки не проходит", () => {
    const вопрос = "Объясни по-русски: зачем защищать центр?";
    expect(стримГоден(вопрос, "The Hindi phrase \\")).toBe(false);
  });

  // 🔴 Две причины брака проверяются ПО ОТДЕЛЬНОСТИ и обязательно через
  //    судью. Первая версия этих двух проверок звала половинки напрямую — и
  //    мутации «убрать язык» и «убрать обрыв» обе выжили: настоящий случай
  //    приёмки ловится обеими сразу, поэтому по нему одному нельзя понять,
  //    какая из половин работает. Нужны случаи, где виновата ровно одна.
  it("одна только чужеязычность — уже брак (обрыва нет)", () => {
    const вопрос = "Почему плох мой ход?";
    const длинныйАнглийский =
      "Because it loses a pawn for nothing. After Nf3 White keeps the extra " +
      "tempo, the centre stays under control, and Black has no compensation " +
      "for the material anywhere on the board, so the position is simply bad.";
    expect(длинныйАнглийский.length).toBeGreaterThanOrEqual(200); // обрывком не считается
    expect(ответОгрызок(длинныйАнглийский)).toBe(false);
    expect(стримГоден(вопрос, длинныйАнглийский)).toBe(false);
  });

  it("один только обрыв — уже брак (язык свой)", () => {
    const вопрос = "Почему плох мой ход?";
    const обрывок = "Отличный вопрос! Давай разбер";
    expect(языкНеТот(вопрос, обрывок)).toBe(false); // язык правильный
    expect(стримГоден(вопрос, обрывок)).toBe(false);
  });

  it("контроль: нормальный русский разбор проходит", () => {
    const вопрос = "Почему плох мой ход?";
    const ответ =
      "Ход отдаёт пешку без компенсации: после Кf3 у белых лишний темп, " +
      "и центр остаётся за ними.";
    expect(стримГоден(вопрос, ответ)).toBe(true);
  });

  it("контроль: ход латиницей — не чужой язык", () => {
    expect(стримГоден("Что играть?", "Nf3.")).toBe(true);
  });

  it("контроль: длинный английский ответ на АНГЛИЙСКИЙ вопрос проходит", () => {
    const длинный =
      "Because it loses a pawn for nothing, and after Nf3 White keeps " +
      "the extra tempo while the centre stays under control.";
    expect(стримГоден("Why is my move bad?", длинный)).toBe(true);
  });

  it("🔴 ветка стрима в панели СПРАШИВАЕТ судью, а не засчитывает всё подряд", () => {
    // Проверка по исходнику: панель — это один файл на 15 тысяч строк, поднять
    // её в тесте нельзя. Поэтому спрашиваем механизм минимально: судья позван
    // в файле, и прежнего безусловного зачёта в ветке стрима больше нет.
    const файл = path.join(__dirname, "..", "page.tsx");
    const исходник = fs.readFileSync(файл, "utf8");
    expect(исходник).toContain("стримГоден(");
    expect(исходник).not.toContain("if(acc.trim())streamed=true");
  });
});
