// Место опасное: эта строка стоит на карточке товара, то есть человек
// читает её перед оплатой $149/мес. Тот же дефект я чинил раньше на
// карточке тарифа — здесь ДРУГАЯ поверхность, и она ближе к кнопке.
//
// Запрет намеренно привязан к записи DevHub, а не к словам во всём файле:
// «Railway» и «Vercel» могут законно упоминаться у других товаров, и
// широкий запрет сделал бы сторожа лгущим (см. узкий список выше).
// ДОБАВЛЕНО 31.08.2026: QVenture обещал величину, которой не считает.
//
// Описание товара обещало «TAM/SAM/SOM». Замер по продукту: TAM и SOM
// считаются по-настоящему (lib/qventure/tam.ts — claimedTamUsd, sectorTamUsd,
// somAt1PctUsd) и показываются человеку (_result.tsx — «Claimed TAM»,
// «SOM @ 1%»). SAM не считается нигде: два его упоминания во всём модуле —
// это ТЕКСТ ПРОМТА для ИИ-линзы и строка-оговорка «TAM/SAM/SOM and CAC/LTV
// unconfirmed». Ни поля, ни строки на экране.
//
// Разница с обычной опечаткой в том, что SAM — отдельная величина, которую
// покупатель за $39/мес ищет специально. Продукт при этом честен: он
// печатает TAM и SOM и прямо пишет, что цифры не подтверждены. Завышала
// одна продающая строка.
describe("QVenture не обещает величин, которых не считает", () => {
  const src = readFileSync(CATALOG, "utf8");

  function qventureEntry(): string {
    const at = src.indexOf('id: "qventure"');
    return at < 0 ? "" : src.slice(at, at + 700);
  }

  it("контроль: запись QVenture найдена и это она", () => {
    const e = qventureEntry();
    expect(e.length, "запись QVenture не найдена — id или файл изменились").toBeGreaterThan(100);
    expect(e, "найдена не та запись").toContain("QVenture");
    expect(e, "в записи нет описания — проверять нечего").toContain("desc:");
  });

  it("не обещает SAM — модуль его не считает", () => {
    expect(
      qventureEntry(),
      "описание обещает SAM, а в модуле нет ни поля, ни строки на экране: " +
        "SAM упоминается только в тексте промта и в оговорке про неподтверждённость. " +
        "Либо считайте величину, либо не называйте её покупателю.",
    ).not.toContain("SAM");
  });

  it("то, что модуль считает, названо", () => {
    // Обратная ошибка: вычистить всё — тоже неправда, оценка рынка есть.
    const e = qventureEntry();
    expect(e, "в описании не осталось TAM, хотя модуль его считает").toContain("TAM");
    expect(e, "в описании не осталось SOM, хотя модуль его считает").toContain("SOM");
  });
});

