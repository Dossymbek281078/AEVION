// Автообновления зависимостей не должны воспроизводить всплеск, за который
// аккаунт GitHub приостановили 27.07.2026.
//
// Тогда причиной стала СУММА за сутки: около 165 коммитов, десятки пушей и
// 25 мержей выглядели машинными. Настройка dependabot могла повторить это
// сама: пять наборов, суммарный потолок 35 открытых PR, все npm-наборы в
// понедельник, два из них в один час — до тридцати PR за несколько минут.
//
// Сторож темпа ~/.claude/hooks/github-push-guard.js этого НЕ ВИДИТ: он
// считает вызовы из вкладок, а dependabot ходит от нашего аккаунта на стороне
// GitHub. Поэтому ограничение живёт здесь, в самом конфиге, и охраняется
// отсюда — иначе лимиты вернут обратно, и заметит это только блокировка.

import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";

const CONFIG = path.resolve(__dirname, "../../.github/dependabot.yml");

// Читаем без try/catch намеренно: пропавший конфиг обязан ронять прогон
// громко. Пустая строка сделала бы все проверки ниже зелёными.
const yml = readFileSync(CONFIG, "utf8");

const limits = [...yml.matchAll(/open-pull-requests-limit:\s*(\d+)/g)].map(
  (m) => Number(m[1]),
);
const days = [...yml.matchAll(/day:\s*"(\w+)"/g)].map((m) => m[1]);

describe("dependabot не может устроить всплеск", () => {
  it("контроль: конфиг прочитан и наборы найдены", () => {
    // Без этого регулярка, переставшая совпадать, дала бы пустые списки —
    // и любая проверка «сумма меньше N» прошла бы на нуле.
    expect(limits.length).toBeGreaterThanOrEqual(5);
    expect(days.length).toBeGreaterThanOrEqual(5);
  });

  it("суммарный потолок открытых PR не больше 12", () => {
    // Было 35. Группировка патчей схлопывает мелочь в один PR, поэтому
    // 2-3 на набор — не ограничение по сути, а защита от пачки.
    const total = limits.reduce((a, b) => a + b, 0);
    expect(total, `суммарный потолок ${total}`).toBeLessThanOrEqual(12);
  });

  it("ни один набор не открывает больше 3 PR за раз", () => {
    for (const l of limits) expect(l).toBeLessThanOrEqual(3);
  });

  it("наборы разнесены по разным дням недели", () => {
    // Главное в этой проверке: суммарный потолок можно соблюсти и всё равно
    // выстрелить всем разом в один день — снаружи это выглядит одинаково.
    expect(new Set(days).size, `дни: ${days.join(", ")}`).toBe(days.length);
  });

  it("в шапке не обещан авто-мерж, которого нет", () => {
    // 27.08.2026 там было написано «auto-merge enabled for patch bumps», а
    // workflow авто-мержа в репозитории нет. Обещание механизма, которого не
    // существует, опаснее его отсутствия: на него ссылаются при решениях.
    expect(yml).not.toMatch(/auto-merge enabled/i);
  });
});
