// Спецификация обещала то, чего код не делает.
//
// Поле `valid` у ручки проверки описывалось как «Сертификат найден И НЕ
// ОТОЗВАН», а в коде оно ЗАШИТО в true для любого существующего сертификата,
// включая отозванный. Тут же, следующей фразой, описание само себя
// опровергало («у найденного значение всегда true») — внимательный читатель
// поймёт, беглый возьмёт первую фразу.
//
// Цена ошибки не косметическая: спецификацию читает интегратор — суд,
// площадка, работодатель, — и по названию `valid` он примет отозванный
// сертификат за действительный.
//
// Менять ЗНАЧЕНИЕ поля нельзя: страница /verify/[id] решает по нему, разбирать
// ли ответ вообще (`if (!res.ok || !json.valid)`), и `valid:false` у
// отозванного увело бы её в ветку ошибки — то есть отзыв перестал бы
// показываться. Поэтому честной делается ДОКУМЕНТАЦИЯ, а признак отзыва
// остаётся там, где он настоящий: в поле `status`.
import { describe, it, expect } from "vitest";
import { openapiSpec } from "../src/lib/openapiSpec";

type Schema = { properties?: Record<string, { description?: string }> };

function validDescription(): string {
  const spec = openapiSpec as unknown as Record<string, any>;
  const op = spec.paths?.["/api/pipeline/verify/{certId}"]?.get;
  const schema: Schema =
    op?.responses?.["200"]?.content?.["application/json"]?.schema;
  const d = schema?.properties?.valid?.description;
  // Контроль прибора: если путь до описания сломается, тест обязан упасть
  // здесь, а не молча признать пустую строку безобидной.
  expect(typeof d, "не нашёл описание поля valid в спецификации").toBe("string");
  return String(d);
}

describe("спецификация не обещает, что valid учитывает отзыв", () => {
  it("описание НЕ утверждает «не отозван»", () => {
    expect(validDescription()).not.toMatch(/не отозван/i);
  });

  it("описание прямо называет отозванный сертификат и отсылает к status", () => {
    const d = validDescription();
    expect(d, "интегратору не сказано, где смотреть отзыв").toMatch(/status/);
    expect(d).toMatch(/отозван/i);
  });

  it("контроль: шаблон умеет находить запрещённую фразу", () => {
    // Без этого «совпадений нет» одинаково значит «чисто» и «шаблон не ловит».
    expect("Сертификат найден и не отозван.").toMatch(/не отозван/i);
  });
});
