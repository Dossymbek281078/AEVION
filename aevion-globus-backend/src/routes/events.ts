/**
 * Метка чужой площадки в безопасном виде.
 *
 * Правило простое и названное: нижний регистр, разрешены латиница, цифры,
 * точка, подчёркивание и дефис; всё прочее — один знак `?`. Длина до 40.
 * Кириллицу тоже заменяем: ответ публичный, и единственное, что нам нужно от
 * метки, — узнать площадку, а её имя всегда латиницей.
 */
export function безопаснаяМетка(сырое: string): string {
  const низ = String(сырое ?? "").trim().toLowerCase().slice(0, 40);
  let из = "";
  for (const знак of низ) {
    из += /[a-z0-9._-]/.test(знак) ? знак : "?";
  }
  return из;
}

/** Метка из пути, если канал для неё НЕ распознан. Иначе null. */
export function чужаяМетка(
  канал: string,
  path: string | null | undefined,
): string | null {
  // «unknown» ставит фронт, когда метка в адресе есть, а каталог её не знает.
  // Опираемся на его ответ, а не заводим второй список каналов на бэкенде:
  // два списка одного и того же неизбежно разъезжаются (урок 30.09–05.10).
  if (канал !== "unknown") return null;
  const p = String(path ?? "");
  const m = /[?&](c|ref)=([^&#]+)/.exec(p);
  if (!m) return null;
  let сырое: string;
  try {
    сырое = decodeURIComponent(m[2]);
  } catch {
    сырое = m[2];
  }
  const безопасная = безопаснаяМетка(сырое);
  if (!безопасная) return null;
  /*
   * Откуда метка — часть ответа, а не косметика. `?c=` ставим мы сами
   * (значит, в тексте поста опечатка или метка не заведена), `?ref=`
   * дописывает ПЛОЩАДКА (значит, появился каталог, о котором мы не знаем, и
   * заводить надо не опечатку, а канал). Это разные поручения, поэтому имена
   * в разрезе разные: `ref:<значение>`.
   */
  return m[1] === "ref" ? `ref:${безопасная}` : безопасная;
}

/*
 * 🔴 СОСТАВ СТРОКИ РАЗРЕЗА ЖИВЁТ В ОДНОМ МЕСТЕ.
 *
 * Повод, замеченный приёмкой 07.10.2026 как повторяющийся: за сутки дважды моя
 * правка разреза покрасила чужие сторожа — они сравнивают строгим `toEqual` по
 * составу, и добавление ступени требовало правки в пяти файлах. Ослаблять
 * строгость нельзя: именно она ловит тихое ИСЧЕЗНОВЕНИЕ поля.
 *
 * Поэтому состав объявлен фабриками, и ими же инициализируется разрез. Сторожа
 * строят ожидание как `{ ...пустойКанал(), visits: 2 }` — тогда новое поле не
 * ломает их, а пропавшее по-прежнему ломает. Сам состав закреплён в ОДНОМ
 * стороже (`cutShapeIsPinned`), где ключи перечислены руками: без него фабрика
 * стала бы и определением, и проверкой себя самой.
 */
