import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * 🔴 ПРИШЁЛ ЗА ЗАДАЧЕЙ — ШАПКА В ОДИН РЯД (стол).
 *
 * Замер «после» волны 88 на проде 75777c6c1786, 1463×724: доска выросла до
 * 317, но её верх так и стоит на y=290 — два ряда шапки (~230 px) остались
 * главным ограничителем высоты. Второй ряд — профиль (рейтинг + Chessy) и
 * «⚙ Ещё», которые переносятся на новую строку, когда не влезают. Слово
 * оркестратора: при заходе по ?puzzle= сворачивать ТОЛЬКО их; главная
 * навигация (Играть/Задачи/Анализ/Коуч, «от $12/мес») остаётся; другие режимы
 * не трогать.
 */
const СТР = readFileSync(join(process.cwd(), "src/app/cyberchess/page.tsx"), "utf8");
const КОД = СТР.split("\n").filter((с) => !/^\s*(\/\/|\*|\/\*)/.test(с)).join("\n");

describe("шапка при заходе за задачей", () => {
  it("🔴 признак выводится из захода по ссылке и только для стола", () => {
    expect(КОД).toContain("const шапкаКомпактна=зашёлЗаЗадачей&&!isMobileLayout;");
    // Объявлен ПОСЛЕ isMobileLayout — иначе TS2448 (поймано при первой правке).
    expect(КОД.indexOf("const isMobileLayout")).toBeLessThan(КОД.indexOf("const шапкаКомпактна"));
  });

  it("🔴 профиль (рейтинг + Chessy) не рисуется в компактной шапке", () => {
    expect(КОД).toContain('{vwPx>=769&&!шапкаКомпактна&&<div className="cc-hzone"');
  });

  it("🔴 кнопка «⚙ Ещё» не рисуется в компактной шапке", () => {
    expect(КОД).toContain('{!шапкаКомпактна&&<button onClick={()=>sMoreMenuOpen(v=>!v)} aria-haspopup="menu"');
  });

  it("🔴 главная навигация и цена НЕ зависят от признака — знаменатель по вкладкам", () => {
    // Вкладки берутся из TAB_META; их рендер не должен быть обёрнут нашим флагом.
    const вкладки = (КОД.match(/data-cc-buy="header"/g) || []).length;
    expect(вкладки, "кнопка «от $12/мес» в шапке стола").toBe(1);
    const i = КОД.indexOf('data-cc-buy="header"');
    const окно = КОД.slice(Math.max(0, i - 400), i);
    expect(окно, "кнопка цены оказалась под флагом компактной шапки").not.toContain("шапкаКомпактна");
    // Флаг встречается ровно в трёх местах: объявление + два гейта. Четвёртое —
    // повод перепроверить, что не свернули лишнего.
    expect((КОД.match(/шапкаКомпактна/g) || []).length).toBe(3);
  });
});
