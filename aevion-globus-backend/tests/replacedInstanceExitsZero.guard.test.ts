import { describe, test, expect, vi } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { обработчикЗавершения, зарегистрироватьЗавершение } from "../src/lib/gracefulShutdown";

/**
 * Сторож: заменяемый экземпляр уходит КОДОМ 0.
 *
 * Повод 30.09–01.10.2026: Railway прислал «Deploy Crashed!» на каждую из пяти
 * выкаток, хотя в истории все деплои SUCCESS и /health отвечал новым коммитом.
 * Гас старый экземпляр: обработчика SIGTERM не было, и штатная замена читалась
 * платформой как авария. Опасность не в письмах, а в привычке их не читать —
 * настоящее падение утонуло бы среди ложных.
 *
 * Проверяется НАСТОЯЩАЯ функция завершения с подставными сервером и пулом:
 * порядок (сервер → пул → выход), код выхода и то, что ненулевого кода не будет
 * ни при одной ветви.
 *
 * 🔴 КАК ПРОВЕРИТЬ НА ПРОДЕ, и это неочевидно. Выкатка, которая ПРИВЕЗЁТ этот
 * обработчик, письмо «Deploy Crashed!» всё равно пришлёт: при замене гасится СТАРЫЙ
 * экземпляр, а в нём обработчика ещё нет. Правда видна только на СЛЕДУЮЩЕЙ выкатке
 * после неё — там гасится уже экземпляр с обработчиком. Поправку назвало окно
 * оркестратора 01.10.2026; я сперва написал «правда = выкатка без письма» и был неправ
 * на один цикл. Класс общий: починку ЗАВЕРШЕНИЯ всегда проверяет следующий цикл, а не
 * тот, который её привёз.
 */

function стенд(опции: { пулПадает?: boolean; серверСОшибкой?: boolean } = {}) {
  const порядок: string[] = [];
  const коды: number[] = [];
  let обратныйСервера: ((e?: Error) => void) | null = null;
  const журнал = { log: vi.fn(), warn: vi.fn(), error: vi.fn() };
  let сработалТаймер: (() => void) | null = null;

  const цель = {
    сервер: {
      close(обратно: (e?: Error) => void) {
        порядок.push("сервер");
        обратныйСервера = обратно;
      },
    },
    закрытьПул: async () => {
      порядок.push("пул");
      if (опции.пулПадает) throw new Error("пул не отпустил соединения");
    },
    выход: (код: number) => {
      порядок.push("выход");
      коды.push(код);
    },
    журнал,
    пределМс: 50,
    таймер: (обратно: () => void) => {
      сработалТаймер = обратно;
      return { unref: () => {} };
    },
  };

  return {
    цель,
    порядок,
    коды,
    журнал,
    закрытьСервер: () => обратныйСервера?.(опции.серверСОшибкой ? new Error("уже закрыт") : undefined),
    выдержать: () => сработалТаймер?.(),
  };
}

describe("замена экземпляра", () => {
  test("порядок: сервер, затем пул, затем выход нулём", async () => {
    const с = стенд();
    обработчикЗавершения(с.цель)("SIGTERM");
    expect(с.порядок, "сервер должен закрываться первым").toEqual(["сервер"]);
    с.закрытьСервер();
    await new Promise((r) => setImmediate(r));
    expect(с.порядок).toEqual(["сервер", "пул", "выход"]);
    expect(с.коды, "код выхода обязан быть 0: замена — не авария").toEqual([0]);
  });

  test("пул не закрылся — всё равно код 0, но в журнале ошибка", async () => {
    const с = стенд({ пулПадает: true });
    обработчикЗавершения(с.цель)("SIGTERM");
    с.закрытьСервер();
    await new Promise((r) => setImmediate(r));
    expect(с.коды, "ненулевой код превратил бы замену в «Crashed»").toEqual([0]);
    expect(с.журнал.error, "отказ пула обязан быть слышен").toHaveBeenCalled();
  });

  test("сервер не закрылся за предел — выходим нулём, не зависаем", () => {
    const с = стенд();
    обработчикЗавершения(с.цель)("SIGTERM");
    с.выдержать();
    expect(с.коды, "по пределу тоже 0").toEqual([0]);
    expect(с.журнал.warn, "про предел надо предупредить").toHaveBeenCalled();
  });

  test("второй сигнал не запускает второе закрытие", async () => {
    const с = стенд();
    const о = обработчикЗавершения(с.цель);
    о("SIGTERM");
    о("SIGINT");
    с.закрытьСервер();
    await new Promise((r) => setImmediate(r));
    // Считать надо ОБА действия. Сперва я проверял только пул — и мутация «снять
    // защиту от повторного сигнала» прошла незаметно: второй сигнал закрывает сервер
    // ещё раз, а пул всё равно закрывался один, потому что обратный вызов в стенде
    // один. Ветви различает именно счёт закрытий СЕРВЕРА.
    expect(с.порядок.filter((ш) => ш === "сервер"), "сервер закрывается один раз").toHaveLength(1);
    expect(с.порядок.filter((ш) => ш === "пул"), "пул закрывается один раз").toHaveLength(1);
    expect(с.журнал.log, "про повторный сигнал надо сказать в журнал").toHaveBeenCalledWith(
      "[SIGINT] завершение уже идёт",
    );
    expect(с.коды).toEqual([0]);
  });

  test("подписаны ОБА сигнала", () => {
    const подписки: string[] = [];
    const с = стенд();
    зарегистрироватьЗавершение({ on: (с2: string) => подписки.push(с2) }, с.цель);
    expect(подписки.sort(), "без SIGTERM платформа читает замену как аварию").toEqual([
      "SIGINT",
      "SIGTERM",
    ]);
  });

  test("index.ts действительно подписывает процесс", () => {
    // ⚠️ Это проверка ТЕКСТА, и она слабее остальных: импортировать index.ts нельзя,
    // он поднимает сервер и занимает порт. Держим её рядом с поведенческими, чтобы
    // поймать самый тупой случай — связку удалили. Правду про прод даёт выкатка без
    // письма «Crashed».
    const src = readFileSync(join(__dirname, "..", "src", "index.ts"), "utf8");
    expect(src, "связка завершения пропала из index.ts").toContain("зарегистрироватьЗавершение(process");
    expect(src, "закрытие пула должно идти безопасной функцией").toContain("закрытьПулЕслиОткрыт");
  });
});
