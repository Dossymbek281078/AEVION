import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";

/* Голосовой комментатор не выдаёт наружу устройство системы. 13.08.2026.
 *
 * Эти ручки ходят в языковую модель и в синтез речи. Сообщения таких сервисов
 * содержат чужое устройство: адрес апстрима, имя провайдера, подробности
 * запроса, иногда кусок ключа в тексте отказа. Раньше это уходило вызывающему
 * в поле `message` — шесть мест.
 *
 * Ведущему нужно знать, ЧТО чинить, а не как устроен наш бэкенд, поэтому
 * наружу едет категория, а полный текст остаётся в логе и в capture().
 *
 * Проверка по исходнику, а не прогоном: ручки требуют внешних сервисов и
 * секретов, поднимать их ради этого нечестно — и об этом сказано прямо, чтобы
 * следующий не принял текстовую проверку за поведенческую.
 */

const SRC = "src/routes/cyberchessVoiceCoach.ts";
const src = readFileSync(SRC, "utf8");

describe("ответы не содержат текста ошибок внешних сервисов", () => {
  test("сообщение апстрима не кладётся в ответ", () => {
    // Ищем именно подстановку в ответ; чтение .message внутри классификатора
    // законно и остаётся.
    expect(src).not.toMatch(/message:\s*\(err as Error\)\?\.message/);
    expect(src).not.toMatch(/detail:\s*errText/);
  });

  test("вместо текста отдаётся категория", () => {
    expect(src).toMatch(/function upstreamErrorKind/);
    expect(src).toMatch(/reason:\s*upstreamErrorKind\(err\)/);
  });

  test("категории покрывают то, ради чего смотрят в ошибку", () => {
    // Пустая категория бесполезна: по ней нельзя понять, чинить сеть, ключ или
    // квоту. Проверяем, что различия есть.
    for (const kind of ["timeout", "upstream_unreachable", "upstream_auth", "upstream_rate_limited", "upstream_quota"]) {
      expect(src).toContain(kind);
    }
  });
});
