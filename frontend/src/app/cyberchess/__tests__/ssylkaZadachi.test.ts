import { describe, it, expect } from "vitest";
import { reshenieVozvrata } from "../ssylkaZadachi";

/*
 * 🔴 Решение «возвращать ли задачу, которую просил адрес» — проверяется вызовами с
 * заранее известным ответом.
 *
 * ПОВОД. 07.10 я нашёл один путь подмены задачи по ссылке, закрыл его и доложил
 * «починено». Проверка окна 10 браузером на проде 08.10: ссылка по-прежнему
 * открывает чужую задачу — ждали ★678, на экране ★1882; ждали ★877, на экране
 * ★1152. Числа каждый раз РАЗНЫЕ, то есть подменяет случайный подбор, но какой
 * именно установщик успевает это сделать, найти не удалось: их в модуле больше
 * десяти. Поэтому мера оборонительная — задача возвращается на доску, кто бы её ни
 * сместил.
 *
 * Почему проверка здесь, а не в эффекте: эффект живёт в странице на 16 тысяч строк,
 * и вызовами с известным ответом его не проверить. Вторую НЕПРОВЕРЕННУЮ починку
 * ссылки отдавать нельзя — один раз это уже стоило ложного обещания на канале.
 *
 * ⚠️ Что эта проверка НЕ доказывает: что на живой странице ссылка теперь открывает
 * свою задачу. Это проверяется только браузером на проде — командой окна 10 с
 * флагом --фронт, и до её зелёного ответа «починено» говорить нельзя.
 */

const ЦЕЛЬ = { fen: "6k1/5ppp/8/8/8/8/5PPP/R5K1 w - - 0 1", попытки: 0, доМс: 10_000 };

describe("возврат задачи, которую просил адрес", () => {
  it("на доске чужая задача, окно открыто → вернуть", () => {
    const р = reshenieVozvrata(ЦЕЛЬ, "другая/позиция w - - 0 1", 5_000, true);
    expect(р.действие, р.причина).toBe("вернуть");
  });

  it("на доске та самая задача → ничего не делать", () => {
    const р = reshenieVozvrata(ЦЕЛЬ, ЦЕЛЬ.fen, 5_000, true);
    expect(р.действие, р.причина).toBe("ничего");
  });

  it("ссылки не было → ничего не делать", () => {
    expect(reshenieVozvrata(null, "любая", 5_000, true).действие).toBe("ничего");
  });

  it("на доске пока ничего → ничего не делать, а НЕ возвращать", () => {
    // Иначе возврат сработает до того, как страница вообще поставила задачу, и
    // попытка сгорит впустую.
    expect(reshenieVozvrata(ЦЕЛЬ, null, 5_000, true).действие).toBe("ничего");
  });

  it("🔴 окно истекло → сдаться, даже если на доске чужая задача", () => {
    // Без ограничения по времени это война эффектов: человек нажимает «другая
    // задача», а она возвращается. Лечение не должно быть хуже болезни.
    const р = reshenieVozvrata(ЦЕЛЬ, "другая", 10_001, true);
    expect(р.действие, р.причина).toBe("сдаться");
  });

  it("🔴 попытки исчерпаны → сдаться", () => {
    const р = reshenieVozvrata({ ...ЦЕЛЬ, попытки: 3 }, "другая", 5_000, true);
    expect(р.действие, р.причина).toBe("сдаться");
  });

  it("🔴 запрошенной задачи нет в пуле → сдаться с ИМЕННО этой причиной", () => {
    // Причина важна: по ней эффект показывает человеку сообщение. Молчать нельзя —
    // иначе он видит чужую задачу и не знает почему.
    const р = reshenieVozvrata(ЦЕЛЬ, "другая", 5_000, false);
    expect(р.действие).toBe("сдаться");
    expect(р.причина).toBe("запрошенной задачи нет в текущем пуле");
  });

  it("КОНТРОЛЬ: решение РАЗЛИЧАЕТ случаи, а не возвращает одно и то же", () => {
    // Без этого все проверки выше прошли бы и у функции, отвечающей константой.
    const все = new Set([
      reshenieVozvrata(ЦЕЛЬ, "другая", 5_000, true).действие,
      reshenieVozvrata(ЦЕЛЬ, ЦЕЛЬ.fen, 5_000, true).действие,
      reshenieVozvrata(ЦЕЛЬ, "другая", 10_001, true).действие,
    ]);
    expect(все.size, `решение вернуло ${все.size} разных действий из 3`).toBe(3);
  });

  it("КОНТРОЛЬ: порядок проверок — истёкшее окно сильнее отсутствия в пуле", () => {
    // Оба случая ведут к «сдаться», но причина у них разная, и по причине эффект
    // решает, показывать ли человеку сообщение. Если порядок перепутать, человек
    // получит сообщение про фильтры там, где просто истекло время.
    const р = reshenieVozvrata(ЦЕЛЬ, "другая", 10_001, false);
    expect(р.причина).toBe("окно возврата истекло");
  });
});
