import { describe, it, expect } from "vitest";
import { уженеПредлагать } from "../cyberchess/page";

/**
 * Предложение оставить адрес после партии — единственное место, где
 * бесплатный магнит CyberChess вообще спрашивает адрес. Instagram даёт туда
 * самый большой поток (347 визитов за 14 дней на 30.09.2026), и заметная его
 * часть открывает ссылку во ВСТРОЕННОМ браузере соцсети или в приватном окне,
 * где localStorage бросает при чтении.
 *
 * До 30.09.2026 код читал отметку так: `catch { return; }` — то есть
 * «хранилище недоступно, не показывать никогда». Снаружи это неотличимо от
 * «человек не захотел»: молчаливый отказ, выглядящий как успех.
 *
 * Тест держит обе стороны: отметка стоит — не предлагаем (иначе будем
 * надоедать каждому); хранилище бросает или пусто — предлагаем.
 */
describe("предложение адреса после партии", () => {
  it("отметка стоит — второй раз не предлагаем", () => {
    expect(уженеПредлагать({ getItem: () => "1" })).toBe(true);
  });

  it("отметки нет — предлагаем", () => {
    expect(уженеПредлагать({ getItem: () => null })).toBe(false);
  });

  it("🔴 хранилище БРОСАЕТ — всё равно предлагаем, а не молчим", () => {
    const приватноеОкно = {
      getItem: () => {
        throw new DOMException("The operation is insecure.", "SecurityError");
      },
    };
    expect(
      уженеПредлагать(приватноеОкно),
      "в приватном окне форма не показывалась никогда — адрес терялся молча",
    ).toBe(false);
  });

  it("хранилища нет вовсе (сервер) — предлагаем", () => {
    expect(уженеПредлагать(undefined)).toBe(false);
  });
});
