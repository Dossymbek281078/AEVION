import { describe, it, expect, vi, beforeEach } from "vitest";

/**
 * Упавшее чтение прав превращается в «не знаю», а не в «не куплено».
 *
 * Вторая половина находки 02.09.2026. Первую (гейт обязан отвечать «не смог
 * проверить», а не «купите тариф») стережёт `gateSaysCheckFailedNotUpgrade`,
 * но тот тест ПОДМЕНЯЕТ этот модуль целиком — значит про само превращение
 * `null → "unknown"` он не утверждает ничего.
 *
 * Проверено на себе: мутация `return "unknown"` → `return "none"` тем
 * сторожем НЕ ловится, и «не поймана» там означает «мутация до теста не
 * доходит», а не «сторож пуст». Поэтому здесь модуль настоящий, а падает
 * запрос к базе.
 */

let ронятьЗапрос = true;

/**
 * Подменяем ОБА звена: и пул, и создание таблицы.
 *
 * Первая редакция подменяла только пул — и контроль немедленно показал, что
 * «успешный пустой ответ» тоже даёт «не знаю». Причина: путь идёт через
 * `ensureAppSubscriptionTable(pool)` ДО запроса, и он уходил к настоящей
 * базе. То есть тест мерил не код, а отсутствие базы в прогоне, и первое
 * утверждение проходило бы при любой реализации.
 */
vi.mock("../src/lib/dbPool", () => ({
  getPool: () => ({
    query: async () => {
      if (ронятьЗапрос) throw new Error("база недоступна");
      return { rows: [] };
    },
  }),
}));

vi.mock("../src/lib/ensureAppSubscriptionTable", () => ({
  ensureAppSubscriptionTable: async () => {},
}));

// eslint-disable-next-line import/first
import { appSubscriptionState } from "../src/lib/appEntitlements";

describe("сбой чтения прав не выдаётся за отсутствие прав", () => {
  beforeEach(() => { ронятьЗапрос = true; });

  it("упавший запрос даёт «не знаю»", async () => {
    const s = await appSubscriptionState("kto@to.example", "devhub");
    expect(
      s,
      "сбой базы превращён в «не куплено» — заплативший получит отказ как приговор",
    ).toBe("unknown");
  });

  it("контроль: успешный пустой ответ даёт «не куплено», а не «не знаю»", async () => {
    // Без этого контроля проверка выше проходила бы и в случае, когда
    // функция ВСЕГДА отвечает «не знаю» — то есть охраняла бы пустоту.
    ронятьЗапрос = false;
    const s = await appSubscriptionState("kto@to.example", "devhub");
    expect(s, "честное «не куплено» подменено на «не знаю»").toBe("none");
  });

  it("без почты спрашивать нечего — «не куплено» без обращения к базе", async () => {
    ронятьЗапрос = true; // если бы обращение было, вернулось бы «не знаю»
    const s = await appSubscriptionState(null, "devhub");
    expect(s).toBe("none");
  });
});
