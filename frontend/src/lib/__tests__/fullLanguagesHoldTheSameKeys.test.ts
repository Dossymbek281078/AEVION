import { describe, test, expect } from "vitest";
import { translations } from "../i18n-all";

/**
 * У ТРЁХ ПОЛНЫХ ЯЗЫКОВ ОДИН И ТОТ ЖЕ НАБОР КЛЮЧЕЙ.
 *
 * Живой повод, 17.09.2026. В казахском словаре не хватало 41 ключа: 37 кнопок
 * `common.*` (сохранить, отправить, удалить, кошелёк…) и четыре строки
 * `constitution.pay.*`. Казахский пользователь видел эти надписи ПО-АНГЛИЙСКИ.
 *
 * 🔴 Почему это не поймал ни один существующий сторож — и в этом вся ценность
 * записи. Резолвер устроен как `peekDict(lang)?.[key] || en[key] || key`:
 * пропуск не падает, не пишет в журнал и не даёт сырого ключа на экране. Он
 * ТИХО ОТКАТЫВАЕТСЯ на английский. Проверка, которая смотрит на ошибки, здесь
 * слепа по устройству: ошибок нет. Нашлось это сравнением счётчиков
 * (7426 против 7385), то есть вопросом «сколько», а не вопросом «что сломалось».
 *
 * Чем этот сторож отличается от соседей, чтобы не плодить второй способ:
 *   • `i18n-split.test.ts` сверяет LANG_KEY_COUNT со словарём — то есть число
 *     с самим собой. Оно честно совпадало и при 7385: пропуск был УЧТЁН.
 *   • `langCoverage.test.ts` считает проценты поверх того же числа и называет
 *     язык «usable» — при 99.4 % он и должен был молчать.
 *   • Здесь спрашивается другое: СОВПАДАЮТ ЛИ НАБОРЫ. На этот вопрос ни один
 *     из них не отвечает.
 *
 * Про пустые значения сторож намеренно молчит. В kk их три (` entry`, `The `,
 * `s`), в ru — два, и это НЕ пропуски: части фразы вокруг подставляемого
 * значения, которых в другом языке не бывает. Требовать непустоту значило бы
 * ломать сборку фразы ради красивого счёта.
 */

/** Языки, которые витрина предлагает как полноценные (langCoverage: usable). */
const FULL = ["ru", "en", "kk"] as const;

/**
 * Подстановки, которые обязаны исчезать при переводе, — английская грамматика,
 * а не значение. Место вызова подставляет в них окончание множественного числа:
 * `AutopilotStatement.tsx` передаёт `ms: stats.manualFreezes === 1 ? "" : "s"`,
 * `ReferralsPanel.tsx` — то же для `plural`. В русском и казахском множественное
 * число так не строится, поэтому «1 заморозка / 5 заморозок» пишется формой
 * слова, и связки в переводе просто нет.
 *
 * Требовать их наличия значило бы заставить переводчика вставлять в казахскую
 * фразу английский суффикс — сторож толкал бы к худшему тексту. Значащие
 * подстановки ({count}, {n}, {tier}, {manual}…) под это исключение НЕ попадают:
 * их потеря показывает фразу без числа, и тест ниже за этим следит.
 */
const GRAMMAR_HELPERS = new Set(["{plural}", "{ms}", "{as}", "{us}"]);

function keysOf(lang: (typeof FULL)[number]): Set<string> {
  return new Set(Object.keys(translations[lang] as Record<string, string>));
}

describe("полные языки держат один набор ключей", () => {
  test("КОНТРОЛЬ прибора: словари на месте и непустые", () => {
    // Ноль ключей прошёл бы все проверки ниже: пустое равно пустому.
    for (const lang of FULL) {
      expect(keysOf(lang).size, lang).toBeGreaterThan(7000);
    }
  });

  test("в казахском есть каждый ключ английского", () => {
    const en = keysOf("en");
    const kk = keysOf("kk");
    const missing = [...en].filter((k) => !kk.has(k));

    expect(
      missing,
      "этих надписей в казахском нет — человек увидит их по-английски, " +
        "и ни один сторож по ошибкам этого не заметит",
    ).toEqual([]);
  });

  test("в русском есть каждый ключ английского и наоборот", () => {
    const en = keysOf("en");
    const ru = keysOf("ru");
    expect([...en].filter((k) => !ru.has(k)), "нет в ru").toEqual([]);
    expect([...ru].filter((k) => !en.has(k)), "нет в en").toEqual([]);
  });

  test("в казахском нет ключей, которых нет у остальных", () => {
    // Обратная сторона: разница счётчиков направления не называет. «Короче на
    // 41» могло означать «не хватает 45, а четыре лишних» — и лишний ключ это
    // мёртвый перевод, который никто никогда не покажет.
    const en = keysOf("en");
    const extra = [...keysOf("kk")].filter((k) => !en.has(k));

    expect(extra, "эти ключи есть только в казахском — их никто не прочитает").toEqual([]);
  });

  test("значащие подстановки переживают перевод", () => {
    // Перевод, потерявший {tier} или {count}, не падает — он показывает фразу
    // без числа или без имени тарифа. Это тот же тихий класс, что и пропуск ключа.
    const en = translations.en as Record<string, string>;
    const withPlaceholders = Object.keys(en).filter((k) => /\{[a-zA-Z0-9_]+\}/.test(en[k] ?? ""));
    expect(withPlaceholders.length, "КОНТРОЛЬ: ключи с подстановками вообще есть").toBeGreaterThan(10);

    const broken: string[] = [];
    for (const lang of FULL) {
      const dict = translations[lang] as Record<string, string>;
      for (const key of withPlaceholders) {
        const source = en[key] ?? "";
        const target = dict[key];
        if (typeof target !== "string" || target === "") continue;
        for (const ph of source.match(/\{[a-zA-Z0-9_]+\}/g) ?? []) {
          if (GRAMMAR_HELPERS.has(ph)) continue;
          if (!target.includes(ph)) broken.push(`${lang} ${key} :: потеряна ${ph}`);
        }
      }
    }
    expect(broken, "подстановка исчезла при переводе — фраза покажется без значения").toEqual([]);
  });

  test("список грамматических связок не мёртвый: каждая ещё встречается в английском", () => {
    // Исключение, которому нечего исключать, застывает и прикрывает будущий
    // дефект: связку переименуют, а сторож продолжит молчать про старое имя.
    const en = translations.en as Record<string, string>;
    const used = new Set<string>();
    for (const value of Object.values(en)) for (const ph of value.match(/\{[a-zA-Z0-9_]+\}/g) ?? []) used.add(ph);

    const dead = [...GRAMMAR_HELPERS].filter((ph) => !used.has(ph));
    expect(dead, "этих связок больше нет в английском — уберите их из GRAMMAR_HELPERS").toEqual([]);
  });
});
