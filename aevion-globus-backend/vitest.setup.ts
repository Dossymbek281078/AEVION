/**
 * Общая подготовка для ВСЕХ тестов бэкенда.
 *
 * Дедупликация вебхуков (lib/webhookDedup) намеренно переживает перезапуск —
 * платёжные кассы доставляют события «хотя бы один раз», и без постоянного
 * хранилища повтор после падения выдал бы покупку дважды.
 *
 * У тестов от этого появляется неочевидная беда: файл по умолчанию лежит в
 * data/webhook-dedup.jsonl рабочего каталога, один на все прогоны. 18.08.2026
 * это дало 8 падений подряд в четырёх файлах — обработчик честно отвечал
 * «уже видели» на события, которые тест отправлял впервые за сегодня, но не
 * впервые за неделю. Хуже того, на чистой машине набор был зелёным: проверки
 * молча проходили, ничего не проверяя.
 *
 * Здесь каждый прогон получает свой файл во временном каталоге. Тест, которому
 * нужно проверить саму дедупликацию, по-прежнему может задать
 * WEBHOOK_DEDUP_FILE сам — своё значение мы не перетираем.
 */
import { mkdtempSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";

if (!process.env.WEBHOOK_DEDUP_FILE) {
  process.env.WEBHOOK_DEDUP_FILE = join(
    mkdtempSync(join(tmpdir(), "aevion-webhook-dedup-")),
    "webhook-dedup.jsonl",
  );
}
