import { describe, test, expect } from "vitest";
import { lemonSqueezySellable } from "../src/data/lemonSqueezyVariants";
import { TIERS } from "../src/data/pricing";

/**
 * Тариф с НАЗНАЧЕННОЙ ценой обязан иметь способ его купить.
 *
 * Замер 13.09.2026. Тариф `pro` (на витрине он называется «Universe») стоит
 * $149/мес и $1490/год — это флагман платформы. Ссылки на товар у него нет
 * вовсе: в списке товаров есть lite/medium/full/planet, а `tier_pro_*` нет.
 *
 * Чем это плохо на экране. Кнопка гасится проверкой «нет ли ссылки в списке
 * НЕдоступных» (`sellable.missing`). Ссылки `tier_pro_monthly` нет ни в
 * доступных, ни в недоступных — её нет в справочнике вообще, — поэтому
 * проверка отвечает «продаётся», кнопка остаётся живой, а касса отвечает 503.
 * Проверка ловит «ссылка есть, но не настроена» и слепа к «ссылки нет вовсе».
 *
 * Enterprise так не страдает: у него цена не назначена (null), и интерфейс
 * ведёт его отдельной веткой на «связаться». Различает именно ЦЕНА.
 *
 * БАЗОВАЯ ЛИНИЯ, и почему она такая. Сторож, красный с рождения, приучает
 * себя не читать, поэтому известный случай записан в список ниже. Но список
 * разрешено только СОКРАЩАТЬ: сторож краснеет, если непокупаемым станет ещё
 * какой-то тариф, и НЕ краснеет, когда `pro` починят. Иначе сторож ругался бы
 * на собственную починку.
 */
const ИЗВЕСТНЫЕ_БЕЗ_КАССЫ = new Set(["pro"]);

function безКассы(): string[] {
  const { configured, missing } = lemonSqueezySellable();
  const ссылки = [...configured, ...missing];
  const тарифыСоСсылкой = new Set(
    ссылки.filter((r) => r.startsWith("tier_")).map((r) => r.slice("tier_".length).replace(/_(monthly|annual)$/, ""))
  );
  return TIERS.filter((t) => typeof t.priceMonthly === "number" && (t.priceMonthly as number) > 0)
    .map((t) => t.id as string)
    .filter((id) => !тарифыСоСсылкой.has(id));
}

describe("тариф с ценой обязан быть покупаемым", () => {
  test("проверка не пуста: цены и ссылки на месте", () => {
    // Без этого «нарушений ноль» означало бы «нечего проверять».
    const сЦеной = TIERS.filter((t) => typeof t.priceMonthly === "number" && (t.priceMonthly as number) > 0);
    const { configured, missing } = lemonSqueezySellable();
    expect(сЦеной.length, "тарифов с ценой нет — сторож ничего не проверяет").toBeGreaterThanOrEqual(4);
    expect([...configured, ...missing].length, "справочник товаров пуст").toBeGreaterThanOrEqual(10);
  });

  test("новых тарифов без кассы не появилось", () => {
    const новые = безКассы().filter((id) => !ИЗВЕСТНЫЕ_БЕЗ_КАССЫ.has(id));
    expect(новые, "у тарифа с назначенной ценой не стало способа его купить").toEqual([]);
  });

  test("известный случай всё ещё описан верно", () => {
    const сейчас = безКассы();
    // Сокращение списка — это ПОЧИНКА, и ронять на ней прогон нельзя.
    // Поэтому проверяется только то, что известный случай не исчез молча
    // из самих данных: если pro перестал быть тарифом с ценой, список надо
    // пересмотреть осознанно.
    const proЕстьИСЦеной = TIERS.some((t) => t.id === "pro" && typeof t.priceMonthly === "number");
    expect(proЕстьИСЦеной, "тариф pro исчез или лишился цены — пересмотрите базовую линию").toBe(true);
    expect(сейчас.length, "базовая линия описывает больше случаев, чем есть").toBeLessThanOrEqual(ИЗВЕСТНЫЕ_БЕЗ_КАССЫ.size);
  });
});
