import { describe, test, expect } from "vitest";
// @ts-expect-error — скрипты аудита на .mjs без типов, тип здесь не нужен
import { median } from "../scripts/lib/stats.mjs";

/**
 * Медиана из отчёта о слепых высотах. Проверяется не ради арифметики: именно
 * этой функцией получено «медиана жилых домов Астаны 33.6 м» — число, которое
 * ушло в записку основателю и в разбор по безопасности. Чётная ветка (80
 * известных высот) до 12.08.2026 не была покрыта ничем.
 */
describe("median", () => {
  test("нечётная длина — средний элемент, порядок входа не важен", () => {
    expect(median([3, 1, 2])).toBe(2);
    expect(median([10])).toBe(10);
  });

  test("чётная длина — среднее двух средних, округление до 0.1", () => {
    expect(median([1, 2, 3, 4])).toBe(2.5);
    // ветка, которой посчитаны 33.6 м: среднее даёт длинный хвост
    expect(median([33.2, 34.1])).toBe(33.7);
    expect(median([1, 2])).toBe(1.5);
  });

  test("пустой вход — null, а не 0: «нет данных» и «ноль метров» разные ответы", () => {
    expect(median([])).toBeNull();
  });

  test("исходный массив не мутируется — его считают дальше по отчёту", () => {
    const xs = [5, 1, 3];
    median(xs);
    expect(xs).toEqual([5, 1, 3]);
  });
});
