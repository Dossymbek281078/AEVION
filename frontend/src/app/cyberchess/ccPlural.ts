/**
 * Русское склонение по числу: 1 задача, 2 задачи, 5 задач.
 *
 * Вынесено из page.tsx 29.08.2026, когда нашлись ДВА места, где склоняли
 * вручную и ошибались:
 *   «тем{n === 1 ? "а" : "ы"}»  → при пяти давало «5 темы»
 *   «ход{n === 1 ? "" : "ов"}»  → при двух давало «2 ходов»
 *
 * Ошибку видит тот, у кого число дошло до второго десятка, — то есть самый
 * прилежный игрок. Поэтому способ склонять должен быть один на модуль.
 */
export function ccPlural(n: number, one: string, few: string, many: string): string {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b > 1 && b < 5) return few;
  if (b === 1) return one;
  return many;
}
