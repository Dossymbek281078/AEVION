/**
 * Картинки товаров для разметки поисковика — ОДИН источник.
 *
 * 🔴 ЗАЧЕМ. У Google `image` — обязательное поле Product: без него товар не
 * попадает в товарный блок выдачи вовсе, то есть вся разметка цены и наличия
 * работает вхолостую. Поиск — единственный наш канал, который заводится без
 * чужих логинов и без публикаций, поэтому цена поля прямая.
 *
 * 🔴 ЧЕГО ЗДЕСЬ НЕТ И НЕ БУДЕТ. Выдуманных картинок. Правило Google — «картинка
 * обязана представлять размеченное содержимое»; поставить вместо обложки наш
 * логотип или кадр чужой страницы значит пообещать в выдаче то, чего человек не
 * получит. Замер 12.10.2026 по кассе: своя обложка есть у протокола долголетия
 * (600×600) и у книги Gratitude (1005×1596); у «Анти-седины» в обеих языковых
 * версиях на странице товара лежит только НАШ АВАТАР (400×400 глобус AEVION),
 * то есть обложки нет. Этим двум товарам картинка не ставится, и они просто не
 * получат товарный блок — пока не нарисована настоящая обложка.
 *
 * Файлы лежат у нас, а не ссылками в кассу: адрес у поставщика живёт до первой
 * перезаливки, а битая картинка в выдаче хуже отсутствующей.
 */

export const САЙТ_КАРТИНОК = "https://aevion.app";

/** Обложка книги «Gratitude ∞ Forever Young» — одна на все её варианты. */
const ОБЛОЖКА_КНИГИ = "/covers/gratitude-forever-young.png";

/**
 * id товара витрины → путь картинки. Товара нет в карте — картинки нет, и это
 * честный ответ, а не недоработка.
 */
export const КАРТИНКИ_ТОВАРОВ: Readonly<Record<string, string>> = {
  // Протокол долголетия — своя обложка.
  oijxmq: "/covers/protokol-dolgoletiya.png",
  // Три варианта ОДНОЙ книги: обложка у них общая по существу, и это не
  // подмена — в пакет входит та же книга, что на обложке.
  orcfbo: ОБЛОЖКА_КНИГИ,
  lelzw: ОБЛОЖКА_КНИГИ,
  ghvzq: ОБЛОЖКА_КНИГИ,
};

/** Полный адрес картинки товара или null, если настоящей картинки нет. */
export function kartinkaTovara(id: string): string | null {
  const путь = КАРТИНКИ_ТОВАРОВ[id];
  return путь ? `${САЙТ_КАРТИНОК}${путь}` : null;
}

/**
 * Страница приложения — источник его картинки.
 *
 * У каждой страницы модуля есть своя `opengraph-image`: Next рисует её из
 * настоящих данных страницы. Это и есть картинка, представляющая товар, —
 * в отличие от общего логотипа.
 *
 * Ключ — slug из STANDALONE_APPS, значение — адрес страницы. Карта нужна
 * потому, что slug и адрес совпадают не всегда (ip_bureau живёт на /bureau).
 * Сторож kartinkiTovarov.guard проверяет, что у КАЖДОЙ записи страница и файл
 * картинки существуют: мёртвый адрес в разметке — обещание, которого нет.
 */
export const СТРАНИЦЫ_ПРИЛОЖЕНИЙ: Readonly<Record<string, string>> = {
  cyberchess: "/cyberchess",
  multichat: "/multichat-engine",
  qventure: "/qventure",
  ip_bureau: "/bureau",
  devhub: "/devhub",
  qright: "/qright",
  qsign: "/qsign",
  startup_exchange: "/startup-exchange",
  qskyway: "/qskyway",
};

/** Картинка приложения по его slug или null. */
export function kartinkaPrilozheniya(slug: string): string | null {
  const стр = СТРАНИЦЫ_ПРИЛОЖЕНИЙ[slug];
  return стр ? `${САЙТ_КАРТИНОК}${стр}/opengraph-image` : null;
}
