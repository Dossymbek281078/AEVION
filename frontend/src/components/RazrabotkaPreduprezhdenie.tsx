"use client";

import { useI18nOptional } from "@/lib/i18n";

/**
 * Честное предупреждение: платформа в активной разработке.
 *
 * 🔴 ПРЯМОЕ СЛОВО ОСНОВАТЕЛЯ 12.10.2026. Смысл дословно: AEVION в активной
 * разработке, возможны технические сбои; мы их исправляем, а время, когда
 * платная функция не работала ПО НАШЕЙ ВИНЕ, компенсируем продлением подписки.
 *
 * ПОЧЕМУ НЕ МЕЛКИМ ШРИФТОМ В ПОДВАЛЕ. Человек должен прочесть это ДО оплаты, а
 * не после: предупреждение, найденное после списания, читается как отговорка, и
 * оно хуже отсутствующего. Поэтому блок ставится рядом с кнопками покупки, на
 * экранах «входит в подписку» и на странице после оплаты.
 *
 * ПОЧЕМУ ОБЕЩАНИЕ ИМЕННО «ПРОДЛИМ НА ВРЕМЯ ПРОСТОЯ», а не проценты и не возврат
 * денег: продление мы можем исполнить своими руками в любой день, а возврат —
 * это касса, сроки и решение человека. Обещание, которое нельзя исполнить
 * тихо и сразу, на продающей странице не пишется.
 *
 * Адрес — data@aevion.app: его читаемость подтверждена замером (окно продаж,
 * 12.10). Второй адрес здесь не заводится: ящик, в который никто не смотрит,
 * хуже отсутствия адреса.
 */

export const ADRES_PODDERZHKI = "data@aevion.app";

type Вид = "строка" | "блок";

export function RazrabotkaPreduprezhdenie({
  вид = "блок",
  отступСверху = 12,
}: {
  /** «блок» — рамка рядом с кнопкой покупки; «строка» — одна строка под плашкой. */
  вид?: Вид;
  отступСверху?: number;
}) {
  const i18n = useI18nOptional();
  const tr = (key: string, ru: string): string => (i18n ? i18n.t(key) : ru);

  const текст = tr(
    "razrabotka.notice",
    "AEVION в активной разработке: возможны технические сбои. Мы их исправляем, а время, когда платная функция не работала по нашей вине, компенсируем продлением подписки.",
  );
  const напишите = tr("razrabotka.write", "Напишите на");

  /*
   * Корень — span с display:block, а не div и не p. Плашка модуля
   * (ModulePricingChip) сама отрисована как <span>, и блочный потомок внутри
   * строчного элемента — невалидная разметка: браузер её «чинит» разрывом
   * узла, и на части из сорока страниц вёрстка поехала бы молча. span ведёт
   * себя одинаково и внутри строки, и в блоке.
   */
  if (вид === "строка") {
    // 144 (18.10.2026): на телефоне (≤768, globals.css) полный текст занимал 4–5 строк первого экрана на 40+ страницах
    // модулей; там он свёрнут в <details> — одна строка, полный текст и адрес одним нажатием. На десктопе — как был.
    // Оба варианта в разметке: решает CSS, без matchMedia и расхождения серверной и клиентской отрисовки.
    const кратко = tr("razrabotka.kratko", "AEVION в активной разработке — подробнее");
    const полный = (
      <>
        {текст}{" "}
        {напишите}{" "}
        <a href={`mailto:${ADRES_PODDERZHKI}`} style={{ color: "#92400e", fontWeight: 700 }}>
          {ADRES_PODDERZHKI}
        </a>
      </>
    );
    return (
      <span style={{ display: "block", marginTop: отступСверху, fontSize: 12, lineHeight: 1.6, color: "#92400e" }}>
        <span className="aevion-razrabotka-polno">{полный}</span>
        <details className="aevion-razrabotka-kratko">
          <summary style={{ cursor: "pointer", fontWeight: 700 }}>{кратко}</summary>
          <span style={{ display: "block", marginTop: 4 }}>{полный}</span>
        </details>
      </span>
    );
  }

  return (
    <span
      style={{
        display: "block",
        marginTop: отступСверху,
        padding: "10px 12px",
        border: "1px solid #fcd34d",
        borderRadius: 8,
        background: "#fffbeb",
        color: "#92400e",
        fontSize: 13,
        lineHeight: 1.6,
      }}
    >
      {текст}{" "}
      {напишите}{" "}
      <a href={`mailto:${ADRES_PODDERZHKI}`} style={{ color: "#92400e", fontWeight: 700 }}>
        {ADRES_PODDERZHKI}
      </a>
    </span>
  );
}
