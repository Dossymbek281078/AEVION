// Разобранные вручную сомнительные высоты твинов QSkyway.
//
// Твин помечает высоту сомнительной по двум правилам: тег спорит с собственным
// счётом этажей (тогда движок сам берёт счёт этажей — такие случаи закрыты), и
// «towers over the city» — высота в разы выше всей остальной застройки. Второй
// случай движок НЕ переопределяет: сам по себе он не доказывает ошибку, в
// городах действительно бывают одиночные башни.
//
// Значит по каждому такому случаю нужен ответ человека, иначе он живёт в данных
// годами. Так и вышло: расхождение по Абу-Даби Плаза нашли 27.07.2026 скриптом
// `audit-height-claims.mjs`, а 11.08 оно всё ещё было в твине — потому что аудит
// только сообщает и его никто не звал. Здесь ответ фиксируется, а тест
// `qskywayHeightReview.test.ts` не даёт появиться неразобранному случаю.
//
// Что здесь НЕ делается: высота не переписывается. Позиция модуля — «честная
// починка выше по течению, в самом OSM» (см. хвост вывода аудита), и переписать
// чужой источник у себя значит начать вести собственную правду о городе. Здесь
// записано, что мы проверили и что published говорит на самом деле, чтобы
// интерфейс мог назвать расхождение числом, а не только «в 4.66 раза выше».

export interface HeightReview {
  city: string;
  /**
   * Индекс здания в twin.buildings — тот же, что в dataQuality.suspect[].i.
   *
   * Хрупкая привязка, и это осознанно: OSM-идентификатор в твин не едет (в
   * генераторе он лежит в служебном массиве meta, который не отгружается),
   * поэтому индекс — единственная ручка. Пересборка твина его сдвигает: 12.08.2026
   * Абу-Даби Плаза переехала со 195 на 194, когда в bbox добавилось пять зданий.
   * Ровно на этот случай в `qskywayHeightReview.test.ts` стоит проверка, что
   * разбор описывает здание, которое в твине действительно есть, — она и поймала
   * сдвиг в ту же минуту.
   */
  index: number;
  /** элемент OSM, чтобы починку можно было довести до источника */
  osm: string;
  /** что стоит в теге и, соответственно, в твине */
  taggedM: number;
  /** что публикует статья, на которую ссылается сам объект */
  publishedM: number;
  publishedSource: string;
  /** «завышено» — коридор летит выше нужного; «занижено» — опаснее, см. ниже */
  verdict: "overstated" | "understated" | "confirmed";
  reviewedAt: string;
  note: string;
}

export const HEIGHT_REVIEWS: HeightReview[] = [
  {
    city: "astana",
    index: 194,
    osm: "way/486561786",
    taggedM: 382,
    publishedM: 310.8,
    publishedSource: "https://en.wikipedia.org/wiki/Abu_Dhabi_Plaza",
    verdict: "overstated",
    reviewedAt: "2026-08-11",
    note:
      "Абу-Даби Плаза. Тег OSM даёт 382 м при 75 этажах — 5.09 м на этаж, что вдвое выше обычного; "
      + "статья, на которую ссылается сам объект, публикует 310.8 м. Ошибка в безопасную сторону: "
      + "завышенное препятствие стоит крюка, тогда как заниженное означало бы пролёт без запаса. "
      + "Высоту в твине не переписываем — починка принадлежит OSM; здесь зафиксировано, что расхождение "
      + "проверено и на сколько именно.",
  },
];

/**
 * Разбор по городу — сперва по элементу OSM, и только потом по индексу.
 *
 * Индекс живёт до следующей пересборки твина (12.08.2026 Абу-Даби Плаза уехала
 * со 195 на 194, когда в bbox добавилось пять домов), а идентификатор элемента
 * переживает её. С 12.08 твин везёт `osm` в каждой спорной высоте, поэтому
 * привязка по нему — основная, а индекс остался запасной: у старых твинов,
 * пересобранных до этого дня, поля ещё нет.
 */
export function heightReviewFor(city: string, index: number, osm?: string | null): HeightReview | null {
  // Если элемент известен, ответ даёт ТОЛЬКО он. Откат на индекс здесь был бы
  // хуже отсутствия ответа: совпадение номера при несовпадении элемента значит,
  // что под этим номером теперь ДРУГОЕ здание, и разбор Абу-Даби Плаза
  // приклеился бы к чужому дому. Первая версия этой функции так и делала —
  // поймал тест «чужой osm не выдаёт чужой разбор за свой».
  if (osm) return HEIGHT_REVIEWS.find((r) => r.city === city && r.osm === osm) ?? null;
  // Элемента нет — значит твин собран до 12.08.2026, когда `osm` в спорных
  // высотах ещё не отгружался. Тогда индекс остаётся единственной ручкой.
  return HEIGHT_REVIEWS.find((r) => r.city === city && r.index === index) ?? null;
}

/** Все разборы города — в том виде, в каком их удобно приложить к ответу API. */
export function heightReviewsForCity(city: string): HeightReview[] {
  return HEIGHT_REVIEWS.filter((r) => r.city === city);
}
