/*
 * 28.10.2026 (окно «Приложения-2»). Ошибки сервера PsyApp — человеческим текстом.
 * Прежде компоненты показывали d.error как есть: «alias_owned_by_another_user»,
 * «intensity_1_10 must be 1..10», а при обрыве сети — «Failed to fetch».
 * Неизвестный код не показываем сырым: вместо него запасной текст места.
 */
const ПОНЯТНО: Array<[RegExp, string]> = [
  [/^alias_owned_by_another_user$/, "Этот псевдоним уже занят другим человеком. Выбери другой."],
  [/^alias (must|invalid)/, "Псевдоним: 2–40 символов, латиница, цифры, _ или -."],
  [/^user_not_found$/, "Не нашли твой путь на сервере. Начни заново — это займёт минуту."],
  [/^addiction must/, "Выбери, от чего уходишь: алкоголь, курение или другое."],
  [/^trigger_type must/, "Выбери тип триггера."],
  [/^intensity_1_10 must/, "Интенсивность — от 1 до 10."],
  [/^message required$/, "Напиши хотя бы пару слов."],
  [/^invalid_json$/, "Не получилось отправить. Обнови страницу и попробуй ещё раз."],
];

export function ошибкаСервера(raw: unknown, запасной: string): string {
  const код = typeof raw === "string" ? raw.trim() : "";
  for (const [re, текст] of ПОНЯТНО) if (re.test(код)) return текст;
  return запасной;
}

/** fetch упал до ответа (нет сети, сервер спит) — «Failed to fetch» человеку ничего не говорит. */
export const НЕТ_СВЯЗИ = "Нет связи с сервером. Проверь интернет и попробуй ещё раз.";
