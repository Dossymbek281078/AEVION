import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Три молчаливых отказа на пути платежей.
 *
 * Замер 28.08.2026: в `qpaynet.ts` четыре места, где ошибка проглатывалась
 * `.catch(() => {})`. Разобрано по правилу «молчать можно при уборке, нельзя при
 * осмысленном действии»:
 *
 *   ROLLBACK транзакции — ДОПУСТИМО. Это уборка, и её провал не должен
 *   маскировать исходную ошибку, ради которой мы и откатываемся.
 *
 *   Остальные три — дефекты, и худший первый:
 *
 * 1. ЗАПИСЬ ИДЕМПОТЕНТНОСТИ. `readIdempotency` при отсутствии строки возвращает
 *    «ничего», и вызывающий считает повтор НОВЫМ запросом. Значит провал этой
 *    записи снимает защиту от дубля: повтор того же платёжного запроса
 *    обработается заново. Ронять ответ нельзя — запрос уже выполнен, и отказ
 *    заставил бы клиента повторить его, создав тот самый дубль. Поэтому отказ
 *    остаётся не смертельным и становится видимым.
 *
 * 2. МИГРАЦИЯ КОЛОНОК УВЕДОМЛЕНИЙ. Колонок не станет, а запросы к ним прикрыты
 *    мягкими catch выше по стеку и отвечают 200 — уведомления мерчанту
 *    перестанут уходить, и никто не узнает. Это тот же класс, что «SQL для
 *    TypeScript — просто строка».
 *
 * 3. УЧЁТ ОТПРАВКИ УВЕДОМЛЕНИЯ. Провал молча значит либо повторную отправку
 *    мерчанту (не записан признак «отправлено»), либо вечные повторы (не вырос
 *    счётчик попыток). Оба исхода выглядят снаружи штатной работой.
 *
 * СТОРОЖ ПО ИСХОДНИКУ. Поведенческий путь потребовал бы живой базы, которая
 * принимает SELECT и отказывает на INSERT в одну конкретную таблицу; такого
 * харнеса в проекте нет. Сторож ловит возврат молчаливого проглатывания и
 * пропажу следа, но не докажет, что запись в журнал случилась.
 */

const FILE = path.join(__dirname, "..", "src", "routes", "qpaynet.ts");

/** Код без комментариев: объяснение обязано цитировать прежний вид. */
function code(): string {
  return fs
    .readFileSync(FILE, "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .split("\n")
    .filter((l) => !l.trim().startsWith("//"))
    .join("\n");
}

describe("молчаливые отказы на пути платежей", () => {
  test("прибор работает: файл читается и платежи в нём есть", () => {
    const c = code();
    expect(c.length).toBeGreaterThan(2000);
    expect(c).toContain("qpaynet_idempotency");
  });

  test("молчаливым остался ровно один — откат транзакции", () => {
    const silent = [...code().matchAll(/\.catch\(\(\) => \{\}\)/g)];
    // Больше одного значит, что вернулся дефект: остальные три обязаны
    // оставлять след.
    expect(
      silent.length,
      "на пути платежей снова больше одного молчаливого проглатывания",
    ).toBe(1);
    expect(code()).toMatch(/"ROLLBACK"\)\.catch\(\(\) => \{\}\)/);
  });

  test("отказ записи идемпотентности назван и отправлен", () => {
    const c = code();
    expect(c).toContain("ЗАПИСЬ ИДЕМПОТЕНТНОСТИ НЕ ПРОШЛА");
    // Без ключа и владельца дубль потом не найти.
    expect(c).toMatch(/ЗАПИСЬ ИДЕМПОТЕНТНОСТИ НЕ ПРОШЛА[^`]*\$\{key\}/);
    expect(c).toMatch(/ЗАПИСЬ ИДЕМПОТЕНТНОСТИ НЕ ПРОШЛА[^`]*\$\{ownerId\}/);
    expect(c).toMatch(/captureException\(e, \{ route: "qpaynet\/saveIdempotency"/);
  });

  test("отказ миграции колонок уведомлений назван", () => {
    expect(code()).toContain("МИГРАЦИЯ КОЛОНОК УВЕДОМЛЕНИЙ НЕ ПРОШЛА");
    expect(code()).toMatch(/captureException\(e, \{ route: "qpaynet\/ensureNotifyColumns"/);
  });

  test("отказ учёта уведомления назван вместе с заявкой", () => {
    const c = code();
    expect(c).toContain("УЧЁТ УВЕДОМЛЕНИЯ НЕ ЗАПИСАН");
    expect(c).toMatch(/УЧЁТ УВЕДОМЛЕНИЯ НЕ ЗАПИСАН[^`]*\$\{pr\.id\}/);
  });

  test("направление: ни одна из трёх правок не роняет вызывающего", () => {
    // «Видно» не должно превратиться в «падает»: платёжный запрос уже выполнен,
    // а отказ ответа заставил бы клиента повторить его и создать дубль.
    const c = code();
    const blocks = [...c.matchAll(/\.catch\(\(e: unknown\) => \{([\s\S]{0,700}?)\n\s*\}\);/g)].map((m) => m[1]);
    expect(blocks.length).toBeGreaterThanOrEqual(3);
    for (const b of blocks) expect(b).not.toMatch(/throw\s/);
  });
});
