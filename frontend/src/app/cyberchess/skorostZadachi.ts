/**
 * Сколько человек решал задачу — и честный отказ, когда мы этого не знаем.
 *
 * 🔴 ПОВОД, замер на проде 12.10.2026: после решения задачи всплывало
 * «+5 Chessy · ⏱ скорость 1791803299с». Это не скорость, а время с 1970 года:
 * секундомер `pzTimerRef` заводится только в двух путях (выбор задачи из
 * списка и загрузка FEN из файла), а задача приходит и ТРЕТЬИМ — по ссылке
 * `?puzzle=<id>` из ролика. В этом пути ref оставался нулём, и вычитание
 * `Date.now() - 0` давало метку времени.
 *
 * Беда двойная, и вторая половина дороже первой: по условию бонуса
 * (<10 с → 20, <30 с → 10, иначе 5) такой «результат» всегда попадал в
 * последнюю ветку, то есть пришедший ИЗ РОЛИКА — самый ценный для нас
 * человек — молча получал минимальную награду и нелепое число в придачу.
 *
 * Правило здесь одно: НЕ ЗНАЕМ — НЕ ПЕЧАТАЕМ. Выдуманная секунда хуже
 * отсутствующей, а «бонус за скорость», выданный без измерения скорости, —
 * это наша же неправда на экране человека.
 */
import { CHESS_LAUNCH_UTC } from "./launchDate";

/** Нижняя граница правдоподобия: раньше этого момента наш секундомер не мог стартовать. */
// Нижняя граница — дата запуска шахмат из ЕДИНОГО источника (launchDate.ts):
// до запуска решений быть не могло, а свой литерал даты ловит dataZapuskaOdna.
const РАНЬШЕ_НЕ_БЫВАЕТ = CHESS_LAUNCH_UTC;

/**
 * Секунды решения, либо null — если измерить не удалось.
 *
 * null даётся в трёх случаях, и все три означают «не знаем», а не «ноль»:
 *   • секундомер не заводился (0 или отрицательное);
 *   • метка старта выглядит не как наше время (до 2026 года) — так ловится
 *     ровно тот дефект, из-за которого правило написано;
 *   • «сейчас» раньше старта (переведённые часы, подмена времени).
 */
export function sekundyResheniya(начало: number, сейчас: number): number | null {
  if (!Number.isFinite(начало) || !Number.isFinite(сейчас)) return null;
  if (начало < РАНЬШЕ_НЕ_БЫВАЕТ) return null;
  if (сейчас < начало) return null;
  return Math.floor((сейчас - начало) / 1000);
}

/**
 * Бонус за скорость. Не измерили — бонуса НЕТ.
 *
 * Шкала та же, что была на экране: до 10 с — 20, до 30 с — 10, дальше 5.
 */
export function bonusZaSkorost(секунды: number | null): number {
  if (секунды === null) return 0;
  if (секунды < 10) return 20;
  if (секунды < 30) return 10;
  return 5;
}

/** Подпись к начислению, либо null — тогда строки про скорость быть не должно. */
export function podpisSkorosti(секунды: number | null): string | null {
  return секунды === null ? null : `⏱ скорость ${секунды}с`;
}
