/**
 * Подсказка к задаче дня называет ход РЕШАЮЩЕГО, а не соперника.
 *
 * 🔴 ПОВОД 30.09.2026. GET /api/cyberchess-daily/puzzle отдавал
 * `solHint: sol[0]`. У задач в сыром формате lichess `sol[0]` — ход СОПЕРНИКА,
 * который делается из позиции `fen`; игрок ходит следующим. Живой замер
 * сегодняшней задачи:
 *   fen  6k1/1ppq1ppp/3p4/1P1P4/2PN4/2Q5/r4KPP/B7 w - - 7 25
 *   sol  f2g1, d7g4, a1b2, g4d1
 * Подсказка приходила «f2g1» — ход белых, которого человек не делает; играет
 * он «d7g4».
 *
 * Наша страница solHint не читает (проверено 29.09), но ручка ПУБЛИЧНАЯ: любой
 * виджет, ролик или партнёр получит неверную подсказку и будет прав, что винит
 * нас. Поэтому чиним на сервере, а не на экране.
 */
import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { подсказкаРешающего, этоСыраяLichess } from "../src/lib/dailyHint";

/** Убрать комментарии, чтобы текст О коде не считался кодом. */
function безКомментариев(src: string): string {
  let out = "";
  let i = 0;
  while (i < src.length) {
    const два = src.slice(i, i + 2);
    if (два === "/*") { const к = src.indexOf("*/", i + 2); i = к < 0 ? src.length : к + 2; continue; }
    if (два === "//" && src[i - 1] !== ":") { const к = src.indexOf(String.fromCharCode(10), i); i = к < 0 ? src.length : к; continue; }
    out += src[i]; i += 1;
  }
  return out;
}

describe("подсказка задачи дня", () => {
  test("🔴 живая задача 30.09: подсказка d7g4, а не f2g1", () => {
    const sol = ["f2g1", "d7g4", "a1b2", "g4d1"];
    expect(подсказкаРешающего(sol)).toBe("d7g4");
    expect(подсказкаРешающего(sol)).not.toBe(sol[0]);
  });

  test("короткая сырая задача в два хода — тоже второй", () => {
    expect(подсказкаРешающего(["e2e4", "e7e5"])).toBe("e7e5");
  });

  test("контроль: у НЕсырой задачи первый ход и есть ход решающего", () => {
    // Нечётная длина — решение уже нормализовано, чужого хода впереди нет.
    expect(этоСыраяLichess(["d7g4", "a1b2", "g4d1"])).toBe(false);
    expect(подсказкаРешающего(["d7g4", "a1b2", "g4d1"])).toBe("d7g4");
  });

  test("контроль: нет решения — нет и подсказки, без выдумывания хода", () => {
    expect(подсказкаРешающего([])).toBeUndefined();
    expect(подсказкаРешающего(undefined)).toBeUndefined();
    expect(подсказкаРешающего(["", "d7g4"])).toBe("d7g4");
    expect(подсказкаРешающего([undefined as unknown as string])).toBeUndefined();
  });

  test("правило распознавания то же, что у фронта: чётная длина — сырая", () => {
    // Если правило здесь разойдётся с puzzleNormalize.ts, две половины
    // продукта начнут считать решающего разными сторонами.
    expect(этоСыраяLichess(["a", "b"])).toBe(true);
    expect(этоСыраяLichess(["a", "b", "c"])).toBe(false);
    expect(этоСыраяLichess([])).toBe(false);
    expect(этоСыраяLichess("не массив")).toBe(false);
  });
  test("ручка ЗОВЁТ помощника, а не берёт первый ход сама", () => {
    /*
     * Почему проверка по исходнику, а не через саму ручку. GET /puzzle берёт
     * задачу из банка, а когда банк не отвечает — из локального запаса на 30
     * задач. Замер: все 30 там НОРМАЛИЗОВАНЫ (длина решения 3 у всех до
     * одной), то есть на резервном пути старый код и новый дают один и тот же
     * ответ. В тесте банк недоступен всегда, значит поведенческой разницы не
     * добыть, и утверждать «проверено ручкой» было бы неправдой.
     *
     * Поэтому здесь охраняется СВЯЗЬ: помощник позван и первый ход напрямую
     * больше не берётся. Комментарии сняты — иначе объяснение про `sol[0]`
     * само же красило бы проверку.
     */
    const код = безКомментариев(
      readFileSync(join(__dirname, "..", "src", "routes", "cyberchessDaily.ts"), "utf8"),
    );
    expect(код).toContain("подсказкаРешающего(p.sol)");
    expect(код).not.toContain("solHint: p.sol[0]");
  });

  test("прибор исправен: комментарии действительно снимаются", () => {
    expect(безКомментариев("a /* solHint: p.sol[0] */ b")).not.toContain("p.sol[0]");
    expect(безКомментариев('const u = "https://a.app"; // x')).toContain("https://a.app");
  });
});
