import { describe, it, expect } from "vitest";
import * as fs from "node:fs";
import * as path from "node:path";

/**
 * 08.09.2026. Русские голосовые команды CyberChess не распознавались ВОВСЕ:
 * JS `\b` — граница класса [A-Za-z0-9_], кириллица в него не входит, поэтому
 * /\b(сдаюсь)\b/.test("сдаюсь") === false. «сдаюсь», «новая партия»,
 * «переверни», «отмена», «анализ», «выключи голос», диктовка ходов («конь эф
 * три», взятия «берёт/бьёт») — молча мимо. Английские альтернативы в тех же
 * шаблонах работали, оттого дефект и не замечали (класс из памяти
 * feedback_regex_word_boundary_cyrillic; тот же баг чинили в Банке).
 *
 * Починка: у многосимвольных команд \b убран (подстрока в коротком транскрипте
 * безопасна); у одиночных букв/чисел и предлога «в» — кириллице-осведомлённая
 * граница (lookaround), чтобы не резать внутри слова. Находку и скрипт передало
 * окно QSpace; правил владелец файла (это окно).
 */

const SRC = path.join(__dirname, "..", "page.tsx");
const src = () => fs.readFileSync(SRC, "utf-8");

describe("русские голосовые команды: \\b больше не глотает кириллицу", () => {
  it("класс подтверждён: старый шаблон \\b(...)\\b не совпадал с кириллицей", () => {
    expect(/\b(сдаюсь|resign)\b/.test("сдаюсь")).toBe(false); // так было — баг
    expect(/(сдаюсь|resign)/.test("сдаюсь")).toBe(true);       // так стало
    expect(/(сдаюсь|resign)/.test("resign")).toBe(true);       // латиница цела
  });

  it("спец-команды в источнике БЕЗ граничного \\b (мутация: вернуть → красный)", () => {
    const s = src();
    // фикс на месте — группы без \b:
    expect(s).toMatch(/if\(\/\(сдаюсь\|сдаться\|resign/);
    expect(s).toMatch(/if\(\/\(новая\\s\+партия/);
    // старого шаблона в ПОЗИЦИИ команды быть не должно (в комментарии-примере
    // \b(сдаюсь) допустим, поэтому якорим по `if(/`):
    expect(s).not.toMatch(/if\(\/\\b\(сдаюсь/);
    expect(s).not.toMatch(/if\(\/\\b\(отмена/);
  });

  it("карты букв/чисел: lookaround с ЗАГЛАВНЫМИ, не режет внутри слова", () => {
    const s = src();
    expect(s).toMatch(/cyrBound/);                 // helper c lookaround заведён
    expect(s).not.toMatch(/RegExp\("\\\\b"\+k/);    // старый \b+ключ убран
    // класс обязан включать заглавную кириллицу — иначе щель «Шэф» (замер
    // user-80: без флага i заглавная перед строчным совпадением). Откат на
    // узкий [\wа-яё] уберёт «А-Яа-яЁё» → эта проверка краснеет.
    expect(s).toMatch(/А-Яа-яЁё/);
    const wide = (w: string) => new RegExp("(?<![\\wА-Яа-яЁё])" + w + "(?![\\wА-Яа-яЁё])", "g");
    const narrow = (w: string) => new RegExp("(?<![\\wа-яё])" + w + "(?![\\wа-яё])", "g");
    expect("конь эф три".replace(wide("эф"), "f")).toBe("конь f три"); // слово ловится
    expect("шэфер".replace(wide("эф"), "f")).toBe("шэфер");             // строчное внутри — нет
    // 🔴 щель user-80: заглавная кириллица перед строчным совпадением, без i.
    expect("Шэф".replace(wide("эф"), "f")).toBe("Шэф");                 // широкий класс — цел
    expect("Шэф".replace(narrow("эф"), "f")).toBe("Шf");               // контроль: узкий РЕЖЕТ
  });
});
