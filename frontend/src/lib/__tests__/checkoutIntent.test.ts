/**
 * Память о намерении покупки: что она обязана помнить и что обязана ЗАБЫТЬ.
 *
 * Забывание здесь важнее запоминания. Просроченное намерение опаснее
 * отсутствующего: оно выглядит знанием, и кнопка «вернуться к тарифу» повела бы
 * человека к тому, что он смотрел позавчера, — а он решит, что мы путаем его
 * покупку.
 *
 * Тест написан после того, как мутация «снять срок жизни» НЕ поймалась ни одним
 * сторожем: свойство было заявлено в коде и не проверялось нигде.
 */
import { describe, it, expect, beforeEach, afterEach, vi } from "vitest";
import { запомнитьНамерение, вспомнитьНамерение, тарифИзСсылки } from "../checkoutIntent";

const КЛЮЧ = "aevion_checkout_intent";

beforeEach(() => sessionStorage.clear());
afterEach(() => {
  sessionStorage.clear();
  vi.useRealTimers();
});

describe("память о намерении покупки", () => {
  it("помнит тариф и период", () => {
    запомнитьНамерение("lite", "monthly");
    expect(вспомнитьНамерение()).toMatchObject({ tier: "lite", period: "monthly" });
  });

  it("забывает просроченное", () => {
    const давно = Date.now() - 3 * 60 * 60 * 1000;
    sessionStorage.setItem(КЛЮЧ, JSON.stringify({ tier: "lite", ts: давно }));
    expect(вспомнитьНамерение(), "просроченное намерение подставилось как свежее").toBeUndefined();
  });

  it("помнит свежее", () => {
    // Контроль к предыдущему: без него «забывает всегда» выглядело бы так же.
    const недавно = Date.now() - 60 * 1000;
    sessionStorage.setItem(КЛЮЧ, JSON.stringify({ tier: "lite", ts: недавно }));
    expect(вспомнитьНамерение()?.tier).toBe("lite");
  });

  it("не верит испорченной записи", () => {
    for (const мусор of ["", "{", "null", '{"tier":""}', '{"tier":"lite"}', '{"ts":123}']) {
      sessionStorage.setItem(КЛЮЧ, мусор);
      expect(вспомнитьНамерение(), `принята запись: ${мусор}`).toBeUndefined();
    }
  });

  it("пустой тариф не запоминается", () => {
    запомнитьНамерение("   ");
    expect(вспомнитьНамерение()).toBeUndefined();
  });

  it("последнее намерение вытесняет прежнее", () => {
    // Правило ОБРАТНО каналу: там первое касание, здесь последняя попытка.
    запомнитьНамерение("lite");
    запомнитьНамерение("full");
    expect(вспомнитьНамерение()?.tier).toBe("full");
  });
});

describe("тариф из ссылки кассы", () => {
  it("берёт идентификатор из tier_<id>_<period>", () => {
    expect(тарифИзСсылки("tier_lite_monthly")).toBe("lite");
    expect(тарифИзСсылки("tier_full_annual")).toBe("full");
  });

  it("молчит на чужих формах, а не выдумывает", () => {
    // `app_constitution` и `app_qventure` — НАСТОЯЩИЕ формы ссылок у второй
    // кассы. Без проверки начала строки из них вышел бы «тариф constitution»,
    // и кнопка повела бы человека на несуществующую страницу тарифа.
    for (const чужое of [
      null,
      undefined,
      "",
      "constitution-pro",
      "tier_",
      "bundle:ip",
      "tier",
      "app_constitution",
      "app_qventure",
    ]) {
      expect(тарифИзСсылки(чужое), `выдуман тариф из: ${String(чужое)}`).toBeUndefined();
    }
  });
});
