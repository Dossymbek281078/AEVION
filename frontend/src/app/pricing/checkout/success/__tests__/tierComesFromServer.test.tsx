import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Сторож: страница успеха берёт тариф У СЕРВЕРА, а не из адресной строки.
 *
 * ЧТО БЫЛО (замер 03.09.2026). Страница читала `?tier=` и показывала его в
 * заголовке: «Тариф Pro активирован». Значение подделывается (?tier=enterprise
 * — и человек видит Enterprise), а главное — оно ничего не знает о неудаче
 * выдачи. Если провижининг не состоялся, покупатель всё равно читал
 * «активирован» и не шёл в поддержку.
 *
 * Проверяется ИСХОДНИК: поднимать React ради одного источника данных дороже
 * пользы, а регрессия здесь выглядит как «кто-то убрал запрос к серверу».
 * Граница записана честно — сторож видит наличие запроса и приоритет
 * подтверждённого значения, но не то, как страница выглядит.
 */
const исходник = readFileSync(
  join(__dirname, "..", "page.tsx"),
  "utf8"
);

describe("страница успеха не верит адресной строке", () => {
  test("КОНТРОЛЬ: исходник прочитан", () => {
    expect(исходник.length, "файл страницы пуст").toBeGreaterThan(2000);
  });

  test("страница СПРАШИВАЕТ сервер о статусе выдачи", () => {
    expect(
      исходник,
      "запрос к ручке статуса исчез — страница снова верит адресной строке"
    ).toContain("/api/pricing/checkout/status");
  });

  test("подтверждённый сервером тариф ИМЕЕТ ПРИОРИТЕТ над адресом", () => {
    // Порядок важен: `подтверждённый ?? tier`, а не наоборот. Обратный
    // порядок вернул бы прежнее поведение, оставив запрос декоративным.
    expect(
      исходник.includes("подтверждённый ?? tier"),
      "адресная строка снова важнее ответа сервера — запрос стал декоративным"
    ).toBe(true);
  });

  test("неудача проверки НЕ выдаётся за отказ в выдаче", () => {
    // В catch не должно быть установки состояния «не выдано»: сеть могла
    // просто не ответить, а человек уже заплатил.
    const iCatch = исходник.indexOf("} catch {");
    expect(iCatch, "блок catch не найден — проверка неактуальна").toBeGreaterThan(0);
    const хвост = исходник.slice(iCatch, iCatch + 200);
    expect(
      /setПодтверждённый\s*\(\s*(null|false)/.test(хвост),
      "при сетевой ошибке страница делает вывод о выдаче"
    ).toBe(false);
  });
});
