/** Склонение «день» по числу: ru — три формы, en — one/many, kk — одна. */
export function dayKey(lang: string, n: number): Key {
  if (lang === "ru") {
    const m10 = n % 10, m100 = n % 100;
    if (m100 >= 11 && m100 <= 14) return "streak.day.many";
    if (m10 === 1) return "streak.day.one";
    if (m10 >= 2 && m10 <= 4) return "streak.day.few";
    return "streak.day.many";
  }
  return n === 1 ? "streak.day.one" : "streak.day.many";
}

