import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * Палец на 3D-холсте не должен замораживать страницу.
 *
 * OrbitControls в своём конструкторе ставит холсту `touchAction = "none"` —
 * в исходнике библиотеки это подписано «Disable touch scroll». Для страницы,
 * целиком занятой сценой, это верно; у нас холст занимает 42vh посреди
 * длинной страницы, и следствие обратное задуманному.
 *
 * Замерено 13.09.2026 пробой на 390x844 по собранной странице:
 *
 *     свайп пальцем ПО ХОЛСТУ    978 -> 978    (страница стоит)
 *     контроль, свайп РЯДОМ      978 -> 1183   (страница листается)
 *
 * Контроль здесь обязателен: без него «страница стоит» неотличимо от
 * «страница не прокручивается вовсе».
 *
 * Лечение — `pan-y`: вертикаль отдаётся браузеру, горизонталь остаётся
 * повороту модели. Оно ДОЛЖНО стоять после конструктора OrbitControls,
 * иначе он затрёт значение своим.
 *
 * Сторож смотрит исходник, а не отрисовку: браузерная проба стоит минут и в
 * наборе не живёт. Значит он стережёт присутствие и ПОРЯДОК строк — ровно то,
 * что легко потерять при переносе кода.
 */
const NL_ТЕСТА = String.fromCharCode(10);
const КЛИЕНТ = readFileSync(path.join(__dirname, "_client.tsx"), "utf8");

describe("прокрутка пальцем по 3D-холсту", () => {
  it("вертикальный свайп отдан странице во ВСЕХ местах, где задан touch-action", () => {
    // Форм записи две, и первая редакция сторожа знала только одну.
    // Из-за этого он был зелёным, пока прокрутка оставалась сломанной:
    // правка легла на <canvas> (форма «= "..."»), а обёртка холста несла
    // СВОЙ зашитый none в объекте стилей (форма «: "..."»). touch-action
    // считается по цепочке предков, поэтому none на обёртке решал всё.
    // Комментарии вырезаются: строка 203 ЦИТИРУЕТ «touchAction: "none"» как
    // поведение библиотеки, и без вырезания сторож краснел на исправном коде.
    // Текст О вещи неотличим от вещи для любого разбора по образцу.
    const безКомментариев = КЛИЕНТ.split(/\r?\n/)
      .filter((строка) => !/^\s*\/\//.test(строка))
      .join(NL_ТЕСТА);
    const задано = [...безКомментариев.matchAll(/touchAction\s*[:=]\s*"([^"]+)"/g)]
      .map((m) => m[1]);
    expect(задано.length).toBeGreaterThanOrEqual(2);
    expect(задано.filter((v) => v !== "pan-y")).toEqual([]);
  });

  it("отдан ПОСЛЕ конструктора OrbitControls, иначе он затрёт", () => {
    const создание = КЛИЕНТ.indexOf("new OrbitControls(");
    const правка = КЛИЕНТ.indexOf('touchAction = "pan-y"');
    expect(создание).toBeGreaterThan(-1);
    expect(правка).toBeGreaterThan(создание);
  });
});

/**
 * Подпись, объясняющая управление, не имеет права называть только мышь.
 *
 * Страница открывается на телефоне (у неё для этого есть своя медиазапросная
 * раскладка), а на телефоне мыши нет. Особый случай — `aria-label` холста:
 * его произносит экранный диктор, и «вращение мышью» там звучит как отказ.
 *
 * Проверяется СЛЕДСТВИЕ, а не наличие слова: рядом с «мышью» обязано стоять
 * касание. Список слов касания намеренно широк — подпись можно переписать,
 * лишь бы она осталась верной на телефоне.
 */
describe("подписи об управлении верны и на телефоне", () => {
  // Флаг i обязателен: «Пальцем» с заглавной иначе не совпадёт, и сторож
  // покраснеет на исправном тексте. В JS регистронезависимость с кириллицей
  // работает — это grep -i её не понимает.
  const КАСАНИЕ = /пальц|касани|свайп/i;
  // Подпись в JSX переносится через строки, поэтому «мышью» и слово про
  // касание почти никогда не лежат в ОДНОЙ строке. Смотрим окно соседей:
  // двух строк хватает на абзац, и при этом нельзя «оправдать» подпись
  // касанием из чужого блока.
  const ОКНО = 2;

  it("у каждой строки про мышь рядом названо касание", () => {
    const строки = КЛИЕНТ.split(/\r?\n/);
    const подозрительные = строки
      .map((строка, i) => ({ строка, i, n: i + 1 }))
      .filter(({ строка }) => /мышью/i.test(строка) && !/^\s*\/\//.test(строка))
      .filter(({ i }) =>
        !КАСАНИЕ.test(строки.slice(Math.max(0, i - ОКНО), i + ОКНО + 1).join(" ")));
    expect(подозрительные.map((x) => `${x.n}: ${x.строка.trim()}`)).toEqual([]);
  });

  it("подпись холста для экранного диктора называет касание", () => {
    const m = КЛИЕНТ.match(/aria-label="3D-модель помещения[^"]*"/);
    expect(m).not.toBeNull();
    expect(m![0]).toMatch(КАСАНИЕ);
  });
});
