import { describe, expect, it } from "vitest";
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { stripComments } from "./helpers/sourceCode";

/**
 * LIMIT в SQL подставляется плейсхолдером, а не значением из шаблона.
 *
 * 🔴 ЗАЧЕМ. Замер 08.09.2026 на живом проде: GET /api/pipeline/certificates.csv
 * отвечал 500 при ЛЮБЫХ параметрах — экспорт реестра сертификатов не работал
 * НИКОГДА с момента переноса. Причина в одном символе: `LIMIT ${params.length}`
 * вместо `LIMIT $${params.length}`. Без доллара в текст запроса уходит ЧИСЛО
 * параметров, сам параметр остаётся непривязанным, и Postgres отбивает запрос.
 *
 * Класс тихий вдвойне: SQL для TypeScript — обычная строка, поэтому ни типы,
 * ни сборка ошибку не видят; а ответ 500 из общего catch выглядит как
 * временный сбой базы, а не как то, что ручка мертва с рождения.
 *
 * ГРАНИЦА, названная честно. Сторож ловит РОВНО ОДНУ форму: `LIMIT
 * ${params.length}` — то есть подстановку ЧИСЛА ПАРАМЕТРОВ как значения
 * лимита. Это всегда опечатка: количество параметров бессмысленно в роли
 * лимита, а рядом стоит правильный вид `$${params.length}`.
 *
 * Первая редакция была шире — ловила любой `LIMIT ${...}` — и покраснела на
 * ИСПРАВНОМ коде: `LIMIT ${ROW_CAP}` в constitutionWaitlist.ts подставляет
 * КОНСТАНТУ из кода, и это законно. Сторож, краснеющий на здоровом коде,
 * отключают в первый же день, поэтому правило сужено до признака опечатки. Он НЕ понимает SQL и не заметит
 * той же ошибки у OFFSET, у сравнения или у собранного из кусков запроса.
 * Это дешёвая проверка на конкретную опечатку, а не анализатор запросов, — и
 * писать её шире смысла нет: попытка обобщить дала бы ложные срабатывания на
 * каждом месте, где число подставляется в запрос законно (ORDER BY, имена
 * колонок из белого списка).
 */
const ROUTES = join(__dirname, "..", "src", "routes");

describe("LIMIT в запросах — плейсхолдер, а не подставленное число", () => {
  const файлы = readdirSync(ROUTES).filter((f) => f.endsWith(".ts"));

  it("прибор видит предмет: файлы маршрутов на месте", () => {
    expect(файлы.length).toBeGreaterThan(20);
  });

  it("нигде нет LIMIT со значением прямо из шаблона", () => {
    const находки: string[] = [];
    for (const имя of файлы) {
      const src = stripComments(readFileSync(join(ROUTES, имя), "utf8"));
      let i = 0;
      for (;;) {
        const at = src.indexOf("LIMIT ${params.length}", i);
        if (at < 0) break;
        находки.push(`${имя}: LIMIT ${"${params.length}"} — забыт доллар перед скобкой`);
        i = at + 10;
      }
    }
    expect(находки, "LIMIT подставляет значение в текст запроса — параметр останется непривязанным").toEqual([]);
  });
});
