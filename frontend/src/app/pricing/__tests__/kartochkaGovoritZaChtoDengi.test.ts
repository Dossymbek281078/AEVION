import { describe, it, expect } from "vitest";
import { readFileSync, existsSync } from "node:fs";
import { join } from "node:path";

/**
 * Карточка приложения обязана говорить, ЗА ЧТО деньги.
 *
 * ПОВОД 06.10.2026, замер на проде. Карточка CyberChess на /pricing содержала
 * ровно это: «CyberChess · $24/мес · $24 за месяц · Max: $12/мес · Купить
 * CyberChess». Цена есть, предложения нет.
 *
 * А бесплатно у шахмат — почти всё: задачи, партия, задача дня и ИИ-тренер
 * открыты без входа и без оплаты. Проверено ручками на проде:
 *   /api/cyberchess-puzzles/meta   → 200
 *   /api/cyberchess-daily/puzzle   → 200
 *   контроль тем же прибором:
 *   /api/multichat/presets         → 402 upgrade_required
 * То есть человеку предлагали заплатить за то, что у него уже есть, —
 * и не называли единственное, что оплата действительно открывает.
 *
 * Страница самих шахмат этот же дефект чинила 29.09 (см. соседний сторож
 * buyPromiseMatchesWhatIsGated), а витрина цен осталась с ним.
 *
 * Здесь проверяется СООТВЕТСТВИЕ обещания и гейта, а не красота формулировки.
 */

const КОРЕНЬ = process.cwd();
const СТРАНИЦА = readFileSync(join(КОРЕНЬ, "src/app/pricing/page.tsx"), "utf8");

/** Значение ключа в словаре КОНКРЕТНОГО языка, без отката на английский. */
function значение(язык: string, ключ: string): string | null {
  const путь = join(КОРЕНЬ, `src/lib/i18n-lang/${язык}.ts`);
  if (!existsSync(путь)) return null;
  const src = readFileSync(путь, "utf8");
  const i = src.indexOf(`"${ключ}"`);
  if (i < 0) return null;
  const начало = src.indexOf('"', src.indexOf(":", i) + 1);
  if (начало < 0) return null;
  let j = начало + 1;
  let текст = "";
  while (j < src.length && src[j] !== '"') { текст += src[j]; j++; }
  return текст;
}

/** Слаги, у которых карточка обещает платную часть. */
function slagiSObeschaniem(): string[] {
  const i = СТРАНИЦА.indexOf("const ЧТО_ПЛАТНО");
  expect(i, "карта ЧТО_ПЛАТНО исчезла — карточка снова молчит о том, за что деньги").toBeGreaterThan(0);
  const конец = СТРАНИЦА.indexOf("};", i);
  const тело = СТРАНИЦА.slice(i, конец);
  return [...тело.matchAll(/(\w[\w-]*):\s*"([^"]+)"/g)].map((m) => m[1]);
}

describe("карточка приложения говорит, за что деньги", () => {
  it("строка о платной части выводится, а не просто объявлена", () => {
    // Объявить карту и забыть вывести — самый тихий способ «починить».
    expect(СТРАНИЦА, "ЧТО_ПЛАТНО нигде не выводится").toContain("t(ЧТО_ПЛАТНО[a.slug])");
    // И само УСЛОВИЕ вывода, а не только вызов внутри него: мутация
    // «{ЧТО_ПЛАТНО[a.slug] && (» → «{false && (» прошла мимо первой версии
    // этой проверки — текст оставался в файле, а на экран не попадал ничего.
    expect(
      СТРАНИЦА,
      "условие вывода подменено — строка в исходнике есть, на экран не попадает"
    ).toContain("{ЧТО_ПЛАТНО[a.slug] && (");
  });

  it("🔴 у CyberChess обещания НЕТ — назвать платную часть сейчас нечем", () => {
    // ПЕРЕВЁРНУТО 07.10.2026 вслед за решением, а не ослаблено.
    //
    // Вчера здесь требовалось обратное: карточка ОБЯЗАНА была назвать платную
    // часть, и ею был «Глубокий анализ». Сегодняшний замер показал, что он не
    // работает ни у кого, включая оплативших: движок берёт нейросети по адресу
    // /nnue, а их на проде нет (404; каталога в сборке нет; переменная
    // NEXT_PUBLIC_NNUE_BASE не задана — в бандле осталось само выражение).
    //
    // Остальное у шахмат бесплатно, и это измерено: /api/cyberchess-puzzles/meta
    // и /cyberchess-daily/puzzle отвечают 200 без входа. Значит платную часть
    // назвать НЕЧЕМ, и пустая запись честнее любой формулировки.
    const слаги = slagiSObeschaniem();
    expect(слаги, `у CyberChess снова есть обещание: ${слаги.join(", ")}`).not.toContain("cyberchess");
  });

  it("контроль: любое появившееся обещание обязано быть осознанным", () => {
    // Сейчас обещаний нет вовсе, и это намеренное состояние. Появится первое —
    // здесь придётся осознанно решить, что оно правдиво, а не добавить молча.
    const слаги = slagiSObeschaniem();
    expect(слаги, `появились обещания: ${слаги.join(", ")} — проверьте, что каждое правдиво`).toEqual([]);
  });
  it("обещание есть на всех полных языках, а не только по-русски", () => {
    // Неполные языки (de, fr, es, zh, ja, ar, pt, tr) откатываются на
    // английский — это штатно. Полных три, и в них ключ обязан БЫТЬ.
    const пропуски: string[] = [];
    let проверено = 0;
    for (const язык of ["ru", "en", "kk"]) {
      for (const слаг of slagiSObeschaniem()) {
        проверено++;
        const v = значение(язык, `pricing.home.apps.whatIsPaid.${слаг}`);
        if (!v || v.trim().length < 20) пропуски.push(`${язык}/${слаг}`);
      }
    }
    expect(пропуски, `проверено пар язык×приложение: ${проверено}; без текста: ${пропуски.join(", ")}`).toEqual([]);
  });
});
