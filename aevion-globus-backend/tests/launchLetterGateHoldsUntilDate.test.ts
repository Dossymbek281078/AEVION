import { describe, test, expect } from "vitest";
import { isModuleLiveNow } from "../src/lib/constitutionBrevo";

/**
 * Ворота письма запуска держат дату — прямой тест isModuleLiveNow.
 *
 * Функция заведена 06.09.2026 взамен чтения поля liveFromUtcMidnight из
 * LAUNCH_MODULES: поле переехало, скрипт отправки молча сломался (поймал
 * пятый конфиг типов), и вместе с ним могла бы сломаться ГРАНИЦА «письмо
 * "модуль открыт" не уходит до даты». Здесь граница закреплена поведением
 * с параметром now — без перевода часов на машине.
 *
 * cyberchess выбран не случайно: это единственная запись LIVE_ENTRIES с
 * датой в будущем (30.09) на день написания. Если её дата пройдёт или
 * запись переедет — тест скажет об этом сам (контроль ниже).
 */

const ДО = new Date(Date.UTC(2026, 8, 20, 12));    // 20.09 — до 30.09
const ПОСЛЕ = new Date(Date.UTC(2026, 9, 2, 12));  // 02.10 — после

describe("ворота письма держат дату", () => {
  test("контроль: у cyberchess дата ещё в будущем относительно ДО-точки", () => {
    // Иначе пара ниже проверяла бы прошлое и была бы зелёной ни о чём.
    expect(isModuleLiveNow("cyberchess", ДО), "запись с будущей датой исчезла — подберите тесту другую").toBe(false);
  });

  test("до даты — НЕ живой, после — живой (обе стороны)", () => {
    expect(isModuleLiveNow("cyberchess", ДО)).toBe(false);
    expect(isModuleLiveNow("cyberchess", ПОСЛЕ)).toBe(true);
  });

  test("языковая приставка не обнуляет дату", () => {
    // en-cyberchess — тот же модуль; ворота обязаны совпадать (класс
    // «два ключа одной личности», уже стрелявший 29.08).
    expect(isModuleLiveNow("en-cyberchess", ДО)).toBe(false);
  });

  test("модуль без записи о дате — живой (дата не назначена ≠ запрещён)", () => {
    expect(isModuleLiveNow("nosuch-module-xyz", ДО)).toBe(true);
  });
});
