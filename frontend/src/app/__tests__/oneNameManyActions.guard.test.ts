/**
 * ОДНО ИМЯ У НЕСКОЛЬКИХ ДЕЙСТВИЙ.
 *
 * Подпись внутри `.map(...)`, которая не зависит НИ ОТ ОДНОГО параметра
 * колбэка, звучит одинаково у всех элементов списка. Глазами страница
 * выглядит правильно — рядом с полем стоит название упражнения. Читалке
 * достаётся только подпись, и человек слышит «Ваш ответ» шесть раз подряд,
 * не понимая, какое из них какое.
 *
 * Замер 04.09.2026: 121 подпись внутри `.map`, у 31 зависимости нет.
 *
 * ГРАНИЦЫ, которые надо знать, иначе зелёный цвет прочтут шире, чем он есть:
 *
 *   ВИДИТ    подпись-литерал и подпись-выражение внутри `.map(...)`;
 *            зависимость от ЛЮБОГО параметра колбэка — элемента, индекса,
 *            разобранного поля — считается законной.
 *   НЕ ВИДИТ списки через `for` и заранее собранный массив JSX (`flatMap` и
 *            `Array.from` с 04.09.2026 ВИДИТ); подписи из словаря, где одинаковым оказался КЛЮЧ;
 *            совпадение имён у РАЗНЫХ списков на одной странице.
 *   НЕ СУДИТ о том, различимы ли имена по смыслу: `${s.title}` он засчитает,
 *            даже если у двух элементов title одинаков.
 *
 * ⚠️ Первая версия сканера считала скобки ВНУТРИ строк и потому теряла
 * настоящие дефекты (`cables/page.tsx` — «Число» внутри `STEPS.map`).
 * Ноль от такого сканера читался бы как «чисто». Отсюда `пропуститьСтроку`
 * и оба контроля ниже: прибор обязан находить заведомо плохое И молчать на
 * заведомо хорошем.
 */

const КОРЕНЬ = path.join(__dirname, "..");

/** Пропустить строковый литерал целиком: скобки внутри него — текст, не код. */
function пропуститьСтроку(s: string, i: number): number {
  const кавычка = s[i];
  let k = i + 1;
  while (k < s.length) {
    if (s[k] === "\\") { k += 2; continue; }
    if (s[k] === кавычка) return k + 1;
    k++;
  }
  return s.length;
}

/** Конец выражения, открытого скобкой в позиции `откуда`. Строки пропускаются. */
export function конецСкобки(s: string, откуда: number): number {
  let глубина = 0;
  let k = откуда;
  while (k < s.length) {
    const c = s[k];
    if (c === '"' || c === "'" || c === "`") { k = пропуститьСтроку(s, k); continue; }
    if (c === "(") глубина++;
    else if (c === ")") { глубина--; if (глубина === 0) return k; }
    k++;
  }
  return -1;
}

/** Имена ВСЕХ параметров колбэка: (q, i) => …, ({ label }) => …, (node) => … */
export function параметрыКолбэка(s: string, скобка: number): string[] {
  const стрелка = s.indexOf("=>", скобка);
  if (стрелка < 0 || стрелка - скобка > 300) return [];
  return (s.slice(скобка + 1, стрелка).match(/[A-Za-z_$][\w$]*/g) || [])
    .filter((имя) => имя !== "_");
}

/** Часть идентификатора: буква, цифра, _ или $. */
function частьИмени(c: string): boolean {
  return (c >= "a" && c <= "z") || (c >= "A" && c <= "Z")
    || (c >= "0" && c <= "9") || c === "_" || c === "$";
}

/**
 * Упоминается ли имя ЦЕЛИКОМ, а не куском другого слова.
 * Намеренно без регулярки: граница слова пишется обратным слэшем, а он
 * теряется на границе вызова и молча становится символом ЗАБОЯ — проверка
 * тогда не совпадает НИ С ЧЕМ и сторож зеленеет на сломанном коде.
 * Ровно это и случилось при первом написании этого файла.
 */
export function упоминает(подпись: string, имя: string): boolean {
  let i = 0;
  for (;;) {
    i = подпись.indexOf(имя, i);
    if (i < 0) return false;
    const до = i > 0 ? подпись[i - 1] : " ";
    const после = i + имя.length < подпись.length ? подпись[i + имя.length] : " ";
    if (!частьИмени(до) && !частьИмени(после)) return true;
    i += имя.length;
  }
}

/**
 * Формы, которыми у нас строят списки. `.map` даёт все сегодняшние находки;
 * две другие добавлены не от находок, а чтобы завтрашние не прошли молча —
 * замер 04.09.2026: в `flatMap` и `Array.from` дефектов НОЛЬ, и это проверено
 * контролями ниже, а не выведено из тишины.
 */
const ФОРМЫ_СПИСКА = [".map(", ".flatMap(", "Array.from("];

export type Находка = { путь: string; строка: number; подпись: string };

export function однимИменемНесколькоДействий(
  исходники: { путь: string; текст: string }[]
): Находка[] {
  const находки: Находка[] = [];
  for (const { путь, текст } of исходники) {
    let i = 0;
    for (;;) {
      i = текст.indexOf("aria-label=", i);
      if (i < 0) break;
      const j = i + 11;
      let подпись = "";
      if (текст[j] === '"') {
        подпись = текст.slice(j + 1, текст.indexOf('"', j + 1));
      } else if (текст[j] === "{") {
        let глубина = 0, k = j;
        while (k < текст.length) {
          const c = текст[k];
          if (c === '"' || c === "'" || c === "`") { k = пропуститьСтроку(текст, k); continue; }
          if (c === "{") глубина++;
          else if (c === "}") { глубина--; if (глубина === 0) break; }
          k++;
        }
        подпись = текст.slice(j + 1, k);
      } else { i = j; continue; }

      // Ближайший `.map(` может успеть ЗАКРЫТЬСЯ до подписи — настоящий список
      // тогда начинается выше. Проверяя только ближайший, сканер терял
      // настоящие дефекты (cables/page.tsx: «Число» внутри списка шагов).
      let объемлющая = -1;
      for (const форма of ФОРМЫ_СПИСКА) {
        let место = текст.lastIndexOf(форма, i);
        while (место >= 0) {
          const с = текст.indexOf("(", место + форма.length - 1);
          if (конецСкобки(текст, с) > i) { объемлющая = с; break; }
          место = текст.lastIndexOf(форма, место - 1);
        }
        if (объемлющая >= 0) break;
      }
      if (объемлющая >= 0) {
        {
          const параметры = параметрыКолбэка(текст, объемлющая);
          const зависит = параметры.some((имя) => упоминает(подпись, имя));
          if (!зависит) {
            находки.push({
              путь,
              строка: текст.slice(0, i).split("\n").length,
              подпись: подпись.trim().slice(0, 60),
            });
          }
        }
      }
      i = j;
    }
  }
  return находки;
}

function файлы(дир: string, найдено: string[] = []): string[] {
  for (const имя of fs.readdirSync(дир)) {
    const п = path.join(дир, имя);
    if (fs.statSync(п).isDirectory()) {
      if (имя !== "node_modules" && имя !== "__tests__") файлы(п, найдено);
    } else if (имя.endsWith(".tsx")) найдено.push(п);
  }
  return найдено;
}

describe("одно имя у нескольких действий", () => {
  const исходники = файлы(КОРЕНЬ).map((п) => ({
    путь: path.relative(КОРЕНЬ, п).split(path.sep).join("/"),
    текст: fs.readFileSync(п, "utf8"),
  }));

  it("прибор НАХОДИТ: подпись-литерал внутри map даёт находку", () => {
    expect(однимИменемНесколькоДействий([{ путь: "о.tsx",
      текст: 'items.map((ex) => (<input aria-label="Ваш ответ" />))' },
    ])).toHaveLength(1);
  });

  it("прибор МОЛЧИТ: подпись, зависящая от элемента, законна", () => {
    expect(однимИменемНесколькоДействий([{ путь: "о.tsx",
      текст: 'items.map((ex) => (<input aria-label={`Ответ: ${ex.title}`} />))' },
    ])).toHaveLength(0);
  });

  it("прибор МОЛЧИТ: зависимость от ИНДЕКСА тоже различает элементы", () => {
    expect(однимИменемНесколькоДействий([{ путь: "о.tsx",
      текст: 'items.map((_, i) => (<input aria-label={`Ответ ${i + 1}`} />))' },
    ])).toHaveLength(0);
  });

  it("прибор МОЛЧИТ: подпись вне списка одинаковой быть не может", () => {
    expect(однимИменемНесколькоДействий([{ путь: "о.tsx",
      текст: '<input aria-label="Поиск" />' },
    ])).toHaveLength(0);
  });

  it("скобки ВНУТРИ строк не обрывают область списка", () => {
    // именно на этом сканер и слеп: ")" в тексте закрывал map раньше времени
    expect(однимИменемНесколькоДействий([{ путь: "о.tsx",
      текст: 'items.map((ex) => (<b>{"текст с ) скобкой"}</b><input aria-label="Число" />))' },
    ])).toHaveLength(1);
  });

  /**
   * Храповик. 38 мест на 04.09.2026 — это ДОЛГ, а не норма: он записан,
   * чтобы новые не появлялись незаметно, и обязан только уменьшаться.
   * Список — `AppData/Local/Temp/dupwide.txt` на день замера; воспроизвести
   * можно прогоном этого же сторожа.
   */
  const ДОЛГ_НА_04_09_2026 = 15;

  it("новых мест не появилось", () => {
    const н = однимИменемНесколькоДействий(исходники);
    expect(н.length).toBeLessThanOrEqual(ДОЛГ_НА_04_09_2026);
  });

  it("долг не занижен: сторож всё ещё видит существующие места", () => {
    // Обратная сторона храповика: если сканер ослепнет, число упадёт в ноль
    // и это прочтётся как победа. Нижняя граница ловит именно ослепление.
    const н = однимИменемНесколькоДействий(исходники);
    expect(н.length).toBeGreaterThan(12);
  });

  it("видит список, ВНУТРИ которого закрылся соседний список", () => {
    // Ровно эта слепота теряла настоящий дефект: ближайший .map закрывался
    // раньше подписи, и место считалось «вне списка».
    expect(однимИменемНесколькоДействий([{ путь: "о.tsx",
      текст: 'ex.map((e) => (<div>{STEPS.map((s) => (<b>{s}</b>))}'
        + '<input aria-label="Число" /></div>))' },
    ])).toHaveLength(1);
  });

  it("видит список через Array.from", () => {
    expect(однимИменемНесколькоДействий([{ путь: "о.tsx",
      текст: 'Array.from(list, (it) => (<input aria-label="Ответ" />))' },
    ])).toHaveLength(1);
  });

  it("не клевещет на Array.from с зависимой подписью", () => {
    expect(однимИменемНесколькоДействий([{ путь: "о.tsx",
      текст: 'Array.from(list, (it) => (<input aria-label={`Ответ ${it.n}`} />))' },
    ])).toHaveLength(0);
  });

  it("видит список через flatMap", () => {
    expect(однимИменемНесколькоДействий([{ путь: "о.tsx",
      текст: 'xs.flatMap((g) => (<input aria-label="Число" />))' },
    ])).toHaveLength(1);
  });

  it("не клевещет на flatMap с зависимой подписью", () => {
    expect(однимИменемНесколькоДействий([{ путь: "о.tsx",
      текст: 'xs.flatMap((g) => (<input aria-label={`Число ${g.id}`} />))' },
    ])).toHaveLength(0);
  });

  it("сборка читается: страниц найдено достаточно", () => {
    expect(исходники.length).toBeGreaterThan(200);
  });

  it("границы сторожа записаны В НЁМ САМОМ", () => {
    const свой = fs.readFileSync(__filename, "utf8");
    expect(свой).toContain("НЕ ВИДИТ");
    expect(свой).toContain("НЕ СУДИТ");
  });
});
