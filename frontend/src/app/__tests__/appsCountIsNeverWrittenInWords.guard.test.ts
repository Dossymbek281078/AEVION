import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { STANDALONE_APPS } from "@/lib/termPricing";

/**
 * СКОЛЬКО ПРИЛОЖЕНИЙ ПРОДАЁТСЯ ОТДЕЛЬНО — одно число на всех страницах.
 *
 * Повод 29.09.2026: страницы писали «пять приложений продаются отдельно», а
 * продавались девять — и рядом сумма считалась по всем девяти. Число жило
 * СЛОВОМ в четырёх файлах и трёх словарях, поэтому расходилось молча: правка
 * списка ничего из этого не трогала.
 *
 * Где можно, число подставляется из STANDALONE_APPS прямо в вёрстке. В
 * описаниях для поисковика оно стоит цифрой: это статические строки, и перевод
 * их в шаблонные ради одного числа ломает длинные многострочные литералы
 * (пробовал 29.09 — 123 ошибки сборки, откатил). От расхождения защищает эта
 * проверка: она читает исходники и требует, чтобы цифра совпадала со списком.
 */

/** Прибор ОДИН на проверку и на контроль: две копии одной регулярки в этом
 *  файле уже разошлись, и контроль краснел на исправном коде. */
const числаРядомСоСловом = (текст: string): string[] =>
  [...текст.matchAll(/(\d+)\s+(?:приложени\S*|apps)/g)].map((m) => m[0]);

const СТРАНИЦЫ = [
  "src/app/shop/page.tsx",
  "src/app/en/shop/page.tsx",
  "src/app/pricing/layout.tsx",
  "src/app/apps/page.tsx",
];

describe("число отдельных приложений на всех страницах", () => {
  it("КОНТРОЛЬ: прибор находит числа и по-русски, и по-английски", () => {
    const проба = "продаётся 9 приложений отдельно, sold as 9 apps separately";
    expect(числаРядомСоСловом(проба)).toEqual(["9 приложений", "9 apps"]);
  });

  it("КОНТРОЛЬ: прибор не находит там, где числа нет", () => {
    expect(числаРядомСоСловом("приложений много, apps too")).toEqual([]);
  });

  it("нигде не написано словом", () => {
    const словом = /(five apps|Five apps|пять приложени|Пять приложени)/;
    const виновные = СТРАНИЦЫ.filter((путь) =>
      словом.test(readFileSync(join(process.cwd(), путь), "utf8")),
    );
    expect(
      виновные,
      "число снова написано словом — оно разойдётся со списком при первой же правке",
    ).toEqual([]);
  });

  it("написанная цифра совпадает с длиной списка", () => {
    const сколько = STANDALONE_APPS.length;
    const мимо: string[] = [];
    for (const путь of СТРАНИЦЫ) {
      const src = readFileSync(join(process.cwd(), путь), "utf8");
      for (const найдено of числаРядомСоСловом(src)) {
        const n = Number(найдено.match(/^\d+/)![0]);
        if (n !== сколько) мимо.push(`${путь}: ${найдено} вместо ${сколько}`);
      }
    }
    expect(мимо, "на странице стоит не то число приложений").toEqual([]);
  });
});
