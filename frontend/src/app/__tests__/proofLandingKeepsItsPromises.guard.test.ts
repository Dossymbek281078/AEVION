/**
 * Посадочная для покупателей данных обещает ровно то, что письмо, и не больше.
 *
 * ПОВОД (08.10.2026). Замер воронки за четыре дня, первый с исправленной
 * единицей byPost и пометкой «наше»: из шестнадцати писем площадкам
 * лицензирования живых переходов оказалось ТРИ (Protege 1, Innodata 2), до
 * страницы цен не дошёл НИ ОДИН, ответов ноль. Письма при этом доходят —
 * клики это и доказывают. Умирал следующий шаг: ссылки вели на /bureau, где
 * нет ни слова provenance, training data или dataset, то есть получатель не
 * находил на странице ничего из того, что ему написали.
 *
 * Страница /proof сделана как продолжение письма. Этот сторож держит её
 * честной в обе стороны:
 *   1. она ОБЯЗАНА называть каждую границу, которую называет письмо;
 *   2. она НЕ ИМЕЕТ ПРАВА обещать того, чего у нас нет;
 *   3. она обязана доносить метку канала, иначе мы снова не узнаем, какое
 *      письмо привело человека;
 *   4. числа на ней обязаны совпадать с теми, что в письмах.
 *
 * Проверка идёт по ИСХОДНИКУ страницы, и это названная граница: она отвечает
 * «что написано», а не «что увидел человек». Отрисовку проверяет браузерный
 * прогон после выкатки.
 */

import { describe, it, expect } from "vitest";
import { existsSync, readFileSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const КОРЕНЬ = join(dirname(fileURLToPath(import.meta.url)), "..");
const СТРАНИЦА = join(КОРЕНЬ, "proof", "page.tsx");

/**
 * Комментарии снимаются перед проверкой запретов. Иначе объяснение рядом с
 * правкой ослепляет собственный сторож — на этом я уже попадался четырежды:
 * текст О вещи неотличим от вещи, если читать файл целиком.
 */
function безКомментариев(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, " ").replace(/^\s*\/\/.*$/gm, " ");
}

const исходник = readFileSync(СТРАНИЦА, "utf8");
const текст = безКомментариев(исходник);

/** Границы, которые письмо называет прямо. Пропажа любой — молчаливое приукрашивание. */
const ГРАНИЦЫ: Array<[string, RegExp]> = [
  ["каталога нет", /hold no catalogue/i],
  ["личность автора не удостоверяем", /do not certify the author/i],
  ["проверка документов — заглушка", /stub today/i],
  ["нотариального соподписания нет", /no notary co-signature/i],
  ["SOC 2 и ISO 27001 не проходились", /No SOC 2, no ISO 27001/i],
  ["согласие на обучение не построено", /specified, not built/i],
  ["внешних платящих покупателей нет", /no external paying customers/i],
];

/** Чего на этой странице быть не должно ни при каких правках. */
const ЗАПРЕЩЕНО: Array<[string, RegExp]> = [
  ["заявление о патенте", /\bpatent(ed|s)?\b/i],
  ["обещание сертификации", /\b(SOC 2|ISO 27001)[- ]certified\b/i],
  ["юридическая сила нотариата", /notaris|notarial force (is|was) /i],
  ["гарантия", /\bwe guarantee\b/i],
  ["слово «лидер рынка»", /market leader/i],
];

describe("/proof — продолжение письма, а не витрина", () => {
  it("КОНТРОЛЬ: файл прочитан и это нужная страница", () => {
    expect(исходник.length).toBeGreaterThan(3000);
    expect(текст).toMatch(/Provenance for the data you license/);
  });

  it.each(ГРАНИЦЫ)("называет границу: %s", (_имя, образец) => {
    expect(
      образец.test(текст),
      "страница перестала называть границу, которую называет письмо — это приукрашивание",
    ).toBe(true);
  });

  it.each(ЗАПРЕЩЕНО)("не обещает того, чего нет: %s", (_имя, образец) => {
    expect(образец.test(текст), "на странице появилось обещание, которого продукт не выполняет").toBe(
      false,
    );
  });

  it("доносит метку канала", () => {
    /*
     * Без PageTracking переход из письма неотличим от прямого захода, и вся
     * разметка волн 1–3 перестаёт что-либо значить. Держимся за ФАКТ вызова,
     * а не за написание имени: переименование компонента не должно красить.
     */
    expect(/<PageTracking/.test(текст), "страница не доносит метку канала").toBe(true);
    expect(/page="proof"/.test(текст)).toBe(true);
  });

  it("не продаёт: ни цен, ни кнопки покупки", () => {
    /*
     * Витрина с ценой — ровно то, из-за чего предыдущая посадочная не
     * сработала: человек приходил за доказательством происхождения, а видел
     * прайс. Если цена понадобится, она появится после ответа покупателя и
     * другим путём.
     */
    expect(/ModulePricingChip|\$\d+\/mo|Buy now|Купить/i.test(текст)).toBe(false);
  });

  it("числа совпадают с письмами: 42 подписи и 20 отозванных", () => {
    expect(/42 signatures/i.test(текст)).toBe(true);
    expect(/20 of them revoked/i.test(текст)).toBe(true);
  });

  it("отрицательный контроль проверяльщика назван, а не только положительный", () => {
    /*
     * Половина, ради которой архив вообще убедителен: проверяльщик, который
     * на всё отвечает OK, доказывает ноль. Если со страницы исчезнет команда с
     * отозванной подписью, останется реклама.
     */
    expect(/manifest-control-revoked/.test(текст)).toBe(true);
    expect(/must fail|refused/i.test(текст)).toBe(true);
  });

  /*
   * ПОВОД 11.10. До этого дня страница заканчивалась словами «ответьте на
   * письмо, и мы пришлём архив». Это и был единственный шаг, требовавший от
   * занятого инженера ответить на холодное письмо: за четыре дня при трёх
   * живых переходах ответов пришло ноль. Архив выложен статикой, ссылка
   * прямая. Эти три проверки держат связь между ОБЕЩАНИЕМ и ФАЙЛОМ: обещание
   * без файла даст покупателю 404 на самом убедительном месте страницы.
   */
  const АРХИВ = join(КОРЕНЬ, "..", "..", "public", "aevion-verify.zip");

  it("архив лежит там, куда ведёт ссылка", () => {
    expect(existsSync(АРХИВ), `нет файла ${АРХИВ} — ссылка на странице даст 404`).toBe(true);
    expect(statSync(АРХИВ).size).toBeGreaterThan(5000);
  });

  it("ссылка на архив прямая, без формы и без ответа на письмо", () => {
    expect(/aevion-verify\.zip/.test(текст), "со страницы исчезла прямая ссылка на проверяльщик").toBe(
      true,
    );
    // Обещание «ответьте, и мы пришлём» вернуться не должно: оно и было узким местом.
    expect(/Reply to the letter and we send/i.test(текст)).toBe(false);
  });

  it("число файлов на странице равно числу файлов В АРХИВЕ", () => {
    /*
     * Считаем по записи конца центрального каталога (подпись PK\x05\x06,
     * общее число записей — два байта по смещению 10). Подпись локального
     * заголовка PK\x03\x04 для счёта не годится: она случайно встречается
     * внутри сжатых данных, то есть давала бы завышенный счёт.
     */
    const b = readFileSync(АРХИВ);
    let eocd = -1;
    for (let i = b.length - 22; i >= 0; i--) {
      if (b[i] === 0x50 && b[i + 1] === 0x4b && b[i + 2] === 0x05 && b[i + 3] === 0x06) {
        eocd = i;
        break;
      }
    }
    expect(eocd, "в архиве не найдена запись конца каталога — это не zip").toBeGreaterThan(-1);
    const вАрхиве = b.readUInt16LE(eocd + 10);
    const наСтранице = текст.match(/(\d+)\s*files,\s*no dependencies/i);
    expect(наСтранице, "страница перестала называть число файлов архива").not.toBeNull();
    expect(Number(наСтранице![1]), `страница обещает ${наСтранице![1]}, в архиве ${вАрхиве}`).toBe(
      вАрхиве,
    );
  });

  it("не предполагает, что у читателя есть наше письмо", () => {
    /*
     * ПОВОД 11.10. Страница открывалась словами «You received a letter from us»
     * и трижды отсылала «reply to the letter». Самый вероятный путь к решающему
     * человеку — пересылка: инженер отправляет ссылку юристу или в закупки, и
     * тот открывает страницу без письма. Плюс /proof лежит в карте сайта (731
     * адрес), то есть приходят и из поиска. Для такого читателя первая фраза
     * была ложной, а инструкция — невыполнимой.
     *
     * Сторож держит ровно это: утверждение о письме допустимо условное
     * («если пришли из письма»), безусловное — нет.
     */
    expect(
      /You received a letter from us/i.test(текст),
      "страница снова утверждает, что письмо у читателя есть",
    ).toBe(false);
    // И обязана сказать пересланному, что проверить нас можно без нас.
    expect(/forwarded/i.test(текст), "нет слова для того, кому ссылку переслали").toBe(true);
    /*
     * Пробелы через \s+, а не литералом: исходник свёрнут по 90 знаков, и фраза
     * «requires contacting us» разорвана переносом между словами. Образец с
     * литеральным пробелом дал ЛОЖНОЕ «обещания нет» — третий раз за день один
     * и тот же класс (тот же перенос ослепил сторож числа файлов и образец
     * «no dependencies» в блок-цитате). На свёрнутом тексте пробел — это \s+.
     */
    expect(/(?:without\s+\S{0,20}\s*|requires\s+)contacting\s+us/i.test(текст)).toBe(true);
  });

  it("страница серверная: её видно без браузера", () => {
    /*
     * Замер 02.10: /bureau отдаёт не-браузеру 719 знаков «Загрузка…» против
     * 5011 после отрисовки. Для посадочной из письма это смерть: часть
     * получателей откроет ссылку в почтовом клиенте или предпросмотре.
     */
    expect(/^"use client"/m.test(текст), "страница стала клиентской — её не увидит ни краулер, ни предпросмотр").toBe(
      false,
    );
  });
});
