/**
 * У модуля, который продаётся, на его собственной странице есть путь к оплате.
 *
 * Замер 30.08.2026. Ссылки на модули мы раздаём — в соцсетях, в письмах, в
 * карточках. Пришедший по прямой ссылке видит страницу модуля, а не витрину. Если
 * там нет ни цены, ни кнопки, он не узнаёт, что продукт платный, и уходит.
 *
 * Это тише всего, что ловится: противоречие человек видит и спрашивает, молчание
 * не видит по определению.
 *
 * ⚠️ ИСТОРИЯ ПРИБОРА, потому что она полезнее самой проверки.
 *
 * Путь к оплате искали двумя способами, и оба соврали. Обход по разметке искал
 * `<BuyLink`; браузерная проба соседнего окна искала кнопку со словом «Купить».
 * У DevHub кнопка называется «Upgrade — $149/mo» и сделана обычной ссылкой —
 * оба прибора её пропустили, и находка «DevHub не продаётся со своей страницы»
 * прожила несколько часов, попав в отчёт основателю, пока не была отозвана.
 *
 * Оба вопроса были заданы ИМЕНЕМ, а не смыслом. Поэтому здесь список признаков,
 * и он про способность: плашка цены, кнопка апгрейда, ссылка в кассу, вызов
 * ручки чекаута, платная стена. Любой из них означает, что путь к оплате есть.
 *
 * Признак `ModulePricingChip` добавлен последним и закрыл главную слепоту:
 * четыре модуля продают именно им, а он живёт в общих компонентах, вне
 * поддерева модуля.
 *
 * ⚠️ ГРАНИЦА, названная честно. Проверка статическая: она видит, что путь
 * ЕСТЬ В КОДЕ, но не видит, отрисуется ли он живому посетителю. У шахмат
 * плашка обёрнута в пять условий, и браузерная проба показала, что цены на
 * экране нет вовсе. Такое ловится только браузером — здесь оно записано в
 * список известных, а не притворяется проверенным.
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = resolve(HERE, "..");
const SRC = resolve(APP, "..");

/** Известные случаи. Список обязан только сокращаться. */
const KNOWN_SILENT = [
  // bureau СНЯТ из списка 29.09.2026 — путь к оплате на странице появился.
  //
  // Что было: с 30.08 здесь стояло «$29 в каталоге, на странице ни плашки, ни
  // кнопки», и отдельный храповик следил, чтобы запись не сняли впустую.
  //
  // Что стало: 28.09 на /bureau поставлен чип цены, выкачено в 24fbe418365a.
  // Проверено БРАУЗЕРОМ 29.09, а не поиском по коду: страница цен по ссылке
  // чипа показывает карточку «$32/мес · $32 за месяц» и кнопку «Купить IP
  // Bureau»; касса на это отвечает настоящей ссылкой Lemon Squeezy
  // (`tierId: lite`, `app: ip_bureau` → 200, mode real), и все пять сроков
  // бюро числятся продаваемыми в checkout/healthz.
  //
  // ⚠️ Прежний комментарий ПРЕДУПРЕЖДАЛ, что ModulePricingChip сюда не годится:
  // «показывает тарифы платформы, а купить Бюро по-прежнему нельзя». На 31.08
  // это было верно — отдельной продажи модулей тогда не было. Сегодня она есть,
  // и предупреждение устарело. Оставляю его след здесь, чтобы следующий не
  // принял снятие записи за небрежность: старое возражение проверено и снято
  // замером, а не молча затёрто.
  //
  // Что НЕ закрыто и к этому списку отношения не имеет: платный шаг
  // «Upgrade to Verified ($19)» за сертификат — ручка отвечает 503
  // (identity и payment на заглушке). Это другой товар, и он честно не
  // предлагается: кнопка спрашивает состояние бюро и показывает отказ отказом.
  // Плашка есть, но за пятью условиями (идёт партия, задача, режим стримера,
  // онбординг). В обычном состоянии цены на экране нет — измерено браузером.
  // Статически этот случай выглядит здоровым, поэтому он ЗДЕСЬ, а не в
  // результате проверки: иначе сторож молчал бы о нём вечно.
  "cyberchess",
];

const SIGNALS: Array<[string, (s: string) => boolean]> = [
  ["плашка цены", (s) => renders(s, "ModulePricingChip")],
  ["кнопка апгрейда", (s) => renders(s, "UpgradeButton")],
  ["BuyLink", (s) => renders(s, "BuyLink")],
  ["ссылка в кассу", (s) => s.includes("lemonsqueezy.com") || s.includes("gumroad.com")],
  // 15.09.2026: пять приложений продаются через страницу цен с выбранным
  // приложением — это и есть их касса (оттуда заказ уходит полем `app`).
  ["ссылка к выбору срока", (s) => s.includes("/pricing?app=") || s.includes("PRICING_APP(")],
  ["ручка чекаута", (s) => s.includes("/api/pricing/checkout") || s.includes("checkout/session")],
  ["платная стена", (s) => renders(s, "PaywallScreen") || renders(s, "PaywallModal")],
];

/**
 * Признаки оплаты в ИСХОДНИКЕ страницы.
 *
 * Срез комментариев живёт ЗДЕСЬ, в одной функции, а не у каждого вызывающего:
 * пока каждый читал файл сам, контроль звал срез своей рукой и проверял
 * композицию, которую сам же собрал, а не боевой путь. Мутация такого среза
 * прошла бы молча.
 */
function signalsIn(source: string): string[] {
  const text = stripComments(source);
  return SIGNALS.filter(([, test]) => test(text)).map(([name]) => name);
}

function walk(dir: string, out: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    if (entry === "__tests__") continue;
    const p = join(dir, entry);
    try {
      if (statSync(p).isDirectory()) walk(p, out);
      else if (p.endsWith(".tsx") || p.endsWith(".ts")) out.push(p);
    } catch {
      /* каталог исчез между обходом и чтением — не наш случай */
    }
  }
  return out;
}

/** Продаваемые модули каталога: есть цена и это модуль, а не книга. */
function soldModules(): Array<{ id: string; dir: string }> {
  const cat = readFileSync(join(SRC, "lib", "products.ts"), "utf8");
  const anchors = [...cat.matchAll(/id:\s*"([a-z0-9-]+)"/g)].map((m) => ({
    id: m[1],
    at: m.index ?? 0,
  }));
  const dirs = readdirSync(APP, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name);
  const out: Array<{ id: string; dir: string }> = [];
  for (let i = 0; i < anchors.length; i += 1) {
    const end = i + 1 < anchors.length ? anchors[i + 1].at : cat.length;
    const win = cat.slice(anchors[i].at, end);
    // Цена бывает литералом (гайды) или вычислением из лестницы сроков
    // (appBase("…"), политика 15.09.2026) — оба значат «продаётся».
    if (!/priceUsd:\s*(\d+|appBase\(|PLANET_BASE_MONTHLY)/.test(win)) continue;
    const kind = /kind:\s*"([a-z]+)"/.exec(win);
    if (kind && kind[1] !== "module") continue;
    const app = /appId:\s*"([a-z0-9-]+)"/.exec(win);
    const dir = [app?.[1], anchors[i].id].find((d) => d && dirs.includes(d));
    if (dir) out.push({ id: anchors[i].id, dir });
  }
  return out;
}

function signalsFor(dir: string): string[] {
  const found = new Set<string>();
  for (const f of walk(join(APP, dir))) {
    for (const name of signalsIn(readFileSync(f, "utf8"))) found.add(name);
  }
  return [...found];
}

describe("продаваемый модуль предлагает оплату на своей странице", () => {
  const sold = soldModules();
  const silent = sold.filter((m) => signalsFor(m.dir).length === 0).map((m) => m.id);

  test("контроль: продаваемые модули найдены", () => {
    // Пустой список сделал бы всё ниже зелёным при любом состоянии сайта.
    expect(sold.length, `найдено: ${sold.map((m) => m.id).join(", ")}`).toBeGreaterThanOrEqual(5);
  });

  test("контроль: способ различает страницу с оплатой и без", () => {
    // Витрина обязана определяться как продающая — иначе список признаков слеп,
    // и «все продают» будет означать «я ничего не умею видеть».
    const shop = readFileSync(join(APP, "shop", "page.tsx"), "utf8");
    expect(
      signalsIn(shop).length > 0,
      "витрина не опознана как продающая — список признаков слеп",
    ).toBe(true);
    // И наоборот: страница заведомо не продающая не должна давать признаков.
    const legal = join(APP, "terms", "page.tsx");
    if (existsSync(legal)) {
      expect(
        signalsIn(readFileSync(legal, "utf8")).length > 0,
        "условия использования опознаны как продающая страница — признак слишком широк",
      ).toBe(false);
    }
  });

  test("контроль: признак отличает ОТРИСОВКУ от упоминания", () => {
    // Четыре случая, и каждый стоил разбора на живом коде.
    const nl = String.fromCharCode(10);

    // 1. Только в комментарии — не признак. Страница может объяснять, почему
    //    плашки цены на ней нет; объяснение не продаёт.
    expect(
      signalsIn("// ModulePricingChip тут не нужен" + nl + "/* <PaywallScreen /> тоже */" + nl + "export default function P() { return null; }").length,
      "комментарий засчитан как способ заплатить — модуль без оплаты сойдёт за продающий",
    ).toBe(0);

    // 2. Опечатка в имени — не признак. Отрисовки `UpgradeButtonX` в React не
    //    существует, кнопка бы исчезла, а сторож остался бы зелёным.
    expect(
      signalsIn("export default function P() { return <UpgradeButtonX />; }").length,
      "опечатка в имени компонента засчитана как настоящая кнопка",
    ).toBe(0);

    // 3. Приставка в имени — ПРИЗНАК. Настоящая кнопка называется
    //    PaddleUpgradeButton, и таких страниц девять из девяти.
    expect(
      signalsIn("export default function P() { return <PaddleUpgradeButton appId={1} />; }").length,
      "настоящая кнопка апгрейда не опознана — сторож покраснеет на исправных модулях",
    ).toBeGreaterThan(0);

    // 4. Имя в коде, но без отрисовки — не признак. Мёртвый импорт не продаёт.
    expect(
      signalsIn("import { ModulePricingChip } from " + JSON.stringify("@/x") + ";" + nl + "export default function P() { return null; }").length,
      "неиспользованный импорт засчитан как плашка цены",
    ).toBe(0);
  });

  test("новых молчащих модулей нет", () => {
    const fresh = silent.filter((id) => !KNOWN_SILENT.includes(id));
    expect(
      fresh,
      `модуль продаётся, а со своей страницы купить нельзя: ${fresh.join(", ")}`,
    ).toEqual([]);
  });

  /*
   * Храповик по bureau снят 29.09.2026 вместе с самой записью: путь к оплате
   * на странице появился и проверен браузером. Держать проверку «всё ещё
   * молчит» после этого — значит требовать, чтобы дефект НЕ чинился.
   *
   * Что теперь стережёт бюро: основная проверка выше. Как только со страницы
   * снимут путь к оплате, bureau снова попадёт в её список — и красным, а не
   * записью в списке известных.
   */
});
