import { describe, test, expect } from "vitest";

import { CITY } from "../src/routes/qskyway.city";
import { CITY_NYC } from "../src/routes/qskyway.city.nyc";
import { CITY_TOKYO } from "../src/routes/qskyway.city.tokyo";
import { CITY_AMSTERDAM } from "../src/routes/qskyway.city.amsterdam";
import { CITY_BERLIN } from "../src/routes/qskyway.city.berlin";
import type { CityData } from "../src/routes/qskyway.city";

/**
 * Сколько высот в твине ВЫДУМАНО — величина, которую легко ухудшить молча.
 *
 * Твин пересобирается скриптом из Overpass, и ответ Overpass меняется от
 * прогона к прогону: он умеет отдать HTTP 200 с УРЕЗАННЫМ списком элементов,
 * сообщив об этом только в `remark` (так в июле в твин Нью-Йорка не попал
 * вокзал Пенн). Урезанный ответ означает больше зданий без тегов, то есть
 * больше слепых 12-метровых высот — и никакого признака беды в самих данных.
 *
 * Поэтому доля угаданных высот здесь прибита. Тест не запрещает пересборку:
 * он требует, чтобы ухудшение профиля данных ЗАМЕТИЛИ и обновили числа руками,
 * а не узнали о нём через полгода. Замер 12.08.2026 —
 * `npm run audit:guessed-heights <город>` печатает эти же цифры.
 */

const PROFILE: Record<string, { twin: CityData; total: number; measured: number; guessed: number }> = {
  // Астана: городского обмера нет вовсе, тег несущий — тут слепота дороже всего
  // 15.09.2026: у Астаны появился обмер — 3D-модель зданий города
  // (gis.esaulet.kz, Build_151222): 264 из 476 по центроиду внутри контура OSM.
  // Вечером того же дня — контуры города (выпуклые оболочки мешей): +165 зданий,
  // которых в OSM нет, и обмер по центроиду OSM внутри контура: 532 из 641 (тег 382 м Абу-Даби Плазы выше обмера 311 — остаётся тегом, hs=1).
  astana: { twin: CITY, total: 641, measured: 532, guessed: 77 },
  // Нью-Йорк и Токио: высоты перекрыты городским обмером
  // 12.08.2026: пересборка добавила один обмеренный дом (2879 → 2880).
  nyc: { twin: CITY_NYC, total: 2976, measured: 2880, guessed: 28 },
  tokyo: { twin: CITY_TOKYO, total: 3781, measured: 3504, guessed: 116 },
  // Амстердам (16.09.2026): лидар 3D BAG по каждому зданию страны — 559 из 586
  // по ядру Зёйдаса, +88 контуров, которых в OSM нет. Сингапура в профиле нет
  // намеренно: у него обмера ноль, и прибивать «не меньше нуля» нечего.
  amsterdam: { twin: CITY_AMSTERDAM, total: 586, measured: 559, guessed: 21 },
  // Берлин (16.09.2026): LoD2 Сената (WFS Umweltatlas) — 264 из 274 по квадрату
  // Потсдамер-плац. 274, а не 1935: 1661 «здания» первой сборки были стелами
  // Мемориала (2.4×0.95 м, building=yes) — контуры <5 м² сборщик теперь отсекает.
  berlin: { twin: CITY_BERLIN, total: 274, measured: 264, guessed: 3 },
};

describe("профиль слепых высот в твинах", () => {
  // Тот же предохранитель: профиль перебирается по PROFILE, и пустой объект
  // дал бы зелёный файл без единой проверки.
  test("профиль описывает все пять городов с обмером", () => {
    expect(Object.keys(PROFILE).length).toBe(5);
  });

  for (const [city, p] of Object.entries(PROFILE)) {
    test(`[${city}] доля угаданных высот не выросла молча`, () => {
      const dq = p.twin.dataQuality;
      expect(dq.total).toBe(p.total);
      // Пол, а не точка. Строгое равенство здесь краснело на УЛУЧШЕНИИ данных:
      // 12.08.2026 пересборка Нью-Йорка добавила один обмеренный дом (2879 →
      // 2880), и сторож упал на том, ради чего он и стоит. Такой тест не чинят —
      // его удаляют вместе с настоящим покрытием, а покрытие тут настоящее:
      // урезанный ответ источника означал бы обвал числа обмеров, и заметить
      // это надо в ту же минуту, а не через полгода.
      expect(dq.measured).toBeGreaterThanOrEqual(p.measured);
      // Та же логика с другой стороны: слепых высот не стало БОЛЬШЕ.
      expect(dq.guessed).toBeLessThanOrEqual(p.guessed);
    });
  }

  test("[astana] обмера нет ни у одного здания — это свойство города, а не сбой сборки", () => {
    // Если однажды у Астаны появится городской обмер, тест упадёт, и это
    // правильный повод пересмотреть и класс высот, и текст на странице.
    // 15.09.2026: это и случилось — обмер пришёл из 3D-модели города. Теперь
    // храповик в другую сторону: измеренных не меньше, чем при подключении.
    expect(CITY.dataQuality.measured).toBeGreaterThanOrEqual(532);
    expect(CITY.dataQuality.measuredPct).toBeGreaterThanOrEqual(83);
    expect(CITY.dataQuality.source).toContain("esaulet");
  });
});
