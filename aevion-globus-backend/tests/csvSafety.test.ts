import { describe, test, expect } from "vitest";

/**
 * Защита CSV-выгрузок — под присмотром CI.
 *
 * Удвоение кавычек закрывает структуру файла, но не читателя: значение с ведущим
 * `=`, `+`, `-`, `@` Excel и Google Sheets исполняют как ФОРМУЛУ при открытии.
 * В выгрузках AEVION лежат поля, которые заполняет посторонний — User-Agent
 * просмотра документа в QContract, текст переписок Multichat и QCoreAI, имя и
 * сообщение соискателя, email и utm-метки лида, заголовки объектов QRight,
 * description транзакций QPayNet. Открывает файл администратор. 26.07.2026
 * защиты не было ни в одном из 16 экспортов.
 *
 * Тест держит ОБЕ стороны, и вторая не менее важна первой: защита, ломающая
 * живые значения, будет снята первым же, кому она помешает.
 *
 * Рядом лежит scripts/csv-safety-test.js — тот же набор против СОБРАННОГО dist.
 * Здесь проверяется исходник, чтобы регрессия краснела в PR, а не после сборки.
 */

import { csvEscape, csvNeutralizeFormula, csvFromRows } from "../src/lib/csv";

describe("csv formula injection", () => {
  test.each([
    ["=cmd|'/c calc'!A0"],
    ['=HYPERLINK("http://evil","click")'],
    ["+1+1"],
    ["-2+3"],
    ["@SUM(A1)"],
    ["\tведущая табуляция"],
    ["\rведущий возврат каретки"],
  ])("гасится: %j", (payload) => {
    expect(csvNeutralizeFormula(payload)).toBe(`'${payload}`);
  });

  test("csvEscape гасит формулу ДО оборачивания в кавычки", () => {
    // Иначе апостроф окажется не первым символом ячейки и Excel всё равно
    // посчитает её формулой.
    expect(csvEscape("=1+1")).toBe("\"'=1+1\"");
  });
});

describe("живые данные не портятся", () => {
  test.each([
    ["ivan@mail.ru", "e-mail: не начинается с @, под правило не попадает"],
    ["Mozilla/5.0 (Windows NT 10.0)", "User-Agent"],
    ["Иван Петров", "кириллица"],
    ["Астана-2026", "минус внутри строки — не формула"],
  ])("проходит без изменений: %j (%s)", (value) => {
    expect(csvNeutralizeFormula(value)).toBe(value);
  });

  test("отрицательное число гасится намеренно", () => {
    // Ложноположительное срабатывание, с которым мирятся: отличить «-5» от
    // формулы «-5+A1» на уровне ячейки нельзя, а цена ошибки несимметрична.
    expect(csvNeutralizeFormula("-5")).toBe("'-5");
  });
});

describe("структура CSV цела", () => {
  test("кавычки удваиваются", () => {
    expect(csvEscape('он сказал "да"')).toBe('"он сказал ""да"""');
  });

  test("запятая внутри поля", () => {
    expect(csvEscape("Петров, Иван")).toBe('"Петров, Иван"');
  });

  test("перенос строки внутри поля", () => {
    expect(csvEscape("строка1\nстрока2")).toBe('"строка1\nстрока2"');
  });

  test("null и число", () => {
    expect(csvEscape(null)).toBe('""');
    expect(csvEscape(42)).toBe('"42"');
  });

  test("строка из значений", () => {
    expect(csvFromRows([["=1+1", "ok"]])).toBe("\"'=1+1\",\"ok\"");
  });
});
