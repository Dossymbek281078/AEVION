import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Замер прода 08.09.2026, экран 360×640: единственное поле ввода страницы
 * /devhub/launch стояло на 697px при сгибе 640. Человек, пришедший по письму
 * в день запуска, не видел действия, ради которого посадочная существует.
 *
 * Откуда 697: 234px — общая шапка сайта, 287 — заголовок с абзацем из четырёх
 * предложений, и форма начиналась уже за экраном (её собственные заголовок с
 * описанием добавляют к началу поля ещё 158). На 390×844 всё было в порядке,
 * поэтому глазами это не находилось.
 *
 * Настоящую высоту меряет только браузер, и такой пробы в наборе нет — она
 * дорога и требует прода. Здесь закреплены две вещи, которые до высоты
 * ДОВОДЯТ и меняются в коде: порядок блоков и длина текста над формой.
 * Граница честная: зелёный этого файла не значит «поле видно», он значит
 * «то, что подняло поле, никто не откатил».
 */
const LAUNCH = fs.readFileSync(path.resolve(__dirname, "..", "launch", "page.tsx"), "utf8");

/** Текст первого абзаца — того, что стоит между заголовком и формой. */
function heroParagraph(): string {
  const form = LAUNCH.indexOf("<WaitlistCapture");
  // Именно lastIndexOf: та же фраза стоит ВЫШЕ, в metadata страницы, и поиск
  // с начала брал бы её — кусок разрастался до всего тела функции (2006 знаков
  // против настоящих 150), и любой порог оказывался бы ложно-красным.
  const h1 = LAUNCH.lastIndexOf("Опишите приложение словами", form);
  expect(h1, "заголовок не найден — сторож мерит не ту страницу").toBeGreaterThan(0);
  expect(form, "формы на странице нет вовсе").toBeGreaterThan(0);
  const between = LAUNCH.slice(h1, form);
  // Только видимый текст: без разметки, стилей и комментариев.
  return between
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, " ")
    .replace(/<[^>]*>/g, " ")
    .replace(/\{[^}]*\}/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

describe("на посадочной запуска поле адреса не уезжает под сгиб", () => {
  test("прибор работает: текст между заголовком и формой найден и непуст", () => {
    const p = heroParagraph();
    expect(p.length, "прибор ничего не нашёл — дальше любой порог был бы зелёным").toBeGreaterThan(30);
    expect(p, "должен остаться пример запроса — ради него сюда и приходят").toContain("помодоро");
  });

  /**
   * Порог — не вкус. На 360px строка вмещает около 45 знаков, строка занимает
   * ~23px. Замеренный лишний путь до поля был ~120px, то есть примерно пять
   * строк, или ~230 знаков. Оставляем запас: 320 знаков — это ещё ~7 строк,
   * при которых поле остаётся в первом экране.
   */
  test("текст над формой не отрастает обратно", () => {
    const p = heroParagraph();
    expect(
      p.length,
      `над формой снова ${p.length} знаков: на 360×640 это уводит поле адреса за экран`,
    ).toBeLessThanOrEqual(320);
  });

  test("форма стоит ВЫШЕ длинного объяснения, а не под ним", () => {
    const form = LAUNCH.indexOf("<WaitlistCapture");
    const tail = LAUNCH.indexOf("Начинать со списка возможностей");
    expect(tail, "объяснение исчезло — проверьте, не потеряно ли оно вовсе").toBeGreaterThan(0);
    expect(
      form,
      "объяснение снова выше формы — поле адреса уедет под сгиб на маленьком экране",
    ).toBeLessThan(tail);
  });

  test("объяснение не потеряно при переносе, оба предложения на месте", () => {
    expect(LAUNCH, "пропало предложение про список возможностей").toContain("он ниже");
    expect(LAUNCH, "пропало предложение про дату открытия").toContain("Дату открытия объявим");
  });
});
