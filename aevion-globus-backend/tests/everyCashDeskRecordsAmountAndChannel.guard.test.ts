import { describe, it, expect } from "vitest";
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { stripComments } from "./helpers/sourceCode";

/**
 * Каждая касса записывает СУММУ и КАНАЛ, а не только факт покупки.
 *
 * ЗАЧЕМ. Панель «фактически списано по каналам» считает по двум полям записи
 * подписки: `amountUsd` и `channel`. Касса, которая их не передаёт, попадает
 * в панель как покупка БЕЗ денег и с каналом «direct» — цифра при этом есть,
 * она правдоподобна и она неверна. Заметить это можно только сравнив кассы
 * между собой, потому что каждая по отдельности выглядит исправной.
 *
 * ЗАМЕР 03.09.2026, из-за которого сторож и написан:
 *
 *     paypalWebhook       amountUsd 0  ← единственная без суммы
 *     payboxWebhook       amountUsd 3
 *     gumroadWebhook      amountUsd 1
 *     lemonSqueezyWebhook amountUsd 2
 *
 * Канал у PayPal при этом ДОЕЗЖАЛ и выбрасывался при разборе `custom_id` —
 * нашло соседнее окно. Обе половины закрыты, сторож не даёт им разойтись
 * снова и не даёт ПЯТОЙ кассе появиться без этих полей.
 *
 * ГРАНИЦА ЧЕСТНАЯ. Это проверка ИСХОДНИКА: она видит, что поле упомянуто, и
 * не доказывает, что оно доедет до записи при всех входах. Поведение
 * проверяется отдельными тестами каждой кассы; здесь — симметрия, которую
 * иначе не проверяет никто.
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const ROUTES = join(HERE, "..", "src", "routes");

/** Файлы вебхуков касс — по имени, потому что имя тут и есть признак. */
function кассы(): string[] {
  return readdirSync(ROUTES).filter((f) => /Webhook\.ts$/.test(f) && !/qsign|planet/i.test(f));
}

/**
 * Исходник БЕЗ комментариев, и поле ищется как ПРИСВАИВАНИЕ.
 *
 * ⚠️ Первая редакция искала просто `amountUsd` в тексте файла — и мутацию
 * «сумма убрана» НЕ ловила: слово оставалось в моём же комментарии про эту
 * находку и в имени переменной `paypalAmountUsd`. То есть сторож охранял
 * собственное объяснение вместо кода. Поймано мутацией, не чтением.
 */
function код(file: string): string {
  return stripComments(readFileSync(join(ROUTES, file), "utf8"));
}

/**
 * Поле ПЕРЕДАЁТСЯ в запись, а не просто упомянуто.
 *
 * В ходу обе формы, и обе законные:
 *
 *     { amountUsd: paidUsd }      явная
 *     { amountUsd }               сокращённая (paybox, lemonSqueezy)
 *
 * Требовать только первую — сторож краснеет на исправном коде; принимать
 * любое упоминание — сторож зеленеет на `const amountUsd = ...`, оставшемся
 * без передачи. Поэтому ровно две формы.
 */
function передаётся(src: string, поле: string): boolean {
  return src.includes(поле + ":") || src.includes("{ " + поле + " }");
}

describe("все кассы записывают сумму и канал", () => {
  const files = кассы();

  it("контроль: кассы найдены, и их несколько", () => {
    // Пустой список сделал бы проверки ниже зелёными при любом состоянии.
    expect(files.length, `найдено: ${files.join(", ")}`).toBeGreaterThanOrEqual(4);
  });

  it("контроль: способ отличает упомянутое поле от неупомянутого", () => {
    const src = код(files[0]);
    expect(передаётся(src, "amountUsd"), "не вижу поле, которое ТОЧНО есть").toBe(true);
    expect(передаётся(src, "amountUsdНетТакогоПоля"), "вижу выдуманное поле").toBe(false);
  });

  it("ни одна касса не теряет сумму", () => {
    const без = files.filter((f) => !передаётся(код(f), "amountUsd"));
    expect(
      без,
      "касса не передаёт сумму: её покупки попадут в панель «фактически списано» " +
        "без денег, и знаменатель withAmount занизит именно этот канал",
    ).toEqual([]);
  });

  it("ни одна касса не теряет канал", () => {
    const без = files.filter((f) => !передаётся(код(f), "channel"));
    expect(
      без,
      "касса не передаёт канал: её покупки лягут как «direct», и разбивка по " +
        "каналам занизит тот канал, который приводит этих покупателей",
    ).toEqual([]);
  });
});
