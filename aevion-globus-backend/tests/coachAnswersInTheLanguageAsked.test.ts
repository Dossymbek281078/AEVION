/**
 * Русский вопрос — русский ответ, и не огрызок.
 *
 * ПОВОД 29.09.2026: приёмка спросила по-русски «3 причины 1.e4» и получила
 * «Η απάντηση…» — греческий, оборванный на 79 знаках. Требование языка живёт
 * в промпте, то есть это просьба, а не механизм: тот же класс, что «ходы
 * только из отчёта».
 *
 * Признаки намеренно грубые и односторонние — ложная тревога здесь дороже
 * пропуска, потому что прячет полезный ответ.
 */

import { describe, it, expect } from "vitest";
import { языкНеТот, ответОгрызок } from "../src/routes/coach";

const ГРЕЧЕСКИЙ = "Η απάντηση σε αυτό το ερώτημα είναι απλή: ο έλεγχος του κέντρου";

describe("язык ответа", () => {
  it("русский вопрос → греческий ответ ловится", () => {
    expect(языкНеТот("Назови 3 причины играть 1.e4", ГРЕЧЕСКИЙ)).toBe(true);
  });

  it("русский вопрос → английский ответ тоже ловится", () => {
    expect(языкНеТот("Что играть?", "The best move here is Nf3, controlling the center.")).toBe(true);
  });

  it("🔴 контроль: настоящий русский разбор С ЛАТИНСКИМИ ХОДАМИ проходит", () => {
    // Иначе мы прятали бы нормальные ответы: ходы у нас часто латиницей.
    expect(языкНеТот("Что играть?", "Играй Nf3 — конь держит e5 и готовит рокировку.")).toBe(false);
  });

  it("контроль: латинский вопрос не судим", () => {
    expect(языкНеТот("What should I play?", "Play Nf3, it controls the center.")).toBe(false);
  });

  it("🔴 КОРОТКИЙ чужеязычный ответ ловится — порог был дырой", () => {
    // Настоящий случай приёмки 30.09: на русский вопрос пришло
    // «The Hindi phrase \» — 18 знаков, то есть КОРОЧЕ прежнего порога в 20,
    // и признак языка молчал. Короткий чужеязычный ответ не «слишком мал,
    // чтобы судить», а самый очевидный брак.
    expect(языкНеТот("Объясни по-русски: зачем защищать центр?", "The Hindi phrase \\")).toBe(true);
  });

  it("контроль: ХОД латиницей ответом на чужом языке НЕ считается", () => {
    // Ради этого и был порог: «Nf3» — ход, а не проза, кириллицы в нём нет
    // законно. Теперь условие про СЛОВО (три латинские буквы подряд), а не
    // про длину.
    expect(языкНеТот("Что играть?", "Nf3")).toBe(false);
    expect(языкНеТот("Что играть?", "e4 e5 Nf3")).toBe(false);
    expect(языкНеТот("Что играть?", "O-O")).toBe(false);
  });
});

describe("огрызок", () => {
  it("короткое вступление без конца — огрызок", () => {
    expect(ответОгрызок("Отличный вопрос! Давай разберёмся, что происходит на доске и какой")).toBe(true);
  });

  it("пустой ответ — огрызок", () => {
    expect(ответОгрызок("   ")).toBe(true);
  });

  it("🔴 контроль: длинный разбор без финальной точки НЕ прячем", () => {
    // Человек дочитает и поймёт; прятать полезное из-за пунктуации нельзя.
    const длинный = "Играй Nf3. ".repeat(20) + "и далее по плану";
    expect(длинный.length).toBeGreaterThan(200);
    expect(ответОгрызок(длинный)).toBe(false);
  });

  it("контроль: короткий, но законченный ответ проходит", () => {
    expect(ответОгрызок("Играй Nf3 — это лучший ход.")).toBe(false);
  });
  it("🔴 английский ответ с ОДНИМ русским словом больше не проходит", () => {
    // Замер 30.09: прежнее правило («есть хоть одна кириллица — свой язык»)
    // пропускало это. Тренера зовут Алексей, и модель охотно подписывается
    // его именем посреди английского текста — случай не выдуманный.
    const вопрос = "Один совет по дебюту новичку.";
    const почтиАнглийский =
      "Based on the description provided here is the text from the image: " +
      "AEVION CyberChess, the ultimate strategy game. (Алексей)";
    expect(языкНеТот(вопрос, почтиАнглийский)).toBe(true);
  });

  it("контроль: русский ответ с шахматной записью проходит", () => {
    // Законная латиница: ходы и имя движка. По замеру прода доля кириллицы у
    // таких ответов 92–100 %, порог стоит на 40 %.
    const вопрос = "Какой ход лучше?";
    const ответ =
      "Лучше Nf3: конь выходит с темпом и держит e5. Stockfish оценивает " +
      "позицию как равную, но у белых приятнее игра по линии d.";
    expect(языкНеТот(вопрос, ответ)).toBe(false);
  });

  it("контроль: ответ из одних ходов не судится по языку вовсе", () => {
    expect(языкНеТот("Что играть?", "1.e4 e5 2.Nf3 Nc6 3.Bb5")).toBe(false);
  });
});
