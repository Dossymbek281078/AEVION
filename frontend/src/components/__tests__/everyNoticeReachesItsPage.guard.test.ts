import { describe, test, expect } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { ALL_PRODUCTS } from "@/lib/products";

/**
 * Оговорка продукта доходит до страницы модуля, а не только до витрины цен.
 *
 * ЗАМЕР 04.09.2026 с контролем. У двух продуктов каталога есть `notice` —
 * «Демонстрационный режим. AEVION не является лицензированным банком… реальные
 * средства и платежи не обрабатываются». Поиск этих слов давал:
 *
 *     lib/products.ts        3 вхождения   ← контроль, там они точно есть
 *     app/payments/page.tsx  0
 *     app/qpaynet/page.tsx   0
 *     app/qcontract/page.tsx 0
 *
 * При этом обещания живут именно на страницах: дорожная карта `/payments`
 * помечает «12-rail unified checkout» и «Settlements — bank + AEC wallet» как
 * `live`. Человек, пришедший по ссылке или из поиска, видел только уверенную
 * половину, а оговорку — лишь если доходил до кассы.
 *
 * ГРАНИЦА ЧЕСТНАЯ. Сторож проверяет, что оговорка ОТРИСОВЫВАЕТСЯ где-то на
 * страницах модулей, а не что она стоит на правильной странице и на видном
 * месте. Второе проверяется глазами; здесь закрыт случай «оговорку добавили в
 * каталог и забыли показать вовсе».
 *
 * ВТОРАЯ ГРАНИЦА, про которую легко забыть: обход ищет ЛИТЕРАЛЬНУЮ запись
 * `productId="…"`. Если страница однажды начнёт передавать идентификатор
 * переменной (`productId={id}`), сторож её не увидит и покраснеет ЛОЖНО —
 * скажет «оговорка не показывается», хотя она показывается. Признак такого
 * ложного красного: продукт в списке потерянных, а на странице глазами видно
 * обращение к ProductNotice. Лечение — расширить разбор, а не убрать продукт
 * из каталога и не ослабить утверждение.
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, "..", "..", "app");

/** Идентификаторы, для которых где-нибудь на страницах отрисован ProductNotice. */
function покрытые(): Set<string> {
  const out = new Set<string>();
  const обход = (dir: string) => {
    for (const n of readdirSync(dir)) {
      if (n === "node_modules" || n === "__tests__") continue;
      const p = join(dir, n);
      if (statSync(p).isDirectory()) обход(p);
      else if (n === "page.tsx") {
        const s = readFileSync(p, "utf8");
        for (const m of s.matchAll(/<ProductNotice[^>]*productId="([a-z0-9-]+)"/g)) out.add(m[1]);
      }
    }
  };
  обход(APP);
  return out;
}

describe("оговорка продукта доходит до страницы модуля", () => {
  const есть = покрытые();
  const сОговоркой = ALL_PRODUCTS.filter((p) => p.notice).map((p) => p.id);

  test("контроль: продукты с оговоркой в каталоге вообще есть", () => {
    // Иначе «все покрыты» означало бы «покрывать нечего».
    expect(сОговоркой.length, "в каталоге не осталось оговорок").toBeGreaterThanOrEqual(1);
  });

  test("контроль: обход страниц вообще что-то находит", () => {
    // Иначе пустой результат читался бы как «оговорок нет нигде».
    expect(есть.size, "обход не нашёл ни одного ProductNotice — сломан поиск").toBeGreaterThanOrEqual(1);
  });

  test("ни одна оговорка не осталась только в каталоге", () => {
    const потерянные = сОговоркой.filter((id) => !есть.has(id));
    expect(
      потерянные,
      "у продукта есть оговорка, но на страницах модулей она не отрисовывается: " +
        "человек читает обещания и не видит условия, на которых они верны",
    ).toEqual([]);
  });
});
