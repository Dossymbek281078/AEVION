import type { Metadata } from "next";

/* Только canonical, ничего больше.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Посадочная запуска бюро наследовала canonical из
 * макета раздела (`bureau/layout.tsx` -> "/bureau") и говорила поисковику
 * «я копия раздела, показывай его вместо меня». Для посадочной это худший
 * случай: её и ищут отдельно от раздела — по названию продукта и по дате
 * запуска.
 *
 * Почему не правкой в page.tsx: у той страницы на 30.08.2026 ТРИ разные
 * версии по веткам, и точечная правка встретилась бы с чужой. Новый файл
 * конфликтовать не может по определению — проверено, что layout.tsx здесь
 * не существует ни в одной ветке.
 *
 * Заголовок и описание страница задаёт сама; здесь их намеренно НЕТ, чтобы
 * не спорить с ней. Next сливает метаданные сверху вниз, и page.tsx
 * перекрывает layout по тем полям, которые объявляет; canonical она не
 * объявляет, поэтому применится этот. */
export const metadata: Metadata = {
  alternates: { canonical: "/bureau/launch" },
};

export default function BureauLaunchLayout({ children }: { children: React.ReactNode }) {
  return <>{children}</>;
}
