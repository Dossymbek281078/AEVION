import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const PAGE = readFileSync(join(HERE, "..", "page.tsx"), "utf8");
const CAPTURE = readFileSync(join(HERE, "..", "..", "..", "..", "components", "WaitlistCapture.tsx"), "utf8");

/**
 * Подтверждение подписки называет ту же дату, что и вся страница.
 *
 * Замер 28.08.2026 через саму страницу на телефоне: человек оставляет адрес и
 * видит «Напишем, когда будет что показать» — расплывчатее, чем обещание над
 * формой («напишем в день запуска») и чем письмо, которое называет 30 августа.
 */
describe("подтверждение подписки на странице запуска", () => {
  test("страница передаёт своё подтверждение и называет дату", () => {
    const at = PAGE.indexOf("doneText=");
    expect(at, "страница не задаёт текст подтверждения").toBeGreaterThan(-1);
    // Сверяем подтверждение С ЗАГОЛОВКОМ страницы, а не с числом.
    // 30.08.2026 дату запуска перенесли, и эта проверка покраснела на
    // ВЕРНОЙ правке: она держала литерал «30 августа». Сторож, который
    // краснеет от переноса даты, отключат при следующем переносе.
    // Теперь он краснеет только когда подтверждение и заголовок
    // называют РАЗНЫЕ даты — то есть на настоящем расхождении.
    //
    // Ищем позиционно, без регулярки: собранный из строки шаблон здесь
    // уже терял обратные слэши и давал ложное «заголовка нет».
    const H = "Открываем ";
    const h = PAGE.indexOf(H);
    expect(h, "на странице нет заголовка «Открываем …»").toBeGreaterThan(-1);
    const date = PAGE.slice(h + H.length, h + H.length + 40)
      .split("<")[0].trim();
    expect(date.length, "после «Открываем» не удалось прочитать дату").toBeGreaterThan(3);
    expect(
      PAGE.slice(at, at + 160),
      "подтверждение не называет дату, которую обещает заголовок: " + date,
    ).toContain(date);
  });

  test("компонент действительно использует переданный текст, а не только свой", () => {
    // Иначе свойство было бы декоративным: страница его задаёт, а на экране
    // остаётся общий текст.
    expect(CAPTURE).toContain("setMessage(doneText || copy.done)");
  });

  test("умолчание компонента НЕ изменено — другие страницы не трогаем", () => {
    expect(CAPTURE).toContain('done: "Готово — адрес записан. Напишем, когда будет что показать."');
  });
});

describe("страница обещает ровно то, что проверено", () => {
  test("задача дня в списке — она настоящая с 28.08", () => {
    // Условие, из-за которого её убирали (365 позиций-пустышек на 18.08),
    // снято: прод отдаёт позицию из банка на 502 584 задачи.
    expect(PAGE).toContain("Задача дня из настоящего банка");
  });

  test("таблица лидеров НЕ обещана — она пуста", () => {
    // Проверено на проде: cpi/leaderboard возвращает items: []. Обещать
    // пустой рейтинг — ровно то, из-за чего страницы теряли доверие.
    const facts = PAGE.slice(PAGE.indexOf("Что уже работает"));
    expect(facts).not.toContain("таблица лидеров");
    expect(facts).not.toContain("Таблица лидеров");
  });

  test("причина возврата записана рядом с правкой", () => {
    // Иначе следующий читатель увидит противоречие с шапкой файла, где
    // написано «ни слова про задачу дня», и не поймёт, кто прав.
    expect(PAGE).toContain("ЗАДАЧА ДНЯ ВЕРНУЛАСЬ В СПИСОК");
  });
});
