import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/*
 * 🔴 СПИСКОВ ИМЁН СОБЫТИЙ ТРИ, А НЕ ДВА — и они обязаны сходиться.
 *
 * Что я знал до 07.10: списка два (фронт шлёт — сервер принимает), и за сутки
 * до этого я свёл воедино третью пару (сервер принимает — сервер умеет
 * спрашивать), потому что про `cta_click` ручка отвечала 400, пока события
 * лежали в журнале.
 *
 * Чего я НЕ знал: у фронта есть ещё и союз типов `EventType` в `lib/track.ts`.
 * Нашлось случайно — TypeScript отказался собирать новое событие `engaged`.
 * То есть третий список существовал, и его держала только проверка типов,
 * причём лишь на той половине, где её запускают.
 *
 * Поэтому утверждение здесь про КЛАСС: каждое имя из фронтового союза должно
 * приниматься сервером. Обратное НЕ требуется: сервер принимает и то, что
 * пишут вебхуки (подтверждение оплаты), — фронт такого не шлёт и знать не должен.
 *
 * Сторож читает ИСХОДНИК, и это его честная слабость: имена в союзе он берёт
 * регуляркой. Поэтому ниже стоит контроль прибора — он обязан найти заведомо
 * существующие имена; если список окажется пустым, сторож краснеет, а не
 * молчаливо «проверяет ноль имён».
 */
const КОРЕНЬ = join(__dirname, "..", "..");

function именаФронта(): string[] {
  const текст = readFileSync(join(КОРЕНЬ, "frontend", "src", "lib", "track.ts"), "utf8");
  const начало = текст.indexOf("export type EventType =");
  expect(начало, "союз типов EventType не найден — сторож смотрит не туда").toBeGreaterThan(-1);
  const конец = текст.indexOf(";", текст.indexOf("\n", начало));
  const блок = текст.slice(начало, конец);
  return [...блок.matchAll(/\|\s*"([a-z_]+)"/g)].map((m) => m[1]);
}

function именаСервера(): string[] {
  const текст = readFileSync(
    join(КОРЕНЬ, "aevion-globus-backend", "src", "routes", "events.ts"),
    "utf8",
  );
  const начало = текст.indexOf("export const ALLOWED_TYPES = new Set([");
  expect(начало, "ALLOWED_TYPES не найден — сторож смотрит не туда").toBeGreaterThan(-1);
  const конец = текст.indexOf("]);", начало);
  return [...текст.slice(начало, конец).matchAll(/"([a-z_]+)"/g)].map((m) => m[1]);
}

describe("три списка имён событий сходятся", () => {
  it("КОНТРОЛЬ прибора: оба списка непусты и содержат известные имена", () => {
    const ф = именаФронта();
    const с = именаСервера();
    // Без этого «все имена приняты» было бы истиной ни о чём: пустое множество
    // подходит под любое условие — на этом мы уже обжигались с byDay.
    expect(ф.length).toBeGreaterThanOrEqual(5);
    expect(с.length).toBeGreaterThanOrEqual(5);
    expect(ф).toContain("page_view");
    expect(с).toContain("page_view");
    expect(ф).toContain("engaged");
  });

  it("🔴 каждое имя, которое шлёт фронт, сервер ПРИНИМАЕТ", () => {
    const принимаются = new Set(именаСервера());
    const непринятые = именаФронта().filter((имя) => !принимаются.has(имя));
    expect(
      непринятые,
      `фронт шлёт имена, которые сервер отвергнет с 400: ${непринятые.join(", ")}`,
    ).toEqual([]);
  });

  it("🔴 про каждое принимаемое имя можно СПРОСИТЬ", async () => {
    // Третья пара, сведённая 06.10: список для чтения производный от списка
    // приёма, поэтому расхождение невозможно по устройству. Проверяем, что это
    // так и осталось, — иначе события снова будут лежать в журнале немыми.
    const { ALLOWED_TYPES } = await import("../src/routes/events");
    const принимаются = [...ALLOWED_TYPES];
    for (const имя of именаСервера()) {
      expect(принимаются, `имя ${имя} есть в исходнике, но не в наборе`).toContain(имя);
    }
  });
});
