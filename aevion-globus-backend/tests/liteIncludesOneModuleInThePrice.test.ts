import { describe, test, expect } from "vitest";
import { buildQuote, TIERS, TERM_TIERS, MODULES_PRICING, STANDALONE_APPS, getModulePrice } from "../src/data/pricing";

/**
 * Сторож: модуль, входящий в тариф, НЕ тарифицируется сверху — и платный там, где не входит.
 *
 * ИСТОРИЯ. 04.09.2026 здесь охранялся «бесплатный слот» Lite: один выбранный
 * модуль входил в цену, второй прибавлял. Мутация «убрать слот» НЕ ЛОВИЛАСЬ ничем,
 * а ошибка стоила денег в обе стороны:
 *   • включённое посчитано сверху → покупателю показывают лишнее, часть уходит;
 *   • платное раздали → мы отдаём модуль бесплатно там, где он платный.
 *
 * С 15.09.2026 (слово основателя) тариф — это СРОК доступа ко всей планете:
 * Lite больше не «один модуль на выбор», любой платный срок открывает все модули.
 * Слот исчез, но оба направления той же ошибки остались, и сторож держит их:
 *   • на любом платном сроке надстройка НЕ прибавляет к цене (всё в подписке);
 *   • на free надстройка приложения стоит его базу — иначе мы раздаём платное.
 *
 * Имя файла прежнее, чтобы история сторожа не терялась. Числа берутся ИЗ КАТАЛОГА.
 */
const надстройки = STANDALONE_APPS.map((a) => a.moduleId).filter((id) => (getModulePrice(id)?.addonMonthly ?? 0) > 0);

describe("модуль в подписке не тарифицируется, вне подписки — платный", () => {
  test("КОНТРОЛЬ: в каталоге каждый платный модуль входит в каждый срок", () => {
    // Если каталог изменят и срок снова станет набором модулей, сторож обязан
    // краснеть, а не молча проверять несуществующее правило.
    expect(надстройки.length, "нет платных надстроек — проверять нечего").toBeGreaterThan(0);
    const платныеМодули = MODULES_PRICING.filter((m) => !m.includedIn.includes("free") && m.includedIn.some((t) => t !== "enterprise"));
    expect(платныеМодули.length).toBeGreaterThan(10);
    const урезано = платныеМодули.flatMap((m) =>
      TERM_TIERS.filter((t) => !m.includedIn.includes(t)).map((t) => `${m.id} не входит в ${t}`),
    );
    expect(урезано, "срок перестал открывать всю планету").toEqual([]);
  });

  test.each([...TERM_TIERS])("срок %s: все надстройки сразу НЕ прибавляют к цене", (срок) => {
    const без = buildQuote({ tierId: срок, seats: 1, modules: [] });
    const с = buildQuote({ tierId: срок, seats: 1, modules: надстройки });
    const tier = TIERS.find((t) => t.id === срок)!;
    expect(без.total, `смета пустого ${срок} разошлась с каталогом`).toBe(tier.priceTermTotal);
    expect(
      с.total,
      `${срок} с модулями ${надстройки.join(", ")} стоит ${с.total} вместо ${без.total}: включённое посчитано сверху`
    ).toBe(без.total);
  });

  test("вне подписки (free) надстройка приложения стоит его базу", () => {
    // Вторая половина: без неё «модули не прибавляют» удовлетворялось бы кодом,
    // который раздаёт модули бесплатно без счёта.
    for (const id of надстройки) {
      const база = getModulePrice(id)!.addonMonthly!;
      expect(buildQuote({ tierId: "free", seats: 1, modules: [id] }).total, `${id} на free не стоит своей базы`).toBe(база);
    }
  });

  test("вне подписки второй модуль прибавляет к цене", () => {
    const [первый, второй] = надстройки;
    const один = buildQuote({ tierId: "free", seats: 1, modules: [первый] });
    const два = buildQuote({ tierId: "free", seats: 1, modules: [первый, второй] });
    expect(два.total, "второй модуль вне подписки ничего не прибавил: мы отдаём платное бесплатно").toBeGreaterThan(один.total);
  });
});
