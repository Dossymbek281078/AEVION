/**
 * Подпись задачи обязана совпадать с её РЕШЕНИЕМ.
 *
 * Повод (05.10.2026). В банке лежат задачи с подписью «Мат в 5 · Мастер»,
 * которые на деле матуют на 6–7-м ходу. Это не наша опечатка: у Lichess набор
 * тем заканчивается на `mateIn5`, и любой мат длиннее пяти ходов помечен тем же
 * словом. Наш сев (scripts/seed-puzzles.mjs) скопировал это число и в поле
 * `mateIn`, и прямо в название. Замер окна Связи: 6 из 43 задач темы «Мат в 5+»
 * матуют не в 5. Имя корзины «Мат в 5+» честное, а подпись КОНКРЕТНОЙ задачи —
 * нет, и человек читает именно её.
 *
 * Это тот самый класс, за который основатель ругал ролик «мат в 1»: утверждение
 * о позиции взято из подписи рядом, а не из решения.
 *
 * Чиним на ВЫДАЧЕ, без миграции базы: правда считается из `sol` каждый раз,
 * когда задача уходит наружу. Переписывать 500 000 строк ради числа, которое
 * выводится из данных, незачем — и миграция всё равно не спасла бы от нового
 * сева с тем же дефектом.
 */

/**
 * Сколько ходов РЕШАТЕЛЯ до мата, по самому решению.
 *
 * ⚠️ Решение приходит в двух видах, и их надо различать:
 *   сырой формат Lichess — первый ход принадлежит СОПЕРНИКУ (длина чётная);
 *   нормализованный      — первый ход уже решателя (длина нечётная).
 * Признак — чётность, тот же, по которому страница строит позицию.
 *
 * null — решения нет или оно пустое: тогда подпись не трогаем, выдумывать
 * число нельзя.
 */
export function matIzResheniya(sol: unknown): number | null {
  if (!Array.isArray(sol) || sol.length === 0) return null;
  // Ответ один для обоих форматов, и ветка по чётности не нужна:
  //   сырой, длина 2k   — первый ход соперника, дальше k ходов решателя => k
  //   нормализованный, 2k+1 — первый ход решателя                      => k+1
  // и то и другое равно ceil(n / 2).
  //
  // Первая версия честно разветвлялась по чётности и вычитала единицу. Мутация
  // «убрать вычитание» прошла насквозь — не потому, что проверка слабая, а
  // потому, что мутация РАВНОЗНАЧНА: ceil((2k-1)/2) = k = ceil(2k/2).
  // То есть ветка не работала, а только выглядела работой.
  return Math.ceil(sol.length / 2);
}

/** Подпись вида «Мат в 5 · Мастер» — число в ней и всё, что после. */
const PODPIS_MATA = /^Мат в (\d+)(\s*\+)?(.*)$/;

export interface PodpisVhod {
  name?: string | null;
  sol?: unknown;
  goal?: string | null;
  mateIn?: number | null;
}

export interface PodpisVyhod {
  name: string;
  mateIn?: number;
  /** true — подпись в базе расходилась с решением и была исправлена на выдаче. */
  ispravleno: boolean;
}

/**
 * Приводит подпись и поле `mateIn` в соответствие с решением.
 * Задачи не про мат не трогает вовсе.
 */
export function ispravitPodpisMata(p: PodpisVhod): PodpisVyhod {
  const ishodnoe = String(p.name ?? "").trim();
  const mateIn = p.mateIn == null ? undefined : Number(p.mateIn);

  // Не про мат — не наше дело. Цель может не прийти вовсе: тогда судим по подписи.
  const proMat = p.goal === "Mate" || PODPIS_MATA.test(ishodnoe);
  if (!proMat) return { name: ishodnoe, ...(mateIn != null ? { mateIn } : {}), ispravleno: false };

  const nastoyaschiy = matIzResheniya(p.sol);
  // Решения нет — честнее оставить как есть, чем подставить выдуманное число.
  if (nastoyaschiy == null) return { name: ishodnoe, ...(mateIn != null ? { mateIn } : {}), ispravleno: false };

  const m = PODPIS_MATA.exec(ishodnoe);
  let novoeImya = ishodnoe;
  if (m) {
    const bylo = Number(m[1]);
    if (bylo !== nastoyaschiy) novoeImya = `Мат в ${nastoyaschiy}${m[3] ?? ""}`;
    // Плюс в подписи КОНКРЕТНОЙ задачи неуместен: «Мат в 5+» — имя корзины,
    // а у задачи длина мата известна точно. Снимаем, даже если число совпало.
    else if (m[2]) novoeImya = `Мат в ${nastoyaschiy}${m[3] ?? ""}`;
  }

  const ispravleno = novoeImya !== ishodnoe || (mateIn != null && mateIn !== nastoyaschiy);
  return { name: novoeImya, mateIn: nastoyaschiy, ispravleno };
}
