import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync, existsSync } from "node:fs";
import { join } from "node:path";

/**
 * «Глубокий анализ» нигде не продаётся как платная возможность.
 *
 * ПОВОД 07.10.2026, замер на проде. Продающие места обещали «платно — Глубокий
 * анализ движком Stockfish 17.1». Проверка показала, что эта платная часть НЕ
 * РАБОТАЕТ НИ У КОГО, включая оплативших:
 *   движок берёт нейросети по адресу NET_BASE = NEXT_PUBLIC_NNUE_BASE || "/nnue";
 *   каталога frontend/public/nnue НЕТ в дереве прода 31da232507e7;
 *   переменная НЕ задана — в выкаченном бандле осталось само выражение
 *   process.env.NEXT_PUBLIC_NNUE_BASE||"/nnue" (Next впекает значение литералом,
 *   когда оно есть);
 *   https://aevion.app/nnue/<имя> → 404.
 * Сети весят ~75 МБ, без них движок не поднимается; в самом коде движка это
 * записано как незакрытое.
 *
 * Продавать то, чего не получит и заплативший, нельзя — обещание снято со всех
 * продающих мест и всех языков. Решение оркестратора, PAID_ACTIONS не включали,
 * код движка не трогали, кнопка для всех не открыта.
 *
 * Сторож ищет ПО ВСЕМ языковым файлам и продающим страницам, а не по трём
 * местам, которые я помню: завтра обещание может вернуться в четвёртое.
 */

const КОРЕНЬ = process.cwd();

/** Файлы, где живут продающие тексты: словари всех языков + страницы продаж. */
function prodayushchieFayly(): string[] {
  const список: string[] = [];
  const словари = join(КОРЕНЬ, "src/lib/i18n-lang");
  if (existsSync(словари)) {
    for (const f of readdirSync(словари)) if (f.endsWith(".ts")) список.push(join(словари, f));
  }
  for (const п of [
    "src/app/cyberchess/i18n.ts",
    "src/app/cyberchess/page.tsx",
    "src/app/cyberchess/DeepAnalysisPanel.tsx",
    "src/app/pricing/page.tsx",
  ]) {
    const полный = join(КОРЕНЬ, п);
    if (existsSync(полный)) список.push(полный);
  }
  return список;
}

/** Строки кода без комментариев: в комментариях повод записан намеренно. */
function bezKommentariev(s: string): string {
  const ПС = String.fromCharCode(10);
  return s
    .split(ПС)
    .map((l) => { const i = l.indexOf("//"); return i >= 0 ? l.slice(0, i) : l; })
    .join(ПС)
    .replace(/\/\*[\s\S]*?\*\//g, "");
}

/** Признаки того, что глубокий анализ подан как ПЛАТНАЯ возможность. */
// ⚠️ Хвост слова — НЕ \w: в JavaScript \w это [A-Za-z0-9_], кириллицу он не
// покрывает. Из-за этого первая версия признака не поймала собственный пример
// «Платно — «Глубокий анализ» движком…»: после «Глубок» шло «ий», и совпадение
// рвалось. Поймал встроенный контроль, а не чтение. Берём явный класс букв.
const БУКВЫ = "[A-Za-zА-Яа-яЁёӘҒҚҢӨҰҮҺІәғқңөұүһі]";
const ПРОДАЖА: Array<[string, RegExp]> = [
  [
    "русский",
    new RegExp(
      `(Глубок${БУКВЫ}* анализ[^.]{0,60}(платн|подписк|оплат))` +
        `|((платн|подписк|оплат)${БУКВЫ}*[^.]{0,60}Глубок${БУКВЫ}* анализ)`,
      "i",
    ),
  ],
  ["английский", /(Deep analysis[^.]{0,60}(paid|subscription|unlock))|((paid|unlocks?)[^.]{0,60}Deep analysis)/i],
  [
    "казахский",
    new RegExp(
      `(Терең талдау[^.]{0,60}(ақылы|жазылым|төле))|((ақылы|жазылым|төле)${БУКВЫ}*[^.]{0,60}Терең талдау)`,
      "i",
    ),
  ],
];

describe("глубокий анализ не продаётся как платная возможность", () => {
  it("ни в одном продающем месте и ни на одном языке", () => {
    const файлы = prodayushchieFayly();
    // Знаменатель: если файлов вдруг стало мало, сторож ослеп.
    expect(файлы.length, `продающих файлов просмотрено: ${файлы.length}`).toBeGreaterThanOrEqual(12);

    const находки: string[] = [];
    for (const f of файлы) {
      const текст = bezKommentariev(readFileSync(f, "utf8"));
      for (const [язык, признак] of ПРОДАЖА) {
        const m = текст.match(признак);
        if (m) находки.push(`${f.replace(КОРЕНЬ, "").replace(/\\/g, "/")} (${язык}): «${m[0].slice(0, 90)}»`);
      }
    }
    expect(
      находки,
      `просмотрено файлов: ${файлы.length}; обещание платного глубокого анализа осталось в: ${находки.join(" | ")}`
    ).toEqual([]);
  });

  it("контроль прибора: признак ловит такое обещание, если его вернуть", () => {
    // Без этого проверка выше говорила бы лишь «регулярка ничего не нашла» —
    // в том числе если бы она не находила вообще ничего.
    const примеры = [
      'Платно — «Глубокий анализ» движком Stockfish 17.1.',
      "Paid part: Deep analysis powered by Stockfish",
      "Card payment · unlocks Deep analysis (Stockfish NNUE)",
      "Ақылы бөлігі — Stockfish қозғалтқышымен «Терең талдау»",
      // 🔴 Настоящая строка с прода, которую первая версия признака НЕ ловила:
      // по-казахски продажа названа словом «төлеу» (оплата), а не «ақылы».
      // Нашла калибровка на живом проде, а не чтение.
      "Картамен төлеу · «Терең талдауды» ашады (Stockfish NNUE)",
      "🔒 Глубокий анализ — в платной подписке CyberChess",
    ];
    for (const пример of примеры) {
      const поймано = ПРОДАЖА.some(([, признак]) => признак.test(пример));
      expect(поймано, `признак НЕ ловит обещание: «${пример}»`).toBe(true);
    }
  });

  it("контроль в обратную сторону: нейтральные подписи не считаются продажей", () => {
    // Иначе сторож запретил бы упоминать анализ вообще — и правку пришлось бы
    // обходить, а не соблюдать.
    const нейтральные = [
      "🔒 Глубокий анализ пока недоступен",
      "Оплата картой · подписка CyberChess",
      "Card payment · CyberChess subscription",
      "Глубокий анализ (Stockfish 17.1 · NNUE)",
    ];
    for (const пример of нейтральные) {
      const поймано = ПРОДАЖА.some(([, признак]) => признак.test(пример));
      expect(поймано, `признак ложно считает продажей: «${пример}»`).toBe(false);
    }
  });
});
