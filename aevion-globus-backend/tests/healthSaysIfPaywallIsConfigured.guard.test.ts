import { describe, test, expect, beforeEach, afterAll } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { сводкаПейволла } from "../src/lib/paywallHealth";

/**
 * РУЧКА СОСТОЯНИЯ ОБЯЗАНА ОТВЕЧАТЬ, НАСТРОЕНА ЛИ ВЫДАЧА КУПЛЕННОГО.
 *
 * Повод 06.10.2026: в /health было 18 полей и ни одного про гейт, поэтому вопрос
 * "открывает ли оплата то, что продано" снаружи было не задать. Спросить сервис
 * тоже не вышло: railway CLI из worktree без привязки отвечает "No linked project
 * found", а его "переменных 0" выглядит как "переменная не задана". 05.10 я на этом
 * едва не доложил, что пейволл не настроен, не имея сведений вообще.
 *
 * Проверяется ПОВЕДЕНИЕ при разных настройках, а не форма ответа: настройка читается
 * из окружения на каждый вызов (кэша нет), поэтому сторож её меняет и смотрит,
 * меняется ли число. Копии правила в тесте нет — зовётся та же функция, что уходит
 * в ответ ручки.
 */

const СОХРАНЕНО = process.env.PAYWALL_MODULES;
const СОХРАНЕНО_ДЕЙСТВИЯ = process.env.PAID_ACTIONS;
const ПЕРЕВОД = String.fromCharCode(10); // эскейп съедается на границе вызова (§2е)

beforeEach(() => {
  delete process.env.PAYWALL_MODULES;
});
afterAll(() => {
  if (СОХРАНЕНО === undefined) delete process.env.PAYWALL_MODULES;
  else process.env.PAYWALL_MODULES = СОХРАНЕНО;
  if (СОХРАНЕНО_ДЕЙСТВИЯ === undefined) delete process.env.PAID_ACTIONS;
  else process.env.PAID_ACTIONS = СОХРАНЕНО_ДЕЙСТВИЯ;
});

describe("состояние: настроена ли выдача купленного", () => {
  test("ЗНАМЕНАТЕЛЬ: сколько модулей рассмотрено и сколько продаётся", () => {
    const с = сводкаПейволла();
    process.stderr.write(
      `[сторож] модулей рассмотрено: ${с.modulesChecked}, продаётся: ${с.soldTotal}, ` +
        `закрыто по данным: ${с.walledByData}` + ПЕРЕВОД,
    );
    // Ноль рассмотренных означает, что таблица доступа опустела, а сводка при этом
    // продолжала бы отвечать бодрым "закрыто 0" — то есть ложью про благополучие.
    // Порог закреплён по ЗАМЕРУ 06.10: в таблице 14 записей, продаётся 5. Сорок я взял
    // по памяти из другой совокупности (витрины каталога) — сторож это и поймал.
    expect(с.modulesChecked, "таблица доступа опустела — сводке нечего отвечать").toBeGreaterThanOrEqual(14);
    expect(с.soldTotal, "ни один модуль не продаётся — проверьте данные").toBeGreaterThanOrEqual(1);
  });

  test("БЕЗ настройки стена СПИТ: configured false и закрыто ноль", () => {
    // Это защитное свойство уже переворачивали 01.10 (данные стали значением по
    // умолчанию, и paywallEnabledFor("qnews") отвечал true при удалённой переменной).
    // "Забыл настроить" обязано означать "пропускать", а не "отказывать всем".
    const с = сводкаПейволла();
    expect(с.configured, "переменной нет, а сводка говорит «настроено»").toBe(false);
    expect(с.walledNow, "переменной нет, а модули закрыты — защитное умолчание перевёрнуто").toBe(0);
    // И тогда всё продаваемое по факту открыто: число должно совпасть, а не быть «похожим».
    expect(с.soldButOpen, "спящая стена — значит открыто ВСЁ продаваемое").toBe(с.soldTotal);
  });

  test("с настройкой закрытое число РАСТЁТ — сводка читает живую настройку", () => {
    // Модуль выбран ЗАМЕРОМ, а не наугад: из пяти продаваемых закрываем по данным
    // только multichat-engine. Сперва я написал сюда qnews — он закрываем, но НЕ
    // продаётся, и утверждение про soldButOpen честно покраснело.
    const открытоБез = сводкаПейволла().soldButOpen;
    process.env.PAYWALL_MODULES = "multichat-engine";
    const с = сводкаПейволла();
    expect(с.configured, "переменная задана, а сводка это не видит").toBe(true);
    expect(с.walledNow, "переменная называет закрываемый модуль, а закрыто ноль").toBeGreaterThanOrEqual(1);
    expect(
      с.soldButOpen,
      "закрыли ПРОДАВАЕМЫЙ модуль, а «продаётся и открыто» не уменьшилось",
    ).toBeLessThan(открытоБез);
  });

  test("КОНТРОЛЬ: модуль из UNSAFE_TO_GATE в настройке НЕ делает его закрытым", () => {
    // Иначе сводка пересказывала бы ЖЕЛАНИЕ настройки вместо фактического ответа.
    // qcoreai не закрывается никогда: его бесплатный тариф обещан людям.
    process.env.PAYWALL_MODULES = "qcoreai";
    const с = сводкаПейволла();
    expect(с.configured).toBe(true);
    expect(с.walledNow, "сводка пересказала настройку, а не фактический ответ гейта").toBe(0);
  });

  test("НОРМА: сводка говорит, включены ли платные действия и какие", () => {
    // Повод: я доложил «у CyberChess товар есть — оплата снимает норму коуча», а норма
    // СПИТ, пока действие не названо в PAID_ACTIONS. Снаружи это было не проверить.
    delete process.env.PAID_ACTIONS;
    const спит = сводкаПейволла().paidActions;
    expect(спит.configured, "переменной нет, а механизм назван включённым").toBe(false);
    expect(спит.count, "действий ноль, а счёт не ноль").toBe(0);

    process.env.PAID_ACTIONS = "cyberchess_coach, qright_protect";
    const живёт = сводкаПейволла().paidActions;
    expect(живёт.configured).toBe(true);
    expect(живёт.count, "названы два действия, а сводка видит другое число").toBe(2);
    expect(живёт.actions, "имена действий не названы — «включено: да» ни на что не отвечает").toContain(
      "cyberchess_coach",
    );
    process.stderr.write(
      `[сторож] платных действий названо: ${живёт.count} — ${живёт.actions.join(", ")}` + ПЕРЕВОД,
    );
  });

  test("КОНТРОЛЬ: пробелы и пустые куски не создают действий из воздуха", () => {
    // Иначе PAID_ACTIONS=",, ," читалось бы как «три платных действия», и сводка
    // отвечала бы «включено» на пустую настройку — худший исход для денежного вопроса.
    process.env.PAID_ACTIONS = " , ,, ";
    const с = сводкаПейволла().paidActions;
    expect(с.count, "пустые куски посчитаны действиями").toBe(0);
    expect(с.configured, "пустая настройка названа включённой").toBe(false);
  });

  test("ручка состояния действительно отдаёт эту сводку", () => {
    // Проверка по ИСХОДНИКУ, и это названо вслух: импортировать index.ts нельзя —
    // там app.listen безусловен, тест поднял бы настоящий сервер на занятом порту.
    // Поэтому здесь утверждается только ПРОВОДКА: что ответ ручки её зовёт.
    // Чего эта проверка НЕ доказывает: что ответ дойдёт до клиента неизменным.
    // 30.09 ровно так и терялись разрезы воронки — считались верно и не попадали в json.
    const src = readFileSync(join(__dirname, "..", "src", "index.ts"), "utf8");
    expect(src, "сводка не подключена к ответу ручки состояния").toContain("paywall: сводкаПейволла(),");
  });
});
