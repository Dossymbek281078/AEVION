import { describe, test, expect } from "vitest";
import { buildQuote } from "../src/data/pricing";

/**
 * Сторож: один и тот же модуль тарифицируется ОДИН раз.
 *
 * ЗАМЕР 04.09.2026 (проба buildQuote, до починки):
 *   lite [qsign]              = $19
 *   lite [qsign, qsign]       = $28   ← повтор продан как второй продукт
 *   lite [qsign, qsign, qsign]= $37
 *   lite [qsign, qright]      = $28   ← а это законно: модули РАЗНЫЕ
 *
 * То есть повтор в списке стоил ровно столько же, сколько настоящий второй
 * модуль. Список приходит из тела запроса и ничем не ограничен
 * (`routes/checkout.ts` не проверяет `body.modules`), так что достаточно,
 * чтобы он собрался с повтором — восстановление выбора, двойное нажатие.
 *
 * Проверка ДВУСТОРОННЯЯ: без второй половины «повтор бесплатен»
 * удовлетворялось бы кодом, который перестал брать деньги за модули вовсе.
 */
const q = (modules: string[], tierId: Parameters<typeof buildQuote>[0]["tierId"] = "lite") =>
  buildQuote({ tierId, period: "monthly", seats: 1, modules, currency: "USD" }).total;

describe("повтор модуля не продаётся дважды", () => {
  test("КОНТРОЛЬ: два РАЗНЫХ модуля по-прежнему дороже одного", () => {
    // Иначе «повтор бесплатен» проходило бы и на коде, раздающем модули даром.
    expect(
      q(["qsign", "qright"]),
      "два разных модуля перестали стоить дороже — мы раздаём платное"
    ).toBeGreaterThan(q(["qsign"]));
  });

  test("тот же модуль дважды стоит столько же, сколько один раз", () => {
    expect(
      q(["qsign", "qsign"]),
      "повтор в списке продан как второй продукт: человек платит за то, что у него уже есть"
    ).toBe(q(["qsign"]));
  });

  test("трижды — тоже столько же", () => {
    expect(q(["qsign", "qsign", "qsign"])).toBe(q(["qsign"]));
  });

  test("повтор не удорожает и там, где модуль не входит в тариф", () => {
    // У lite первый модуль укладывается в бесплатный слот, поэтому проверку
    // легко провести мимо настоящего платного случая. На medium слота нет.
    const один = q(["qsign"], "medium");
    expect(q(["qsign", "qsign"], "medium"), "на medium повтор всё ещё удорожает").toBe(один);
  });
});
