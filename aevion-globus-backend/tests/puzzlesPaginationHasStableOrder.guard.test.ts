import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/*
 * 🔴 Утверждение: выборка задач упорядочена ОДНОЗНАЧНО, иначе постраничный обход
 * по offset молча теряет и дублирует строки.
 *
 * ПОВОД 07.10.2026, и он измерен, а не придуман. Запрос стоял с
 * `ORDER BY "rating" ASC` — по НЕУНИКАЛЬНОМУ полю. Равных рейтингов в банке много
 * (замер: запрос полосы 1800–2000 вернул пять задач ровно по 1800), а Postgres
 * вправе отдавать строки с равным ключом сортировки в любом порядке между
 * запросами. Следствие: обход банка для сопоставления происхождения дважды прошёл
 * ЦЕЛИКОМ и дал разные числа — 2409 и 2394 сопоставленных задачи из 2491.
 * Пятнадцать строк разницы там, где обход считался детерминированным.
 *
 * Для случайной выборки (`random=1`) это было безразлично, поэтому дефект жил
 * незаметно: ручкой пользовались именно так.
 *
 * ⚠️ ЧЕСТНАЯ ГРАНИЦА ЭТОГО СТОРОЖА, и я называю её сам, потому что она большая.
 * Он читает ИСХОДНИК и проверяет, что в запросе есть уникальный ключ сортировки.
 * Он НЕ делает запроса к базе: первая версия подменяла `pg` и ловила уходящий SQL,
 * но в этом репозитории файлы с `vi.mock("pg")` до пула не доходят (у меня это уже
 * записано как класс), и сторож получал ноль запросов — то есть проверял пустоту.
 * Пустой сторож хуже отсутствующего, поэтому оставлен честно слабый, но с
 * названной слабостью.
 *
 * Что проверяет НАСТОЯЩУЮ вещь: два полных обхода банка на проде после выкатки
 * обязаны дать совпадающие множества идентификаторов. Это поведение, и его можно
 * проверить только на живых данных; команда —
 * `node sopostavit-proishozhdenie.cjs` из папки
 * `Desktop/АЕВИОН/07-Заявки-и-инвесторы/2026-10-02-RL-СРЕДЫ`, два прогона подряд,
 * числа обязаны совпасть.
 */

const ФАЙЛ = join(process.cwd(), "src/routes/puzzles.ts");

/**
 * ORDER BY только у запросов, которые ЛИСТАЮТСЯ (есть OFFSET).
 *
 * Первая версия брала любой ORDER BY к таблице задач и забраковала законные
 * агрегаты: `ORDER BY cnt DESC` в подсчёте тем и в сводке. Там нет постраничного
 * обхода, и уникальный ключ им не нужен — требование к ним было бы ложной
 * тревогой, а ложная тревога на верном коде опаснее отсутствия сторожа.
 *
 * Признак, который действительно важен: сортировка обязана быть полной там, где
 * строки берутся срезом по OFFSET, — только там неоднозначность порядка приводит
 * к пропускам и дублям.
 */
function bezKommentariev(s: string): string {
  const ПС = String.fromCharCode(10);
  return s
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .split(ПС)
    .map((l) => { const i = l.indexOf("//"); return i >= 0 ? l.slice(0, i) : l; })
    .join(ПС);
}

function poryadkiStranits(исходникСКомментариями: string): string[] {
  // Комментарии вырезаются ДО разбора. Иначе сторож краснеет на тексте, которым я
  // же объясняю правку: в разборе рядом с запросом написано «было ORDER BY "rating"
  // ASC», и это слово в слово то, что сторож ищет. Второй раз за день тот же класс —
  // свой комментарий ослепляет (а здесь наоборот, ложно краснит) свой же сторож.
  const исходник = bezKommentariev(исходникСКомментариями);
  const ответ: string[] = [];
  const re = /FROM\s+"ChessPuzzle"[\s\S]{0,400}?ORDER BY([\s\S]*?)OFFSET/gi;
  let m: RegExpExecArray | null;
  while ((m = re.exec(исходник)) !== null) ответ.push(m[1].replace(/LIMIT[\s\S]*$/i, "").trim());
  return ответ;
}

describe("выборка задач упорядочена однозначно", () => {
  const исходник = readFileSync(ФАЙЛ, "utf8");

  it("КОНТРОЛЬ: разбор находит порядки сортировки в этом файле", () => {
    // Знаменатель: при нуле найденных порядков проверка ниже была бы пустой и
    // зелёной при любом состоянии кода.
    const порядки = poryadkiStranits(исходник);
    expect(порядки.length, `порядков сортировки найдено: ${порядки.length}`).toBeGreaterThan(0);
  });

  it("🔴 в каждом ORDER BY есть уникальное поле, а не только rating", () => {
    const порядки = poryadkiStranits(исходник);
    const плохие = порядки.filter((п) => !/"id"/.test(п));
    expect(
      плохие,
      `сортировка без уникального поля: ${плохие.join(" | ")} — страницы по offset будут ` +
        "одновременно пропускать и дублировать строки, и делать это молча",
    ).toEqual([]);
  });

  it("КОНТРОЛЬ: разбор РАЗЛИЧАЕТ годный порядок от негодного", () => {
    // Иначе проверка выше прошла бы и у разбора, который всегда возвращает пустой
    // список плохих — то есть у сторожа, не стерегущего ничего.
    const плохой = 'pool.query(`SELECT * FROM "ChessPuzzle" WHERE x ORDER BY "rating" ASC LIMIT $1 OFFSET $2`)';
    const хороший = 'pool.query(`SELECT * FROM "ChessPuzzle" WHERE x ORDER BY "rating" ASC, "id" ASC LIMIT $1 OFFSET $2`)';
    // И отдельно: агрегат без OFFSET не обязан иметь уникальный ключ — он не листается.
    const агрегат = 'pool.query(`SELECT "theme", COUNT(*) AS cnt FROM "ChessPuzzle" GROUP BY "theme" ORDER BY cnt DESC`)';
    expect(poryadkiStranits(агрегат).length, "сторож требует уникальный ключ там, где нет листания").toBe(0);
    expect(poryadkiStranits(плохой).filter((п) => !/"id"/.test(п)).length,
      "разбор не замечает сортировки без уникального поля").toBe(1);
    expect(poryadkiStranits(хороший).filter((п) => !/"id"/.test(п)).length,
      "разбор ложно бракует правильную сортировку").toBe(0);
  });
});
