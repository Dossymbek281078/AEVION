import { describe, test, expect } from "vitest";

import { daysUntilLaunch } from "@/lib/daysUntilLaunch";

/**
 * Счётчик «сколько осталось» на посадочной запуска.
 *
 * Считался по UTC, а читатель живёт в UTC+5. Замер 28.08.2026 в 00:20 местного
 * (19:20 UTC): страница печатала «Через 3 дня», календарь читателя показывал
 * 28 августа — то есть два. Расхождение живёт пять часов в СУТКИ.
 *
 * Хуже всего последний день: 30 августа с 00:00 до 05:00 по местному страница
 * сказала бы «Через 1 день» — в сам день запуска, человеку, который открыл
 * ссылку из письма про сегодняшний запуск. Это не косметика: письмо и страница
 * противоречили бы друг другу в самый заметный момент.
 */

/** 30 августа 2026 — день запуска CyberChess. */
const CHESS = Date.UTC(2026, 7, 30);
const at = (iso: string) => daysUntilLaunch(CHESS, new Date(iso));

describe("до запуска считается по календарю запуска, а не по UTC", () => {
  test("день запуска: 00:30 по местному — это уже НОЛЬ, а не «ещё день»", () => {
    // 2026-08-29T19:30Z = 2026-08-30 00:30 в UTC+5.
    expect(at("2026-08-29T19:30:00Z")).toBe(0);
  });

  test("день запуска, середина дня — тоже ноль", () => {
    expect(at("2026-08-30T06:00:00Z")).toBe(0);
  });

  test("ночь на 28-е по местному — два дня, как в календаре читателя", () => {
    // Именно этот момент и был замерен: по UTC ещё 27-е, по местному уже 28-е.
    expect(at("2026-08-27T19:20:00Z")).toBe(2);
  });

  test("день 28-го — те же два дня: внутри суток число не скачет", () => {
    expect(at("2026-08-28T10:00:00Z")).toBe(2);
  });

  test("накануне: 29-е по местному — один день", () => {
    expect(at("2026-08-29T10:00:00Z")).toBe(1);
  });

  test("после запуска число уходит в минус, а не застревает на нуле", () => {
    // Чтобы страница могла отличить «сегодня» от «уже прошло» и не звала
    // подписаться на событие, которое состоялось.
    expect(at("2026-09-01T10:00:00Z")).toBeLessThan(0);
  });

  test("контроль: по UTC ответ БЫЛ БЫ другим — иначе проверка ничего не ловит", () => {
    // Отрицательный контроль к самой причине: если однажды смещение уберут,
    // этот тест обязан покраснеть, а не молча согласиться.
    const utcWay = (iso: string) => {
      const now = new Date(iso);
      const launch = Date.UTC(2026, 7, 30);
      const today = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());
      return Math.round((launch - today) / 86_400_000);
    };
    expect(utcWay("2026-08-27T19:20:00Z")).toBe(3);
    expect(at("2026-08-27T19:20:00Z")).toBe(2);
  });
});

describe("тот же счёт у второй посадочной — бюро, 6 сентября", () => {
  // Дефект был в ДВУХ копиях одной функции, поэтому и проверка общая: копии
  // больше нет, но проверить надо обе даты, иначе «починил» относится к одной.
  const BUREAU = Date.UTC(2026, 8, 6);
  const atB = (iso: string) => daysUntilLaunch(BUREAU, new Date(iso));

  test("00:30 6 сентября по местному — ноль, а не «ещё день»", () => {
    expect(atB("2026-09-05T19:30:00Z")).toBe(0);
  });

  test("ночь на 5-е по местному — один день, как в календаре читателя", () => {
    expect(atB("2026-09-04T19:20:00Z")).toBe(1);
  });
});
