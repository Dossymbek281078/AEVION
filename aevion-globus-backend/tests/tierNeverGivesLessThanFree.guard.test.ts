import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Платный тариф не может давать МЕНЬШЕ бесплатного.
 *
 * ЗАЧЕМ. 01.09.2026 у озвучки было ровно так: free 100000, pro 30000 — то есть
 * заплативший $149 получал втрое меньше того, кто не платил. Единица у обоих
 * одна (символы текста: и проверка нормы, и списание считают text.trim()), так
 * что это не разные меры, а инверсия.
 *
 * Ни один тест этого не видел и не мог: каждое число по отдельности осмысленно,
 * ошибка живёт в ОТНОШЕНИИ между строками таблицы. Такие вещи не падают — их
 * замечает первый заплативший.
 *
 * Правило намеренно слабое: «не меньше», а не «во столько-то раз». Во сколько
 * именно больше — решение об упаковке, оно основателя. А «платный не хуже
 * бесплатного» решением не является: так не проектируют нарочно.
 */

const ФАЙЛ = join(__dirname, "..", "src", "routes", "devhub.ts");
const src = readFileSync(ФАЙЛ, "utf8");

/** Строка тарифа → карта возможностей. Разбор простой намеренно: сложный молча
 *  вернул бы пустоту и превратил сторожа в вечно зелёный. */
function тариф(имя: string): Record<string, number> {
  // БЕЗ регулярки: шаблон, собранный из строки, теряет экранирование на границе
  // вызова — первый вариант этой функции дал ноль ключей, и только контроль
  // охвата не дал сторожу стать зелёным на пустоте. Позиционный разбор проще и
  // не зависит от того, чем его записали.
  const из: Record<string, number> = {};
  const at = src.indexOf("const TIER_LIMITS");
  if (at < 0) return из;
  const строка = src.indexOf(имя + ":", at);
  if (строка < 0) return из;
  const открыть = src.indexOf("{", строка);
  const закрыть = src.indexOf("}", открыть);
  if (открыть < 0 || закрыть < 0) return из;
  for (const кусок of src.slice(открыть + 1, закрыть).split(",")) {
    const двоеточие = кусок.indexOf(":");
    if (двоеточие < 0) continue;
    const ключ = кусок.slice(0, двоеточие).trim();
    const знач = Number(кусок.slice(двоеточие + 1).trim());
    if (ключ && Number.isFinite(знач)) из[ключ] = знач;
  }
  return из;
}

describe("платный тариф не даёт меньше бесплатного", () => {
  const free = тариф("free");
  const pro = тариф("pro");

  it("прибор исправен: обе строки таблицы разобраны", () => {
    // Контроль охвата. Пустой разбор дал бы «нарушений нет» — самый частый вид
    // ложного зелёного, и здесь особенно правдоподобный: формат таблицы могут
    // переписать, а регулярка промолчит.
    expect(Object.keys(free).length, "строка free не разобрана").toBeGreaterThanOrEqual(4);
    expect(Object.keys(pro).length, "строка pro не разобрана").toBeGreaterThanOrEqual(4);
    expect(Object.keys(free).sort()).toEqual(Object.keys(pro).sort());
  });

  it("по каждой возможности платный не хуже бесплатного", () => {
    const хуже: string[] = [];
    for (const ключ of Object.keys(free)) {
      const f = free[ключ];
      const p = pro[ключ];
      if (p === -1) continue;            // -1 значит без ограничения
      if (f === -1) { хуже.push(`${ключ}: free без предела, pro ${p}`); continue; }
      if (p < f) хуже.push(`${ключ}: free ${f}, pro ${p}`);
    }
    expect(
      хуже,
      "Платный тариф даёт МЕНЬШЕ бесплатного. Заплативший получит хуже, чем " +
        "тот, кто не платил, и узнает об этом сам. Поднимите значение у pro " +
        "хотя бы до уровня free — во сколько больше, решает основатель, но " +
        "меньше нельзя.",
    ).toEqual([]);
  });
});
