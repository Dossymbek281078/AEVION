/*
 * Число на продающей странице — только с источником.
 *
 * 🔴 Замер 01.10.2026. На отраслевых страницах стояло шестнадцать чисел, и ни
 * одно ничем не подтверждалось: «−68 % time-to-deploy», «−40 % compliance-затрат»,
 * «SLA отклика 1h», «84 % экономии против DocuSign+OpenAI+Patently», «27
 * open-source аудитируемых модулей», «70 % сокращение бумажного оборота»,
 * «Регионов pilot: 3», «$480/мес экономии», «Seats на Full: 12» и другие.
 *
 * Два из них проверяются и проваливаются сразу: «SLA отклика 1h» мы в тот же день
 * убрали из тарифа Enterprise как неисполнимое, а «27 открытых модулей» не
 * подтверждается ничем — публичной организации на GitHub нет (ответ 404), списка
 * открытых модулей в коде тоже нет.
 *
 * Правило отсюда: у значения с цифрой обязан быть `source` — строка, называющая,
 * откуда число взято. Нет источника — число на странице не живёт.
 */
import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const СТРАНИЦА = join(
  dirname(fileURLToPath(import.meta.url)), "..", "..", "app", "pricing", "for", "[industry]", "page.tsx",
);

/** Метрика из исходника: её значение и есть ли у неё источник. */
function метрики(src: string): Array<{ значение: string; естьИсточник: boolean }> {
  const куски = src.split("labelKey:").slice(1);
  return куски.map((кусок) => {
    const до = кусок.slice(0, 400);
    const v = /value:\s*"([^"]*)"/.exec(до);
    return { значение: v ? v[1] : "", естьИсточник: /source:\s*"/.test(до.split("labelKey:")[0]) };
  });
}

describe("числа на отраслевых страницах — только с источником", () => {
  it("контроль прибора: метрики разбираются и цифра распознаётся", () => {
    const список = метрики(readFileSync(СТРАНИЦА, "utf8"));
    expect(список.length, "ни одной метрики не разобрано — сторож пуст").toBeGreaterThan(1);
    expect(/[0-9]/.test("−68%"), "цифра в проценте не распознана").toBe(true);
    expect(/[0-9]/.test("Crypto-grade"), "текст без цифр принят за число").toBe(false);
  });

  it("у каждого значения с цифрой есть источник", () => {
    const список = метрики(readFileSync(СТРАНИЦА, "utf8"));
    const безИсточника = список
      .filter((м) => /[0-9]/.test(м.значение) && !м.естьИсточник)
      .map((м) => м.значение);
    expect(безИсточника, `проверено метрик: ${список.length}`).toEqual([]);
  });
});
