import { describe, expect, it } from "vitest";
import { листПлана } from "./pdfText";

describe("выбор листа плана в альбоме дизайн-проекта", () => {
  const оглавление = "лист Содержание проекта Обмерный план 02 План расстановки мебели 03 План розеток 04";
  const обмерный = "Обмерный план М1:50 02 " + Array.from({ length: 30 }, (_, i) => String(1000 + i * 137)).join(" ");
  const мебель = "План расстановки мебели с размерами 03 " + Array.from({ length: 40 }, (_, i) => String(500 + i * 91)).join(" ");
  it("оглавление с теми же словами не выбирается: там нет размерных чисел", () => {
    expect(листПлана([оглавление, обмерный], [168, 8652])).toBe(2);
  });
  it("из нескольких планов с размерами берётся с наименьшим числом линий (обмерный чище мебели)", () => {
    expect(листПлана(["титул", оглавление, обмерный, мебель], [13, 168, 8652, 15087])).toBe(3);
  });
  it("«обмерный» в штампе побеждает лист с меньшим числом линий (OTDL: лист 4 против «плана перегородок» на листе 12)", () => {
    const перегородки = "ПЛАН ВОЗВОДИМЫХ ПЕРЕГОРОДОК Лист 12 " + Array.from({ length: 20 }, (_, i) => String(600 + i * 113)).join(" ");
    expect(листПлана(["титул", оглавление, "реклама", обмерный, перегородки], [48, 462, 78, 3906, 3903])).toBe(4);
  });
  it("без подписи или без чисел — null, решает счёт линий", () => {
    expect(листПлана(["титул", "розетки 220 В"], [13, 9000])).toBeNull();
    expect(листПлана([оглавление], [168])).toBeNull();
  });
  it("подпись есть, но линий меньше ста (страница-заглушка) — не берётся", () => {
    expect(листПлана([обмерный], [40])).toBeNull();
  });
});
