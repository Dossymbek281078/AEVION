import { captureException } from "./sentry";

/**
 * Сколько писем ушло за сутки — чтобы исчерпание квоты перестало быть НЕВИДИМЫМ.
 *
 * У Brevo на текущем плане потолок 300 писем в сутки (CLAUDE.md окна запуска).
 * Публичная подписка шлёт письмо на каждый запрос, и предела «10 в минуту на адрес»
 * хватало, чтобы выбрать суточную квоту с одного адреса за полчаса. После этого
 * подтверждения не приходят НИКОМУ, а снаружи это выглядит как «письма задерживаются».
 *
 * Здесь намеренно СЧЁТЧИК И ТРЕВОГА, а не запрет: запрет никого не спасает — упёрлись
 * мы сами или посторонний, подписчик всё равно останется без письма. Спасает то, что
 * основатель узнаёт об исчерпании до того, как воронка тихо умрёт.
 *
 * Счётчик в памяти процесса: при перезапуске обнуляется, при нескольких экземплярах
 * недосчитывает. Это осознанно — он ПОРОГОВЫЙ сигнал, а не учёт для биллинга, и
 * недосчёт здесь означает «сообщим позже», а не «пропустим навсегда».
 */
const DAILY_SOFT_CAP = Number(process.env.BREVO_DAILY_SOFT_CAP) || 300;
let sentDay = "";
let sentCount = 0;
const warnedAt = new Set<number>();

/** Отмечает отправку и поднимает тревогу на 2/3 и на 9/10 квоты. Только читает наружу. */
export function noteEmailSent(): { day: string; count: number } {
  const today = new Date().toISOString().slice(0, 10);
  if (today !== sentDay) {
    sentDay = today;
    sentCount = 0;
    warnedAt.clear();
  }
  sentCount += 1;
  // Порог 1.0 добавлен 28.08.2026. Раньше последний сигнал был на 9/10, и
  // САМО ИСЧЕРПАНИЕ проходило молча: письма просто переставали доходить, а
  // снаружи это выглядит как «почта задерживается» — то есть как ничто.
  // Доставку здесь НЕ меняем: наш потолок мягкий (переопределяется
  // переменной), и жёсткий стоп мог бы оборвать письма раньше настоящего
  // лимита провайдера. Задача этого порога — сделать исчерпание ВИДИМЫМ.
  for (const share of [2 / 3, 9 / 10, 1]) {
    const mark = Math.floor(DAILY_SOFT_CAP * share);
    if (sentCount >= mark && !warnedAt.has(mark)) {
      warnedAt.add(mark);
      // Текст начинается со слова ПРЕДУПРЕЖДЕНИЕ намеренно.
      //
      // Уходит это через captureException, то есть в Sentry ляжет как ошибка, а
      // утренняя сводка считает ошибками прода письма с темой «проект - ТипОшибки»
      // — значит предупреждение попадёт в счёт аварий. Выбор осознанный:
      // captureMessage(level="warning") пометил бы верно, но правила оповещений
      // срабатывают на ошибках, и письма могло не быть вовсе — тревога стала бы
      // невидимой. Видимость здесь важнее аккуратности ярлыка, а чтобы человек не
      // принял это за аварию, сообщение само говорит, чем оно является.
      const msg =
        (sentCount >= DAILY_SOFT_CAP
          ? `ИСЧЕРПАНО: [Brevo] суточный потолок ${DAILY_SOFT_CAP} писем достигнут — `
            + `подтверждения подписки дальше могут не доходить, и снаружи это выглядит `
            + `как «письма задерживаются». Отправлено ${sentCount}.`
          : "") ||
        `ПРЕДУПРЕЖДЕНИЕ (не авария): [Brevo] за сутки отправлено ${sentCount} писем ` +
        `из ${DAILY_SOFT_CAP} — при исчерпании подтверждения подписки перестанут ` +
        `приходить всем, и снаружи это выглядит как «письма задерживаются»`;
      console.warn(msg);
      captureException(new Error(msg), { where: "brevo.dailyQuota", sent: sentCount, cap: DAILY_SOFT_CAP });
    }
  }
  return { day: sentDay, count: sentCount };
}

/**
 * Сколько писем ушло СЕГОДНЯ и каков потолок.
 *
 * Нужно не только проверкам: скрипт рассылки на запуск живёт в отдельном
 * процессе и счётчик сервера не видит. Без этого числа он считал бы, что
 * сегодня не ушло ничего, и мог бы пробить суточный потолок провайдера —
 * 301-е письмо просто не уходит, и узнать об этом неоткуда.
 *
 * Отдаётся наружу через /api/health/channels, значений и адресов там нет.
 */
export function emailQuotaToday(): { day: string; count: number; cap: number } {
  return { day: sentDay, count: sentCount, cap: DAILY_SOFT_CAP };
}

/** Для проверок: текущее состояние счётчика без побочных действий. */
export function __emailCounter(): { day: string; count: number; cap: number } {
  return { day: sentDay, count: sentCount, cap: DAILY_SOFT_CAP };
}

/** Для проверок: обнулить счётчик между случаями. */
export function __resetEmailCounter(): void {
  sentDay = "";
  sentCount = 0;
  warnedAt.clear();
}
