import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Бесплатным ступеням генерация идёт через дешёвого поставщика первым.
 * Платным порядок НЕ меняется.
 *
 * Решение основателя 05.10.2026, принятое по замеру (цены из ответов сервера,
 * поле runCostUsd — не прайс и не расчёт):
 *   gemini-2.5-flash: 3852 выходных токена, $0.002331, выдал 3 файла
 *   claude-opus-4-8:  2756 выходных токенов, $0.069880, выдал 2 файла
 * Дороже в 30 раз при МЕНЬШЕМ результате. Норма гостя — 30 генераций в месяц:
 * $0.07 против $2.10 на гостя, то есть $7 против $210 на сотне гостей, с которых
 * выручки ноль по определению.
 *
 * ⚠️ Самое важное в этой правке — НЕ экономия, а то, что она не превращается в
 * отказ. До 05.10 цепочка запасных существовала только для картинок, а для текста
 * стоял ОДИН поставщик: отказ первого означал отказ человеку. Поставить дешёвого
 * первым без цепочки значило бы менять деньги на работоспособность.
 */
const ФАЙЛ = join(__dirname, "..", "src", "routes", "devhub.ts");
const src = readFileSync(ФАЙЛ, "utf8");

/**
 * Тело функции по имени.
 *
 * Тело ищется ПОСЛЕ закрытия списка параметров, а не по первой «{» — иначе у
 * обобщённой функции разбор попадает в дженерик. Поймал на себе: для
 * `порядокПоСтупени<T extends { id: string }>(…)` первая «{» это `{ id: string }`,
 * и три проверки падали на теле длиной 14 знаков, хотя код был верным.
 */
function телоФункции(имя: string): string {
  const i = src.indexOf("function " + имя);
  if (i < 0) return "";
  // конец списка параметров: от первой «(» считаем круглые скобки
  const пар = src.indexOf("(", i);
  if (пар < 0) return "";
  let кр = 0;
  let послеПараметров = -1;
  for (let c = пар; c < src.length; c++) {
    if (src[c] === "(") кр++;
    else if (src[c] === ")") {
      кр--;
      if (кр === 0) { послеПараметров = c; break; }
    }
  }
  if (послеПараметров < 0) return "";
  const от = src.indexOf("{", послеПараметров);
  let гл = 0;
  for (let c = от; c < src.length; c++) {
    if (src[c] === "{") гл++;
    else if (src[c] === "}") {
      гл--;
      if (гл === 0) return src.slice(от, c + 1);
    }
  }
  return "";
}

describe("бесплатным — дешёвый поставщик первым", () => {
  it("прибор исправен: помощник порядка найден", () => {
    expect(телоФункции("порядокПоСтупени").length, "помощник не найден — сторож смотрит не туда").toBeGreaterThan(60);
    expect(телоФункции("этойФункцииНет"), "разбор находит несуществующее").toBe("");
  });

  it("бесплатные ступени названы, и платных среди них нет", () => {
    const i = src.indexOf("БЕСПЛАТНЫЕ_СТУПЕНИ");
    const объявление = src.slice(i, i + 160);
    expect(объявление, "free не считается бесплатной").toContain("free");
    expect(объявление, "registered не считается бесплатной").toContain("registered");
    // Контроль в обратную сторону: платные ступени НЕ должны попасть в список,
    // иначе экономия ударит по тем, кто за качество заплатил.
    for (const платная of ["pro", "max", "enterprise", "full", "medium", "lite"]) {
      expect(объявление.includes(`"${платная}"`), `платная ступень ${платная} попала в бесплатные`).toBe(false);
    }
  });

  it("платным порядок НЕ меняется", () => {
    const тело = телоФункции("порядокПоСтупени");
    // Первое же действие — выход для неперечисленных ступеней.
    expect(тело, "для платных список не возвращается как есть").toContain("if (!БЕСПЛАТНЫЕ_СТУПЕНИ.has(ступень)) return список;");
  });

  it("дешёвый встаёт ПЕРВЫМ, остальные сохраняются", () => {
    const тело = телоФункции("порядокПоСтупени");
    expect(тело, "дешёвый не ставится в начало").toContain("[...дешёвый, ...список.filter");
    // И его отсутствие не ломает порядок: если gemini не настроен, список прежний.
    expect(тело, "нет защиты от отсутствия дешёвого среди настроенных").toContain("дешёвый.length === 0");
  });

  it("порядок применяется к настроенным поставщикам генерации", () => {
    // Иначе помощник остаётся теорией: он есть, а выбор его не спрашивает.
    expect(src, "порядок не применён к configured").toContain("порядокПоСтупени(providers.filter((p) => p.configured), ступеньДляПорядка)");
  });

  it("ЦЕПОЧКА ЗАПАСНЫХ есть и для текста, не только для картинок", () => {
    /*
     * Главная проверка этого сторожа. Было `: [provider]` — один поставщик, и
     * отказ дешёвого стал бы отказом человеку. Экономия не имеет права
     * превращаться в отказ.
     */
    expect(src, "для текста снова один поставщик вместо цепочки").toContain("visionChain : configured");
    expect(src.includes("visionChain.length > 0 ? visionChain : [provider]"), "вернулся одиночный поставщик").toBe(false);
    // И перебор по цепочке на месте — без него список бесполезен.
    expect(src, "перебор цепочки исчез").toContain("for (const cand of chain)");
  });
});
