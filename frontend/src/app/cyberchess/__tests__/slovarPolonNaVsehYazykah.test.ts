import { describe, it, expect } from "vitest";
import { SUPPORTED_LOCALES } from "../i18n";
import { blokSlovarya } from "./_slovar";

/**
 * Словарь шахмат заполнен на КАЖДОМ языке целиком.
 *
 * Зачем отдельный сторож, если переводы уже проверяют другие. Потому что
 * пропуск ключа здесь — самый дешёвый способ сломать язык и не заметить:
 * `tFor` при отсутствии ключа молча отдаёт русское значение. Экран выглядит
 * рабочим, человек видит смесь двух языков, никто не падает.
 *
 * 05.10.2026 ровно так и было: ключи `tc.bullet/blitz/rapid/custom` жили
 * в русском и английском, а в казахском их не было — и выбравший «Қазақша»
 * читал «Пуля · Блиц · Рапид · Свой». Нашлось не проверкой, а глазами на
 * кадре с прода.
 *
 * Сторож печатает ЗНАМЕНАТЕЛЬ: число ключей на язык. Упало — значит словарь
 * порезали, а не «всё сошлось».
 */

/** Ключи одного языка, прочитанные из самого i18n.ts (а не через tFor с откатом). */
function klyuchi(код: string): string[] {
  const блок = blokSlovarya(код);
  expect(блок.length, `словаря ${код} нет в i18n.ts — сторож смотрит не туда`).toBeGreaterThan(100);
  return [...блок.matchAll(/"([^"]+)":\s*"/g)].map((m) => m[1]);
}

describe("словарь шахмат заполнен на всех языках", () => {
  it("в каждом языке те же ключи, что и в русском", () => {
    const ru = new Set(klyuchi("ru"));
    // Контроль охвата: ключей было 251. Станет заметно меньше — словарь порезали.
    expect(ru.size, `ключей в русском словаре: ${ru.size}`).toBeGreaterThanOrEqual(240);

    const дыры: string[] = [];
    for (const { code } of SUPPORTED_LOCALES) {
      if (code === "ru") continue;
      const свои = new Set(klyuchi(code));
      for (const k of ru) if (!свои.has(k)) дыры.push(`${code}/${k}`);
    }
    expect(
      дыры,
      `ключей в русском ${ru.size}; без перевода (молча откатятся на русский): ${дыры.slice(0, 20).join(", ")}${дыры.length > 20 ? ` …и ещё ${дыры.length - 20}` : ""}`
    ).toEqual([]);
  });

  it("нет пустых значений — пустая строка это не перевод", () => {
    const пустые: string[] = [];
    let проверено = 0;
    for (const { code } of SUPPORTED_LOCALES) {
      const блок = blokSlovarya(code);
      for (const m of блок.matchAll(/"([^"]+)":\s*"([^"]*)"/g)) {
        проверено++;
        if (m[2].trim() === "") пустые.push(`${code}/${m[1]}`);
      }
    }
    expect(пустые, `проверено значений: ${проверено}; пустые: ${пустые.join(", ")}`).toEqual([]);
  });
});
