/* Запись прогресса на диск может отказать — и об этом надо сказать игроку.
 *
 * В модуле 58 ключей localStorage, и почти каждая запись обёрнута в
 * `try { setItem(...) } catch {}`. Для настроек это правильно: браузер в приватном
 * режиме законно запрещает запись, и ронять из-за этого игру незачем.
 *
 * Но те же три строки сторожат историю партий, счёт побед и кошелёк Chessy. Когда
 * место в хранилище кончается (история держит до 200 партий с ходами и разбором),
 * запись начинает отказывать — молча. Экран продолжает показывать заработанное,
 * потому что оно живёт в памяти; всё расходится с диском только до перезагрузки,
 * после которой пропадает всё, начиная с последней удавшейся записи. Ни ошибки, ни
 * предупреждения: ровно тот случай, когда тихая неправильная работа дороже падения.
 *
 * Здесь запись сообщает о своём исходе, а первый отказ поднимает флаг один раз —
 * чтобы интерфейс мог показать одно предупреждение и увести к резервной копии,
 * которая в продукте уже есть.
 */

let failed = false;
const listeners = new Set<() => void>();

/** Был ли отказ записи с момента загрузки страницы. */
export function storageFailed(): boolean {
  return failed;
}

/**
 * Отметить отказ. Слушатели вызываются ОДИН раз: предупреждение об одном и том же
 * не должно всплывать на каждой следующей неудачной записи.
 */
export function markStorageFailed(): void {
  if (failed) return;
  failed = true;
  for (const fn of listeners) {
    try {
      fn();
    } catch {
      // сломавшийся слушатель не должен мешать остальным узнать
    }
  }
}

/** Подписаться на первый отказ. Возвращает отписку. */
export function onStorageFailure(fn: () => void): () => void {
  if (failed) {
    // отказ уже был — сообщаем сразу, иначе подписавшийся позже не узнает никогда
    try {
      fn();
    } catch {
      /* см. выше */
    }
  }
  listeners.add(fn);
  return () => {
    listeners.delete(fn);
  };
}

/**
 * Записать значение как JSON. Возвращает true, если запись удалась.
 * Вызывающий волен игнорировать результат — для настроек это нормально, — но отказ
 * всё равно будет учтён, и игрок увидит предупреждение.
 */
export function writeJson(key: string, value: unknown): boolean {
  try {
    if (typeof window === "undefined") return false;
    window.localStorage.setItem(key, JSON.stringify(value));
    return true;
  } catch {
    markStorageFailed();
    return false;
  }
}

/** Только для тестов: вернуть модуль в исходное состояние. */
export function resetStorageHealth(): void {
  failed = false;
  listeners.clear();
}
