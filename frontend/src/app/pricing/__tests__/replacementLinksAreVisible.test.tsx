import { describe, test, expect, vi } from "vitest";
import { render, waitFor } from "@testing-library/react";

/**
 * Замена мёртвых ящиков ВИДНА человеку, а не просто есть в исходнике.
 *
 * ЗАЧЕМ ОТДЕЛЬНО. Сторожа `noNewDeadMailboxes` и `securityContactMatches`
 * следят, чтобы адрес на домене без записи MX не появился снова. Они
 * отвечают на вопрос «убрано ли плохое» и молчат о втором, который для
 * человека и есть главный: «появилось ли взамен хорошее».
 *
 * Разница не теоретическая. Убрать `mailto:` и не поставить ничего — это
 * зелёный храповик и страница, с которой некуда написать; для человека
 * такой исход ХУЖЕ мёртвого ящика, потому что раньше он хотя бы пытался.
 *
 * Проверяется отрисовкой: ссылка может быть в исходнике и не доехать до
 * экрана — за условием, в невыполнимой ветке, в неотрисованном блоке.
 */

const ПАРАМЕТРЫ = new URLSearchParams("");
vi.mock("next/navigation", () => ({ useSearchParams: () => ПАРАМЕТРЫ }));

// eslint-disable-next-line import/first
import { I18nProvider } from "@/lib/i18n";

/** Страницы, где мёртвый ящик заменён ссылкой на форму связи. */
const СТРАНИЦЫ: Array<[string, () => Promise<{ default: React.ComponentType }>]> = [
  ["/pricing/refund-policy", () => import("../refund-policy/page")],
  ["/pricing/glossary", () => import("../glossary/page")],
];

/**
 * ДВЕ СТРАНИЦЫ СЮДА НЕ ВОШЛИ, и причины разные — обе замерены, а не
 * предположены. Список без объяснений читался бы как «проверено всё».
 *
 * `/pricing/security` — серверный компонент (`export default async`, нет
 * «use client»). Этот стенд его не отрисовывает: длина текста 0, ссылок 0.
 * Это граница ИНСТРУМЕНТА, а не оценка страницы; четыре её ссылки на форму
 * связи в исходнике есть. Проверять их надо иначе — обходом живого адреса.
 * СДЕЛАНО 02.09.2026: `curl https://aevion.app/pricing/security` — ссылок на
 * `/pricing/contact` восемь, адресов на домене без MX ноль. То есть замена
 * там на месте; молчание этого сторожа о ней — граница инструмента, а не
 * дыра в охране.
 *
 * `/pricing/affiliate-dashboard` — ссылка стоит ЗА ВХОДОМ. Незалогиненный
 * видит только экран «введите почту, пришлём ссылку» (замер: 267 символов,
 * 2 ссылки, ни одной на форму связи). То есть партнёр, который НЕ МОЖЕТ
 * войти — а это ровно тот, кому нужна поддержка, — со страницы до нас не
 * дотянется.
 *
 * Чинить это здесь не стал намеренно: понадобилась бы новая подпись на трёх
 * языках, то есть новая работа, а не починка. Записано, чтобы не выглядело
 * проверенным.
 */

describe("на месте убранных ящиков стоит видимая ссылка", () => {
  test.each(СТРАНИЦЫ)("%s ведёт к форме связи", async (_адрес, загрузить) => {
    const { default: Страница } = await загрузить();
    const { container } = render(
      <I18nProvider>
        <Страница />
      </I18nProvider>,
    );

    // Контроль: страница вообще отрисовалась. Без него проверка ниже
    // прошла бы на пустом экране, найдя ноль ссылок и ноль нарушений.
    await waitFor(
      () => expect((container.textContent ?? "").length).toBeGreaterThan(300),
      { timeout: 15000 },
    );

    const ссылки = [...container.querySelectorAll("a")].filter((a) =>
      (a.getAttribute("href") ?? "").includes("/pricing/contact"),
    );

    expect(
      ссылки.length,
      "на странице нет ни одной ВИДИМОЙ ссылки на форму связи — а прежний " +
        "почтовый адрес отсюда убран, то есть написать нам неоткуда",
    ).toBeGreaterThan(0);

    const немые = ссылки.filter((a) => (a.textContent ?? "").trim().length < 2);
    expect(
      немые.length,
      "ссылка на форму есть, но без текста: человек её не увидит",
    ).toBe(0);
  }, 60000);
});
