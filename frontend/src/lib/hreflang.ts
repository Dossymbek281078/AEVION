/**
 * Языковые пары страниц для поисковика (`hreflang`).
 *
 * 🔴 ЗАЧЕМ. Замер 20.09.2026: ни на одной странице прода нет `hreflang` — ни
 * одной. При этом у части витрин есть настоящие английские двойники, и
 * поисковик видит две страницы с одинаковым смыслом на разных адресах. Без
 * `hreflang` он выбирает ОДНУ и показывает её всем; вторая теряет свой рынок.
 *
 * ОБЪЯВЛЯЕМ ТОЛЬКО ТО, ЧТО ЕСТЬ. Пара попадает сюда, если обе страницы
 * существуют И действительно написаны на заявленных языках. Замер по проду
 * в день заведения:
 *
 *   /shop     74 % кириллицы   ↔  /en/shop   0 %
 *   /go       90 % кириллицы   ↔  /en/go     0 %
 *
 * `/pricing` сюда НЕ входит намеренно: `/en/pricing` отвечает 404, и объявить
 * его двойником значило бы показать поисковику несуществующий адрес. Ложное
 * объявление хуже отсутствия объявления: оно тратит доверие ко всем остальным.
 */
export const ЯЗЫКОВЫЕ_ПАРЫ: ReadonlyArray<{ ru: string; en: string }> = [
  { ru: "/shop", en: "/en/shop" },
  { ru: "/go", en: "/en/go" },

  // Заведено 06.10.2026, по тому же правилу «объявляем только то, что есть».
  // Повод: сайт заявлен в Google и НЕ заявлен в Яндексе, а аудитория
  // русскоязычная; из 730 адресов карты на /en/ приходится 7, то есть сайт по
  // адресам почти целиком русский и при этом не сообщает поисковику пары.
  //
  // Замер каждой пары на проде в день заведения (кириллица/латиница в видимом
  // тексте серверного HTML, оба адреса отвечали 200):
  //
  //   /longevity      1875/669   ↔  /en/longevity      0/6119
  //   /qrenew          815/613   ↔  /en/qrenew         0/976
  //   /qskyway        2676/2005  ↔  /en/qskyway        0/1380
  //   /smeta-trainer  2260/581   ↔  /en/smeta-trainer  9/955
  { ru: "/longevity", en: "/en/longevity" },
  { ru: "/qrenew", en: "/en/qrenew" },
  { ru: "/qskyway", en: "/en/qskyway" },
  { ru: "/smeta-trainer", en: "/en/smeta-trainer" },

  // 🔴 /devhub сюда НЕ входит, хотя /en/devhub существует и отвечает 200.
  // Замер 06.10.2026: у /devhub кириллицы 0, латиницы 5121 — русский адрес
  // отдаёт АНГЛИЙСКИЙ текст. Объявить пару значило бы сказать поисковику
  // «вот русская версия», показав английскую. Это тот же запрет, по которому
  // здесь нет /pricing: ложное объявление хуже отсутствующего.
  // Отдельно отмечено в разборе 06.10 (06-Витрина-цены-SEO): то, что главная
  // продуктовая страница русскоязычной витрины не имеет русской версии, —
  // вопрос к продукту, а не к hreflang.

  // /cyberchess тоже не входит: /en/cyberchess отвечает 308, то есть это
  // перенаправление, а не вторая страница.
];

/**
 * Значение для `metadata.alternates.languages`.
 * `x-default` указывает на русскую версию: это основной язык наших витрин, и
 * именно её стоит показывать там, где язык посетителя неизвестен.
 */
export function языки(путь: string): Record<string, string> | undefined {
  const пара = ЯЗЫКОВЫЕ_ПАРЫ.find((p) => p.ru === путь || p.en === путь);
  if (!пара) return undefined;
  return { ru: пара.ru, en: пара.en, "x-default": пара.ru };
}

/**
 * Англоязычный псевдоним для англоязычных посадочных.
 *
 * Зачем отдельное имя: сторож enModuleLandings запрещает русские слова в
 * исходниках /en/* — посадочная обязана быть английской целиком. Вызов
 * `языки(...)` его законно краснит (проверено 06.10.2026: «русские слова в
 * EN-посадочной: языки»), и это не придирка: имя попадает в исходник
 * страницы, который сторож и читает. Поведение то же самое, это тот же
 * список пар.
 */
export const languagesFor = языки;
