/**
 * Свой турнир для теста — через ТУ ЖЕ ручку, которой пользуется человек.
 *
 * ПОВОД 06–07.10.2026. Двадцать два теста турниров покраснели разом, и причина
 * была одна: они брали предмет проверки из витрины
 * `GET /api/cyberchess-tournaments/list`. А витрина с 30.09 отдаёт только
 * турниры с origin "user" (толькоНастоящие): до фильтра она показывала 12
 * наших фикстур и заявляла 534 участника при нуле живых. Фильтр правильный и
 * трогать его нельзя — значит неправ был тест.
 *
 * Тест проверяет РЕГИСТРАЦИЮ и СЕТКУ, а не политику показа. Поэтому предмет он
 * теперь заводит сам: POST / создаёт турнир с origin "user", realPlayers true и
 * статусом "upcoming" — ровно то, что создаёт живой человек со страницы.
 *
 * Побочная польза, ради которой это даже лучше файла с заготовкой: тест
 * перестал зависеть и от НАБОРА фикстур в коде. Раньше любая правка заготовок
 * могла его уронить или, хуже, незаметно подменить предмет проверки.
 *
 * ⚠️ ПОЧЕМУ ПОМОЩНИК НЕ ИМПОРТИРУЕТ supertest. Первая версия импортировала — и
 * файлы с vi.mock("pg") переставали подниматься вовсе: beforeAll с
 * `await import(роутер)` висел и падал по таймауту 60 с. Проверено подстановкой:
 * без импорта те же три проверки проходят за секунды. Поэтому помощник принимает
 * готовую функцию запроса, а supertest остаётся в самом тесте.
 *
 * ⚠️ ОГРАНИЧИТЕЛЬ. Создание ограничено пятью турнирами за 10 минут с адреса
 * (CREATE_MAX=5). В прогоне адрес у всех запросов один, поэтому в ОДНОМ файле
 * нельзя создавать больше пяти: шестой получит 429, и тест упадёт по причине,
 * не имеющей отношения к проверяемому. Заводите турнир в beforeAll и
 * переиспользуйте, а не на каждый случай.
 */
export interface SvoyTurnirOpts {
  /** Нижняя граница рейтинга. Больше нуля — когда проверяются рамки допуска. */
  eloMin?: number;
  eloMax?: number;
  maxPlayers?: number;
  format?: "single_elimination" | "swiss" | "round_robin";
  /** Контроль времени: от него зависит, в какой скорости спрашивают рейтинг. */
  timeControl?: "blitz" | "rapid" | "classic";
  /** Создателя записывают первым участником. Пусто — турнир пустой. */
  userId?: string;
  title?: string;
}

let счётчик = 0;

/** Как тест отправляет POST. Обычно: (u, b) => request(a).post(u).send(b) */
export type Otpravitel = (url: string, body: unknown) => Promise<{ status: number; body: any }>;

export async function svoyTurnir(
  post: Otpravitel,
  opts: SvoyTurnirOpts = {},
): Promise<Record<string, any>> {
  // Имя уникальное: id собирается из него, и два одинаковых турнира в одном
  // прогоне путали бы поиск по списку.
  const title = opts.title ?? `Тестовый турнир ${++счётчик}`;
  const r = await post("/api/cyberchess-tournaments/", {
      title,
      format: opts.format ?? "single_elimination",
      timeControl: opts.timeControl ?? "blitz",
      eloMin: opts.eloMin ?? 0,
      eloMax: opts.eloMax ?? 3000,
      maxPlayers: opts.maxPlayers ?? 8,
      ...(opts.userId ? { userId: opts.userId, displayName: opts.userId } : {}),
  });

  if (r.status !== 201) {
    // Ошибку называем целиком: 429 здесь означает ограничитель создания, и
    // без этой подсказки следующий будет искать дефект в самой регистрации.
    throw new Error(
      `не удалось создать турнир: ${r.status} ${JSON.stringify(r.body)}` +
        (r.status === 429 ? " — это ограничитель создания, в одном файле их не больше пяти" : ""),
    );
  }
  const t = r.body?.tournament;
  if (!t || !t.id) throw new Error(`ручка создания вернула не турнир: ${JSON.stringify(r.body)}`);
  return t;
}
