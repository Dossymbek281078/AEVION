/** Сколько живых запросов получает гость в сутки. */
export function гостевойЛимит(): number {
  const raw = Number(process.env.MULTICHAT_GUEST_FREE_PER_DAY ?? "2");
  return Number.isFinite(raw) && raw >= 0 ? Math.floor(raw) : 2;
}

/**
 * Потолок на ОДИН адрес в сутки (решение Оркестратора 30.10.2026). Норма гостя — личная, на устройство
 * (гостевойЛимит); адрес держит только крышу: до 30.10 оба ключа считались по максимуму, и два
 * запроса одного человека гасили гостей всего адреса — мобильный оператор или офис давал
 * следующему человеку «осталось 0» без единой его попытки (замер на проде 30.10: три разных
 * x-aevion-device с одного адреса — у всех «использовано 2»).
 */
export function потолокНаАдрес(): number {
  const raw = Number(process.env.MULTICHAT_GUEST_FREE_PER_IP_DAY ?? "10");
  return Number.isFinite(raw) && raw >= 0 ? Math.floor(raw) : 10;
}

/** Ключ суток — норма обновляется в полночь UTC, а не «через 24 часа». */
function сутки(now = new Date()): string {
  return denPoMestnomu(now);
}

/** Откат: счёт в памяти процесса — только когда база недоступна. Обнуляется выкаткой, поэтому не основа. */
const счёт = new Map<string, number>();

/* ───────── Хранилище счёта в Postgres ───────── */

type Пул = { query: (text: string, params?: unknown[]) => Promise<{ rows?: Array<Record<string, unknown>> }> };

let таблицаГотова = false;
async function обеспечитьТаблицу(pool: Пул): Promise<void> {
  if (таблицаГотова) return;
  await pool.query(
    'CREATE TABLE IF NOT EXISTS "MultichatGuestUsage" (' +
      '"key" TEXT NOT NULL, "day" TEXT NOT NULL, ' +
      '"count" INTEGER NOT NULL DEFAULT 0, "updatedAt" TIMESTAMPTZ NOT NULL DEFAULT NOW(), ' +
      'PRIMARY KEY ("key", "day"))',
  );
  таблицаГотова = true;
}

/**
 * Одна строка на процесс о том, что счёт гостя ведётся в памяти, а не в базе. Не на запрос:
 * при упавшей базе журнал забило бы тысячами одинаковых строк, и настоящая причина утонула бы.
 */
let сбойБазыСказан = false;
function сказатьОСбоеБазы(err: unknown): void {
  if (сбойБазыСказан) return;
  сбойБазыСказан = true;
  console.error(
    "[multichat] СЧЁТ ГОСТЯ НЕ В БАЗЕ — считается в памяти процесса (обнулится выкаткой): " +
      (err instanceof Error ? err.message : String(err)),
  );
}

/**
 * Выполнить работу с базой; null — база недоступна, вызывающий откатывается на память.
 * getPool() с подменой в тестах возвращает null; без DATABASE_URL — пул, чей запрос падает на
 * соединении: оба случая здесь один исход — откат без 5xx.
 */
async function вБазе<T>(работа: (pool: Пул) => Promise<T>): Promise<T | null> {
  let pool: Пул | null | undefined;
  try {
    pool = getPool() as unknown as Пул | null | undefined;
  } catch (err) {
    сказатьОСбоеБазы(err);
    return null;
  }
  if (!pool || typeof pool.query !== "function") {
    сказатьОСбоеБазы(new Error("getPool() не дал пула (нет базы)"));
    return null;
  }
  try {
    await обеспечитьТаблицу(pool);
    return await работа(pool);
  } catch (err) {
    сказатьОСбоеБазы(err);
    return null;
  }
}

/** Сколько потрачено по каждому ключу за сутки. null — база недоступна. */
async function прочитатьСчёт(ключи: string[], день: string): Promise<Map<string, number> | null> {
  if (!ключи.length) return new Map();
  return вБазе(async (pool) => {
    const r = await pool.query(
      'SELECT "key", "count" FROM "MultichatGuestUsage" WHERE "day" = $1 AND "key" = ANY($2::text[])',
      [день, ключи],
    );
    const итог = new Map<string, number>();
    for (const row of r.rows ?? []) итог.set(String(row.key), Number(row.count ?? 0));
    return итог;
  });
}

/** +1 по каждому ключу за сутки. false — база недоступна (память уже обновлена вызывающим). */
async function прибавитьСчёт(ключи: string[], день: string): Promise<boolean> {
  const итог = await вБазе(async (pool) => {
    for (const key of ключи) {
      await pool.query(
        'INSERT INTO "MultichatGuestUsage" ("key","day","count","updatedAt") VALUES ($1,$2,1,NOW()) ' +
          'ON CONFLICT ("key","day") DO UPDATE SET "count" = "MultichatGuestUsage"."count" + 1, "updatedAt" = NOW() ' +
          'RETURNING "count"',
        [key, день],
      );
    }
    return true;
  });
  return итог === true;
}

/** Гость — тот, у кого нет разобранного входа. */
export function этоГость(req: Request): boolean {
  return !req.auth?.sub;
}

/** Идентификатор устройства, если страница его прислала. Одно место на модуль. */
function устройствоЗапроса(req: Request): string {
  return String(
    req.get("x-aevion-device") || (req.body as Record<string, unknown> | undefined)?.deviceId || "",
  ).trim().slice(0, 64);
}

/**
 * Нет адреса гостя от сайта (не задан AEVION_EDGE_KEY, нет заголовка или чужой секрет) —
 * норма откатывается к прежнему счёту: адрес соединения + устройство. Не 0 вопросов и не 5xx
 * (требование Оркестратора 20.10.2026), но и не молча: одна строка в журнал на процесс.
 */
let безАдресаСказано = false;
function предупредитьБезАдресаСайта(): void {
  if (безАдресаСказано) return;
  безАдресаСказано = true;
  console.warn("[multichat] адрес гостя от сайта не пришёл (нет AEVION_EDGE_KEY, заголовка или секрет не совпал) — норма гостя считается по устройству и адресу соединения");
}

function ключи(req: Request): { день: string; вошедший: string | null; адрес: string; устройство: string } {
  const день = сутки();
  // 🔴 20.10.2026 22:1x (прод, волна 5): вошедший считается ТОЛЬКО по своему id. Перед этим слоем нет
  // общей проверки входа (req.auth пуст), и вошедший шёл по ключам гостя — адресу и устройству. Пока
  // адрес был узлом Vercel, ключ адреса был мёртвым; с настоящим адресом гость, исчерпав норму, отнимал
  // её у человека, только что вошедшего с той же машины: «использовано 2, осталось 0», консилиум не уходил.
  const вошедший = verifyBearerOptional(req)?.sub;
  if (вошедший) return { день, вошедший: `user:${String(вошедший)}:${день}`, адрес: "", устройство: "" };
  // Адрес гостя от прокси сайта (по секрету AEVION_EDGE_KEY) — раньше clientIp: через
  // rewrite /api-backend бэкенд видит адрес узла Vercel, и счёт «по адресу» не держал.
  // Замер 20.10.2026: новое окно с того же адреса снова получало 2 вопроса.
  const сСайта = адресОтПроксиСайта(req);
  if (!сСайта) предупредитьБезАдресаСайта();
  const ip = сСайта ?? clientIp(req);
  const устройство = устройствоЗапроса(req);
  return { день, вошедший: null, адрес: `ip:${ip}:${день}`, устройство: устройство ? `dev:${устройство}:${день}` : "" };
}

/**
 * Устойчивая ЛИЧНОСТЬ гостя — чтобы его консилиум принадлежал ему же.
 *
 * 🔴 Зачем это понадобилось (замер 29.09.2026 на живом проде). Гостевой пропуск
 * снимал платную стену, но обработчик берёт владельца из `req.auth!.sub`, а у
 * гостя его нет: запрос отбивался 401 «auth required» ещё до всякой проверки
 * нормы, при том что страница честно писала «осталось 2 запроса». То есть
 * бесплатный вход, который и был первым экраном страницы цен, не работал вовсе.
 *
 * Идентификатор НЕ содержит суток: консилиум, начатый в 23:59, должен остаться
 * своим и в 00:01 — иначе ответ агентов уйдёт в чужую переписку. Норму по-прежнему
 * считают дневные ключи выше, это разные вопросы.
 *
 * IP и идентификатор устройства не кладём в базу как есть: это персональные
 * данные. Кладём короткий хеш — его достаточно, чтобы связать создание и выдачу.
 */
export function гостевойИдентификатор(req: Request): string {
  const основа = устройствоЗапроса(req) || clientIp(req) || "неизвестно";
  return `guest_${createHash("sha256").update(основа).digest("hex").slice(0, 16)}`;
}

export interface ОстатокГостя {
  лимит: number;
  использовано: number;
  осталось: number;
}

/**
 * Сколько живых запросов у этого гостя ещё есть. Ничего не тратит.
 * Счёт — из базы; база недоступна — из памяти процесса (откат, см. шапку).
 */
export async function остатокГостя(req: Request): Promise<ОстатокГостя> {
  const лимит = гостевойЛимит();
  const к = ключи(req);
  const нужные = [к.вошедший, к.адрес, к.устройство].filter((k): k is string => !!k);
  const изБазы = await прочитатьСчёт(нужные, к.день);
  const взять = (key: string): number => (изБазы ? изБазы.get(key) ?? 0 : счёт.get(key) ?? 0);
  if (к.вошедший) {
    const использовано = взять(к.вошедший);
    return { лимит, использовано, осталось: Math.max(0, лимит - использовано) };
  }
  const поАдресу = взять(к.адрес);
  // Устройство прислано — норма личная, адрес держит только потолок. Не прислано (скрипт, старый
  // клиент) — различить людей нельзя, и действует прежняя строгая норма на адрес.
  const осталось = к.устройство
    ? Math.min(лимит - взять(к.устройство), потолокНаАдрес() - поАдресу)
    : лимит - поАдресу;
  return { лимит, использовано: лимит - Math.max(0, осталось), осталось: Math.max(0, осталось) };
}

/**
 * Тратит одну единицу нормы. Зовётся, когда гостя ПУСКАЮТ, а не когда он пришёл.
 * Память обновляется всегда (она — откат на случай, если база упадёт позже в тот же день),
 * база — основа: именно её читает остатокГостя, когда она отвечает.
 */
export async function засчитатьГостю(req: Request): Promise<ОстатокГостя> {
  const к = ключи(req);
  const нужные = [к.вошедший, к.адрес, к.устройство].filter((k): k is string => !!k);
  for (const k of нужные) счёт.set(k, (счёт.get(k) ?? 0) + 1);
  await прибавитьСчёт(нужные, к.день);
  return остатокГостя(req);
}

/**
 * GET /api/multichat-guest/allowance. Ручка висит на app, мимо слоя авторизации:
 * req.auth здесь не заполнен, и этоГость() отвечал true даже с токеном (замер на
 * проде 20.10.2026: вошедший получал «гость»:true). Токен проверяем сами.
 * Вынесено сюда, чтобы сторож звал ту же функцию, что смонтирована в index.ts.
 */
export const ручкаОстатка: RequestHandler = (req, res, next) => {
  остатокГостя(req)
    .then((о) => {
      const вошёл = !!verifyBearerOptional(req)?.sub;
      res.json({ лимит: о.лимит, использовано: о.использовано, осталось: о.осталось, гость: !вошёл && этоГость(req) });
    })
    .catch(next);
};

/** Только для тестов: обнулить счёт в памяти между случаями и повторить CREATE TABLE. База в тестах подменяется. */
export function сброситьСчётГостей(): void {
  счёт.clear();
  таблицаГотова = false;
}

/**
 * Какие вызовы мультичата открыты гостю. Ровно два: завести разговор и один
 * веер по нему. Всё остальное — за платной стеной, как было.
 */
export function гостевойПуть(method: string, path: string): boolean {
  if (method.toUpperCase() !== "POST") return false;
  return path === "/conversations" || /^\/conversations\/[^/]+\/dispatch$/.test(path);
}

/**
 * Решение по ОДНОМУ запросу: пускать ли гостя мимо платного гейта и тратить ли
 * единицу нормы. Тратим только на веере: создание пустого разговора моделей не
 * зовёт и денег не стоит, а списание за него съедало бы норму впустую.
 *
 * Функция экспортирована намеренно: её зовёт index.ts, и сторож проверяет ЕЁ,
 * а не свою копию правила.
 */
export async function решениеПоГостю(req: Request): Promise<{ пускать: boolean; тратить: boolean }> {
  if (!гостевойПуть(req.method, req.path)) return { пускать: false, тратить: false };
  if (!этоГость(req)) return { пускать: false, тратить: false };
  if ((await остатокГостя(req)).осталось <= 0) return { пускать: false, тратить: false };
  return { пускать: true, тратить: req.path.endsWith("/dispatch") };
}

/**
 * Гостевой слой Мультичата ОДНИМ местом: и прод, и сторож зовут его.
 *
 * 🔴 Зачем функция, а не пять строк в index.ts. 30.09.2026 я написал сторожа на
 * гостевой путь — и он собрал цепочку СВОЕЙ копией правила, потому что `index.ts`
 * целиком в тест не поднять. Мутации в боевом коде такой сторож не ловит: обе
 * («списывать при входе» и «не списывать никогда») прошли зелёными. Это тот же
 * класс, из-за которого бесплатный вход не работал месяц: проверялась копия, а не
 * работа.
 *
 * Здесь правило живёт целиком: кого пускать, какую личность дать, когда списать.
 *
 * СПИСАНИЕ ПОСЛЕ ОТВЕТА И НЕ ЗА ОТКАЗЫ. Замер того же дня на живом проде: запрос
 * без поля `agents` получил 400, а норма уменьшилась с 2 до 1 — человек, ошибшийся
 * дважды, терял всё бесплатное обещание, не увидев ни одного ответа агентов.
 * Норма — плата за РАБОТУ, а не за попытку. Прерванный клиентом запрос списывается:
 * работа поставщика ИИ к тому моменту сделана, иначе отмена стала бы способом
 * получить бесплатно сколько угодно.
 *
 * Решение теперь асинхронное (счёт в базе): обёртка ловит отказ обещания и отдаёт
 * его next(err) — не глотает. Сам счёт при сбое базы откатывается в память внутри
 * остатокГостя/засчитатьГостю, так что до next(err) дело доходит только при настоящей ошибке.
 */
export function гостевойСлой(роутер: RequestHandler, стена: RequestHandler): RequestHandler {
  return (req, res, next) => {
    решениеПоГостю(req)
      .then((решение) => {
        if (!решение.пускать) {
          стена(req, res, () => routerДалее(роутер, req, res, next));
          return;
        }
        if (решение.тратить) {
          let списано = false;
          const списать = () => {
            if (списано) return;
            списано = true;
            if (res.statusCode >= 400) return;
            // Ответ уже ушёл — next(err) здесь некуда; но и молчать нельзя.
            засчитатьГостю(req).catch((err: unknown) => {
              console.error(
                "[multichat] списание нормы гостя не удалось: " + (err instanceof Error ? err.message : String(err)),
              );
            });
          };
          res.on("finish", списать);
          res.on("close", списать);
        }
        // Гостю нужны ДВЕ вещи, и до 29.09.2026 не давалось ни одной: метка, по которой
        // роутер пропускает проверку входа именно у гостевых запросов, и устойчивая
        // личность, чтобы его консилиум принадлежал ему и ответ агентов нашёл ту же
        // переписку. Без первой приходил 401, без второй обработчик падал на
        // `req.auth!.sub`.
        (req as unknown as { гостьМультичата?: boolean }).гостьМультичата = true;
        (req as unknown as { auth?: { sub: string; гость: boolean } }).auth = {
          sub: гостевойИдентификатор(req),
          гость: true,
        };
        routerДалее(роутер, req, res, next);
      })
      .catch(next);
  };
}

/** Мелкий помощник: роутер — тоже обработчик, и вызывается так же. */
function routerДалее(
  роутер: RequestHandler,
  req: Parameters<RequestHandler>[0],
  res: Parameters<RequestHandler>[1],
  next: Parameters<RequestHandler>[2],
): void {
  роутер(req, res, next);
}
