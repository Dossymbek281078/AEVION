/**
 * Исходник БЕЗ комментариев — для сторожей, которые ищут по коду.
 *
 * Сторож «такая строка должна БЫТЬ» удовлетворяется совпадением в комментарии:
 * закомментируй проверяемое место — и он останется зелёным, охраняя пустоту.
 * Поймано мутацией 21.08.2026 на двух сторожах сразу.
 *
 * Копия помощника из бэкенда: наборы тестов раздельные, общего места нет.
 * Разбор — aevion-globus-backend/tests/helpers/sourceCode.ts.
 */
export function stripComments(src: string): string {
  /*
   * Разбор с состоянием, а не заменой по шаблону.
   *
   * Прежняя редакция вырезала `/*…*` + `/` регуляркой и обрубала строку на
   * первом `//`. Обе привычки дают ТИХИЙ ЛОЖНЫЙ ЗЕЛЁНЫЙ у сторожей вида
   * «такого не должно быть»: спрятанное вырезалкой они не видят и молчат.
   *
   * Два случая, пойманные 01.09.2026 на живых файлах:
   *
   *   путь-шаблон в комментарии   frontend/src/app/developers/fintech/**
   *     — незакрытый «открыватель», и всё до следующего закрытия съедалось
   *       вместе с настоящим адресом на странице;
   *   адрес в строке              href="https://aevion.app/x"
   *     — обрубалось по `//` внутри кавычек.
   *
   * Здесь состояния: код, строка (три вида кавычек), строчный и блочный
   * комментарий. Внутри строки ни `//`, ни `/*` комментария не начинают.
   */
  let из = "";
  let состояние: "код" | "строка" | "строчный" | "блочный" = "код";
  let кавычка = "";
  for (let i = 0; i < src.length; i += 1) {
    const c = src[i];
    const след = src[i + 1] ?? "";
    if (состояние === "код") {
      if (c === "/" && след === "/") { состояние = "строчный"; i += 1; continue; }
      if (c === "/" && след === "*") { состояние = "блочный"; i += 1; continue; }
      if (c === '"' || c === "'" || c === "`") { состояние = "строка"; кавычка = c; }
      из += c;
      continue;
    }
    if (состояние === "строка") {
      из += c;
      if (c === "\\") { из += след; i += 1; continue; }
      if (c === кавычка) состояние = "код";
      continue;
    }
    if (состояние === "строчный") {
      if (c === "\n") { состояние = "код"; из += c; }
      continue;
    }
    // блочный
    if (c === "*" && след === "/") { состояние = "код"; i += 1; continue; }
    if (c === "\n") из += c;
  }
  return из;
}
