import { productById, withChannel } from "./products";
import { PLANET_BASE_MONTHLY, fromPricePerMonth } from "./termPricing";

export type ПокупкаНаГлавной = {
  вид: string;
  название: string;
  цена: string;
  href: string;
};

/**
 * Что можно купить прямо сейчас — для первого экрана главной.
 *
 * 🔴 ЗАЧЕМ. Замер 22.09.2026: главная написана для ИНВЕСТОРА — «$340B
 * addressable market», «≈$28.75M modelled ARR», кнопка «Investor pitch».
 * Слово «Купить» встречалось на странице НОЛЬ раз, цен товаров не было ни
 * одной. Человек, пришедший с ролика про книгу, попадал на страницу про объём
 * рынка. При этом на сайт за сутки заходят единицы — и каждый уходил, не
 * увидев ни одного предложения купить.
 *
 * ЦЕНЫ ИЗ КАТАЛОГА, не переписаны числами: иначе главная разойдётся с кассой
 * при первой же правке цены, и мы пообещаем одно, а возьмём другое. Ссылки
 * помечаются каналом, поэтому покупка свяжется с источником перехода.
 *
 * Порядок намеренный: первой стоит книга за $9.99 — единственный товар,
 * который у нас когда-либо покупали (2 покупки, $19.98 за всё время).
 */
export function покупкиНаГлавной(канал: string | null): ПокупкаНаГлавной[] {
  const из: ПокупкаНаГлавной[] = [];
  const книга = productById("orcfbo");
  const протокол = productById("oijxmq");
  if (книга) {
    из.push({
      вид: "книга · PDF + EPUB",
      название: книга.title,
      цена: "$" + книга.priceUsd,
      href: withChannel(книга.href, канал, "home"),
    });
  }
  if (протокол) {
    из.push({
      вид: "PDF · 9 страниц",
      название: протокол.title,
      цена: "$" + протокол.priceUsd,
      href: withChannel(протокол.href, канал, "home"),
    });
  }
  из.push({
    вид: "подписка · вся планета",
    название: "Все модули AEVION",
    цена: "от $" + fromPricePerMonth(PLANET_BASE_MONTHLY) + "/мес",
    href: withChannel("/pricing#tiers", канал, "home"),
  });
  return из;
}
