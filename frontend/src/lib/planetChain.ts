/**
 * Порядок комнат в цепочке планеты — ОДИН источник на все страницы.
 *
 * Заведён 03.09.2026 по прямой просьбе окна запуска: готового места, где
 * записана последовательность «отметка → договор → подпись → выплата», в коде
 * не было. Очередь запуска живёт в уставе (документ, не код), каталог
 * продуктов упорядочен по цене, а не по пути.
 *
 * 🔴 Почему именно ОДИН источник, а не по строке на каждой странице: за один
 * день у соседних окон случилось три случая, когда один и тот же факт лежал в
 * трёх местах и разошёлся молча. Расхождение здесь означало бы, что человеку
 * объявляют «шаг 2 из 4» на странице, которая на деле третья.
 *
 * Состав цепочки может измениться: основатель ещё выбирает состав
 * демонстрации, и четвёртой комнаты может не быть. Поэтому порядок —
 * ДАННЫЕ, а не разложенная по коду логика: правится один массив.
 */

export type КомнатаЦепочки = {
  /** Путь страницы. Сравнение идёт по началу пути: /qsign покрывает /qsign/verify. */
  путь: string;
  /**
   * Ключ словаря: платформа трёхъязычная, и объявление обязано звучать на
   * языке интерфейса. Замер 03.09.2026 вскрыл это на мне же: имя комнаты было
   * зашито по-русски, и на английской странице человек услышал бы смесь —
   * «Отметка авторства. Шаг 1 из 4. Protect Your Work».
   */
  ключ: string;
  /**
   * Запасное имя на случай, если ключа в словаре ещё нет. Молчать хуже, чем
   * сказать на одном языке: без имени объявление превращается в «Шаг 1 из 4»
   * без указания, шаг ЧЕГО.
   */
  имя: string;
};

export const ЦЕПОЧКА_ПЛАНЕТЫ: КомнатаЦепочки[] = [
  { путь: "/qright", ключ: "chain.room.qright", имя: "Отметка авторства" },
  { путь: "/qcontract", ключ: "chain.room.qcontract", имя: "Договор" },
  { путь: "/qsign", ключ: "chain.room.qsign", имя: "Подпись" },
  { путь: "/qpaynet", ключ: "chain.room.qpaynet", имя: "Выплата" },
];

/**
 * Место страницы в цепочке или null, если она вне её.
 *
 * Возвращаем null, а не «шаг 0»: страница вне цепочки и первая страница
 * цепочки — разные вещи, и объявлять их одинаково нельзя.
 */
export function местоВЦепочке(
  путь: string
): { номер: number; всего: number; имя: string; ключ: string } | null {
  if (!путь) return null;
  const i = ЦЕПОЧКА_ПЛАНЕТЫ.findIndex(
    (к) => путь === к.путь || путь.startsWith(к.путь + "/")
  );
  if (i < 0) return null;
  return {
    номер: i + 1,
    всего: ЦЕПОЧКА_ПЛАНЕТЫ.length,
    имя: ЦЕПОЧКА_ПЛАНЕТЫ[i].имя,
    ключ: ЦЕПОЧКА_ПЛАНЕТЫ[i].ключ,
  };
}
