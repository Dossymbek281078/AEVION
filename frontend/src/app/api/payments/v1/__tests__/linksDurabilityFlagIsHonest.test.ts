import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { LINKS_ARE_MEMORY_ONLY } from "../_lib";

/**
 * Сторож: флаг о долговечности ссылок обязан совпадать с кодом.
 *
 * ЗАЧЕМ. Ручка состояния отдаёт durable по kvBackend(), и это поле оказалось
 * ШИРЕ того, что измеряет: платёжные ссылки в KV не пишутся вовсе, только в
 * globalThis. Настроят Redis — durable станет true, «записи сохраняются
 * долговременно» будет напечатано, а ссылки продолжат исчезать при холодном
 * старте. Поэтому у ссылок отдельный ответ, и он не должен разойтись с кодом:
 * тот, кто переведёт ссылки в хранилище, обязан поправить флаг тем же
 * движением, иначе ручка начнёт занижать состояние.
 */
const src = readFileSync(
  join(__dirname, "..", "links", "route.ts"),
  "utf8"
);

describe("флаг долговечности ссылок не расходится с кодом", () => {
  it("память-только заявлено ровно тогда, когда записи в хранилище нет", () => {
    // Пишет ли обработчик ссылок хоть что-то в KV.
    const пишетВХранилище = /\bkv(Set|Push)\s*\(/.test(src);

    // Контроль прибора: в файле ТОЧНО есть запись в память, иначе шаблоны
    // ничего не находят и «ноль» был бы ложным.
    expect(src.includes("store.links.set"), "прибор не видит даже записи в память").toBe(true);

    expect(
      LINKS_ARE_MEMORY_ONLY,
      пишетВХранилище
        ? "ссылки уже пишутся в хранилище — флаг занижает состояние"
        : "ссылки пишутся только в память — флаг завышает состояние"
    ).toBe(!пишетВХранилище);
  });
});
