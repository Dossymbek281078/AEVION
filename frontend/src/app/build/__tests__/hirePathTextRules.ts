/*
 * Правила сторожа «текст мимо словаря» для пути найма QBuild (29.10.2026).
 * Вынесены отдельно от теста, чтобы их можно было прогнать и без vitest
 * (`node hirePathTextRules.ts <файл>` — Node 24 читает этот файл как есть).
 */

/** Видимый текст, который не переводится: бренды, эмодзи-кнопки, коды валют. */
export const ИСКЛЮЧЕНИЯ: RegExp[] = [
  />\s*AEVION QBuild\s*</,
  /^\s*AEVION QBuild\s*$/, // бренд в подвале встраиваемой вакансии
  />\s*🛜 RSS\s*</,
  />\s*✈ Telegram\s*</,
  />\s*🟢 WhatsApp\s*</,
  /^\s*in LinkedIn\s*$/,
  /<option value="(USD|RUB|KZT|EUR)">\1<\/option>/,
  />RUB<\/span>/, // код валюты рядом с суммой тестового задания
];

const КЛЮЧЕВЫЕ = /^\s*(return|if|else|await|type|new|const|let|throw|import|export|case)\b/;

/** Исходник без комментариев; содержимое <code>…</code> (форматы: колонки CSV, ключ qb_pk_…) опущено. */
export function безКомментариев(src: string): string {
  return src
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, "")
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/^\s*\/\/.*$/gm, "")
    .replace(/<code([^>]*)>[^<]*<\/code>/g, "<code$1></code>");
}

/** Строка исходника показывает человеку текст мимо словаря. */
export function мимоСловаря(l: string): boolean {
  if (ИСКЛЮЧЕНИЯ.some((r) => r.test(l))) return false;
  return (
    // текст между тегами на одной строке (не стрелка «=>» и не «->»)
    /(?<![=-])>\s*[A-Za-zА-Яа-яЁё][^<{}]*</.test(l) ||
    // текст сразу после открывающего тега, закрывающий — на следующей строке (`<span className="…">Оценка`)
    /<[A-Za-z][\w.]*(\s[^<>]*)?(?<![=-])>\s*[A-Za-zА-Яа-яЁё][^<>{}]*$/.test(l) ||
    // текст в начале строки перед закрывающим тегом (`  Оценка</span>`)
    /^\s+[A-Za-zА-Яа-яЁё][^<>{}=;()]*<\//.test(l) ||
    // атрибуты, которые видит или слышит человек (адрес и пример почты — не текст)
    /\b(placeholder|aria-label|title|alt|label|hint|emptyHint|buttonLabel|doneText|description)=\s*["'](?!https?:|[\w.]+@[\w.]+["'])[^"']*[A-Za-zА-Яа-яЁё]{3}/.test(l) ||
    (/\b(label|title|text):\s*["'`][^"'`]*[A-Za-zА-Яа-яЁё]{3}[^"'`]*["'`]/.test(l) && !/key:/.test(l)) ||
    // сообщения человеку из кода
    /\b(toast\.\w+|confirm|prompt|alert|setError|setErr|setMsg|Error)\(\s*["'`](?!HTTP \$)[^"'`]*[A-Za-zА-Яа-яЁё]{3}/.test(l) ||
    // проза на отдельной строке JSX: слова через пробел, без скобок и «;» (это код)
    (/^\s+[A-Za-zА-Яа-яЁё][A-Za-zА-Яа-яЁё']*( [A-Za-zА-Яа-яЁё,.—'&:!?-]+)+$/.test(l) && !КЛЮЧЕВЫЕ.test(l)) ||
    // одно слово на отдельной строке JSX («Filters», «Cancel»)
    /^\s+[A-Z][a-z]{2,}[…!?]?$|^\s+[А-ЯЁ][а-яё]{2,}[.…!?]?$/.test(l) ||
    // кириллица в строковом литерале — русский текст мимо словаря
    (/["'`][^"'`\n]*[А-Яа-яЁё][^"'`\n]*["'`]/.test(l) && !/replace\(\/\[\^a-z0-9а-яё\]/.test(l))
  );
}
