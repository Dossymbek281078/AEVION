/**
 * Текст одной клетки суточного разреза: живое, всего и наши — тремя числами.
 *
 * 🔴 Три исхода, а не два. `null` значит «не измерялось» (так приходит `paid` за
 * окно, начавшееся раньше вебхука кассы), отсутствие поля «наши» значит
 * «неизвестно, сколько из этого наше», и в обоих случаях ЖИВОЕ число назвать
 * нельзя. Печатать там ноль — то же самое, что печатать ноль при отказе ручки:
 * читатель примет наши пробы за людей (ровно это страница и делала в итоге до
 * 11.10.2026).
 */
export function клеткаСуток(строка: Record<string, unknown>, поле: string): string {
  const всего = строка[поле];
  if (всего === null) return "не измерялось";
  if (typeof всего !== "number") return "нет числа";
  const наши = строка[поле + "Ours"];
  if (наши === null || наши === undefined) return `всего ${всего} · наши неизвестно · живые неизвестно`;
  if (typeof наши !== "number") return `всего ${всего} · наши нет числа · живые неизвестно`;
  return `всего ${всего} · наши ${наши} · живые ${всего - наши}`;
}

/** Похоже ли поле ответа на разрез: словарь, где у каждой строки есть числа. */
export function этоРазрез(значение: unknown): значение is Record<string, Клетка> {
  if (!значение || typeof значение !== "object" || Array.isArray(значение)) return false;
  const строки = Object.values(значение as Record<string, unknown>);
  if (!строки.length) return true; // пустой разрез — это ответ «никого не было»
  return строки.every(
    (с) =>
      !!с &&
      typeof с === "object" &&
      !Array.isArray(с) &&
      Object.values(с as Record<string, unknown>).some((v) => typeof v === "number"),
  );
}

/*
 * 🔴 ТРИ ИСХОДА, А НЕ ДВА — тот же урок, что в `клеткаСуток`.
 *
 * Здесь стоял `?? 0`: разрез без оси «наши» печатал «наши 0 · живые = всего»,
 * то есть наши пробы выглядели людьми. Замер 12.10.2026: сейчас ВСЕ
 * отрисовываемые разрезы ось несут, поэтому лжи на странице нет — но первый же
 * разрез без неё соврал бы молча, а именно так эта страница уже однажды
 * показывала пробы живыми людьми. Поэтому `null` вместо нуля.
 */
function живое(
  клетка: Клетка,
): { всего: number; наши: number | null; живые: number | null } | null {
  const всего = клетка.visits ?? клетка.сессий ?? null;
  if (всего === null) return null;
  const наши = клетка.visitsOurs ?? клетка.сессийНаших ?? null;
  if (наши === null) return { всего, наши: null, живые: null };
  return { всего, наши, живые: всего - наши };
}

