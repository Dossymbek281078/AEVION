/**
 * День «ГГГГ-ММ-ДД» по времени платформы — Asia/Almaty (UTC+5), календарные
 * сутки, как у разрезов воронки.
 *
 * Повод 13.10.2026 (bd, оркестратор): ключ суток в нормах, сериях и «сегодня»
 * бэкенда писался через toISOString() — это UTC, и до 05:00 утра по месту
 * «сегодня» ещё вчера: норма гостя Мультичата обновлялась в 05:00, серии и
 * дневные счётчики росли дважды за одни сутки по часам человека. Тот же класс
 * закрыт в шахматах на фронте (denPoMestnomu там — по часам браузера); на
 * сервере часов человека нет, и зона платформы — Алматы.
 *
 * Формат совпадает с прежним (первые десять знаков ISO-строки): ключи, уже
 * записанные в базе и памяти процесса, читаются как раньше; меняется только
 * граница суток.
 */
export const ЗОНА_ПЛАТФОРМЫ = "Asia/Almaty";

const формат = new Intl.DateTimeFormat("en-CA", {
  timeZone: ЗОНА_ПЛАТФОРМЫ,
  year: "numeric",
  month: "2-digit",
  day: "2-digit",
});

/** День по Алматы для момента `d` (по умолчанию — сейчас). en-CA даёт ровно ГГГГ-ММ-ДД. */
export function denPoMestnomu(d: Date = new Date()): string {
  return формат.format(d);
}

/** Календарный день назад по Алматы (границу месяца и года считает сам календарь). */
export function vcheraPoMestnomu(now: Date = new Date()): string {
  return denPoMestnomu(new Date(now.getTime() - 86_400_000 + смещениеВнутриСуток(now)));
}

