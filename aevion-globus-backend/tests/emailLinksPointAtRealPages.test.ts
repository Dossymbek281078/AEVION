import { describe, test, expect } from "vitest";
import { existsSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Каждый адрес, который уходит подписчику в письме, ведёт на существующую страницу.
 *
 * ЗАЧЕМ. Адреса в письмах записаны жёсткими строками
 * (`https://aevion.app/bureau/launch` и т. п.). Переименуй или убери маршрут —
 * ссылка станет мёртвой МОЛЧА: письмо соберётся, уйдёт, человек нажмёт и
 * получит 404. Ни один тест почты этого не увидит, потому что почта про
 * отправку, а не про то, куда ведёт.
 *
 * Класс тот же, что «обещанный канал, который никто не проверял»: обещание
 * живёт в одном месте, а исполнение — в другом, и связи между ними нет.
 *
 * ПОЧЕМУ ОФЛАЙН, А НЕ ЗАПРОСОМ. Проверка, которой нужен живой сайт, не
 * запускается никогда: в прогоне сети нет, и такая проверка либо молча
 * пропускается, либо краснеет от связи. Здесь сверяется то, что можно сверить
 * без сети, — есть ли у адреса своя страница в репозитории. Замер живости
 * делается отдельно и руками: 31.08.2026 все 10 адресов отвечали 200 при
 * отрицательном контроле 404 на выдуманном адресе.
 *
 * ГРАНИЦА ЧЕСТНАЯ. Сторож видит статические маршруты. Динамический сегмент
 * (`/bureau/cert/[certId]`) он пропустит: такой адрес собирается из данных, и
 * файла с точным именем для него нет. Пока в письмах таких нет — если появятся,
 * их надо проверять иначе, и молчание сторожа тут будет честным «не знаю», а не
 * «всё хорошо».
 */

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = resolve(HERE, "..", "src");
const APP = resolve(HERE, "..", "..", "frontend", "src", "app");

/** Файлы, которые собирают письма подписчикам. */
const MAIL_SOURCES = [
  join(SRC, "lib", "constitutionBrevo.ts"),
  join(SRC, "lib", "launchAnnounce.ts"),
];

/** Адреса нашего сайта, встречающиеся в этих файлах. */
function siteUrls(): string[] {
  const out = new Set<string>();
  for (const f of MAIL_SOURCES) {
    if (!existsSync(f)) continue;
    const text = readFileSync(f, "utf8");
    for (const m of text.matchAll(/https:\/\/aevion\.app(\/[a-z0-9/_-]*)/g)) {
      const path = m[1];
      if (path === "/" || path === "") continue;
      out.add(path.replace(/\/+$/, ""));
    }
  }
  return [...out].sort();
}

/** Есть ли у адреса своя страница. Динамические сегменты сюда не попадают. */
function hasPage(path: string): boolean {
  return existsSync(join(APP, ...path.split("/").filter(Boolean), "page.tsx"));
}

describe("ссылки из писем ведут на существующие страницы", () => {
  const urls = siteUrls();

  test("контроль: адреса в письмах вообще найдены", () => {
    // Пустой список сделал бы проверку ниже зелёной при любом состоянии —
    // в том числе если файлы писем переименуют и сторож начнёт читать пустоту.
    expect(urls.length, `найдено: ${urls.join(", ")}`).toBeGreaterThanOrEqual(5);
  });

  test("контроль: способ отличает существующую страницу от несуществующей", () => {
    // Обе стороны пробой: иначе «все страницы на месте» могло бы означать
    // «мой способ отвечает да на что угодно».
    expect(hasPage("/go"), "не видит страницу, которая точно есть").toBe(true);
    expect(hasPage("/net-takoy-stranicy-xyz"), "видит страницу, которой нет").toBe(false);
  });

  test("ни одна ссылка из письма не ведёт в никуда", () => {
    const dead = urls.filter((u) => !hasPage(u));
    expect(
      dead,
      "письмо зовёт подписчика по адресу, которому не соответствует страница: " +
        "человек нажмёт и получит 404, а отправка при этом пройдёт успешно",
    ).toEqual([]);
  });
});
