import type { Metadata } from "next";

/* Заголовок предпросмотра для клиентской страницы с динамическим адресом.
 *
 * ГРАНИЦА, И ОНА ЧЕСТНАЯ: заголовок здесь ОБЩИЙ для раздела, без имени
 * конкретного тарифа или отрасли. Имя живёт в данных, которые страница
 * забирает у API уже в браузере, а метаданные Next собирает на сервере.
 * Чтобы подставить имя, нужен generateMetadata с запросом к бэкенду во время
 * сборки — а серверный запрос отсюда 29.08.2026 уже пробовали на /shop, он
 * не отработал (адрес API на сервере резолвится через внутренние переменные),
 * и правку пришлось откатывать.
 *
 * Поэтому здесь сознательный размен: общий заголовок раздела вместо общего
 * заголовка САЙТА. Это лучше, чем было, и хуже, чем могло бы быть.
 * Когда у страницы появится серверный источник тарифов — заменить на
 * generateMetadata и подставить имя.
 *
 * ДОПОЛНЕНО 30.08.2026: сюда же добавлен canonical. Он выводится ИЗ АДРЕСА,
 * запроса к API не требует, и потому оговорка выше его не касается. Без него
 * страница наследовала canonical раздела /pricing — то есть каждый тариф
 * представлялся поиску копией общей страницы цен и в выдачу не попадал.
 */
type Props = { params: Promise<{ tierId: string }> };

/**
 * Идентификаторы тарифов, у которых есть своя страница.
 *
 * ЗАЧЕМ СПИСОК ЗДЕСЬ. Замер 08.09.2026: /pricing/no-such-page-zzz отвечает
 * 200 с полной страницей и заголовком «AEVION — тариф», то есть любой
 * выдуманный адрес под денежным разделом — индексируемый мусор. Отдать 404
 * отсюда нельзя: страница клиентская, тарифы приходят в браузер из API, а
 * серверный запрос за ними уже пробовали 29.08 и откатывали (адрес API на
 * сервере резолвится через внутренние переменные). Поэтому делается то, что
 * сторож динамических маршрутов сам называет правильным для таких случаев:
 * не ложный 404, а noindex на пустоте.
 *
 * Список короткий и стабильный, но расходиться с бэкендом он не должен —
 * это стережёт tierSlugsMatchBackend.guard.test.ts, сверяя его с массивом
 * TIERS в aevion-globus-backend/src/data/pricing.ts.
 */
const ИЗВЕСТНЫЕ_ТАРИФЫ = new Set([
  "free", "lite", "medium", "full", "pro", "enterprise",
]);

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const raw = (await params).tierId || "";
  // Значение приходит из адреса: обрезаем и кодируем, чтобы в canonical
  // не уехал чужой текст.
  const slug = encodeURIComponent(raw.slice(0, 64));
  const известный = ИЗВЕСТНЫЕ_ТАРИФЫ.has(raw.trim().toLowerCase());
  return {
    alternates: { canonical: `/pricing/${slug}` },
    // Неизвестный идентификатор: страница покажет «тариф не найден», и в
    // поиске ей делать нечего. Известные не трогаем — они должны индексироваться.
    ...(известный ? {} : { robots: { index: false, follow: true } }),
  title: "AEVION — тариф",
  description:
    "Что входит в тариф, сколько стоит и чем он отличается от соседних. Мгновенная выдача после оплаты.",
  openGraph: {
    title: "AEVION — тариф",
    description:
      "Что входит в тариф, сколько стоит и чем он отличается от соседних. Мгновенная выдача после оплаты.",
    type: "website",
    siteName: "AEVION",
  },
  twitter: {
    card: "summary_large_image",
    title: "AEVION — тариф",
    description:
      "Что входит в тариф, сколько стоит и чем он отличается от соседних. Мгновенная выдача после оплаты.",
  },
  };
}

export default function PricingTierLayout({ children }: { children: React.ReactNode }) {
  return <>{children}</>;
}
