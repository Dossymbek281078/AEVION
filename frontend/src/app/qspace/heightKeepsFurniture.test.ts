import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * Смена высоты потолка НЕ должна стирать расставленную мебель.
 *
 * Найдено 13.09.2026 сквозной пробой. Замер до починки:
 *
 *     предметов сразу после загрузки        14
 *     после ввода своей высоты              раздела «Предметы в сцене» НЕТ
 *
 * Худший класс: потеря работы на действии, к которому модуль САМ приглашает —
 * на странице написано «Поставьте свою». Человек делает ровно то, о чём
 * просят, и теряет всё расставленное. Без единого слова.
 *
 * Причина структурная: высота хранится У СТЕН, поэтому её правка меняет план,
 * а на любую смену плана сцена пересобирается и слой декора очищается. Для
 * НОВОГО чертежа это верно — мебель из другой квартиры бессмысленна. При той
 * же геометрии терять нечего.
 *
 * ПЕРВАЯ починка НЕ ПОДЕЙСТВОВАЛА, и прежняя редакция этого сторожа была при
 * ней ЗЕЛЁНОЙ. Она снимала мебель в обработчике высоты, а возвращала отдельным
 * эффектом — то есть держалась на порядке объявления двух эффектов. Сторож
 * закреплял ровно ту проводку, которая была написана, и потому подтверждал
 * неработающее. Отсюда вид проверки ниже: закрепляется ОДИН проход — снимок,
 * очистка, возврат, — внутри которого терять нечего.
 *
 * Здесь намеренно нет ни одной регулярки: сторож пишется скриптом, а обратный
 * слэш на границе вызова съедается и превращает шаблон в тихо несовпадающий.
 */
const NL = String.fromCharCode(10);
const CR = String.fromCharCode(13);

const КЛИЕНТ = readFileSync(path.join(__dirname, "_client.tsx"), "utf8")
  .split(NL)
  .map((строка) => (строка.endsWith(CR) ? строка.slice(0, -1) : строка))
  .filter((строка) => !строка.trim().startsWith("//"))
  .join(NL);

/** Тело эффекта, который пересобирает сцену под новый план. */
function телоПерестройки(): string {
  const i = КЛИЕНТ.indexOf("const сохранённые = снятьМебель");
  expect(i, "эффект перестройки не найден — сторож устарел").toBeGreaterThan(-1);
  const конец = КЛИЕНТ.indexOf("const b = planBounds(plan);", i);
  expect(конец, "конец участка не найден — сторож устарел").toBeGreaterThan(i);
  return КЛИЕНТ.slice(i, конец);
}

describe("пересборка плана сохраняет мебель", () => {
  it("контроль прибора: участок найден и непустой", () => {
    expect(телоПерестройки().length).toBeGreaterThan(200);
  });

  it("мебель снимается ДО очистки слоя декора", () => {
    const тело = телоПерестройки();
    const снимок = тело.indexOf("снятьМебель(t, placedRef.current)");
    const очистка = тело.indexOf("очиститьСлой(t.gDecor)");
    expect(снимок, "снимок не делается — мебель исчезнет").toBeGreaterThan(-1);
    expect(очистка, "очистки нет — сторож устарел").toBeGreaterThan(-1);
    expect(
      снимок,
      "снимок делается ПОСЛЕ очистки — к этому моменту брать уже нечего",
    ).toBeLessThan(очистка);
  });

  it("мебель возвращается ПОСЛЕ очистки, в том же проходе", () => {
    const тело = телоПерестройки();
    const очистка = тело.indexOf("очиститьСлой(t.gDecor)");
    const возврат = тело.indexOf("вернутьМебель(t, сохранённые)");
    expect(возврат, "возврата нет — снимок никому не нужен").toBeGreaterThan(-1);
    expect(
      возврат,
      "возврат стоит ДО очистки — она его же и сотрёт",
    ).toBeGreaterThan(очистка);
  });

  it("в состояние кладётся ВЕРНУВШЕЕСЯ, а не пустой список", () => {
    // Главный признак, и мутацией ловится именно он: вернуть мебель в сцену и
    // тут же объявить состоянию «предметов ноль» — значит показать человеку
    // пустой раздел при полной сцене. Прежняя редакция писала setPlaced([]).
    const тело = телоПерестройки();
    expect(
      тело.includes("setPlaced(вернулись)"),
      "состояние получает не возвращённый список — раздел останется пустым",
    ).toBe(true);
    expect(
      тело.includes("setPlaced([])"),
      "состояние затирается пустым списком",
    ).toBe(false);
  });

  it("возврат — ОДИН помощник на оба пути, а не две ветки", () => {
    // Второй способ делать то же самое разошёлся бы с первым молча: у загрузки
    // сохранённого проекта та же задача — поставить мебель из снимка.
    const вызовов = КЛИЕНТ.split("вернутьМебель(").length - 1;
    expect(вызовов, "помощник объявлен, но зовут его не отовсюду").toBeGreaterThanOrEqual(3);
    expect(
      КЛИЕНТ.includes("const added = вернутьМебель(t, pendingRestore.placed)"),
      "эффект восстановления проекта перестал звать общий помощник",
    ).toBe(true);
  });

  it("снимок берёт ПОЛОЖЕНИЕ из сцены, а не из состояния", () => {
    // Мебель двигают мышью, и состояние о перетаскивании не знает: сняв
    // положение из состояния, мы вернули бы предметы на исходные места.
    const i = КЛИЕНТ.indexOf("function снятьМебель(");
    expect(i, "помощник снимка не найден").toBeGreaterThan(-1);
    const тело = КЛИЕНТ.slice(i, КЛИЕНТ.indexOf("function вернутьМебель("));
    expect(тело).toContain("gDecor.children");
    expect(тело).toContain("x: g.position.x");
    expect(тело).toContain("rotY: g.rotation.y");
  });

  it("загрузка проекта ЧИСТИТ слой декора перед добавлением", () => {
    // Иначе загруженная мебель ляжет поверх той, которую вернула пересборка,
    // и в сцене останутся призраки: предметов нет в списке, их нельзя выбрать,
    // нельзя удалить, и в смету они не попадают. Найдено вычиткой правки —
    // прогоном не находится: список и сцена нигде не сверяются.
    const i = КЛИЕНТ.indexOf("if (!pendingRestore) return;");
    expect(i, "эффект восстановления не найден — сторож устарел").toBeGreaterThan(-1);
    const тело = КЛИЕНТ.slice(i, КЛИЕНТ.indexOf("setPendingRestore(null)", i));
    const очистка = тело.indexOf("очиститьСлой(t.gDecor)");
    const добавление = тело.indexOf("вернутьМебель(t, pendingRestore.placed)");
    expect(очистка, "слой не чистится — в сцене останутся призраки").toBeGreaterThan(-1);
    expect(добавление, "добавления нет — сторож устарел").toBeGreaterThan(-1);
    expect(
      очистка,
      "чистка стоит ПОСЛЕ добавления — сотрёт то, что только что добавили",
    ).toBeLessThan(добавление);
  });

  it("ДРУГОЙ чертёж снимает мебель — и говорит об этом", () => {
    // Обратная сторона той же правки. Пересборка бережёт расставленное, но у
    // импорта смысл противоположный: это другая квартира, и предметы висели бы
    // по старым координатам, заезжая в новые стены. Сравнением геометрии это
    // не решается — проём тоже меняет стены, поэтому признак явный.
    const i = КЛИЕНТ.indexOf("const поставитьЧертёж = useCallback");
    expect(i, "помощника нет — импорт сохранит чужую мебель").toBeGreaterThan(-1);
    const тело = КЛИЕНТ.slice(i, КЛИЕНТ.indexOf("}, []);", i));
    expect(тело, "слой декора не чистится").toContain("очиститьСлой(t.gDecor)");
    expect(тело, "список предметов не чистится").toContain("setPlaced([])");
    expect(
      тело.includes("setWarnings("),
      "мебель снимается МОЛЧА — ровно тот дефект, из-за которого всё писалось",
    ).toBe(true);
  });

  it("каждый путь ИМПОРТА идёт через поставитьЧертёж", () => {
    // Пути перечислены поимённо: чертёж DXF, план из PDF, картинка и две
    // кнопки демо-плана. Новый путь импорта, заведённый мимо помощника, этот
    // список не обновит — поэтому ниже ещё и счёт прямых вызовов setPlan.
    for (const признак of [
      "поставитьЧертёж({ ...r.plan, name: f.name })",
      "поставитьЧертёж({ ...r.plan, name: имяФайла || r.plan.name })",
      "поставитьЧертёж({ ...p, name: имяФайла || p.name })",
    ]) {
      expect(КЛИЕНТ.includes(признак), `путь импорта мимо помощника: ${признак}`).toBe(true);
    }
    expect(
      КЛИЕНТ.split("поставитьЧертёж(demoPlan())").length - 1,
      "кнопки демо-плана ставят чертёж мимо помощника",
    ).toBe(2);
  });

  it("высота потолка переезжает в новый чертёж — поле и модель говорят одно", () => {
    // Чертёж плоский и высоты не несёт: разбор ставит стенам 2.70. А поле на
    // экране оставалось с прежним числом — человек видел свои 3.0, смета
    // считала по 2.70. Пятая часть краски и штукатурки, и ошибка тихая.
    const i = КЛИЕНТ.indexOf("const поставитьЧертёж = useCallback");
    expect(i, "помощника нет").toBeGreaterThan(-1);
    const тело = КЛИЕНТ.slice(i, КЛИЕНТ.indexOf("}, [", i));
    expect(тело, "высота человека не переносится — поле разойдётся с моделью")
      .toContain("const h = Number(heightM)");
    expect(тело, "высота не прописывается стенам нового плана")
      .toContain("walls: p.walls.map((w) => ({ ...w, height: h }))");
    expect(тело, "план ставится мимо высоты").toContain("setPlan(сВысотой)");
    // Границы те же, что у поля ввода: за ними высоты не бывает, и мусор из
    // поля не должен уехать в модель.
    expect(тело).toContain("h >= 2 && h <= 5");
    expect(
      КЛИЕНТ.includes("}, [heightM]);"),
      "помощник не видит поля высоты — возьмёт его значение с первой отрисовки",
    ).toBe(true);
  });

  it("слово о снятой мебели не затирается предупреждениями пути импорта", () => {
    // setWarnings со СПИСКОМ заменяет его целиком, а помощник дописывает своё
    // слово функциональным обновлением. Значит у каждого пути импорта замена
    // обязана стоять ВЫШЕ вызова помощника — иначе путь снимает мебель молча.
    // Растровый путь именно так и работал: четыре пути говорили, пятый молчал.
    for (const [имя, метка] of [
      ["картинка", "масштаб задан вами по картинке"],
    ] as const) {
      const i = КЛИЕНТ.indexOf(метка);
      expect(i, `путь «${имя}» не найден — сторож устарел`).toBeGreaterThan(-1);
      const начало = КЛИЕНТ.lastIndexOf("onAccept", i);
      const конец = КЛИЕНТ.indexOf("setRasterUrl(null)", i);
      expect(конец).toBeGreaterThan(начало);
      const кусок = КЛИЕНТ.slice(начало, конец);
      const замена = кусок.indexOf("setWarnings([");
      const помощник = кусок.indexOf("поставитьЧертёж(");
      expect(замена, "замены предупреждений нет — сторож устарел").toBeGreaterThan(-1);
      expect(помощник, "путь не зовёт помощника").toBeGreaterThan(-1);
      expect(
        замена,
        `путь «${имя}» заменяет предупреждения ПОСЛЕ смены чертежа — слово о снятой мебели стирается`,
      ).toBeLessThan(помощник);
    }
  });

  it("снятие мебели — один помощник, а не копия петли", () => {
    // Сохранение проекта спрашивало сцену тем же вопросом собственной петлёй.
    // Копии расходятся молча: одна учтёт поворот предмета, другая забудет.
    expect(КЛИЕНТ, "сохранение проекта снимает мебель своей петлёй")
      .toContain("снятьМебель(t, placed)");
    // Признак узкий намеренно: сцену обходят и для другого вопроса — пересчёт
    // замечаний собирает размеры предметов, и запрещать это нельзя. Копией
    // считается только сборка СНИМКА, а её узнают по полю снимка.
    expect(
      КЛИЕНТ.split("catalogId: rec.catalogId").length - 1,
      "снимок собирают в двух местах — копии расходятся молча",
    ).toBe(1);
  });

  it("проёмы и высота мебель НЕ снимают — они про ту же квартиру", () => {
    // Храповик: прямых setPlan ровно столько, сколько мест, где чертёж тот же.
    // Вырос счёт — значит завели путь, который меняет план мимо помощника, и
    // надо решить, чертёж это новый или тот же.
    const прямых = КЛИЕНТ.split("setPlan(").length - 1;
    expect(
      прямых,
      "число прямых смен плана изменилось: проверьте, новый это чертёж или тот же",
    ).toBe(4);
    expect(КЛИЕНТ, "проёмы перестали менять план напрямую").toContain("setPlan(r.plan)");
    expect(КЛИЕНТ, "высота перестала менять план напрямую")
      .toContain("setPlan((p) => ({ ...p, walls:");
  });

  it("список предметов читается через ref, а не из замыкания", () => {
    // У эффекта перестройки нет placed в зависимостях — и правильно: иначе он
    // пересобирал бы сцену на каждую постановку предмета. Значит список обязан
    // приходить через ref, иначе снимок выйдет пустым при полной сцене.
    expect(телоПерестройки()).toContain("placedRef.current");
    expect(
      КЛИЕНТ.includes("placedRef.current = placed"),
      "ref перестал синхронизироваться — он замрёт на первом значении",
    ).toBe(true);
  });
});
