import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Витрина `/apps` не должна обещать того, чего продукт не делает.
 *
 * 19.08.2026 сверка каждого обещания с кодом дала четыре расхождения из
 * одиннадцати карточек — и худшее сидело на продукте, который продаёт
 * доказуемость:
 *
 *   «Ed25519 signature»  → HMAC-SHA256, ключом которого служит ПУБЛИЧНЫЙ ключ
 *                          нотариуса. Пересчитать может любой: certId,
 *                          contentHash и открытый ключ — открытые данные.
 *   «OpenTimestamps …»   → в bureau.ts слово anchor встречается дважды, и оба
 *                          раза это text-anchor в SVG.
 *   «Virtual cards»      → выпуска карт нет нигде; есть приём платежей и
 *                          выплаты НА карту.
 *   «Unlimited usage»    → месячная квота токенов бесплатного тарифа.
 *
 * Витрина и код лежат в разных файлах и расходятся молча — карточку правит
 * маркетинг, реализацию инженер, и никто не сверяет. Этот сторож проверяет
 * ровно те формулировки, которые уже один раз оказались ложью.
 *
 * Как добавлять сюда новую строку: не «слово выглядит громким», а «проверено,
 * что кода за ним нет». Список должен состоять из уличённых обещаний, иначе он
 * начнёт краснеть на честных и его отключат.
 */

const APPS = join(dirname(fileURLToPath(import.meta.url)), "..", "apps", "page.tsx");

// ДОБАВЛЕНО 21.08.2026. Сторож читал ТОЛЬКО страницу /apps, а те же самые
// опровергнутые обещания жили в каталоге товаров и продавались там за $29/мес:
// «подпись Ed25519» и «привязка ко времени через OpenTimestamps» на продукте,
// который покупают ИМЕННО за доказуемость. Прожили два дня после того, как их
// признали неподтверждёнными.
//
// Это класс «проверка охватывала одну страницу из многих»: сторож был, был
// зелёным и защищал не то место.
const CATALOG = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "lib", "products.ts");

// Обещания записаны по-английски, а каталог на русском — поэтому сверяем по
// КЛЮЧЕВОМУ слову, а не по фразе целиком. Иначе «подпись Ed25519» прошла бы
// мимо запрета «Ed25519 signature», и сторож молчал бы на настоящем нарушении.
const CLAIM_KEYWORDS: Record<string, string[]> = {
  // ПУСТ НАМЕРЕННО с 27.08.2026, и это главный вывод из истории файла.
  //
  // Здесь стояли два «однозначных технических термина» — Ed25519 и
  // OpenTimestamps, — и оба оказались НАСТОЯЩИМИ возможностями продукта.
  // Проверено вызовом прода, а не чтением кода:
  //
  //   GET /api/qsign/v2/keys      -> kid qsign-ed25519-v1, algo "Ed25519",
  //                                  status active, publicKey 63fd4f60e1839498...
  //   POST /api/qright/protect    -> certificate.bitcoinAnchor
  //                                  { status: "pending", hasProof: true }
  //   POST /api/pipeline/ots/:id/upgrade, /ots/:id/verify — отдельные ручки
  //
  // То есть сторож ЗАПРЕЩАЛ витрине называть то, что мы умеем. Это дороже
  // отсутствия сторожа: молчание о готовой функции никто не заметит, а
  // красный тест закрепляет молчание навсегда.
  //
  // Почему я так ошибся: смотрел, где вызова НЕТ (bureau.ts подписывает
  // HMAC — это правда), и делал вывод обо ВСЁМ продукте. Ноль вызовов в
  // одном файле значит «в этом файле не зовут», а не «не умеем». Различает
  // это только проба.
  //
  // Прежде чем вносить сюда новое слово: выпусти артефакт продукта и покажи
  // его отсутствие в артефакте. Отсутствие в исходнике основанием НЕ является.
};

/**
 * Обещания, за которыми нет реализации.
 *
 * Список 19.08.2026 содержал ПЯТЬ записей. 27.08 каждая перепроверена вызовом
 * прода, и две пришлось убрать целиком, а одну сузить — то есть больше
 * половины «опровержений» были неверны. Ошибка одного рода: вывод о продукте
 * делался из наблюдения о файле.
 *
 * Убрано:
 *   Ed25519 signature — ключ qsign-ed25519-v1 активен на проде, публичный
 *                       ключ отдаётся. Верно лишь то, что СЕРТИФИКАТ БЮРО
 *                       подписывается HMAC — но это не «свойства подписи нет».
 *   OpenTimestamps    — якорение работает: сертификат приходит с
 *                       bitcoinAnchor { pending, hasProof: true }, есть
 *                       ручки /ots/:id/upgrade и /ots/:id/verify.
 *
 * Сужено:
 *   Club & tournament — турниры ЕСТЬ (12 живых, форматы swiss / round_robin /
 *                       single_elimination). Нет только управления клубами,
 *                       поэтому запрет теперь на слово о клубах, а не на пару.
 */
const DISPROVEN_CLAIMS: Array<{ text: string; why: string }> = [
  {
    text: "Virtual cards",
    why: "выпуска карт нет; qpaynet принимает платежи и делает выплаты на карту",
  },
  {
    text: "Unlimited usage",
    why: "в qcoreai есть месячная квота токенов бесплатного тарифа",
  },
  {
    text: "Club management",
    why: "управления клубами нет; Club это рейтинговый разряд и категория косметики. ТУРНИРЫ при этом есть — их называть можно и нужно",
  },
];

describe("витрина /apps не обещает несуществующего", () => {
  const src = readFileSync(APPS, "utf8");

  // Отрицательный контроль: если файл вдруг переименуют или он опустеет, все
  // проверки ниже станут зелёными молча — а это ровно тот случай, ради которого
  // сторож и написан.
  it("файл каталога на месте и содержит карточки", () => {
    expect(src.length).toBeGreaterThan(1000);
    expect(src).toContain('id: "bureau"');
    expect(src).toContain("highlights:");
  });

  for (const { text, why } of DISPROVEN_CLAIMS) {
    it(`не обещает «${text}» — ${why}`, () => {
      // Ищем в тексте карточек, а не в комментариях: разбор 19.08 ссылается на
      // эти же слова, и запрет на упоминание сделал бы невозможным объяснить,
      // почему их убрали.
      const withoutComments = src
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .split("\n")
        .filter((l) => !l.trim().startsWith("//"))
        .join("\n");
      expect(withoutComments).not.toContain(text);
    });
  }
});

describe("каталог товаров не обещает несуществующего", () => {
  const src = readFileSync(CATALOG, "utf8");

  // Тот же отрицательный контроль: переименуют файл — проверки станут
  // зелёными молча.
  it("каталог на месте и содержит товары", () => {
    expect(src.length).toBeGreaterThan(1000);
    expect(src).toContain("export const MODULES");
    expect(src).toContain("priceUsd:");
  });

  // Раньше здесь перебирались CLAIM_KEYWORDS. 27.08 список опустел (оба слова
  // оказались правдой), и describe остался БЕЗ ЕДИНОЙ проверки — зелёный и
  // пустой. Мутация это и показала: «Virtual cards», вписанное в карточку,
  // прошло насквозь. Каталог проверяется тем же списком, что и витрина:
  // пустой сторож опаснее отсутствующего, потому что его считают защитой.
  for (const { text, why } of DISPROVEN_CLAIMS) {
    it(`не продаёт «${text}» — ${why}`, () => {
      const withoutComments = src
        .split(String.fromCharCode(10))
        .filter((l) => !l.trim().startsWith("//"))
        .join(String.fromCharCode(10));
      expect(withoutComments).not.toContain(text);
    });
  }
});

// ──────────────────────────────────────────────────────────────────────────
// ДОБАВЛЕНО 21.08.2026: юридические страницы.
//
// ⚠️ ПРЕМИССА ЭТОГО РАЗДЕЛА ОПРОВЕРГНУТА 27.08.2026 — читать до конца.
//
// Было написано: «Те же два обещания стоят в /terms и /privacy, то есть в
// ДОГОВОРЕ. Замер: в qright.ts ноль упоминаний Ed25519, OpenTimestamps и
// подписи вообще». Замер верен, вывод из него — нет.
//
// Проба прода 27.08:
//   POST /api/qright/protect -> bitcoinAnchor { status: pending,
//                               hasProof: true } — якорение РАБОТАЕТ;
//                               вызов живёт в pipeline.ts, не в qright.ts
//   GET  /api/qsign/v2/keys  -> qsign-ed25519-v1, algo Ed25519, active
//
// То есть договор обещает то, что продукт делает, и «поправить текст
// договора» означало бы удалить ПРАВДУ из юридического документа.
// Ноль упоминаний в одном файле значит «в этом файле не зовут».
//
// Оговорка ради справедливости: техника в коде ЕСТЬ и работает — в
// dataQuality, pipeline, qskyway, quantum-shield. Это расхождение между
// документом и сборкой продукта, а не выдумка.
//
// Текст договора здесь НЕ правится: формулировки контракта — решение
// основателя (разбор с предлагаемой заменой лежит в
// 15-Аудиты-и-сводки). Сторож фиксирует ГРАНИЦУ: обещания не расползутся
// дальше, а когда текст поправят, проверка ниже заставит убрать файл из
// списка.

const LEGAL_PAGES = ["terms", "privacy"] as const;

// Ждут решения по тексту договора. Список тает; добавлять сюда новое НЕЛЬЗЯ.
const LEGAL_PENDING = new Set(["terms", "privacy"]);

describe("юридические страницы: обещания криптографии", () => {
  for (const page of LEGAL_PAGES) {
    const file = join(dirname(fileURLToPath(import.meta.url)), "..", page, "page.tsx");

    it(`${page}: состояние совпадает со списком ожидающих`, () => {
      const src = readFileSync(file, "utf8");
      const withoutComments = src
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .replace(/(^|[^:])\/\/.*$/gm, "$1");
      const hit = ["Ed25519", "OpenTimestamps"].some((k) =>
        withoutComments.includes(k),
      );

      if (LEGAL_PENDING.has(page)) {
        // Пока текст не поправлен — обещание обязано БЫТЬ. Иначе список
        // протух, и его надо сократить: сторож с выдуманными долгами
        // так же бесполезен, как сторож без долгов.
        expect(hit).toBe(true);
      } else {
        expect(hit).toBe(false);
      }
    });
  }

  it("контроль прибора: страницы читаются и непусты", () => {
    for (const page of LEGAL_PAGES) {
      const file = join(dirname(fileURLToPath(import.meta.url)), "..", page, "page.tsx");
      expect(readFileSync(file, "utf8").length).toBeGreaterThan(1000);
    }
  });
});
