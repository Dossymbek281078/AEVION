import { describe, expect, it } from "vitest";
import { readFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { stripComments } from "./helpers/sourceCode";

/**
 * Страница запуска переключается ПО ДАТЕ, а не руками.
 *
 * 🔴 ЗАЧЕМ. Замер 08.09.2026, за два дня до запуска. Посадочные /devhub/launch
 * и /multichat-engine/launch писали «Дату открытия объявим отдельно» и не
 * знали про дату вовсе — ни Date.UTC, ни daysUntilLaunch. То есть 10 сентября
 * подписчик получил бы письмо «модуль открыт», пришёл бы по ссылке из письма
 * и прочёл «дату объявим отдельно, оставьте адрес». У /bureau/launch и
 * /cyberchess/launch переключение уже было — класс проявлялся ровно там, где
 * его не сделали.
 *
 * Это общий класс платформы: то, что обязано стать правдой в назначенный
 * день, должно меняться ПО дате. Руками в день запуска никто не успевает, а
 * расхождение видно самому ценному посетителю — тому, кто пришёл из письма.
 *
 * ГРАНИЦА. Сторож требует лишь СВЯЗЬ страницы с датой (вычисление остатка
 * дней) — он не проверяет формулировки и не знает, какая дата верна. Дату
 * подтверждает документ основателя, а не этот файл.
 */
const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, "..");

/** Посадочные запуска, которые обещают написать в день открытия. */
const СТРАНИЦЫ = [
  "bureau/launch/page.tsx",
  "cyberchess/launch/page.tsx",
  "devhub/launch/page.tsx",
  "multichat-engine/launch/page.tsx",
];

describe("посадочные запуска меняются по дате", () => {
  it("прибор видит предмет: все страницы на месте", () => {
    const нет = СТРАНИЦЫ.filter((p) => !existsSync(join(APP, p)));
    expect(нет, `страницы не найдены: ${нет.join(", ")}`).toEqual([]);
  });

  for (const p of СТРАНИЦЫ) {
    it(`${p}: знает про дату открытия`, () => {
      const src = stripComments(readFileSync(join(APP, p), "utf8"));
      expect(
        /daysUntilLaunch\s*\(/.test(src),
        "страница не вычисляет остаток дней — значит её текст не изменится в "
        + "день запуска, и пришедший из письма прочтёт обещание вместо открытия",
      ).toBe(true);
      // Результат обязан ВЛИЯТЬ на текст, а не лежать без дела.
      const развилки = (src.match(/left *(>|<|===|!==)/g) || []).length;
      expect(развилки, "остаток дней вычисляется, но ни на что не влияет")
        .toBeGreaterThan(0);
      // Страница обязана иметь ОБА состояния: до открытия и после. Без
      // этого «ветвление есть» удовлетворялось бы одной веткой.
      expect(
        /откр(ыт|ываем)/i.test(src),
        "на странице нет текста про открытие — нечему меняться в день запуска",
      ).toBe(true);

      // 🔴 ГРАНИЦА, НАЗВАННАЯ ЧЕСТНО. Проверяется СВЯЗЬ страницы с датой, а
      // не каждое её проявление. Мутация `{left > 0` → `{false` в ОДНОЙ из
      // нескольких развилок этот сторож переживает: остальные ветвления на
      // месте, и признак выполняется. Правило «ветвлений не меньше, чем
      // упоминаний» я пробовал — оно ложно краснеет на исправном коде, где
      // left законно используется дважды внутри одной ветки (`left === 1 ?
      // "завтра" : `через ${left} дн.``). Ложная тревога хуже узкой
      // границы: сторожа, который краснеет на здоровом, отключают.
      // Что этот файл ЛОВИТ: страницу, которая про дату не знает вовсе —
      // именно так выглядели devhub и multichat до 08.09.2026.
    });
  }
});
