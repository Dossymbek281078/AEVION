import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Смета пайплайна «книга → озвучка → фильм» должна быть ВИДНА покупателю.
 *
 * Замысел основателя 28.09: человек говорит, что хочет, и слышит цену сразу.
 * Ручка /api/devhub/pipeline/quote считала её с 29.09 — но на странице не было ни
 * поля, ни кнопки, ни числа. Это ровно тот класс, который я в этот же день чинил у
 * входа пользователей: «написано, но не вызывается». Работа сделана и не работает.
 *
 * Сторож держит четыре вещи, и две последние важнее первых: цену нельзя показывать
 * молча про остановленный шаг, и нельзя брать деньги до подтверждения.
 */
const страница = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");
const словарь = readFileSync(join(__dirname, "..", "i18n.ts"), "utf8");

describe("экран сметы на витрине DevHub", () => {
  it("страница спрашивает цену у той самой ручки", () => {
    expect(страница).toContain("/api/devhub/pipeline/quote");
    expect(страница).toContain("знаковКниги");
    expect(страница).toContain("секундВидео");
    expect(страница).toContain("озвучка");
  });

  it("человек видит итог и построчный расчёт, а не одно общее число", () => {
    expect(страница).toContain("quote.total");
    expect(страница).toContain("сметаОтвет.строки.map");
  });

  it("про остановленный шаг с фильмом сказано ПРЯМО, когда фильм заказан", () => {
    // Обещать фильм, пока счёт поставщика видео пуст, нельзя — это обещание,
    // которое продукт сегодня не выполняет.
    expect(страница).toContain("quote.videoPaused");
    const i = страница.indexOf("quote.videoPaused");
    const окно = страница.slice(Math.max(0, i - 200), i + 80);
    expect(окно).toContain("сметаСекунд > 0");
  });

  it("сказано, что до подтверждения не списывается ничего", () => {
    expect(страница).toContain("quote.note");
    for (const язык of ["ru", "en", "kk"]) {
      const есть = словарь.match(new RegExp('"quote\\.note": "[^"]+"', "g")) ?? [];
      expect(есть.length, язык).toBe(3);
    }
    // и текст действительно про это, а не заглушка
    expect(словарь).toMatch(/"quote\.note": "[^"]*(не списывается|charged|алынбайды)/);
  });

  it("подписи есть на всех трёх языках страницы", () => {
    for (const ключ of ["quote.title", "quote.chars", "quote.seconds", "quote.voice", "quote.ask"]) {
      const сколько = (словарь.match(new RegExp('"' + ключ.replace(".", "\\.") + '":', "g")) ?? []).length;
      expect(сколько, ключ).toBe(3);
    }
  });

  it("поля ограничены теми же пределами, что и сервер", () => {
    // 500 000 знаков и 600 секунд — предел ручки; расхождение дало бы человеку
    // цену за объём, который сервер всё равно обрежет.
    expect(страница).toContain("max={500000}");
    expect(страница).toContain("max={600}");
  });
});
