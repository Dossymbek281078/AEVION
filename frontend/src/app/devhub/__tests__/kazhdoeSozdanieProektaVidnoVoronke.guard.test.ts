/**
 * 🔴 КАЖДЫЙ ПУТЬ СОЗДАНИЯ ПРОЕКТА ОТЧИТЫВАЕТСЯ ВОРОНКЕ.
 *
 * Повод 12.10.2026, и это не про код, а про вывод, который мы чуть не сделали.
 * Воронка показывала «build_from_idea: 4 сессии, все наши» и читалась как
 * «живых сборок нет, людям не интересно». Счёт ПО БАЗЕ за тот же день:
 * 14 проектов от 11 браузерных гостей, двое с выкаченным адресом; наши
 * инструменты — 9 проектов, 0 адресов.
 *
 * Причина: событие слалось РОВНО из одного места — кнопки «⚡ Построить».
 * Создание через модалку «+ Новый проект» не слало ничего, и такой человек для
 * воронки не существовал. Вывод строился на половине данных.
 *
 * Сторож считает ЗНАМЕНАТЕЛЬ: сколько в файле мест, создающих проект, и все ли
 * они отчитываются. Появится третий путь — проверка покраснеет, а не промолчит.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const СТРАНИЦА = readFileSync(join(process.cwd(), "src/app/devhub/page.tsx"), "utf8");

/** Места, где страница СОЗДАЁТ проект: POST на /api/devhub/projects. */
function местаСоздания(): string[] {
  const куски: string[] = [];
  const re = /fetch\(apiUrl\("\/api\/devhub\/projects"\)/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(СТРАНИЦА))) {
    // Берём окно вокруг вызова: тело запроса и то, что делается после ответа.
    const окно = СТРАНИЦА.slice(m.index, m.index + 1800);
    /*
     * ⚠️ Только СОЗДАНИЕ: тот же адрес используется и для чтения списка
     * (`cache: "no-store"` без метода). Первая редакция считала и его, нашла
     * «3 пути» и упала — ошибка была в приборе, а не в коде. Признак создания
     * один и явный: method: "POST".
     */
    if (/method:\s*"POST"/.test(окно.slice(0, 220))) куски.push(окно);
  }
  return куски;
}

describe("создание проекта видно воронке", () => {
  it("🔴 контроль прибора: места создания вообще находятся", () => {
    const места = местаСоздания();
    expect(места.length, "ни одного POST на создание проекта — прибор слеп").toBeGreaterThanOrEqual(2);
    expect(СТРАНИЦА.length).toBeGreaterThan(20_000);
  });

  it("🔴 ОБА пути создания шлют событие — знаменатель 2 из 2", () => {
    const места = местаСоздания();
    expect(места.length, `путей создания найдено ${места.length}`).toBe(2);
    const немые = места.filter((к) => !/track\(\{\s*type:\s*"feature_use"/.test(к));
    expect(немые.length, `путей без события: ${немые.length} из ${места.length}`).toBe(0);
  });

  it("🔴 у путей РАЗНЫЕ имена шага — иначе не ответить, какой вход работает", () => {
    const имена = [...СТРАНИЦА.matchAll(/feature:\s*"([a-z_]+)"/g)].map((m) => m[1]);
    expect(имена, "нет шага «нажал Построить»").toContain("build_from_idea");
    expect(имена, "нет шага «создал проект через модалку»").toContain("create_project");
    // И ровно по одному разу каждый: двойной счёт одного проекта испортил бы
    // любую долю, посчитанную по этим шагам.
    expect(имена.filter((и) => и === "build_from_idea").length).toBe(1);
    expect(имена.filter((и) => и === "create_project").length).toBe(1);
  });

  it("канал и пост не передаются руками — их ставит общий track", () => {
    // Своя подстановка канала на каждой странице — второй источник правды;
    // track берёт его из адреса, а при отсутствии — из памяти вкладки, поэтому
    // метка переживает переход на страницу проекта.
    const создания = местаСоздания().join("\n");
    expect(создания).not.toMatch(/meta:\s*\{[^}]*channel:/);
  });
});
