import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

/**
 * Сторож: у каждого живого маршрута есть описание в опубликованной спеке.
 *
 * ЗАЧЕМ. Интегратор читает не страницу, а /api/openapi.json. Спека и код —
 * два наших ответа об одном и том же, и расходятся они молча: маршрут
 * появляется, спека остаётся прежней, и снаружи API выглядит меньше, чем
 * есть. Обратный случай хуже: спека описывает то, чего нет, и запрос по
 * документации отвечает 404.
 *
 * Сторож проверяет одну сторону — что живой маршрут описан. Обратную
 * сторону (описан, но не существует) он НЕ проверяет: для этого нужен
 * запуск приложения, здесь его нет. Границу называю прямо, чтобы зелёный
 * цвет не читался шире, чем он есть.
 */
const V1 = join(__dirname, "..");
const spec = readFileSync(join(V1, "..", "..", "openapi.json", "route.ts"), "utf8");

describe("спека описывает каждый живой маршрут", () => {
  it("у всех каталогов маршрутов есть путь в спеке", () => {
    const dirs = readdirSync(V1, { withFileTypes: true })
      .filter((d) => d.isDirectory() && d.name !== "__tests__")
      .map((d) => d.name);

    // Знаменатель обязателен: без него зелёный цвет может означать «каталогов
    // не нашлось», а не «все описаны».
    expect(dirs.length, "маршрутов не найдено — сторож проверял пустоту").toBeGreaterThan(5);

    const необъявленные = dirs.filter((d) => !spec.includes(`"/v1/${d}"`));
    expect(необъявленные, "маршрут живёт, а в спеке его нет").toEqual([]);
  });
});
