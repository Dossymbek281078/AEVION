/**
 * Запрет полётов — на КАЖДОЙ строке площадки, а не только в регуляторной карточке.
 *
 * У Нью-Йорка ячейка с нулевым потолком помечена прямо в строке площадки
 * («нужна координация с УВД»), и это правильно: ограничение стоит там, где
 * человек выбирает, откуда лететь. У Астаны запрет жёстче — зона UAP28 из AIP
 * Казахстана накрывает 100% твина круглосуточно, — но в панели площадок он не
 * упоминался вовсе: строка читалась как «H-1 · кандидат на площадку · 78» под
 * заголовком «Пригодность площадок». Сам ярлык честный — «кандидат», не
 * «разрешено»; проблема в другом: оценка считает открытый радиус и просвет, то
 * есть отвечает на вопрос «сядет ли сюда аппарат», а не «можно ли отсюда
 * лететь». Рядом эти два ответа складывались в третий, которого никто не давал.
 *
 * Модуль уже держит это правило в другом месте: подписанное обоснование обязано
 * называть запрет запретом и никогда — «режимом разрешений». Здесь то же самое
 * правило доведено до экрана.
 */
export interface PadPermission {
  available: boolean;
  authority?: string;
  kind?: "permission" | "prohibition";
  /** человекочитаемое правило: «Запретная зона UAP28: полёты запрещены …» */
  regime?: string;
  /** публикация, из которой оно взято */
  source?: string;
  coveragePct?: number;
}

export interface PadProhibition {
  authority: string;
  /**
   * Что именно запрещено — уходит в подсказку строки. Берётся `regime`, а НЕ
   * `basis`: на живых данных `basis` это способ получения («ingested»,
   * «raster-sampled»), и в подсказке он не значит ничего.
   */
  rule: string;
}

/**
 * Метку получает каждая площадка города — значит и утверждение должно быть
 * верно для каждой. Поэтому нужен ПОЛНЫЙ охват: при частичном покрытии
 * (`coveragePct < 100`) какие-то площадки вне зоны, а какие именно — вопрос
 * геометрии, которой у панели нет. Городская карточка про частичный запрет
 * говорит и без нас; врать по строке ради заметности нельзя.
 *
 * Режим разрешений (`kind: "permission"`) сюда не попадает намеренно: «нужно
 * разрешение» и «запрещено» — разные ответы, и подменять один другим в сторону
 * строгости так же неверно, как в сторону мягкости.
 */
export function padProhibition(p?: PadPermission | null): PadProhibition | null {
  if (!p?.available) return null;
  if (p.kind !== "prohibition") return null;
  if ((p.coveragePct ?? 0) < 100) return null;
  return { authority: p.authority ?? "—", rule: p.regime ?? p.source ?? "" };
}
