/**
 * У каждой метки канала есть короткий вход — иначе рекламная ссылка ведёт в 404.
 *
 * Короткие адреса вида `aevion.app/fb` — это ТО, что мы кладём в подпись под
 * роликом, в шапку профиля и в объявление. Они перенаправляют на `/go?c=<метка>`
 * и тем доносят происхождение до кассы.
 *
 * Расхождение уже случалось: замер 30.08.2026 показал десять меток в каталоге
 * при шести входах — метка `fb` работала через `?c=fb`, а короткого адреса не
 * было, и `/fb` отвечал 404. Починили руками, а сторожа не поставили.
 *
 * Класс тут «список ведут в двух местах»: метку добавляют в CHANNELS (это
 * дёшево и очевидно), а страницу-вход завести забывают. Ошибка не падает и не
 * краснеет — она проявляется тем, что человек по объявлению попадает в никуда,
 * а мы видим просто отсутствие трафика.
 */
import { describe, it, expect } from "vitest";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { CHANNELS } from "../products";

const метки = Object.keys(CHANNELS);

describe("короткие входы каналов", () => {
  it("метки вообще прочитаны", () => {
    // Знаменатель: без него пустой CHANNELS дал бы зелёный «все входы на месте».
    expect(метки.length, "каталог меток не прочитан").toBeGreaterThan(5);
  });

  it.each(метки)("у метки «%s» есть страница-вход", (метка) => {
    const путь = join(process.cwd(), "src/app", метка, "page.tsx");
    expect(existsSync(путь), `нет короткого адреса /${метка} — ссылка в объявлении даст 404`).toBe(
      true,
    );
  });

  it.each(метки)("вход /%s доносит СВОЮ метку, а не чужую", (метка) => {
    /*
     * Вторая половина, и она важнее первой: страница может существовать и
     * перенаправлять с ЧУЖОЙ меткой — тогда 404 нет, а происхождение покупки
     * приписывается другому каналу. Такую ошибку не видно вообще ничем.
     */
    const код = readFileSync(join(process.cwd(), "src/app", метка, "page.tsx"), "utf8");
    expect(код, `/${метка} не перенаправляет на /go со своей меткой`).toContain(
      'redirect("/go?c=' + метка + '")',
    );
  });
});
