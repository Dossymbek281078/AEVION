import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Сторож: денежные роутеры действительно смонтированы в приложении.
 *
 * ЗАЧЕМ. Все остальные тесты монтируют роутер САМИ — и потому зелены даже
 * тогда, когда приложение его не монтирует вовсе. В этом репозитории такое
 * уже случалось: коммит, целью которого было ВЕРНУТЬ два потерянных роутера,
 * заодно удалил монтирование третьего; страница три месяца открывалась на
 * проде, а обе ручки, которые она зовёт, молча отдавали 404.
 *
 * Настоящее приложение поднять в тесте нельзя: src/index.ts при импорте
 * стартует сервер и не экспортирует app. Поэтому сторож читает ИСХОДНИК
 * index.ts. Это слабее, чем поднять приложение, но ловит ровно ту регрессию,
 * которой боимся: строка монтирования исчезла или путь переименован.
 *
 * ГРАНИЦА, записанная честно: сторож видит НАЛИЧИЕ строки, а не то, что
 * маршрут отвечает. Живость на проде проверяет aevion-after-deploy.mjs.
 */
const ИСХОДНИК = readFileSync(join(__dirname, "..", "src", "index.ts"), "utf8");

const ОБЯЗАТЕЛЬНЫЕ: Array<[string, string]> = [
  ["/api/pricing", "pricingRouter"],
  ["/api/pricing/checkout", "checkoutRouter"],
  ["/api/pricing/provisioning", "provisioningRouter"],
  ["/api/lemonsqueezy", "lemonSqueezyWebhookRouter"],
  ["/api/gumroad", "gumroadWebhookRouter"],
  ["/api/paybox", "payboxWebhookRouter"],
  ["/api/paypal", "paypalWebhookRouter"],
];

describe("денежные роутеры смонтированы", () => {
  test("КОНТРОЛЬ: исходник прочитан и в нём есть монтирования", () => {
    // Иначе «все на месте» удовлетворялось бы пустым файлом.
    expect(ИСХОДНИК.length, "index.ts прочитан пустым").toBeGreaterThan(1000);
    expect(
      (ИСХОДНИК.match(/app\.use\("\/api\//g) ?? []).length,
      "в исходнике не нашлось ни одного монтирования — сломан прибор"
    ).toBeGreaterThan(10);
  });

  test.each(ОБЯЗАТЕЛЬНЫЕ)("смонтирован %s", (путь, роутер) => {
    // Регулярку из СТРОКИ здесь не строим намеренно: обратные слэши
    // схлопываются на границе вызова, шаблон молча превращается в поиск
    // букв (\s -> s) и находит ноль везде. Позиционный поиск надёжнее.
    const ожидаемо = `app.use("${путь}", ${роутер})`;
    expect(
      ИСХОДНИК.includes(ожидаемо),
      `${роутер} не смонтирован на ${путь} — ручки этого модуля будут отдавать 404, а тесты останутся зелёными: они монтируют роутер сами`
    ).toBe(true);
  });

  test("КОНТРОЛЬ ОХВАТА: каждый импортированный роутер вебхука смонтирован", () => {
    // Список выводится из ИСХОДНИКА, а не написан рукой: пятая касса,
    // добавленная и забытая, попадёт сюда сама.
    const импортированы = [...ИСХОДНИКА_импорты()];
    expect(импортированы.length, "не найдено ни одного роутера вебхука — сломан прибор").toBeGreaterThan(0);
    const несмонтированные = импортированы.filter(
      (имя) => !ИСХОДНИК.includes(`, ${имя})`)
    );
    expect(
      несмонтированные,
      "роутер вебхука импортирован, но не смонтирован: касса будет слать оплаты в никуда"
    ).toEqual([]);
  });
});

function* ИСХОДНИКА_импорты() {
  const re = /import \{\s*([a-zA-Z]*WebhookRouter)\s*\}/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(ИСХОДНИК)) !== null) yield m[1];
}
