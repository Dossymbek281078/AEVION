import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { bezKommentariev } from "./bezKommentariev";

/**
 * Тренер доступен там, где он ценнее всего — на задачах.
 *
 * ПОВОД 06.10.2026, находка окна Роликов на проде, 390×844, гостем. Три
 * наблюдения, и два из них оказались настоящими дефектами:
 *
 *   1) во вкладке «Задачи» кнопки тренера нет вовсе — панель живёт в своей
 *      вкладке, и застрявший на задаче спросить о НЕЙ не мог;
 *   2) плитка «🧩 Из задач» ВНУТРИ панели тренера грузила позицию и последним
 *      действием звала sCoachAIEnabled(false) — то есть выключала тренера.
 *      Панель вопроса рисуется при tab==="coach" && !editorMode && coachAIEnabled,
 *      поэтому позиция вставала, а спросить о ней было нечем. Судя по всему,
 *      скопировано у соседних плиток «Свободная игра» и «Импорт», где
 *      выключение осмысленно;
 *   3) кнопка «🔤 FEN» звала window.prompt — модальное окно браузера. На
 *      телефоне ненадёжно, в автоматике гасится, и выглядит это как «кнопка
 *      не работает».
 *
 * Сторож смотрит не на файл целиком, а на КОНКРЕТНЫЕ обработчики: иначе
 * «sCoachAIEnabled(true) где-то есть» — не утверждение о той кнопке, которую
 * чинили.
 */

const ИСХОДНИК = bezKommentariev(readFileSync(join(__dirname, "..", "page.tsx"), "utf8"));

/** Кусок исходника от якоря до конца обработчика — чтобы судить именно о нём. */
function obrabotchik(якорь: string, длина = 900): string {
  const i = ИСХОДНИК.indexOf(якорь);
  expect(i, `якорь «${якорь}» не найден — сторож смотрит не туда`).toBeGreaterThan(0);
  return ИСХОДНИК.slice(i, i + длина);
}

describe("тренер доступен на задачах", () => {
  it("🔴 плитка «Из задач» ВКЛЮЧАЕТ тренера, а не выключает", () => {
    const h = obrabotchik('modeBtn("🧩","Из задач"');
    expect(h, "плитка снова выключает тренера — позиция встанет, спросить будет нечем").not.toContain("sCoachAIEnabled(false)");
    expect(h, "плитка не включает тренера").toContain("sCoachAIEnabled(true)");
  });

  it("кнопка «Текущая задача» в блоке импорта тоже включает тренера", () => {
    // Якорь — ТЕКСТ ИЗВЕЩЕНИЯ внутри обработчика, а не подпись кнопки: подпись
    // лежит в другом месте файла, и первая версия сторожа смотрела на 35 тысяч
    // знаков мимо, но выглядела осмысленной.
    const i = ИСХОДНИК.indexOf("Из задачи ·");
    expect(i, "обработчик кнопки «Текущая задача» не найден").toBeGreaterThan(0);
    const назад = ИСХОДНИК.slice(Math.max(0, i - 600), i);
    expect(назад, "кнопка не включает тренера").toContain("sCoachAIEnabled(true)");
  });

  it("🔴 во вкладке «Задачи» есть вход к тренеру с этой позицией", () => {
    const i = ИСХОДНИК.indexOf("🎓 Спросить тренера");
    expect(i, "во вкладке «Задачи» снова нет входа к тренеру").toBeGreaterThan(0);
    const назад = ИСХОДНИК.slice(Math.max(0, i - 900), i);
    // Вход обязан делать три вещи сразу, иначе он бесполезен:
    expect(назад, "не переносит позицию задачи").toContain("pzCurrent.fen");
    expect(назад, "не включает тренера").toContain("sCoachAIEnabled(true)");
    expect(назад, "не переключает на вкладку тренера").toContain('sTab("coach")');
  });

  it("🔴 FEN вводится полем на странице, а не модальным окном", () => {
    // Якорь — кнопка, переключающая поле. Она одна такая: вторая кнопка FEN
    // на странице (во вкладке анализа) этого состояния не трогает.
    const i = ИСХОДНИК.indexOf("aria-expanded={fenPole!==null}");
    expect(i, "кнопка FEN больше не раскрывает поле").toBeGreaterThan(0);
    const блок = ИСХОДНИК.slice(i, i + 1800);
    expect(блок, "поле ввода FEN пропало").toContain("aria-label=\"FEN позиции\"");
    expect(блок, "поле не связано с состоянием").toContain("onChange={e=>sFenPole(e.target.value)}");
    expect(блок, "в этом месте снова модальное окно").not.toContain("prompt(");

    // И загрузка включает тренера — поле живёт в его панели.
    const загрузка = obrabotchik("const zagruzitFen=useCallback", 1000);
    expect(загрузка, "загрузка FEN не включает тренера").toContain("sCoachAIEnabled(true)");
    expect(загрузка, "пустое поле должно молча ничего не делать").toContain("if(!fen)return;");
  });

  it("контроль: соседние плитки по-прежнему ВЫКЛЮЧАЮТ тренера — это их замысел", () => {
    // Без этого контроля первая проверка доказывает лишь то, что строка
    // sCoachAIEnabled(false) исчезла отовсюду, — а у «За обоих» и
    // «Импорта» она на месте по делу: там человек играет сам или выбирает
    // источник, и комментарий тренера не нужен.
    const свободная = obrabotchik('modeBtn("✋","За обоих"');
    const импорт = obrabotchik('modeBtn("📥","Импорт"');
    expect(свободная + импорт, "соседние плитки перестали выключать тренера — правка задела не то").toContain("sCoachAIEnabled(false)");
  });
});
