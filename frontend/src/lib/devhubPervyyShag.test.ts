import { describe, it, expect } from "vitest";
import { primerDlyaPustogoPolya } from "./devhubPervyyShag";

const ПРИМЕРЫ = [
  "лендинг кофейни с меню, часами работы и картой проезда",
  "страница мероприятия с программой и обратным отсчётом",
  "портфолио фотографа с галереей и тёмной темой",
];

/**
 * Сторож на замеренный дефект: 66 заходов на /devhub за неделю и ноль живых
 * нажатий «Построить» (разрез byFeature, 12.10.2026). Поле встречало человека
 * пустым, кнопка была выключена до первого знака.
 */
describe("поле описания не встречает человека пустым", () => {
  it("пустое поле получает первый пример — значит кнопка сразу рабочая", () => {
    expect(primerDlyaPustogoPolya({ введено: "", примеры: ПРИМЕРЫ })).toBe(ПРИМЕРЫ[0]);
    expect(primerDlyaPustogoPolya({ введено: "   ", примеры: ПРИМЕРЫ })).toBe(ПРИМЕРЫ[0]);
  });

  it("🔴 набранное ЧЕЛОВЕКОМ не затирается — это главное свойство", () => {
    expect(primerDlyaPustogoPolya({ введено: "мой магазин кроссовок", примеры: ПРИМЕРЫ })).toBeNull();
    // даже один знак, даже с пробелами по краям
    expect(primerDlyaPustogoPolya({ введено: "  а  ", примеры: ПРИМЕРЫ })).toBeNull();
  });

  it("примеров нет или они пустые — не подставляем пустоту", () => {
    expect(primerDlyaPustogoPolya({ введено: "", примеры: [] })).toBeNull();
    expect(primerDlyaPustogoPolya({ введено: "", примеры: ["", "   "] })).toBeNull();
    // первый пустой, второй годный — берём годный, а не пустоту
    expect(primerDlyaPustogoPolya({ введено: "", примеры: ["", ПРИМЕРЫ[1]] })).toBe(ПРИМЕРЫ[1]);
  });

  it("подставленный текст — это то, что человек увидит и сможет стереть", () => {
    const п = primerDlyaPustogoPolya({ введено: "", примеры: ПРИМЕРЫ })!;
    expect(п.length).toBeGreaterThan(20);
    expect(п.trim()).toBe(п);
    // и он действительно один из показанных примеров, а не выдуманный текст
    expect(ПРИМЕРЫ).toContain(п);
  });
});
