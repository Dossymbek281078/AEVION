import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { productById } from "@/lib/products";
import { fromPricePerMonth } from "@/lib/termPricing";

/**
 * Цена DevHub стоит в ПЕРВОМ экране обеих посадочных.
 *
 * Повод денежный, 01.10.2026: с Product Hunt и LaunchNest пришло 16 сессий на
 * /devhub и /en/devhub, и до страницы цен не дошёл НИ ОДИН человек. Ссылки на
 * /pricing были — но ниже сгиба, то есть их никто не видел. За 14 дней картина
 * та же: 125 живых визитов, 22 до цен, 0 до кассы.
 *
 * ⚠️ ЧТО ЭТОТ СТОРОЖ МОЖЕТ И ЧЕГО НЕ МОЖЕТ, честно.
 * Он читает исходник и отвечает на вопрос «цена и путь в кассу объявлены рядом с
 * первым экраном, и числа взяты из источника». Он НЕ доказывает, что цена
 * ВИДНА без прокрутки: это измеряется только браузером при конкретных размерах
 * окна (1568×744 и 390×844), и такой замер идёт отдельно, после выкатки.
 * Путать эти два утверждения нельзя — сторож по исходнику зелен и тогда, когда
 * блок уехал под сгиб.
 */
const RU = readFileSync(join(__dirname, "..", "page.tsx"), "utf8");
const СЛОВАРЬ = readFileSync(join(__dirname, "..", "i18n.ts"), "utf8");
const EN = readFileSync(join(__dirname, "..", "..", "en", "devhub", "page.tsx"), "utf8");

/** Текст без комментариев: рассказ О цене ценой не является. */
function безКомментариев(текст: string): string {
  const БЛОЧНЫЙ = new RegExp("/\\*[\\s\\S]*?\\*/", "g");
  const СТРОЧНЫЙ = new RegExp("(^|[^:])//.*$", "gm");
  return текст.replace(БЛОЧНЫЙ, " ").replace(СТРОЧНЫЙ, "$1");
}

/** Часть файла до первого «второго экрана» — там, где человек оказывается сразу. */
function первыйЭкран(исходник: string): string {
  const код = безКомментариев(исходник);
  const i = код.indexOf("styles.section");
  const j = код.indexOf("store.orExample");
  const граница = [i, j].filter((n) => n > 0).sort((a, b) => a - b)[0];
  return граница ? код.slice(0, граница) : код;
}

describe("цена DevHub стоит в первом экране", () => {
  it("прибор исправен: исходники прочитаны и первый экран не пуст", () => {
    // Без этого три проверки ниже были бы зелёными на пустой строке.
    expect(RU.length).toBeGreaterThan(5000);
    expect(EN.length).toBeGreaterThan(3000);
    expect(первыйЭкран(RU).length, "первый экран русской страницы не выделился").toBeGreaterThan(500);
    expect(первыйЭкран(EN).length, "первый экран английской страницы не выделился").toBeGreaterThan(500);
    // И сам отсекатель комментариев работает — на нём уже обжигались трижды.
    expect(безКомментариев("/* $200 */ x").includes("$200")).toBe(false);
  });

  it("на английской посадочной цена и путь в кассу объявлены в первом экране", () => {
    const экран = первыйЭкран(EN);
    expect(экран, "в первом экране нет блока цены").toContain("heroPrice");
    expect(экран, "цена за длинный срок не считается из источника").toContain("fromPricePerMonth(devhub.priceUsd)");
    expect(экран, "помесячной цены нет").toContain("${devhub.priceUsd}/mo");
    expect(экран, "нет пути в кассу").toContain("devhub.href");
  });

  it("на основной посадочной цена и путь в кассу объявлены в первом экране", () => {
    const экран = первыйЭкран(RU);
    expect(экран, "в первом экране нет строки цены").toContain('t("hero.price")');
    expect(экран, "цена за длинный срок не считается из источника").toContain("fromPricePerMonth(devhubProduct.priceUsd)");
    expect(экран, "помесячной цены нет").toContain("devhubProduct.priceUsd");
    expect(экран, "нет пути в кассу").toContain("devhubProduct.href");
    expect(экран, "нет подписи ссылки").toContain('t("hero.priceCta")');
  });

  it("строка цены переведена на все три языка, иначе она откатится на английский молча", () => {
    // Пропущенный перевод у нас откатывается БЕЗ ошибки — человек видит чужой
    // язык и уходит. Поэтому ключ обязан быть в каждом словаре.
    expect((СЛОВАРЬ.match(/"hero\.price":/g) ?? []).length, "ключ цены не в трёх словарях").toBe(3);
    expect((СЛОВАРЬ.match(/"hero\.priceCta":/g) ?? []).length, "подпись ссылки не в трёх словарях").toBe(3);
    // В каждом варианте обязаны быть ОБА места подстановки, иначе одна из двух
    // цен потеряется в этом языке и никто этого не заметит.
    for (const m of СЛОВАРЬ.matchAll(/"hero\.price": "([^"]+)"/g)) {
      expect(m[1], `в строке цены нет места для срочной цены: ${m[1]}`).toContain("{a}");
      expect(m[1], `в строке цены нет места для помесячной: ${m[1]}`).toContain("{b}");
    }
  });

  it("числа НЕ вписаны руками: источник один с кассой", () => {
    // Требование оркестратора и наше правило: цена на странице и цена в кассе
    // обязаны быть одним числом. Вписанное руками расходится молча.
    const devhub = productById("devhub");
    expect(devhub, "продукт devhub не найден в каталоге").toBeTruthy();
    const помесячно = devhub!.priceUsd;
    const заГод = fromPricePerMonth(помесячно);
    expect(помесячно, "помесячная цена перестала быть числом").toBeGreaterThan(0);
    expect(заГод, "цена за длинный срок не дешевле помесячной").toBeLessThan(помесячно);

    for (const [имя, экран] of [["ru", первыйЭкран(RU)], ["en", первыйЭкран(EN)]] as const) {
      expect(
        экран.includes(`$${помесячно}`),
        `${имя}: помесячная цена вписана числом ${помесячно} вместо источника`,
      ).toBe(false);
      expect(
        экран.includes(`$${заГод}`),
        `${имя}: цена за год вписана числом ${заГод} вместо источника`,
      ).toBe(false);
    }
  });
});
