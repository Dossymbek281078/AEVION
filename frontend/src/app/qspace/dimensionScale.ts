/**
 * Масштаб PDF-чертежа по его размерным числам — чтобы не спрашивать габарит.
 *
 * PDF масштаба не хранит, но CAD-план подписан размерами в миллиметрах:
 * «1400», «2000», «4200» стоят цепочкой вдоль стены. Надпись каждого отрезка
 * цепочки стоит посередине своего отрезка, поэтому расстояние между центрами
 * СОСЕДНИХ надписей равно (a + b) / 2 мм. Делим на расстояние в пунктах листа —
 * получаем миллиметры в пункте.
 *
 * Отдельная пара врёт: между соседями бывает стена, надпись короткого отрезка
 * выносят в сторону, подписи площадей и отметок стоят в ряд случайно. Поэтому
 * берём САМУЮ ПЛОТНУЮ группу отношений (допуск 1.5 %) и её медиану.
 * Замер на LA VIE.pdf: 63 пары, 12 согласных, 42.59 мм/пт (разброс 0.3 %);
 * пары через стену дают 41.0 — на 3.7 % меньше, и при допуске 3 % они
 * подмешивались бы в группу.
 */

/** Надпись на листе: текст и центр в пунктах листа; ось — вдоль какой прямой она написана. */
export interface СловоНаЛисте {
  text: string;
  x: number;
  y: number;
  axis: "h" | "v";
}

export interface МасштабПоРазмерам {
  mmPerPt: number;
  /** сколько пар соседних чисел рассмотрено */
  pairs: number;
  /** сколько из них согласны с ответом */
  agree: number;
  /** масштаб отдельно по горизонтальным и вертикальным цепочкам, если по оси есть ≥ 2 согласных пар */
  byAxis?: { h?: number; v?: number };
  /** расхождение масштабов по осям в процентах; есть только когда найдены обе оси */
  axisMismatchPct?: number;
}

/** Меньше стольких согласных пар — ответа нет: три случайных совпадения ещё правдоподобны. */
export const МИН_СОГЛАСНЫХ_ПАР = 3;
const ДОПУСК = 0.015;

/** Элемент текста в том виде, как его отдаёт pdf.js (getTextContent). */
export interface ЭлементТекста {
  str: string;
  transform: number[];
  width: number;
}

/**
 * Из элементов pdf.js — центры числовых надписей. Берём только горизонтальные и
 * вертикальные: наклонные подписи к размерам цепочек не относятся.
 */
export function словаИзТекста(items: ЭлементТекста[]): СловоНаЛисте[] {
  const out: СловоНаЛисте[] = [];
  for (const it of items) {
    const text = (it.str ?? "").trim();
    if (!/^[0-9]{3,5}$/.test(text)) continue;
    const t = it.transform;
    if (!t || t.length < 6) continue;
    const len = Math.hypot(t[0], t[1]);
    if (!(len > 0)) continue;
    const cos = t[0] / len, sin = t[1] / len;
    const axis = Math.abs(sin) < 0.05 ? "h" : Math.abs(cos) < 0.05 ? "v" : null;
    if (!axis) continue;
    const w = Number.isFinite(it.width) ? it.width : 0;
    out.push({ text, x: t[4] + (cos * w) / 2, y: t[5] + (sin * w) / 2, axis });
  }
  return out;
}

export function масштабПоРазмерам(слова: СловоНаЛисте[]): МасштабПоРазмерам | null {
  const отношения: number[] = [];
  const поОсям: Record<"h" | "v", number[]> = { h: [], v: [] };
  for (const axis of ["h", "v"] as const) {
    const ключ = (w: СловоНаЛисте): number => (axis === "h" ? w.y : w.x);
    const место = (w: СловоНаЛисте): number => (axis === "h" ? w.x : w.y);
    const свои = слова
      .filter((w) => w.axis === axis && Number(w.text) >= 100 && Number(w.text) <= 30000)
      .sort((a, b) => ключ(a) - ключ(b));
    const группы: СловоНаЛисте[][] = [];
    let текущая: СловоНаЛисте[] = [];
    for (const w of свои) {
      if (текущая.length > 0 && Math.abs(ключ(w) - ключ(текущая[текущая.length - 1])) > 2) {
        группы.push(текущая);
        текущая = [];
      }
      текущая.push(w);
    }
    if (текущая.length > 0) группы.push(текущая);
    for (const г of группы) {
      const ряд = [...г].sort((a, b) => место(a) - место(b));
      for (let i = 1; i < ряд.length; i++) {
        const d = место(ряд[i]) - место(ряд[i - 1]);
        if (d > 3) {
          const r = (Number(ряд[i - 1].text) + Number(ряд[i].text)) / 2 / d;
          отношения.push(r);
          поОсям[axis].push(r);
        }
      }
    }
  }
  const лучшая = плотнаяГруппа(отношения);
  if (лучшая.length < МИН_СОГЛАСНЫХ_ПАР) return null;
  const итог: МасштабПоРазмерам = { mmPerPt: медиана(лучшая), pairs: отношения.length, agree: лучшая.length };

  // Масштаб по каждой оси отдельно. Чертёж, растянутый при печати (подгон под
  // лист, «по ширине»), даёт по горизонтали и вертикали РАЗНЫЕ масштабы, а общая
  // группа берёт одну ось и молчит — размеры по другой оси в модели врут.
  // Оси нужны те же три согласных пары, что и общему ответу: на LA VIE две
  // вертикальные пары «через стену» сходятся между собой на 38.3 при настоящих
  // 42.6 — с порогом в две пары это дало бы ложное «растянуто на 11 %».
  const byAxis: { h?: number; v?: number } = {};
  for (const axis of ["h", "v"] as const) {
    const г = плотнаяГруппа(поОсям[axis]);
    if (г.length >= МИН_СОГЛАСНЫХ_ПАР) byAxis[axis] = медиана(г);
  }
  if (byAxis.h !== undefined || byAxis.v !== undefined) итог.byAxis = byAxis;
  if (byAxis.h !== undefined && byAxis.v !== undefined) {
    итог.axisMismatchPct = (Math.abs(byAxis.h - byAxis.v) / Math.min(byAxis.h, byAxis.v)) * 100;
  }
  return итог;
}

/** Расхождение масштабов по осям, начиная с которого чертёж считаем растянутым. */
export const ПОРОГ_РАСХОЖДЕНИЯ_ОСЕЙ_ПРОЦ = 2;

/** Строка для человека, если чертёж растянут по одной оси; пустой список — если всё сходится. */
export function предупреждениеОбОсях(м: МасштабПоРазмерам): string[] {
  if (м.axisMismatchPct === undefined || м.axisMismatchPct < ПОРОГ_РАСХОЖДЕНИЯ_ОСЕЙ_ПРОЦ) return [];
  const h = м.byAxis?.h ?? 0, v = м.byAxis?.v ?? 0;
  return [
    `По горизонтальным размерам масштаб ${h.toFixed(1)} мм/пт, по вертикальным ${v.toFixed(1)} — `
    + `расходятся на ${м.axisMismatchPct.toFixed(1)} %. Похоже, чертёж растянут при печати «по ширине листа»: `
    + "размеры вдоль одной из осей в модели будут неверны. Сохраните PDF из CAD заново, с масштабом 1:1.",
  ];
}

function плотнаяГруппа(значения: number[]): number[] {
  let лучшая: number[] = [];
  for (const r of значения) {
    const группа = значения.filter((x) => Math.abs(x - r) / r <= ДОПУСК);
    if (группа.length > лучшая.length) лучшая = группа;
  }
  return [...лучшая].sort((a, b) => a - b);
}

function медиана(отсортированные: number[]): number {
  return отсортированные[Math.floor(отсортированные.length / 2)];
}
