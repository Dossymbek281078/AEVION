import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Не удалось загрузить — это не «ноль».
 *
 * 28.08.2026, проверка ворот запуска «отказ показывается отказом»: перекрыл
 * модулю и сервер, и запасной файл с задачами. На экране появилось
 * «◆ Решить задачу 0», а строчкой ниже — «Полмиллиона задач в банке».
 * Человек не может понять, сломалось у нас или задач правда нет; ни одного
 * слова об отказе на экране не было.
 *
 * Три исхода вместо двух: грузятся / загружены / загрузить НЕ удалось.
 */
const PAGE = path.join(__dirname, "..", "page.tsx");
const src = fs.readFileSync(PAGE, "utf8");

describe("неудачная загрузка задач не выглядит как ноль", () => {
  it("есть отдельное состояние отказа", () => {
    expect(src).toContain("pzLoadFailed");
  });

  it("оба пути загрузки отмечают отказ", () => {
    // маленький слайс при старте и полный пул при открытии вкладки
    expect((src.match(/sPzLoadFailed\(true\)/g) || []).length).toBeGreaterThanOrEqual(2);
  });

  it("успешная загрузка снимает отметку", () => {
    expect(src).toContain("sPzLoadFailed(false)");
  });

  it("число на экране считается с учётом отказа", () => {
    const m = src.match(/const pzCountLabel=([\s\S]{0,200}?);/);
    expect(m, "pzCountLabel должен существовать").toBeTruthy();
    expect(m![1], "в подписи числа должен участвовать признак отказа").toContain("pzLoadFailed");
  });

  it("отказ не молчит: человеку говорят словами", () => {
    expect(src).toContain("Задачи не загрузились");
  });
});
