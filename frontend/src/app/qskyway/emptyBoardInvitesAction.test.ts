import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * Пустая доска слотов зовёт к действию, а не просто сообщает о пустоте.
 *
 * ЗАЧЕМ. С 30.09.2026 ручка не отдаёт наши прогоны, и доска честно пуста:
 * настоящих броней нет ни одной (замер: 41 запись, все наши). «Пусто» без
 * следующего шага читается как поломка.
 *
 * И вторая половина, важнее первой: приглашение обязано вести к действию с
 * ВИДИМЫМ следом. Кнопка брони шлёт `holder: "AEVION demo"` — по нашему
 * признаку это проба, и до правки шага 2 такая бронь исчезала с доски сразу
 * после нажатия. Приглашать нажимать кнопку, чей результат пропадает, нельзя:
 * это молчаливый отказ, и он хуже пустой доски.
 *
 * ГРАНИЦА, названная честно: это проверка ИСХОДНИКА. Она отвечает
 * «приглашение есть и висит на той же ручке брони», но НЕ «человек увидел его
 * и бронь появилась». Второе проверяется браузером; существующий
 * everyButtonIsPressed мою кнопку не покрывает — мутация `onClick={() => {}}`
 * прошла мимо него, и я это проверил, а не предположил.
 */

const CLIENT = path.join(__dirname, "_client.tsx");
const src = readFileSync(CLIENT, "utf8");

describe("пустая доска слотов приглашает к действию", () => {
  it("контроль: файл прочитан и это нужный экран", () => {
    expect(src.length).toBeGreaterThan(5000);
    expect(src).toContain("qskyway.slots.empty");
  });

  it("рядом с сообщением о пустоте есть приглашение", () => {
    expect(
      src.includes("qskyway.slots.emptyCta"),
      "пустая доска снова только сообщает о пустоте — человек прочитает это как поломку",
    ).toBe(true);
  });

  it("приглашение зовёт ту же бронь, а не ведёт в никуда", () => {
    const начало = src.indexOf("qskyway.slots.empty");
    const конец = src.indexOf("qskyway.slots.emptyCta");
    expect(конец, "приглашение не найдено").toBeGreaterThan(-1);
    const блок = src.slice(начало, конец);
    expect(
      блок.includes("onClick={bookSlot}"),
      "приглашение не привязано к брони — нажатие ничего не сделает",
    ).toBe(true);
  });

  it("подпись берётся из переводов, а не вписана строкой", () => {
    // Иначе русская надпись поедет англоязычному посетителю.
    expect(src).toContain('t("qskyway.slots.emptyCta")');
  });
});
