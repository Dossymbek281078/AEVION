import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Две подписи чипа происхождения обязаны РАЗЛИЧАТЬСЯ в каждом языке.
 *
 * ЗАЧЕМ. Чип печатает в одну строку два РАЗНЫХ числа:
 *
 *     {measuredPct}% {L.measured}, {realPct}% {L.real}
 *
 * `measured` — доля обмеренного нами; `real` — доля не выдуманного (взятого
 * из открытых источников, а не подставленного моделью). Это разные вещи, и
 * различие — суть обещания модуля: не выдавать догадку за факт.
 *
 * ЗАМЕР 04.09.2026, находка соседнего окна. В английском словаре обе подписи
 * были словом «measured», и на живых числах QSkyway с прода (measured=0,
 * derived=238, guessed=237) страница печатала:
 *
 *     0% measured, 50.1% measured
 *
 * То есть мы заявляли 50.1 % измеренности там, где наш собственный счёт
 * измеренного равен НУЛЮ, — ровно то заявление, которое модуль обещает не
 * делать. По-русски и по-казахски различие было, по-английски пропало:
 * сломан один язык из трёх, и именно тот, на котором читает покупатель за
 * пределами СНГ.
 *
 * Проверяем СВОЙСТВО (подписи различны), а не конкретные слова: перевод
 * менять можно, склеивать две меры в одно слово — нельзя.
 */

const LANG = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "lib", "i18n-lang");

function подпись(язык: string, ключ: string): string | null {
  const src = readFileSync(join(LANG, `${язык}.ts`), "utf8");
  const якорь = `"${ключ}": "`;
  const i = src.indexOf(якорь);
  if (i < 0) return null;
  const j = src.indexOf('"', i + якорь.length);
  return j < 0 ? null : src.slice(i + якорь.length, j);
}

const ЯЗЫКИ = ["ru", "en", "kk"];

describe("подписи происхождения данных различимы", () => {
  it("прибор исправен: обе подписи читаются во всех трёх языках", () => {
    // Без этого пропажа ключа делала бы сторожа зелёным: null !== null ложно,
    // но два отсутствующих ключа сравнивать бессмысленно.
    for (const я of ЯЗЫКИ) {
      expect(подпись(я, "provenance.measured"), `${я}: нет provenance.measured`).toBeTruthy();
      expect(подпись(я, "provenance.real"), `${я}: нет provenance.real`).toBeTruthy();
    }
  });

  it("«измерено» и «реальных» — не одно слово", () => {
    for (const я of ЯЗЫКИ) {
      const m = подпись(я, "provenance.measured");
      const r = подпись(я, "provenance.real");
      expect(
        r,
        `${я}: обе доли подписаны одинаково — страница заявит измеренность там, где измеренного нет`,
      ).not.toBe(m);
    }
  });

  it("подпись «реальных» не обещает измерения", () => {
    // Отдельно от различия: «measured data» отличалось бы от «measured», но
    // обещало бы то же самое. Слово об измерении в этой подписи неуместно.
    const en = (подпись("en", "provenance.real") ?? "").toLowerCase();
    expect(en.includes("measur"), "английская подпись доли реальных обещает измерение").toBe(false);
  });
});
