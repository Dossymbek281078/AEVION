/*
 * Отказ «этот срок не продаётся» доходит до покупателя на его языке.
 *
 * 🔴 Замер 30.09.2026. QSkyway продаётся только на месяц: 3, 6, 9 и 12 месяцев
 * касса отбивает `checkout_unavailable` (защита — у приложения нет своего товара,
 * а на длинных сроках запасной путь выдал бы всю платформу). А витрина на этот
 * ответ показывала «Ошибка оплаты. Попробуйте ещё раз или свяжитесь с
 * продажами»: человека, выбравшего САМЫЙ выгодный срок, отправляли повторять то,
 * что не заработает никогда.
 *
 * Сторож стоит на двух поломках, которые в этом тексте случаются молча:
 *   1. перевода нет на каком-то языке — откат на английский происходит тихо,
 *      и русскоязычный покупатель читает чужой язык в момент оплаты;
 *   2. подстановка написана не той формой скобок — тогда человек видит
 *      буквальное «{{months}}». У меня это и было в первой редакции: словарь
 *      платформы подставляет ОДИНАРНЫЕ скобки.
 */
import { describe, expect, it } from "vitest";
import ru from "../i18n-lang/ru";
import en from "../i18n-lang/en";
import kk from "../i18n-lang/kk";

const КЛЮЧ = "pricing.home.notice.termNotSold";
const ЯЗЫКИ: Array<[string, Record<string, string>]> = [
  ["ru", ru as unknown as Record<string, string>],
  ["en", en as unknown as Record<string, string>],
  ["kk", kk as unknown as Record<string, string>],
];

describe("отказ по непродаваемому сроку переведён и подставляется", () => {
  it("ключ есть на каждом языке — иначе откат на английский пройдёт молча", () => {
    for (const [имя, словарь] of ЯЗЫКИ) {
      expect(словарь[КЛЮЧ], `нет перевода для ${имя}`).toBeTruthy();
    }
  });

  it("подстановка одинарными скобками, как во всём словаре платформы", () => {
    for (const [имя, словарь] of ЯЗЫКИ) {
      const текст = словарь[КЛЮЧ];
      expect(текст, `${имя}: нет места для списка сроков`).toContain("{months}");
      expect(текст, `${имя}: двойные скобки покупатель увидит буквально`).not.toContain("{{");
    }
  });

  it("текст называет рабочий срок, а не предлагает повторить", () => {
    // Контроль смысла, а не наличия строки: прежний текст отправлял повторять.
    for (const [имя, словарь] of ЯЗЫКИ) {
      const текст = словарь[КЛЮЧ].toLowerCase();
      expect(текст, `${имя}: снова «попробуйте ещё раз»`).not.toContain("попробуйте ещё раз");
      expect(текст, `${имя}: снова «try again»`).not.toContain("try again");
    }
    // И контроль прибора: у СТАРОГО ключа эти слова действительно есть.
    const старый = (ru as unknown as Record<string, string>)["pricing.home.notice.checkoutError"].toLowerCase();
    expect(старый).toContain("попробуйте ещё раз");
  });
});
