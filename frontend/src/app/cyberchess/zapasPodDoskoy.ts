/**
 * Запас высоты ПОД доской на столе — от него напрямую зависит размер доски:
 * boardPx = vhPx − (boardTopPx + запас). Чем больше запас, тем меньше доска.
 *
 * 🔴 Замер 12.10.2026 на проде, окно ноутбука 1463×724, заход по ?puzzle=:
 * доска 257×257 — 18 % ширины, самое маленькое на экране; запас 186 держал
 * место под два ряда кнопок ПАРТИИ («Новая партия», «Сдаться», «Ничья»),
 * которые пришедшему за задачей не нужны. На телефоне (390×844) доска 351,
 * 90 % ширины — там беды нет.
 */
export const ЗАПАС_ЗАДАЧА_ПО_ССЫЛКЕ = 96;
export const ЗАПАС_НИЗКИЙ_СТОЛ = 186;
export const ЗАПАС_СТОЛ = 150;

export function zapasPodDoskoy(зашёлЗаЗадачей: boolean, lowDesktop: boolean): number {
  if (зашёлЗаЗадачей) return ЗАПАС_ЗАДАЧА_ПО_ССЫЛКЕ;
  return lowDesktop ? ЗАПАС_НИЗКИЙ_СТОЛ : ЗАПАС_СТОЛ;
}
