import { describe, test, expect } from "vitest";
import { readFileSync, existsSync } from "node:fs";
import { resolve } from "node:path";
import { TIER_BADGE, ЗНАЧОК_НЕИЗВЕСТНОГО, значокТарифа } from "../caseTierBadge";

/**
 * Незнакомый тариф не должен ронять публичную страницу цен.
 *
 * Тариф примера приходит С СЕРВЕРА, а список примеров редактируется без правки
 * кода. Значок брался прямо из таблицы: `TIER_BADGE[c.tier].bg`. В день, когда
 * появится пример с тарифом `pro` (настоящий продаваемый, $149 в месяц), поиск
 * вернул бы пустоту, обращение к `.bg` бросило бы, и страница упала бы у
 * КАЖДОГО посетителя — не у автора примера, а у всех сразу.
 *
 * Замер 05.09.2026: на проде 6 примеров, тарифы enterprise/full/medium, все
 * покрыты. Это мина, а не пожар; тест держит её обезвреженной.
 */
describe("значок тарифа переживает незнакомый тариф", () => {
  test("знакомый тариф отдаёт свой цвет", () => {
    expect(значокТарифа("enterprise")).toEqual(TIER_BADGE.enterprise);
    expect(значокТарифа("medium")).toEqual(TIER_BADGE.medium);
  });

  test("pro — настоящий тариф, которого нет в таблице: нейтральный значок, без падения", () => {
    expect(() => значокТарифа("pro")).not.toThrow();
    expect(значокТарифа("pro")).toEqual(ЗНАЧОК_НЕИЗВЕСТНОГО);
    // Именно `.bg` роняло страницу — проверяем то, что читает разметка.
    expect(значокТарифа("pro").bg).toBeTruthy();
    expect(значокТарифа("pro").fg).toBeTruthy();
  });

  test("служебные имена не выдаются за значок", () => {
    // В обычном объекте они НАХОДЯТСЯ и возвращают функцию из прототипа:
    // у неё нет `.bg`, и на экран уехала бы пустота вместо цвета.
    for (const служебное of ["constructor", "toString", "__proto__", "hasOwnProperty"]) {
      expect(значокТарифа(служебное)).toEqual(ЗНАЧОК_НЕИЗВЕСТНОГО);
      expect(значокТарифа(служебное).bg).toBeTruthy();
    }
  });

  test("пустое и не-строка тоже не роняют", () => {
    for (const мусор of ["", null, undefined]) {
      expect(значокТарифа(мусор as unknown as string)).toEqual(ЗНАЧОК_НЕИЗВЕСТНОГО);
    }
  });

  test("страница не ходит в таблицу напрямую по тарифу примера", () => {
    // Утверждение про СТРАНИЦУ, а не про функцию: защита бесполезна, если
    // рядом останется прямой поиск. Возврат к нему — самая вероятная регрессия.
    const путь = resolve(process.cwd(), "src/app/pricing/cases/page.tsx");
    expect(existsSync(путь), `не найден ${путь} — сторож ослеп`).toBe(true);

    const исходник = readFileSync(путь, "utf8");
    // Контроль охвата: файл прочитан целиком, а не пустой.
    expect(исходник.length).toBeGreaterThan(1000);
    expect(исходник).toContain("значокТарифа(");
    expect(исходник).not.toContain("TIER_BADGE[c.tier]");
  });
});
