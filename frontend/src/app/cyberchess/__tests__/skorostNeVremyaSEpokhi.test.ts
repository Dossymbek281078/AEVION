/**
 * 🔴 «СКОРОСТЬ» — ЭТО СЕКУНДЫ РЕШЕНИЯ, А НЕ ВРЕМЯ С 1970 ГОДА.
 *
 * Замер на проде 12.10.2026: после решения задачи всплывало
 * «+5 Chessy · ⏱ скорость 1791803299с». Секундомер заводился только в двух
 * путях — выбор задачи из списка и загрузка FEN из файла, — а задача приходит
 * и ТРЕТЬИМ путём, по ссылке `?puzzle=<id>` из ролика. Там ref оставался нулём,
 * и `Date.now() - 0` давало метку времени.
 *
 * Беда двойная, и вторая дороже: по шкале бонуса (<10 с → 20, <30 с → 10,
 * иначе 5) такой «результат» всегда попадал в последнюю ветку. То есть
 * пришедший ИЗ РОЛИКА — самый ценный для нас человек, и шахматы наш
 * крупнейший вход (40 сессий youtube|/cyberchess) — молча получал минимальную
 * награду и нелепое число в придачу.
 *
 * Правило: НЕ ЗНАЕМ — НЕ ПЕЧАТАЕМ. Выдуманная секунда хуже отсутствующей, а
 * «бонус за скорость» без измерения скорости — наша же неправда на экране.
 */
import { describe, it, expect } from "vitest";
import { sekundyResheniya, bonusZaSkorost, podpisSkorosti } from "../skorostZadachi";
import { CHESS_LAUNCH_UTC } from "../launchDate";

const СЕЙЧАС = Date.UTC(2026, 9, 12, 11, 8, 19); // 1791803299000

describe("секунды решения", () => {
  it("🔴 секундомер не заводился — числа НЕТ, а не «1791803299»", () => {
    expect(sekundyResheniya(0, СЕЙЧАС)).toBeNull();
    // Ровно то, что было на экране: вычитание нуля дало бы метку времени.
    expect(Math.floor((СЕЙЧАС - 0) / 1000)).toBe(1791803299);
  });

  it("🔴 бонус за неизмеренную скорость НЕ начисляется", () => {
    expect(bonusZaSkorost(null)).toBe(0);
    expect(podpisSkorosti(null)).toBeNull();
    // И контроль в обратную сторону: прежнее поведение дало бы минимальный
    // бонус 5 — то есть человек из ролика терял 15 Chessy молча.
    expect(bonusZaSkorost(1791803299)).toBe(5);
  });

  it("обычное решение считается правильно, и шкала прежняя", () => {
    const старт = СЕЙЧАС - 7_000;
    expect(sekundyResheniya(старт, СЕЙЧАС)).toBe(7);
    expect(bonusZaSkorost(7)).toBe(20);
    expect(bonusZaSkorost(20)).toBe(10);
    expect(bonusZaSkorost(45)).toBe(5);
    expect(podpisSkorosti(7)).toBe("⏱ скорость 7с");
  });

  it("🔴 метка старта «из прошлого века» не принимается за секундомер", () => {
    // Любое значение ДО ЗАПУСКА ШАХМАТ — это не наш старт, а чей-то ноль:
    // до запуска решений быть не могло. Граница берётся из единого источника
    // launchDate.ts (12.10.2026: свой литерал даты здесь ловил dataZapuskaOdna).
    expect(sekundyResheniya(1, СЕЙЧАС)).toBeNull();
    expect(sekundyResheniya(CHESS_LAUNCH_UTC - 1, СЕЙЧАС)).toBeNull();
    // А день запуска — уже правдоподобно.
    expect(sekundyResheniya(CHESS_LAUNCH_UTC, СЕЙЧАС)).not.toBeNull();
  });

  it("часы перевели назад — не выдумываем отрицательное время", () => {
    expect(sekundyResheniya(СЕЙЧАС + 5_000, СЕЙЧАС)).toBeNull();
  });

  it("мусор вместо чисел не ломает начисление", () => {
    expect(sekundyResheniya(Number.NaN, СЕЙЧАС)).toBeNull();
    expect(sekundyResheniya(СЕЙЧАС, Number.POSITIVE_INFINITY)).toBeNull();
  });
});
