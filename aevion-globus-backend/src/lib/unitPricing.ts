/**
 * Цены поверхностей, которые считаются НЕ в токенах.
 *
 * ЗАЧЕМ. Карточка DevHub обещает: «logs what every AI run cost». На проде 29.09.2026
 * у 50 прогонов из 73 цены не было вовсе. Причина оказалась не в отсутствии тарифа
 * у поставщика, как выглядело снаружи: восемь поверхностей DevHub (звук, клон голоса
 * и предпрослушка, распознавание речи, три ручки перевода, шаблон письма) считаются
 * в ЗНАКАХ и СЕКУНДАХ, а таблица цен модели знает только токены. Токенов у секунды
 * звука не бывает, поэтому расчёт молча возвращал ничего.
 *
 * ПРАВИЛО ЧИСЕЛ. Цены — только из опубликованных прайсов поставщиков, с источником
 * рядом, и по ВЕРХНЕЙ границе, если прайс называет вилку: занизить себестоимость
 * хуже, чем завысить — по заниженной мы назначим цену, на которой теряем деньги.
 * Выдумывать цену нельзя вообще: выдумка, поданная как замер, дороже отсутствия числа.
 */

export type ЕдиницаЦены = "знаки" | "секунды";

export interface ТарифПоЕдиницам {
  /** Цена за 1000 знаков или за 1 секунду — смотри `единица`. */
  доллары: number;
  единица: ЕдиницаЦены;
  /** Откуда число. Без источника тариф не заводится. */
  источник: string;
  /*
   * ЧЕЙ прайс посчитан (01.10.2026).
   *
   * Без этого поля тариф применялся к ЛЮБОМУ фактическому поставщику. Замер на
   * проде: квота DeepL исчерпалась, перевод ушёл на запасной канал (ответ честно
   * сказал provider: "anthropic", fallbackReason: "deepl_quota_exhausted") — а в
   * журнал расхода легла цена по прайсу DeepL. То есть считали по одному
   * поставщику, платили другому, и число в отчёте стало совпадением.
   *
   * Ложная цена хуже отсутствия цены: по отчёту о расходе принимают решения о
   * деньгах. Поэтому при несовпадении цена не выдумывается, а честно не
   * считается — и в журнале видно, КТО выполнил работу.
   */
  поставщик: string;
}

/**
 * Тарифы по поверхностям DevHub. Ключ — та же строка, что уходит в журнал прогонов.
 *
 * Чего здесь НЕТ намеренно: `sfx`, `voice-clone` и `voice-clone-preview`. У звуковых
 * эффектов ElevenLabs считает в своих кредитах и не публикует прямой цены за секунду,
 * а клон голоса входит в подписку и не тарифицируется поштучно. Поставить туда число
 * «примерно» значило бы выдать догадку за замер — они остаются без цены честно.
 */
export const ТАРИФЫ_ПО_ЕДИНИЦАМ: Record<string, ТарифПоЕдиницам> = {
  // DeepL: Developer/Growth — $25 за 1 000 000 знаков сверх пакета (прайс 29.09.2026).
  // Берём эту, верхнюю, а не $5.49 старого API Pro: он с июля 2026 не продаётся.
  translate: { доллары: 0.025, единица: "знаки", поставщик: "deepl", источник: "DeepL Developer/Growth, $25 за 1M знаков, прайс 29.09.2026" },
  "files-translate": { доллары: 0.025, единица: "знаки", поставщик: "deepl", источник: "DeepL Developer/Growth, $25 за 1M знаков, прайс 29.09.2026" },
  "files-translate-bulk": { доллары: 0.025, единица: "знаки", поставщик: "deepl", источник: "DeepL Developer/Growth, $25 за 1M знаков, прайс 29.09.2026" },
  // ElevenLabs Scribe: $0.22 за час входного звука = $0.0000611 за секунду.
  stt: { доллары: 0.0000611, единица: "секунды", поставщик: "elevenlabs", источник: "ElevenLabs Scribe, $0.22 за час, прайс 29.09.2026" },
};

/**
 * Цена прогона по объёму. Возвращает `null`, когда тарифа нет — это ТРЕТИЙ исход,
 * и он не равен нулю: ноль читается как «попользовались бесплатно», а null значит
 * «посчитать нечем», и это видно в журнале.
 */
export function ценаПоЕдиницам(
  поверхность: string,
  объём: number,
  фактическийПоставщик?: string | null,
): number | null {
  const тариф = ТАРИФЫ_ПО_ЕДИНИЦАМ[поверхность];
  if (!тариф) return null;
  // Поставщика не назвали — считаем по тарифу, как раньше: вызывающий, который
  // его не знает, не становится от этого неправ. А назвали ЧУЖОГО — цены нет.
  if (фактическийПоставщик && фактическийПоставщик !== тариф.поставщик) return null;
  const n = Number(объём);
  if (!Number.isFinite(n) || n <= 0) return null;
  const цена = тариф.единица === "знаки" ? (n / 1000) * тариф.доллары : n * тариф.доллары;
  // Округляем до одной десятитысячной цента: меньше нам всё равно не выставят,
  // а длинный хвост в журнале мешает читать.
  return Math.round(цена * 1e6) / 1e6;
}

/** Есть ли у поверхности тариф вообще. Нужен сторожу и ответу о состоянии. */
export function тарифЕсть(поверхность: string): boolean {
  return Object.prototype.hasOwnProperty.call(ТАРИФЫ_ПО_ЕДИНИЦАМ, поверхность);
}
