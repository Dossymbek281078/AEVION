import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Отказ остаётся на экране, пока человек его не закрыл. Успех исчезает сам.
 *
 * ЦЕНА ЭТОЙ ПРАВКИ УЖЕ ИЗМЕРЕНА, и она в полдня работы трёх окон, 05.10.2026.
 * Ролики трижды нажали «Выкатить» на проекте, где генерация ещё не началась.
 * Сервер трижды ответил 400 и ПОКАЗАЛ понятный тост — «В проекте нет файлов.
 * Добавьте хотя бы index.html и повторите» (проверено живым прогоном, текст
 * взят из DOM). Они его не увидели: тост исчезал через 4 секунды, а их проверка
 * смотрела позже. Дальше два окна искали дефект, которого не существует.
 *
 * Правка влияет на 58 сообщений об отказе из 108 вызовов тоста в этом файле —
 * знаменатель назван намеренно, чтобы следующий видел охват, а не «одно место».
 *
 * ⚠️ ГРАНИЦА СТОРОЖА, честно: он читает ИСХОДНИК и отвечает на вопрос «написано
 * ли, что отказ не гасится по таймеру». Он НЕ доказывает, что на экране это
 * работает: тост рисуется в браузере, и проверяется он живым прогоном после
 * выкатки. Сторож по исходнику зелен и тогда, когда компонент Toast решит иначе.
 */
const ФАЙЛ = join(__dirname, "..", "[id]", "page.tsx");
const src = readFileSync(ФАЙЛ, "utf8");

/** Тело функции по имени, по балансу фигурных скобок. */
function телоФункции(имя: string): string {
  const i = src.indexOf(имя);
  if (i < 0) return "";
  const откуда = src.indexOf("{", i);
  let гл = 0;
  for (let c = откуда; c < src.length; c++) {
    if (src[c] === "{") гл++;
    else if (src[c] === "}") {
      гл--;
      if (гл === 0) return src.slice(откуда, c + 1);
    }
  }
  return "";
}

describe("отказ не исчезает сам", () => {
  it("прибор исправен: разбор находит нужное и не находит выдуманное", () => {
    expect(телоФункции("const drainToasts").length, "drainToasts не найден").toBeGreaterThan(80);
    expect(телоФункции("const выдуманнаяФункция"), "разбор находит несуществующее").toBe("");
  });

  it("у отказа таймер НЕ ставится", () => {
    const тело = телоФункции("const drainToasts");
    expect(тело, "отказ по-прежнему гасится по таймеру").toContain('next.type === "error"');
    // Именно выход ДО установки таймера, а не просто упоминание типа.
    const i = тело.indexOf('next.type === "error"');
    const после = тело.slice(i, i + 160);
    expect(после, "после проверки типа не сбрасывается таймер").toContain("toastTimer.current = null");
    expect(после, "после проверки типа нет выхода").toContain("return");
  });

  it("успех по-прежнему исчезает сам: правка не сломала обычный путь", () => {
    // Контроль в обратную сторону. Без него «отказ не гаснет» можно было бы
    // получить, выключив таймер вообще — и тогда экран залипал бы на всём.
    const тело = телоФункции("const drainToasts");
    expect(тело, "таймер для обычных сообщений исчез").toContain("setTimeout(drainToasts");
    expect(тело, "прежние задержки потеряны").toMatch(/2200|4000/);
  });

  it("закрытие отказа продолжает очередь", () => {
    // Иначе следующий тост не покажется НИКОГДА: у отказа таймера нет, и
    // очередь останется стоять после закрытия.
    expect(src, "очередь не продолжается после закрытия").toContain("if (toastQueue.current.length > 0) drainToasts()");
  });
});

describe("кнопка выкатки неактивна без файлов", () => {
  it("обе кнопки проверяют наличие файлов", () => {
    // Сервер отвечает 400 «нет файлов» — не давать нажать честнее, чем дать и
    // отказать. Две кнопки: главная и в панели выкатки.
    expect(src).toContain("disabled={deploying || pagesDeploying || files.length === 0}");
    expect(src).toContain("disabled={pagesDeploying || files.length === 0}");
  });

  it("у неактивной кнопки есть объяснение, иначе она читается как поломка", () => {
    expect(src, "подсказки у неактивной кнопки нет").toContain("files.length === 0 ? GL.deployNeedsFiles");
    // И прежняя подсказка о возможностях не потеряна: она показывается, когда
    // файлы есть. Два title на одном элементе — ошибка, которую я уже сделал.
    expect(src).toContain("GL.deployNeedsFiles : capabilityHint");
    expect((src.match(/title=\{files\.length === 0/g) ?? []).length).toBe(2);
  });

  it("подсказка переведена на все три языка, иначе молча откатится на русский", () => {
    expect((src.match(/deployNeedsFiles: "/g) ?? []).length, "ключ не в трёх словарях").toBe(3);
    expect(src, "нет русского варианта").toContain("Сначала соберите проект");
    expect(src, "нет английского варианта").toContain("Build the project first");
    expect(src, "нет казахского варианта").toContain("Алдымен жобаны жинаңыз");
  });
});
