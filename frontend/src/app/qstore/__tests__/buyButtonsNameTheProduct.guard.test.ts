import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Кнопка покупки называет ТОВАР, а не действие.
 *
 * ЗАМЕР соседнего окна на живом проде 04.09.2026: на этой странице 27 кнопок
 * с одинаковым доступным именем «купить». Читалка умеет показать список
 * кнопок страницы — человек так и выбирает, куда нажать. Двадцать семь
 * одинаковых строк подряд выбирать не дают, а это единственный экран
 * платформы, где отдают деньги за КОНКРЕТНЫЙ товар.
 *
 * Признак опасного места общий и стоит запомнить: подпись, написанная ВНУТРИ
 * цикла отрисовки. Диф показывает, ЧТО изменилось, и молчит о том, СКОЛЬКО
 * РАЗ строка отрисуется — поэтому глазами такое не ловится.
 *
 * ГРАНИЦА. Сторож стережёт ЭТУ страницу, а не класс: он читает исходник и
 * требует, чтобы имя кнопки было выведено из товара. Другие списки платформы
 * он не видит. Класс шире — 28 находок на 17 страницах в том же замере, — и
 * закрывать его надо там, где живут те списки.
 */

const КАТАЛОГ = join(dirname(fileURLToPath(import.meta.url)), "..");
const СТРАНИЦА = readFileSync(join(КАТАЛОГ, "page.tsx"), "utf8");
const СЛОВАРЬ = readFileSync(join(КАТАЛОГ, "i18n.ts"), "utf8");

// 05.11.2026: подписи переехали в словарь i18n.ts. Сторож стережёт то же самое:
// каждая ветка имени получает название товара, и в каждом языке словаря в строке стоит {title}.
describe("кнопки покупки различают товар", () => {
  it("прибор исправен: кнопка покупки на странице есть", () => {
    // Без этого переименование кнопки делает сторожа вечнозелёным.
    expect(СТРАНИЦА, "кнопки покупки не найдено — сторож проверял бы пустоту")
      .toContain('t("getFree") : t("buy")');
  });

  it("имя кнопки выведено из товара, а не зашито", () => {
    const i = СТРАНИЦА.indexOf('aria-label={');
    expect(i, "у кнопки покупки нет собственного имени").toBeGreaterThan(-1);
    const блок = СТРАНИЦА.slice(i, СТРАНИЦА.indexOf("}" + String.fromCharCode(10), i) + 1);
    // КАЖДАЯ ветка (платный и бесплатный товар) подставляет название товара.
    const вызовы = блок.match(/t\("[A-Za-z.]+"[^)]*\)/g) ?? [];
    expect(вызовы.length, "имя кнопки разобрать не удалось").toBe(2);
    expect(
      вызовы.filter((в) => !в.includes("title: product.title")),
      "ветка имени без подстановки: кнопки этого списка назовутся одинаково",
    ).toEqual([]);
    // И в самом словаре: все языки держат {title} в обеих строках.
    const строки = СЛОВАРЬ.split(String.fromCharCode(10)).filter((л) => /"(buy|getFree)\.aria":/.test(л));
    expect(строки.length, "по две строки на три языка").toBe(6);
    expect(строки.filter((л) => !л.includes("{title}"))).toEqual([]);
  });
});
