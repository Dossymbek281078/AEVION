import { describe, it, expect } from "vitest";
import express from "express";
import request from "supertest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { devhubRouter } from "../src/routes/devhub.js";

/**
 * Ограничитель на трёх платных ручках DevHub ОТВЕЧАЕТ 429, а не просто
 * подключён.
 *
 * Зачем отдельный файл, когда рядом уже есть costlyEndpointsProtected.guard:
 * тот сторож читает исходник и доказывает, что middleware НАВЕШЕН. Это
 * утверждение о форме. Оно остаётся зелёным, если ограничитель навешен и при
 * этом ничего не отвергает — предел выкручен, условие всегда ложно, ключ у
 * каждого запроса свой. Ровно тот случай, когда «форма закреплена, а следствие
 * нет».
 *
 * Здесь проверяется следствие: поток запросов упирается в потолок.
 *
 * ДЕНЕГ НЕ ТРАТИТ, и это не случайность, а условие приёма. Тело пустое, поэтому
 * обработчик отвечает 400 «idea is required» ДО обращения к платному
 * провайдеру (devhub.ts: проверка тела стоит на два десятка строк раньше
 * вызова planProjectWithAI). Ограничитель — middleware, он идёт ещё раньше.
 * Значит поток бьётся о проверку тела и о потолок, но не о кассу.
 *
 * Проверяется В ОБЕ СТОРОНЫ. Только «где-то встретился 429» прошло бы и на
 * ограничителе, который отвергает ВСЁ подряд, — а такой хуже отсутствующего:
 * он молча ломает ручку для первого же настоящего пользователя. Поэтому
 * первый запрос обязан пройти, и только последующие упереться.
 */

// Монтируем так же, как боевое приложение. Тест, который монтирует иначе,
// доказывает работу своей сборки, а не нашей: удали строку из index.ts —
// и он останется зелёным при живом 404 на проде.
const МОНТИРОВАНИЕ = 'app.use("/api/devhub", devhubRouter);';

function приложение() {
  const app = express();
  app.use(express.json());
  app.use("/api/devhub", devhubRouter);
  return app;
}

/** Предел по умолчанию из devhub.ts. Берётся с запасом, чтобы поймать потолок. */
const ПОТОЛОК = 30;
const ПОПЫТОК = ПОТОЛОК + 5;

async function долбить(путь: string): Promise<number[]> {
  const app = приложение();
  const коды: number[] = [];
  for (let i = 0; i < ПОПЫТОК; i++) {
    const r = await request(app).post(путь).send({});
    коды.push(r.status);
    if (r.status === 429) break;
  }
  return коды;
}

// Одиннадцать платных ручек модуля. Три верхние закрыты утром 01.09, восемь
// нижних — в тот же день после того, как ПРОПУЩЕННЫЙ целевой тест показал их
// в списке известных незащищённых.
//
// Проверять их потоком безопасно и бесплатно: у каждой проверка тела стоит в
// первых строках обработчика, то есть пустое тело отбивается ДО обращения к
// платному провайдеру. Это свойство закреплено отдельным утверждением ниже —
// ослабнет проверка тела, и поток уйдёт в кассу, а мы об этом узнаем.
const РУЧКИ: Array<[string, string]> = [
  ["/api/devhub/plan", "план проекта"],
  ["/api/devhub/projects/proba/agent/workflow", "прогон агента"],
  ["/api/devhub/projects/proba/agent/workflow/stream", "прогон агента потоком"],
  ["/api/devhub/media/sfx", "звуковой эффект"],
  ["/api/devhub/media/voice-clone", "клон голоса"],
  ["/api/devhub/media/voice-clone/preview", "превью клона голоса"],
  ["/api/devhub/media/stt", "распознавание речи"],
  ["/api/devhub/media/translate", "перевод текста"],
  ["/api/devhub/projects/proba/files/translate", "перевод файла"],
  ["/api/devhub/projects/proba/files/translate-bulk", "перевод пачкой"],
  ["/api/devhub/media/email-template-create", "шаблон письма"],
];

describe("платные ручки DevHub упираются в потолок, а не отвечают бесконечно", () => {
  it("прибор исправен: боевое приложение монтирует роутер тем же префиксом", () => {
    // Контроль охвата. Без него весь файл проверял бы собственную сборку.
    const index = readFileSync(join(__dirname, "..", "src", "index.ts"), "utf8");
    expect(index, "боевой префикс разошёлся с тестовым").toContain(МОНТИРОВАНИЕ);
  });

  it.each(РУЧКИ)("%s: первый запрос проходит, поток упирается в 429", async (путь) => {
    const коды = await долбить(путь);

    // Сторона первая: ограничитель НЕ отвергает всё подряд.
    expect(коды[0], "первый же запрос отвергнут — ручка сломана для всех").not.toBe(429);

    // Сторона вторая: поток всё-таки упирается.
    expect(коды.at(-1), `за ${ПОПЫТОК} обращений потолок не сработал`).toBe(429);

    // И ни одного успеха: пустое тело обязано отбиваться, иначе поток ушёл бы
    // в платный вызов, а вместе с ним и стоимость этой проверки.
    expect(коды.filter((c) => c === 200), "пустое тело приняли как валидное").toHaveLength(0);

    // Счётчик у ручки свой, а не общий с предыдущей. Ручки проверяются по
    // очереди в одном окне: будь бюджет один на всех, второй и третьей
    // досталось бы одно обращение вместо целого потолка.
    expect(
      коды.length,
      "потолок наступил слишком рано — похоже, бюджет общий с соседней ручкой",
    ).toBeGreaterThan(ПОТОЛОК / 2);
  }, 30_000);

  it("подделанный заголовок адреса НЕ обнуляет счётчик", async () => {
    // Класс, давший на платформе 13 дефектов: ключ предела читался из
    // X-Forwarded-For — то есть из значения, которое пишет САМ вызывающий.
    // Предел при этом стоит, выглядит рабочим и обходится одной строкой в
    // заголовке. Для платной ручки это значит, что защита от робота есть
    // только на бумаге.
    //
    // Проверяем СЛЕДСТВИЕ, а не устройство: выбираем потолок обычными
    // запросами, потом шлём такой же с чужим адресом в заголовке — он обязан
    // получить тот же отказ.
    const коды = await долбить(РУЧКИ[2][0]);
    expect(коды.at(-1), "потолок не сработал — проверять нечего").toBe(429);

    const app = приложение();
    const r = await request(app)
      .post(РУЧКИ[2][0])
      .set("X-Forwarded-For", "203.0.113.7")
      .send({});
    expect(
      r.status,
      "чужой адрес в заголовке снял предел — значит ключ берётся из того, " +
        "что пишет сам вызывающий, и защита обходится одной строкой",
    ).toBe(429);
  }, 30_000);

  /*

   * Про раздельность счётчиков отдельного случая НЕТ намеренно.
   *
   * Он тут был и падал — но не потому, что счётчик общий, а потому что мой же
   * `it.each` выше уже выбирал потолок соседней ручки: окно 60 секунд, файл
   * идёт 16. То есть утверждение опиралось на данные, оставленные соседом, —
   * и «находка» была бы клеветой на исправный код.
   *
   * Раздельность доказывает сам замер выше, без единого лишнего запроса.
   * Ручки долбятся ПО ОЧЕРЕДИ, и у каждой первый запрос проходит, а до потолка
   * набегает почти полный бюджет. Будь счётчик общим, вторая и третья
   * упирались бы с ПЕРВОГО обращения — их бюджет выбрала бы предыдущая.
   * Это и закреплено проверкой длины ниже.
   */
});
