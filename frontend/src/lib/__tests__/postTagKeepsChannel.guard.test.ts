import { describe, test, it, expect } from "vitest";
import { channelFrom, postFrom, CHANNELS } from "../products";

/**
 * Сторож: подметка поста не отбирает канал.
 *
 * 🔴 Замер 30.09.2026. Instagram — единственный канал, приводящий людей до цен
 * (12 человек из 304 заходов), и трафик идёт рывками, то есть постами. Но у всех
 * ссылок ОДНА метка `?c=ig`, поэтому «какой пост сработал» ответить нечем.
 *
 * Опасность была не в отсутствии ответа, а в попытке его получить: до этой правки
 * метка `ig-post3` в список не входила, `channelFrom` возвращал null, и переход
 * терял КАНАЛ — попадал в «прямые заходы». Разметив посты своими силами, окно
 * публикаций сделало бы Instagram похожим на умерший канал, а «прямые» — на
 * выросший. Поэтому здесь проверяется ИМЕННО это: канал остаётся.
 */
describe("подметка поста", () => {
  test("канал определяется по префиксу", () => {
    expect(channelFrom("ig-kartinka3")).toBe("instagram");
    expect(channelFrom("yt-video7")).toBe("youtube");
    expect(channelFrom("ig")).toBe("instagram");
  });

  test("пост читается отдельно", () => {
    expect(postFrom("ig-kartinka3")).toBe("kartinka3");
    expect(postFrom("yt-video_7")).toBe("video_7");
    expect(postFrom("ig"), "без подметки поста нет").toBeNull();
  });

  test("КОНТРОЛЬ: выдуманный префикс по-прежнему НЕ канал", () => {
    // Иначе любая строка в адресе заводила бы новый канал, и отчёт по каналам
    // стал бы мусорным.
    for (const метка of ["vymysel-post1", "constructor-x", "-ig", "ig_post1"]) {
      expect(channelFrom(метка), `«${метка}» принято за канал`).toBeNull();
    }
  });

  test("КОНТРОЛЬ: унаследованные свойства не становятся каналом", () => {
    // Замер 02.09.2026: channelFrom("constructor") возвращал ФУНКЦИЮ Object.
    expect(channelFrom("constructor")).toBeNull();
    expect(postFrom("constructor-x")).toBeNull();
  });

  test("КОНТРОЛЬ: кривой хвост теряет И пост, И канал", () => {
    // 🔴 ЭТО ОЖИДАНИЕ Я ПОМЕНЯЛ 30.09.2026, и поменял осознанно.
    //
    // Сперва я требовал обратного: «канал остаётся при мусоре в посте». Мысль
    // была такая: если окно публикаций напишет кривую подпись, не терять же из-за
    // неё площадку. Соседнее окно показало последствие: при таком правиле
    // `?c=ig-<что угодно>` делает ЛЮБОЙ заход инстаграмным, то есть аттрибуцию
    // можно накрутить из адресной строки.
    //
    // Для решения «куда вкладываться» переоценка канала хуже недооценки: она
    // отправляет работу в площадку, которая ничего не привела. Поэтому кривой
    // хвост снова даёт null — «канал неизвестен», ровно то умолчание, что стояло
    // здесь до подметок. Наши собственные ссылки строит код, у него хвост годный.
    for (const метка of ["ig-Пост №3 <b>", `ig-${"a".repeat(41)}`, "ig-ПОСТ", "yt-a b"]) {
      expect(channelFrom(метка), `«${метка}» считается каналом — аттрибуцию можно накрутить`).toBeNull();
      expect(postFrom(метка), `«${метка}» принято как имя поста`).toBeNull();
    }
    // А годный хвост по-прежнему даёт и канал, и пост.
    expect(channelFrom("ig-kartinka3")).toBe("instagram");
    expect(postFrom("ig-kartinka3")).toBe("kartinka3");
  });
});

/**
 * 🔴 ДОБАВЛЕНО 07.10.2026: ключ канала берётся самым ДЛИННЫМ совпадением.
 *
 * Прежний разбор резал по первому дефису, а у четырёх каналов дефис есть в самом
 * ключе. Замер до починки (вывод того же прибора, что ниже):
 *   x-devhub-post7   -> канал «x», пост «devhub-post7»   ← подмена канала
 *   ads-devhub-post7 -> канал null, пост null            ← потеря канала
 * Подмена опаснее потери: объявление о DevHub записывалось каналу X, и решение
 * «куда вкладываться» уезжало в площадку, которая ничего не привела.
 *
 * Сторож нужен именно здесь, потому что с 07.10 КАЖДЫЙ короткий вход несёт метку
 * целиком: без длинного совпадения ссылка `/ads-devhub?c=ads-devhub-sept`
 * приходила бы вовсе без канала.
 */
describe("ключ канала с дефисом внутри", () => {
  const сДефисом = Object.keys(CHANNELS).filter((к) => к.includes("-"));

  it("такие ключи вообще есть", () => {
    // Знаменатель: исчезнут ключи с дефисом — проверка станет пустой и зелёной.
    expect(сДефисом.length, "ключей с дефисом не найдено — сторож проверяет пустоту")
      .toBeGreaterThanOrEqual(4);
  });

  it.each(сДефисом)("метка «%s-post7» остаётся своим каналом", (ключ) => {
    expect(channelFrom(`${ключ}-post7`), `метка с хвостом отобрала канал у ${ключ}`)
      .toBe(CHANNELS[ключ]);
    expect(postFrom(`${ключ}-post7`), `пост у ${ключ} прочитан неверно`).toBe("post7");
  });

  it("короткий ключ не проигрывает длинному там, где длинного нет", () => {
    // Обратный контроль: `x-anons` ключом не является, и здесь должен выиграть «x».
    expect(channelFrom("x-anons")).toBe(CHANNELS.x);
    expect(postFrom("x-anons")).toBe("anons");
  });

  it("выдуманный длинный префикс по-прежнему даёт null", () => {
    expect(channelFrom("ads-vydumka-post7")).toBeNull();
    expect(postFrom("ads-vydumka-post7")).toBeNull();
  });
});

describe("голый ключ канала поста не содержит", () => {
  const ключи = Object.keys(CHANNELS);

  it("ключи прочитаны", () => {
    expect(ключи.length, "каталог меток не прочитан").toBeGreaterThan(5);
  });

  it.each(ключи)("у метки «%s» поста нет", (ключ) => {
    /*
     * Найдено мутацией 07.10.2026 (снятие точного совпадения в ключКанала): без
     * него `x-devhub` разбирался как канал «x» + пост «devhub». То есть каждый
     * заход по короткому адресу /x-devhub приносил бы ВЫДУМАННЫЙ пост, и разрез
     * «какой пост сработал» наполнился бы именами каналов. Утверждение дешёвое, а
     * дыру закрывает целиком: у голого ключа поста быть не может по определению.
     */
    expect(postFrom(ключ), `у голого ключа ${ключ} прочитан пост`).toBeNull();
  });
});
