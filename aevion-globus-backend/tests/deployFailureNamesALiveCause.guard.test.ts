import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Текст неудачной выкатки обязан называть причину, которая МОЖЕТ БЫТЬ ПРАВДОЙ.
 *
 * Замер 08.09.2026: `/studio/deploy-stats` показал за неделю 5 выкаток и НОЛЬ
 * успешных. Разбирать их будут по журналу сборки — а он говорил: «CF
 * direct-upload via raw REST is deprecated, wrangler-based upload needed».
 * Загрузка при этом идёт ЧЕРЕЗ wrangler и давно только через него: сообщение
 * посылало разбирающего менять загрузчик, который менять не надо.
 *
 * Ложная причина в журнале дороже самой неудачи: неудачу видно по статусу, а
 * ложный след стоит человеку часа и уводит от настоящей.
 */
const SRC = fs.readFileSync(path.join(__dirname, "..", "src", "routes", "devhub.ts"), "utf8");

/**
 * Код БЕЗ комментариев. Первая редакция сторожа покраснела на СОБСТВЕННОМ
 * пояснении: комментарий рядом с починкой цитирует мёртвую фразу, рассказывая,
 * почему её убрали, — и проверка «фраза не вернулась» нашла её в тексте о том,
 * как этого больше не делают. Ловушка записана в правилах и всё равно
 * сработала: комментарий пишется как объяснение, а в голове «не считается».
 */
const CODE = SRC
  .split("/*").map((часть, i) => (i === 0 ? часть : часть.split("*/").slice(1).join("*/")))
  .join("")
  .split(String.fromCharCode(10))
  .filter((строка) => !строка.trim().startsWith("//"))
  .join(String.fromCharCode(10));

describe("журнал неудачной выкатки не врёт о причине", () => {
  test("прибор исправен: обе ветки отказа в файле есть", () => {
    expect(SRC, "исчезла ветка ошибки загрузчика").toContain("`wrangler: ${wranglerResult.error}`");
    expect(SRC, "исчезла ветка проверки обслуживания").toContain("verify: wrangler upload finished");
  });

  test("мёртвая причина не вернулась", () => {
    expect(
      CODE.includes("raw REST is deprecated"),
      "журнал снова винит сырой REST — а загрузка идёт через wrangler",
    ).toBe(false);
  });

  test("загрузка действительно идёт через wrangler — иначе текст пора менять обратно", () => {
    // Обратная сторона: если однажды вернутся к сырому REST, прежняя формулировка
    // снова станет правдой, и этот сторож обязан об этом сказать.
    expect(SRC, "deployViaWrangler больше не зовётся — проверьте, что говорит журнал").toContain("await deployViaWrangler(");
  });

  test("текст называет обе возможности, а не одну", () => {
    // «Не ответил» может значить и «ещё не распространилось», и «правда не
    // работает». Журнал, называющий только вторую, чинил бы не то.
    const i = SRC.indexOf("verify: wrangler upload finished");
    const кусок = SRC.slice(i, i + 400);
    expect(кусок).toContain("has not propagated yet");
    expect(кусок).toContain("does not serve");
    expect(кусок, "не сказано, сколько ждали — без этого причину не оценить").toMatch(/25s|5 attempts/);
  });
});
