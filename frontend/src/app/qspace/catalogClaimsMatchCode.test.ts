import { describe, expect, it } from "vitest";
import { readFileSync, readdirSync } from "node:fs";
const NL_КОДА = String.fromCharCode(10);
import path from "node:path";
import { MATERIALS } from "./materials";
import { CATALOG } from "./furniture";
import { CEILING_STRETCH, FLOOR_WET, WALL_BLOCK, WALL_FRAME, finishedHeightM, totalMm } from "./wallStructure";
import { WALL_HEIGHT } from "./planModel";

/**
 * Числа, которые модуль обещает СЛОВАМИ, обязаны совпадать с кодом.
 *
 * Повод конкретный и свежий: описание QSpace в реестре платформы за один день
 * разошлось с продуктом — там осталось «JPEG/PDF не разбираются», когда оба
 * формата уже работали. Прозу никто не проверяет, поэтому она стареет молча,
 * а читают её и покупатель, и соседняя вкладка.
 *
 * Здесь сверяются ДВА наших собственных ответа об одном и том же: описание в
 * реестре бэкенда против массивов в коде фронта. Расхождение — красный.
 */

const REGISTRY = path.resolve(
  __dirname, "..", "..", "..", "..",
  "aevion-globus-backend", "src", "data", "projects.ts",
);

function qspaceDescription(): string {
  const src = readFileSync(REGISTRY, "utf8");
  const start = src.indexOf('id: "qspace"');
  expect(start, "записи qspace нет в реестре").toBeGreaterThan(-1);
  const end = src.indexOf('id: "qskyway"', start);
  return src.slice(start, end > start ? end : start + 6000);
}

/** Число из фразы вида «каталог 14 материалов». */
function claimedNumber(text: string, re: RegExp): number | null {
  const m = re.exec(text);
  return m ? Number(m[1]) : null;
}

describe("описание QSpace в реестре не расходится с кодом", () => {
  const text = qspaceDescription();

  it("число материалов в описании равно длине каталога", () => {
    const claimed = claimedNumber(text, /каталог (\d+) материалов/);
    expect(claimed, "в описании нет фразы «каталог N материалов»").not.toBeNull();
    expect(claimed).toBe(MATERIALS.length);
  });

  it("число предметов мебели равно каталогу в клиенте", () => {
    const claimed = claimedNumber(text, /(\d+) предмет/);
    expect(claimed, "в описании нет фразы «N предметов»").not.toBeNull();
    // каталог живёт в furniture.ts — не в компоненте: он растёт, а страница
    // расти вместе с ним не должна
    const actual = CATALOG.length;
    expect(actual, "каталог мебели пуст").toBeGreaterThan(5);
    expect(claimed).toBe(actual);
  });

  it("толщины конструкций в описании — те же, что считает код", () => {
    expect(claimedNumber(text, /пирог пола (\d+) мм/)).toBe(totalMm(FLOOR_WET));
    expect(claimedNumber(text, /газоблок (\d+) мм/i)).toBe(totalMm(WALL_BLOCK));
    expect(claimedNumber(text, /каркас ГКЛ (\d+) мм/)).toBe(totalMm(WALL_FRAME));
    expect(claimedNumber(text, /потолок (\d+) мм/)).toBe(totalMm(CEILING_STRETCH));
  });

  it("обещанная чистовая высота — результат расчёта, а не круглое число из головы", () => {
    const m = /(\d+\.\d+) м после ремонта/.exec(text);
    expect(m, "в описании нет фразы «N.NN м после ремонта»").not.toBeNull();
    const real = finishedHeightM(WALL_HEIGHT, FLOOR_WET, CEILING_STRETCH);
    expect(Number(m![1])).toBeCloseTo(Number(real.toFixed(2)), 6);
  });

  it("описание не обещает того, чего модуль не делает", () => {
    // 09.09.2026 граница СДВИНУЛАСЬ: проёмы из DXF распознаются по блокам,
    // из PDF и картинки — нет. Сторож стерёг прежнюю формулировку и честно
    // покраснел на правке, которая ограничение сняла. Это правильно: он
    // держит ГРАНИЦУ, а границу положено переписывать осознанно, а не молча.
    // Теперь проверяются обе половины новой границы.
    expect(text, "описание молчит о том, что проёмы берутся из блоков DXF")
      .toMatch(/проёмы из DXF/i);
    expect(text, "описание молчит, что из PDF и картинки проёмы ставит человек")
      .toMatch(/PDF и картинки.{0,60}(ставит|нажатием)/i);
    // 09.09.2026, второй сдвиг границы за день: ширина теперь ИЗМЕРЯЕТСЯ по
    // определению блока. Прежнее утверждение шло шаблоном /ширина.{0,40}типова/ и
    // оставалось ЗЕЛЁНЫМ после правки — цеплялось за ДРУГОЕ предложение
    // («измеренная ширина выходит неправдоподобной, ставится типовая»). Зелёный по
    // совпадению хуже красного: он гасит перепроверку.
    expect(text, "описание молчит, что ширина измеряется по блоку")
      .toMatch(/ИЗМЕРЯЕТСЯ по определению блока/);
    expect(text, "описание не признаёт запасной типовой ширины")
      .toMatch(/определения в файле нет[^.]{0,80}типовая/);
    // и не должно утверждать обратное.
    // Порядок слов важен: прежний шаблон знал только «двери и окна», а в описании
    // стояло «Окна и двери из чертежа не распознаются вовсе» — описание спорило
    // само с собой целые сутки, а сторож молчал.
    expect(/распознаёт проёмы/i.test(text)).toBe(false);
    expect(/(двери и окна|окна и двери) из чертежа не распозна/i.test(text),
      "описание спорит само с собой: выше — распознаются, ниже — нет").toBe(false);
  });

  // 🔴 Класс, повторившийся ТРИЖДЫ за двое суток: возможность появилась в
  // коде, а описание молчит. Здесь проверяется не текст, а СООТВЕТСТВИЕ:
  // подключено в клиенте — обязано быть названо в реестре.
  it("каждая заметная возможность модуля названа в описании", () => {
    // ⚠️ 13.09.2026: сторож читал ТОЛЬКО _client.tsx — и пары, чей признак
    // живёт в dxf.ts, wallMerge.ts или rooms.ts, молча пропускались. Проверка
    // при этом была зелёной: пара, у которой не нашлось кода, считается
    // неприменимой. Поймала мутация: убрал слово из описания — сторож не
    // покраснел. У охвата сторожа ДВА измерения, и второе (какие ФАЙЛЫ) я
    // забыл, добавляя пары.
    //
    // Тесты исключены намеренно: иначе мой же тест, упоминающий символ,
    // сделал бы возможность «существующей» без единой строки продукта.
    const clientSrc = readdirSync(__dirname)
      .filter((f) => /\.tsx?$/.test(f) && !/\.test\./.test(f))
      .map((f) => readFileSync(path.join(__dirname, f), "utf8"))
      .join(NL_КОДА);
    const пары: Array<[string, RegExp, RegExp]> = [
      ["ручная установка проёмов", /placeOpening/, /ставит человек|нажатием на стену/i],
      ["экспорт GLB", /GLTFExporter/, /GLB/],
      ["сохранение проекта", /saveLocal|loadLocal/, /сохраняется в браузере|qspace\.json/i],
      ["распознавание картинки", /RasterReview/, /РАСТРОВЫЙ|картинк/i],
      ["чтение PDF", /readPdfSegments/, /PDF/],
      ["площади помещений", /findRooms/, /помещени|комнат/i],
      ["проверка прохода", /checkPassage/, /перегородила|не дойти от двери/i],
      // \w в JS — это [A-Za-z0-9_]: кириллицу он НЕ покрывает, и шаблон
      // «тёпл\w+ пол» не совпадал с «тёплый пол». Сторож покраснел по делу.
      ["тёплый пол", /HeatingPanel/, /тёплый пол|тёплого пола/i],
      ["вентиляция", /VentilationPanel/, /вентиляц|воздухообмен/i],
      // «чертёж» и «чертежом» — разные буквы (ё/е): шаблон обязан брать обе,
      // иначе сторож краснеет на верном описании (поймано сразу же).
      // И признак ОБЯЗАН быть однозначным: слово «чертежа» уже есть в описании
      // в другом смысле («проёмы из чертежа не распознаются»), и сторож был бы
      // зелёным по чужому слову. Мутация это и вскрыла — третий раз за окно.
      ["чертёж сверху", /floorPlanSvg/, /черт[ёе]ж(ом|а)? сверху|схем[аы] сверху/i],
      // Признак — ФРАЗА: слово «сплит» стоит в описании ещё и как предмет
      // каталога, и сторож зеленел бы, даже если подбора мощности нет вовсе.
      ["подбор сплита", /CoolingPanel/, /подбирается сплит-система/],
      // 13.09.2026: пять возможностей 09.09 в описании ОТСУТСТВОВАЛИ — при
      // живом контроле. Класс повторился четвёртый раз, поэтому пары
      // заведены сразу, а не после следующей пропажи.
      ["сведение двойных стен", /mergeDoubleWalls/, /двум[яи] лини/i],
      ["толщина из чертежа", /wallMerge/, /ТОЛЩИНА берётся из чертежа/],
      ["двери-разрывы", /closeDoorGaps|rooms/, /РАЗРЫВОМ/],
      ["таблица единиц с футами", /ЕДИНИЦЫ/, /ФУТЫ/],
      ["высоту потолка спрашиваем", /planWallHeight/, /ВЫСОТА ПОТОЛКА/],
      // 13.09.2026, после починки прокрутки пальцем: описание обещало
      // «перетаскивание мышью» и молчало о телефоне, а вертикаль у холста
      // теперь отдана прокрутке страницы. Признак в коде — именно pan-y:
      // при возврате к "none" обещание снова станет неполным.
      ["палец тянет поперёк", /touchAction: "pan-y"/, /пальцем предмет тянется поперёк/],
      // Высота 2.70 подавалась как факт, хотя стала УМОЛЧАНИЕМ: человек
      // называет свою. Признак — слово «по умолчанию» рядом с числом.
      ["2.70 названа умолчанием", /WALL_HEIGHT/, /высоте по умолчанию 2\.70/],
      // Возможности, добавленные 13.09 во второй половине дня. Заводятся
      // СРАЗУ, а не после того, как кто-то заметит, что описание отстало:
      // за день это уже случалось пять раз подряд.
      ["старый POLYLINE", /val === "POLYLINE"/, /POLYLINE СТАРОГО ВИДА/],
      ["запятая в координате", /ЗАПЯТАЯ, а не точка/, /ЗАПЯТОЙ вместо точки/],
      ["разрыв в геометрии PDF", /долиРазрыв/, /РАЗРЫВ в геометрии/],
      ["граница по наклону скана", /ГРАНИЦА ПО НАКЛОНУ/, /ВЫРОВНЕНЫ/],
    ];
    const пропущены: string[] = [];
    for (const [имя, вКоде, вОписании] of пары) {
      if (вКоде.test(clientSrc) && !вОписании.test(text)) пропущены.push(имя);
    }
    expect(
      пропущены,
      "возможность есть в коде, а описание о ней молчит — покупатель о ней не узнает",
    ).toEqual([]);

    // ОБРАТНОЕ направление, и оно дороже. Проверка выше отвечает на вопрос
    // «описание отстало от кода» — это потеря, но честная. Вопрос «описание
    // обещает то, чего в коде НЕТ» — уже ложное обещание покупателю, и до
    // 13.09.2026 его не задавал никто. Поймано мутацией: я снял pan-y из кода,
    // сторож промолчал — и был прав по СВОЕМУ вопросу, но описание в этот
    // момент обещало поведение, которого нет.
    //
    // Направления разделены намеренно, а не слиты в равенство: у них разная
    // цена и разные тексты отказа, а сообщение «пары не сошлись» не говорит,
    // что чинить — описание или код.
    const обещано: string[] = [];
    for (const [имя, вКоде, вОписании] of пары) {
      if (вОписании.test(text) && !вКоде.test(clientSrc)) обещано.push(имя);
    }
    expect(
      обещано,
      "описание обещает возможность, которой в коде НЕТ — это ложное обещание покупателю",
    ).toEqual([]);
  });

  it("контроль прибора: выдуманной фразы в описании НЕ находится", () => {
    // без этого «совпало» неотличимо от «мой поиск находит что угодно»
    expect(claimedNumber(text, /каталог (\d+) единорогов/)).toBeNull();
  });
});

describe("описание не обещает лишнего про подбор сплита", () => {
  const cooling = readFileSync(path.join(__dirname, "cooling.ts"), "utf8");
  const text = qspaceDescription();

  it("названия из магазина, обещанные описанием, есть в коде", () => {
    for (const имя of ["девятка", "двенашка"]) {
      if (!text.includes(имя)) continue; // описание о нём не говорит — и ладно
      expect(cooling, `описание обещает «${имя}», а в подборе такого нет`).toContain(имя);
    }
  });

  it("обещание «светильники по помещениям» держится кодом", () => {
    const client = readFileSync(path.join(__dirname, "_client.tsx"), "utf8");
    if (!/светильники по помещениям/.test(text)) return; // описание об этом молчит
    // Признак — ОТСУТСТВИЕ прежнего вызова, а не наличие нового: вызовов два
    // (сцена и смета), и мутация одного из них переживала бы проверку «новый
    // вызов есть». Четвёртый раз за окно ловлюсь на признаке-по-наличию.
    expect(client, "описание обещает свет по помещениям, а сетка снова по габариту")
      .not.toContain("generateLights(plan)");
  });

  it("обещанное округление ВВЕРХ действительно вверх", () => {
    // описание говорит «округлением ВВЕРХ до типоразмера» — это утверждение о
    // поведении, и его стережёт cooling.test.ts; здесь проверяется, что в коде
    // выбор идёт по «не меньше», а не по ближайшему
    expect(cooling).toMatch(/s\.watt >= needWatt/);
  });
});
