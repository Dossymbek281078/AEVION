/**
 * СМЕТА ДО ЗАПУСКА: «книга → озвучка → короткий фильм».
 *
 * 🔴 ЗАЧЕМ. Человек говорит: «сделай книгу по моим мотивам, озвучь и сними по
 * ней фильм». За этим стоят наши деньги: текст идёт по нашим ключам моделей,
 * голос и видео — по кредитам Higgsfield. Пока цена не названа ЗАРАНЕЕ,
 * возможны ровно две плохие вещи: человек получает счёт, которого не ждал,
 * либо мы молча платим за чужую фантазию. Смета закрывает обе.
 *
 * 🔴 РАСЦЕНКИ ИЗМЕРЕНЫ, А НЕ ПРИДУМАНЫ (28.09.2026, предварительный расчёт
 * Higgsfield `get_cost`, без единого потраченного кредита):
 *   • видео kling3_0_turbo 720p: 5 секунд = 7.5 кредита → 1.5 за секунду;
 *   • озвучка seed_audio: 150 знаков = 0.7, 950 знаков = 4.8 → ≈5 за 1000 знаков.
 * Текст считается по таблице цен моделей (`services/qcoreai/pricing`), она уже
 * возвращает ДОЛЛАРЫ по фактическим токенам.
 *
 * ⚠️ ЧЕГО ЗДЕСЬ НЕТ. Перевод кредитов в доллары: цена пачки кредитов живёт в
 * кабинете Higgsfield и у нас не измерена. Поэтому смета называет кредиты
 * честно, а доллары — только там, где они действительно известны. Придумать
 * курс значило бы назвать человеку цену, которой мы не проверяли.
 */

/** Расценки в кредитах Higgsfield. Замер 28.09.2026. */
export const РАСЦЕНКИ = {
  видеоЗаСекунду: 1.5,
  озвучкаЗа1000Знаков: 5,
  /** Наша цена генерации текста, замер окна DevHub 28.09: gemini-2.5-flash. */
  долларЗаГенерациюТекста: 0.00206,
  /**
   * Цена одного кредита Higgsfield в долларах. ЗАМЕР 28.09.2026 по их же
   * прайсу: пачка 4000 кредитов стоит $190, 2000 — $95, 1000 — $49, 500 — $26.
   * Берём цену БОЛЬШОЙ пачки (0.0475), потому что мелкие дороже (до 0.052):
   * занижать себестоимость нельзя, а завышать — значит пугать человека.
   */
  долларЗаКредит: 0.0475,
} as const;

export interface ЗамыселРаботы {
  /** Сколько знаков текста в книге. */
  знаковКниги: number;
  /** Озвучивать ли книгу целиком. */
  озвучка: boolean;
  /** Длина фильма в секундах; 0 — фильм не нужен. */
  секундВидео: number;
  /** Сколько раз модель пишет текст (главы + правки). */
  генерацийТекста?: number;
}

export interface СтрокаСметы {
  шаг: string;
  кредиты: number;
  доллары: number | null;
  объяснение: string;
}

export interface Смета {
  строки: СтрокаСметы[];
  итогоКредитов: number;
  итогоДолларов: number | null;
  долларыНеполные: boolean;
  предупреждения: string[];
}

function округлить(x: number): number {
  return Math.round(x * 100) / 100;
}

/**
 * Смета по замыслу. Ничего не запускает и не тратит.
 *
 * Порядок строк = порядок работ, чтобы человек видел, за что платит на каждом
 * шаге, а не одно общее число.
 */
export function сметаРаботы(з: ЗамыселРаботы): Смета {
  const строки: СтрокаСметы[] = [];
  const предупреждения: string[] = [];

  const знаков = Math.max(0, Math.floor(з.знаковКниги || 0));
  // Скобки обязательны: смешивать ?? и || в одном выражении запрещено
  // синтаксисом, и сборщик падает разбором, а не типами.
  const поУмолчанию = Math.ceil(знаков / 4000) || 1;
  const генераций = Math.max(1, Math.floor(з.генерацийТекста ?? поУмолчанию));

  строки.push({
    шаг: "текст книги",
    кредиты: 0,
    доллары: округлить(генераций * РАСЦЕНКИ.долларЗаГенерациюТекста),
    объяснение: `${генераций} обращений к модели на ${знаков} знаков`,
  });

  if (з.озвучка && знаков > 0) {
    строки.push({
      шаг: "озвучка",
      кредиты: округлить((знаков / 1000) * РАСЦЕНКИ.озвучкаЗа1000Знаков),
      доллары: округлить((знаков / 1000) * РАСЦЕНКИ.озвучкаЗа1000Знаков * РАСЦЕНКИ.долларЗаКредит),
      объяснение: `${знаков} знаков по ${РАСЦЕНКИ.озвучкаЗа1000Знаков} кредита за 1000`,
    });
  }

  const секунд = Math.max(0, Math.floor(з.секундВидео || 0));
  if (секунд > 0) {
    строки.push({
      шаг: "фильм",
      кредиты: округлить(секунд * РАСЦЕНКИ.видеоЗаСекунду),
      доллары: округлить(секунд * РАСЦЕНКИ.видеоЗаСекунду * РАСЦЕНКИ.долларЗаКредит),
      объяснение: `${секунд} секунд по ${РАСЦЕНКИ.видеоЗаСекунду} кредита за секунду`,
    });
  }

  const итогоКредитов = округлить(строки.reduce((s, r) => s + r.кредиты, 0));
  const известныеДоллары = строки.filter((r) => r.доллары !== null);
  const долларыНеполные = строки.some((r) => r.доллары === null);
  const итогоДолларов = известныеДоллары.length
    ? округлить(известныеДоллары.reduce((s, r) => s + (r.доллары ?? 0), 0))
    : null;

  if (долларыНеполные) {
    предупреждения.push(
      "Часть шагов без цены в долларах — итог неполный, кредиты точные.",
    );
  }
  // Курс кредита измерен по прайсу БОЛЬШОЙ пачки. Мелкими пачками тот же заказ
  // выйдет дороже примерно на десятую часть — предупреждаем, а не молчим.
  предупреждения.push(
    `Курс кредита $${РАСЦЕНКИ.долларЗаКредит} взят по пачке 4000 за $190; мелкими пачками дороже.`,
  );
  if (итогоКредитов === 0 && знаков === 0) {
    предупреждения.push("Пустой замысел: ни текста, ни озвучки, ни видео.");
  }

  return { строки, итогоКредитов, итогоДолларов, долларыНеполные, предупреждения };
}

/** Хватает ли остатка кредитов на этот замысел. Ответ «не знаю» отличается от «нет». */
export function хватитЛи(
  смета: Смета,
  остатокКредитов: number | null,
): { хватает: boolean | null; нехватка: number } {
  if (остатокКредитов === null || !Number.isFinite(остатокКредитов)) {
    return { хватает: null, нехватка: 0 };
  }
  const нехватка = округлить(Math.max(0, смета.итогоКредитов - остатокКредитов));
  return { хватает: нехватка === 0, нехватка };
}

/*
 * ═══ ПОПРАВКА 29.09.2026: считать надо по ТЕМ каналам, которыми пайплайн пойдёт ═══
 *
 * Расценки выше — в кредитах Higgsfield, и они верны для НАШЕЙ внутренней работы
 * (ролики для маркетинга через окно Claude). Но продуктовый пайплайн ими идти не
 * может: у бэкенда НЕТ ключа Higgsfield. Замер 29.09 по переменным сервиса — там
 * только ELEVENLABS_API_KEY и REPLICATE_API_TOKEN. Higgsfield подключён как MCP к
 * окну, а не к серверу, и человек с сайта до него не дотянется.
 *
 * Поэтому смета, которую ВИДИТ ПОКУПАТЕЛЬ, считается по нашим каналам:
 *   текст   — наши провайдеры (замер DevHub 28.09: gemini-2.5-flash, $0.00206 за прогон);
 *   озвучка — ElevenLabs (прайс 29.09: Flash $0.05 за 1000 знаков, Multilingual $0.10);
 *   видео   — Replicate, Veo 3 Fast (прайс 29.09: $0.10–0.15 за секунду).
 *
 * Берём ВЕРХНЮЮ границу цены видео и дорогую озвучку: занизить себестоимость хуже,
 * чем завысить — по заниженной мы назначим цену, на которой будем терять деньги.
 */
export const РАСЦЕНКИ_ПРОДУКТА = {
  /** ElevenLabs Multilingual — качество, которое не стыдно отдать покупателю. */
  долларЗаОзвучку1000Знаков: 0.10,
  /** Replicate Veo 3 Fast, верхняя граница; без звука дешевле на треть. */
  долларЗаСекундуВидео: 0.15,
  /** Та же цена генерации текста, что и выше: канал один и тот же. */
  долларЗаГенерациюТекста: 0.00206,
} as const;

/**
 * Смета ПРОДУКТОВОГО заказа — в долларах, по нашим каналам.
 *
 * Отдельная функция, а не флаг у прежней: у них разные единицы (кредиты против
 * долларов) и разные поставщики. Слить их в одну значило бы получить число, про
 * которое нельзя сказать, чьё оно.
 */
/*
 * 29.09.2026: строки сметы несут КЛЮЧ и ОБЪЁМ, а не только русское название.
 * Сторож витрины поймал: англоязычный посетитель видел бы «книга», «озвучка»,
 * «фильм» по-русски — сервер отдавал готовый текст, и перевести его было нечем.
 * Русское поле оставлено для тех, кто уже читает ответ, ключ — для интерфейса.
 */
export function сметаПродукта(з: ЗамыселРаботы): {
  строки: Array<{ шаг: string; ключ: "book" | "voice" | "film"; объём: number; подробно: string; доллары: number }>;
  итогоДолларов: number;
  предупреждения: string[];
} {
  const знаков = Math.max(0, Math.round(з.знаковКниги || 0));
  const секунд = Math.max(0, Math.round(з.секундВидео || 0));
  const прогонов = Math.max(1, Math.round(з.генерацийТекста ?? Math.max(1, Math.ceil(знаков / 8000))));
  const строки: Array<{ шаг: string; ключ: "book" | "voice" | "film"; объём: number; подробно: string; доллары: number }> = [];
  const округлить = (n: number) => Math.round(n * 10000) / 10000;

  строки.push({
    шаг: "книга",
    ключ: "book",
    объём: знаков,
    подробно: `${знаков} знаков, ${прогонов} прогон(ов) модели`,
    доллары: округлить(прогонов * РАСЦЕНКИ_ПРОДУКТА.долларЗаГенерациюТекста),
  });

  if (з.озвучка && знаков > 0) {
    строки.push({
      шаг: "озвучка",
      ключ: "voice",
      объём: знаков,
      подробно: `${знаков} знаков, ElevenLabs`,
      доллары: округлить((знаков / 1000) * РАСЦЕНКИ_ПРОДУКТА.долларЗаОзвучку1000Знаков),
    });
  }

  if (секунд > 0) {
    строки.push({
      шаг: "фильм",
      ключ: "film",
      объём: секунд,
      подробно: `${секунд} с, Veo 3 Fast на Replicate`,
      доллары: округлить(секунд * РАСЦЕНКИ_ПРОДУКТА.долларЗаСекундуВидео),
    });
  }

  const итогоДолларов = округлить(строки.reduce((s, r) => s + r.доллары, 0));
  const предупреждения: string[] = [];
  if (секунд > 0) {
    предупреждения.push(
      "видео считается по верхней границе цены Veo 3 Fast ($0.15/с); без звука выходит дешевле",
    );
  }
  return { строки, итогоДолларов, предупреждения };
}
