import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Даты запуска живут в ДВУХ списках разных файлов, и оба уходят человеку:
 * `constitutionBrevo.ts` — письмо подписчику, `launchAnnounce.ts` — анонс.
 * Два источника одного факта расходятся молча: ничего не падает, письмо
 * просто называет не тот день.
 *
 * Замер 30.08.2026: расходились ЧЕТЫРЕ строки из пяти. Письмо обещало шахматы
 * 30 августа (перенесено на 30 сентября), DevHub 13 сентября и мультичат
 * 20 сентября — при плане основателя на 10 сентября. Часть сентябрьских дат
 * прежняя сессия честно пометила как выдуманные: каждая опиралась на файлы,
 * написанные ею же в тот день.
 *
 * Сторож проверяет ДВА разных утверждения, и это не одно и то же:
 *   1) списки согласны между собой;
 *   2) они согласны с решением основателя.
 * Второе важнее: два списка могут дружно врать.
 */

const SRC = join(__dirname, "..", "src", "lib");
const brevo = readFileSync(join(SRC, "constitutionBrevo.ts"), "utf8");
const announce = readFileSync(join(SRC, "launchAnnounce.ts"), "utf8");

/*
 * 🔴 ЕСЛИ ЭТОТ СТОРОЖ ПОКРАСНЕЛ ПОСЛЕ МЕРЖА — НЕ ПРАВЬТЕ PLAN НИЖЕ.
 *
 * Замер 31.08.2026 по веткам, поле `plan` в письме подписчику:
 *
 *   deliver/all-work-2026-08-20          расхождений с планом 0
 *   deploy/launch-2026-08-30-chess       0
 *   deliver/silent-failures-2026-08-28   5   ← все пять старые
 *   merge/devhub-backlog-2026-08-27      5   ← все пять старые
 *
 * У последних двух стоит прежний набор: шахматы «30 августа» (дата уже
 * прошла), бюро и QRight «6 сентября», DevHub «13 сентября», мультичат
 * «20 сентября». План основателя от 30.08 — соответственно 30 сентября и
 * 10 сентября у остальных четырёх.
 *
 * Это ХУЖЕ обычного расхождения в коде: поле `plan` уходит В ПИСЬМО
 * подписчику. Победит их сторона при мерже — и люди получат письмо с датами,
 * одна из которых в прошлом.
 *
 * Правильная починка — взять НАШУ сторону constitutionBrevo.ts (и
 * launchAnnounce.ts). Подгонять PLAN под приехавшее нельзя: PLAN здесь и есть
 * решение основателя, а не наше удобство.
 */
/** Даты из плана основателя от 30.08.2026. Менять только вместе с планом. */
const PLAN: Record<string, string> = {
  cyberchess: "30 сентября",
  bureau: "10 сентября",
  qright: "10 сентября",
  devhub: "10 сентября",
  multichat: "10 сентября",
  // ⚠️ Дополнено 31.08.2026 до ПОЛНОГО плана основателя на 10 сентября.
  //
  // Прежний список знал ПЯТЬ модулей, а в плане их восемь. Расхождение вскрылось
  // так: в письмо добавили QSkyway, сторож покраснел — и оказалось, что красный
  // он не из-за новой строки, а из-за трёх СТАРЫХ пропусков. Подписчики QSign,
  // биржи стартапов и QVenture получили бы общее письмо в день выпуска своего
  // модуля.
  //
  // Урок для этого файла: неполный эталон опаснее отсутствующего. Пока список
  // знал пять модулей, он уверенно отвечал «расхождений нет» — про те пять.
  // Менять только вместе с планом основателя, и целиком, а не по одной строке.
  qskyway: "10 сентября",
  qsign: "10 сентября",
  startup: "10 сентября",
  qventure: "10 сентября",
};

function planDates(src: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const m of src.matchAll(/prefix: "([a-z]+)"[^}]*?plan: "([^"]+)"/g)) out[m[1]] = m[2];
  return out;
}

describe("даты запуска не расходятся между письмом, анонсом и планом основателя", () => {
  it("письмо подписчику называет даты из плана", () => {
    const got = planDates(brevo);
    // Контроль охвата: разбор обязан НАЙТИ все модули, иначе пустой результат
    // прошёл бы как «расхождений нет» — самый частый вид ложного зелёного.
    expect(
      Object.keys(got).sort(),
      "Набор модулей в письме разошёлся с планом. Это НЕ про даты: либо модуль " +
        "исчез из письма, либо появился новый. Пустой разбор дал бы «расхождений " +
        "нет» — самый частый вид ложного зелёного, поэтому охват проверяется " +
        "отдельно от значений.",
    ).toEqual(Object.keys(PLAN).sort());
    for (const [prefix, date] of Object.entries(PLAN)) {
      expect(
        got[prefix],
        `Модуль ${prefix}: письмо подписчику называет не ту дату. НЕ правьте ` +
          "PLAN под приехавшее — это решение основателя от 30.08, а не наше " +
          "удобство. Красный значит, что мерж привёз старый набор дат (две " +
          "ветки несут его, и шахматы там стоят «30 августа» — дата уже в " +
          "прошлом). Правильно: взять НАШУ сторону constitutionBrevo.ts. " +
          "Поле plan уходит В ПИСЬМО человеку, а не остаётся в коде.",
      ).toBe(date);
    }
  });

  it("реестр анонсов согласен с планом там, где дата у него задана", () => {
    // Между name и date может стоять ПОЯСНЕНИЕ — так и вышло при сведении с
    // продом 30.08. Прежний шаблон требовал их подряд и объявил, что дат нет
    // ни у одного модуля. Сторож не должен ломаться от комментария.
    // БЕЗ регулярки: между name и date может стоять пояснение (так и вышло при
    // сведении с продом 30.08), а шаблон, собранный из строки, дважды терял
    // экранирование и молча давал ноль. Разбираем по блокам вхождением.
    const dated: Array<[string, string, string]> = [];
    for (const chunk of announce.split(/^  ([a-z_]+): \{$/m)) {
      const d = chunk.indexOf('date: "');
      if (d < 0) continue;
      const v = chunk.slice(d + 7, chunk.indexOf('"', d + 7));
      const n = chunk.indexOf('name: "');
      const nm = n < 0 ? "" : chunk.slice(n + 7, chunk.indexOf('"', n + 7));
      dated.push(["", nm, v]);
    }
    expect(dated.length, "хотя бы у одного модуля дата должна быть задана").toBeGreaterThan(0);
    for (const m of dated) {
      const [, slug, date] = m;
      if (PLAN[slug]) {
        expect(
          date,
          `Модуль ${slug}: анонс называет не ту дату. Как и с письмом — ` +
            "правится анонс, а НЕ таблица PLAN. Разбор в шапке файла.",
        ).toBe(PLAN[slug]);
      }
    }
  });

  it("старая дата 30 августа не осталась ни в одном из двух списков", () => {
    for (const [name, src] of [["письмо", brevo], ["анонс", announce]] as const) {
      const inList = [...src.matchAll(/(?:plan|date): "30 августа"/g)];
      expect(
        inList.length,
        `${name}: вернулась дата «30 августа» — она в ПРОШЛОМ. Это признак ` +
          "того, что при мерже победила чужая сторона файла. Правильно: взять " +
          "нашу. Подгонять список под приехавшее нельзя — человек получит " +
          "письмо с прошедшей датой.",
      ).toBe(0);
    }
  });

  it("у заданной даты в анонсе названо ПРОИСХОЖДЕНИЕ, а не пустая строка", () => {
    // Поле dateSource завела прежняя сессия после того, как обнаружила у себя
    // круговое доказательство: даты ссылались на её же файлы того же дня.
    for (const m of announce.matchAll(/date: "([^"]+)",\s*dateSource: "([^"]*)"/g)) {
      expect(m[2].length, `дата ${m[1]} без указания источника`).toBeGreaterThan(10);
    }
  });
});

