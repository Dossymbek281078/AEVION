import { describe, expect, it } from "vitest";
import { localeForCheckout } from "../src/lib/payment/lemonSqueezyProvider";

/**
 * Язык страницы оплаты: наш код -> код кассы.
 *
 * 🔴 ЗАЧЕМ. Замер 09.09.2026, накануне запуска: страница оплаты открывалась
 * ПО-БОЛГАРСКИ, потому что мы не передавали язык вовсе. Починка добавляет поле,
 * и здесь опаснее не косметика, а ОТКАЗ: код, которого касса не знает, может
 * уронить создание оплаты целиком. Поэтому главная проверка ниже — не «русский
 * стал русским», а «ничего лишнего наружу не уходит».
 *
 * Списки языков у нас и у кассы РАЗНЫЕ: из 11 наших она принимает 8. Китайский
 * у неё есть, но называется иначе.
 */
describe("язык страницы оплаты не может сломать оплату", () => {
  it("наши языки, которые касса знает, доезжают как есть", () => {
    for (const код of ["ru", "en", "de", "es", "fr", "ja", "pt", "tr"]) {
      expect(localeForCheckout(код), `язык ${код}`).toBe(код);
    }
  });

  it("китайский переименовывается в тот код, который касса понимает", () => {
    // у нас файл называется zh, у кассы такого кода нет — есть zh-CN
    expect(localeForCheckout("zh")).toBe("zh-CN");
  });

  it("🔴 языки, которых у кассы НЕТ, не уходят наружу вовсе", () => {
    // казахский и арабский: передать их — риск отказа при создании оплаты
    expect(localeForCheckout("kk"), "казахский").toBeUndefined();
    expect(localeForCheckout("ar"), "арабский").toBeUndefined();
  });

  it("региональный код сводится к языку, а не отбрасывается", () => {
    expect(localeForCheckout("ru-RU")).toBe("ru");
    expect(localeForCheckout("EN-us")).toBe("en");
  });

  it("пустое и мусор дают «не передавать», а не подстановку", () => {
    // подставить английский молча было бы хуже: покупатель увидит навязанный
    // нами чужой язык вместо языка своего браузера
    for (const плохое of ["", "   ", "нет-такого", "javascript:alert(1)"]) {
      expect(localeForCheckout(плохое), JSON.stringify(плохое)).toBeUndefined();
    }
    expect(localeForCheckout(undefined)).toBeUndefined();
    expect(localeForCheckout(null)).toBeUndefined();
  });
});
