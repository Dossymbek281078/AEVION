import { describe, expect, test } from "vitest";
import { ТЕМА_ДОСКИ_ПО_УМОЛЧАНИЮ, yarkostCveta, ПОРОГ_ТЁМНОЙ_КЛЕТКИ, ПОРОГ_СВЕТЛОЙ_КЛЕТКИ } from "../page";

/*
 * 🔴 Доска по умолчанию не темнее привычной шахматной.
 *
 * ПОВОД — прямое слово основателя 09.10.2026, переданное оркестратором: «в
 * задачах слишком тёмная доска». Замер «до» на живом проде (вычисленный цвет
 * клеток, не из кода): светлая rgb(232,224,213), тёмная rgb(93,138,110) —
 * ОДИНАКОВО на задачах и в партии, на 390×844 и 1366×720, при светлой и тёмной
 * системной схеме. То есть дело было в самой палитре, а не в наложении на экране
 * задач; яркость тёмной клетки 121 против 145 у привычной.
 *
 * Порог отсчитывается от классической палитры (#f0d9b5 / #b58863) — её назвал
 * основатель как привычную. «Светлее» проверяется ЧИСЛОМ: вкусовое требование
 * иначе тихо откатится при следующей правке палитры.
 *
 * ⚠️ Чего эти проверки НЕ доказывают: что фигуры и подсветка ходов читаются на
 * новом фоне. Это видно только в кадре, и кадры «после» снимаются на проде.
 */

describe("палитра доски по умолчанию", () => {
  test("тёмная клетка НЕ темнее привычной шахматной", () => {
    const я = yarkostCveta(ТЕМА_ДОСКИ_ПО_УМОЛЧАНИЮ.dark);
    expect(я, `яркость тёмной клетки ${я.toFixed(1)}, порог ${ПОРОГ_ТЁМНОЙ_КЛЕТКИ.toFixed(1)}`)
      .toBeGreaterThanOrEqual(ПОРОГ_ТЁМНОЙ_КЛЕТКИ);
  });

  test("светлая клетка НЕ темнее привычной шахматной", () => {
    const я = yarkostCveta(ТЕМА_ДОСКИ_ПО_УМОЛЧАНИЮ.light);
    expect(я, `яркость светлой клетки ${я.toFixed(1)}, порог ${ПОРОГ_СВЕТЛОЙ_КЛЕТКИ.toFixed(1)}`)
      .toBeGreaterThanOrEqual(ПОРОГ_СВЕТЛОЙ_КЛЕТКИ);
  });

  test("🔴 КОНТРОЛЬ: прежний цвет порог НЕ проходит", () => {
    // Без этого обе проверки выше прошли бы и у порога, который пропускает всё, —
    // а именно прежняя тёмная клетка и была поводом жалобы.
    expect(yarkostCveta("#5d8a6e")).toBeLessThan(ПОРОГ_ТЁМНОЙ_КЛЕТКИ);
  });

  test("КОНТРОЛЬ прибора: яркость различает чёрное, серое и белое", () => {
    const [ч, с, б] = ["#000000", "#808080", "#ffffff"].map(yarkostCveta);
    expect([Math.round(ч), Math.round(с), Math.round(б)]).toEqual([0, 128, 255]);
    expect(ч < с && с < б).toBe(true);
  });

  test("клетки РАЗЛИЧИМЫ между собой — доска не стала однотонной", () => {
    // Осветление тёмной клетки не должно сблизить её со светлой: иначе поля
    // перестанут читаться, и «починка» окажется хуже жалобы.
    const раз = yarkostCveta(ТЕМА_ДОСКИ_ПО_УМОЛЧАНИЮ.light) - yarkostCveta(ТЕМА_ДОСКИ_ПО_УМОЛЧАНИЮ.dark);
    expect(раз, `разница яркостей ${раз.toFixed(1)}`).toBeGreaterThan(30);
  });
});
