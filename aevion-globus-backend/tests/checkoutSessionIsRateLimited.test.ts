import { describe, test, expect } from "vitest";
import express from "express";
import request from "supertest";

/**
 * Сторож: создание платёжной сессии ограничено по темпу.
 *
 * ЗАЧЕМ. Ручка анонимная и на каждый вызов ходит во ВНЕШНЮЮ кассу. До
 * 02.09.2026 предела не было ни в модуле (0 ограничителей), ни на роутере
 * (нет .use), ни глобально (в index.ts до маршрутов только bodyLimitByPath) —
 * то есть темп обращений к платёжному провайдеру задавал вызывающий.
 *
 * Проверяется не «есть ли строка rateLimit в файле», а СПОСОБНОСТЬ отказать:
 * поток запросов должен упереться в 429.
 */
const { checkoutRouter } = await import("../src/routes/checkout");

function приложение() {
  const a = express();
  a.use(express.json());
  a.use("/api/pricing/checkout", checkoutRouter);
  return a;
}

async function попытка(app: express.Express) {
  return request(app)
    .post("/api/pricing/checkout/session")
    // Тариф заведомо неверный: нас интересует ТЕМП, а не оформление покупки.
    // Обработчик ответит 400 — и это нормально: предел должен срабатывать
    // раньше, чем разбирается тело.
    .send({ tier: "nonsense", period: "monthly" });
}

describe("темп создания платёжных сессий ограничен", () => {
  // ПОРЯДОК ВАЖЕН: предел общий на весь файл (ключ — адрес клиента), поэтому
  // контроль обязан идти ПЕРВЫМ. Иначе он получит 429, оставшийся от теста
  // выше, и покрасит исправный код.
  test("КОНТРОЛЬ: первые запросы проходят, предел не бьёт сразу", async () => {
    // Без этого «есть 429» удовлетворялся бы кодом, который отказывает
    // ВСЕГДА, — то есть сломанной кассой.
    const app = приложение();
    const первый = await попытка(app);
    expect(первый.status, "первый же запрос отбит — это не предел, это поломка").not.toBe(429);
  });
  test("поток запросов упирается в 429", async () => {
    const app = приложение();
    const коды: number[] = [];
    for (let i = 0; i < 45; i += 1) {
      const r = await попытка(app);
      коды.push(r.status);
      if (r.status === 429) break;
    }
    expect(
      коды,
      "45 запросов подряд прошли без единого отказа — предела нет, темп обращений к платёжному провайдеру задаёт вызывающий"
    ).toContain(429);
  });

});
