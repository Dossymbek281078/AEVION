/**
 * У подписи движка ТРИ исхода, а не два.
 *
 * ПОВОД 29.09.2026. Соседнее окно увидело на 1280×768 «Движок: не запустился»,
 * а на 1440×900 «Stockfish 18 · d22» и предположило дефект узкого экрана.
 * Ширина ни при чём: запуск привязан к состоянию игры и вкладке, ширины в
 * условии нет вовсе. Настоящая причина — окно ожидания: опрос готовности идёт
 * 15 секунд, и всё это время признак ложен, а подпись уже утверждала отказ.
 *
 * Это правило §14 «три исхода, а не два»: нет данных — так и скажи. Разница
 * не косметическая: «не запустился» человек читает как поломку продукта и
 * уходит, «загружается» — как ожидание.
 */

import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { bezKommentariev } from "./bezKommentariev";

const КОД = bezKommentariev(readFileSync(join(__dirname, "..", "page.tsx"), "utf8"));

describe("подпись движка", () => {
  it("различает «готов», «загружается» и «не запустился»", () => {
    expect(КОД).toContain('sfOk?"Stockfish 18 · d22":sfZapusk?"загружается…":"не запустился');
  });

  it("признак загрузки поднимается при запуске", () => {
    expect(КОД).toContain("sSfZapusk(true)");
  });

  it("🔴 и ГАСНЕТ по истечении окна ожидания", () => {
    // Иначе «загружается…» осталось бы навсегда, и отказ стал бы невидим —
    // это хуже прежнего вранья, а не лучше.
    expect(КОД).toContain("sSfZapusk(false)");
  });

  it("контроль: сам запуск по-прежнему привязан к игре и вкладкам, а не к ширине", () => {
    expect(КОД).toContain('if(on||tab==="analysis"||tab==="coach")ensureSF();');
  });
});
