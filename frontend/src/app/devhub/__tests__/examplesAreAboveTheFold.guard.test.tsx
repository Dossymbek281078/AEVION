/**
 * Примеры «в один тап» стоят ВЫШЕ блока цены — то есть в первом экране телефона.
 *
 * 🔴 ЗАМЕР 07.10.2026, прод ffa6cbcaddd6, iframe 390×844 и 1366×720 на живом сайте:
 *   поле ввода           y=340, видно целиком, достижимо (elementFromPoint)
 *   кнопка «Построить»    y=416, достижима, включается при наборе
 *   подпись «Или начните с примера»  y=832 — у самого края
 *   три примера          y=859 / 916 / 972 — ЗА экраном (высота 844)
 * На 1366×720 те же примеры видны (527–595). То есть на столе путь «начать БЕЗ
 * НАБОРА» существовал, а на телефоне его не было видно без прокрутки.
 *
 * Почему это денежный вопрос, а не вкусовщина: за сутки youtube→/devhub дал
 * 15 живых сессий, 2 с чтением и НОЛЬ попыток — при 6 из 6 у шахмат на том же
 * канале. Поле и кнопка при этом были в первом экране и достижимы, то есть
 * мешал не доступ к полю, а отсутствие видимого способа начать без печатания.
 * Нажатие примера заполняет поле (54 знака) и включает кнопку — проверено.
 *
 * ⚠️ ЧТО ЭТОТ СТОРОЖ МОЖЕТ И ЧЕГО НЕ МОЖЕТ, честно — та же граница, что у
 * priceIsInTheFirstScreen по соседству. Он проверяет ПОРЯДОК в отрисованном
 * документе: примеры раньше цены и раньше выбора режима. В вертикальном потоке
 * порядок документа и есть порядок на экране, но доказательством ВИДИМОСТИ это
 * не является: пиксели мерятся браузером при конкретных размерах, и такой замер
 * идёт отдельно, после выкатки. Путать два утверждения нельзя.
 */
import { describe, test, expect, vi } from "vitest";
import { render, act } from "@testing-library/react";

vi.mock("next/navigation", () => ({
  useRouter: () => ({ push: vi.fn(), replace: vi.fn() }),
  useSearchParams: () => new URLSearchParams(),
  usePathname: () => "/devhub",
}));
vi.mock("@/lib/apiBase", () => ({
  // Подменяем ВСЕ вывозы модуля: vitest требует полной подмены, и первая
  // редакция упала на отсутствующем getApiBase — «Tests no tests», то есть
  // ошибка подмены, а не отсутствие проверок.
  apiUrl: (p: string) => p,
  getApiBase: () => "",
  getClientApiBase: () => "",
  getBackendOrigin: () => "",
  serverFetch: (input: RequestInfo | URL, init?: RequestInit) => globalThis.fetch(input, init),
  fetchWithRedeployRetry: (input: RequestInfo | URL, init?: RequestInit) =>
    globalThis.fetch(input, init),
}));
vi.mock("@/components/Wave1Nav", () => ({ Wave1Nav: () => null }));
vi.mock("@monaco-editor/react", () => ({ default: () => null }));

import DevHubPage from "../page";
import { I18nProvider } from "@/lib/i18n";
import { tDevhub } from "../i18n";

const РАНЬШЕ = Node.DOCUMENT_POSITION_FOLLOWING;

/* Пример ищем НА ЛЮБОМ из трёх языков: обёртка словаря в проверке поднимается
   со своим умолчанием, и первая редакция искала только русский текст — получила
   «кнопка-пример не отрисована» на исправной странице. Язык здесь не предмет
   проверки, предмет — порядок блоков. */
const ТЕКСТЫ_ПРИМЕРА = ["ru", "en", "kk"].map((l) => tDevhub(l, "hero.ex1"));
function найтиПример(c: HTMLElement): HTMLButtonElement | undefined {
  return [...c.querySelectorAll("button")].find((b) =>
    ТЕКСТЫ_ПРИМЕРА.some((t) => t && (b.textContent || "").includes(t)),
  ) as HTMLButtonElement | undefined;
}

async function отрисовать() {
  globalThis.fetch = vi.fn(async () =>
    ({ ok: true, status: 200, json: async () => ({}), text: async () => "{}" }) as never);
  // Страница читает словарь через useI18n — без обёртки падает «must be used
  // within I18nProvider». Так же обёрнуты соседние тесты страниц.
  const r = render(<I18nProvider><DevHubPage /></I18nProvider>);
  // Один тик, чтобы прошли эффекты монтирования: без него чипы ещё не в дереве.
  await act(async () => { await Promise.resolve(); });
  return r.container;
}

describe("примеры в один тап — выше цены и выбора режима", () => {
  test("все три опоры найдены в отрисованном дереве", async () => {
    const c = await отрисовать();
    // Знаменатель: без этой проверки отсутствие любой опоры дало бы зелёное
    // «порядок верен» на пустом дереве.
    expect(c.querySelector("textarea"), "поле ввода не отрисовано").toBeTruthy();
    expect(c.querySelector("[data-devhub-price]"), "блок цены не отрисован").toBeTruthy();
    const пример = найтиПример(c);
    expect(пример, "кнопка-пример не отрисована").toBeTruthy();
  });

  test("пример стоит РАНЬШЕ подзаголовка — то есть поднят из-под сгиба", async () => {
    /*
     * 🔴 УТВЕРЖДЕНИЕ ПЕРЕПИСАНО ПО СМЫСЛУ в ходе работы. Сперва я требовал
     * «примеры раньше ЦЕНЫ» — но это было моим выбором места, а не требованием:
     * сторож приёмки priceIsInTheFirstScreen считает первый экран префиксом
     * ИСХОДНИКА, и вставка перед ценой выбила бы цену из его окна. Правильный
     * признак подъёма — примеры стоят раньше ПОДЗАГОЛОВКА и выбора режима, под
     * которыми они и лежали (замер: подзаголовок около y=800, примеры y=859).
     */
    const c = await отрисовать();
    const пример = найтиПример(c)!;
    const подзаголовок = [...c.querySelectorAll("div")].find((d) =>
      ["ru", "en", "kk"].some((l) => {
        const t = tDevhub(l, "hero.subtitle");
        return t && (d.textContent || "").trim() === t.trim();
      }));
    expect(подзаголовок, "подзаголовок не найден — сравнивать не с чем").toBeTruthy();
    expect(
      Boolean(пример.compareDocumentPosition(подзаголовок!) & РАНЬШЕ),
      "примеры ниже подзаголовка — значит они остались под сгибом (замер: y=859 при высоте 844)",
    ).toBe(true);
    /*
     * КОНТРОЛЬ НАПРАВЛЕНИЯ вместо мутации переносом блока: перенос 25 строк JSX
     * скриптом я пробовал — сломал разметку («Tests no tests», ошибка РАЗБОРА), и
     * такая мутация ничего не доказывает. Обратное утверждение надёжнее: поменяй
     * блоки местами — первая проверка станет ложной, а эта истинной.
     */
    expect(
      Boolean(подзаголовок!.compareDocumentPosition(пример) & РАНЬШЕ),
      "подзаголовок оказался выше примеров — порядок обратный проверяемому",
    ).toBe(false);
  });

  test("пример стоит РАНЬШЕ поля ввода? нет — сразу ПОСЛЕ него", async () => {
    /*
     * Порядок именно такой: поле → кнопка → примеры. Поставить примеры ПЕРЕД
     * полем значило бы предложить выбор до того, как человек увидел, куда писать.
     */
    const c = await отрисовать();
    const поле = c.querySelector("textarea")!;
    const пример = найтиПример(c)!;
    expect(Boolean(поле.compareDocumentPosition(пример) & РАНЬШЕ), "примеры оказались выше поля").toBe(true);
  });

  test("пример заполняет поле, а не просто подсвечивается", async () => {
    // Иначе «путь без набора» был бы украшением: кнопка есть, а начать нельзя.
    const c = await отрисовать();
    const поле = c.querySelector("textarea") as HTMLTextAreaElement;
    const пример = найтиПример(c)!;
    expect(поле.value, "поле изначально должно быть пустым").toBe("");
    await act(async () => { пример.click(); });
    expect(поле.value.length, "нажатие примера не заполнило поле").toBeGreaterThan(10);
  });
});
