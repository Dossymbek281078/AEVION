import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Матрица сравнения — русская, а страницы, где она стоит, объявлены английскими.
 *
 * Замер 27.08.2026 на живой `/qskyway`: документ отдаётся с `lang="en"`, шапка и
 * описание английские, а матрица даёт 53 строки кириллицы против 32 латинских.
 * Данные в `lib/competitors.ts` русские ПО ПОСТРОЕНИЮ: языковых ключей в них
 * ноль, компонент в словарь не ходит.
 *
 * Перевод — это контент и позиционирование, решение основателя. Но пока его нет,
 * блок обязан быть помечен своим настоящим языком: иначе браузер считает его
 * английским и предлагает машинно перевести ВСЮ страницу, ломая и английскую
 * половину.
 *
 * Сторож снимется сам, когда перевод появится: третий тест следит за тем,
 * остались ли данные одноязычными.
 */

const SRC = join(__dirname, "..", "..");

describe("матрица сравнения: язык блока назван честно", () => {
  test("корневой элемент помечен lang", () => {
    const s = readFileSync(join(SRC, "components", "CompetitorMatrix.tsx"), "utf8");
    expect(
      /<section\s+lang="ru"/.test(s),
      "матрица русская, но не помечена lang — браузер сочтёт её английской",
    ).toBe(true);
  });

  test("данные действительно одноязычные — иначе метка была бы ложью", () => {
    // Отрицательный контроль к первому тесту. Если бы данные уже были
    // многоязычными, жёсткий lang="ru" стал бы новым враньём, а не починкой.
    const s = readFileSync(join(SRC, "lib", "competitors.ts"), "utf8");
    const hasLangKeys = /(^|\s)(ru|en|kk)\s*:/m.test(s);
    expect(
      hasLangKeys,
      "в данных появились языковые ключи — снимите жёсткий lang и берите язык из словаря",
    ).toBe(false);
  });

  test("в данных действительно есть кириллица — прибор не пустой", () => {
    // Без этого первые два теста были бы зелёными и на пустом файле.
    const s = readFileSync(join(SRC, "lib", "competitors.ts"), "utf8");
    const cyr = (s.match(/[Ѐ-ӿ]/g) ?? []).length;
    expect(cyr).toBeGreaterThan(200);
  });
});
