// AEVION — сравнение модуля с аналогами, устроенное так, чтобы им нельзя было
// соврать.
//
// Таблица «мы против них» — самый лёгкий способ незаметно перейти от фактов к
// маркетингу: своя колонка пишется по памяти, чужая — по впечатлению, и обе
// выглядят одинаково убедительно. Поэтому здесь у КАЖДОЙ ячейки обязателен
// источник, и интерфейс показывает его рядом со значением:
//
//   measured   — наше число из фактического прогона; `href` ведёт на живую ручку,
//                которой это число можно перепроверить прямо сейчас;
//   public     — бесспорный публичный факт: чем компания является, что говорит
//                регламент. Не свойства продукта и не сравнительные оценки;
//   unverified — заявление, которое мы НЕ проверяли. Рисуется приглушённо и с
//                оговоркой; в демо такое не должно читаться как факт.
//
// Правило, из-за которого таблица остаётся честной: про СЕБЯ мы утверждаем
// сколько угодно конкретно, потому что можем показать прогон. Про чужой продукт
// утверждаем только то, что он публично о себе говорит, и НИКОГДА не заявляем
// отсутствие функции у конкурента — отсутствие невозможно проверить, а ошибка в
// эту сторону дороже всего стоит доверию.

export type ClaimSource = "measured" | "public" | "unverified";

export interface Claim {
  text: string;
  source: ClaimSource;
  /** живая ручка или публичный документ, которым значение перепроверяется */
  href?: string;
}

/** Кто сильнее по этой оси. `different` — когда сравнивать некорректно. */
export type Verdict = "ours" | "theirs" | "different";

export interface CompareRow {
  axis: string;
  ours: Claim;
  theirs: Claim;
  verdict: Verdict;
  /** одна фраза: почему именно так, а не «мы лучше» */
  why?: string;
}

export interface Peer {
  name: string;
  /** чем является — категория, а не оценка */
  kind: string;
}

export interface CompetitorSet {
  moduleId: string;
  title: string;
  /** С кем сравниваем и кто они. Категории публичные и бесспорные. */
  peers: Peer[];
  rows: CompareRow[];
  /**
   * Где мы объективно слабее. Это не раздел вежливости: слабости
   * формулируются про НАС, поэтому их можно утверждать точно, и именно они
   * делают остальную таблицу проверяемой, а не рекламной.
   */
  weaknesses: string[];
  /** Что ещё предстоит заземлить источниками, если чего-то не хватает. */
  todo?: string[];
}

