/**
 * Исходник БЕЗ комментариев — для сторожей, которые читают код глазами грепа.
 *
 * ЗАЧЕМ ОБЩИЙ ДОМ. За один день 28.09.2026 я наступил на одну и ту же ловушку
 * ТРИЖДЫ: писал рядом с правкой комментарий, объясняющий механизм, а сторож
 * искал название этого механизма в исходнике — и находил его в моём же
 * объяснении. Убери рабочую строку, оставь рассказ о ней — проверка остаётся
 * зелёной. Текст О вещи неотличим от вещи, если смотреть грепом.
 *
 * Каждый раз это ловила мутация, и каждый раз я чинил один сторож, а через час
 * писал следующий с тем же дефектом. Помнить правило в момент написания теста
 * не получается — поэтому механизм, а не правило.
 *
 * Границы намеренные и простые: снимаются блочные комментарии и строки,
 * начинающиеся с `//`. Строковый литерал, внутри которого стоит `/*`, эта
 * функция тоже посчитает началом комментария — для проверок исходника такая
 * точность избыточна, а разбор настоящим парсером стоил бы дороже задачи.
 */
export function безКомментариев(код: string): string {
  const части = код.split("/*");
  const безБлочных = части
    .map((часть, i) => (i === 0 ? часть : часть.slice(часть.indexOf("*/") + 2)))
    .join("");
  return безБлочных
    .split(String.fromCharCode(10))
    .filter((строка) => !строка.trim().startsWith("//"))
    .join(String.fromCharCode(10));
}
