import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Личность посетителя ставится ГЛОБАЛЬНО, а не только под /devhub.
 *
 * Подмена запросов, которая добавляет заголовок гостя, жила в макете модуля.
 * Замер 29.08.2026: API модуля зовут из браузера ещё три страницы вне его —
 * /studio, /acquire и /compare, — и оттуда заголовок не уходил. Человек видел
 * тариф и расход общей «анонимной» личности вместо своих, а медиа-ручки
 * списывали общую норму. Хуже всего это на /studio: там продают Studio Pro.
 *
 * Ставить глобально безопасно: подмена проверяет адрес и трогает только
 * запросы к /api/devhub/.
 */
const ROOT = path.resolve(__dirname, "..", "..", "layout.tsx");
const SRC = fs.readFileSync(ROOT, "utf8");

describe("личность посетителя доступна всем страницам", () => {
  it("прибор исправен: корневой макет прочитан", () => {
    expect(SRC.length, "корневой макет не прочитался").toBeGreaterThan(500);
    expect(SRC).toContain("<body");
  });

  it("корневой макет ставит личность DevHub", () => {
    expect(
      SRC,
      "личность ставится не глобально: страницы вне /devhub будут ходить в API модуля без заголовка гостя",
    ).toContain("<DevHubGuestIdentity />");

    // И ВНУТРИ body, а не рядом с ним. Первая версия правки поставила
    // компонент соседом <body> — то есть дочерним элементом <html>, где
    // React его не отрисует. Проверка «строка есть в файле» такую починку
    // пропускает: строка-то есть, а толку ноль.
    expect(
      SRC.indexOf("<DevHubGuestIdentity />") > SRC.indexOf("<body"),
      "компонент стоит вне <body> — он не отрисуется и заголовок не появится",
    ).toBe(true);
  });
});
