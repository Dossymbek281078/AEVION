import { getApiBase } from "@/lib/apiBase";

/**
 * Жив ли контур на боевом сервере. Для посадочных страниц запуска.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Функция появилась в двух посадочных сразу
 * (`/multichat-engine/launch`, `/devhub/launch`) двумя копиями, и третья
 * страница запуска породила бы третью. Одна копия расходится с другой на первом
 * же уточнении — например, если понадобится другой срок кэша.
 *
 * ПОЧЕМУ «НЕ 404», А НЕ `r.ok`. Посадочные бюро и шахмат считают контур живым по
 * `r.ok`, и для их ручек это верно. Но у модулей, которые я проверял, осмысленные
 * ответы как раз не 2xx:
 *
 *   POST /api/multichat/receipt/verify с неверным пакетом → 400 (поля проверены)
 *   GET  /api/multichat/conversations без токена          → 402 (платная стена)
 *
 * По `r.ok` оба выглядели бы мёртвыми, и страница написала бы «проверяется» о
 * работающем модуле. 404 же отвечает и на несуществующий путь внутри живого
 * роутера, и на отсутствующий роутер — то есть именно он означает «этого нет».
 *
 * Приём взят из scripts/contact-channels-smoke.mjs: там ручку приёма обращений
 * проверяют ЗАВЕДОМО НЕВЕРНЫМ пакетом и ждут 400, чтобы проверка не оставляла на
 * проде ни одной настоящей записи. Тот же расчёт здесь: пробы идут при сборке,
 * и ни одна из них ничего не создаёт.
 *
 * Сетевая ошибка — это «не подтвердилось», а не «мертво»: страница честно скажет
 * «проверяется», и это лучше, чем объявить контур сломанным из-за таймаута
 * сборки.
 */
export interface ProbeOptions {
  /**
   * Считать 404 признаком ЖИЗНИ, а не смерти.
   *
   * Нужно для ручек, которые ищут объект по идентификатору: у них 404 —
   * законный и правильный ответ на «такого нет». Замер 19.08.2026:
   * `GET /api/multichat/shared/launch-page-probe` отвечает
   * `{"error":"not_found_or_revoked"}` с кодом 404, потому что токена с таким
   * именем не существует — и не должно существовать, проба его не создаёт.
   *
   * По умолчанию проба считала это смертью, и метка «Совет можно открыть
   * ссылкой» на посадочной Multichat не могла стать «работает» НИКОГДА,
   * сколько бы контур ни работал.
   *
   * Отличить «нет объекта» от «нет роутера» по коду здесь нельзя, и вот
   * почему: несуществующий путь внутри multichat отвечает не 404, а **402**
   * `upgrade_required` — платная стена срабатывает раньше маршрутизации.
   * Значит для таких проб единственный честный критерий — «сервер вообще
   * ответил», и он ниже.
   */
  aliveOn404?: boolean;
}

export async function probeLive(
  path: string,
  init?: RequestInit,
  opts?: ProbeOptions,
): Promise<boolean> {
  try {
    const r = await fetch(`${getApiBase()}${path}`, { ...init, next: { revalidate: 1800 } });
    if (opts?.aliveOn404) return true; // сервер ответил — контур на месте
    return r.status !== 404;
  } catch {
    return false;
  }
}

/**
 * Сколько дней осталось до даты запуска.
 *
 * Считается по UTC-полуночи с обеих сторон: иначе страница, собранная вечером,
 * и страница, собранная утром того же дня, показали бы разное число дней.
 * Даты запуска модулей — в scripts/launch-readiness.mjs, там же они и решаются.
 */
export function daysUntil(year: number, monthIndex: number, day: number): number {
  const launch = Date.UTC(year, monthIndex, day);
  const now = new Date();
  const today = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());
  return Math.round((launch - today) / 86_400_000);
}
