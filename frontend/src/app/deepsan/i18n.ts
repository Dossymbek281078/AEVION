const DICT: Partial<Record<string, Record<Key, string>>> = { en: EN, ru: RU, kk: KK };

/** Перевод по ключу. Нет языка — английский; нет ключа — тоже английский. */
export function tDeepsan(lang: string, key: Key, vars?: Record<string, string | number>): string {
  let s = DICT[lang]?.[key] ?? EN[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export const DEEPSAN_KEYS = Object.keys(EN) as Key[];
export const DEEPSAN_DICT = DICT;

export function useDeepsanT() {
  const { lang } = useI18n();
  return useCallback((key: Key, vars?: Record<string, string | number>) => tDeepsan(lang, key, vars), [lang]);
}
