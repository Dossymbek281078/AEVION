import { describe, expect, it, test } from "vitest";
import { allTranslations } from "../__tests__/localeSource";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * Сообщение об ошибке QSkyway говорило посетителю: «Проверь, что бэкенд поднят
 * (/api/qskyway/city)». Человек, зашедший на публичную страницу, поднять
 * бэкенд не может — такой текст лишь сообщает ему, что о нём не думали.
 *
 * Найдено 28.08.2026 чтением страницы глазами новичка, а не проверкой
 * правильности: сообщение было ВЕРНЫМ по смыслу и переведённым на три языка.
 *
 * ⚠️ Граница: сторож смотрит ТОЛЬКО ключи `qskyway.err.*`, то есть тексты
 * отказов. Технические слова в подсказках и раскрытиях модуля он не трогает
 * НАМЕРЕННО: «слоты живут в памяти процесса и теряются при перезапуске» — это
 * честное раскрытие ограничения демо, и запрещать его значило бы поощрять
 * умолчание. Аудитория модуля — инженеры и регуляторы, им техническое слово в
 * подсказке уместно. Недопустимо оно там, где человек ждёт, что ему скажут,
 * ЧТО ДЕЛАТЬ.
 */

// Слова, которые в тексте ОТКАЗА означают «сделай работу разработчика».
// Дополнено 02.09.2026: «смоук» — тоже наше слово, а не человеческое. Нашлось
// не сторожем, а ЧТЕНИЕМ всех 139 строк модуля подряд: список литеральный и
// знает ровно те слова, которые в него внесли. Это его честная граница —
// расширять его стоит после каждого чтения, а не вместо чтения.
const DEV_ONLY = ["бэкенд", "backend", "localhost", ":4001", "npm ", "docker", "консол",
  "смоук", "smoke run", "smoke-"];

describe("тексты отказов QSkyway обращены к посетителю", () => {
  const T = allTranslations();

  it("контроль прибора: словари прочитаны и ключи отказов в них есть", () => {
    // Иначе «запрещённых слов нет» верно и для пустого словаря.
    expect(Object.keys(T).length).toBeGreaterThan(2);
    const moduleKeys = Object.keys(T.ru || {}).filter((k) => k.startsWith("qskyway."));
    expect(moduleKeys.length, "ключей модуля нет — проверять нечего").toBeGreaterThan(0);
  });

  for (const lang of ["en", "ru", "kk"]) {
    it(`${lang}: отказ не просит человека чинить инфраструктуру`, () => {
      const table = (T[lang] || {}) as Record<string, string>;
      const bad: string[] = [];
      for (const [k, v] of Object.entries(table)) {
        // ОХВАТ РАСШИРЕН 02.09.2026 с `qskyway.err.*` на ВСЕ ключи модуля.
        //
        // ПОВОД. Слово «бэкенд» стояло в четырёх строках, и сторож молчал: они
        // лежат под `tel.*`, `just.*`, `slots.*` и `tip.*`, а он смотрел только
        // `err.*`. При этом «Бэкенд не ответил» — сообщение об отказе по
        // существу, просто ключ ему дали по МЕСТУ показа, а не по смыслу.
        //
        // Класс общий: охват, заданный префиксом ключа, отстаёт от смысла,
        // потому что ключи именуют по месту в интерфейсе.
        //
        // ⚠️ И отдельно: расширять надо ЗДЕСЬ. Строкой выше есть похожий
        // фильтр для контроля охвата — я сперва поправил его, мутация не
        // поймалась, и полчаса ушло бы на догадки. Отбор, решающий дело,
        // стоит внутри цикла.
        if (!k.startsWith("qskyway.")) continue;
        const low = String(v).toLowerCase();
        for (const w of DEV_ONLY) {
          if (low.includes(w)) { bad.push(k + ": " + String(v).slice(0, 60)); break; }
        }
      }
      expect(
        bad,
        "в тексте отказа стоит инструкция разработчику. Посетитель не может её "
          + "выполнить: скажите, что делать ЕМУ (обновить страницу, зайти позже), "
          + "а техническую подробность положите в подсказку или журнал.",
      ).toEqual([]);
    });
  }

  it("текст исключения не приклеивается к сообщению на экране", () => {
    // Дыра, которую этот сторож сперва не видел. Словарь был чист, а в месте
    // вызова стояло `setBooking(t("qskyway.err.network") + String(e))` — и
    // человек получал «Ошибка сети: TypeError: Failed to fetch».
    //
    // Проверять надо ОБА места: текст в словаре и то, что к нему приклеили.
    const src = readFileSync(path.join(__dirname, "_client.tsx"), "utf8");
    const bad: string[] = [];
    for (const line of src.split(String.fromCharCode(10))) {
      const t = line.trim();
      if (t.startsWith("//") || t.startsWith("*")) continue;
      // сеттер состояния, показываемого человеку, склеенный со String(e)
      // Ищем именно СКЛЕЙКУ перевода с текстом исключения — это и есть форма
      // дефекта. Просто сохранить исключение в состояние законно: у загрузки
      // города оно лежит в `err` и показывается ТОЛЬКО в подсказке, а на экран
      // идёт переведённая фраза. Сторож, запрещающий и это, гонит автора к
      // худшему решению — вообще не сохранять диагностику.
      if (!t.includes("String(e)") && !t.includes("String(err)")) continue;
      if (!t.includes('t("')) continue;
      if (t.includes("console.")) continue;
      bad.push(t.slice(0, 90));
    }
    expect(
      bad,
      "текст исключения уходит на экран. Человеку он ничего не говорит: положите "
        + "его в console.warn или в подсказку, а на экран — что делать ЕМУ.",
    ).toEqual([]);
  });

  test("причина отказа различается, а не подставляется", () => {
    // 28.08.2026: после починки «сырое исключение на экран» я стал показывать
    // ЛЮБУЮ ошибку как «ошибка сети». Но `fetch` бросает TypeError только когда
    // запрос НЕ УШЁЛ; разбор ответа падает иначе, и тогда запрос ушёл — человек
    // шёл бы проверять вайфай вместо того, чтобы просто повторить.
    //
    // В тот же день тот же класс нашёлся в машинном инструменте: один catch
    // подписал пять разных ошибок одной причиной и дал пять ложных находок.
    const src = readFileSync(path.join(__dirname, "_client.tsx"), "utf8");
    expect(src.includes("e instanceof TypeError"), "причина больше не различается").toBe(true);
    // Обе ветки обязаны вести к РАЗНЫМ ключам: одна ветка на два ключа — это
    // распознавание, которое ничего не меняет.
    expect(src.includes('"qskyway.err.network"'), "ключ про сеть исчез").toBe(true);
    expect(src.includes('"qskyway.err.unexpected"'), "ключ про непредвиденное исчез").toBe(true);
    // И настоящая причина обязана оставаться в журнале: человеку — короткий
    // текст, разработчику — исключение целиком.
    expect(src.includes('console.warn("[qskyway] бронь не прошла:"'), "исключение перестало попадать в журнал").toBe(true);
  });
});
