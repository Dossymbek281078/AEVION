import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { buildPlatformWaitlistEmail, модульОткрыт, модулиБезДняОткрытия } from "../src/lib/constitutionBrevo";

/**
 * «Модуль открыт» решается в ОДНОМ месте — `модульОткрыт`.
 *
 * До 30.09.2026 ответ складывался в двух местах независимо: письмо смотрело,
 * есть ли запись в `LIVE_ENTRIES`, а `planPhrase` — есть ли отметка `openedAt`.
 * Они не обязаны расходиться, но ничто не мешало, и один раз уже разошлись: у
 * cyberchess отметки нет, а письмо он шлёт как открытый. На этом споткнулась
 * проверка, выбиравшая «неоткрытый модуль» по отметке.
 *
 * Сторож держит две стороны: поведение (что говорит письмо) обязано совпадать
 * с ответом единого источника, и второго места, где этот ответ вычисляют, в
 * файле быть не должно.
 */
const ИСТОЧНИК = join(__dirname, "..", "src", "lib", "constitutionBrevo.ts");
const ЖДЁМ_RU = "как только откроем";
const ЖДЁМ_EN = "we will write the moment it opens";

function тело(источник: string): string {
  const письмо = buildPlatformWaitlistEmail("probe@aevion.app", источник) as unknown as {
    htmlContent?: string; textContent?: string;
  };
  return `${письмо.htmlContent ?? ""}\n${письмо.textContent ?? ""}`;
}

describe("один источник ответа «модуль открыт»", () => {
  const ПРОВЕРЯЕМ = ["cyberchess", "devhub", "multichat", "qright", "qventure", "bureau", "qsign", "startup", "qskyway"];

  it("письмо говорит ровно то, что отвечает единый источник", () => {
    const расхождения: string[] = [];
    for (const модуль of ПРОВЕРЯЕМ) {
      const т = тело(модуль);
      expect(т.length, `${модуль}: письмо прочитано пустым — проверка слепа`).toBeGreaterThan(50);
      const ждёт = т.includes(ЖДЁМ_RU) || т.includes(ЖДЁМ_EN);
      if (модульОткрыт(модуль) === ждёт) {
        расхождения.push(`${модуль}: источник говорит открыт=${модульОткрыт(модуль)}, письмо ${ждёт ? "ждёт открытия" : "зовёт внутрь"}`);
      }
    }
    expect(расхождения, "письмо и единый источник разошлись").toEqual([]);
  });

  it("КОНТРОЛЬ: среди проверяемых есть и открытые, и ещё нет — иначе проверка пуста", () => {
    const открытых = ПРОВЕРЯЕМ.filter((м) => модульОткрыт(м)).length;
    expect(открытых, "ни один модуль не считается открытым — сравнивать не с чем").toBeGreaterThan(0);
    expect(открытых, "открыты ВСЕ — вторая сторона проверки ничего не ловит").toBeLessThan(ПРОВЕРЯЕМ.length);
  });

  it("список «ещё не открытых» согласован с единым источником", () => {
    for (const м of модулиБезДняОткрытия()) {
      expect(модульОткрыт(м.prefix), `${м.prefix} в списке неоткрытых, а источник считает его открытым`).toBe(false);
    }
  });

  it("второго места, где вычисляют открытость, в файле нет", () => {
    /*
     * Структурная половина. Смотрим на ЧТЕНИЕ полей `openedAt` и `liveFrom`:
     * их разрешено читать только там, где ответ и формируется. Появится второй
     * читатель — значит завелось второе мнение, и рано или поздно они разойдутся.
     *
     * Считаем обращения вида `.openedAt` и `.liveFrom` (чтение поля), а не само
     * слово: объявление в таблице и присваивания в записях не в счёт.
     */
    const код = readFileSync(ИСТОЧНИК, "utf8")
      .split("\n")
      // Комментарии выбрасываем: текст О вещи неотличим от самой вещи, а этот
      // файл объясняет словами, где поля живут. Без отбрасывания сторож считал
      // бы собственные объяснения нарушениями.
      .filter((строка) => !/^\s*(\*|\/\/|\/\*)/.test(строка))
      .join("\n");
    const читатели = (код.match(/\.(openedAt|liveFrom)\b/g) ?? []).length;
    expect(
      читатели,
      "поля открытости читают больше чем в одном месте: ответ «открыт ли модуль» " +
        "снова вычисляется дважды. Читайте `модульОткрыт`, а не поля напрямую",
      // Порог 3: два чтения внутри `модульОткрыт` и одно в `liveEntryFromSource`,
      // которую он же и зовёт. Четвёртое чтение — это новое мнение.
    ).toBeLessThanOrEqual(3);
    expect(читатели, "чтений не найдено вовсе — проверка смотрит не туда").toBeGreaterThan(0);
  });
});
