import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Книга «Gratitude ∞ Forever Young» и страница долголетия — одно направление
 * (бренд ForeverYoung, тема антиэйджа). Замер 29.08.2026: книга продавалась,
 * а страница не упоминала её ни разу, и своей страницы у книги нет вовсе.
 *
 * Сторож охраняет ровно два свойства, а не вёрстку:
 *  1) страница ведёт в кассу книги через позицию каталога;
 *  2) цена книги не написана прозой (её называет чекаут).
 *
 * Проверено мутацией: убрать блок BOOK — краснеет; вписать «$29.99» в
 * текст — краснеет. Границу знать полезно: сторож не проверяет, что
 * карточка ВИДНА человеку, это свойство отрисовки, а не исходника.
 */
const SRC = readFileSync(
  join(process.cwd(), "src/app/longevity/_client.tsx"),
  "utf8",
);

describe("страница долголетия предлагает книгу того же направления", () => {
  it("книга берётся из каталога, а не зашита ссылкой", () => {
    expect(SRC).toContain('productById("ghvzq")');
    // ссылка строится из позиции каталога, а не из литерала gumroad
    expect(SRC).toMatch(/withChannel\(\s*BOOK\.href/);
  });

  it("в кассу ведёт настоящая кнопка покупки с меткой канала", () => {
    const card = SRC.slice(SRC.indexOf("{BOOK && ("));
    expect(card.length).toBeGreaterThan(0);
    expect(card).toContain("<BuyLink");
    expect(card).toContain('source="longevity-book"');
    expect(card).toContain("productId={BOOK.id}");
  });

  it("цена книги не названа числом в прозе", () => {
    /*
     * 🔴 02.10.2026: сторож краснел ЛОЖНО. Он читал исходник целиком и не
     * отличал комментарий от разметки, поэтому объяснение вида «пакет ghvzq за
     * $29.99 не купил никто» в КОММЕНТАРИИ он считал ценой, написанной прозой
     * на странице. Это обратная сторона известного класса «текст О вещи
     * неотличим от вещи»: там свой комментарий ослеплял сторожа, здесь —
     * заставлял краснеть на верном коде.
     *
     * Свойство, которое он охраняет, остаётся прежним и ценным: цену называет
     * касса, а не проза, иначе цена на странице и цена в чеке разъезжаются
     * молча. Поменялось только то, ГДЕ он её ищет — в коде, а не в пояснениях.
     *
     * Граница очистки, названная честно: `//` внутри `https://` не убирается
     * (иначе срезало бы остаток строки и спрятало настоящий литерал), блочные
     * комментарии убираются целиком. Литерал цены на одной строке ПОСЛЕ адреса
     * сторож пропустит — случай искусственный, но умолчать было бы нечестно.
     */
    const безКомментариев = SRC
      .replace(/\/\*[\s\S]*?\*\//g, " ")
      .split("\n")
      .map((л) => {
        const i = л.search(/(?<!:)\/\//);
        return i >= 0 ? л.slice(0, i) : л;
      })
      .join("\n");

    // Цена, подставленная из каталога, — это НЕ проза: её и убираем.
    const prose = безКомментариев
      .replace(/\{BOOK\.priceUsd\}/g, "")
      .replace(/\{КНИГА\.priceUsd\}/g, "");

    // Контроль прибора: очистка не должна съесть сам код, иначе проверка
    // станет зелёной на любом файле.
    expect(prose, "очистка съела разметку — сторож проверяет пустоту").toContain("<BuyLink");
    expect(prose, "очистка съела позицию каталога").toContain('productById("ghvzq")');

    for (const n of ["29.99", "14.99", "9.99"]) {
      expect(prose, `цена ${n} написана прозой — её обязана называть касса`).not.toContain(n);
    }
  });

  it("дешёвая книга тоже берётся из каталога и не может пропасть молча", () => {
    /*
     * Добавлено 02.10.2026 под новый замысел (решение основателя): на странице
     * ДВА товара — книга `orcfbo` $9.99 первой и пакет `ghvzq` $29.99 вторым.
     * Книга — единственное, что у нас когда-либо покупали (три продажи), и
     * исчезнуть она не должна.
     *
     * ПОРЯДОК здесь намеренно не проверяется: он проверяется по ОТРИСОВАННОМУ
     * тексту в longevity/__tests__/bookIsInFirstScreen.guard — там видно, что
     * реально увидит человек. Дублировать его исходником значило бы завести
     * вторую, более слабую копию правила.
     */
    expect(SRC, "позиция каталога для книги $9.99 исчезла").toContain('productById("orcfbo")');
    expect(SRC, "ссылка книги строится не из каталога").toMatch(/withChannel\(\s*КНИГА\.href/);
  });
});
