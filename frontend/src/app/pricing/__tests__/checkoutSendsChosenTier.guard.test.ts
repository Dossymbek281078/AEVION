import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * В кассу уходит ТОТ тариф, который человек выбрал.
 *
 * Найдено мутационным свипом 01.09.2026. Подмена тела запроса на
 * `{ ...opts, tierId: "lite", currency }` — то есть «какую кнопку ни нажми,
 * закажем Lite» — не ловилась НИ ОДНИМ тестом.
 *
 * Причина не в небрежности: у главной страницы оплаты нет ни одной проверки
 * ПОВЕДЕНИЯ. Её нельзя смонтировать в тестах без полного снимка данных, и
 * поэтому окно воронки вынесло отсюда даже подпись про валюту — чтобы её
 * можно было проверить в отдельном модуле.
 *
 * ⚠️ ГРАНИЦА ЭТОГО СТОРОЖА, названная честно. Он читает ИСХОДНИК, а не
 * поведение: поймает возврат зашитого тарифа и потерю выбранного, но НЕ
 * поймает случая, когда `opts.tierId` заполняется неверно выше по коду.
 * Проверка поведения тут стоила бы снимка данных всей страницы; сторож по
 * исходнику — не идеал, а то, что можно иметь сегодня.
 *
 * Соседняя кнопка модуля закрыта иначе и лучше: там проверяется тело запроса
 * на живой отрисовке (`chipNeverDowngrades`).
 */

const СТРАНИЦА = join(__dirname, "..", "page.tsx");

/** Строки кода без комментариев: свой же комментарий уже ловил свой шаблон. */
function кодом(src: string): string[] {
  return src.split(String.fromCharCode(10)).filter((l) => {
    const t = l.trim();
    return !t.startsWith("//") && !t.startsWith("*") && !t.startsWith("/*");
  });
}

describe("касса получает выбранный тариф, а не зашитый", () => {
  const src = readFileSync(СТРАНИЦА, "utf8");
  const строки = кодом(src);

  it("контроль: страница прочитана и обращается в кассу", () => {
    expect(src.length, "страница подозрительно короткая").toBeGreaterThan(5000);
    expect(
      строки.some((l) => l.includes("/api/pricing/checkout/session")),
      "обращение в кассу исчезло — сторож смотрит не туда",
    ).toBe(true);
  });

  it("тело запроса собирается из ВЫБОРА, а не из литерала", () => {
    const тело = строки.filter((l) => l.includes("JSON.stringify({") && l.includes("opts"));
    expect(тело.length, "тело запроса в кассу не найдено").toBeGreaterThan(0);
    for (const l of тело) {
      expect(
        /tierId\s*:\s*"/.test(l),
        "в теле запроса зашит тариф строкой: какую кнопку ни нажми, закажем его — " + l.trim(),
      ).toBe(false);
    }
  });

  it("выбранный тариф действительно доезжает до запроса", () => {
    // Без этой стороны предыдущая проверка была бы зелёной и на теле, где
    // тарифа нет ВООБЩЕ: касса тогда подставила бы свой умолчательный.
    expect(
      строки.some((l) => l.includes("tier: opts.tierId") || l.includes("...opts")),
      "выбор человека не доезжает до тела запроса",
    ).toBe(true);
  });
});
