import { test, expect } from "@playwright/test";

/**
 * Карточка приложения называет, ЧТО покупается, и даёт это сменить.
 *
 * 🔴 ЗАМЕР ПУТИ ПОКУПАТЕЛЯ 06.10.2026, 390×844, прод. Переход с /devhub ведёт на
 * /pricing?app=devhub, страница сама доводит до карточки (автопрокрутка 29.09) —
 * и переключатель срока оказывается на 793 px ВЫШЕ экрана: видимых из пяти кнопок
 * НОЛЬ, по умолчанию выбран «Lite · 1 month». На экране человек видел «$200/mo»,
 * «Buy DevHub» и ни слова «Pro». Пришедший за Pro ($150/мес, $900 за 6 месяцев)
 * покупал месяц за $200, не узнав, что бывает иначе.
 *
 * Проверка идёт НА ШИРИНЕ ТЕЛЕФОНА и смотрит ТЕКСТ КАРТОЧКИ — то, что человек
 * читает, а не наличие узлов в разметке.
 */
const ТЕЛЕФОН = { width: 390, height: 844 };

test.use({ viewport: ТЕЛЕФОН });

test("карточка называет ступень и полную сумму; смена срока меняет текст", async ({ page }) => {
  await page.goto("/pricing?app=devhub&c=probe-e2e");

  const карточка = page.locator('[data-app="devhub"]');
  await expect(карточка, "карточки DevHub нет — проверять нечего").toBeVisible();

  // 1. Ступень названа на самой карточке.
  const метка = карточка.locator("[data-app-term-badge]");
  await expect(метка, "на карточке не названа ступень — человек не знает, что покупает").toBeVisible();
  await expect(метка).toHaveText(/Lite/);

  // 2. Полная сумма за срок — в тексте карточки.
  await expect(карточка, "на карточке нет полной суммы за срок").toContainText("$200");

  // 3. Нажатие метки приводит к переключателю: он должен оказаться на экране.
  await метка.click();
  const переключатель = page.locator("#app-term");
  await expect(переключатель, "метка не приводит к переключателю срока").toBeInViewport();

  // 4. Смена срока меняет ТЕКСТ карточки: это и есть «видно, что покупаешь».
  await переключатель.getByRole("button", { name: /Pro/ }).click();
  await expect(метка, "после смены срока метка всё ещё говорит Lite").toHaveText(/Pro/);
  await expect(карточка, "после смены срока на карточке нет суммы Pro ($900)").toContainText("$900");
});
