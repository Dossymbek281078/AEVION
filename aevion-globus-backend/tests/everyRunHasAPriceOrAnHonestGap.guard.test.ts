import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { ценаПоЕдиницам, тарифЕсть, ТАРИФЫ_ПО_ЕДИНИЦАМ } from "../src/lib/unitPricing";

/**
 * Карточка DevHub обещает: «logs what every AI run cost».
 *
 * Замер прода 29.09.2026: у 50 прогонов из 73 цены не было. Причина оказалась НЕ в
 * отсутствии тарифа у поставщика, как выглядело снаружи: восемь поверхностей считают
 * в знаках и секундах, а таблица цен знает только токены. Токенов у секунды звука не
 * бывает — расчёт молча возвращал ничего.
 *
 * Сторож держит три вещи: цена считается там, где есть опубликованный прайс; у каждого
 * тарифа назван источник; там, где прайса нет, остаётся честная пометка, а не выдуманный
 * ноль. Последнее важнее первых двух: ноль читается как «попользовались бесплатно».
 */
const маршрут = readFileSync(join(__dirname, "..", "src", "routes", "devhub.ts"), "utf8");

describe("цена по единицам", () => {
  it("перевод считается по знакам, распознавание речи — по секундам", () => {
    // 20 000 знаков по $25 за миллион = $0.50
    expect(ценаПоЕдиницам("translate", 20000)).toBeCloseTo(0.5, 6);
    // час звука = 3600 с по $0.22 за час
    expect(ценаПоЕдиницам("stt", 3600)).toBeCloseTo(0.22, 3);
  });

  it("нет тарифа — НЕ ноль, а «посчитать нечем»", () => {
    // ноль читается как «бесплатно», а это разные вещи
    expect(ценаПоЕдиницам("sfx", 10)).toBeNull();
    expect(ценаПоЕдиницам("voice-clone", 1)).toBeNull();
    expect(тарифЕсть("sfx")).toBe(false);
  });

  it("пустой объём не даёт цену: платить не за что", () => {
    expect(ценаПоЕдиницам("translate", 0)).toBeNull();
    expect(ценаПоЕдиницам("translate", -5)).toBeNull();
    expect(ценаПоЕдиницам("translate", Number.NaN)).toBeNull();
  });

  it("у каждого тарифа назван источник — цифра без источника не заводится", () => {
    const без = Object.entries(ТАРИФЫ_ПО_ЕДИНИЦАМ).filter(([, т]) => !т.источник || т.источник.length < 20);
    expect(без.map(([k]) => k), "тариф без источника").toEqual([]);
    for (const [имя, т] of Object.entries(ТАРИФЫ_ПО_ЕДИНИЦАМ)) {
      expect(т.доллары, имя).toBeGreaterThan(0);
      expect(["знаки", "секунды"], имя).toContain(т.единица);
    }
  });
});

describe("подключение к маршрутам", () => {
  it("три поверхности перевода передают ОБЪЁМ, а не просто метку", () => {
    expect(маршрут).toContain('учтиПоОбъёму("translate"');
    expect(маршрут).toContain('учтиПоОбъёму("files-translate"');
    // Пакетный перевод считает сумму по файлам, поэтому вызов многострочный:
    // проверяем СУТЬ (метка и объём рядом), а не форматирование.
    const iПакет = маршрут.indexOf('"files-translate-bulk",');
    expect(iПакет).toBeGreaterThan(0);
    const окно = маршрут.slice(Math.max(0, iПакет - 200), iПакет + 300);
    expect(окно).toContain('учтиПоОбъёму(');
    expect(окно).toContain('r.bytes');
    // и объём берётся из данных, а не из воздуха
    expect(маршрут).toContain('String(text ?? "").length');
  });

  it("поверхности без прайса по-прежнему помечаются честно", () => {
    expect(маршрут).toContain('учтиБезЦены("sfx"');
    expect(маршрут).toContain('учтиБезЦены("voice-clone"');
  });

  it("учёт по объёму падает обратно на честную пометку, когда тарифа нет", () => {
    const i = маршрут.indexOf("function учтиПоОбъёму");
    expect(i).toBeGreaterThan(0);
    const тело = маршрут.slice(i, i + 700);
    expect(тело).toContain("ценаПоЕдиницам(");
    expect(тело).toContain("учтиБезЦены(поверхность, userId")  // без закрывающей скобки: 01.10 добавлен третий аргумент (фактический поставщик), и дословная строка краснела на ПОЧИНКЕ;
  });

  it("расход показывает РАЗБИВКУ: одно число не подсказывает, что чинить", () => {
    expect(маршрут).toContain("unpricedByModule");
  });
});
