/**
 * Вердикт проверки подписи — ТРИ исхода, а не два.
 *
 * Повод. В странице стояло `res.ok && j.valid === true ? "valid" : "invalid"`,
 * и в «недействительна» сваливались три разных случая:
 *
 *  • упавшая сеть (fetch бросил),
 *  • ответ 500/404 от бэкенда,
 *  • `valid: null` — принятое на платформе значение «подтверждать нечего»
 *    (так qsignV2 отвечает в предварительном режиме, чтобы не выдавать
 *    `true` там, где подписи нет).
 *
 * Во всех трёх случаях пользователю показывалось «✗ проверка не прошла», то
 * есть **сбой связи обвинял документ в подделке**. Для модуля, чей смысл —
 * доказуемость маршрута перед регулятором, это худший вид ошибки: он не падает
 * и выглядит как обычная работа.
 *
 * «Не смогли проверить» и «подпись не сошлась» — разные утверждения, и второе
 * нельзя выводить из неполученного ответа.
 */
export type Verdict = "valid" | "invalid" | "unknown";

/**
 * @param ok    `Response.ok` — дошёл ли ответ вообще
 * @param valid поле `valid` из тела: `true` / `false` / `null` (нечего
 *              подтверждать) / отсутствует (старая сборка бэкенда)
 */
export function verifyVerdict(ok: boolean, valid: unknown): Verdict {
  if (!ok) return "unknown";
  if (valid === true) return "valid";
  if (valid === false) return "invalid";
  // null, undefined, строка, число — всё это НЕ отрицательный вердикт.
  // Отсутствие поля тоже: старый бэкенд его не отдаёт, и молча считать это
  // подделкой нельзя.
  return "unknown";
}


export type VerifyReason = "tampered" | "forged" | null;

/**
 * КАКАЯ половина не сошлась — и только по ПОЛОЖИТЕЛЬНОМУ признаку.
 *
 * Бэкенд считает `hashValid` и `signatureValid` раздельно, потому что действия
 * противоположные: документ изменён после выпуска — перевыпустить; подпись не
 * наша — кто-то выдаёт чужую бумагу за нашу.
 *
 * ⚠️ Прежняя версия жила внутри компонента и писала «подпись не наша» всякий
 * раз, когда `hashValid` не был строго `false` — включая случай, когда поля нет
 * вовсе. То есть по ОТСУТСТВУЮЩИМ данным выбиралось более тяжёлое из двух
 * обвинений. Сегодня такой ответ недостижим, но дефолт был выбран не в ту
 * сторону, а такие дефолты переживают тот код, который их делал безопасными.
 *
 * Нет положительного признака — нет обвинения: `null`, и человек видит «не
 * сошлось» без указания виновного.
 */
export function verifyReasonOf(
  verdict: Verdict,
  hashValid: unknown,
  signatureValid: unknown,
): VerifyReason {
  if (verdict !== "invalid") return null;
  if (hashValid === false) return "tampered";
  if (signatureValid === false) return "forged";
  return null;
}
