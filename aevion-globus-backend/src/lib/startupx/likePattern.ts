/**
 * Экранирование пользовательского запроса для `ILIKE … ESCAPE '\'`.
 *
 * Вынесено из роутера, чтобы на это была отдельная проверка: два дефекта,
 * которые здесь жили, не ловились ничем, кроме прогона по настоящему Postgres —
 * in-memory ветка ищет обычным `includes` и переживает любое экранирование.
 *
 *   1. `` `\${m}` `` в шаблонной строке — это литерал «${m}», а не «\%».
 *      Запрос «5%» превращался в «5${m}» и не находил ничего.
 *   2. `` ESCAPE '\' `` в шаблонной строке даёт SQL `ESCAPE ''`, то есть
 *      экранирующего символа нет вовсе.
 *
 * Итог обоих: любой запрос с процентом или подчёркиванием молча отдавал пустую
 * ленту. Инвестор ищет «5%» — и видит, что заявок нет.
 */
export function escapeLikePattern(raw: string): string {
  return raw.replace(/[%_\\]/g, (m) => "\\" + m);
}

/**
 * Escape-символ ровно в том виде, в каком его должен увидеть Postgres.
 * Держим рядом с экранированием: если кто-то поменяет одно, тест на пару
 * покажет, что второе больше не соответствует.
 */
export const LIKE_ESCAPE_SQL = "ESCAPE '\\'";
