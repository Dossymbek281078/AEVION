import { describe, test, expect } from "vitest";
import {
  hvataetMestaPodDoskoy,
  ВЫСОТА_СЖАТОЙ_СТРОКИ,
  ВЫСОТА_НИЖНЕЙ_ПАНЕЛИ,
  ВЫСОТА_РЯДА_КНОПОК,
  ЗАЗОР_ПРИЛИПШИХ,
} from "../page";

/*
 * Сторож на решение «прилеплять ли строку адреса».
 *
 * Повод — дефект 11.10.2026 на проде: прилипшая строка легла поверх доски, и
 * клетки под ней не нажимались (40 из 64 в партии на 390×844, 24 на 1463×724,
 * 32 и 16 на пути из ролика). Прежнее условие спрашивало только «влезла ли
 * строка в кадр» и про доску не знало ничего.
 *
 * Числа ниже — НЕ придуманы: это замер низа доски и высоты окна на проде
 * (`zamer-vysoty-stroki-adresa.cjs`, 11.10, после первого хода).
 */

const ОКНА = [
  { имя: "390×844 (телефон)", ширинаОкна: 390, высотаОкна: 844, низДоски: 673 },
  { имя: "768×1024 (планшет)", ширинаОкна: 768, высотаОкна: 1024, низДоски: 971 },
  { имя: "1280×900 (стол)", ширинаОкна: 1280, высотаОкна: 900, низДоски: 728 },
  { имя: "1463×724 (широкое низкое)", ширинаОкна: 1463, высотаОкна: 724, низДоски: 532 },
];

describe("место под доской для строки адреса", () => {
  test("замеренные окна: где хватает места, где нет — и числами", () => {
    const итог = ОКНА.map((о) => {
      const р = hvataetMestaPodDoskoy({ ...о, высотаСтроки: ВЫСОТА_СЖАТОЙ_СТРОКИ, идётПартия: false });
      return { имя: о.имя, хватает: р.хватает, свободно: р.свободно };
    });
    // 768×1024 — доска почти во всю высоту окна (низ 971 из 1024), там прилипать нельзя.
    expect(итог.map((и) => и.хватает), JSON.stringify(итог)).toEqual([true, false, true, true]);
    // Знаменатель виден: проверено четыре пары окна, а не одна ширина.
    expect(итог).toHaveLength(4);
  });

  test("идёт партия — ряд «Сдаться» отнимает место, и на телефоне его уже не хватает", () => {
    const тел = ОКНА[0];
    const без = hvataetMestaPodDoskoy({ ...тел, высотаСтроки: ВЫСОТА_СЖАТОЙ_СТРОКИ, идётПартия: false });
    const сРядом = hvataetMestaPodDoskoy({ ...тел, высотаСтроки: ВЫСОТА_СЖАТОЙ_СТРОКИ, идётПартия: true });
    expect(без.хватает).toBe(true);
    expect(сРядом.хватает).toBe(false);
    // Ряд отнимает ровно свою высоту и зазор — иначе условие охраняло бы не то.
    expect(без.свободно - сРядом.свободно).toBe(ВЫСОТА_РЯДА_КНОПОК + ЗАЗОР_ПРИЛИПШИХ);
  });

  test("нижняя панель вычитается только до 769 px", () => {
    const узкое = hvataetMestaPodDoskoy({ низДоски: 600, высотаОкна: 844, ширинаОкна: 768, высотаСтроки: 56, идётПартия: false });
    const широкое = hvataetMestaPodDoskoy({ низДоски: 600, высотаОкна: 844, ширинаОкна: 769, высотаСтроки: 56, идётПартия: false });
    expect(широкое.свободно - узкое.свободно).toBe(ВЫСОТА_НИЖНЕЙ_ПАНЕЛИ);
  });

  test("ГРАНИЦА: зазор обязателен — свободного ровно в высоту строки НЕ хватает", () => {
    /*
     * Случай-носитель для мутации «убрать + ЗАЗОР_ПРИЛИПШИХ». Без него обе
     * версии условия отвечали бы одинаково на всех замеренных окнах, и мутация
     * прошла бы насквозь — ровно то, на чём горели сторожа 10–11.10.
     */
    const в_притык = hvataetMestaPodDoskoy({
      низДоски: 844 - 8 - ВЫСОТА_СЖАТОЙ_СТРОКИ, // свободно === высота строки
      высотаОкна: 844, ширинаОкна: 1280, высотаСтроки: ВЫСОТА_СЖАТОЙ_СТРОКИ, идётПартия: false,
    });
    expect(в_притык.свободно).toBe(ВЫСОТА_СЖАТОЙ_СТРОКИ);
    expect(в_притык.хватает, "ровно в высоту строки, без зазора — не хватает").toBe(false);

    const с_зазором = hvataetMestaPodDoskoy({
      низДоски: 844 - 8 - ВЫСОТА_СЖАТОЙ_СТРОКИ - ЗАЗОР_ПРИЛИПШИХ,
      высотаОкна: 844, ширинаОкна: 1280, высотаСтроки: ВЫСОТА_СЖАТОЙ_СТРОКИ, идётПартия: false,
    });
    expect(с_зазором.хватает, "на зазор больше — хватает").toBe(true);
  });

  test("отрицательное «свободно» называет, насколько не хватило", () => {
    const р = hvataetMestaPodDoskoy({ низДоски: 971, высотаОкна: 1024, ширинаОкна: 768, высотаСтроки: 56, идётПартия: false });
    expect(р.свободно).toBeLessThan(0);
    expect(р.свободно).toBe(1024 - 971 - ВЫСОТА_НИЖНЕЙ_ПАНЕЛИ - ЗАЗОР_ПРИЛИПШИХ);
  });

  test("🔴 потолок высоты проходит в замеренное место на ТЕЛЕФОНЕ", () => {
    /*
     * Поправка 11.10 вечером: первая версия ставила 56 px как ожидание, ничем не
     * обоснованное; на проде сжатая строка вышла 97, и прилипание на телефоне
     * сняла проверка после отрисовки. Теперь константа — ПОТОЛОК, и он охраняется
     * тем самым местом, из-за которого всё и случилось: под доской на 390×844
     * свободно 96 px (844 − 673 − 70 панель − 8 зазор, вне партии).
     */
    const свободноНаТелефоне = 844 - 673 - ВЫСОТА_НИЖНЕЙ_ПАНЕЛИ - ЗАЗОР_ПРИЛИПШИХ;
    expect(свободноНаТелефоне).toBe(93);
    expect(ВЫСОТА_СЖАТОЙ_СТРОКИ + ЗАЗОР_ПРИЛИПШИХ,
      "потолок плюс зазор обязан влезать в замеренное место под доской на телефоне")
      .toBeLessThanOrEqual(свободноНаТелефоне);
    // И замеренные 97 px (волна 44) в это место НЕ влезали — иначе правка ничего не меняет.
    expect(97 + ЗАЗОР_ПРИЛИПШИХ).toBeGreaterThan(свободноНаТелефоне);
  });

  test("🔴 замеренные 83 px на телефоне тоже влезали — но запас был 2 px, а не 5", () => {
    /*
     * Волна 45, замер приёмки и мой прогон сошлись: прилипшая строка 83 px на
     * 390×844 и 68 на столе. Разница — вторая строка текста обещания, который на
     * узком экране переносился; с волны 46 там короткий текст в одну строку.
     *
     * Этот случай оставлен в стороже НЕ ради 83, а ради правила: «влезает» и
     * «есть запас» — разные утверждения, и второе надо проверять отдельно,
     * иначе любая правка отступов молча съедает прилипание (проверка после
     * отрисовки его снимет, доска останется цела, но обещание не выполнится).
     */
    const свободноНаТелефоне = 844 - 673 - ВЫСОТА_НИЖНЕЙ_ПАНЕЛИ - ЗАЗОР_ПРИЛИПШИХ;
    expect(свободноНаТелефоне).toBe(93);
    expect(83 + ЗАЗОР_ПРИЛИПШИХ, "83 px влезали").toBeLessThanOrEqual(свободноНаТелефоне);
    expect(свободноНаТелефоне - (83 + ЗАЗОР_ПРИЛИПШИХ), "но запас был всего 2 px").toBe(2);
    expect(свободноНаТелефоне - (ВЫСОТА_СЖАТОЙ_СТРОКИ + ЗАЗОР_ПРИЛИПШИХ),
      "с объявленным потолком запас 5 px").toBe(5);
  });

  test("ожидаемая высота сжатой строки меньше замеренной полной", () => {
    // Полная карточка на проде: 200 px, на 390 — 277. Если константа однажды
    // подрастёт до этих значений, смысл сжатия исчезнет молча.
    expect(ВЫСОТА_СЖАТОЙ_СТРОКИ).toBeLessThan(200);
  });
});
