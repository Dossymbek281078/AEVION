/**
 * Полнота сводки расходов: три исхода, а не два.
 *
 * Учёт расхода на сервере — «по возможности»: он не роняет операцию, ради
 * которой его зовут, и потому может тихо не записать. Сводка при сломанной
 * записи выглядит ровно как при исправной, просто чисел меньше.
 *
 * Отсюда правило, ради которого это вынесено из компонента: «поля нет» —
 * это НЕ ноль. Старый бэкенд поля не шлёт, и ответа у нас нет вовсе.
 * Свести оба к «всё хорошо» — значит показать спокойствие там, где его
 * никто не проверял; это тот же класс, что «пустой список вместо отказа».
 *
 * Живёт отдельным модулем, а не внутри страницы: файл страницы в Next
 * ограничен в экспортах, а решение, которое нельзя вызвать из теста,
 * нельзя и закрепить.
 */
export type SpendCompleteness =
  | { kind: "unknown" }
  | { kind: "complete" }
  | { kind: "incomplete"; lost: number };

export function spendCompleteness(droppedRuns?: number | null): SpendCompleteness {
  if (droppedRuns == null) return { kind: "unknown" };
  if (!Number.isFinite(droppedRuns) || droppedRuns <= 0) return { kind: "complete" };
  return { kind: "incomplete", lost: droppedRuns };
}
