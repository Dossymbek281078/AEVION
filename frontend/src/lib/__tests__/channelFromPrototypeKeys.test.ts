/**
 * Служебное слово в метке канала не становится каналом.
 *
 * `?c=<метка>` разбирается прямой индексацией словаря каналов, а `?? null`
 * отсеивает только null и undefined. Унаследованное значение проходит: замер
 * 02.09.2026 показал, что `channelFrom("constructor")` возвращал ФУНКЦИЮ.
 *
 * Дальше она уезжала как «канал» по двум путям, и оба тихие:
 *   - в meta события учёта, где JSON.stringify молча выбрасывает функции —
 *     канал исчезал совсем, и покупка становилась «прямой»;
 *   - в withChannel(), то есть в адрес кассы строкой
 *     «function Object() { [native code] }».
 *
 * Достаточно было зайти по ссылке с `?c=constructor`. Ни падения, ни ошибки.
 *
 * Тот же класс платформа уже ловила у ссылок Gumroad и вариантов LemonSqueezy —
 * там стоят такие же сторожа. Этот закрывает третью дверь.
 *
 * ЭТО НЕ ДУБЛЬ СОСЕДНЕГО СТОРОЖА, и вот почему — не удаляйте его.
 * Рядом живёт `channelsCoverRealSources.test.ts`, и у него есть случай с
 * буквально тем же названием: «неизвестная метка даёт null, а не мусорный
 * канал». Но проверяется он входами `"не-существует"`, `undefined` и `""` —
 * обычными неизвестными значениями. Служебных слов среди них нет, поэтому
 * тот сторож был ЗЕЛЁНЫМ всё время, пока `channelFrom("constructor")`
 * возвращал функцию.
 *
 * То есть вопрос был задан правильный, а вход — не тот. Такая проверка тише
 * отсутствующей: она создаёт уверенность, что случай покрыт. Здесь тот же
 * вопрос задан входами, на которых он ломается.
 *
 * СВИП ПО ЗОНЕ ПЕРЕДЕЛАН 04.09.2026 — ПЕРВАЯ ВЕРСИЯ БЫЛА СЛЕПА, и её вывод
 * («ключом посетителя таких мест два») оказался неверным.
 *
 * Она требовала, чтобы объявление ключа и `sp.get(...)` стояли на ОДНОЙ
 * строке. А в коде объявления многострочные:
 *
 *     const provider =
 *       sp.get("provider") ??
 *       (sp.get("paypal") ? "paypal" : null) ?? ...
 *
 * Из-за этого свип не увидел `PROCESSOR_LABEL[provider]` на экране оплаты —
 * место, где соседнее окно потом ОТРИСОВКОЙ нашло «paid via function Object()
 * { [native code] }» трижды на одном экране.
 *
 * Переделанный свип (объявление ищется многострочным) по src/lib,
 * src/app/pricing, src/components, src/app/go, src/app/account: 65 поисков по
 * словарю, ключом ИЗ АДРЕСА — ровно два, и оба теперь защищены:
 * `APP_LINKS[appId]` и `PROCESSOR_LABEL[provider]`. Контроль: исправленный
 * прибор находит тот случай, который прежний терял.
 *
 * Урок общий: свип, ограниченный СТРОКОЙ, слеп к многострочным объявлениям —
 * а именно так пишут там, где значение собирается из нескольких источников,
 * то есть в самых интересных местах.
 *
 * И честная граница свипа: фильтр «ключ выведен из адреса в ТОМ ЖЕ файле»
 * ЭТУ находку не нашёл бы — сюда ключ приходит параметром функции. Нашлась
 * она чтением, а не фильтром. Значит «кандидатов больше нет» относится к
 * форме записи, а не к классу: тот же дефект за границей функции фильтр не
 * видит, и полагаться на его ноль нельзя.
 */
import { describe, it, expect } from "vitest";
import { channelFrom, withChannel } from "../products";

const СЛУЖЕБНЫЕ = ["constructor", "__proto__", "toString", "valueOf", "hasOwnProperty", "prototype"];

describe("метка канала", () => {
  it.each(СЛУЖЕБНЫЕ)("«%s» каналом не считается", (k) => {
    const r = channelFrom(k);
    expect(typeof r, `${k} вернул ${typeof r}`).not.toBe("function");
    expect(r, `${k} принят за канал`).toBeNull();
  });

  it("настоящая метка по-прежнему работает", () => {
    // Контроль: без него «всегда null» выглядело бы как починка.
    expect(channelFrom("tg")).toBe("telegram");
  });

  it("в адрес кассы служебное слово не попадает", () => {
    /*
     * Проверяем СЛЕДСТВИЕ, а не только разбор: адрес — то, что реально уедет
     * к продавцу и вернётся в запись подписки.
     */
    const адрес = withChannel("https://example.test/checkout", channelFrom("constructor"), "pricing");
    expect(адрес, "в адрес кассы уехала функция").not.toContain("native code");
    expect(адрес, "в адрес кассы уехало служебное слово").not.toContain("constructor");
  });

  it("настоящая метка в адрес кассы попадает", () => {
    const адрес = withChannel("https://example.test/checkout", channelFrom("tg"), "pricing");
    expect(адрес, "канал не доехал до адреса кассы").toContain("telegram");
  });
});
