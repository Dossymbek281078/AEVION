import type { Request, Response, NextFunction } from "express";

/**
 * Предел размера тела для отдельных путей — ДО общего разбора JSON.
 *
 * Зачем не через `express.json({ limit })`. Общий разборщик стоит в index.ts
 * раньше всех роутеров, значит к моменту ручки тело уже прочитано и разобрано —
 * поставить меньший предел «на ручке» физически поздно. Проверка здесь смотрит
 * `Content-Length` и отказывает ДО чтения тела: работа не делается вовсе.
 *
 * Зачем не опустить общий предел с 10 МБ. Он высокий не случайно: замер по
 * бэкенду дал 25 ручек-кандидатов на большое тело в 12 файлах — base64-аудио для
 * расшифровки, клон голоса, картинки DevHub, сканы резюме. Список к тому же
 * неполон (искал признаки грепом). Опустить общий предел значило бы сломать
 * денежные медиа-пути ради одной публичной ручки — поэтому здесь узкий список
 * исключений вниз, а не смена умолчания.
 *
 * Почему 256 КБ для чека. Замерено боевым `buildReceipt` на максимальном чеке
 * (8 агентов — предел отправки, ответы по 4000 символов, 40 пунктов «что
 * проверить», подпись и хеш): **7628 байт**, то есть 7.4 КБ. Чек мал по
 * устройству — он хранит ХЕШИ ответов, а не тексты. 256 КБ даёт 34-кратный
 * запас на будущие поля и при этом сокращает худший случай публичной ручки в
 * сорок раз против общих 10 МБ.
 *
 * Отказ отдаётся ошибкой той же формы, что бросает body-parser (`status` +
 * `type: entity.too.large`), чтобы её разобрал общий обработчик ошибок и человек
 * увидел 413 с внятной причиной, а не 500.
 */

/**
 * Общий предел `express.json` в байтах — тот же, что стоит в index.ts.
 *
 * Дублировать число нельзя: текст отказа называет предел человеку, и разойдись
 * оно с настоящим — сообщение станет ложью (так уже случилось: текст обещал
 * 10 МБ, когда на чек поставили 256 КБ). Меняете limit в index.ts — меняйте и
 * здесь; сторож в тестах сверяет две записи.
 */
export const GLOBAL_BODY_LIMIT_BYTES = 10 * 1024 * 1024;

/** Нормализованный путь запроса: без строки запроса и без хвостовых слешей. */
export function requestPath(url: string | undefined): string {
  const p = (url || "").split("?")[0].replace(/\/+$/, "");
  return p || "/";
}

/** Путь → предел в байтах. Точное совпадение, без префиксов: правило должно быть видно целиком. */
export const BODY_LIMITS: Record<string, number> = {
  "/api/multichat/receipt/verify": 256 * 1024,
  // 29.08.2026, QSkyway. Обработчик проверки якоря УЖЕ отбивал доказательства
  // крупнее 64 КБ и объяснял почему: «разбирать такое, прежде чем понять
  // негодность, — работа, которую выбирает атакующий». Но проверка стояла В
  // ОБРАБОТЧИКЕ, то есть после того, как разобраны все десять мегабайт общего
  // предела. Намерение было названо, а исполнено наполовину — и механизм,
  // который закрывает разрыв, лежал рядом всё это время.
  //
  // 96 КБ: сериализованный .ots на один хэш — единицы килобайт (наш с
  // Bitcoin-подтверждением 3.7 КБ), 64 КБ уже стократный запас, остальное на
  // конверт JSON. Больше — не доказательство, которое мы могли бы проверить.
  "/api/qskyway/airspace/anchor/verify": 96 * 1024,
};

export function bodyLimitByPath(req: Request, _res: Response, next: NextFunction): void {
  // `req.path` здесь недоступен так же надёжно, как в роутере (мидлвара стоит на
  // приложении), поэтому нормализуем сами — той же функцией, что и остальные
  // проверки по путям.
  const limit = BODY_LIMITS[requestPath(req.originalUrl || req.url)];
  if (limit === undefined) {
    next();
    return;
  }

  const raw = req.headers["content-length"];
  const len = typeof raw === "string" ? Number(raw) : NaN;
  // Нет заголовка или он не число — пропускаем: тело может идти chunked, и тогда
  // размер заранее неизвестен. Страховкой остаётся общий предел express.json.
  // Молча закрывать такие запросы нельзя: это ломало бы законных клиентов ради
  // случая, который общий предел и так ловит.
  if (!Number.isFinite(len) || len <= limit) {
    next();
    return;
  }

  next(
    Object.assign(new Error(`request entity too large: ${len} > ${limit}`), {
      status: 413,
      statusCode: 413,
      type: "entity.too.large",
      expose: true,
    }),
  );
}
