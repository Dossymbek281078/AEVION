import type { Request } from "express";

import { verifyBearerOptional } from "./authJwt";

/**
 * Предел размера запроса к платным ИИ-ручкам для АНОНИМНОГО вызывающего.
 *
 * Замер 23.08.2026 на проде. Один POST без токена на `/api/qcoreai/chat`
 * получил ответ от `claude-opus-4-8` — самой дорогой модели в парке. Ни
 * аккаунта, ни учёта: `enforceFreeTokenQuota` первой же строкой возвращает
 * `false` для анонима, и в шапке того файла это записано прямо — «anon abuse
 * is a separate rate-limit concern».
 *
 * Ограничитель частоты этой роли не выполняет, и это тоже замерено, а не
 * предположено. 100 запросов за 11 секунд с одного адреса против объявленного
 * `max: 30` дали 2 отказа. Заголовок `X-RateLimit-Remaining` в двенадцати
 * ПОСЛЕДОВАТЕЛЬНЫХ запросах шёл 29, 28, 29, 28, 29, 29, 27, 28, 29, 26, 29, 29 —
 * то есть счётчиков несколько.
 *
 * ПОЧЕМУ их несколько — вопрос открытый: первое объяснение («процессов у
 * сервиса несколько») проверено 28.08 и оказалось НЕВЕРНЫМ — экземпляр один.
 * Разбор в шапке rateLimit.ts. Для этого модуля ничего не меняется: предел
 * цены одного вызова не зависит ни от числа процессов, ни от того, чем
 * считается ключ, — тем он здесь и хорош.
 *
 * Что бесплатно и надёжно можно ограничить, не заводя общего хранилища, — это
 * стоимость ОДНОГО вызова. Сейчас она упирается только в общий предел тела
 * (10 МБ): `sanitizeMessages` режет каждое сообщение до 32 000 знаков, а
 * ЧИСЛО сообщений не ограничено ничем. То есть один анонимный запрос может
 * увезти порядка двух с половиной миллионов входных токенов.
 *
 * Пределы выбраны так, чтобы настоящий разговор в них не упирался: 24 000
 * знаков — это примерно шесть тысяч токенов, длинная беседа целиком. Клиенты
 * платформы историю не обрезают (проверено: ни в одном из трёх мест нет
 * `slice`), поэтому предел на ЧИСЛО сообщений держится с запасом.
 *
 * Вошедшего это не касается: он опознан, его расход учитывается
 * (`addTokenUsage`) и на него распространяются тарифные квоты. Смысл здесь
 * ровно один — у неопознанного вызова должна быть верхняя граница цены.
 */

/**
 * ⚠️ ГДЕ ЭТОТ ПРЕДЕЛ ПРИМЕНЯТЬ НЕЛЬЗЯ (проверено 27.08.2026).
 *
 * Он исходит из того, что неопознанный вызывающий — это чужой скрипт, а свои
 * приходят с токеном. У части ручек это НЕ так: их законный потребитель
 * анонимен по устройству.
 *
 * Пример, на котором я едва не ошибся: `/api/i18n/translate`. Выглядит как
 * идеальный кандидат — аноним, платный провайдер, до 200 текстов по 5 000
 * знаков за вызов. Но зовёт её `components/AutoTranslate.tsx` из БРАУЗЕРА
 * посетителя, пачками по 100 строк интерфейса, на живых страницах (QBuild,
 * QRight). Предел в 24 000 знаков сломал бы перевод страницы обычному человеку,
 * и выглядело бы это как поломка продукта, а не как защита.
 *
 * Правило: прежде чем ставить эти ворота, найди, КТО зовёт ручку. Если среди
 * вызывающих есть наша же страница без входа — предел нужен другой (по объёму
 * за сутки с адреса, по размеру одной строки), а не этот.
 */

/** Сколько знаков суммарно может прислать неопознанный вызывающий. */
export const ANON_MAX_TOTAL_CHARS = 24_000;
/** Сколько сообщений в истории может прислать неопознанный вызывающий. */
export const ANON_MAX_MESSAGES = 40;

export type InputBudgetVerdict =
  | { ok: true }
  | { ok: false; error: string; message: string; limit: number; got: number };

/**
 * @param isAnonymous — вынесен параметром, а не вычисляется внутри, чтобы
 * проверку можно было прогнать без подписанного токена. Разбор подписи уже
 * проверен своими тестами, и повторять его здесь значило бы мерить чужое.
 */
export function checkAiInputBudget(
  messages: Array<{ content?: unknown }>,
  isAnonymous: boolean,
): InputBudgetVerdict {
  if (!isAnonymous) return { ok: true };

  if (messages.length > ANON_MAX_MESSAGES) {
    return {
      ok: false,
      error: "too_many_messages",
      message:
        `Без входа в аккаунт можно прислать не больше ${ANON_MAX_MESSAGES} сообщений за раз. ` +
        "Войдите — тогда ограничение снимается.",
      limit: ANON_MAX_MESSAGES,
      got: messages.length,
    };
  }

  let total = 0;
  for (const m of messages) total += typeof m?.content === "string" ? m.content.length : 0;
  if (total > ANON_MAX_TOTAL_CHARS) {
    return {
      ok: false,
      error: "input_too_large",
      message:
        `Без входа в аккаунт запрос ограничен ${ANON_MAX_TOTAL_CHARS} знаками, ` +
        `пришло ${total}. Войдите — тогда ограничение снимается.`,
      limit: ANON_MAX_TOTAL_CHARS,
      got: total,
    };
  }

  return { ok: true };
}

/** Опознан ли вызывающий. Отдельной функцией — её подменяют в тестах. */
export function isAnonymousRequest(req: Request): boolean {
  try {
    return !verifyBearerOptional(req)?.sub;
  } catch {
    // Разобрать токен не удалось — считаем вызов неопознанным. Это строже, а
    // не мягче: неотвеченный вопрос не равен «свой».
    return true;
  }
}
