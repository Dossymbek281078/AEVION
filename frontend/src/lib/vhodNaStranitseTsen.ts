/**
 * Что показать ПЕРВЫМ экраном на /pricing, когда человек пришёл по ссылке.
 *
 * 🔴 ПОВОД 12.10.2026. Из трёх живых людей, нажавших «Купить CyberChess» в
 * шахматах, до цен дошёл ОДИН (воронка, канал youtube, 14 дней). Кнопка ведёт
 * на `/pricing?app=cyberchess`, а верхний блок всё это время включался только
 * по `?module=`. Пришедший по `?app=` попадал на страницу длиной 23 экрана,
 * где его карточка стоит на 6162 px — 7.3 экрана вниз, — и видел её лишь
 * после 1402 КБ кода, если вообще дожидался.
 *
 * Решение вынесено сюда отдельной функцией намеренно: пока оно жило строкой
 * внутри useEffect, проверить его было нечем — а это развилка, от которой
 * зависит, увидит ли человек то, за чем пришёл.
 */

export type ВходСтраницыЦен = {
  /** `?module=<id>` — ссылка со страницы продукта, самая точная. */
  module?: string | null;
  /** `?app=<слаг>` — кнопка «Купить» внутри приложения. */
  app?: string | null;
  /** Есть ли такой модуль в данных страницы. */
  естьМодуль: (id: string) => boolean;
  /** Продаётся ли такое приложение отдельно (bureau — нет). */
  prodayotsyaOtdelno: (слаг: string) => boolean;
};

/**
 * Слаг для верхнего блока или пустая строка.
 *
 * `?module=` главнее `?app=`: его ставит страница продукта, и он точнее.
 * Неизвестное или не продаваемое отдельно — пустая строка, то есть обычный
 * холодный вход: лучше показать общий вход, чем обещать карточку, которой нет.
 */
export function vybratVhod(о: ВходСтраницыЦен): string {
  const модуль = (о.module ?? "").trim();
  if (модуль && о.естьМодуль(модуль)) return модуль;
  const прил = (о.app ?? "").trim();
  if (прил && о.естьМодуль(прил) && о.prodayotsyaOtdelno(прил)) return прил;
  return "";
}
