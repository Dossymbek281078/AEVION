import { describe, it, expect } from "vitest";
import { fmt } from "../clockFormat";

/* Циферблат читают каждую секунду всю партию, поэтому ошибка здесь видна сразу и
   выглядит как поломка. Секунды приходят из (deadline - now)/1000, то есть дробными:
   защита обязана стоять в самой функции, а не в памяти того, кто её зовёт. */

describe("формат часов", () => {
  it("дробные секунды не попадают на циферблат", () => {
    expect(fmt(157.4159)).toBe("2:37");
    expect(fmt(59.9)).toBe("1:00");
    expect(fmt(5.03)).toBe("0:05");
  });

  it("целые секунды форматируются как раньше", () => {
    expect(fmt(120)).toBe("2:00");
    expect(fmt(65)).toBe("1:05");
    expect(fmt(9)).toBe("0:09");
  });

  it("ноль и отрицательное дают 0:00, а не минус", () => {
    expect(fmt(0)).toBe("0:00");
    expect(fmt(-5)).toBe("0:00");
  });

  it("NaN и бесконечность не выводятся на экран", () => {
    expect(fmt(NaN)).toBe("0:00");
    expect(fmt(Infinity)).toBe("0:00");
  });

  it("секунды всегда двумя цифрами", () => {
    for (let s = 0; s < 600; s++) {
      const parts = fmt(s + 0.4).split(":");
      expect(parts[1]).toHaveLength(2);
    }
  });

  it("длинные контроли не ломают минуты", () => {
    expect(fmt(3600)).toBe("60:00");
    expect(fmt(5400)).toBe("90:00");
  });
});
