import { describe, test, expect } from "vitest";
import { isSeededEntry, isProbeEntry, публичныеЗаписи } from "../src/routes/cyberchessDaily";

/**
 * Сторож: публичная таблица лидеров не показывает наши пробы.
 *
 * 🔴 ЗАМЕР 29.09.2026, накануне запуска шахмат (30.09). Ручка
 * `GET /api/cyberchess-daily/leaderboard` отдавала ПЕРВОЙ строкой:
 *
 *     {"userId":"smoke-c2-verify","name":"smoke-c2","streak":1,"score":355}
 *
 * Запись оставил наш же прогон, доказывавший, что засчитывание решения работает
 * после починки. То есть в день запуска посетитель увидел бы во главе доски
 * отладочную строку — это хуже пустой доски, ровно по той причине, по которой
 * 10.08.2026 убрали сотню выдуманных игроков.
 *
 * Класс не единичный: у платформы уже была «витрина, заполненная нашими
 * пробами» накануне прошлого запуска. Поэтому защита ставится НА ЧТЕНИЕ и
 * работает для будущих прогонов, а не только для этой одной строки.
 *
 * Контроли обязательны в обе стороны: честное имя, начинающееся на «test…»
 * (например «testimonial» или игрок «Testarossa»), скрывать НЕЛЬЗЯ — иначе
 * защита от проб превратится в потерю настоящих игроков.
 */
const проба = { userId: "smoke-c2-verify", name: "smoke-c2", streak: 1, score: 355 };
const человек = { userId: "u-9981", name: "Айдана", streak: 7, score: 4120 };

describe("публичная таблица лидеров", () => {
  test("наша проба скрыта", () => {
    expect(isProbeEntry(проба), "запись прогона не опознана как проба").toBe(true);
    expect(публичныеЗаписи([проба, человек])).toEqual([человек]);
  });

  test("пробу видно и по имени, и по идентификатору — любой из двух достаточно", () => {
    expect(isProbeEntry({ userId: "probe-1", name: "Иван" })).toBe(true);
    expect(isProbeEntry({ userId: "u-100", name: "smoke run" })).toBe(true);
    expect(isProbeEntry({ userId: "test:42", name: "кто-то" })).toBe(true);
  });

  test("посевные записи по-прежнему скрыты", () => {
    // Прежнее правило не должно пропасть при добавлении нового.
    expect(публичныеЗаписи([{ userId: "seed_001", name: "Magnus" }, человек])).toEqual([человек]);
    expect(isSeededEntry({ userId: "seed_001" })).toBe(true);
  });

  test("КОНТРОЛЬ: настоящих игроков не прячем", () => {
    for (const имя of ["Testarossa", "Protey", "Smokey", "Тест-драйв Иванов", "testimonial"]) {
      expect(
        isProbeEntry({ userId: "u-1", name: имя }),
        `«${имя}» принято за пробу — защита превратилась в потерю игрока`,
      ).toBe(false);
    }
    expect(публичныеЗаписи([человек]), "обычная запись исчезла из таблицы").toEqual([человек]);
  });

  test("КОНТРОЛЬ: пустой список остаётся пустым, а не превращается в ошибку", () => {
    expect(публичныеЗаписи([])).toEqual([]);
  });
});
