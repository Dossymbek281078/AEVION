/**
 * AEVION против аналогов — единый источник для страницы сравнения.
 *
 * Правила, без которых эта таблица бесполезна:
 *
 * 1. **У каждого модуля обязательно есть «где мы слабее».** Сравнение, где мы
 *    выигрываем по всем строкам, читается как реклама и не помогает принять
 *    решение ни инвестору, ни пользователю. Если слабых мест не нашлось —
 *    значит, конкурентов смотрели невнимательно.
 * 2. **У каждого утверждения есть основание.** `measured` — наш собственный
 *    прогон с числом; `public` — публичные данные конкурента с датой среза;
 *    `design` — свойство архитектуры, которое видно в коде. Утверждение без
 *    основания в таблицу не попадает.
 * 3. **Модуль без разбора честно помечен**, а не заполнен догадками:
 *    `UNANALYSED` внизу файла.
 *
 * Как добавить модуль: провести срез (кто рядом, что у них лучше), собрать
 * основания, добавить запись сюда. Страница `/compare` подхватит автоматически.
 */

/**
 * Через сколько дней срез считается протухшим. Девяносто — потому что за
 * квартал конкурент успевает выпустить то, что переворачивает строку таблицы,
 * а мы успеваем закрыть то, что в ней записано как наша слабость.
 */
export const REVIEW_AFTER_DAYS = 90;

/**
 * Дата, после которой строку надо пересмотреть.
 *
 * Считается ТОЛЬКО из даты среза, без обращения к часам. Это принципиально:
 * страница статическая, и «прошло N дней» замёрзло бы на моменте сборки —
 * читатель видел бы свежую цифру у полугодового среза. Здесь он видит дату
 * и сравнивает со своим сегодня сам.
 */
export function reviewAfter(surveyedAt: string, days: number = REVIEW_AFTER_DAYS): string {
  const d = new Date(`${surveyedAt}T00:00:00Z`);
  if (Number.isNaN(d.getTime())) return surveyedAt;
  d.setUTCDate(d.getUTCDate() + days);
  return d.toISOString().slice(0, 10);
}

export type Basis = "measured" | "public" | "design";

export interface Claim {
  /** Одно утверждение — одна мысль. */
  text: string;
  /** Чем подтверждено. Без этого утверждение не публикуем. */
  basis: Basis;
  /** Конкретика: число, дата, ссылка на прогон. */
  evidence: string;
}

export interface Rival {
  name: string;
  url: string;
  /** Чем он реально хорош. Не «слабая копия нас», а честная сила. */
  strength: string;
}

