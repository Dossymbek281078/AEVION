/**
 * competitors — честное сравнение модулей AEVION с существующими аналогами.
 *
 * ЗАЧЕМ ЭТОТ ФАЙЛ. Человек, впервые видящий платформу из 41 модуля, задаёт один
 * вопрос: «а чем это лучше того, чем я уже пользуюсь». Ответ «у нас всё в одном
 * месте» его не устраивает и правильно делает. Здесь на этот вопрос отвечают
 * помодульно и с двух сторон.
 *
 * ГЛАВНОЕ ПРАВИЛО: поле `weaker` обязано быть непустым.
 * Сравнение, в котором мы сильнее по всем пунктам, — это не сравнение, а
 * реклама, и читатель распознаёт её мгновенно. Если по модулю не удаётся
 * назвать, в чём аналог лучше, значит аналог не изучен — и такой модуль честнее
 * не публиковать вовсе, чем публиковать односторонним.
 * Страж `competitors.guard.test.ts` не даёт добавить запись без `weaker`.
 *
 * ЧТО СЧИТАЕТСЯ ОСНОВАНИЕМ (`basis`):
 *   "measured"      — есть наш прогон или замер, на который можно сослаться;
 *   "public-facts"  — общедоступные факты о продуктах: тарифы, наличие функции,
 *                     лицензия, публичная документация;
 *   "reasoned"      — вывод из устройства продуктов, без замера. Самый слабый
 *                     уровень: годится для «у них закрытый код, у нас открытый
 *                     API», не годится для «мы быстрее».
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Цифр вида «на 40% быстрее» и «в 3 раза дешевле» не
 * будет, пока не появится прогон, который можно показать. Сравнительные
 * замеры чужих продуктов мы не проводили, а брать их из чужого маркетинга —
 * тот же самый выдуманный факт, только с чужой подписью.
 */

export type ComparisonBasis = "measured" | "public-facts" | "reasoned";

export interface ModuleComparison {
  /** id из реестра модулей (`/api/aevion/catalog`). */
  id: string;
  /** Человеческое имя — как называем на витрине. */
  name: string;
  /** Одна строка: что это вообще такое. */
  what: string;
  /** С чем сравниваем. Реальные продукты, которыми люди пользуются сегодня. */
  rivals: string[];
  /** В чём мы сильнее. Формулировки проверяемые, а не оценочные. */
  stronger: string[];
  /** В чём аналог сильнее. ОБЯЗАТЕЛЬНО непустое — см. правило выше. */
  weaker: string[];
  basis: ComparisonBasis;
  /** Зрелость по реестру: live или mvp. */
  stage: "live" | "mvp";
}

