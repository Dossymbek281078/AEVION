/**
 * Медиана — вынесена из `audit-guessed-heights.mjs`, чтобы её можно было
 * проверить тестом.
 *
 * Повод конкретный: цифра «медиана жилых домов Астаны 33.6 м» попала в записку
 * основателю и в разбор по безопасности, а получена она чётной веткой (80
 * известных высот), которую ничто не проверяло. Число, на которое ссылаются
 * при решении, не должно приходить из непокрытой ветки.
 */

/** Медиана массива чисел; у чётной длины — среднее двух средних, до 0.1. */
export function median(xs) {
  if (!xs.length) return null;
  const s = [...xs].sort((x, y) => x - y);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : +(((s[m - 1] + s[m]) / 2).toFixed(1));
}
