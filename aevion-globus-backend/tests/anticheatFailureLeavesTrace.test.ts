/**
 * Сторож: провал античита не проходит молча.
 *
 * Разбор партии на читерство намеренно best-effort — он не должен ронять
 * расчёт партии. Но до 27.08.2026 он был ещё и БЕЗМОЛВНЫМ: `catch {}` без
 * единой строки. Если разбор начнёт падать, партии продолжат засчитываться,
 * ошибок нигде не появится, и всё будет выглядеть работающим.
 *
 * Цена молчания здесь выше обычной: посадочная страница шахмат обещает
 * человеку «подозрительные партии помечаются автоматически, без ручного
 * разбора каждой». Молчащий сбой превращает это обещание в ложное, и никто
 * об этом не узнает — ни игрок, ни мы.
 *
 * Проверяется статически: функция приватная, а поднимать ради одной строки
 * весь матчмейкинг дороже пользы. Зато проверка закрепляет ровно то, что
 * важно, — что след есть и что он НАЗЫВАЕТ партию и игроков. След без этого
 * бесполезен: «что-то упало» не даёт ни разобраться, ни перепроверить.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const SRC = readFileSync(
  join(__dirname, "..", "src", "routes", "cyberchessMatchmaking.ts"),
  "utf8",
);

function блокФункции(имя: string): string {
  const начало = SRC.indexOf(`function ${имя}(`);
  if (начало === -1) return "";
  // До начала следующего объявления верхнего уровня.
  const хвост = SRC.slice(начало + 1);
  const конец = хвост.search(/\n(function |const |export |\/\*\*)/);
  return конец === -1 ? хвост : хвост.slice(0, конец);
}

describe("провал античита оставляет след", () => {
  it("контроль: функция разбора найдена в исходнике", () => {
    // Без этого «след есть» могло бы означать «искали не там».
    expect(блокФункции("submitServerAnticheatSignals").length).toBeGreaterThan(200);
  });

  it("перехват не пустой — падение видно в журнале", () => {
    const блок = блокФункции("submitServerAnticheatSignals");
    expect(блок, "перехват молчит: сбой античита будет неотличим от успеха").toMatch(
      /catch\s*\([^)]*\)\s*\{[\s\S]*console\.(error|warn)/,
    );
  });

  it("след называет партию и игроков, а не просто «упало»", () => {
    // Смотрим ВНУТРЬ перехвата и требуем ПОЛЕ, а не подстроку. Первая версия
    // искала «matchId» по всей функции — и мутация, выбросившая поле из
    // объекта, прошла незамеченной: имя осталось в `m.matchId` строкой выше.
    // Проверка была зелёной на сломанном коде, то есть охраняла не то, что
    // обещает её название.
    const блок = блокФункции("submitServerAnticheatSignals");
    const перехват = блок.slice(блок.indexOf("catch ("));
    expect(перехват.length, "контроль: перехват не найден").toBeGreaterThan(50);
    expect(перехват, "по следу нельзя найти партию").toMatch(/matchId:\s*m\.matchId/);
    expect(перехват, "по следу нельзя понять, кого не проверили").toMatch(/players:\s*\[/);
  });

  it("расчёт партии по-прежнему не роняется — перехват на месте", () => {
    // Обратная сторона: сделать сбой громким ценой падения матча нельзя.
    const блок = блокФункции("submitServerAnticheatSignals");
    expect(блок).toMatch(/catch\s*\(/);
    expect(блок, "ошибка пробрасывается — партия не засчитается").not.toMatch(
      /catch\s*\([^)]*\)\s*\{[\s\S]*\bthrow\b/,
    );
  });
});
