/**
 * Куда ведёт короткий адрес канала — та страница ОБЯЗАНА читать метку.
 *
 * ЗАЧЕМ. Короткий адрес (`aevion.app/habr`, `aevion.app/ads-multichat`) только
 * перенаправляет и доносит `?c=<метка>`. Дальше метку должен кто-то прочитать:
 * `channelNow()` берёт её из адреса и кладёт КОРОТКУЮ метку в память вкладки, а
 * оттуда её забирают касса и форма подписки. Зовёт `channelNow` только тот, кто
 * шлёт событие, то есть `PageTracking`; глобального вызова нет (проверено в
 * ClientProviders). Значит страница без него не запоминает НИЧЕГО.
 *
 * Дефект, ради которого сторож написан, нашёлся замером 28.09.2026 по всем
 * 18 коротким входам: 11 ведут на `/go`, 4 на `/devhub`, 4 на `/en/devhub` —
 * все читают. И ровно ОДИН адрес назначения не читал вовсе: `/multichat-engine`,
 * куда ведут `/x-multichat` и `/ads-multichat`, то есть в том числе ПЛАТНАЯ
 * кампания. Переход оплачен, а в отчёте он «unattributed».
 *
 * Почему это не видно ничем другим: ссылка работает, страница открывается, 404
 * нет. Теряется только происхождение — и узнать об этом можно лишь тогда, когда
 * спросишь «какой канал дал продажу» и не получишь ответа. Ровно так уже
 * потеряли 37 постов с `?c=post`.
 *
 * Сторож смотрит на СВЯЗЬ между двумя файлами, а не на один: завести метку,
 * завести вход и забыть про страницу назначения — три разных действия, и
 * забывается всегда третье.
 *
 * ГРАНИЦА, названная честно. Сторож отвечает на вопрос «читает ли страница
 * метку ВООБЩЕ» — то есть ловит полное отсутствие механизма, а это и был
 * настоящий дефект. Он НЕ проверяет, что механизм отработал на конкретном
 * пути: у `/go` их два сразу (`PageTracking` и `channelFrom`), и убрать один
 * из двух — не поломка, страница продолжает читать метку вторым. Мутация,
 * снимающая один механизм из двух, здесь законно проходит; мутация, снимающая
 * единственный, — ловится (проверено на `/multichat-engine`).
 */
import { describe, it, expect } from "vitest";
import { existsSync, readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const APP = join(process.cwd(), "src/app");

/** Достаёт `<цель>?c=<метка>` из строки вида redirect("/devhub?c=habr"). */
function целиПеренаправлений(): Array<{ вход: string; цель: string }> {
  const найдено: Array<{ вход: string; цель: string }> = [];
  const обход = (dir: string, префикс: string) => {
    for (const имя of readdirSync(dir, { withFileTypes: true })) {
      if (!имя.isDirectory()) continue;
      if (имя.name.startsWith("[") || имя.name.startsWith("_")) continue;
      const путь = join(dir, имя.name);
      const страница = join(путь, "page.tsx");
      if (existsSync(страница)) {
        const код = readFileSync(страница, "utf8");
        const МЕТКА = 'redirect("';
        let i = код.indexOf(МЕТКА);
        while (i >= 0) {
          const конец = код.indexOf('"', i + МЕТКА.length);
          const адрес = код.slice(i + МЕТКА.length, конец);
          if (адрес.includes("?c=")) {
            найдено.push({ вход: префикс + "/" + имя.name, цель: адрес.split("?")[0] });
          }
          i = код.indexOf(МЕТКА, конец);
        }
      }
      обход(путь, префикс + "/" + имя.name);
    }
  };
  обход(APP, "");
  return найдено;
}

/**
 * Комментарии прочь ПЕРЕД проверкой.
 *
 * Первая редакция сторожа мутацию не поймала, и причина поучительнее самой
 * находки: в комментарии рядом с правкой я объяснил, что метку читает
 * `channelNow()`. Сторож искал это слово в ИСХОДНИКЕ — и находил его в моём же
 * объяснении. Убери из файла рабочую строку, оставь рассказ о ней — проверка
 * остаётся зелёной. Текст О вещи неотличим от вещи, если смотреть грепом.
 */
function безКомментариев(код: string): string {
  const части = код.split("/*");
  const безБлочных = части
    .map((часть, i) => (i === 0 ? часть : часть.slice(часть.indexOf("*/") + 2)))
    .join("");
  return безБлочных
    .split(String.fromCharCode(10))
    .filter((строка) => !строка.trim().startsWith("//"))
    .join(String.fromCharCode(10));
}

/** Страница читает метку, если шлёт событие (PageTracking) или разбирает сама. */
function читаетМетку(цель: string): { есть: boolean; чем: string } {
  const файл = join(APP, цель.replace(/^\//, ""), "page.tsx");
  if (!existsSync(файл)) return { есть: false, чем: "страницы нет вовсе" };
  const код = безКомментариев(readFileSync(файл, "utf8"));
  if (код.includes("<PageTracking")) return { есть: true, чем: "PageTracking" };
  if (код.includes("channelNow(")) return { есть: true, чем: "channelNow" };
  if (код.includes("channelFrom(")) return { есть: true, чем: "channelFrom" };
  return { есть: false, чем: "ничем" };
}

describe("адреса назначения коротких входов читают метку канала", () => {
  const пары = целиПеренаправлений();

  it("входы вообще найдены", () => {
    // Знаменатель: без него пустой список дал бы зелёное «все читают».
    expect(пары.length, "коротких входов не найдено — сторож проверял пустоту").toBeGreaterThan(10);
  });

  it("ни один вход не ведёт туда, где метку никто не читает", () => {
    const глухие = пары
      .map((p) => ({ ...p, ...читаетМетку(p.цель) }))
      .filter((p) => !p.есть);
    expect(
      глухие.map((p) => `${p.вход} -> ${p.цель} (${p.чем})`),
      "ссылка сработает, человек придёт, но канал не запишется — и узнать это нельзя ничем",
    ).toEqual([]);
  });

  it("отрицательный контроль: несуществующая цель считается глухой", () => {
    // Иначе первая проверка была бы зелёной и у сломанного определителя.
    expect(читаетМетку("/такой-страницы-нет").есть).toBe(false);
  });
});
