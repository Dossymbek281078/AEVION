describe("кнопка покупки не обещает недоезжающую сумму", () => {
  afterEach(() => { cleanup(); vi.unstubAllGlobals(); });

  it("ЗНАМЕНАТЕЛЬ: все вызовы покупки найдены и ни один не несёт мест или промокода", () => {
    const вызовы = вызовыПокупки();
    process.stderr.write(`[сторож] вызовов startCheckout: ${вызовы.length}` + ПЕРЕВОД);
    // Ноль найденных означал бы, что разбор перестал понимать код, а сторож зеленеет.
    expect(вызовы.length, "разбор не нашёл ни одного вызова покупки — сторож ослеп").toBeGreaterThanOrEqual(4);
    /*
     * Разбор СТРОКАМИ, без регулярок. Первая версия была /seats:\s*(?!1)/ — и ``
     * доехал сюда БАЙТОМ BACKSPACE: lookahead требовал «1» перед невидимым символом,
     * никогда не совпадал, и сторож краснел на исправном коде (все четыре вызова
     * «передают места»). Нашлось через cat -A. Это наш записанный класс, и в тестах он
     * особенно коварен: образец выглядит правильным в любом выводе.
     */
    const значениеМест = (вызов: string): string | null => {
      const плоский = вызов.split(/\s+/).join(" ");
      const где = плоский.indexOf("seats:");
      if (где < 0) return null;
      const хвост = плоский.slice(где + "seats:".length).trim();
      const конец = Math.min(
        ...[",", "}", ")"].map((з) => (хвост.indexOf(з) < 0 ? хвост.length : хвост.indexOf(з))),
      );
      return хвост.slice(0, конец).trim();
    };
    const сМестами = вызовы.filter((в) => {
      const з = значениеМест(в);
      return з !== null && з !== "1";
    });
    const сПромо = вызовы.filter((в) => в.includes("promoCode"));
    expect(
      сМестами,
      "вызов покупки передаёт места не равные одному, а сумма до кассы не доводится",
    ).toEqual([]);
    expect(сПромо, "вызов покупки передаёт промокод, а сумма до кассы не доводится").toEqual([]);
  });

  it("условия показа: кнопка только при одном месте без промокода, иначе ссылка на счёт", () => {
    /*
     * ⚠️ ЧТО ЭТА ПРОВЕРКА НЕ ДЕЛАЕТ, И ЭТО НАЗВАНО ВСЛУХ. Я пытался проверить
     * ОТРИСОВКОЙ: выставить в поле мест 3 и убедиться, что вместо кнопки появилась
     * ссылка. В jsdom контролируемое number-поле не принимает значение — после
     * fireEvent.change (и даже после нативного сеттера плюс input/change) диагностика
     * показывала в поле единицу, то есть состояние не менялось, и проверка краснела на
     * ИСПРАВНОМ коде. Тратить на обход этого больше времени, чем стоит сама проверка,
     * я не стал.
     *
     * Поэтому здесь утверждаются САМИ УСЛОВИЯ показа — то, из чего вёрстка следует
     * однозначно. Чего это не доказывает: что человек действительно видит строку на
     * экране. Это проверяется живым браузером при приёмке, и я прошу об этом отдельно.
     *
     * Контроль обеих сторон ниже обязателен: без него «условие есть» прошло бы и на
     * коде, где кнопка показывается ВСЕГДА.
     */
    const плоский = ИСХОДНИК.split(/\s+/).join(" ");
    expect(
      плоский.includes('calcTier !== "enterprise" && (calcSeats > 1 || calcPromo) && ('),
      "нет условия показа ссылки на счёт при местах > 1 или промокоде",
    ).toBe(true);
    expect(
      плоский.includes('calcTier !== "enterprise" && calcSeats <= 1 && !calcPromo && ('),
      "кнопка покупки не ограничена одним местом без промокода",
    ).toBe(true);
    expect(
      плоский.includes("topic=seats-invoice"),
      "ссылка ведёт не на оформление счётом — человеку некуда написать",
    ).toBe(true);
  });
});
