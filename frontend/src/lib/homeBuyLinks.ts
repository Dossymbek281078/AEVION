import { PRICING_TERMS, productById, withChannel } from "./products";
import { PLANET_BASE_MONTHLY, fromPricePerMonth } from "./termPricing";

export type ПокупкаНаГлавной = {
  вид: string;
  название: string;
  цена: string;
  href: string;
  /** Ведёт ли ссылка НАРУЖУ, в кассу продавца. У внешних клик обязан уходить
   *  в воронку через `BuyLink` (sendBeacon), иначе мы не узнаем, кликал ли
   *  кто-нибудь вообще: покупка видна только по вебхуку кассы, а «никто не
   *  нажал» и «нажали, но не купили» — это два РАЗНЫХ диагноза и два разных
   *  следующих шага. Внутренние ссылки события не шлют: у них checkout_start
   *  уйдёт на странице цен, при настоящем начале оплаты. */
  внешняя: boolean;
  /** Для события воронки: что именно и почём. */
  id?: string;
  ценаUsd?: number;
};

/**
 * Что можно купить прямо сейчас — для первого экрана главной.
 *
 * 🔴 ЗАЧЕМ. Замер 22.09.2026: главная написана для ИНВЕСТОРА — «$340B
 * addressable market», «≈$28.75M modelled ARR», кнопка «Investor pitch».
 * Слово «Купить» встречалось на странице НОЛЬ раз, цен товаров не было ни
 * одной. Человек, пришедший с ролика про книгу, попадал на страницу про объём
 * рынка. При этом на сайт за сутки заходят единицы — и каждый уходил, не
 * увидев ни одного предложения купить.
 *
 * ЦЕНЫ ИЗ КАТАЛОГА, не переписаны числами: иначе главная разойдётся с кассой
 * при первой же правке цены, и мы пообещаем одно, а возьмём другое. Ссылки
 * помечаются каналом, поэтому покупка свяжется с источником перехода.
 *
 * Порядок намеренный: первой стоит книга за $9.99 — единственный товар,
 * который у нас когда-либо покупали (2 покупки, $19.98 за всё время).
 *
 * 🔴 ПОДПИСИ ПО-АНГЛИЙСКИ, и это не вкусовщина. Замер живой главной 22.09.2026:
 * 40 кириллических слов против 432 латинских, то есть страница на 92 % английская
 * («New planet QVenture — AI Investment Analyst…»). Отдельной /en главной НЕ
 * существует — этот же файл обслуживает оба языка. Русский блок на английской
 * странице выглядит поломкой, а поломка на ПЕРВОМ экране стоит покупателя.
 * Заголовки товаров тоже свои, а не из каталога: там они смешанные.
 */
export function покупкиНаГлавной(канал: string | null): ПокупкаНаГлавной[] {
  const из: ПокупкаНаГлавной[] = [];
  const книга = productById("orcfbo");
  const протокол = productById("oijxmq");
  if (книга) {
    из.push({
      вид: "book · PDF + EPUB",
      // 🔴 Имя — КАК В КАССЕ, а не как удобнее витрине. Проверено браузером
      // 22.09: чекаут Gumroad называет товар «Gratitude ∞ Forever Young —
      // Book (PDF + EPUB)». Берём общее ядро, чтобы человек узнал товар на
      // странице оплаты. Из каталога взять нельзя: там смешанное
      // «Gratitude ∞ Forever Young — книга».
      название: "Gratitude ∞ Forever Young",
      цена: "$" + книга.priceUsd,
      href: withChannel(книга.href, канал, "home"),
      внешняя: true,
      id: книга.id,
      ценаUsd: книга.priceUsd,
    });
  }
  if (протокол) {
    из.push({
      вид: "PDF · 9 pages",
      // 🔴 По-русски, и это НЕ недосмотр. Проверено браузером 22.09: в кассе
      // Gumroad товар называется «Протокол долголетия AEVION — 12 недель».
      // Английская подпись на витрине привела бы человека на страницу оплаты
      // с ДРУГИМ названием — ровно тот разрыв доверия, из-за которого выше
      // стоит translate="no". Имя товара принадлежит товару, а не странице;
      // переводятся вид карточки и цена, а не оно.
      название: "Протокол долголетия AEVION — 12 недель",
      цена: "$" + протокол.priceUsd,
      href: withChannel(протокол.href, канал, "home"),
      внешняя: true,
      id: протокол.id,
      ценаUsd: протокол.priceUsd,
    });
  }
  из.push({
    вид: "subscription · all modules",
    название: "Every AEVION module",
    цена: "from $" + fromPricePerMonth(PLANET_BASE_MONTHLY) + "/mo",
    // Адрес берём КОНСТАНТОЙ каталога, а не строкой: якорь `#tiers` живёт
    // в products.ts, и переименуй его там — главная молча вела бы на верх
    // страницы цен, то есть мимо лестницы сроков, ради которой ссылка и есть.
    href: withChannel(PRICING_TERMS, канал, "home"),
    внешняя: false,
  });
  return из;
}
