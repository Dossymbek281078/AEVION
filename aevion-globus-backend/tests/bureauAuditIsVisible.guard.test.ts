import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Пропажа записи в журнал действий бюро не имеет права быть молчаливой.
 *
 * `logBureauAudit` пишет в `BureauAuditLog`: кто выдал сертификат, кто проверил,
 * кто отозвал. Отказ записи проглатывался `.catch(() => {})`.
 *
 * Почему это серьёзнее обычного журнала: продукт бюро — ДОКАЗУЕМОЕ авторство.
 * Молча пропавшая запись означает, что доказать потом будет нечем, и снаружи
 * это неотличимо от того, что действия не было вовсе.
 *
 * Ронять действие нельзя: отказ журнала не должен отменять уже совершённую
 * выдачу или отзыв. Поэтому отказ остался не смертельным и стал видимым.
 *
 * РАЗБОР ВСЕГО ФАЙЛА, чтобы следующий не проходил его заново. В `bureau.ts`
 * было четыре проглатывания:
 *
 *   2 — ROLLBACK транзакции. ДОПУСТИМО: уборка, её провал не должен
 *       маскировать исходную ошибку.
 *   1 — счётчик обращений к сертификату (`BureauCertFetchSource`). Оставлен
 *       молчаливым ОСОЗНАННО: таблица пишется и НИКЕМ не читается — ни
 *       бэкендом, ни страницами бюро. Потеря приращения сегодня не стоит
 *       ничего. Отдельный вопрос, зачем она вообще пишется.
 *   1 — журнал действий. ДЕФЕКТ, починен здесь.
 *
 * Сторож по исходнику: поведенческий путь потребовал бы живой базы, которая
 * принимает остальные запросы и отказывает на вставке в одну таблицу.
 */

const FILE = path.join(__dirname, "..", "src", "routes", "bureau.ts");

function code(): string {
  return fs
    .readFileSync(FILE, "utf8")
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .split("\n")
    .filter((l) => !l.trim().startsWith("//"))
    .join("\n");
}

describe("журнал действий бюро не теряется молча", () => {
  test("прибор работает: файл читается и журнал в нём есть", () => {
    const c = code();
    expect(c.length).toBeGreaterThan(2000);
    expect(c).toContain("BureauAuditLog");
  });

  test("отказ записи назван — с действием, сертификатом и автором", () => {
    const c = code();
    expect(c).toContain("ЗАПИСЬ В ЖУРНАЛ НЕ ПРОШЛА");
    // Без этих трёх сведений запись потом не восстановить и не приписать.
    expect(c).toMatch(/ЗАПИСЬ В ЖУРНАЛ НЕ ПРОШЛА[^`]*\$\{opts\.action\}/);
    expect(c).toMatch(/ЗАПИСЬ В ЖУРНАЛ НЕ ПРОШЛА[^`]*opts\.certId/);
    expect(c).toMatch(/ЗАПИСЬ В ЖУРНАЛ НЕ ПРОШЛА[^`]*opts\.actor/);
  });

  test("отказ уходит и в Sentry", () => {
    expect(code()).toMatch(/captureException\(e, \{\s*route: "bureau\/logBureauAudit"/);
  });

  test("молчаливыми остались ровно три, и это откаты и счётчик обращений", () => {
    const silent = [...code().matchAll(/\.catch\(\(\) => \{\}\)/g)];
    expect(
      silent.length,
      "в бюро снова стало больше молчаливых проглатываний, чем разобрано",
    ).toBe(3);
    const rollbacks = [...code().matchAll(/"ROLLBACK"\)\.catch\(\(\) => \{\}\)/g)];
    expect(rollbacks.length, "откатов должно остаться два").toBe(2);
  });

  test("направление: журнал НЕ роняет действие", () => {
    // Отказ журнала не должен отменять выдачу или отзыв сертификата.
    const c = code();
    const i = c.indexOf("ЗАПИСЬ В ЖУРНАЛ НЕ ПРОШЛА");
    const around = c.slice(Math.max(0, i - 400), i + 600);
    expect(around).not.toMatch(/throw\s/);
  });
});
