import { describe, test, expect } from "vitest";

import { padProhibition } from "./padPermission";

/**
 * Замер 12.08.2026 на живом движке: у Астаны зона UAP28 накрывает 100% твина
 * круглосуточно, а панель площадок показывала «H-1 · кандидат на площадку · 78»
 * и ни слова о запрете — он стоял в другой карточке страницы (легенда карты при
 * этом подписывала тот же класс сильнее: «годна»). У Нью-Йорка ограничение
 * ячейки в строке было («нужна координация с УВД»), то есть правило в модуле
 * уже есть, просто до самого жёсткого случая не доходило.
 */
describe("метка запрета на строке площадки", () => {
  /**
   * Объект — не выдуманный: снят с живого движка
   * `GET /api/qskyway/city?city=astana` → `airspace.permission` (12.08.2026).
   * Придуманная мной первая версия ставила в подсказку `basis`, и тест был
   * зелёным — пока не выяснилось, что на реальных данных там лежит способ
   * получения («ingested»), а не правило.
   */
  const astana = {
    available: true,
    authority: "Казаэронавигация / AIP KZ",
    kind: "prohibition" as const,
    regime: "Запретная зона UAP28: полёты запрещены от земли до 4800 ft, круглосуточно",
    source: "AIP Kazakhstan ENR 5.1 — запретная зона UAP28",
    basis: "ingested",
    coveragePct: 100,
  };

  test("сплошной запрет города попадает на каждую площадку", () => {
    const r = padProhibition(astana);
    expect(r).not.toBeNull();
    expect(r!.authority).toBe("Казаэронавигация / AIP KZ");
    // В подсказке — что именно запрещено, а не как данные получены.
    expect(r!.rule).toContain("полёты запрещены");
    expect(r!.rule).not.toBe("ingested");
  });

  test("режим разрешений запретом не объявляется", () => {
    // «Нужно разрешение» и «запрещено» — разные ответы регулятора. Токио:
    // полёт над плотным районом требует разрешения министра, но не запрещён.
    expect(padProhibition({ ...astana, kind: "permission" })).toBeNull();
  });

  test("частичный охват не даёт утверждения по строке", () => {
    // Метка стоит на КАЖДОЙ площадке, значит и верна должна быть для каждой.
    // При 60% часть площадок вне зоны, а какие именно — вопрос геометрии,
    // которой у панели нет.
    expect(padProhibition({ ...astana, coveragePct: 60 })).toBeNull();
    // Отсутствие цифры охвата — тоже не основание.
    expect(padProhibition({ ...astana, coveragePct: undefined })).toBeNull();
  });

  test("подсказка запрета говорит на языке посетителя", () => {
    // ПОВОД (01.09.2026). Английское правило лежало в данных давно, и
    // основной текст карточки его брал (`regimeEn ?? regime`). А подсказка
    // строки шла мимо: `rule` всегда был русским, и англоязычный посетитель
    // видел «Запретная зона UAP28…» в модуле, который сам же и проверяет,
    // не выдаёт ли кто чужие данные за свои.
    //
    // Почему не нашлось раньше: сторож языка сравнивает видимый текст, а
    // подсказка живёт в атрибуте `title` и попадает на экран только при
    // наведении. Граница охвата, а не дефект сторожа.
    const en = "Prohibited area UAP28: flights banned from ground to 450 m";
    const both = padProhibition({ ...astana, regimeEn: en });

    expect(both?.rule).toContain("UAP28");
    expect(both?.rule).toContain("Запретная");
    expect(both?.ruleEn).toBe(en);
    // Русская половина не потерялась, пока чинили английскую.
    expect(both?.ruleEn).not.toContain("Запретная");
  });

  test("без английской версии подсказка говорит по-русски, а не молчит", () => {
    // Пустая строка означала бы «запрета нет» — а он есть. Сказать
    // по-русски хуже, чем по-английски, но несравнимо лучше, чем скрыть
    // запрет от того, кто по нему летит.
    const only = padProhibition(astana);
    expect(only?.ruleEn.length ?? 0).toBeGreaterThan(10);
    expect(only?.ruleEn).toBe(only?.rule);
  });

  test("город без опубликованного режима молчит", () => {
    expect(padProhibition({ available: false })).toBeNull();
    expect(padProhibition(null)).toBeNull();
    expect(padProhibition(undefined)).toBeNull();
  });
});
