import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * LifeBox обязан сказать, что капсула НЕ сохранена всерьёз.
 *
 * Замер 19.08.2026: ответ на создание капсулы был ОДИНАКОВ независимо от того,
 * легла она в Postgres или в массив в памяти процесса:
 *
 *   const capsule = isLifeBoxDbReady() ? await dbInsert(fields) : memInsert(fields);
 *   res.status(201).json({ ok: true, capsule: publicView(capsule) });
 *
 * Человек видел ok:true и запертую капсулу с датой открытия. При следующем
 * перезапуске — а выкаток бывает шесть в день — она исчезала. Узнать об этом
 * было неоткуда.
 *
 * Цена ошибки здесь выше, чем в других модулях с тем же устройством: LifeBox
 * называется «сейф для себя будущего», продаётся за $9/мес и обещает сохранить
 * послание на годы. Молча потерять его — не сбой, а обман того самого обещания,
 * ради которого модуль купили.
 *
 * Проверяем ИСХОДНИК, а не поведение: запустить модуль с упавшей базой в тесте
 * дороже, чем удержать инвариант в коде, а класс дефекта именно в том, что две
 * ветки возвращают неразличимое.
 */

const SRC = readFileSync(join(__dirname, "..", "src", "routes", "lifebox.ts"), "utf8");

describe("LifeBox не выдаёт временное хранилище за сейф", () => {
  test("контроль: исходник прочитан и содержит обе ветки", () => {
    // Иначе проверки ниже искали бы в пустоте и были бы зелёными всегда.
    expect(SRC.length).toBeGreaterThan(1000);
    expect(SRC, "ветка записи в базу исчезла").toContain("dbInsert(fields)");
    expect(SRC, "ветка записи в память исчезла").toContain("memInsert(fields)");
  });

  test("ответ на создание называет хранилище", () => {
    expect(
      SRC,
      "ответ снова не различает базу и память — человек не узнает, что капсула временная",
    ).toMatch(/storage:\s*persisted\s*\?\s*"db"\s*:\s*"memory"/);
  });

  test("при памяти человек получает предупреждение словами", () => {
    expect(
      SRC,
      "машиночитаемого признака мало: интерфейс может его не читать, а капсулу теряет человек",
    ).toMatch(/warning:/);
    expect(SRC, "предупреждение не говорит о потере при перезапуске").toMatch(/перезапуск/);
  });

  test("признак вычисляется ДО записи, а не угадывается после", () => {
    // Если бы persisted считали после вставки, ветка памяти могла бы вернуть
    // «db» на восстановившейся базе — и снова соврать, только реже.
    const iFlag = SRC.indexOf("const persisted = isLifeBoxDbReady()");
    const iWrite = SRC.indexOf("? await dbInsert(fields)");
    expect(iFlag, "флаг хранилища не найден").toBeGreaterThan(0);
    expect(iFlag).toBeLessThan(iWrite);
  });
});
