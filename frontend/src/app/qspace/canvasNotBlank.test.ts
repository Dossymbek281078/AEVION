import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import path from "node:path";

/**
 * Пока модель строится, область холста обязана ГОВОРИТЬ, а не быть пустой.
 *
 * Замер 13.09.2026, 390x844, эмуляция медленного 4G:
 *
 *     DOM готов                 1784 мс
 *     первый кадр модели        4721 мс
 *     между ними область холста ПУСТА: ни canvas, ни строки текста
 *
 * Почти три секунды человек смотрит на пустую рамку, которая занимает 94 %
 * первого экрана телефона. Пустота неотличима от поломки: на сломанной
 * странице видно ровно то же самое, поэтому ждать её не станут. На десктопе
 * окно вдвое короче (370 мс и 1047 мс), и там дефект почти не виден — это и
 * есть причина, по которой он дожил до сегодня.
 *
 * Сторож проверяет три вещи, и все три нужны по отдельности:
 *   1) состояние «сцена ещё строится» существует;
 *   2) оно СБРАСЫВАЕТСЯ, когда сцена построена (иначе подпись висит вечно);
 *   3) пока оно не сброшено, в области холста есть ТЕКСТ.
 *
 * Комментарии вырезаются: этот файл сам цитирует имена состояний, и без
 * вырезания сторож зеленел бы от собственных объяснений в соседнем файле.
 */
const КЛИЕНТ = readFileSync(path.join(__dirname, "_client.tsx"), "utf8")
  .split(/\r?\n/)
  .filter((строка) => !/^\s*\/\//.test(строка))
  .join(String.fromCharCode(10));

describe("область холста не пустует, пока строится модель", () => {
  it("состояние «сцена строится» заведено и начинается с НЕготовности", () => {
    expect(КЛИЕНТ).toMatch(/const \[сценаГотова, setСценаГотова\] = useState\(false\)/);
  });

  it("состояние сбрасывается после сборки сцены, а не висит вечно", () => {
    const объявление = КЛИЕНТ.indexOf("three.current = {");
    const сброс = КЛИЕНТ.indexOf("setСценаГотова(true)");
    expect(объявление, "сцена больше не собирается здесь — сторож устарел").toBeGreaterThan(-1);
    expect(сброс, "подпись «строю модель» не снимается никогда").toBeGreaterThan(-1);
    expect(сброс).toBeGreaterThan(объявление);
  });

  it("пока не готово — в области холста есть текст, а не пустота", () => {
    const i = КЛИЕНТ.indexOf("{!сценаГотова && (");
    expect(i, "заглушка исчезла: область холста снова пустует").toBeGreaterThan(-1);
    // Смотреть надо ТЕКСТ ВНУТРИ тега, а не окно вокруг блока. Первая
    // редакция брала срез в 220 знаков и искала в нём кириллицу — а в срез
    // попадает имя состояния «сценаГотова», само кириллическое. Проверка
    // совпадала с ним ВСЕГДА и была зелёной даже на пустом <p></p>.
    // Поймано мутацией; пятый случай за день, когда мой же текст ослепляет
    // мой же сторож.
    const кусок = КЛИЕНТ.slice(i, i + 260);
    const внутри = кусок.match(/<p[^>]*>([^<]*)<\/p>/);
    expect(внутри, "в области холста нет <p> с подписью").not.toBeNull();
    expect(
      (внутри![1] || "").trim(),
      "заглушка есть, но ничего не говорит: пустая рамка неотличима от поломки",
    ).toMatch(/[А-ЯЁа-яё]{4,}/);
  });
});
