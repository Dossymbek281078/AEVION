import { describe, it, expect } from "vitest";
import { readFileSync } from "fs";
import { join } from "path";
import { SUPPORTED_LOCALES, tFor } from "../i18n";
import { blokSlovarya } from "./_slovar";

/**
 * Названия уровней ИИ переведены на все языки, и ни одно не разваливает строку.
 *
 * Повод. До 05.10.2026 семь мест вывода тянули поле `ru` из таблицы ALS
 * напрямую, и на казахском экране уровень оставался русским. Пропуск перевода
 * не падает — он выглядит как обычная подпись, просто не на том языке.
 *
 * Вторая половина — длина. Уровень печатается в одной строке с рейтингом
 * (`{имя} · {elo}`) и этот контейнер стоит с whiteSpace:"nowrap". Буквальный
 * перевод «Новичка» на казахский — «Жаңадан бастаушы», 16 знаков: строка
 * вылезет за край, и ошибку увидит только тот, кто откроет страницу на
 * казахском. Такое у нас уже было в нижней навигации в тот же день.
 *
 * Знаменатель берётся из САМОЙ таблицы уровней, а не переписывается сюда
 * списком: добавят восьмой уровень без перевода — сторож покраснеет сам.
 */

const ИСХОДНИК = () => readFileSync(join(process.cwd(), "src/app/cyberchess/page.tsx"), "utf8");

/** Имена уровней из таблицы ALS — то, из чего строится ключ словаря. */
function urovniIzTablicy(): string[] {
  const s = ИСХОДНИК();
  const i = s.indexOf("const ALS: AL[] = [");
  expect(i, "таблица уровней ALS не найдена — сторож смотрит не туда").toBeGreaterThan(0);
  const конец = s.indexOf("\n];", i);
  expect(конец, "конец таблицы ALS не найден").toBeGreaterThan(i);
  const тело = s.slice(i, конец);
  return [...тело.matchAll(/name:"([^"]+)"/g)].map((m) => m[1]);
}

describe("уровни ИИ переведены на каждый язык", () => {
  it("у каждого уровня есть имя во всех языках", () => {
    const уровни = urovniIzTablicy();
    // Контроль охвата: уровней было семь. Стало меньше — проверка ослепла.
    expect(уровни.length, `уровней в таблице: ${уровни.length}`).toBeGreaterThanOrEqual(7);

    // 🔴 Спрашивать tFor БЕСПОЛЕЗНО: при пропуске ключа он отдаёт РУССКОЕ
    // значение, а не ключ (`DICTIONARY[locale]?.[key] ?? DICTIONARY.ru[key] ?? key`).
    // Первая версия этой проверки именно так и делала — и мутация «убрать
    // казахский ключ» прошла мимо неё. Поэтому смотрим в САМ словарь: ключ
    // обязан лежать в блоке своего языка.
    const пропуски: string[] = [];
    let проверено = 0;
    for (const { code } of SUPPORTED_LOCALES) {
      const блок = blokSlovarya(code);
      for (const имя of уровни) {
        const ключ = "ai." + имя.toLowerCase();
        проверено++;
        if (!блок.includes(`"${ключ}":`)) пропуски.push(`${code}/${ключ}`);
      }
    }
    expect(
      пропуски,
      `проверено ${проверено} пар (уровень × язык); без перевода: ${пропуски.join(", ")}`
    ).toEqual([]);
  });

  it("имя уровня не разваливает строку «имя · рейтинг»", () => {
    // Строка стоит с nowrap: слишком длинное имя не переносится, оно вылезает.
    const ПРЕДЕЛ = 13;
    const уровни = urovniIzTablicy();
    const длинные: string[] = [];
    for (const { code } of SUPPORTED_LOCALES) {
      for (const имя of уровни) {
        const текст = tFor(code, "ai." + имя.toLowerCase());
        if (текст.length > ПРЕДЕЛ) длинные.push(`${code}/${имя} = «${текст}» (${текст.length})`);
      }
    }
    expect(
      длинные,
      `предел ${ПРЕДЕЛ} знаков; не помещаются: ${длинные.join(", ")}`
    ).toEqual([]);
  });

  it("вывод идёт через словарь, а не через поле ru напрямую", () => {
    // Поле `ru` остаётся как ЗАПАС на случай пропавшего ключа — но подписи
    // на экране обязаны идти через помощника, иначе язык снова застрянет.
    const s = ИСХОДНИК();
    expect(s, "помощник имени уровня пропал").toContain("const imyaUrovnya=useCallback");
    // Прямые обращения допустимы только там, где текст и так целиком русский
    // (сводка партии) или это формат обмена (PGN). В разметке их быть не должно.
    const вРазметке = [...s.matchAll(/\}\}>\{(?:lv|al)\.ru\}/g)].length;
    expect(вРазметке, "имя уровня снова берут из поля ru прямо в разметке").toBe(0);
  });
});
