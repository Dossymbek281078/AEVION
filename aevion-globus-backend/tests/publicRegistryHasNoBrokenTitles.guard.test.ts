import { describe, test, expect } from "vitest";
import { этоНашаПроба, нечитаемыйЗаголовок, ПРОБЫ_БЕЗ_МЕТКИ } from "../src/lib/publicRegistryProbes";

/**
 * Сторож: в публичном реестре нет заголовков с ПОТЕРЯННОЙ КОДИРОВКОЙ.
 *
 * 🔴 Замер прода 05.10.2026 браузером: на /bureau один из двух сертификатов показывал
 * вместо названия «��������». В данных лежат байты EF BF BD (U+FFFD, символ замены) —
 * восемь, пробел, пять: кириллица потерялась ДО записи, ответ ручки при этом корректный
 * UTF-8. Выводом такое не лечится.
 *
 * Для писем лабораториям это особенно дорого: реестр из двух записей, и одна выглядит
 * сломанной — доказательство авторства, которое мы продаём, подрывается собственной
 * витриной.
 *
 * Данные НЕ удаляем (порча необратима, след прогона нужен) — запись скрыта явным
 * списком `ПРОБЫ_БЕЗ_МЕТКИ`. Этот сторож держит ДВА утверждения: конкретная запись
 * скрыта, и ЛЮБАЯ запись с символом замены в заголовке считается нашей пробой, то есть
 * не покажется посетителю.
 */

const СИМВОЛ_ЗАМЕНЫ = "�";

describe("публичный реестр и битые заголовки", () => {
  test("конкретная запись с 05.10 скрыта", () => {
    expect(
      ПРОБЫ_БЕЗ_МЕТКИ.has("cert-47273244bb7dc5ef"),
      "запись с потерянной кодировкой вернулась в публичный список",
    ).toBe(true);
    expect(
      этоНашаПроба({ id: "cert-47273244bb7dc5ef", title: `${СИМВОЛ_ЗАМЕНЫ.repeat(8)} ${СИМВОЛ_ЗАМЕНЫ.repeat(5)}` }),
      "фильтр не признал её нашей",
    ).toBe(true);
  });

  test("ЛЮБОЙ заголовок с символом замены не попадает в публичный список", () => {
    // Правило, а не одна строка: такие записи будут появляться, пока кто-то пишет
    // кириллицу скриптом из консоли Windows (наш записанный класс).
    for (const заголовок of [
      `${СИМВОЛ_ЗАМЕНЫ}`,
      `Патент ${СИМВОЛ_ЗАМЕНЫ}${СИМВОЛ_ЗАМЕНЫ}`,
      `${СИМВОЛ_ЗАМЕНЫ.repeat(13)}`,
    ]) {
      // Признак ОТДЕЛЬНЫЙ: «нечитаемо» это не утверждение о принадлежности.
      expect(
        нечитаемыйЗаголовок({ title: заголовок }),
        `заголовок «${заголовок}» показался бы посетителю`,
      ).toBe(true);
      expect(
        этоНашаПроба({ id: "cert-прочий", title: заголовок }),
        "нечитаемость не должна выдаваться за «нашу пробу»",
      ).toBe(false);
    }
  });

  test("КОНТРОЛЬ: нормальная кириллица остаётся видимой", () => {
    // Без этого контроля правка превратилась бы в «скрыть всё русское» — то есть
    // спрятала бы настоящие работы живых авторов.
    for (const заголовок of ["Патент на двигатель", "Музыкальный трек", "Моя книга"]) {
      expect(
        этоНашаПроба({ id: "cert-живой", title: заголовок, author: "Иван Петров" }),
        `живая работа «${заголовок}» была бы спрятана`,
      ).toBe(false);
      expect(
        нечитаемыйЗаголовок({ title: заголовок }),
        `живая работа «${заголовок}» названа нечитаемой`,
      ).toBe(false);
    }
  });

  test("КОНТРОЛЬ: прежние пробы по-прежнему скрыты, список не сократился", () => {
    // Знаменатель: список явных записей не должен молча уменьшиться.
    expect(ПРОБЫ_БЕЗ_МЕТКИ.size, "явный список проб сократился").toBeGreaterThanOrEqual(4);
    for (const id of ["cert-c597672d2aab5cd1", "cert-f7ac411b5a1929ad", "cert-54825970871a4eb6"]) {
      expect(ПРОБЫ_БЕЗ_МЕТКИ.has(id), `проба ${id} перестала быть скрытой`).toBe(true);
    }
  });
});
