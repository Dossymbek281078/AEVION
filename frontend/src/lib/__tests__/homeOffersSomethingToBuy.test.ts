import { describe, it, expect } from "vitest";
import { покупкиНаГлавной } from "@/lib/homeBuyLinks";
import { PRICING_TERMS, productById } from "@/lib/products";
import { PLANET_BASE_MONTHLY, fromPricePerMonth } from "@/lib/termPricing";

/**
 * 🔴 Главная обязана предлагать купить — и по ценам КАТАЛОГА.
 *
 * ЗАМЕР 22.09.2026: на главной слово «Купить» встречалось НОЛЬ раз, цен
 * товаров не было ни одной, зато были «$340B addressable market» и кнопка
 * «Investor pitch». Человек, пришедший с ролика про книгу, попадал на страницу
 * про объём рынка. На сайт за сутки заходят единицы — и каждый уходил, не
 * увидев ни одного предложения купить.
 *
 * Сторож проверяет не «блок есть», а два свойства, ради которых он заведён:
 * цена берётся из каталога и ссылка помечена каналом. Зашитая цена разошлась
 * бы с кассой при первой правке, а непомеченная ссылка потеряла бы источник
 * покупки — оба случая уже случались на этой платформе.
 */
describe("главная предлагает купить по ценам каталога", () => {
  it("прибор видит предмет: блок не пуст", () => {
    expect(покупкиНаГлавной(null).length).toBeGreaterThanOrEqual(3);
  });

  it("цена книги равна цене каталога, а не переписана числом", () => {
    const книга = productById("orcfbo");
    expect(книга).toBeTruthy();
    const блок = покупкиНаГлавной(null);
    expect(блок.some((п) => п.цена === "$" + книга!.priceUsd)).toBe(true);
  });

  it("цена подписки считается формулой, а не зашита", () => {
    const ожид = "от $" + fromPricePerMonth(PLANET_BASE_MONTHLY) + "/мес";
    expect(покупкиНаГлавной(null).some((п) => п.цена === ожид)).toBe(true);
  });

  it("ссылки помечаются каналом, когда он известен", () => {
    const с = покупкиНаГлавной("youtube");
    const внешние = с.filter((п) => п.href.startsWith("http"));
    expect(внешние.length).toBeGreaterThan(0);
    for (const п of внешние) expect(п.href).toContain("channel=youtube");
  });

  it("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: без канала ссылки не ломаются", () => {
    // withChannel возвращает адрес без изменений, когда канала нет. Если бы
    // здесь появился «channel=null», покупка ушла бы в несуществующий источник.
    for (const п of покупкиНаГлавной(null)) {
      expect(п.href).not.toContain("channel=null");
      expect(п.href).not.toContain("c=null");
      expect(п.href.length).toBeGreaterThan(3);
    }
  });

  it("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: первой идёт книга — единственный проданный товар", () => {
    // 2 покупки за всё время, $19.98. Ставить первым то, что уже покупали,
    // разумнее, чем то, что ни разу не купили.
    expect(покупкиНаГлавной(null)[0].href).toContain("orcfbo");
  });
  it("ссылка на подписку ведёт на ЯКОРЬ лестницы, а не на верх страницы цен", () => {
    // Якорь `#tiers` живёт константой в каталоге. Если его там переименуют,
    // главная молча повела бы человека на верх /pricing — мимо блока сроков,
    // ради которого ссылка и стоит. Проверяем по константе, а не по строке.
    const подписка = покупкиНаГлавной(null).find((п) => п.href.includes("/pricing"));
    expect(подписка).toBeDefined();
    expect(подписка!.href).toBe(PRICING_TERMS);
    // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ: якорь вообще не пустой — иначе проверка выше
    // была бы зелёной при любом адресе страницы цен.
    expect(PRICING_TERMS).toContain("#");
  });

  it("метка канала на внутренней ссылке стоит ДО якоря", () => {
    // `/pricing#tiers?c=yt` потерял бы метку целиком: всё после `#` браузер
    // считает якорем и серверу не отправляет. Это уже ловили на переходах
    // /longevity → /shop, и повторять не хотим.
    const подписка = покупкиНаГлавной("youtube").find((п) => п.href.includes("/pricing"));
    expect(подписка).toBeDefined();
    expect(подписка!.href).toContain("c=yt");
    expect(подписка!.href.indexOf("c=yt")).toBeLessThan(подписка!.href.indexOf("#"));
  });
  it("ни одна цена не печатается как $undefined или $NaN", () => {
    // Цены склеиваются строкой ("$" + p.priceUsd). Пропадёт поле у товара —
    // на ГЛАВНОЙ появится «$undefined», и это увидит каждый посетитель.
    // Класс дешёвый в починке и дорогой в последствии, поэтому закреплён.
    for (const п of покупкиНаГлавной(null)) {
      expect(п.цена).toMatch(/^(от )?\$\d[\d.,]*/);
      expect(п.цена).not.toMatch(/undefined|NaN|\$\s*$/);
      // Название и вид тоже видит человек: пустая карточка хуже отсутствующей.
      expect(п.название.trim().length).toBeGreaterThan(2);
      expect(п.вид.trim().length).toBeGreaterThan(2);
    }
  });
});
