import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Кнопка, за которой стоит внешний поставщик, спрашивает состояние ДО вызова.
 *
 * Механизм в модуле есть и продуман (isCapabilityBlocked + capabilityHint,
 * намеренно fail-open: незагруженная панель не должна гасить рабочую кнопку).
 * Но охват его никто не считал. Замер 08.09.2026: IDE звал шесть ручек
 * генерации, а состояние спрашивал у пяти — перевод шёл мимо. И ровно он в тот
 * день был degraded: у DeepL выжжена месячная квота. Человек узнавал об этом
 * после нажатия, общей фразой «Не удалось перевести», хотя причина была
 * известна заранее.
 *
 * ГРАНИЦА, названная явно. Ручки ОТПРАВКИ (почта, SMS, WhatsApp) сюда не
 * входят намеренно: у них отказ сервера «not configured» переводится границей
 * показа в человеческое «канал не подключён», то есть человек объяснение
 * получает — только после нажатия, а не до. Это осознанный размен, а не
 * недосмотр; если менять, то менять вместе с ними.
 */
const IDE = fs.readFileSync(path.resolve(__dirname, "..", "[id]", "page.tsx"), "utf8");

/** Ручка генерации → возможность, которой она живёт. */
const ГЕНЕРАЦИЯ: Record<string, string> = {
  image: "image",
  video: "video",
  "3d": "3d",
  tts: "audio_tts",
  music: "audio_music",
  translate: "translate",
};

function зовётРучку(имя: string): boolean {
  return IDE.includes(`api/devhub/media/${имя}`);
}
function спрашиваетСостояние(cap: string): boolean {
  return IDE.includes(`isCapabilityBlocked(caps, "${cap}")`);
}

describe("кнопки генерации спрашивают состояние до вызова", () => {
  test("прибор исправен: ручки в файле находятся", () => {
    // Без этого проверки ниже прошли бы на пустоте — «ручку не зовут, значит
    // и спрашивать нечего» выглядит как успех.
    const найдено = Object.keys(ГЕНЕРАЦИЯ).filter(зовётРучку);
    expect(найдено.length, `ручек генерации найдено ${найдено.length} из ${Object.keys(ГЕНЕРАЦИЯ).length}`).toBe(
      Object.keys(ГЕНЕРАЦИЯ).length,
    );
  });

  for (const [ручка, cap] of Object.entries(ГЕНЕРАЦИЯ)) {
    test(`${ручка}: состояние «${cap}» спрашивается`, () => {
      expect(зовётРучку(ручка), `ручка media/${ручка} больше не зовётся — обнови карту`).toBe(true);
      expect(
        спрашиваетСостояние(cap),
        `media/${ручка} вызывается без проверки «${cap}»: человек узнает об отказе только после нажатия`,
      ).toBe(true);
    });
  }

  test("подсказка берёт язык читателя, а не зашитую подпись", () => {
    // Пятнадцать вызовов передавали подпись русской строкой; подсказка живёт в
    // тосте, а его машинный доводчик не кроет по устройству.
    expect(IDE).toContain("capabilityHint(caps, \"translate\", uiLang)");
    expect(
      /capabilityHint\(caps, "[a-z0-9_]+", "/.test(IDE),
      "подпись снова передаётся строкой из места вызова",
    ).toBe(false);
  });
});
