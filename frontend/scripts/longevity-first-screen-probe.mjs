#!/usr/bin/env node
/*
 * Зонд: видна ли платная книга в ПЕРВОМ ЭКРАНЕ телефона на /longevity, и ведёт
 * ли якорь #kniga на её карточку.
 *
 * Почему зонд, а не тест. Требование звучит «цена и кнопка выше 600 px на
 * 390×700», то есть это про ОТРИСОВКУ. jsdom вёрстку не считает — все размеры
 * в нём нулевые, и тест, который «проверяет» пиксели в jsdom, проверяет ноль
 * против ноля. Сторож рядом (bookIsInFirstScreen.guard) честно берёт то, что
 * от вёрстки не зависит: порядок блоков, цену, кнопку, якорь. Пиксели мерит
 * этот зонд, на живой странице и руками после выкатки.
 *
 * Коды выхода: 0 — книга в первом экране и якорь работает, 1 — НЕТ,
 * 2 — спросить не удалось. Код 2 не означает ни «хорошо», ни «плохо».
 *
 * Запуск:
 *   node scripts/longevity-first-screen-probe.mjs [адрес]
 * Браузера здесь нет намеренно: зонд считает по РАЗМЕТКЕ ответа сервера, то
 * есть отвечает на вопрос «что приедет человеку», не завися от окна Chrome.
 * Границу называю прямо: порядок и наличие он видит, высоту в пикселях — нет;
 * высоту проверяют браузером по инструкции в выводе.
 */
const АДРЕС = process.argv[2] || "https://aevion.app/longevity?c=probe-first-screen";

/** Цена: знак и число могут лежать в разных тегах, между ними остаётся пробел. */
const ЦЕНА_КНИГИ = /[$][\s ]*9[.,]99/;
const ЦЕНА_ПАКЕТА = /[$][\s ]*29[.,]99/;

function видимыйТекст(html) {
  return html
    .replace(/<script[\s\S]*?<\/script>/gi, " ")
    .replace(/<style[\s\S]*?<\/style>/gi, " ")
    .replace(/<[^>]+>/g, " ")
    .replace(/\s+/g, " ");
}

/** Самоконтроль прибора до того, как верить его ответу (правило 2е). */
function приборИсправен() {
  const да = ЦЕНА_КНИГИ.test("книга $ 9.99 купить") && ЦЕНА_ПАКЕТА.test("пакет $29.99");
  const нет = ЦЕНА_КНИГИ.test("цен нет вовсе") || ЦЕНА_ПАКЕТА.test("$19 протокол");
  if (да && !нет) return true;
  console.error(`самоконтроль зонда провален: находит=${да}, ложно срабатывает=${нет}`);
  return false;
}

async function спросить() {
  if (!приборИсправен()) return 2;

  let ответ;
  try {
    ответ = await fetch(АДРЕС, { redirect: "follow" });
  } catch (e) {
    console.error(`не удалось спросить ${АДРЕС}: ${e.message}`);
    return 2;
  }
  if (!ответ.ok) {
    console.error(`${АДРЕС} ответил ${ответ.status} — это не ответ про первый экран`);
    return 2;
  }
  const html = await ответ.text();
  const текст = видимыйТекст(html);

  const якорь = /id="kniga"/.test(html);
  const iКнига = текст.search(ЦЕНА_КНИГИ);
  const iПакет = текст.search(ЦЕНА_ПАКЕТА);
  const iБесплатно = текст.indexOf("Собрать план");

  console.log(`адрес:          ${АДРЕС}`);
  console.log(`знаков HTML:    ${html.length}`);
  console.log(`якорь #kniga:   ${якорь ? "есть" : "НЕТ"}`);
  console.log(`цена $9.99:     ${iКнига >= 0 ? `есть, знак ${iКнига} из ${текст.length}` : "НЕТ"}`);
  console.log(`цена $29.99:    ${iПакет >= 0 ? `есть, знак ${iПакет}` : "НЕТ"}`);
  console.log(`бесплатное:     ${iБесплатно >= 0 ? `есть, знак ${iБесплатно}` : "НЕТ"}`);

  const беды = [];
  if (!якорь) беды.push("нет якоря #kniga — платный клик приедет в начало страницы");
  if (iКнига < 0) беды.push("цены $9.99 нет в ответе сервера — книги на странице нет");
  if (iПакет < 0) беды.push("цены $29.99 нет — пакет пропал");
  if (iБесплатно < 0) беды.push("бесплатный инструмент пропал — его убирать не просили");
  if (iКнига >= 0 && iПакет >= 0 && iКнига > iПакет) беды.push("пакет $29.99 стоит ВЫШЕ книги $9.99");
  if (iКнига >= 0 && iБесплатно >= 0 && iКнига > iБесплатно) {
    беды.push("книга стоит НИЖЕ бесплатного инструмента — порядок прежний, правка не доехала");
  }

  if (беды.length) {
    for (const б of беды) console.error(`  ✗ ${б}`);
    return 1;
  }
  console.log("Книга $9.99 выше пакета и выше бесплатного, якорь на месте.");
  console.log("");
  console.log("Высоту в пикселях этот зонд НЕ мерит. Проверить браузером так:");
  console.log("  открыть /longevity?c=probe-... в iframe шириной 390 (окно не слушается resize),");
  console.log("  затем document.querySelector('#kniga').getBoundingClientRect().top + scrollY < 600");
  return 0;
}

process.exitCode = await спросить();
