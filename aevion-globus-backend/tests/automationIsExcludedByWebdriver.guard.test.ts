import { describe, it, expect } from "vitest";
import { видОтправителя } from "../src/routes/events";

/**
 * Автоматика отсекается по ДВУМ приметам, а не по одной.
 *
 * Замер 06.10.2026 (окно Роликов): съёмка через Playwright с боевой меткой
 * `yt-chess-coach` дала три «визита зрителей», и фильтр их не отсёк — в
 * User-Agent той сборки Chromium слова «Headless» нет. То есть наша же съёмка
 * считалась живым трафиком, а отличить её на сервере было нечем.
 *
 * Вторая примета — `navigator.webdriver`, его ставит сам браузер, когда им
 * управляет программа. Клиент шлёт его полем события (`webdriver: true`), а
 * воронка по нему отсекает.
 */
describe("признаки автоматики", () => {
  it("строка браузера ловит только то, что себя называет", () => {
    expect(видОтправителя("Mozilla/5.0 HeadlessChrome/120")).toBe("headless");
    expect(видОтправителя("AEVION-probe/1.0")).toBe("probe");
    expect(видОтправителя("curl/8.4.0")).toBe("bot");
  });

  it("🔴 обычная строка Playwright по UA НЕ ловится — ради этого и поле", () => {
    const ua =
      "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36";
    expect(
      видОтправителя(ua),
      "если это когда-нибудь станет ловиться по UA — проверку ниже можно упрощать",
    ).toBeNull();
  });

  it("пустая строка браузера НЕ объявляется автоматикой", () => {
    // Намеренно: в журнале есть записи до того дня, когда UA начали сохранять.
    expect(видОтправителя(""), "старые записи записаны в роботы задним числом").toBeNull();
    expect(видОтправителя(undefined)).toBeNull();
  });
});
