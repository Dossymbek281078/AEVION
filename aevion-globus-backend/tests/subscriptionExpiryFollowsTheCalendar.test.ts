import { describe, test, expect } from "vitest";
import { вычислитьСрок } from "../src/routes/provisioning";

/**
 * Сторож: оплаченный доступ длится до ТОГО ЖЕ ЧИСЛА следующего месяца.
 *
 * ЧТО БЫЛО (замер 03.09.2026). Срок считался как «30 дней», а касса списывает
 * по календарной дате. В месяцах из 31 дня доступ гас на сутки РАНЬШЕ
 * продления: заплативший человек видел «Free, оформите подписку», хотя платёж
 * был в силе. Таких месяцев в году семь. Отсрочки в коде нет, и ни один тест
 * это правило не закреплял — то есть менять его было нечему помешать.
 *
 * Годовой срок считался как 365 дней и давал те же сутки разрыва в високосном
 * году.
 *
 * Проверяются именно ГРАНИЦЫ, а не середина: конец длинного месяца, переход
 * через год, 29 февраля и пробный период.
 */
const D = (s: string) => new Date(s);

describe("срок доступа идёт по календарю", () => {
  test("месяц из 31 дня: доступ до того же числа, а не 30 дней", () => {
    // Купил 1 января — касса спишет 1 февраля. Прежний расчёт давал 31 января.
    expect(вычислитьСрок(D("2026-01-01T10:00:00.000Z"), "monthly", 0)).toBe(
      "2026-02-01T10:00:00.000Z"
    );
  });

  test("31-е число: зажимаем к последнему дню короткого месяца", () => {
    // 31 января + месяц — это 28 февраля, а не 3 марта. Без зажима JS
    // переносит остаток и дарит человеку лишние дни.
    expect(вычислитьСрок(D("2026-01-31T10:00:00.000Z"), "monthly", 0)).toBe(
      "2026-02-28T10:00:00.000Z"
    );
  });

  test("переход через границу года", () => {
    expect(вычислитьСрок(D("2026-12-15T10:00:00.000Z"), "monthly", 0)).toBe(
      "2027-01-15T10:00:00.000Z"
    );
  });

  test("годовой срок: то же число через год, а не 365 дней", () => {
    // 2028 високосный: 365 дней от 01.03.2027 дали бы 29 февраля 2028.
    expect(вычислитьСрок(D("2027-03-01T10:00:00.000Z"), "annual", 0)).toBe(
      "2028-03-01T10:00:00.000Z"
    );
  });

  test("29 февраля + год: зажимаем к 28-му", () => {
    expect(вычислитьСрок(D("2028-02-29T10:00:00.000Z"), "annual", 0)).toBe(
      "2029-02-28T10:00:00.000Z"
    );
  });

  test("пробный период остаётся В ДНЯХ", () => {
    // Он и продаётся днями — календарь тут ни при чём.
    expect(вычислитьСрок(D("2026-01-01T10:00:00.000Z"), "monthly", 7)).toBe(
      "2026-01-08T10:00:00.000Z"
    );
  });

  test("КОНТРОЛЬ: срок всегда В БУДУЩЕМ и не короче 27 дней", () => {
    // Без этого любая ошибка в арифметике, дающая прошлое или нулевой срок,
    // прошла бы мимо точечных проверок выше.
    for (const д of ["2026-01-31", "2026-02-28", "2026-04-30", "2026-12-31"]) {
      const от = D(`${д}T10:00:00.000Z`);
      const до = D(вычислитьСрок(от, "monthly", 0));
      const дней = (до.getTime() - от.getTime()) / 86400000;
      expect(дней, `${д}: срок ${дней} дней — это не месяц`).toBeGreaterThanOrEqual(27);
      expect(дней, `${д}: срок ${дней} дней — это больше месяца`).toBeLessThanOrEqual(31);
    }
  });
});
