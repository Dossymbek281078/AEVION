/**
 * Тренер не имеет права назвать ход, которого в позиции нет.
 *
 * Прямой вопрос основателя 28.09: «ChatGPT придумывал несуществующие ходы —
 * адекватен ли наш ИИ-тренер». Устройство у нас надёжнее (Stockfish считает
 * ДО запроса, модель переводит его отчёт), но запрет жил только в промпте —
 * то есть держался на добросовестности модели. С 28.09 при закрытом счёте
 * Anthropic отвечает Gemini, у которого свои повадки.
 *
 * Здесь проверяется МЕХАНИЗМ на настоящих позициях, а не формулировка правила.
 */

import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { нелегальныеХоды, ходыИзТекста, вЛатинскуюЗапись, текстВместоОтвета } from "../проверьХодыОтвета";

// Итальянская партия после 1.e4 e5 2.Nf3 Nc6 3.Bc4 — ход чёрных.
const ИТАЛЬЯНСКАЯ = "r1bqkbnr/pppp1ppp/2n5/4p3/2B1P3/5N2/PPPP1PPP/RNBQK2R b KQkq - 3 3";
// Начальная позиция.
const НАЧАЛО = "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1";

describe("русская запись переводится в понятную движку", () => {
  it("Кр — король, К — конь, и порядок не путается", () => {
    // Если бы «К» проверялась раньше «Кр», король стал бы конём — и настоящий
    // ход короля объявили бы выдуманным.
    expect(вЛатинскуюЗапись("Крe2")).toBe("Ke2");
    expect(вЛатинскуюЗапись("Кf3")).toBe("Nf3");
    expect(вЛатинскуюЗапись("Фd8")).toBe("Qd8");
    expect(вЛатинскуюЗапись("Лxd8")).toBe("Rxd8");
    expect(вЛатинскуюЗапись("Сc5")).toBe("Bc5");
  });

  it("латиница не ломается", () => {
    expect(вЛатинскуюЗапись("Nf3")).toBe("Nf3");
    expect(вЛатинскуюЗапись("O-O")).toBe("O-O");
    expect(вЛатинскуюЗапись("0-0")).toBe("O-O");
  });
});

describe("что считается заявленным ходом", () => {
  it("ход с буквой фигуры и рокировка — считаются", () => {
    expect(ходыИзТекста("чёрные играют Кf6, затем O-O")).toEqual(["Кf6", "O-O"]);
  });

  it("номер хода делает ходом даже пешечный", () => {
    expect(ходыИзТекста("14...e4 выигрывает")).toEqual(["e4"]);
  });

  it("🔴 голое поле в тексте ходом НЕ считается", () => {
    // Направление ошибки выбрано осознанно: принять «слон смотрит на e5» за
    // ход значило бы спрятать ВЕРНЫЙ разбор. Ложная тревога дороже пропуска.
    expect(ходыИзТекста("слон смотрит на e5, поле d4 под контролем")).toEqual([]);
  });
});

describe("нелегальные ходы находятся, легальные не трогаются", () => {
  it("настоящий ответ из отчёта проходит чисто", () => {
    const ответ = "Чёрные играют Кf6 — развитие с темпом. Также хорош Сc5.";
    expect(нелегальныеХоды(ИТАЛЬЯНСКАЯ, ответ)).toEqual([]);
  });

  it("🔴 выдуманный ход ловится — русской записью", () => {
    // Ферзя на d8 некуда вывести через занятые поля; Фa5 в этой позиции нет.
    const ответ = "Сильнейшее — Фa5 с двойным ударом.";
    expect(нелегальныеХоды(ИТАЛЬЯНСКАЯ, ответ)).toContain("Фa5");
  });

  it("🔴 выдуманный ход ловится — латинской записью", () => {
    expect(нелегальныеХоды(НАЧАЛО, "Лучше всего Qh5xf7#")).not.toEqual([]);
  });

  it("несуществующее поле не роняет проверку", () => {
    // «Qz9» — не шахматная запись вовсе; разбор не должен падать.
    expect(() => нелегальныеХоды(НАЧАЛО, "играй Qz9")).not.toThrow();
  });

  it("ход ЗА СОПЕРНИКА в разборе линии не считается выдуманным", () => {
    // Разбор говорит о линии: «Кf6, в ответ белые d3». Ход белых в позиции
    // с очередью чёрных нелегален формально, но это верный разбор.
    const ответ = "После Кf6 белые отвечают d3.";
    expect(нелегальныеХоды(ИТАЛЬЯНСКАЯ, ответ)).toEqual([]);
  });

  it("битый или пустой FEN — «не знаю», а не обвинение", () => {
    // Судить по неизвестной позиции значило бы прятать верные разборы
    // при нашей собственной поломке.
    expect(нелегальныеХоды("", "Фa5")).toEqual([]);
    expect(нелегальныеХоды("это не FEN", "Фa5")).toEqual([]);
  });

  it("контроль: пустой текст даёт пустой список, а не находку", () => {
    expect(нелегальныеХоды(ИТАЛЬЯНСКАЯ, "")).toEqual([]);
  });
});

describe("подмена ответа называет себя", () => {
  it("говорит, ЧТО произошло, и даёт ход движка", () => {
    const t = текстВместоОтвета("Кf6");
    expect(t).toContain("которого в этой позиции нет");
    expect(t).toContain("Кf6");
    expect(t).toContain("Движок и задачи работают");
  });

  it("без хода движка не выдумывает его, а называет путь", () => {
    const t = текстВместоОтвета();
    expect(t).toContain("Анализ");
    expect(t).not.toContain("сильнейшее —");
  });
});

describe("все три места вызова тренера проверяют ответ", () => {
  const читать = (имя: string) =>
    readFileSync(join(__dirname, "..", имя), "utf8");

  it("проверка стоит в каждом из трёх, а не в одном", () => {
    // Ради этого правило и вынесено в отдельный файл: у окна после партии
    // свой текст, но признак у всех общий. Пропусти одно место — и дыра
    // останется ровно там, куда никто не смотрит.
    for (const имя of ["AiCoach.tsx", "WhatIfButton.tsx", "page.tsx"]) {
      expect(читать(имя), имя).toContain("нелегальныеХоды(");
      expect(читать(имя), имя).toContain("текстВместоОтвета(");
    }
  });

  it("отклонённый ответ не показывается как обычный", () => {
    // Контроль в обратную сторону: если бы подстановка стояла ПОСЛЕ показа,
    // человек успел бы прочитать выдуманный ход.
    const код = читать("AiCoach.tsx");
    const где = код.indexOf("нелегальныеХоды(");
    const показ = код.indexOf("content: reply +");
    expect(где).toBeGreaterThan(-1);
    expect(показ).toBeGreaterThan(где);
  });
});
