import { describe, it, expect } from "vitest";
import express from "express";
import request from "supertest";
import { devhubRouter } from "../src/routes/devhub.js";

/**
 * Мусор в теле запроса даёт 4xx, а не 5xx.
 *
 * ЗАЧЕМ. Неверные данные в запросе — это ответ О ЗАПРОСЕ, то есть 4xx. Пятисотка
 * означает «у нас сломалось»: она уходит в Sentry, поднимает людей и тонет в
 * шуме, среди которого потом не видно настоящих аварий. Один запрос робота,
 * повторяемый в цикле, превращается в поток ложных тревог.
 *
 * ПОЧЕМУ ЗДЕСЬ. У шахмат, календаря и QSkyway такие сторожа есть, у DevHub не
 * было ни одного — асимметрия защиты при том же классе риска. Замер 01.09.2026
 * на 40 маршрутах из 50: пятисоток НОЛЬ (400 — девятнадцать, 404 — двадцать,
 * 503 — один, и тот законный). То есть сторож не чинит найденное, а удерживает
 * уже достигнутое: класс дешевле не пустить обратно, чем ловить потом в Sentry.
 *
 * Тело намеренно враждебное: ключи прототипа (этот класс дал на платформе
 * восемь дефектов за один день), объект вместо строки, массив вместо строки,
 * число вместо имени.
 */

const МУСОР = {
  __proto__: { взлом: 1 },
  constructor: "строка вместо конструктора",
  id: { $ne: 1 },
  prompt: [],
  name: 12345,
  toString: "не функция",
};

/**
 * Законные 5xx. Список намеренно КРОШЕЧНЫЙ и с причиной у каждой строки: список
 * исключений, который растёт молча, превращает сторожа в опись поражений.
 */
const ЗАКОННЫЕ_5XX = new Map<string, string>([
  ["/media/drive-search", "503 при ненастроенном внешнем диске — осознанная деградация, а не падение"],
]);

function постМаршруты(): string[] {
  const слой = (devhubRouter as unknown as {
    stack: Array<{ route?: { path: string; methods: Record<string, boolean> } }>;
  }).stack;
  return слой.filter((s) => s.route?.methods?.post).map((s) => s.route!.path);
}

describe("DevHub: мусор в теле не превращается в поломку сервера", () => {
  it("прибор исправен: маршруты найдены", () => {
    // Контроль охвата. Пустой список дал бы «пятисоток нет» — самый частый вид
    // ложного зелёного, и здесь он особенно правдоподобен: разбор внутренностей
    // роутера ломается от смены версии express молча.
    expect(постМаршруты().length, "POST-маршруты не найдены — сторож смотрит не туда").toBeGreaterThan(30);
  });

  it("ни один POST-маршрут не отвечает 5xx на враждебное тело", async () => {
    const app = express();
    app.use(express.json());
    app.use("/api/devhub", devhubRouter);

    const плохие: string[] = [];
    for (const шаблон of постМаршруты()) {
      const путь = шаблон.replace(/:[a-zA-Z]+/g, "proba");
      const r = await request(app).post("/api/devhub" + путь).send(МУСОР as unknown as object);
      if (r.status < 500) continue;
      if (ЗАКОННЫЕ_5XX.has(шаблон)) continue;
      плохие.push(`${шаблон} → ${r.status}`);
    }

    expect(
      плохие,
      "Эти маршруты отвечают 5xx на неверные данные в запросе. 5xx означает " +
        "«у нас сломалось»: тревога уходит дежурному, а виноват был запрос. " +
        "Верните 400 с человеческим текстом. Если 5xx здесь законна (внешний " +
        "сервис не настроен) — внесите маршрут в ЗАКОННЫЕ_5XX С ПРИЧИНОЙ.",
    ).toEqual([]);
  }, 180_000);

  it("список исключений не растёт молча", () => {
    // Храповик: два исключения ещё можно прочитать глазами, десять — уже опись
    // поражений, которую перестают читать.
    expect(ЗАКОННЫЕ_5XX.size, "исключений стало больше трёх — разберите их, а не копите").toBeLessThanOrEqual(3);
    for (const [путь, причина] of ЗАКОННЫЕ_5XX) {
      expect(причина.length, `у исключения ${путь} нет внятной причины`).toBeGreaterThan(25);
    }
  });
});
