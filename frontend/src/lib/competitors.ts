/** Сколько ячеек в наборе ещё не заземлено источником — показывается честно. */
export function unverifiedCount(set: CompetitorSet): number {
  return set.rows.filter((r) => r.ours.source === "unverified" || r.theirs.source === "unverified").length;
}
