import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stripComments } from "./helpers/sourceCode";

/**
 * Кто ОТПРАВИТЕЛЬ — решает окружение, а не тело запроса.
 *
 * 🔴 ЗАЧЕМ. Замер на боевом проде 09.09.2026, за сутки до рассылки запуска.
 * `POST /api/devhub/media/sms` и `/media/email` открыты без входа
 * (`verifyBearerOptional` в них не вызывается, в отличие от соседней
 * `/media/image`), а имя и адрес отправителя брались ИЗ ТЕЛА:
 *
 *     sender.trim().slice(0, 11)      → уходило в Brevo как есть
 *     from.trim() при верном формате  → уходило в Brevo как есть
 *
 * То есть кто угодно отправлял сообщение с НАШЕГО аккаунта, назвавшись кем
 * угодно. Одиннадцати знаков хватает, чтобы назваться банком.
 *
 * 🔴 ПОЧЕМУ ПРЕДЕЛ ТЕМПА ЭТО НЕ ЗАКРЫВАЕТ. Ограничитель на этих путях ЕСТЬ и
 * работает — замер: пять запросов проходят, шестой даёт 429. Он ограничивает
 * ОБЪЁМ. Подмену имени объём не ограничивает: одного сообщения достаточно.
 * Соседнее окно, найдя эти ручки, сочло что предела нет вовсе — он стоит на
 * уровне роутера, а не в обработчике, и построчное чтение его не видит.
 *
 * 🔴 ПОЧЕМУ ПРОВЕРКА ФОРМАТА АДРЕСА НЕ СЧИТАЕТСЯ ЗАЩИТОЙ. Она отвечает на
 * вопрос «похоже ли это на адрес», а не «наш ли он». Письмо с чужого адреса,
 * ушедшее с нашего аккаунта, бьёт по репутации домена — а ею мы отправляем
 * письма запуска.
 *
 * ГРАНИЦА, названная честно. Сторож текстовый: он видит, что значение берётся
 * из `process.env`, и НЕ видит, что произойдёт с новой ручкой отправки,
 * которую заведут завтра. Поэтому список путей здесь явный — новая ручка в
 * него не попадёт сама, и это осознанный размен: лучше узкая проверка,
 * которая точно работает, чем широкая, которая краснеет на здоровом коде.
 *
 * WhatsApp в список НЕ входит намеренно: там отправитель и так берётся только
 * из `BREVO_WHATSAPP_SENDER_ID`, то есть чинить нечего. Проверено чтением.
 */
const ФАЙЛ = join(__dirname, "..", "src", "routes", "devhub.ts");

/** Тело обработчика — от объявления маршрута до следующего маршрута. */
function телоРучки(src: string, путь: string): string {
  const от = src.indexOf(`devhubRouter.post("${путь}"`);
  if (от < 0) return "";
  const до = src.indexOf("devhubRouter.", от + 40);
  return src.slice(от, до > 0 ? до : от + 6000);
}

describe("отправитель берётся из окружения, а не из запроса", () => {
  const src = stripComments(readFileSync(ФАЙЛ, "utf8"));

  it("прибор видит предмет: обе ручки на месте и разобраны", () => {
    // Без этого «подмены нет» означало бы «ручку переименовали».
    for (const путь of ["/media/sms", "/media/email"]) {
      expect(телоРучки(src, путь).length, `обработчик ${путь} не найден`).toBeGreaterThan(200);
    }
  });

  it("SMS: имя отправителя не приходит из тела запроса", () => {
    const тело = телоРучки(src, "/media/sms");
    expect(
      /senderName\s*=\s*process\.env\./.test(тело),
      "имя отправителя SMS обязано браться из окружения",
    ).toBe(true);
    // Спрашиваем РАЗБОР тела, а не соседство слова: первая редакция искала
    // `body[^;]*sender` и краснела на исправном коде — слово `body:` есть в
    // опциях fetch, а `sender:` в его полезной нагрузке. Поле, не разобранное
    // из запроса, использовать нельзя — это точный признак вместо косвенного.
    const разбор = (тело.match(/const\s*\{[^}]*\}\s*=\s*req\.body/) || [""])[0];
    expect(разбор.length, "разбор тела запроса не найден — сторож смотрит не туда").toBeGreaterThan(10);
    expect(
      /\bsender\b/.test(разбор),
      "поле sender снова разбирается из тела запроса — это подмена бренда чужими руками",
    ).toBe(false);
  });

  it("почта: адрес отправителя не приходит из тела запроса", () => {
    const тело = телоРучки(src, "/media/email");
    expect(
      /senderEmail\s*=\s*process\.env\./.test(тело),
      "адрес отправителя письма обязан браться из окружения",
    ).toBe(true);
    const разбор = (тело.match(/const\s*\{[^}]*\}\s*=\s*req\.body/) || [""])[0];
    expect(разбор.length, "разбор тела запроса не найден — сторож смотрит не туда").toBeGreaterThan(10);
    expect(
      /\bfrom\b/.test(разбор),
      "поле from снова разбирается из тела запроса",
    ).toBe(false);
  });

  it("предел темпа на путях отправки остался на месте", () => {
    // Отдельная проверка: подмену чинили здесь, а объём держит ограничитель
    // уровня роутера. Убрать его, чиня подмену, было бы разменом в минус.
    // Ищем ПРИМЕНЕНИЕ, а не объявление. Первая редакция брала первое вхождение
    // `dhSendLimit()` — им оказалась строка `function dhSendLimit() {`, и окно
    // вокруг неё путей, разумеется, не содержало. Сторож краснел на исправном
    // коде: ошибка была в приборе, а выглядела как пропажа защиты.
    const at = src.indexOf("devhubRouter.use(");
    expect(at, "монтирование middleware не найдено").toBeGreaterThan(-1);
    const at2 = src.indexOf("dhSendLimit()", at);
    expect(at2, "ограничитель отправки не применён ни к одному пути").toBeGreaterThan(-1);
    const окно = src.slice(Math.max(0, at2 - 400), at2 + 40);
    for (const путь of ["/media/email", "/media/sms", "/media/whatsapp"]) {
      expect(окно.includes(путь), `путь ${путь} выпал из-под ограничителя отправки`).toBe(true);
    }
  });
});
