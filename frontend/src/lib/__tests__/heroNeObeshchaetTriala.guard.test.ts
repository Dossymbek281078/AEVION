/**
 * 🔴 НИ ОДИН ВАРИАНТ ЗАГОЛОВКА /pricing НЕ ОБЕЩАЕТ ТОГО, ЧЕГО НЕТ.
 *
 * Повод 12.10.2026: вариант «C» опыта `hero` показывал «14 ДНЕЙ FREE · NO
 * CREDIT CARD», «Free trial 14 дней» и «Customer Success включён бесплатно».
 * Триала касса не даёт ни одного дня и ни по одному тарифу, а вариант
 * доставался КАЖДОМУ ТРЕТЬЕМУ посетителю страницы цен.
 * Вариант «B» заявлял «−73% VS DOCUSIGN+OPENAI+STRIPE» — расчёта под этим
 * числом в коде нет ни строки, источник не назван, проверить нечем.
 *
 * Сторож держит ДВА свойства, и оба про честность, а не про вёрстку:
 *   • в текстах заголовка нет обещания триала и бесплатной карты;
 *   • в них нет сравнительного процента (его нечем подтвердить).
 * Плюс третье, механическое: вариант «C» больше не выдаётся для `hero` — ни
 * новому человеку, ни тому, у кого он уже записан в куке.
 */
import { describe, it, expect } from "vitest";
import { PRICING_DICT } from "@/lib/pricingI18n";

const ЗАПРЕЩЕНО = [
  /\bfree\s*trial\b/i,
  /триал/i,
  /14\s*дн/i,
  /14\s*days?\b/i,
  /no\s*credit\s*card/i,
  /без\s*(?:credit\s*card|карты)/i,
];

/** Все строки заголовка во всех языках словаря цен. */
function строкиHero(): Array<[string, string]> {
  const out: Array<[string, string]> = [];
  for (const [язык, словарь] of Object.entries(PRICING_DICT)) {
    for (const [ключ, значение] of Object.entries(словарь)) {
      if (ключ.startsWith("hero.")) out.push([`${язык}:${ключ}`, String(значение)]);
    }
  }
  return out;
}

describe("заголовок страницы цен не обещает несуществующего", () => {
  it("🔴 контроль прибора: строки заголовка вообще находятся", () => {
    const строки = строкиHero();
    expect(строки.length, "строк hero не найдено — прибор слеп").toBeGreaterThanOrEqual(6);
  });

  it("🔴 ни одной строки про триал и «без карты»", () => {
    const плохие = строкиHero().filter(([, v]) => ЗАПРЕЩЕНО.some((re) => re.test(v)));
    expect(плохие.map(([k, v]) => `${k} → ${v.slice(0, 60)}`), "обещание, которого касса не выполняет").toEqual([]);
  });

  it("🔴 ни одного сравнительного процента без источника", () => {
    // Любой «−NN%» в заголовке — это утверждение о чужих ценах. Пока в коде нет
    // расчёта с источником, такого числа на странице быть не должно.
    const сПроцентом = строкиHero().filter(([, v]) => /[−-]\s*\d{1,3}\s*%/.test(v));
    expect(сПроцентом.map(([k, v]) => `${k} → ${v.slice(0, 60)}`)).toEqual([]);
  });
});
