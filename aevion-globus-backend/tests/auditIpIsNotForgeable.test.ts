// Адрес в журнале сессий и аудита подделывался заголовком.
//
// НАЙДЕНО 27.08.2026 свипом по 44 местам, где берётся адрес клиента. В
// routes/auth.ts и routes/authOauth.ts жили ДВЕ копии функции, читавшие ЛЕВОЕ
// значение `X-Forwarded-For`:
//
//     const first = xff.split(",")[0]?.trim();
//     return first || req.ip || ...
//
// Прокси дописывает свой адрес СПРАВА, поэтому левое значение пишет сам
// вызывающий и не проверяет никто. Любой мог прислать
// `X-Forwarded-For: 8.8.8.8` и получить этот адрес в записи о своём входе.
//
// ⚠️ ОГРАНИЧИТЕЛИ ЭТИМ НЕ ЗАТРОНУТЫ — проверено отдельно: вход ограничивается
// `rateLimit()` без своего keyFn, а он берёт нормализованный req.ip. Перебор
// паролей не обходился. Затронуты записи, по которым разбираются ПОСЛЕ
// инцидента: «недавние входы» у пользователя и журнал аудита. Подделываемый
// след хуже отсутствующего — отсутствующий хотя бы не вводит в заблуждение.

import { describe, expect, it } from "vitest";
import { observedIp } from "../src/lib/observedIp";

describe("адрес для журнала берётся у прокси, а не у вызывающего", () => {
  it("заголовок X-Forwarded-For не влияет на результат", () => {
    // Главный случай: заголовок кричит одно, express наблюдал другое.
    const req = {
      ip: "203.0.113.7",
      headers: { "x-forwarded-for": "8.8.8.8, 203.0.113.7" },
      socket: { remoteAddress: "10.0.0.1" },
    };
    expect(observedIp(req)).toBe("203.0.113.7");
    expect(observedIp(req)).not.toBe("8.8.8.8");
  });

  it("подделка в заголовке в любом виде игнорируется", () => {
    const forged = [
      "8.8.8.8",
      "  8.8.8.8  ",
      "8.8.8.8, 1.1.1.1",
      "не адрес вовсе",
      "",
    ];
    for (const xff of forged) {
      expect(
        observedIp({ ip: "203.0.113.7", headers: { "x-forwarded-for": xff } } as never),
        `заголовок ${JSON.stringify(xff)}`,
      ).toBe("203.0.113.7");
    }
  });

  it("контроль: адрес вообще возвращается, а не всегда null", () => {
    // Без этого проверки выше прошли бы и на функции, возвращающей null:
    // журнал стал бы пустым, и это выглядело бы как «подделка невозможна».
    expect(observedIp({ ip: "203.0.113.7" })).toBe("203.0.113.7");
    expect(observedIp({ ip: "2001:db8::1" })).toBe("2001:db8::1");
  });

  it("нет req.ip — берём адрес сокета", () => {
    expect(observedIp({ socket: { remoteAddress: "10.0.0.1" } })).toBe("10.0.0.1");
  });

  it("нет ничего — null, а не выдуманное значение", () => {
    expect(observedIp({})).toBeNull();
  });

  it("адрес НЕ схлопывается до подсети — журналу нужен точный", () => {
    // В ключе ограничителя IPv6 намеренно сводится к /64, здесь — нет:
    // два входа с разных адресов одной подсети должны различаться в журнале.
    const a = observedIp({ ip: "2001:db8:abcd:1234::1" });
    const b = observedIp({ ip: "2001:db8:abcd:1234::9999" });
    expect(a).not.toBe(b);
  });
});
