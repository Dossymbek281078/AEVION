import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Общий контейнер всплывашек прижат к низу экрана (bottom:16, z-index 9999),
 * и каждая всплывашка перехватывает касания (pointerEvents:"auto"). На
 * телефоне 390px это ровно то место, где стоит нижняя навигация.
 *
 * Замер 01.09.2026 сразу после закрытия окна приветствия: недоступны касанию
 * ПЯТЬ кнопок из шести — «Играть», «Задачи», «Анализ», «Коуч», «Профиль».
 * Через ~6 секунд всплывашка уходит и навигация оживает.
 *
 * Приветствие дублировало то, что окно приветствия уже сказало, поэтому
 * убрано целиком. Сообщение не потеряно — см. контроль ниже.
 */

const КОД = () => readFileSync(join(__dirname, "..", "page.tsx"), "utf8");
const ОКНО = () => readFileSync(join(__dirname, "..", "OnboardingOverlay.tsx"), "utf8");

describe("приветствие новичка", () => {
  it("не показывается всплывашкой поверх нижней навигации", () => {
    expect(КОД()).not.toContain("Добро пожаловать! +50 Chessy на счёте");
  });

  it("но сообщение о +50 Chessy человек всё равно видит", () => {
    // Иначе «починка» просто отняла бы у новичка новость про монеты.
    expect(ОКНО()).toContain("+50 Chessy");
  });

  it("после закрытия окна приветствия всплывашек не остаётся", () => {
    const код = КОД();
    const i = код.indexOf("onSkip={()=>{markOnboardingDone()");
    expect(i, "обработчик «просто осмотрюсь» пропал — проверку переписать").toBeGreaterThan(0);
    const тело = код.slice(i, i + 700);
    expect(тело).not.toContain("showToast(");
  });
});
