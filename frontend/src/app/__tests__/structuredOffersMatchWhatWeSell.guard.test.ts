// Разметка для поисковиков не обещает того, что мы не продаём.
//
// ЗАЧЕМ. `app/constitution/layout.tsx` объявлял поисковикам `Offer` с
// `price: "9"` и именем «Constitution Pro». Решение основателя 15.09.2026:
// отдельно продаются только шахматы, патентное бюро, DevHub, мультичат и
// бизнес-анализатор — Конституции в этом списке нет. Замеры 17.09.2026: касса
// сайта отвечает `410 not_sold_separately` и уводит на /pricing; в каталоге
// продаж (`lib/products.ts`) слова `constitution` нет.
//
// ⚠️ Честная оговорка, найденная при проверке: товар за $9 при этом НЕ исчез
// физически — старая ссылка Gumroad «Constitution Pro» (слаг pyiaz) отвечает
// 200, и вебхук выдаёт по ней доступ. То есть разметка рекламировала не
// выдуманный товар, а забытый, продающийся вопреки решению. Снять его с
// публикации — рука основателя в кабинете Gumroad, а не этот код; здесь
// закрывается только реклама этого товара в поиске.
//
// ПОЧЕМУ ЭТОГО НЕ ВИДЕЛ НИКТО. Сторожей на цены в структурной разметке не было
// ни одного. Слой невидим для человека: его читают робот поисковика и
// мессенджер, а не посетитель страницы. Проверка типов бессильна — это строка
// в объекте. Свип по ценам в текстах тоже мимо: там цена ищется как `$9`, здесь
// она лежит как `price: "9"`.
//
// ГРАНИЦА СТОРОЖА. Он читает ИСХОДНИКИ, а не собранный HTML: цена, собранная в
// рантайме из данных товара (как в `qstore/[id]/layout.tsx`), под литеральное
// правило не попадает — и это верно, такая цена приходит из того же источника,
// что и продажа. Ловится именно ВПИСАННАЯ РУКАМИ ненулевая цена. И «продаётся»
// здесь значит «есть в каталоге сайта», а не «где-то есть ссылка оплаты».

import { describe, it, expect } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, dirname, relative } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "..", "..");            // frontend/src
const APP = join(SRC, "app");

/** Все .ts/.tsx под src/app, кроме тестов. */
function файлы(корень: string): string[] {
  const out: string[] = [];
  const обойти = (d: string) => {
    for (const e of readdirSync(d)) {
      const p = join(d, e);
      if (statSync(p).isDirectory()) {
        if (e === "__tests__" || e === "node_modules") continue;
        обойти(p);
      } else if ((e.endsWith(".ts") || e.endsWith(".tsx")) && !e.includes(".test.")) {
        out.push(p);
      }
    }
  };
  обойти(корень);
  return out;
}

/**
 * Литеральные цены рядом с priceCurrency: `price: "9"` или `price: 9`.
 * Вычисляемое значение пропускаем намеренно — см. границу в шапке.
 */
const ЦЕНА_ЛИТЕРАЛОМ = /price:\s*"?(\d+(?:\.\d+)?)"?/g;

describe("структурная разметка не обещает снятое с продажи", () => {
  it("контроль: разметка с ценами вообще находится", () => {
    const сцены = файлы(APP).filter((p) => readFileSync(p, "utf8").includes("priceCurrency"));
    // Если ноль — прибор слеп, и зелёный результат ничего не значит.
    expect(сцены.length, "контроль: файлов с priceCurrency не найдено — прибор слеп").toBeGreaterThan(0);
  });

  it("ни один Offer не объявляет ненулевую цену модуля, которого нет в каталоге", () => {
    const каталог = readFileSync(join(SRC, "lib", "products.ts"), "utf8");
    const находки: string[] = [];

    for (const p of файлы(APP)) {
      const t = readFileSync(p, "utf8");
      if (!t.includes("priceCurrency")) continue;
      for (const m of t.matchAll(ЦЕНА_ЛИТЕРАЛОМ)) {
        const цена = Number(m[1]);
        if (!(цена > 0)) continue;   // бесплатная посадочная — законный случай
        const путь = relative(SRC, p).split("\\").join("/");
        // Имя модуля из пути: app/<модуль>/... — по нему спрашиваем каталог.
        const модуль = путь.split("/")[1] ?? "";
        const вКаталоге = модуль.length > 0 && каталог.includes(модуль);
        if (!вКаталоге) {
          находки.push(`${путь}: price "${m[1]}" — модуля "${модуль}" нет в каталоге продаж сайта`);
        }
      }
    }

    expect(
      находки,
      "поисковикам объявлена цена того, чего нет в каталоге продаж сайта",
    ).toEqual([]);
  });
});
