/**
 * Какой стек создавать из идеи главного входа «опиши → построй».
 *
 * До 05.09.2026 главный вход ВСЕГДА создавал react — а правка кликами
 * (Visual Edit), которую витрина обещает тремя формулировками, отрисовывается
 * только на static. Человек с «лендингом кофейни» попадал в проект, где
 * обещанная панель не появлялась никогда.
 *
 * Правило: страничные идеи без данных и логики → static (мгновенное превью,
 * правка кликами работает сразу); идеи с базой, аккаунтами, API → react.
 *
 * «баз» без окончания: \b и диапазоны с кириллицей в регулярках не работают
 * (известный класс), а «с базой» через баз[ае] не ловилось.
 */
const NEEDS_APP = /баз|данн|трекер|database|api|логин|auth|аккаунт|регистрац|заказ|корзин|оплат|статус|канбан|доск[аи]/i;
const PAGE_LIKE = /лендинг|landing|портфолио|portfolio|визитк|страниц|галере|меню|резюме|приглашени|invitation|афиш|постер|промо|презентац/i;

/**
 * 28.09.2026. Раньше здесь для «идей с данными» выбирался react — и это молча
 * ломало главное обещание входа. Замер на живом проде: проект react
 * (public/index.html, src/App.jsx) публиковался с ok:true, а адрес отдавал 404
 * и через 155 секунд, потому что Cloudflare Pages отдаёт файлы как есть и
 * ничего не собирает. Тот же промпт статикой: index.html + style.css +
 * script.js (6465 знаков, localStorage) — адрес 200 за 88 секунд, тело на месте.
 *
 * Значит вход «опиши — получишь живой адрес» обязан создавать static: только он
 * доходит до живого адреса, и только на нём работает обещанная правка кликами.
 * Остальные стеки остаются осознанным выбором в форме «создать проект» — там
 * человек просит КОД, а не публикацию.
 */
export function stackForIdea(_idea: string): "static" {
  return "static";
}

/**
 * Нужен ли идее настоящий сервер (аккаунты, база, оплата, API). Статика с
 * localStorage покрывает работу в одном браузере, но не это. Пригодно для
 * честной подписи на экране; на выбор стека НЕ влияет.
 */
export function даннымНуженСервер(idea: string): boolean {
  return NEEDS_APP.test(idea);
}

/**
 * РАЗВИЛКА ВХОДА: одна страница или полноценное приложение (28.09.2026).
 *
 * Зачем. Сегодня вход всегда строит static — единственный стек, который доходит до
 * живого адреса. Это честно, но узко: человеку с «магазином с личным кабинетом»
 * статика не подходит по сути, а не по нашему удобству. Приложение с сервером
 * становится возможным, как только у платформы появляется сборка на стороне Vercel
 * (маршрут /deploy/vercel уже написан и ждёт VERCEL_API_TOKEN).
 *
 * Поэтому развилка НЕ включается вручную и не обещает заранее: она спрашивает
 * возможности сервера. Нет сборки — выбора нет, и человеку это сказано прямо.
 * Появился токен — выбор возникает сам, без новой выкатки кода.
 */
export type РежимПостройки = "page" | "app";

/** Доступен ли режим «приложение»: нужен канал, который умеет СОБИРАТЬ проект. */
export function доступенРежимПриложения(
  проверка: (id: string) => boolean,
): boolean {
  // Собирает Next именно Vercel. Cloudflare Pages отдаёт файлы как есть и для
  // приложения не годится — это и была причина мёртвых адресов до 28.09.
  return проверка("vercel");
}

/** Стек для выбранного режима. Развилка знает про стеки, страница — нет. */
export function стекДляРежима(режим: РежимПостройки): "static" | "next" {
  return режим === "app" ? "next" : "static";
}
