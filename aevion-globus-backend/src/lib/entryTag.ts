/**
 * Метка захода, с которой человек начал запись (проект DevHub, диалог Мультичата).
 *
 * Сырая метка целиком («yt-chess-level», «probe-prodakt») — её шлёт фронт
 * `меткаЗаходаДляЗаписи()`. Это чужой ввод из адреса, поэтому принимаем только
 * короткое [a-z0-9_-]; всё прочее — честный null, а не «почищенная» строка:
 * выдуманная метка хуже отсутствующей, по ней потом делают вывод о канале.
 */
export function меткаЗахода(сырое: unknown): string | null {
  if (typeof сырое !== "string") return null;
  const t = сырое.trim().toLowerCase();
  if (t.length > 60) return null;
  return t && /^[a-z0-9_-]+$/.test(t) ? t : null;
}
