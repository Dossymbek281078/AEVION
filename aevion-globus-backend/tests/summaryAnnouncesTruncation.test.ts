/**
 * Обрезанное окно обязано называть себя.
 *
 * Сводка берёт ПОСЛЕДНИЕ `limit` строк журнала и только потом фильтрует по
 * времени. Значит при журнале длиннее предела ответ на вопрос «что было за
 * 30 дней» молча превращается в «что было за последние N событий» — и выглядит
 * как полный.
 *
 * Замер 01.09.2026: в журнале прода 4476 событий при пределе 5000. Первый же
 * всплеск трафика — ради которого реклама и запускается — сделает выручку по
 * каналам тихо заниженной, а заметить это будет нечем.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const исходник = readFileSync(join(process.cwd(), "src/routes/events.ts"), "utf8");

describe("сводка сообщает об обрезке", () => {
  it("признак обрезки означает упор в предохранитель ВНУТРИ окна", () => {
    // Прежняя редакция считала «строк в файле больше предела» — и кричала
    // «обрезано» при полностью покрытом окне, если в журнале много старых
    // событий. Ложная тревога на панели, по которой решают о бюджете, ничем
    // не лучше молчания: к ней привыкают и перестают читать.
    expect(исходник).toContain("const обрезано = упёрлисьВПредохранитель;");
    expect(
      исходник,
      "признак должен взводиться там, где предохранитель и срабатывает",
    ).toContain("упёрлисьВПредохранитель = true;");
    // И окно берётся по ВРЕМЕНИ: без этой строки предохранитель снова стал бы окном.
    expect(исходник).toContain("new Date(ts).getTime() < sinceMs) break;");
  });

  it("ответ несёт и признак, и знаменатель", () => {
    expect(исходник).toContain("truncated: обрезано");
    expect(исходник, "без знаменателя признак не читается").toContain("totalEvents: lines.length");
    expect(исходник).toContain("consideredEvents: tail.length");
  });

  it("витрина показывает предупреждение, а не прячет его в ответе", () => {
    const админка = readFileSync(
      join(process.cwd(), "../frontend/src/app/pricing/admin/page.tsx"),
      "utf8",
    );
    expect(админка, "поле есть, а читателя нет").toContain("summary.truncated");
    expect(админка).toContain("summary.totalEvents");
  });
});
