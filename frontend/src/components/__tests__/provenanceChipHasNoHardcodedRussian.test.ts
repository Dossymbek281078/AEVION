import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { DEFAULT_PROVENANCE_LABELS } from "@/lib/dataQuality";

/**
 * В общем компоненте провенанса не остаётся русских слов, зашитых в разметку.
 *
 * Замер 01.09.2026: их было СЕМЬ. Сторож языка QSkyway нашёл ОДНО — «реальных».
 * Остальные шесть живут в подсказке (атрибут `text` у InfoTip) и попадают на
 * экран только при наведении, то есть его охвату недоступны.
 *
 * ⚠️ Это не вина того сторожа: он сравнивает ВИДИМЫЙ текст, и граница у него
 * честная. Урок другой — на один сторож полагаться нельзя: он видит подпись и
 * не видит пояснение к ней. Поэтому здесь проверка по ИСХОДНИКУ, она достаёт
 * туда, куда отрисовка не дотягивается.
 *
 * Цена: компонент используют три страницы. Зашитое слово доезжало до всех
 * сразу — на английской человек читал «96% measured, 50.1% реальных».
 */

const ФАЙЛ = join(__dirname, "..", "DataProvenanceChip.tsx");

/** Строки кода без комментариев: свой же комментарий уже ловил свой шаблон
 *  четырежды за сегодня, и в этом файле он тоже подробный. */
function кодом(): string[] {
  return readFileSync(ФАЙЛ, "utf8")
    .split(String.fromCharCode(10))
    .filter((l) => {
      const t = l.trim();
      return !t.startsWith("//") && !t.startsWith("*") && !t.startsWith("/*");
    });
}

const кириллица = (s: string) => /[А-Яа-яЁё]/.test(s);

describe("общий компонент провенанса переводится целиком", () => {
  it("контроль: файл прочитан и в нём есть разметка", () => {
    const строки = кодом();
    expect(строки.length, "файл подозрительно короткий").toBeGreaterThan(40);
    expect(
      строки.some((l) => l.includes("InfoTip")),
      "подсказка исчезла — сторож смотрит не туда",
    ).toBe(true);
  });

  it("в разметке нет русских слов — все подписи приходят из ProvenanceLabels", () => {
    const плохие = кодом().filter(кириллица);
    expect(
      плохие.map((l) => l.trim().slice(0, 70)),
      "русское слово зашито в разметке: на английской странице человек увидит его как есть",
    ).toEqual([]);
  });

  it("все подписи объявлены и непусты — иначе на экране будет пустота", () => {
    // Без этой стороны предыдущая проверка была бы зелёной и на компоненте,
    // где подписи объявлены пустыми строками: русского нет, и текста тоже нет.
    for (const [ключ, значение] of Object.entries(DEFAULT_PROVENANCE_LABELS)) {
      if (значение === undefined) continue;
      expect(String(значение).trim().length, `подпись ${ключ} пуста`).toBeGreaterThan(0);
    }
    for (const обязательная of ["real", "tipMeasured", "tipSource", "tipTotal", "tipLabel"]) {
      expect(
        DEFAULT_PROVENANCE_LABELS as Record<string, unknown>,
        `подпись ${обязательная} не заведена`,
      ).toHaveProperty(обязательная);
    }
  });
});
