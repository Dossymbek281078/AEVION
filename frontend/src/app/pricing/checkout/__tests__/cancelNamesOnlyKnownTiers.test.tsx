import { describe, test, expect, beforeEach, vi } from "vitest";
import { render } from "@testing-library/react";

/**
 * Экран отмены не выдумывает тариф и не ведёт в никуда.
 *
 * Вторая половина пути возврата из кассы. На экране УСПЕХА этот класс закрыт
 * 04.09.2026: `?tier=Zolotoy` показывался как подтверждённый тариф. Здесь то
 * же самое осталось: подпись кнопки собиралась как `tier` с заглавной буквы, а
 * адрес — как `/pricing/${tier}`, без единой проверки.
 *
 * Следствий два, и оба тихие:
 *   - собранная ссылка рисует на нашем домене кнопку «Вернуться к <что угодно>»;
 *   - служебное имя (`constructor`) через общий `tierLabel` даёт ФУНКЦИЮ, и на
 *     кнопке появляется «function Object() { [native code] }».
 *
 * Проверяется ПОВЕДЕНИЕ отрисовки: по исходнику отличить «подпись из словаря»
 * от «подпись из адреса» нельзя — обе выглядят как обращение к переменной.
 */

let query = "";
vi.mock("next/navigation", () => ({
  useSearchParams: () => new URLSearchParams(query),
}));
vi.mock("@/lib/track", () => ({ track: () => {} }));
vi.mock("@/lib/pricingI18n", () => ({ usePricingT: () => (k: string) => k }));

// eslint-disable-next-line import/first
import CancelPage from "../cancel/page";

beforeEach(() => {
  query = "";
});

function экран(q: string) {
  query = q;
  const { container } = render(<CancelPage />);
  return {
    текст: container.textContent || "",
    ссылки: [...container.querySelectorAll("a")].map((a) => a.getAttribute("href") || ""),
  };
}

describe("экран отмены называет только известные тарифы", () => {
  test("контроль: известный тариф даёт кнопку и ссылку на него", () => {
    // Иначе «неизвестный не показан» могло бы означать «кнопки нет никогда».
    const { текст, ссылки } = экран("paybox=1&tier=lite");
    expect(ссылки, "нет ссылки на страницу тарифа").toContain("/pricing/lite");
    expect(текст, "тариф не назван").toContain("Lite");
  });

  test("служебное имя не превращается в название тарифа", () => {
    const { текст } = экран("paybox=1&tier=constructor");
    expect(текст.toLowerCase(), "на кнопку попало внутреннее значение").not.toContain("native code");
  });

  test("незнакомый тариф ведёт на страницу, которая честно говорит «не найден»", () => {
    // Сперва я записал сюда требование «ссылки на незнакомый тариф быть не
    // должно» и получил красный. Проверил назначение — и требование оказалось
    // ЛОЖНЫМ: `/pricing/<что угодно>` отрисовывает состояние «тариф не найден»
    // с указанием идентификатора. То есть человек попадает не в никуда, а в
    // понятный отказ, и запрещать ссылку значило бы чинить работающее.
    //
    // Оставляю проверку перевёрнутой: она закрепляет, что ссылка ведёт внутрь
    // нашего сайта, а не наружу и не в подделанный путь.
    const { ссылки } = экран("paybox=1&tier=zolotoy");
    const тарифная = ссылки.find((h) => h.startsWith("/pricing/"));
    expect(тарифная, "ссылка на тариф исчезла вовсе").toBeTruthy();
    expect(тарифная, "ссылка уводит за пределы сайта").toMatch(/^\/pricing\/[^/]+$/);
  });

  test("выход в каталог есть всегда", () => {
    // Что бы ни пришло в адресе, человеку есть куда нажать.
    const { ссылки } = экран("paybox=1&tier=zolotoy");
    expect(ссылки, "с экрана отмены некуда идти").toContain("/pricing");
  });
});
