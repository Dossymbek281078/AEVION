import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Гостевая работа обязана переезжать в аккаунт при входе — и НЕ САМА СОБОЙ.
 *
 * Замер 03.09.2026, двумя независимыми способами:
 *   поиск по именам   claimGuest|migrateGuest|adoptGuest  -> 0
 *   поиск по СПОСОБНОСТИ  SET "userId" в SQL              -> 0
 * То есть человек, попробовавший DevHub гостем и затем вошедший, терял свои
 * проекты из виду: они остаются на «guest:<id>», а личностью после входа
 * становится sub из токена. Ни одного отказа при этом не происходит —
 * список просто приходит пустым, и это неотличимо от «у вас ничего нет».
 *
 * Ручка переноса написана (`POST /api/devhub/studio/adopt-guest`) и закрыта
 * тестами на стороне бэкенда. Здесь охраняется ВТОРАЯ половина, которой у
 * платформы уже не раз не хватало: «механизм собран, части не связаны».
 * Ручка без вызывающего работает ровно как отсутствующая.
 *
 * Сторож намеренно читает ИСХОДНИК, а не рендерит компонент: он ничего не
 * рисует и в тесте пришлось бы подменять и fetch, и хранилище, и токен —
 * тогда проверялись бы заглушки. Цена решения честная: перенос вызова в
 * соседний модуль сторож увидит как пропажу. Это не ложная тревога, а повод
 * прийти сюда и перенести проверку следом.
 */

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const ФАЙЛ = join(ЗДЕСЬ, "..", "DevHubGuestIdentity.tsx");
const src = readFileSync(ФАЙЛ, "utf8");

describe("гостевая работа переезжает в аккаунт: вызов на месте", () => {
  it("прибор исправен: файл прочитан и это тот компонент", () => {
    // Контроль охвата. Без него пустой или чужой файл дал бы «расхождений
    // нет» — самый частый вид ложного зелёного.
    expect(src.length, "файл пуст — сторож охраняет пустоту").toBeGreaterThan(200);
    expect(src, "прочитан не тот файл").toContain("installDevhubGuestHeader");
  });

  it("ручка переноса действительно вызывается", () => {
    expect(
      src,
      "Вызов POST /api/devhub/studio/adopt-guest исчез. Ручка на бэкенде " +
        "останется зелёной по своим тестам, а человек после входа перестанет " +
        "видеть работу, сделанную гостем. Если вызов ПЕРЕЕХАЛ в другой модуль " +
        "— перенесите сюда и эту проверку, а не удаляйте её.",
    ).toContain("/api/devhub/studio/adopt-guest");
    expect(src, "перенос должен идти методом POST").toContain('method: "POST"');
  });

  it("вызов снабжён токеном — иначе ручка не знает, КОМУ переносить", () => {
    // Без Authorization ручка отвечает not_signed_in, и перенос молча
    // не происходит: та же пустота, только с лишним запросом.
    expect(src, "токен входа не читается").toContain("getAuthToken");
    expect(src, "заголовок Authorization не отправляется").toContain("Authorization");
  });

  it("вызов не делается без входа и без гостевой личности", () => {
    // Обе проверки нужны: без входа переносить некуда, без гостя нечего.
    // Их отсутствие — не авария, но это запрос на каждый заход анонимного
    // посетителя, то есть шум в журналах и лишняя нагрузка.
    expect(src, "не проверяется наличие токена и гостевого идентификатора")
      .toMatch(/if\s*\(!\s*[^)]*\|\|\s*!/);
    expect(src, "гостевой идентификатор не читается").toContain("getDevhubGuestId");
  });

  it("успех запоминается, а отказ — нет", () => {
    // Отметка при ОТКАЗЕ означала бы «попробовали один раз и молча сдались»:
    // сеть моргнула — работа потеряна навсегда. Проверяем не строку, а УЧАСТОК
    // между началом обработчика и записью отметки: форма кода менялась уже
    // дважды, а требование к ней всё то же.
    const at = src.indexOf("setItem");
    expect(at, "отметка о переносе не ставится вовсе — ручку будут звать при каждом заходе")
      .toBeGreaterThan(0);
    const начало = src.indexOf(".then(");
    expect(начало, "обработчик ответа не найден").toBeGreaterThan(0);
    expect(
      src.slice(начало, at),
      "Между получением ответа и записью отметки нет проверки r.ok — значит " +
        "отметка ставится и при отказе, и перенос больше НИКОГДА не " +
        "повторится. Гостевая работа будет потеряна насовсем.",
    ).toContain("r.ok");
  });

  it("отметка помнит ЛИЧНОСТЬ, а не просто «да»", () => {
    // Простое «да/нет» возвращает исходный дефект: человек вошёл (перенос
    // сработал), вышел, поработал гостем и вошёл снова — личность браузера та
    // же, отметка стоит, переноса нет, работа снова не видна. То же на общем
    // браузере у второго человека.
    expect(
      src,
      "отметка сравнивается не с гостевой личностью — значит второй перенос " +
        "в этом браузере не произойдёт никогда, и работа снова потеряется",
    ).toContain("getItem(ОТМЕТКА) === гость");
    expect(
      src,
      "в отметку пишется не личность, а признак — тот же дефект с другой стороны",
    ).toContain("setItem(ОТМЕТКА, гость)");
  });

  it("после реального переезда браузер получает новую гостевую личность", () => {
    // Прежняя личность теперь принадлежит аккаунту. Оставить её браузеру —
    // значит положить следующую гостевую работу на уже разобранную личность.
    expect(src, "личность не обновляется после переезда").toContain("rotateDevhubGuestId()");
    const at = src.indexOf("rotateDevhubGuestId()");
    const начало = src.indexOf("adopted > 0");
    expect(начало, "условие реального переезда не найдено").toBeGreaterThan(0);
    expect(
      at > начало,
      "личность меняется НЕ внутри проверки «что-то реально переехало» — тогда " +
        "каждая загрузка страницы меняла бы личность и порождала лишний запрос",
    ).toBe(true);
  });

  it("о переносе оповещают, и оповещение кто-то слушает", () => {
    // Список проектов грузится параллельно переносу и успевает уехать пустым.
    // Без пары «оповестили — перечитали» человек видит ту же пустоту, ради
    // устранения которой перенос и написан: механизм собран, части не связаны.
    expect(src, "о переносе никто не оповещается").toContain("dispatchEvent");
    expect(
      src,
      "оповещение уходит всегда, а не только когда что-то реально переехало — " +
        "это лишний запрос у каждого обычного посетителя",
    ).toContain("adopted > 0");

    // Слушателей ДВА, и они про разное: список проектов и цифра расхода.
    // Второй нашёлся только потому, что я пошёл проверять соседнее место —
    // сама по себе первая починка выглядела законченной.
    for (const [где, путь] of [
      ["список проектов", ["app", "devhub", "page.tsx"]],
      ["цифра расхода", ["app", "studio", "page.tsx"]],
    ] as const) {
        const стр = readFileSync(join(ЗДЕСЬ, "..", "..", ...путь), "utf8");
      expect(
        стр,
        `Страница НЕ слушает оповещение о переносе (${где}). Значит после ` +
          "входа человек увидит пустоту до ручной перезагрузки — ровно ту, " +
          "ради устранения которой перенос и написан.",
      ).toContain("addEventListener(СОБЫТИЕ_ПЕРЕНОСА");
      expect(
        стр,
      "имя события скопировано строкой вместо импорта — две копии одного имени " +
          "расходятся молча",
      ).toContain('from "@/components/DevHubGuestIdentity"');
    }
  });
});
