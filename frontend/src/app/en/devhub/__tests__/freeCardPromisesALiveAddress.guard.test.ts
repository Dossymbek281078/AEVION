/**
 * Карточка бесплатного обещает ЖИВОЙ АДРЕС и называет предел числом из кода.
 *
 * ЗАЧЕМ. Замер первого экрана 07.10.2026 (iframe 390×844 на живом проде): текст
 * единственной бесплатной кнопки — 265 знаков, и 123 из них (46 %) занимал абзац
 * про язык интерфейса. При этом заголовок страницы обещает «Get a deployed
 * project», а карточка гостю — только «generation allowance», то есть сильное из
 * двух обещаний в кнопку не попадало. Выкатка гостю доступна (замер прода 06.10:
 * deploy → живой адрес 200), поэтому недообещание было потерей, а не честностью.
 *
 * ПОЧЕМУ СТОРОЖ ЗВОНИТ В СТРАНИЦУ, А НЕ ЧИТАЕТ ИСХОДНИК. Проверка «в файле есть
 * слово published» зелена и у страницы, где этот текст лежит в неиспользуемой
 * переменной. Здесь страница ИСПОЛНЯЕТСЯ, карточка находится в дереве по своей
 * подписи, и утверждения делаются об ОТРИСОВАННОМ тексте (0-СТОРОЖ-ДЕЛАЕТ-ЗАПРОС).
 *
 * ВТОРАЯ ПОЛОВИНА — число. Предел на странице ДУБЛИРУЕТ таблицу тарифов бэкенда,
 * и это осознанно: посадочная статическая. Такое дублирование уже расходилось —
 * 08.09.2026 в /studio Free обещал 100k знаков озвучки при пределе 10k, то есть
 * переобещание вдесятеро. Поэтому здесь предел читается ИЗ ФАЙЛА БЭКЕНДА и
 * сверяется с текстом; разойдутся — сторож краснеет.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

import Page from "../page";

type Узел = { props?: { children?: unknown }; [k: string]: unknown };

function текст(узел: unknown): string {
  if (typeof узел === "string") return узел;
  if (typeof узел === "number") return String(узел);
  if (Array.isArray(узел)) return узел.map(текст).join("");
  if (узел && typeof узел === "object") return текст((узел as Узел).props?.children);
  return "";
}

function всеУзлы(узел: unknown, собрано: Узел[] = []): Узел[] {
  if (Array.isArray(узел)) {
    for (const э of узел) всеУзлы(э, собрано);
    return собрано;
  }
  if (!узел || typeof узел !== "object") return собрано;
  собрано.push(узел as Узел);
  всеУзлы((узел as Узел).props?.children, собрано);
  return собрано;
}

/** Предел бесплатных выкаток ИЗ КОДА бэкенда — источник правды. */
function пределИзКода(): number {
  const файл = join(process.cwd(), "..", "aevion-globus-backend", "src", "routes", "devhub.ts");
  const код = readFileSync(файл, "utf8");
  const м = код.match(/free:\s*\{[^}]*?deploy:\s*(\d+)/);
  expect(м, "в бэкенде не найден TIER_LIMITS.free.deploy — сторожу не с чем сверять").not.toBeNull();
  const число = Number(м![1]);
  // Контроль прибора: ноль или NaN означали бы «не умею читать», а не «предела нет».
  expect(Number.isInteger(число) && число > 0, `прочитан негодный предел: ${м![1]}`).toBe(true);
  return число;
}

async function текстКарточки(): Promise<string> {
  const дерево = await Page({ searchParams: Promise.resolve({}) } as never);
  const карточки = всеУзлы(дерево).filter((у) => {
    const т = текст(у);
    return т.includes("Open DevHub") && т.includes("$0");
  });
  // Знаменатель: исчезнет подпись — сторож скажет об этом, а не станет зелёным.
  expect(карточки.length, "карточка «Open DevHub» в дереве страницы не найдена")
    .toBeGreaterThanOrEqual(1);
  // Самая глубокая из найденных — сама карточка, а не обёртки вокруг неё.
  return текст(карточки[карточки.length - 1]).replace(/\s+/g, " ");
}

describe("карточка бесплатного на /en/devhub", () => {
  it("обещает живой адрес опубликованного проекта", async () => {
    const т = await текстКарточки();
    expect(т, "в карточке нет обещания публикации — заголовок обещает выкатку, а кнопка нет")
      .toMatch(/publish|live address/i);
  });

  it("называет предел ТЕМ ЖЕ числом, что в таблице тарифов бэкенда", async () => {
    const предел = пределИзКода();
    const т = await текстКарточки();
    /*
     * Граница слова собрана КЛАССАМИ, без экранирования вовсе. Первая редакция
     * писала new RegExp со слэш-b внутри ШАБЛОННОЙ строки — а там одиночный
     * слэш-b означает не границу слова, а символ BACKSPACE (U+0008). Регулярка
     * искала «забой, 10, забой» и честно не находила ничего: проверка краснела
     * на ВЕРНОЙ правке. В регулярных литералах рядом один слэш — то, что нужно;
     * разница в уровне экранирования, а не в съеденном слэше.
     */
    const сЧислом = new RegExp("(?:^|[^0-9])" + предел + "(?:[^0-9]|$)");
    expect(т, `карточка не называет предел ${предел} из TIER_LIMITS.free.deploy`)
      .toMatch(сЧислом);
  });

  it("не тратит текст кнопки на язык интерфейса", async () => {
    /*
     * Отрицательная проверка — против возврата того самого абзаца. Он не был
     * ложью, он занимал 46 % текста в самом дорогом месте страницы.
     */
    const т = await текстКарточки();
    expect(т, "в карточку вернулся абзац про язык интерфейса").not.toMatch(/browser language/i);
  });

  it("сохраняет прежние обещания гостю", async () => {
    // Правка текста не должна втихую убрать то, что уже обещано и работает.
    const т = await текстКарточки();
    expect(т).toMatch(/generation allowance/i);
    expect(т).toMatch(/transfers to your account/i);
    expect(т).toMatch(/\$0/);
  });
});
