import { describe, test, expect } from "vitest";
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

/**
 * Сторож: каждая касса записывает идентификатор платежа у провайдера.
 *
 * ЗАЧЕМ. До 03.09.2026 связать платёж с выдачей можно было только у paybox и
 * paypal — там идентификатор зашит в номер подписки. У Gumroad (главная касса)
 * и LemonSqueezy он не сохранялся вовсе. Следствия:
 *   • поддержка не может ответить «человек заплатил, выдали ли мы»;
 *   • страница успеха не может СПРОСИТЬ, состоялась ли выдача, и потому
 *     показывает тариф прямо из адресной строки — то есть из того, что
 *     подделывается, и из того, что не знает о неудаче.
 *
 * Проверяется ИСХОДНИК, а не поведение: у каждой кассы свой стенд, и поднимать
 * четыре ради одного поля дороже пользы. Зато список касс выводится из
 * КАТАЛОГА ФАЙЛОВ — пятая, добавленная и забытая, попадёт сюда сама.
 *
 * ГРАНИЦА, записанная честно: сторож видит НАЛИЧИЕ поля в вызове, а не то,
 * что в нём непустое значение. Непустоту проверяют поведенческие сторожа
 * конкретных касс.
 */
const каталог = join(__dirname, "..", "src", "routes");

const кассы = readdirSync(каталог)
  .filter((f) => /Webhook\.ts$/.test(f))
  .map((f) => ({ имя: f, текст: readFileSync(join(каталог, f), "utf8") }));

describe("идентификатор платежа сохраняется", () => {
  test("КОНТРОЛЬ: кассы вообще найдены", () => {
    // Иначе «все записывают» удовлетворялось бы пустым списком.
    expect(кассы.map((к) => к.имя).sort(), "список касс пуст или неполон").toEqual([
      "gumroadWebhook.ts",
      "lemonSqueezyWebhook.ts",
      "payboxWebhook.ts",
      "paypalWebhook.ts",
    ]);
  });

  test("каждая касса, которая выдаёт подписку, пишет providerPaymentId", () => {
    const без: string[] = [];
    for (const к of кассы) {
      const выдаёт = к.текст.includes("provisionSubscription({");
      if (!выдаёт) continue;
      if (!к.текст.includes("providerPaymentId:")) без.push(к.имя);
    }
    expect(
      без,
      "касса выдаёт подписку, но не сохраняет идентификатор платежа: связать оплату с выдачей будет нечем"
    ).toEqual([]);
  });

  test("КОНТРОЛЬ: проверка умеет находить отсутствие", () => {
    // Ложный контроль опаснее отсутствия: убеждаемся, что признак ищется, а не
    // совпадает всегда.
    const выдуманная = "provisionSubscription({ email, tierId });";
    expect(выдуманная.includes("providerPaymentId:")).toBe(false);
  });
});
