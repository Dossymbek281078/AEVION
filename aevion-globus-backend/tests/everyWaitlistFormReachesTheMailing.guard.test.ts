import { describe, expect, it } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { matchesModule, isGeneralWaitlist, LAUNCH_MODULES } from "../src/lib/launchAnnounce";

/**
 * Каждая форма подписки доводит человека до письма запуска.
 *
 * 🔴 ЗАЧЕМ. Замер 09.09.2026, за сутки до выхода восьми модулей. Форма
 * подписки стоит на ДВЕНАДЦАТИ страницах, а отбор получателей берёт только две
 * породы меток: метку модуля и метку общей очереди (`go`). Две формы пишут
 * метку вне обоих правил — `home` (ГЛАВНАЯ страница) и `pricing` (страница
 * цен), — и обе показывают текст компонента по умолчанию, а он обещает
 * дословно: «Оставьте адрес — напишем в день запуска того, что вам ближе».
 *
 * То есть человек оставил адрес на главной, прочитав прямое обещание, и письма
 * не получит. Ошибки при этом не произойдёт: рассылка отработает, отчитается
 * числом отправленных, файл списка появится — этих людей просто не будет в
 * списке. Тихий отказ, который выглядит как выполненная работа.
 *
 * 🔴 ПОЧЕМУ СТОРОЖ ХОДИТ ОТ ФОРМ, А НЕ ОТ ПРАВИЛ. Ровно этот случай уже
 * находили 28.08.2026 — тогда с меткой `go` на странице `/go`. Починили
 * добавлением ОДНОЙ метки в правило, а остальные одиннадцать форм не
 * пересмотрели, и через двенадцать дней класс вернулся на других страницах.
 * Проверка, идущая от правил, отвечает на вопрос «покрыты ли известные метки»
 * и по устройству не видит новую форму. Идти надо от того, что обещано
 * человеку, — то есть от форм.
 */

const ФРОНТ = join(__dirname, "..", "..", "frontend", "src", "app");

/**
 * Метки, намеренно НЕ входящие в рассылку запуска, и причина у каждой.
 * Список — утверждение, которое проверяется третьим тестом ниже.
 */
const ИСКЛЮЧЕНИЯ: Record<string, string> = {
  "en-go": "письмо запуска существует только по-русски; отправить его тому, кому обещали английскую страницу, хуже, чем не отправить",
  longevity: "форма книги: обещает протокол долголетия, а не запуск модуля",
  "en-longevity": "то же, английская страница книги",
};

/**
 * Известный долг на 09.09.2026 — метки, которые ДОЛЖНЫ попадать в рассылку,
 * но пока не попадают. Держатся здесь, чтобы набор не покраснел у всех окон до
 * выкатки правки; третий тест следит, чтобы список не пережил свою причину.
 */
const ИЗВЕСТНЫЙ_ДОЛГ: Record<string, string> = {
  // ПУСТО — и это правильное состояние.
  //
  // 09.09.2026: `home` и `pricing` были здесь ровно один день. Окно выкатки
  // добавило их в `isGeneralWaitlist` (коммит ae4df1ab8, цикл 13, на проде),
  // и третий тест ниже потребовал убрать строки отсюда — иначе список
  // известного долга переживает свою причину и превращается в разрешение.
  //
  // Если сюда снова что-то добавляют — рядом обязана быть дата и что именно
  // ждём. Запись без срока живёт вечно.
};

/** Все .tsx страниц, кроме тестов. */
function файлыСтраниц(корень: string): string[] {
  const out: string[] = [];
  const обход = (путь: string) => {
    for (const имя of readdirSync(путь)) {
      const p = join(путь, имя);
      if (statSync(p).isDirectory()) {
        if (имя !== "__tests__") обход(p);
      } else if (имя.endsWith(".tsx") && !имя.includes(".test.")) {
        out.push(p);
      }
    }
  };
  обход(корень);
  return out;
}

/**
 * Метки source у форм подписки.
 *
 * Берём только ЛИТЕРАЛЬНЫЕ значения: `source={source}` на посадочных
 * вычисляется из канала (`bureau`, `bureau-ig`) и всегда начинается с метки
 * модуля — такие ловит matchesModule по префиксу, и проверять их здесь нечем.
 * Граница названа честно: сторож видит литералы, а не выражения.
 */
function меткиФорм(): Array<{ метка: string; файл: string }> {
  const найдено: Array<{ метка: string; файл: string }> = [];
  for (const файл of файлыСтраниц(ФРОНТ)) {
    const src = readFileSync(файл, "utf8");
    let i = 0;
    for (;;) {
      const at = src.indexOf("<WaitlistCapture", i);
      if (at < 0) break;
      const конец = src.indexOf(">", at);
      const блок = src.slice(at, конец < 0 ? at + 600 : конец);
      const m = блок.match(/source=["']([^"']+)["']/);
      if (m) найдено.push({ метка: m[1], файл: файл.slice(файл.indexOf("app")) });
      i = at + 16;
    }
  }
  return найдено;
}

/** Дойдёт ли до человека письмо запуска хотя бы по одному модулю. */
function попадаетВРассылку(метка: string): boolean {
  if (isGeneralWaitlist(метка)) return true;
  return Object.keys(LAUNCH_MODULES).some((slug) => matchesModule(метка, slug));
}

describe("каждая форма подписки доводит до письма запуска", () => {
  const формы = меткиФорм();

  it("прибор видит предмет: формы найдены", () => {
    // без этого «нарушений нет» означало бы «я не нашёл ни одной формы»
    expect(формы.length, "форм подписки не найдено — переименовали компонент?").toBeGreaterThanOrEqual(6);
  });

  it("каждая метка либо попадает в рассылку, либо названа исключением", () => {
    const нарушения: string[] = [];
    for (const { метка, файл } of формы) {
      if (попадаетВРассылку(метка)) continue;
      if (метка in ИСКЛЮЧЕНИЯ) continue;
      if (метка in ИЗВЕСТНЫЙ_ДОЛГ) continue;
      нарушения.push(`${метка} (${файл}) — форма обещает письмо, а отбор её не берёт`);
    }
    expect(нарушения, "новая форма подписки не доходит до рассылки").toEqual([]);
  });

  it("список известного долга не переживает свою причину", () => {
    // Когда метку добавят в isGeneralWaitlist, строка отсюда обязана уйти:
    // иначе список известного превращается в разрешение и живёт вечно.
    const лишние = Object.keys(ИЗВЕСТНЫЙ_ДОЛГ).filter((м) => попадаетВРассылку(м));
    expect(
      лишние,
      "метка уже попадает в рассылку — убери её из ИЗВЕСТНЫЙ_ДОЛГ, долг закрыт",
    ).toEqual([]);
  });
});
