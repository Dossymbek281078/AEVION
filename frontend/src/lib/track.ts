import { apiUrl } from "./apiBase";
import { channelNow, postNow } from "./channelNow";


/**
 * Лёгкий analytics-трекер для GTM-страниц.
 * Без cookies, без fingerprinting — только sessionStorage sid и body event.
 *
 * Использует navigator.sendBeacon когда возможно — гарантирует доставку
 * даже при unload (клик "Купить" → redirect → fetch отменяется в обычном
 * случае, beacon — нет).
 */

const SID_KEY = "aevion_gtm_sid";

export type EventType =
  | "page_view"
  // Использование ключевой возможности продукта (не клик по CTA и не покупка):
  // «дошёл до первого результата». Заведено 06.09.2026 — воронка DevHub была
  // слепа между page_view и checkout_start, и к запуску 10.09 нельзя было бы
  // ответить, сколько посетителей сгенерировало хоть что-то.
  | "feature_use"
  | "cta_click"
  // Карточку приложения ДОВЕЗЛИ до глаз: пара к cta_click на витрине модуля.
  // Заведено 29.09.2026 — переход `/pricing?app=<слаг>` оставлял человека
  // наверху 23-экранной страницы, а карточка стояла на 7.3 экрана вниз, и
  // место обрыва («дошёл до цен, но карточку не увидел») было неразличимо.
  | "app_card_shown"
  | "calculator_open"
  | "calculator_quote"
  | "checkout_start"
  | "checkout_success"
  | "checkout_cancel"
  | "lead_submit"
  | "tier_view"
  | "industry_view"
  | "faq_open"
  | "comparison_view"
  | "affiliate_apply"
  | "partner_apply"
  | "edu_apply"
  // Человек ОТКРЫЛ задачу дня. Заведено 30.09.2026, в день запуска шахмат:
  // за сутки пришло 99 человек и задачу дня решил НОЛЬ. Механизм возврата
  // (серия, цели, плитка) в тот день чинили весь день, и он работает —
  // проверено ручкой, серия 0 → 1. Но до него никто не дошёл, а почему
  // именно, сказать было нечем: события «открыл задачу дня» не было.
  // Без него любая правка входа остаётся догадкой.
  | "daily_open"
  // Человек РЕШИЛ задачу дня и сервер это засчитал. Пара к daily_open: без неё
  // воронка возврата обрывается на «открыл», и отличить «открыл и бросил» от
  // «решил» нечем. Заведено 05.10.2026 — серверная половина имя уже принимала
  // (проверено на проде: daily_solved → 204, выдуманное имя → 400 invalid_type),
  // а фронт его не слал, то есть шаг терялся целиком.
  //
  // Шлём ТОЛЬКО после ответа сервера r.ok: засчитал он, а не мы. Отправка по
  // факту хода на доске считала бы и те решения, которые сервер отверг
  // (wrong_day после UTC-полуночи, 429, 5xx) — и число в воронке разошлось бы
  // с таблицей лидеров.
  | "daily_solved"
  // 07.10.2026. Партия КОНЧИЛАСЬ; meta.outcome — "win" | "loss" | "draw" |
  // "unknown". Пара к серверному ALLOWED_TYPES, завожу одновременно с ним.
  //
  // Зачем, если «попробовал» уже считается через feature_use: feature_use
  // отвечает «сел за доску», а воронка магнита обрывается ПОСЛЕ этого —
  // доиграл ли человек партию или ушёл с третьего хода, по нему не отличить.
  // И ровно к концу партии привязана форма приёма адреса (она открывается
  // через 2.2 с после конца), так что без этой ступени «сколько людей вообще
  // увидело форму» остаётся догадкой.
  | "game_end"
  // 07.10.2026. Человек оставил адрес, и сервер подтвердил постоянное
  // хранение. Шлём ТОЛЬКО после подтверждения — как daily_solved: засчитал
  // сервер, а не мы. Форма жила на проде и писала в базу, а событий не
  // отправляла вовсе: ступень была невидима, и я сам принял это за
  // отсутствие формы.
  //
  // 🔴 Адрес в событие НЕ кладётся никогда: ручка воронки открыта без токена.
  // Только meta.source — имя страницы-источника.
  | "waitlist_submit"
  | "ab_assigned";

export interface TrackPayload {
  type: EventType;
  source?: string;
  tier?: string;
  industry?: string;
  value?: number;
  meta?: Record<string, string | number | boolean | null>;
}

function getSid(): string {
  if (typeof window === "undefined") return "";
  try {
    let sid = sessionStorage.getItem(SID_KEY);
    if (!sid) {
      sid = `s_${Date.now().toString(36)}_${Math.random().toString(36).slice(2, 10)}`;
      sessionStorage.setItem(SID_KEY, sid);
    }
    return sid;
  } catch {
    return "";
  }
}

export function track(payload: TrackPayload): void {
  if (typeof window === "undefined") return;

  // Метка канала приезжает в meta, и сводка воронки читает ТОЛЬКО её: поле
  // path рядом тоже несёт ?c=, но никто его не разбирает — и правильно, туда
  // может прийти что угодно.
  //
  // Найдено 30.08.2026: из десяти мест, шлющих начало оплаты, метку клали два.
  // Восемь остальных — страницы модулей, витрина, тарифы, посадочные под
  // ролики — сообщали «начали платить», не говоря откуда пришёл человек.
  // Чинится здесь, в единственной точке, через которую проходят все события:
  // восемь одинаковых правок были бы восемью копиями одного механизма, и
  // девятое место снова родилось бы без метки.
  //
  // Если отправитель метку передал — она старше: серверная страница читает ?c=
  // надёжнее, чем мы здесь по адресу в браузере.
  const givenChannel = payload.meta?.channel;

  const channel = channelNow();
  // Пост — рядом с каналом, отдельным полем. Без него «какой пост сработал»
  // остаётся без ответа: у канала одна метка на все ссылки (замер 30.09.2026).
  const post = postNow();
  /*
   * 🔴 ПОСТ ПРИКЛАДЫВАЕТСЯ ВСЕГДА, а не только когда канал определили мы.
   *
   * Было: если отправитель передал свой `channel`, meta возвращалась КАК ЕСТЬ —
   * вместе с каналом терялся и пост. А `channel` передают все: `PageTracking`
   * шлёт `meta: { channel }` на каждой странице, вычисляя его сам. То есть
   * ветка «добавить пост» не исполнялась практически никогда.
   *
   * Замер 05.10.2026: разрез `byPost` пуст за 1/7/14/30 дней, при том что три
   * ролика с подметками (`?c=yt-chess-level` и соседние) собрали 457 просмотров
   * с 01.10. Канал при этом доезжает верно — проверено заходом: две мои пробы
   * с `?c=yt-chess-level` легли в `youtube`, а не в «direct». Терялся ровно пост.
   *
   * Поэтому правило теперь простое и несимметричное по-честному:
   *   канал — старше у отправителя (серверная страница знает лучше нас);
   *   пост  — добавляем, если его никто не передал и мы его знаем.
   */
  const givenPost = payload.meta?.post;
  const собранная: Record<string, string | number | boolean | null> = { ...(payload.meta ?? {}) };
  if (!givenChannel && channel) собранная.channel = channel;
  if (!givenPost && post) собранная.post = post;
  const meta = Object.keys(собранная).length > 0 ? собранная : undefined;

  /*
   * 🔴 Признак автоматики шлём САМИ: по строке браузера её видно не всегда.
   *
   * Замер 06.10.2026 (окно Роликов): съёмка через Playwright с боевой меткой
   * дала три «визита зрителей», и фильтр роботов их не отсёк — в User-Agent
   * той сборки Chromium слова «Headless» нет. То есть наша же съёмка попадала
   * в живые числа, а отличить её на сервере было нечем.
   *
   * `navigator.webdriver` ставит сам браузер, когда им управляет программа
   * (Playwright, Puppeteer, Selenium). Это булево про ПРОГРАММУ, а не про
   * человека: ничего личного в нём нет, и отправляем мы его только когда он
   * истинен — чтобы не раздувать каждое событие ложным полем.
   */
  /*
   * 🔴 ОТКУДА ПРИШЁЛ — только ХОСТ, и только он.
   *
   * Замер 06.10.2026: канал `direct` дал 226 живых заходов за 14 дней, из них
   * 212 неопознанных — 60 % всего живого трафика, про который нельзя сказать
   * ничего. Причина не в недосмотре: `document.referrer` мы не записывали
   * нигде, ни на фронте, ни на сервере. То есть вопрос «откуда люди» был
   * неотвечаем ПО УСТРОЙСТВУ.
   *
   * Берём именно хост, а не адрес целиком: в пути и запросе чужой страницы
   * живут идентификаторы, поисковые фразы и токены — им в нашем журнале не
   * место, тем более что разрез воронки публичный. Хост отвечает на вопрос
   * «какая площадка привела» и больше ни на какой.
   *
   * Пустая строка — тоже ответ, и важный: её дают встроенные браузеры
   * приложений, закладки, набранный вручную адрес и переход с https на http.
   * Поэтому отсутствие ОТЛИЧАЕМ от «не записали»: пустую не шлём вовсе, а на
   * сервере она читается как «источник не назван».
   */
  const откуда = (() => {
    try {
      const r = typeof document === "undefined" ? "" : document.referrer;
      if (!r) return "";
      const хост = new URL(r).hostname.toLowerCase().replace(/^www\./, "");
      return хост.slice(0, 60);
    } catch {
      return "";
    }
  })();

  const подУправлением =
    typeof navigator !== "undefined" && (navigator as Navigator).webdriver === true;

  /*
   * Оповещаем страницу о событии — этим пользуются рекламные счётчики.
   *
   * Найдено 31.08.2026: счётчик Meta/TikTok ловил только клики по ССЫЛКАМ в
   * кассу. А три главных пути оплаты — таблица тарифов, чип модуля и кнопка
   * апселла — это КНОПКИ: адрес они получают от бэкенда и уходят по нему
   * скриптом. То есть при включённой рекламе покупки с самой посещаемой
   * денежной страницы до площадки бы не дошли, а площадка учится именно на
   * этих событиях.
   *
   * Событие идёт через window, а не прямым вызовом счётчика: учёт не должен
   * знать про рекламу. Кто хочет — подписывается.
   */
  try {
    window.dispatchEvent(new CustomEvent("aevion:track", { detail: { ...payload, meta } }));
  } catch {
    // Оповещение не должно ломать сам замер: если CustomEvent недоступен,
    // событие всё равно уйдёт на сервер строкой ниже.
  }

  const body = JSON.stringify({
    ...payload,
    ...(meta ? { meta } : {}),
    ...(подУправлением ? { webdriver: true } : {}),
    ...(откуда ? { refHost: откуда } : {}),
    sid: getSid(),
    path: window.location.pathname + window.location.search,
  });

  const url = apiUrl("/api/pricing/events");

  // sendBeacon — лучший выбор: переживёт unload, не блокирует UI
  if (typeof navigator !== "undefined" && typeof navigator.sendBeacon === "function") {
    try {
      const blob = new Blob([body], { type: "application/json" });
      const ok = navigator.sendBeacon(url, blob);
      if (ok) return;
    } catch {
      // fall through to fetch
    }
  }

  // Fallback: fire-and-forget fetch с keepalive
  try {
    fetch(url, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body,
      keepalive: true,
    }).catch(() => {
      // Аналитика не должна ломать UX — глотаем
    });
  } catch {
    // ignore
  }
}
