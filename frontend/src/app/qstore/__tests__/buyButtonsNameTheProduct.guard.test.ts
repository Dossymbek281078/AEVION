import { describe, expect, it } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Кнопка покупки называет ТОВАР, а не действие.
 *
 * ЗАМЕР соседнего окна на живом проде 04.09.2026: на этой странице 27 кнопок
 * с одинаковым доступным именем «купить». Читалка умеет показать список
 * кнопок страницы — человек так и выбирает, куда нажать. Двадцать семь
 * одинаковых строк подряд выбирать не дают, а это единственный экран
 * платформы, где отдают деньги за КОНКРЕТНЫЙ товар.
 *
 * Признак опасного места общий и стоит запомнить: подпись, написанная ВНУТРИ
 * цикла отрисовки. Диф показывает, ЧТО изменилось, и молчит о том, СКОЛЬКО
 * РАЗ строка отрисуется — поэтому глазами такое не ловится.
 *
 * ГРАНИЦА. Сторож стережёт ЭТУ страницу, а не класс: он читает исходник и
 * требует, чтобы имя кнопки было выведено из товара. Другие списки платформы
 * он не видит. Класс шире — 28 находок на 17 страницах в том же замере, — и
 * закрывать его надо там, где живут те списки.
 */

const СТРАНИЦА = readFileSync(
  join(dirname(fileURLToPath(import.meta.url)), "..", "page.tsx"),
  "utf8",
);

describe("кнопки покупки различают товар", () => {
  it("прибор исправен: кнопка покупки на странице есть", () => {
    // Без этого переименование кнопки делает сторожа вечнозелёным.
    expect(СТРАНИЦА, "кнопки покупки не найдено — сторож проверял бы пустоту")
      .toContain('"Get free" : "Buy"');
  });

  it("имя кнопки выведено из товара, а не зашито", () => {
    // Ищем подстановку названия товара В ИМЕНИ. Просто наличие aria-label
    // не годится: aria-label="Buy" отличался бы от содержимого и не различал
    // бы ничего — то есть был бы формой без следствия.
    const i = СТРАНИЦА.indexOf('aria-label={');
    expect(i, "у кнопки покупки нет собственного имени").toBeGreaterThan(-1);
    const блок = СТРАНИЦА.slice(i, СТРАНИЦА.indexOf("}" + String.fromCharCode(10), i) + 1);
    // Проверяем КАЖДУЮ ветку, а не наличие подстановки где-нибудь.
    //
    // Первая редакция требовала `product.title` хотя бы раз — и мутация её
    // НЕ поймала: у имени две ветки (платный товар и бесплатный), я сломал
    // одну, вторая сохранила подстановку, сторож остался зелёным. «Хотя бы
    // один» терпит потерю всех, кроме одного.
    // Разбираем позиционно, без регулярок: на этой машине они трижды за день
    // теряли слэши на границе вызова и молча переставали находить что-либо.
    // Обратная кавычка — через код символа: пара `` в исходнике это
    // ПУСТАЯ шаблонная строка, а не символ. Первая редакция сравнивала символ
    // с пустотой, находила ноль кусков и падала на собственном контроле —
    // хорошо, что контроль был.
    const КАВЫЧКИ = [String.fromCharCode(96), '"', "'"];
    const куски: string[] = [];
    let k = 0;
    while (k < блок.length) {
      if (КАВЫЧКИ.includes(блок[k])) {
        const конец = блок.indexOf(блок[k], k + 1);
        if (конец < 0) break;
        куски.push(блок.slice(k, конец + 1));
        k = конец + 1;
      } else {
        k += 1;
      }
    }
    const безПодстановки = куски.filter((к) => !к.includes("${") && к.length > 4);
    expect(
      безПодстановки,
      "ветка имени без подстановки: кнопки этого списка назовутся одинаково",
    ).toEqual([]);
    expect(куски.length, "имя кнопки разобрать не удалось").toBeGreaterThan(0);
  });
});
