import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Списание, «припаркованное» в память при отказе записи, обязано читаться обратно.
 *
 * Половина починки от 12.08, которую ничего не охраняло. `debitCredit()` при
 * отказе записи в базу кладёт списание в `memUsage`. Раньше `getMonthUsage()`
 * читал эту память ТОЛЬКО когда база заведомо недоступна — а при базе,
 * формально живой и при этом отказывающей, списание уходило в никуда. Починка
 * добавила слагаемое `+ memUsage.get(memKey)` в путь «база отвечает».
 *
 * ПОЧЕМУ СТОРОЖ ПО ИСХОДНИКУ, А НЕ ПО ПОВЕДЕНИЮ — и это его слабость, которую
 * надо знать. Чтобы списание вообще случилось, маршрут должен успешно
 * сгенерировать картинку (или звук, или выкатку): `debitCredit` стоит ПОСЛЕ
 * успеха провайдера. В харнесе честности учёта провайдеров нет намеренно
 * (`getProviders: () => []`), поэтому до списания дело не доходит, и
 * поведенческого пути к этой ветке из тестов нет.
 *
 * Замер, из-за которого сторож и появился: мутация, удаляющая слагаемое, НЕ
 * ловилась ни одним из шести перенесённых тестов. То есть строку можно было
 * снять, и все проверки остались бы зелёными.
 *
 * Сторож слабее поведенческого: он ловит удаление строки, но не докажет, что
 * число сложилось верно. Это лучше, чем ничего, и честнее, чем поведенческий
 * тест, который пришлось бы построить на выдуманном провайдере.
 */

const FILE = path.join(__dirname, "..", "src", "routes", "devhub.ts");

/** Тело функции чтения расхода, без комментариев. */
function getMonthUsageBody(): string {
  const src = fs.readFileSync(FILE, "utf8");
  const start = src.indexOf("async function getMonthUsage");
  expect(start, "функция чтения расхода не найдена — сторож смотрит не туда").toBeGreaterThan(-1);
  const end = src.indexOf("\n}", start);
  return src
    .slice(start, end)
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .split("\n")
    .filter((l) => !l.trim().startsWith("//"))
    .join("\n");
}

describe("припаркованное списание читается обратно", () => {
  test("прибор работает: тело функции найдено и непустое", () => {
    const body = getMonthUsageBody();
    expect(body.length).toBeGreaterThan(150);
    expect(body).toContain("DevHubUsage");
  });

  test("к прочитанному из базы прибавляется запасная память", () => {
    const body = getMonthUsageBody();
    expect(
      body,
      "слагаемое из запасной памяти убрано — списания, сделанные во время отказа записи, снова уходят в никуда",
    ).toMatch(/memUsage\.get\(memKey\)/);
    // Именно СЛОЖЕНИЕ, а не выбор одного из двух: при живой базе обе величины
    // настоящие, и потерять надо ни одну.
    expect(body).toMatch(/\+\s*\(memUsage\.get\(memKey\) \?\? 0\)/);
  });

  test("неудачное чтение по-прежнему отвечает «не знаю», а не нулём", () => {
    // Направление: «слагаемое на месте» выполняется и в версии, которая на
    // отказе возвращает 0 — а это исходный дефект.
    // Закреплять ФОРМУ молчаливого catch нельзя: 30.08.2026 в эту ветку
    // добавлен след в журнал (без него отказ чтения невидим, и предел
    // перестаёт применяться незаметно). Смысл тот же — отказ отдаёт null, а
    // не число, — и проверяем теперь его, а не запись.
    const body = getMonthUsageBody();
    expect(body).toMatch(/catch\s*\(?e?\)?\s*\{[\s\S]*?return null;[\s\S]*?\}/);
  });
});
