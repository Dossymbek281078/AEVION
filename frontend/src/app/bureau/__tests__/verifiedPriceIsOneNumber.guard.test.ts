/*
 * Цена на витрине бюро — ОДНО число, и оно то же, что назовёт касса.
 *
 * 🔴 Замер 30.09.2026: «$19» стояло зашитым в 11 строках шести файлов бюро, а
 * бэкенд уже считал $29 (решение основателя 14.09, период 15.09 — ежемесячно).
 * Одиннадцать копий одного числа расходятся молча и всегда; здесь они разошлись
 * на самом денежном шаге платформы, где бюро — объявленный фокус продаж.
 *
 * Сторож читает файл БЭКЕНДА, а не повторяет число: иначе модуль верifiedPrice
 * стал бы двенадцатой копией, а не источником.
 */
import { describe, expect, it } from "vitest";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ЦЕНА_ПРОВЕРКИ_ЦЕНТЫ, ценаТекстом, ценаСПериодом } from "../verifiedPrice";

const ЗДЕСЬ = dirname(fileURLToPath(import.meta.url));
const БЮРО = join(ЗДЕСЬ, "..");
const БЭКЕНД = join(ЗДЕСЬ, "..", "..", "..", "..", "..", "aevion-globus-backend", "src", "lib", "payment", "index.ts");

function файлы(каталог: string, собрано: string[] = []): string[] {
  for (const имя of readdirSync(каталог)) {
    const путь = join(каталог, имя);
    if (statSync(путь).isDirectory()) {
      if (имя === "__tests__" || имя === "node_modules") continue;
      файлы(путь, собрано);
    } else if (/\.tsx?$/.test(имя) && !/\.test\.tsx?$/.test(имя) && имя !== "verifiedPrice.ts") {
      собрано.push(путь);
    }
  }
  return собрано;
}

/*
 * Ищем ЦЕНУ ОТМЕТКИ, а не любые доллары.
 *
 * Первая редакция этого сторожа запрещала в разметке любое «$<число>» — и
 * покраснела на законных ценах ДРУГИХ товаров бюро ($0 у бесплатной ступени,
 * $89 у нотариальной). Сторож, который краснеет на верном коде, отключают, а не
 * читают, — поэтому сузил до цены отметки: сегодняшней (из модуля) и прежней
 * $19, которая и разъехалась с кассой. Сменится цена — сменится и образец, а
 * зашитая копия снова станет видимой.
 */
function безКомментариев(src: string): string {
  return src.replace(new RegExp("\\/\\*[\\s\\S]*?\\*\\/", "g"), "")
            .replace(new RegExp("\\/\\/.*$", "gm"), "");
}

const ЦЕНА_ОТМЕТКИ = new RegExp(
  // Обычные строки с удвоенным слэшем: в шаблонной `\$` становится ЯКОРЕМ конца
  // строки, а String.raw оставляет двойной слэш как есть. Оба раза прибор молча
  // не находил ничего — поймано контролем ниже, он ради этого и стоит.
  "\\$(?:" + (ЦЕНА_ПРОВЕРКИ_ЦЕНТЫ / 100).toFixed(0) + "|19)(?:\\.00)?\\b",
  "g",
);




describe("цена проверки бюро живёт в одном месте", () => {
  it("число на витрине равно умолчанию бэкенда", () => {
    const src = readFileSync(БЭКЕНД, "utf8");
    const m = /if \(!raw\) return (\d+);/.exec(src);
    expect(m, "не нашёл умолчание цены в бэкенде — сторож ослеп, а не «всё хорошо»").toBeTruthy();
    expect(Number(m![1]), "витрина и касса назвали бы разные суммы").toBe(ЦЕНА_ПРОВЕРКИ_ЦЕНТЫ);
  });

  it("период — часть цены: «$29» без «в месяц» это другое обещание", () => {
    expect(ценаТекстом()).toBe("$29");
    expect(ценаСПериодом()).toBe("$29/month");
    // Живое значение главнее записанного: касса назовёт именно его.
    expect(ценаСПериодом(3200)).toBe("$32/month");
    // Отрицательные контроли: мусор не превращается в цену молча.
    expect(ценаТекстом(null)).toBe("$29");
    expect(ценаТекстом(Number.NaN)).toBe("$29");
  });

  it("ни один файл бюро не пишет цену числом в разметке", () => {
    const список = файлы(БЮРО);
    // Знаменатель печатаем: сторож, который обошёл ноль файлов, зелёный и слепой.
    expect(список.length, "обход не нашёл файлов бюро — проверять было нечего").toBeGreaterThan(5);
    const виновные: string[] = [];
    for (const путь of список) {
      // Комментарии снимаем: текст О цене — не цена. Без этого сторож краснел на
      // пояснении «заплатить $29 в месяц» в kycDisclosure.ts, то есть на верном
      // коде, а такие проверки перестают читать (проверено на себе же).
      const текст = безКомментариев(readFileSync(путь, "utf8"));
      const найдено = текст.match(ЦЕНА_ОТМЕТКИ);
      if (найдено) виновные.push(`${путь.replace(БЮРО, "bureau")}: ${[...new Set(найдено)].join(", ")}`);
    }
    expect(виновные, `проверено файлов: ${список.length}`).toEqual([]);
  });

  it("контроль прибора: он находит цену, когда она есть", () => {
    expect("Pay $19 now".match(ЦЕНА_ОТМЕТКИ)).toEqual(["$19"]);
    expect("Pay {ценаСПериодом()} now".match(ЦЕНА_ОТМЕТКИ)).toBeNull();
  });
});
