import { describe, it, expect } from "vitest";
import { наградаЗаВозврат } from "../dailyReward";

/**
 * Награда за возвращение — то, ради чего человек приходит на второй день.
 * До 28.08.2026 расчёт жил четырьмя строками внутри компонента и не был
 * закреплён ничем: сдвинь порог — никто не заметит, пока не пожалуется
 * человек, у которого серия обнулилась.
 */
describe("награда за возвращение", () => {
  const сегодня = "2026-8-28";
  const вчера = "2026-8-27";

  it("пришёл сегодня повторно — награды нет", () => {
    expect(наградаЗаВозврат(сегодня, 3, сегодня, вчера)).toBeNull();
  });

  it("был вчера — серия растёт", () => {
    expect(наградаЗаВозврат(вчера, 3, сегодня, вчера)).toEqual({ streak: 4, bonus: 30 });
  });

  it("пропустил день — серия начинается заново", () => {
    expect(наградаЗаВозврат("2026-8-20", 9, сегодня, вчера)).toEqual({ streak: 1, bonus: 5 });
  });

  it("первый заход без истории — серия 1", () => {
    expect(наградаЗаВозврат(undefined, 0, сегодня, вчера)).toEqual({ streak: 1, bonus: 5 });
  });

  it("пороги наград на своих местах", () => {
    // 3 дня → 30, 7 → 100, 14 → 200. Числа обещаны человеку в окне награды
    // («Следующий рубеж: 7 дней → +100»), поэтому меняются только осознанно.
    expect(наградаЗаВозврат(вчера, 2, сегодня, вчера)?.bonus).toBe(30);
    expect(наградаЗаВозврат(вчера, 6, сегодня, вчера)?.bonus).toBe(100);
    expect(наградаЗаВозврат(вчера, 13, сегодня, вчера)?.bonus).toBe(200);
    expect(наградаЗаВозврат(вчера, 1, сегодня, вчера)?.bonus).toBe(5);
  });
});
