// Откуда взялась бронь в рынке 4D-слотов: человек её сделал или смоук-прогон.
//
// 10.08.2026, живой aevion.app: панель писала «Рынок 4D-слотов (QRight) · 34», и
// 33 из этих 34 были выводом смоук-набора — маршруты `smoke-route-…`,
// держатели `op0..op3`, `late`, `verify`, `smoke-holder`. Прочитано это как
// рыночная активность: в панели настоящие SHA-256-квитанции, отличить нечем.
//
// Прятать их неправильно: право действительно зафиксировано, квитанция честная,
// а молча вычесть 33 из 34 — значит подменить одну неправду другой. Правильно —
// НАЗВАТЬ: сколько записей тестовые и какая именно тестовая. Это ровно то, чем
// занят весь модуль — отличать «наше» от «регуляторного» и «замеренное» от
// «угаданного»; своя тестовая бронь ничем не лучше.

export interface SlotLike {
  routeId?: string;
  holder?: string;
  /**
   * Ответ сервера. Он считает то же самое (`lib/slotOrigin.ts`) и является
   * источником правды: если поле пришло — верим ему, а не пересчитываем. Свой
   * разбор остаётся только на случай, когда фронт новее задеплоенного бэкенда —
   * иначе на проде до выката панель молчала бы о тестовых бронях.
   */
  test?: boolean;
}

/** Держатели, которыми представляются смоук-сценарии (см. scripts/*-smoke.js). */
const SMOKE_HOLDERS = new Set(["smoke-holder", "verify", "op0", "op1", "op2", "op3", "late", "h0", "h1", "h2", "h3"]);

/** Держатель демо-кнопки самой страницы — не рынок (см. lib/slotOrigin.ts на сервере). */
const DEMO_HOLDERS = new Set(["aevion demo"]);

/**
 * Тестовая ли это бронь.
 *
 * Признак маршрута — основной: смоки строят `smoke-route-…`. Держатель —
 * второй, для записей, где маршрут назван иначе. Оба намеренно грубые: ошибка в
 * сторону «пометил тестовой настоящую» видна и чинится, а обратная — снова
 * выдаёт прогон за рынок.
 */
export function isSmokeSlot(slot: SlotLike): boolean {
  if (typeof slot.test === "boolean") return slot.test;
  const route = (slot.routeId ?? "").toLowerCase();
  if (route.startsWith("smoke-") || route.includes("-smoke-")) return true;
  const holder = (slot.holder ?? "").toLowerCase();
  return SMOKE_HOLDERS.has(holder) || DEMO_HOLDERS.has(holder);
}

/** Сколько записей из списка — тестовые. */
export function countSmokeSlots(slots: readonly SlotLike[]): number {
  return slots.reduce((n, s) => n + (isSmokeSlot(s) ? 1 : 0), 0);
}
