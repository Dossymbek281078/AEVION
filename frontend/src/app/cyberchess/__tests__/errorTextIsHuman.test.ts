import { describe, test, expect } from "vitest";
import * as fs from "node:fs";
import * as path from "node:path";
import { stripComments } from "./_stripComments";

// Тексты ошибок — человеческие. 19.08.2026.
//
// Ворота запуска, пункт 4: «отказ показывается отказом; тексты ошибок
// человеческие, без кодов и адресов серверов». На странице повторов партий в
// сообщение попадал текст исключения — то есть «HTTP 500» и «API returned
// ok=false». Это язык разработчика: человек из него не понимает ни что
// случилось, ни что делать.
//
// Технический текст не потерян — он уходит в консоль, где и нужен.

const SRC = path.join(__dirname, "..", "replays", "page.tsx");

describe("страница повторов говорит с человеком по-человечески", () => {
  test("в сообщение не подставляется текст исключения", () => {
    const s = stripComments(fs.readFileSync(SRC, "utf-8")).replace(/\s+/g, " ");
    expect(s).not.toMatch(/setError\(e instanceof Error \? e\.message/);
    expect(s).toMatch(/Не удалось загрузить партии/);
  });

  test("технический текст всё же сохраняется — в консоли", () => {
    // Иначе починка «для человека» превратилась бы в потерю диагностики.
    const s = stripComments(fs.readFileSync(SRC, "utf-8"));
    expect(s).toMatch(/console\.warn\(/);
  });
});

describe("во всём модуле текст исключения не показывается человеку", () => {
  test("ни одна страница не подставляет e.message в сообщение", () => {
    // Свип по классу, а не по одному файлу: сегодня нашлось три места, и все
    // три показывали «HTTP 500» или «API returned ok=false».
    const корень = path.join(__dirname, "..");
    const файлы: string[] = [];
    const обойти = (d: string) => {
      for (const e of fs.readdirSync(d, { withFileTypes: true })) {
        const p = path.join(d, e.name);
        if (e.isDirectory()) { if (e.name !== "__tests__") обойти(p); }
        else if (/\.tsx?$/.test(e.name)) файлы.push(p);
      }
    };
    обойти(корень);
    // ЗНАМЕНАТЕЛЬ. Без него «нарушений нет» неотличимо от «не просмотрено ни
    // одного файла» — и сторож зеленеет, ничего не проверив. Проверено на
    // себе: мутация в spectator/page.tsx не краснела, потому что обход не
    // доходил до файлов.
    expect(файлы.length, "обход не нашёл файлов — сторож ничего не проверил").toBeGreaterThan(15);
    // НЕСКОЛЬКО простых шаблонов вместо одного хитрого. Первая редакция была
    // «умной» — и не ловила НИ ОДНОГО из трёх вариантов, что показал контроль.
    // Сложный шаблон невозможно проверить глазами, а простые — можно.
    //
    // Урок того же дня: чужой сторож требовал двойных кавычек и не видел 7
    // объявлений из 513; ровно те пять оказались единственными незащищёнными.
    const ПОКАЗ_ИСКЛЮЧЕНИЯ = [
      /set(Error|Message)\(\s*\(?\s*(e|err|error)\b[^;]{0,40}\.message/,  // setError(e.message), setError((e as Error).message)
      /set(Error|Message)\(\s*String\(\s*(e|err|error)\b/,                // setError(String(e))
      /set(Error|Message)\(\s*`[^`]*\$\{\s*(e|err|error)\b/,              // setError(`${e}`)
    ];
    // ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ шаблонов — прямо здесь, а не мутацией руками.
    //
    // 19.08.2026 этот сторож был ложно-зелёным: граница слова уехал в файл символом
    // BACKSPACE (правка через heredoc), и шаблоны не совпадали НИ С ЧЕМ,
    // выглядя правильными в редакторе. Мутационный контроль тогда тоже
    // соврал — красный цвет был от parse error, а не от поимки.
    //
    // Теперь каждый шаблон обязан узнать свой образец. Испортится шаблон —
    // сторож краснеет сразу, а не молчит годами.
    const ОБРАЗЦЫ = [
      'setError(err.message);',
      'setError(String(e));',
      'setError(`сбой: ${e}`);',
    ];
    ПОКАЗ_ИСКЛЮЧЕНИЯ.forEach((re, i) => {
      expect(re.test(ОБРАЗЦЫ[i]), `шаблон ${i + 1} не узнаёт свой образец ${ОБРАЗЦЫ[i]} — он испорчен`).toBe(true);
    });
    // И отрицательный контроль: на человеческом тексте не срабатывает ни один.
    const ЧЕЛОВЕЧЕСКИЙ = 'setError("Не удалось загрузить список. Попробуйте позже.");';
    expect(ПОКАЗ_ИСКЛЮЧЕНИЯ.some((re) => re.test(ЧЕЛОВЕЧЕСКИЙ)), "шаблон краснеет на нормальном тексте").toBe(false);

    // Читаем СЫРОЙ исходник, отбрасывая только строки-комментарии.
    //
    // Через stripComments сторож был ЛОЖНО-ЗЕЛЁНЫМ: шаблон находил мутацию в
    // сыром файле и не находил после обработки. Это известный класс — вырезалка
    // теряет состояние кавычек на одной непарной и съедает код за ней.
    //
    // Отбросить строки, начинающиеся с // или *, достаточно: шаблоны здесь
    // узкие, и пример в конце строки кода нам не помеха.
    const плохие = файлы.filter((f) => {
      const src = fs.readFileSync(f, "utf-8")
        .split("\n")
        .filter((l) => { const t = l.trim(); return !(t.startsWith("//") || t.startsWith("*") || t.startsWith("/*")); })
        .join("\n");
      return ПОКАЗ_ИСКЛЮЧЕНИЯ.some((re) => re.test(src));
    });
    expect(плохие.map((f) => path.relative(корень, f))).toEqual([]);
  });
});

// ГРАНИЦА ЭТОГО СТОРОЖА, названная честно.
//
// Он смотрит setError/setMessage и сообщение очереди. НЕ смотрит showToast —
// а это 315 вызовов, и все они в page.tsx, который ведут четыре чужие ветки.
// Расширить сюда значит завести заведомо красный тест на файле, который я не
// правлю: такой тест снимут в первый же день, и защиты не станет вовсе.
//
// Три места там реальны и переданы владельцу списком
// (Desktop\АЕВИОН-CyberChess6-08-19\ГЛАВНАЯ-страница-язык-12-мест.md):
// «Lichess: <текст исключения>», «Lichess недоступен: <…>», «Голос: <код>».
// Когда файл станет доступен — сюда добавляется showToast и строка исчезает.

describe("код ошибки не доходит до человека", () => {
  // 21.08. В матчмейкинге при отказе показывали «Не удалось встать в очередь:
  // unknown» — внутренний код в тексте для человека. Он ничего не объясняет и
  // выглядит поломкой. Код теперь уходит в консоль.
  const SRC_MM = path.join(__dirname, "..", "matchmaking", "page.tsx");

  test("шаблон узнаёт свой образец", () => {
    const obrazec = 'message: `Не удалось встать в очередь: ${data?.error || "unknown"}`';
    expect(/message:[^;]*\$\{[^}]*error/.test(obrazec)).toBe(true);
  });

  test("в сообщении очереди нет кода ошибки", () => {
    const src = fs.readFileSync(SRC_MM, "utf-8")
      .split("\n")
      .filter((l) => !l.trim().startsWith("//"))
      .join("\n");
    expect(src, "код ошибки вернулся в текст для человека")
      .not.toMatch(/message:[^;]*\$\{[^}]*error/);
    expect(src, "код перестал уходить в консоль").toContain("[matchmaking] очередь отказала:");
  });
});
