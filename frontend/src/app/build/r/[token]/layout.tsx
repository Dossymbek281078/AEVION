import type { Metadata } from "next";

/**
 * Персональная ссылка рекрутёра не должна попадать в поисковую выдачу.
 *
 * Страница — чистое перенаправление: содержимого у неё нет вовсе, только
 * «Redirecting…». Индексировать такое бессмысленно, а вредно дважды:
 *
 * 1. Токенов бесконечно много (это идентификатор пользователя), и каждый
 *    отвечал бы 200 с полной страницей — бесконечный индексируемый мусор.
 * 2. В выдачу попали бы личные идентификаторы рекрутёров. Секретом токен
 *    не является (так и написано в page.tsx), но это не повод его
 *    публиковать в поиске.
 *
 * Метаданные живут ЗДЕСЬ, а не в page.tsx, потому что страница браузерная
 * ("use client"), а Next не разрешает экспортировать metadata из такой.
 *
 * `follow: true` намеренно: ссылка ведёт на живой список вакансий, и обход
 * по ней полезен — запрещаем индексировать саму страницу-перенаправление,
 * а не то, куда она ведёт.
 */
export const metadata: Metadata = {
  robots: { index: false, follow: true },
};

export default function ShareLinkLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  return <>{children}</>;
}
