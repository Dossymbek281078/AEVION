/**
 * ЗАВЕРШЕНИЕ ПО СИГНАЛУ ЗАМЕНЫ — С КОДОМ 0.
 *
 * 🔴 Повод, замер 30.09–01.10.2026: Railway прислал «Deploy Crashed!» на КАЖДУЮ из
 * пяти выкаток, каждое письмо через ~2 минуты после старта. При этом в истории все
 * деплои SUCCESS→REMOVED, ни одного FAILED, а /health отвечал новым коммитом. То есть
 * «падал» СТАРЫЙ экземпляр в момент, когда его гасят при замене: у процесса не было
 * обработчика SIGTERM, Node уходил по умолчанию, и платформа читала это как аварию.
 *
 * Цена дефекта не в письмах, а в том, что они приучают НЕ ЧИТАТЬ письма: настоящее
 * падение утонет среди пяти ложных. Это наш записанный класс «сторож, который всегда
 * красный, перестают смотреть».
 *
 * Правило здесь: сначала перестать принимать новые соединения, потом закрыть пул базы,
 * и только потом выйти — кодом 0, потому что замена это не авария.
 *
 * ⚠️ Жёсткий предел обязателен. Если долгий запрос или живой websocket держит сервер,
 * `close` не позовёт обратный вызов никогда, и процесс будет убит платформой по
 * таймауту — то есть письмо «Crashed» вернётся. Поэтому через `пределМс` выходим
 * нулём в любом случае, предупредив в журнал: честный выход лучше молчаливого зависания.
 */

export interface Завершаемое {
  /** HTTP-сервер: перестать принимать соединения. */
  сервер: { close(обратно: (ошибка?: Error) => void): void };
  /** Закрыть пул базы. Не должен открывать его, если пула не было. */
  закрытьПул: () => Promise<void>;
  /** Выход. Отдельно, чтобы сторож мог увидеть КОД. */
  выход: (код: number) => void;
  /** Куда писать. По умолчанию console. */
  журнал?: { log: (...а: unknown[]) => void; warn: (...а: unknown[]) => void; error: (...а: unknown[]) => void };
  /** Предел ожидания закрытия, мс. По умолчанию 8000. */
  пределМс?: number;
  /** Таймер; выделен, чтобы тест не ждал восемь секунд. */
  таймер?: (обратно: () => void, мс: number) => { unref?: () => void };
}

/** Подписчик на сигнал. Возвращается отдельно, чтобы сторож мог позвать его сам. */
export function обработчикЗавершения(ц: Завершаемое): (сигнал: string) => void {
  const журнал = ц.журнал ?? console;
  const предел = ц.пределМс ?? 8000;
  const таймер = ц.таймер ?? ((о, м) => setTimeout(о, м));
  let уже = false;

  return (сигнал: string) => {
    // Повторный сигнал при уже идущем завершении игнорируем: два параллельных
    // закрытия пула дают ошибку, и она превратила бы штатный выход в ненулевой код.
    if (уже) {
      журнал.log(`[${сигнал}] завершение уже идёт`);
      return;
    }
    уже = true;
    журнал.log(`[${сигнал}] замена экземпляра: закрываю сервер, затем пул базы`);

    let вышли = false;
    const выйти = (почему: string) => {
      if (вышли) return;
      вышли = true;
      журнал.log(`[${сигнал}] выходим кодом 0 (${почему})`);
      ц.выход(0);
    };

    const сторожВремени = таймер(() => {
      журнал.warn(`[${сигнал}] закрытие не уложилось в ${предел} мс — выходим нулём, не дожидаясь`);
      выйти("предел ожидания");
    }, предел);
    сторожВремени.unref?.();

    ц.сервер.close((ошибка) => {
      if (ошибка) журнал.error(`[${сигнал}] сервер закрылся с ошибкой: ${ошибка.message}`);
      void ц
        .закрытьПул()
        .catch((e: unknown) => {
          // Пул не закрылся — это НЕ повод выйти ненулевым кодом: замену экземпляра
          // платформа прочитает как аварию. Но и молчать нельзя.
          журнал.error(`[${сигнал}] пул базы не закрылся: ${e instanceof Error ? e.message : String(e)}`);
        })
        .finally(() => выйти("сервер и пул закрыты"));
    });
  };
}

/** Подписать процесс на оба сигнала. Отдельная функция — её и зовёт index.ts. */
export function зарегистрироватьЗавершение(
  процесс: { on: (сигнал: string, обратно: () => void) => unknown },
  ц: Завершаемое,
  сигналы: readonly string[] = ["SIGTERM", "SIGINT"],
): void {
  const обработчик = обработчикЗавершения(ц);
  for (const сигнал of сигналы) процесс.on(сигнал, () => обработчик(сигнал));
}
