/** Оба конца градиента карточки — то, на чём поле лежит. */
export const ГРАДИЕНТ_КАРТОЧКИ: Array<[number, number, number]> = [
  [15, 23, 42],
  [19, 78, 74],
];

function относительнаяЯркость([r, g, b]: [number, number, number]): number {
  const к = (v: number) => {
    const x = v / 255;
    return x <= 0.03928 ? x / 12.92 : Math.pow((x + 0.055) / 1.055, 2.4);
  };
  return 0.2126 * к(r) + 0.7152 * к(g) + 0.0722 * к(b);
}

/** Разбирает `#rrggbb` в тройку. Другие форматы сюда не кладут. */
export function razobratHex(hex: string): [number, number, number] {
  const m = /^#([0-9a-f]{6})$/i.exec(hex.trim());
  if (!m) throw new Error(`не шестнадцатеричный цвет: ${hex}`);
  const n = parseInt(m[1], 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/** Отношение контраста по WCAG: от 1 (неразличимо) до 21. */
export function kontrast(a: [number, number, number], b: [number, number, number]): number {
  const L1 = относительнаяЯркость(a);
  const L2 = относительнаяЯркость(b);
  return (Math.max(L1, L2) + 0.05) / (Math.min(L1, L2) + 0.05);
}
