import { describe, test, expect, vi } from "vitest";
import { refusesPlatformDatabase } from "../src/lib/devhubDbProvision";

/**
 * Сторож, не дающий DevHub создавать схемы на боевой базе платформы, при
 * неразобранном адресе ОТКАЗЫВАЕТ, а не пропускает.
 *
 * Найдено 30.08.2026 свипом по денежному пути: искал места, где сбой чтения
 * молча превращается в отрицательный ответ. Одиннадцать кандидатов, разобрано
 * три, настоящий один — этот.
 *
 * Было: `catch { return false }` — «не возражаю». То есть сторож, поставленный
 * против создания схем и ролей в боевой базе всей платформы, при кривом адресе
 * молча отходил в сторону, и провижининг шёл дальше.
 *
 * Направление отказа выбирается по ЦЕНЕ, и здесь она несимметрична: отказ
 * стоит несозданной базы и понятного сообщения, пропуск — записи в боевую базу
 * платформы. Поэтому теперь отказываем и говорим об этом в журнал.
 *
 * Ложных отказов это почти не добавляет: `new URL` не разбирает только заведомо
 * сломанную настройку, с которой провижининг и так не состоялся бы — разница в
 * том, что теперь он остановится ДО первой команды.
 */

describe("сторож чужой базы отказывает при неясности", () => {
  test("контроль: обычные разные адреса — не возражает", () => {
    // Без этого «отказывает всегда» выглядело бы как исправная защита.
    expect(
      refusesPlatformDatabase(
        "postgres://u:p@devhub-db.example.com:5432/devhub",
        "postgres://u:p@platform-db.example.com:5432/platform",
      ),
      "сторож возражает против ЧУЖОЙ базы — тогда он просто всё запрещает",
    ).toBe(false);
  });

  test("тот же хост и та же база — возражает", () => {
    expect(
      refusesPlatformDatabase(
        "postgres://admin:p@db.example.com:5432/platform",
        "postgres://app:p@db.example.com:5432/platform",
      ),
    ).toBe(true);
  });

  test("адрес не разобрался — ОТКАЗЫВАЕТ, а не пропускает", () => {
    const err = vi.spyOn(console, "error").mockImplementation(() => {});
    expect(
      refusesPlatformDatabase("это вообще не адрес", "postgres://u:p@db.example.com:5432/platform"),
      "сторож против боевой базы платформы молча отошёл в сторону",
    ).toBe(true);
    expect(err.mock.calls.length, "отказ не назван — человек не поймёт, почему не создалось")
      .toBeGreaterThan(0);
    err.mockRestore();
  });

  test("платформенный адрес неизвестен — поведение НЕ меняем", () => {
    // Осознанная граница: без DATABASE_URL сравнивать не с чем, и это
    // законный случай (локальная разработка, тесты). Отказывать здесь значило
    // бы сломать среды, где боевой базы просто нет.
    expect(refusesPlatformDatabase("postgres://u:p@db.example.com:5432/devhub", undefined)).toBe(
      false,
    );
  });
});
