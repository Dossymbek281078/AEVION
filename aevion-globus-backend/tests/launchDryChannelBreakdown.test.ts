import { describe, test, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Сухой прогон отвечает, ОТКУДА пришли подписчики.
 *
 * Метка канала у подписчиков появилась 31.08.2026. Смотреть на неё больше
 * негде: экрана со списком подписчиков не существует, и единственные читатели
 * выгрузки — два скрипта рассылки. Поэтому ответ печатает сухой прогон.
 *
 * Проверка читает исходник, а не запускает скрипт: тот ходит в прод за списком
 * подписчиков по админ-токену, и запускать его в наборе нельзя.
 */

const SRC = readFileSync(
  join(process.cwd(), "scripts/launch-announce-dry.ts"),
  "utf8",
);

describe("сухой прогон печатает каналы", () => {
  test("канал читается из строки списка", () => {
    expect(SRC, "тип строки не знает о канале").toMatch(/channel\?:\s*string/);
    expect(SRC).toContain("r.channel");
  });

  test("незнание не выдаётся за прямой заход", () => {
    // Подписавшиеся до 31.08 и пришедшие без метки — это «не знаем».
    // Слить их с «direct» значит завысить долю прямых и спрятать каналы,
    // которые просто не доехали.
    expect(SRC).toContain("не знаем");
    expect(SRC, "появился выдуманный direct").not.toMatch(/["']direct["']/);
  });

  test("разбивка печатается, а не считается молча", () => {
    expect(SRC).toContain("откуда пришли");
  });
});
