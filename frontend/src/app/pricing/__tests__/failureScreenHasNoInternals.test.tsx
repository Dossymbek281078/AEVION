import { describe, test, expect, vi } from "vitest";
import { render, waitFor } from "@testing-library/react";

/**
 * Экран отказа денежных страниц не показывает человеку наших внутренностей.
 *
 * НАЙДЕНО 02.09.2026 ОТРИСОВКОЙ, а не чтением исходника. Когда бэкенд не
 * отвечает, покупатель на странице цен видел:
 *
 *     Pricing unavailable
 *     /api/pricing. Failed to parse URL from /api-backend/api/pricing
 *     Проверь, что бэкенд запущен (npm run dev в aevion-globus-backend).
 *
 * То есть внутренний адрес нашего API, сырое сообщение движка и инструкцию
 * РАЗРАБОТЧИКУ — на странице, где принимают деньги, на обоих языках, на трёх
 * адресах сразу (`/pricing`, `/pricing/cases`, `/pricing/compare`).
 *
 * ПОЧЕМУ ЭТОГО НЕ ВИДЕЛ НИ ОДИН СТОРОЖ. Все наши проверки этих страниц читают
 * ИСХОДНИК, а строка собиралась из трёх мест: заголовок из словаря, путь —
 * жёсткой строкой в разметке, подробность — из пойманного исключения. По
 * отдельности каждое место выглядит безобидно; беда существует только на
 * собранном экране. Это находится отрисовкой и ничем другим.
 *
 * ГРАНИЦА ЧЕСТНАЯ. Сторож смотрит ЭКРАН ОТКАЗА (в прогоне запрос к API не
 * проходит по устройству среды, и страница честно уходит в эту ветку). Про
 * успешный экран он не утверждает ничего.
 *
 * ⚠️ Отдельный урок, стоивший времени: я раньше отказался от проверок
 * отрисовкой, решив, что импорт страницы «висит дольше десяти минут».
 * Замер соседнего окна и мой собственный показали 1.6 с. Виснет не импорт —
 * страница без поставщика переводов бросает исключение сразу, и это легко
 * принять за зависание.
 */

vi.mock("next/navigation", () => ({
  useSearchParams: () => new URLSearchParams(""),
}));

// eslint-disable-next-line import/first
import { I18nProvider } from "@/lib/i18n";

/** То, чего человеку видеть нельзя ни на одной денежной странице. */
const ВНУТРЕННЕЕ = [
  "/api/pricing",
  "/api-backend",
  "npm run dev",
  "localhost",
  "Failed to parse URL",
  "aevion-globus-backend",
];

const СТРАНИЦЫ: Array<[string, () => Promise<{ default: React.ComponentType }>]> = [
  ["/pricing", () => import("../page")],
  ["/pricing/cases", () => import("../cases/page")],
  ["/pricing/compare", () => import("../compare/page")],
];

describe("экран отказа денежных страниц человеческий", () => {
  test.each(СТРАНИЦЫ)("%s не показывает внутренностей", async (_адрес, загрузить) => {
    const { default: Страница } = await загрузить();
    const { container } = render(
      <I18nProvider>
        <Страница />
      </I18nProvider>,
    );

    // Контроль: экран вообще дорисовался до состояния отказа, а не остался
    // на «загружаем». Без этого проверки ниже прошли бы на пустой странице.
    await waitFor(
      () => expect((container.textContent ?? "").length).toBeGreaterThan(30),
      { timeout: 15000 },
    );

    const текст = container.textContent ?? "";
    for (const образец of ВНУТРЕННЕЕ) {
      expect(
        текст,
        `на экране отказа видно «${образец}» — это наши внутренности, а не сообщение человеку`,
      ).not.toContain(образец);
    }
  }, 60000);
});
