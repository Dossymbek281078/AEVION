/**
 * Сторож: подтверждение ПО ПЛАТЕЖУ не перезаписывается ответом ПО АККАУНТУ.
 *
 * ЗАМЫСЕЛ, записанный в самой странице (page.tsx, у setConfirmed(true)):
 * «Выдача по ЭТОМУ платежу состоялась — это и есть подтверждение, более
 * сильное, чем совпадение тарифа аккаунта». То есть ответ ручки
 * /api/pricing/checkout/status сильнее ответа /api/me/entitlements.
 *
 * ЧТО НАШЛОСЬ (замер 11.10.2026 ночью, окно user-d7). Оба вопроса задаются
 * ДВУМЯ независимыми эффектами, и каждый пишет в одно и то же состояние
 * `confirmed`. Кто ответил ПОЗЖЕ — тот и выиграл. Ответ по аккаунту для
 * гостя всегда отрицательный: прод-замер 11.10, /api/me/entitlements без
 * входа отдаёт 200 и `plan: "free"` (контроль: выдуманный путь той же ручки —
 * 404, значит 200 настоящий). Касса Lemon Squeezy возвращает покупателя БЕЗ
 * входа в браузере, поэтому «аккаунт говорит нет» — это норма, а не отказ.
 *
 * ЦЕНА. Покупатель, которому выдача УЖЕ подтверждена по его платежу, читает
 * «Оплата принята — проверяем доступ» вместо «Pro активирован!». Ложного
 * обещания здесь нет (ошибка в безопасную сторону), но человек не узнаёт,
 * что доступ готов, и уходит с экрана в неизвестности — а это тот самый
 * экран, на котором он только что отдал деньги.
 *
 * ЧЕГО ЭТОТ СТОРОЖ НЕ ПРОВЕРЯЕТ (честная граница): он не проверяет саму
 * ручку статуса на бэкенде и не трогает обратный класс — ложное «активирован»
 * без платежа; его держат соседние bareVisitIsNotAPurchase и noPaymentNoClaim.
 * Здесь проверяется ровно порядок двух ответов и его последствие на экране.
 */
import { describe, it, expect, vi, afterEach } from "vitest";
import { render, cleanup, act } from "@testing-library/react";
import { I18nProvider } from "@/lib/i18n";
import en from "@/lib/i18n-lang/en";

/*
 * Подписи берём ИЗ СЛОВАРЯ, а не литералами. Первый замер этого сторожа
 * (23:54) покраснел трижды на русских литералах — и покраснел НЕ из-за
 * дефекта: поставщик переводов по замыслу стартует с "en" (i18n.tsx: «Первый
 * рендер обязан совпасть с сервером»). Ошибся прибор, не страница.
 */
const АКТИВИРОВАН = (en["pricing.checkoutSuccess.titleActivated"] ?? "").replace("{tier}", "Pro");
const ОЖИДАНИЕ = en["pricing.checkoutSuccess.titlePending"] ?? "";

const параметры = { value: "" };
vi.mock("next/navigation", () => ({
  useSearchParams: () => new URLSearchParams(параметры.value),
  useRouter: () => ({ push: vi.fn(), replace: vi.fn() }),
  usePathname: () => "/pricing/checkout/success",
}));

/** Ответ, который отдаёт наш поддельный fetch. */
function ответ(тело: unknown) {
  return { ok: true, status: 200, json: async () => тело };
}

/** Обещание, которым управляем вручную: так задаётся ПОРЯДОК ответов. */
function отложить<T>() {
  let выполнить!: (v: T) => void;
  const обещание = new Promise<T>((r) => {
    выполнить = r;
  });
  return { обещание, выполнить };
}

const АДРЕС_ВОЗВРАТА = "provider=lemonsqueezy&session_id=sess-probe-user-d7&total=20000";

async function открыть(поиск: string) {
  параметры.value = поиск;
  const m = await import("@/app/pricing/checkout/success/page");
  const Страница = m.default as () => import("react").JSX.Element;
  await act(async () => {
    render(
      <I18nProvider>
        <Страница />
      </I18nProvider>,
    );
  });
}

const текст = () => document.body.textContent ?? "";

afterEach(() => {
  cleanup();
  vi.unstubAllGlobals();
});

describe("экран после оплаты: платёж сильнее аккаунта", () => {
  it("КОНТРОЛЬ: подписи существуют и РАЗЛИЧНЫ — иначе утверждения ниже пусты", () => {
    expect(АКТИВИРОВАН.length, "подпись активации пропала из словаря").toBeGreaterThan(5);
    expect(ОЖИДАНИЕ.length, "подпись ожидания пропала из словаря").toBeGreaterThan(5);
    expect(
      АКТИВИРОВАН === ОЖИДАНИЕ,
      "подписи активации и ожидания совпали — различить состояния нечем",
    ).toBe(false);
    expect(
      ОЖИДАНИЕ.includes(АКТИВИРОВАН),
      "подпись ожидания содержит подпись активации — проверка на подстроку обманет",
    ).toBe(false);
  });

  it("ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: выдача не подтверждена — активацию не обещаем", async () => {
    vi.stubGlobal("fetch", (u: string) =>
      String(u).includes("/api/me/entitlements")
        ? Promise.resolve(ответ({ plan: "free", email: null }))
        : Promise.resolve(ответ({ ready: false })),
    );
    await открыть(АДРЕС_ВОЗВРАТА);
    expect(текст(), "активация обещана без подтверждения выдачи").not.toContain(АКТИВИРОВАН);
    expect(текст(), "покупателю не сказано даже, что оплата принята").toContain(ОЖИДАНИЕ);
  }, 60000);

  it("касса ответила ПЕРВОЙ, аккаунт ПОЗЖЕ — активация остаётся на экране", async () => {
    // Это главный случай: вебхук уже дошёл, выдача состоялась, и покупатель
    // (гость, без входа) возвращается из кассы. Ответ по аккаунту приходит
    // последним и НЕ ИМЕЕТ ПРАВА его отменить.
    const права = отложить<ReturnType<typeof ответ>>();
    vi.stubGlobal("fetch", (u: string) =>
      String(u).includes("/api/me/entitlements")
        ? права.обещание
        : Promise.resolve(ответ({ ready: true, tier: "pro" })),
    );
    await открыть(АДРЕС_ВОЗВРАТА);
    expect(текст(), "подтверждение по платежу не показано вовсе").toContain(АКТИВИРОВАН);

    await act(async () => {
      права.выполнить(ответ({ plan: "free", email: null }));
      await Promise.resolve();
    });
    expect(
      текст(),
      "ответ по аккаунту (гость, plan=free) перезаписал подтверждение по платежу",
    ).toContain(АКТИВИРОВАН);
  }, 60000);

  it("касса подтвердила, а связь с аккаунтом оборвалась — активация остаётся", async () => {
    /*
     * Третий путь понижения, который легко пропустить: не ОТВЕТ аккаунта, а
     * его ОТСУТСТВИЕ. В обработчике отказа стояло «не знаем» (null), и оно
     * тоже стирало подтверждение по платежу. Для покупателя разницы нет —
     * заголовок так же забирает активацию назад из-за НАШЕГО обрыва связи.
     */
    const права = отложить<ReturnType<typeof ответ>>();
    vi.stubGlobal("fetch", (u: string) =>
      String(u).includes("/api/me/entitlements")
        ? права.обещание
        : Promise.resolve(ответ({ ready: true, tier: "pro" })),
    );
    await открыть(АДРЕС_ВОЗВРАТА);
    expect(текст(), "подтверждение по платежу не показано вовсе").toContain(АКТИВИРОВАН);

    await act(async () => {
      // Обрыв, а не отрицательный ответ: обещание отклоняется.
      (права as unknown as { выполнить: (v: unknown) => void }).выполнить(
        Promise.reject(new Error("сеть недоступна")),
      );
      await Promise.resolve();
    });
    expect(
      текст(),
      "обрыв связи с ручкой аккаунта стёр подтверждение по платежу",
    ).toContain(АКТИВИРОВАН);
  }, 60000);

  it("аккаунт ответил ПЕРВЫМ, касса ПОЗЖЕ — активация появляется", async () => {
    const касса = отложить<ReturnType<typeof ответ>>();
    vi.stubGlobal("fetch", (u: string) =>
      String(u).includes("/api/me/entitlements")
        ? Promise.resolve(ответ({ plan: "free", email: null }))
        : касса.обещание,
    );
    await открыть(АДРЕС_ВОЗВРАТА);
    expect(текст(), "до ответа кассы активация обещана зря").not.toContain(АКТИВИРОВАН);

    await act(async () => {
      касса.выполнить(ответ({ ready: true, tier: "pro" }));
      await Promise.resolve();
    });
    expect(текст(), "подтверждение по платежу не доехало до экрана").toContain(АКТИВИРОВАН);
  }, 60000);
});
