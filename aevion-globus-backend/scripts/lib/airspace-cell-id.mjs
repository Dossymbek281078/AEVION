/**
 * QSkyway — устойчивый идентификатор ячейки воздушного пространства.
 *
 * ЗАЧЕМ. Первая версия ингеста брала ключ прямо из фида: `faa-${OBJECTID}`.
 * `OBJECTID` в ArcGIS — это номер строки во внутренней базе публикатора, а не
 * свойство ячейки: он меняется при каждой перепубликации слоя, даже когда в
 * содержимом не изменилось ничего. 2026-07-28 это дало ровно такую картину —
 * редакция та же (`effective` 7/9/2026), потолки те же (`cellsChanged: 0`), а
 * все 9 идентификаторов разошлись, и сторож закричал «дрейф».
 *
 * Цена такой ложной тревоги выше, чем кажется: к сторожу, который звенит на
 * каждой перепубликации, привыкают — и настоящее изменение воздушного
 * пространства проходит незамеченным.
 *
 * ЧТО ВМЕСТО. У ячейки есть собственная identity, не зависящая от чужой базы:
 * её границы и аэропорт, к которому она относится. Юго-западный угол задаёт
 * положение однозначно — ячейки UASFM не накладываются друг на друга.
 *
 * ⚠️ ТОЧНОСТЬ 4 ЗНАКА ВЫБРАНА НЕ НАУГАД. Это ~11 м по широте, тогда как ячейка
 * UASFM — это километры. Больше знаков сделали бы ключ хрупким: публикатор
 * пересчитывает геометрию, и седьмой знак «плавает» между выгрузками, то есть
 * мы вернули бы ту же болезнь, только тише. Меньше — и соседние ячейки начали
 * бы сливаться в один ключ.
 */

/** Число → строка с фиксированным числом знаков, без «-0» и без экспоненты. */
function fixed(n, digits) {
  const v = Number(n);
  if (!Number.isFinite(v)) return "nan";
  const s = v.toFixed(digits);
  return s === "-" + (0).toFixed(digits) ? (0).toFixed(digits) : s;
}

/**
 * Ключ ячейки: аэропорт (если фид его назвал) + юго-западный угол.
 *
 * Аэропорт входит в ключ не для уникальности, а для человека: `faa-KJFK-40.7500_-74.0000`
 * читается, а `faa-40.7500_-74.0000` нет. Если ICAO не указан, часть просто
 * отсутствует — подставлять «unknown» значило бы притворяться, что мы знаем.
 */
export function stableCellId(cell, { prefix = "faa", digits = 4 } = {}) {
  const icao = typeof cell?.airportIcao === "string" ? cell.airportIcao.trim().toUpperCase() : "";
  const sw = `${fixed(cell?.minLat, digits)}_${fixed(cell?.minLon, digits)}`;
  return icao ? `${prefix}-${icao}-${sw}` : `${prefix}-${sw}`;
}
