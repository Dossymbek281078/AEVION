#!/usr/bin/env node
// Один вход во все отчёты о расхождениях: `npm run audit:drift`.
//
// Зачем сведено в одну команду. Отчёты, каждый со своим именем файла, никто не
// открывает — это в AEVION уже случалось: ежедневный claims-audit исправно
// складывал находки в OneDrive, и они лежали там неделями непрочитанными.
// Четыре имени скриптов запомнить некому; одна команда — можно.
//
// Все четыре ОТЧЁТЫ, а не гейты: каждый находит класс, где часть попаданий
// требует решения человека, а не правки «чтобы стало зелено». Гейт в проекте
// ровно один и он отдельно — scripts/auth-token-key-ratchet.test.mjs, там
// список имён закрыт и «правильно» определено однозначно.
//
// Общая мысль всех четырёх: сопоставить то, что код ДЕЛАЕТ, с тем, что где-то
// ОБЪЯВЛЕНО. Расхождение в этом шве не роняет систему — она просто молча
// работает не так, как написано. Три из четырёх нашли настоящие дефекты в
// первый же прогон 12.08.2026.

import { spawnSync } from "node:child_process";
import path from "node:path";

const HERE = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));

const CHECKS = [
  {
    script: "dead-storage-keys.mjs",
    title: "Ключи хранилища: читают, но не пишет никто",
    found: "нашёл два семейства мёртвых ключей входа — 78 страниц не видели вошедшего человека",
  },
  {
    script: "api-docs-drift.mjs",
    title: "Публичная документация API против зарегистрированных маршрутов",
    found: "из 65 обещанных путей не разрешались 26",
  },
  {
    script: "env-drift.mjs",
    title: "Переменные окружения: код читает, нигде не заведены",
    found: "13 платёжных переменных не были описаны нигде, включая основной канал",
  },
  {
    script: "secret-fail-open.mjs",
    title: "Секреты, при отсутствии которых проверка молча выключается",
    found: "117 мест, открывается одно и осознанно — остальное закрывается верно",
  },
];

let failed = 0;
for (const c of CHECKS) {
  console.log(`\n${"─".repeat(72)}\n▸ ${c.title}\n  (в первый прогон: ${c.found})\n`);
  const r = spawnSync(process.execPath, [path.join(HERE, c.script)], { encoding: "utf8" });
  if (r.error) {
    console.log(`  НЕ ЗАПУСТИЛСЯ: ${r.error.message}`);
    failed++;
    continue;
  }
  process.stdout.write(r.stdout || "");
  if (r.stderr) process.stderr.write(r.stderr);
}

console.log(`\n${"─".repeat(72)}`);
console.log(
  failed
    ? `${failed} проверок не запустилось`
    : "Все четыре отчёта построены. Числа сами по себе не вердикт: каждое попадание дочитывать руками до конца обработчика — на этом я ошибался в первый же день.",
);
process.exitCode = failed ? 1 : 0;
