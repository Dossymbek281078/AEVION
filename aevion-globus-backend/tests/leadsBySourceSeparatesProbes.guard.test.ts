import { describe, test, expect, vi, beforeEach } from "vitest";

/**
 * Сторож: разрез заявок по источнику отделяет людей от НАШИХ проб и не врёт
 * нулём при отказе базы.
 *
 * 🔴 Зачем ручка вообще. 30.09.2026 соседнее окно спросило: «сколько в списке
 * адресов с source=qventure-result, кроме моего?» — то есть оставил ли модуль хоть
 * одного живого человека. Ответить было нечем: детализация жила в админской ручке
 * с токеном прода, и вопрос решался перепиской.
 *
 * Два требования, оба денежные:
 *   1. пробы считаются ОТДЕЛЬНОЙ колонкой, а не вычитаются молча. Замер того же
 *      дня: из 113 «пользователей» 108 были нашими пробами; вычитай счётчик сам —
 *      спорить о его правоте было бы нечем;
 *   2. отказ базы отдаёт `измерено: false` и 503, а не пустой разрез. Пустой
 *      читался бы как «ни один модуль не собрал никого», а это решение о деньгах.
 */

// Оснастка ТА ЖЕ, что у соседнего сторожа этого же счётчика
// (`registeredCounterIsHonest`): обычная функция, а не `vi.fn()`. Причина не
// стилистическая — `mockRejectedValue`/бросок из `vi.fn()` vitest считает
// необработанной ошибкой и краснит тест, хотя код ошибку ловит (проверено:
// журнал «[stats/leads] разрез не удался» печатался, а тест падал). Падение было
// в оснастке, не в коде.
const ответ: { rows: Record<string, unknown>[]; бросать: boolean } = { rows: [], бросать: false };
const запросы: string[] = [];

vi.mock("../src/lib/dbPool", () => ({
  getPool: () => ({
    query: async (sql: string) => {
      запросы.push(sql);
      if (ответ.бросать) throw new Error("сеть до базы недоступна");
      return { rows: ответ.rows };
    },
  }),
}));
vi.mock("../src/lib/sentry/platform", () => ({ makeServiceCapture: () => vi.fn() }));

const { заявкиПоИсточнику } = await import("../src/routes/publicStats");

beforeEach(() => {
  ответ.rows = [];
  ответ.бросать = false;
  запросы.length = 0;
});

describe("разрез заявок по источнику", () => {
  test("людей и пробы отдаёт отдельными числами", async () => {
    ответ.rows = [
      { источник: "qventure-result", люди: 0, пробы: 2 },
      { источник: "cyberchess", люди: 3, пробы: 1 },
    ];

    const о = await заявкиПоИсточнику();
    expect(о.измерено).toBe(true);
    expect(
      о.поИсточнику["qventure-result"],
      "проба смешана с людьми — «модуль собрал двоих» было бы неправдой",
    ).toEqual({ люди: 0, пробы: 2 });
    expect(о.поИсточнику["cyberchess"]).toEqual({ люди: 3, пробы: 1 });
    expect(о.итого).toEqual({ люди: 3, пробы: 3 });
  });

  test("КОНТРОЛЬ: отказ базы — это «не знаю», а не «никого нет»", async () => {
    ответ.бросать = true;

    const о = await заявкиПоИсточнику();
    expect(о.измерено, "отказ выдан за измерение").toBe(false);
    expect(о.итого, "нули вместо «не знаю»").toEqual({ люди: null, пробы: null });
    expect(о.поИсточнику).toEqual({});
    expect(о.почему, "причина отказа не названа").toBeTruthy();
  });

  test("КОНТРОЛЬ: пустой список — честный ноль, а не отказ", async () => {
    // Иначе «никто не подписался» было бы не отличить от поломки.
    ответ.rows = [];

    const о = await заявкиПоИсточнику();
    expect(о.измерено).toBe(true);
    expect(о.итого).toEqual({ люди: 0, пробы: 0 });
  });
  test("сам ЗАПРОС отделяет пробы — иначе разделения нет вовсе", async () => {
    // 🔴 Почему проверяется текст запроса, а не результат. Разделение живёт в SQL
    // (`FILTER (WHERE NOT ...)`), а в этом наборе база подменена — мок отдаёт уже
    // готовые числа, поэтому предикат не исполняется. Мутация «считать всех
    // подряд» такой проверкой НЕ ловится: замерено, она прошла зелёной.
    //
    // Значит охранять надо запрос. Это слабее прогона по настоящей базе, но не
    // пусто: снятие предиката или потеря нашего домена краснит сторожа. Тот же
    // приём стоит у соседнего сторожа этого счётчика.
    ответ.rows = [];
    await заявкиПоИсточнику();

    const sql = запросы[0] ?? "";
    expect(sql, "запрос не дошёл до базы").toContain("constitution_waitlist");

    for (const слово of ["smoke-", "probe-", "test-", "smoke@", "example.com", "aevion.app"]) {
      expect(sql, `признак пробы потерял «${слово}»`).toContain(слово);
    }

    // 🔴 И ОБРАТНАЯ СТОРОНА, важнее первой: признак не должен ловить ЖИВЫХ.
    // Замер соседнего окна 30.09.2026: голый `ILIKE 'test%'` съедал `testov@…`
    // (Тестов — обычная фамилия латиницей) и `testing@<компания>` — рабочий ящик
    // отдела тестирования у настоящего клиента. Живых заявок у нас единицы, и
    // один потерянный лид это заметная доля. Поэтому слово обязано идти с
    // разделителем, и в запросе не должно быть широких форм.
    for (const широкая of ["'smoke%'", "'probe%'", "'test%'"]) {
      expect(
        sql,
        `в запросе осталась широкая форма ${широкая} — она съест живого человека вида testov@ или smokehouse@`,
      ).not.toContain(широкая);
    }
    // Подчёркивание как разделитель НЕ используется: в ILIKE это шаблон «любой
    // один знак», и `smoke_%` совпал бы с `smokehouse@`.
    expect(sql, "подчёркивание в ILIKE — шаблон, оно вернёт широту").not.toContain("smoke_%");

    // ── ВТОРОЙ ПРИЗНАК: ИМЯ ИСТОЧНИКА ───────────────────────────────
    // Замер соседнего окна 30.09.2026 на проде: адресный признак пропускал
    // 16 «людей» из 26 — они сидели в источниках `branch-check` (5),
    // `crowd-check` (5), `cyberchess-probe` (2, буквально слово «проба»),
    // `cyberchess-launch-check`, `launch-readiness-check`, `rate-check`,
    // `same-check`. Имя говорит «прогон», а адрес был правдоподобным.
    for (const форма of ["'check'", "'check-%'", "'%-check'", "'%-check-%'", "'%-probe'"]) {
      expect(sql, `признак по имени источника потерял форму ${форма}`).toContain(форма);
    }
    expect(sql, "признак по имени должен смотреть на колонку source").toContain('"source" ILIKE');

    // 🔴 И ОБРАТНАЯ СТОРОНА, ради которой формы именно такие: привязка к ГРАНИЦЕ
    // слова, а не к вхождению. `%check%` съел бы живой источник `checkout-page` и
    // `checklist` — это недооценка, и заметить её труднее переоценки: она
    // выглядит осторожностью. Мутация «расширить до вхождения» ловится здесь.
    for (const жадная of ["'%check%'", "'%probe%'", "'%smoke%'", "'%test%'"]) {
      expect(
        sql,
        `в запросе есть жадная форма ${жадная} — она съест живой источник вроде checkout-page`,
      ).not.toContain(жадная);
    }

    // Обе колонки обязаны фильтровать: «люди» — без проб, «пробы» — только пробы.
    const людиКолонка = /COUNT\(\*\) FILTER \(WHERE NOT \(/.test(sql);
    const пробыКолонка = /COUNT\(\*\) FILTER \(WHERE \(/.test(sql);
    expect(людиКолонка, "колонка «люди» считает всех подряд — пробы уйдут в рост").toBe(true);
    expect(пробыКолонка, "колонка «пробы» не отфильтрована").toBe(true);
  });
});
