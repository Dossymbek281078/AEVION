/**
 * Сведение стены, начерченной ДВУМЯ линиями, в одну.
 *
 * Общий модуль для DXF и PDF: оба приходят из одной и той же CAD-программы и
 * несут одну и ту же манеру черчения — у стены рисуют внутреннюю и внешнюю
 * грань, а не ось. Второй способ делать то же самое стал бы источником
 * расхождений между путями, а расходятся они молча.
 *
 * Растровый путь сюда не входит намеренно: он сливает параллельные прогоны
 * пикселей ещё до того, как получаются отрезки, — там задача другая.
 */

import type { Wall } from "./planModel";

/**
 * Толщина стены, в которую мы верим, м.
 *
 * Обе границы физические, а не подобранные. Тоньше 5 см стен не строят: такой
 * зазор между параллельными линиями — это штриховка, двойная обводка или
 * размерная выноска. Толще 40 см в квартире не бывает, а самый узкий проход
 * шире, поэтому две стены коридора в пару не слипнутся.
 *
 * Нижняя граница появилась не из головы: без неё чертёж со штриховкой шагом
 * 10 мм схлопывался в ОДНУ стену — поймал прежний тест обрезки, а не мой
 * новый. Проверка, написанная для другого, отработала как контроль.
 */
const MIN_WALL_T = 0.05;
const MAX_WALL_T = 0.4;

/**
 * Стена, начерченная ДВУМЯ линиями, сводится в одну.
 *
 * Это стандартная манера архитектурного чертежа: у стены рисуют внутреннюю и
 * внешнюю грань, а не ось. Без сведения комната из четырёх стен приезжает
 * восемью (замерено), и последствия не косметические:
 *
 *  - смета берёт площадь стен из комнат, а если комнаты не выделились —
 *    из СУММЫ ДЛИН стен. Тогда краска и штукатурка считаются ДВАЖДЫ;
 *  - между парой линий остаётся щель в несколько сантиметров, и обход комнат
 *    видит её как отдельное помещение;
 *  - толщина стены была зашита числом 0.15, хотя чертёж её знает: это и есть
 *    расстояние между гранями.
 *
 * Правила намеренно строгие, потому что ошибка слияния тише ошибки его
 * отсутствия: сводятся только отрезки, лежащие по одной оси, перекрывающиеся
 * вдоль неё и отстоящие меньше чем на 0.4 м — толще любой квартирной стены,
 * но тоньше самого узкого прохода. Косые стены не сводятся вовсе.
 *
 * Ось новой стены — СЕРЕДИНА между гранями, то есть настоящая осевая линия.
 */
/**
 * Допуск, в пределах которого два конца считаются ОДНОЙ точкой, м.
 *
 * Миллиметр, а не сантиметр, и это не придирка. В CAD-файле дубль — это
 * буквально та же линия, координаты совпадают точно; допуск нужен только на
 * шум округления при пересчёте единиц. Первая редакция брала 1 см — и на
 * чертеже со штриховкой шагом 1 см объявила дублями 116 РАЗНЫХ линий
 * (284 стены вместо 400).
 *
 * Поймал это, как и в прошлый раз, СТАРЫЙ тест обрезки длинного чертежа,
 * написанный для совсем другого. Второй раз за день щедрый порог съедал
 * законное различие, и второй раз ловила чужая проверка.
 */
const SAME_POINT = 0.001;

/**
 * Стена, начерченная ДВАЖДЫ, выбрасывается.
 *
 * В CAD-файлах линию нередко обводят повторно — при копировании, при правке
 * поверх старого слоя. Для модели это невидимо: два одинаковых отрезка
 * рисуются один поверх другого. А для расчётов НЕТ.
 *
 * Замер: одна дублированная стена демо-квартиры добавляет ТРИ лишние точки
 * электрики (15 против 18) — то есть лишние розетки и лишние метры кабеля в
 * смете. На настоящем чертеже таких дублей бывают десятки.
 *
 * Признак структурный: у двух стен совпадают ОБА конца (в любом порядке) с
 * точностью до сантиметра. Две настоящие разные стены не могут занимать одно
 * место, поэтому ложных срабатываний тут быть не может.
 */
function dropDuplicates(walls: Wall[]): { walls: Wall[]; dropped: number } {
  const тот = (a: number, b: number) => Math.abs(a - b) <= SAME_POINT;
  const совпали = (u: Wall, v: Wall) =>
    (тот(u.x1, v.x1) && тот(u.y1, v.y1) && тот(u.x2, v.x2) && тот(u.y2, v.y2)) ||
    (тот(u.x1, v.x2) && тот(u.y1, v.y2) && тот(u.x2, v.x1) && тот(u.y2, v.y1));
  const out: Wall[] = [];
  let dropped = 0;
  for (const w of walls) {
    if (out.some((u) => совпали(u, w))) { dropped++; continue; }
    out.push(w);
  }
  return { walls: out, dropped };
}

export function mergeDoubleWalls(
  вход: Wall[],
): { walls: Wall[]; merged: number; dropped: number } {
  // Дубли убираются ДО сведения: иначе две одинаковые стены с зазором 0
  // пройдут мимо правила слияния и останутся обе.
  const безДублей = dropDuplicates(вход);
  const walls = безДублей.walls;
  const ось = (w: Wall): "h" | "v" | null => {
    if (Math.abs(w.y2 - w.y1) < 1e-6) return "h";
    if (Math.abs(w.x2 - w.x1) < 1e-6) return "v";
    return null;
  };
  const поперёк = (w: Wall, a: "h" | "v") => (a === "h" ? w.y1 : w.x1);
  const начало = (w: Wall, a: "h" | "v") =>
    a === "h" ? Math.min(w.x1, w.x2) : Math.min(w.y1, w.y2);
  const конец = (w: Wall, a: "h" | "v") =>
    a === "h" ? Math.max(w.x1, w.x2) : Math.max(w.y1, w.y2);

  // Порядок стен СОХРАНЯЕТСЯ таким, каким пришёл. Первая редакция собирала
  // сперва горизонтальные, потом вертикальные — и переставила стены местами.
  // Поймал существующий тест разбора PDF, который брал walls[1]. Перестановка
  // здесь никому не нужна: это побочное действие, а побочные действия ломают
  // то, о чём не думал автор.
  const представитель = new Map<Wall, Wall>();
  let merged = 0;

  for (const a of ["h", "v"] as const) {
    const свои = walls.filter((w) => ось(w) === a)
      .sort((p1, p2) => поперёк(p1, a) - поперёк(p2, a) || начало(p1, a) - начало(p2, a));
    const собранные: Wall[] = [];
    const занятые = new Set<Wall>();
    for (const w of свои) {
      // Стена имеет РОВНО ДВЕ грани, поэтому слияние только парное.
      // Цепочка была бы хуже отсутствия слияния: стопка параллельных линий
      // схлопнулась бы в одну стену неправдоподобной толщины.
      const пара = собранные.find((m) => {
        if (занятые.has(m)) return false;
        const d = Math.abs(поперёк(m, a) - поперёк(w, a));
        if (d < MIN_WALL_T || d > MAX_WALL_T) return false;
        // перекрытие вдоль оси обязательно: иначе это разные стены
        if (!(начало(w, a) < конец(m, a) && конец(w, a) > начало(m, a))) return false;
        // 🔴 Главный признак, и он физический, а не пороговый: МЕЖДУ двумя
        // гранями одной стены не лежит ничего. У штриховки лежит — там линии
        // идут частым шагом, и на любом пороге найдётся пара «подходящего»
        // расстояния. Прежняя редакция без этой проверки схлопывала чертёж со
        // штриховкой шагом 1 см вдвое: находились пары ровно в 5 см.
        const лоу = Math.min(поперёк(m, a), поперёк(w, a));
        const хай = Math.max(поперёк(m, a), поперёк(w, a));
        const естьМежду = свои.some((t) => {
          if (t === m || t === w) return false;
          const c = поперёк(t, a);
          if (c <= лоу + 1e-9 || c >= хай - 1e-9) return false;
          return начало(t, a) < конец(m, a) && конец(t, a) > начало(m, a);
        });
        return !естьМежду;
      });
      if (!пара) {
        const копия = { ...w };
        собранные.push(копия);
        представитель.set(w, копия);
        continue;
      }
      представитель.set(w, пара);
      занятые.add(пара);
      const d = Math.abs(поперёк(пара, a) - поперёк(w, a));
      const серединаПоперёк = (поперёк(пара, a) + поперёк(w, a)) / 2;
      const s0 = Math.min(начало(пара, a), начало(w, a));
      const s1 = Math.max(конец(пара, a), конец(w, a));
      if (a === "h") {
        пара.x1 = s0; пара.x2 = s1; пара.y1 = серединаПоперёк; пара.y2 = серединаПоперёк;
      } else {
        пара.y1 = s0; пара.y2 = s1; пара.x1 = серединаПоперёк; пара.x2 = серединаПоперёк;
      }
      пара.thickness = d;
      merged++;
    }
  }

  // Собираем в исходном порядке: каждая стена появляется там, где стояла её
  // ПЕРВАЯ из пары грань, и ровно один раз.
  const out: Wall[] = [];
  const выданные = new Set<Wall>();
  for (const w of walls) {
    const rep = представитель.get(w) ?? { ...w }; // косые идут как есть
    if (выданные.has(rep)) continue;
    выданные.add(rep);
    out.push(rep);
  }
  return { walls: out, merged, dropped: безДублей.dropped };
}

