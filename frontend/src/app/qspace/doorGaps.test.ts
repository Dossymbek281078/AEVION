import { describe, expect, it } from "vitest";
import { findRooms } from "./rooms";
import type { Plan } from "./planModel";

/**
 * Дверь, нарисованная РАЗРЫВОМ стены.
 *
 * В архитектурном чертеже проём часто не рисуют: перегородку просто
 * прерывают. Для модели это верно, для обхода помещений — дыра, и заливка
 * через неё протекает. Замер до правки: коробка 8×6 с перегородкой и проёмом
 * 0.9 м давала ОДНУ комнату 43 м² вместо двух по 21. Итог по площади при этом
 * сходился, поэтому ошибка была тихой: неверна разбивка, а именно по ней
 * покупают плитку и обои.
 */
const стена = (x1: number, y1: number, x2: number, y2: number) =>
  ({ x1, y1, x2, y2, thickness: 0.2, height: 2.7 });

const коробка = () => [
  стена(0, 0, 8, 0), стена(8, 0, 8, 6), стена(8, 6, 0, 6), стена(0, 6, 0, 0),
];

const план = (walls: ReturnType<typeof стена>[]): Plan =>
  ({ name: "проба", source: "demo", openings: [], walls });

describe("дверь-разрыв не сливает помещения", () => {
  it("перегородка с проёмом 0.9 м даёт ДВЕ комнаты, а не одну", () => {
    const r = findRooms(план([
      ...коробка(),
      стена(4, 0, 4, 2.5), стена(4, 3.4, 4, 6),
    ]));
    expect(r.rooms.length, "комнаты слились через дверной проём").toBe(2);
    // каждая примерно вдвое меньше прежних 43 м²
    for (const c of r.rooms) expect(c.area).toBeGreaterThan(15);
    for (const c of r.rooms) expect(c.area).toBeLessThan(25);
  });

  it("человеку сказано, что разрыв мы СЧИТАЕМ дверью", () => {
    // это наше допущение, а не факт из файла: если там открытый проход,
    // площади надо складывать, и человек должен об этом знать
    const r = findRooms(план([
      ...коробка(), стена(4, 0, 4, 2.5), стена(4, 3.4, 4, 6),
    ]));
    const w = r.warnings.join(" ");
    expect(w).toMatch(/Разрывов в стенах/);
    expect(w, "не сказано, что делать, если это открытый проход")
      .toMatch(/сложить/);
  });

  it("входная дверь разрывом ВНЕШНЕЙ стены не выпускает комнату наружу", () => {
    // Самый частый случай на настоящем плане: входную дверь рисуют разрывом
    // наружной стены. Без закрытия заливка утекает на улицу, весь внутренний
    // объём касается края и отбрасывается как «улица» — то есть помещений
    // не находится ВОВСЕ, а площади исчезают молча.
    const r = findRooms(план([
      стена(0, 0, 3, 0), стена(3.9, 0, 8, 0), // разрыв 0.9 м — входная дверь
      стена(8, 0, 8, 6), стена(8, 6, 0, 6), стена(0, 6, 0, 0),
    ]));
    expect(r.rooms.length, "комната утекла наружу через входную дверь").toBe(1);
    expect(r.rooms[0].area).toBeGreaterThan(35);
    expect(r.warnings.join(" ")).toMatch(/Разрывов в стенах/);
  });

  it("контроль: у ЦЕЛОЙ перегородки сообщения нет", () => {
    // иначе «предупреждаем» неотличимо от «предупреждаем всегда»
    const r = findRooms(план([...коробка(), стена(4, 0, 4, 6)]));
    expect(r.rooms.length).toBe(2);
    expect(r.warnings.join(" ")).not.toMatch(/Разрывов в стенах/);
  });

  it("контроль: широкий проём 2.4 м НЕ закрывается — это одна зона", () => {
    // шире 1.6 м это уже не дверь, а открытый проход между зонами, и считать
    // такие зоны одним помещением как раз правильно
    const r = findRooms(план([
      ...коробка(), стена(4, 0, 4, 1.8), стена(4, 4.2, 4, 6),
    ]));
    expect(r.rooms.length, "широкий проход ошибочно принят за дверь").toBe(1);
    expect(r.warnings.join(" ")).not.toMatch(/Разрывов в стенах/);
  });

  it("контроль: стены НЕ на одной прямой не соединяются", () => {
    // две перегородки в разных местах комнаты с «подходящим» расстоянием
    // между концами — не дверь, и объединять их нельзя
    const r = findRooms(план([
      ...коробка(),
      стена(3, 0, 3, 2), стена(5, 3, 5, 6),
    ]));
    expect(r.warnings.join(" "), "соединили стены, лежащие на разных прямых")
      .not.toMatch(/Разрывов в стенах/);
  });

  it("сам план НЕ меняется: проход в модели остаётся проходом", () => {
    // закрывается только клетка сетки для подсчёта площадей
    const walls = [...коробка(), стена(4, 0, 4, 2.5), стена(4, 3.4, 4, 6)];
    const p = план(walls);
    const былоСтен = p.walls.length;
    findRooms(p);
    expect(p.walls.length, "findRooms изменил план").toBe(былоСтен);
    expect(p.walls[4].y2, "findRooms удлинил стену").toBeCloseTo(2.5, 9);
  });
});
