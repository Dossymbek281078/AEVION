import { productById } from "@/lib/products";

/**
 * Оговорка продукта — там, где даются обещания, а не только там, где платят.
 *
 * ЗАМЕР 04.09.2026. У двух продуктов каталога есть поле `notice`, и написано
 * оно не для красоты:
 *
 *   qpaynet:   «Демонстрационный режим. AEVION не является лицензированным
 *               банком, платёжным институтом или эмитентом электронных денег:
 *               реальные средства и платежи не обрабатываются».
 *   qcontract: своя оговорка того же рода.
 *
 * Видел её только тот, кто дошёл до витрины цен. На страницах самих модулей —
 * `/payments`, `/qpaynet`, `/qcontract` — оговорки было НОЛЬ (проверено
 * поиском с контролем: тот же поиск по каталогу даёт три вхождения). А
 * обещания живут именно там: дорожная карта `/payments` помечает «12-rail
 * unified checkout» и «Settlements — bank + AEC wallet» как `live`.
 *
 * То есть один и тот же продукт говорил о себе две разные вещи, и человек,
 * пришедший на страницу модуля по ссылке или из поиска, видел только уверенную
 * половину.
 *
 * ПОЧЕМУ КОМПОНЕНТ, А НЕ ТЕКСТ НА СТРАНИЦЕ. Скопированная оговорка расходится
 * с оригиналом при первой же правке одного из них — а правят обычно тот, что
 * ближе к деньгам. Здесь текст ровно один: каталог. Нет оговорки у продукта —
 * компонент не рисует ничего, и добавлять её на страницу вручную не надо.
 */
export function ProductNotice({
  productId,
  theme = "light",
}: {
  productId: string;
  /** Страницы модулей тёмные; тёмный текст на тёмном фоне не читается. */
  theme?: "light" | "dark";
}) {
  const notice = productById(productId)?.notice;
  if (!notice) return null;
  return (
    <div
      role="note"
      style={{
        maxWidth: 760,
        margin: "0 auto 20px",
        padding: "10px 14px",
        border:
          theme === "dark"
            ? "1px solid rgba(148,163,184,0.35)"
            : "1px solid rgba(148,163,184,0.45)",
        borderRadius: 10,
        background: theme === "dark" ? "rgba(15,23,42,0.55)" : "rgba(148,163,184,0.10)",
        color: theme === "dark" ? "#cbd5e1" : "#475569",
        fontSize: 13,
        lineHeight: 1.55,
        textAlign: "left",
      }}
    >
      {notice}
    </div>
  );
}

export default ProductNotice;
