import { describe, expect, it } from "vitest";
import { findRooms } from "./rooms";
import type { Plan } from "./planModel";

/**
 * В дизайн-проекте мебель начерчена такими же тонкими линиями, что и
 * перегородки, и заливка режет по ней помещение на куски: замер 23.09 на
 * альбоме — 32.39 м² по экспликации против 25.2 у большого куска плюс осколки
 * 4.1, 1.9, 1.2, 1.1. Площадь под шкафом — это площадь помещения, за неё
 * платят как за пол.
 *
 * Различаем не «мебель» (её признака в чертеже нет), а ТОЛЩИНУ: измеренную по
 * чертежу против принятой нами у одиночной линии. Правило срабатывает, только
 * если внутри области, ограниченной измеренными стенами, ровно один крупный
 * кусок: два крупных — это настоящая перегородка, и она остаётся.
 */
const стена = (x1: number, y1: number, x2: number, y2: number, t: number) =>
  ({ x1, y1, x2, y2, thickness: t, height: 2.7 });
const принятая = (x1: number, y1: number, x2: number, y2: number) =>
  ({ ...стена(x1, y1, x2, y2, 0.1), assumed: true });

const коробка = (): Plan["walls"] => [
  стена(0, 0, 6, 0, 0.2), стена(6, 0, 6, 5, 0.2),
  стена(6, 5, 0, 5, 0.2), стена(0, 5, 0, 0, 0.2),
];
const план = (walls: Plan["walls"]): Plan => ({ walls, openings: [], height: 2.7 });
const вСвету = (6 - 0.2) * (5 - 0.2);
// допуск — одна клетка сетки 5 см по периметру: точнее сетка не умеет
const предел = (6 - 0.2 + 0.05) * (5 - 0.2 + 0.05) - вСвету + 1e-9;

describe("мебель не режет помещение", () => {
  it("шкаф в углу не отнимает свою площадь у комнаты", () => {
    const шкаф = [
      принятая(0, 1.2, 1.6, 1.2), принятая(1.6, 1.2, 1.6, 0), // приставлен к двум стенам
    ];
    const r = findRooms(план([...коробка(), ...шкаф]));
    expect(r.rooms.length, "комната должна остаться одной").toBe(1);
    expect(Math.abs(r.rooms[0].area - вСвету)).toBeLessThanOrEqual(предел);
  });

  it("настоящая перегородка с измеренной толщиной делит комнату надвое", () => {
    const перегородка = [стена(3, 0, 3, 5, 0.12)];
    const r = findRooms(план([...коробка(), ...перегородка]));
    expect(r.rooms.length, "перегородка обязана делить").toBe(2);
  });

  it("два крупных куска — перегородку не убираем, даже если толщина принята", () => {
    const тонкая = [принятая(3, 0, 3, 5)];
    const r = findRooms(план([...коробка(), ...тонкая]));
    expect(r.rooms.length, "оба куска больше 5 м² — это перегородка").toBe(2);
  });

  it("без измеренных стен правило молчит: гадать не на чем", () => {
    const всеПринятые = коробка().map((w) => ({ ...w, assumed: true }));
    const r = findRooms(план([...всеПринятые, принятая(3, 0, 3, 5)]));
    expect(r.rooms.length, "ничего не склеиваем").toBe(2);
  });
});
