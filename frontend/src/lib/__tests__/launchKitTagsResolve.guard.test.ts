// Каждая метка из набора запуска обязана опознаваться САЙТОМ.
//
// ЗАЧЕМ. 28.09.2026 собран набор для западных площадок (Product Hunt, Show HN,
// Reddit, X). Метка, которой сайт не знает, возвращает из channelFrom null:
// ссылка работает, человек приходит, а канал в отчёте становится
// «unattributed» — то есть запуск состоялся, а измерить его нечем. Проверять
// это ПОСЛЕ публикации поздно: ссылка уже ушла к людям.
//
// Замер того же дня: из пяти меток набора четыре опознавались, а `rd` (Reddit)
// — нет. Сторож заведён, чтобы следующая площадка не повторила это молча.
import { describe, it, expect } from "vitest";
import { channelFrom, keepChannel } from "../products";

const НАБОР_ЗАПУСКА = ["ph", "hn", "rd", "li", "x-devhub"];

describe("метки набора запуска", () => {
  it("каждая опознаётся, а не превращается в null", () => {
    for (const м of НАБОР_ЗАПУСКА) {
      expect(channelFrom(м), `метка ${м} уйдёт в unattributed`).toBeTruthy();
    }
  });

  // ПОПРАВКА к первой редакции этого сторожа: я подавал в keepChannel КОРОТКУЮ
  // метку, а она ждёт каноническое имя канала («product-hunt», не «ph») и сама
  // приводит его обратно к короткой. Сторож краснел на исправном коде — прибор
  // был мой. Проверяем настоящий путь: метка из адреса → канал → снова метка.
  it("метка переживает переход между страницами", () => {
    for (const м of НАБОР_ЗАПУСКА) {
      const канал = channelFrom(м);
      expect(keepChannel("/pricing#tiers", канал), м).toContain(`c=${м}`);
    }
  });

  it("метка остаётся ПЕРЕД якорем, иначе сервер её не увидит", () => {
    const адрес = keepChannel("/pricing#tiers", channelFrom("ph"));
    expect(адрес.indexOf("c=ph")).toBeLessThan(адрес.indexOf("#"));
  });

  it("контроль: выдуманная метка по-прежнему null", () => {
    expect(channelFrom("zz-нет-такой")).toBeNull();
  });
});
