import { describe, expect, it } from "vitest";
import { TIERS, TERM_TIERS, STANDALONE_APPS } from "../src/data/pricing";
import { TERM_REFERENCES } from "../src/data/lemonSqueezyVariants";

/**
 * У каждого платного тарифа есть путь оплаты — или он назван здесь поимённо.
 *
 * 🔴 ЗАЧЕМ. Замер 08.09.2026: витрина продавала тариф `pro`, а ключей оплаты
 * под него в таблице ссылок не было вовсе — там жили варианты старого имени
 * `planet`. Покупатель верхнего тарифа получал честный отказ 503 «платёжный
 * вариант не настроен», и флагманский тариф продавался только вручную.
 *
 * ПОЧЕМУ НЕ ЛОВИЛОСЬ. Ручка checkout/healthz проверяет СВОЮ таблицу ссылок на
 * связность — она не знает списка тарифов витрины. Два списка ведут разные
 * файлы, а пересечение не считает никто. Этот файл закрывает ровно ту щель.
 *
 * С 15.09.2026 тариф — это срок, касса строит ссылку `tier_<ступень>` и
 * `app_<приложение>_<ступень>`. Сверка идёт ИМПОРТОМ, а не разбором текста:
 * тарифы теперь собираются функцией (planetTier), и текстовый разбор pricing.ts
 * их бы не увидел — сторож ослеп бы и молчал.
 *
 * ЧЕГО ЭТОТ ФАЙЛ НЕ РЕШАЕТ. Цена и состав пакетов — решение основателя. Известные
 * случаи без кассы перечисляются в ИЗВЕСТНЫЕ, и сторож на них не краснеет.
 */

/**
 * Известные тарифы без пути оплаты — ждут решения основателя.
 * Строка живёт здесь ровно до того дня, когда касса заведена.
 * 15.09.2026: пусто — у всех пяти ступеней ссылка есть (прежний случай `pro` закрыт).
 */
const ИЗВЕСТНЫЕ: Record<string, string> = {};

const платные = TIERS.filter((t) => typeof t.priceMonthly === "number" && t.priceMonthly > 0);
const ссылки = new Set<string>(TERM_REFERENCES);

describe("платный тариф не остаётся без кассы незамеченно", () => {
  it("прибор видит предмет: тарифы найдены, таблица ссылок прочитана", () => {
    // без этого «ноль находок» означал бы «не умею искать», а не «всё хорошо»
    expect(платные.length).toBeGreaterThanOrEqual(5);
    expect(платные.map((t) => t.id)).toContain("max");
    // положительный контроль: ключ, который в таблице ТОЧНО есть
    expect(ссылки.has("tier_full")).toBe(true);
    // отрицательный: выдуманного и прежнего (не продаётся) там быть не должно
    expect(ссылки.has("tier_zzz")).toBe(false);
    expect(ссылки.has("tier_full_monthly")).toBe(false);
  });

  it("у каждого платного тарифа есть ссылка оплаты или он назван в ИЗВЕСТНЫЕ", () => {
    const новые: string[] = [];
    for (const t of платные) {
      if (ссылки.has(`tier_${t.id}`) || ИЗВЕСТНЫЕ[t.id]) continue;
      новые.push(`${t.id} ($${t.priceMonthly}/мес) — ключа tier_${t.id} в таблице оплаты нет`);
    }
    expect(
      новые,
      "платный тариф без пути оплаты: покупатель увидит отказ 503, а продажа не состоится.\n"
      + новые.join("\n")
      + "\nЛибо заведите вариант оплаты, либо впишите тариф в ИЗВЕСТНЫЕ с причиной и датой.",
    ).toEqual([]);
  });

  it("у каждого отдельного приложения есть ссылка оплаты на каждой ступени срока", () => {
    // Приложение продаётся на той же лестнице сроков: пропущенная ступень — это
    // кнопка на витрине, за которой 503.
    const нет = STANDALONE_APPS.flatMap((a) =>
      TERM_TIERS.filter((t) => !ссылки.has(`app_${a.slug}_${t}`)).map((t) => `app_${a.slug}_${t}`),
    );
    expect(нет).toEqual([]);
    expect(ссылки.size, "в таблице оплаты есть лишнее или не хватает позиций").toBe(
      TERM_TIERS.length * (1 + STANDALONE_APPS.length),
    );
  });

  it("список ИЗВЕСТНЫЕ не переживает свою причину", () => {
    // тариф, у которого касса появилась, обязан уйти из списка — иначе
    // исключение молча защищает уже исправленное и прячет новый случай
    const лишние = Object.keys(ИЗВЕСТНЫЕ).filter((id) => ссылки.has(`tier_${id}`));
    expect(лишние, `у этих тарифов касса уже есть — уберите их из ИЗВЕСТНЫЕ: ${лишние.join(", ")}`)
      .toEqual([]);
  });
});
