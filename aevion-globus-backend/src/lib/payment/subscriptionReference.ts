/**
 * Похожа ли ссылка заказа на покупку ПОДПИСКИ.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ. Вебхуков три, и у каждого была своя копия разбора
 * тарифа — уже разошедшаяся: у PayBox незнакомая ссылка пишется в журнал и в
 * Sentry, у PayPal молча уходит в `lite`. Правило «это вообще про подписку?»
 * копировать нельзя тем более: копия расходится с оригиналом при первой правке
 * одного из них, а правят обычно тот, что ближе к деньгам.
 *
 * ЗАЧЕМ ВООБЩЕ. Вебхук кассы приходит на ВЕСЬ аккаунт, а не только на заказы,
 * созданные нашим чекаутом. Прямой перевод, счёт, старая подписка — событие
 * придёт, почта в нём будет, а ссылки нашего формата не будет. Без этой
 * проверки разбор тарифа возвращает умолчание, и человек, не покупавший у нас
 * ничего, получает доступ.
 *
 * ГРАНИЦА ТОКЕНА, а не подстрока. 04.09.2026 первая редакция искала слово
 * тарифа где угодно в строке, и «promo» содержало «pro»:
 *
 *     tier_pro_monthly   ПОДПИСКА  -> pro     (положительный контроль)
 *     promo-2026-09      ПОДПИСКА  -> lite    <- дефект
 *     deposit-9912       не подписка          (отрицательный контроль)
 *
 * Поэтому слово обязано стоять отдельным токеном: в начале строки или между
 * разделителями.
 */
export function ссылкаПодписки(ref: string): boolean {
  return (
    /^tier[_-]/i.test(ref) ||
    /(^|[_-])(lite|medium|full|business|team|all-access|enterprise|pro)([_-]|$)/i.test(ref)
  );
}

export default ссылкаПодписки;
