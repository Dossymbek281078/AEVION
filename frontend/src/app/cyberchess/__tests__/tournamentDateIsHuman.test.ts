/**
 * Сторож: дата турнира читается человеком, а не машиной.
 *
 * Замер 27.08.2026 на живой странице турниров, экран телефона: ДВЕНАДЦАТЬ
 * машинных меток вида «2026-08-12T18:11:04.050Z» прямо на экране вместо
 * «12 августа, 23:11». С сервера время приходит именно так, а на экран
 * попадало без обработки.
 *
 * Ни один тест этого не ловил: строка есть, она непустая, компонент
 * отрисовался, ошибок в консоли нет. Нашлось чтением того, что реально
 * написано на странице.
 *
 * Проверяется ПОВЕДЕНИЕ функции и отдельно — что страница её зовёт. Без
 * второго можно оставить функцию правильной, а на экран снова вывести сырое
 * поле: класс «правда останавливается на границе».
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { человеческаяДата } from "../tournaments/tournamentDate";

const PAGE = readFileSync(
  join(dirname(fileURLToPath(import.meta.url)), "..", "tournaments", "page.tsx"),
  "utf8",
);

describe("формат даты турнира", () => {
  it("метка с сервера превращается в человеческую строку", () => {
    const s = человеческаяДата("2026-08-12T18:11:04.050Z");
    expect(s, "сырая метка осталась как есть").not.toContain("T");
    expect(s, "не убраны миллисекунды и Z").not.toContain("Z");
    expect(s).toMatch(/^\d{1,2} [а-яё]+, \d{2}:\d{2}$/);
    expect(s).toContain("августа");
  });

  it("образец без часового пояса читается буквально", () => {
    // Такие строки лежат в списке образцов и рендерятся на сервере тоже —
    // текст обязан совпасть в любом поясе, иначе поедет гидрация.
    expect(человеческаяДата("2026-05-18 19:00")).toBe("18 мая, 19:00");
    expect(человеческаяДата("2026-01-01 09:05")).toBe("1 января, 09:05");
  });

  it("минуты и часы всегда двузначные", () => {
    expect(человеческаяДата("2026-03-07 08:05")).toBe("7 марта, 08:05");
  });

  it("все двенадцать месяцев названы по-русски", () => {
    const месяцы = [];
    for (let m = 1; m <= 12; m++) {
      const дд = "2026-" + String(m).padStart(2, "0") + "-15 12:00";
      // Месяц идёт с запятой («15 января, 12:00») — её надо снять.
      месяцы.push(человеческаяДата(дд).split(" ")[1].replace(",", ""));
    }
    expect(месяцы).toEqual([
      "января", "февраля", "марта", "апреля", "мая", "июня",
      "июля", "августа", "сентября", "октября", "ноября", "декабря",
    ]);
  });

  it("непонятная строка возвращается как есть, а не «Invalid Date»", () => {
    // Показать сырое лучше, чем показать «Invalid Date»: человек хотя бы
    // увидит данные и поймёт, что что-то не так.
    expect(человеческаяДата("совсем не дата")).toBe("совсем не дата");
    expect(человеческаяДата("")).toBe("");
  });

  it("страница действительно зовёт этот формат", () => {
    expect(PAGE, "сырое поле снова попадает на экран").not.toContain(">{t.startsAt}<");
    expect(PAGE, "формат не применён к дате турнира").toContain("человеческаяДата(t.startsAt)");
    expect(PAGE, "функция не импортирована").toContain('from "./tournamentDate"');
  });

  it("в странице не осталось второй копии формата", () => {
    // Два способа делать одно и то же расходятся молча: правят один, а на
    // экране остаётся другой.
    expect(PAGE, "формат объявлен и в модуле, и в странице").not.toContain(
      "function человеческаяДата",
    );
  });
});
