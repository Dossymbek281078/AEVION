import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/*
 * 🔴 Утверждение: задача, поставленная НАМЕРЕННО (ссылка `?puzzle=<id>` или
 * задача дня), не подменяется случайным подбором.
 *
 * ПОВОД 07.10.2026 — дефект на ЖИВОМ ПРОДЕ, замер окна 10 браузером:
 *   li_2orYN  ждали ★678   — на экране ★1062
 *   li_382iH  ждали ★687   — на экране ★2769
 *   li_17VuS  ждали ★1649  — на экране ★1361
 * Ручка `:id` отдавала верную задачу. Подменял фронт, и подменял МОЙ ЖЕ код:
 * `postavitZadachuNaDosku` зовёт `sTab("puzzles")`, а `tab` входит в ключ выбора
 * эффекта, подбирающего случайную задачу под фильтры. Ключ менялся → эффект
 * просыпался → ставил случайную поверх только что поставленной. То есть само
 * открытие задачи и вызывало её подмену, и чем надёжнее работала ссылка, тем
 * вернее срабатывала подмена.
 *
 * ⚠️ ГРАНИЦА, названная прямо. Сторож читает ИСХОДНИК: поднять шестнадцать тысяч
 * строк страницы в jsdom ради одного эффекта нельзя, а браузерная проверка живёт
 * в e2e и гоняется отдельно. Значит здесь проверяется УСТРОЙСТВО защиты
 * (одноразовый пропуск заведён, взводится при установке задачи и читается
 * подбором ДО его собственного стража), а не поведение на экране.
 * Поведение проверяет e2e-проверка `cyberchess-puzzle-link.spec.ts`: открыть
 * `?puzzle=<id>` и сверить рейтинг на доске с тем, что отдала ручка. Без неё этот
 * файл доказывает только намерение.
 */

const СТРАНИЦА = join(process.cwd(), "src/app/cyberchess/page.tsx");
const текст = readFileSync(СТРАНИЦА, "utf8");

/** Тело функции от объявления до закрывающей строки того же отступа. */
function тело(исходник: string, объявление: string): string {
  const i = исходник.indexOf(объявление);
  if (i < 0) return "";
  const ПС = String.fromCharCode(10);
  const строки = исходник.slice(i).split(ПС);
  const куски: string[] = [строки[0]];
  for (let k = 1; k < строки.length; k++) {
    куски.push(строки[k]);
    if (строки[k] === "  };") break;
  }
  return куски.join(ПС);
}

describe("намеренно поставленная задача не подменяется случайной", () => {
  it("КОНТРОЛЬ: разбор нашёл тело функции установки задачи", () => {
    const т = тело(текст, "  const postavitZadachuNaDosku=");
    expect(т.length, "тело postavitZadachuNaDosku не найдено — разбор смотрит не туда").toBeGreaterThan(200);
    expect(т, "в теле нет установки текущей задачи — взята не та функция").toContain("sPzCurrent(pz)");
  });

  it("🔴 установка задачи взводит одноразовый пропуск подбора", () => {
    const т = тело(текст, "  const postavitZadachuNaDosku=");
    expect(т, "задача ставится, но подбор об этом не узнает — он её затрёт")
      .toContain("postavlenoNamerennoRef.current=true");
  });

  it("🔴 подбор случайной задачи читает пропуск ДО своего собственного стража", () => {
    // Порядок важен: собственный страж подбора срабатывает только при СОВПАДЕНИИ
    // ключа выбора, а установка задачи ключ как раз меняет (через sTab). Если
    // пропуск стоит после него, он не сработает именно в том случае, ради
    // которого заведён.
    const гдеПропуск = текст.indexOf("if(postavlenoNamerennoRef.current)");
    const гдеСтраж = текст.indexOf('if(pzCurrent&&pzAttempt==="idle"&&выборЗадачиRef.current===ключВыбора)');
    expect(гдеПропуск, "подбор не читает пропуск вовсе").toBeGreaterThan(-1);
    expect(гдеСтраж, "страж подбора исчез — проверка смотрит не туда").toBeGreaterThan(-1);
    expect(гдеПропуск, "пропуск стоит ПОСЛЕ стража и потому не сработает").toBeLessThan(гдеСтраж);
  });

  it("🔴 пропуск ОДНОРАЗОВЫЙ: он снимается, иначе фильтры перестанут работать", () => {
    // Иначе защита превратится в поломку: человек меняет фильтр, а задача не
    // меняется никогда. Лечение не должно быть хуже болезни.
    const i = текст.indexOf("if(postavlenoNamerennoRef.current)");
    const строка = текст.slice(i, текст.indexOf(String.fromCharCode(10), i));
    expect(строка, "пропуск не снимается — подбор замолчит навсегда")
      .toContain("postavlenoNamerennoRef.current=false");
  });

  it("🔴 приход по ссылке не открывает приветственное окно поверх доски", () => {
    // Человек пришёл из ролика смотреть конкретную позицию; окно про первый визит
    // закрывает собой ровно то, ради чего он пришёл.
    const i = текст.indexOf("hasCompletedOnboarding()");
    expect(i, "проверка онбординга исчезла — сторож смотрит не туда").toBeGreaterThan(-1);
    // Проверяется УСЛОВИЕ, а не наличие строки рядом. Первая версия искала
    // `get("puzzle")` в окрестности — и мутация «убрать !поСсылке из условия»
    // прошла насквозь: вычисление признака осталось на месте, использоваться
    // перестало. Сторож проверял, что признак ПОСЧИТАН, а не что он ВЛИЯЕТ.
    const ПС = String.fromCharCode(10);
    const строкаОткрытия = текст
      .split(ПС)
      .find((л) => л.includes("sShowOnboarding(true)") && л.includes("hasCompletedOnboarding()")) ?? "";
    expect(строкаОткрытия, "строка открытия онбординга не найдена — сторож смотрит не туда").not.toBe("");
    expect(строкаОткрытия, "онбординг открывается независимо от ссылки на задачу")
      .toContain("!поСсылке");
  });
});
