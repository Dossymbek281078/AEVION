import type { Metadata } from "next";

/*
 * Панель управления модулем QBuild: списки пользователей, заявок и проверок.
 * Все четыре страницы отвечают «Admin only» и получают данные по токену.
 *
 * Запрет ставится ЗДЕСЬ, а не в robots.txt, и это не случайность. Два запрета
 * решают разные задачи и мешают друг другу: robots.txt говорит «не заходи», а
 * index: false — «не показывай». Робот, которому запрещено зайти, не прочитает
 * второй запрет и может показать голый адрес, узнав о нём по ссылке. Поэтому
 * для страницы, которую надо УБРАТЬ из выдачи, выбирают запрет показа и вход
 * оставляют открытым. Скрывать тут нечего: без токена страница пуста.
 *
 * Соседний /admin/ закрыт в robots.txt исторически — это чужая зона, не трогаю.
 */
export const metadata: Metadata = {
  robots: { index: false, follow: false },
};

export default function BuildAdminLayout({ children }: { children: React.ReactNode }) {
  return <>{children}</>;
}
