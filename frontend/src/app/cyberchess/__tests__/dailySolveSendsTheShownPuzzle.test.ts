/**
 * На сервер уходит решение ТОЙ задачи, которая на доске.
 *
 * 🔴 ЗАМЕР НА ЖИВОМ ПРОДЕ 29.09.2026. Решил задачу дня руками — три верных
 * хода приняты, бот ответил, — а страница отправила
 * `["f3e5","c6e5","d3d4"]`: решение ВСТРОЕННОЙ ЗАПАСНОЙ задачи, которая
 * показывается первые доли секунды, пока грузится задача из банка. Сервер
 * ответил 400 `wrong_solution`, серия осталась 0, в таблице лидеров
 * «сегодня задачу ещё никто не решал».
 *
 * То есть задача дня не засчитывалась НИКОМУ и никогда, и ни одной ошибки на
 * экране при этом не было. Ворота №5 (возврат на второй день) держались на
 * механизме, который молча не работал.
 *
 * Причина: `finalizeSolved` — useCallback без `puzzle` в зависимостях.
 * Замыкание держало задачу первого рендера. Дефект существовал до моих
 * сегодняшних правок; я его не внёс, а нашёл, когда пошёл проверять
 * засчитывание руками вместо чтения кода.
 */

import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const СТРАНИЦА = readFileSync(join(__dirname, "..", "daily", "page.tsx"), "utf8");

/** Список зависимостей у finalizeSolved. */
function зависимостиFinalize(): string {
  const i = СТРАНИЦА.indexOf("const finalizeSolved");
  expect(i, "finalizeSolved не найден").toBeGreaterThan(-1);
  const j = СТРАНИЦА.indexOf("}, [", i);
  return СТРАНИЦА.slice(j, СТРАНИЦА.indexOf("]", j) + 1);
}

describe("отправка решения задачи дня", () => {
  it("🔴 finalizeSolved видит текущую задачу", () => {
    // Без этого на сервер уходит решение задачи, которой на доске нет.
    expect(зависимостиFinalize()).toContain("puzzle");
  });

  it("контроль: прежние зависимости не потеряны", () => {
    // Убрать лишнее заодно с починкой — способ сломать серию молча.
    const д = зависимостиFinalize();
    expect(д).toContain("streak");
    expect(д).toContain("stopTimer");
  });

  it("на сервер уходит СЫРОЕ решение, а не то, что играли на доске", () => {
    // Сервер сверяет с каноническим решением дня целиком, включая ход
    // соперника; нормализованное короче на один ход и будет отвергнуто.
    expect(СТРАНИЦА).toContain("moves: puzzle.solRaw ?? puzzle.sol");
  });
});
