import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

/**
 * Плавающая кнопка агента закреплена в правом нижнем углу. Подвал — в самом
 * низу страницы, дальше мотать некуда, поэтому кнопка накрывает его последнюю
 * строку НАВСЕГДА, а не «при этой прокрутке».
 *
 * Замер 02.09.2026 на проде: ссылка «Помощь» -> /help недостижима на 40
 * адресах, накрыта кнопкой «Открыть AEVION AI Agent».
 *
 * 🔴 Главное, что охраняет этот сторож: отступ обязан быть задан ТАМ, где его
 * не перебьёт строчный стиль. Первая моя попытка была правилом в globals.css
 * — и она бы молча не сработала: у всех трёх подвалов отступ задан inline, а
 * строчный стиль сильнее правила из таблицы. Правило в globals.css оставлено
 * для подвалов БЕЗ строчного отступа, но само по себе оно ничего не решает.
 */

const КОМП = path.join(__dirname, "..");
const читать = (о: string) => fs.readFileSync(path.join(КОМП, о), "utf8");

const ПОДВАЛЫ = [
  "SiteFooter.tsx",
  "fintech/FintechFooter.tsx",
  "build/BuildShell.tsx",
];

/** Учитывает ли строчный отступ высоту кнопки агента. */
export function отступУчитываетКнопку(текст: string) {
  return /padding[^;]{0,120}var\(--aevion-agent-h/.test(текст)
    || /paddingBottom[^;]{0,120}var\(--aevion-agent-h/.test(текст);
}

describe("подвал не накрыт кнопкой агента", () => {
  it("прибор умеет краснеть: обычный отступ находкой не считает", () => {
    expect(отступУчитываетКнопку('padding: "40px 20px 28px",')).toBe(false);
  });

  it("прибор не клевещет: отступ с переменной признаёт", () => {
    expect(отступУчитываетКнопку(
      'padding: "40px 20px calc(28px + var(--aevion-agent-h, 0px))",')).toBe(true);
  });

  for (const п of ПОДВАЛЫ) {
    it("отступ учитывает кнопку: " + п, () => {
      expect(отступУчитываетКнопку(читать(п))).toBe(true);
    });
  }

  it("кнопка публикует свою высоту, иначе отступ всегда нулевой", () => {
    const s = читать("AgentDock.tsx");
    expect(s).toContain('setProperty("--aevion-agent-h"');
    // Док открыт — кнопки нет; переменную обязаны снять, иначе подвал
    // держит отступ под то, чего на экране уже нет.
    expect(s).toContain('removeProperty("--aevion-agent-h")');
  });
});
