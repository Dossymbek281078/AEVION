/* Кому принадлежит полуход.
 *
 * В разборе партии рядом живут ДВА разных счёта, и они сдвинуты друг относительно
 * друга на единицу:
 *   • `analysis[k].move` и `MoveMetric.ply` — номер полухода, считая с ЕДИНИЦЫ.
 *     Первый ход белых — это 1. Значит НЕЧЁТНЫЙ ply принадлежит белым.
 *   • индекс в массиве `analysis[]` — считая с НУЛЯ. analysis[0] — тот же первый
 *     ход белых. Значит ЧЁТНЫЙ индекс принадлежит белым.
 *
 * Оба выражения выглядят одинаково («%2») и стоят в одном файле в трёх экранах
 * друг от друга, поэтому их регулярно путают. Реальный случай (2026-07-27): спарклайн
 * «тренд точности» на главном экране фильтровал сохранённый ply как индекс — и рисовал
 * игроку точность СОПЕРНИКА. Причём при обоих цветах: для белых он брал чётные ply
 * (ходы чёрных), для чёрных — нечётные (ходы белых), то есть всегда бота.
 *
 * Две функции вместо одной — намеренно: имя обязано называть, какой счёт имеется в виду.
 */

/** Ход игрока? `ply` считается с 1 (analysis[].move, MoveMetric.ply). */
export function isPlayerPly(ply: number, playerColor: "w" | "b"): boolean {
  const whiteMoved = ply % 2 === 1;
  return whiteMoved === (playerColor === "w");
}

/** Ход игрока? `index` — позиция в массиве analysis[], считается с 0. */
export function isPlayerIndex(index: number, playerColor: "w" | "b"): boolean {
  const whiteMoved = index % 2 === 0;
  return whiteMoved === (playerColor === "w");
}
