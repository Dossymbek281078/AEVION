/**
 * Сторож: подсказки сочетаний клавиш не показываются на телефоне.
 *
 * «⌃K» в шапке — подсказка нажать то, чего на телефоне нет. Замер 27.08.2026
 * на экране 375 пикселей: шапка занимала треть экрана и несла 13 управляющих
 * элементов, при этом шахматной доски не было видно вовсе. Каждый лишний
 * элемент там платный.
 *
 * Проверка статическая и намеренно узкая: она закрепляет, что подсказка
 * ОБЁРНУТА в условие мобильной вёрстки, а не просто присутствует в файле.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const PAGE = readFileSync(
  join(dirname(fileURLToPath(import.meta.url)), "..", "page.tsx"),
  "utf8",
);

describe("подсказки клавиш на телефоне", () => {
  it("контроль: подсказка ⌃K вообще есть в интерфейсе", () => {
    // Без этого «всё скрыто» могло бы значить «искали не то».
    expect(PAGE).toContain("⌃K");
  });

  it("⌃K обёрнута в проверку мобильной вёрстки", () => {
    // Ищем МЕСТО ОТРИСОВКИ, а не первое упоминание строки: первым в файле
    // идёт мой же комментарий про эту подсказку, и тест, искавший «⌃K»,
    // разбирал комментарий вместо разметки — и краснел на исправном коде.
    const i = PAGE.indexOf("⌃K</kbd>");
    expect(i, "контроль: разметка подсказки не найдена").toBeGreaterThan(-1);
    const перед = PAGE.slice(Math.max(0, i - 400), i);
    expect(
      перед,
      "подсказка сочетания клавиш рисуется и на телефоне, где нажать её нечем",
    ).toMatch(/!isMobileLayout\s*&&\s*<kbd/);
  });

  it("всплывающая подсказка про Ctrl+K не показывается на телефоне", () => {
    // Она приходит через 2.4 секунды после открытия — то есть ровно тогда,
    // когда человек читает окно приветствия, и на телефоне ложится поверх него.
    const i = PAGE.indexOf("Жми Ctrl+K");
    expect(i, "контроль: подсказка не найдена").toBeGreaterThan(-1);
    const блок = PAGE.slice(Math.max(0, i - 700), i);
    expect(
      блок,
      "подсказка про сочетание клавиш всплывает и на телефоне",
    ).toMatch(/if\s*\(\s*isMobileLayout\s*\)\s*return/);
  });
});
