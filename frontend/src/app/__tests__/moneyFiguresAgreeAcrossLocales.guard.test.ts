import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/**
 * Сторож: суммы в тексте не имеют права расходиться между языками.
 *
 * Повод. Цену правят в одном месте и забывают в двух других: у нас три
 * словаря (en/ru/kk), и сторож согласованности следит за НАЛИЧИЕМ ключей,
 * а не за их содержимым. То есть английский мог обещать $19, а русский $29,
 * и ни одна проверка бы не покраснела.
 *
 * Замер при написании (29.08.2026): 25 ключей с суммами, расхождений ноль.
 * То есть сторож заводится на ЧИСТОМ состоянии и охраняет его.
 *
 * ⚠️ Разделители тысяч у языков РАЗНЫЕ и это правильно: `$5,000` по-английски
 * и `$5 000` по-русски (неразрывный пробел). Первая версия проверки этого не
 * учитывала и нашла «расхождение» там, где суммы совпадали. Поэтому числа
 * нормализуются перед сравнением, а тест на это есть отдельно.
 */
const ФАЙЛ = join(process.cwd(), "src", "lib", "i18n-data.ts");

/** Суммы из строки, без разделителей тысяч. */
export function суммы(текст: string): string[] {
  const out: string[] = [];
  for (const m of текст.matchAll(/\$\s?(\d[\d.,   ]*)/g)) {
    out.push(m[1].replace(/[,   ]/g, "").replace(/\.$/, ""));
  }
  return out;
}

function словари(): Record<string, Record<string, string>> {
  // ⚠️ Переписано 31.08.2026 при сборке к 10.09.
  //
  // Прежняя версия читала src/lib/i18n-data.ts и разбирала в нём блоки
  // en/ru/kk. Словарь разбит по языкам 10.08 (ради веса страницы: 1.3 МБ из
  // 2.5 грузились на каждой), блоков там больше нет, и сторож получал пустоту.
  // То есть проверка «суммы в разных языках не спорят» сравнивала три пустых
  // словаря и была бы зелёной всегда.
  //
  // Разбор ПОЗИЦИОННЫЙ, без регулярок: обратный слэш в этой среде теряется на
  // границе вызова, и шаблон молча перестаёт совпадать — сегодня это трижды
  // ломало файлы до состояния «no tests».
  const dir = join(process.cwd(), "src", "lib", "i18n-lang");
  const out: Record<string, Record<string, string>> = {};
  for (const яз of ["en", "ru", "kk"]) {
    const текст = readFileSync(join(dir, яз + ".ts"), "utf8");
    const d: Record<string, string> = {};
    for (const line of текст.split(String.fromCharCode(10))) {
      const t = line.trim();
      if (!t.startsWith('"')) continue;
      const kEnd = t.indexOf('":');
      if (kEnd < 1) continue;
      const key = t.slice(1, kEnd);
      let val = t.slice(kEnd + 2).trim();
      if (val.endsWith(",")) val = val.slice(0, -1).trim();
      if (val.length > 1 && val.startsWith('"') && val.endsWith('"')) d[key] = val.slice(1, -1);
    }
    out[яз] = d;
  }
  return out;
}
describe("суммы согласованы между языками", () => {
  it("разделители тысяч не считаются расхождением", () => {
    // Это и есть та ошибка, на которой я поймал себя при написании.
    expect(суммы("Rewards up to $5,000 for critical")).toEqual(суммы("Вознаграждение до $5 000 за"));
  });

  it("разные СУММЫ ловятся", () => {
    expect(суммы("$19/mo")).not.toEqual(суммы("$29/мес"));
  });

  it("ни одна сумма не расходится между en и ru", () => {
    // Сравниваем ключи, где сумма есть У ОБОИХ языков. Валюты разные
    // намеренно ($0 против 0 ₽), поэтому «есть у одного, нет у другого»
    // расхождением не считается — иначе сторож краснел бы на правильном
    // тексте, а такого перестают читать.
    const d = словари();
    const общие = Object.keys(d.en).filter((k) => k in d.ru);
    const спор = общие.filter((k) => {
      const a = суммы(d.en[k]), b = суммы(d.ru[k]);
      return a.length && b.length && JSON.stringify(a) !== JSON.stringify(b);
    });
    expect(спор).toEqual([]);
  });

  it("ненулевая цена не исчезает при переводе", () => {
    // Щель предыдущей проверки: en обещает сумму, ru не обещает никакой.
    // Для нуля это законно ($0 = 0 ₽), для настоящей цены — нет: человек
    // увидел бы бесплатно там, где мы берём деньги.
    // Замер при написании: таких ключей 2, и оба — нули с обеих сторон.
    const d = словари();
    const пропало = Object.keys(d.en).filter((k) => {
      if (!(k in d.ru)) return false;
      const a = суммы(d.en[k]);
      return a.some((x) => Number(x) > 0) && суммы(d.ru[k]).length === 0;
    });
    expect(пропало).toEqual([]);
  });
});
