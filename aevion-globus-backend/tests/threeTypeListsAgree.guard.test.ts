import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";

/*
 * 🔴 СПИСКОВ ИМЁН СОБЫТИЙ ТРИ, А НЕ ДВА — и они обязаны сходиться.
 *
 * Что я знал до 07.10: списка два (фронт шлёт — сервер принимает), и за сутки
 * до этого я свёл воедино третью пару (сервер принимает — сервер умеет
 * спрашивать), потому что про `cta_click` ручка отвечала 400, пока события
 * лежали в журнале.
 *
 * Чего я НЕ знал: у фронта есть ещё и союз типов `EventType` в `lib/track.ts`.
 * Нашлось случайно — TypeScript отказался собирать новое событие `engaged`.
 * То есть третий список существовал, и его держала только проверка типов,
 * причём лишь на той половине, где её запускают.
 *
 * Поэтому утверждение здесь про КЛАСС: каждое имя из фронтового союза должно
 * приниматься сервером. Обратное НЕ требуется: сервер принимает и то, что
 * пишут вебхуки (подтверждение оплаты), — фронт такого не шлёт и знать не должен.
 *
 * Сторож читает ИСХОДНИК, и это его честная слабость: имена в союзе он берёт
 * регуляркой. Поэтому ниже стоит контроль прибора — он обязан найти заведомо
 * существующие имена; если список окажется пустым, сторож краснеет, а не
 * молчаливо «проверяет ноль имён».
 */
const КОРЕНЬ = join(__dirname, "..", "..");

/**
 * 🔴 КОММЕНТАРИИ ВЫРЕЗАЮТСЯ ДО РАЗБОРА, иначе сторож читает ПРОЗУ как код.
 *
 * Повод 07.10.2026, и это уже ТРЕТИЙ читатель одного и того же блока с одной и
 * той же слабостью (в `funnelEventTypesAgree` она починена утром того же дня).
 * У нового типа события `game_end` в комментарии объяснено, что кладётся в
 * meta.outcome: "win" | "loss" | "draw" | "unknown". Разбор зачислил `win` в
 * ПРИНИМАЕМЫЕ ИМЕНА, не нашёл его в наборе и покраснел — на совершенно верной
 * правке. Красное на верном коде опаснее отсутствия сторожа: к нему привыкают.
 *
 * И опаснее этого — обратная сторона: достаточно упомянуть имя в комментарии с
 * ДВУХ сторон, и списки «сходятся», хотя сервер имени не принимает, а клиент его
 * не шлёт. Сторож, читающий рассказ О вещи вместо вещи, доказывает согласие
 * рассказов.
 */
function безКомментариев(s: string): string {
  const ПС = String.fromCharCode(10);
  return s
    .replace(/\/\*[\s\S]*?\*\//g, " ")
    .split(ПС)
    .map((l) => { const i = l.indexOf("//"); return i >= 0 ? l.slice(0, i) : l; })
    .join(ПС);
}

function именаФронта(): string[] {
  const текст = безКомментариев(readFileSync(join(КОРЕНЬ, "frontend", "src", "lib", "track.ts"), "utf8"));
  const начало = текст.indexOf("export type EventType =");
  expect(начало, "союз типов EventType не найден — сторож смотрит не туда").toBeGreaterThan(-1);
  const конец = текст.indexOf(";", текст.indexOf("\n", начало));
  const блок = текст.slice(начало, конец);
  return [...блок.matchAll(/\|\s*"([a-z_]+)"/g)].map((m) => m[1]);
}

function именаСервера(): string[] {
  const текст = безКомментариев(readFileSync(
    join(КОРЕНЬ, "aevion-globus-backend", "src", "routes", "events.ts"),
    "utf8",
  ));
  const начало = текст.indexOf("export const ALLOWED_TYPES = new Set([");
  expect(начало, "ALLOWED_TYPES не найден — сторож смотрит не туда").toBeGreaterThan(-1);
  const конец = текст.indexOf("]);", начало);
  return [...текст.slice(начало, конец).matchAll(/"([a-z_]+)"/g)].map((m) => m[1]);
}

describe("три списка имён событий сходятся", () => {
  it("КОНТРОЛЬ: имя, живущее только в КОММЕНТАРИИ, именем события не считается", () => {
    // Без этого контроля вырезание комментариев можно было бы отключить, и сторож
    // снова начал бы читать прозу как код — а именно это и случилось 07.10 на
    // слове "win" из разбора meta.outcome. В отрывке ниже настоящее имя одно.
    const ПС = String.fromCharCode(10);
    const отрывок = [
      "export const ALLOWED_TYPES = new Set([",
      '  // meta.outcome бывает "win" | "loss" | "draw" | "unknown"',
      '  /* и блочный комментарий про "vydumannyj_tip" тоже не имя */',
      '  "page_view",',
      "]);",
    ].join(ПС);
    const нач = отрывок.indexOf("export const ALLOWED_TYPES = new Set([");
    const кон = отрывок.indexOf("]);", нач);
    const имена = [...безКомментариев(отрывок).slice(нач, кон).matchAll(/"([a-z_]+)"/g)].map((m) => m[1]);
    expect(имена, `разбор зачислил слова из комментария: ${имена.join(", ")}`).toEqual(["page_view"]);
  });

  it("КОНТРОЛЬ: фронтовый разбор тоже не считает именами слова из комментария", () => {
    /*
     * Отдельный контроль для ФРОНТОВОГО разбора, и вот почему он нужен.
     * Мутация «фронтовый разбор снова читает комментарии» на живых файлах НЕ
     * краснела — но не потому, что слабости нет. В комментарии к `game_end`
     * стоит точка с запятой («Партия КОНЧИЛАСЬ; meta.outcome — …»), и союз
     * обрезается на ней РАНЬШЕ слов в кавычках. То есть защищал нас не разбор, а
     * случайность расстановки знаков в прозе: уберут точку с запятой — и
     * "loss" | "draw" | "unknown" поедут в список имён.
     *
     * Полагаться на такую случайность нельзя, поэтому утверждение проверяется на
     * отрывке, где слова в кавычках стоят ПОСЛЕ союза и без обрезающей точки.
     */
    const ПС = String.fromCharCode(10);
    const отрывок = [
      "export type EventType =",
      '  // meta.outcome бывает "win" | "loss" | "draw"',
      '  | "page_view"',
      '  | "cta_click";',
    ].join(ПС);
    const нач = отрывок.indexOf("export type EventType =");
    const чистый = безКомментариев(отрывок);
    const кон = чистый.indexOf(";", чистый.indexOf(ПС, нач));
    const имена = [...чистый.slice(нач, кон).matchAll(/\|\s*"([a-z_]+)"/g)].map((m) => m[1]);
    expect(имена.sort(), `фронтовый разбор зачислил слова из комментария: ${имена.join(", ")}`)
      .toEqual(["cta_click", "page_view"]);
  });

  it("КОНТРОЛЬ прибора: оба списка непусты и содержат известные имена", () => {
    const ф = именаФронта();
    const с = именаСервера();
    // Без этого «все имена приняты» было бы истиной ни о чём: пустое множество
    // подходит под любое условие — на этом мы уже обжигались с byDay.
    expect(ф.length).toBeGreaterThanOrEqual(5);
    expect(с.length).toBeGreaterThanOrEqual(5);
    expect(ф).toContain("page_view");
    expect(с).toContain("page_view");
    expect(ф).toContain("engaged");
  });

  it("🔴 каждое имя, которое шлёт фронт, сервер ПРИНИМАЕТ", () => {
    const принимаются = new Set(именаСервера());
    const непринятые = именаФронта().filter((имя) => !принимаются.has(имя));
    expect(
      непринятые,
      `фронт шлёт имена, которые сервер отвергнет с 400: ${непринятые.join(", ")}`,
    ).toEqual([]);
  });

  it("🔴 про каждое принимаемое имя можно СПРОСИТЬ", async () => {
    // Третья пара, сведённая 06.10: список для чтения производный от списка
    // приёма, поэтому расхождение невозможно по устройству. Проверяем, что это
    // так и осталось, — иначе события снова будут лежать в журнале немыми.
    const { ALLOWED_TYPES } = await import("../src/routes/events");
    const принимаются = [...ALLOWED_TYPES];
    for (const имя of именаСервера()) {
      expect(принимаются, `имя ${имя} есть в исходнике, но не в наборе`).toContain(имя);
    }
  });
});
