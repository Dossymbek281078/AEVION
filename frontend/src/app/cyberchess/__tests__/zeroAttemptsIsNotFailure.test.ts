import { describe, test, expect } from "vitest";
import * as fs from "node:fs";
import * as path from "node:path";

const SRC = path.join(__dirname, "..", "OpeningRepertoire.tsx");
const src = () => fs.readFileSync(SRC, "utf-8");

// 21.08.2026, найдено глазами на /cyberchess/repertoire. У ветки, которую
// человек ещё ни разу не тренировал, стояло КРАСНОЕ «Успех: 0%». Ноль попыток
// это «неизвестно», а не «плохо»: страница сообщала о провале в том, чего он
// не пробовал. Тот же изъян, что «100% побед» из одной партии — число верное,
// вывод из него ложный.

describe("ноль попыток не выдаётся за провал", () => {
  test("у ветки без попыток показывается прочерк, а не 0%", () => {
    const s = src();
    expect(s, "нет ветки для нулевых попыток").toContain("branch.attempts === 0");
    expect(s, "нет честной подписи вместо процента").toContain("ещё не тренировали");
  });

  test("в сводке тоже прочерк, а не ноль процентов", () => {
    expect(src()).toContain('totals.attempts === 0 ? "—"');
  });

  test("цветовая шкала осталась для настоящих попыток", () => {
    // Проверка не только «стало хорошо», но и «не сломали работавшее»:
    // при попытках > 0 процент по-прежнему красится по величине.
    const s = src();
    expect(s).toMatch(/rate >= 70 \? COLORS\.green/);
  });
});
