import { describe, test, expect } from "vitest";
import { MODULES_PRICING } from "../src/data/pricing";
import { модулиИзКассы, модулиДляКассы } from "../src/lib/payment/customData";

/**
 * Сторож: КАЖДЫЙ идентификатор из каталога переживает поездку через кассу.
 *
 * Список купленных модулей уезжает в кассу строкой и возвращается оттуда,
 * поэтому на обеих границах стоит отбор по шаблону идентификатора
 * (`lib/payment/customData`). Отбор нужен: значение приходит снаружи.
 *
 * Но он же создаёт связь между ДВУМЯ файлами, которую не проверяет больше
 * ничто. Заведут завтра модуль с подчёркиванием или заглавной буквой в id —
 * и его покупки начнут молча терять этот модуль: касса примет, вебхук
 * отфильтрует, в подписке его не окажется. Оплачено и не выдано, без
 * единой ошибки в журнале.
 *
 * Замер 04.09.2026: 43 идентификатора из 43 проходят. Сторож нужен не
 * потому, что сейчас плохо, а потому, что связь неявная.
 */
const ИДЕНТИФИКАТОРЫ = MODULES_PRICING.map((m) => m.id);

describe("идентификаторы каталога переживают поездку через кассу", () => {
  test("КОНТРОЛЬ: отбор ДЕЙСТВИТЕЛЬНО отбрасывает негодное", () => {
    // Без этого «все прошли» удовлетворялось бы отбором, который пропускает
    // всё подряд, — то есть проверкой, не проверяющей ничего.
    expect(
      модулиДляКассы(["ПЛОХОЙ", "../etc/passwd", "A_b", ""]),
      "отбор пропустил заведомо негодные значения"
    ).toEqual([]);
  });

  test("каждый идентификатор каталога проходит ИСХОДЯЩИЙ отбор", () => {
    const потеряны = ИДЕНТИФИКАТОРЫ.filter((id) => модулиДляКассы([id]).length === 0);
    expect(
      потеряны,
      `эти модули не уедут в кассу и будут потеряны при покупке: ${потеряны.join(", ")}`
    ).toEqual([]);
  });

  test("каждый идентификатор каталога проходит ВХОДЯЩИЙ отбор", () => {
    const потеряны = ИДЕНТИФИКАТОРЫ.filter((id) => модулиИзКассы(id).length === 0);
    expect(
      потеряны,
      `эти модули касса вернёт, а мы отфильтруем и не запишем: ${потеряны.join(", ")}`
    ).toEqual([]);
  });

  test("весь каталог разом переживает круговорот целиком", () => {
    // И предел длины списка. Он поставлен против враждебного ввода, но
    // первым же прогоном поймал СВОЮ ошибку: стояло 20 при каталоге в 43,
    // то есть честная покупка «всего сразу» теряла бы 23 модуля молча.
    // Требуем, чтобы каталог проходил ЦЕЛИКОМ: перерастёт предел — этот
    // тест покраснеет раньше, чем покупатель заметит пропажу.
    const уехало = модулиДляКассы(ИДЕНТИФИКАТОРЫ);
    const вернулось = модулиИзКассы(уехало.join(","));
    expect(вернулось).toEqual(уехало);
    expect(
      уехало.length,
      `каталог вырос до ${ИДЕНТИФИКАТОРЫ.length}, а через кассу проходит только ${уехало.length}: хвост теряется молча`
    ).toBe(ИДЕНТИФИКАТОРЫ.length);
  });
});
