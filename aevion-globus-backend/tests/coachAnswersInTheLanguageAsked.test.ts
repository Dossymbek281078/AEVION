/**
 * Русский вопрос — русский ответ, и не огрызок.
 *
 * ПОВОД 29.09.2026: приёмка спросила по-русски «3 причины 1.e4» и получила
 * «Η απάντηση…» — греческий, оборванный на 79 знаках. Требование языка живёт
 * в промпте, то есть это просьба, а не механизм: тот же класс, что «ходы
 * только из отчёта».
 *
 * Признаки намеренно грубые и односторонние — ложная тревога здесь дороже
 * пропуска, потому что прячет полезный ответ.
 */

import { describe, it, expect } from "vitest";
import { языкНеТот, ответОгрызок } from "../src/routes/coach";

const ГРЕЧЕСКИЙ = "Η απάντηση σε αυτό το ερώτημα είναι απλή: ο έλεγχος του κέντρου";

describe("язык ответа", () => {
  it("русский вопрос → греческий ответ ловится", () => {
    expect(языкНеТот("Назови 3 причины играть 1.e4", ГРЕЧЕСКИЙ)).toBe(true);
  });

  it("русский вопрос → английский ответ тоже ловится", () => {
    expect(языкНеТот("Что играть?", "The best move here is Nf3, controlling the center.")).toBe(true);
  });

  it("🔴 контроль: настоящий русский разбор С ЛАТИНСКИМИ ХОДАМИ проходит", () => {
    // Иначе мы прятали бы нормальные ответы: ходы у нас часто латиницей.
    expect(языкНеТот("Что играть?", "Играй Nf3 — конь держит e5 и готовит рокировку.")).toBe(false);
  });

  it("контроль: латинский вопрос не судим", () => {
    expect(языкНеТот("What should I play?", "Play Nf3, it controls the center.")).toBe(false);
  });

  it("контроль: слишком короткий ответ языком не судим", () => {
    expect(языкНеТот("Что играть?", "Nf3")).toBe(false);
  });
});

describe("огрызок", () => {
  it("короткое вступление без конца — огрызок", () => {
    expect(ответОгрызок("Отличный вопрос! Давай разберёмся, что происходит на доске и какой")).toBe(true);
  });

  it("пустой ответ — огрызок", () => {
    expect(ответОгрызок("   ")).toBe(true);
  });

  it("🔴 контроль: длинный разбор без финальной точки НЕ прячем", () => {
    // Человек дочитает и поймёт; прятать полезное из-за пунктуации нельзя.
    const длинный = "Играй Nf3. ".repeat(20) + "и далее по плану";
    expect(длинный.length).toBeGreaterThan(200);
    expect(ответОгрызок(длинный)).toBe(false);
  });

  it("контроль: короткий, но законченный ответ проходит", () => {
    expect(ответОгрызок("Играй Nf3 — это лучший ход.")).toBe(false);
  });
});
