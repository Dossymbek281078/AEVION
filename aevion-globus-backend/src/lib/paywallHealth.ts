import { paywallEnabledFor } from "./planGate";
import { ДОСТУП_МОДУЛЕЙ, модулиСоСтенойПоДанным } from "../data/moduleAccess";

/**
 * Сводка о том, настроена ли ВЫДАЧА КУПЛЕННОГО — для ручки состояния.
 *
 * 🔴 06.10.2026, повод. В /health было 18 полей и ни одного про гейт. Чтобы узнать,
 * закрыто ли хоть что-то, приходилось спрашивать Railway — а из worktree без привязки
 * CLI отвечает "No linked project found", и его "переменных 0" читается как
 * "переменная не задана", хотя означает "прибор не ответил". На этом 05.10 я едва не
 * доложил основателю, что пейволл не настроен, не имея об этом никаких сведений.
 *
 * Почему отдельный модуль, а не прямо в index.ts: импорт index.ts поднимает сервер
 * (app.listen там безусловен), то есть сторож не смог бы позвать эту сводку вовсе.
 *
 * Второй копии правила здесь НЕТ: спрашиваем ту же функцию, что решает на живом
 * запросе (paywallEnabledFor — она учитывает UNSAFE_TO_GATE и случай "ни один тариф
 * не даёт доступ"), и те же данные. Иначе появился бы второй способ считать то же,
 * и расхождение между ними стало бы новым источником неправды.
 *
 * Значения переменных НЕ печатаются никогда — только факт наличия и числа.
 *
 * ⚠️ ГРАНИЦА ЗНАМЕНАТЕЛЯ, иначе числа прочтут шире, чем они есть. modulesChecked —
 * это размер ТАБЛИЦЫ ДОСТУПА (замер 06.10: 14 записей, из них продаётся 5), а не весь
 * каталог: витрин и страниц с ценами у нас больше. "Закрыто 6 из 14" не означает
 * "закрыто 6 из всего, что мы продаём". Модуль, которого в таблице нет, этой сводке
 * невидим вовсе — и это худший исход, потому что выглядит он как благополучие.
 * Замер того же дня: из пяти продаваемых стена по данным есть ровно у ОДНОГО
 * (multichat-engine); cyberchess, qventure, aevion-ip-bureau и devhub продаются без неё.
 */
export interface СводкаПейволла {
  /** Факт наличия настройки сервиса, без значения. */
  configured: boolean;
  /** Знаменатель: сколько модулей рассмотрено. Без него "закрыто 6" не отвечает ни на что. */
  modulesChecked: number;
  /** ФАКТИЧЕСКИ закрыто сейчас — ответ той функции, что работает на запросе. */
  walledNow: number;
  /** Заявлено данными. Расхождение с walledNow значит, что настройка и данные говорят разное. */
  walledByData: number;
  /** Главное денежное число: продаётся, а по факту открыто. */
  soldButOpen: number;
  soldTotal: number;
}

export function сводкаПейволла(): СводкаПейволла {
  const продаётся = ДОСТУП_МОДУЛЕЙ.filter((м) => м.продаётся);
  return {
    configured: Boolean(process.env.PAYWALL_MODULES?.trim()),
    modulesChecked: ДОСТУП_МОДУЛЕЙ.length,
    walledNow: ДОСТУП_МОДУЛЕЙ.filter((м) => paywallEnabledFor(м.moduleId)).length,
    walledByData: модулиСоСтенойПоДанным().length,
    soldButOpen: продаётся.filter((м) => !paywallEnabledFor(м.moduleId)).length,
    soldTotal: продаётся.length,
  };
}
