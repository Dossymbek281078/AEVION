/**
 * Плитка «Реши задачу дня» обязана открывать ЗАДАЧУ ДНЯ.
 *
 * 🔴 ЗАМЕР НА ПРОДЕ 29.09.2026, числами. Плитка открывала `PUZZLES[idx]` —
 * задачу из загруженной пачки по локальному индексу. Индекс 283 дал позицию
 * `8/8/6P1/8/8/2K3kp/7R/5b2`, а сервер на тот же день отдавал
 * `6k1/1p3pp1/2p3n1/B2n4/P1QPr3/1P5P/5KP1/8`. Это разные задачи.
 *
 * Отметка «решено» при этом ставилась по совпадению позиции с серверной — то
 * есть не ставилась никогда, и третий механизм возврата (после серии и целей
 * дня) тоже молчал.
 *
 * Рядом жила ВТОРАЯ дверь: кнопка «☀ Задача дня» брала верную, серверную
 * задачу, но без нормализации (показывала позицию ДО хода соперника) и без
 * решения — решить её было нельзя вовсе. Две реализации одного и того же,
 * сломанные по-разному.
 */

import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { bezKommentariev } from "./bezKommentariev";

const КОД = bezKommentariev(readFileSync(join(__dirname, "..", "page.tsx"), "utf8"));

describe("задача дня на главной странице шахмат", () => {
  it("открывается серверная задача, а не локальный индекс", () => {
    expect(КОД).toContain("normalizePuzzle({fen:srvDaily.fen,sol:srvDaily.sol");
    expect(КОД).not.toContain("normalizePuzzle(PUZZLES[dailyState.idx]");
  });

  it("🔴 отметка «решено» ставится по признаку, а не по совпадению позиций", () => {
    // После нормализации позиция заведомо не равна серверной, и сравнение
    // fen молчало бы даже с правильной задачей — то есть починка одной
    // половины без второй ничего бы не дала.
    expect(КОД).toContain("!dailyState.solved&&этоЗадачаДня");
    expect(КОД).not.toContain("srvDaily?.fen===pzCurrent.fen");
  });

  it("признак снимается при загрузке обычной задачи", () => {
    // Иначе решённая случайная задача засчиталась бы как задача дня.
    const i = КОД.indexOf("const ldPz=");
    expect(КОД.slice(i, i + 200)).toContain("sЭтоЗадачаДня(false)");
  });

  it("вторая дверь ведёт в ту же комнату", () => {
    // Кнопка «☀ Задача дня» должна звать общий путь, а не свою копию.
    expect(КОД).not.toContain("const pz={fen:srvDaily.fen,r:srvDaily.rating,name:srvDaily.theme}");
  });

  it("контроль: отказы названы, а не проглочены", () => {
    // Если задача дня не загрузилась, человек обязан это узнать.
    expect(КОД).toContain("Задача дня не загрузилась");
    expect(КОД).toContain("Задача дня ещё грузится");
  });
});
