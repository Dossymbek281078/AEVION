/**
 * Событие покупки доходит от УЧЁТА до РЕКЛАМНОГО СЧЁТЧИКА.
 *
 * Между ними граница: учёт (PurchaseReturnTracker) кладёт поля в событие, счётчик
 * (AdPixels) их читает. Проверки по обе стороны были, а на СТЫК — ни одной.
 * Это тот самый класс «правда обрывается на границе»: обе половины зелёные,
 * а поле по дороге переименовали, и реклама молча перестала считать покупки.
 *
 * Цена ошибки прежняя: площадки учатся на покупках, а не на заходах.
 */
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { stripComments } from "../../app/__tests__/helpers/sourceCode";
import { сигналОПокупке } from "@/lib/adPurchaseSignal";

const учёт = stripComments(
  readFileSync(join(process.cwd(), "src/components/PurchaseReturnTracker.tsx"), "utf8"),
);

describe("покупка доходит до рекламного счётчика", () => {
  it("счётчик срабатывает на том, что реально шлёт учёт", () => {
    // Форма события такая, какой её собирает учёт: сумма верхним уровнем,
    // касса в мете. Если переименуют любое из двух — здесь станет null.
    const событие = { value: 49, meta: { provider: "paybox", stub: false } };
    const сигнал = сигналОПокупке(событие);
    expect(сигнал, "счётчик не признал событие покупкой").not.toBeNull();
    expect(сигнал?.деньги).toEqual({ value: 49, currency: "USD" });
  });

  it("учёт кладёт сумму ВЕРХНИМ уровнем, а не в мету", () => {
    // Счётчик читает d.value. Переезд суммы в meta оставил бы обе стороны
    // зелёными по отдельности и обнулил выручку в рекламе.
    expect(учёт, "сумма ушла из верхнего уровня события").toContain("{ value }");
  });

  it("учёт кладёт кассу в мету — по ней счётчик решает про Meta", () => {
    // У возврата Gumroad свой Purchase шлёт сама касса; без provider счётчик
    // отправил бы второй и удвоил выручку в кабинете Meta.
    // Проверяем КЛЮЧ, а не подстроку: первая редакция искала "provider," и
    // пережила переименование в "providerName: provider," — подстрока-то на
    // месте. Требуем сокращённую запись ключа сразу за открытием меты.
    // Перевод строки собираем из кода символа: обратная косая теряется на
    // границе инструмента, и в прошлой попытке она превратилась в НАСТОЯЩИЙ
    // перенос — файл перестал разбираться, а vitest ответил «no tests».
    const перенос = String.fromCharCode(10);
    const ключВМете = "meta: {" + перенос + "        provider,";
    expect(учёт, "касса больше не кладётся в мету под именем provider").toContain(ключВМете);
    expect(сигналОПокупке({ value: 19, meta: { provider: "gumroad" } })?.вMeta).toBe(false);
  });

  it("заглушка учёта не становится покупкой в рекламе", () => {
    expect(сигналОПокупке({ value: 49, meta: { stub: true } })).toBeNull();
  });
});
