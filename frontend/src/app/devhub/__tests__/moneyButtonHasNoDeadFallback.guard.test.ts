import { describe, test, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { productById } from "@/lib/products";

/**
 * Кнопка покупки Studio Pro не существует без товара в каталоге.
 *
 * Замер 28.08.2026. В разметке стояло `href={STUDIO_PRO?.href ?? "#"}`, а
 * надпись — `Upgrade — {STUDIO_PRO?.priceUsd ?? 149}/mo`. То есть при пропаже
 * записи из каталога человек видел бы полноценную кнопку с ценой, нажимал и не
 * попадал НИКУДА.
 *
 * Мёртвая кнопка — не главное. Обработчик нажатия при этом отправлял событие
 * `checkout_start`, и отправлял бы его и с адресом «#». В воронке появлялись бы
 * начатые оплаты, которых не было: отчёт о деньгах врал бы правдоподобно, и
 * разбираться в нём стали бы позже всего — числа-то растут.
 *
 * Зашитая рядом цена 149 — вторая беда: второй источник числа, которое уже
 * лежит в каталоге. Такие двойники расходятся молча.
 */

const PAGE = path.join(__dirname, "..", "page.tsx");

/**
 * Исходник БЕЗ комментариев.
 *
 * Отсекать по началу строки мало: блочный комментарий занимает несколько строк,
 * и его продолжения начала не имеют. Первая версия этого сторожа на том и
 * попалась — покраснела на комментарии, где процитирован прежний, дефектный
 * код. Сторож, который читает собственное объяснение как содержимое, даёт
 * ложную тревогу ровно там, где объяснение подробнее всего.
 */
function code(): string {
  return fs
    .readFileSync(PAGE, "utf8")
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, " ")   // {/* ... */} в разметке
    .replace(/\/\*[\s\S]*?\*\//g, " ")         // /* ... */ в коде
    .split("\n")
    .filter((l) => !l.trim().startsWith("//"))
    .join("\n");
}

describe("денежная кнопка DevHub", () => {
  test("прибор работает: страница читается и кнопка в ней есть", () => {
    const c = code();
    expect(c.length).toBeGreaterThan(5000);
    expect(c).toContain("STUDIO_PRO");
    expect(c).toContain("checkout_start");
  });

  test("товар есть в каталоге — иначе кнопки не будет вовсе", () => {
    // Проверка не декоративная: если запись когда-нибудь исчезнет, этот тест
    // покраснеет раньше, чем покупатель увидит блок без кнопки.
    const p = productById("devhub");
    expect(p, "товара devhub нет в каталоге — покупать нечем").toBeTruthy();
    expect(p!.href, "у товара нет адреса кассы").toMatch(/^https?:\/\//);
    expect(p!.priceUsd).toBeGreaterThan(0);
  });

  test("нет запасного адреса «#» на денежном пути", () => {
    expect(code(), "вернулся мёртвый запасной адрес").not.toMatch(/href=\{STUDIO_PRO\?\.href \?\? "#"\}/);
    expect(code(), "вернулся мёртвый запасной адрес").not.toContain('?? "#"');
  });

  test("цена берётся только из каталога, без зашитого двойника", () => {
    const c = code();
    expect(c, "цена снова продублирована в разметке").not.toMatch(/priceUsd \?\? \d+/);
  });

  test("и кнопка, и событие оплаты — внутри проверки на наличие товара", () => {
    const c = code();
    const gate = c.indexOf("{STUDIO_PRO ? (");
    expect(gate, "проверка на наличие товара исчезла").toBeGreaterThan(-1);
    const checkout = c.indexOf("checkout_start");
    expect(checkout, "событие оплаты не найдено").toBeGreaterThan(-1);
    expect(checkout, "событие оплаты уходит вне проверки на наличие товара").toBeGreaterThan(gate);
  });

  test("надпись кнопки взята из словаря, а не зашита по-английски", () => {
    const c = code();
    expect(c, "надпись снова зашита").not.toContain("Upgrade — ");
    expect(c).toContain('t("pro.upgrade")');
    expect(c).toContain('t("pro.perMonth")');
  });
});
