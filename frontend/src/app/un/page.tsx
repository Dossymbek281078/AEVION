import { redirect } from "next/navigation";

import type { Metadata } from "next";

// Метаданные обязательны у каждой публичной страницы (сторож pageMetadata), и
// у перенаправления они решают отдельную задачу: закрыть его от поисковика.
// Короткий адрес — вход для человека из каталога, а не страница: в выдаче ему
// делать нечего, и без noindex он соревновался бы за показы с той страницей,
// на которую ведёт.
export const metadata: Metadata = {
  title: { absolute: "AEVION" },
  robots: { index: false, follow: true },
};

// /un — короткий адрес для каталога Uneed.
//
// ЗАЧЕМ. Канал отрабатывает ОДИН раз: публикация в каталоге либо приводит
// людей, либо нет, и проверять разметку после неё поздно. Без метки в каталоге
// `channelFrom` вернул бы null, переход лёг бы в «прямые заходы», и на вопрос
// «сработал ли Uneed» ответа бы не нашлось. Ровно это случилось 29.09.2026 с
// запуском на Product Hunt: все переходы оттуда стали неизмеримы.
//
// Метка заведена с двух сторон: `?c=un` в нашей ссылке и `?ref=uneed` в
// REF_ALIASES — на случай, если каталог допишет свой параметр сам, как это
// делает Product Hunt.
export const dynamic = "force-static";

export default function Page() {
  /*
   * Ведём на СТРАНИЦУ ПРОДУКТА, а не на общий вход, — так же, как /ph: в
   * каталоге стоит карточка DevHub («Describe it. Get a deployed project»), и
   * человек должен попасть на то, что он там увидел.
   *
   * ⚠️ Замер, который стоит знать публикующему. За 14 дней
   * `product-hunt|/en/devhub` — 14 сессий, до цен дошли 0. Сама страница
   * исправна (замер 01.10: три цены, «Full studio from $100/mo» в первом
   * экране, восемь ссылок к ценам), поэтому адрес здесь тот же. Но если и
   * Uneed даст такую же картину, вопрос будет не к странице, а к тому, что
   * каталожная публика смотрит, а не покупает, — и это решается предложением,
   * а не перенаправлением.
   */
  redirect("/en/devhub?c=un");
}
