// Решение об отказе живёт ОТДЕЛЬНО от page.tsx: у страницы App Router
// разрешён лишь узкий набор экспортов, и лишний экспорт роняет проверку
// типов (TS2344 в .next/types). Заодно функции стали проверяемы отдельно.

/**
 * Ошибка запроса записи, которая ПОМНИТ код ответа.
 *
 * Раньше код сворачивался в текст `HTTP 404`, и страница показывала один и тот
 * же совет «попробуйте обновить страницу» в двух разных случаях: когда партии
 * нет вовсе и когда не дошёл запрос. В первом случае обновлять бесполезно —
 * человек будет жать перезагрузку, пока не уйдёт.
 */
export class ReplayFetchError extends Error {
  constructor(readonly status: number) {
    super(`HTTP ${status}`);
    this.name = "ReplayFetchError";
  }
}

/**
 * Текст отказа по коду ответа. Отдельная функция, потому что проверить надо
 * именно ПАРУ «код → совет»: страница, которая советует обновиться там, где
 * запись удалена, честнее не станет от того, что оба текста существуют.
 *
 * null — кода нет вовсе (запрос не дошёл, разбор не удался).
 */
export function tekstOtkaza(status: number | null): string {
  if (status === 404 || status === 410) {
    return "Такой партии нет — возможно, ссылка устарела или запись удалили.";
  }
  return "Не удалось загрузить партию. Проверьте связь и попробуйте ещё раз.";
}

/** Код ответа из ошибки запроса; null, если ошибка не про ответ сервера. */
export function kodOtveta(e: unknown): number | null {
  return e instanceof ReplayFetchError ? e.status : null;
}
