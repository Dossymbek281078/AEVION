/**
 * Каждая подпись, которую просит экран, должна найтись в словаре.
 *
 * Ненайденный ключ у нас не падает и не пустеет — `t()` печатает САМ КЛЮЧ
 * (src/lib/i18n.tsx: `tbl[lang]?.[key] || tbl["en"]?.[key] || key`). То есть
 * человек, только что заплативший, увидел бы вместо заголовка строку
 * `pricing.checkoutSuccess.titleActivatedNoTier`.
 *
 * Повод не выдуманный. Словарь платформы сейчас существует в двух устройствах:
 * в живой сборке это монолит `i18n-data.ts`, а в ветках будущей сборки он
 * разбит на файлы `i18n-lang`, и монолит там — заглушка. Любая такая миграция
 * переносит ключи, которые существовали НА МОМЕНТ переноса; десять ключей,
 * добавленных позже, уедут молча. Ни типы, ни сборка этого не заметят.
 *
 * Экран ОТМЕНЫ сюда намеренно не включён: он к словарю не обращается вовсе,
 * весь текст на нём зашит (это отдельный пробел — у платформы три языка).
 * Проверка там была бы пустой и создавала бы ложное чувство охвата.
 *
 * Поэтому сторож спрашивает не словарь, а ЭКРАН: ни один ключ, который просит
 * страница, не должен остаться на нём видимым текстом. Проверка не зависит от
 * того, как устроен словарь сегодня, — она переживёт переход.
 */
import { describe, it, expect, vi, afterEach } from "vitest";
import { render, cleanup, act } from "@testing-library/react";
import { readFileSync } from "node:fs";
import { I18nProvider } from "@/lib/i18n";

const параметры = { value: "" };
vi.mock("next/navigation", () => ({
  useSearchParams: () => new URLSearchParams(параметры.value),
  useRouter: () => ({ push: vi.fn(), replace: vi.fn() }),
  usePathname: () => "/pricing/checkout/success",
}));

/**
 * Ключи берём из исходника страницы, а не из списка в тесте: список пришлось бы
 * пополнять руками, и он молча отстал бы от страницы — то есть новый ключ, ради
 * которого сторож и написан, как раз и остался бы непроверенным.
 *
 * Разбор без регулярных выражений намеренно: одиночная обратная косая теряется
 * на границе вызова инструмента, и шаблон тогда компилируется, но ищет не то.
 */
function ключиИзИсходника(путь: string): string[] {
  const текст = readFileSync(путь, "utf8");
  const метка = 't("';
  const найденные: string[] = [];
  // Граница слова обязательна: без неё `get("tier")` и `set("x")` тоже кончаются
  // на `t("`, и разборщик выдавал «ключ» tier. Слово «tier» есть на экране как
  // обычный текст, поэтому сторож краснел бы по ложному поводу.
  const частьИмени = (c: string) =>
    (c >= "a" && c <= "z") || (c >= "A" && c <= "Z") || (c >= "0" && c <= "9") || c === "_" || c === "$" || c === ".";
  let i = текст.indexOf(метка);
  while (i !== -1) {
    const от = i + метка.length;
    const до = текст.indexOf('"', от);
    const предыдущий = i > 0 ? текст[i - 1] : " ";
    const ключ = до > от ? текст.slice(от, до) : "";
    // Ключи словаря у нас всегда с точками; строка без точки — не подпись.
    if (ключ.includes(".") && !частьИмени(предыдущий)) найденные.push(ключ);
    i = текст.indexOf(метка, до === -1 ? от : до);
  }
  return Array.from(new Set(найденные));
}

async function открыть(модуль: string, поиск: string) {
  параметры.value = поиск;
  const m = await import(/* @vite-ignore */ модуль);
  const Страница = m.default as () => JSX.Element;
  await act(async () => {
    render(
      <I18nProvider>
        <Страница />
      </I18nProvider>,
    );
  });
}

afterEach(() => cleanup());

describe("подписи экрана после оплаты находятся в словаре", () => {
  it("экран оплаты не показывает ключей вместо текста", async () => {
    const ключи = ключиИзИсходника("src/app/pricing/checkout/success/page.tsx");
    // Знаменатель: без него сторож, разучившийся находить ключи, остался бы
    // зелёным и означал бы «проверено ноль штук».
    expect(ключи.length, "ключи со страницы не разобрались").toBeGreaterThan(10);

    await открыть("@/app/pricing/checkout/success/page", "paybox=1&ref=abc&tier=lite&total=4900");
    const текст = document.body.textContent ?? "";
    expect(текст, "экран пуст").not.toBe("");
    for (const ключ of ключи) {
      expect(текст, `на экране виден ключ словаря: ${ключ}`).not.toContain(ключ);
    }
  }, 60000);

});
