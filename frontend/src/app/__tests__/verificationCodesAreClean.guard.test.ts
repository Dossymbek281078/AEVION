import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Коды подтверждения прав не содержат невидимых знаков.
 *
 * Повод 07.10.2026: метка Яндекса доехала до прода со знаком U+FEFF в начале
 * значения (байты ef bb bf перед шестнадцатью верными). Знак прилип при
 * переносе значения через буфер обмена. Снаружи всё выглядело исправным —
 * метка в разметке есть, проверка «метка присутствует» зелёная, — а Яндекс
 * ответил «Метатег не найден» и права не подтвердил. Две сборки ушли впустую.
 *
 * Невидимый знак нельзя увидеть при вычитке дифа: он занимает ноль ширины.
 * Поэтому его ищет сторож, а не глаз.
 *
 * Проверяем ИСХОДНИК: значения кодов лежат литералами в корневом макете,
 * и это сделано намеренно — метка подтверждения публична по своей природе,
 * а переменную Vercel не отдаёт обратно (тип Sensitive), то есть убедиться в
 * её годности можно было бы только выкаткой.
 */
const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = readFileSync(join(HERE, "..", "layout.tsx"), "utf8");

/**
 * Значение поля внутри блока verification.
 *
 * Без регулярного выражения намеренно. Первая версия сторожа искала
 * `${поле}:\s*"..."` внутри шаблонной строки — и один слэш съелся на границе
 * вызова, превратив `\s` в букву `s`. Шаблон перестал совпадать, сторож
 * ответил «кода нет» на исправном файле. Ловушка известная (съеденный слэш),
 * и дешевле её обойти, чем помнить: здесь только поиск подстроки.
 */
function код(поле: string): string | null {
  const метка = поле + ': "';
  const i = SRC.indexOf(метка);
  if (i < 0) return null;
  const начало = i + метка.length;
  const конец = SRC.indexOf('"', начало);
  return конец < 0 ? null : SRC.slice(начало, конец);
}

/** Невидимый знак: управляющий, неразрывный пробел или метка порядка байтов. */
const BOM = String.fromCharCode(0xfeff);
const NBSP = String.fromCharCode(0x00a0);
function невидимые(v: string): string[] {
  return [...v]
    .filter((c) => c.charCodeAt(0) < 32 || c === BOM || c === NBSP)
    .map((c) => "U+" + c.charCodeAt(0).toString(16).toUpperCase().padStart(4, "0"));
}

describe("коды подтверждения прав чисты", () => {
  it("прибор видит предмет: блок verification на месте и коды читаются", () => {
    expect(SRC).toContain("verification:");
    expect(код("google"), "кода Google нет — разбор сломан").toBeTruthy();
    expect(код("yandex"), "кода Яндекса нет — метка пропала из макета").toBeTruthy();
  });

  it("в кодах нет невидимых знаков", () => {
    for (const поле of ["google", "yandex"]) {
      expect(
        невидимые(код(поле) ?? ""),
        `в коде ${поле} невидимые знаки — именно из-за такого Яндекс не признал метку 07.10.2026`,
      ).toEqual([]);
    }
  });

  it("код Яндекса имеет его формат: ровно 16 шестнадцатеричных знаков", () => {
    expect(код("yandex")).toMatch(/^[0-9a-f]{16}$/);
  });

  it("ОТРИЦАТЕЛЬНЫЙ контроль: проверка формата не пропускает мусор", () => {
    const годен = (v: string) => /^[0-9a-f]{16}$/.test(v);
    expect(годен("f63de927a85b4103")).toBe(true);
    expect(годен(BOM + "f63de927a85b4103"), "знак U+FEFF обязан валить проверку").toBe(false);
    expect(годен("f63de927a85b410"), "пятнадцать знаков — не код").toBe(false);
    expect(годен("F63DE927A85B4103"), "верхний регистр Яндекс не отдаёт").toBe(false);
  });
});
